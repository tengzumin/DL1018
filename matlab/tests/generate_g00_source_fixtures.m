function generate_g00_source_fixtures(sourceRoot,projectRoot,fixturePath)
% Generate deterministic numerical outputs in a source-only MATLAB path.
sourceRoot=char(java.io.File(sourceRoot).getCanonicalPath());
projectRoot=char(java.io.File(projectRoot).getCanonicalPath());
fixturePath=char(java.io.File(fixturePath).getCanonicalPath());
restoredefaultpath;rehash toolboxcache;
sourceDirs={fullfile(sourceRoot,'RBF-BS0','code','code'), ...
    fullfile(sourceRoot,'RBF-BS0','experiments','kan_position_attitude_followup_v2','local_runtime'), ...
    fullfile(sourceRoot,'RBF-BS0','experiments','position_advantage_stage1_v1','methods'), ...
    fullfile(sourceRoot,'RBF-BS0','experiments','k1_command_filter_update_coordination_v3_5','local_runtime'), ...
    fullfile(sourceRoot,'RBF-BS0','experiments','attitude_kan_legal_input_reuse_upgrade_v3_6','local_runtime'), ...
    fullfile(sourceRoot,'RBF-BS0','experiments','x29_head_v39','local_runtime')};
for i=1:numel(sourceDirs),addpath(sourceDirs{i});end
required={'default_config','simulation_parameters','controller_parameters', ...
    'position_bs_step','attitude_bs_step','baseline_force_to_attitude', ...
    'command_filter_init','command_filter_step','rbf_mimo_basis','rbf_mimo_update', ...
    'rbf_event_scheduler_step','position_stage1_model_forward_v2', ...
    'position_stage1_update_head_pcf_v3_5','position_filter_realization_pcf_step_v3_5', ...
    'attitude_feature_row_v3_6','attitude_model_feature_x29_v39', ...
    'attitude_kan_head_step_v39','trim_head_audit_v39'};
for i=1:numel(required)
    resolved=which(required{i});assert(startsWith(resolved,sourceRoot), ...
        'DL1018:SourceFixturePath','Source fixture resolved outside the selected source: %s',resolved);
end
loaded=load(fullfile(projectRoot,'configs','effective_config.mat'),'cfg');cfg=loaded.cfg;
Pplant=simulation_parameters(cfg,cfg.plant.arm_initial,zeros(4,1));
P0=controller_parameters(cfg,Pplant,'fixed');
inputs=struct();expected=struct();
inputs.cfg=cfg;inputs.states=zeros(12,3);
inputs.states(:,2)=[.05;-.03;.10;.12;-.08;.03;.15;-.10;.20;.21;-.17;.09];
inputs.states(:,3)=[-.20;.15;-.30;-.20;.30;-.10;-.25;.12;-.35;-.20;.18;-.11];
inputs.reference=struct('position',[.25;-.15;.40],'velocity',[.10;-.04;.02], ...
    'acceleration',[-.20;.30;.10],'yaw',.3,'yaw_rate',-.1,'yaw_acceleration',.05);
expected.mass=P0.mass;expected.J0=P0.inertia;expected.C0=P0.allocation.C;
expected.nominal_mass_properties=struct('cog',Pplant.cog,'inertia',Pplant.inertia, ...
    'inertia_dot',Pplant.inertia_dot,'cog_rate',Pplant.cog_rate);
inputs.morph_lengths=[.15;.20;.25;.18];inputs.morph_rates=[.05;-.05;0;.025];
Pm=simulation_parameters(cfg,inputs.morph_lengths,inputs.morph_rates);
expected.morph_mass_properties=struct('cog',Pm.cog,'inertia',Pm.inertia, ...
    'inertia_dot',Pm.inertia_dot,'cog_rate',Pm.cog_rate,'C',Pm.allocation.C);
inputs.wind_profile_cfg=struct('type','biased_dual_sine','direction',[1;2;-1], ...
    'V0',9,'A1',1.5,'f1',.25,'phi1',.2,'A2',1.0,'f2',2.0,'phi2',-.3,'rise_time_s',.8);
[expected.wind_profile.velocity,expected.wind_profile.details]= ...
    wind_velocity_profile([0;.2;.8;1.2],inputs.wind_profile_cfg);
inputs.wind_load_cfg=struct('rho_air',1.225,'CdBody',1.0,'CdArm',1.0);
inputs.wind_state=inputs.states(:,2);inputs.wind_state(4:6)=[.2;-.15;.08];
expected.wind_load=cell(1,2);plants={Pplant,Pm};
for i=1:2
    [f,t,d]=morphology_aware_wind_load(inputs.wind_state,plants{i}, ...
        expected.wind_profile.velocity(:,3),inputs.wind_load_cfg);
    expected.wind_load{i}=struct('force',f,'torque',t,'details',d);
end
expected.position=cell(1,3);expected.attitude=cell(1,3);expected.force_to_attitude=cell(1,3);
for i=1:3
    [pc,pi]=position_bs_step(inputs.states(:,i),inputs.reference,zeros(3,1),P0);
    [thrust,euler,limited]=baseline_force_to_attitude(pi.commanded_acceleration,inputs.states(9,i),P0);
    filt=command_filter_init(inputs.states(7:9,i));
    [ir,next,requestedAcceleration]=command_filter_step(inputs.reference.yaw*[0;0;1],filt,P0);
    attRef=struct('euler',inputs.states(7:9,i)+[.08;-.06;.03], ...
        'euler_rate',[.1;-.05;.02],'euler_acceleration',[-.2;.12;.04]);
    [moment,ai]=attitude_bs_step(inputs.states(:,i),attRef,zeros(3,1),P0);
    expected.position{i}=struct('command',pc,'info',pi);
    expected.attitude{i}=struct('moment',moment,'info',ai);
    expected.force_to_attitude{i}=struct('thrust',thrust,'euler',euler,'limited',limited);
    if i==2
        inputs.filter_state=filt;inputs.filter_target=[.2;-.1;.25];
        [expected.filter.reference,expected.filter.next,expected.filter.requested]= ...
            command_filter_step(inputs.filter_target,filt,P0);
        inputs.filter_debug=[ir.euler;next.euler;requestedAcceleration];
    end
end

inputs.rbf_position_cfg=cfg.rbf.position;
inputs.rbf_position_cfg.gamma=inputs.rbf_position_cfg.gamma(:)*cfg.rbf.position.gamma_scale;
inputs.rbf_attitude_cfg=cfg.rbf.attitude;
inputs.rbf_attitude_cfg.gamma=inputs.rbf_attitude_cfg.gamma(:)*cfg.rbf.attitude.gamma_scale;
inputs.rbf_position_W=reshape(.01*sin((1:105)*.17),35,3);
inputs.rbf_attitude_W=reshape(.002*cos((1:243)*.13),81,3);
inputs.rbf_position_z=[.2;-.4;.7];inputs.rbf_attitude_z=[.1;-.2;.3;.4;-.5;.6];
inputs.rbf_position_surfaces=[1 -2 3;-4 5 -6;7 -8 9];
inputs.rbf_attitude_surfaces=[.5 -1 .8;-1.2 .6 -.4;2.4 -2.5 1.5];
expected.rbf_position=cell(1,3);expected.rbf_attitude=cell(1,3);
net=struct('W',inputs.rbf_position_W);
for i=1:3
    z=inputs.rbf_position_z+(i-1)*[.1;-.05;.08];
    [y,net,info]=rbf_mimo_update(z,inputs.rbf_position_surfaces(i,:).',net,inputs.rbf_position_cfg,.01);
    expected.rbf_position{i}=struct('y',y,'W',net.W,'info',info);
end
net=struct('W',inputs.rbf_attitude_W);
for i=1:3
    z=inputs.rbf_attitude_z+(i-1)*[.01;-.02;.03;-.01;.02;-.03];
    [y,net,info]=rbf_mimo_update(z,inputs.rbf_attitude_surfaces(i,:).',net,inputs.rbf_attitude_cfg,.01);
    expected.rbf_attitude{i}=struct('y',y,'W',net.W,'info',info);
end

inputs.position_model=make_position_model();
inputs.position_window=reshape(3.8*sin((1:448)*.071),14,32);
inputs.position_window(1,end)=5.5;inputs.position_window(2,end)=-5.25;
inputs.position_phi=position_stage1_model_forward_v2(inputs.position_model,inputs.position_window);
inputs.position_head_W=reshape(.07*cos((1:99)*.12),33,3);
inputs.position_head_surface=[7.5;-8.5;11];inputs.position_eta=[.2;-.15;.35];
[expected.position_head.raw,expected.position_head.applied,expected.position_head.W, ...
    expected.position_head.projection,expected.position_head.info]= ...
    position_stage1_update_head_pcf_v3_5(inputs.position_phi,inputs.position_head_W, ...
    inputs.position_head_surface,.01,.85,[3;3;3],inputs.position_eta,true);
inputs.eta_step=struct('thrust',P0.mass*9.3,'euler',[.12;-.08;.15], ...
    'a_requested',[.4;-.3;.1],'eta',[.03;-.04;.02],'k2',P0.bs.position.k2);
[expected.eta_step.a_filtered,expected.eta_step.r_filtered,expected.eta_step.eta_next, ...
    expected.eta_step.rotation]=position_filter_realization_pcf_step_v3_5( ...
    inputs.eta_step.thrust,inputs.eta_step.euler,inputs.eta_step.a_requested, ...
    inputs.eta_step.eta,inputs.eta_step.k2,P0.mass,P0.g,.001,true);

inputs.attitude_model=make_attitude_model();
inputs.attitude_history=reshape(1.4*sin((1:29*32)*.037),29,32);
[inputs.attitude_phi,inputs.attitude_W0,inputs.attitude_readout]= ...
    attitude_model_feature_x29_v39(inputs.attitude_model,inputs.attitude_history);
inputs.attitude_state=inputs.states(:,2);
inputs.attitude_ir=struct('euler',inputs.attitude_state(7:9)+[.08;-.06;.03], ...
    'euler_rate',[.1;-.05;.02],'euler_acceleration',[-.2;.12;.04]);
[~,inputs.attitude_ai0]=attitude_bs_step(inputs.attitude_state,inputs.attitude_ir,zeros(3,1),P0);
inputs.attitude_feature=attitude_feature_row_v3_6(inputs.attitude_ai0,inputs.attitude_state, ...
    inputs.attitude_ir,P0.mass*9.3,[120;130;140;150],zeros(0,1),P0.mass, ...
    cfg.plant.limits.motor_max,29);
aiHead=inputs.attitude_ai0;aiHead.J0=P0.inertia;
[expected.attitude_frozen.raw,expected.attitude_frozen.applied,expected.attitude_frozen.torque, ...
    expected.attitude_frozen.DeltaW,expected.attitude_frozen.diag]= ...
    attitude_kan_head_step_v39(inputs.attitude_phi,inputs.attitude_W0,zeros(33,3), ...
    aiHead,.8,.01,inputs.attitude_model.dmax,true,false);
aiBoundary=aiHead;aiBoundary.surface=[2.3;2.3;1.4];
drive=-.002*.8*inputs.attitude_phi*((inputs.attitude_model.dmax(:).* ...
    (aiBoundary.euler_rate_map.'*aiBoundary.surface)).');
inputs.attitude_DeltaW_boundary=.19999*drive/norm(drive,'fro');
[expected.attitude_projected.raw,expected.attitude_projected.applied,expected.attitude_projected.torque, ...
    expected.attitude_projected.DeltaW,expected.attitude_projected.diag]= ...
    attitude_kan_head_step_v39(inputs.attitude_phi,inputs.attitude_W0, ...
    inputs.attitude_DeltaW_boundary,aiBoundary,.8,.01,inputs.attitude_model.dmax,true,true);
assert(expected.attitude_projected.diag.projection_active&& ...
    norm(expected.attitude_frozen.raw)>0&&isequal(expected.attitude_frozen.DeltaW,zeros(33,3)), ...
    'DL1018:FixtureCoverage','Frozen-output or projection boundary fixture is not active.');

audit=struct('time',[.01;.02;.03],'dt_event_s',[.01;.01;.01], ...
    'weight_before',reshape(1:297,33,3,3),'weight_after',reshape(298:594,33,3,3), ...
    'phi',reshape(1:99,33,3),'y_raw',reshape(1:9,3,3));
expected.trim_empty=trim_head_audit_v39(audit,0);
expected.trim_single=trim_head_audit_v39(audit,1);
expected.trim_multi=trim_head_audit_v39(audit,3);
save(fixturePath,'inputs','expected','-v7.3');
end

function m=make_position_model()
m=struct('architecture','N_KAN','input_mu',linspace(-.1,.1,14).', ...
    'input_sigma',linspace(.7,1.3,14).','knots',single([-4 -4 -4 -4 -2.4 -.8 .8 2.4 4 4 4 4]), ...
    'spline_W',reshape(.015*sin((1:32*14*8)*.019),32,14,8), ...
    'linear_W',reshape(.02*cos((1:32*14)*.031),32,14), ...
    'feature_b',.03*sin((1:32).'),'output_W',reshape(.04*cos((1:99)*.07),33,3), ...
    'kan_silu_unclipped',true);
end

function m=make_attitude_model()
p=struct('spline_W',reshape(.012*sin((1:32*29*8)*.013),32,29,8), ...
    'linear_W',reshape(.018*cos((1:32*29)*.021),32,29), ...
    'feature_b',.025*sin((1:32).'),'readout__weight',reshape(.025*cos((1:99)*.043),3,33));
m=struct('architecture','KAN','input_dim',29,'input_mu',linspace(-.2,.2,29).', ...
    'input_sigma',linspace(.6,1.4,29).','dmax',[45;45;4.7124], ...
    'knots',[-4 -4 -4 -4 -2.4 -.8 .8 2.4 4 4 4 4],'params',p);
end
