function x=attitude_feature_row_v3_6(ai0,state,ir,thrustN,previousEventSetpoint,currentRawCommand,mass0,motorMax,inputDim)
% V3.6 lawful attitude features; no geometry, inertia, or configuration proxy is accepted.
state=double(state(:));previousEventSetpoint=double(previousEventSetpoint(:));
currentRawCommand=double(currentRawCommand(:));
assert(numel(state)==12&&numel(previousEventSetpoint)==4&& ...
    isscalar(thrustN)&&isfinite(thrustN)&&isscalar(mass0)&&mass0>0&& ...
    isscalar(motorMax)&&motorMax>0&&ismember(inputDim,[29 33]), ...
    'PCF36:FeatureShape','Invalid lawful attitude feature fields.');
base=[double(ai0.error(:));double(ai0.surface(:));state(10:12); ...
    double(ir.euler_rate(:));double(ir.euler_acceleration(:));state(7:9);state(4:6); ...
    double(ai0.nominal_body_angular_acceleration(:));double(thrustN)/double(mass0); ...
    previousEventSetpoint/double(motorMax)];
assert(numel(base)==29,'PCF36:FeatureDimension','X29 base must have 29 values.');
if inputDim==29
    x=base;
else
    assert(numel(currentRawCommand)==4&&all(isfinite(currentRawCommand)), ...
        'PCF36:CommandShape','X33 requires the current emitted raw four-channel command.');
    x=[base;currentRawCommand];
end
assert(isequal(size(x),[inputDim 1])&&all(isfinite(x)), ...
    'PCF36:FeatureFinite','Legal attitude feature row must be finite and dimensionally exact.');
end
