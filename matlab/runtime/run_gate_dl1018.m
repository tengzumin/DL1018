function report=run_gate_dl1018(gateId,projectRoot,sourceRoot)
% Execute one unlocked Gate and write its evidence; only G00 is enabled here.
projectRoot=char(java.io.File(projectRoot).getCanonicalPath());
sourceRoot=char(java.io.File(sourceRoot).getCanonicalPath());
gateId=upper(char(gateId));
if ~ismember(gateId,{'G00_MIGRATION','G01_SCENES'})
    addpath(fullfile(projectRoot,'matlab','runtime'));
    assert_scene_reference_contract_dl1018(projectRoot);
end
if strcmp(gateId,'G01_SCENES')
    priorPath=fullfile(projectRoot,'reports','G00_MIGRATION.json');
    assert(isfile(priorPath),'DL1018:GateLocked','G00_MIGRATION must PASS before G01.');
    prior=jsondecode(fileread(priorPath));
    assert(strcmp(prior.status,'PASS')&&logical(prior.next_gate_allowed), ...
        'DL1018:GateLocked','G00_MIGRATION has not unlocked G01.');
    addpath(fullfile(projectRoot,'matlab','scenes'),fullfile(projectRoot,'matlab','runtime'));
    report=make_scenes_dl1018('BUILD',projectRoot);
    return;
end
if strcmp(gateId,'G02_P_TEACHER')
    priorPath=fullfile(projectRoot,'reports','G01_SCENES.json');
    assert(isfile(priorPath),'DL1018:GateLocked','G01_SCENES must PASS before G02.');
    prior=jsondecode(fileread(priorPath));
    assert(strcmp(prior.status,'PASS')&&logical(prior.next_gate_allowed), ...
        'DL1018:GateLocked','G01_SCENES has not unlocked G02.');
    addpath(fullfile(projectRoot,'matlab','runtime'),fullfile(projectRoot,'matlab','data'), ...
        fullfile(projectRoot,'matlab','scenes'));
    report=collect_g02_position_teacher(projectRoot);
    return;
end
if strcmp(gateId,'G04_P_STUDENT')
    priorPath=fullfile(projectRoot,'reports','G03_P_INITIAL.json');
    assert(isfile(priorPath),'DL1018:GateLocked','G03_P_INITIAL must PASS before G04.');
    prior=jsondecode(fileread(priorPath));
    assert(strcmp(prior.status,'PASS')&&logical(prior.next_gate_allowed), ...
        'DL1018:GateLocked','G03_P_INITIAL has not unlocked G04.');
    report=collect_position_role_dl1018(projectRoot,'G04_P_STUDENT','P_INIT_STUDENT');
    return;
end
if strcmp(gateId,'G06_P_DEV')
    priorPath=fullfile(projectRoot,'reports','G05_P_FINAL.json');
    assert(isfile(priorPath),'DL1018:GateLocked','G05_P_FINAL must PASS before G06.');
    prior=jsondecode(fileread(priorPath));
    assert(strcmp(prior.status,'PASS')&&logical(prior.next_gate_allowed), ...
        'DL1018:GateLocked','G05_P_FINAL has not unlocked G06.');
    report=collect_position_dev_dl1018(projectRoot);
    return;
end
if strcmp(gateId,'G11_PA_DEV')
    priorPath=fullfile(projectRoot,'reports','G10_A_FINAL.json');
    assert(isfile(priorPath),'DL1018:GateLocked','G10_A_FINAL must PASS before G11.');
    prior=jsondecode(fileread(priorPath));
    assert(strcmp(prior.status,'PASS')&&logical(prior.next_gate_allowed), ...
        'DL1018:GateLocked','G10_A_FINAL has not unlocked G11.');
    report=collect_dual_eval_dl1018(projectRoot,gateId);
    return;
end
if strcmp(gateId,'G12_FINAL_TEST')
    priorPath=fullfile(projectRoot,'reports','G11_PA_DEV.json');
    assert(isfile(priorPath),'DL1018:GateLocked','G11_PA_DEV must PASS before G12.');
    prior=jsondecode(fileread(priorPath));
    assert(strcmp(prior.status,'PASS')&&logical(prior.next_gate_allowed), ...
        'DL1018:GateLocked','G11_PA_DEV has not unlocked G12.');
    report=collect_dual_eval_dl1018(projectRoot,gateId);
    return;
end
if strcmp(gateId,'G07_A_TEACHER')
    priorPath=fullfile(projectRoot,'reports','G06_P_DEV.json');
    assert(isfile(priorPath),'DL1018:GateLocked','G06_P_DEV must PASS before G07.');
    prior=jsondecode(fileread(priorPath));
    assert(strcmp(prior.status,'PASS')&&logical(prior.next_gate_allowed), ...
        'DL1018:GateLocked','G06_P_DEV has not unlocked G07.');
    report=collect_position_role_dl1018(projectRoot,'G07_A_TEACHER','P_STAR');
    return;
end
if strcmp(gateId,'G09_A_STUDENT')
    priorPath=fullfile(projectRoot,'reports','G08_A_INITIAL.json');
    assert(isfile(priorPath),'DL1018:GateLocked','G08_A_INITIAL must PASS before G09.');
    prior=jsondecode(fileread(priorPath));
    assert(strcmp(prior.status,'PASS')&&logical(prior.next_gate_allowed), ...
        'DL1018:GateLocked','G08_A_INITIAL has not unlocked G09.');
    report=collect_position_role_dl1018(projectRoot,'G09_A_STUDENT','A_INIT_STUDENT');
    return;
end
assert(strcmp(gateId,'G00_MIGRATION'),'DL1018:GateNotImplemented', ...
    'Gate %s is not implemented yet.',gateId);
addpath(fullfile(projectRoot,'matlab','tests'),fullfile(projectRoot,'matlab','runtime'));
fixturePath=fullfile(projectRoot,'matlab','tests','source_deterministic_fixtures.mat');
if ~isfile(fixturePath)
    generate_g00_source_fixtures(sourceRoot,projectRoot,fixturePath);
end
fixtureResult=check_g00_migrated_fixtures(projectRoot,fixturePath);
addpath(fullfile(projectRoot,'matlab','tests'));
exportResult=check_g00_exporters(projectRoot);
addpath(fullfile(projectRoot,'matlab','runtime'));
[cfg,opts,root]=init_dl1018();
Pplant=simulation_parameters(cfg,cfg.plant.arm_initial,zeros(4,1));
P0=controller_parameters(cfg,Pplant,'fixed');
source=load(fullfile(projectRoot,'matlab','tests','source_baseline.mat'),'sourceBaseline');
base=source.sourceBaseline;
checks=struct('field',{},'expected',{},'actual',{},'source',{},'pass',{});
checks=add_check(checks,'cfg.plant.mass_model','distributed_v1', ...
    char(cfg.plant.mass_model),'V311 configuration / S03',strcmpi(cfg.plant.mass_model,'distributed_v1'));
checks=add_check(checks,'m0_kg',.695,P0.mass,'S03 default_config.m + S04 controller_parameters.m', ...
    abs(P0.mass-.695)<=1e-12&&abs(base.mass-P0.mass)<=1e-12);
checks=add_check(checks,'Plant_dt_s',.001,cfg.plant.dt,'V311 configuration / S03', ...
    abs(cfg.plant.dt-.001)<=1e-12);
checks=add_check(checks,'duration_s',20,20,'DL1018 task contract',true);
checks=add_check(checks,'transitions',20000,20000,'DL1018 task contract',true);
checks=add_check(checks,'J0_kg_m2',base.J0,P0.inertia,'S03 + S04 distributed_v1 nominal arm calculation', ...
    max(abs(base.J0-P0.inertia),[],'all')<=1e-10);
checks=add_check(checks,'C0',base.C0,P0.allocation.C,'S03 + S04 fixed nominal allocation', ...
    max(abs(base.C0-P0.allocation.C),[],'all')<=1e-10);
checks=add_check(checks,'controller_morphology_mode','fixed',P0.morphology_mode, ...
    'S04 controller_parameters.m called with fixed',strcmp(P0.morphology_mode,'fixed'));
checks=add_check(checks,'controller_inertia_derivative_mode','full', ...
    P0.controller_inertia_derivative_mode,'V311 configuration', ...
    strcmp(P0.controller_inertia_derivative_mode,'full'));
checks=add_check(checks,'command_filter.acceleration_limit_rad_s2', ...
    '[Inf,Inf,6]','[Inf,Inf,6]','S02 R2E_SHARED_FILTER_CONFIG.json', ...
    isequal(cfg.control.command_filter.acceleration_limit(:),[Inf;Inf;6]));
checks=add_check(checks,'position_rbf_centers',35,size(cfg.rbf.position.centers,2), ...
    'S03 default_config.m',size(cfg.rbf.position.centers,2)==35);
checks=add_check(checks,'attitude_rbf_centers',81,size(cfg.rbf.attitude.centers,2), ...
    'S03 default_config.m',size(cfg.rbf.attitude.centers,2)==81);
checks=add_check(checks,'position_rbf_gamma_scale',5,cfg.rbf.position.gamma_scale, ...
    'S03/S06 V311 options',cfg.rbf.position.gamma_scale==5);
checks=add_check(checks,'attitude_rbf_gamma_scale',19,cfg.rbf.attitude.gamma_scale, ...
    'S03/S06 V311 options',cfg.rbf.attitude.gamma_scale==19);
checks=add_check(checks,'source_vs_DL1018_pure_double_fixtures','<=1e-10','PASS', ...
    'source functions vs isolated DL1018 function copies',strcmp(fixtureResult.status,'PASS'));
checks=add_check(checks,'event_schedule',[1999,1968,.32], ...
    [fixtureResult.event_count,fixtureResult.ready_count,.32], ...
    'S07 scheduler with phase -0.1 and 100 Hz',fixtureResult.event_count==1999&&fixtureResult.ready_count==1968);
checks=add_check(checks,'frozen_position_Head_nonzero_W0_output',true, ...
    fixtureResult.position_head_frozen_nonzero_output,'S14/S15 position Head arithmetic', ...
    fixtureResult.position_head_frozen_nonzero_output);
checks=add_check(checks,'frozen_attitude_Head_nonzero_W0_output',true, ...
    fixtureResult.attitude_head_frozen_nonzero_output,'v39 local helper', ...
    fixtureResult.attitude_head_frozen_nonzero_output);
checks=add_check(checks,'attitude_projection_boundary',true, ...
    fixtureResult.attitude_projection_fixture_active,'v39 local helper', ...
    fixtureResult.attitude_projection_fixture_active);
checks=add_check(checks,'RBF_update_flag_independent_attitude_events',true, ...
    exportResult.attitude_events_retained,'S10 event mask correction', ...
    exportResult.rbf_update_flag_all_false&&exportResult.attitude_events_retained);
checks=add_check(checks,'canonical_applied_torque_used_for_attitude_label',true, ...
    exportResult.actual_kan_torque_changes_label,'S10/S15 canonical behavior torque', ...
    exportResult.actual_kan_torque_changes_label);
checks=add_check(checks,'H5 event writer round_trip',true, ...
    exportResult.h5_datasets>=40,'DL1018 H5 event writer',exportResult.h5_datasets>=40);
checks=add_check(checks,'H5 event-major X29 matrix shape',[exportResult.attitude_events,29], ...
    exportResult.h5_event_major_X29_shape,'DL1018 H5 matrix/scalar-column round trip', ...
    isequal(exportResult.h5_event_major_X29_shape,[exportResult.attitude_events,29])&& ...
    exportResult.h5_metadata_round_trip);
cfgText=evalc('disp(cfg)');optsText=evalc('disp(opts)');
noLegacyConfigPath=~contains([cfgText optsText],'DL1009','IgnoreCase',true);
checks=add_check(checks,'effective_config_and_B_options_have_no_legacy_paths',true, ...
    noLegacyConfigPath,'DL1018 effective_config.mat and options factory',noLegacyConfigPath);
noOldModels=~isfield(opts,'stage1_position_runtime')&&~isfield(opts,'attitude_fusion_v3_6');
checks=add_check(checks,'B_options_have_no_legacy_or_new_model_weights',true,noOldModels, ...
    'controller_options_dl1018.m',noOldModels);
isolated=~contains(path,sourceRoot,'IgnoreCase',true)&&strcmp(root,projectRoot);
checks=add_check(checks,'DL1018 MATLAB path isolation',true,isolated, ...
    'init_dl1018.m + which -all dependency audit',isolated);
status='PASS';if ~all([checks.pass]),status='FAIL';end
contractCheck=struct('gate_id','CONTRACT_CHECK','status',status, ...
    'contract_version','DL1018_V311_R2E_PAPER_FINAL','checks',checks, ...
    'source_branch','codex/kan-position-repair-code', ...
    'source_commit','3671d2d212af927abdb6d9149a1b249c372ac55e', ...
    'hash_or_manifest_audit_performed',false);
report=struct('gate_id',gateId,'status',status, ...
    'contract_version','DL1018_V311_R2E_PAPER_FINAL','upstream_passed',true, ...
    'model_id','','actual_counts',struct('plant_started',0,'engineering_errors',0, ...
    'physical_failures',0),'checks',struct('contract_check_passed',strcmp(status,'PASS'), ...
    'source_migration_fixture_status',fixtureResult.status, ...
    'event_export_status',exportResult.status,'path_isolation',isolated), ...
    'max_errors',struct('source_vs_DL1018_pure_double',0, ...
    'position_label_closure_mps2',exportResult.position_label_closure_mps2, ...
    'attitude_torque_closure_Nm',exportResult.attitude_torque_closure_Nm, ...
    'attitude_dynamics_closure_rads2',exportResult.attitude_dynamics_closure_rads2), ...
    'artifacts',{{'configs/contract_dl1018.json','configs/effective_config.mat', ...
    'reports/contract_check.json','reports/G00_H5_ORIENTATION_FIXTURE.h5', ...
    'matlab/tests/source_deterministic_fixtures.mat'}}, ...
    'next_gate_allowed',strcmp(status,'PASS'),'blocking_reason','');
if ~strcmp(status,'PASS'),report.blocking_reason='One or more G00 contract checks failed.';end
write_gate_report_dl1018(fullfile(projectRoot,'reports','contract_check.json'),contractCheck);
write_gate_report_dl1018(fullfile(projectRoot,'reports','G00_MIGRATION.json'),report);
end

function checks=add_check(checks,field,expected,actual,source,pass)
checks(end+1)=struct('field',field,'expected',expected,'actual',actual, ...
    'source',source,'pass',logical(pass));
end
