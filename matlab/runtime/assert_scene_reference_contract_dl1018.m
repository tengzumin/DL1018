function assert_scene_reference_contract_dl1018(root)
% Fail closed before collectors can reuse runs from another scene reference.
root=char(java.io.File(root).getCanonicalPath());
reportPath=fullfile(root,'reports','G01_SCENES.json');
assert(isfile(reportPath),'DL1018:ReferenceIdentityMismatch', ...
    'A current G01 reference identity is required before collection.');
report=jsondecode(fileread(reportPath));
assert(isfield(report,'reference_contract_id')&& ...
    strcmp(char(string(report.reference_contract_id)),'DL1018_SCENE_REF_FIG8_A2_V2')&& ...
    isfield(report,'status')&&strcmp(report.status,'PASS')&& ...
    isfield(report,'next_gate_allowed')&&logical(report.next_gate_allowed), ...
    'DL1018:ReferenceIdentityMismatch', ...
    'G01 reference identity is missing or incompatible; use a fresh output root.');
end
