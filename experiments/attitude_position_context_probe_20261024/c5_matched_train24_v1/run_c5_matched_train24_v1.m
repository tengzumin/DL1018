    assert(isequaln(runStart.scene,scene), ...
        'C5Train24:RunStartScene','Nested run_start scene differs from pinned raw scene.');
else
    error('C5Train24:RunStartSchema','run_start lacks raw_path and embedded scene binding.');
end
