    isequaln(runStart.cfg,expectedCfg)&& ...
    isequaln(double(runStart.initial_state(:)),double(scene.initial_state(:))), ...
    'C5Train24:RunStartState','Source run_start cfg or initial state differs from scene/C5 snapshot.');
