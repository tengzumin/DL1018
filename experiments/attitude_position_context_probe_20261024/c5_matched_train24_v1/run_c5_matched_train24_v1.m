assert(logical(b.formal_rbf_baseline)&&logical(b.rbf_position_output_enabled)&& ...
    logical(b.rbf_position_update_enabled)&&~logical(c.rbf_position_output_enabled)&& ...
    ~logical(c.rbf_position_update_enabled)&&logical(c.position_delayed_prediction_enabled)&& ...
    isequal(double(c.position_coordinate_mask(:)),[1;1;0])&& ...
    logical(c.stage1_position_runtime.enabled)&&logical(c.stage1_position_runtime.update_enabled)&& ...
    logical(c.stage1_position_runtime.command_filter_coordination_v3_5.enabled)&& ...
    logical(c.stage1_position_runtime.position_only_search_head.enabled)&& ...
    ~isfield(b,'stage1_position_runtime')&&~isfield(b,'position_coordinate_mask')&& ...
    ~isfield(b,'position_delayed_prediction_enabled'), ...
    'C5Train24:PositionTreatment','B/C5 position options differ from the locked treatment.');
end
function assert_position_only_diff(rows)
allowed={'opts.rbf_position_output_enabled','opts.rbf_position_update_enabled', ...
    'opts.position_delayed_prediction_enabled','opts.position_coordinate_mask','opts.stage1_position_runtime'};
for k=1:numel(rows),p=rows(k).path;assert(any(cellfun(@(x)strcmp(p,x)||startsWith(p,[x '.']),allowed)), ...
        'C5Train24:UnexpectedOptionDiff','Non-position option differs: %s.',p);end
end
function rows=leaf_diff(a,b)
aRows=flatten(a,'opts');bRows=flatten(b,'opts');paths=unique([string({aRows.path}),string({bRows.path})]);
rows=repmat(struct('path','','B_value_json','','C5_value_json',''),0,1);
for k=1:numel(paths)
    p=char(paths(k));ia=find(strcmp({aRows.path},p),1);ib=find(strcmp({bRows.path},p),1);
    av='<ABSENT>';bv='<ABSENT>';if ~isempty(ia),av=aRows(ia).value_json;end;if ~isempty(ib),bv=bRows(ib).value_json;end
    if ~strcmp(av,bv),rows(end+1)=struct('path',p,'B_value_json',av,'C5_value_json',bv);end %#ok<AGROW>
end
end
function rows=flatten(x,prefix)
rows=struct('path',{},'value_json',{});
if isstruct(x)&&isscalar(x)
    f=fieldnames(x);for k=1:numel(f),sub=flatten(x.(f{k}),[prefix '.' f{k}]);rows=[rows sub];end %#ok<AGROW>
else
    rows=struct('path',prefix,'value_json',jsonencode(x));
end
