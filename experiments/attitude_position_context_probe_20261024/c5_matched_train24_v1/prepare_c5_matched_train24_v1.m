function verify_source_run_start(runStart,scene,rawPath,expectedCfg,repoRoot)
assert(isfield(runStart,'cfg')&&isfield(runStart,'initial_state')&& ...
    isequaln(runStart.cfg,expectedCfg)&& ...
    isequaln(double(runStart.initial_state(:)),double(scene.initial_state(:))), ...
    'C5Train24:RunStartState','Source run_start cfg or initial state differs from the scene/C5 snapshot.');
if isfield(runStart,'raw_path')
    assert(same_path(resolve_source_path(repoRoot,char(runStart.raw_path)),rawPath), ...
        'C5Train24:RunStartPath','Source run_start raw_path points to another scene.');
elseif isfield(runStart,'scene')
    assert(isequaln(runStart.scene,scene), ...
        'C5Train24:RunStartScene','Nested run_start scene differs from the pinned raw scene.');
else
    error('C5Train24:RunStartSchema','run_start has neither a raw_path nor an embedded scene binding.');
end
if isfield(runStart,'scene_id')
    assert(strcmp(char(runStart.scene_id),char(scene.scene_id)), ...
        'C5Train24:RunStartSceneId','run_start scene_id differs from raw scene.');
elseif isfield(runStart,'sceneMeta')&&isfield(runStart.sceneMeta,'scene_id')
    assert(strcmp(char(runStart.sceneMeta.scene_id),char(scene.scene_id)), ...
        'C5Train24:RunStartSceneId','run_start sceneMeta.scene_id differs from raw scene.');
end
end
function [opts,markerPath,markerSha]=strip_source_marker(opts,rawPath,required)
markerPath='';markerSha='';field='r2e_first_plant_step_marker';
if isfield(opts,field)
    markerPath=char(opts.(field));if ~is_absolute_path(markerPath),markerPath=fullfile(fileparts(rawPath),markerPath);end
    assert(~isempty(markerPath)&&isfile(markerPath),'C5Train24:SourcePlantMarker','Historical first-Plant marker is missing.');
    expected=fullfile(fileparts(rawPath),'plant_started.marker');
    assert(same_path(markerPath,expected),'C5Train24:SourcePlantMarker', ...
        'Historical marker is not the marker beside its pinned raw source.');
    markerSha=sha256_file(markerPath);opts=rmfield(opts,field);
elseif required
    error('C5Train24:SourcePlantMarker','Corrected T2 run_start must bind its historical marker.');
end
end
function x=strip_position_opts(x)
for f={'rbf_position_output_enabled','rbf_position_update_enabled','position_delayed_prediction_enabled', ...
        'position_coordinate_mask','stage1_position_runtime'}
    if isfield(x,f{1}),x=rmfield(x,f{1});end
end
end
function path=resolve_source_path(root,path)
path=char(path);
if ~is_absolute_path(path),path=fullfile(root,strrep(path,'/',filesep));end
assert(isfile(path),'C5Train24:MissingSource','Missing source path %s.',path);
path=char(java.io.File(path).getCanonicalPath());
end
function tf=is_absolute_path(path)
tf=~isempty(regexp(path,'^(?:[A-Za-z]:[\\/]|\\\\)','once'));
end
function tf=same_path(a,b)
tf=strcmpi(char(java.io.File(a).getCanonicalPath()),char(java.io.File(b).getCanonicalPath()));
end
function n=folder_bytes(path)
d=dir(fullfile(path,'**','*'));d=d(~[d.isdir]);if isempty(d),n=0;else,n=sum([d.bytes]);end
end
function verify_baseline_options(b,c)
fields={'formal_rbf_baseline','position_rbf_frequency_hz','attitude_rbf_frequency_hz', ...
    'rbf_phase_start','rbf_full_phase_start','rbf_position_gamma_scale','rbf_attitude_gamma_scale', ...
    'rbf_attitude_enabled','rbf_attitude_output_enabled','rbf_attitude_update_enabled','v1_adaptive'};
for k=1:numel(fields)
    f=fields{k}; assert(isfield(b,f)&&isfield(c,f)&&isequaln(b.(f),c.(f)), ...
        'MatchedProbe:CommonOption','Shared option %s differs between old B and C5.',f);
end
assert(logical(b.formal_rbf_baseline)&&logical(b.rbf_position_output_enabled)&& ...
    logical(b.rbf_position_update_enabled)&&~logical(c.rbf_position_output_enabled)&& ...
    ~logical(c.rbf_position_update_enabled)&&logical(c.position_delayed_prediction_enabled)&& ...
    isequal(double(c.position_coordinate_mask(:)),[1;1;0])&& ...
    logical(c.stage1_position_runtime.enabled)&&logical(c.stage1_position_runtime.update_enabled)&& ...
    logical(c.stage1_position_runtime.command_filter_coordination_v3_5.enabled)&& ...
    logical(c.stage1_position_runtime.position_only_search_head.enabled), ...
    'MatchedProbe:PositionPackage','B/C5 position package differs from the locked treatment.');
assert(~isfield(b,'stage1_position_runtime')&&~isfield(b,'position_coordinate_mask')&& ...
    ~isfield(b,'position_delayed_prediction_enabled'), ...
    'MatchedProbe:BPositionPackage','B options must use the original default full mask and no C5 PCF/runtime.');
end
