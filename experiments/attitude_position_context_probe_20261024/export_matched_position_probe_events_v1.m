function phaseCode=classify_phase(scene,idx)
rho=double(scene.arms.rho_true);cmd=double(scene.arms.command);phase=zeros(numel(idx),1,'uint8');
for q=1:numel(idx)
    k=idx(q);
    if ~any(abs(cmd(:))>0),code=0;
    elseif any(cmd(k,:)>0),code=2;
    elseif any(cmd(k,:)<0),code=4;
    elseif any(rho(k,:)>.150001),code=3;
    elseif any(any(abs(cmd(1:k,:))>0))&&~any(any(abs(cmd(k:end,:))>0)),code=5;
    else,code=1;end
    phase(q)=uint8(code);
end
phaseCode=phase;
end
function names=phase_code_names(code)
levels={'STATIC','PRE','EXTEND','HOLD','RETRACT','RECOVERY'};names=levels(double(code(:))+1).';
end
function assert_sha(path,expected)
assert(isfile(path)&&strcmpi(sha256_file(path),char(expected)), ...
    'ProbeExport:SHA','Missing file or SHA-256 mismatch: %s.',path);
end
function tf=same_path(a,b)
tf=strcmpi(char(java.io.File(a).getCanonicalPath()),char(java.io.File(b).getCanonicalPath()));
end
function tf=valid_sha(value)
tf=numel(value)==64&&all(isstrprop(value,'xdigit'));
end
function h=sha256_file(path)
md=java.security.MessageDigest.getInstance('SHA-256');fid=fopen(path,'rb');
assert(fid>=0,'ProbeExport:Read','Cannot read %s.',path);c=onCleanup(@()fclose(fid)); %#ok<NASGU>
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end

