function verify_baseline_options(b,c)
fields={'formal_rbf_baseline','position_rbf_frequency_hz','attitude_rbf_frequency_hz', ...
    'rbf_phase_start','rbf_full_phase_start','rbf_position_gamma_scale','rbf_attitude_gamma_scale', ...
    'rbf_attitude_enabled','rbf_attitude_output_enabled','rbf_attitude_update_enabled','v1_adaptive'};
for k=1:numel(fields)
    f=fields{k}; assert(isfield(b,f)&&isfield(c,f)&&isequaln(b.(f),c.(f)), ...
        'MatchedProbe:CommonOption','Shared option %s differs between old B and C5.',f);
end
assert(logical(b.formal_rbf_baseline)&&logical(b.rbf_position_output_enabled)&& ...
    logical(b.rbf_position_update_enabled)&&~logical(c.rbf_position_output_enabled)&& ...
    ~logical(c.rbf_position_update_enabled)&&logical(c.position_delayed_prediction_enabled)&& ...
    isequal(double(c.position_coordinate_mask(:)),[1;1;0])&& ...
    logical(c.stage1_position_runtime.enabled)&&logical(c.stage1_position_runtime.update_enabled)&& ...
    logical(c.stage1_position_runtime.command_filter_coordination_v3_5.enabled)&& ...
    logical(c.stage1_position_runtime.position_only_search_head.enabled), ...
    'MatchedProbe:PositionPackage','B/C5 position package differs from the locked treatment.');
assert(~isfield(b,'stage1_position_runtime')&&~isfield(b,'position_coordinate_mask')&& ...
    ~isfield(b,'position_delayed_prediction_enabled'), ...
    'MatchedProbe:BPositionPackage','B options must use the original default full mask and no C5 PCF/runtime.');
end
function assert_position_only_diff(rows)
allowed={'opts.rbf_position_output_enabled','opts.rbf_position_update_enabled', ...
    'opts.position_delayed_prediction_enabled','opts.position_coordinate_mask','opts.stage1_position_runtime'};
for k=1:numel(rows)
    p=rows(k).path;
    assert(any(cellfun(@(x)strcmp(p,x)||startsWith(p,[x '.']),allowed)), ...
        'MatchedProbe:UnexpectedOptsDiff','Non-position option differs: %s.',p);
end
end
