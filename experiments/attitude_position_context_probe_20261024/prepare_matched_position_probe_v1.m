function rows=leaf_diff(a,b)
aRows=flatten(a,'opts');bRows=flatten(b,'opts');paths=unique([string({aRows.path}),string({bRows.path})]);rows=repmat(struct('path','','B_value_json','','C5_value_json',''),0,1);
for k=1:numel(paths)
    p=char(paths(k));ia=find(strcmp({aRows.path},p),1);ib=find(strcmp({bRows.path},p),1);
    av='<ABSENT>';bv='<ABSENT>';if ~isempty(ia),av=aRows(ia).value_json;end;if ~isempty(ib),bv=bRows(ib).value_json;end
    if ~strcmp(av,bv),rows(end+1)=struct('path',p,'B_value_json',av,'C5_value_json',bv);end %#ok<AGROW>
end
end
function rows=flatten(x,prefix)
rows=struct('path',{},'value_json',{});
if isstruct(x)&&isscalar(x)
    f=fieldnames(x);
    for k=1:numel(f), sub=flatten(x.(f{k}),[prefix '.' f{k}]);rows=[rows sub];end %#ok<AGROW>
else
    rows=struct('path',prefix,'value_json',jsonencode(x));
end
end
