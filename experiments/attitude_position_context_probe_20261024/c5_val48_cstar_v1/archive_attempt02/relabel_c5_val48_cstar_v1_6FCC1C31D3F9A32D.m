% Direct-Cstar relabel of the pinned C5 VAL48 set; no Plant, engine, or training.
here=fileparts(mfilename('fullpath'));repoRoot=fileparts(fileparts(fileparts(here)));
manifestRel='reports/attitude_cm18_datarepair_20261024/c5_val48_c5_teacher_v3/C5_VAL48_EVENT_CACHE_MANIFEST_v3.json';
manifestSha='3e72f4726219cfd0e89476c70d24796a06c8f8447d4064cfdc471433a863a501';
candidateRel='reports/attitude_position_context_probe_20261024/C5_MATCHED_VAL_REUSE_CANDIDATES_v1.json';
candidateSha='80ef7a37cb0fff237086ccc138772c71494cacd50a916ed2dba4037d4f833494';
extractorRel='experiments/attitude_cm18_datarepair_20261024/extract_cm18_events_v1.m';
extractorSha='15d8fb369b93e3a251d70c7eb7a590f732da839d35a5bebfb2011f25123e37c1';
reportDir=fullfile(repoRoot,'reports','attitude_position_context_probe_20261024','c5_val48_cstar_v1');
cacheDir=fullfile(reportDir,'cache');
outputPath=fullfile(reportDir,'C5_VAL48_CSTAR_RELABEL_v1.json');
failurePath=fullfile(reportDir,'C5_VAL48_CSTAR_RELABEL_FAILURE_v1.json');
budgetBytes=128*1024^2;minimumFreeBytes=30*1024^3;
assert(~isfolder(reportDir)&&~isfile(outputPath)&&~isfile(failurePath), ...
    'C5ValCstar:NoOverwrite','Refusing to reuse or overwrite the output directory.');
entryPath=[mfilename('fullpath') '.m'];entrySha=sha256_file(entryPath);
result=struct('schema','CM18_C5_VAL48_CSTAR_RELABEL_MANIFEST_V1','status','INCOMPLETE', ...
    'entry_path',repo_relative(entryPath,repoRoot),'entry_sha256',entrySha, ...
    'source_manifest_path',manifestRel,'source_manifest_sha256',manifestSha, ...
    'candidate_manifest_path',candidateRel,'candidate_manifest_sha256',candidateSha, ...
    'extractor_path',extractorRel,'extractor_sha256',extractorSha, ...
    'output_directory',repo_relative(reportDir,repoRoot),'training_eligible',false, ...
    'TEST_accessed',false,'scope',struct('scene_count',48,'events_expected',48*1999, ...
    'plant_calls_during_relabel',0,'engine_calls_during_relabel',0, ...
    'optimizer_steps',0,'TEST_accessed',false,'all_events_retained',true, ...
    'X18_copied_from_bound_cache',true), ...
    'summary',struct(),'scenes',[],'global_error','');
stage='manifest_preflight';activeScene='';
try
    assert_free_space(repoRoot,minimumFreeBytes);
    manifestPath=fullfile(repoRoot,strrep(manifestRel,'/',filesep));
    candidatePath=fullfile(repoRoot,strrep(candidateRel,'/',filesep));
    assert_sha(manifestPath,manifestSha);assert_sha(candidatePath,candidateSha);
    M=jsondecode(fileread(manifestPath));C=jsondecode(fileread(candidatePath));
    assert(strcmp(M.schema,'C5_MATCHED_VAL48_EVENT_CACHE_MANIFEST_V3')&& ...
        strcmp(M.status,'PASS')&&numel(M.scenes)==48&& ...
        double(M.summary.scene_count)==48&&double(M.summary.passed)==48&& ...
        double(M.summary.failed)==0&&double(M.summary.same_source_sha_count)==32&& ...
        double(M.summary.T2_acc_fix_count)==16&&double(M.summary.attitude_event_count_expected_each)==1999&& ...
        double(M.summary.reused_v2_cache_count)==47&&double(M.summary.new_cache_count)==1&& ...
        logical(M.summary.complete_48)&&logical(M.summary.all_pass)&&~logical(M.training_eligible)&& ...
        strcmpi(M.candidate_manifest_sha256,candidateSha), ...
        'C5ValCstar:Manifest','Pinned C5 VAL48 V3 manifest/status/coverage changed.');
    assert(strcmp(C.schema,'ROOT_C5_MATCHED_VAL_REUSE_CANDIDATES_V1')&& ...
        strcmp(C.status,'CANDIDATE_METADATA_ONLY_FULL_RAW_CFG_CERTIFICATION_PENDING')&& ...
        numel(C.scenes)==48&&double(C.summary.val_candidates)==48&& ...
        double(C.summary.same_A1_B_raw_sha)==32&& ...
        double(C.summary.T2_ACC_FIX_V1_sha_different)==16&& ...
        double(C.summary.C5_new_DEV72_runs)==36&&double(C.summary.C5_reused_SCREEN12_runs)==12, ...
        'C5ValCstar:CandidateManifest','Pinned candidate metadata schema/counts changed.');
    sourceChecks=json_rows(M.source_pin_checks,'C5 manifest source pins');
    verify_candidate_pins(C,sourceChecks,repoRoot);
    extractorPath=fullfile(repoRoot,strrep(extractorRel,'/',filesep));
    assert_sha(extractorPath,extractorSha);
    coreDir=fullfile(repoRoot,'matlab','core');
    helperNames={'allocate_control','simulation_parameters','controller_parameters', ...
        'allocation_matrix','arm_mass_properties','distributed_mass_properties','arm_directions'};
    helperShas={ ...
        '5ac26d8c5ba6243f755bcf6ad3a07e98e503c213e4c95edbee7dd2c2627f3d53', ...
        '962b5434c23d5ac1a9ac568f136635a8ea651a775165d84b7d95250ca88bb9ae', ...
        '4fad5e78c0bd4177461647af167e7c86a7defa628b43d523b0b7da2ef5556398', ...
        '5886c00b3f8800301a324159e534b4c65e857cdd00392a3231af22c6dbba517d', ...
        '8ec66e107156b5219f7e41aca2464eef1ec8043eb7f67df313c0f23ef4b551f5', ...
        'db380b506e4bacc37bc398d5726c5ebd25be8ebc08b6c9e76ff59bc78fd45d3a', ...
        '517bbfcd0df9526b189f64bff067a49551f573ad96e682ee005533ab510e686c'};
    for h=1:numel(helperNames),assert_sha(fullfile(coreDir,[helperNames{h} '.m']),helperShas{h});end
    pin=C.source_pins.C5_SNAPSHOT;
    snapshotPath=resolve_path(repoRoot,char(pin.path));assert_sha(snapshotPath,char(pin.sha256));
    snapshot=load(snapshotPath,'cfg','opts','W0','modelIdentity','sourceIdentity');
    assert(all(isfield(snapshot,{'cfg','opts','W0','modelIdentity','sourceIdentity'})), ...
        'C5ValCstar:Snapshot','Pinned C5 snapshot MAT schema changed.');
    snapshotSha=char(pin.sha256);bindingSha=char(C.source_pins.C5_SOURCE_BINDING.sha256);
    snapshotPinIndex=find(cellfun(@(p)strcmp(char(p.name),'C5_SNAPSHOT'),sourceChecks));
    assert(isscalar(snapshotPinIndex)&& ...
        strcmpi(char(sourceChecks{snapshotPinIndex}.expected_sha256),snapshotSha), ...
        'C5ValCstar:SnapshotPin','C5 snapshot identity differs between candidate and C5 manifest pins.');
    sourceFileCache=containers.Map('KeyType','char','ValueType','char');
    activePaths=text_cells(snapshot.sourceIdentity.active_paths);
    activeHashes=text_cells(snapshot.sourceIdentity.active_sha256);
    assert(numel(activePaths)==32&&numel(activeHashes)==32, ...
        'C5ValCstar:ActiveSourceCount','Pinned C5 snapshot must bind its 32 active sources.');
    verify_source_entries(activePaths,activeHashes,repoRoot,sourceFileCache);
    addpath(coreDir,'-begin');addpath(fileparts(extractorPath),'-begin');
    helper1Index=find(cellfun(@(p)strcmp(char(p.name),'T2_FORMULA_HELPER_1'),sourceChecks));
    helper2Index=find(cellfun(@(p)strcmp(char(p.name),'T2_FORMULA_HELPER_2'),sourceChecks));
    assert(isscalar(helper1Index)&&isscalar(helper2Index), ...
        'C5ValCstar:T2HelperPins','T2 formula helper pins must each occur exactly once in V3 source_pin_checks.');
    helper1Path=char(sourceChecks{helper1Index}.path);
    helper2Path=char(sourceChecks{helper2Index}.path);
    helperExternal=fileparts(helper1Path);
    addpath(helperExternal,'-begin');rehash;
    for h=1:numel(helperNames)
        assert(same_path(which(helperNames{h}),fullfile(coreDir,[helperNames{h} '.m'])), ...
            'C5ValCstar:HelperResolution','Unexpected helper resolution: %s.',helperNames{h});
    end
    assert(same_path(which('extract_cm18_events_v1'),extractorPath)&& ...
        same_path(which('audit_reference_original'),helper1Path)&& ...
        same_path(which('audit_reference_fixed'),helper2Path), ...
        'C5ValCstar:ExtractorResolution','Extractor or T2 helper resolution changed.');

    manifestRows=json_rows(M.scenes,'C5 VAL48 manifest scenes');
    candidateRows=json_rows(C.scenes,'candidate manifest scenes');
    idsM=cellfun(@(r)char(string(r.scene_id)),manifestRows,'UniformOutput',false);
    idsC=cellfun(@(r)char(string(r.scene_id)),candidateRows,'UniformOutput',false);
    assert(isequal(idsM,idsC)&&numel(unique(idsM))==48&& ...
        all(startsWith(idsM,'DL1018_VAL_')), ...
        'C5ValCstar:SceneOrder','The pinned candidate and C5 manifests must contain the same ordered VAL48 set.');
    assert(~isfolder(reportDir),'C5ValCstar:NoOverwrite','Output directory appeared after preflight.');
    [ok,msg]=mkdir(cacheDir);assert(ok,'C5ValCstar:OutputCreate','Cannot create output directory: %s.',msg);
    sceneResults=cell(48,1);maxParityX=0;maxParityBehavior=0;
    commonJ0=[];commonC0=[];commonDmax=[];commonBeta=[];
    stage='val48_scene_relabel';
    for q=1:48
        row=manifestRows{q};cand=candidateRows{q};activeScene=char(string(row.scene_id));
        assert(startsWith(char(string(row.scene_id)),'DL1018_VAL_')&& ...
            strcmp(char(string(cand.split)),'VAL')&&strcmp(char(string(cand.collector)),'B')&& ...
            strcmp(char(string(row.status)),'PASS')&& ...
            any(strcmp(char(string(row.run_status)), ...
            {'RUN_COMPLETE_RAW_PENDING_AUDIT','RUN_COMPLETE_STABLE'})), ...
            'C5ValCstar:RowEligibility','Unexpected split/status for %s.',activeScene);
        sceneResult=inspect_scene(row,cand,q,repoRoot,snapshot,snapshotSha,bindingSha, ...
            manifestSha,candidateSha,extractorSha,sourceFileCache, ...
            commonJ0,commonC0,commonDmax,commonBeta);
        commonJ0=sceneResult.nominal_inertia_J0_kg_m2;
        commonC0=sceneResult.nominal_allocation_C0;
        commonDmax=sceneResult.dmax_rad_s2;
        commonBeta=sceneResult.beta_rise_time_s;
        maxParityX=max(maxParityX,sceneResult.extractor_cache_max_abs_X18_delta);
        maxParityBehavior=max(maxParityBehavior,sceneResult.extractor_cache_max_abs_behavior_target_delta_rad_s2);
        cacheName=sprintf('%02d_%s_CSTAR_V1.mat',q,regexprep(activeScene,'[^A-Za-z0-9_.-]','_'));
        cachePath=fullfile(cacheDir,cacheName);
        assert(~isfile(cachePath),'C5ValCstar:CacheExists','Refusing to overwrite cache: %s.',cachePath);
        cache=sceneResult.cache_payload; %#ok<NASGU>
        save(cachePath,'cache','-v7');
        d=dir(cachePath);sceneResult=rmfield(sceneResult,'cache_payload');
        sceneResult.cache_filename=cacheName;
        sceneResult.cache_path=repo_relative(cachePath,repoRoot);
        sceneResult.cache_sha256=sha256_file(cachePath);
        sceneResult.cache_bytes=double(d.bytes);
        sceneResult.status='PASS';sceneResult.qualified=true;
        sceneResults{q}=sceneResult;
        assert(directory_bytes(reportDir)<=budgetBytes, ...
            'C5ValCstar:Budget','New VAL48 outputs exceed the 128 MiB budget.');
    end
    stage='final_manifest';
    result.status='PASS';result.global_error='';
    result.C5_snapshot_sha256=snapshotSha;
    result.C5_source_binding_sha256=bindingSha;
    result.nominal_inertia_J0_kg_m2=commonJ0;
    result.nominal_allocation_C0=commonC0;
    result.dmax_rad_s2=commonDmax;
    result.beta_rise_time_s=commonBeta;
    result.scenes=[sceneResults{:}];
    result.summary=struct('scene_count',48,'qualified_count',48,'failed_count',0, ...
        'split_counts',struct('TRAIN',0,'VAL',48),'event_count',48*1999, ...
        'cache_bytes_total',sum([result.scenes.cache_bytes]), ...
        'within_128_MiB_budget',directory_bytes(reportDir)<=budgetBytes, ...
        'same_A1_B_raw_sha_count',32,'T2_ACC_FIX_V1_sha_different_count',16, ...
        'new_DEV72_candidate_count',36,'reused_SCREEN12_candidate_count',12, ...
        'max_extractor_cache_X18_delta',maxParityX, ...
        'max_extractor_cache_behavior_target_delta_rad_s2',maxParityBehavior, ...
        'runtime_source_caveat','36 DEV72 rows bind the pinned C5 snapshot source set; 12 reused SCREEN12 rows retain their pinned historical runtime-source identity and parent audit. This does not claim identical source bytes for all 48 runs.', ...
        'parent_event_count_semantics','The C5 parent count 1968 refers to position-inference events; every relabeled scene retains 1999 attitude events.', ...
        'training_eligible',false,'TEST_accessed',false);
    assert(result.summary.within_128_MiB_budget,'C5ValCstar:FinalBudget','Output directory exceeds the budget.');
    write_json_no_overwrite(outputPath,result);
catch ME
    result.status='INCOMPLETE';
    result.global_error=sprintf('%s: %s (stage=%s, scene=%s)',ME.identifier,ME.message,stage,activeScene);
    if isfolder(reportDir)&&~isfile(failurePath)
        write_json_no_overwrite(failurePath,result);
    end
    rethrow(ME);
end
end

function out=inspect_scene(row,cand,q,repoRoot,snapshot,snapshotSha,bindingSha,manifestSha, ...
    candidateSha,extractorSha,sourceFileCache,J0,C0,dmax,betaRise)
id=char(string(row.scene_id));candidate=cand.C5_candidate;
assert(logical(candidate.raw_exists)&&logical(candidate.reused)==logical(row.reused_screen)&& ...
    strcmp(char(candidate.parent_event_audit_status),char(row.parent_audit_status))&& ...
    strcmp(char(candidate.parent_event_audit_status),'PASS_C5_RAW_ALL_EVENTS')&& ...
    double(candidate.parent_audit_event_count)==double(row.parent_audit_event_count)&& ...
    strcmpi(char(row.parent_audit_raw_sha256),char(row.candidate_raw_sha256))&& ...
    same_path(resolve_path(repoRoot,char(row.parent_audit_raw_path)), ...
        resolve_path(repoRoot,char(candidate.raw_path)))&& ...
    strcmp(char(cand.C5_physical_B_source.classification),char(row.source_classification)), ...
    'C5ValCstar:ParentAudit','Candidate/source row lacks exact pinned parent audit or source-class binding for %s.',id);
rawPath=resolve_path(repoRoot,char(candidate.raw_path));
startPath=resolve_path(repoRoot,char(candidate.run_start_path));
statusPath=resolve_path(repoRoot,char(candidate.run_status_path));
physicalPath=resolve_path(repoRoot,char(cand.C5_physical_B_source.path));
oldCacheRel=strrep(char(row.cache_path_relative),'\','/');
assert(startsWith(oldCacheRel,'reports/attitude_cm18_datarepair_20261024/c5_val48_c5_teacher_v2/cache/')|| ...
    startsWith(oldCacheRel,'reports/attitude_cm18_datarepair_20261024/c5_val48_c5_teacher_v3/cache/'), ...
    'C5ValCstar:OldCachePath','Old cache does not resolve under the pinned C5 VAL cache roots.');
oldCachePath=resolve_path(repoRoot,oldCacheRel);
rawSha=verify_file_pin(rawPath,char(row.candidate_raw_sha256),double(row.candidate_raw_bytes),'C5 candidate raw');
startSha=verify_file_pin(startPath,char(row.candidate_run_start_sha256),[],'C5 run_start');
statusSha=verify_file_pin(statusPath,char(row.candidate_run_status_sha256),[],'C5 run_status');
physicalSha=verify_file_pin(physicalPath,char(row.physical_B_source_sha256),double(row.physical_B_source_bytes),'physical B raw');
cacheSha=verify_file_pin(oldCachePath,char(row.cache_sha256),double(row.cache_bytes),'old C5 cache');
assert(strcmpi(rawSha,char(candidate.raw_sha256))&&strcmpi(startSha,char(candidate.run_start_sha256))&& ...
    strcmpi(statusSha,char(candidate.run_status_sha256))&& ...
    strcmpi(physicalSha,char(cand.C5_physical_B_source.sha256)), ...
    'C5ValCstar:CandidatePins','Candidate manifest and C5 V3 row hashes disagree for %s.',id);
if startsWith(id,'DL1018_VAL_T2_')
    assert(strcmp(char(row.source_classification),'T2_ACC_FIX_V1_SHA_DIFFERENT')&& ...
        startsWith(char(row.t2_acc_fix_check),'PASS_ONLY_REFERENCE_ACCELERATION_YZ_CHANGED')&& ...
        ~strcmpi(char(row.a1_source_raw_sha256),physicalSha), ...
        'C5ValCstar:T2SourceClass','T2 corrected reference/source proof changed for %s.',id);
    a1Path=resolve_path(repoRoot,char(cand.A1_B_source.repo_relative_raw_path));
    verify_file_pin(a1Path,char(cand.A1_B_source.sha256),double(cand.A1_B_source.size_bytes),'T2 original B source');
    t2ReferenceProof=verify_t2_reference(a1Path,physicalPath,id);
else
    t2ReferenceProof='NOT_APPLICABLE_SAME_SOURCE_SHA';
    assert(strcmp(char(row.source_classification),'SAME_SHA_AS_A1_B_SOURCE')&& ...
        strcmpi(char(row.a1_source_raw_sha256),physicalSha), ...
        'C5ValCstar:SameSourceClass','Non-T2 physical B source is not the pinned original B raw for %s.',id);
end

status=jsondecode(fileread(statusPath));
assert(same_path(resolve_path(repoRoot,char(status.raw_path)),rawPath)&& ...
    same_path(resolve_path(repoRoot,char(status.run_start_path)),startPath)&& ...
    strcmpi(char(status.raw_sha256),rawSha)&&strcmpi(char(status.run_start_sha256),startSha)&& ...
    strcmp(char(status.status),char(row.run_status))&& ...
    any(strcmp(char(status.status),{'RUN_COMPLETE_RAW_PENDING_AUDIT','RUN_COMPLETE_STABLE'}))&& ...
    strcmp(char(status.scene_id),id)&&strcmp(char(status.log_status),'STABLE')&& ...
    double(status.transitions)==20000&&double(status.state_samples)==20001&& ...
    isempty(strtrim(char(string(status.safety_stop_reason))))&& ...
    double(status.plant_calls)==1&&double(status.training_steps)==0&& ...
    double(status.optimizer_steps)==0&&~logical(status.TEST_accessed), ...
    'C5ValCstar:RunStatus','C5 run_status is not a completed stable 20-second record for %s.',id);
if isfield(status,'raw_bytes')&&isnumeric(status.raw_bytes)&&isscalar(status.raw_bytes)
    d=dir(rawPath);assert(double(status.raw_bytes)==double(d.bytes), ...
        'C5ValCstar:RunStatusBytes','run_status raw size differs for %s.',id);
end
verify_file_pin(char(status.first_plant_step_marker_path),char(status.first_plant_step_marker_sha256), ...
    [],'historical C5 first-Plant marker');
physicalStatusSha='';
if isfield(status,'physical_B_source_sha256')
    physicalStatusSha=char(status.physical_B_source_sha256);
    assert(strcmp(char(row.status_physical_B_source_identity_basis),'RUN_STATUS_PHYSICAL_B_SOURCE_SHA256'), ...
        'C5ValCstar:PhysicalStatusBasis','Unexpected run_status physical-source identity basis for %s.',id);
else
    assert(logical(candidate.reused)&&strcmp(id,'DL1018_VAL_T2_C00_W10')&& ...
        strcmp(char(row.run_start_schema),'C5_AXIS_COORDINATE_RUN_START_V1'), ...
        'C5ValCstar:LegacyPhysicalSource','Missing physical-source status hash is only allowed for the pinned legacy T2 row.');
    assert(strcmp(char(row.status_physical_B_source_identity_basis), ...
        'LEGACY_T2_C00_W10_RUN_START_SCENE_RAW_SHA256'), ...
        'C5ValCstar:LegacyPhysicalBasis','Unexpected legacy physical-source identity basis for %s.',id);
end

loadedStart=load(startPath,'runStart');
assert(isfield(loadedStart,'runStart')&&isscalar(loadedStart.runStart), ...
    'C5ValCstar:RunStartMat','Pinned run_start MAT lacks a scalar runStart struct for %s.',id);
runStart=loadedStart.runStart;
assert(isfield(runStart,'schema')&&strcmp(char(runStart.schema),char(row.run_start_schema)), ...
    'C5ValCstar:RunStartSchema','run_start schema differs from V3 manifest for %s.',id);
switch char(row.run_start_schema)
    case 'C5_AXIS_COORDINATE_DEV72_RUN_START_V3'
        assert(isfield(runStart,'source_paths')&&isfield(runStart,'source_sha256'), ...
            'C5ValCstar:RunStartV3','DEV72 V3 source identity fields are missing.');
    case 'C5_TAIL11_RUN_START_V2'
        assert(isfield(runStart,'source_identity')&& ...
            strcmp(char(string(row.runtime_source_identity_type)),'REUSED_SCREEN_RUN_START_SOURCE_IDENTITY'), ...
            'C5ValCstar:RunStartV2','Reused SCREEN12 V2 source identity fields are missing.');
    case 'C5_AXIS_COORDINATE_RUN_START_V1'
        assert(strcmp(id,'DL1018_VAL_T2_C00_W10')&&isfield(runStart,'scene_raw_sha256'), ...
            'C5ValCstar:RunStartV1','Legacy V1 schema is only allowed for T2_C00_W10.');
    otherwise
        error('C5ValCstar:RunStartSchema','Unsupported pinned run_start schema %s.',char(row.run_start_schema));
end
assert(isfield(runStart,'cfg')&&isequaln(runStart.cfg,snapshot.cfg)&& ...
    isfield(runStart,'opts'),'C5ValCstar:RunStartCfg','run_start cfg/options differ or are missing for %s.',id);
if ~isempty(physicalStatusSha)
    assert(strcmpi(physicalStatusSha,char(row.physical_B_source_sha256)), ...
        'C5ValCstar:PhysicalStatusHash','run_status physical B source differs for %s.',id);
else
    assert(strcmpi(char(runStart.scene_raw_sha256),char(row.physical_B_source_sha256)), ...
        'C5ValCstar:PhysicalLegacyHash','Legacy run_start source SHA differs for %s.',id);
end
sharedOpts={'formal_rbf_baseline','attitude_rbf_frequency_hz','rbf_phase_start', ...
    'rbf_full_phase_start','rbf_attitude_gamma_scale','rbf_attitude_enabled', ...
    'rbf_attitude_output_enabled','rbf_attitude_update_enabled','v1_adaptive'};
for j=1:numel(sharedOpts)
    name=sharedOpts{j};
    assert(isfield(runStart.opts,name)&&isfield(snapshot.opts,name)&& ...
        isequaln(runStart.opts.(name),snapshot.opts.(name)), ...
        'C5ValCstar:SharedAttitudeOpts','Shared attitude option %s differs for %s.',name,id);
end
[w0Exact,~,w0Proof]=verify_model_W0(runStart,snapshot);
assert(w0Exact,'C5ValCstar:PositionW0','Initial C5 position-model W0 differs for %s.',id);
[sourceType,sourceCorePath,sourceCoreSha,activeCount]=verify_run_source_identity( ...
    runStart,row,snapshot,repoRoot,sourceFileCache);

raw=load(rawPath,'scene','log');
physical=load(physicalPath,'scene');
assert(all(isfield(raw,{'scene','log'}))&&isfield(physical,'scene'), ...
    'C5ValCstar:RawSchema','C5 raw or physical source lacks scene/log for %s.',id);
runtimeId=char(string(row.candidate_raw_scene_id));
assert(strcmp(char(string(raw.scene.scene_id)),runtimeId), ...
    'C5ValCstar:RuntimeScene','Embedded C5 scene id changed for %s.',id);
[sourceAliasOK,sourceAlias]=scene_alias(physical.scene.scene_id,id);
[candidateAliasOK,candidateAlias]=scene_alias(raw.scene.scene_id,id);
assert(sourceAliasOK&&candidateAliasOK, ...
    'C5ValCstar:SceneAlias','Physical/C5 scene IDs are not canonical or the pinned ACC_FIX alias for %s.',id);
physicalScene=physical.scene;candidateScene=raw.scene;
physicalScene.scene_id=id;candidateScene.scene_id=id;
assert(isempty(scene_diff_paths(candidateScene,physicalScene,'scene')), ...
    'C5ValCstar:EmbeddedScene','C5 embedded full scene differs from its pinned physical B source for %s.',id);
log=raw.log;
assert(isfield(log,'status')&&strcmp(char(string(log.status)),'STABLE')&& ...
    isfield(log,'safety_stop_reason')&&isempty(strtrim(char(string(log.safety_stop_reason))))&& ...
