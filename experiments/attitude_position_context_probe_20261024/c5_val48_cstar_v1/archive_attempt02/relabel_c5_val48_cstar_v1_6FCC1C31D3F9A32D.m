    'C5ValCstar:SourceIdentityType','Runtime source identity type differs for %s.',char(row.scene_id));
end

function [ok,shaExpected,proof]=verify_model_W0(R,snapshot)
expected=snapshot.modelIdentity;shaExpected=char(expected.W0_sha256);
proof=struct('basis','RUN_START_MODEL_IDENTITY','legacy_nested_model_exact',false, ...
    'legacy_model_metadata_exact',false,'legacy_normalizer_arrays_exact',false, ...
    'legacy_runtime_weight_exact',false,'legacy_head_W0_exact',false);
if isfield(R,'model_identity')
    actual=R.model_identity;ok=true;
    names={'model_id','W0_sha256','normalizer_arrays_sha256','selected_step'};
    for k=1:numel(names)
        name=names{k};if ~isfield(actual,name)||~isequaln(actual.(name),expected.(name)),ok=false;end
    end
    if isfield(R,'W0'),ok=ok&&isequaln(R.W0,snapshot.W0);
    elseif isfield(R,'opts')&&isfield(R.opts,'stage1_position_runtime')&& ...
            isfield(R.opts.stage1_position_runtime,'position_only_search_head')&& ...
            isfield(R.opts.stage1_position_runtime.position_only_search_head,'W0')
        ok=ok&&isequaln(R.opts.stage1_position_runtime.position_only_search_head.W0,snapshot.W0);
    else,ok=false;
    end
    if isfield(R,'initial_W0_sha256'),ok=ok&&strcmpi(char(R.initial_W0_sha256),shaExpected);end
    if isfield(R,'W0_sha256'),ok=ok&&strcmpi(char(R.W0_sha256),shaExpected);end
    return
end
allowed=isfield(R,'scene_id')&&strcmp(char(R.scene_id),'DL1018_VAL_T2_C00_W10')&& ...
    isfield(R,'schema')&&strcmp(char(R.schema),'C5_AXIS_COORDINATE_RUN_START_V1')&& ...
    isfield(R,'opts')&&isfield(R.opts,'stage1_position_runtime')&& ...
    isfield(snapshot.opts,'stage1_position_runtime');
