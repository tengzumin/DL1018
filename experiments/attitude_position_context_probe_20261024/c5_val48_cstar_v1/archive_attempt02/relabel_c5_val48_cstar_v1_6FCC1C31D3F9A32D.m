function sha=sha256_file(path)
fid=fopen(path,'rb');assert(fid>=0,'C5ValCstar:FileOpen','Cannot open input: %s.',path);
c=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true
    bytes=fread(fid,1024*1024,'*uint8');if isempty(bytes),break;end
    md.update(bytes);
end
raw=typecast(md.digest(),'uint8');sha=lower(reshape(dec2hex(raw,2).',1,[]));
end

