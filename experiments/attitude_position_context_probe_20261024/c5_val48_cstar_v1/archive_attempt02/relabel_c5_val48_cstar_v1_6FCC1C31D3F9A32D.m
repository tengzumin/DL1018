function diffs=scene_diff_paths(a,b,prefix)
diffs={};if isequaln(a,b),return;end
if isstruct(a)&&isstruct(b)
    if ~isequal(size(a),size(b)),diffs={[prefix '<shape>']};return;end
    fa=sort(fieldnames(a));fb=sort(fieldnames(b));
    if ~isequal(fa,fb),diffs={[prefix '<fields>']};return;end
    for q=1:numel(a)
        for j=1:numel(fa),name=fa{j};diffs=[diffs scene_diff_paths(a(q).(name),b(q).(name),[prefix '.' name])];end %#ok<AGROW>
    end
elseif iscell(a)&&iscell(b)
    if ~isequal(size(a),size(b)),diffs={[prefix '<shape>']};return;end
    for q=1:numel(a),diffs=[diffs scene_diff_paths(a{q},b{q},sprintf('%s{%d}',prefix,q))];end %#ok<AGROW>
else,diffs={prefix};end
end

