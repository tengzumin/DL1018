assert(isequal(diffs,{'scene.reference.acceleration'})&&isequaln(old.time,fixed.time), ...
    'C5ValCstar:T2Diff','T2 corrected source differs outside reference.acceleration.');
t=double(old.time(:));ro=audit_reference_original('FIG8_3D',t);rf=audit_reference_fixed('FIG8_3D',t);
