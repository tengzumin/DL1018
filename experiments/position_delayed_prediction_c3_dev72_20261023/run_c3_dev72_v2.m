    strcmpi(prep.source_lock_sha256,sourceLockSha)&&strcmpi(prep.snapshot_sha256,snapshotSha)&& ...
    double(prep.B_scene_files_sha_and_schema_checked)==72&&double(prep.C2_cfg_opts_records_checked)==12&& ...
    strcmpi(lock.source_files.runner.sha256,runnerSha), ...
    'C3D72:PreparedBinding','Prepared source/input lock or no-Plant results differ.');
