    strcmp(release.state,'APPROVED_C3_DEV72_V2')&&logical(release.plant_authorized)&& ...
    double(release.max_new_Plant)==60&&isequal(cellstr(string(release.scene_ids(:))),cellstr(string(lock.scene_ids_new_60(:))))&& ...
    strcmpi(release.authorization_sha256,lock.authorization_and_scope_refs.authorization.sha256)&& ...
    strcmpi(release.input_lock_sha256,sourceLockSha)&&strcmpi(release.contract_sha256,contractSha)&& ...
