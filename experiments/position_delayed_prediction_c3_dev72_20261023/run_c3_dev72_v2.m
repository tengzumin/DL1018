function secondsEstimate=estimated_scene_seconds(reuseRows)
durations=zeros(1,numel(reuseRows));
for k=1:numel(reuseRows)
    r=reuseRows(k).C3_reuse; a=dir(r.run_start_path); b=dir(r.raw_path);
    assert(numel(a)==1&&numel(b)==1,'C3D72:DurationEstimate','Cannot estimate a C3 scene duration from frozen run files.');
    durations(k)=max(0,(b.datenum-a.datenum)*86400);
end
assert(any(durations>0),'C3D72:DurationEstimate','Frozen C3 run-file timestamps do not support a scene-time estimate.');
secondsEstimate=1.5*max(durations);
end
function assert_time_for_one_scene(deadline,secondsEstimate)
remaining=seconds(deadline-datetime('now','TimeZone','UTC'));
assert(remaining>=secondsEstimate,'C3D72:Deadline','Less than one estimated C3 scene runtime remains before the authorized hard deadline.');
end
