    double(release.new_training)==0&&~logical(release.parameter_or_seed_search)&& ...
    double(release.new_B_sorties)==0&&~logical(release.TEST_authorized), ...
    'C3D72:Release','Parent release does not authorize this exact fixed 60-scene runner.');
