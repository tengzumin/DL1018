        runRows{end+1}=runStatus; %#ok<AGROW>
        progress.status='SCENE_COMPLETE_RAW_PENDING_AUDIT'; progress.completed_scene_count=numel(runRows);
        progress.runs=runRows; progress.current_scene_index_1based=si; progress.updated_utc=utc_now();
        write_json_replace(progressPath,progress);
    catch ME
        failed=struct('schema','C3_DELAYED_PREDICTION_DEV72_FAILURE_V1','status','FAILED_NO_RETRY', ...
            'scene_index_1based',si,'scene_id',sceneId,'identifier',ME.identifier,'message',ME.message, ...
            'failed_utc',utc_now(),'attempt_dir',attemptDir,'plant_invocation_entered',invocationEntered, ...
            'plant_start_confirmed',isfile(plantMarker),'plant_calls',double(invocationEntered), ...
            'raw_path',rawPath,'partial_raw_preserved',isfile(rawPath),'partial_raw_sha256',file_sha_if_exists(rawPath), ...
            'run_start_sha256',file_sha_if_exists(runStartPath),'input_lock_sha256',sourceLockSha, ...
            'release_sha256',releaseSha,'attempt_bytes_at_failure',directory_bytes(attemptDir), ...
            'experiment_bytes_at_failure',directory_bytes(here));
        write_json_new(failurePath,failed); progress.status='FAILED_NO_RETRY';
        progress.current_scene_index_1based=si; progress.completed_scene_count=numel(runRows);
        progress.runs=runRows; progress.failure=failed; progress.updated_utc=utc_now();
        write_json_replace(progressPath,progress); rethrow(ME);
    end
end
progress.status='ALL_60_COMPLETE_RAW_PENDING_AUDIT'; progress.completed_scene_count=60;
progress.runs=runRows; progress.updated_utc=utc_now(); write_json_replace(progressPath,progress);
write_json_new(summaryPath,progress);
end

function [paths,hashes]=active_source_inventory(lock)
base=lock.c3_source_lock; paths={}; hashes={};
for k=1:numel(base.frozen_runtime_files)
    item=base.frozen_runtime_files(k); [~,n,e]=fileparts(char(item.path)); leaf=[n e]; role='';
    if strcmpi(leaf,'run_dl1018_closed_loop.m'), role='runtime_core'; end
    if strcmpi(leaf,'run_episode_dl1018.m'), role='episode_wrapper'; end
    if isempty(role), path=char(item.path); hash=char(item.sha256);
    else
        ix=find(strcmp({lock.source_files.isolated_c3_sources.role},role));
        assert(numel(ix)==1,'C3D72:SourceInventory','Expected one local %s source.',role);
        path=char(lock.source_files.isolated_c3_sources(ix).path); hash=char(lock.source_files.isolated_c3_sources(ix).sha256);
    end
    paths{end+1}=path; hashes{end+1}=hash; %#ok<AGROW>
end
ix=find(strcmp({lock.source_files.isolated_c3_sources.role},'prediction_helper'));
assert(numel(ix)==1,'C3D72:SourceInventory','Expected one local prediction helper.');
paths{end+1}=char(lock.source_files.isolated_c3_sources(ix).path); hashes{end+1}=char(lock.source_files.isolated_c3_sources(ix).sha256);
for k=1:numel(base.frozen_plant_files), paths{end+1}=char(base.frozen_plant_files(k).path); hashes{end+1}=char(base.frozen_plant_files(k).sha256); end %#ok<AGROW>
end
function add_active_paths(paths)
for k=1:numel(paths), [~,~,e]=fileparts(paths{k}); if strcmpi(e,'.m'), addpath(fileparts(paths{k}),'-end'); end, end
end
function path=source_path(items,name)
if isstruct(items)&&isfield(items,'role')&&any(strcmp({items.role},name))
    idx=find(strcmp({items.role},name));
else
    names=cell(size(items)); for k=1:numel(items), [~,n,e]=fileparts(char(items(k).path)); names{k}=[n e]; end
    idx=find(strcmp(names,name));
end
assert(numel(idx)==1,'C3D72:SourceName','Expected one locked source %s.',name); path=char(items(idx).path);
end
function ok=valid_scene(s,sceneId)
ok=isstruct(s)&&isfield(s,'scene_id')&&(strcmp(char(s.scene_id),sceneId)||strcmp(char(s.scene_id),[sceneId '_ACC_FIX_V1']))&& ...
    isfield(s,'time')&&numel(s.time)==20001&&abs(double(s.time(1)))<=1e-12&&abs(double(s.time(end))-20)<=1e-12&& ...
    isfield(s,'environment_wind_I')&&isequal(size(s.environment_wind_I),[20001,3])&&isfield(s,'initial_state')&&numel(s.initial_state)==12&& ...
    isfield(s,'arms')&&all(isfield(s.arms,{'command','rhoDot_hat','rhoDot_true','rho_hat','rho_true'}))&&isfield(s,'reference')&& ...
    all(isfield(s.reference,{'position','velocity','acceleration','yaw','yaw_rate','yaw_acceleration'}))&& ...
    isequal(size(s.reference.position),[20001,3])&&isequal(size(s.reference.velocity),[20001,3])&& ...
