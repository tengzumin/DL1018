    verify_file(r.raw_path,r.scope_raw_sha256); verify_file(r.status_path,r.scope_status_sha256);
    verify_file(r.run_start_path,r.run_start_sha256); verify_file(r.first_plant_step_marker_path,r.first_plant_step_marker_sha256);
    s=jsondecode(fileread(r.status_path));
