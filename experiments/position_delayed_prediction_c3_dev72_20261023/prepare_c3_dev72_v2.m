function result=prepare_c3_dev72_v2()
% No-Plant setup: verify frozen candidate identity and all 72 physical scenes.
here=fileparts(mfilename('fullpath')); repoRoot=fileparts(fileparts(here));
lockPath=fullfile(here,'C3_DEV72_INPUT_LOCK_v2.json'); contractPath=fullfile(here,'C3_DEV72_RUN_CONTRACT_v2.json');
resultPath=fullfile(here,'C3_DEV72_PREPARE_RESULT_v2.json'); snapshotPath=fullfile(here,'C3_DEV72_PREPARED_CONFIG_OPTS_v2.mat');
assert(isfile(lockPath)&&isfile(contractPath)&&~isfile(resultPath)&&~isfile(snapshotPath), ...
    'C3D72:NoOverwrite','Input lock/contract must exist and PREPARE outputs must be absent.');
lock=jsondecode(fileread(lockPath)); contract=jsondecode(fileread(contractPath));
assert(strcmp(lock.schema,'C3_DELAYED_PREDICTION_DEV72_INPUT_LOCK_V1')&& ...
    strcmp(lock.state,'LOCKED_INPUTS_AND_SOURCES_NO_PLANT_PARENT_REVIEW_REQUIRED')&& ...
    ~logical(lock.plant_authorized_by_this_lock)&& ...
    strcmp(contract.schema,'C3_DELAYED_PREDICTION_DEV72_RUN_CONTRACT_V1')&& ...
    double(contract.authorization.max_new_Plant)==60&&double(contract.authorization.new_training)==0&& ...
    ~logical(contract.authorization.TEST_authorized)&&~logical(contract.execution.plant_authorized_by_this_contract), ...
    'C3D72:Scope','Locked DEV72 scope or authorization differs.');
verify_ref(lock.source_files.runner); verify_ref(lock.source_files.prepare_entry);
assert(same_path(lock.source_files.runner.path,[here filesep 'run_c3_dev72_v2.m'])&& ...
    same_path(lock.source_files.prepare_entry.path,[mfilename('fullpath') '.m']), ...
    'C3D72:EntryPath','Runner or PREPARE path differs from the lock.');
verify_ref(lock.source_files.contract); verify_ref(lock.authorization_and_scope_refs.authorization);
verify_ref(lock.authorization_and_scope_refs.taskbook); verify_ref(lock.authorization_and_scope_refs.scope);
verify_ref(lock.historical_review_refs.history_manifest); verify_ref(lock.historical_review_refs.history_review);
verify_ref(lock.historical_review_refs.b_scene_payload_review);
refNames=fieldnames(lock.c3_reference_refs);
for k=1:numel(refNames), verify_ref(lock.c3_reference_refs.(refNames{k})); end
for k=1:numel(lock.shared_input_files), verify_ref(lock.shared_input_files(k)); end

c3lock=jsondecode(fileread(lock.c3_reference_refs.c3_source_lock.path));
prep=jsondecode(fileread(lock.c3_reference_refs.c3_prepare_result.path));
assert(strcmp(prep.status,'PREPARED_WAIT_PARENT_PROBE_RELEASE')&&double(prep.plant_calls)==0&& ...
    strcmpi(prep.cfg_opts_snapshot_sha256,lock.c3_reference_refs.c3_snapshot.sha256), ...
    'C3D72:C3Preparation','Frozen C3 preparation identity is not the reviewed no-Plant snapshot.');
snapshotPathC3=lock.c3_reference_refs.c3_snapshot.path;
verify_file(snapshotPathC3,lock.c3_reference_refs.c3_snapshot.sha256);
pack=load(snapshotPathC3,'cfg','opts','W0','modelIdentity','sceneIdentity','sourceIdentity');
assert(all(isfield(pack,{'cfg','opts','W0','modelIdentity','sceneIdentity','sourceIdentity'}))&& ...
    logical(pack.opts.position_delayed_prediction_enabled), ...
    'C3D72:Snapshot','Frozen C3 config/options/model snapshot is incomplete.');

auth=jsondecode(fileread(lock.authorization_and_scope_refs.authorization.path));
assert(strcmp(auth.status,'USER_AUTHORIZED_MAX_60_FROZEN_C3_DEV72_SORTIES')&& ...
    double(auth.max_new_Plant)==60&&double(auth.reuse_C3_screen_sorties)==12&& ...
    double(auth.total_development_unique_scenes)==72&&double(auth.fixed_tau_s)==1&& ...
    abs(double(auth.fixed_rho)-0.01)<eps&&double(auth.new_training)==0&& ...
    ~logical(auth.parameter_or_seed_search)&&double(auth.new_B_sorties)==0&&~logical(auth.TEST_authorized), ...
    'C3D72:UserAuthorization','Active user authorization does not cover this fixed scope.');
sceneIdsFromRows={lock.scenes.scene_id}; sceneIdsFromRows=cellstr(string(sceneIdsFromRows(:)));
assert(isequal(sceneIdsFromRows(:),cellstr(string(lock.scene_ids_all_72(:))))&& ...
    numel(lock.scenes)==72&&numel(lock.scene_ids_new_60)==60&&numel(lock.scene_ids_reuse_12)==12, ...
    'C3D72:SceneInventory','Frozen 72-scene inventory is inconsistent.');

% Restore the exact locked runtime path after init_dl1018, which resets MATLAB paths.
runtimeFiles=c3lock.frozen_runtime_files; plantFiles=c3lock.frozen_plant_files;
initPath=source_path(runtimeFiles,'init_dl1018.m'); optionsPath=source_path(runtimeFiles,'position_only_search_options.m');
headPath=source_path(runtimeFiles,'position_only_search_head_step.m'); forwardPath=source_path(runtimeFiles,'position_stage1_model_forward_v2.m');
activeLock=lock; activeLock.c3_source_lock=c3lock;
[activePaths,activeHashes]=active_source_inventory(activeLock);
add_active_paths(activePaths); addpath(fullfile(repoRoot,'matlab','runtime'),'-end'); addpath(fullfile(repoRoot,'matlab','core'),'-end');
addpath(fileparts(initPath),'-begin'); clear init_dl1018; rehash;
assert(same_path(which('init_dl1018'),initPath),'C3D72:InitPath','init_dl1018 resolves outside the frozen source.');
[cfg,~,resolvedRoot]=init_dl1018();
assert(same_path(resolvedRoot,repoRoot),'C3D72:ProjectRoot','Frozen runtime resolved a different repository root.');
add_active_paths(activePaths); addpath(fullfile(repoRoot,'matlab','runtime'),'-end'); addpath(fullfile(repoRoot,'matlab','core'),'-end');
addpath(fileparts(optionsPath),'-begin'); addpath(fileparts(headPath),'-begin'); addpath(fileparts(forwardPath),'-begin'); addpath(here,'-begin');
clear run_episode_dl1018 run_dl1018_closed_loop delayed_prediction_step_candidate position_only_search_options ...
    position_only_search_head_step position_stage1_model_forward_v2 init_dl1018;
rehash;
sourcePaths=activePaths; sourceHashes=activeHashes;
for k=1:numel(sourcePaths)
    [~,n,e]=fileparts(sourcePaths{k}); verify_file(sourcePaths{k},sourceHashes{k});
    if strcmpi(e,'.m'), assert(same_path(which(n),sourcePaths{k}),'C3D72:WhichShadow','Locked source %s resolves to a shadow.',n); end
end
assert(same_path(which('init_dl1018'),initPath)&&same_path(which('position_only_search_options'),optionsPath)&& ...
    same_path(which('position_only_search_head_step'),headPath)&&same_path(which('position_stage1_model_forward_v2'),forwardPath), ...
    'C3D72:CandidatePath','Frozen C1 runtime function resolved to a shadow.');

% Reconstruct the candidate options and compare to the frozen snapshot.
modelMat=source_path(lock.shared_input_files,'model_mat');
modelPack=load(modelMat,'model'); assert(isfield(modelPack,'model')&&isstruct(modelPack.model),'C3D72:Model','Frozen model variable absent.');
model=modelPack.model; W0=double(model.output_W);
assert(isequal(size(W0),[33,3])&&all(isfinite(W0(:)))&& ...
    strcmpi(hash_bytes(typecast(W0(:),'uint8')),lock.candidate_identity.W0_sha256)&& ...
    strcmp(char(model.model_id),'DSSM14')&&double(model.seed)==2026102001&& ...
    double(model.selected_step)==60000&&double(model.input_dim)==14&&double(model.window)==32, ...
    'C3D72:ModelIdentity','Frozen X14 model/W0 identity differs.');
normalizerHash=hash_normalizer_arrays(model);
assert(strcmpi(normalizerHash,lock.candidate_identity.normalizer_arrays_sha256), ...
    'C3D72:NormalizerIdentity','Frozen X14 normalizer arrays differ.');
opts=position_only_search_options(cfg,model,'FEATURE',12,1); opts.position_delayed_prediction_enabled=true;
assert(isequaln(cfg,pack.cfg)&&isequaln(opts,pack.opts)&& ...
    isequal(double(pack.W0),W0)&&strcmpi(normalizerHash,pack.modelIdentity.normalizer_arrays_sha256), ...
    'C3D72:CandidateConfig','Current frozen runtime does not reconstruct the reviewed cfg/opts/W0.');

% Check cfg/opts against every available C2 run_start. The C2 scene-2 recovery row stays FAILED_NO_RETRY.
c2Rows=c3lock.c2_baseline_runs; assert(numel(c2Rows)==12,'C3D72:C2Inventory','Expected twelve locked C2 run_start records.');
for k=1:numel(c2Rows)
    verify_file(c2Rows(k).run_start_path,c2Rows(k).run_start_sha256);
    c2=load(c2Rows(k).run_start_path,'runStart');
    assert(isfield(c2,'runStart')&&all(isfield(c2.runStart,{'cfg','opts'})), ...
        'C3D72:C2RunStart','C2 cfg/opts missing for %s.',c2Rows(k).scene_id);
    old=c2.runStart.opts; base=opts;
    if isfield(old,'r2e_first_plant_step_marker'), old=rmfield(old,'r2e_first_plant_step_marker'); end
    if isfield(base,'r2e_first_plant_step_marker'), base=rmfield(base,'r2e_first_plant_step_marker'); end
    if isfield(old,'position_delayed_prediction_enabled'), old=rmfield(old,'position_delayed_prediction_enabled'); end
    if isfield(base,'position_delayed_prediction_enabled'), base=rmfield(base,'position_delayed_prediction_enabled'); end
    assert(isequaln(c2.runStart.cfg,cfg)&&isequaln(old,base), ...
        'C3D72:C2ConfigOpts','Candidate cfg/opts differ from frozen C2 run_start for %s.',c2Rows(k).scene_id);
end

% Check actual scene IDs, time grids, shape/finite values and source SHA for all 72 fixed inputs.
sceneIdentity=repmat(struct('scene_id','','raw_scene_id','','canonical_scene_id','','alias_normalized_in_memory',false, ...
    'B_raw_path','','B_raw_sha256','','payload_review_sha256',''),1,72);
for k=1:72
    row=lock.scenes(k); verify_file(row.B_source.path,row.B_source.sha256);
    assert(same_path(row.B_source.path,row.b_scene_to_scored_log.path)&& ...
        strcmpi(row.B_source.sha256,row.b_scene_to_scored_log.sha256)&&numel(row.b_scene_to_scored_log.matching_fields)==14, ...
        'C3D72:BReviewBinding','B source does not match the independently reviewed physical-input identity for %s.',row.scene_id);
    d=load(row.B_source.path,'scene'); assert(isfield(d,'scene'),'C3D72:SceneMissing','No scene in %s.',row.B_source.path);
    s=d.scene; rawId=char(s.scene_id); canonical=char(row.scene_id);
    assert(valid_scene(s,canonical),'C3D72:SceneIdentity','B source scene fails frozen schema/time/alias check: %s.',canonical);
    sceneIdentity(k)=struct('scene_id',canonical,'raw_scene_id',rawId,'canonical_scene_id',canonical, ...
        'alias_normalized_in_memory',~strcmp(rawId,canonical),'B_raw_path',char(row.B_source.path), ...
        'B_raw_sha256',char(row.B_source.sha256),'payload_review_sha256',char(lock.historical_review_refs.b_scene_payload_review.sha256));
    if ~isempty(row.C3_reuse)
        assert(same_path(row.C3_reuse.scope_raw_path,row.C3_reuse.raw_path)&& ...
            strcmpi(row.C3_reuse.scope_raw_sha256,row.C3_reuse.raw_sha256)&& ...
            strcmpi(row.C3_reuse.scope_status_sha256,row.C3_reuse.status_sha256), ...
            'C3D72:ReuseScopeAnchor','C3 reuse path/hash differs from the frozen scope row: %s.',canonical);
        verify_file(row.C3_reuse.raw_path,row.C3_reuse.scope_raw_sha256);
        verify_file(row.C3_reuse.status_path,row.C3_reuse.scope_status_sha256);
        verify_file(row.C3_reuse.status_path,row.C3_reuse.status_sha256);
        verify_file(row.C3_reuse.run_start_path,row.C3_reuse.run_start_sha256);
        verify_file(row.C3_reuse.first_plant_step_marker_path,row.C3_reuse.first_plant_step_marker_sha256);
        reuseStatus=jsondecode(fileread(row.C3_reuse.status_path));
        assert(strcmpi(row.C3_reuse.B_raw_sha256,row.B_source.sha256)&& ...
            strcmpi(row.C3_reuse.raw_sha256,reuseStatus.raw_sha256)&& ...
            strcmp(reuseStatus.status,'RUN_COMPLETE_RAW_PENDING_AUDIT')&& ...
            strcmp(reuseStatus.log_status,'STABLE')&&double(reuseStatus.plant_calls)==1, ...
            'C3D72:ReuseBinding','C3 reused run input/status differs from the locked B source: %s.',canonical);
    end
end

sourceIdentity=struct('runner',lock.source_files.runner.path,'runner_sha256',lock.source_files.runner.sha256, ...
    'prepare_entry',lock.source_files.prepare_entry.path,'prepare_entry_sha256',lock.source_files.prepare_entry.sha256, ...
    'source_paths',{sourcePaths},'source_sha256',{sourceHashes},'which_checks',numel(sourcePaths));
modelIdentity=pack.modelIdentity; modelIdentity.W0_sha256=lock.candidate_identity.W0_sha256;
save(snapshotPath,'cfg','opts','W0','modelIdentity','sourceIdentity','sceneIdentity','-v7.3');
result=struct('schema','C3_DELAYED_PREDICTION_DEV72_PREPARE_RESULT_V1', ...
    'status','PREPARED_NO_PLANT_WAIT_PARENT_RELEASE','created_utc',utc_now(), ...
    'source_lock_path',lockPath,'source_lock_sha256',sha256_file(lockPath), ...
    'contract_path',contractPath,'contract_sha256',sha256_file(contractPath), ...
    'runner_path',lock.source_files.runner.path,'runner_sha256',lock.source_files.runner.sha256, ...
    'snapshot_path',snapshotPath,'snapshot_sha256',sha256_file(snapshotPath), ...
    'candidate_condition_id',contract.candidate_condition_id,'tau_s',1,'rho',0.01, ...
    'scene_ids_all_72',{lock.scene_ids_all_72},'scene_ids_new_60',{lock.scene_ids_new_60}, ...
    'scene_ids_reuse_12',{lock.scene_ids_reuse_12},'scene_identity',sceneIdentity, ...
    'cfg_opts_matches_all_available_C2_run_start',true,'C2_cfg_opts_records_checked',12, ...
    'B_scene_files_sha_and_schema_checked',72,'B_physical_inputs_bound_to_scored_log_review',true, ...
    'which_checks',numel(sourcePaths),'plant_calls',0,'run_episode_called',false, ...
    'training_steps',0,'optimizer_steps',0,'parameter_or_seed_search',false, ...
    'new_B_sorties',0,'TEST_accessed',false);
write_json_new(resultPath,result);
end

function add_active_paths(paths)
for q=1:numel(paths), [~,~,ext]=fileparts(paths{q}); if strcmpi(ext,'.m'), addpath(fileparts(paths{q}),'-end'); end, end
end
function path=source_path(items,role)
if isstruct(items)&&isfield(items,'role')&&any(strcmp({items.role},role))
    idx=find(strcmp({items.role},role)); assert(numel(idx)==1,'C3D72:SourceRole','Expected one source role %s.',role);
else
    names=cell(size(items));
    for k=1:numel(items), [~,b,e]=fileparts(char(items(k).path)); names{k}=[b e]; end
    idx=find(strcmp(names,role)); assert(numel(idx)==1,'C3D72:SourceName','Expected one source file %s.',role);
end
path=char(items(idx).path);
end
function [paths,hashes]=active_source_inventory(lock)
base=lock.c3_source_lock; paths={}; hashes={};
for k=1:numel(base.frozen_runtime_files)
    item=base.frozen_runtime_files(k); [~,n,e]=fileparts(char(item.path)); leaf=[n e]; role='';
    if strcmpi(leaf,'run_dl1018_closed_loop.m'), role='runtime_core'; end
    if strcmpi(leaf,'run_episode_dl1018.m'), role='episode_wrapper'; end
    if isempty(role), path=char(item.path); hash=char(item.sha256);
    else
        ix=find(strcmp({lock.source_files.isolated_c3_sources.role},role));
        assert(numel(ix)==1,'C3D72:SourceInventory','Expected one local %s source.',role);
        path=char(lock.source_files.isolated_c3_sources(ix).path); hash=char(lock.source_files.isolated_c3_sources(ix).sha256);
    end
    paths{end+1}=path; hashes{end+1}=hash; %#ok<AGROW>
end
ix=find(strcmp({lock.source_files.isolated_c3_sources.role},'prediction_helper'));
assert(numel(ix)==1,'C3D72:SourceInventory','Expected one local prediction helper.');
paths{end+1}=char(lock.source_files.isolated_c3_sources(ix).path); hashes{end+1}=char(lock.source_files.isolated_c3_sources(ix).sha256);
for k=1:numel(base.frozen_plant_files)
    paths{end+1}=char(base.frozen_plant_files(k).path); hashes{end+1}=char(base.frozen_plant_files(k).sha256); %#ok<AGROW>
end
end
function ok=valid_scene(s,sceneId)
ok=isstruct(s)&&isfield(s,'scene_id')&& ...
    (strcmp(char(s.scene_id),sceneId)||strcmp(char(s.scene_id),[sceneId '_ACC_FIX_V1']))&& ...
    isfield(s,'time')&&numel(s.time)==20001&&abs(double(s.time(1)))<=1e-12&&abs(double(s.time(end))-20)<=1e-12&& ...
    isfield(s,'environment_wind_I')&&isequal(size(s.environment_wind_I),[20001,3])&& ...
    isfield(s,'initial_state')&&numel(s.initial_state)==12&&isfield(s,'arms')&& ...
    all(isfield(s.arms,{'command','rhoDot_hat','rhoDot_true','rho_hat','rho_true'}))&&isfield(s,'reference')&& ...
    all(isfield(s.reference,{'position','velocity','acceleration','yaw','yaw_rate','yaw_acceleration'}))&& ...
    isequal(size(s.reference.position),[20001,3])&&isequal(size(s.reference.velocity),[20001,3])&& ...
    isequal(size(s.reference.acceleration),[20001,3])&&isequal(size(s.reference.yaw),[20001,1])&& ...
    isequal(size(s.reference.yaw_rate),[20001,1])&&isequal(size(s.reference.yaw_acceleration),[20001,1])&& ...
    isequal(size(s.arms.command),[20001,4])&&isequal(size(s.arms.rhoDot_hat),[20001,4])&& ...
    isequal(size(s.arms.rhoDot_true),[20001,4])&&isequal(size(s.arms.rho_hat),[20001,4])&& ...
    isequal(size(s.arms.rho_true),[20001,4])&&all(isfinite(s.time(:)))&& ...
    all(isfinite(s.environment_wind_I(:)))&&all(isfinite(s.initial_state(:)))&& ...
    all(isfinite(s.arms.command(:)))&&all(isfinite(s.arms.rhoDot_hat(:)))&&all(isfinite(s.arms.rhoDot_true(:)))&& ...
    all(isfinite(s.arms.rho_hat(:)))&&all(isfinite(s.arms.rho_true(:)))&& ...
    all(isfinite(s.reference.position(:)))&&all(isfinite(s.reference.velocity(:)))&& ...
    all(isfinite(s.reference.acceleration(:)))&&all(isfinite(s.reference.yaw(:)))&& ...
    all(isfinite(s.reference.yaw_rate(:)))&&all(isfinite(s.reference.yaw_acceleration(:)));
end
function verify_ref(item), verify_file(item.path,item.sha256); end
function verify_file(path,expected)
assert(isfile(path),'C3D72:MissingFile','Missing frozen file: %s.',path);
assert(strcmpi(sha256_file(path),expected),'C3D72:SHA','SHA-256 mismatch: %s.',path);
end
function h=sha256_file(path)
md=java.security.MessageDigest.getInstance('SHA-256'); fid=fopen(path,'r'); assert(fid>=0,'C3D72:ReadFile','Cannot read %s.',path);
c=onCleanup(@()fclose(fid)); while true, b=fread(fid,8*1024*1024,'*uint8'); if isempty(b), break; end; md.update(b); end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
function h=hash_bytes(bytes)
md=java.security.MessageDigest.getInstance('SHA-256'); md.update(typecast(uint8(bytes(:)),'int8'));
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
function h=hash_normalizer_arrays(model)
md=java.security.MessageDigest.getInstance('SHA-256');
for name={'input_mu','input_sigma'}
    field=name{1}; a=reshape(double(model.(field)),1,[]);
    assert(numel(a)==14&&all(isfinite(a)),'C3D72:NormalizerShape','Invalid %s.',field);
    header=[field char(0) '((1, 14), ''float64'')' char(0)];
    md.update(typecast(uint8(unicode2native(header,'UTF-8')),'int8')); md.update(typecast(a(:),'int8'));
end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
function tf=same_path(a,b), tf=strcmpi(char(java.io.File(a).getCanonicalPath()),char(java.io.File(b).getCanonicalPath())); end
function write_json_new(path,value)
assert(~isfile(path),'C3D72:NoOverwrite','Refusing to overwrite %s.',path);
fid=fopen(path,'w'); assert(fid>=0,'C3D72:WriteFile','Cannot create %s.',path); c=onCleanup(@()fclose(fid)); fwrite(fid,jsonencode(value),'char');
end
function t=utc_now(), t=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z''')); end
