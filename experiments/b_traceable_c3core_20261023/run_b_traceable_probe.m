function runStatus=run_b_traceable_probe(mode)
% One release-bound B run; never execute without explicit parent approval.
if nargin~=1||~strcmpi(char(mode),'PARENT_APPROVED_B_PROBE')
    error('BTRACE:Mode','Pass exactly PARENT_APPROVED_B_PROBE after parent review.');
end
here=fileparts(mfilename('fullpath')); repoRoot=fileparts(fileparts(here));
lockPath=fullfile(here,'B_TRACEABLE_INPUT_LOCK.json'); contractPath=fullfile(here,'B_TRACEABLE_RUN_CONTRACT.json');
releasePath=fullfile(here,'B_TRACEABLE_RELEASE.json'); preparePath=fullfile(here,'B_TRACEABLE_PREPARE_RESULT.json');
snapshotPath=fullfile(here,'B_TRACEABLE_PREPARED_CFG_OPTS.mat');
assert(all([isfile(lockPath),isfile(contractPath),isfile(releasePath),isfile(preparePath),isfile(snapshotPath)]), ...
    'BTRACE:ReleaseInputs','Parent release and all frozen no-Plant inputs are required.');
lock=jsondecode(fileread(lockPath)); contract=jsondecode(fileread(contractPath));
release=jsondecode(fileread(releasePath)); prep=jsondecode(fileread(preparePath));
lockSha=sha256_file(lockPath); contractSha=sha256_file(contractPath); releaseSha=sha256_file(releasePath);
prepareSha=sha256_file(preparePath); snapshotSha=sha256_file(snapshotPath);
runnerPath=[mfilename('fullpath') '.m']; runnerSha=sha256_file(runnerPath);
assert(strcmp(release.schema,'B_TRACEABLE_C3CORE_RELEASE_V1')&& ...
    strcmp(release.state,'APPROVED_B_TRACEABLE_C3CORE_PROBE')&&logical(release.plant_authorized)&& ...
    double(release.max_new_Plant)==1&&strcmpi(release.input_lock_sha256,lockSha)&& ...
    strcmpi(release.contract_sha256,contractSha)&&strcmpi(release.prepare_result_sha256,prepareSha)&& ...
    strcmpi(release.cfg_opts_snapshot_sha256,snapshotSha)&&strcmpi(release.runner_sha256,runnerSha)&& ...
    same_path(release.runner_path,runnerPath)&&strcmp(release.scene_id,lock.scene_id)&& ...
    strcmpi(release.scene_raw_sha256,lock.scene_raw_sha256), ...
    'BTRACE:Release','Release does not bind this exact one-scene runner/input/snapshot.');
assert(strcmp(lock.state,'LOCKED_SINGLE_SCENE_NO_PLANT_PARENT_REVIEW_REQUIRED')&& ...
    strcmp(prep.status,'PREPARED_NO_PLANT_WAIT_PARENT_RELEASE')&&prep.plant_calls==0&& ...
    prep.run_episode_called==false&&prep.TEST_accessed==false&& ...
    strcmpi(prep.input_lock_sha256,lockSha)&&strcmpi(prep.snapshot_sha256,snapshotSha)&& ...
    strcmpi(lock.source_files.runner.sha256,runnerSha), ...
    'BTRACE:PreparedBinding','Frozen no-Plant setup differs from the release binding.');
verify_ref(lock.source_files.runner); verify_ref(lock.source_files.prepare_entry);
verify_ref(lock.source_files.contract); verify_ref(lock.source_files.input_lock_builder);
refs=fieldnames(lock.upstream_refs); for k=1:numel(refs), verify_ref(lock.upstream_refs.(refs{k})); end
for k=1:numel(lock.active_source_inventory), verify_ref(lock.active_source_inventory(k)); end
verify_file(lock.scene_raw_path,lock.scene_raw_sha256);
verify_file(lock.scene_scored_log_path,lock.scene_scored_log_sha256);
verify_file(lock.c3_source_lock.path,lock.c3_source_lock.sha256);

attemptRoot=fullfile(here,'runs_b'); attemptDir=fullfile(attemptRoot,lock.scene_id,contract.collector_tag,'attempt_01');
assert(~isfolder(attemptDir)&&(~isfolder(attemptRoot)||isempty(dir(fullfile(attemptRoot,'**','attempt_started.marker'))))&& ...
    (~isfolder(attemptRoot)||isempty(dir(fullfile(attemptRoot,'**','first_plant_step.marker')))), ...
    'BTRACE:NoRetry','A prior attempt/Plant marker exists; refusing to rerun.');
auth=jsondecode(fileread(lock.upstream_refs.authorization.path));
deadline=datetime(char(auth.original_deadline_utc),'InputFormat',"yyyy-MM-dd'T'HH:mm:ss'Z'",'TimeZone','UTC');
assert(deadline>datetime('now','TimeZone','UTC')&& ...
    double(java.io.File(repoRoot).getUsableSpace())>=double(lock.resource_limits.minimum_free_bytes), ...
    'BTRACE:ResourceDeadline','Hard deadline or free-space floor has been reached.');
assert(directory_bytes(here)+1e6<double(lock.resource_limits.max_output_bytes), ...
    'BTRACE:OutputReserve','Not enough output budget remains for one traceable B run.');

% Resolve and recheck the full active C3 source inventory after init_dl1018 resets MATLAB paths.
active=lock.active_source_inventory; initPath=source_path(active,'init_dl1018.m'); optionsPath=source_path(active,'controller_options_dl1018.m');
add_active_paths(active); addpath(fullfile(repoRoot,'matlab','runtime'),'-end'); addpath(fullfile(repoRoot,'matlab','core'),'-end');
addpath(fileparts(initPath),'-begin'); addpath(fileparts(optionsPath),'-begin'); addpath(here,'-begin');
clear init_dl1018 controller_options_dl1018 run_episode_dl1018 run_dl1018_closed_loop; rehash;
assert(same_path(which('init_dl1018'),initPath)&&same_path(which('controller_options_dl1018'),optionsPath), ...
    'BTRACE:InitPath','Frozen init/options source resolves to a shadow.');
[cfg,optsInit,resolvedRoot]=init_dl1018();
assert(same_path(resolvedRoot,repoRoot),'BTRACE:ProjectRoot','Runtime resolved a different project root.');
add_active_paths(active); addpath(fullfile(repoRoot,'matlab','runtime'),'-end'); addpath(fullfile(repoRoot,'matlab','core'),'-end');
addpath(fileparts(initPath),'-begin'); addpath(fileparts(optionsPath),'-begin'); addpath(here,'-begin');
clear controller_options_dl1018 run_episode_dl1018 run_dl1018_closed_loop; rehash;
for k=1:numel(active)
    item=active(k); [~,name,ext]=fileparts(item.path);
    if strcmpi(ext,'.m'), assert(same_path(which(name),item.path),'BTRACE:WhichShadow','Active source %s resolves to a shadow.',name); end
end
assert(same_path(which('run_episode_dl1018'),source_path(active,'run_episode_dl1018.m'))&& ...
    same_path(which('run_dl1018_closed_loop'),source_path(active,'run_dl1018_closed_loop.m')), ...
    'BTRACE:RuntimePath','Frozen C3 wrapper/core resolution changed.');
pack=load(snapshotPath,'cfg','opts','sceneIdentity','sourceIdentity');
assert(all(isfield(pack,{'cfg','opts','sceneIdentity','sourceIdentity'})), ...
    'BTRACE:Snapshot','Prepared cfg/options/identity snapshot is incomplete.');
opts=controller_options_dl1018(cfg,'B');
assert(isequaln(cfg,pack.cfg)&&isequaln(opts,pack.opts)&&isequaln(optsInit,opts), ...
    'BTRACE:CfgOptsChanged','Fresh B config/options differ from the no-Plant snapshot.');
scenePack=load(lock.scene_raw_path,'scene'); scene=scenePack.scene; rawId=char(scene.scene_id);
assert(valid_scene(scene,lock.scene_id)&&strcmp(rawId,pack.sceneIdentity.raw_scene_id)&& ...
    strcmpi(lock.scene_raw_sha256,pack.sceneIdentity.B_raw_sha256), ...
    'BTRACE:SceneChanged','B scene no longer matches the no-Plant identity.');
scene.scene_id=char(lock.scene_id);
assert(~isfield(opts,'stage1_position_runtime')&&~isfield(opts,'position_delayed_prediction_enabled')&& ...
    logical(opts.rbf_position_output_enabled)&&logical(opts.rbf_position_update_enabled), ...
    'BTRACE:NotBaselineB','B options include candidate state or disable baseline position RBF.');

% Try the existing shared heavy-job lock; never wait by seizing or interrupting another run.
assert(isfile(lock.shared_heavy_job_lock_path),'BTRACE:SharedLockMissing','Shared heavy-job lock is missing.');
raf=java.io.RandomAccessFile(lock.shared_heavy_job_lock_path,'rw'); channel=raf.getChannel(); jobLock=channel.tryLock();
assert(~isempty(jobLock),'BTRACE:ConcurrentHeavyJob','Shared heavy-job lock is already held.');
cleanup=onCleanup(@()release_job_lock(jobLock,channel,raf)); %#ok<NASGU>
if ~isfolder(attemptDir), mkdir(attemptDir); end
markerPath=fullfile(attemptDir,'first_plant_step.marker'); rawPath=fullfile(attemptDir,'raw_run.mat');
runStartPath=fullfile(attemptDir,'run_start.mat'); statusPath=fullfile(attemptDir,'run_status.json');
failurePath=fullfile(attemptDir,'B_TRACEABLE_FAILURE.json');
assert(~isfile(markerPath)&&~isfile(rawPath)&&~isfile(runStartPath)&&~isfile(statusPath)&&~isfile(failurePath), ...
    'BTRACE:NoOverwrite','Attempt output already exists.');
opts.r2e_first_plant_step_marker=markerPath; startedUtc=utc_now(); invocationEntered=false;
runStart=struct('schema','B_TRACEABLE_C3CORE_RUN_START_V1','scene_id',lock.scene_id, ...
    'source_scene_id',rawId,'condition',contract.collector_tag,'runtime_method',contract.method, ...
    'started_utc',startedUtc,'release_sha256',releaseSha,'input_lock_sha256',lockSha, ...
    'prepare_result_sha256',prepareSha,'cfg_opts_snapshot_sha256',snapshotSha, ...
    'scene_identity',pack.sceneIdentity,'source_identity',pack.sourceIdentity, ...
    'source_paths',{pack.sourceIdentity.source_paths},'source_sha256',{pack.sourceIdentity.source_sha256}, ...
    'runner_path',runnerPath,'runner_sha256',runnerSha,'cfg',cfg,'opts',opts, ...
    'plant_calls_before_invocation',0,'training_steps',0,'optimizer_steps',0,'TEST_accessed',false);
save(runStartPath,'runStart','-v7.3');
write_text(fullfile(attemptDir,'attempt_started.marker'),[startedUtc newline 'ABOUT_TO_CALL_EPISODE' newline]);
try
    invocationEntered=true;
    clear run_dl1018_closed_loop;
    log=run_episode_dl1018(scene,contract.collector_tag,cfg,opts,rawPath);
    assert(isfile(rawPath)&&isfile(markerPath),'BTRACE:PlantOutput','Episode returned without raw or first-Plant marker.');
    runIdentity=struct('schema','B_TRACEABLE_C3CORE_RUN_IDENTITY_V1','scene_id',lock.scene_id, ...
        'collector_tag',contract.collector_tag,'runtime_method',contract.method,'release_sha256',releaseSha, ...
        'input_lock_sha256',lockSha,'prepare_result_sha256',prepareSha,'scene_raw_sha256',lock.scene_raw_sha256, ...
        'external_identity_sha256',lock.scene_external_identity_sha256,'runner_sha256',runnerSha, ...
        'training_steps',0,'optimizer_steps',0,'TEST_accessed',false);
    save(rawPath,'runIdentity','-append');
    rawSha=sha256_file(rawPath); runStartSha=sha256_file(runStartPath); markerSha=sha256_file(markerPath);
    finiteLog=isfield(log,'state')&&all(isfinite(log.state(:)))&&isfield(log,'reference')&& ...
        all(isfinite(log.reference.position(:)))&&all(isfinite(log.time(:)));
    complete=strcmpi(log.status,'STABLE')&&isempty(char(log.safety_stop_reason))&& ...
        double(log.last_transition)==20000&&numel(log.transition_time)==20000&&numel(log.time)==20001&&finiteLog;
    stateLabel='FAILED_NO_RETRY'; if complete, stateLabel='RUN_COMPLETE_RAW_PENDING_AUDIT'; end
    runStatus=struct('schema','B_TRACEABLE_C3CORE_RUN_STATUS_V1','status',stateLabel, ...
        'scene_id',lock.scene_id,'source_scene_id',rawId,'collector_tag',contract.collector_tag, ...
        'runtime_method',contract.method,'log_status',log.status,'safety_stop_reason',log.safety_stop_reason, ...
        'last_transition',double(log.last_transition),'transitions',numel(log.transition_time), ...
        'state_samples',numel(log.time),'raw_path',rawPath,'raw_sha256',rawSha,'raw_bytes',double(dir(rawPath).bytes), ...
        'run_start_path',runStartPath,'run_start_sha256',runStartSha,'first_plant_step_marker_path',markerPath, ...
        'first_plant_step_marker_sha256',markerSha,'release_sha256',releaseSha,'input_lock_sha256',lockSha, ...
        'prepare_result_sha256',prepareSha,'cfg_opts_snapshot_sha256',snapshotSha, ...
        'scene_raw_sha256',lock.scene_raw_sha256,'external_identity_sha256',lock.scene_external_identity_sha256, ...
        'plant_invocation_entered',true,'plant_start_confirmed',true,'plant_calls',1, ...
        'training_steps',0,'optimizer_steps',0,'parameter_or_seed_search',false,'TEST_accessed',false, ...
        'output_bytes_after_raw',directory_bytes(here),'created_utc',utc_now());
    if runStatus.output_bytes_after_raw+1e6>double(lock.resource_limits.max_output_bytes)
        runStatus.status='FAILED_NO_RETRY';
        runStatus.failure_reason='Output budget exceeded after raw; raw retained.';
    end
    write_json_new(statusPath,runStatus);
    assert(strcmp(runStatus.status,'RUN_COMPLETE_RAW_PENDING_AUDIT'), ...
        'BTRACE:UnsafeStop','B run is incomplete/non-STABLE or exceeds the output cap; raw/status retained, no retry.');
catch ME
    failed=struct('schema','B_TRACEABLE_C3CORE_FAILURE_V1','status','FAILED_NO_RETRY', ...
        'scene_id',lock.scene_id,'identifier',ME.identifier,'message',ME.message,'failed_utc',utc_now(), ...
        'attempt_dir',attemptDir,'plant_invocation_entered',invocationEntered, ...
        'plant_start_confirmed',isfile(markerPath),'plant_calls',double(invocationEntered), ...
        'raw_path',rawPath,'partial_raw_preserved',isfile(rawPath),'partial_raw_sha256',file_sha_if_exists(rawPath), ...
        'run_start_sha256',file_sha_if_exists(runStartPath),'input_lock_sha256',lockSha,'release_sha256',releaseSha, ...
        'attempt_bytes_at_failure',directory_bytes(attemptDir),'experiment_bytes_at_failure',directory_bytes(here));
    if ~isfile(failurePath), write_json_new(failurePath,failed); end
    rethrow(ME);
end
end

function add_active_paths(items)
for k=1:numel(items), [~,~,ext]=fileparts(items(k).path); if strcmpi(ext,'.m'), addpath(fileparts(items(k).path),'-end'); end, end
end
function path=source_path(items,name)
names=cell(1,numel(items)); for k=1:numel(items), [~,n,e]=fileparts(items(k).path); names{k}=[n e]; end
idx=find(strcmpi(names,name)); assert(numel(idx)==1,'BTRACE:SourceName','Expected exactly one source %s.',name); path=items(idx).path;
end
function ok=valid_scene(s,sceneId)
ok=isstruct(s)&&isfield(s,'scene_id')&&(strcmp(char(s.scene_id),sceneId)||strcmp(char(s.scene_id),[sceneId '_ACC_FIX_V1']))&& ...
    isfield(s,'time')&&numel(s.time)==20001&&abs(double(s.time(1)))<=1e-12&&abs(double(s.time(end))-20)<=1e-12&& ...
    isfield(s,'environment_wind_I')&&isequal(size(s.environment_wind_I),[20001,3])&&isfield(s,'initial_state')&&numel(s.initial_state)==12&& ...
    isfield(s,'arms')&&all(isfield(s.arms,{'command','rhoDot_hat','rhoDot_true','rho_hat','rho_true'}))&&isfield(s,'reference')&& ...
    all(isfield(s.reference,{'position','velocity','acceleration','yaw','yaw_rate','yaw_acceleration'}))&& ...
    isequal(size(s.reference.position),[20001,3])&&isequal(size(s.reference.velocity),[20001,3])&& ...
    isequal(size(s.reference.acceleration),[20001,3])&&isequal(size(s.reference.yaw),[20001,1])&& ...
    isequal(size(s.reference.yaw_rate),[20001,1])&&isequal(size(s.reference.yaw_acceleration),[20001,1])&& ...
    isequal(size(s.arms.command),[20001,4])&&isequal(size(s.arms.rhoDot_hat),[20001,4])&& ...
    isequal(size(s.arms.rhoDot_true),[20001,4])&&isequal(size(s.arms.rho_hat),[20001,4])&&isequal(size(s.arms.rho_true),[20001,4])&& ...
    all(isfinite(s.time(:)))&&all(isfinite(s.environment_wind_I(:)))&&all(isfinite(s.initial_state(:)))&& ...
    all(isfinite(s.arms.command(:)))&&all(isfinite(s.arms.rhoDot_hat(:)))&&all(isfinite(s.arms.rhoDot_true(:)))&& ...
    all(isfinite(s.arms.rho_hat(:)))&&all(isfinite(s.arms.rho_true(:)))&&all(isfinite(s.reference.position(:)))&& ...
    all(isfinite(s.reference.velocity(:)))&&all(isfinite(s.reference.acceleration(:)))&&all(isfinite(s.reference.yaw(:)))&& ...
    all(isfinite(s.reference.yaw_rate(:)))&&all(isfinite(s.reference.yaw_acceleration(:)));
end
function verify_ref(item), verify_file(item.path,item.sha256); end
function verify_file(path,expected)
assert(isfile(path),'BTRACE:MissingFile','Missing frozen file: %s.',path);
assert(strcmpi(sha256_file(path),expected),'BTRACE:SHA','SHA-256 mismatch: %s.',path);
end
function h=sha256_file(path)
md=java.security.MessageDigest.getInstance('SHA-256'); fid=fopen(path,'r'); assert(fid>=0,'BTRACE:ReadFile','Cannot read %s.',path); c=onCleanup(@()fclose(fid)); %#ok<NASGU>
while true, b=fread(fid,8*1024*1024,'*uint8'); if isempty(b), break; end; md.update(typecast(b,'int8')); end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
function n=directory_bytes(path)
n=0; if ~isfolder(path), return; end; d=dir(fullfile(path,'**','*')); for k=1:numel(d), if ~d(k).isdir, n=n+double(d(k).bytes); end, end
end
function h=file_sha_if_exists(path), if isfile(path), h=sha256_file(path); else, h=''; end, end
function tf=same_path(a,b), tf=strcmpi(char(java.io.File(a).getCanonicalPath()),char(java.io.File(b).getCanonicalPath())); end
function write_text(path,value), fid=fopen(path,'w'); assert(fid>=0,'BTRACE:Write','Cannot create %s.',path); c=onCleanup(@()fclose(fid)); fwrite(fid,value,'char'); end
function write_json_new(path,value), assert(~isfile(path),'BTRACE:NoOverwrite','Refusing to overwrite %s.',path); write_text(path,jsonencode(value)); end
function t=utc_now(), t=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z''')); end
function release_job_lock(lock,channel,raf), try, lock.release(); catch, end; try, channel.close(); catch, end; try, raf.close(); catch, end, end