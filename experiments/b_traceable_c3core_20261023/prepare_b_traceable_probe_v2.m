function result=prepare_b_traceable_probe_v2()
% No-Plant setup for one traceable B reconstruction under the frozen C3 runtime.
here=fileparts(mfilename('fullpath')); repoRoot=fileparts(fileparts(here));
lockPath=fullfile(here,'B_TRACEABLE_INPUT_LOCK_v2.json'); contractPath=fullfile(here,'B_TRACEABLE_RUN_CONTRACT_v2.json');
resultPath=fullfile(here,'B_TRACEABLE_PREPARE_RESULT_v2.json'); snapshotPath=fullfile(here,'B_TRACEABLE_PREPARED_CFG_OPTS_v2.mat');
assert(isfile(lockPath)&&isfile(contractPath)&&~isfile(resultPath)&&~isfile(snapshotPath), ...
    'BTRACE:NoOverwrite','Input lock/contract must exist and prepare outputs must be absent.');
lock=jsondecode(fileread(lockPath)); contract=jsondecode(fileread(contractPath));
assert(strcmp(lock.schema,'B_TRACEABLE_C3CORE_INPUT_LOCK_V2')&& ...
    strcmp(lock.state,'LOCKED_SINGLE_SCENE_NO_PLANT_PARENT_REVIEW_REQUIRED_V2')&& ...
    ~logical(lock.plant_authorized_by_this_lock)&& ...
    strcmp(contract.schema,'B_TRACEABLE_C3CORE_CONTRACT_V2')&& ...
    strcmp(contract.scene_id,lock.scene_id)&&strcmp(contract.scene_id,'DL1018_VAL_T2_C00_W10')&& ...
    contract.limits.max_new_Plant==1&&contract.limits.max_output_bytes==134217728&& ...
    contract.limits.minimum_free_bytes==30000000000, ...
    'BTRACE:Scope','Single-scene B scope differs from its fixed contract.');
assert(same_path(lock.source_files.runner.path,[here filesep 'run_b_traceable_probe_v2.m'])&& ...
    same_path(lock.source_files.prepare_entry.path,[mfilename('fullpath') '.m'])&& ...
    same_path(lock.source_files.contract.path,contractPath), ...
    'BTRACE:EntryIdentity','Runner, prepare or contract path differs from frozen lock.');
verify_ref(lock.source_files.runner); verify_ref(lock.source_files.prepare_entry);
verify_ref(lock.source_files.contract); verify_ref(lock.source_files.input_lock_builder);
refNames=fieldnames(lock.upstream_refs);
for k=1:numel(refNames), verify_ref(lock.upstream_refs.(refNames{k})); end
assert(numel(lock.active_source_inventory)==32&&lock.source_counts.matlab==31&&lock.source_counts.mat==1, ...
    'BTRACE:SourceCount','Expected the locked 32-file C3 source inventory.');
for k=1:numel(lock.active_source_inventory), verify_ref(lock.active_source_inventory(k)); end

c3Dev72Lock=jsondecode(fileread(lock.upstream_refs.c3_dev72_input_lock.path));
c3Dev72Prep=jsondecode(fileread(lock.upstream_refs.c3_dev72_prepare_result.path));
assert(strcmp(c3Dev72Prep.status,'PREPARED_NO_PLANT_WAIT_PARENT_RELEASE')&& ...
    c3Dev72Prep.plant_calls==0&&c3Dev72Prep.run_episode_called==false&& ...
    c3Dev72Prep.TEST_accessed==false&& ...
    strcmpi(c3Dev72Prep.snapshot_sha256,lock.upstream_refs.c3_dev72_prepared_snapshot.sha256), ...
    'BTRACE:C3Preparation','Frozen C3 no-Plant config identity is missing or changed.');
rowIx=find(strcmp({c3Dev72Lock.scenes.scene_id},lock.scene_id));
assert(numel(rowIx)==1,'BTRACE:SceneRow','Fixed scene is absent or ambiguous in the reviewed C3 DEV72 lock.');
row=c3Dev72Lock.scenes(rowIx);
assert(strcmp(row.candidate_action,'REUSE_C3_SCREEN')&& ...
    same_path(row.B_source.path,lock.scene_raw_path)&&strcmpi(row.B_source.sha256,lock.scene_raw_sha256)&& ...
    same_path(row.b_scene_to_scored_log.path,lock.scene_scored_log_path)&& ...
    strcmpi(row.b_scene_to_scored_log.sha256,lock.scene_scored_log_sha256)&& ...
    numel(row.b_scene_to_scored_log.matching_fields)==14&& ...
    strcmpi(row.external_identity_sha256,lock.scene_external_identity_sha256), ...
    'BTRACE:SceneSourceBinding','B scene/source differs from frozen DEV72 physical-input review.');

% Match the fresh effective config to the locked C3 snapshot, then construct B options from scratch.
packC3=load(lock.upstream_refs.c3_dev72_prepared_snapshot.path,'cfg');
assert(isfield(packC3,'cfg')&&isstruct(packC3.cfg),'BTRACE:C3Snapshot','Frozen snapshot lacks cfg.');
active=lock.active_source_inventory; initPath=source_path(active,'init_dl1018.m');
optionsPath=source_path(active,'controller_options_dl1018.m');
corePath=source_path(active,'run_dl1018_closed_loop.m');
forwardPath=source_path(active,'position_stage1_model_forward_v2.m');
headPath=source_path(active,'position_only_search_head_step.m');
c3CoreDir=fileparts(corePath); archiveDirs=unique({fileparts(forwardPath),fileparts(headPath),fileparts(source_path(active,'position_only_search_options.m'))},'stable');
add_active_paths(active); addpath(fullfile(repoRoot,'matlab','runtime'),'-end');
addpath(fullfile(repoRoot,'matlab','core'),'-end');
addpath(fileparts(initPath),'-begin'); addpath(fileparts(optionsPath),'-begin');
for di=1:numel(archiveDirs), addpath(archiveDirs{di},'-begin'); end
addpath(c3CoreDir,'-begin'); addpath(here,'-begin');
clear init_dl1018 controller_options_dl1018 run_episode_dl1018 run_dl1018_closed_loop; rehash;
assert(same_path(which('init_dl1018'),initPath)&& ...
    same_path(which('controller_options_dl1018'),optionsPath), ...
    'BTRACE:InitPath','Frozen init/options source resolves to a shadow.');
[cfg,optsInit,resolvedRoot]=init_dl1018();
assert(same_path(resolvedRoot,repoRoot)&&isequaln(cfg,packC3.cfg), ...
    'BTRACE:ConfigMismatch','Fresh effective cfg differs from the frozen C3 prepared cfg.');
add_active_paths(active); addpath(fullfile(repoRoot,'matlab','runtime'),'-end');
addpath(fullfile(repoRoot,'matlab','core'),'-end');
addpath(fileparts(initPath),'-begin'); addpath(fileparts(optionsPath),'-begin');
for di=1:numel(archiveDirs), addpath(archiveDirs{di},'-begin'); end
addpath(c3CoreDir,'-begin'); addpath(here,'-begin');
clear controller_options_dl1018 run_episode_dl1018 run_dl1018_closed_loop; rehash;
for k=1:numel(active)
    item=active(k); [~,name,ext]=fileparts(item.path);
    if strcmpi(ext,'.m')
        assert(same_path(which(name),item.path),'BTRACE:WhichShadow','Active source %s resolves to a shadow.',name);
    end
end
assert(same_path(which('init_dl1018'),initPath)&& ...
    same_path(which('controller_options_dl1018'),optionsPath)&& ...
    same_path(which('run_episode_dl1018'),source_path(active,'run_episode_dl1018.m'))&& ...
    same_path(which('run_dl1018_closed_loop'),source_path(active,'run_dl1018_closed_loop.m')), ...
    'BTRACE:RuntimePath','Fresh runtime/wrapper/core paths do not match the lock.');
opts=controller_options_dl1018(cfg,'B');
assert(isequaln(opts,optsInit)&& ...
    logical(opts.rbf_position_output_enabled)&&logical(opts.rbf_position_update_enabled)&& ...
    logical(opts.rbf_attitude_enabled)&&logical(opts.rbf_attitude_output_enabled)&& ...
    logical(opts.rbf_attitude_update_enabled)&&double(opts.position_rbf_frequency_hz)==100&& ...
    double(opts.attitude_rbf_frequency_hz)==100&&~logical(opts.v1_adaptive), ...
    'BTRACE:BOptions','Fresh B opts do not match the baseline contract.');
for name={'stage1_position_runtime','position_only_search','position_delayed_prediction_enabled', ...
        'position_search','pcf','position_pcf','delayed_prediction'}
    assert(field_is_false_or_absent(opts,name{1}),'BTRACE:CandidateOption','B opts enable candidate option %s.',name{1});
end

verify_file(lock.scene_raw_path,lock.scene_raw_sha256);
scenePack=load(lock.scene_raw_path,'scene');
assert(isfield(scenePack,'scene')&&valid_scene(scenePack.scene,lock.scene_id), ...
    'BTRACE:SceneSchema','Frozen B source scene fails the complete C2 scene schema/time/alias contract.');
scene=scenePack.scene; rawSceneId=char(scene.scene_id); scene.scene_id=char(lock.scene_id);
sceneIdentity=struct('scene_id',char(lock.scene_id),'raw_scene_id',rawSceneId, ...
    'canonical_scene_id',char(lock.scene_id),'alias_normalized_in_memory',~strcmp(rawSceneId,char(lock.scene_id)), ...
    'alias_rule','C2 valid_scene: canonical scene ID or canonical ID plus _ACC_FIX_V1', ...
    'B_raw_path',lock.scene_raw_path,'B_raw_sha256',lock.scene_raw_sha256, ...
    'external_identity_sha256',lock.scene_external_identity_sha256, ...
    'B_scored_log_path',lock.scene_scored_log_path,'B_scored_log_sha256',lock.scene_scored_log_sha256, ...
    'matching_fields',{lock.scene_matching_fields});
sourcePaths={lock.active_source_inventory.path}; sourceHashes={lock.active_source_inventory.sha256};
sourceIdentity=struct('input_lock_path',lockPath,'input_lock_sha256',sha256_file(lockPath), ...
    'runner_path',lock.source_files.runner.path,'runner_sha256',lock.source_files.runner.sha256, ...
    'prepare_entry_path',lock.source_files.prepare_entry.path,'prepare_entry_sha256',lock.source_files.prepare_entry.sha256, ...
    'source_paths',{sourcePaths},'source_sha256',{sourceHashes},'which_checks',31);

attemptRoot=fullfile(here,'runs_b');
assert(~isfolder(attemptRoot),'BTRACE:NoOverwrite','B attempt root already exists.');
assert(~isfile(fullfile(here,'B_TRACEABLE_RELEASE_v2.json')),'BTRACE:PrematureRelease','Release must be issued only after review.');
save(snapshotPath,'cfg','opts','sceneIdentity','sourceIdentity','-v7.3');
result=struct('schema','B_TRACEABLE_C3CORE_PREPARE_RESULT_V2', ...
    'status','PREPARED_NO_PLANT_WAIT_PARENT_RELEASE','created_utc',utc_now(), ...
    'input_lock_path',lockPath,'input_lock_sha256',sha256_file(lockPath), ...
    'contract_path',contractPath,'contract_sha256',sha256_file(contractPath), ...
    'runner_path',lock.source_files.runner.path,'runner_sha256',lock.source_files.runner.sha256, ...
    'snapshot_path',snapshotPath,'snapshot_sha256',sha256_file(snapshotPath), ...
    'scene_id',lock.scene_id,'raw_scene_id',rawSceneId,'alias_normalized_in_memory',sceneIdentity.alias_normalized_in_memory, ...
    'B_raw_path',lock.scene_raw_path,'B_raw_sha256',lock.scene_raw_sha256, ...
    'external_identity_sha256',lock.scene_external_identity_sha256, ...
    'method',contract.method,'collector_tag',contract.collector_tag, ...
    'cfg_matches_C3_prepared_cfg',true,'B_opts_reconstructed_from_controller_options',true, ...
    'position_rbf_output_enabled',opts.rbf_position_output_enabled, ...
    'position_rbf_update_enabled',opts.rbf_position_update_enabled, ...
    'attitude_rbf_enabled',opts.rbf_attitude_enabled,'position_rbf_frequency_hz',opts.position_rbf_frequency_hz, ...
    'attitude_rbf_frequency_hz',opts.attitude_rbf_frequency_hz, ...
    'which_checks',31,'active_sources',32,'plant_calls',0,'run_episode_called',false, ...
    'training_steps',0,'optimizer_steps',0,'parameter_or_seed_search',false,'TEST_accessed',false);
write_json_new(resultPath,result);
end

function add_active_paths(items)
for k=1:numel(items), [~,~,ext]=fileparts(items(k).path); if strcmpi(ext,'.m'), addpath(fileparts(items(k).path),'-end'); end, end
end
function path=source_path(items,name)
names=cell(1,numel(items)); for k=1:numel(items), [~,n,e]=fileparts(items(k).path); names{k}=[n e]; end
idx=find(strcmpi(names,name)); assert(numel(idx)==1,'BTRACE:SourceName','Expected exactly one source %s.',name); path=items(idx).path;
end
function ok=valid_scene(s,sceneId)
ok=isstruct(s)&&isfield(s,'scene_id')&&(strcmp(char(s.scene_id),sceneId)||strcmp(char(s.scene_id),[sceneId '_ACC_FIX_V1']))&& ...
    isfield(s,'time')&&numel(s.time)==20001&&abs(double(s.time(1)))<=1e-12&&abs(double(s.time(end))-20)<=1e-12&& ...
    isfield(s,'environment_wind_I')&&isequal(size(s.environment_wind_I),[20001,3])&&isfield(s,'initial_state')&&numel(s.initial_state)==12&& ...
    isfield(s,'arms')&&all(isfield(s.arms,{'command','rhoDot_hat','rhoDot_true','rho_hat','rho_true'}))&&isfield(s,'reference')&& ...
    all(isfield(s.reference,{'position','velocity','acceleration','yaw','yaw_rate','yaw_acceleration'}))&& ...
    isequal(size(s.reference.position),[20001,3])&&isequal(size(s.reference.velocity),[20001,3])&& ...
    isequal(size(s.reference.acceleration),[20001,3])&&isequal(size(s.reference.yaw),[20001,1])&& ...
    isequal(size(s.reference.yaw_rate),[20001,1])&&isequal(size(s.reference.yaw_acceleration),[20001,1])&& ...
    isequal(size(s.arms.command),[20001,4])&&isequal(size(s.arms.rhoDot_hat),[20001,4])&& ...
    isequal(size(s.arms.rhoDot_true),[20001,4])&&isequal(size(s.arms.rho_hat),[20001,4])&&isequal(size(s.arms.rho_true),[20001,4])&& ...
    all(isfinite(s.time(:)))&&all(isfinite(s.environment_wind_I(:)))&&all(isfinite(s.initial_state(:)))&& ...
    all(isfinite(s.arms.command(:)))&&all(isfinite(s.arms.rhoDot_hat(:)))&&all(isfinite(s.arms.rhoDot_true(:)))&& ...
    all(isfinite(s.arms.rho_hat(:)))&&all(isfinite(s.arms.rho_true(:)))&&all(isfinite(s.reference.position(:)))&& ...
    all(isfinite(s.reference.velocity(:)))&&all(isfinite(s.reference.acceleration(:)))&&all(isfinite(s.reference.yaw(:)))&& ...
    all(isfinite(s.reference.yaw_rate(:)))&&all(isfinite(s.reference.yaw_acceleration(:)));
end
function ok=field_is_false_or_absent(s,name)
ok=~isfield(s,name)||isempty(s.(name))||isequal(s.(name),false)|| ...
    (isstruct(s.(name))&&isfield(s.(name),'enabled')&&~logical(s.(name).enabled));
end
function verify_ref(item), verify_file(item.path,item.sha256); end
function verify_file(path,expected)
assert(isfile(path),'BTRACE:MissingFile','Missing frozen file: %s.',path);
assert(strcmpi(sha256_file(path),expected),'BTRACE:SHA','SHA-256 mismatch: %s.',path);
end
function h=sha256_file(path)
md=java.security.MessageDigest.getInstance('SHA-256'); fid=fopen(path,'r'); assert(fid>=0,'BTRACE:ReadFile','Cannot read %s.',path); c=onCleanup(@()fclose(fid)); %#ok<NASGU>
while true, b=fread(fid,8*1024*1024,'*uint8'); if isempty(b), break; end; md.update(typecast(b,'int8')); end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
function tf=same_path(a,b), tf=strcmpi(char(java.io.File(a).getCanonicalPath()),char(java.io.File(b).getCanonicalPath())); end
function write_json_new(path,value)
assert(~isfile(path),'BTRACE:NoOverwrite','Refusing to overwrite %s.',path); fid=fopen(path,'w'); assert(fid>=0,'BTRACE:Write','Cannot write %s.',path); c=onCleanup(@()fclose(fid)); fwrite(fid,jsonencode(value),'char');
end
function t=utc_now(), t=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z''')); end