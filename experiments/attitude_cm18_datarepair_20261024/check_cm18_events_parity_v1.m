function outputPath=check_cm18_events_parity_v1()
% Read-only parity check of the pure extractor against four pinned event exports.
here=fileparts(mfilename('fullpath'));repoRoot=fileparts(fileparts(here));
reportDir=fullfile(repoRoot,'reports','attitude_position_context_probe_20261024');
outDir=fullfile(repoRoot,'reports','attitude_cm18_datarepair_20261024');
outputPath=fullfile(outDir,'CM18_EVENT_EXTRACTION_PARITY_v1.json');
assert(~isfolder(outDir)&&~isfile(outputPath),'CM18Parity:OutputExists', ...
    'Refusing to reuse an existing parity output path.');

extractorPath=fullfile(here,'extract_cm18_events_v1.m');
probeExporterPath=fullfile(repoRoot,'experiments','attitude_position_context_probe_20261024', ...
    'export_matched_position_probe_events_v2.m');
legacyExporterPath=fullfile(repoRoot,'experiments','attitude_cm18_a1_20261024','export_cm18_events_v1.m');
coreDir=fullfile(repoRoot,'matlab','core');
assert_sha(probeExporterPath,'ddb1684b1d720d9bee80b3bcda2c95bf855faee1220fc54e9ba764695c5a54a9');
assert_sha(legacyExporterPath,'5264586d5e2120cdaf5f5cf6a42c07e21e1ed9afd244b92ef7a7f89bbedfc6d6');
addpath(coreDir,'-begin');addpath(here,'-begin');rehash;
helperNames={'arm_mass_properties','distributed_mass_properties','arm_directions'};
helperSHAs={ ...
    '8ec66e107156b5219f7e41aca2464eef1ec8043eb7f67df313c0f23ef4b551f5', ...
    'db380b506e4bacc37bc398d5726c5ebd25be8ebc08b6c9e76ff59bc78fd45d3a', ...
    '517bbfcd0df9526b189f64bff067a49551f573ad96e682ee005533ab510e686c'};
helperRows=repmat(struct('name','','path','','sha256',''),numel(helperNames),1);
for h=1:numel(helperNames)
    helperPath=fullfile(coreDir,[helperNames{h} '.m']);
    assert(same_path(which(helperNames{h}),helperPath)&&strcmpi(sha256_file(helperPath),helperSHAs{h}), ...
        'CM18Parity:PhysicalHelper','Physical helper source/path mismatch: %s.',helperNames{h});
    helperRows(h).name=helperNames{h};
    helperRows(h).path=strrep(helperPath,[repoRoot filesep],'');
    helperRows(h).sha256=helperSHAs{h};
end
assert(same_path(which('extract_cm18_events_v1'),extractorPath), ...
    'CM18Parity:ExtractorPath','MATLAB resolved another extractor source.');

contracts={ ...
    make_contract('T1_B','DL1018_TRAIN_T1_C15_W14','B_POSITION_RBF',2, ...
        '574edcdc35483c6069bd053ae345a2ddee1c61780b7e044dea422b7b01fbf08c', ...
        'b6e26264ffd7d4c86f1c78aaa734ec5ee9d77bb415273fc2657366bb77fa61e4', ...
        'e44d75f8fb784ed30f7b72057fda2183ad09c9286271b8db15cc3f5aeafd830a', ...
        '88433eb2d15552e3a30310a6b80c763b31e1f7285436b38b3cdd88bf1fe8d83b', ...
        'b770618d897463b779f60b97d5ace24cd128f776b8aff91445e67843a41806dd'), ...
    make_contract('T1_C5','DL1018_TRAIN_T1_C15_W14','C5_POSITION_M110',1, ...
        '6440649b1f6b45b483158d963e34f99ee6d5d47b961860422556f9c450f75749', ...
        '9975f2e18c8a510544bc6e65ad173df9b606ac4160c5ce22e5d20829815b65b1', ...
        '0ed32edca581d98901cf1b92a4816e3c5870a2b4344a10ad4697f1b85c05c01f', ...
        '753e83b6d01928d7bc91bf094ca842e8527afdf1e496f8e6002fb69da9679e76', ...
        'c86e4a9467f39d32f1eb05c560dd969a47517a3a8eb9598f6107f9aa5b44231e'), ...
    make_contract('T3_B','DL1018_TRAIN_T3_C15_W14','B_POSITION_RBF',1, ...
        'bc5e8499347d071f736a5aa7a0a8d1173e3b9633aaeb2182b14256666d2f7594', ...
        'fd6576d070dd36d60a94c3a083aedbcef0a6168213bd6047d09b9583605b381a', ...
        '195f48180d180f2760186b11a20170d92febf659a3340cf117eff5431d201aad', ...
        '4446356de080a727889adede094f5760b9ad85896d6726389e96bd48f3c105c0', ...
        '82b6b12f8a31e9c0865728a71827205979bd19f28d457765790f3eabe2eaaff7'), ...
    make_contract('T3_C5','DL1018_TRAIN_T3_C15_W14','C5_POSITION_M110',1, ...
        '27c5af24ac01f0ea90eb8a1138a8d947c9c568f945c64c05cced3da08117a7f4', ...
        '028d204a6773389399b2ecd251268db02c1e02edc88fd8e01fab99aaf8d82a3f', ...
        'aebdb44f6119110c6faf0c87511a5f5b3b9736a1c8d2e7bc007b2c78965cb74a', ...
        '2890f2c0998226145a5e4f320b9264bf6604ef08e1ccaa7a9afbfd6a5d3aaadb', ...
        '1c794dea4f4b549db4d6eeb10387e2ef228f9457cb89fd3c44579fbdcb3f3ea5')};

% Preflight all identities and file hashes before opening any raw MAT arrays.
preflight=cell(1,numel(contracts));
for s=1:numel(contracts)
    c=contracts{s};attemptDir=fullfile(reportDir,'runs',c.flight_id,sprintf('attempt_%02d',c.attempt_id));
    statusPath=fullfile(attemptDir,'run_status.json');rawPath=fullfile(attemptDir,'raw_run.mat');
    runStartPath=fullfile(attemptDir,'run_start.mat');
    eventPath=fullfile(reportDir,'offline_events_v2',['events_' c.flight_id '_v2.json']);
    releasePath=fullfile(reportDir,['ROOT_RELEASE_' c.flight_id '_v2.json']);
    assert_sha(statusPath,c.status_sha256);assert_sha(rawPath,c.raw_sha256);
    assert_sha(runStartPath,c.run_start_sha256);assert_sha(eventPath,c.event_sha256);
    assert_sha(releasePath,c.release_sha256);
    status=jsondecode(fileread(statusPath));
    assert(strcmp(status.schema,'MATCHED_POSITION_PROBE_RUN_STATUS_V1')&& ...
        strcmp(status.status,'RUN_COMPLETE_STABLE')&&strcmp(status.engine_status,'STABLE')&& ...
        strcmp(status.flight_id,c.flight_id)&&double(status.attempt_id)==c.attempt_id&& ...
        strcmp(status.scene_id,c.scene_id)&&strcmp(status.position_mode,c.position_mode)&& ...
        double(status.transitions)==20000&&double(status.state_samples)==20001&& ...
        double(status.plant_calls)==1&&double(status.training_steps)==0&& ...
        double(status.optimizer_steps)==0&&~logical(status.TEST_accessed)&& ...
        isempty(status.safety_stop_reason)&&strcmpi(status.raw_sha256,c.raw_sha256)&& ...
        same_path(status.raw_path,rawPath), ...
        'CM18Parity:RunStatus','Fixed run status is incomplete or mismatched: %s.',c.flight_id);
    Rload=load(runStartPath,'runStart');runStart=Rload.runStart;
    assert(strcmp(runStart.schema,'MATCHED_POSITION_PROBE_RUN_START_V1')&& ...
        strcmp(runStart.flight_id,c.flight_id)&&strcmp(runStart.scene_id,c.scene_id)&& ...
        strcmp(runStart.position_mode,c.position_mode)&&double(runStart.attempt_id)==c.attempt_id&& ...
        strcmpi(runStart.release_sha256,c.release_sha256)&&same_path(runStart.release_path,releasePath), ...
        'CM18Parity:RunStart','Fixed run_start identity mismatch: %s.',c.flight_id);
    release=jsondecode(fileread(releasePath));
    assert(strcmp(release.schema,'MATCHED_POSITION_PROBE_RELEASE_V1')&& ...
        strcmp(release.decision,'APPROVE_ONE_FLIGHT')&&strcmp(release.flight_id,c.flight_id)&& ...
        double(release.attempt_id)==c.attempt_id, ...
        'CM18Parity:Release','Fixed release identity mismatch: %s.',c.flight_id);
    E=jsondecode(fileread(eventPath));I=E.identity;
    assert(strcmp(E.schema,'MATCHED_POSITION_PROBE_EVENT_EXPORT_V2')&&strcmp(E.status,'PASS')&& ...
        strcmp(I.flight_id,c.flight_id)&&double(I.attempt_id)==c.attempt_id&& ...
        strcmp(I.scene_id,c.scene_id)&&strcmp(I.position_mode,c.position_mode)&&strcmp(I.split,'TRAIN')&& ...
        strcmpi(I.status_sha256,c.status_sha256)&&strcmpi(I.raw_sha256,c.raw_sha256)&& ...
        strcmpi(I.run_start_sha256,c.run_start_sha256)&&strcmpi(I.release_sha256,c.release_sha256)&& ...
        strcmpi(I.exporter_source_sha256,'ddb1684b1d720d9bee80b3bcda2c95bf855faee1220fc54e9ba764695c5a54a9')&& ...
        double(E.scope.training_steps)==0&&double(E.scope.optimizer_steps)==0&& ...
        double(E.scope.new_plant_calls)==0&&~logical(E.scope.TEST_accessed), ...
        'CM18Parity:EventExport','Pinned event export identity/scope mismatch: %s.',c.flight_id);
    preflight{s}=struct('contract',c,'status_path',statusPath,'raw_path',rawPath, ...
        'run_start_path',runStartPath,'runStart',runStart,'event_path',eventPath, ...
        'event_sha256',c.event_sha256,'event',E);
end

rows=cell(1,numel(preflight));
for s=1:numel(preflight)
    input=preflight{s};c=input.contract;R=input.runStart;
    D=load(input.raw_path,'log','scene','method');
    assert(strcmp(char(D.method),c.position_mode)&&strcmp(char(D.scene.scene_id),c.scene_id), ...
        'CM18Parity:RawIdentity','Loaded raw scene/method identity mismatch: %s.',c.flight_id);
    events=extract_cm18_events_v1(R.cfg,D.scene,D.log);E=input.event;
    eventIndex=double(E.event_index(:));plantIndex=double(E.plant_index(:));
    eventTime=double(E.event_time_s(:));phaseCode=double(E.phase_code(:));
    refX=double(E.X18);refTarget=double(E.target_raw);
    assert(isscalar(E)&&numel(eventIndex)==1999&&numel(plantIndex)==1999&& ...
        isequal(size(refX),[1999,18])&&isequal(size(refTarget),[1999,3])&& ...
        numel(eventTime)==1999&&numel(phaseCode)==1999&& ...
        isequal(eventIndex,(1:1999).')&&isequal(plantIndex,(11:10:19991).')&& ...
        all(isfinite([eventTime;phaseCode;refX(:);refTarget(:)])), ...
        'CM18Parity:ReferenceShape','Pinned exporter event arrays have invalid shape/values: %s.',c.flight_id);
    assert(isequal(events.event_index,eventIndex)&&isequal(events.plant_index,plantIndex)&& ...
        max(abs(events.event_time_s-eventTime))<=1e-12&&isequal(double(events.phase_code),phaseCode), ...
        'CM18Parity:Schedule','Extractor schedule/phase differs from exporter: %s.',c.flight_id);
    xDelta=max(abs(events.X18-refX),[],'all');targetDelta=max(abs(events.target_raw-refTarget),[],'all');
    requestDelta=abs(events.closure.requested_torque_vs_nominal_minus_applied_max_abs_Nm- ...
        double(E.closure.requested_torque_vs_nominal_minus_applied_max_abs_Nm));
    dynamicsDelta=abs(events.closure.true_dynamics_equation_residual_max_abs_Nm- ...
        double(E.closure.true_dynamics_equation_residual_max_abs_Nm));
    assert(xDelta<=1e-10&&targetDelta<=1e-10&&requestDelta<=1e-12&&dynamicsDelta<=1e-12, ...
        'CM18Parity:NumericalParity','Extractor output differs from pinned exporter: %s.',c.flight_id);
    rows{s}=struct('flight_id',c.flight_id,'scene_id',c.scene_id,'position_mode',c.position_mode, ...
        'attempt_id',c.attempt_id,'raw_sha256',c.raw_sha256,'event_export_sha256',c.event_sha256, ...
        'event_count',numel(eventIndex),'max_abs_X18_delta',xDelta,'max_abs_target_delta_rad_s2',targetDelta, ...
        'phase_code_exact_match',true,'max_abs_event_time_delta_s',max(abs(events.event_time_s-eventTime)), ...
        'requested_torque_closure_max_abs_Nm',events.closure.requested_torque_vs_nominal_minus_applied_max_abs_Nm, ...
        'true_dynamics_equation_residual_max_abs_Nm',events.closure.true_dynamics_equation_residual_max_abs_Nm, ...
        'max_abs_request_closure_metadata_delta_Nm',requestDelta, ...
        'max_abs_dynamics_closure_metadata_delta_Nm',dynamicsDelta);
end

result=struct;
result.schema='CM18_EVENT_EXTRACTION_PARITY_V1';result.status='PASS';
result.extractor_path=strrep(extractorPath,[repoRoot filesep],'');
result.extractor_sha256=sha256_file(extractorPath);
result.probe_event_exporter_sha256=sha256_file(probeExporterPath);
result.legacy_cm18_exporter_sha256=sha256_file(legacyExporterPath);
result.physical_helper_sources=helperRows;result.flights=rows;
result.scope=struct('events_per_flight',1999,'flight_count',4,'raw_files_read',true, ...
    'old_B_h5_read',false,'TEST_accessed',false,'training_steps',0,'optimizer_steps',0, ...
    'Plant_calls',0,'engine_calls',0,'model_forward_calls',0);
assert(isscalar(result),'CM18Parity:ResultScalar','Expected one scalar parity report.');
encoded=jsonencode(result,'PrettyPrint',true);bytes=unicode2native(encoded,'UTF-8');
assert(numel(bytes)<=4*1024^2,'CM18Parity:ResultSize','Parity report exceeds 4 MiB.');
mkdir(outDir);fid=fopen(outputPath,'wb');
assert(fid>=0,'CM18Parity:OutputOpen','Could not create parity result.');
closer=onCleanup(@()fclose(fid));
written=fwrite(fid,bytes,'uint8');
assert(written==numel(bytes),'CM18Parity:OutputWrite','Incomplete parity result write.');
clear closer
end

function c=make_contract(flight,scene,mode,attempt,eventSha,statusSha,rawSha,startSha,releaseSha)
c=struct('flight_id',flight,'scene_id',scene,'position_mode',mode,'attempt_id',attempt, ...
    'event_sha256',eventSha,'status_sha256',statusSha,'raw_sha256',rawSha, ...
    'run_start_sha256',startSha,'release_sha256',releaseSha);
end

function assert_sha(path,expected)
assert(isfile(path)&&strcmpi(sha256_file(path),char(expected)), ...
    'CM18Parity:SHA','Missing file or SHA-256 mismatch: %s.',path);
end

function tf=same_path(a,b)
tf=strcmpi(char(java.io.File(a).getCanonicalPath()),char(java.io.File(b).getCanonicalPath()));
end

function h=sha256_file(path)
md=java.security.MessageDigest.getInstance('SHA-256');fid=fopen(path,'rb');
assert(fid>=0,'CM18Parity:Read','Cannot read %s.',path);closer=onCleanup(@()fclose(fid));
while true
    b=fread(fid,8*1024*1024,'*uint8');
    if isempty(b),break;end
    md.update(typecast(b(:),'int8'));
end
clear closer
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
