clipInfo=struct('event_beta_first_last',[beta(1),beta(end)], ...
    'beta_index_clock_minus_raw_event_time_s_first_last',[betaClockOffset(1),betaClockOffset(end)], ...
    'event_count_beta_zero',nnz(beta==0),'event_count_beta_below_one',nnz(beta<1), ...
