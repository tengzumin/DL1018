function value = read_vector(path,dataset,n)
value=double(h5read(path,dataset)); value=value(:);
assert(numel(value)==n&&all(isfinite(value)), ...
    'CM18Target:H5Vector','Unexpected or non-finite vector dataset %s.',dataset);
end

function value = read_rows(path,dataset,nRows,nCols)
value=double(h5read(path,dataset));
if isequal(size(value),[nCols,nRows]), value=value.'; end
assert(isequal(size(value),[nRows,nCols])&&all(isfinite(value),'all'), ...
    'CM18Target:H5Matrix','Unexpected/non-finite matrix dataset %s.',dataset);
end

function value = matrix_rows(value,nRows,nCols)
value=double(value);
if isequal(size(value),[nCols,nRows]), value=value.'; end
assert(isequal(size(value),[nRows,nCols])&&all(isfinite(value),'all'), ...
    'CM18Target:JSONMatrix','Unexpected/non-finite JSON matrix.');
end

function value = rms_value(x)
assert(all(isfinite(x(:))),'CM18Target:MetricFinite','A summary metric has non-finite events.');
value=sqrt(mean(double(x(:)).^2));
end

function text = matlab_text(value)
if ischar(value), text=strtrim(value);
elseif isstring(value)&&isscalar(value), text=char(value);
elseif iscell(value)&&isscalar(value), text=matlab_text(value{1});
elseif isnumeric(value)&&isvector(value), text=char(value(:).');
else, error('CM18Target:Text','Expected a scalar text value.');
end
text=strtrim(text);
end

function path = repo_relative(path,repoRoot)
path=strrep(char(path),[repoRoot filesep],''); path=strrep(path,'\','/');
end

function tf = same_path(a,b)
tf=strcmpi(char(java.io.File(char(a)).getCanonicalPath()), ...
    char(java.io.File(char(b)).getCanonicalPath()));
end

function assert_sha(path,expected)
assert(isfile(path)&&strcmpi(sha256_file(path),char(expected)), ...
    'CM18Target:SHA','Missing file or SHA-256 mismatch: %s',path);
end

function digest = sha256_file(path)
fid=fopen(path,'rb'); assert(fid>=0,'CM18Target:HashOpen','Cannot open %s for SHA-256.',path);
closer=onCleanup(@()fclose(fid)); md=java.security.MessageDigest.getInstance('SHA-256');
while true
    bytes=fread(fid,1024*1024,'*uint8'); if isempty(bytes), break; end
    md.update(typecast(bytes(:),'int8'));
end
digest=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[])); clear closer
end
