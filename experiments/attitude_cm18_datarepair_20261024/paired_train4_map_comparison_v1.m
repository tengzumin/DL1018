function [result,J0,C0,dmax,betaRise] = inspect_scene(input,repoRoot,phaseNames,pR,pT,J0,C0,dmax,betaRise)
c = input.contract; runStart = input.runStart; cfg = runStart.cfg;
assert(strcmp(matlab_text(cfg.controller_morphology_mode),'fixed')&& ...
    strcmp(matlab_text(cfg.controller_inertia_derivative_mode),'full'), ...
    'CM18Target:ControllerConfig','The pinned cfg must use fixed controller inertia and full Jdot.');
dmaxNow = double(cfg.rbf.attitude.dmax(:)); betaNow = double(cfg.rbf.attitude.beta_rise_time);
assert(isequal(size(dmaxNow),[3,1])&&all(isfinite(dmaxNow))&&all(dmaxNow>0)&& ...
    abs(betaNow-2.2)<=1e-12&&max(abs(dmaxNow-[45;45;4.7124]))<=1e-12, ...
    'CM18Target:ClipBeta','A1 runtime clip/beta contract differs from its frozen candidate.');
if isempty(dmax), dmax=dmaxNow; betaRise=betaNow;
else
    assert(max(abs(dmax-dmaxNow))<=1e-14&&abs(betaRise-betaNow)<=1e-14, ...
        'CM18Target:ClipBetaPair','The four flights do not share one clip/beta contract.');
end

rawPath = input.raw_path; E = input.event_export;
n = 20000; state = read_rows(rawPath,'/log/state',n+1,12);
sceneTime = read_vector(rawPath,'/scene/time',n+1);
time = read_vector(rawPath,'/log/time',n+1); transitionTime = read_vector(rawPath,'/log/transition_time',n);
eventFlag = read_vector(rawPath,'/log/attitude_event_flag',n)~=0;
tauNom = read_rows(rawPath,'/log/attitude_bs_nominal_torque_Nm',n,3);
tauComp = read_rows(rawPath,'/log/attitude_compensation_applied_torque_Nm',n,3);
requested = read_rows(rawPath,'/log/requested_generalized',n,4);
realized = read_rows(rawPath,'/log/realized_generalized',n,4);
windTorque = read_rows(rawPath,'/log/wind_torque_B',n,3);
allocatorClip = read_rows(rawPath,'/log/generalized_clipped',n,4)~=0;
motorSaturated = read_rows(rawPath,'/log/motor_saturated',n,4)~=0;
rho = read_rows(rawPath,'/scene/arms/rho_true',n+1,4);
rhoDot = read_rows(rawPath,'/scene/arms/rhoDot_true',n+1,4);
motorTc = double(h5read(rawPath,'/log/motor_time_constant_s'));
idx = find(eventFlag); expectedIdx=(11:10:19991).'; dt=diff(time);
assert(numel(idx)==1999&&isequal(idx,expectedIdx)&& ...
    max(abs(double(E.plant_index(:))-idx))<=0&& ...
    max(abs(double(E.event_time_s(:))-time(idx)))<=1e-12&& ...
    isequal(size(state),[n+1,12])&&max(abs(sceneTime-time))<=1e-12&& ...
    max(abs(transitionTime-time(1:n)))<=1e-12&&max(abs(dt-0.001))<=1e-12&& ...
    abs(double(cfg.plant.dt)-0.001)<=1e-12&& ...
    max(abs(time(idx)-(idx-1)*double(cfg.plant.dt)))<=1e-10&& ...
    max(abs(diff(time(idx))-0.010))<=1e-12&&isfinite(motorTc)&&abs(motorTc)<=1e-12, ...
    'CM18Target:Schedule','Raw/export schedule or ideal actuator contract differs.');
assert(all(isfinite([state(:);tauNom(:);tauComp(:);requested(:);realized(:); ...
    windTorque(:);rho(:);rhoDot(:)])), ...
    'CM18Target:Finite','A required pinned raw physical input is non-finite.');
N=1999; phaseCode = double(E.phase_code(:)); targetOld = matrix_rows(E.target_raw,N,3);
X18 = matrix_rows(E.X18,N,18);
assert(numel(phaseCode)==N&&all(phaseCode>=0&phaseCode<=5)&& ...
    double(input.scene_summary.event_export_max_abs_X18_difference)==0, ...
    'CM18Target:X18Identity','Pinned raw-derived X18 parity or phase code changed.');
summaryEvents=input.scene_summary.event_records;
summaryTarget=matrix_rows(summaryEvents.target_raw_rad_s2,N,3);
summaryPhase=double(summaryEvents.phase_code(:));
summaryPlantIndex=double(summaryEvents.plant_index(:));
summaryTime=double(summaryEvents.event_time_s(:));
rawTargetYawCross=double(summaryEvents.component_sum_yaw_rad_s2(:));
assert(numel(phaseCode)==1999&&numel(rawTargetYawCross)==1999&& ...
    numel(summaryPhase)==1999&&numel(summaryPlantIndex)==1999&&numel(summaryTime)==1999&& ...
    isequal(phaseCode,summaryPhase)&&isequal(summaryPlantIndex,idx)&& ...
    max(abs(summaryTime-time(idx)))<=1e-12&& ...
    max(abs(summaryTarget-targetOld),[],'all')<=1e-10&& ...
    max(abs(targetOld(:,3)-rawTargetYawCross))<=1e-8, ...
    'CM18Target:YawCrosscheck','Event export differs from the pinned 3-axis/yaw event records.');

P0 = simulation_parameters(cfg,cfg.plant.arm_initial,zeros(4,1));
Pc = controller_parameters(cfg,P0,'fixed');
J0Now=double(P0.inertia); Jdot0=double(P0.inertia_dot); C0Now=double(Pc.allocation.C);
assert(isequal(size(J0Now),[3,3])&&isequal(size(Jdot0),[3,3])&& ...
    isequal(size(C0Now),[4,4])&&max(abs(double(Pc.inertia)-J0Now),[],'all')<=1e-14, ...
    'CM18Target:NominalModel','Invalid fixed J0/C0 identities.');
if isempty(J0), J0=J0Now; C0=C0Now;
else
    assert(max(abs(J0-J0Now),[],'all')<=1e-14&&max(abs(C0-C0Now),[],'all')<=1e-14, ...
        'CM18Target:NominalPair','The four flights do not share fixed J0/C0.');
end

alphaBS=zeros(N,3); cOld=zeros(N,3);
betaClockOffset=zeros(N,1); dtPlant=double(cfg.plant.dt);
cStar=zeros(N,3); oldLinearError=zeros(N,3); cStarLinearError=zeros(N,3);
rawR=zeros(N,3); clippedR=zeros(N,3); appliedR=zeros(N,3); linearR=zeros(N,3);
rawT=zeros(N,3); clippedT=zeros(N,3); appliedT=zeros(N,3); linearT=zeros(N,3);
rawTargetErrorR=zeros(N,3); rawTargetErrorT=zeros(N,3);
appliedCstarErrorR=zeros(N,3); appliedCstarErrorT=zeros(N,3);
clipFlagR=false(N,3); clipFlagT=false(N,3); eventRecords=cell(N,1);
oldMatrixTarget=zeros(N,3); directTarget=zeros(N,3);
oldDeployError=zeros(N,3); oldFullBetaError=zeros(N,3);
cStarDeployError=zeros(N,3); cStarFullBetaError=zeros(N,3);
baseAllocatorDelta=zeros(N,4);
currentAllocatorClip=false(N,4); currentMotorSaturated=false(N,4);
baseAllocatorClip=false(N,4); baseMotorSaturated=false(N,4);
oldOutputClip=false(N,3); cStarFullBetaClip=false(N,3); cStarBetaCorrectedClip=false(N,3);
cStarAllocatorClip=false(N,4); cStarMotorSaturated=false(N,4);
cStarFullBetaAllocatorClip=false(N,4); cStarFullBetaMotorSaturated=false(N,4);
beta=zeros(N,1); betaZeroUnreachable=false(N,3); GCondition=zeros(N,1); GRcond=zeros(N,1);
maxBaseWrenchDelta=0; maxRawTargetClosure=0; maxMatrixTargetClosure=0; maxE0Identity=0;
maxCurrentRequestClosure=0; maxCurrentAllocatorClosure=0;
for q=1:N
    k=idx(q); w=state(k,10:12).'; tn=tauNom(k,:).'; tc=tauComp(k,:).';
    T=requested(k,1); wt=windTorque(k,:).';
    Ptrue=simulation_parameters(cfg,rho(k,:).',rhoDot(k,:).');
    J=double(Ptrue.inertia); Jdot=double(Ptrue.inertia_dot); Ct=double(Ptrue.allocation.C);
    gyro0=cross(w,J0*w); gyroTrue=cross(w,J*w);
    alphaBS(q,:)=(J0\(tn-gyro0-Jdot0*w)).';
    cOld(q,:)=(J0\tc).';

    rawRequest=requested(k,:).'; requestedFromController=[T;tn-tc];
    maxCurrentRequestClosure=max(maxCurrentRequestClosure,max(abs(rawRequest-requestedFromController)));
    [~,currentRealized,currentInfo]=allocate_control(requestedFromController,Pc,Ptrue,[]);
    currentAllocatorClip(q,:)=logical(currentInfo.generalized_command_clipped(:)).';
    currentMotorSaturated(q,:)=logical(currentInfo.motor_saturated(:)).';
    maxCurrentAllocatorClosure=max(maxCurrentAllocatorClosure,max(abs(currentRealized-realized(k,:).')));
    assert(isequal(currentAllocatorClip(q,:),allocatorClip(k,:))&& ...
        isequal(currentMotorSaturated(q,:),motorSaturated(k,:)), ...
        'CM18Target:AllocatorRawFlags','Pure allocate_control flags differ from raw for %s event %d.',c.flight_id,k);
    forcingActual=realized(k,2:4).'+wt-gyroTrue-Jdot*w;
    alphaActualRaw=J\forcingActual;
    assert(max(abs(J*alphaActualRaw-forcingActual))<=1e-12, ...
        'CM18Target:DynamicsSolve','True-inertia solve residual is too large.');
    alphaVirtual=J0\(tn-tc-gyro0-Jdot0*w);
    directTarget(q,:)=(alphaActualRaw-alphaVirtual).';

    L=[zeros(1,3);J0]; transfer=Ct*(C0\L); G=J\transfer(2:4,:);
    nominalRequest=[T;tn];
    [~,baseRealized,baseInfo]=allocate_control(nominalRequest,Pc,Ptrue,[]);
    baseAllocatorClip(q,:)=logical(baseInfo.generalized_command_clipped(:)).';
    baseMotorSaturated(q,:)=logical(baseInfo.motor_saturated(:)).';
    baseAllocatorDelta(q,:)=(baseRealized-Ct*(C0\nominalRequest)).';
    maxBaseWrenchDelta=max(maxBaseWrenchDelta,max(abs(baseAllocatorDelta(q,:))));
    wrench0=Ct*(C0\nominalRequest);
    E0=J\(wrench0(2:4)+wt-gyroTrue-Jdot*w)-alphaBS(q,:).';
    oldMatrixTarget(q,:)=(E0+(eye(3)-G)*cOld(q,:).').';
    maxRawTargetClosure=max(maxRawTargetClosure,max(abs(directTarget(q,:)-targetOld(q,:))));
    maxMatrixTargetClosure=max(maxMatrixTargetClosure,max(abs(oldMatrixTarget(q,:)-targetOld(q,:))));
    eIdentity=E0-(targetOld(q,:).'-((eye(3)-G)*cOld(q,:).'));
    maxE0Identity=max(maxE0Identity,max(abs(eIdentity)));
    oldLinearError(q,:)=(E0-G*targetOld(q,:).').';

    GCondition(q)=cond(G); GRcond(q)=rcond(G);
    assert(all(isfinite([G(:);E0(:);GCondition(q);GRcond(q)]))&& ...
        rank(G)==3&&GRcond(q)>1e-12, ...
        'CM18Target:SingularG','G singular/ill-conditioned; no regularization: %s event %d, cond=%g, rcond=%g.', ...
        c.flight_id,k,GCondition(q),GRcond(q));
    cs=G\E0; cStar(q,:)=cs.'; cStarLinearError(q,:)=(E0-G*cs).';
    beta(q)=min(k*dtPlant/betaNow,1);
    betaClockOffset(q)=k*dtPlant-time(k);
    assert(isfinite(beta(q))&&beta(q)>=0&&beta(q)<=1&& ...
        abs(time(k)-(k-1)*dtPlant)<=1e-10&& ...
        abs(betaClockOffset(q)-dtPlant)<=1e-10, ...
        'CM18Target:BetaClock','Raw event time or preserved one-based beta clock differs.');
    assert(beta(q)>0,'CM18Target:BetaZero','A mapped-model target is undefined at beta zero.');
    rawR(q,:)=cm18_a1_forward_v1(X18(q,:),pR);
    rawT(q,:)=cm18_a1_forward_v1(X18(q,:),pT);
    clippedR(q,:)=min(max(rawR(q,:),-dmax.'),dmax.');
    clippedT(q,:)=min(max(rawT(q,:),-dmax.'),dmax.');
    clipFlagR(q,:)=abs(rawR(q,:)-clippedR(q,:))>1e-12;
    clipFlagT(q,:)=abs(rawT(q,:)-clippedT(q,:))>1e-12;
    appliedR(q,:)=beta(q)*clippedR(q,:); appliedT(q,:)=beta(q)*clippedT(q,:);
    rawTargetErrorR(q,:)=rawR(q,:)-cs.'/beta(q);
    rawTargetErrorT(q,:)=rawT(q,:)-cs.'/beta(q);
    appliedCstarErrorR(q,:)=appliedR(q,:)-cs.';
    appliedCstarErrorT(q,:)=appliedT(q,:)-cs.';
    linearR(q,:)=(E0-G*appliedR(q,:).').';
    linearT(q,:)=(E0-G*appliedT(q,:).').';
    eventRecords{q}=struct('event_index',q,'plant_index',k,'time_s',time(k), ...
        'phase_code',phaseCode(q),'beta',beta(q),'G_row_major',reshape(G.',1,9), ...
        'E0_rad_s2',E0.','Cstar_rad_s2',cs.', ...
        'A1R',struct('raw_prediction_rad_s2',rawR(q,:), ...
            'clipped_prediction_rad_s2',clippedR(q,:),'applied_action_rad_s2',appliedR(q,:), ...
            'raw_prediction_minus_Cstar_over_beta_rad_s2',rawTargetErrorR(q,:), ...
            'applied_action_minus_Cstar_rad_s2',appliedCstarErrorR(q,:), ...
            'linear_surrogate_E0_minus_G_action_rad_s2',linearR(q,:), ...
            'clip_flag_by_axis',clipFlagR(q,:)), ...
        'A1T',struct('raw_prediction_rad_s2',rawT(q,:), ...
            'clipped_prediction_rad_s2',clippedT(q,:),'applied_action_rad_s2',appliedT(q,:), ...
            'raw_prediction_minus_Cstar_over_beta_rad_s2',rawTargetErrorT(q,:), ...
            'applied_action_minus_Cstar_rad_s2',appliedCstarErrorT(q,:), ...
            'linear_surrogate_E0_minus_G_action_rad_s2',linearT(q,:), ...
            'clip_flag_by_axis',clipFlagT(q,:)));
    oldOutput=targetOld(q,:).'; oldClipped=min(max(oldOutput,-dmax),dmax);
    oldOutputClip(q,:)=abs(oldOutput-oldClipped)>1e-12;
    oldApplied=beta(q)*oldClipped;
    [alphaOldDeploy,~,~]=alpha_for_applied_compensation(T,tn,oldApplied,J0,Pc,Ptrue,wt,w,J,Jdot);
    oldDeployError(q,:)=(alphaOldDeploy-alphaBS(q,:).').';
    [alphaOldFullBeta,~,~]=alpha_for_applied_compensation(T,tn,oldClipped,J0,Pc,Ptrue,wt,w,J,Jdot);
    oldFullBetaError(q,:)=(alphaOldFullBeta-alphaBS(q,:).').';

    csClipped=min(max(cs,-dmax),dmax);
    cStarFullBetaClip(q,:)=abs(cs-csClipped)>1e-12;
    [alphaStarFullBeta,~,fullInfo]=alpha_for_applied_compensation( ...
        T,tn,csClipped,J0,Pc,Ptrue,wt,w,J,Jdot);
    cStarFullBetaError(q,:)=(alphaStarFullBeta-alphaBS(q,:).').';
    cStarFullBetaAllocatorClip(q,:)=logical(fullInfo.generalized_command_clipped(:)).';
    cStarFullBetaMotorSaturated(q,:)=logical(fullInfo.motor_saturated(:)).';

    if beta(q)==0
        betaZeroUnreachable(q,:)=abs(cs(:).')>1e-10;
        rawNeeded=zeros(3,1); appliedStar=zeros(3,1);
    else
        rawNeeded=cs/beta(q);
        rawLimited=min(max(rawNeeded,-dmax),dmax);
        cStarBetaCorrectedClip(q,:)=abs(rawNeeded-rawLimited)>1e-12;
        appliedStar=beta(q)*rawLimited;
    end
    [alphaStarDeploy,~,deployInfo]=alpha_for_applied_compensation( ...
        T,tn,appliedStar,J0,Pc,Ptrue,wt,w,J,Jdot);
    cStarDeployError(q,:)=(alphaStarDeploy-alphaBS(q,:).').';
    cStarAllocatorClip(q,:)=logical(deployInfo.generalized_command_clipped(:)).';
    cStarMotorSaturated(q,:)=logical(deployInfo.motor_saturated(:)).';
end

assert(maxCurrentRequestClosure<=1e-8&&maxCurrentAllocatorClosure<=1e-8&& ...
    maxRawTargetClosure<=1e-8&&maxMatrixTargetClosure<=1e-8&&maxE0Identity<=1e-8, ...
    'CM18Target:Closure','Current allocation/request or full-matrix target closure failed.');
phaseSummary=repmat(empty_summary(),1,numel(phaseNames));
data=struct('old_minus_cstar',targetOld-cStar,'old_linear_error',oldLinearError, ...
    'old_deploy_error',oldDeployError,'old_fullbeta_error',oldFullBetaError, ...
    'cstar_linear_error',cStarLinearError,'cstar_deploy_error',cStarDeployError, ...
    'cstar_fullbeta_error',cStarFullBetaError,'target_matrix_closure',oldMatrixTarget-targetOld, ...
    'target_direct_closure',directTarget-targetOld,'old_output_clip',oldOutputClip, ...
    'cstar_fullbeta_clip',cStarFullBetaClip,'cstar_beta_corrected_clip',cStarBetaCorrectedClip, ...
    'beta_zero_unreachable',betaZeroUnreachable,'condition',GCondition,'rcond',GRcond);
for p=1:numel(phaseNames)
    phaseSummary(p)=summarize_subset(phaseNames{p},p-1,phaseCode==(p-1),data);
end
allSummary=summarize_subset('ALL',-1,true(N,1),data);
mapWindows=repmat(struct('window','','event_count',0,'A1R',[],'A1T',[]),1,3);
