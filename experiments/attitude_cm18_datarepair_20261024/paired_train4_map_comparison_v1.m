end

function [alpha,realized,info] = alpha_for_applied_compensation(T,tauNom,comp,J0,Pc,Ptrue,wind,w,J,Jdot)
[~,realized,info]=allocate_control([T;tauNom-J0*comp],Pc,Ptrue,[]);
alpha=J\(realized(2:4)+wind-cross(w,J*w)-Jdot*w);
end

