end
currentFlags=struct('request_matches_nominal_minus_applied_comp',maxCurrentRequestClosure<=1e-8, ...
    'pure_allocator_matches_raw_realized',maxCurrentAllocatorClosure<=1e-8, ...
    'max_abs_current_request_closure_generalized_mixed_units',maxCurrentRequestClosure, ...
    'max_abs_current_allocator_realized_delta_generalized_mixed_units',maxCurrentAllocatorClosure, ...
