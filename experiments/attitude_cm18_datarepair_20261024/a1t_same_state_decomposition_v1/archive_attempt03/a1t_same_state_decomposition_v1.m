function s=metric_summary(x)
x=double(x); assert(~isempty(x)&&all(isfinite(x(:))),'A1TDecomp:Metric','Metric input is empty/non-finite.');
axisNames={'roll','pitch','yaw'};
axisStats=repmat(struct('axis','','signed_mean',0,'rms',0),1,3);
for a=1:3
    axisStats(a)=struct('axis',axisNames{a},'signed_mean',mean(x(:,a)), ...
        'rms',sqrt(mean(x(:,a).^2)));
end
s=struct('count',size(x,1),'axis',axisStats, ...
    'vector_rms',sqrt(mean(sum(x.^2,2))));
end

