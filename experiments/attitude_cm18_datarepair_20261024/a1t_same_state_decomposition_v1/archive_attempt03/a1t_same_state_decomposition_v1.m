    summaries(p).base_allocator_clip_count_by_channel=sum(D.base_allocator_clip(ids,:),1);
    summaries(p).base_motor_saturation_count_by_motor=sum(D.base_motor_saturated(ids,:),1);
    summaries(p).cproj_linear_surrogate_lower_bound_norm_mean=mean(D.cproj_lower(ids));
    summaries(p).cproj_linear_surrogate_upper_bound_norm_mean=mean(D.cproj_upper(ids));
    summaries(p).min_sigma_min_G=min(D.sigma_min(ids));
    summaries(p).max_condition_G=max(D.condition(ids));
