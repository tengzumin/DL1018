    'A1TDecomp:MissingRun','A required completed-scene artifact is missing.');
freeBytes = java.io.File(repoRoot).getFreeSpace();
assert(freeBytes>=30*1024^3,'A1TDecomp:DiskSpace','Require at least 30 GiB free before raw reads.');
outDir=fullfile(reportRoot,'a1t_same_state_decomposition_v1',sceneId);
outputPath=fullfile(outDir,['A1T_SAME_STATE_DECOMPOSITION_' sceneId '_v1.json']);
assert(~isfolder(outDir)&&~isfile(outputPath), ...
    'A1TDecomp:NoOverwrite','Refusing to reuse an existing diagnostic output directory.');

% All audit/status/release gates precede the raw SHA/read.
status = jsondecode(fileread(statusPath));
release = jsondecode(fileread(releasePath));
assert(strcmp(status.schema,'A1T_SCREEN12_CONTROL_RUN_STATUS_V1')&& ...
    strcmp(status.status,'RUN_COMPLETE_PENDING_ROOT_AUDIT')&& ...
    strcmp(status.log_status,'STABLE')&&strcmp(status.scene_id,sceneId)&& ...
    status.transitions==20000&&status.state_samples==20001&&status.cm18_events==1999&& ...
    status.first_plant_step_confirmed&&status.engine_invocation_entered&&status.plant_calls==1&& ...
    status.training_steps==0&&status.optimizer_steps==0&&~status.TEST_accessed&& ...
    isempty(status.safety_stop_reason)&&strcmpi(status.raw_sha256,audit.raw_sha256)&& ...
    strcmpi(status.run_start_sha256,audit.run_start_sha256)&& ...
    same_path(resolve_path(repoRoot,status.raw_path),rawPath), ...
    'A1TDecomp:RunStatus','The scene is not a terminal stable run with the expected scope.');
releaseSha = sha256_file(releasePath);
assert(strcmp(release.schema,'A1T_SCREEN12_CONTROL_ROOT_RELEASE_V1')&& ...
    strcmp(release.decision,'APPROVE_ONE_A1T_SCREEN12_FLIGHT')&& ...
    strcmp(release.scene_id,sceneId)&&release.sequence_index==1&& ...
    release.training_authorized==false&&release.optimizer_steps_authorized==0&& ...
    ~release.TEST_accessed&&strcmpi(release.preparation_result_sha256,prepSha)&& ...
    strcmpi(release.screen12_manifest_sha256,manifestSha)&& ...
    strcmpi(audit.release_sha256,releaseSha)&& ...
    strcmpi(release.deployment_parameters_sha256,audit.deployment_parameters_sha256)&& ...
    strcmpi(status.root_release_sha256,releaseSha), ...
    'A1TDecomp:Release','The exact first-scene release is not valid.');
rawSha = sha256_file(rawPath);
startSha = sha256_file(startPath);
statusSha = sha256_file(statusPath);
assert(strcmpi(rawSha,audit.raw_sha256)&&strcmpi(rawSha,status.raw_sha256)&& ...
    strcmpi(startSha,audit.run_start_sha256)&&strcmpi(startSha,status.run_start_sha256), ...
    'A1TDecomp:RawIdentity','Raw or run_start SHA differs from the independent PASS audit.');

deployment = jsondecode(fileread(deploymentPath));
deploymentSha = sha256_file(deploymentPath);
assert(strcmp(deployment.schema,'CM18_A1T_DEPLOYMENT_PARAMETERS_V1')&& ...
    strcmp(deployment.artifact_class,'DO_NOT_GIT_UPLOAD')&& ...
    strcmp(deployment.label_semantics, ...
        'direct compensation C*: raw network target is C*/beta; runtime clip then beta is unchanged')&& ...
    strcmpi(deployment.identity.checkpoint_sha256,release.checkpoint_sha256)&& ...
    deployment.identity.selected_step==40000&& ...
    strcmpi(deployment.identity.canonical_normalizer_float64_sha256, ...
        release.canonical_normalizer_float64_sha256)&& ...
    strcmpi(deploymentSha,release.deployment_parameters_sha256)&& ...
    deployment.identity.deployment_authorized==false, ...
    'A1TDecomp:Deployment','Frozen selected A1T model/deployment identity changed.');
assert_sha(forwardPath,release.forward_sha256);
enginePath = fullfile(repoRoot,'experiments','attitude_cm18_a1_20261024', ...
    'run_cm18_closed_loop_v1.m');
runnerPath = fullfile(runnerRoot,'run_a1t_screen12_control_v1.m');
prepareSourcePath = fullfile(runnerRoot,'prepare_a1t_screen12_control_v1.m');
assert_sha(enginePath,release.engine_sha256);
assert_sha(runnerPath,release.runner_sha256);
assert_sha(prepareSourcePath,release.prepare_script_sha256);

% Verify active source identities from the frozen preparation inventory.
inventory = normalize_struct_array(prep.c5_source_identity.c5_active_source_inventory);
assert(numel(inventory)==32&&audit.c5_active_source_file_count_sha_verified==numel(inventory)&& ...
    strcmpi(prep.c5_active_source_inventory_sha256,prep.c5_source_identity.c5_active_source_inventory_sha256)&& ...
    strcmpi(prep.c5_active_source_inventory_sha256,release.c5_active_source_inventory_sha256), ...
    'A1TDecomp:Inventory','The frozen 32-source inventory identity changed.');
inventoryReceipt = verify_inventory(inventory,repoRoot);
requiredHelpers = {'allocate_control','simulation_parameters','controller_parameters', ...
    'allocation_matrix','arm_mass_properties','distributed_mass_properties','arm_directions', ...
    'attitude_bs_step'};
coreDir = fullfile(repoRoot,'matlab','core');
for j=1:numel(requiredHelpers)
    helperPath = fullfile(coreDir,[requiredHelpers{j} '.m']);
    entry = find_inventory_path(inventory,helperPath,repoRoot);
    assert(strcmpi(sha256_file(helperPath),char(entry.sha256)), ...
        'A1TDecomp:HelperSHA','Reviewed helper changed: %s.',requiredHelpers{j});
end
oldPath = path;
pathCleanup = onCleanup(@()path(oldPath));
addpath(coreDir,'-begin');
addpath(fileparts(forwardPath),'-begin');
for j=1:numel(requiredHelpers)
    helperPath = fullfile(coreDir,[requiredHelpers{j} '.m']);
    assert(same_path(which(requiredHelpers{j}),helperPath), ...
        'A1TDecomp:HelperPath','Unexpected MATLAB helper resolution: %s.',requiredHelpers{j});
end
assert(same_path(which('cm18_a1_forward_v1'),forwardPath), ...
    'A1TDecomp:ForwardPath','Unexpected frozen forward-helper resolution.');

% Raw is opened only after its terminal/PASS/release/SHA gates above.
loaded = load(rawPath,'runStart','runIdentity');
assert(isfield(loaded,'runStart')&&isfield(loaded,'runIdentity')&& ...
    strcmp(matlab_text(loaded.runStart.schema),'A1T_SCREEN12_CONTROL_RUN_START_V1')&& ...
    strcmp(matlab_text(loaded.runIdentity.schema),'A1T_SCREEN12_CONTROL_RUN_IDENTITY_V1')&& ...
    strcmp(matlab_text(loaded.runStart.scene_id),sceneId)&& ...
    strcmp(matlab_text(loaded.runIdentity.scene_id),sceneId)&& ...
    strcmpi(matlab_text(loaded.runStart.root_release_sha256),releaseSha)&& ...
    strcmpi(matlab_text(loaded.runIdentity.root_release_sha256),releaseSha)&& ...
    strcmpi(matlab_text(loaded.runStart.preparation_result_sha256),prepSha)&& ...
    strcmpi(matlab_text(loaded.runStart.screen12_manifest_sha256),manifestSha), ...
    'A1TDecomp:EmbeddedIdentity','Embedded raw run identity differs from the audited run.');
runStart = loaded.runStart;
cfg = runStart.cfg;
assert(abs(double(cfg.plant.dt)-0.001)<=1e-15&& ...
    strcmp(matlab_text(cfg.controller_morphology_mode),'fixed')&& ...
    strcmp(matlab_text(cfg.controller_inertia_derivative_mode),'full')&& ...
    isequal(size(double(cfg.rbf.attitude.dmax(:))),[3 1])&& ...
    max(abs(double(cfg.rbf.attitude.dmax(:))-[45;45;4.7124]))<=1e-12&& ...
    abs(double(cfg.rbf.attitude.beta_rise_time)-2.2)<=1e-12, ...
    'A1TDecomp:ControllerConfig','Frozen dt, fixed J0, beta, or clip contract changed.');
parameters = deployment.parameters;
runtimeModel = runStart.opts.cm18_attitude_v1.model;
for nameCell = {'W1','b1','W2','b2','W3','b3','input_mean','input_std','train_axis_rms_rad_s2'}
    name = nameCell{1};
    assert(isfield(runtimeModel,name)&& ...
        isequaln(double(runtimeModel.(name)),double(parameters.(name))), ...
        'A1TDecomp:RuntimeModel','Raw runtime parameter differs from deployment: %s.',name);
end

n = 20000; dt = double(cfg.plant.dt);
time = read_vector(rawPath,'/log/time',n+1);
transitionTime = read_vector(rawPath,'/log/transition_time',n);
state = read_rows(rawPath,'/log/state',n+1,12);
rho = read_rows(rawPath,'/scene/arms/rho_true',n+1,4);
rhoDot = read_rows(rawPath,'/scene/arms/rhoDot_true',n+1,4);
windTorque = read_rows(rawPath,'/log/wind_torque_B',n,3);
nominalTorque = read_rows(rawPath,'/log/attitude_bs_nominal_torque_Nm',n,3);
requested = read_rows(rawPath,'/log/requested_generalized',n,4);
realized = read_rows(rawPath,'/log/realized_generalized',n,4);
eventFlag = read_vector(rawPath,'/log/cm18_event_flag',n)~=0;
eventRaw = read_rows_event_nan(rawPath,'/log/cm18_event_raw_acceleration_rad_s2',n,3,eventFlag);
held = read_rows(rawPath,'/log/cm18_applied_acceleration_held_rad_s2',n,3);
betaHeld = read_vector(rawPath,'/log/cm18_beta_held',n);
heldClipLog = read_vector(rawPath,'/log/cm18_clip_flag_held',n)~=0;
rawGeneralizedClip = read_rows(rawPath,'/log/generalized_clipped',n,4)~=0;
rawMotorSaturated = read_rows(rawPath,'/log/motor_saturated',n,4)~=0;
motorTc = double(h5read(rawPath,'/log/motor_time_constant_s'));
J0Logged = read_constant_matrix(rawPath,'/log/cm18_fixed_inertia_J0_kgm2',3,3,n);
assert(numel(time)==n+1&&numel(transitionTime)==n&& ...
    max(abs(time-(0:dt:20).'))<=1e-10&& ...
    max(abs(transitionTime-time(1:n)))<=1e-12&& ...
    all(isfinite([state(:);rho(:);rhoDot(:);windTorque(:);nominalTorque(:); ...
        requested(:);realized(:);held(:);betaHeld(:)]))&& ...
    all(isfinite(motorTc(:)))&&all(abs(motorTc(:))<=1e-12), ...
    'A1TDecomp:Trajectory','Raw scene must be finite, 20 s, and use ideal instantaneous motors.');

P0 = simulation_parameters(cfg,cfg.plant.arm_initial,zeros(4,1));
Pc = controller_parameters(cfg,P0,'fixed');
J0 = double(Pc.inertia); Jdot0 = double(Pc.inertia_dot); C0 = double(Pc.allocation.C);
assert(isequal(size(J0),[3 3])&&isequal(size(Jdot0),[3 3])&& ...
    isequal(size(C0),[4 4])&&max(abs(J0-J0Logged),[],'all')<=1e-12&& ...
    max(abs(Jdot0),[],'all')<=1e-14, ...
    'A1TDecomp:FixedController','Raw logged J0 differs or the fixed-controller Jdot is nonzero.');

eventRows = find(eventFlag);
expectedEvents = (11:10:19991).';
assert(isequal(eventRows,expectedEvents)&&numel(eventRows)==1999, ...
    'A1TDecomp:Events','Expected the frozen 100 Hz event schedule 11:10:19991.');
dmax = double(cfg.rbf.attitude.dmax(:));
betaRise = double(cfg.rbf.attitude.beta_rise_time);
expectedHeld = zeros(n,3); expectedBeta = zeros(n,1); expectedHeldClip = false(n,1);
for q=1:numel(eventRows)
    k = eventRows(q);
    y = eventRaw(k,:).';
    yClip = min(max(y,-dmax),dmax);
    b = min(k*dt/betaRise,1);
    kEnd = n;
    if q<numel(eventRows), kEnd=eventRows(q+1)-1; end
    expectedHeld(k:kEnd,:) = (b*yClip).';
    expectedBeta(k:kEnd) = b;
    expectedHeldClip(k:kEnd) = any(y~=yClip);
end
maxHeldRecon = max(abs(expectedHeld-held),[],'all');
maxBetaRecon = max(abs(expectedBeta-betaHeld));
assert(maxHeldRecon<=1e-10&&maxBetaRecon<=1e-12&&isequal(expectedHeldClip,heldClipLog), ...
    'A1TDecomp:HeldReconstruction','Raw event outputs do not reproduce beta/clip/ZOH logs.');

sceneCommand = read_rows(rawPath,'/scene/arms/command',n+1,4);
logCommand = read_rows(rawPath,'/log/arms/command',n+1,4);
assert(max(abs(sceneCommand-logCommand),[],'all')==0, ...
    'A1TDecomp:Command','Logged and source morphology commands differ.');
zAll = [zeros(1,4); cumsum(sceneCommand(1:n,:)*dt,1)];
validRows = (11:n).';
validCount = numel(validRows);
eventCount = numel(eventRows);
eventData = init_event_data(eventCount);
freshMinusHeld = zeros(validCount,3);
freshPhysicalDelta = zeros(validCount,3);
freshLinearDelta = zeros(validCount,3);
heldMinusFreshResidualLinear = zeros(validCount,3);
freshAllocatorMismatch = zeros(validCount,3);
freshClipRows = false(validCount,3);
freshAllocClipRows = false(validCount,4);
freshMotorSatRows = false(validCount,4);
heldAllocClipRows = false(n,4);
heldMotorSatRows = false(n,4);
baseAllocClipRows = false(n,4);
baseMotorSatRows = false(n,4);
actualRequestClosure = 0; actualAllocatorClosure = 0; eventForwardClosure = 0;
eventInputClosure = 0; eventResidualClosure = 0; eventTargetSolveClosure = 0;
eventBoundViolation = 0;
gCond = zeros(eventCount,1); gSigmaMin = zeros(eventCount,1);
baseAllocatorDelta = zeros(n,4);
allocatorCalls = 0; eventCounter = 0;

for k=1:n
    omega = state(k,10:12).';
    tauNom = nominalTorque(k,:).';
    alphaBS = J0\(tauNom-cross(omega,J0*omega)-Jdot0*omega);
    T = requested(k,1);
    Ptrue = simulation_parameters(cfg,rho(k,:).',rhoDot(k,:).');
    J = double(Ptrue.inertia);
    Jdot = double(Ptrue.inertia_dot);
    Ct = double(Ptrue.allocation.C);
    assert(all(isfinite([J(:);Jdot(:);Ct(:)]))&&rank(J)==3&&rank(Ct)==4, ...
        'A1TDecomp:TruePlantMatrix','Non-finite/singular true-inertia or allocation at transition %d.',k);

    L = [zeros(1,3);J0];
    M = Ct*(C0\L);
    G = J\M(2:4,:);
    assert(all(isfinite(G(:)))&&rank(G)==3, ...
        'A1TDecomp:SingularG','The full matrix G is singular/non-finite at transition %d.',k);
    wrench0 = Ct*(C0\[T;tauNom]);
    E0 = J\(wrench0(2:4)+windTorque(k,:).'-cross(omega,J*omega)-Jdot*omega)-alphaBS;
    assert(all(isfinite(E0)),'A1TDecomp:NonfiniteE0','E0 is non-finite at transition %d.',k);

    heldRequest = [T;tauNom-J0*held(k,:).'];
    [~,heldRealized,heldInfo] = allocate_control(heldRequest,Pc,Ptrue,[]);
    allocatorCalls = allocatorCalls+1;
    actualRequestClosure = max(actualRequestClosure,max(abs(requested(k,:).'-heldRequest)));
    actualAllocatorClosure = max(actualAllocatorClosure,max(abs(realized(k,:).'-heldRealized)));
    assert(isequal(logical(heldInfo.generalized_command_clipped(:)).',rawGeneralizedClip(k,:))&& ...
        isequal(logical(heldInfo.motor_saturated(:)).',rawMotorSaturated(k,:)), ...
        'A1TDecomp:ActualAllocatorFlags','Actual held allocator flags differ at transition %d.',k);
    heldAllocClipRows(k,:) = logical(heldInfo.generalized_command_clipped(:)).';
    heldMotorSatRows(k,:) = logical(heldInfo.motor_saturated(:)).';
    [~,baseRealized,baseInfo] = allocate_control([T;tauNom],Pc,Ptrue,[]);
    allocatorCalls = allocatorCalls+1;
    baseAllocClipRows(k,:) = logical(baseInfo.generalized_command_clipped(:)).';
    baseMotorSatRows(k,:) = logical(baseInfo.motor_saturated(:)).';
    baseAllocatorDelta(k,:) = (baseRealized-wrench0).';
    alphaHeld = J\(heldRealized(2:4)+windTorque(k,:).'-cross(omega,J*omega)-Jdot*omega);

    if k<11, continue; end
    r = k-10;
    previousTorqueMean = mean(requested(k-10:k-1,2:4),1);
    rawFeatures = [omega.' alphaBS.' T/double(cfg.plant.mass) ...
        sceneCommand(k,:) zAll(k,:) previousTorqueMean];
    [y,~,~,basis] = cm18_a1_forward_v1(rawFeatures,parameters);
    assert(numel(y)==3&&all(isfinite(y))&&all(isfinite(basis)), ...
        'A1TDecomp:Forward','Frozen forward is non-finite at transition %d.',k);
    clipped = min(max(y(:),-dmax),dmax);
    beta = betaHeld(k);
    assert(beta>0&&beta<=1,'A1TDecomp:Beta','Expected positive held beta after first event.');
    cFresh = beta*clipped;
    cHeld = held(k,:).';
    freshMinusHeld(r,:) = (cFresh-cHeld).';
    freshClipRows(r,:) = abs(y(:)-clipped)>1e-12;
    [~,freshRealized,freshInfo] = allocate_control( ...
        [T;tauNom-J0*cFresh],Pc,Ptrue,[]);
    allocatorCalls = allocatorCalls+1;
    freshAllocClipRows(r,:) = logical(freshInfo.generalized_command_clipped(:)).';
    freshMotorSatRows(r,:) = logical(freshInfo.motor_saturated(:)).';
    alphaFresh = J\(freshRealized(2:4)+windTorque(k,:).'-cross(omega,J*omega)-Jdot*omega);
    freshPhysicalDelta(r,:) = (alphaFresh-alphaHeld).';
    freshLinearDelta(r,:) = (-G*(cFresh-cHeld)).';
    heldMinusFreshResidualLinear(r,:) = (G*(cFresh-cHeld)).';
    freshAllocatorMismatch(r,:) = freshPhysicalDelta(r,:)-freshLinearDelta(r,:);

    if eventFlag(k)
        eventCounter = eventCounter+1;
        eventForwardClosure = max(eventForwardClosure,max(abs(y(:)-eventRaw(k,:).')));
    end
end

assert(eventCounter==eventCount&&actualRequestClosure<=1e-9&& ...
    actualAllocatorClosure<=1e-8, ...
    'A1TDecomp:CurrentClosure','Event count or actual request/allocator closure failed.');

% Read sparse event inputs once and compare them with the same reconstructed X18.
eventInputLog = read_rows_event_nan(rawPath,'/log/cm18_event_input_18',n,18,eventFlag);
eventZLog = read_rows_event_nan(rawPath,'/log/cm18_event_z_before_4',n,4,eventFlag);
eventULog = read_rows_event_nan(rawPath,'/log/cm18_event_u_current_4',n,4,eventFlag);
eventALog = read_rows_event_nan(rawPath, ...
    '/log/cm18_event_a_previous_requested_torque_mean_Nm',n,3,eventFlag);
for q=1:eventCount
    k=eventRows(q); omega=state(k,10:12).'; tauNom=nominalTorque(k,:).';
    alphaBS=J0\(tauNom-cross(omega,J0*omega)-Jdot0*omega);
    previousTorqueMean=mean(requested(k-10:k-1,2:4),1);
    x=[omega.' alphaBS.' requested(k,1)/double(cfg.plant.mass) ...
        sceneCommand(k,:) zAll(k,:) previousTorqueMean];
    eventInputClosure=max(eventInputClosure,max(abs(x-eventInputLog(k,:))));
    eventInputClosure=max(eventInputClosure,max(abs(zAll(k,:)-eventZLog(k,:))));
    eventInputClosure=max(eventInputClosure,max(abs(sceneCommand(k,:)-eventULog(k,:))));
    eventInputClosure=max(eventInputClosure,max(abs(previousTorqueMean-eventALog(k,:))));
end
assert(eventInputClosure<=1e-10&&eventForwardClosure<=1e-10, ...
    'A1TDecomp:EventParity','Reconstructed event X18 or forward differs from the audited raw log.');

% Event-only C*, fit/clip decomposition, linear-surrogate bounds and full allocator check.
for q=1:eventCount
    k=eventRows(q);
    omega=state(k,10:12).'; tauNom=nominalTorque(k,:).'; T=requested(k,1);
    Ptrue=simulation_parameters(cfg,rho(k,:).',rhoDot(k,:).');
    J=double(Ptrue.inertia); Jdot=double(Ptrue.inertia_dot); Ct=double(Ptrue.allocation.C);
    alphaBS=J0\(tauNom-cross(omega,J0*omega)-Jdot0*omega);
    L=[zeros(1,3);J0]; M=Ct*(C0\L); G=J\M(2:4,:);
    wrench0=Ct*(C0\[T;tauNom]);
    E0=J\(wrench0(2:4)+windTorque(k,:).'-cross(omega,J*omega)-Jdot*omega)-alphaBS;
    cStar=G\E0;
    eventTargetSolveClosure=max(eventTargetSolveClosure,max(abs(E0-G*cStar)));
    sigma=svd(G); sigmaMin=min(sigma);
    assert(all(isfinite([cStar(:);sigma(:)]))&&sigmaMin>0, ...
        'A1TDecomp:EventSolve','Singular event map or non-finite cStar at %d.',k);
    beta=betaHeld(k); y=eventRaw(k,:).';
    yClip=min(max(y,-dmax),dmax);
    cActual=held(k,:).';
    fitApplied=cStar-beta*y;
    clipIncrement=beta*(y-yClip);
    linearFit=G*fitApplied;
    linearClip=G*clipIncrement;
    linearResidual=E0-G*cActual;
    algebraResidual=linearResidual-(linearFit+linearClip);
    eventResidualClosure=max(eventResidualClosure,max(abs(algebraResidual)));
    assert(max(abs(cActual-beta*yClip))<=1e-10, ...
        'A1TDecomp:ActualAction','Logged held action differs from fresh event output.');
    if beta>0
        cProj=beta*min(max(cStar/beta,-dmax),dmax);
        projectionClip=abs(cStar/beta)>dmax;
    else
        cProj=zeros(3,1);
        projectionClip=abs(cStar)>1e-10;
    end
    lowerBound=sigmaMin*norm(cStar-cProj,2);
    upperBound=norm(G*(cStar-cProj),2);
    eventBoundViolation=max(eventBoundViolation,max(lowerBound-upperBound,0));
    [~,projRealized,projInfo]=allocate_control([T;tauNom-J0*cProj],Pc,Ptrue,[]);
    allocatorCalls=allocatorCalls+1;
    alphaProj=J\(projRealized(2:4)+windTorque(k,:).'-cross(omega,J*omega)-Jdot*omega);
    [~,actualRealized,actualInfo]=allocate_control([T;tauNom-J0*cActual],Pc,Ptrue,[]);
    allocatorCalls=allocatorCalls+1;
    alphaActual=J\(actualRealized(2:4)+windTorque(k,:).'-cross(omega,J*omega)-Jdot*omega);
    eventData.time(q)=transitionTime(k);
    eventData.plant_index(q)=k;
    eventData.beta(q)=beta;
    eventData.alpha_bs(q,:)=alphaBS.';
    eventData.E0(q,:)=E0.';
    eventData.G_row_major(q,:)=reshape(G.',1,9);
    eventData.raw_output(q,:)=y.';
    eventData.raw_target(q,:)=(cStar/beta).';
    eventData.raw_output_error(q,:)=(y-cStar/beta).';
    eventData.actual_action(q,:)=cActual.';
    eventData.fit_applied(q,:)=fitApplied.';
    eventData.clip_increment(q,:)=clipIncrement.';
    eventData.linear_fit_error(q,:)=linearFit.';
    eventData.linear_clip_error(q,:)=linearClip.';
    eventData.linear_actual_residual(q,:)=linearResidual.';
    eventData.full_actual_error(q,:)=(alphaActual-alphaBS).';
    eventData.full_cproj_error(q,:)=(alphaProj-alphaBS).';
    eventData.cstar(q,:)=cStar.';
    eventData.cproj(q,:)=cProj.';
    eventData.cproj_lower(q)=lowerBound;
    eventData.cproj_upper(q)=upperBound;
    eventData.sigma_min(q)=sigmaMin;
    eventData.condition(q)=cond(G);
    eventData.net_clip(q,:)=abs(y-yClip)>1e-12;
    eventData.cstar_projection_clip(q,:)=projectionClip.';
    eventData.actual_allocator_clip(q,:)=logical(actualInfo.generalized_command_clipped(:)).';
    eventData.actual_motor_saturated(q,:)=logical(actualInfo.motor_saturated(:)).';
    eventData.cproj_allocator_clip(q,:)=logical(projInfo.generalized_command_clipped(:)).';
    eventData.cproj_motor_saturated(q,:)=logical(projInfo.motor_saturated(:)).';
    eventData.base_allocator_clip(q,:)=baseAllocClipRows(k,:);
    eventData.base_motor_saturated(q,:)=baseMotorSatRows(k,:);
    eventData.base_matrix_delta(q,:)=baseAllocatorDelta(k,:);
    eventData.mse_cross_axis(q,:)=2*(linearFit.*linearClip).';
    eventData.mse_cross_vector(q)=2*dot(linearFit,linearClip);
    eventData.mse_identity_error(q,:)= ...
        (linearResidual.^2-linearFit.^2-linearClip.^2-2*linearFit.*linearClip).';
    gCond(q)=cond(G); gSigmaMin(q)=sigmaMin;
end
assert(eventResidualClosure<=1e-9&&eventTargetSolveClosure<=1e-9&&eventBoundViolation<=1e-10, ...
