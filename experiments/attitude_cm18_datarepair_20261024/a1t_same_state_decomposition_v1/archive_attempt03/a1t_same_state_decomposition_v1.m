        'cross_term',crossAxis,'actual',mseActual, ...
        'closure_error',mseActual-mseFit-mseClip-crossAxis, ...
        'definition','MSE_actual=MSE_fit+MSE_clip+2*mean(fit.*clip)');
    vectorFit=sqrt(mean(sum(D.linear_fit_error(ids,:).^2,2)));
    vectorClip=sqrt(mean(sum(D.linear_clip_error(ids,:).^2,2)));
    vectorActual=sqrt(mean(sum(D.linear_actual_residual(ids,:).^2,2)));
    vectorCross=mean(D.mse_cross_vector(ids));
    summaries(p).mse_vector=struct('fit',vectorFit^2,'clip',vectorClip^2, ...
        'cross_term',vectorCross,'actual',vectorActual^2, ...
        'closure_error',vectorActual^2-vectorFit^2-vectorClip^2-vectorCross);
    summaries(p).raw_clip_count_by_axis=sum(D.net_clip(ids,:),1);
    summaries(p).cstar_raw_clip_count_by_axis=sum(D.cstar_projection_clip(ids,:),1);
    summaries(p).actual_allocator_clip_count_by_channel=sum(D.actual_allocator_clip(ids,:),1);
    summaries(p).actual_motor_saturation_count_by_motor=sum(D.actual_motor_saturated(ids,:),1);
