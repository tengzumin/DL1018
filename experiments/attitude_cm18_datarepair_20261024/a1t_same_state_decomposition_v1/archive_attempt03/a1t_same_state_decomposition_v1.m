end

function M=read_constant_matrix(path,dataset,nr,nc,n)
a=double(h5read(path,dataset)); sz=size(a);
if isequal(sz,[nr nc])
    M=a;
elseif ndims(a)==3&&size(a,1)==nr&&size(a,2)==nc&&size(a,3)==n
    M=a(:,:,1);
    assert(max(abs(a-repmat(M,1,1,n)),[],'all')<=1e-12, ...
        'A1TDecomp:ConstantMatrix','Logged constant matrix varies: %s.',dataset);
elseif ndims(a)==3&&size(a,1)==n&&size(a,2)==nr&&size(a,3)==nc
    M=squeeze(a(1,:,:));
    assert(max(abs(a-repmat(reshape(M,1,nr,nc),n,1,1)),[],'all')<=1e-12, ...
        'A1TDecomp:ConstantMatrix','Logged constant matrix varies: %s.',dataset);
else
    error('A1TDecomp:MatrixLayout','Unsupported logged matrix layout: %s.',dataset);
end
assert(isequal(size(M),[nr nc])&&all(isfinite(M),'all'), ...
    'A1TDecomp:ConstantMatrix','Invalid constant matrix: %s.',dataset);
end

function value=matlab_text(value)
if ischar(value), value=strtrim(value);
elseif isstring(value)&&isscalar(value), value=char(value);
elseif iscell(value)&&isscalar(value), value=matlab_text(value{1});
elseif isnumeric(value)&&isscalar(value), value=char(value);
else, error('A1TDecomp:Text','Expected scalar text.');
end
end

function p=repo_relative(pathValue,repoRoot)
p=strrep(char(pathValue),[repoRoot filesep],''); p=strrep(p,'\','/');
end

function tf=same_path(a,b)
tf=strcmpi(char(java.io.File(char(a)).getCanonicalPath()), ...
    char(java.io.File(char(b)).getCanonicalPath()));
end

function assert_sha(pathValue,expected)
assert(isfile(pathValue)&&strcmpi(sha256_file(pathValue),char(expected)), ...
    'A1TDecomp:SHA','Missing file or SHA-256 mismatch: %s.',pathValue);
end

function digest=sha256_file(pathValue)
fid=fopen(pathValue,'rb'); assert(fid>=0,'A1TDecomp:HashOpen','Cannot read %s.',pathValue);
closer=onCleanup(@()fclose(fid));
md=java.security.MessageDigest.getInstance('SHA-256');
while true
    bytes=fread(fid,1024*1024,'*uint8');
    if isempty(bytes), break; end
    md.update(typecast(bytes(:),'int8'));
end
digest=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
clear closer
end
