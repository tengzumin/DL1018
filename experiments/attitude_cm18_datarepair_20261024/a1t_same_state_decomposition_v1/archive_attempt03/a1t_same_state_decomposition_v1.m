function summaries=summarize_event_phases(D,time,eventFlag)
names={'ALL_0_20','PRE_0_5','POST_5_20'};
masks={true(size(D.time)),D.time<5,D.time>=5};
template=struct('window','','event_count',0,'plant_index_first_last',[], ...
    'cstar_rad_s2',[],'cproj_feasible_action_rad_s2',[], ...
    'fit_applied_rad_s2',[],'clip_increment_rad_s2',[], ...
    'linear_fit_error_rad_s2',[],'linear_clip_error_rad_s2',[], ...
    'linear_actual_residual_rad_s2',[],'full_allocator_actual_error_rad_s2',[], ...
    'full_allocator_cproj_error_rad_s2',[],'mse_axis',[],'mse_vector',[], ...
    'raw_clip_count_by_axis',[],'cstar_raw_clip_count_by_axis',[], ...
    'actual_allocator_clip_count_by_channel',[],'actual_motor_saturation_count_by_motor',[], ...
    'cproj_allocator_clip_count_by_channel',[],'cproj_motor_saturation_count_by_motor',[], ...
    'base_allocator_clip_count_by_channel',[],'base_motor_saturation_count_by_motor',[], ...
    'cproj_linear_surrogate_lower_bound_norm_mean',[],'cproj_linear_surrogate_upper_bound_norm_mean',[], ...
    'min_sigma_min_G',[],'max_condition_G',[]);
