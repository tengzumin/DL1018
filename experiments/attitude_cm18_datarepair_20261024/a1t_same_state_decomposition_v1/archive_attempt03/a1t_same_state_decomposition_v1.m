    strcmp(prep.status,'PREPARED_A1T_SCREEN12_CONTROL_NO_PLANT_V1')&& ...
    prep.scene_count==12&&strcmpi(prep.screen12_manifest_sha256,manifestSha)&& ...
    strcmpi(prep.taskbook_sha256,'060ae7dbd36df7000711c961967a694186239af3520bdd581cf7d04b7b3e75fd'), ...
    'A1TDecomp:Preparation','The pinned A1T preparation identity changed.');
assert(strcmp(manifest.schema,'CM18_A1_FUTURE_DEVELOPMENT_SCREEN12_V1')&& ...
    strcmp(manifest.first_engineering_scene,sceneId), ...
    'A1TDecomp:Manifest','The fixed SCREEN12 manifest identity changed.');
manifestRow = find_scene(manifest.scenes,sceneId);
prepRow = find_scene(prep.scene_rows,sceneId);
assert(strcmp(manifestRow.task,'T1')&&strcmp(manifestRow.category,'ACTIVE_NO_WIND')&& ...
    strcmp(prepRow.task,'T1')&&strcmp(prepRow.category,'ACTIVE_NO_WIND'), ...
    'A1TDecomp:Scene','The fixed first scene does not match its manifest identity.');

assert(strcmp(audit.schema,'A1T_SCREEN12_INDEPENDENT_LOG_AUDIT_V1')&& ...
    strcmp(audit.status,'PASS')&&strcmp(audit.scene_id,sceneId)&& ...
    strcmpi(audit.audit_source_sha256,auditSourceSha)&& ...
    audit.counts.transitions==20000&&audit.counts.state_samples==20001&& ...
    audit.counts.cm18_events==1999&&isequal(double(audit.counts.event_first_last_matlab_index(:)),[11;19991])&& ...
    audit.c5_active_source_file_count_sha_verified==32&& ...
    audit.rbf_off.three_options_false&&audit.rbf_off.three_runtime_log_flags_false&& ...
    audit.rbf_off.fusion_and_head_false&&audit.rbf_off.update_flags_zero&& ...
    audit.rbf_off.raw_unclipped_held_outputs_zero&&audit.rbf_off.attitude_rbf_compensation_torque_zero, ...
    'A1TDecomp:Audit','The independent A1T scene audit is not a complete pinned PASS.');
