function receipts=verify_inventory(inventory,repoRoot)
template=struct('role','','path','','sha256','');
receipts=repmat(template,numel(inventory),1);
for k=1:numel(inventory)
    p=resolve_path(repoRoot,matlab_text(inventory(k).path));
    digest=sha256_file(p);
    assert(strcmpi(digest,matlab_text(inventory(k).sha256)), ...
        'A1TDecomp:InventorySHA','Active C5 source changed: %s.',p);
    receipts(k)=struct('role',matlab_text(inventory(k).role), ...
        'path',repo_relative(p,repoRoot),'sha256',digest);
end
end

function entry=find_inventory_path(inventory,target,repoRoot)
idx=[];
for k=1:numel(inventory)
    p=resolve_path(repoRoot,matlab_text(inventory(k).path));
    if same_path(p,target), idx(end+1)=k; end %#ok<AGROW>
end
assert(numel(idx)==1,'A1TDecomp:InventoryEntry','Expected one inventory entry for %s.',target);
entry=inventory(idx);
end

function p=resolve_path(repoRoot,value)
value=char(value);
if ~isempty(regexp(value,'^[A-Za-z]:[\\/]|^\\\\','once'))
    p=value;
else
    p=fullfile(repoRoot,strrep(value,'/',filesep));
end
end

function value=read_rows(path,dataset,nRows,nCols)
value=double(h5read(path,dataset));
if isequal(size(value),[nCols,nRows]), value=value.'; end
assert(isequal(size(value),[nRows,nCols]), ...
    'A1TDecomp:H5Matrix','Unexpected matrix shape at %s.',dataset);
end

function value=read_rows_event_nan(path,dataset,nRows,nCols,eventFlag)
