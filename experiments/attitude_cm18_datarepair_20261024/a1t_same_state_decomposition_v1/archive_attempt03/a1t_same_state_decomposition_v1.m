for p=1:numel(names)
    mask=masks{p}; ids=find(mask); summaries(p).window=names{p};
    summaries(p).event_count=numel(ids);
    if isempty(ids), continue; end
    summaries(p).plant_index_first_last=[D.plant_index(ids(1)) D.plant_index(ids(end))];
    fieldPairs={ ...
        'fit_applied','fit_applied_rad_s2'; ...
        'clip_increment','clip_increment_rad_s2'; ...
        'linear_fit_error','linear_fit_error_rad_s2'; ...
        'linear_clip_error','linear_clip_error_rad_s2'; ...
        'linear_actual_residual','linear_actual_residual_rad_s2'; ...
