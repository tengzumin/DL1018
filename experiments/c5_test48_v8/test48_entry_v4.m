function out = test48_entry_v4(mode,methodId)
% Isolated v4 runner. Every phase needs its own parent release.
if nargin<1, error('TEST48V4:Mode','An exact v4 mode is required.'); end
if nargin<2, methodId=''; end
mode=char(mode); methodId=char(methodId);
allowed={'PREPARE_NO_PLANT','ENGINEERING_DEV2','RUN_UNSTARTED_TEST_PARENT_APPROVED'};
assert(any(strcmp(mode,allowed)),'TEST48V4:Mode','Unsupported v4 mode.');
here=fileparts(mfilename('fullpath')); root=fileparts(fileparts(here));

contractPath=fullfile(here,'TEST48_RUN_CONTRACT_v4.json');
assert(isfile(contractPath),'TEST48V4:Inputs','v4 contract is missing.');
contract=jsondecode(fileread(contractPath));
manifestPath=repo_path(root,char(contract.method_source_manifest_path));
reportDir=fileparts(manifestPath);
assert(isfile(manifestPath),'TEST48V4:Inputs','Contract-bound v4 manifest is missing.');
manifest=jsondecode(fileread(manifestPath));
verify_code_contract(contract,manifest,root,contractPath,manifestPath);
switch mode
    case 'PREPARE_NO_PLANT'
        releasePath=fullfile(reportDir,'PREPARE_NO_PLANT_PARENT_RELEASE_v1.json');
        release=verify_stage_release(releasePath,'TEST48_V4_PREPARE_NO_PLANT_RELEASE_V1', ...
            'APPROVED_PREPARE_NO_PLANT_V1',contractPath,manifestPath,false,false,true);
        assert(double(release.max_plant_calls)==0,'TEST48V4:PrepareScope','Prepare release must authorize zero Plant calls.');
        resultPath=fullfile(reportDir,'PREPARE_NO_PLANT_RESULT_v1.json');
        failurePath=fullfile(reportDir,'PREPARE_NO_PLANT_FAILURE_v1.json');
        assert(~isfile(resultPath)&&~isfile(failurePath),'TEST48V4:NoRetry','Prepare output exists; preserve it and do not retry.');
        try
            out=prepare_no_plant(root,reportDir,contract,manifest);
        catch ME
            if ~isfile(failurePath), write_json_new(failurePath,struct('schema','TEST48_V4_PREPARE_FAILURE_V1', ...
                'status','FAILED_NO_RETRY','identifier',ME.identifier,'message',ME.message, ...
                'TEST_accessed',true,'plant_calls',0,'training_steps',0,'failed_utc',utc_now())); end
            rethrow(ME);
        end
    case 'ENGINEERING_DEV2'
        assert(any(strcmp(methodId,{'CORRECTED_DSSM14_G12_R32','CORRECTED_KAN14_G12_R32'})), ...
            'TEST48V4:EngineeringMethod','Engineering method must be the frozen DSSM or KAN identity.');
        releasePath=fullfile(reportDir,'ENGINEERING_DEV2_PARENT_RELEASE_v1.json');
        release=verify_stage_release(releasePath,'TEST48_V4_ENGINEERING_DEV2_RELEASE_V1', ...
            'APPROVED_ENGINEERING_DEV2_V1',contractPath,manifestPath,true,false,false);
        verify_prepare_precondition(reportDir,release);
        assert(double(release.max_plant_calls)==2&&strcmp(char(release.scene_id),char(contract.engineering_dev2(1).scene_id))&& ...
            isequal(string(release.method_ids(:)),string({'CORRECTED_DSSM14_G12_R32';'CORRECTED_KAN14_G12_R32'})), ...
            'TEST48V4:EngineeringReleaseScope','Engineering release must bind only DSSM/KAN, one fixed shared VAL scene, and two Plant calls.');
        out=run_engineering_dev2(root,here,reportDir,contract,manifest,release,methodId);
    case 'RUN_UNSTARTED_TEST_PARENT_APPROVED'
        assert(any(strcmp(methodId,contract.execution.unstarted_method_ids)), ...
            'TEST48V4:TestMethod','Method is not in the fixed five-method unstarted set.');
        releasePath=fullfile(reportDir,'RUN_UNSTARTED_TEST_PARENT_RELEASE_v1.json');
        release=verify_stage_release(releasePath,'TEST48_V4_UNSTARTED_TEST_RELEASE_V1', ...
            'APPROVED_RUN_UNSTARTED_TEST_V4',contractPath,manifestPath,true,false,true);
        verify_prepare_precondition(reportDir,release); verify_engineering_precondition(reportDir,release,contract);
        assert(double(release.max_plant_calls)==240&&double(release.scene_count)==48&& ...
            isequal(string(release.method_ids(:)),string(contract.execution.unstarted_method_ids(:))), ...
            'TEST48V4:TestReleaseScope','TEST release must bind the fixed five unstarted methods x 48 shared scenes.');
        out=run_one_method(root,here,reportDir,contract,manifest,release,methodId);
end
end
function verify_code_contract(c,m,root,contractPath,manifestPath)
