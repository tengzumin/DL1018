function [audits,maxAbs,elementCount]=compare_raw_tree(a,b,where)
audits=struct('path',{},'element_count',{},'max_abs_difference',{}); maxAbs=0; elementCount=0;
assert(isequal(class(a),class(b))||((isnumeric(a)||islogical(a))&&(isnumeric(b)||islogical(b))), ...
    'TEST48V4:EngineeringRawType','Raw type differs at %s.',where);
if isnumeric(a)||islogical(a)
    assert((isnumeric(b)||islogical(b))&&isequal(size(a),size(b)),'TEST48V4:EngineeringRawShape','Raw numeric shape differs at %s.',where);
    af=double(a(:)); bf=double(b(:));
    assert(isequal(isnan(af),isnan(bf))&&isequal(isinf(af),isinf(bf))&&all(af(isinf(af))==bf(isinf(bf))), ...
        'TEST48V4:EngineeringRawNonfinite','Raw NaN/Inf positions differ at %s.',where);
    mask=isfinite(af)&isfinite(bf); d=0; if any(mask), d=max(abs(af(mask)-bf(mask))); end
    assert(d<=1e-12,'TEST48V4:EngineeringRawTolerance','Numeric raw differs by %.17g at %s.',d,where);
    audits=struct('path',where,'element_count',numel(a),'max_abs_difference',d); maxAbs=d; elementCount=numel(a); return
elseif isstruct(a)
    assert(isstruct(b)&&isequal(size(a),size(b))&&isequal(sort(fieldnames(a)),sort(fieldnames(b))), ...
        'TEST48V4:EngineeringRawStruct','Raw struct schema differs at %s.',where);
    names=fieldnames(a); skipTiming={'controller_call_time_s','network_call_time_s','stage1_position_inference_time_s','stage1_position_event_inference_time_s'};
    for i=1:numel(a), for k=1:numel(names)
        if any(strcmpi(names{k},skipTiming)), continue; end
        [rows,d,n]=compare_raw_tree(a(i).(names{k}),b(i).(names{k}),[where '.' names{k}]); audits=[audits rows]; maxAbs=max(maxAbs,d); elementCount=elementCount+n; %#ok<AGROW>
    end, end
elseif iscell(a)
    assert(iscell(b)&&isequal(size(a),size(b)),'TEST48V4:EngineeringRawCell','Raw cell shape differs at %s.',where);
    for k=1:numel(a), [rows,d,n]=compare_raw_tree(a{k},b{k},sprintf('%s{%d}',where,k)); audits=[audits rows]; maxAbs=max(maxAbs,d); elementCount=elementCount+n; %#ok<AGROW>
    end
elseif istable(a)
    assert(istable(b)&&height(a)==height(b)&&isequal(a.Properties.VariableNames,b.Properties.VariableNames), ...
        'TEST48V4:EngineeringRawTable','Raw table schema differs at %s.',where);
    for k=1:width(a), [rows,d,n]=compare_raw_tree(a.(k),b.(k),[where '.' a.Properties.VariableNames{k}]); audits=[audits rows]; maxAbs=max(maxAbs,d); elementCount=elementCount+n; %#ok<AGROW>
    end
else
    assert(isequaln(a,b),'TEST48V4:EngineeringRawValue','Raw nonnumeric field differs at %s.',where);
end
end
