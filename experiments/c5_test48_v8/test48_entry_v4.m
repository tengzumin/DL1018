    assert(strcmp(c.method_order(k).id,method.method_id)&&strcmp(c.method_order(k).alias,method.alias)&& ...
        double(method.order)==k&&strcmp(method.v3_method_id,method.method_id)&&double(method.v3_order)==k, ...
        'TEST48V4:MethodOrder','v3/v4 method identity or order changed at row %d.',k);
    if isfield(method,'input_lock_path')&&~isempty(char(method.input_lock_path)), verify_file(repo_path(root,char(method.input_lock_path)),char(method.input_lock_sha256)); end
    if isfield(method,'run_contract_path')&&~isempty(char(method.run_contract_path)), verify_file(repo_path(root,char(method.run_contract_path)),char(method.run_contract_sha256)); end
    if isfield(method,'cfg_opts_snapshot_path')&&~isempty(char(method.cfg_opts_snapshot_path)), verify_file(repo_path(root,char(method.cfg_opts_snapshot_path)),char(method.cfg_opts_snapshot_sha256)); end
    for j=1:numel(method.source_refs), verify_file(repo_path(root,char(method.source_refs(j).path)),char(method.source_refs(j).sha256)); end
    for j=1:numel(method.model_refs), verify_file(repo_path(root,char(method.model_refs(j).path)),char(method.model_refs(j).sha256)); end
    if isfield(method,'runtime_tree_path')&&~isempty(char(method.runtime_tree_path))
        assert(strcmpi(sha256_tree(char(method.runtime_tree_path)),char(method.runtime_tree_sha256)), ...
            'TEST48V4:RuntimeTree','Frozen method runtime tree changed for %s.',method.method_id);
    end
    assert(strcmpi(char(method.global_platform_lock_sha256),char(m.global_platform_lock_sha256)), ...
        'TEST48V4:PlatformInheritance','Method does not inherit the locked global platform identity.');
end
for j=1:numel(m.shared_source_refs), verify_file(repo_path(root,char(m.shared_source_refs(j).path)),char(m.shared_source_refs(j).sha256)); end
assert(strcmpi(char(c.global_platform_lock_sha256),char(m.global_platform_lock_sha256))&& ...
    numel(m.global_platform_refs)==double(c.global_platform_ref_count), ...
    'TEST48V4:GlobalPlatformLock','v3 B platform lock/count differs from the contract.');
canonical='';
for j=1:numel(m.global_platform_refs)
    ref=m.global_platform_refs(j); verify_file(repo_path(root,char(ref.path)),char(ref.sha256));
    canonical=[canonical char(ref.path) ':' char(ref.sha256) newline]; %#ok<AGROW>
end
assert(strcmpi(sha256_bytes(uint8(unicode2native(canonical,'UTF-8'))),char(m.global_platform_lock_sha256)), ...
    'TEST48V4:GlobalPlatformSHA','v3 B global platform reference-set hash changed.');
helper='position_filter_realization_pcf_step_v3_5.m';
for id={'CORRECTED_DSSM14_G12_R32','CORRECTED_KAN14_G12_R32'}
    method=find_method(m,id{1}); ref=find_function_ref(method,'position_filter_realization_pcf_step_v3_5');
    assert(strcmpi(char(ref.sha256),'b4ae22db5bd444a162d0cd01a3a59a589f2e37077b089bb33693401b660228d0'), ...
        'TEST48V4:PCFIdentity','D/K active filter helper SHA changed.');
    assert(isempty(find_function_ref_optional(method,'position_stage1_update_head_pcf_v3_5')), ...
        'TEST48V4:InactivePCFUpdater','Do not bind the unreachable PCF updater branch.');
end
assert(strcmpi(char(m.v3_frozen_inputs.shared_scenes_sha256),'da207d858e8918f27c19fef30d4ad57206e20f1971e743515043d1a88a995d5c')&& ...
    strcmpi(char(m.v3_frozen_inputs.cfg_opts_sha256),'389fdfabd9fbd350d3bdd6df934cfe718eb7208bef2b7b4af02f1192cbb1b9e4')&& ...
    strcmpi(char(m.v3_frozen_inputs.index_sha256),'90940a818d293c66c34423a63088113557518c5ecdfd528a3f37867f391eef68'), ...
    'TEST48V4:FrozenInputIdentity','v4 does not point to the exact v3 frozen TEST input bytes.');
inputs=m.v3_frozen_inputs;
verify_file(repo_path(root,char(inputs.shared_scenes_path)),char(inputs.shared_scenes_sha256));
verify_file(repo_path(root,char(inputs.cfg_opts_path)),char(inputs.cfg_opts_sha256));
verify_file(repo_path(root,char(inputs.index_path)),char(inputs.index_sha256));
verify_file(repo_path(root,char(inputs.freeze_result_path)),char(inputs.freeze_result_sha256));
