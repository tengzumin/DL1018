    'TEST48V4:CodeSHA','The contract does not bind the exact v4 entry and launcher.');
% Verify the parent code-only authorization, taskbook, peer dependency review, and v3 source identity.
taskbookPath=repo_path(root,char(c.taskbook_path)); releasePath=repo_path(root,char(c.code_only_release_path));
