function release=verify_stage_release(path,schema,status,contractPath,manifestPath,plant,sceneGeneration,testAccess)
assert(isfile(path),'TEST48V4:ParentRelease','The separate parent stage release is missing: %s.',path);
release=jsondecode(fileread(path)); root=fileparts(fileparts(fileparts(mfilename('fullpath'))));
taskbookPath=fullfile(root,'reports','paper_continuation_20261023','TEST_UNSTARTED_DEPENDENCY_REPAIR_TASKBOOK_v4_ZH.md');
launcherPath=fullfile(fileparts(mfilename('fullpath')),'RUN_TEST48_EXACT_v1.ps1');
assert(isfield(release,'schema')&&strcmp(release.schema,schema)&&isfield(release,'status')&&strcmp(release.status,status), ...
    'TEST48V4:ParentRelease','Parent release schema/status mismatch.');
assert(isfield(release,'taskbook_sha256')&&strcmpi(release.taskbook_sha256,sha256_file(taskbookPath))&& ...
    isfield(release,'contract_sha256')&&strcmpi(release.contract_sha256,sha256_file(contractPath))&& ...
    isfield(release,'method_source_manifest_sha256')&&strcmpi(release.method_source_manifest_sha256,sha256_file(manifestPath))&& ...
    isfield(release,'entry_sha256')&&strcmpi(release.entry_sha256,sha256_file([mfilename('fullpath') '.m']))&& ...
    isfield(release,'launcher_sha256')&&strcmpi(release.launcher_sha256,sha256_file(launcherPath)), ...
    'TEST48V4:ParentReleaseBinding','Parent release does not bind exact v4 taskbook, contract, manifest, entry, and launcher.');
assert(isfield(release,'plant_authorized')&&logical(release.plant_authorized)==plant&& ...
    isfield(release,'scene_generation_authorized')&&logical(release.scene_generation_authorized)==sceneGeneration&& ...
    isfield(release,'TEST_accessed')&&logical(release.TEST_accessed)==testAccess&& ...
    isfield(release,'training_authorized')&&~logical(release.training_authorized), ...
    'TEST48V4:ParentReleaseFlags','Parent stage permissions are not exact.');
assert(isfield(release,'no_retry')&&logical(release.no_retry), ...
    'TEST48V4:ParentReleaseRetry','Each v4 stage release must preserve no-retry.');
end
function verify_prepare_precondition(reportDir,release)
resultPath=fullfile(reportDir,'PREPARE_NO_PLANT_RESULT_v1.json'); osPath=fullfile(reportDir,'PREPARE_NO_PLANT_MATLAB_OS_EXIT_v1.json');
assert(isfile(resultPath)&&isfile(osPath),'TEST48V4:PrepareEvidence','A completed no-Plant preparation and natural OS receipt are required.');
result=jsondecode(fileread(resultPath)); os=jsondecode(fileread(osPath));
assert(strcmp(result.status,'PASS_PREPARE_NO_PLANT')&&double(result.plant_calls)==0&&double(result.training_steps)==0&& ...
    logical(result.TEST_accessed)&&double(os.matlab_os_exit_code)==0, ...
    'TEST48V4:PrepareEvidence','Preparation must naturally exit OS0 after exact frozen-input/dependency preflight, with zero Plant/training.');
require_release_sha(release,'prepare_result_sha256',resultPath); require_release_sha(release,'prepare_os_exit_sha256',osPath);
end

function verify_engineering_precondition(reportDir,release,contract)
for k=1:2
    spec=contract.engineering_dev2(k); alias=char(spec.alias);
    resultPath=fullfile(reportDir,['ENGINEERING_' alias '_RESULT_v1.json']); osPath=fullfile(reportDir,['ENGINEERING_' alias '_MATLAB_OS_EXIT_v1.json']);
    assert(isfile(resultPath)&&isfile(osPath),'TEST48V4:EngineeringEvidence','Both engineering DEV2 results and natural OS receipts are required.');
    result=jsondecode(fileread(resultPath)); os=jsondecode(fileread(osPath));
    assert(strcmp(result.status,'PASS_ENGINEERING_DEV2_FULL_RAW')&&strcmp(result.method_id,char(spec.method_id))&& ...
        strcmp(result.scene_id,char(spec.scene_id))&&double(result.plant_calls)==1&&double(result.training_steps)==0&& ...
        double(result.max_abs_numeric_difference)<=1e-12&&logical(result.full_raw_numeric_comparison_pass)&& ...
        double(os.matlab_os_exit_code)==0, ...
        'TEST48V4:EngineeringResult','DSSM/KAN engineering replay failed identity, full-raw numeric comparison, or natural OS0.');
    field=['engineering_' alias '_result_sha256']; require_release_sha(release,field,resultPath);
    field=['engineering_' alias '_os_exit_sha256']; require_release_sha(release,field,osPath);
end
end

function require_release_sha(release,field,path)
assert(isfield(release,field)&&strcmpi(char(release.(field)),sha256_file(path)), ...
    'TEST48V4:ReleaseEvidenceHash','Stage release does not bind %s.',field);
end

