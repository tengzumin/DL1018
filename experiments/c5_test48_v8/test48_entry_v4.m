    'TEST48V4:BReuse','B48 reuse binding changed.');
verify_v3_unstarted_guard(root,m.v3_unstarted_guard);
for k=1:2
    e=c.engineering_dev2(k); me=m.engineering_dev2(k);
    assert(strcmp(e.method_id,me.method_id)&&strcmp(e.scene_id,'DL1018_VAL_T1_C00_W07'), ...
        'TEST48V4:EngineeringIdentity','Engineering DEV2 scene/method identity changed.');
