function result = prepare_c3_probe()
% Prepare and freeze the authorized C3 probe inputs. This entry never calls Plant.
here=fileparts(mfilename('fullpath')); repoRoot=fileparts(fileparts(here));
lockPath=fullfile(here,'C3_SOURCE_LOCK.json');
contractPath=fullfile(here,'C3_RUN_CONTRACT.json');
authPath=fullfile(repoRoot,'reports','delayed_prediction_c3_parent_20261023','USER_AUTHORIZATION.json');
assert(isfile(lockPath)&&isfile(contractPath)&&isfile(authPath), ...
    'C3:MissingPreparationInput','Source lock, contract, or user authorization is missing.');
lock=jsondecode(fileread(lockPath)); contract=jsondecode(fileread(contractPath));
auth=jsondecode(fileread(authPath));
assert(strcmp(lock.schema,'C3_DELAYED_PREDICTION_SOURCE_LOCK_V1')&& ...
    strcmp(lock.state,'PREPARED_NO_PLANT_PARENT_REVIEW_REQUIRED')&& ...
    strcmp(contract.schema,'C3_DELAYED_PREDICTION_RUN_CONTRACT_V1')&& ...
    strcmp(auth.status,'USER_AUTHORIZED_NEW_MECHANISM_STAGE_MAX_12')&& ...
    double(auth.max_new_sorties)==12&&double(auth.probe_sorties)==1&& ...
    double(auth.tau_s)==1&&double(auth.rho)==0.01&&double(auth.new_training)==0&& ...
    ~logical(auth.full72_authorized)&&~logical(auth.TEST_authorized), ...
    'C3:Scope','C3 lock, contract, or user authorization differs from the fixed stage.');
verify_file(authPath,lock.authorization_sha256);
verify_file(contractPath,lock.run_contract_sha256);
assert(strcmpi(sha256_file([mfilename('fullpath') '.m']),lock.prepare_entry_sha256), ...
    'C3:EntryHash','Preparation entry does not match its source lock.');
for q=1:numel(lock.isolated_sources), verify_file(lock.isolated_sources(q).path,lock.isolated_sources(q).sha256); end
for q=1:numel(lock.frozen_runtime_files), verify_file(lock.frozen_runtime_files(q).path,lock.frozen_runtime_files(q).sha256); end
for q=1:numel(lock.frozen_plant_files), verify_file(lock.frozen_plant_files(q).path,lock.frozen_plant_files(q).sha256); end
for q=1:numel(lock.shared_input_files), verify_file(lock.shared_input_files(q).path,lock.shared_input_files(q).sha256); end
verify_file(lock.c2_source_lock.path,lock.c2_source_lock.sha256);
verify_file(lock.c1_source_lock.path,lock.c1_source_lock.sha256);
verify_file(lock.c1_release.path,lock.c1_release.sha256);
verify_file(lock.c2_execution_ledger.path,lock.c2_execution_ledger.sha256);
verify_file(lock.c2_probe_summary.path,lock.c2_probe_summary.sha256);
c1lock=jsondecode(fileread(lock.c1_source_lock.path));
c1release=jsondecode(fileread(lock.c1_release.path));
verify_file(c1lock.r2_lock.path,c1lock.r2_lock.sha256);
r2=jsondecode(fileread(c1lock.r2_lock.path));
assert(numel(c1lock.shared_scenes)==12&&numel(r2.runtimeFiles)==9&&numel(r2.plantFiles)==22, ...
    'C3:Inventory','Expected fixed VAL12 and frozen 9-runtime/22-Plant inventory.');
sceneIds=string({c1lock.shared_scenes.scene_id}).';
assert(isequal(sceneIds,string(lock.scene_ids(:)))&&strcmp(char(sceneIds(1)),lock.probe_scene_id), ...
    'C3:SceneOrder','VAL12 order differs from the source lock.');
ledger=jsondecode(fileread(lock.c2_execution_ledger.path));
assert(strcmp(ledger.schema,'C2_EXECUTION_LEDGER_V1')&& ...
    double(ledger.authorization.actual_new_plant_starts)==12&&double(ledger.authorization.remaining)==0&& ...
    strcmp(ledger.run_template,'experiments/position_beta_clock_c2_20261023/runs_c2/<scene_id>/C2_ON1_BETA_ALIGNED/attempt_01/'), ...
    'C3:C2Ledger','C2 ledger is not the frozen completed 12-sortie ledger.');
baselineRows=lock.c2_baseline_runs;
assert(numel(ledger.run_rows)==12&&numel(baselineRows)==12&& ...
    isequal(string({baselineRows.scene_id}).',sceneIds), ...
    'C3:C2BaselineInventory','C2 ledger baseline paths do not cover VAL12 in fixed order.');
for q=1:numel(baselineRows)
    ledgerRow=find(strcmp({ledger.run_rows.scene_id},baselineRows(q).scene_id));
    attemptPath=fullfile(repoRoot,strrep(ledger.run_template,'<scene_id>',baselineRows(q).scene_id));
    assert(numel(ledgerRow)==1&&strcmpi(ledger.run_rows(ledgerRow).raw_sha256,baselineRows(q).raw_sha256)&& ...
        strcmpi(ledger.run_rows(ledgerRow).run_start_sha256,baselineRows(q).run_start_sha256)&& ...
        same_path(fullfile(attemptPath,'raw_run.mat'),baselineRows(q).raw_path)&& ...
        same_path(fullfile(attemptPath,'run_start.mat'),baselineRows(q).run_start_path), ...
        'C3:C2BaselineLedgerBinding','C2 raw/run_start SHA differs from execution ledger.');
end
probeRow=find(strcmp({baselineRows.scene_id},lock.probe_scene_id));
assert(numel(probeRow)==1&&strcmp(baselineRows(probeRow).status,'STABLE')&& ...
    strcmpi(baselineRows(probeRow).raw_sha256,lock.c2_probe_raw_sha256), ...
    'C3:C2Baseline','First-scene C2 raw differs from the frozen ledger.');
probeSummary=jsondecode(fileread(lock.c2_probe_summary.path));
summaryRow=probeSummary.run_rows;
assert(strcmp(summaryRow.scene_id,lock.probe_scene_id)&& ...
    strcmpi(summaryRow.raw_sha256,lock.c2_probe_raw_sha256)&& ...
    same_path(summaryRow.raw_path,baselineRows(probeRow).raw_path), ...
    'C3:C2SummaryPath','C2 probe summary path/hash differs from the frozen ledger-derived path.');
verify_file(baselineRows(probeRow).raw_path,lock.c2_probe_raw_sha256);
for q=1:numel(r2.runtimeFiles), addpath(fileparts(char(r2.runtimeFiles(q).path)),'-end'); end
for q=1:numel(r2.plantFiles), addpath(fileparts(char(r2.plantFiles(q).path)),'-end'); end
addpath(fullfile(repoRoot,'matlab','runtime'),'-end');
addpath(fullfile(repoRoot,'matlab','core'),'-end');
initPath=source_path(r2.runtimeFiles,'init_dl1018.m');
optionsPath=source_path(r2.runtimeFiles,'position_only_search_options.m');
headStepPath=source_path(r2.runtimeFiles,'position_only_search_head_step.m');
modelForwardPath=source_path(r2.runtimeFiles,'position_stage1_model_forward_v2.m');
addpath(fileparts(initPath),'-begin'); clear init_dl1018; rehash;
assert(same_path(which('init_dl1018'),initPath),'C3:InitPath','init_dl1018 resolved outside the frozen runtime.');
[cfg,~,resolvedRoot]=init_dl1018();
assert(same_path(resolvedRoot,repoRoot),'C3:ProjectRoot','init_dl1018 resolved a different project root.');
for q=1:numel(r2.runtimeFiles), addpath(fileparts(char(r2.runtimeFiles(q).path)),'-end'); end
for q=1:numel(r2.plantFiles), addpath(fileparts(char(r2.plantFiles(q).path)),'-end'); end
addpath(fullfile(repoRoot,'matlab','runtime'),'-end'); addpath(fullfile(repoRoot,'matlab','core'),'-end');
addpath(fileparts(initPath),'-begin');
addpath(fileparts(optionsPath),'-begin');
addpath(here,'-begin');
clear run_episode_dl1018 run_dl1018_closed_loop delayed_prediction_step_candidate ...
    position_only_search_options position_only_search_head_step position_stage1_model_forward_v2;
rehash;
assert(same_path(which('run_episode_dl1018'),fullfile(here,'run_episode_dl1018.m'))&& ...
    same_path(which('run_dl1018_closed_loop'),fullfile(here,'run_dl1018_closed_loop.m'))&& ...
    same_path(which('delayed_prediction_step_candidate'),fullfile(here,'delayed_prediction_step_candidate.m'))&& ...
    same_path(which('position_only_search_options'),optionsPath)&& ...
    same_path(which('position_only_search_head_step'),headStepPath)&& ...
    same_path(which('position_stage1_model_forward_v2'),modelForwardPath)&& ...
    same_path(which('init_dl1018'),initPath), ...
    'C3:CandidatePath','C3 or frozen C1 runtime resolved outside the locked paths.');
modelPack=load(lock.shared_input_files(strcmp({lock.shared_input_files.role},'model_mat')).path,'model');
assert(isfield(modelPack,'model')&&isstruct(modelPack.model),'C3:Model','Frozen DSSM14 model variable is absent.');
model=modelPack.model; W0=double(model.output_W);
assert(isequal(size(W0),[33,3])&&all(isfinite(W0(:)))&& ...
    strcmpi(hash_bytes(typecast(W0(:),'uint8')),lock.w0_sha256)&& ...
    strcmp(char(model.model_id),'DSSM14')&&double(model.seed)==2026102001&& ...
    double(model.selected_step)==60000&&double(model.input_dim)==14&& ...
    double(model.window)==32&&double(model.context_length)==32, ...
    'C3:ModelIdentity','Frozen X14 DSSM14 architecture or W0 identity mismatch.');
normalizerHash=hash_normalizer_arrays(model);
assert(strcmpi(normalizerHash,lock.normalizer_arrays_sha256), ...
    'C3:NormalizerIdentity','Frozen X14 normalizer arrays differ.');
assert(abs(double(cfg.plant.dt)-0.001)<=1e-12&& ...
    abs(double(cfg.rbf.position.beta_rise_time)-1.8)<=1e-12&& ...
    double(cfg.rbf.runtime.position_update_hz)==100, ...
    'C3:Clock','Plant/event/beta clocks differ from C2.');
opts=position_only_search_options(cfg,model,'FEATURE',12,1);
opts.position_delayed_prediction_enabled=true;
probeRun=baselineRows(probeRow);
verify_file(probeRun.run_start_path,probeRun.run_start_sha256);
runStartPack=load(probeRun.run_start_path,'runStart');
assert(isfield(runStartPack,'runStart')&&isfield(runStartPack.runStart,'cfg')&& ...
    isfield(runStartPack.runStart,'opts'),'C3:C2RunStart','Frozen C2 run_start lacks cfg/opts.');
c2Opts=runStartPack.runStart.opts; c3Opts=opts;
if isfield(c2Opts,'r2e_first_plant_step_marker'), c2Opts=rmfield(c2Opts,'r2e_first_plant_step_marker'); end
if isfield(c2Opts,'position_delayed_prediction_enabled')
    assert(~logical(c2Opts.position_delayed_prediction_enabled), ...
        'C3:ExistingPredictionFlag','Frozen C2 opts already enable the new prediction term.');
    c2Opts=rmfield(c2Opts,'position_delayed_prediction_enabled');
end
c3Opts=rmfield(c3Opts,'position_delayed_prediction_enabled');
c2Fields=sort(fieldnames(c2Opts)); c3Fields=sort(fieldnames(c3Opts)); optionDiffFields={};
if ~isequal(c2Fields,c3Fields)
    optionDiffFields={'<top_level_field_set>'};
else
    for q=1:numel(c2Fields)
        name=c2Fields{q}; if ~isequaln(c2Opts.(name),c3Opts.(name)), optionDiffFields{end+1}=name; end %#ok<AGROW>
    end
end
assert(isequaln(runStartPack.runStart.cfg,cfg)&&isequal(optionDiffFields,{}), ...
    'C3:C2OptionDiff','Candidate cfg/opts differ from frozen C2 run_start beyond the one prediction flag.');
pcf=opts.stage1_position_runtime; head=pcf.position_only_search_head;
assert(logical(pcf.enabled)&&logical(pcf.update_enabled)&& ...
    logical(pcf.command_filter_coordination_v3_5.enabled)&&logical(head.enabled)&& ...
    strcmpi(char(head.head_type),'FEATURE')&&double(head.gamma)==12&& ...
    double(head.kappa)==1&&double(pcf.beta_scale)==1&&isequal(double(pcf.weight),W0)&& ...
    isequal(double(pcf.model.output_W),W0)&&isequal(double(head.W0),W0)&& ...
    isscalar(opts.position_delayed_prediction_enabled)&&opts.position_delayed_prediction_enabled, ...
    'C3:Options','Candidate options differ beyond the single delayed-prediction flag.');
meta=c1lock.shared_scenes(1);
verify_file(meta.b_raw_path,meta.b_raw_sha256);
scenePack=load(meta.b_raw_path,'scene'); scene=scenePack.scene;
rawSceneId=char(scene.scene_id); disp(['C3_B_RAW_SCENE_ID=' rawSceneId]);
canonicalSceneId=char(sceneIds(1));
assert(valid_scene(scene,canonicalSceneId),'C3:SceneInput','Frozen B probe scene identity failed.');
sceneAliasNormalized=~strcmp(rawSceneId,canonicalSceneId);
if sceneAliasNormalized, scene.scene_id=canonicalSceneId; end
snapshotPath=fullfile(here,'C3_PREPARED_CONFIG_OPTS.mat');
resultPath=fullfile(here,'C3_PREPARE_RESULT.json');
assert(~isfile(snapshotPath)&&~isfile(resultPath),'C3:NoOverwrite','Prepared snapshot already exists.');
sourceIdentity=struct('wrapper',which('run_episode_dl1018'), ...
    'runtime',which('run_dl1018_closed_loop'),'helper',which('delayed_prediction_step_candidate'), ...
    'options',which('position_only_search_options'),'init',which('init_dl1018'));
sceneIdentity=struct('scene_id',canonicalSceneId,'raw_scene_id',rawSceneId, ...
    'canonical_scene_id',canonicalSceneId,'alias_normalized_in_memory',sceneAliasNormalized, ...
    'alias_rule','C2 valid_scene: canonical scene ID or canonical ID plus _ACC_FIX_V1', ...
    'B_raw_path',meta.b_raw_path, ...
    'B_raw_sha256',meta.b_raw_sha256,'C2_raw_path',probeRun.raw_path, ...
    'C2_raw_sha256',probeRun.raw_sha256,'C2_ledger_sha256',lock.c2_execution_ledger.sha256, ...
    'payload_sha256',meta.payload_sha256);
modelIdentity=struct('model_id',char(model.model_id),'W0_sha256',lock.w0_sha256, ...
    'normalizer_arrays_sha256',normalizerHash,'input_dim',double(model.input_dim), ...
    'window',double(model.window),'selected_step',double(model.selected_step));
save(snapshotPath,'cfg','opts','W0','modelIdentity','sceneIdentity','sourceIdentity','-v7.3');
snapshotSha=sha256_file(snapshotPath);
result=struct('schema','C3_PREPARE_RESULT_V1','status','PREPARED_WAIT_PARENT_PROBE_RELEASE', ...
    'created_utc',utc_now(),'source_lock_sha256',sha256_file(lockPath), ...
    'run_contract_sha256',sha256_file(contractPath),'probe_scene_id',char(sceneIds(1)), ...
    'candidate_condition_id',contract.candidate_condition_id,'tau_s',1,'rho',0.01, ...
    'new_flag_only','opts.position_delayed_prediction_enabled=true', ...
    'cfg_opts_snapshot_path',snapshotPath,'cfg_opts_snapshot_sha256',snapshotSha, ...
    'c2_run_start_path',probeRun.run_start_path,'c2_run_start_sha256',probeRun.run_start_sha256, ...
    'cfg_matches_c2_run_start',true,'opts_diff_fields',{{'position_delayed_prediction_enabled'}}, ...
    'source_identity',sourceIdentity,'scene_identity',sceneIdentity,'model_identity',modelIdentity, ...
    'plant_calls',0,'run_episode_called',false,'training_steps',0,'optimizer_steps',0, ...
    'gain_or_seed_search',false,'full72_started',false,'TEST_accessed',false);
write_json_new(resultPath,result);
end
function ok=valid_scene(scene,sceneId)
ok=isstruct(scene)&&isfield(scene,'scene_id')&& ...
    (strcmp(char(scene.scene_id),sceneId)||strcmp(char(scene.scene_id),[sceneId '_ACC_FIX_V1']))&& ...
    isfield(scene,'time')&&numel(scene.time)==20001&&abs(double(scene.time(1)))<=1e-12&& ...
    abs(double(scene.time(end))-20)<=1e-12&&isfield(scene,'environment_wind_I')&& ...
    isequal(size(scene.environment_wind_I),[20001,3])&&isfield(scene,'initial_state')&&numel(scene.initial_state)==12&& ...
    isfield(scene,'arms')&&all(isfield(scene.arms,{'command','rhoDot_hat','rhoDot_true','rho_hat','rho_true'}))&& ...
    isfield(scene,'reference')&&all(isfield(scene.reference,{'position','velocity','acceleration','yaw','yaw_rate','yaw_acceleration'}))&& ...
    isequal(size(scene.reference.position),[20001,3])&&isequal(size(scene.reference.velocity),[20001,3])&& ...
    isequal(size(scene.reference.acceleration),[20001,3])&&isequal(size(scene.reference.yaw),[20001,1])&& ...
    isequal(size(scene.reference.yaw_rate),[20001,1])&&isequal(size(scene.reference.yaw_acceleration),[20001,1])&& ...
    isequal(size(scene.arms.command),[20001,4])&&isequal(size(scene.arms.rhoDot_hat),[20001,4])&& ...
    isequal(size(scene.arms.rhoDot_true),[20001,4])&&isequal(size(scene.arms.rho_hat),[20001,4])&& ...
    isequal(size(scene.arms.rho_true),[20001,4])&&all(isfinite(scene.time(:)))&& ...
    all(isfinite(scene.environment_wind_I(:)))&&all(isfinite(scene.initial_state(:)))&& ...
    all(isfinite(scene.arms.command(:)))&&all(isfinite(scene.arms.rhoDot_hat(:)))&& ...
    all(isfinite(scene.arms.rhoDot_true(:)))&&all(isfinite(scene.arms.rho_hat(:)))&&all(isfinite(scene.arms.rho_true(:)))&& ...
    all(isfinite(scene.reference.position(:)))&&all(isfinite(scene.reference.velocity(:)))&& ...
    all(isfinite(scene.reference.acceleration(:)))&&all(isfinite(scene.reference.yaw(:)))&& ...
    all(isfinite(scene.reference.yaw_rate(:)))&&all(isfinite(scene.reference.yaw_acceleration(:)));
end
function path=source_path(items,name)
assert(isfield(items,'path'),'C3:SourceInventory','Frozen source inventory lacks path fields.');
names=cell(size(items));
for k=1:numel(items), [~,base,ext]=fileparts(char(items(k).path)); names{k}=[base ext]; end
idx=find(strcmp(names,name)); assert(numel(idx)==1,'C3:SourceInventory','Expected exactly one frozen source %s.',name);
path=char(items(idx).path);
end
function verify_file(path,expected)
assert(isfile(path),'C3:MissingFile','Missing frozen file: %s',path);
assert(strcmpi(sha256_file(path),expected),'C3:SourceHash','Frozen file SHA-256 mismatch: %s',path);
end
function h=sha256_file(path)
md=java.security.MessageDigest.getInstance('SHA-256'); fid=fopen(path,'r');
assert(fid>=0,'C3:ReadFile','Cannot read %s.',path); cleanup=onCleanup(@()fclose(fid));
while true, b=fread(fid,8*1024*1024,'*uint8'); if isempty(b), break; end; md.update(b); end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
function h=hash_bytes(bytes)
md=java.security.MessageDigest.getInstance('SHA-256'); md.update(typecast(uint8(bytes(:)),'int8'));
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
function h=hash_normalizer_arrays(model)
md=java.security.MessageDigest.getInstance('SHA-256');
for name={'input_mu','input_sigma'}
    field=name{1}; a=reshape(double(model.(field)),1,[]);
    assert(numel(a)==14&&all(isfinite(a)),'C3:NormalizerShape','Invalid %s.',field);
    header=[field char(0) '((1, 14), ''float64'')' char(0)];
    md.update(typecast(uint8(unicode2native(header,'UTF-8')),'int8'));
    md.update(typecast(a(:),'int8'));
end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
function tf=same_path(a,b)
tf=strcmpi(char(java.io.File(a).getCanonicalPath()),char(java.io.File(b).getCanonicalPath()));
end
function write_json_new(path,value)
fid=fopen(path,'w'); assert(fid>=0,'C3:NoOverwrite','Cannot create %s.',path);
cleanup=onCleanup(@()fclose(fid)); fwrite(fid,jsonencode(value),'char');
end
function t=utc_now()
t=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z'''));
end

