        'partial_raw_sha256',file_sha_if_exists(rawPath),'run_start_sha256',file_sha_if_exists(runStartPath), ...
        'source_lock_sha256',sourceLockSha,'release_sha256',releaseSha, ...
        'prepare_result_sha256',prepareSha,'cfg_opts_snapshot_sha256',snapshotSha, ...
        'training_steps',0,'optimizer_steps',0,'TEST_accessed',false, ...
        'attempt_bytes_at_failure',directory_bytes(attemptDir),'experiment_bytes_at_failure',directory_bytes(here));
