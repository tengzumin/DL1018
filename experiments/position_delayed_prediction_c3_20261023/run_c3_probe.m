function status=run_c3_probe(mode)
% Run the single C3 probe only after a parent release binds this exact build.
if nargin~=1||~strcmpi(char(mode),'PARENT_APPROVED_PROBE')
    error('C3:Mode','Pass exactly PARENT_APPROVED_PROBE after parent review.');
end
here=fileparts(mfilename('fullpath')); repoRoot=fileparts(fileparts(here));
releasePath=fullfile(here,'C3_PROBE_RELEASE.json');
lockPath=fullfile(here,'C3_SOURCE_LOCK.json'); contractPath=fullfile(here,'C3_RUN_CONTRACT.json');
resultPath=fullfile(here,'C3_PREPARE_RESULT.json'); snapshotPath=fullfile(here,'C3_PREPARED_CONFIG_OPTS.mat');
assert(isfile(releasePath)&&isfile(lockPath)&&isfile(contractPath)&&isfile(resultPath)&&isfile(snapshotPath), ...
    'C3:ReleaseInputs','Parent release, source lock, contract, preparation result, and snapshot are required.');
release=jsondecode(fileread(releasePath)); lock=jsondecode(fileread(lockPath));
contract=jsondecode(fileread(contractPath)); prepared=jsondecode(fileread(resultPath));
sourceLockSha=sha256_file(lockPath); releaseSha=sha256_file(releasePath);
prepareSha=sha256_file(resultPath); snapshotSha=sha256_file(snapshotPath);
runnerPath=[mfilename('fullpath') '.m']; runnerSha=sha256_file(runnerPath);
assert(strcmp(release.schema,'C3_DELAYED_PREDICTION_PROBE_RELEASE_V1')&& ...
    strcmp(release.state,'APPROVED_C3_PROBE')&&logical(release.plant_authorized)&& ...
    double(release.max_new_sorties)==1&&double(release.probe_sorties)==1&& ...
    ~logical(release.full72_authorized)&&~logical(release.TEST_authorized)&& ...
    double(release.training_steps)==0&&double(release.optimizer_steps)==0&& ...
    ~logical(release.gain_or_seed_search)&&strcmpi(release.candidate_condition_id,contract.candidate_condition_id)&& ...
    strcmpi(release.probe_scene_id,prepared.probe_scene_id)&&same_path(release.runner_path,runnerPath)&& ...
    strcmpi(release.runner_sha256,runnerSha)&&strcmpi(release.source_lock_sha256,sourceLockSha)&& ...
    strcmpi(release.prepare_result_sha256,prepareSha)&&strcmpi(release.cfg_opts_snapshot_sha256,snapshotSha), ...
    'C3:ReleaseBinding','Parent release does not approve this exact one-probe runner and prepared inputs.');
assert(strcmp(lock.schema,'C3_DELAYED_PREDICTION_SOURCE_LOCK_V1')&& ...
    strcmp(lock.state,'PREPARED_NO_PLANT_PARENT_REVIEW_REQUIRED')&& ...
    ~logical(lock.plant_call_in_prepare)&&~logical(lock.plant_authorized_by_this_lock)&& ...
    strcmp(prepared.status,'PREPARED_WAIT_PARENT_PROBE_RELEASE')&& ...
    strcmpi(prepared.source_lock_sha256,sourceLockSha)&&strcmpi(prepared.cfg_opts_snapshot_sha256,snapshotSha)&& ...
    strcmpi(contract.schema,'C3_DELAYED_PREDICTION_RUN_CONTRACT_V1')&& ...
    strcmpi(contract.candidate_condition_id,release.candidate_condition_id)&& ...
    double(contract.candidate.tau_s)==1&&double(contract.candidate.rho)==0.01, ...
    'C3:PreparedBinding','Prepared state, candidate, or immutable source lock differs from release.');
verify_file(lock.run_contract_path,lock.run_contract_sha256);
verify_file(lock.authorization_path,lock.authorization_sha256);
verify_file(lock.c2_source_lock.path,lock.c2_source_lock.sha256);
verify_file(lock.c2_release.path,lock.c2_release.sha256);
verify_file(lock.c2_probe_summary.path,lock.c2_probe_summary.sha256);
for k=1:numel(lock.isolated_sources), verify_file(lock.isolated_sources(k).path,lock.isolated_sources(k).sha256); end
for k=1:numel(lock.frozen_runtime_files), verify_file(lock.frozen_runtime_files(k).path,lock.frozen_runtime_files(k).sha256); end
for k=1:numel(lock.frozen_plant_files), verify_file(lock.frozen_plant_files(k).path,lock.frozen_plant_files(k).sha256); end
for k=1:numel(lock.shared_input_files), verify_file(lock.shared_input_files(k).path,lock.shared_input_files(k).sha256); end
verify_file(lock.c1_source_lock.path,lock.c1_source_lock.sha256);
verify_file(lock.c1_release.path,lock.c1_release.sha256);
verify_file(lock.c2_execution_ledger.path,lock.c2_execution_ledger.sha256);
c1lock=jsondecode(fileread(lock.c1_source_lock.path)); c1release=jsondecode(fileread(lock.c1_release.path));
verify_file(c1lock.r2_lock.path,c1lock.r2_lock.sha256); r2=jsondecode(fileread(c1lock.r2_lock.path));
ledger=jsondecode(fileread(lock.c2_execution_ledger.path));
probeRow=find(strcmp({lock.c2_baseline_runs.scene_id},prepared.probe_scene_id));
ledgerRow=find(strcmp({ledger.run_rows.scene_id},prepared.probe_scene_id));
assert(numel(probeRow)==1&&numel(ledgerRow)==1&& ...
    same_path(lock.c2_baseline_runs(probeRow).raw_path,prepared.scene_identity.C2_raw_path)&& ...
    same_path(lock.c2_baseline_runs(probeRow).raw_path,lock.c2_probe_raw_path)&& ...
    same_path(lock.c2_baseline_runs(probeRow).run_start_path,prepared.c2_run_start_path)&& ...
    strcmpi(lock.c2_baseline_runs(probeRow).raw_sha256,prepared.scene_identity.C2_raw_sha256)&& ...
    strcmpi(lock.c2_baseline_runs(probeRow).raw_sha256,ledger.run_rows(ledgerRow).raw_sha256)&& ...
    strcmpi(lock.c2_baseline_runs(probeRow).run_start_sha256,ledger.run_rows(ledgerRow).run_start_sha256), ...
    'C3:C2Comparator','C2 comparator identity differs from frozen ledger.');
verify_file(prepared.scene_identity.C2_raw_path,prepared.scene_identity.C2_raw_sha256);
verify_file(prepared.scene_identity.B_raw_path,prepared.scene_identity.B_raw_sha256);
verify_file(prepared.c2_run_start_path,prepared.c2_run_start_sha256);
assert(strcmp(prepared.scene_identity.scene_id,prepared.probe_scene_id)&& ...
    strcmp(prepared.scene_identity.canonical_scene_id,prepared.probe_scene_id)&& ...
    (strcmp(prepared.scene_identity.raw_scene_id,prepared.probe_scene_id)|| ...
    strcmp(prepared.scene_identity.raw_scene_id,[prepared.probe_scene_id '_ACC_FIX_V1'])), ...
    'C3:SceneIdentity','Prepared source/canonical B scene ID mapping differs from the C2 alias contract.');
pack=load(snapshotPath,'cfg','opts','W0','modelIdentity','sceneIdentity','sourceIdentity');
assert(isfield(pack,'cfg')&&isfield(pack,'opts')&&isfield(pack,'W0')&& ...
    isfield(pack,'modelIdentity')&&isfield(pack,'sceneIdentity')&&isfield(pack,'sourceIdentity')&& ...
    isequaln(pack.sceneIdentity,prepared.scene_identity)&& ...
    isequaln(pack.sourceIdentity,prepared.source_identity)&& ...
    logical(pack.opts.position_delayed_prediction_enabled), ...
    'C3:Snapshot','Prepared cfg/opts/source/scene snapshot differs from the parent-approved result.');
cfg=pack.cfg; opts=pack.opts; opts.r2e_first_plant_step_marker='';
scenePack=load(prepared.scene_identity.B_raw_path,'scene'); scene=scenePack.scene;
sourceSceneId=char(scene.scene_id); sceneId=char(prepared.probe_scene_id);
assert(valid_scene(scene,sceneId)&&strcmp(sourceSceneId,prepared.scene_identity.raw_scene_id), ...
    'C3:SceneRaw','Frozen B scene no longer matches the prepared identity.');
scene.scene_id=sceneId;
initPath=source_path(r2.runtimeFiles,'init_dl1018.m');
optionsPath=source_path(r2.runtimeFiles,'position_only_search_options.m');
headStepPath=source_path(r2.runtimeFiles,'position_only_search_head_step.m');
modelForwardPath=source_path(r2.runtimeFiles,'position_stage1_model_forward_v2.m');
restoredefaultpath; rehash;
[sourcePaths,sourceHashes]=active_source_files(lock);
for k=1:numel(sourcePaths)
    [~,~,ext]=fileparts(sourcePaths{k}); if strcmpi(ext,'.m'), addpath(fileparts(sourcePaths{k}),'-end'); end
end
addpath(fullfile(repoRoot,'matlab','runtime'),'-end'); addpath(fullfile(repoRoot,'matlab','core'),'-end');
addpath(fileparts(optionsPath),'-begin'); addpath(fileparts(initPath),'-begin'); addpath(here,'-begin');
clear run_episode_dl1018 run_dl1018_closed_loop delayed_prediction_step_candidate ...
    position_only_search_options position_only_search_head_step position_stage1_model_forward_v2 init_dl1018;
rehash;
for k=1:numel(sourcePaths)
    verify_file(sourcePaths{k},sourceHashes{k}); [~,name,ext]=fileparts(sourcePaths{k});
    if strcmpi(ext,'.m')
        assert(same_path(which(name),sourcePaths{k}),'C3:ResolvedSourceShadow', ...
            'Locked source %s resolved to a shadowed path.',name);
    end
end
assert(same_path(which('position_only_search_options'),optionsPath)&& ...
    same_path(which('position_only_search_head_step'),headStepPath)&& ...
    same_path(which('position_stage1_model_forward_v2'),modelForwardPath)&& ...
    same_path(which('init_dl1018'),initPath), ...
    'C3:CandidatePath','Resolved C1 option/model/init source differs from the source lock.');
attemptRoot=fullfile(here,'runs_c3');
if isfolder(attemptRoot)
    startedMarkers=dir(fullfile(attemptRoot,'**','attempt_started.marker'));
    plantMarkers=dir(fullfile(attemptRoot,'**','first_plant_step.marker'));
else
    startedMarkers=struct('name',{}); plantMarkers=struct('name',{});
end
attemptDir=fullfile(attemptRoot,sceneId,contract.candidate_condition_id,'attempt_01');
conditionDir=fileparts(attemptDir); existing=dir(fullfile(conditionDir,'attempt_*'));
assert(isempty(startedMarkers)&&isempty(plantMarkers),'C3:GlobalAttemptExists', ...
    'A C3 attempt marker already exists anywhere under runs_c3; no retry is allowed.');
assert(~isfolder(attemptDir)&&isempty(existing)&&~isfile(fullfile(here,'C3_PROBE_SUMMARY.json')), ...
    'C3:NoRetry','A C3 probe attempt or summary already exists; retries are forbidden.');
budget=jsondecode(fileread(lock.authorization_path)); reserveBytes=int64(80000000);
assert(double(budget.max_new_sorties)==12&&double(budget.probe_sorties)==1&& ...
    double(budget.remaining_after_parent_probe_gate)==11&&double(budget.new_output_cap_bytes)==1073741824&& ...
    double(budget.minimum_free_bytes)==30000000000&&double(release.max_new_sorties)==1, ...
    'C3:UserBudget','This release must authorize the single probe only; 11 sorties remain gated.');
assert(directory_bytes(here)+double(reserveBytes)<=double(budget.new_output_cap_bytes)&& ...
    double(java.io.File(repoRoot).getUsableSpace())-double(reserveBytes)>=double(budget.minimum_free_bytes), ...
    'C3:ResourceBudget','Probe reserve violates the one-GiB output cap or 30-GB free-space floor.');
jobLockPath=char(c1release.shared_heavy_job_lock_path);
assert(isfile(jobLockPath),'C3:SharedLockMissing','The frozen C1 shared heavy-job lock is missing.');
raf=java.io.RandomAccessFile(jobLockPath,'rw'); channel=raf.getChannel(); jobLock=channel.tryLock();
assert(~isempty(jobLock),'C3:ConcurrentHeavyJob','The shared closed-loop heavy-job lock is held.');
cleanup=onCleanup(@()release_job_lock(jobLock,channel,raf)); %#ok<NASGU>
if ~isfolder(attemptDir), mkdir(attemptDir); end
markerPath=fullfile(attemptDir,'first_plant_step.marker'); assert(~isfile(markerPath),'C3:MarkerExists','Probe marker already exists.');
opts.r2e_first_plant_step_marker=markerPath;
rawPath=fullfile(attemptDir,'raw_run.mat'); runStartPath=fullfile(attemptDir,'run_start.mat');
statusPath=fullfile(attemptDir,'run_status.json'); failurePath=fullfile(attemptDir,'C3_PROBE_FAILURE.json');
assert(~isfile(rawPath)&&~isfile(runStartPath)&&~isfile(statusPath)&&~isfile(failurePath), ...
    'C3:NoOverwrite','Probe output path already exists.');
startedUtc=utc_now(); invocationEntered=false;
try
    write_text(fullfile(attemptDir,'attempt_started.marker'),[startedUtc newline 'ABOUT_TO_CALL_EPISODE' newline]);
    runStart=struct('schema','C3_DELAYED_PREDICTION_RUN_START_V1','scene_id',sceneId, ...
        'source_scene_id',sourceSceneId,'condition',contract.candidate_condition_id, ...
        'started_utc',startedUtc,'source_lock_sha256',sourceLockSha,'release_sha256',releaseSha, ...
        'prepare_result_sha256',prepareSha,'cfg_opts_snapshot_sha256',snapshotSha, ...
        'C2_raw_path',prepared.scene_identity.C2_raw_path,'C2_raw_sha256',prepared.scene_identity.C2_raw_sha256, ...
        'C2_run_start_path',prepared.c2_run_start_path,'C2_run_start_sha256',prepared.c2_run_start_sha256, ...
        'B_raw_path',prepared.scene_identity.B_raw_path,'B_raw_sha256',prepared.scene_identity.B_raw_sha256, ...
        'scene_alias_normalized_in_memory',logical(prepared.scene_identity.alias_normalized_in_memory), ...
        'model_identity',pack.modelIdentity,'source_identity',pack.sourceIdentity, ...
        'source_paths',{sourcePaths},'source_sha256',{sourceHashes}, ...
        'r2e_first_plant_step_marker_path',markerPath,'cfg',cfg,'opts',opts, ...
        'plant_calls_before_invocation',0,'training_steps',0,'optimizer_steps',0,'TEST_accessed',false);
    save(runStartPath,'runStart','-v7.3'); invocationEntered=true;
    log=run_episode_dl1018(scene,contract.candidate_condition_id,cfg,opts,rawPath);
    assert(isfile(rawPath)&&isfile(markerPath),'C3:ProbeOutput','Episode returned without raw output or first-Plant marker.');
    runIdentity=struct('schema','C3_DELAYED_PREDICTION_RUN_IDENTITY_V1','scene_id',sceneId, ...
        'condition',contract.candidate_condition_id,'source_lock_sha256',sourceLockSha, ...
        'release_sha256',releaseSha,'prepare_result_sha256',prepareSha, ...
        'cfg_opts_snapshot_sha256',snapshotSha,'C2_raw_sha256',prepared.scene_identity.C2_raw_sha256, ...
        'B_raw_sha256',prepared.scene_identity.B_raw_sha256,'model_identity',pack.modelIdentity, ...
        'optimizer_steps',0,'training_steps',0,'TEST_accessed',false);
    save(rawPath,'runIdentity','-append');
    markerSha=sha256_file(markerPath); runStartSha=sha256_file(runStartPath); rawSha=sha256_file(rawPath);
    status=struct('schema','C3_DELAYED_PREDICTION_RUN_STATUS_V1','status','RUN_COMPLETE_RAW_PENDING_AUDIT', ...
        'scene_id',sceneId,'source_scene_id',sourceSceneId,'condition',contract.candidate_condition_id, ...
        'log_status',field_or_empty(log,'status'),'raw_path',rawPath,'raw_sha256',rawSha, ...
        'raw_bytes',double(dir(rawPath).bytes),'run_start_path',runStartPath,'run_start_sha256',runStartSha, ...
        'run_status_path',statusPath,'first_plant_step_marker_path',markerPath, ...
        'first_plant_step_marker_sha256',markerSha,'source_lock_sha256',sourceLockSha, ...
        'release_sha256',releaseSha,'prepare_result_sha256',prepareSha, ...
        'cfg_opts_snapshot_sha256',snapshotSha,'C2_raw_path',prepared.scene_identity.C2_raw_path, ...
        'C2_raw_sha256',prepared.scene_identity.C2_raw_sha256,'B_raw_sha256',prepared.scene_identity.B_raw_sha256, ...
        'plant_invocation_entered',true,'plant_start_confirmed',true,'plant_calls',1, ...
        'training_steps',0,'optimizer_steps',0,'gain_or_seed_search',false,'full72_started',false,'TEST_accessed',false);
    statusText=jsonencode(status); write_text(statusPath,statusText);
    assert(directory_bytes(here)<=double(budget.new_output_cap_bytes)&& ...
        directory_bytes(attemptDir)<=80000000,'C3:ActualOutputBudget','C3 output cap exceeded after probe.');
catch ME
    failed=struct('schema','C3_DELAYED_PREDICTION_PROBE_FAILURE_V1','status','FAILED_NO_RETRY', ...
        'scene_id',sceneId,'condition',contract.candidate_condition_id,'identifier',ME.identifier, ...
        'message',ME.message,'failed_utc',utc_now(),'attempt_dir',attemptDir, ...
        'plant_invocation_entered',invocationEntered,'plant_start_confirmed',isfile(markerPath), ...
