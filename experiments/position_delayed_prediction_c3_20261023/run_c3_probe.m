end

function path=source_path(items,name)
names=cell(size(items));
for k=1:numel(items), [~,base,ext]=fileparts(char(items(k).path)); names{k}=[base ext]; end
idx=find(strcmp(names,name)); assert(numel(idx)==1,'C3:SourceInventory','Expected one source named %s.',name);
path=char(items(idx).path);
end
function ok=valid_scene(scene,sceneId)
ok=isstruct(scene)&&isfield(scene,'scene_id')&& ...
    (strcmp(char(scene.scene_id),sceneId)||strcmp(char(scene.scene_id),[sceneId '_ACC_FIX_V1']))&& ...
    isfield(scene,'time')&&numel(scene.time)==20001&&abs(double(scene.time(1)))<=1e-12&& ...
    abs(double(scene.time(end))-20)<=1e-12&&isfield(scene,'environment_wind_I')&& ...
    isequal(size(scene.environment_wind_I),[20001,3])&&isfield(scene,'initial_state')&&numel(scene.initial_state)==12&& ...
    isfield(scene,'arms')&&all(isfield(scene.arms,{'command','rhoDot_hat','rhoDot_true','rho_hat','rho_true'}))&& ...
    isfield(scene,'reference')&&all(isfield(scene.reference,{'position','velocity','acceleration','yaw','yaw_rate','yaw_acceleration'}))&& ...
    isequal(size(scene.reference.position),[20001,3])&&isequal(size(scene.reference.velocity),[20001,3])&& ...
    isequal(size(scene.reference.acceleration),[20001,3])&&isequal(size(scene.reference.yaw),[20001,1])&& ...
    isequal(size(scene.reference.yaw_rate),[20001,1])&&isequal(size(scene.reference.yaw_acceleration),[20001,1])&& ...
    isequal(size(scene.arms.command),[20001,4])&&isequal(size(scene.arms.rhoDot_hat),[20001,4])&& ...
    isequal(size(scene.arms.rhoDot_true),[20001,4])&&isequal(size(scene.arms.rho_hat),[20001,4])&& ...
    isequal(size(scene.arms.rho_true),[20001,4])&&all(isfinite(scene.time(:)))&& ...
    all(isfinite(scene.environment_wind_I(:)))&&all(isfinite(scene.initial_state(:)))&& ...
    all(isfinite(scene.arms.command(:)))&&all(isfinite(scene.arms.rhoDot_hat(:)))&& ...
    all(isfinite(scene.arms.rhoDot_true(:)))&&all(isfinite(scene.arms.rho_hat(:)))&&all(isfinite(scene.arms.rho_true(:)))&& ...
    all(isfinite(scene.reference.position(:)))&&all(isfinite(scene.reference.velocity(:)))&& ...
    all(isfinite(scene.reference.acceleration(:)))&&all(isfinite(scene.reference.yaw(:)))&& ...
    all(isfinite(scene.reference.yaw_rate(:)))&&all(isfinite(scene.reference.yaw_acceleration(:)));
end
function [paths,hashes]=active_source_files(lock)
paths={}; hashes={};
for k=1:numel(lock.frozen_runtime_files)
    item=lock.frozen_runtime_files(k); [~,name,ext]=fileparts(char(item.path)); leaf=[name ext];
    role='';
    if strcmpi(leaf,'run_dl1018_closed_loop.m'), role='runtime_core'; end
    if strcmpi(leaf,'run_episode_dl1018.m'), role='episode_wrapper'; end
    if isempty(role)
        path=char(item.path); sha=char(item.sha256);
    else
        ix=find(strcmp({lock.isolated_sources.role},role));
        assert(numel(ix)==1,'C3:SourceInventory','Expected one isolated %s source.',role);
        path=char(lock.isolated_sources(ix).path); sha=char(lock.isolated_sources(ix).sha256);
    end
    paths{end+1}=path; hashes{end+1}=sha; %#ok<AGROW>
end
ix=find(strcmp({lock.isolated_sources.role},'prediction_helper'));
assert(numel(ix)==1,'C3:SourceInventory','Expected one isolated prediction helper.');
paths{end+1}=char(lock.isolated_sources(ix).path); hashes{end+1}=char(lock.isolated_sources(ix).sha256);
for k=1:numel(lock.frozen_plant_files)
    paths{end+1}=char(lock.frozen_plant_files(k).path); %#ok<AGROW>
    hashes{end+1}=char(lock.frozen_plant_files(k).sha256); %#ok<AGROW>
end
end
function verify_file(path,expected)
assert(isfile(path),'C3:MissingFile','Missing file: %s',path);
assert(strcmpi(sha256_file(path),expected),'C3:SourceHash','SHA-256 mismatch: %s',path);
end
function h=sha256_file(path)
md=java.security.MessageDigest.getInstance('SHA-256'); fid=fopen(path,'r');
assert(fid>=0,'C3:ReadFile','Cannot read %s.',path); cleanup=onCleanup(@()fclose(fid)); %#ok<NASGU>
while true, b=fread(fid,8*1024*1024,'*uint8'); if isempty(b), break; end; md.update(typecast(b,'int8')); end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
function n=directory_bytes(path)
n=0; if ~isfolder(path), return; end; d=dir(fullfile(path,'**','*'));
for k=1:numel(d), if ~d(k).isdir, n=n+double(d(k).bytes); end, end
end
function write_text(path,value)
fid=fopen(path,'w'); assert(fid>=0,'C3:WriteFile','Cannot create %s.',path);
cleanup=onCleanup(@()fclose(fid)); fwrite(fid,value,'char');
end
function write_json_new(path,value)
assert(~isfile(path),'C3:NoOverwrite','Refusing to overwrite %s.',path);
write_text(path,jsonencode(value));
end
function h=file_sha_if_exists(path)
if isfile(path), h=sha256_file(path); else, h=''; end
end
function value=field_or_empty(s,name)
if isfield(s,name), value=s.(name); else, value=''; end
end
function tf=same_path(a,b)
tf=strcmpi(char(java.io.File(a).getCanonicalPath()),char(java.io.File(b).getCanonicalPath()));
end
function t=utc_now()
t=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z'''));
end
function release_job_lock(jobLock,channel,raf)
try, if jobLock.isValid(), jobLock.release(); end, catch, end
try, if channel.isOpen(), channel.close(); end, catch, end
try, raf.close(); catch, end
end
