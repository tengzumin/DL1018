function progress=run_c3_continue(mode)
% Run the fixed C3 VAL12 scenes 2:12 after a parent continuation release.
if nargin~=1||~strcmpi(char(mode),'PARENT_APPROVED_CONTINUE')
    error('C3:Mode','Pass exactly PARENT_APPROVED_CONTINUE after parent review.');
end
here=fileparts(mfilename('fullpath')); repoRoot=fileparts(fileparts(here));
releasePath=fullfile(here,'C3_CONTINUE_RELEASE.json');
lockPath=fullfile(here,'C3_SOURCE_LOCK.json');
contractPath=fullfile(here,'C3_RUN_CONTRACT.json');
preparePath=fullfile(here,'C3_PREPARE_RESULT.json');
snapshotPath=fullfile(here,'C3_PREPARED_CONFIG_OPTS.mat');
probeReleasePath=fullfile(here,'C3_PROBE_RELEASE.json');
attemptRoot=fullfile(here,'runs_c3');
progressPath=fullfile(here,'C3_CONTINUE_PROGRESS.json');
summaryPath=fullfile(here,'C3_CONTINUE_SUMMARY.json');
assert(isfile(releasePath)&&isfile(lockPath)&&isfile(contractPath)&& ...
    isfile(preparePath)&&isfile(snapshotPath)&&isfile(probeReleasePath), ...
    'C3:ReleaseInputs','Continue release and frozen C3 inputs are required.');
release=jsondecode(fileread(releasePath)); lock=jsondecode(fileread(lockPath));
contract=jsondecode(fileread(contractPath)); prepared=jsondecode(fileread(preparePath));
sourceLockSha=sha256_file(lockPath); releaseSha=sha256_file(releasePath);
prepareSha=sha256_file(preparePath); snapshotSha=sha256_file(snapshotPath);
probeReleaseSha=sha256_file(probeReleasePath);
runnerPath=[mfilename('fullpath') '.m']; runnerSha=sha256_file(runnerPath);
sceneIds=cellstr(string(lock.scene_ids(:)))'; selectedIds=sceneIds(2:12);
expectedIndices=2:12;
auditPath=fullfile(repoRoot,'reports','delayed_prediction_c3_parent_20261023','PROBE_RAW_AUDIT.json');
assert(strcmp(release.schema,'C3_DELAYED_PREDICTION_CONTINUE_RELEASE_V1')&& ...
    strcmp(release.state,'APPROVED_C3_CONTINUE')&&logical(release.plant_authorized)&& ...
    double(release.max_new_sorties)==11&&double(release.probe_sorties_already_run)==1&& ...
    double(release.total_sortie_cap)==12&& ...
    isequal(double(release.scene_indices_1based(:))',expectedIndices)&& ...
    isequal(cellstr(string(release.scene_ids(:)))',selectedIds)&& ...
    ~logical(release.full72_authorized)&&~logical(release.TEST_authorized)&& ...
    double(release.training_steps)==0&&double(release.optimizer_steps)==0&& ...
    ~logical(release.gain_or_seed_search)&& ...
    strcmpi(release.candidate_condition_id,contract.candidate_condition_id)&& ...
    same_path(release.runner_path,runnerPath)&&strcmpi(release.runner_sha256,runnerSha)&& ...
    strcmpi(release.source_lock_sha256,sourceLockSha)&& ...
    strcmpi(release.prepare_result_sha256,prepareSha)&& ...
    strcmpi(release.cfg_opts_snapshot_sha256,snapshotSha)&& ...
    strcmpi(release.probe_release_sha256,probeReleaseSha)&& ...
    same_path(release.probe_raw_audit_path,auditPath), ...
    'C3:ContinueRelease','Parent release does not approve this exact fixed 11-scene runner.');
assert(strcmp(lock.schema,'C3_DELAYED_PREDICTION_SOURCE_LOCK_V1')&& ...
    strcmp(lock.state,'PREPARED_NO_PLANT_PARENT_REVIEW_REQUIRED')&& ...
    strcmp(prepared.status,'PREPARED_WAIT_PARENT_PROBE_RELEASE')&& ...
    strcmpi(prepared.source_lock_sha256,sourceLockSha)&& ...
    strcmpi(prepared.cfg_opts_snapshot_sha256,snapshotSha)&& ...
    strcmpi(contract.schema,'C3_DELAYED_PREDICTION_RUN_CONTRACT_V1')&& ...
    strcmpi(contract.candidate_condition_id,release.candidate_condition_id)&& ...
    double(contract.candidate.tau_s)==1&&double(contract.candidate.rho)==0.01, ...
    'C3:PreparedBinding','Frozen candidate, preparation, or source-lock identity differs.');

verify_file(lock.run_contract_path,lock.run_contract_sha256);
verify_file(lock.authorization_path,lock.authorization_sha256);
verify_file(lock.prepare_entry_path,lock.prepare_entry_sha256);
verify_file(lock.c2_source_lock.path,lock.c2_source_lock.sha256);
verify_file(lock.c2_release.path,lock.c2_release.sha256);
verify_file(lock.c1_source_lock.path,lock.c1_source_lock.sha256);
verify_file(lock.c1_release.path,lock.c1_release.sha256);
verify_file(lock.c2_execution_ledger.path,lock.c2_execution_ledger.sha256);
verify_file(lock.c2_probe_summary.path,lock.c2_probe_summary.sha256);
for k=1:numel(lock.isolated_sources), verify_file(lock.isolated_sources(k).path,lock.isolated_sources(k).sha256); end
for k=1:numel(lock.frozen_runtime_files), verify_file(lock.frozen_runtime_files(k).path,lock.frozen_runtime_files(k).sha256); end
for k=1:numel(lock.frozen_plant_files), verify_file(lock.frozen_plant_files(k).path,lock.frozen_plant_files(k).sha256); end
for k=1:numel(lock.shared_input_files), verify_file(lock.shared_input_files(k).path,lock.shared_input_files(k).sha256); end
c1lock=jsondecode(fileread(lock.c1_source_lock.path));
c2lock=jsondecode(fileread(lock.c2_source_lock.path));
verify_file(c1lock.r2_lock.path,c1lock.r2_lock.sha256);
r2=jsondecode(fileread(c1lock.r2_lock.path));
shared=c2lock.shared_c1_inputs;
ledger=jsondecode(fileread(lock.c2_execution_ledger.path));
assert(strcmpi(release.c2_execution_ledger_sha256,lock.c2_execution_ledger.sha256), ...
    'C3:C2LedgerRelease','Continuation release does not bind the frozen C2 ledger.');
assert(isequal({c1lock.shared_scenes.scene_id},sceneIds), ...
    'C3:SceneOrder','C1 shared-scene order differs from the frozen C3 scene order.');

probeScene=sceneIds{1};
probeDir=fullfile(attemptRoot,probeScene,contract.candidate_condition_id,'attempt_01');
probeStatusPath=fullfile(probeDir,'run_status.json');
probeRawPath=fullfile(probeDir,'raw_run.mat');
probeStartPath=fullfile(probeDir,'run_start.mat');
probeMarkerPath=fullfile(probeDir,'first_plant_step.marker');
assert(isfile(probeStatusPath)&&isfile(probeRawPath)&&isfile(probeStartPath)&&isfile(probeMarkerPath), ...
    'C3:ProbeEvidence','Audited first-probe files are required before continuation.');
verify_file(probeStatusPath,release.probe_run_status_sha256);
verify_file(probeRawPath,release.probe_raw_sha256);
verify_file(probeStartPath,release.probe_run_start_sha256);
verify_file(probeMarkerPath,release.probe_marker_sha256);
verify_file(auditPath,release.probe_raw_audit_sha256);
probeStatus=jsondecode(fileread(probeStatusPath));
probeAudit=jsondecode(fileread(auditPath));
probeRelease=jsondecode(fileread(probeReleasePath));
assert(strcmp(probeStatus.status,'RUN_COMPLETE_RAW_PENDING_AUDIT')&& ...
    strcmp(probeStatus.log_status,'STABLE')&&double(probeStatus.plant_calls)==1&& ...
    strcmpi(probeStatus.source_lock_sha256,sourceLockSha)&& ...
    strcmpi(probeStatus.release_sha256,probeReleaseSha)&& ...
    strcmpi(probeStatus.raw_sha256,release.probe_raw_sha256)&& ...
    strcmp(probeAudit.status,'PASS_RAW_AUDIT')&& ...
    strcmpi(probeAudit.metrics.raw_sha256,probeStatus.raw_sha256)&& ...
    strcmp(probeRelease.state,'APPROVED_C3_PROBE')&&logical(probeRelease.plant_authorized), ...
    'C3:ProbeAudit','First probe status or independent raw audit did not pass.');

allStarted=dir(fullfile(attemptRoot,'**','attempt_started.marker'));
allPlant=dir(fullfile(attemptRoot,'**','first_plant_step.marker'));
allAttempts=dir(fullfile(attemptRoot,'**','attempt_*'));
allAttempts=allAttempts([allAttempts.isdir]);
assert(numel(allStarted)==1&&numel(allPlant)==1&&numel(allAttempts)==1&& ...
    isfile(probeMarkerPath)&&~isfile(progressPath)&&~isfile(summaryPath), ...
    'C3:InitialAttemptCount','Continuation must start from exactly one audited probe and no prior continuation.');

pack=load(snapshotPath,'cfg','opts','W0','modelIdentity','sceneIdentity','sourceIdentity');
assert(isfield(pack,'cfg')&&isfield(pack,'opts')&&isfield(pack,'W0')&& ...
    isfield(pack,'modelIdentity')&&isfield(pack,'sceneIdentity')&&isfield(pack,'sourceIdentity')&& ...
    logical(pack.opts.position_delayed_prediction_enabled), ...
    'C3:Snapshot','Prepared configuration, C3 option, model or input identity is missing.');
cfg=pack.cfg; baseOpts=pack.opts; W0=double(pack.W0);
pcf=baseOpts.stage1_position_runtime; head=pcf.position_only_search_head;
assert(isequal(double(pcf.weight),W0)&&isequal(double(pcf.model.output_W),W0)&& ...
    isequal(double(head.W0),W0)&& ...
    strcmpi(hash_bytes(typecast(W0(:),'uint8')),shared.w0_output_W_double_f_order_sha256)&& ...
    strcmpi(lock.w0_sha256,shared.w0_output_W_double_f_order_sha256)&& ...
    strcmpi(probeStatus.scene_id,probeScene)&&same_path(probeStatus.raw_path,probeRawPath), ...
    'C3:InitialW0','Candidate runtime must start every scene from the frozen W0.');
probeStart=load(probeStartPath,'runStart');
assert(isfield(probeStart,'runStart')&& ...
    isequal(probeStart.runStart.source_paths,active_source_paths(lock))&& ...
    isequal(probeStart.runStart.source_sha256,active_source_hashes(lock)), ...
    'C3:ProbeSourceIdentity','Probe source record differs from the frozen runtime inventory.');

auth=jsondecode(fileread(lock.authorization_path));
assert(double(auth.max_new_sorties)==12&&double(auth.probe_sorties)==1&& ...
    double(auth.remaining_after_parent_probe_gate)==11&& ...
    double(auth.new_output_cap_bytes)==1073741824&&double(auth.minimum_free_bytes)==30000000000, ...
    'C3:UserBudget','The original user authorization does not cover exactly 12 sorties.');
reserveBytes=int64(11*80000000);
assert(directory_bytes(here)+double(reserveBytes)<=double(auth.new_output_cap_bytes)&& ...
    double(java.io.File(repoRoot).getUsableSpace())-double(reserveBytes)>=double(auth.minimum_free_bytes), ...
    'C3:ResourceBudget','Eleven-scene reserve exceeds the output cap or free-space floor.');
jobLockPath=char(jsondecode(fileread(lock.c1_release.path)).shared_heavy_job_lock_path);
assert(isfile(jobLockPath),'C3:SharedLockMissing','The frozen C1 shared heavy-job lock is missing.');
raf=java.io.RandomAccessFile(jobLockPath,'rw'); channel=raf.getChannel(); jobLock=channel.tryLock();
assert(~isempty(jobLock),'C3:ConcurrentHeavyJob','The shared closed-loop heavy-job lock is held.');
cleanup=onCleanup(@()release_job_lock(jobLock,channel,raf)); %#ok<NASGU>

% Resolve the exact frozen inventory once; the wrapper checks the C3 core again per call.
runtimeSourcePaths=active_source_paths(lock); runtimeSourceHashes=active_source_hashes(lock);
for k=1:numel(runtimeSourcePaths)
    [~,~,ext]=fileparts(runtimeSourcePaths{k});
    if strcmpi(ext,'.m'), addpath(fileparts(runtimeSourcePaths{k}),'-end'); end
end
addpath(fullfile(repoRoot,'matlab','runtime'),'-end');
addpath(fullfile(repoRoot,'matlab','core'),'-end');
initPath=source_path(r2.runtimeFiles,'init_dl1018.m');
optionsPath=source_path(r2.runtimeFiles,'position_only_search_options.m');
headStepPath=source_path(r2.runtimeFiles,'position_only_search_head_step.m');
modelForwardPath=source_path(r2.runtimeFiles,'position_stage1_model_forward_v2.m');
addpath(fileparts(optionsPath),'-begin'); addpath(fileparts(initPath),'-begin'); addpath(here,'-begin');
clear run_episode_dl1018 run_dl1018_closed_loop delayed_prediction_step_candidate ...
    position_only_search_options position_only_search_head_step position_stage1_model_forward_v2 init_dl1018;
rehash;
for k=1:numel(runtimeSourcePaths)
    verify_file(runtimeSourcePaths{k},runtimeSourceHashes{k});
    [~,name,ext]=fileparts(runtimeSourcePaths{k});
    if strcmpi(ext,'.m')
        assert(same_path(which(name),runtimeSourcePaths{k}),'C3:ResolvedSourceShadow', ...
            'Locked source %s resolved to a shadowed path.',name);
    end
end
assert(same_path(which('position_only_search_options'),optionsPath)&& ...
    same_path(which('position_only_search_head_step'),headStepPath)&& ...
    same_path(which('position_stage1_model_forward_v2'),modelForwardPath)&& ...
    same_path(which('init_dl1018'),initPath), ...
    'C3:CandidatePath','Resolved C1 option/model/init source differs from the source lock.');

% Check all twelve C2 run_start cfg/opts records before the first continuation Plant call.
bindings=cell(1,11);
for si=1:12
    sceneId=sceneIds{si};
    c1idx=find(strcmp({c1lock.shared_scenes.scene_id},sceneId));
    c3idx=find(strcmp({lock.c2_baseline_runs.scene_id},sceneId));
    lid=find(strcmp({ledger.run_rows.scene_id},sceneId));
    assert(numel(c1idx)==1&&numel(c3idx)==1&&numel(lid)==1,'C3:SceneInventory', ...
        'Expected one fixed C1/C2 row for scene %s.',sceneId);
    c1scene=c1lock.shared_scenes(c1idx); c2row=lock.c2_baseline_runs(c3idx);
    ledgerRow=ledger.run_rows(lid);
    expectedRunDir=fullfile(char(ledger.project_root),strrep(char(ledger.run_template),'<scene_id>',sceneId));
    assert(same_path(c2row.raw_path,fullfile(expectedRunDir,'raw_run.mat'))&& ...
        same_path(c2row.run_start_path,fullfile(expectedRunDir,'run_start.mat'))&& ...
        strcmpi(c2row.raw_sha256,ledgerRow.raw_sha256)&& ...
        strcmpi(c2row.run_start_sha256,ledgerRow.run_start_sha256), ...
        'C3:C2Comparator','C2 path or hashes differ from frozen ledger for %s.',sceneId);
    verify_file(c1scene.b_raw_path,c1scene.b_raw_sha256);
    verify_file(c2row.raw_path,c2row.raw_sha256);
    verify_file(c2row.run_start_path,c2row.run_start_sha256);
    c2Data=load(c2row.run_start_path,'runStart');
    assert(isfield(c2Data,'runStart')&& ...
        check_c2_identity(c2Data.runStart,sceneId,c1scene,cfg,baseOpts,shared,pack.modelIdentity), ...
        'C3:C2ConfigIdentity','C2 run_start cfg/opts or fixed input identity differs for %s.',sceneId);
    if si>1
        bindings{si-1}=struct('scene_id',sceneId,'B_raw_path',char(c1scene.b_raw_path), ...
            'B_raw_sha256',char(c1scene.b_raw_sha256),'C2_raw_path',char(c2row.raw_path), ...
            'C2_raw_sha256',char(c2row.raw_sha256),'C2_run_start_path',char(c2row.run_start_path), ...
            'C2_run_start_sha256',char(c2row.run_start_sha256), ...
            'scene_payload_sha256',char(c1scene.payload_sha256));
    end
end

progress=struct('schema','C3_DELAYED_PREDICTION_CONTINUE_PROGRESS_V1', ...
    'status','CONTINUE_STARTED','release_sha256',releaseSha,'runner_sha256',runnerSha, ...
    'source_lock_sha256',sourceLockSha,'probe_raw_sha256',probeStatus.raw_sha256, ...
    'scene_indices_1based',expectedIndices,'scene_ids',{selectedIds}, ...
    'completed_scene_count',0,'runs',{{}},'updated_utc',utc_now());
write_json_new(progressPath,progress);
runRows={};
for j=1:11
    si=j+1; sceneId=sceneIds{si}; input=bindings{j};
    attemptDir=fullfile(attemptRoot,sceneId,contract.candidate_condition_id,'attempt_01');
    conditionDir=fileparts(attemptDir); existing=dir(fullfile(conditionDir,'attempt_*'));
    currentStarted=dir(fullfile(attemptRoot,'**','attempt_started.marker'));
    currentPlant=dir(fullfile(attemptRoot,'**','first_plant_step.marker'));
    assert(~isfolder(attemptDir)&&isempty(existing)&& ...
        numel(currentStarted)==j&&numel(currentPlant)==j, ...
        'C3:NoRetry','Unexpected attempt or marker count before fixed scene %d.',si);
    reserveOne=int64(80000000);
    assert(directory_bytes(here)+double(reserveOne)<=double(auth.new_output_cap_bytes)&& ...
        double(java.io.File(repoRoot).getUsableSpace())-double(reserveOne)>=double(auth.minimum_free_bytes), ...
        'C3:ResourceBudget','Per-scene reserve violates the output cap or 30-GB free-space floor.');
    verify_file(input.B_raw_path,input.B_raw_sha256);
    verify_file(input.C2_raw_path,input.C2_raw_sha256);
    verify_file(input.C2_run_start_path,input.C2_run_start_sha256);
    if ~isfolder(attemptDir), mkdir(attemptDir); end
    markerPath=fullfile(attemptDir,'first_plant_step.marker');
    rawPath=fullfile(attemptDir,'raw_run.mat'); runStartPath=fullfile(attemptDir,'run_start.mat');
    statusPath=fullfile(attemptDir,'run_status.json'); failurePath=fullfile(attemptDir,'C3_CONTINUE_FAILURE.json');
    assert(~isfile(markerPath)&&~isfile(rawPath)&&~isfile(runStartPath)&& ...
        ~isfile(statusPath)&&~isfile(failurePath),'C3:NoOverwrite','Attempt output already exists.');
    scenePack=load(input.B_raw_path,'scene'); scene=scenePack.scene;
    rawSceneId=char(scene.scene_id);
    assert(valid_scene(scene,sceneId)&& ...
        (strcmp(rawSceneId,[sceneId '_ACC_FIX_V1'])||strcmp(rawSceneId,sceneId)), ...
        'C3:SceneIdentity','Frozen B scene does not match fixed scene %s.',sceneId);
    scene.scene_id=sceneId;
    sceneIdentity=struct('scene_id',sceneId,'raw_scene_id',rawSceneId, ...
        'canonical_scene_id',sceneId,'alias_normalized_in_memory',~strcmp(rawSceneId,sceneId), ...
        'alias_rule','C2 valid_scene: canonical scene ID or canonical ID plus _ACC_FIX_V1', ...
        'B_raw_path',input.B_raw_path,'B_raw_sha256',input.B_raw_sha256, ...
        'C2_raw_path',input.C2_raw_path,'C2_raw_sha256',input.C2_raw_sha256, ...
        'C2_ledger_sha256',lock.c2_execution_ledger.sha256, ...
        'payload_sha256',input.scene_payload_sha256);
    c2Data=load(input.C2_run_start_path,'runStart');
    assert(check_c2_identity(c2Data.runStart,sceneId, ...
        c1lock.shared_scenes(si),cfg,baseOpts,shared,pack.modelIdentity), ...
        'C3:C2ConfigIdentity','C2 cfg/opts identity changed before Plant for %s.',sceneId);
    opts=pack.opts; opts.r2e_first_plant_step_marker=markerPath;
    pcf=opts.stage1_position_runtime; head=pcf.position_only_search_head;
    assert(logical(opts.position_delayed_prediction_enabled)&& ...
        isequal(double(pcf.weight),W0)&&isequal(double(pcf.model.output_W),W0)&& ...
        isequal(double(head.W0),W0), ...
        'C3:W0Reset','Candidate weight must reset to frozen W0 for scene %s.',sceneId);
    progress.status='SCENE_READY'; progress.current_scene_index_1based=si;
    progress.completed_scene_count=numel(runRows); progress.runs=runRows;
    progress.updated_utc=utc_now(); write_json_replace(progressPath,progress);
    invocationEntered=false; startedUtc=utc_now();
    try
        write_text(fullfile(attemptDir,'attempt_started.marker'), ...
            [startedUtc newline 'ABOUT_TO_CALL_EPISODE' newline]);
        runStart=struct('schema','C3_DELAYED_PREDICTION_RUN_START_V1', ...
            'global_scene_index_1based',si,'scene_id',sceneId,'source_scene_id',rawSceneId, ...
            'condition',contract.candidate_condition_id,'started_utc',startedUtc, ...
            'continuation_release_sha256',releaseSha,'probe_release_sha256',probeReleaseSha, ...
            'probe_raw_sha256',probeStatus.raw_sha256,'probe_raw_audit_sha256',release.probe_raw_audit_sha256, ...
            'source_lock_sha256',sourceLockSha,'prepare_result_sha256',prepareSha, ...
            'cfg_opts_snapshot_sha256',snapshotSha,'C2_raw_path',input.C2_raw_path, ...
            'C2_raw_sha256',input.C2_raw_sha256,'C2_run_start_path',input.C2_run_start_path, ...
            'C2_run_start_sha256',input.C2_run_start_sha256,'B_raw_path',input.B_raw_path, ...
            'B_raw_sha256',input.B_raw_sha256,'scene_payload_sha256',input.scene_payload_sha256, ...
            'scene_alias_normalized_in_memory',logical(sceneIdentity.alias_normalized_in_memory), ...
            'model_identity',pack.modelIdentity,'source_identity',pack.sourceIdentity, ...
            'source_paths',{runtimeSourcePaths},'source_sha256',{runtimeSourceHashes}, ...
            'continue_runner_path',runnerPath,'continue_runner_sha256',runnerSha, ...
            'first_plant_step_marker_path',markerPath,'cfg',cfg,'opts',opts, ...
            'plant_calls_before_invocation',0,'training_steps',0,'optimizer_steps',0,'TEST_accessed',false);
        save(runStartPath,'runStart','-v7.3');
        invocationEntered=true;
        clear run_dl1018_closed_loop delayed_prediction_step_candidate;
        log=run_episode_dl1018(scene,contract.candidate_condition_id,cfg,opts,rawPath);
        assert(isfile(rawPath)&&isfile(markerPath),'C3:ProbeOutput', ...
            'Episode returned without raw output or first-Plant marker.');
        runIdentity=struct('schema','C3_DELAYED_PREDICTION_RUN_IDENTITY_V1', ...
            'global_scene_index_1based',si,'scene_id',sceneId, ...
            'condition',contract.candidate_condition_id,'source_lock_sha256',sourceLockSha, ...
            'continuation_release_sha256',releaseSha,'probe_raw_sha256',probeStatus.raw_sha256, ...
            'prepare_result_sha256',prepareSha,'cfg_opts_snapshot_sha256',snapshotSha, ...
            'C2_raw_sha256',input.C2_raw_sha256,'B_raw_sha256',input.B_raw_sha256, ...
            'model_identity',pack.modelIdentity,'initial_W0_sha256',lock.w0_sha256, ...
            'optimizer_steps',0,'training_steps',0,'TEST_accessed',false);
        save(rawPath,'runIdentity','-append');
        markerSha=sha256_file(markerPath); runStartSha=sha256_file(runStartPath); rawSha=sha256_file(rawPath);
        logStatus=field_or_empty(log,'status');
        completedStable=strcmpi(logStatus,'STABLE')&& ...
            isempty(char(field_or_empty(log,'safety_stop_reason')));
        runStatusLabel='FAILED_NO_RETRY';
        if completedStable, runStatusLabel='RUN_COMPLETE_RAW_PENDING_AUDIT'; end
        runStatus=struct('schema','C3_DELAYED_PREDICTION_RUN_STATUS_V1', ...
            'status',runStatusLabel,'global_scene_index_1based',si, ...
            'scene_id',sceneId,'source_scene_id',rawSceneId,'condition',contract.candidate_condition_id, ...
            'log_status',logStatus,'raw_path',rawPath,'raw_sha256',rawSha, ...
            'raw_bytes',double(dir(rawPath).bytes),'run_start_path',runStartPath, ...
            'run_start_sha256',runStartSha,'run_status_path',statusPath, ...
            'first_plant_step_marker_path',markerPath,'first_plant_step_marker_sha256',markerSha, ...
            'source_lock_sha256',sourceLockSha,'continuation_release_sha256',releaseSha, ...
            'probe_release_sha256',probeReleaseSha,'probe_raw_sha256',probeStatus.raw_sha256, ...
            'prepare_result_sha256',prepareSha,'cfg_opts_snapshot_sha256',snapshotSha, ...
            'C2_raw_path',input.C2_raw_path,'C2_raw_sha256',input.C2_raw_sha256, ...
            'C2_run_start_sha256',input.C2_run_start_sha256,'B_raw_path',input.B_raw_path, ...
            'B_raw_sha256',input.B_raw_sha256,'plant_invocation_entered',true, ...
            'plant_start_confirmed',true,'plant_calls',1,'training_steps',0,'optimizer_steps',0, ...
            'gain_or_seed_search',false,'full72_started',false,'TEST_accessed',false);
        write_json_new(statusPath,runStatus);
        assert(completedStable,'C3:UnsafeContinueStop', ...
            'Scene %s returned a non-STABLE or safety-stop log; preserving raw/status and stopping.',sceneId);
        assert(directory_bytes(attemptDir)<=80000000&& ...
            directory_bytes(here)<=double(auth.new_output_cap_bytes), ...
            'C3:ActualOutputBudget','C3 output limit exceeded after scene %s.',sceneId);
        runRows{end+1}=runStatus; %#ok<AGROW>
        progress.status='SCENE_COMPLETE_RAW_PENDING_AUDIT';
