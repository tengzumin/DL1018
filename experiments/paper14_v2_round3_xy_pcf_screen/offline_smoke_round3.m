function offline_smoke_round3
% Pure offline options/equation smoke. It does not invoke an episode or simulator.
here=fileparts(mfilename('fullpath'));repo=fileparts(fileparts(here));
lockPath=fullfile(here,'frozen_inputs.json');lock=jsondecode(fileread(lockPath));
assert(strcmp(lock.schema,'ROUND3_XY_PCF_SCREEN_INPUTS_V1')&& ...
    strcmpi(sha_local(lock.taskbook.path),lock.taskbook.sha256)&& ...
    strcmp(lock.taskbook.sha256,'a9d876f0e22175785f184707ba0f35090be3adf6a25317e83c39a9c88a1ccb4a'), ...
    'ROUND3:SmokeLock','Taskbook/input lock changed.');
assert(strcmpi(sha_local(lock.upstream_round2.lock_path),lock.upstream_round2.lock_sha256), ...
    'ROUND3:SmokeR2','Upstream R2 lock changed.');
for k=1:numel(lock.localRuntimeFiles)
    assert(strcmpi(sha_local(lock.localRuntimeFiles(k).path),lock.localRuntimeFiles(k).sha256), ...
        'ROUND3:SmokeRuntime','Local runtime SHA changed: %s',lock.localRuntimeFiles(k).name);
end
for k=1:numel(lock.setupFiles)
    assert(strcmpi(sha_local(lock.setupFiles(k).path),lock.setupFiles(k).sha256), ...
        'ROUND3:SmokePackage','Package source SHA changed: %s',lock.setupFiles(k).name);
end
idx=find(endsWith(string({lock.runtimeFiles.path}),string(filesep)+"init_dl1018.m"),1);
assert(~isempty(idx),'ROUND3:SmokeInit','Frozen initializer missing.');
restoredefaultpath;addpath(fileparts(lock.runtimeFiles(idx).path),'-begin');
[cfg,~,root]=init_dl1018();assert(strcmpi(char(java.io.File(root).getCanonicalPath()), ...
    char(java.io.File(repo).getCanonicalPath())),'ROUND3:SmokeRoot','Initializer resolved wrong repository.');
runtime=fullfile(here,'runtime');addpath(fullfile(repo,'matlab','core'),'-begin');addpath(runtime,'-begin');addpath(here,'-begin');
clear position_only_search_options position_only_search_head_step position_filter_realization_pcf_step_v3_5;
rehash;
assert(strcmpi(which('position_only_search_options'),fullfile(runtime,'position_only_search_options.m'))&& ...
    strcmpi(which('position_only_search_head_step'),fullfile(runtime,'position_only_search_head_step.m'))&& ...
    strcmpi(which('position_filter_realization_pcf_step_v3_5'),fullfile(runtime,'position_filter_realization_pcf_step_v3_5.m'))&& ...
    strcmpi(which('build_round3_xy_pcf_options'),fullfile(here,'build_round3_xy_pcf_options.m')), ...
    'ROUND3:SmokePath','Options/helper path is not the locked R3 local copy.');
checkcode(fullfile(here,'run_round3_xy_pcf_screen.m'),'-id');
modelPack=load(lock.model.mat_path,'model');[opts,audit]=build_round3_xy_pcf_options(cfg,modelPack.model);
assert(isequal(double(opts.stage1_position_runtime.position_only_search_head.eta_mask(:)),[1;1;0])&& ...
    logical(opts.stage1_position_runtime.command_filter_coordination_v3_5.enabled)&& ...
    logical(opts.formal_rbf_baseline)&&logical(opts.rbf_attitude_enabled)&& ...
    logical(opts.rbf_attitude_output_enabled)&&logical(opts.rbf_attitude_update_enabled)&& ...
    ~audit.attitude_fusion_enabled,'ROUND3:SmokeOptions','PCF/FEATURE/attitude options contract failed.');

surface=[0.31;-0.42;0.16];eta=[0.08;-0.10;0.03];k2=[2;0;4];rf=[0.02;-0.03;0.01];
dt=0.001;eventDt=0.01;maskXY=[1;1;0];maskOn=[1;1;1];maskOff=[0;0;0];
phi=sin((1:33)'/5);W=double(modelPack.model.output_W);gamma=12;beta=0.8;dmax=double(cfg.rbf.position.dmax(:));
xy=round3_xy_math(surface,eta,k2,rf,dt,eventDt,maskXY,phi,W,gamma,beta,dmax);
on=round3_xy_math(surface,eta,k2,rf,dt,eventDt,maskOn,phi,W,gamma,beta,dmax);
off=round3_xy_math(surface,eta,k2,rf,dt,eventDt,maskOff,phi,W,gamma,beta,dmax);
assert(max(abs(xy.s_eff(1:2)-on.s_eff(1:2)))==0&&xy.s_eff(3)==off.s_eff(3), ...
    'ROUND3:SameStateMask','Same-record XY/Z identities failed.');
[~,~,etaFromLockedHelper]=position_filter_realization_pcf_step_v3_5( ...
    9.81,[0;0;0],rf,eta,k2,1,9.81,dt,true);
assert(max(abs(etaFromLockedHelper-xy.eta_next))<=1e-12,'ROUND3:EtaParity','Eta recurrence parity failed.');
[raw,applied,Wnext]=position_only_search_head_step(phi,W,W,'FEATURE',gamma,1, ...
    xy.s_eff,eventDt,beta,dmax);
rawErr=max(abs(raw-xy.raw_before_update));appliedErr=max(abs(applied-xy.applied_output));
weightErr=max(abs(Wnext(:)-xy.weight_after(:)));
W0FromModel=double(modelPack.model.output_W);W0Err=max(abs(W(:)-W0FromModel(:)));
if max([rawErr appliedErr weightErr W0Err])>1e-12
    failed=struct('schema','ROUND3_OFFLINE_MATH_DIAGNOSTIC_V1','status','FAILED', ...
        'created_utc',char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z''')), ...
        'frozen_inputs_sha256',sha_local(lockPath),'round3_runner_sha256',sha_local(fullfile(here,'run_round3_xy_pcf_screen.m')), ...
        'matlab_offline_source_sha256',sha_local(fullfile(here,'offline_smoke_round3.m')), ...
        'helper_sha256',sha_local(fullfile(runtime,'position_only_search_head_step.m')), ...
        'equation_source_sha256',sha_local(fullfile(here,'round3_xy_math.m')), ...
        'W0_output_W_sha256',audit.W0_output_W_sha256,'W0_identity_error',W0Err, ...
        'raw_output_mismatch',rawErr,'applied_output_mismatch',appliedErr, ...
        'W_next_mismatch',weightErr,'raw_shape',size(raw),'expected_raw_shape',size(xy.raw_before_update), ...
        'applied_shape',size(applied),'expected_applied_shape',size(xy.applied_output), ...
        'W_next_shape',size(Wnext),'expected_W_next_shape',size(xy.weight_after), ...
        'test_accessed',false,'plant_or_episode_called',false);
    write_json(fullfile(here,'reports','offline_smoke_failure_04.json'),failed);
end
assert(rawErr<=1e-12&&appliedErr<=1e-12&&weightErr<=1e-12, ...
    'ROUND3:HeadParity','FEATURE parity failed: raw=%.17g applied=%.17g weight=%.17g W0=%.17g.',rawErr,appliedErr,weightErr,W0Err);
assert(isequal(size(raw),[3 1])&&isequal(size(Wnext),[33 3]), ...
    'ROUND3:MatrixDirection','FEATURE projection dimensions/direction changed.');

report=struct('schema','ROUND3_OFFLINE_MATH_SMOKE_V1','status','PASS', ...
    'frozen_inputs_sha256',sha_local(lockPath),'taskbook_sha256',lock.taskbook.sha256, ...
    'setup_manifest_sha256',setup_manifest_sha(lock), ...
    'round3_runner_sha256',sha_local(fullfile(here,'run_round3_xy_pcf_screen.m')), ...
    'offline_smoke_source_sha256',sha_local(fullfile(here,'offline_smoke_round3.m')), ...
    'builder_sha256',sha_local(which('build_round3_xy_pcf_options')), ...
    'W0_output_W_sha256',audit.W0_output_W_sha256, ...
    'normalizer_arrays_identity_sha256',audit.normalizer_identity_sha256, ...
    'runtime_runner_sha256',sha_local(fullfile(runtime,'run_dl1018_closed_loop.m')), ...
    'feature_helper_sha256',sha_local(fullfile(runtime,'position_only_search_head_step.m')), ...
    'pcf_eta_helper_sha256',sha_local(fullfile(runtime,'position_filter_realization_pcf_step_v3_5.m')), ...
    'mask',[1 1 0],'same_record_xy_s_eff_error',max(abs(xy.s_eff(1:2)-on.s_eff(1:2))), ...
    'same_record_z_s_eff_error',abs(xy.s_eff(3)-off.s_eff(3)), ...
    'feature_raw_helper_error',rawErr,'feature_applied_helper_error',appliedErr, ...
    'feature_weight_helper_error',weightErr,'W0_identity_error',W0Err, ...
    'eta_recurrence_error',max(abs(etaFromLockedHelper-xy.eta_next)), ...
    'raw_before_update_error',max(abs(raw-xy.raw_before_update)), ...
    'applied_output_error',max(abs(applied-xy.applied_output)), ...
    'weight_update_error',max(abs(Wnext(:)-xy.weight_after(:))), ...
    'synthetic_inputs',struct('surface',surface,'eta_before',eta,'k2',k2,'residual',rf, ...
        'plant_dt',dt,'event_dt',eventDt,'mask',[1;1;0],'phi',phi,'W',W, ...
        'gamma',gamma,'beta',beta,'dmax',dmax), ...
    'synthetic_outputs',struct('eta_next',xy.eta_next,'eta_effective',xy.eta_effective, ...
        's_coord',xy.s_coord,'s_eff',xy.s_eff,'raw_before_update',xy.raw_before_update, ...
        'applied_output',xy.applied_output,'weight_after',xy.weight_after), ...
    'phi_dim',numel(phi),'W_shape',size(W),'raw_shape',size(raw),'weight_after_shape',size(Wnext), ...
    'run_episode_called',false,'plant_called',false,'actuator_called',false, ...
    'training_called',false,'test_accessed',false,'scene_or_raw_read',false, ...
    'optimizer_steps',0,'head_type',audit.head_type,'update_enabled',audit.update_enabled, ...
    'pcf_enabled',audit.pcf_enabled,'attitude_fusion_enabled',audit.attitude_fusion_enabled, ...
    'formal_rbf_baseline',audit.formal_rbf_baseline,'rbf_attitude_enabled',audit.rbf_attitude_enabled, ...
    'rbf_attitude_output_enabled',audit.rbf_attitude_output_enabled, ...
    'rbf_attitude_update_enabled',audit.rbf_attitude_update_enabled, ...
    'round3_runner_parse_check_complete',true, ...
    'created_utc',char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z''')));
path=fullfile(here,'reports','offline_math_smoke_matlab_final.json');
assert(~isfile(path),'ROUND3:NoOverwrite','Refusing to overwrite the MATLAB smoke report.');
write_json(path,report);fprintf('ROUND3 MATLAB OFFLINE SMOKE PASS; no episode/Plant/TEST calls.\n');
end

function h=sha_local(path)
md=java.security.MessageDigest.getInstance('SHA-256');f=fopen(path,'r');assert(f>=0);c=onCleanup(@()fclose(f));
while true,b=fread(f,1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
function h=setup_manifest_sha(lock)
parts=cell(1,numel(lock.setupFiles));
for k=1:numel(lock.setupFiles),parts{k}=[char(lock.setupFiles(k).name) '|' lower(char(lock.setupFiles(k).sha256))];end
s=strjoin(parts,';');md=java.security.MessageDigest.getInstance('SHA-256');md.update(typecast(uint8(unicode2native(s,'UTF-8')),'int8'));
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
function write_json(path,value)
f=fopen(path,'w','n','UTF-8');assert(f>=0);c=onCleanup(@()fclose(f));fwrite(f,jsonencode(value),'char');fwrite(f,newline,'char');
end
