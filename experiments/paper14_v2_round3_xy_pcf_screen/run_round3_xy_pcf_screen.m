function a=event_audit(log,cfg,lock)
ix=find(log.position_head_update_executed(:));n=numel(ix);assert(n>0,'ROUND3:NoEvents','No Head update events.');
s=double(log.stage1_position_pcf_event_s_original_mps(ix,:));e=double(log.stage1_position_pcf_event_eta_before_mps(ix,:));
ee=double(log.stage1_position_pcf_event_eta_effective_mps(ix,:));m=double(log.stage1_position_pcf_event_eta_mask(ix,:));
c=double(log.stage1_position_pcf_event_s_coord_mps(ix,:));ce=double(log.stage1_position_pcf_event_s_coord_eff_mps(ix,:));
wb=double(log.stage1_position_event_weight_before_33x3);wa=double(log.stage1_position_event_weight_after_33x3);
phi=double(log.stage1_position_event_phi_33(ix,:));raw=double(log.stage1_position_event_raw_acceleration_mps2(ix,:));
dt=double(log.stage1_position_event_dt_s(ix));beta=double(log.stage1_position_event_beta(ix));
assert(isequal(size(s),[n 3])&&isequal(size(wb),[33 3 n])&&isequal(size(wa),size(wb))&& ...
    isequal(size(phi),[n 33])&&isequal(size(raw),[n 3]),'ROUND3:EventShape','Event log dimensions invalid.');
assert(all(isfinite([s(:);e(:);ee(:);m(:);c(:);ce(:);wb(:);wa(:);phi(:);raw(:);dt(:);beta(:)])), ...
    'ROUND3:EventFinite','Event logs contain nonfinite values.');
lim=[7 8 10];dmax=double(cfg.rbf.position.dmax(:)).';expectedMask=repmat([1 1 0],n,1);
maskErr=max(abs(m(:)-expectedMask(:)));em=max(abs(ee(:)-reshape(e.*m,[],1)));
cm=max(abs(c(:)-reshape(s-ee,[],1)));cl=max(abs(ce(:)-reshape(max(min(c,lim),-lim),[],1)));
re=0;we=0;md=0;
for j=1:n
    b=wb(:,:,j);v=phi(j,:).';raw0=(b.'*v).';re=max(re,max(abs(raw(j,:)-raw0)));
    out=beta(j)*max(min(raw0,dmax),-dmax);actual=double(log.stage1_position_event_applied_acceleration_mps2(ix(j),:));
    re=max(re,max(abs(out-actual)));
    nxt=max(min(b+dt(j)*(-lock.run.gamma*beta(j)*v*(ce(j,:))-0.002*b),60),-60);
    we=max(we,max(abs(wa(:,:,j)-nxt),[],'all'));md=max(md,max(abs(wa(:,:,j)-b),[],'all'));
end
assert(max([maskErr em cm cl re we])<=1e-12,'ROUND3:EventEquation','Event mask/output/update equation error exceeds 1e-12.');
a=struct('count',n,'mask_err',maskErr,'eta_err',em,'coord_err',cm,'clip_err',cl,'raw_err',re,'weight_err',we,'max_delta',md);
end

