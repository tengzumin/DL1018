function verify_file(p,h),assert(isfile(p)&&strcmpi(sha_file(p),h),'ROUND3:InputSHA','Input SHA mismatch: %s',p);end
function h=sha_file(p)
md=java.security.MessageDigest.getInstance('SHA-256');f=fopen(p,'r');assert(f>=0);c=onCleanup(@()fclose(f));
while true,b=fread(f,1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
function x=file_id(p),d=dir(p);x=struct('bytes',double(d.bytes),'mtime',double(d.datenum),'sha256',sha_file(p));end
function n=dir_bytes(p),n=0;if ~isfolder(p),return;end;d=dir(fullfile(p,'**','*'));for k=1:numel(d),if ~d(k).isdir,n=n+double(d(k).bytes);end,end,end
function write_text(p,t),f=fopen(p,'w','n','UTF-8');assert(f>=0);c=onCleanup(@()fclose(f));fwrite(f,t,'char');end
function write_json(p,x),f=fopen(p,'w','n','UTF-8');assert(f>=0);c=onCleanup(@()fclose(f));fwrite(f,jsonencode(x),'char');fwrite(f,newline,'char');end
function h=maybe_sha(p),h='';if isfile(p),h=sha_file(p);end,end

