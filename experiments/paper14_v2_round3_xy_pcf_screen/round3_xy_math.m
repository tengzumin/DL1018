function out=round3_xy_math(surface,etaBefore,k2,rf,plantDt,eventDt,mask,phi,W,gamma,beta,dmax)
% Pure offline equations only; no Plant, runtime callback, or controller call.
surface=double(surface(:)); etaBefore=double(etaBefore(:)); k2=double(k2(:));
rf=double(rf(:)); mask=double(mask(:)); phi=double(phi(:)); W=double(W);
dmax=double(dmax(:));
assert(isequal(size(surface),[3,1])&&isequal(size(etaBefore),[3,1])&& ...
    isequal(size(k2),[3,1])&&isequal(size(rf),[3,1])&&isequal(size(mask),[3,1])&& ...
    numel(phi)==33&&isequal(size(W),[33,3])&&numel(dmax)==3&& ...
    all(isfinite([surface;etaBefore;k2;rf;mask;phi;W(:);dmax]))&& ...
    all(k2>=0)&&all(dmax>0)&&isscalar(plantDt)&&plantDt>0&& ...
    isscalar(eventDt)&&eventDt>0&&gamma>0&&beta>=0&&beta<=1, ...
    'ROUND3:MathInput','Invalid offline equation-smoke input.');
limits=[7;8;10];
decay=exp(-k2*plantDt); integral=plantDt*ones(3,1); positive=k2>0;
integral(positive)=-expm1(-k2(positive)*plantDt)./k2(positive);
etaNext=decay.*etaBefore+integral.*rf;
etaEffective=mask.*etaBefore;
sCoord=surface-etaEffective;
sEff=max(min(sCoord,limits),-limits);
raw=W.'*phi;
clippedRaw=max(min(raw,dmax),-dmax);
applied=beta*clippedRaw;
WNext=max(min(W+eventDt*(-gamma*beta*phi*sEff.'-0.002*W),60),-60);
out=struct('eta_next',etaNext,'eta_effective',etaEffective,'s_coord',sCoord, ...
    's_eff',sEff,'raw_before_update',raw,'clipped_raw',clippedRaw, ...
    'applied_output',applied,'weight_after',WNext, ...
    'off_s_eff',max(min(surface,limits),-limits), ...
    'on_s_eff',max(min(surface-etaBefore,limits),-limits));
end
