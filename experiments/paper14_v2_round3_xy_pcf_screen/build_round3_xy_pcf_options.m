function [optsXY,audit] = build_round3_xy_pcf_options(cfg,model)
% R3 candidate: preserve the locked PCF-on options and mask eta only at Z Head update.
arguments
    cfg (1,1) struct
    model (1,1) struct
end
assert(strcmp(char(model.model_id),'DSSM14')&&strcmp(char(model.architecture),'DSSM')&& ...
    double(model.seed)==2026102001&&double(model.selected_step)==60000&& ...
    double(model.input_dim)==14&&double(model.window)==32&&double(model.context_length)==32, ...
    'ROUND3:ModelIdentity','Unexpected frozen DSSM14 model identity.');
W0=double(model.output_W);
assert(isequal(size(W0),[33,3])&&strcmpi(hash_bytes(typecast(W0(:),'uint8')), ...
    '88f8c4f2495438c3797655c48bab1bf0c11ac2e27bff1f5f2a7423a8f0a2cf53'), ...
    'ROUND3:W0Identity','Frozen W0 shape or identity changed.');
normalizerIdentity=hash_normalizer_arrays(model);
assert(strcmpi(normalizerIdentity, ...
    '533aad9a2c66874cfa67f5d268661835e81e58b797cba7d6fc1c12d4013de5f0'), ...
    'ROUND3:NormalizerIdentity','Loaded normalizer arrays differ from frozen R2.');

optsOn=position_only_search_options(cfg,model,'FEATURE',12,1);
assert(logical(optsOn.stage1_position_runtime.command_filter_coordination_v3_5.enabled), ...
    'ROUND3:PCFOnBase','The base options must retain PCF-on.');
assert(~isfield(optsOn.stage1_position_runtime.position_only_search_head,'eta_mask'), ...
    'ROUND3:UnexpectedBaseMask','The frozen PCF-on builder must not inject an eta mask.');
optsXY=optsOn;
optsXY.stage1_position_runtime.position_only_search_head.eta_mask=[1;1;0];
optsXYWithoutMask=optsXY;
optsXYWithoutMask.stage1_position_runtime.position_only_search_head= ...
    rmfield(optsXYWithoutMask.stage1_position_runtime.position_only_search_head,'eta_mask');
assert(isequaln(optsXYWithoutMask,optsOn),'ROUND3:SingleFactor', ...
    'Removing only eta_mask must recover the frozen PCF-on options exactly.');
p=optsXY.stage1_position_runtime; h=p.position_only_search_head;
assert(logical(p.enabled)&&logical(p.update_enabled)&&logical(h.enabled)&& ...
    strcmpi(char(h.head_type),'FEATURE')&&double(h.gamma)==12&&double(h.kappa)==1&& ...
    double(p.beta_scale)==1&&isequal(double(p.weight),W0)&&isequal(double(h.W0),W0)&& ...
    isequal(double(h.eta_mask(:)),[1;1;0]), ...
    'ROUND3:HeadContract','Head type/update/W0/gamma/kappa/beta/mask changed.');
fusionEnabled=isfield(optsXY,'attitude_fusion_v3_6')&& ...
    isstruct(optsXY.attitude_fusion_v3_6)&&logical(optsXY.attitude_fusion_v3_6.enabled);
assert(~fusionEnabled,'ROUND3:FusionContract', ...
    'The inherited V3.6 attitude fusion must stay disabled.');
assert(logical(optsXY.formal_rbf_baseline)&&logical(optsXY.rbf_attitude_enabled)&& ...
    logical(optsXY.rbf_attitude_output_enabled)&&logical(optsXY.rbf_attitude_update_enabled), ...
    'ROUND3:AttitudeControl','Formal B/RBF attitude baseline, output, or update flags changed.');
assert(abs(double(cfg.plant.dt)-0.001)<=1e-12&&double(cfg.rbf.runtime.position_update_hz)==100, ...
    'ROUND3:Clocks','Expected locked 1-kHz Plant and 100-Hz Head clock.');
audit=struct('experimental_difference','position_only_search_head.eta_mask', ...
    'eta_mask',[1;1;0],'pcf_enabled',true,'update_enabled',true,'head_enabled',true, ...
    'head_type','FEATURE','gamma',12,'kappa',1,'beta_scale',1, ...
    'attitude_fusion_enabled',false,'formal_rbf_baseline',true, ...
    'rbf_attitude_enabled',true,'rbf_attitude_output_enabled',true, ...
    'rbf_attitude_update_enabled',true, ...
    'normalizer_identity_sha256',normalizerIdentity, ...
    'W0_output_W_sha256',hash_bytes(typecast(W0(:),'uint8')));
end

function h=hash_normalizer_arrays(model)
md=java.security.MessageDigest.getInstance('SHA-256');
for name={'input_mu','input_sigma'}
    field=name{1}; a=reshape(double(model.(field)),1,[]);
    assert(numel(a)==14,'ROUND3:NormalizerShape','Expected fourteen %s entries.',field);
    header=[field char(0) '((1, 14), ''float64'')' char(0)];
    md.update(typecast(uint8(unicode2native(header,'UTF-8')),'int8'));
    md.update(typecast(a(:),'int8'));
end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end

function h=hash_bytes(bytes)
md=java.security.MessageDigest.getInstance('SHA-256');
md.update(typecast(uint8(bytes(:)),'int8'));
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
