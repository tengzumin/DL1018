function batch=run_c6_startup_ramp_tail11_v1(mode)
% Sequential C6 tail batch; executable only after the separate parent release.
if nargin~=1||~strcmpi(char(mode),'PARENT_APPROVED_C6_TAIL11_V1')
    error('C6:TailMode','Pass exactly PARENT_APPROVED_C6_TAIL11_V1 after parent release.');
end
here=fileparts(mfilename('fullpath')); repoRoot=fileparts(fileparts(fileparts(here)));
lockPath=fullfile(here,'C6_STARTUP_RAMP_INPUT_LOCK_v1.json');
contractPath=fullfile(here,'C6_STARTUP_RAMP_RUN_CONTRACT_v1.json');
prepPath=fullfile(here,'C6_STARTUP_RAMP_PREPARE_RESULT_v1.json');
snapshotPath=fullfile(here,'C6_STARTUP_RAMP_PREPARED_CFG_OPTS_v1.mat');
firstReleasePath=fullfile(here,'C6_FIRST_PARENT_RELEASE_v1.json');
tailContractPath=fullfile(here,'C6_TAIL11_RUN_CONTRACT_v1.json');
bindingPath=fullfile(here,'C6_TAIL11_SOURCE_BINDING_v1.json');
releaseContractPath=fullfile(here,'C6_TAIL11_PARENT_RELEASE_CONTRACT_v1.json');
releasePath=fullfile(here,'C6_TAIL11_PARENT_RELEASE_v1.json');
batchStatusPath=fullfile(here,'C6_TAIL11_BATCH_STATUS_v1.json');
bodyPath=fullfile(here,'C6_TAIL11_BODY_COMPLETE_v1.json');
osExitPath=fullfile(here,'C6_TAIL11_OS_EXIT_v1.json');
preflightFailurePath=fullfile(here,'C6_TAIL11_PREFLIGHT_FAILURE_v1.json');
batchWritten=false; records=empty_records(); batch=struct();
try
    required={lockPath,contractPath,prepPath,snapshotPath,firstReleasePath,tailContractPath, ...
        bindingPath,releaseContractPath,releasePath};
    assert(all(cellfun(@isfile,required)),'C6:TailInputs','Frozen C6 inputs, source binding and separate parent release are required.');
    assert(~any(isfile({batchStatusPath,bodyPath,osExitPath,preflightFailurePath})), ...
        'C6:TailNoRetry','Tail batch output already exists; preserve it and do not retry.');
    lock=jsondecode(fileread(lockPath)); contract=jsondecode(fileread(contractPath));
    prep=jsondecode(fileread(prepPath)); firstRelease=jsondecode(fileread(firstReleasePath));
    tailContract=jsondecode(fileread(tailContractPath)); binding=jsondecode(fileread(bindingPath));
    releaseContract=jsondecode(fileread(releaseContractPath)); release=jsondecode(fileread(releasePath));
    lockSha=sha256_file(lockPath); contractSha=sha256_file(contractPath); prepSha=sha256_file(prepPath);
    snapshotSha=sha256_file(snapshotPath); firstReleaseSha=sha256_file(firstReleasePath);
    tailContractSha=sha256_file(tailContractPath); bindingSha=sha256_file(bindingPath);
    releaseContractSha=sha256_file(releaseContractPath); releaseSha=sha256_file(releasePath);
    runnerPath=[mfilename('fullpath') '.m']; runnerSha=sha256_file(runnerPath);
    assert(strcmp(lock.schema,'C6_STARTUP_RAMP_INPUT_LOCK_V1')&& ...
        strcmp(lock.state,'LOCKED_C6_STARTUP_RAMP_NO_PLANT_PARENT_REVIEW_REQUIRED_V1')&& ...
        ~logical(lock.plant_authorized_by_this_lock)&&double(lock.source_counts.total)==32&& ...
        double(lock.source_counts.matlab)==31&&double(lock.source_counts.mat)==1&& ...
        strcmp(contract.schema,'C6_STARTUP_RAMP_RUN_CONTRACT_V1')&&strcmp(contract.state,lock.state)&& ...
        strcmp(prep.schema,'C6_STARTUP_RAMP_PREPARE_RESULT_V1')&& ...
        strcmp(prep.status,'PREPARED_C6_STARTUP_RAMP_NO_PLANT_WAIT_PARENT_RELEASE_V1')&& ...
        double(prep.plant_calls)==0&&~logical(prep.run_episode_called)&&~logical(prep.TEST_accessed)&& ...
        strcmpi(prep.input_lock_sha256,lockSha)&&strcmpi(prep.snapshot_sha256,snapshotSha)&& ...
        strcmpi(contractSha,lock.source_files.contract.sha256)&& ...
        isequal(double(lock.coordinate_mask(:)),[1;1;0])&&isequal(double(contract.coordinate_mask(:)),[1;1;0])&& ...
        strcmp(contract.candidate,'C6_STARTUP_PREDICTION_RAMP')&&logical(contract.pcf_auxiliary_enabled)&& ...
        logical(contract.algorithm_change.prediction_gradient_scaled_by_beta), ...
        'C6:FrozenInputs','Frozen C6 v1 lock, contract or no-Plant preparation changed.');
    assert(strcmp(tailContract.schema,'C6_TAIL11_RUN_CONTRACT_V1')&& ...
        strcmp(tailContract.state,'LOCKED_C6_TAIL11_WAIT_PARENT_RELEASE_V1')&& ...
        strcmp(tailContract.candidate,contract.candidate)&& ...
        isequal(double(tailContract.coordinate_mask(:)),[1;1;0])&& ...
        isequaln(tailContract.model,contract.model)&& ...
        isequaln(tailContract.fixed_parameters,contract.fixed_parameters)&& ...
        strcmp(tailContract.scoring_comparator,contract.scoring_comparator)&& ...
        strcmpi(tailContract.input_lock_sha256,lockSha)&&strcmpi(tailContract.original_run_contract_sha256,contractSha)&& ...
        strcmpi(tailContract.prepare_result_sha256,prepSha)&&strcmpi(tailContract.snapshot_sha256,snapshotSha)&& ...
        isequal(string(tailContract.original_scene_ids(:)),string(contract.scene_ids(:)))&& ...
        strcmp(tailContract.first_scene_id,contract.first_scene_id)&& ...
        double(tailContract.limits.max_new_Plant)==11&&double(tailContract.limits.max_total_Plant_including_pilot)==12&& ...
        double(tailContract.limits.max_output_bytes)==double(contract.limits.max_output_bytes)&& ...
        double(tailContract.limits.minimum_free_bytes)==double(contract.limits.minimum_free_bytes)&& ...
        double(tailContract.limits.per_scene_output_reserve_bytes)==double(contract.limits.per_scene_output_reserve_bytes)&& ...
        strcmp(char(tailContract.limits.deadline_utc),char(contract.limits.deadline_utc))&& ...
        double(tailContract.limits.seconds_per_remaining_scene_for_deadline_guard)==180&& ...
        double(tailContract.limits.process_exit_buffer_seconds)==600, ...
        'C6:TailContract','Tail contract differs from the exact frozen C6 inputs.');
    assert(strcmp(firstRelease.schema,'C6_FIRST_PARENT_RELEASE_V1')&& ...
        strcmp(firstRelease.state,'APPROVED_C6_FIRST_SCENE_V1')&&logical(firstRelease.plant_authorized)&& ...
        double(firstRelease.max_new_Plant)==1&&strcmp(firstRelease.scene_id,contract.first_scene_id)&& ...
        isequal(double(firstRelease.coordinate_mask(:)),[1;1;0]), ...
        'C6:FirstRelease','The first-scene release is missing or does not bind the approved pilot.');
    assert(strcmp(binding.schema,'C6_TAIL11_SOURCE_BINDING_V1')&& ...
        strcmp(binding.state,'SOURCE_BOUND_C6_TAIL11_WAIT_PARENT_RELEASE_V1')&& ...
        strcmpi(binding.input_lock_sha256,lockSha)&&strcmpi(binding.original_run_contract_sha256,contractSha)&& ...
        strcmpi(binding.prepare_result_sha256,prepSha)&&strcmpi(binding.snapshot_sha256,snapshotSha)&& ...
        strcmpi(binding.first_scene_release_sha256,firstReleaseSha)&& ...
        strcmpi(binding.tail_runner_sha256,runnerSha)&&isequal(double(binding.coordinate_mask(:)),[1;1;0])&& ...
        double(binding.active_source_count)==32&&double(binding.shared_input_count)==6&& ...
        isequal(string(binding.tail_scene_ids(:)),string(tailContract.tail_scene_ids(:))), ...
        'C6:SourceBinding','Tail binding differs from the frozen C6 v1 inputs or runner.');
    assert(same_path(binding.source_files(ref_index(binding,'tail_runner')).path,runnerPath)&& ...
        same_path(binding.source_files(ref_index(binding,'launcher')).path,fullfile(here,'RUN_C6_TAIL11_EXACT_v1.ps1'))&& ...
        same_path(binding.source_files(ref_index(binding,'tail_contract')).path,tailContractPath)&& ...
        same_path(binding.source_files(ref_index(binding,'parent_release_contract')).path,releaseContractPath)&& ...
        same_path(binding.source_files(ref_index(binding,'input_lock')).path,lockPath)&& ...
        same_path(binding.source_files(ref_index(binding,'original_run_contract')).path,contractPath)&& ...
        same_path(binding.source_files(ref_index(binding,'prepare_result')).path,prepPath)&& ...
        same_path(binding.source_files(ref_index(binding,'prepared_snapshot')).path,snapshotPath)&& ...
        same_path(binding.source_files(ref_index(binding,'first_scene_release')).path,firstReleasePath), ...
        'C6:SourceBindingPaths','Tail source binding paths do not resolve to the isolated C6 inputs.');
    verify_tail_release_contract(releaseContract,release,tailContract);
    assert(all(isfield(release,releaseContract.required_fields))&& ...
        strcmp(release.schema,'C6_TAIL11_PARENT_RELEASE_V1')&& ...
        strcmp(release.state,'APPROVED_C6_TAIL11_V1')&&logical(release.plant_authorized)&& ...
        logical(release.subsequent_11_flights_authorized)&&double(release.max_new_Plant)==11&& ...
        strcmpi(release.tail_source_binding_sha256,bindingSha)&& ...
        strcmpi(release.tail_runner_sha256,runnerSha)&&same_path(release.tail_runner_path,runnerPath)&& ...
        strcmpi(release.launcher_sha256,ref_sha(binding,'launcher'))&& ...
        strcmpi(release.tail_run_contract_sha256,tailContractSha)&& ...
        strcmpi(release.parent_release_contract_sha256,releaseContractSha)&& ...
        strcmpi(release.c6_input_lock_sha256,lockSha)&&strcmpi(release.c6_run_contract_sha256,contractSha)&& ...
        strcmpi(release.prepare_result_sha256,prepSha)&&strcmpi(release.cfg_opts_snapshot_sha256,snapshotSha)&& ...
        strcmpi(release.first_scene_parent_release_sha256,firstReleaseSha)&& ...
        isequal(string(release.tail_scene_ids(:)),string(tailContract.tail_scene_ids(:)))&& ...
        isequal(double(release.coordinate_mask(:)),[1;1;0]), ...
        'C6:TailRelease','A separate exact parent release for the fixed eleven-scene tail is required.');
    verify_tail_release_evidence(release,binding,lock,firstReleaseSha,lockSha,contractSha,prepSha, ...
        snapshotSha,runnerSha,bindingSha,tailContractSha,releaseContractSha);
    verify_c6_lock_sources(lock,binding);

    tailIds=contract.scene_ids; firstIx=find(strcmp(tailIds,contract.first_scene_id));
    assert(numel(firstIx)==1,'C6:FirstSceneIndex','The frozen first scene must occur once in the original scene list.');
    tailIds(firstIx)=[];
    assert(numel(tailIds)==11&&numel(unique(string(tailIds)))==11&& ...
        isequal(string(tailIds(:)),string(tailContract.tail_scene_ids(:)))&& ...
        isequal(string(tailIds(:)),string(binding.tail_scene_ids(:)))&& ...
        isequal(string(tailIds(:)),string(release.tail_scene_ids(:)))&& ...
        isequal(string(contract.scene_ids(:)),string(lock.scene_ids_reuse_12(:))), ...
        'C6:TailSceneOrder','Tail must be the original twelve-scene order with only the already-run first scene removed.');
    assert(double(release.per_scene_output_reserve_bytes)==double(tailContract.limits.per_scene_output_reserve_bytes)&& ...
        double(release.max_output_bytes)==double(tailContract.limits.max_output_bytes)&& ...
        double(release.minimum_free_bytes)==double(tailContract.limits.minimum_free_bytes)&& ...
        strcmp(char(release.deadline_utc),char(tailContract.limits.deadline_utc))&& ...
        double(release.seconds_per_remaining_scene_for_deadline_guard)==180&& ...
        double(release.process_exit_buffer_seconds)==600&&double(release.training_steps)==0&& ...
        double(release.optimizer_steps)==0&&~logical(release.parameter_or_seed_search)&& ...
        double(release.new_B_sorties)==0&&~logical(release.TEST_accessed)&&~logical(release.automatic_retry)&& ...
        ~logical(release.separate_MATLAB_process_per_scene), ...
        'C6:TailScope','Release changes the frozen resource limits or prohibitions.');
    assert(same_path(tailContract.b72_binding.raw_manifest_path,release.b72_raw_manifest_path)&& ...
        strcmpi(tailContract.b72_binding.raw_manifest_sha256,release.b72_raw_manifest_sha256)&& ...
        same_path(tailContract.b72_binding.parent_review_path,release.b72_parent_review_path)&& ...
        strcmpi(tailContract.b72_binding.parent_review_sha256,release.b72_parent_review_sha256)&& ...
        same_path(tailContract.b72_binding.batch_status_path,release.b72_batch_status_path)&& ...
        strcmpi(tailContract.b72_binding.batch_status_sha256,release.b72_batch_status_sha256)&& ...
        same_path(tailContract.b72_binding.raw_manifest_path,binding.b72.raw_manifest_path)&& ...
        strcmpi(tailContract.b72_binding.raw_manifest_sha256,binding.b72.raw_manifest_sha256)&& ...
        same_path(tailContract.b72_binding.parent_review_path,binding.b72.parent_review_path)&& ...
        strcmpi(tailContract.b72_binding.parent_review_sha256,binding.b72.parent_review_sha256)&& ...
        same_path(tailContract.b72_binding.batch_status_path,binding.b72.batch_status_path)&& ...
        strcmpi(tailContract.b72_binding.batch_status_sha256,binding.b72.batch_status_sha256)&& ...
        strcmpi(tailContract.b72_binding.input_lock_sha256,lock.upstream_refs.b72_input_lock.sha256)&& ...
        strcmpi(tailContract.b72_binding.run_contract_sha256,lock.upstream_refs.b72_run_contract.sha256)&& ...
        strcmpi(tailContract.b72_binding.prepare_result_sha256,lock.upstream_refs.b72_prepare_result.sha256)&& ...
        strcmpi(tailContract.b72_binding.release_sha256,lock.upstream_refs.b72_release.sha256), ...
        'C6:B72ContractBinding','The C6 tail contract and parent release disagree on the exact B72 scoring sources.');

    % The first scene is an audited engineering pilot, not a scientific pass or tail authorization.
    b72=verify_b72_parent_and_manifest(release,binding,lock);
    assert(strcmp(b72.schema,'C5_B72_SCORING_MANIFEST_V1')&&numel(b72.records)==72, ...
        'C6:EvidenceBinding','B72 scoring evidence is incomplete.');

    % Rebuild the exact frozen runtime stack after init_dl1018 resets the MATLAB path.
    active=lock.active_source_inventory; initPath=source_path(active,'init_dl1018.m');
    optionsPath=source_path(active,'position_only_search_options.m');
    headPath=source_path(active,'position_only_search_head_step.m');
    forwardPath=source_path(active,'position_stage1_model_forward_v2.m');
    add_active_paths(active); addpath(fullfile(repoRoot,'matlab','runtime'),'-end'); addpath(fullfile(repoRoot,'matlab','core'),'-end');
    addpath(fileparts(initPath),'-begin'); clear init_dl1018; rehash;
    [cfgNow,~,resolvedRoot]=init_dl1018();
    assert(same_path(resolvedRoot,repoRoot),'C6:ProjectRoot','Runtime resolved a different repository root.');
    add_active_paths(active); addpath(fullfile(repoRoot,'matlab','runtime'),'-end'); addpath(fullfile(repoRoot,'matlab','core'),'-end');
    addpath(fileparts(optionsPath),'-begin'); addpath(fileparts(headPath),'-begin');
    addpath(fileparts(forwardPath),'-begin'); addpath(here,'-begin');
    clear run_episode_dl1018 run_dl1018_closed_loop delayed_prediction_step_candidate ...
        position_only_search_options position_only_search_head_step position_stage1_model_forward_v2 init_dl1018; rehash;
    for k=1:numel(active)
        verify_ref(active(k)); [~,name,ext]=fileparts(char(active(k).path));
        if strcmpi(ext,'.m'), assert(same_path(which(name),active(k).path), ...
                'C6:WhichShadow','Locked source %s resolves to a shadow.',name); end
    end
    assert(same_path(which('run_dl1018_closed_loop'),fullfile(here,'run_dl1018_closed_loop.m'))&& ...
        same_path(which('run_episode_dl1018'),fullfile(here,'run_episode_dl1018.m'))&& ...
        same_path(which('delayed_prediction_step_candidate'),fullfile(here,'delayed_prediction_step_candidate.m')), ...
        'C6:Isolation','The C6 core, wrapper and helper must resolve from the isolated directory.');
    pack=load(snapshotPath,'cfg','opts','W0','modelIdentity','sourceIdentity','sceneIdentity');
    assert(all(isfield(pack,{'cfg','opts','W0','modelIdentity','sourceIdentity','sceneIdentity'}))&& ...
        isequaln(cfgNow,pack.cfg)&&isequal(double(pack.opts.position_coordinate_mask(:)),[1;1;0])&& ...
        logical(pack.opts.position_delayed_prediction_enabled)&& ...
        double(pack.sourceIdentity.which_checks)==numel(active)&& ...
        same_path(pack.sourceIdentity.runtime_core_path,fullfile(here,'run_dl1018_closed_loop.m'))&& ...
        strcmpi(pack.sourceIdentity.runtime_core_sha256,source_ref_sha(lock.source_files.isolated_sources,'runtime_core')), ...
        'C6:Snapshot','Fresh C6 config/options/source identity differ from the no-Plant snapshot.');
    modelPath=source_role(lock.shared_input_files,'model_mat');
    modelPack=load(modelPath,'model'); assert(isfield(modelPack,'model')&&isstruct(modelPack.model),'C6:Model','Frozen model is missing.');
    model=modelPack.model;
    optsTemplate=position_only_search_options(cfgNow,model,'FEATURE',12,1);
    optsTemplate.position_delayed_prediction_enabled=true; optsTemplate.position_coordinate_mask=[1;1;0];
    assert(isequaln(optsTemplate,pack.opts)&&isequal(double(model.output_W),double(pack.W0))&& ...
        strcmp(char(model.model_id),char(contract.model.id))&&double(model.seed)==double(contract.model.seed)&& ...
        double(model.selected_step)==double(contract.model.selected_step)&&double(model.input_dim)==double(contract.model.input_dim)&& ...
        double(model.window)==double(contract.model.window)&&strcmpi(pack.modelIdentity.W0_sha256,contract.model.W0_sha256), ...
        'C6:OptsOrModelChanged','The model, W0 or reconstructed C6 options differ from the prepared snapshot.');
    pilot=verify_c6_first_pilot(binding,release,lock,contract,firstRelease,firstReleaseSha, ...
        lockSha,contractSha,prepSha,snapshotSha,pack);
    assert(strcmp(pilot.scene_id,contract.first_scene_id),'C6:PilotSceneIdentity', ...
        'Pilot scene identity differs from the prepared snapshot.');

    maxBytes=double(contract.limits.max_output_bytes); reserveBytes=double(contract.limits.per_scene_output_reserve_bytes);
    minFree=double(contract.limits.minimum_free_bytes);
    deadline=datetime(char(contract.limits.deadline_utc),'InputFormat',"yyyy-MM-dd'T'HH:mm:ss'Z'",'TimeZone','UTC');
    runRoot=fullfile(here,'runs_c6_startup_ramp_v1');
    check_resources(here,repoRoot,maxBytes,reserveBytes,minFree,deadline,numel(tailIds));
    for k=1:numel(tailIds)
        row=scene_row(lock,char(tailIds{k}));
        b72row=b72_scene_row(b72,char(tailIds{k}));
        verify_file(row.B_source.path,row.B_source.sha256);
        verify_file(b72row.raw_path,b72row.raw_sha256); verify_file(b72row.run_status_path,b72row.run_status_sha256);
        verify_b72_scene(b72row,char(tailIds{k}));
        attemptDir=fullfile(runRoot,char(tailIds{k}),'C6_STARTUP_PREDICTION_RAMP','attempt_01');
        assert(~isfolder(attemptDir),'C6:TailNoRetry','Prior C6 tail attempt exists for %s.',char(tailIds{k}));
    end
    sharedRelease=jsondecode(fileread(lock.upstream_refs.shared_job_release.path));
    assert(isfile(sharedRelease.shared_heavy_job_lock_path),'C6:SharedLockMissing','Frozen shared-job lock is missing.');
    raf=java.io.RandomAccessFile(sharedRelease.shared_heavy_job_lock_path,'rw');
    channel=raf.getChannel(); jobLock=channel.tryLock();
    assert(~isempty(jobLock),'C6:ConcurrentHeavyJob','Shared heavy-job lock is held; do not wait or seize it.');
    cleanup=onCleanup(@()release_job_lock(jobLock,channel,raf)); %#ok<NASGU>
    batchId=['C6_TAIL11_' strrep(utc_now(),':','')];
    batch=struct('schema','C6_TAIL11_BATCH_STATUS_V1');
    batch.status='RUNNING'; batch.batch_id=batchId; batch.process_scope='ONE_SEQUENTIAL_MATLAB_PROCESS';
    batch.source_binding_sha256=bindingSha; batch.tail_release_sha256=releaseSha; batch.runner_sha256=runnerSha;
    batch.tail_scene_ids=tailIds; batch.completed_scenes=0; batch.plant_calls=0;
    batch.records=records; batch.created_utc=utc_now();
    write_json_new(batchStatusPath,batch); batchWritten=true;

    for k=1:numel(tailIds)
        sceneId=char(tailIds{k}); row=scene_row(lock,sceneId); b72row=b72_scene_row(b72,sceneId);
        attemptDir=fullfile(runRoot,sceneId,'C6_STARTUP_PREDICTION_RAMP','attempt_01');
        attemptStartedPath=fullfile(attemptDir,'attempt_started.marker');
        markerPath=fullfile(attemptDir,'first_plant_step.marker'); rawPath=fullfile(attemptDir,'raw_run.mat');
        runStartPath=fullfile(attemptDir,'run_start.mat'); statusPath=fullfile(attemptDir,'run_status.json');
        failurePath=fullfile(attemptDir,'C6_TAIL11_FAILURE_V1.json');
        invocationEntered=false; attemptCreated=false; rawSceneId=''; startedUtc=utc_now();
        try
            remaining=numel(tailIds)-k+1;
            check_resources(here,repoRoot,maxBytes,reserveBytes,minFree,deadline,remaining);
            verify_ref(binding.source_files(ref_index(binding,'tail_runner')));
            verify_file(bindingPath,bindingSha); verify_file(releasePath,releaseSha);
            for j=1:numel(active), verify_ref(active(j)); end
            row=scene_row(lock,sceneId); b72row=b72_scene_row(b72,sceneId);
            verify_file(row.B_source.path,row.B_source.sha256);
            sceneIdentity=scene_identity_row(pack,sceneId);
            assert(same_path(sceneIdentity.B_raw_path,row.B_source.path)&& ...
                strcmpi(sceneIdentity.B_raw_sha256,row.B_source.sha256), ...
                'C6:PhysicalSceneIdentity','Locked physical B source differs from the prepared scene identity for %s.',sceneId);
            verify_file(b72row.raw_path,b72row.raw_sha256); verify_file(b72row.run_status_path,b72row.run_status_sha256);
            verify_b72_scene(b72row,sceneId);
            assert(~isfolder(attemptDir),'C6:TailNoRetry','Prior C6 tail attempt exists for %s.',sceneId);
            [mkStatus,mkMessage]=mkdir(attemptDir);
            assert(mkStatus,'C6:TailCreateAttempt','Cannot create attempt directory for %s: %s.',sceneId,mkMessage);
            attemptCreated=true;
            assert(~any(isfile({attemptStartedPath,markerPath,rawPath,runStartPath,statusPath,failurePath})), ...
                'C6:TailNoOverwrite','Attempt output already exists for %s.',sceneId);
            scenePack=load(row.B_source.path,'scene'); scene=scenePack.scene;
            assert(valid_scene(scene,sceneId),'C6:SceneChanged','Physical B input is not a valid locked scene: %s.',sceneId);
            rawSceneId=char(scene.scene_id); scene.scene_id=sceneId;
            % Rebuild a value-copy of frozen opts and W0 for every new episode.
            modelPack=load(modelPath,'model'); sceneModel=modelPack.model;
            assert(isequal(double(sceneModel.output_W),double(pack.W0))&& ...
                strcmp(char(sceneModel.model_id),char(contract.model.id))&& ...
                double(sceneModel.seed)==double(contract.model.seed)&& ...
                double(sceneModel.selected_step)==double(contract.model.selected_step), ...
                'C6:ResetW0','Fresh episode model does not start at the frozen W0 for %s.',sceneId);
            optsForScene=pack.opts; optsForScene.r2e_first_plant_step_marker=markerPath;
            assert(isequaln(rmfield(optsForScene,'r2e_first_plant_step_marker'),pack.opts), ...
                'C6:ResetOpts','Episode options were not rebuilt from the immutable prepared snapshot.');
            runStart=struct('actual_weight_update_enabled',true,'actual_prediction_gradient_enabled',true,'schema','C6_TAIL11_RUN_START_V1','batch_id',batchId,'batch_index',k, ...
                'batch_scope','ONE_SEQUENTIAL_MATLAB_PROCESS','scene_id',sceneId,'source_scene_id',rawSceneId, ...
                'candidate',contract.candidate,'coordinate_mask',[1 1 0],'started_utc',startedUtc, ...
                'source_binding_sha256',bindingSha,'tail_release_sha256',releaseSha, ...
                'input_lock_sha256',lockSha,'run_contract_sha256',tailContractSha,'prepare_result_sha256',prepSha, ...
                'cfg_opts_snapshot_sha256',snapshotSha,'physical_B_source_path',row.B_source.path, ...
                'physical_B_source_sha256',row.B_source.sha256,'scoring_B72_raw_path',b72row.raw_path, ...
                'scoring_B72_raw_sha256',b72row.raw_sha256,'scoring_B72_status_path',b72row.run_status_path, ...
                'scoring_B72_status_sha256',b72row.run_status_sha256,'source_identity',pack.sourceIdentity, ...
                'model_identity',pack.modelIdentity,'scene_identity',sceneIdentity,'W0',pack.W0, ...
