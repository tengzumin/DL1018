        result.attempt_output_bytes = directory_bytes(attemptDir);
        write_text(fullfile(here, 'reports', 'probe_round1.json'), jsonencode(result));
        fprintf('FROZEN_W0_PROBE %s stable=%s seconds=%.3f output_bytes=%d\n', ...
            sceneId, char(log.status), elapsedSeconds, directory_bytes(attemptDir));
        return; % No automatic continuation after the timing probe.
    end
    fprintf('FROZEN_W0_OFF %02d/12 %s stable=%s last_transition=%d max_dW=%.3g\n', ...
        i, sceneId, char(log.status), double(log.last_transition), max(beforeDelta, afterDelta));
end
end

function identity = verify_source_chain(files)
identity = repmat(struct('name', '', 'path', '', 'sha256', ''), numel(files), 1);
for k = 1:numel(files)
    expectedPath = char(files(k).path);
    activePath = which(char(files(k).name));
    assert(~isempty(activePath) && strcmpi(char(java.io.File(activePath).getCanonicalPath()), ...
        char(java.io.File(expectedPath).getCanonicalPath())), ...
        'FROZENW0:PlantSourcePath', 'Active Plant source path differs for %s.', files(k).name);
    actualHash = sha256_file_local(expectedPath);
    assert(strcmpi(actualHash, char(files(k).sha256)), ...
        'FROZENW0:PlantSourceHash', 'Plant source SHA256 changed for %s.', files(k).name);
    identity(k) = struct('name', char(files(k).name), 'path', expectedPath, 'sha256', actualHash);
end
end

