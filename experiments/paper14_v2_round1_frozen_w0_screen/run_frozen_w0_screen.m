function run_frozen_w0_screen(mode)
% FUTURE RUN ENTRY. Parent model review is required before any launch.
if nargin < 1, mode = 'PROBE'; end
mode = upper(char(mode));
assert(ismember(mode, {'PROBE','CONTINUE'}), 'FROZENW0:Mode', 'Mode must be PROBE or CONTINUE.');
here = fileparts(mfilename('fullpath'));
repoRoot = fileparts(fileparts(here));
lockPath = fullfile(here, 'frozen_inputs.json');
lock = jsondecode(fileread(lockPath));
globalDeadline = datetime(lock.safety.global_deadline_utc, 'InputFormat', ...
    'yyyy-MM-dd''T''HH:mm:ss''Z''', 'TimeZone', 'UTC');
assert(globalDeadline == datetime('2026-10-24T17:01:00Z', ...
    'InputFormat', 'yyyy-MM-dd''T''HH:mm:ss''Z''', 'TimeZone', 'UTC') && ...
    datetime('now', 'TimeZone', 'UTC') < globalDeadline, ...
    'FROZENW0:GlobalDeadline', 'Global hard deadline changed or has passed.');
preflightPath = fullfile(here, 'reports', 'preflight_round1.json');
