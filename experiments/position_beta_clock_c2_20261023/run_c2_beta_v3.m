assert(strcmp(pf.status,'PASS') && strcmp(pf.mode,mode) && ...
    strcmpi(pf.source_lock_sha256,sourceLockSha) && strcmpi(pf.release_sha256,releaseSha) && ...
    strcmpi(pf.approval_sha256,approvalSha) && strcmpi(pf.user_budget_authorization_sha256,release.user_budget_authorization_sha256) && ...
    pfAge>=seconds(0) && pfAge<=minutes(5) && logical(pf.fixed_step_screen_allowed) && ...
    double(pf.matlab_process_count)==0 && double(pf.other_heavy_job_count)==0 && ...
    isfield(pf,'gpu_compute_rows') && double(pf.gpu_compute_counter_active_rows)==0 && ...
    double(pf.remaining_attempt_count)==remainingAuthorized && ...
    double(pf.max_output_bytes)==double(budget.new_output_cap_bytes) && ...
    double(pf.minimum_free_bytes)==30000000000 && ...
    double(pf.projected_reserved_bytes)==remainingAuthorized*80000000 && ...
    double(pf.existing_c2_bytes)+double(pf.projected_reserved_bytes)<=double(budget.new_output_cap_bytes) && ...
    double(pf.free_bytes_before)-double(pf.projected_reserved_bytes)>=30000000000 && ...
    logical(pf.formal_timing_qualified)==false && ...
    logical(pf.plant_started)==false && double(pf.optimizer_steps)==0 && double(pf.gpu_jobs)==0 && ...
    logical(pf.TEST_accessed)==false && datetime('now','TimeZone','UTC')<datetime('2026-10-24T17:01:00Z', ...
        'InputFormat','yyyy-MM-dd''T''HH:mm:ss''Z''','TimeZone','UTC'), ...
    'C2:PreflightStale','Fresh matching preflight and remaining authorized scope are required.');
