mtime=datetime(mtimeMs/1000,'ConvertFrom','posixtime','TimeZone','UTC');
marker=struct('sha256',sha256_file(path),'mtime_utc',char(mtime,'yyyy-MM-dd''T''HH:mm:ss.SSS''Z'''));
end

function out=verify_active_sources(r2,candidateRuntime)
allPaths={}; allShas={};
for k=1:numel(r2.runtimeFiles)
    path=char(r2.runtimeFiles(k).path); [~,name,ext]=fileparts(path);
    if strcmpi([name ext],'run_dl1018_closed_loop.m'), expected=fullfile(candidateRuntime,'run_dl1018_closed_loop.m');
    elseif strcmpi([name ext],'run_episode_dl1018.m'), expected=fullfile(candidateRuntime,'run_episode_dl1018.m');
    else, expected=path; end
    verify_file(expected,sha_for_runtime(r2.runtimeFiles(k),name,ext,candidateRuntime));
    if strcmpi(ext,'.m')
        active=which(name); assert(~isempty(active)&&same_path(active,expected), ...
            'C2:RuntimePath','Active runtime path differs for %s.',name);
    end
    allPaths{end+1}=char(java.io.File(expected).getCanonicalPath()); %#ok<AGROW>
    allShas{end+1}=sha256_file(expected); %#ok<AGROW>
end
for k=1:numel(r2.plantFiles)
    path=char(r2.plantFiles(k).path); [~,name,~]=fileparts(path); active=which(name);
    assert(~isempty(active)&&same_path(active,path),'C2:PlantPath','Active Plant path differs for %s.',name);
    verify_file(path,r2.plantFiles(k).sha256);
    allPaths{end+1}=char(java.io.File(path).getCanonicalPath()); %#ok<AGROW>
    allShas{end+1}=sha256_file(path); %#ok<AGROW>
end
out=struct('paths',{allPaths},'sha256',{allShas});
end

