            'attempt_started_marker_sha256',sha256_file(fullfile(attemptDir,'attempt_started.marker')), ...
            'r2e_first_plant_step_marker_path',markerPath,'r2e_first_plant_step_marker_sha256',markerInfo.sha256, ...
