        'scene_payload_sha256',char(sceneMeta.payload_sha256), ...
        'c1_b_comparator_raw_path',c1bPath,'c1_b_comparator_raw_sha256',bBefore.sha256, ...
        'c1_on1_comparator_raw_path',c1onPath,'c1_on1_comparator_raw_sha256',onBefore.sha256, ...
        'model_mat_path',lock.shared_c1_inputs.model_mat_path,'model_mat_sha256',lock.shared_c1_inputs.model_mat_sha256, ...
        'model_id',char(model.model_id),'model_W0_sha256',lock.shared_c1_inputs.w0_output_W_double_f_order_sha256, ...
        'normalizer_npz_path',lock.shared_c1_inputs.normalizer_npz_path, ...
        'normalizer_npz_sha256',lock.shared_c1_inputs.normalizer_npz_sha256, ...
        'effective_config_path',lock.shared_c1_inputs.effective_config_path, ...
        'effective_config_sha256',lock.shared_c1_inputs.effective_config_sha256, ...
