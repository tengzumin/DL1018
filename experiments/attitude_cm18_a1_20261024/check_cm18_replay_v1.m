function R=evaluate_new_scene(R,rows,B,p)
log=B.log;scene=B.scene;cfg=B.cfg;idx=B.eventIndex;rawPred=R.raw_prediction(rows,:);
dmax=double(cfg.rbf.attitude.dmax(:)).';betaRise=double(cfg.rbf.attitude.beta_rise_time);
request=double(log.requested_generalized);wind=double(log.wind_torque_B);
for q=1:numel(idx)
    k=idx(q);w=double(log.state(k,10:12)).';
    clipped=max(min(rawPred(q,:),dmax),-dmax);clipAxis=abs(clipped-rawPred(q,:))>0;
    beta=min(k*double(B.dt(k))/betaRise,1);applied=beta*clipped(:);tauComp=B.J0*applied;
    tauReq=R.tau_BS_recomputed(rows(q),:).'-tauComp;
    command=[request(k,1);tauReq];
    Ptrue=simulation_parameters(cfg,double(scene.arms.rho_true(k,:)).', ...
        double(scene.arms.rhoDot_true(k,:)).');
    previous=double(log.motor_command(k-1,:)).';
    [setpoint,~,allocInfo]=allocate_control(command,B.Pnom,Ptrue,previous);
    motor=setpoint(:);
    if B.motorTc>0
        actAlpha=-expm1(-double(B.dt(k))/B.motorTc);
        motor=previous+actAlpha*(motor-previous);
    end
    wrench=Ptrue.allocation.C*motor.^2;
    J=double(Ptrue.inertia);Jdot=double(Ptrue.inertia_dot);
    omegaDot=(J\(wrench(2:4)+wind(k,:).'-cross(w,J*w)-Jdot*w)).';
    R.beta(rows(q))=beta;R.output_clipped(rows(q),:)=clipAxis;
    R.clipped_prediction(rows(q),:)=clipped;R.applied_acceleration(rows(q),:)=applied.';
    R.new_compensation_torque(rows(q),:)=tauComp.';R.new_request(rows(q),:)=command.';
    R.new_motor_setpoint(rows(q),:)=setpoint(:).';R.new_motor_command(rows(q),:)=motor.';
    R.new_realized(rows(q),:)=wrench.';
    R.new_generalized_clipped(rows(q),:)=logical(allocInfo.generalized_command_clipped(:)).';
    R.new_motor_saturated(rows(q),:)=logical(allocInfo.motor_saturated(:)).';
    R.new_omega_dot(rows(q),:)=omegaDot;R.new_E_omegaDot_minus_alphaBS(rows(q),:)=omegaDot-R.alpha_BS(rows(q),:);
    R.new_minus_old_E(rows(q),:)=R.new_E_omegaDot_minus_alphaBS(rows(q),:)-R.old_E_omegaDot_minus_alphaBS(rows(q),:);
    R.new_action_evaluated(rows(q))=true;
    assert(all(isfinite([clipped(:);applied(:);tauComp(:);command(:);setpoint(:);motor(:); ...
        wrench(:);omegaDot(:)])),'CM18Replay:NonfiniteNewAction','New same-state action produced non-finite values.');
end
end

