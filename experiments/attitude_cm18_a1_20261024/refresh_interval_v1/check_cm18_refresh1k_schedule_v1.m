function result = check_cm18_refresh1k_schedule_v1()
% Synthetic schedule/source-order check only; never calls the engine or Plant.
dt=0.001; n=20000; t=(0:n)'*dt;
oldEvents=(11:10:19991)'; newEvents=(11:20000)';
assert(numel(oldEvents)==1999&&numel(newEvents)==19990&& ...
    oldEvents(1)==11&&oldEvents(end)==19991&&newEvents(1)==11&&newEvents(end)==20000, ...
    'CM18Refresh1k:Schedule','Legacy or refresh event indices changed.');
oldIntervals=[t(oldEvents(1));diff(t(oldEvents))];
newIntervals=[t(newEvents(1));diff(t(newEvents))];
assert(abs(oldIntervals(1)-.010)<1e-12&&all(abs(oldIntervals(2:end)-.010)<1e-12)&& ...
    abs(newIntervals(1)-.010)<1e-12&&all(abs(newIntervals(2:end)-.001)<1e-12), ...
    'CM18Refresh1k:Intervals','First/subsequent refresh intervals are incorrect.');
betaOld=min(oldEvents*dt/2.2,1); betaNew=min(newEvents*dt/2.2,1);
assert(isequal(betaOld,min(oldEvents*dt/2.2,1))&&isequal(betaNew,min(newEvents*dt/2.2,1))&& ...
    betaNew(1)==min(11*.001/2.2,1)&&betaNew(end)==1, ...
    'CM18Refresh1k:Beta','Frozen beta schedule changed.');
windowStart=newEvents-10; windowEnd=newEvents-1;
assert(all(windowEnd-windowStart+1==10)&&all(windowStart>=1)&& ...
    all(abs(t(newEvents)-t(windowStart)-.010)<1e-12), ...
    'CM18Refresh1k:PastWindow','The 10-row past-action window was shortened or shifted.');
% Check the isolated engine has the intended trigger and output-before-z-update ordering.
here=fileparts(mfilename('fullpath')); enginePath=fullfile(here,'run_cm18_refresh1k_closed_loop_v1.m');
source=fileread(enginePath);
trigger=strfind(source,'cm18RefreshEvent(k)=k>=11&&mod(k-11,cm18RefreshStep)==0;');
forward=strfind(source,'rawAcceleration=double(cm18_a1_forward_v1(input18,cm18Model));');
zBefore=strfind(source,'zBefore=cm18CommandIntegral;'); zUpdate=strfind(source,'cm18CommandIntegral=cm18CommandIntegral+dt*double(s.arms.command(k,:)).'';');
expectedCount=strfind(source,[char(39) 'cm18_refresh_expected_event_count' char(39) ',max(n-10,0),']);
assert(numel(trigger)==1&&numel(forward)==1&&numel(zBefore)==1&&numel(zUpdate)==1&& ...
    numel(expectedCount)==1&&zBefore<forward&&forward<zUpdate, ...
    'CM18Refresh1k:SourceOrder','Refresh trigger, expected count, or output/z-update order changed.');
% A synthetic recurrence confirms the forward output consumes the pre-update integral.
z=zeros(4,1); u=[.2;-.1;.05;.3]; eventLog=zeros(1,4); zLog=zeros(1,4);
for i=1:4
    zBefore=z; y=zBefore(1); z=z+dt*u; eventLog(i)=y; zLog(i)=zBefore(1);
end
assert(isequal(eventLog,zLog)&&eventLog(1)==0&&z(1)>.0, ...
    'CM18Refresh1k:CausalZ','Synthetic forward did not use the prior integral state.');
result=struct('status','PASS_SYNTHETIC_NO_PLANT','plant_calls',0,'engine_called',false, ...
    'training_steps',0,'optimizer_steps',0,'TEST_accessed',false,'legacy_event_count',numel(oldEvents), ...
    'refresh_event_count',numel(newEvents),'first_refresh_interval_s',newIntervals(1), ...
    'subsequent_refresh_interval_s',newIntervals(2),'past_requested_rows',10, ...
    'past_window_span_s',.010,'beta_formula','min(k*dt/2.2,1)');
end