    c5Raw=load(c5Path,'scene','runIdentity');
    assert(strcmp(char(c5Raw.scene.scene_id),sid)&&strcmp(char(c5Raw.runIdentity.scene_id),sid)&& ...
        strcmp(char(c5Raw.runIdentity.candidate),'C5_AXIS_MIXED_COORDINATE_M110')&& ...
