    'taskbook_sha256',lower(sha256_file(taskbookPath)),'screen12_manifest_path',manifestPath, ...
    'screen12_manifest_sha256',lower(sha256_file(manifestPath)),'screen12_raw_audit_path',screenAuditPath, ...
