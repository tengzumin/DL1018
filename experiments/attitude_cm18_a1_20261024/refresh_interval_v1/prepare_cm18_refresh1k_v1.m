firstAuditPath=fullfile(repoRoot,'reports','attitude_cm18_a1_20261024','first_flight_preparation_v1','A1_FIRST_FLIGHT_LOG_AUDIT_v1.json');
c5SnapshotPath=fullfile(repoRoot,'experiments','position_axis_coordinate_c5_dev72_20261023','C5_DEV72_PREPARED_CFG_OPTS_v3.mat');
c5BodyPath=fullfile(repoRoot,'experiments','position_axis_coordinate_c5_dev72_20261023','C5_DEV72_BODY_COMPLETE_v3.json');
deploymentPath=fullfile(experimentDir,'deployment_v1','deployment_parameters_v1.json');
enginePath=fullfile(here,'run_cm18_refresh1k_closed_loop_v1.m');
forwardPath=fullfile(here,'matlab','cm18_a1_forward_v1.m'); helperPath=fullfile(here,'delayed_prediction_step_candidate.m');
parentEnginePath=fullfile(experimentDir,'run_cm18_closed_loop_v1.m');
taskbookPath=fullfile(repoRoot,'reports','attitude_cm18_a1_20261024','A1_REFRESH_INTERVAL_DISCRIMINATION_TASKBOOK_v1_ZH.md');
expectedManifestSha='fdca3f17c0f39d19eb5b08e94e7e5b1f148ec03cf861eacec64d86ab7922f923';
expectedTaskbookSha='4b86385a8ed6b112c3537f5f31206916772a9e4192a9d819869ef1133f13ec07';
expectedIds={'DL1018_DEV_T3_C15_W14','DL1018_DEV_T1_C15_W14','DL1018_VAL_T2_C15_W09','DL1018_DEV_T1_C01_W15'};
assert(~isfolder(preparedDir)&&~isfile(resultPath), ...
    'CM18Refresh1k:NoOverwrite','Preparation outputs exist; preserve them and do not rerun.');
verify_file(manifestPath,expectedManifestSha); verify_file(taskbookPath,expectedTaskbookSha);
assert(isfile(screenPrepPath)&&isfile(screenAuditPath)&&isfile(firstPrepPath)&&isfile(firstAuditPath), ...
    'CM18Refresh1k:AuditsRequired','Prior no-Plant preparation and independent A1 raw audits are required.');
manifest=jsondecode(fileread(manifestPath)); screenPrep=jsondecode(fileread(screenPrepPath));
screenAudit=jsondecode(fileread(screenAuditPath)); firstPrep=jsondecode(fileread(firstPrepPath)); firstAudit=jsondecode(fileread(firstAuditPath));
assert(strcmp(manifest.schema,'CM18_A1_FUTURE_DEVELOPMENT_SCREEN12_V1')&& ...
    strcmp(screenPrep.schema,'CM18_A1_SCREEN12_REMAINING_PREPARATION_V1')&& ...
    strcmp(screenPrep.status,'PREPARED_SCREEN12_REMAINING_NO_PLANT_V1')&&double(screenPrep.scene_count)==11&& ...
    strcmp(screenAudit.schema,'ROOT_CM18_SCREEN12_INDEPENDENT_RAW_AUDIT_V1')&&strcmp(screenAudit.status,'PASS')&& ...
    strcmp(firstPrep.schema,'CM18_A1_FIRST_FLIGHT_PREPARATION_V1')&& ...
    strcmp(firstPrep.status,'PREPARED_A1_FIRST_FLIGHT_NO_PLANT_V1')&& ...
    strcmp(firstAudit.schema,'CM18_A1_FIRST_FLIGHT_LOG_AUDIT_V1')&&strcmp(firstAudit.status,'PASS')&& ...
    strcmp(firstAudit.scene_id,'DL1018_DEV_T1_C01_W15')&&double(firstPrep.plant_calls)==0&& ...
    ~logical(firstPrep.engine_called)&&~logical(firstPrep.run_episode_called)&&~logical(firstPrep.TEST_accessed)&& ...
    double(screenPrep.plant_calls)==0&&~logical(screenPrep.engine_called)&&~logical(screenPrep.run_episode_called)&& ...
    double(screenPrep.training_steps)==0&&double(screenPrep.optimizer_steps)==0&&~logical(screenPrep.TEST_accessed), ...
    'CM18Refresh1k:PriorAudit','A1 baseline preparation/audit evidence is not PASS/no-Plant.');
assert(strcmpi(firstAudit.raw_sha256,'cb70eec663da6248d6291fb4b64bdf943cdf284a1d608313edb166c616d771f9')&& ...
    strcmpi(firstAudit.preparation_result_sha256,sha256_file(firstPrepPath))&& ...
    strcmpi(firstAudit.prepared_snapshot_sha256,firstPrep.prepared_snapshot_sha256), ...
    'CM18Refresh1k:FirstAuditBinding','First-flight raw audit does not bind its preparation and raw.');
verify_file(firstPrep.c5_snapshot_path,firstPrep.c5_snapshot_sha256);
verify_file(c5SnapshotPath,firstPrep.c5_snapshot_sha256);
verify_file(deploymentPath,firstPrep.deployment_parameters_sha256);
deployment=jsondecode(fileread(deploymentPath));
assert(strcmp(deployment.schema,'CM18_A1_DEPLOYMENT_PARAMETERS_V1')&& ...
    strcmpi(deployment.identity.checkpoint_sha256,'105585385157da3f1b404ab24606d0717287638e4a1ca710790633cd16d233a4')&& ...
    double(deployment.identity.selected_step)==30000&& ...
    strcmpi(screenPrep.deployment_parameters_sha256,sha256_file(deploymentPath)), ...
    'CM18Refresh1k:Model','Only the pinned best step-30000 deployment is allowed.');
assert(strcmpi(screenPrep.screen12_manifest_sha256,expectedManifestSha)&& ...
    strcmpi(screenPrep.first_flight_audit_sha256,sha256_file(firstAuditPath))&& ...
    strcmpi(screenPrep.c5_snapshot_sha256,sha256_file(c5SnapshotPath)), ...
    'CM18Refresh1k:PriorPrepPins','Existing SCREEN12 preparation identities changed.');
verify_file(enginePath,sha256_file(enginePath)); verify_file(forwardPath,sha256_file(forwardPath));
verify_file(helperPath,sha256_file(helperPath));
assert(isfile(parentEnginePath),'CM18Refresh1k:ParentEngine','Frozen 100-Hz parent engine is missing.');
base=load(firstPrep.prepared_snapshot_path,'cfg','opts','scene','sceneIdentity','modelIdentity','sourceIdentity');
c5=load(c5SnapshotPath,'cfg','opts','sceneIdentity');
assert(isequaln(base.cfg,c5.cfg)&&isequal(double(base.opts.position_coordinate_mask(:)),[1;1;0])&& ...
    logical(base.opts.cm18_attitude_v1.enabled)&&double(base.modelIdentity.selected_step)==30000, ...
    'CM18Refresh1k:C5Base','First-flight prepared configuration is not the fixed C5/A1 baseline.');
body=jsondecode(fileread(c5BodyPath)); assert(strcmp(body.schema,'C5_AXIS_COORDINATE_DEV72_BODY_COMPLETE_V3'));
allRows=manifest.scenes; rows=repmat(allRows(1),numel(expectedIds),1);
for q=1:numel(expectedIds)
