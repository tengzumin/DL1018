function [E,meta]=export_cm18_events_v1(log,scene,cfg,h5ref,split)
% Rebuild deployable CM18 and instantaneous physical labels from raw logs.
% h5ref contains scene_id, split, model_id, contract_version, plant_index,
% event_time_s, x, and target_raw read by the caller from the paired B.h5.
requiredLog={'time','transition_time','state','attitude_event_flag', ...
    'attitude_bs_nominal_torque_Nm','attitude_compensation_applied_torque_Nm', ...
    'requested_generalized','realized_generalized','wind_torque_B'};
assert(isstruct(log)&&all(isfield(log,requiredLog)), ...
    'CM18:LogFields','Required raw log fields are missing.');
assert(isstruct(scene)&&isfield(scene,'scene_id')&&isfield(scene,'time')&& ...
    isfield(scene,'arms')&&all(isfield(scene.arms,{'command','rho_true','rhoDot_true'})), ...
    'CM18:SceneFields','Scene identity, time, and arm trajectories are required.');
assert(isstruct(cfg)&&isfield(cfg,'plant')&&isfield(cfg,'controller_morphology_mode')&& ...
    strcmpi(char(string(cfg.controller_morphology_mode)),'fixed'), ...
    'CM18:FixedNominal','CM18 labels require the frozen fixed nominal controller model.');
assert(isfield(cfg.plant,'mass')&&isscalar(cfg.plant.mass)&&isfinite(cfg.plant.mass)&&cfg.plant.mass>0, ...
    'CM18:PlantMass','A positive finite plant mass is required.');
if isfield(cfg,'controller_inertia_derivative_mode')
    jdotMode=lower(char(string(cfg.controller_inertia_derivative_mode)));
else
    jdotMode='full';
end
assert(ismember(jdotMode,{'full','omit_jdot'}), ...
    'CM18:JdotMode','Unsupported fixed-controller inertia-derivative mode.');
assert(strcmp(jdotMode,'full'), ...
    'CM18:JdotMode','The sealed CM18 data protocol requires controller_inertia_derivative_mode=full.');
assert(isstruct(h5ref)&&all(isfield(h5ref,{'scene_id','split','model_id','contract_version', ...
    'plant_index','event_time_s','phase_code','x','target_raw'})), ...
    'CM18:H5Reference','Paired B.h5 identity and reference arrays are required.');
split=upper(char(string(split)));
assert(ismember(split,{'TRAIN','VAL'})&&strcmp(char(string(scene.scene_id)),char(string(h5ref.scene_id)))&& ...
    strcmp(split,upper(char(string(h5ref.split))))&&strcmp(char(string(h5ref.model_id)),'B')&& ...
    strcmp(char(string(h5ref.contract_version)),'DL1018_V311_R2E_PAPER_FINAL'), ...
    'CM18:Identity','Scene, split, collector, or H5 contract identity mismatch.');

n=numel(log.transition_time);time=double(log.transition_time(:));fullTime=double(log.time(:));
sceneTime=double(scene.time(:));state=double(log.state);idx=find(logical(log.attitude_event_flag(:)));
assert(n==20000&&numel(time)==n&&numel(fullTime)==n+1&&numel(sceneTime)==n+1&& ...
    isequal(size(state),[n+1,12])&&isequal(size(double(log.attitude_event_flag(:))),[n,1])&& ...
    all(diff(time)>0)&&abs(time(1))<=1e-12&&abs(time(end)-19.999)<=1e-12&& ...
    abs(fullTime(1))<=1e-12&&abs(fullTime(end)-20)<=1e-12&& ...
    max(abs(fullTime-sceneTime))<=1e-12&& ...
    max(abs(time-fullTime(1:n)))<=1e-12, ...
    'CM18:TimeShape','Raw state/time dimensions or log-scene time alignment failed.');
dt=diff(sceneTime);
assert(all(isfinite(dt))&&all(dt>0)&&max(abs(dt-0.001))<=1e-12, ...
    'CM18:TimeStep','The audited 1 ms scene timebase changed.');
assert(numel(idx)==1999&&idx(1)==11&&idx(end)==19991&&all(diff(idx)==10), ...
    'CM18:EventSchedule','Canonical attitude event schedule is invalid.');

request=double(log.requested_generalized);realized=double(log.realized_generalized);
tauNom=double(log.attitude_bs_nominal_torque_Nm);tauComp=double(log.attitude_compensation_applied_torque_Nm);
windTorque=double(log.wind_torque_B);command=double(scene.arms.command);
rho=double(scene.arms.rho_true);rhoDot=double(scene.arms.rhoDot_true);
assert(isequal(size(request),[n,4])&&isequal(size(realized),[n,4])&& ...
    isequal(size(tauNom),[n,3])&&isequal(size(tauComp),[n,3])&& ...
    isequal(size(windTorque),[n,3])&&isequal(size(command),[n+1,4])&& ...
    isequal(size(rho),[n+1,4])&&isequal(size(rhoDot),[n+1,4])&& ...
    all(isfinite([state(:);request(:);realized(:);tauNom(:);tauComp(:);windTorque(:); ...
    command(:);rho(:);rhoDot(:)]))&&all(ismember(command(:),[-1,0,1])), ...
    'CM18:RawShape','Raw numeric arrays have invalid shape, values, or command range.');

plantIndex=double(h5ref.plant_index(:));eventTime=double(h5ref.event_time_s(:));
xOld=as_event_rows(double(h5ref.x),numel(idx),29,'x');yOld=as_event_rows(double(h5ref.target_raw),numel(idx),3,'target_raw');
phaseRef=double(h5ref.phase_code(:));
assert(isequal(plantIndex,double(idx))&&numel(eventTime)==numel(idx)&& ...
    numel(phaseRef)==numel(idx)&&all(isfinite(phaseRef))&& ...
    all(phaseRef==round(phaseRef))&&all(phaseRef>=0&phaseRef<=5)&& ...
    max(abs(eventTime-time(idx)))<=1e-12, ...
    'CM18:H5EventIndex','H5 event indices/times do not match canonical raw event flags.');

% Fixed nominal model: identical distributed_v1 path, zero arm rates.
[J0,~,Jdot0]=arm_mass_properties(double(cfg.plant.arm_initial(:)),cfg.plant,zeros(4,1));
if strcmp(jdotMode,'omit_jdot')
    Jdot0=zeros(3);
end
assert(isequal(size(J0),[3,3])&&isequal(size(Jdot0),[3,3])&& ...
    all(isfinite([J0(:);Jdot0(:)]))&&all(eig(0.5*(J0+J0.'))>0), ...
    'CM18:NominalInertia','Fixed nominal inertia is invalid.');

N=numel(idx);omega=state(idx,10:12);alphaBS=zeros(N,3);thrustMass=zeros(N,1);
u=command(idx,:);zAll=[zeros(1,4);cumsum(command(1:end-1,:).*repmat(dt,1,4),1)];z=zAll(idx,:);
a=zeros(N,3);target=zeros(N,3);phaseCode=zeros(N,1,'uint8');
maxTrueEquationResidual=0;
for q=1:N
    k=idx(q);w=omega(q,:).';
    alphaBS(q,:)=(J0\(tauNom(k,:).'-cross(w,J0*w)-Jdot0*w)).';
    thrustMass(q)=request(k,1)/double(cfg.plant.mass);
    % Completed interval only: requested-torque rows k-10 through k-1.
    interval=(k-10):(k-1);
    a(q,:)=sum(request(interval,2:4).*dt(interval),1)/sum(dt(interval));

    [Jtrue,~,JdotTrue]=arm_mass_properties(rho(k,:).',cfg.plant,rhoDot(k,:).');
    alphaTrue=Jtrue\(realized(k,2:4).'+windTorque(k,:).'- ...
        cross(w,Jtrue*w)-JdotTrue*w);
    forcing=realized(k,2:4).'+windTorque(k,:).'-cross(w,Jtrue*w)-JdotTrue*w;
    tauVirtual=tauNom(k,:).'-tauComp(k,:).';
    alphaVirtual=J0\(tauVirtual-cross(w,J0*w)-Jdot0*w);
    target(q,:)=(alphaTrue-alphaVirtual).';
    maxTrueEquationResidual=max(maxTrueEquationResidual,max(abs(Jtrue*alphaTrue-forcing)));
    phaseCode(q)=uint8(phaseRef(q));
end
X=[omega,alphaBS,thrustMass,u,z,a];
assert(isequal(size(X),[N,18])&&all(isfinite([X(:);target(:)])), ...
    'CM18:Nonfinite','Reconstructed CM18 features or labels are non-finite.');

% H5 physical columns are cross-checks only; they never enter X or target.
crosscheck=struct();
crosscheck.omega_B_max_abs=max(abs(omega-xOld(:,7:9)),[],'all');
crosscheck.alpha_BS_max_abs=max(abs(alphaBS-xOld(:,22:24)),[],'all');
crosscheck.thrust_over_mass_max_abs=max(abs(thrustMass-xOld(:,25)),[],'all');
labelDelta=target-yOld;
maxTorqueRequestClosure=max(abs(request(idx,2:4)-(tauNom(idx,:)-tauComp(idx,:))),[],'all');
phaseNames={'STATIC','PRE','EXTEND','HOLD','RETRACT','RECOVERY'};
phaseSummary=repmat(struct('phase_code',0,'phase','', 'event_count',0, ...
    'max_abs_label_delta_rad_s2',NaN,'max_abs_label_delta_by_axis_rad_s2',NaN(1,3), ...
    'axis_rms_label_rad_s2',NaN(1,3)),numel(phaseNames),1);
for p=1:numel(phaseNames)
    m=phaseCode==(p-1);phaseSummary(p).phase_code=p-1;phaseSummary(p).phase=phaseNames{p};
    phaseSummary(p).event_count=nnz(m);
    if any(m)
        phaseSummary(p).max_abs_label_delta_rad_s2=max(abs(labelDelta(m,:)),[],'all');
        phaseSummary(p).max_abs_label_delta_by_axis_rad_s2=max(abs(labelDelta(m,:)),[],1);
        phaseSummary(p).axis_rms_label_rad_s2=sqrt(mean(target(m,:).^2,1));
    end
end
meta=struct('schema','CM18_EVENT_EXPORT_META_V1','scene_id',char(string(scene.scene_id)), ...
    'split',split,'event_count',N,'plant_index_matlab_1based',idx, ...
    'max_abs_label_delta_vs_h5_rad_s2',max(abs(labelDelta),[],'all'), ...
    'max_abs_label_delta_by_axis_rad_s2',max(abs(labelDelta),[],1), ...
    'axis_rms_label_rad_s2',sqrt(mean(target.^2,1)), ...
    'phase_summary',phaseSummary, ...
    'requested_torque_vs_nominal_minus_applied_max_abs_Nm',maxTorqueRequestClosure, ...
    'true_dynamics_equation_residual_max_abs_Nm',maxTrueEquationResidual, ...
    'physical_feature_crosscheck',crosscheck,'tolerances',struct( ...
    'label_vs_h5_max_abs_rad_s2',1e-8,'omega_max_abs',1e-10, ...
    'alpha_BS_max_abs_rad_s2',1e-7,'thrust_over_mass_max_abs_m_s2',1e-8, ...
    'time_max_abs_s',1e-12,'torque_request_closure_max_abs_Nm',1e-8, ...
    'true_dynamics_equation_residual_max_abs_Nm',1e-12));
bad={};
if meta.max_abs_label_delta_vs_h5_rad_s2>meta.tolerances.label_vs_h5_max_abs_rad_s2
    bad{end+1}='LABEL_RAW_H5_CLOSURE'; %#ok<AGROW>
end
if crosscheck.omega_B_max_abs>meta.tolerances.omega_max_abs
    bad{end+1}='OMEGA_H5_CROSSCHECK'; %#ok<AGROW>
end
if crosscheck.alpha_BS_max_abs>meta.tolerances.alpha_BS_max_abs_rad_s2
    bad{end+1}='ALPHA_BS_H5_CROSSCHECK'; %#ok<AGROW>
end
if crosscheck.thrust_over_mass_max_abs>meta.tolerances.thrust_over_mass_max_abs_m_s2
    bad{end+1}='THRUST_MASS_H5_CROSSCHECK'; %#ok<AGROW>
end
if maxTorqueRequestClosure>meta.tolerances.torque_request_closure_max_abs_Nm
    bad{end+1}='TORQUE_REQUEST_CLOSURE'; %#ok<AGROW>
end
if maxTrueEquationResidual>meta.tolerances.true_dynamics_equation_residual_max_abs_Nm
    bad{end+1}='TRUE_DYNAMICS_EQUATION_RESIDUAL_NM'; %#ok<AGROW>
end
meta.failure_reasons=bad;
meta.qualified=isempty(bad);
if meta.qualified,meta.status='PASS';else,meta.status='FAIL_CLOSURE';end

E=struct('scene_id',repmat(string(scene.scene_id),N,1), ...
    'split',repmat(string(split),N,1),'event_index',(1:N).', ...
    'plant_index',idx,'event_time_s',time(idx),'phase_code',phaseCode, ...
    'X18',X,'target_raw',target,'target_raw_h5_reference',yOld, ...
    'target_raw_h5_delta',labelDelta);
end

function rows=as_event_rows(value,n,width,name)
if isequal(size(value),[width,n]),value=value.';end
assert(isequal(size(value),[n,width])&&all(isfinite(value),'all'), ...
    'CM18:H5ArrayShape','H5 %s has invalid dimensions or non-finite values.',name);
rows=value;
end
