function priorRuns=ledger_gate(ledger,sceneId,allowedSceneIds)
sceneId=char(sceneId); allowedSceneIds=cellstr(string(allowedSceneIds(:)));
assert(any(strcmp(allowedSceneIds,sceneId)),'CM18Screen12:SceneScope','Ledger gate received a scene outside the release.');
events={ledger.event}; statuses={ledger.status}; scenes={ledger.scene_id};
starts=find(strcmp(events,'RUN_STARTED')); terminals=find(strcmp(events,'RUN_TERMINAL'));
assert(numel(starts)==numel(terminals)||numel(starts)==numel(terminals)+1, ...
    'CM18Screen12:LedgerPair','Ledger does not contain complete per-scene start/terminal pairs.');
assert(numel(starts)<11,'CM18Screen12:FlightLimit','All eleven released scene slots are already recorded.');
for k=1:numel(ledger)
    assert(any(strcmp(allowedSceneIds,scenes{k}))&& ...
        (strcmp(events{k},'RUN_STARTED')||strcmp(events{k},'RUN_TERMINAL')), ...
        'CM18Screen12:LedgerRow','Ledger contains an unknown scene or event.');
end
assert(numel(unique(scenes(starts)))==numel(starts), ...
    'CM18Screen12:NoRetry','A scene already has a start record; never retry it.');
assert(~any(strcmp(scenes(starts),sceneId)), ...
    'CM18Screen12:NoRetry','This scene already has a run ledger record; never retry it.');
for k=1:numel(starts)
    matching=find(strcmp(scenes,scenes{starts(k)})&strcmp(events,'RUN_TERMINAL'));
    assert(numel(matching)==1&&matching>starts(k), ...
        'CM18Screen12:StopOnFailure','A prior scene is incomplete; stop the batch and retain evidence.');
    assert(strcmp(statuses{matching},'RUN_COMPLETE_PENDING_ROOT_AUDIT'), ...
        'CM18Screen12:StopOnFailure','A prior scene failed or was incomplete; stop and retain evidence.');
end
assert(numel(terminals)==numel(starts), ...
    'CM18Screen12:StopOnFailure','A prior scene has no successful terminal ledger row.');
priorRuns=numel(starts);
end
