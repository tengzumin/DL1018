function result = prepare_cm18_screen12_remaining_v1()
% No-Plant preparation for the eleven fixed SCREEN12 scenes after first-flight audit.
here=fileparts(mfilename('fullpath')); experimentDir=fileparts(here); repoRoot=fileparts(fileparts(experimentDir));
reportDir=fullfile(repoRoot,'reports','attitude_cm18_a1_20261024','screen12_remaining_v1');
manifestPath=fullfile(repoRoot,'reports','attitude_cm18_a1_20261024','CM18_A1_DEV_SCREEN12_v1.json');
firstDir=fullfile(repoRoot,'experiments','attitude_cm18_a1_20261024','first_flight_preparation_v1');
firstReportDir=fullfile(repoRoot,'reports','attitude_cm18_a1_20261024','first_flight_preparation_v1');
firstPrepPath=fullfile(firstReportDir,'A1_FIRST_FLIGHT_PREPARATION_RESULT_v1.json');
firstSnapshotPath=fullfile(firstDir,'prepared_a1_first_flight_v1.mat');
firstAuditPath=fullfile(firstReportDir,'A1_FIRST_FLIGHT_LOG_AUDIT_v1.json');
c5SnapshotPath=fullfile(repoRoot,'experiments','position_axis_coordinate_c5_dev72_20261023','C5_DEV72_PREPARED_CFG_OPTS_v3.mat');
deploymentPath=fullfile(experimentDir,'deployment_v1','deployment_parameters_v1.json');
enginePath=fullfile(experimentDir,'run_cm18_closed_loop_v1.m');
prepareResultPath=fullfile(reportDir,'SCREEN12_REMAINING_PREPARATION_RESULT_v1.json');
preparedDir=fullfile(here,'prepared_scenes_v1');
expectedManifestSha='fdca3f17c0f39d19eb5b08e94e7e5b1f148ec03cf861eacec64d86ab7922f923';
firstScene='DL1018_DEV_T1_C01_W15';
expectedIds={'DL1018_DEV_T1_C00_W03','DL1018_DEV_T1_C15_W14','DL1018_DEV_T1_C05_W06', ...
    'DL1018_DEV_T2_C00_W04','DL1018_DEV_T2_C02_W15','DL1018_VAL_T2_C15_W09','DL1018_DEV_T2_C06_W07', ...
    'DL1018_DEV_T3_C00_W05','DL1018_DEV_T3_C03_W15','DL1018_DEV_T3_C15_W14','DL1018_DEV_T3_C05_W02'};
assert(~isfolder(preparedDir)&&~isfile(prepareResultPath), ...
    'CM18Screen12:NoOverwrite','Preparation outputs already exist; retain them and do not rerun.');
verify_file(manifestPath,expectedManifestSha);
assert(isfile(firstAuditPath)&&isfile(firstPrepPath)&&isfile(firstSnapshotPath), ...
    'CM18Screen12:FirstAuditRequired','The first-flight event audit must PASS before this preparation runs.');
audit=jsondecode(fileread(firstAuditPath)); firstPrep=jsondecode(fileread(firstPrepPath));
assert(strcmp(audit.schema,'CM18_A1_FIRST_FLIGHT_LOG_AUDIT_V1')&&strcmp(audit.status,'PASS')&& ...
    strcmp(audit.scene_id,firstScene)&&strcmpi(audit.raw_sha256,'cb70eec663da6248d6291fb4b64bdf943cdf284a1d608313edb166c616d771f9')&& ...
    strcmpi(audit.preparation_result_sha256,sha256_file(firstPrepPath))&& ...
    strcmp(firstPrep.schema,'CM18_A1_FIRST_FLIGHT_PREPARATION_V1')&& ...
    strcmp(firstPrep.status,'PREPARED_A1_FIRST_FLIGHT_NO_PLANT_V1')&&strcmp(firstPrep.scene_id,firstScene)&& ...
    double(firstPrep.plant_calls)==0&&~logical(firstPrep.engine_called)&&~logical(firstPrep.run_episode_called)&& ...
    ~logical(firstPrep.TEST_accessed), ...
    'CM18Screen12:FirstAuditStatus','First-flight audit/preparation identity is not the fixed passing A1 result.');
assert(strcmpi(sha256_file(firstSnapshotPath),firstPrep.prepared_snapshot_sha256)&& ...
    strcmpi(sha256_file(c5SnapshotPath),firstPrep.c5_snapshot_sha256)&& ...
    strcmpi(sha256_file(deploymentPath),firstPrep.deployment_parameters_sha256)&& ...
    strcmpi(sha256_file(enginePath),firstPrep.source_identity.a1_engine_sha256), ...
    'CM18Screen12:FirstFlightInputs','A1 snapshot, C5 source snapshot, model, or engine changed.');
manifest=jsondecode(fileread(manifestPath));
assert(strcmp(manifest.schema,'CM18_A1_FUTURE_DEVELOPMENT_SCREEN12_V1')&& ...
    strcmpi(manifest.parent_sha256,'bb34889559d95a1c995d4d420e3b3d7a702908b58b47cce969dc508a1c697fab')&& ...
    strcmp(manifest.first_engineering_scene,firstScene)&&double(manifest.duration_s)==20&& ...
    ~logical(manifest.current_Plant_release)&&numel(manifest.scenes)==12, ...
    'CM18Screen12:Manifest','The frozen SCREEN12 manifest does not match its expected scope.');
rows=manifest.scenes(~strcmp({manifest.scenes.scene_id},firstScene)); actualIds={rows.scene_id};
assert(numel(rows)==11&&isequal(actualIds(:),expectedIds(:)), ...
    'CM18Screen12:SceneSet','SCREEN12 must contain exactly the fixed remaining eleven scene IDs and order.');
base=load(firstSnapshotPath,'cfg','opts','scene','sceneIdentity','modelIdentity','sourceIdentity');
c5=load(c5SnapshotPath,'cfg','opts','sceneIdentity');
assert(all(isfield(base,{'cfg','opts','scene','sceneIdentity','modelIdentity','sourceIdentity'}))&& ...
    isequaln(base.cfg,c5.cfg)&&isequal(double(base.opts.position_coordinate_mask(:)),[1;1;0])&& ...
    logical(base.opts.cm18_attitude_v1.enabled)&&islogical(base.opts.cm18_attitude_v1.enabled)&& ...
    ~base.opts.rbf_attitude_enabled&&~base.opts.rbf_attitude_output_enabled&&~base.opts.rbf_attitude_update_enabled, ...
    'CM18Screen12:C5Snapshot','The first-flight prepared cfg/opts no longer match the frozen C5 baseline.');
restored=rmfield(base.opts,{'cm18_attitude_v1','r2e_first_plant_step_marker'});
rbfFlags={'rbf_attitude_enabled','rbf_attitude_output_enabled','rbf_attitude_update_enabled'};
for k=1:numel(rbfFlags), restored.(rbfFlags{k})=c5.opts.(rbfFlags{k}); end
assert(isequaln(restored,c5.opts),'CM18Screen12:OptsChanged','Prepared opts differ from original C5 beyond the approved CM18 fields.');
deployment=jsondecode(fileread(deploymentPath));
assert(strcmp(deployment.schema,'CM18_A1_DEPLOYMENT_PARAMETERS_V1')&& ...
    strcmpi(deployment.identity.checkpoint_sha256,'105585385157da3f1b404ab24606d0717287638e4a1ca710790633cd16d233a4')&& ...
    double(deployment.identity.selected_step)==30000, ...
    'CM18Screen12:Model','The fixed best-step-30000 deployment model changed.');

% Validate all baseline raw identities before creating any preparation output.
for k=1:numel(rows)
    verify_file(char(rows(k).baseline_C5_raw_path),char(rows(k).baseline_C5_raw_sha256));
end
mkdir(preparedDir);
sceneRows=struct('task',{},'category',{},'scene_id',{},'baseline_C5_raw_path',{}, ...
    'baseline_C5_raw_sha256',{},'prepared_snapshot_path',{},'prepared_snapshot_sha256',{});
for k=1:numel(rows)
    rawPath=char(rows(k).baseline_C5_raw_path); raw=load(rawPath,'scene','runIdentity');
    assert(all(isfield(raw,{'scene','runIdentity'}))&&strcmp(char(raw.scene.scene_id),char(rows(k).scene_id))&& ...
        strcmp(char(raw.runIdentity.scene_id),char(rows(k).scene_id))&& ...
        strcmp(char(raw.runIdentity.candidate),'C5_AXIS_MIXED_COORDINATE_M110')&& ...
        isequal(double(raw.runIdentity.coordinate_mask(:)),[1;1;0])&& ...
        numel(raw.scene.time)==20001&&abs(double(raw.scene.time(1)))<1e-12&& ...
        abs(double(raw.scene.time(end))-20)<1e-12&&max(abs(diff(double(raw.scene.time(:)))-.001))<1e-12, ...
        'CM18Screen12:BaselineScene','Pinned C5 raw scene identity/time differs for %s.',char(rows(k).scene_id));
    ix=find(strcmp({c5.sceneIdentity.scene_id},char(rows(k).scene_id)));
    assert(numel(ix)==1,'CM18Screen12:SceneIdentity','C5 snapshot scene identity is not unique for %s.',char(rows(k).scene_id));
    scene=raw.scene; sceneIdentity=c5.sceneIdentity(ix); cfg=base.cfg; opts=base.opts;
    snapshotPath=fullfile(preparedDir,[char(rows(k).scene_id) '.mat']);
    opts.r2e_first_plant_step_marker=fullfile(here,'runs',char(rows(k).scene_id),'attempt_01','first_plant_step.marker');
    sourceIdentity=base.sourceIdentity; modelIdentity=base.modelIdentity;
    save(snapshotPath,'cfg','opts','scene','sceneIdentity','modelIdentity','sourceIdentity','-v7.3');
    sceneRows(k)=struct('task',char(rows(k).task),'category',char(rows(k).category), ...
        'scene_id',char(rows(k).scene_id),'baseline_C5_raw_path',rawPath, ...
        'baseline_C5_raw_sha256',lower(char(rows(k).baseline_C5_raw_sha256)), ...
        'prepared_snapshot_path',snapshotPath,'prepared_snapshot_sha256',sha256_file(snapshotPath)); %#ok<AGROW>
end
result=struct('schema','CM18_A1_SCREEN12_REMAINING_PREPARATION_V1', ...
    'status','PREPARED_SCREEN12_REMAINING_NO_PLANT_V1','created_utc',utc_now(), ...
    'screen12_manifest_path',manifestPath,'screen12_manifest_sha256',lower(sha256_file(manifestPath)), ...
    'screen12_parent_sha256',char(manifest.parent_sha256),'excluded_first_engineering_scene',firstScene, ...
    'first_flight_audit_path',firstAuditPath,'first_flight_audit_sha256',lower(sha256_file(firstAuditPath)), ...
    'first_flight_audit_status',char(audit.status),'first_flight_preparation_result_sha256',lower(sha256_file(firstPrepPath)), ...
    'deployment_parameters_path',deploymentPath,'deployment_parameters_sha256',lower(sha256_file(deploymentPath)), ...
    'engine_sha256',lower(sha256_file(enginePath)),'forward_sha256',base.sourceIdentity.a1_forward_sha256, ...
    'prediction_helper_sha256',base.sourceIdentity.a1_prediction_helper_sha256, ...
    'prepare_script_sha256',lower(sha256_file([mfilename('fullpath') '.m'])), ...
    'runner_sha256',lower(sha256_file(fullfile(here,'run_cm18_screen12_remaining_v1.m'))), ...
    'c5_snapshot_sha256',lower(sha256_file(c5SnapshotPath)), ...
    'c5_active_source_inventory_sha256',base.sourceIdentity.c5_active_source_inventory_sha256, ...
    'model_identity',base.modelIdentity,'source_identity',base.sourceIdentity,'scene_rows',sceneRows, ...
    'scene_count',numel(sceneRows),'duration_s',20,'plant_dt_s',.001,'event_rate_hz',100, ...
    'plant_calls',0,'engine_called',false,'run_episode_called',false,'training_steps',0, ...
    'optimizer_steps',0,'TEST_accessed',false);
write_json_new(prepareResultPath,result);
end

function verify_file(path,expected)
assert(isfile(path),'CM18Screen12:MissingFile','Missing pinned input: %s.',path);
assert(strcmpi(sha256_file(path),expected),'CM18Screen12:SHA','SHA-256 mismatch: %s.',path);
end
function h=sha256_file(path)
md=java.security.MessageDigest.getInstance('SHA-256'); fid=fopen(path,'r');
assert(fid>=0,'CM18Screen12:ReadFile','Cannot read %s.',path); c=onCleanup(@()fclose(fid)); %#ok<NASGU>
while true, b=fread(fid,8*1024*1024,'*uint8'); if isempty(b), break; end, md.update(b); end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
function write_json_new(path,value)
assert(~isfile(path),'CM18Screen12:NoOverwrite','Refusing to overwrite %s.',path);
fid=fopen(path,'w'); assert(fid>=0,'CM18Screen12:Write','Cannot create %s.',path); c=onCleanup(@()fclose(fid)); %#ok<NASGU>
fwrite(fid,jsonencode(value),'char');
end
function t=utc_now(), t=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z''')); end
