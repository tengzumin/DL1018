    strcmpi(runStart.prepared_snapshot_sha256,sha256_file(snapshotPath))&& ...
    strcmpi(runStart.c5_raw_scene_sha256,sha256_file(c5RawPath))&& ...
    strcmpi(runStart.deployment_parameters_sha256,sha256_file(modelPath))&& ...
    strcmpi(runStart.engine_sha256,sha256_file(enginePath))&& ...
