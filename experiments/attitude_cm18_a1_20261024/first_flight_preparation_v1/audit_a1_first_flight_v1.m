function h=sha256_file(path)
md=java.security.MessageDigest.getInstance('SHA-256'); fid=fopen(path,'r');
assert(fid>=0,'A1LogAudit:ReadFile','Cannot read %s.',path); c=onCleanup(@()fclose(fid)); %#ok<NASGU>
while true, bytes=fread(fid,8*1024*1024,'*uint8'); if isempty(bytes),break;end,md.update(bytes);end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
function h=sha256_text(text)
bytes=unicode2native(char(text),'UTF-8'); md=java.security.MessageDigest.getInstance('SHA-256');
md.update(typecast(uint8(bytes(:)),'int8')); h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
