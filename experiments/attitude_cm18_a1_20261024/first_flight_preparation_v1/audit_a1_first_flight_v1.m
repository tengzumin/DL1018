function [maximum,trailing]=run_durations(mask,dt)
mask=logical(mask(:)); edges=diff([false;mask;false]); starts=find(edges==1); stops=find(edges==-1)-1;
if isempty(starts), maximum=0; trailing=0; return; end
durations=(stops-starts+1)*dt; maximum=max(durations);
if mask(end), trailing=durations(end); else, trailing=0; end
end

function y=forward_independent(x,p)
x=reshape(double(x),1,[]); mu=reshape(double(p.input_mean),1,[]);
sigma=reshape(double(p.input_std),1,[]); axisRms=reshape(double(p.train_axis_rms_rad_s2),1,[]);
h1=tanh(double(p.W1)*((x-mu)./sigma).'+reshape(double(p.b1),[],1));
h2=tanh(double(p.W2)*h1+reshape(double(p.b2),[],1));
coefficients=reshape((double(p.W3)*h2+reshape(double(p.b3),[],1)).',8,3).';
basis=[x(12:15)/2,x(8:11)]; y=(coefficients*basis.').'.*axisRms;
end

function R=rotation_zyx(e)
p=e(1); q=e(2); y=e(3); cp=cos(p); sp=sin(p); cq=cos(q); sq=sin(q); cy=cos(y); sy=sin(y);
R=[cy*cq,cy*sq*sp-sy*cp,cy*sq*cp+sy*sp; ...
    sy*cq,sy*sq*sp+cy*cp,sy*sq*cp-cy*sp; ...
    -sq,cq*sp,cq*cp];
end

function verify_inventory(root,active,shared,modelSources,expectedInventorySha)
parts=cell(1,3*numel(active));
for k=1:numel(active)
    item=active(k); verify_file(char(item.path),char(item.sha256));
    parts{3*k-2}=char(item.role); parts{3*k-1}=char(item.path); parts{3*k}=lower(char(item.sha256));
