    so3Angle(k)=atan2(sinTheta,cosTheta);
    phi=etaReference(k,1); theta=etaReference(k,2); a=rateReference(k,1);
    b=rateReference(k,2); c=rateReference(k,3);
    omegaRefBody=[a-sin(theta)*c;cos(phi)*b+sin(phi)*cos(theta)*c; ...
