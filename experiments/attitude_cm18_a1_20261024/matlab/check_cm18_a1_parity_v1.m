function result = check_cm18_a1_parity_v1(fixture_path)
%CHECK_CM18_A1_PARITY_V1 Compare MATLAB pure forward with Python fixture.
assert(isfile(fixture_path), 'Parity fixture does not exist.');
fixture = jsondecode(fileread(fixture_path));
assert(strcmp(fixture.schema, 'CM18_A1_PARITY_FIXTURE_V1'), 'Wrong fixture schema.');
tol = double(fixture.tolerance_abs);

[physical, normalized, coefficients, basis] = ...
    cm18_a1_forward_v1(fixture.raw_features, fixture.parameters);
expected = fixture.expected;
coefficient_error = max(abs(coefficients(:) - double(expected.coefficients_3x8(:))));
basis_error = max(abs(basis(:) - double(expected.basis_8(:))));
normalized_error = max(abs(normalized(:) - double(expected.normalized_output(:))));
physical_error = max(abs(physical(:) - double(expected.physical_output_rad_s2(:))));
assert(coefficient_error <= tol && basis_error <= tol && ...
       normalized_error <= tol && physical_error <= tol, ...
       'Python/MATLAB CM18-A1 parity tolerance exceeded.');

[zero_physical, ~, ~, zero_basis] = ...
    cm18_a1_forward_v1(fixture.zero_basis_features, fixture.parameters);
assert(all(zero_basis == 0) && isequal(zero_physical, zeros(1,3)), ...
       'CM18-A1 must output exact zero when z=u=0.');
assert(isequal(double(expected.zero_physical_output_rad_s2(:)), zeros(3,1)), ...
       'Python fixture failed its exact-zero structural check.');

result = struct('schema', 'CM18_A1_PARITY_RESULT_V1', ...
    'status', 'PASS', 'tolerance_abs', tol, ...
    'coefficient_max_abs_error', coefficient_error, ...
    'basis_max_abs_error', basis_error, ...
    'normalized_output_max_abs_error', normalized_error, ...
    'physical_output_max_abs_error_rad_s2', physical_error, ...
    'zero_basis_output_exact_zero', true);
end
