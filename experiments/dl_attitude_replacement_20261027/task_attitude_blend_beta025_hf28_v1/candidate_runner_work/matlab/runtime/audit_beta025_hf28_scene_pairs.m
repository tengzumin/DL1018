function report=audit_beta025_hf28_scene_pairs(studyRoot)
% Read-only B/C5 provenance check. Raw MAT allowlist: runIdentity and scene only.
manifestPath=fullfile(studyRoot,'HF28_EXECUTION_MANIFEST_v1.json');
manifest=jsondecode(fileread(manifestPath));
assert(strcmp(char(manifest.schema),'DL1018_TASK_ATTITUDE_BLEND_BETA025_HF28_EXECUTION_MANIFEST_V1')&& ...
    double(manifest.scene_count)==28&&numel(manifest.scenes)==28&&~logical(manifest.test_accessed)&& ...
    ~logical(manifest.baseline_raw_metrics_recomputed), ...
    'HF28:PairManifest','HF28 execution manifest is invalid or opens TEST/recomputes baselines.');
fields={'time','initial_state','reference','arms','environment_wind_I'};
ids=cellstr(string({manifest.scenes.scene_id}));
assert(numel(unique(ids))==28&&isequal(sort(ids),ids), ...
    'HF28:SceneOrder','Scene IDs must be unique and sorted.');
results=repmat(struct('scene_id','','payload_sha256','','B_raw_sha256','','C5_raw_sha256','', ...
    'B_identity_match',false,'C5_scene_binding_match',false, ...
    'C5_external_identity_sha256_present',false,'scene_fields_match',false),28,1);
for i=1:28
    r=manifest.scenes(i);id=char(r.scene_id);
    assert(any(strcmp(char(r.split),{'DEV','VAL'}))&&isempty(regexp(id,'TEST','once'))&& ...
        ~isempty(regexp(id,'_W(09|10|11|12|13|14)$','once')), ...
        'HF28:SceneScope','Only locked W09-W14 DEV/VAL scenes are allowed.');
    paths={char(r.scene_payload_path),char(r.b_raw_path),char(r.c5_raw_path)};
    hashes={char(r.scene_payload_sha256),char(r.b_raw_sha256),char(r.c5_raw_sha256)};
    for j=1:3
        assert(isfile(paths{j})&&strcmpi(sha256_file(paths{j}),hashes{j}), ...
            'HF28:InputSHA','Locked input SHA changed for %s.',id);
    end
    payload=load(paths{1},'scene');
    assert(isfield(payload,'scene'),'HF28:PayloadScene','Payload lacks scene: %s.',id);
    assert(strcmp(char(payload.scene.scene_id),id),'HF28:PayloadID','Payload scene ID differs: %s.',id);
    for j=2:3
        identity=load(paths{j},'runIdentity');
        assert(isfield(identity,'runIdentity')&& ...
            isfield(identity.runIdentity,'scene_id')&& ...
            isfield(identity.runIdentity,'TEST_accessed')&& ...
            strcmp(char(identity.runIdentity.scene_id),id)&& ...
            ~logical(identity.runIdentity.TEST_accessed), ...
            'HF28:RawIdentity','Allowed scene_id/TEST_accessed fields do not bind %s.',id);
        hasExternalIdentity=isfield(identity.runIdentity,'external_identity_sha256');
        if j==2
            assert(hasExternalIdentity&& ...
                strcmpi(char(identity.runIdentity.external_identity_sha256),char(r.external_identity_sha256)), ...
                'HF28:BIdentity','B runIdentity external identity does not bind %s.',id);
            results(i).B_identity_match=true;
        elseif hasExternalIdentity
            assert(strcmpi(char(identity.runIdentity.external_identity_sha256),char(r.external_identity_sha256)), ...
                'HF28:C5Identity','Available C5 external identity does not bind %s.',id);
            results(i).C5_external_identity_sha256_present=true;
        end
        rawScene=load(paths{j},'scene');
        assert(isfield(rawScene,'scene'),'HF28:RawScene','Raw has no scene variable: %s.',id);
        for k=1:numel(fields)
            f=fields{k};
            assert(isfield(payload.scene,f)&&isfield(rawScene.scene,f)&& ...
                isequaln(payload.scene.(f),rawScene.scene.(f)), ...
                'HF28:SceneMismatch','Allowed scene field %s differs for %s.',f,id);
        end
        if j==3,results(i).C5_scene_binding_match=true;end
    end
    results(i).scene_id=id;results(i).payload_sha256=hashes{1};
    results(i).B_raw_sha256=hashes{2};results(i).C5_raw_sha256=hashes{3};
    results(i).scene_fields_match=true;
end
report=struct('schema','DL1018_TASK_ATTITUDE_BLEND_BETA025_HF28_SCENE_PAIR_PREFLIGHT_V1', ...
    'status','PASS_SCENE_ONLY','created_utc',utc_now(), ...
    'manifest_sha256',sha256_file(manifestPath),'scene_count',28, ...
    'allowed_raw_variables',{{'runIdentity','scene'}}, ...
    'inspected_runIdentity_fields',{{'scene_id','external_identity_sha256','TEST_accessed'}}, ...
    'compared_scene_fields',{fields},'baseline_metrics_recomputed',false, ...
    'C5_external_identity_sha256_present_count',sum([results.C5_external_identity_sha256_present]), ...
    'C5_external_identity_sha256_missing_scene_ids', ...
        {{results(~[results.C5_external_identity_sha256_present]).scene_id}}, ...
    'C5_pairing_rule','scene_id and TEST_accessed required; external identity checked when present; exact allowed scene fields required', ...
    'TEST_read',false,'results',results);
auditDir=fullfile(studyRoot,'audits');if ~isfolder(auditDir),mkdir(auditDir);end
write_json(fullfile(auditDir,'HF28_SCENE_PAIR_PREFLIGHT_v1.json'),report);
end
function h=sha256_file(path)
fid=fopen(path,'rb');assert(fid>=0,'HF28:Read','Cannot hash %s.',path);
cleanup=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear cleanup;
end
function write_json(path,value)
fid=fopen(path,'w','n','UTF-8');assert(fid>=0,'HF28:Write','Cannot write %s.',path);
cleanup=onCleanup(@()fclose(fid));fprintf(fid,'%s\n',jsonencode(value,'PrettyPrint',true));clear cleanup;
end
function value=utc_now()
value=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z'''));
end
