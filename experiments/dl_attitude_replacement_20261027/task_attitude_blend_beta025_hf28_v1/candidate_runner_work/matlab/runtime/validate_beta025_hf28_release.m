function [release,manifest]=validate_beta025_hf28_release(studyRoot)
% Fail closed before payload/raw access unless root has released the exact HF28 lock.
releasePath=fullfile(studyRoot,'RELEASE.json');
assert(isfile(releasePath),'HF28:ReleaseMissing','No HF28 release record exists.');
release=jsondecode(fileread(releasePath));
assert(strcmp(char(release.schema),'DL1018_GRU_STREAM_DEV_RELEASE_V1')&& ...
    strcmp(char(release.study_id),'task_attitude_blend_beta025_hf28_v1')&& ...
    strcmp(char(release.candidate),'GRU32_STREAM_COSINE_TASK_BLEND_BETA025_HF28_V1')&& ...
    strcmp(char(release.status),'RELEASED')&&strcmp(char(release.root_approval_status),'APPROVED')&& ...
    double(release.authorized_Plant_calls)==28&&double(release.Plant_calls)==0&& ...
    ~logical(release.TEST_read), ...
    'HF28:ReleaseClosed','HF28 remains draft or approval/call budget is invalid.');
assert(strcmpi(sha256_file(fullfile(studyRoot,'HF28_CODE_LOCK_v1.json')), ...
    char(release.code_lock_sha256)), ...
    'HF28:CodeLockSHA','Candidate source lock changed.');
codeLock=jsondecode(fileread(fullfile(studyRoot,'HF28_CODE_LOCK_v1.json')));
sourceRoot=fullfile(studyRoot,'candidate_runner_work','matlab');
assert(strcmp(char(codeLock.schema),'DL1018_TASK_ATTITUDE_BLEND_BETA025_CODE_LOCK_V1')&& ...
    strcmpi(char(java.io.File(char(codeLock.root)).getCanonicalPath()), ...
    char(java.io.File(sourceRoot).getCanonicalPath())), ...
    'HF28:CodeRoot','Candidate code lock root mismatch.');
actual=dir(fullfile(sourceRoot,'**','*.m'));
assert(numel(actual)==numel(codeLock.files),'HF28:CodeCount','Candidate MATLAB file set changed.');
for i=1:numel(codeLock.files)
    rel=strrep(char(codeLock.files(i).relative_path),'/',filesep);path=fullfile(sourceRoot,rel);
    canonical=char(java.io.File(path).getCanonicalPath());
    assert(isfile(path)&&startsWith(lower(canonical), ...
        [lower(char(java.io.File(sourceRoot).getCanonicalPath())) filesep])&& ...
        strcmpi(sha256_file(path),char(codeLock.files(i).sha256)), ...
        'HF28:CodeSHA','Candidate code changed or escaped source root: %s.',rel);
end
for i=1:numel(release.locked_files)
    path=char(release.locked_files(i).path);
    assert(isfile(path)&&strcmpi(sha256_file(path),char(release.locked_files(i).sha256)), ...
        'HF28:LockedInput','Locked input changed: %s.',path);
end
manifestPath=fullfile(studyRoot,'HF28_EXECUTION_MANIFEST_v1.json');
inputPath=fullfile(studyRoot,'HF28_INPUT_MANIFEST_v1.json');
manifest=jsondecode(fileread(manifestPath));input=jsondecode(fileread(inputPath));
assert(strcmp(char(manifest.schema),'DL1018_TASK_ATTITUDE_BLEND_BETA025_HF28_EXECUTION_MANIFEST_V1')&& ...
    double(manifest.scene_count)==28&&numel(manifest.scenes)==28&&~logical(manifest.test_accessed)&& ...
    ~logical(manifest.baseline_raw_metrics_recomputed)&& ...
    strcmp(char(input.status),'LOCKED_REFERENCES_ONLY')&&double(input.scene_count)==28&& ...
    ~logical(input.test_accessed), ...
    'HF28:Manifest','HF28 manifests are invalid or TEST/baseline rescoring is marked.');
ids=cellstr(string({manifest.scenes.scene_id}));ids=ids(:);
allowed=cellstr(string(release.authorized_scenes));allowed=allowed(:);
assert(numel(unique(ids))==28&&numel(unique(allowed))==28&& ...
    isequal(sort(ids),ids)&&isequal(sort(allowed),ids), ...
    'HF28:AuthorizedScenes','Release scene IDs are not exactly the locked sorted HF28 cohort.');
for i=1:28
    r=manifest.scenes(i);
    assert(any(strcmp(char(r.split),{'DEV','VAL'}))&& ...
        ~isempty(regexp(char(r.scene_id),'_W(09|10|11|12|13|14)$','once'))&& ...
        isempty(regexp(char(r.scene_id),'TEST','once')), ...
        'HF28:SceneScope','Non-HF or TEST scene in release manifest.');
end
assert(strcmpi(char(java.io.File(char(release.output_root)).getCanonicalPath()), ...
    char(java.io.File(fullfile(studyRoot,'runs_beta025_hf28')).getCanonicalPath())), ...
    'HF28:OutputRoot','Output root must be the new isolated HF28 subtree.');
end
function h=sha256_file(path)
fid=fopen(path,'rb');assert(fid>=0,'HF28:Read','Cannot hash %s.',path);
cleanup=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear cleanup;
end
