function attemptDir=run_beta025_hf28_attempt(sceneId)
% One beta=.25 GRU_STREAM closed-loop flight; any attempt directory blocks retry.
entry=fileparts(mfilename('fullpath'));studyRoot=fileparts(fileparts(fileparts(entry)));
[release,manifest]=validate_beta025_hf28_release(studyRoot);
sceneId=char(string(sceneId));ids=cellstr(string({manifest.scenes.scene_id}));
hit=find(strcmp(ids,sceneId));
assert(isscalar(hit),'HF28:SceneID','Scene is not in the released HF28 manifest.');
r=manifest.scenes(hit);
assert(any(strcmp(char(r.split),{'DEV','VAL'}))&& ...
    ~isempty(regexp(sceneId,'_W(09|10|11|12|13|14)$','once')), ...
    'HF28:SceneScope','Only W09-W14 DEV/VAL scenes can run.');
pairPath=fullfile(studyRoot,'audits','HF28_SCENE_PAIR_PREFLIGHT_v1.json');
assert(isfile(pairPath),'HF28:PairAudit','Run the read-only 28-scene pair preflight first.');
pair=jsondecode(fileread(pairPath));
assert(strcmp(char(pair.status),'PASS_SCENE_ONLY')&&double(pair.scene_count)==28&& ...
    strcmpi(char(pair.manifest_sha256),sha256_file(fullfile(studyRoot,'HF28_EXECUTION_MANIFEST_v1.json')))&& ...
    any(strcmp(cellstr(string({pair.results.scene_id})),sceneId)), ...
    'HF28:PairAudit','Pair preflight is missing, stale, or incomplete.');
assert(strcmpi(sha256_file(char(r.scene_payload_path)),char(r.scene_payload_sha256))&& ...
    strcmpi(sha256_file(char(r.b_raw_path)),char(r.b_raw_sha256))&& ...
    strcmpi(sha256_file(char(r.c5_raw_path)),char(r.c5_raw_sha256)), ...
    'HF28:InputSHA','Payload or B/C5 raw bytes changed after the pair preflight.');
runsRoot=char(java.io.File(char(release.output_root)).getCanonicalPath());
batchLockPath=fullfile(runsRoot,'HF28_BATCH_RUNNING.lock');
assert(isfile(batchLockPath), ...
    'HF28:BatchLock','Candidate attempts may only run under the exclusive HF28 batch lock.');
batchLock=jsondecode(fileread(batchLockPath));
assert(strcmp(char(batchLock.schema),'DL1018_HF28_BATCH_LOCK_V1')&& ...
    strcmpi(char(batchLock.release_sha256),sha256_file(fullfile(studyRoot,'RELEASE.json'))), ...
    'HF28:BatchLock','Batch lock does not bind the currently released taskbook.');
attemptDir=fullfile(runsRoot,sceneId,'attempt_01');
assert(~isfolder(attemptDir)&&~isfile(attemptDir), ...
    'HF28:DuplicateAttempt','This scene already has an attempt record; refusing retry.');
if ~isfolder(fullfile(runsRoot,sceneId)),mkdir(fullfile(runsRoot,sceneId));end
assert(mkdir(attemptDir),'HF28:AttemptCreate','Could not create isolated attempt directory.');
statusPath=fullfile(attemptDir,'run_status.json');rawPath=fullfile(attemptDir,'raw_run.mat');
plantCall=0;rawSha='';releaseSha=sha256_file(fullfile(studyRoot,'RELEASE.json'));
try
    runtime=fullfile(studyRoot,'candidate_runner_work','matlab','runtime');
    addpath(runtime);activate_paired_runner();addpath(runtime,'-begin');
    prepared=prepare_mlp15_dev72_no_plant(char(r.scene_payload_path));
    assert(strcmp(char(prepared.scene_id),sceneId)&& ...
        strcmpi(char(prepared.scene_payload_sha256),char(r.scene_payload_sha256))&& ...
        strcmpi(char(prepared.external_identity_sha256),char(r.external_identity_sha256)), ...
        'HF28:PreparedIdentity','Prepared scene does not match the locked HF28 record.');
    modelPath=char(release.model_path);modelSha=sha256_file(modelPath);
    assert(strcmpi(modelSha,char(release.model_sha256))&& ...
        strcmpi(modelPath,char(input_model_path(studyRoot))), ...
        'HF28:ModelSHA','Frozen GRU model does not match the locked input manifest.');
    model=load(modelPath);
    prepared.opts=make_gate_holdout_options(prepared.cfg,prepared.model,'GRU_STREAM','ACTIVE', ...
        struct,model,modelSha);
    identity=gate_holdout_identity_hashes(prepared.cfg,prepared.model,prepared.opts);
    assert(strcmpi(identity.common.position_options_sha256, ...
        prepared.identity.common.position_options_sha256), ...
        'HF28:PositionIdentity','GRU binding changed common C5 position options.');
    prepared.opts.gate_identity_lock=identity;prepared.identity=identity;
    locked=jsondecode(fileread(fullfile(studyRoot,'LOCKED_CFG.json')));
    assert(strcmp(char(locked.capture_status),'PASS_REAL_PREPARED_CFG')&& ...
        isequal(double(prepared.cfg.control.command_filter.acceleration_limit(:)),[Inf;Inf;6])&& ...
        isequal(double(prepared.cfg.control.bs.attitude.k1(:)),double(locked.K1(:)))&& ...
        isequal(double(prepared.cfg.rbf.attitude.dmax(:)),double(locked.dmax(:)))&& ...
        abs(double(prepared.cfg.rbf.attitude.beta_rise_time)-double(locked.beta_rise_time_s))<1e-12&& ...
        strcmpi(char(prepared.cfg.controller_morphology_mode),'fixed'), ...
        'HF28:LockedCfg','C5 prepared config differs from the reviewed fixed config.');
    Pplant=simulation_parameters(prepared.cfg,prepared.cfg.plant.arm_initial,zeros(4,1));
    Pfixed=controller_parameters(prepared.cfg,Pplant,'fixed');J0=double(Pfixed.inertia);
    assert(isequal(J0,double(prepared.cfg.attitude_replacement.J0_controller_fixed_kgm2))&& ...
        isequal(double(Pfixed.inertia_dot_for_bs),zeros(3))&&isequal(J0,double(locked.J0_kgm2)), ...
        'HF28:FixedJ0','Fixed controller J0 or zero Jdot differs from the C5 snapshot.');
    runnerRoot=fullfile(studyRoot,'candidate_runner_work');
    mustResolve={ ...
        'run_mlp15_dev72_closed_loop',fullfile(runnerRoot,'matlab','runtime','run_mlp15_dev72_closed_loop.m'); ...
        'gru_stream_attitude_step_v1',fullfile(runnerRoot,'matlab','runtime','gru_stream_attitude_step_v1.m'); ...
        'gru_stream_tracking_head_step_v1',fullfile(runnerRoot,'matlab','runtime','gru_stream_tracking_head_step_v1.m'); ...
        'gru_stream_attitude_forward_v1',fullfile(runnerRoot,'matlab','runtime','gru_stream_attitude_forward_v1.m'); ...
        'task_attitude_blend_so3_beta025',fullfile(runnerRoot,'matlab','runtime','task_attitude_blend_so3_beta025.m')};
    for i=1:size(mustResolve,1)
        assert(strcmpi(which(mustResolve{i,1}),mustResolve{i,2}), ...
            'HF28:WhichPath','Unexpected MATLAB resolution for %s.',mustResolve{i,1});
    end
    startedUtc=utc_now();
    runIdentity=struct('schema','DL1018_TASK_ATTITUDE_BLEND_BETA025_HF28_RUN_START_V1', ...
        'scene_id',sceneId,'candidate',char(release.candidate),'split',char(r.split), ...
        'started_utc',startedUtc,'release_sha256',releaseSha, ...
        'execution_manifest_sha256',char(release.execution_manifest_sha256), ...
        'input_manifest_sha256',char(release.input_manifest_sha256), ...
        'code_lock_sha256',char(release.code_lock_sha256), ...
        'payload_sha256',char(r.scene_payload_sha256),'external_identity_sha256',char(r.external_identity_sha256), ...
        'B_raw_sha256',char(r.b_raw_sha256),'C5_raw_sha256',char(r.c5_raw_sha256), ...
        'gru_model_sha256',modelSha,'position_model_sha256',prepared.position_model_sha256, ...
        'c5_snapshot_sha256',prepared.c5_snapshot_sha256, ...
        'common_position_options_sha256',identity.common.position_options_sha256, ...
        'attitude_arm','GRU_STREAM','geometry_arm','ACTIVE','task_attitude_blend_beta',0.25, ...
        'blend','shortest_geodesic_SO3_Rpos_exp_beta_log_RposT_Rtask', ...
        'task_attitude_source','baseline_force_to_attitude(r.acceleration,r.euler(3),P)', ...
        'RBF_attitude_output_enabled',false,'RBF_attitude_update_enabled',false, ...
        'inertia_reconstruction_enabled',false,'Plant_truth_deployment_input',false, ...
        'TEST_read',false,'closed_loop_entry','run_mlp15_dev72_closed_loop(scene,cfg,opts)');
    marker=struct('schema','DL1018_TASK_ATTITUDE_BLEND_BETA025_HF28_ATTEMPT_MARKER_V1', ...
        'scene_id',sceneId,'created_utc',startedUtc,'stage','RUNNING','release_sha256',releaseSha);
    write_json(fullfile(attemptDir,'attempt_started.marker'),marker);
    write_json(fullfile(attemptDir,'run_start.json'),runIdentity);
    plantCall=1;prepared.opts.composite_attempt_marker=fullfile(attemptDir,'attempt_started.marker');
    log=run_mlp15_dev72_closed_loop(prepared.scene,prepared.cfg,prepared.opts);
    log.beta025_release_sha256=releaseSha;
    scene=prepared.scene;save(rawPath,'log','scene','runIdentity','-v7.3');rawSha=sha256_file(rawPath);
    counts=struct('motor_saturation',count_flag(log,'motor_saturated'), ...
        'generalized_clip',count_flag(log,'generalized_clipped'), ...
        'tilt_limit',count_flag(log,'tilt_limited'), ...
        'attitude_head_projection',count_flag(log,'attitude_head_projection_active'), ...
        'attitude_head_output_saturation',count_flag(log,'attitude_head_output_saturated'));
    reason=char(log.safety_stop_reason);safeReason=isempty(strtrim(reason))||strcmpi(strtrim(reason),'none');
    referenceNames=fieldnames(log.reference);finiteReference=true;
    for i=1:numel(referenceNames)
        value=log.reference.(referenceNames{i});
        finiteReference=finiteReference&&isnumeric(value)&&all(isfinite(double(value(:))));
    end
    finite=all(isfinite(double(log.time(:))))&&all(isfinite(double(log.state(:))))&& ...
        finiteReference&&all(isfinite(double(log.motor_command(:))))&& ...
        all(isfinite(double(log.motor_setpoint(:))))&&all(isfinite(double(log.raw_outer_attitude(:))))&& ...
        all(isfinite(double(log.filtered_attitude_reference(:))))&& ...
        all(isfinite(double(log.command_filter_target_euler(:))))&& ...
        all(isfinite(double(log.command_filter_task_attitude_reference_euler(:))))&& ...
        all(isfinite(double(log.command_filter_acceleration_applied_rads2(:))))&& ...
        all(isfinite(double(log.controller_call_time_s(:))));
    transitions=double(log.last_transition);stateSamples=size(log.state,1);
    complete=transitions==20000&&stateSamples==20001&&strcmp(char(log.status),'STABLE')&&safeReason&&finite;
    safeActuators=counts.motor_saturation==0&&counts.generalized_clip==0&& ...
        counts.tilt_limit==0&&counts.attitude_head_projection==0&& ...
        counts.attitude_head_output_saturation==0;
    q=sort(double(log.controller_call_time_s(:)));timing=struct( ...
        'p50_s',sample_percentile(q,.50),'p95_s',sample_percentile(q,.95),'max_s',max(q), ...
        'sample_period_s',1e-3);
    success=complete&&safeActuators;
    runStatus=struct('schema','DL1018_TASK_ATTITUDE_BLEND_BETA025_HF28_RUN_STATUS_V1', ...
        'state',ternary(success,'COMPLETED','FAILED_NO_RETRY'),'scene_id',sceneId, ...
        'candidate',char(release.candidate),'Plant_calls',plantCall,'raw_path',rawPath, ...
        'raw_sha256',rawSha,'transitions',transitions,'state_samples',stateSamples, ...
        'status_value',char(log.status),'safety_stop_reason',reason,'finite_required_signals',finite, ...
        'safety_actuator_counts',counts,'controller_call_time',timing, ...
        'release_sha256',releaseSha,'TEST_read',false,'failure_reason',ternary(success,'','completion_or_safety_gate_failed'));
    write_json(statusPath,runStatus);
catch ME
    runStatus=struct('schema','DL1018_TASK_ATTITUDE_BLEND_BETA025_HF28_RUN_STATUS_V1', ...
        'state','FAILED_NO_RETRY','scene_id',sceneId,'candidate',char(release.candidate), ...
        'Plant_calls',plantCall,'raw_path',rawPath,'raw_sha256',rawSha, ...
        'release_sha256',releaseSha,'TEST_read',false,'error_identifier',char(ME.identifier), ...
        'error_message',char(ME.message));
    write_json(statusPath,runStatus);
    write_json(fullfile(attemptDir,'run_failure.json'),struct('scene_id',sceneId, ...
        'failed_utc',utc_now(),'error_identifier',char(ME.identifier), ...
        'error_message',char(ME.message),'stack',{ME.stack}));
end
end
function path=input_model_path(studyRoot)
input=jsondecode(fileread(fullfile(studyRoot,'HF28_INPUT_MANIFEST_v1.json')));path=char(input.gru_model_path);
end
function n=count_flag(s,name)
assert(isfield(s,name),'HF28:SafetyField','Required safety field missing: %s.',name);
x=s.(name);assert(islogical(x)||isnumeric(x),'HF28:SafetyField','Safety flag is not numeric/logical: %s.',name);
n=nnz(x);
end
function y=sample_percentile(sorted,p)
assert(~isempty(sorted)&&all(isfinite(sorted)),'HF28:Timing','Invalid controller timing samples.');
pos=1+(numel(sorted)-1)*p;lo=floor(pos);hi=ceil(pos);y=sorted(lo)+(pos-lo)*(sorted(hi)-sorted(lo));
end
function y=ternary(test,a,b)
if test,y=a;else,y=b;end
end
function h=sha256_file(path)
fid=fopen(path,'rb');assert(fid>=0,'HF28:Read','Cannot hash %s.',path);
cleanup=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear cleanup;
end
function write_json(path,value)
fid=fopen(path,'w','n','UTF-8');assert(fid>=0,'HF28:Write','Cannot write %s.',path);
cleanup=onCleanup(@()fclose(fid));fprintf(fid,'%s\n',jsonencode(value,'PrettyPrint',true));clear cleanup;
end
function value=utc_now()
value=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z'''));
end
