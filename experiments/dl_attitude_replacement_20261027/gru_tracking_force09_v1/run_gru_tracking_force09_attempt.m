function attemptDir=run_gru_tracking_force09_attempt(sceneId)
% One fixed-screen GRU WN18 run; root controls when this Plant entry is called.
studyRoot=fileparts(mfilename('fullpath'));
release=jsondecode(fileread(fullfile(studyRoot,'RELEASE.json')));
sceneId=char(string(sceneId));
assert(strcmp(char(release.schema),'DL1018_GRU_TRACKING_FORCE09_SCREEN_RELEASE_V1')&& ...
    strcmp(char(release.status),'RELEASED')&& ...
    strcmp(char(release.candidate_arm_id),'GRU32_STREAM72_COSINE_TRACKING_HEAD_FORCE09')&& ...
    double(release.authorized_Plant_calls)==12&& ...
    abs(double(release.position_nn_compensation_scale)-.9)<1e-12&& ...
    any(strcmp(cellstr(string(release.authorized_scenes)),sceneId)), ...
    'GRUForce09:Release','Scene or force09 release is not authorized.');
manifest=jsondecode(fileread(fullfile(studyRoot,'SCENE_INPUT_MANIFEST_v1.json')));
hit=find(strcmp({manifest.records.scene_id},sceneId));
assert(isscalar(hit),'GRUForce09:Scene','Scene is not in the locked 12-scene manifest.');
record=manifest.records(hit);
runsRoot=fullfile(studyRoot,'runs');
attemptDir=fullfile(runsRoot,sceneId,'GRU_FORCE09_ATTEMPT_01');
assert(~isfolder(attemptDir)&&~isfile(attemptDir), ...
    'GRUForce09:Duplicate','Scene already has an attempt.');
markers=dir(fullfile(runsRoot,'**','attempt_started.marker'));
assert(numel(markers)<12,'GRUForce09:CallBudget','All 12 screen calls are used.');
for i=1:numel(markers)
    oldStart=fullfile(markers(i).folder,'run_start.json');
    if isfile(oldStart)
        prior=jsondecode(fileread(oldStart));
        assert(~strcmp(char(prior.scene_id),sceneId),'GRUForce09:Duplicate', ...
            'Scene already has a started attempt.');
    end
end
runtime=fullfile(studyRoot,'candidate_runner_work','matlab','runtime');
addpath(runtime);activate_paired_runner();addpath(runtime,'-begin');addpath(studyRoot,'-begin');
prepared=prepare_gru_tracking_force09_no_plant(char(record.payload_path));
assert(strcmp(prepared.scene_id,sceneId),'GRUForce09:PreparedScene','Prepared scene mismatch.');
assert(java.io.File(attemptDir).mkdirs(),'GRUForce09:AttemptCreate','Cannot create attempt directory.');
started=utc_now();releaseSha=sha256_file(fullfile(studyRoot,'RELEASE.json'));
runIdentity=struct('schema','DL1018_GRU_TRACKING_FORCE09_RUN_START_V1', ...
    'scene_id',sceneId,'source_split',char(record.source_split), ...
    'candidate','GRU32_STREAM72_COSINE_TRACKING_HEAD_FORCE09', ...
    'parent_candidate','GRU32_STREAM72_COSINE_TRACKING_HEAD_S2026102001', ...
    'attitude_arm','GRU_STREAM','geometry_arm','ACTIVE','started_utc',started, ...
    'release_sha256',releaseSha, ...
    'source_hash_manifest_sha256',prepared.source_hash_manifest_sha256, ...
    'scene_input_manifest_sha256',prepared.input_manifest_sha256, ...
    'parent_manifest_sha256',char(release.parent_manifest_sha256), ...
    'scene_payload_sha256',prepared.scene_payload_sha256, ...
    'external_identity_sha256',prepared.external_identity_sha256, ...
    'b_raw_sha256',prepared.b_raw_sha256, ...
    'c5_input_lock_sha256',prepared.c5_input_lock_sha256, ...
    'c5_snapshot_sha256',prepared.c5_snapshot_sha256, ...
    'position_model_sha256',prepared.position_model_sha256, ...
    'gru_model_sha256',prepared.gru_model_sha256, ...
    'position_nn_compensation_scale',sprintf('%.17g',prepared.position_nn_compensation_scale), ...
    'position_compensation_log_fields', ...
    'stage1_position_event_applied_acceleration_unscaled_mps2/stage1_position_event_applied_acceleration_mps2/stage1_position_held_force_I_N', ...
    'command_filter_wn_rad_s',[18;18;12], ...
    'position_method_id','C5_AXIS_MIXED_COORDINATE_M110', ...
    'tracking_runtime','gru_stream_tracking_head_step_v1', ...
    'base_model_weights_fixed',true,'tracking_delta_weights_online',true, ...
    'Plant_truth_deployment_input',false,'TEST_read',false, ...
    'closed_loop_entry','run_mlp15_dev72_closed_loop(scene,cfg,opts)');
write_json(fullfile(attemptDir,'attempt_started.marker'),struct( ...
    'schema','DL1018_GRU_TRACKING_FORCE09_ATTEMPT_MARKER_V1', ...
    'scene_id',sceneId,'created_utc',started,'stage','RUNNING','release_sha256',releaseSha));
write_json(fullfile(attemptDir,'run_start.json'),runIdentity);
prepared.opts.composite_attempt_marker=fullfile(attemptDir,'attempt_started.marker');
rawPath=fullfile(attemptDir,'raw_run.mat');
try
    log=run_mlp15_dev72_closed_loop(prepared.scene,prepared.cfg,prepared.opts);
    log.gru_tracking_force09_release_sha256=releaseSha;
    scene=prepared.scene;save(rawPath,'log','scene','runIdentity','-v7.3');
    rawSha=sha256_file(rawPath);
    assert(double(log.last_transition)==20000&&size(log.state,1)==20001&& ...
        strcmp(char(log.status),'STABLE'),'GRUForce09:Incomplete','Run was incomplete or unstable.');
    write_json(fullfile(attemptDir,'run_status.json'),struct( ...
        'schema','DL1018_GRU_TRACKING_FORCE09_RUN_STATUS_V1','state','COMPLETED', ...
        'scene_id',sceneId,'finished_utc',utc_now(),'Plant_calls',1, ...
        'position_nn_compensation_scale',.9,'raw_path',rawPath,'raw_sha256',rawSha, ...
        'transitions',double(log.last_transition),'state_samples',size(log.state,1), ...
        'status_value',char(log.status),'safety_stop_reason',char(log.safety_stop_reason), ...
        'gru_model_sha256',prepared.gru_model_sha256,'TEST_read',false));
    fprintf('GRU_TRACKING_FORCE09_ATTEMPT_DIR=%s\n',attemptDir);
catch ME
    write_json(fullfile(attemptDir,'run_status.json'),struct( ...
        'schema','DL1018_GRU_TRACKING_FORCE09_RUN_STATUS_V1','state','FAILED', ...
        'scene_id',sceneId,'failed_utc',utc_now(),'Plant_calls',1, ...
        'position_nn_compensation_scale',.9,'raw_path',rawPath, ...
        'error_identifier',char(ME.identifier),'error_message',char(ME.message), ...
        'gru_model_sha256',prepared.gru_model_sha256,'TEST_read',false));
    rethrow(ME);
end
end
function h=sha256_file(path)
fid=fopen(path,'rb');assert(fid>=0,'GRUForce09:Read','Cannot read %s.',path);
cleanup=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear cleanup;
end
function write_json(path,x)
fid=fopen(path,'w');assert(fid>=0,'GRUForce09:Write','Cannot write %s.',path);
cleanup=onCleanup(@()fclose(fid));fwrite(fid,[jsonencode(x,'PrettyPrint',true) newline],'char');clear cleanup;
end
function s=utc_now()
s=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z'''));
end
