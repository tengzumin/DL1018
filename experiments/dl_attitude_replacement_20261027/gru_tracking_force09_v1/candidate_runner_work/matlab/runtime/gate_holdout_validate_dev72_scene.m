function audit=gate_holdout_validate_dev72_scene(scene,cfg,geometryArm)
% Validate the generic locked B72 DEV/VAL scene contract; no GHP7 assumptions.
geometryArm=upper(char(geometryArm));
assert(strcmp(geometryArm,'ACTIVE'),'DEV72:Geometry','Only the frozen ACTIVE geometry arm is allowed.');
entry=fileparts(mfilename('fullpath'));studyRoot=fileparts(fileparts(fileparts(entry)));
    manifest=jsondecode(fileread(fullfile(studyRoot,'SCENE_INPUT_MANIFEST_v1.json')));
assert(strcmp(char(manifest.schema),'DL1018_GRU_TRACKING_FORCE09_INPUT_MANIFEST_V1')&& ...
    strcmp(char(manifest.status),'PASS_FIXED12_INPUT_BINDINGS')&&double(manifest.scene_count)==12&& ...
    ~logical(manifest.TEST_read),'DEV72:Manifest','Invalid fixed 12-scene force09 manifest.');
assert(isstruct(scene)&&isfield(scene,'scene_id')&&isfield(scene,'reference_contract_id')&& ...
    strcmp(char(string(scene.reference_contract_id)),'DL1018_SCENE_REF_FIG8_A2_V2'), ...
    'DEV72:SceneContract','Expected the immutable DEV72 reference contract tag.');
sceneId=char(string(scene.scene_id));
hit=find(strcmp({manifest.records.scene_id},sceneId));
assert(isscalar(hit)&&~contains(sceneId,'TEST')&& ...
    any(startsWith(string(sceneId),["DL1018_DEV_","DL1018_VAL_"])) , ...
    'DEV72:SceneId','Scene ID is outside the locked 72 DEV/VAL scenes.');
assert(isstruct(cfg)&&isfield(cfg,'plant')&&abs(double(cfg.plant.dt)-.001)<1e-12, ...
    'DEV72:PlantDt','Expected the locked 1 kHz Plant.');
N=20001;t=double(scene.time(:));
assert(numel(t)==N&&all(isfinite(t))&&max(abs(t-(0:N-1)'*.001))<1e-12, ...
    'DEV72:Time','Expected 20,001 samples from 0 to 20 s at 1 ms.');
assert(isfield(scene,'initial_state')&&numel(scene.initial_state)==12&& ...
    all(isfinite(double(scene.initial_state(:)))), ...
    'DEV72:InitialState','Invalid DEV72 initial state.');
assert(isstruct(scene.reference)&&all(isfield(scene.reference, ...
    {'position','velocity','acceleration','yaw','yaw_rate','yaw_acceleration'})), ...
    'DEV72:Reference','Missing analytic reference fields.');
for field={'position','velocity','acceleration'}
    x=double(scene.reference.(field{1}));
    assert(isequal(size(x),[N,3])&&all(isfinite(x),'all'), ...
        'DEV72:Reference','Invalid reference.%s.',field{1});
end
for field={'yaw','yaw_rate','yaw_acceleration'}
    x=double(scene.reference.(field{1}));
    assert(numel(x)==N&&all(isfinite(x(:))), ...
        'DEV72:Reference','Invalid reference.%s.',field{1});
end
assert(isfield(scene,'environment_wind_I')&&isequal(size(scene.environment_wind_I),[N,3])&& ...
    all(isfinite(double(scene.environment_wind_I)),'all'), ...
    'DEV72:Wind','Invalid DEV72 wind input.');
assert(isstruct(scene.arms)&&all(isfield(scene.arms, ...
    {'command','rho_true','rho_hat','rhoDot_true','rhoDot_hat'})), ...
    'DEV72:Arms','Missing morphology input arrays.');
for field={'command','rho_true','rho_hat','rhoDot_true','rhoDot_hat'}
    x=double(scene.arms.(field{1}));
    assert(isequal(size(x),[N,4])&&all(isfinite(x),'all'), ...
        'DEV72:Arms','Invalid scene.arms.%s.',field{1});
end
rTaskHash='';
if isfield(scene,'R_task')
    R=double(scene.R_task);
    assert(isequal(size(R),[3,3,N])&&all(isfinite(R),'all'), ...
        'DEV72:RTask','Optional R_task is malformed.');
    rTaskHash=paired_sha256_double(R);
end
record=manifest.records(hit);
audit=struct('scene_id',sceneId,'geometry_arm',geometryArm, ...
    'scene_payload_sha256',char(record.payload_sha256), ...
    'external_identity_sha256',char(record.external_identity_sha256), ...
    'b_raw_sha256',char(record.b_raw_sha256),'R_task_sha256',rTaskHash, ...
    'test_data_read',false,'plant_invoked',false);
end
