function p=prepare_gru_tracking_force09_no_plant(scenePayloadPath)
% Bind one fixed DEV/VAL scene to parent WN18 GRU, C5 M110, and force scale .9.
entry=fileparts(mfilename('fullpath'));
studyRoot=fileparts(fileparts(fileparts(entry)));
projectRoot=fileparts(fileparts(fileparts(studyRoot)));
assert(strcmpi(char(java.io.File(studyRoot).getCanonicalPath()), ...
    char(java.io.File(fullfile(projectRoot,'experiments','dl_attitude_replacement_20261027', ...
    'gru_tracking_force09_v1')).getCanonicalPath())), ...
    'GRUForce09:StudyRoot','Candidate study-root backtracking is wrong.');
runnerRoot=activate_paired_runner();
releasePath=fullfile(studyRoot,'RELEASE.json');
release=jsondecode(fileread(releasePath));
sourceManifestPath=fullfile(studyRoot,'SOURCE_HASH_MANIFEST_v1.json');
assert(strcmp(char(release.schema),'DL1018_GRU_TRACKING_FORCE09_SCREEN_RELEASE_V1')&& ...
    any(strcmp(char(release.status),{'PREPARED_NO_PLANT_PENDING_ROOT_LAUNCH','RELEASED'}))&& ...
    strcmp(char(release.candidate_arm_id),'GRU32_STREAM72_COSINE_TRACKING_HEAD_FORCE09')&& ...
    abs(double(release.position_nn_compensation_scale)-.9)<1e-12&& ...
    double(release.authorized_Plant_calls)==12&&numel(release.authorized_scenes)==12&& ...
    strcmpi(sha256_file(sourceManifestPath),char(release.source_hash_manifest_sha256)), ...
    'GRUForce09:Release','Release/schema/scale/source binding is invalid.');
sourceManifest=jsondecode(fileread(sourceManifestPath));
assert(strcmp(char(sourceManifest.schema),'DL1018_GRU_TRACKING_FORCE09_SOURCE_HASH_MANIFEST_V1')&& ...
    numel(sourceManifest.files)==double(sourceManifest.source_file_count), ...
    'GRUForce09:Sources','Candidate source manifest is malformed.');
for i=1:numel(sourceManifest.files)
    rec=sourceManifest.files(i);sourcePath=fullfile(studyRoot,strrep(char(rec.path),'/',filesep));
    assert(isfile(sourcePath)&&strcmpi(sha256_file(sourcePath),char(rec.sha256)), ...
        'GRUForce09:SourceSHA','Candidate source changed: %s.',sourcePath);
end
inputManifestPath=fullfile(studyRoot,'SCENE_INPUT_MANIFEST_v1.json');
manifest=jsondecode(fileread(inputManifestPath));
parentManifestPath=char(release.parent_manifest_path);
assert(strcmp(char(manifest.schema),'DL1018_GRU_TRACKING_FORCE09_INPUT_MANIFEST_V1')&& ...
    strcmp(char(manifest.status),'PASS_FIXED12_INPUT_BINDINGS')&& ...
    double(manifest.scene_count)==12&&numel(manifest.records)==12&& ...
    ~logical(manifest.TEST_read)&&double(manifest.Plant_calls)==0&& ...
    strcmpi(sha256_file(parentManifestPath),char(release.parent_manifest_sha256))&& ...
    strcmpi(sha256_file(inputManifestPath),char(release.scene_input_manifest_sha256))&& ...
    strcmpi(char(manifest.parent_manifest_sha256),char(release.parent_manifest_sha256)), ...
    'GRUForce09:InputManifest','Fixed 12-scene input/parent manifest identity is invalid.');
parent=jsondecode(fileread(parentManifestPath));
assert(strcmp(char(parent.schema),'GRU_STREAM_COSINE_TRACKING_HEAD_FULL72_MANIFEST_V1')&& ...
    strcmp(char(parent.candidate),'GRU32_STREAM72_COSINE_TRACKING_HEAD_S2026102001')&& ...
    double(parent.scene_count)==72&&double(parent.dev_scene_count)==24&& ...
    double(parent.val_scene_count)==48&&~logical(parent.TEST_read)&& ...
    strcmpi(char(parent.candidate_model_sha256),char(release.gru_model_sha256))&& ...
    strcmpi(sha256_file(char(parent.candidate_model_path)),char(release.gru_model_sha256)), ...
    'GRUForce09:Parent','Only the exact WN18 FULL72 GRU parent is accepted.');
scenePayloadPath=char(java.io.File(char(scenePayloadPath)).getCanonicalPath());
payloadPaths=cellstr(string({manifest.records.payload_path}));
payloadPaths=cellfun(@(x)char(java.io.File(x).getCanonicalPath()),payloadPaths,'UniformOutput',false);
hit=find(strcmp(payloadPaths,scenePayloadPath));
assert(isscalar(hit),'GRUForce09:PayloadPath','Payload is not uniquely bound to the fixed 12.');
record=manifest.records(hit);
authorized=cellstr(string(release.authorized_scenes));
assert(any(strcmp(authorized,char(record.scene_id)))&& ...
    any(strcmp({'DEV','VAL'},char(record.source_split)))&& ...
    ~contains(string(record.scene_id),'TEST')&& ...
    strcmpi(sha256_file(scenePayloadPath),char(record.payload_sha256)), ...
    'GRUForce09:Scene','Scene/payload is outside the fixed DEV/VAL release.');
for pair={record.b_raw_path,record.b_raw_sha256;record.b_status_path,record.b_status_sha256; ...
        record.c5_raw_path,record.c5_raw_sha256;record.c5_status_path,record.c5_status_sha256}.'
    path=char(pair{1});expected=char(pair{2});
    assert(isfile(path)&&strcmpi(sha256_file(path),expected), ...
        'GRUForce09:InputSHA','A B/C5 input hash changed: %s.',path);
end
bStatus=jsondecode(fileread(char(record.b_status_path)));
assert(strcmp(char(bStatus.scene_id),char(record.scene_id))&& ...
    strcmpi(char(bStatus.raw_sha256),char(record.b_raw_sha256))&& ...
    strcmp(char(bStatus.log_status),'STABLE')&&double(bStatus.transitions)==20000&& ...
    double(bStatus.state_samples)==20001&&~logical(bStatus.TEST_accessed), ...
    'GRUForce09:BStatus','Bound B source is not stable/complete or accessed TEST.');
sourceIdentity=load(char(record.b_raw_path),'runIdentity');
assert(isfield(sourceIdentity,'runIdentity')&& ...
    strcmpi(char(sourceIdentity.runIdentity.external_identity_sha256), ...
    char(record.external_identity_sha256))&&~logical(sourceIdentity.runIdentity.TEST_accessed), ...
    'GRUForce09:ExternalIdentity','B external identity differs from the fixed scene manifest.');
vars=whos('-file',scenePayloadPath);
assert(isscalar(vars)&&strcmp(char(vars.name),'scene'), ...
    'GRUForce09:PayloadVariable','Scene payload must contain only scene.');
payload=load(scenePayloadPath,'scene');scene=payload.scene;
scene.reference_contract_id='DL1018_SCENE_REF_FIG8_A2_V2';
lockPath=fullfile(projectRoot,'experiments','position_axis_coordinate_c5_dev72_20261023', ...
    'C5_DEV72_INPUT_LOCK_v3.json');
lock=jsondecode(fileread(lockPath));
lockHit=find(strcmp({lock.scenes.scene_id},char(record.scene_id)));
assert(isscalar(lockHit)&&strcmpi(char(lock.scenes(lockHit).B72_scoring.raw_sha256), ...
    char(record.b_raw_sha256))&&strcmpi(char(lock.scenes(lockHit).external_identity_sha256), ...
    char(record.external_identity_sha256)), ...
    'GRUForce09:C5InputLock','Scene/B identity differs from locked C5 input.');
c5ReceiptPath=fullfile(projectRoot,'experiments','attitude_physics_inertia_observer_20261025', ...
    'holdout_gate_inspection_v2','C5_R_TASK_BINDING_PILOT_RECEIPT_v5.json');
c5Receipt=jsondecode(fileread(c5ReceiptPath));
c5LockPath=char(c5Receipt.input_records.c5_input_lock.path);
c5SnapshotPath=char(c5Receipt.input_records.c5_snapshot_mat.path);
positionModelPath=char(c5Receipt.input_records.model_mat.path);
verify_record(c5Receipt.input_records.c5_input_lock,c5LockPath);
verify_record(c5Receipt.input_records.c5_snapshot_mat,c5SnapshotPath);
verify_record(c5Receipt.input_records.model_mat,positionModelPath);
assert(strcmp(char(c5Receipt.status),'PASS_NO_PLANT_PILOT_PAYLOADS_ONLY')&& ...
    double(c5Receipt.plant_calls)==0&&double(c5Receipt.training_runs)==0&& ...
    ~logical(c5Receipt.tests_data_read)&&strcmpi(sha256_file(lockPath), ...
    char(c5Receipt.input_records.c5_input_lock.sha256)), ...
    'GRUForce09:C5Receipt','C5 no-Plant receipt differs from the fixed input lock.');
snapshot=load(c5SnapshotPath,'cfg','W0');positionPack=load(positionModelPath,'model');
positionModel=positionPack.model;
assert(strcmp(char(positionModel.model_id),'DSSM14')&&double(positionModel.input_dim)==14&& ...
    double(positionModel.window)==32&&isequal(double(positionModel.output_W),double(snapshot.W0))&& ...
    strcmpi(paired_sha256_double(double(snapshot.W0)),char(c5Receipt.W0_sha256))&& ...
    strcmpi(normalizer_sha(positionModel),char(c5Receipt.normalizer_arrays_sha256)), ...
    'GRUForce09:C5Model','DSSM14/W0/normalizer identity mismatch.');
cfg=geometry_cfg(snapshot.cfg);
assert(max(abs(double(cfg.control.command_filter.wn(:))-[18;18;12]))<1e-12, ...
    'GRUForce09:Wn18','Candidate must retain the parent WN18 filter.');
modelPath=char(release.gru_model_path);
assert(strcmpi(sha256_file(modelPath),char(release.gru_model_sha256)), ...
    'GRUForce09:ModelSHA','Locked WN18 GRU model hash changed.');
gruModel=load(modelPath);
gru_stream_tracking_head_step_v1('init',struct,struct,gruModel);
opts=make_gate_holdout_options(cfg,positionModel,'GRU_STREAM','ACTIVE',struct, ...
    gruModel,char(release.gru_model_sha256));
identity=gate_holdout_identity_hashes(cfg,positionModel,opts);
assert(strcmpi(identity.common.position_options_sha256, ...
    char(c5Receipt.common_position_options_sha256)), ...
    'GRUForce09:PositionIdentity','GRU binding changed the C5 M110 position options.');
opts.gate_identity_lock=identity;
opts.position_nn_compensation_scale=double(release.position_nn_compensation_scale);
sceneAudit=gate_holdout_validate_dev72_scene(scene,cfg,'ACTIVE');
scaleTest=position_force09_no_plant_test();
assert(strcmp(char(scaleTest.status),'PASS_NO_PLANT')&&~logical(scaleTest.plant_called), ...
    'GRUForce09:ScaleCheck','No-Plant force-scale/BS check failed.');
p=struct('scene',scene,'cfg',cfg,'position_model',positionModel, ...
    'gru_model',gruModel,'opts',opts,'identity',identity,'scene_audit',sceneAudit, ...
    'scene_id',char(record.scene_id),'scene_payload_path',scenePayloadPath, ...
    'scene_payload_sha256',char(record.payload_sha256), ...
    'external_identity_sha256',char(record.external_identity_sha256), ...
    'b_raw_path',char(record.b_raw_path),'b_raw_sha256',char(record.b_raw_sha256), ...
    'c5_input_lock_sha256',sha256_file(lockPath), ...
    'c5_snapshot_sha256',char(c5Receipt.input_records.c5_snapshot_mat.sha256), ...
    'position_model_sha256',char(c5Receipt.input_records.model_mat.sha256), ...
    'gru_model_sha256',char(release.gru_model_sha256), ...
    'position_nn_compensation_scale',double(release.position_nn_compensation_scale), ...
    'source_hash_manifest_sha256',sha256_file(sourceManifestPath), ...
    'input_manifest_sha256',sha256_file(inputManifestPath), ...
    'runner_root',runnerRoot,'attitude_arm','GRU_STREAM','geometry_arm','ACTIVE', ...
    'no_plant_scale_check',scaleTest);
end
function cfg=geometry_cfg(sourceCfg)
cfg=sourceCfg;
if isfield(cfg,'attitude_replacement'),cfg=rmfield(cfg,'attitude_replacement');end
cfg.plant.arm_initial=repmat(.15,4,1);
cfg=bind_paired_fixed_j0(cfg);
end
function verify_record(record,path)
assert(isfile(path)&&strcmpi(sha256_file(path),char(record.sha256))&& ...
    strcmpi(char(java.io.File(path).getCanonicalPath()), ...
    char(java.io.File(char(record.path)).getCanonicalPath())), ...
    'GRUForce09:LockedInput','Locked C5 input mismatch: %s.',path);
end
function h=normalizer_sha(model)
md=java.security.MessageDigest.getInstance('SHA-256');
for name={'input_mu','input_sigma'}
    f=name{1};a=reshape(double(model.(f)),1,[]);
    header=[f char(0) '((1, 14), ''float64'')' char(0)];
    md.update(typecast(uint8(unicode2native(header,'UTF-8')),'int8'));
    md.update(typecast(a(:),'int8'));
end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
function h=sha256_file(path)
fid=fopen(path,'rb');assert(fid>=0,'GRUForce09:Read','Cannot read %s.',path);
cleanup=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true
    b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end
    md.update(typecast(b(:),'int8'));
end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
clear cleanup;
end
