function report=mlp15_update_first_no_plant_test()
% Deterministic no-Plant check of update-first RLS and later tracking state.
model=struct('input_mean',zeros(13,1),'input_std',ones(13,1), ...
    'target_rms',ones(3,1),'fc1_weight',zeros(64,195),'fc1_bias',zeros(64,1), ...
    'fc2_weight',zeros(32,64),'fc2_bias',zeros(32,1), ...
    'head_weight',zeros(3,32),'head_bias',zeros(3,1), ...
    'target_contract','DL1018_MLP15_TRAIN_C5_24_FIXED_J0_RESIDUAL_V1', ...
    'fixed_J0_kg_m2',diag([1,2,3]));
J0=model.fixed_J0_kg_m2;dmax=100*ones(3,1);

% A disabled head is a strict no-op and requires no event metadata.
[memory,~]=mlp15_physical_residual_step_v1('init',struct,struct,model);
disabled=struct('feature',zeros(13,1),'J0',J0,'beta',1,'dmax',dmax, ...
    'head_enabled',false);
[disabledMemory,disabledOut]=mlp15_physical_residual_step_v1( ...
    'step',memory,disabled,model);
assert(~disabledOut.head.enabled&&~disabledOut.head.update_executed&& ...
    ~disabledOut.head.tracking_update_executed&&disabledMemory.previous_sample_index==0&& ...
    all(disabledMemory.head_weight(:)==0));

% First event seeds phi only; the next event uses exactly its completed interval.
[memory,~]=mlp15_physical_residual_step_v1('init',struct,struct,model);
first=event(10,.010,[0;0;0],0,J0,dmax);
[memory,out1]=mlp15_physical_residual_step_v1('step',memory,first,model);
assert(~out1.head.update_executed&&~out1.head.tracking_update_executed&& ...
    out1.head.output_precedes_tracking_update&& ...
    isequal(out1.head.weight_output_used,out1.head.weight_after_rls));

times=(10:20).'*0.001;omega=zeros(11,3);omega(:,1)=linspace(0,.02,11);
second=event(20,.020,[.02;0;0],.010,J0,dmax);
second.omega_history=omega;second.torque_history=zeros(10,3);
second.history_time=times;second.history_sample_indices=(10:20).';
[memory,out2]=mlp15_physical_residual_step_v1('step',memory,second,model);
h=out2.head;phi=h.phi;scale=model.target_rms(:);
assert(h.update_executed&&h.observation_end_time_s==second.time_s&& ...
    h.issued_torque_max_sample_index==second.sample_index-1&& ...
    all(abs(out2.raw_residual_rad_s2-(h.base_residual_rad_s2+ ...
    scale.*(h.weight_output_used.'*phi)))<1e-12));
assert(norm(h.weight_after_rls-h.weight_before,'fro')>1e-6&& ...
    h.output_precedes_tracking_update&&h.tracking_update_executed&& ...
    norm(h.weight_after-h.weight_after_rls,'fro')>1e-8&& ...
    norm(out2.raw_residual_rad_s2-(h.base_residual_rad_s2+ ...
    scale.*(h.weight_after.'*phi)))>1e-8);
assert(norm(h.weight_output_used,'fro')<=20+1e-12&& ...
    memory.previous_sample_index==second.sample_index&&all(isfinite(memory.head_weight),'all'));
report=struct('status','PASS_NO_PLANT','plant_called',false, ...
    'disabled_head_noop',true,'first_event_seed_only',true, ...
    'current_interval_ends_at_sample',second.sample_index, ...
    'issued_torque_max_sample_index',h.issued_torque_max_sample_index, ...
    'output_uses_post_RLS_pre_tracking_weight',true, ...
    'tracking_remains_after_output',true,'output_weight_norm',norm(h.weight_output_used,'fro'));
end

function in=event(index,time,omegaNow,eventDt,J0,dmax)
feature=zeros(13,1);feature(4:6)=omegaNow;
in=struct('feature',feature,'J0',J0,'beta',1,'dmax',dmax, ...
    'head_enabled',true,'sample_index',index,'time_s',time, ...
    'tracking_surface',[.1;-.2;.3],'tracking_euler_rate_map',eye(3), ...
    'actual_event_dt',eventDt);
end
