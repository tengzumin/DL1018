function preflight_mlp15_physical_residual_no_plant(scenePayloadPath)
% Validate one scene/model/options binding without entering the closed loop.
p=prepare_mlp15_physical_residual_no_plant(scenePayloadPath);
assert(strcmp(char(p.attitude_model.target_contract), ...
    'DL1018_MLP15_TRAIN_C5_24_FIXED_J0_RESIDUAL_V1')&& ...
    strcmpi(char(p.mlp15_model_sha256), ...
    'dfbad11dbc7ed19b42d3b536bb4b019cbf29209d69c904b0b5000a168af58819'), ...
    'DLMLP:PreflightModel','Preflight model contract or frozen weight SHA differs.');
result=struct('status','PASS_NO_PLANT','scene_id',p.scene_id, ...
    'scene_payload_sha256',p.scene_payload_sha256, ...
    'physical_residual_model_sha256',p.mlp15_model_sha256, ...
    'physical_residual_target_contract',char(p.attitude_model.target_contract), ...
    'fixed_J0_kg_m2',double(p.attitude_model.fixed_J0_kg_m2), ...
    'position_nn_compensation_scale',p.position_nn_compensation_scale, ...
    'position_path_changed',true,'C5_position_physical_equivalence_claimed',false, ...
    'source_hash_manifest_sha256',p.source_hash_manifest_sha256, ...
    'c5_position_identity',p.identity.common, ...
    'plant_called',false,'test_data_read',false);
fprintf('%s\n',jsonencode(result,'PrettyPrint',true));
end
