function prepared=prepare_mlp15_physical_residual_no_plant(scenePayloadPath)
% Bind one locked DEV/VAL scene to C5 and the TRAIN_C5_24 physics residual model.
entry=fileparts(mfilename('fullpath'));
studyRoot=fileparts(fileparts(fileparts(entry)));
mlp15Root=fileparts(studyRoot);
projectRoot=fileparts(fileparts(fileparts(mlp15Root)));
runnerRoot=activate_paired_runner();
release=jsondecode(fileread(fullfile(studyRoot,'RELEASE.json')));
sourceManifestPath=fullfile(studyRoot,'SOURCE_HASH_MANIFEST_v1.json');
assert(strcmp(char(release.schema),'DL1018_MLP15_PHYSICAL_RESIDUAL_SCREEN_RELEASE_V1')&& ...
    any(strcmp(char(release.status),{'PREPARED_NO_PLANT_PENDING_ROOT_LAUNCH','RELEASED'}))&& ...
    strcmp(char(release.candidate_arm_id),'DL_MLP15_PHYSICAL_RESIDUAL_FORCE09')&& ...
    abs(double(release.position_nn_compensation_scale)-.9)<1e-12&& ...
    isfile(sourceManifestPath)&&strcmpi(sha256_file(sourceManifestPath), ...
    char(release.source_hash_manifest_sha256)), ...
    'DEV72:Force09Release','Force09 release or source-hash binding is invalid.');
sourceManifest=jsondecode(fileread(sourceManifestPath));
assert(strcmp(char(sourceManifest.schema),'DL1018_MLP15_FORCE09_SOURCE_HASH_MANIFEST_V1')&& ...
    numel(sourceManifest.files)==double(sourceManifest.source_file_count), ...
    'DEV72:Force09Sources','Force09 source-hash manifest is malformed.');
for sourceIndex=1:numel(sourceManifest.files)
    sourceRecord=sourceManifest.files(sourceIndex);
    sourcePath=fullfile(studyRoot,strrep(char(sourceRecord.path),'/',filesep));
    assert(isfile(sourcePath)&&strcmpi(sha256_file(sourcePath),char(sourceRecord.sha256)), ...
        'DEV72:Force09SourceSHA','Force09 source hash mismatch: %s',sourcePath);
end
manifestPath=fullfile(studyRoot,'MLP15_DEV72_PAYLOAD_MANIFEST_v2.json');
manifest=jsondecode(fileread(manifestPath));
taskbookPath=fullfile(studyRoot,'MLP15_DEV72_EXPLORATORY_TASKBOOK_v2.md');
parentManifestPath=fullfile(studyRoot,'MLP15_DEV72_PAYLOAD_MANIFEST_PARENT_v1.json');
assert(strcmp(char(manifest.schema),'DL1018_MLP15_DEV72_PAYLOAD_MANIFEST_V2')&& ...
    strcmp(char(manifest.status),'PASS_NO_PLANT_REUSE')&&double(manifest.scene_count)==72&& ...
    ~logical(manifest.test_data_read)&&double(manifest.plant_calls)==0&& ...
    strcmpi(sha256_file(taskbookPath),char(manifest.taskbook_sha256))&& ...
    strcmpi(sha256_file(parentManifestPath),char(manifest.parent_manifest_sha256))&& ...
    strcmpi(sha256_file(fullfile(projectRoot,'experiments','position_axis_coordinate_c5_dev72_20261023', ...
    'C5_DEV72_INPUT_LOCK_v3.json')),char(manifest.source_c5_input_lock_sha256)), ...
    'DEV72:Manifest','Frozen DEV72 payload/taskbook/C5 lock identity is invalid.');
scenePayloadPath=char(java.io.File(char(scenePayloadPath)).getCanonicalPath());
payloadPaths=cellstr(string({manifest.records.payload_path}));
payloadPaths=cellfun(@(x)char(java.io.File(x).getCanonicalPath()),payloadPaths,'UniformOutput',false);
hit=find(strcmp(payloadPaths,scenePayloadPath));
assert(isscalar(hit),'DEV72:PayloadPath','Payload is not one unique locked DEV72 path.');
record=manifest.records(hit);
assert(strcmpi(sha256_file(scenePayloadPath),char(record.payload_sha256))&& ...
    isfile(char(record.b_raw_path))&&isfile(char(record.b_status_path))&& ...
    strcmpi(sha256_file(char(record.b_raw_path)),char(record.b_raw_sha256))&& ...
    strcmpi(sha256_file(char(record.b_status_path)),char(record.b_status_sha256)), ...
    'DEV72:PayloadSHA','Payload or bound B72 raw/status hash mismatch.');
status=jsondecode(fileread(char(record.b_status_path)));
assert(strcmp(char(status.scene_id),char(record.scene_id))&& ...
    strcmpi(char(status.raw_sha256),char(record.b_raw_sha256))&& ...
    strcmp(char(status.log_status),'STABLE')&&double(status.transitions)==20000&& ...
    double(status.state_samples)==20001&&~logical(status.TEST_accessed), ...
    'DEV72:BStatus','Bound B72 status is incomplete, unstable, or accessed TEST.');
sourceIdentity=load(char(record.b_raw_path),'runIdentity');
assert(isfield(sourceIdentity,'runIdentity')&& ...
    strcmpi(char(sourceIdentity.runIdentity.external_identity_sha256), ...
    char(record.external_identity_sha256))&&~logical(sourceIdentity.runIdentity.TEST_accessed), ...
    'DEV72:ExternalIdentity','B raw external identity differs from the locked scene.');
vars=whos('-file',scenePayloadPath);
assert(isscalar(vars)&&strcmp(char(vars.name),'scene'), ...
    'DEV72:PayloadVariable','Payload MAT must contain only the scenario variable.');
payload=load(scenePayloadPath,'scene');scene=payload.scene;
assert(strcmp(char(scene.scene_id),char(record.scene_id))&& ...
    any(startsWith(string(record.scene_id),["DL1018_DEV_","DL1018_VAL_"]))&& ...
    ~contains(string(record.scene_id),'TEST'), ...
    'DEV72:SceneID','Payload scene is not from the locked DEV/VAL cohort.');
% This is a fixed interface-contract tag only; all physical scenario arrays stay byte-identical.
scene.reference_contract_id='DL1018_SCENE_REF_FIG8_A2_V2';
lockPath=fullfile(projectRoot,'experiments','position_axis_coordinate_c5_dev72_20261023', ...
    'C5_DEV72_INPUT_LOCK_v3.json');
lock=jsondecode(fileread(lockPath));
lockHit=find(strcmp({lock.scenes.scene_id},char(record.scene_id)));
assert(isscalar(lockHit)&&strcmpi(char(lock.scenes(lockHit).B72_scoring.raw_sha256), ...
    char(record.b_raw_sha256))&&strcmpi(char(lock.scenes(lockHit).external_identity_sha256), ...
    char(record.external_identity_sha256)), ...
    'DEV72:InputLock','Scene/B72 identity differs from C5 lock v3.');

c5ReceiptPath=fullfile(projectRoot,'experiments','attitude_physics_inertia_observer_20261025', ...
    'holdout_gate_inspection_v2','C5_R_TASK_BINDING_PILOT_RECEIPT_v5.json');
c5Receipt=jsondecode(fileread(c5ReceiptPath));
c5InputLockPath=char(c5Receipt.input_records.c5_input_lock.path);
c5SnapshotPath=char(c5Receipt.input_records.c5_snapshot_mat.path);
positionModelPath=char(c5Receipt.input_records.model_mat.path);
verify_record(c5Receipt.input_records.c5_input_lock,c5InputLockPath);
verify_record(c5Receipt.input_records.c5_snapshot_mat,c5SnapshotPath);
verify_record(c5Receipt.input_records.model_mat,positionModelPath);
assert(strcmp(char(c5Receipt.status),'PASS_NO_PLANT_PILOT_PAYLOADS_ONLY')&& ...
    double(c5Receipt.plant_calls)==0&&double(c5Receipt.training_runs)==0&& ...
    ~logical(c5Receipt.tests_data_read)&&strcmpi(char(c5Receipt.input_records.c5_input_lock.sha256), ...
    sha256_file(lockPath))&&strcmpi(char(c5Receipt.input_records.c5_input_lock.sha256), ...
    char(manifest.source_c5_input_lock_sha256)), ...
    'DEV72:C5Receipt','C5 no-Plant receipt does not bind the frozen DEV72 stack.');
positionModelPack=load(positionModelPath,'model');snapshot=load(c5SnapshotPath,'cfg','W0');
model=positionModelPack.model;
assert(strcmp(char(model.model_id),'DSSM14')&&double(model.input_dim)==14&& ...
    double(model.window)==32&&isequal(double(model.output_W),double(snapshot.W0))&& ...
    strcmpi(paired_sha256_double(double(snapshot.W0)),char(c5Receipt.W0_sha256))&& ...
    strcmpi(normalizer_sha(model),char(c5Receipt.normalizer_arrays_sha256)), ...
    'DEV72:C5Model','C5 DSSM14/W0/normalizer identity mismatch.');
cfg=geometry_cfg(snapshot.cfg);
assert(max(abs(double(cfg.control.command_filter.wn(:))-[18;18;12]))<1e-12, ...
    'DEV72:Wn18','Residual screen must use the parent WN18 [18;18;12] command filter.');

trainingDir=fullfile(mlp15Root,'runs', ...
    'MLP15_TRAIN_C5_24_PHYSICAL_RESIDUAL_SEED2026102001_REPAIR01');
trainingConfig=jsondecode(fileread(fullfile(mlp15Root,'TRAINING_CONFIG_v1r1.json')));
dataManifest=jsondecode(fileread(fullfile(mlp15Root,'TRAIN_C5_24_PHYSICAL_RESIDUAL_MANIFEST_v1.json')));
postprocess=jsondecode(fileread(fullfile(trainingDir,'training_postprocess_receipt_v1.json')));
weightsPath=fullfile(trainingDir,'mlp15_attitude_weights_v1.mat');
weightsSha=sha256_file(weightsPath);weights=load(weightsPath);
fixedJ0=double(dataManifest.fixed_J0_kg_m2);
targetContract='DL1018_MLP15_TRAIN_C5_24_FIXED_J0_RESIDUAL_V1';
assert(strcmp(char(trainingConfig.status),'FROZEN')&& ...
    strcmp(char(dataManifest.schema),targetContract)&&strcmp(char(dataManifest.status), ...
    'PASS_TRAIN_ONLY_SOURCE_AND_CAUSALITY_AUDIT')&&double(trainingConfig.optimizer_steps)==60000&& ...
    double(trainingConfig.fit_scene_count)==24&&double(trainingConfig.fit_event_count)==47976&& ...
    strcmp(char(postprocess.status),'PASS_CPU_POSTPROCESS')&& ...
    strcmpi(char(postprocess.matlab_weights_sha256),weightsSha)&& ...
    isequal(size(fixedJ0),[3,3])&& ...
    max(abs(fixedJ0(:)-double(cfg.attitude_replacement.J0_controller_fixed_kgm2(:))))<1e-15&& ...
    ~logical(dataManifest.C5_VAL48_loaded_for_training)&&~logical(dataManifest.TEST_read)&& ...
    ~logical(dataManifest.Plant_called), ...
    'DEV72:ResidualTraining','Frozen TRAIN_C5_24 physical-residual model contract failed.');
weights.target_contract=targetContract;
weights.target_definition=char(dataManifest.target_definition);
weights.fixed_J0_kg_m2=fixedJ0;
opts=make_gate_holdout_options(cfg,model,'DL_MLP15','ACTIVE',struct,weights,weightsSha);
identity=gate_holdout_identity_hashes(cfg,model,opts);opts.gate_identity_lock=identity;
spec=gate_attitude_arm_spec('DL_MLP15');
assert(~spec.rbf_enabled&&~spec.physics_helper_enabled&&~spec.feedforward_enabled&& ...
    ~spec.observer_enabled&&strcmpi(identity.common.position_options_sha256, ...
    char(c5Receipt.common_position_options_sha256)), ...
    'DEV72:ControllerContract','Candidate enables a forbidden mechanism or changes C5 position identity.');
opts.position_nn_compensation_scale=double(release.position_nn_compensation_scale);
sceneAudit=gate_holdout_validate_dev72_scene(scene,cfg,'ACTIVE');
prepared=struct('scene',scene,'cfg',cfg,'model',model,'attitude_model',weights, ...
    'opts',opts,'identity',identity, ...
    'scene_audit',sceneAudit,'scene_payload_sha256',char(record.payload_sha256), ...
    'scene_payload_path',scenePayloadPath,'scene_id',char(record.scene_id), ...
    'external_identity_sha256',char(record.external_identity_sha256), ...
    'b_raw_path',char(record.b_raw_path),'b_raw_sha256',char(record.b_raw_sha256), ...
    'b_status_path',char(record.b_status_path),'b_status_sha256',char(record.b_status_sha256), ...
    'c5_input_lock_sha256',char(manifest.source_c5_input_lock_sha256), ...
    'c5_snapshot_sha256',char(c5Receipt.input_records.c5_snapshot_mat.sha256), ...
    'position_model_sha256',char(c5Receipt.input_records.model_mat.sha256), ...
    'mlp15_model_sha256',weightsSha,'mlp15_completed_steps',double(trainingConfig.optimizer_steps), ...
    'position_nn_compensation_scale',double(release.position_nn_compensation_scale), ...
    'source_hash_manifest_path',sourceManifestPath, ...
    'source_hash_manifest_sha256',sha256_file(sourceManifestPath), ...
    'candidate_runner_root',runnerRoot,'attitude_arm','DL_MLP15','geometry_arm','ACTIVE');
end
function cfg=geometry_cfg(sourceCfg)
cfg=sourceCfg;if isfield(cfg,'attitude_replacement'),cfg=rmfield(cfg,'attitude_replacement');end
cfg.plant.arm_initial=repmat(.15,4,1);cfg=bind_paired_fixed_j0(cfg);
end
function verify_record(record,path)
assert(isfile(path)&&strcmpi(sha256_file(path),char(record.sha256))&& ...
    strcmpi(char(java.io.File(path).getCanonicalPath()),char(java.io.File(char(record.path)).getCanonicalPath())), ...
    'DEV72:LockedInput','C5 locked input mismatch: %s',path);
end
function h=normalizer_sha(model)
md=java.security.MessageDigest.getInstance('SHA-256');
for name={'input_mu','input_sigma'}
    f=name{1};a=reshape(double(model.(f)),1,[]);
    header=[f char(0) '((1, 14), ''float64'')' char(0)];
    md.update(typecast(uint8(unicode2native(header,'UTF-8')),'int8'));
    md.update(typecast(a(:),'int8'));
end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
function h=sha256_file(path)
fid=fopen(path,'rb');assert(fid>=0,'DEV72:Read','Cannot open %s.',path);
cleanup=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear cleanup;
end



