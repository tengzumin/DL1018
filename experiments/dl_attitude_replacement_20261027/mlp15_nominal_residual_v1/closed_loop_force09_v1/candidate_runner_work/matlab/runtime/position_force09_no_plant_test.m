function report=position_force09_no_plant_test()
% Check only the position-compensation scale and BS force interface; no Plant call.
mass=.695;scale09=.9;nn=[.6;-.4;.2];
[a1,f1]=position_stage1_scale_compensation_v1(nn,mass,1);
[a09,f09]=position_stage1_scale_compensation_v1(nn,mass,scale09);
assert(isequal(a1,nn)&&isequal(f1,mass*nn)&& ...
    max(abs(a09-scale09*nn))<1e-15&&max(abs(f09-mass*a09))<1e-15, ...
    'DSSM:CompensationScaleParity','Scale 1 must restore parent output; scale .9 must preserve force/acceleration units.');

P=struct('mass',mass,'g',9.8, ...
    'bs',struct('position',struct('k1',[1;1;1],'k2',[4;4;4])), ...
    'limits',struct('max_tilt',pi/6));
state=[.05;-.04;.02;.1;-.08;.03;.1;-.08;.2;zeros(3,1)];
r=struct('position',[.1;-.1;0],'velocity',[.2;-.1;.1], ...
    'acceleration',[.3;-.2;.1]);
[~,nominal]=position_bs_step(state,r,zeros(3,1),P);
[~,parent]=position_bs_step(state,r,f1,P);
[~,scaled]=position_bs_step(state,r,f09,P);
assert(isequal(parent.nominal_force,nominal.nominal_force)&& ...
    isequal(scaled.nominal_force,nominal.nominal_force)&& ...
    max(abs(parent.commanded_force-(nominal.nominal_force-f1)))<1e-14&& ...
    max(abs(scaled.commanded_force-(nominal.nominal_force-f09)))<1e-14&& ...
    max(abs(scaled.commanded_acceleration-(nominal.commanded_acceleration-.9*nn)))<1e-14, ...
    'DSSM:CompensationScaleBS','Compensation scale must not change BS nominal feedback.');

report=struct('status','PASS_NO_PLANT','plant_called',false,'test_data_read',false, ...
    'scale_1_exact_parent_restore',true,'scale_09_acceleration',a09.', ...
    'scale_09_force_N',f09.','BS_nominal_force_unchanged',true, ...
    'PCF_command_acceleration_uses_scaled_force',true);
end
