function attemptDir=run_mlp15_physical_residual_attempt(scenePayloadPath,attemptDir)
% Run one released scene with the fixed-J0 physical-residual MLP15.
entry=fileparts(mfilename('fullpath'));
studyRoot=fileparts(fileparts(fileparts(entry)));
releasePath=fullfile(studyRoot,'RELEASE.json');
assert(isfile(releasePath),'DLMLP:ReleaseMissing','Missing residual-screen release.');
release=jsondecode(fileread(releasePath));
assert(strcmp(char(release.schema),'DL1018_MLP15_PHYSICAL_RESIDUAL_SCREEN_RELEASE_V1')&& ...
    strcmp(char(release.status),'RELEASED')&& ...
    strcmp(char(release.candidate_arm_id),'DL_MLP15_PHYSICAL_RESIDUAL_FORCE09')&& ...
    double(release.authorized_Plant_calls)==12&&logical(release.causal_head_enabled)&& ...
    abs(double(release.position_nn_compensation_scale)-.9)<1e-12&& ...
    ~logical(release.TEST_read), ...
    'DLMLP:Release','Release does not match the 12-scene residual screen.');
prepared=prepare_mlp15_physical_residual_no_plant(scenePayloadPath);
authorized=cellstr(string(release.authorized_scenes));
assert(any(strcmp(authorized,prepared.scene_id))&& ...
    strcmpi(char(release.model_sha256),prepared.mlp15_model_sha256), ...
    'DLMLP:SceneRelease','Scene or model is outside the frozen residual screen.');
assert(isequal(double(release.command_filter_wn_rad_s(:)), ...
    double(prepared.cfg.control.command_filter.wn(:))), ...
    'DLMLP:FilterContract','Prepared candidate did not restore parent WN18 [18;18;12].');
assert(abs(prepared.position_nn_compensation_scale-double(release.position_nn_compensation_scale))<1e-12&& ...
    strcmpi(prepared.source_hash_manifest_sha256,char(release.source_hash_manifest_sha256)), ...
    'DLMLP:Force09Contract','Prepared scale or source-hash manifest differs from the release.');

runsRoot=char(java.io.File(fullfile(studyRoot,'runs')).getCanonicalPath());
attemptDir=char(java.io.File(char(attemptDir)).getCanonicalPath());
assert(startsWith(lower(attemptDir),[lower(runsRoot) filesep])&& ...
    ~isfolder(attemptDir)&&~isfile(attemptDir), ...
    'DLMLP:OutputPath','Output must be a new directory under the isolated run root.');
assert(strcmpi(char(java.io.File(fileparts(attemptDir)).getCanonicalPath()), ...
    fullfile(runsRoot,prepared.scene_id)), ...
    'DLMLP:AttemptParent','Output must be grouped under the exact scene ID.');
markers=dir(fullfile(runsRoot,'**','attempt_started.marker'));
assert(numel(markers)<double(release.authorized_Plant_calls), ...
    'DLMLP:CallBudget','All residual screen calls have been consumed.');
for i=1:numel(markers)
    startPath=fullfile(markers(i).folder,'run_start.json');
    if isfile(startPath)
        old=jsondecode(fileread(startPath));
        assert(~strcmp(char(old.scene_id),prepared.scene_id), ...
            'DLMLP:DuplicateScene','This scene already has a residual attempt.');
    end
end
assert(java.io.File(attemptDir).mkdirs(),'DLMLP:AttemptCreate','Cannot create attempt output.');
startedUtc=utcNow();
runIdentity=struct('schema','DL1018_MLP15_PHYSICAL_RESIDUAL_FORCE09_RUN_START_V1', ...
    'scene_id',prepared.scene_id,'attitude_arm','DL_MLP15_PHYSICAL_RESIDUAL_FORCE09', ...
    'geometry_arm','ACTIVE','started_utc',startedUtc, ...
    'release_sha256',sha256_file(releasePath), ...
    'source_hash_manifest_sha256',prepared.source_hash_manifest_sha256, ...
    'position_nn_compensation_scale',sprintf('%.17g',prepared.position_nn_compensation_scale), ...
    'scene_payload_sha256',prepared.scene_payload_sha256, ...
    'external_identity_sha256',prepared.external_identity_sha256, ...
    'b_raw_sha256',prepared.b_raw_sha256, ...
    'c5_input_lock_sha256',prepared.c5_input_lock_sha256, ...
    'c5_snapshot_sha256',prepared.c5_snapshot_sha256, ...
    'position_model_sha256',prepared.position_model_sha256, ...
    'physical_residual_model_sha256',prepared.mlp15_model_sha256, ...
    'physical_residual_target_contract',char(prepared.attitude_model.target_contract), ...
    'fixed_J0_kg_m2',double(prepared.attitude_model.fixed_J0_kg_m2), ...
    'causal_update_head_enabled',logical(release.causal_head_enabled), ...
    'command_filter_wn_rad_s',double(prepared.cfg.control.command_filter.wn(:)), ...
    'controller_inputs','13 causal runtime features; requested-torque past-10ms observer', ...
    'test_data_read',false,'runner_entry','run_mlp15_physical_residual_closed_loop(scene,cfg,opts)');
write_json(fullfile(attemptDir,'attempt_started.marker'),struct( ...
    'schema','DL1018_MLP15_PHYSICAL_RESIDUAL_ATTEMPT_V1', ...
    'scene_id',prepared.scene_id,'created_utc',startedUtc,'stage','RUNNING'));
write_json(fullfile(attemptDir,'run_start.json'),runIdentity);
try
    prepared.opts.composite_attempt_marker=fullfile(attemptDir,'attempt_started.marker');
    log=run_mlp15_physical_residual_closed_loop(prepared.scene,prepared.cfg,prepared.opts);
    complete=double(log.last_transition)==20000&&size(log.state,1)==20001&& ...
        strcmp(char(log.status),'STABLE');
    assert(complete,'DLMLP:Incomplete','Candidate did not finish a stable 20,000-transition run.');
    scene=prepared.scene;
    save(fullfile(attemptDir,'raw_run.mat'),'log','scene','runIdentity','-v7.3');
    rawPath=fullfile(attemptDir,'raw_run.mat');
    write_json(fullfile(attemptDir,'run_status.json'),struct( ...
        'schema','DL1018_MLP15_PHYSICAL_RESIDUAL_FORCE09_RUN_STATUS_V1','state','COMPLETED', ...
        'scene_id',prepared.scene_id,'attitude_arm','DL_MLP15_PHYSICAL_RESIDUAL_FORCE09', ...
        'geometry_arm','ACTIVE','finished_utc',utcNow(),'plant_calls',1, ...
        'position_nn_compensation_scale',prepared.position_nn_compensation_scale, ...
        'source_hash_manifest_sha256',prepared.source_hash_manifest_sha256, ...
        'raw_path',rawPath,'raw_sha256',sha256_file(rawPath), ...
        'transitions',double(log.last_transition),'state_samples',size(log.state,1), ...
        'status_value',char(log.status),'safety_stop_reason',char(log.safety_stop_reason), ...
        'scene_payload_sha256',prepared.scene_payload_sha256, ...
        'physical_residual_model_sha256',prepared.mlp15_model_sha256,'test_data_read',false));
    fprintf('MLP15_PHYSICAL_RESIDUAL_ATTEMPT_DIR=%s',attemptDir);
catch ME
    write_json(fullfile(attemptDir,'run_status.json'),struct( ...
        'schema','DL1018_MLP15_PHYSICAL_RESIDUAL_FORCE09_RUN_STATUS_V1','state','FAILED', ...
        'scene_id',prepared.scene_id,'attitude_arm','DL_MLP15_PHYSICAL_RESIDUAL_FORCE09', ...
        'geometry_arm','ACTIVE','failed_utc',utcNow(),'plant_calls',1, ...
        'position_nn_compensation_scale',prepared.position_nn_compensation_scale, ...
        'source_hash_manifest_sha256',prepared.source_hash_manifest_sha256, ...
        'error_identifier',char(ME.identifier),'error_message',char(ME.message), ...
        'scene_payload_sha256',prepared.scene_payload_sha256, ...
        'physical_residual_model_sha256',prepared.mlp15_model_sha256, ...
        'test_data_read',false));
    rethrow(ME);
end
end

function h=sha256_file(path)
fid=fopen(path,'rb');assert(fid>=0,'DLMLP:Read','Cannot read %s.',path);
cleanup=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear cleanup;
end
function write_json(path,x)
fid=fopen(path,'w');assert(fid>=0,'DLMLP:Write','Cannot write %s.',path);
cleanup=onCleanup(@()fclose(fid));fwrite(fid,[jsonencode(x,'PrettyPrint',true) newline],'char');clear cleanup;
end
function s=utcNow()
s=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z'''));
end
