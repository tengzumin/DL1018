function run_mlp15_parity_v1()
% One fixture-only parity check. No Plant, runner, dynamics, or actuator calls.
scriptDir = fileparts(mfilename('fullpath'));
runDir = fullfile(scriptDir,'..','..','runs', ...
    'MLP15_TRAIN_C5_24_PHYSICAL_RESIDUAL_SEED2026102001_REPAIR01');
weightsPath = fullfile(runDir,'mlp15_attitude_weights_v1.mat');
fixturePath = fullfile(runDir,'parity_vector_v1.mat');
reportPath = fullfile(scriptDir,'matlab_parity_report_v1.txt');
checkcodePath = fullfile(scriptDir,'checkcode_result_v1.txt');
commandPath = fullfile(scriptDir,'matlab_run_command_v1.txt');
assert(~isfile(reportPath),'DLMLP:NoOverwrite','Parity report already exists.');
assert(isfile(checkcodePath) && isfile(commandPath), ...
    'DLMLP:MissingAudit','Checkcode result or MATLAB command record is missing.');
checkcodeText = fileread(checkcodePath);
assert(contains(checkcodeText,'CHECKCODE: PASS'), ...
    'DLMLP:Checkcode','Isolated forward function checkcode did not pass.');

expectedWeightsHash = 'dfbad11dbc7ed19b42d3b536bb4b019cbf29209d69c904b0b5000a168af58819';
expectedFixtureHash = '2d64707297f1108939e6d788b65f59b74dd3a4b88e9377a43b9e7515db34ff9a';
weightsHash = sha256_file(weightsPath);
fixtureHash = sha256_file(fixturePath);
assert(strcmpi(weightsHash,expectedWeightsHash), ...
    'DLMLP:WeightsHash','Frozen MATLAB weights SHA-256 mismatch.');
assert(strcmpi(fixtureHash,expectedFixtureHash), ...
    'DLMLP:FixtureHash','Frozen parity fixture SHA-256 mismatch.');

weights = load(weightsPath);
fixture = load(fixturePath);
required = {'fc1_weight','fc1_bias','fc2_weight','fc2_bias', ...
    'head_weight','head_bias','target_rms'};
assert(all(isfield(weights,required)), ...
    'DLMLP:WeightsSchema','Frozen weights MAT is missing a required field.');
assert(all(isfield(fixture,{'input_normalized_window','expected_residual_rad_s2'})), ...
    'DLMLP:FixtureSchema','Parity fixture MAT is missing a required field.');
model = struct();
for k = 1:numel(required)
    model.(required{k}) = double(weights.(required{k}));
end
window = double(fixture.input_normalized_window);
expected = double(fixture.expected_residual_rad_s2(:));
assert(isequal(size(window),[13,15]) && numel(expected)==3 && ...
    all(isfinite(expected)) && numel(model.target_rms)==3 && ...
    size(model.fc1_weight,2)==numel(window) && ...
    size(model.fc1_weight,1)==numel(model.fc1_bias) && ...
    size(model.fc2_weight,2)==numel(model.fc1_bias) && ...
    size(model.fc2_weight,1)==numel(model.fc2_bias) && ...
    size(model.head_weight,2)==numel(model.fc2_bias) && ...
    size(model.head_weight,1)==3 && numel(model.head_bias)==3, ...
    'DLMLP:Shape','Fixture or frozen MLP15 layer dimensions are inconsistent.');

actual = mlp15_parity_forward_v1(window,model);
absError = abs(actual-expected);
maxAbsError = max(absError);
tolerance = 1e-6;
if maxAbsError <= tolerance
    status = 'PASS';
else
    status = 'FAIL';
end
forwardPath = fullfile(scriptDir,'mlp15_parity_forward_v1.m');
entryPath = [mfilename('fullpath') '.m'];
reportLines = { ...
    'MLP15 no-Plant MATLAB fixture parity v1', ...
    ['Status: ' status], ...
    ['MATLAB version: ' version], ...
    ['MATLAB release: ' version('-release')], ...
    ['MATLAB command: ' fileread(commandPath)], ...
    'Plant called: false', ...
    'External runner called: false', ...
    'Dynamics called: false', ...
    'Actuator called: false', ...
    ['Weights file: ' weightsPath], ...
    ['Weights SHA-256: ' weightsHash], ...
    ['Parity fixture: ' fixturePath], ...
    ['Parity fixture SHA-256: ' fixtureHash], ...
    ['Forward function SHA-256: ' sha256_file(forwardPath)], ...
    ['Entry point SHA-256: ' sha256_file(entryPath)], ...
    'Fixture input: input_normalized_window, used directly (features/normalization are already in the fixture).', ...
    'Flattening: MATLAB window(:); each chronological event column contributes its 13 features in order.', ...
    'Forward path: fc1 affine + SiLU, fc2 affine + SiLU, head affine, then elementwise target_rms.', ...
    'Output clipping: none (raw physical residual parity).', ...
    ['Input shape: ' mat2str(size(window))], ...
    ['Layer weight shapes: fc1=' mat2str(size(model.fc1_weight)) ...
        ', fc2=' mat2str(size(model.fc2_weight)) ', head=' mat2str(size(model.head_weight))], ...
    ['Expected residual (rad/s^2): ' mat2str(expected.',17)], ...
    ['MATLAB residual (rad/s^2): ' mat2str(actual.',17)], ...
    ['Absolute error by axis (rad/s^2): ' mat2str(absError.',17)], ...
    sprintf('Maximum absolute error (rad/s^2): %.17g',maxAbsError), ...
    sprintf('Absolute tolerance (rad/s^2): %.17g',tolerance), ...
    'MATLAB Code Analyzer result for mlp15_parity_forward_v1.m:', ...
    checkcodeText};
reportText = strjoin(reportLines,newline);
fid = fopen(reportPath,'wt');
assert(fid>=0,'DLMLP:ReportWrite','Could not create parity report.');
cleanup = onCleanup(@() fclose(fid));
fprintf(fid,'%s\n',reportText);
clear cleanup
fprintf('%s\nMaximum absolute error: %.17g rad/s^2\n',status,maxAbsError);
if ~strcmp(status,'PASS')
    error('DLMLP:ParityFail','Fixture parity exceeded the absolute 1e-6 rad/s^2 tolerance.');
end
end

function hash = sha256_file(path)
fid = fopen(path,'rb');
assert(fid>=0,'DLMLP:HashRead','Could not open file for SHA-256.');
cleanup = onCleanup(@() fclose(fid));
bytes = fread(fid,Inf,'*uint8');
md = java.security.MessageDigest.getInstance('SHA-256');
md.update(typecast(bytes(:),'int8'));
digest = typecast(md.digest(),'uint8');
hash = lower(reshape(dec2hex(digest,2).',1,[]));
clear cleanup
end