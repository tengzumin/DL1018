function [memory,out]=gru_stream_tracking_head_step_v1(action,memory,in,model)
% Frozen cosine GRU plus a causal tracking-error residual head.
switch lower(char(action))
    case 'init'
        assert(isstruct(model)&&all(isfield(model,{'input_mean','input_std'}))&& ...
            numel(model.input_mean)==13&&numel(model.input_std)==13&& ...
            all(isfinite(double(model.input_mean(:))))&& ...
            all(isfinite(double(model.input_std(:))))&&all(double(model.input_std(:))>0), ...
            'DLGRUTrack:Normalizer','GRU normalizer is invalid.');
        gru_stream_attitude_forward_v1(zeros(13,1),zeros(32,1),model);
        memory=struct('hidden',zeros(32,1),'DeltaW',zeros(33,3),'event_count',0, ...
            'previous_sample_index',0,'previous_time_s',0);
        out=struct('initialized',true,'hidden_state',memory.hidden, ...
            'tracking_delta_weight',memory.DeltaW);
    case 'step'
        required={'feature','J0','beta','dmax','actual_event_dt','sample_index','time_s', ...
            'tracking_surface','tracking_euler_rate_map','gamma','sigma_w','s_limit','wmax'};
        assert(isstruct(in)&&all(isfield(in,required)), ...
            'DLGRUTrack:StepInput','Missing tracking-head step input fields.');
        feature=double(in.feature(:));J0=double(in.J0);beta=double(in.beta);
        dmax=double(in.dmax(:));dtEvent=double(in.actual_event_dt);
        sampleIndex=double(in.sample_index);timeNow=double(in.time_s);
        surface=double(in.tracking_surface(:));T=double(in.tracking_euler_rate_map);
        gamma=double(in.gamma(:));sigmaW=double(in.sigma_w(:));
        sLimit=double(in.s_limit(:));wmax=double(in.wmax);
        assert(isstruct(memory)&&all(isfield(memory, ...
            {'hidden','DeltaW','event_count','previous_sample_index','previous_time_s'}))&& ...
            numel(memory.hidden)==32&&all(isfinite(double(memory.hidden(:))))&& ...
            isequal(size(memory.DeltaW),[33,3])&&all(isfinite(double(memory.DeltaW(:))))&& ...
            isscalar(memory.event_count)&&isfinite(double(memory.event_count))&&memory.event_count>=0&& ...
            isscalar(memory.previous_sample_index)&&isfinite(double(memory.previous_sample_index))&& ...
            isscalar(memory.previous_time_s)&&isfinite(double(memory.previous_time_s)), ...
            'DLGRUTrack:Memory','GRU or tracking-head state is invalid.');
        assert(numel(feature)==13&&all(isfinite(feature))&&isequal(size(J0),[3,3])&& ...
            all(isfinite(J0),'all')&&numel(dmax)==3&&all(isfinite(dmax))&&all(dmax>0)&& ...
            isscalar(beta)&&isfinite(beta)&&beta>=0&&beta<=1&& ...
            isscalar(dtEvent)&&isfinite(dtEvent)&&dtEvent>0&& ...
            isscalar(sampleIndex)&&isfinite(sampleIndex)&&sampleIndex==round(sampleIndex)&& ...
            sampleIndex>memory.previous_sample_index&&isscalar(timeNow)&&isfinite(timeNow)&& ...
            timeNow>memory.previous_time_s&& ...
            abs(dtEvent-(timeNow-memory.previous_time_s))<1e-10&& ...
            numel(surface)==3&&all(isfinite(surface))&&isequal(size(T),[3,3])&& ...
            all(isfinite(T),'all')&&numel(gamma)==3&&all(isfinite(gamma))&&all(gamma>0)&& ...
            numel(sigmaW)==3&&all(isfinite(sigmaW))&&all(sigmaW>=0)&& ...
            numel(sLimit)==3&&all(isfinite(sLimit))&&all(sLimit>0)&& ...
            isscalar(wmax)&&isfinite(wmax)&&wmax>0, ...
            'DLGRUTrack:StepShape','Invalid feature, controller, event, or tracking-head config.');
        assert(isstruct(model)&&all(isfield(model,{'input_mean','input_std'}))&& ...
            numel(model.input_mean)==13&&numel(model.input_std)==13&& ...
            all(isfinite(double(model.input_mean(:))))&& ...
            all(isfinite(double(model.input_std(:))))&&all(double(model.input_std(:))>0), ...
            'DLGRUTrack:Normalizer','GRU normalizer is invalid.');
        featureNormalized=(feature-double(model.input_mean(:)))./double(model.input_std(:));
        hiddenBefore=double(memory.hidden(:));DeltaWBefore=double(memory.DeltaW);
        [qBase,hiddenAfter]=gru_stream_attitude_forward_v1( ...
            featureNormalized,hiddenBefore,model);
        phi=[hiddenAfter;1];
        qRaw=qBase+DeltaWBefore.'*phi;
        qClipped=min(max(qRaw,-dmax),dmax);
        betaScaledResidual=beta.*qClipped;
        estimateTorque=J0*betaScaledResidual;
        surfaceEffective=min(max(surface,-sLimit),sLimit);
        drive=T.'*surfaceEffective;
        DeltaWDot=-beta.*phi*(gamma.*drive).'-DeltaWBefore.*sigmaW.';
        DeltaWUnprojected=DeltaWBefore+dtEvent.*DeltaWDot;
        DeltaWAfter=min(max(DeltaWUnprojected,-wmax),wmax);
        memory.hidden=hiddenAfter;
        memory.DeltaW=DeltaWAfter;
        memory.event_count=double(memory.event_count)+1;
        memory.previous_sample_index=sampleIndex;memory.previous_time_s=timeNow;
        out=struct('feature_normalized',featureNormalized,'q_base_rad_s2',qBase, ...
            'raw_residual_rad_s2',qRaw,'clipped_residual_rad_s2',qClipped, ...
            'beta_scaled_residual_rad_s2',betaScaledResidual, ...
            'estimateTorque_Nm',estimateTorque,'hidden_before',hiddenBefore, ...
            'hidden_after',hiddenAfter,'phi',phi,'DeltaW_before',DeltaWBefore, ...
            'DeltaW_dot',DeltaWDot,'DeltaW_unprojected',DeltaWUnprojected, ...
            'DeltaW_after',DeltaWAfter,'tracking_surface',surface, ...
            'tracking_surface_effective',surfaceEffective, ...
            'tracking_euler_rate_map',T,'tracking_drive',drive,'gamma',gamma, ...
            'sigma_w',sigmaW,'s_limit',sLimit,'wmax',wmax, ...
            'actual_event_dt',dtEvent,'beta',beta, ...
            'tracking_update_norm',norm(DeltaWAfter-DeltaWBefore,'fro'), ...
            'tracking_weight_projection_active',any(abs(DeltaWUnprojected(:))>wmax), ...
            'sample_index',sampleIndex,'time_s',timeNow, ...
            'event_count',memory.event_count);
        assert(all(isfinite([qBase;qRaw;qClipped;estimateTorque;hiddenAfter; ...
            DeltaWAfter(:);DeltaWDot(:)])), ...
            'DLGRUTrack:Numerics','Tracking head produced a nonfinite value.');
    otherwise
        error('DLGRUTrack:Action','Unknown action %s.',char(action));
end
end
