function result=prepare_c5_matched_ablation_dev72_v2()
% No-Plant preparation for one fixed C5 M110 matched-ablation configuration.
here=fileparts(mfilename('fullpath')); repoRoot=fileparts(fileparts(fileparts(here)));
lockPath=fullfile(here,'C5_ABLATION_DEV72_INPUT_LOCK_v2.json'); contractPath=fullfile(here,'C5_ABLATION_DEV72_RUN_CONTRACT_v2.json');
resultPath=fullfile(here,'C5_ABLATION_DEV72_PREPARE_RESULT_v2.json'); snapshotPath=fullfile(here,'C5_ABLATION_DEV72_PREPARED_CFG_OPTS_v2.mat');
assert(isfile(lockPath)&&isfile(contractPath)&&~isfile(resultPath)&&~isfile(snapshotPath), ...
    'C5:NoOverwrite','C5 lock/contract must exist and preparation outputs must be absent.');
lock=jsondecode(fileread(lockPath)); contract=jsondecode(fileread(contractPath));
assert(strcmp(lock.schema,'C5_MATCHED_ABLATION_DEV72_INPUT_LOCK_V2')&& ...
    strcmp(lock.state,'LOCKED_C5_MATCHED_ABLATION_DEV72_NO_PLANT_WAIT_PARENT_REVIEW_V2')&& ...
    ~logical(lock.plant_authorized_by_this_lock)&&logical(lock.pcf_auxiliary_enabled)&& ...
    isequal(double(lock.coordinate_mask(:)),[1;1;0])&&strcmp(contract.schema,'C5_MATCHED_ABLATION_DEV72_RUN_CONTRACT_V2')&& ...
    strcmp(contract.state,lock.state)&&isequal(string(lock.scene_ids_all_72(:)),string(contract.scene_ids_all_72(:)))&& ...
    isequal(string(lock.scene_ids_remaining_60(:)),string(contract.scene_ids_remaining_60(:)))&& ...
    isequal(string(lock.scene_ids_reuse_12(:)),string(contract.scene_ids_reuse_12(:)))&& ...
    numel(lock.scenes)==72&&numel(contract.scene_ids_all_72)==72&& ...
    numel(contract.scene_ids_remaining_60)==60&&numel(contract.scene_ids_reuse_12)==12&& ...
    strcmp(lock.variant_id,contract.variant_id)&&strcmp(lock.first_scene_id,contract.first_scene_id)&& ...
    strcmp(lock.ablation_mode,contract.ablation_mode)&&logical(contract.legacy_stage1_update_enabled)&& ...
    logical(contract.actual_weight_update_enabled)==strcmp(contract.variant_id,'C5_NO_DELAYED_PREDICTION')&& ...
    ~logical(contract.actual_prediction_gradient_enabled), ...
    'C5:Scope','C5 full72 scope/order differs from the frozen contract.');
sourceFileNames=fieldnames(lock.source_files);
for sf=1:numel(sourceFileNames)
    sourceItem=lock.source_files.(sourceFileNames{sf});
    if isstruct(sourceItem)&&isfield(sourceItem,'path')
        for sj=1:numel(sourceItem), verify_ref(sourceItem(sj)); end
    end
end
for k=1:numel(lock.active_source_inventory), verify_ref(lock.active_source_inventory(k)); end
refNames=fieldnames(lock.upstream_refs); for k=1:numel(refNames), verify_ref(lock.upstream_refs.(refNames{k})); end
for k=1:numel(lock.shared_input_files), verify_ref(lock.shared_input_files(k)); end
assert(numel(lock.active_source_inventory)==32&&lock.source_counts.matlab==31&&lock.source_counts.mat==1, ...
    'C5:SourceCount','Expected the locked 32-source/31-M/1-MAT runtime inventory.');

% Restore the frozen dependency path after init_dl1018 resets the MATLAB path.
active=lock.active_source_inventory; initPath=source_path(active,'init_dl1018.m');
optionsPath=source_path(active,'position_only_search_options.m');
headPath=source_path(active,'position_only_search_head_step.m');
forwardPath=source_path(active,'position_stage1_model_forward_v2.m');
add_active_paths(active); addpath(fullfile(repoRoot,'matlab','runtime'),'-end'); addpath(fullfile(repoRoot,'matlab','core'),'-end');
addpath(fileparts(initPath),'-begin'); clear init_dl1018; rehash;
assert(same_path(which('init_dl1018'),initPath),'C5:InitPath','init_dl1018 resolves outside the frozen runtime.');
[cfg,~,resolvedRoot]=init_dl1018(); assert(same_path(resolvedRoot,repoRoot),'C5:ProjectRoot','Runtime resolved a different repository root.');
add_active_paths(active); addpath(fullfile(repoRoot,'matlab','runtime'),'-end'); addpath(fullfile(repoRoot,'matlab','core'),'-end');
addpath(fileparts(optionsPath),'-begin'); addpath(fileparts(headPath),'-begin'); addpath(fileparts(forwardPath),'-begin'); addpath(here,'-begin');
clear run_episode_dl1018 run_dl1018_closed_loop delayed_prediction_step_candidate ...
    position_only_search_options position_only_search_head_step position_stage1_model_forward_v2 init_dl1018; rehash;
for k=1:numel(active)
    verify_ref(active(k)); [~,name,ext]=fileparts(active(k).path);
    if strcmpi(ext,'.m'), assert(same_path(which(name),active(k).path), ...
            'C5:WhichShadow','Locked source %s resolves to a shadow.',name); end
end
assert(same_path(which('run_dl1018_closed_loop'),fullfile(here,'run_dl1018_closed_loop.m'))&& ...
    same_path(which('run_episode_dl1018'),fullfile(here,'run_episode_dl1018.m'))&& ...
    same_path(which('delayed_prediction_step_candidate'),fullfile(here,'delayed_prediction_step_candidate.m')), ...
    'C5:Isolation','C5 core/wrapper/helper must resolve from the isolated directory.');

% Compare fresh C5 options with frozen C3; only the explicit mask is new.
c3Prep=jsondecode(fileread(lock.upstream_refs.c3_dev72_prepare_result.path));
assert(strcmp(c3Prep.status,'PREPARED_NO_PLANT_WAIT_PARENT_RELEASE')&& ...
    double(c3Prep.plant_calls)==0&&~logical(c3Prep.run_episode_called)&& ...
    ~logical(c3Prep.TEST_accessed)&&strcmpi(c3Prep.snapshot_sha256,lock.upstream_refs.c3_dev72_prepared_snapshot.sha256), ...
    'C5:C3Prepare','Frozen C3 no-Plant preparation identity changed.');
c3Pack=load(lock.upstream_refs.c3_dev72_prepared_snapshot.path,'cfg','opts','W0','modelIdentity','sceneIdentity','sourceIdentity');
assert(all(isfield(c3Pack,{'cfg','opts','W0','modelIdentity','sceneIdentity','sourceIdentity'})), ...
    'C5:C3Snapshot','C3 prepared snapshot is incomplete.');
modelPath=source_role(lock.shared_input_files,'model_mat'); modelPack=load(modelPath,'model');
assert(isfield(modelPack,'model')&&isstruct(modelPack.model),'C5:Model','Frozen model missing.');
model=modelPack.model; W0=double(model.output_W);
assert(strcmp(char(model.model_id),'DSSM14')&&double(model.seed)==2026102001&& ...
    double(model.selected_step)==60000&&double(model.input_dim)==14&&double(model.window)==32&& ...
    isequal(size(W0),[33,3])&&all(isfinite(W0(:)))&&all(abs(W0(:))<=60)&& ...
    strcmpi(hash_bytes(typecast(W0(:),'uint8')),lock.candidate_identity.W0_sha256)&& ...
    strcmpi(hash_normalizer_arrays(model),lock.candidate_identity.normalizer_arrays_sha256), ...
    'C5:ModelIdentity','Frozen DSSM14/W0/normalizer identity changed.');
assert(isequaln(cfg,c3Pack.cfg),'C5:ConfigChanged','C5 config differs from frozen C3.');
opts=position_only_search_options(cfg,model,'FEATURE',12,1);
opts.position_delayed_prediction_enabled=true; opts.position_coordinate_mask=[1;1;0];
assert(isfield(c3Pack.opts,'position_delayed_prediction_enabled')&& ...
    ~isfield(c3Pack.opts,'position_coordinate_mask')&& ...
    isequaln(rmfield(opts,'position_coordinate_mask'),c3Pack.opts), ...
    'C5:OptsChanged','C5 opts must equal C3 opts except for position_coordinate_mask=[1;1;0].');
assert(isequal(W0,double(c3Pack.W0))&& ...
    strcmpi(c3Pack.modelIdentity.W0_sha256,lock.candidate_identity.W0_sha256)&& ...
    strcmpi(c3Pack.modelIdentity.normalizer_arrays_sha256,lock.candidate_identity.normalizer_arrays_sha256), ...
    'C5:C3Model','C3 snapshot model identity differs from the frozen C5 identity.');

% Require the separately run Python/MATLAB synthetic formula/helper check before preparation.
syntheticPath=fullfile(here,'C5_ABLATION_CROSSLANG_RESULT_DEV72_v2.json');
fixturePath=fullfile(here,'C5_ABLATION_CROSSLANG_FIXTURE_v2.json');
assert(isfile(syntheticPath)&&isfile(fixturePath),'C5:SyntheticMissing', ...
    'C5 cross-language synthetic result and fixture are required before preparation.');
synthetic=jsondecode(fileread(syntheticPath));
helperRefs=lock.active_source_inventory(strcmp({lock.active_source_inventory.role},'prediction_helper'));
assert(numel(helperRefs)==1&&strcmp(synthetic.schema,'C5_MATCHED_ABLATION_CROSSLANG_RESULT_V1')&& ...
    strcmp(synthetic.status,'PASS_SYNTHETIC_CROSSLANGUAGE_ONLY')&& ...
    strcmp(synthetic.variant_id,contract.variant_id)&& ...
    strcmp(synthetic.ablation_mode,contract.ablation_mode)&& ...
    logical(synthetic.actual_weight_update_enabled)==logical(contract.actual_weight_update_enabled)&& ...
    ~logical(synthetic.actual_prediction_gradient_enabled)&&logical(synthetic.legacy_stage1_update_enabled)&& ...
    ~logical(synthetic.plant_or_real_data_used)&&double(synthetic.tolerance_abs)==2e-12&& ...
    strcmpi(synthetic.fixture_sha256,sha256_file(fixturePath))&& ...
    strcmpi(synthetic.matlab_helper_sha256,helperRefs.sha256)&& ...
    strcmpi(synthetic.python_kernel_sha256,lock.source_files.python_kernel.sha256), ...
    'C5:Synthetic','C5 cross-language synthetic result/source identity is not PASS.');

% Clone the complete C3 DEV72 identity structure; no old raw MAT is loaded here.
assert(numel(c3Pack.sceneIdentity)==72&&isequal(string({c3Pack.sceneIdentity.scene_id}).',string(lock.scene_ids_all_72(:))), ...
    'C5:SceneIdentityOrder','C3 prepared identity must contain the exact original 72-scene order.');
sceneIdentity=repmat(c3Pack.sceneIdentity(1),1,72);
for k=1:72
    row=lock.scenes(k); ix=find(strcmp({c3Pack.sceneIdentity.scene_id},row.scene_id)); c3ref=row.C3_reference;
    assert(numel(ix)==1&&strcmp(row.scene_id,lock.scene_ids_all_72{k})&& ...
        same_path(row.B_source.path,c3Pack.sceneIdentity(ix).B_raw_path)&& ...
        strcmpi(row.B_source.sha256,c3Pack.sceneIdentity(ix).B_raw_sha256)&& ...
        same_path(c3ref.raw_path,c3Pack.sceneIdentity(ix).C3_raw_path)&& ...
        strcmpi(c3ref.raw_sha256,c3Pack.sceneIdentity(ix).C3_raw_sha256), ...
        'C5:SceneIdentityBinding','Locked physical B/C3 identity differs for %s.',row.scene_id);
    verify_file(row.B_source.path,row.B_source.sha256);
    verify_file(c3ref.raw_path,c3ref.raw_sha256); verify_file(c3ref.run_status_path,c3ref.run_status_sha256);
    verify_file(c3ref.run_start_path,c3ref.run_start_sha256);
    verify_file(c3ref.first_plant_step_marker_path,c3ref.first_plant_step_marker_sha256);
    c3status=jsondecode(fileread(c3ref.run_status_path));
    assert(strcmp(c3status.status,'RUN_COMPLETE_RAW_PENDING_AUDIT')&&strcmp(c3status.log_status,'STABLE')&& ...
        double(c3status.plant_calls)==1&&strcmpi(c3status.raw_sha256,c3ref.raw_sha256), ...
        'C5:C3ReferenceStatus','C3 comparator evidence changed for %s.',row.scene_id);
    sceneIdentity(k)=c3Pack.sceneIdentity(ix);
end
reusePath=lock.source_files.reuse12_binding.path; verify_file(reusePath,lock.source_files.reuse12_binding.sha256);
reuse=jsondecode(fileread(reusePath));
assert(strcmp(reuse.schema,'C5_MATCHED_ABLATION_DEV72_REUSE12_BINDING_V2')&& ...
    strcmp(reuse.state,'PARENT_AUDITED_SCREEN12_REUSE_ONLY_V2')&&strcmp(reuse.variant_id,contract.variant_id)&& ...
    isequal(string({reuse.records.scene_id}).',string(lock.scene_ids_reuse_12(:)))&&numel(reuse.records)==12, ...
    'C5:Reuse12Binding','The twelve reused C5 screen identities/order changed.');
for k=1:12
    rr=reuse.records(k);
    verify_file(rr.raw_path,rr.raw_sha256); verify_file(rr.run_status_path,rr.run_status_sha256);
    verify_file(rr.run_start_path,rr.run_start_sha256); verify_file(rr.attempt_started_marker_path,rr.attempt_started_marker_sha256);
    verify_file(rr.first_plant_step_marker_path,rr.first_plant_step_marker_sha256);
    assert(double(rr.event_count)==1968&&strcmp(rr.audit_status,'PASS_C5_MATCHED_ABLATION_SCREEN12_ALL_EVENTS'), ...
        'C5:Reuse12Audit','Reused screen12 item lacks its complete parent audit: %s.',rr.scene_id);
end

corePath=fullfile(here,'run_dl1018_closed_loop.m'); helperPath=fullfile(here,'delayed_prediction_step_candidate.m');
checkcodeRows=struct('path',{},'id',{},'line',{},'message',{});
for p={corePath,fullfile(here,'run_episode_dl1018.m'),helperPath}
    rows=checkcode(p{1},'-id');
    for j=1:numel(rows), checkcodeRows(end+1)=struct('path',p{1},'id',rows(j).id, ...
            'line',rows(j).line,'message',rows(j).message); end %#ok<AGROW>
end
assert(logical(opts.stage1_position_runtime.update_enabled)&&logical(opts.position_delayed_prediction_enabled), ...
    'C5Ablation:ModeFlags','Stage-1 update and delayed-prediction branch must remain enabled.');
sourceIdentity=struct('variant_id',contract.variant_id,'ablation_mode',contract.ablation_mode, ...
    'actual_weight_update_enabled',logical(contract.actual_weight_update_enabled), ...
    'actual_prediction_gradient_enabled',false, ...
    'legacy_stage1_update_enabled',true,'active_paths',{arrayfun(@(x)char(x.path),active,'UniformOutput',false)}, ...
    'active_sha256',{arrayfun(@(x)char(x.sha256),active,'UniformOutput',false)}, ...
    'which_checks',numel(active),'c5_core_path',corePath,'c5_core_sha256',sha256_file(corePath), ...
    'prediction_helper_sha256',sha256_file(helperPath));
modelIdentity=c3Pack.modelIdentity; modelIdentity.W0_sha256=lock.candidate_identity.W0_sha256;
save(snapshotPath,'cfg','opts','W0','modelIdentity','sceneIdentity','sourceIdentity','-v7.3');
result=struct('schema','C5_MATCHED_ABLATION_DEV72_PREPARE_RESULT_V2','status','PREPARED_C5_MATCHED_ABLATION_DEV72_NO_PLANT_WAIT_PARENT_RELEASE_V2', ...
    'created_utc',utc_now(),'input_lock_path',lockPath,'input_lock_sha256',sha256_file(lockPath), ...
    'contract_path',contractPath,'contract_sha256',sha256_file(contractPath), ...
    'snapshot_path',snapshotPath,'snapshot_sha256',sha256_file(snapshotPath), ...
    'source_identity',sourceIdentity,'model_identity',modelIdentity,'scene_identity',sceneIdentity, ...
    'variant_id',contract.variant_id,'ablation_mode',contract.ablation_mode, ...
    'legacy_stage1_update_enabled',true,'actual_weight_update_enabled',logical(contract.actual_weight_update_enabled), ...
    'actual_prediction_gradient_enabled',false, ...
    'coordinate_mask',[1 1 0],'pcf_auxiliary_enabled',true,'scene_ids_all_72',{contract.scene_ids_all_72},'scene_ids_remaining_60',{contract.scene_ids_remaining_60},'scene_ids_reuse_12',{contract.scene_ids_reuse_12}, ...
    'first_scene_id',contract.first_scene_id,'reuse12_binding_sha256',sha256_file(reusePath),'which_checks',numel(active),'checkcode',checkcodeRows, ...
    'synthetic_check_required',true,'synthetic_check_path',lock.source_files.synthetic_check.path, ...
    'synthetic_result_sha256',sha256_file(syntheticPath),'fixture_sha256',sha256_file(fixturePath), ...
    'plant_calls',0,'run_episode_called',false,'training_steps',0,'optimizer_steps',0, ...
    'parameter_or_seed_search',false,'new_B_sorties',0,'TEST_accessed',false);
write_json_new(resultPath,result);
end

function add_active_paths(items)
for k=1:numel(items), [~,~,ext]=fileparts(char(items(k).path)); if strcmpi(ext,'.m'), addpath(fileparts(char(items(k).path)),'-end'); end, end
end
function path=source_path(items,name)
idx=[]; for k=1:numel(items), [~,n,e]=fileparts(char(items(k).path)); if strcmpi([n e],name), idx(end+1)=k; end, end %#ok<AGROW>
assert(numel(idx)==1,'C5:SourceName','Expected one locked source %s.',name); path=char(items(idx).path);
end
function path=source_role(items,role)
idx=find(strcmpi({items.role},role));
assert(numel(idx)==1,'C5:SourceRole','Expected one shared input role %s.',role); path=char(items(idx).path);
end
function verify_ref(item), verify_file(item.path,item.sha256); end
function verify_file(path,expected)
assert(isfile(path),'C5:MissingFile','Missing frozen file: %s.',path);
assert(strcmpi(sha256_file(path),expected),'C5:SHA','SHA-256 mismatch: %s.',path);
end
function h=sha256_file(path)
md=java.security.MessageDigest.getInstance('SHA-256'); fid=fopen(path,'r'); assert(fid>=0,'C5:ReadFile','Cannot read %s.',path); c=onCleanup(@()fclose(fid)); %#ok<NASGU>
while true, b=fread(fid,8*1024*1024,'*uint8'); if isempty(b), break; end, md.update(b); end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
function h=hash_bytes(bytes)
md=java.security.MessageDigest.getInstance('SHA-256'); md.update(typecast(uint8(bytes(:)),'int8'));
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
function h=hash_normalizer_arrays(model)
md=java.security.MessageDigest.getInstance('SHA-256');
for name={'input_mu','input_sigma'}, field=name{1}; a=reshape(double(model.(field)),1,[]);
    assert(numel(a)==14&&all(isfinite(a)),'C5:NormalizerShape','Invalid %s.',field);
    header=[field char(0) '((1, 14), ''float64'')' char(0)];
    md.update(typecast(uint8(unicode2native(header,'UTF-8')),'int8')); md.update(typecast(a(:),'int8'));
end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
function tf=same_path(a,b), tf=strcmpi(char(java.io.File(a).getCanonicalPath()),char(java.io.File(b).getCanonicalPath())); end
function write_json_new(path,value)
assert(~isfile(path),'C5:NoOverwrite','Refusing to overwrite %s.',path); fid=fopen(path,'w'); assert(fid>=0,'C5:Write','Cannot create %s.',path); c=onCleanup(@()fclose(fid)); fwrite(fid,jsonencode(value),'char');
end
function t=utc_now(), t=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z''')); end
