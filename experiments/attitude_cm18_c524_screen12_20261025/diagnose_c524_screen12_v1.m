function result = diagnose_c524_screen12_v1()
% Read-only feature-support and compensation-scale diagnosis for the 12 runs.
here=fileparts(mfilename('fullpath')); repoRoot=fileparts(fileparts(here));
reportDir=fullfile(repoRoot,'reports','attitude_cm18_c524_screen12_20261025');
jsonPath=fullfile(reportDir,'C524_SCREEN12_MECHANISM_DIAGNOSIS_v1.json');
mdPath=fullfile(reportDir,'C524_SCREEN12_MECHANISM_DIAGNOSIS_v1.md');
assert(~isfile(jsonPath)&&~isfile(mdPath),'C524Diagnosis:NoOverwrite','Diagnosis outputs already exist.');
binding=jsondecode(fileread(fullfile(here,'C524_SCREEN12_BINDING_v1.json')));
modelPack=load(binding.model_path,'model'); model=modelPack.model;
mu=reshape(double(model.input_mean),1,[]); sigma=reshape(double(model.input_std),1,[]);
rows=repmat(struct('scene_id','','group','','event_count',0, ...
    'feature_any_abs_z_gt4_rate',0,'feature_any_abs_z_gt8_rate',0, ...
    'feature_any_abs_z_gt16_rate',0,'feature_max_abs_z',0,'feature_p95_abs_z',0, ...
    'feature_p95_abs_z_per_feature',[],'output_raw_rms_rad_s2',[], ...
    'output_raw_p95_abs_rad_s2',[],'output_clip_event_rate',0, ...
    'CM18_compensation_torque_rms_Nm',0,'C5_RBF_compensation_torque_rms_Nm',0), ...
    numel(binding.scene_ids),1);
allZ=[]; allRaw=[]; allClipped=0; allEvents=0; groups=cell(numel(binding.scene_ids),1);
for k=1:numel(binding.scene_ids)
    sceneId=char(binding.scene_ids{k}); auditPath=fullfile(reportDir,'scene_audits',[sceneId '_C524_AUDIT_v1.json']);
    audit=jsondecode(fileread(auditPath));
    pack=load(audit.candidate_raw_path,'log'); c=pack.log;
    base=load(audit.c5_rbf_raw_path,'log'); r=base.log;
    ev=logical(c.cm18_event_flag(:)); X=double(c.cm18_event_input_18(ev,:));
    raw=double(c.cm18_event_raw_acceleration_rad_s2(ev,:));
    clipped=double(c.cm18_event_clipped_acceleration_rad_s2(ev,:));
    assert(size(X,2)==18&&size(raw,2)==3&&all(isfinite([X(:);raw(:);clipped(:)])), ...
        'C524Diagnosis:EventData','CM18 event inputs/outputs are incomplete for %s.',sceneId);
    Z=(X-mu)./sigma; absZ=abs(Z); perEventMax=max(absZ,[],2);
    clipEvent=any(abs(raw-clipped)>1e-12,2);
    cTau=double(c.cm18_compensation_torque_held_Nm);
    rTau=double(r.attitude_rbf_compensation_torque_Nm);
    group=scene_group(sceneId); groups{k}=group;
    rows(k)=struct('scene_id',sceneId,'group',group,'event_count',size(X,1), ...
        'feature_any_abs_z_gt4_rate',mean(perEventMax>4), ...
        'feature_any_abs_z_gt8_rate',mean(perEventMax>8), ...
        'feature_any_abs_z_gt16_rate',mean(perEventMax>16), ...
        'feature_max_abs_z',max(absZ(:)),'feature_p95_abs_z',percentile(perEventMax,95), ...
        'feature_p95_abs_z_per_feature',arrayfun(@(j)percentile(absZ(:,j),95),1:18), ...
        'output_raw_rms_rad_s2',sqrt(mean(raw.^2,1)), ...
        'output_raw_p95_abs_rad_s2',arrayfun(@(j)percentile(abs(raw(:,j)),95),1:3), ...
        'output_clip_event_rate',mean(clipEvent), ...
        'CM18_compensation_torque_rms_Nm',sqrt(mean(sum(cTau.^2,2))), ...
        'C5_RBF_compensation_torque_rms_Nm',sqrt(mean(sum(rTau.^2,2))));
    allZ=[allZ;absZ]; %#ok<AGROW>
    allRaw=[allRaw;raw]; %#ok<AGROW>
    allClipped=allClipped+sum(clipEvent); allEvents=allEvents+numel(clipEvent);
end
summary=struct('scene_count',numel(rows),'event_count',allEvents, ...
    'event_any_feature_abs_z_gt4_rate',mean(max(allZ,[],2)>4), ...
    'event_any_feature_abs_z_gt8_rate',mean(max(allZ,[],2)>8), ...
    'event_any_feature_abs_z_gt16_rate',mean(max(allZ,[],2)>16), ...
    'feature_max_abs_z',max(allZ(:)), ...
    'feature_p95_abs_z_per_feature',arrayfun(@(j)percentile(allZ(:,j),95),1:18), ...
    'output_raw_rms_rad_s2',sqrt(mean(allRaw.^2,1)), ...
    'output_clip_event_rate',allClipped/allEvents);
groupLabels={'W09_W14_HIGH_FREQUENCY','W15_NO_WIND','OTHER_WIND'};
groupRows=struct('group',{},'scene_count',{},'event_any_feature_abs_z_gt4_rate',{}, ...
    'event_any_feature_abs_z_gt8_rate',{},'event_any_feature_abs_z_gt16_rate',{}, ...
    'feature_max_abs_z',{},'output_clip_event_rate',{},'CM18_compensation_torque_rms_Nm_mean',{}, ...
    'C5_RBF_compensation_torque_rms_Nm_mean',{});
for g=1:numel(groupLabels)
    ix=strcmp(groups,groupLabels{g}); z=[]; rawClip=0; evCount=0;
    for k=find(ix(:)).'
        audit=jsondecode(fileread(fullfile(reportDir,'scene_audits',[rows(k).scene_id '_C524_AUDIT_v1.json'])));
        p=load(audit.candidate_raw_path,'log'); ev=logical(p.log.cm18_event_flag(:));
        X=double(p.log.cm18_event_input_18(ev,:)); z=[z;abs((X-mu)./sigma)]; %#ok<AGROW>
        a=double(p.log.cm18_event_raw_acceleration_rad_s2(ev,:)); b=double(p.log.cm18_event_clipped_acceleration_rad_s2(ev,:));
        rawClip=rawClip+sum(any(abs(a-b)>1e-12,2)); evCount=evCount+size(a,1);
    end
    if isempty(z), z=nan(1,18); end
    groupRows(g)=struct('group',groupLabels{g},'scene_count',sum(ix), ...
        'event_any_feature_abs_z_gt4_rate',mean(max(z,[],2)>4), ...
        'event_any_feature_abs_z_gt8_rate',mean(max(z,[],2)>8), ...
        'event_any_feature_abs_z_gt16_rate',mean(max(z,[],2)>16), ...
        'feature_max_abs_z',max(z(:)),'output_clip_event_rate',rawClip/max(evCount,1), ...
        'CM18_compensation_torque_rms_Nm_mean',mean([rows(ix).CM18_compensation_torque_rms_Nm]), ...
        'C5_RBF_compensation_torque_rms_Nm_mean',mean([rows(ix).C5_RBF_compensation_torque_rms_Nm]));
end
result=struct('schema','CM18_C5_24_SCREEN12_MECHANISM_DIAGNOSIS_V1','status','PASS', ...
    'created_utc',utc_now(),'model_id',binding.model_id,'model_sha256',binding.model_sha256, ...
    'normalizer_feature_order','X18 runtime order from the frozen CM18 training contract', ...
    'overall',summary,'groups',groupRows,'scenes',rows, ...
    'interpretation','Standardized feature excursions describe support shift relative to TRAIN normalization; they do not establish causation. The model is fixed inference with no online weight updates; the matched RBF baseline adapts online.');
write_json_new(jsonPath,result);
lines={'# C5_24 闭环分布与输出诊断';'';'诊断只读 12 场已完成日志，不启动 Plant。'; ...
    sprintf('- 全部 CM18 事件数：%d；任一归一化特征 |z|>4 / >8 / >16：%.2f%% / %.2f%% / %.2f%%。', ...
        allEvents,100*summary.event_any_feature_abs_z_gt4_rate,100*summary.event_any_feature_abs_z_gt8_rate,100*summary.event_any_feature_abs_z_gt16_rate); ...
    sprintf('- 输出裁剪事件比例：%.2f%%；模型输入每事件 18 维，未做在线权重更新。',100*summary.output_clip_event_rate); ...
    '- `|z|` 超出训练标准化尺度说明闭环状态落在 TRAIN 支持域之外的风险；不能单凭该比例断言闭环退化的因果来源。'; ...
    '- 逐场与分组特征、输出 RMS 见 JSON；逐场闭环误差见配对 CSV。'};
write_text_new(mdPath,strjoin(lines,newline));
fprintf('C524_DIAGNOSIS_PASS; event_count=%d; OOD4=%.3f; OOD8=%.3f; clip=%.3f\n', ...
    allEvents,summary.event_any_feature_abs_z_gt4_rate,summary.event_any_feature_abs_z_gt8_rate,summary.output_clip_event_rate);
end

function g=scene_group(sceneId)
token=regexp(sceneId,'_W(\d+)$','tokens','once'); wind=str2double(token{1});
if wind==15, g='W15_NO_WIND'; elseif wind>=9&&wind<=14, g='W09_W14_HIGH_FREQUENCY'; else, g='OTHER_WIND'; end
end
function q=percentile(x,p)
x=sort(double(x(:))); idx=max(1,min(numel(x),ceil((p/100)*numel(x)))); q=x(idx);
end
function write_json_new(path,value)
fid=fopen(path,'w'); assert(fid>=0,'C524Diagnosis:Write','Cannot create %s.',path); c=onCleanup(@()fclose(fid)); %#ok<NASGU>
fwrite(fid,jsonencode(value),'char');
end
function write_text_new(path,value)
fid=fopen(path,'w'); assert(fid>=0,'C524Diagnosis:Write','Cannot create %s.',path); c=onCleanup(@()fclose(fid)); %#ok<NASGU>
fwrite(fid,value,'char');
end
function t=utc_now()
t=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z'''));
end
