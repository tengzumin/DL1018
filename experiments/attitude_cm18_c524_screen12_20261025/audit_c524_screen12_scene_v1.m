function result = audit_c524_screen12_scene_v1(sceneId)
% Independent read-only audit and paired scoring for one completed screen scene.
here=fileparts(mfilename('fullpath')); repoRoot=fileparts(fileparts(here));
reportRoot=fullfile(repoRoot,'reports','attitude_cm18_c524_screen12_20261025','scene_audits');
if ~isfolder(reportRoot), mkdir(reportRoot); end
bindingPath=fullfile(here,'C524_SCREEN12_BINDING_v1.json');
bindingSha=sha256_file(bindingPath); binding=jsondecode(fileread(bindingPath));
sceneId=char(sceneId); rows=binding.scene_rows; ix=find(strcmp({rows.scene_id},sceneId));
assert(numel(ix)==1,'C524Audit:Scene','Scene is absent or duplicated in the frozen binding.');
row=rows(ix); attempt=fullfile(here,'runs',sceneId,'attempt_01');
rawPath=fullfile(attempt,'raw_run.mat'); startPath=fullfile(attempt,'run_start.mat');
statusPath=fullfile(attempt,'run_status.json'); markerPath=fullfile(attempt,'first_plant_step.marker');
outPath=fullfile(reportRoot,[sceneId '_C524_AUDIT_v1.json']);
assert(~isfile(outPath),'C524Audit:NoOverwrite','Refusing to overwrite prior scene audit.');
assert(isfile(rawPath)&&isfile(startPath)&&isfile(statusPath)&&isfile(markerPath), ...
    'C524Audit:Evidence','Completed run evidence is incomplete.');
status=jsondecode(fileread(statusPath)); rawSha=sha256_file(rawPath);
startPack=load(startPath,'runStart'); raw=load(rawPath,'log','scene','runStart','runIdentity');
assert(strcmp(status.status,'RUN_COMPLETE_PENDING_AUDIT')&&strcmp(status.log_status,'STABLE')&& ...
    isempty(char(status.safety_stop_reason))&&status.transitions==20000&&status.state_samples==20001&& ...
    status.plant_calls==1&&status.training_steps==0&&status.optimizer_steps==0&&~status.TEST_accessed&& ...
    strcmpi(status.raw_sha256,rawSha)&&strcmpi(status.binding_sha256,bindingSha)&& ...
    isequaln(startPack.runStart,raw.runStart)&&contains(fileread(markerPath),'first_plant_transition=1'), ...
    'C524Audit:RunnerEvidence','Run status, saved start, raw hash, or first-Plant marker is invalid.');
assert(strcmp(raw.runIdentity.schema,'CM18_C5_24_SCREEN12_RUN_IDENTITY_V1')&& ...
    strcmp(raw.runIdentity.scene_id,sceneId)&&strcmp(raw.runIdentity.candidate,'C5_POSITION_C5_24_ATTITUDE')&& ...
    strcmpi(raw.runIdentity.binding_sha256,bindingSha)&&strcmpi(raw.runIdentity.model_sha256,binding.model_sha256)&& ...
    strcmpi(raw.runIdentity.c5_raw_sha256,row.c5_raw_sha256)&&strcmpi(raw.runIdentity.b_raw_sha256,row.b_raw_sha256)&& ...
    strcmp(raw.scene.scene_id,sceneId)&&raw.runIdentity.training_steps==0&& ...
    raw.runIdentity.optimizer_steps==0&&~raw.runIdentity.TEST_accessed, ...
    'C524Audit:RawIdentity','Raw identity does not match the frozen candidate/scene/baselines.');
log=raw.log; n=20000; dt=.001;
required={'time','transition_time','state','reference','filtered_attitude_reference', ...
    'motor_saturated','generalized_clipped','tilt_limited','status','last_transition','safety_stop_reason', ...
    'cm18_attitude_enabled','cm18_event_flag','cm18_event_count','cm18_rbf_attitude_runtime_enabled', ...
    'cm18_rbf_attitude_output_enabled','cm18_rbf_attitude_update_enabled', ...
    'attitude_rbf_compensation_torque_Nm','rbf_update_flag','rbf_output_raw','rbf_output_held'};
assert(all(isfield(log,required)),'C524Audit:LogFields','Candidate log lacks required dynamics/safety fields.');
assert(strcmp(log.status,'STABLE')&&log.last_transition==n&&isempty(char(log.safety_stop_reason))&& ...
    logical(log.cm18_attitude_enabled)&&~logical(log.cm18_rbf_attitude_runtime_enabled)&& ...
    ~logical(log.cm18_rbf_attitude_output_enabled)&&~logical(log.cm18_rbf_attitude_update_enabled)&& ...
    ~logical(log.attitude_fusion_enabled)&&~logical(log.attitude_head_enabled)&& ...
    log.cm18_event_count==1999&&sum(log.cm18_event_flag)==1999&& ...
    ~any(log.rbf_update_flag(:))&&all(log.rbf_output_raw(:)==0)&&all(log.rbf_output_held(:)==0)&& ...
    all(log.attitude_rbf_compensation_torque_Nm(:)==0), ...
    'C524Audit:ControllerMode','CM18 is not active alone, RBF is not fully off, or the run was incomplete.');
assert(isequal(size(log.time),[n+1,1])&&isequal(size(log.transition_time),[n,1])&& ...
    isequal(size(log.state),[n+1,12])&&isequal(size(log.reference.position),[n+1,3])&& ...
    isequal(size(log.filtered_attitude_reference),[n,3])&& ...
    max(abs(diff(log.time)-dt))<1e-12&&abs(log.time(end)-20)<1e-12&& ...
    all(isfinite(log.state(:)))&&all(isfinite(log.reference.position(:))), ...
    'C524Audit:Timeline','Candidate timeline or state/reference arrays are malformed.');
eventRows=find(log.cm18_event_flag(:));
assert(isequal(eventRows(:),(11:10:n).')&& ...
    max(abs(log.transition_time(eventRows)-((eventRows-1)*dt)))<1e-12, ...
    'C524Audit:EventSchedule','CM18 split-event schedule differs from the frozen 100-Hz contract.');

c5=load(row.c5_raw_path,'log','scene','runIdentity');
b=load(row.b_raw_path,'log','scene');
bScene=b.scene; bSceneId=char(bScene.scene_id);
if row.b_scene_id_alias
    assert(strcmp(bSceneId,[sceneId '_ACC_FIX_V1']),'C524Audit:BAlias','Original B legacy alias differs from binding.');
    bScene.scene_id=sceneId;
else
    assert(strcmp(bSceneId,sceneId),'C524Audit:BScene','Original B scene ID differs from binding.');
end
assert(isequaln(c5.scene,raw.scene)&&isequaln(bScene,raw.scene)&& ...
    strcmp(c5.runIdentity.candidate,'C5_AXIS_MIXED_COORDINATE_M110'), ...
    'C524Audit:BaselineScene','Baseline payloads do not match this candidate scene.');
candidateMetrics=score_log(log,n);
c5Metrics=score_log(c5.log,n); bMetrics=score_log(b.log,n);
result=struct('schema','CM18_C5_24_SCREEN12_SCENE_AUDIT_V1','status','PASS', ...
    'scene_id',sceneId,'created_utc',utc_now(),'binding_sha256',bindingSha, ...
    'candidate_raw_path',rawPath,'candidate_raw_sha256',rawSha, ...
    'c5_rbf_raw_path',row.c5_raw_path,'c5_rbf_raw_sha256',row.c5_raw_sha256, ...
    'original_b_raw_path',row.b_raw_path,'original_b_raw_sha256',row.b_raw_sha256, ...
    'original_b_scene_id_raw',bSceneId,'original_b_scene_id_alias',row.b_scene_id_alias, ...
    'candidate_C5_position_C5_24_attitude',candidateMetrics, ...
    'matched_C5_position_original_RBF',c5Metrics,'original_B_overall_reference',bMetrics, ...
    'candidate_vs_C5_position_RBF_position_Q_delta_m', ...
        candidateMetrics.position_Q_rmse_m-c5Metrics.position_Q_rmse_m, ...
    'candidate_vs_original_B_position_Q_delta_m', ...
        candidateMetrics.position_Q_rmse_m-bMetrics.position_Q_rmse_m);
write_json_new(outPath,result); result.audit_path=outPath;
fprintf('C524_SCENE_AUDIT_PASS; scene=%s; candidate_Q=%.9g m; C5_RBF_Q=%.9g m; B_Q=%.9g m; SO3=%.9g rad\n', ...
    sceneId,candidateMetrics.position_Q_rmse_m,c5Metrics.position_Q_rmse_m, ...
    bMetrics.position_Q_rmse_m,candidateMetrics.SO3_rmse_rad);
end

function m=score_log(log,n)
assert(all(isfield(log,{'state','reference','time','filtered_attitude_reference'})), ...
    'C524Audit:BaselineLog','Baseline log lacks state/reference fields.');
state=double(log.state); position=double(log.reference.position); t=double(log.time(:));
assert(size(state,1)==n+1&&size(state,2)>=12&&isequal(size(position),[n+1,3])&& ...
    numel(t)==n+1&&all(isfinite(state(:)))&&all(isfinite(position(:))), ...
    'C524Audit:BaselineShape','A baseline is incomplete or non-finite.');
pe=position(1:n,:)-state(1:n,1:3); posNorm=sqrt(sum(pe.^2,2));
m=struct('samples',n,'position_Q_rmse_m',sqrt(mean(sum(pe.^2,2))), ...
    'position_axis_rmse_m',sqrt(mean(pe.^2,1)),'position_peak_m',max(posNorm));
if isequal(size(log.filtered_attitude_reference),[n,3])
    ref=double(log.filtered_attitude_reference); actual=state(1:n,7:9);
    euler=atan2(sin(ref-actual),cos(ref-actual)); so3=zeros(n,1);
    for k=1:n
        Ra=rotation_zyx(actual(k,:)); Rr=rotation_zyx(ref(k,:)); Re=Ra.'*Rr;
        c=max(min((trace(Re)-1)/2,1),-1);
        s=.5*sqrt((Re(3,2)-Re(2,3))^2+(Re(1,3)-Re(3,1))^2+(Re(2,1)-Re(1,2))^2);
        so3(k)=atan2(s,c);
    end
    m.Euler_axis_rmse_rad=sqrt(mean(euler.^2,1)); m.SO3_rmse_rad=sqrt(mean(so3.^2));
    m.SO3_peak_rad=max(so3);
else
    m.Euler_axis_rmse_rad=[NaN NaN NaN]; m.SO3_rmse_rad=NaN; m.SO3_peak_rad=NaN;
end
m.peak_body_rate_rad_s=max(sqrt(sum(state(1:n,10:12).^2,2)));
if isfield(log,'motor_saturated'), m.motor_saturated_samples=sum(any(log.motor_saturated,2)); else, m.motor_saturated_samples=NaN; end
if isfield(log,'generalized_clipped'), m.generalized_clipped_samples=sum(any(log.generalized_clipped,2)); else, m.generalized_clipped_samples=NaN; end
if isfield(log,'tilt_limited'), m.tilt_limited_samples=sum(log.tilt_limited(:)); else, m.tilt_limited_samples=NaN; end
if isfield(log,'controller_call_time_s')&&~isempty(log.controller_call_time_s)
    q=double(log.controller_call_time_s(:)); q=q(isfinite(q));
    if isempty(q), m.controller_call_time_median_s=NaN; m.controller_call_time_p95_s=NaN;
    else, q=sort(q); m.controller_call_time_median_s=median(q); m.controller_call_time_p95_s=q(ceil(.95*numel(q))); end
else
    m.controller_call_time_median_s=NaN; m.controller_call_time_p95_s=NaN;
end
end
function R=rotation_zyx(e)
phi=e(1); theta=e(2); psi=e(3); c1=cos(phi); s1=sin(phi); c2=cos(theta); s2=sin(theta); c3=cos(psi); s3=sin(psi);
R=[c3*c2,c3*s2*s1-s3*c1,c3*s2*c1+s3*s1; ...
   s3*c2,s3*s2*s1+c3*c1,s3*s2*c1-c3*s1; -s2,c2*s1,c2*c1];
end
function h=sha256_file(path)
md=java.security.MessageDigest.getInstance('SHA-256'); fid=fopen(path,'r');
assert(fid>=0,'C524Audit:Read','Cannot read %s.',path); c=onCleanup(@()fclose(fid)); %#ok<NASGU>
while true, b=fread(fid,8*1024*1024,'*uint8'); if isempty(b), break; end, md.update(b); end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
function write_json_new(path,value)
fid=fopen(path,'w'); assert(fid>=0,'C524Audit:Write','Cannot create %s.',path); c=onCleanup(@()fclose(fid)); %#ok<NASGU>
fwrite(fid,jsonencode(value),'char');
end
function t=utc_now()
t=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z'''));
end
