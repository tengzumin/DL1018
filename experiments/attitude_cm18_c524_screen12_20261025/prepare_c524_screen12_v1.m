function binding = prepare_c524_screen12_v1()
% Freeze a 12-scene closed-loop screen for C5-24 replacing the attitude RBF.
here=fileparts(mfilename('fullpath')); repoRoot=fileparts(fileparts(here));
reportDir=fullfile(repoRoot,'reports','attitude_cm18_c524_screen12_20261025');
experimentDir=here; modelDir=fullfile(here,'models');
bindingPath=fullfile(here,'C524_SCREEN12_BINDING_v1.json');
taskbookPath=fullfile(reportDir,'C524_SCREEN12_TASKBOOK_v1.md');
assert(~isfile(bindingPath)&&~isfile(taskbookPath), ...
    'C524Prepare:NoOverwrite','Preparation outputs already exist; preserve them and do not replace.');
if ~isfolder(reportDir), mkdir(reportDir); end

sceneIds={'DL1018_DEV_T1_C01_W15','DL1018_DEV_T1_C00_W03','DL1018_DEV_T1_C15_W14', ...
    'DL1018_DEV_T1_C05_W06','DL1018_DEV_T2_C00_W04','DL1018_DEV_T2_C02_W15', ...
    'DL1018_VAL_T2_C15_W09','DL1018_DEV_T2_C06_W07','DL1018_DEV_T3_C00_W05', ...
    'DL1018_DEV_T3_C03_W15','DL1018_DEV_T3_C15_W14','DL1018_DEV_T3_C05_W02'};
c5Dir=fullfile(repoRoot,'experiments','position_axis_coordinate_c5_dev72_20261023');
c5SnapshotPath=fullfile(c5Dir,'C5_DEV72_PREPARED_CFG_OPTS_v3.mat');
firstPrepPath=fullfile(repoRoot,'reports','attitude_cm18_a1_20261024', ...
    'first_flight_preparation_v1','A1_FIRST_FLIGHT_PREPARATION_RESULT_v1.json');
remainingPrepPath=fullfile(repoRoot,'reports','attitude_cm18_a1_20261024', ...
    'screen12_remaining_v1','SCREEN12_REMAINING_PREPARATION_RESULT_v1.json');
manifestPath=fullfile(repoRoot,'reports','attitude_cm18_a1_20261024','CM18_A1_DEV_SCREEN12_v1.json');
exportReceiptPath=fullfile(modelDir,'export_receipt.json');
modelPath=fullfile(modelDir,'C5_24_model.mat');
enginePath=fullfile(repoRoot,'experiments','attitude_cm18_a1_20261024','run_cm18_closed_loop_v1.m');
forwardPath=fullfile(repoRoot,'experiments','attitude_cm18_a1_20261024','matlab','cm18_a1_forward_v1.m');
helperPath=fullfile(repoRoot,'experiments','attitude_cm18_a1_20261024','delayed_prediction_step_candidate.m');
verify_file(c5SnapshotPath,'842ef395569e675db6e139c2684d72b976946915e5e0a58b9b7f24ec10c1d24a');
verify_file(firstPrepPath,''); verify_file(remainingPrepPath,''); verify_file(manifestPath,'');
verify_file(exportReceiptPath,''); verify_file(modelPath,'18bfb15c89b3e516b158b86124fce72aad2733b56a7c50ef4209942a84f6c7f4');
verify_file(enginePath,''); verify_file(forwardPath,''); verify_file(helperPath,'');

first=jsondecode(fileread(firstPrepPath)); remaining=jsondecode(fileread(remainingPrepPath));
manifest=jsondecode(fileread(manifestPath)); exportReceipt=jsondecode(fileread(exportReceiptPath));
assert(strcmp(first.status,'PREPARED_A1_FIRST_FLIGHT_NO_PLANT_V1')&& ...
    strcmp(remaining.status,'PREPARED_SCREEN12_REMAINING_NO_PLANT_V1')&& ...
    strcmp(manifest.schema,'CM18_A1_FUTURE_DEVELOPMENT_SCREEN12_V1')&& ...
    isequal(sort(string({manifest.scenes.scene_id})),sort(string(sceneIds)))&& ...
    strcmp(manifest.first_engineering_scene,'DL1018_DEV_T1_C01_W15'), ...
    'C524Prepare:SceneManifest','The prior fixed screen-12 preparation or scene manifest changed.');
assert(strcmp(exportReceipt.status,'PASS')&&isfield(exportReceipt.branches,'C5_24')&& ...
    strcmpi(exportReceipt.branches.C5_24.model_mat_sha256,sha256_file(modelPath)), ...
    'C524Prepare:ModelExport','The exported C5_24 model differs from the parity-checked export receipt.');
assert(strcmpi(exportReceipt.branches.C5_24.checkpoint_sha256, ...
    '1562e243ec00447d86c3f155c3153b784610aa5ed0aa68b199dcece5ccc36efd'), ...
    'C524Prepare:Checkpoint','C5_24 checkpoint identity differs from the completed 60k training release.');

c5=load(c5SnapshotPath,'cfg','opts','sceneIdentity');
assert(numel(c5.sceneIdentity)==72,'C524Prepare:C5SceneSet','The frozen C5 snapshot must contain all 72 scenes.');
remainingRows=remaining.scene_rows;
rows=repmat(struct('scene_id','','c5_raw_path','','c5_raw_sha256','', ...
    'prepared_snapshot_path','','prepared_snapshot_sha256','', ...
    'b_raw_path','','b_raw_sha256','','b_payload_matches_c5',false, ...
    'b_has_run_identity',false,'b_scene_id_raw','','b_scene_id_alias',false),numel(sceneIds),1);
for k=1:numel(sceneIds)
    sceneId=sceneIds{k};
    if k==1
        c5RawPath=char(first.c5_raw_scene_path); c5RawSha=char(first.c5_raw_scene_sha256);
        snapPath=char(first.prepared_snapshot_path); snapSha=char(first.prepared_snapshot_sha256);
    else
        idx=find(strcmp({remainingRows.scene_id},sceneId));
        assert(numel(idx)==1,'C524Prepare:SceneBinding','Missing or duplicated C5 row for %s.',sceneId);
        row=remainingRows(idx); c5RawPath=char(row.baseline_C5_raw_path); c5RawSha=char(row.baseline_C5_raw_sha256);
        snapPath=char(row.prepared_snapshot_path); snapSha=char(row.prepared_snapshot_sha256);
    end
    verify_file(c5RawPath,c5RawSha); verify_file(snapPath,snapSha);
    s=find(strcmp({c5.sceneIdentity.scene_id},sceneId));
    assert(numel(s)==1,'C524Prepare:C5SceneIdentity','C5 scene identity is missing/duplicated for %s.',sceneId);
    identity=c5.sceneIdentity(s); verify_file(char(identity.B_raw_path),char(identity.B_raw_sha256));
    pack=load(snapPath,'cfg','opts','scene','sceneIdentity','sourceIdentity');
    c5Raw=load(c5RawPath,'scene','runIdentity','log');
    bRaw=load(char(identity.B_raw_path),'scene','log');
    bVariables=whos('-file',char(identity.B_raw_path));
    bHasRunIdentity=any(strcmp({bVariables.name},'runIdentity'));
    bSceneIdRaw=char(bRaw.scene.scene_id); bSceneAlias=strcmp(bSceneIdRaw,[sceneId '_ACC_FIX_V1']);
    bCanonicalScene=bRaw.scene; if bSceneAlias, bCanonicalScene.scene_id=sceneId; end
    assert(all(isfield(pack,{'cfg','opts','scene','sceneIdentity','sourceIdentity'}))&& ...
        isequaln(pack.cfg,c5.cfg)&&strcmp(char(pack.scene.scene_id),sceneId)&& ...
        strcmp(char(pack.sceneIdentity.scene_id),sceneId)&&isequaln(pack.sceneIdentity,identity)&& ...
        isequaln(pack.scene,c5Raw.scene)&&strcmp(char(c5Raw.runIdentity.candidate),'C5_AXIS_MIXED_COORDINATE_M110')&& ...
        isequal(double(c5Raw.runIdentity.coordinate_mask(:)),[1;1;0])&& ...
        (strcmp(bSceneIdRaw,sceneId)||bSceneAlias)&&isequaln(bCanonicalScene,pack.scene)&& ...
        isfield(bRaw,'log')&&isfield(bRaw.log,'state')&&isfield(bRaw.log,'reference'), ...
        'C524Prepare:Payload','C5/B raw data and prepared scene are not aligned for %s.',sceneId);
    rows(k)=struct('scene_id',sceneId,'c5_raw_path',c5RawPath,'c5_raw_sha256',lower(c5RawSha), ...
        'prepared_snapshot_path',snapPath,'prepared_snapshot_sha256',lower(snapSha), ...
        'b_raw_path',char(identity.B_raw_path),'b_raw_sha256',lower(char(identity.B_raw_sha256)), ...
        'b_payload_matches_c5',true,'b_has_run_identity',bHasRunIdentity, ...
        'b_scene_id_raw',bSceneIdRaw,'b_scene_id_alias',bSceneAlias);
end

pack0=load(rows(1).prepared_snapshot_path,'sourceIdentity'); source=pack0.sourceIdentity;
active=source.c5_active_source_inventory; shared=source.c5_shared_inputs;
assert(numel(active)==32&&numel(shared)==6,'C524Prepare:SourceInventory','C5 active/shared source inventory count changed.');
for k=1:numel(active), verify_file(char(active(k).path),char(active(k).sha256)); end
for k=1:numel(shared), verify_file(char(shared(k).path),char(shared(k).sha256)); end
for k=1:numel(rows)
    p=load(rows(k).prepared_snapshot_path,'sourceIdentity');
    assert(strcmpi(p.sourceIdentity.c5_active_source_inventory_sha256, ...
        source.c5_active_source_inventory_sha256),'C524Prepare:SourceDrift','C5 source inventory differs at %s.',rows(k).scene_id);
end

binding=struct('schema','CM18_C5_24_SCREEN12_BINDING_V1','status','PREPARED_NO_PLANT', ...
    'created_utc',utc_now(),'experiment_dir',experimentDir,'plant_calls',0,'training_steps',0, ...
    'optimizer_steps',0,'TEST_accessed',false,'scene_ids',{sceneIds},'scene_rows',rows, ...
    'model_id','C5_24_FINAL60000','model_checkpoint_sha256',exportReceipt.branches.C5_24.checkpoint_sha256, ...
    'model_path',modelPath,'model_sha256',sha256_file(modelPath), ...
    'model_export_receipt_path',exportReceiptPath,'model_export_receipt_sha256',sha256_file(exportReceiptPath), ...
    'c5_snapshot_path',c5SnapshotPath,'c5_snapshot_sha256',sha256_file(c5SnapshotPath), ...
    'c5_active_source_inventory_sha256',source.c5_active_source_inventory_sha256, ...
    'engine_path',enginePath,'engine_sha256',sha256_file(enginePath), ...
    'forward_path',forwardPath,'forward_sha256',sha256_file(forwardPath), ...
    'delayed_prediction_helper_path',helperPath,'delayed_prediction_helper_sha256',sha256_file(helperPath), ...
    'manifest_path',manifestPath,'manifest_sha256',sha256_file(manifestPath), ...
    'first_preparation_sha256',sha256_file(firstPrepPath), ...
    'remaining_preparation_sha256',sha256_file(remainingPrepPath), ...
    'runner_path',fullfile(here,'run_c524_screen12_v1.m'),'runner_sha256','');
assert(isfile(binding.runner_path),'C524Prepare:RunnerMissing','Create the isolated runner before preparation.');
binding.runner_sha256=sha256_file(binding.runner_path);
freeBytes=java.io.File(repoRoot).getFreeSpace();
assert(freeBytes>=30*1024^3,'C524Prepare:Disk','Less than 30 GiB remains; do not launch a flight.');
write_json_new(bindingPath,binding);
bindingSha=sha256_file(bindingPath);
taskbook=sprintf(['# C5_24 attitude-RBF replacement: fixed 12-scene screen\n\n' ...
    '- Status: prepared, no Plant calls.\n' ...
    '- Candidate: frozen C5_24 final-60k model replacing the attitude RBF.\n' ...
    '- Matched control: existing C5 position controller with its original RBF; reuse pinned raw logs.\n' ...
    '- Overall reference: original B raw logs; its scene payload is checked against the same frozen scene.\n' ...
    '- Legacy B scene ID suffix `_ACC_FIX_V1`, when present, is recorded and normalized only for payload identity comparison.\n' ...
    '- B24 is not used as original B.\n' ...
    '- Fixed scene order: %s\n' ...
    '- Maximum new closed-loop calls: 12; one per scene; no retry. First run the engineering scene, review its status, then run the remaining 11.\n' ...
    '- Position C5 config and active-source inventory are preserved; only attitude-RBF flags are disabled and CM18 inference is enabled.\n' ...
    '- No training, no TEST access, no parameter search. Output cap: 100 MiB per flight and 1 GiB total.\n' ...
    '- Binding SHA-256: `%s`\n' ...
    '- C5_24 checkpoint SHA-256: `%s`\n' ...
    '- C5_24 MAT SHA-256: `%s`\n' ...
    '- Original B and matched C5+RBF are reused as references; B-vs-candidate is overall comparison, C5+RBF-vs-candidate isolates the attitude-loop replacement within the C5 stack.\n'], ...
    strjoin(sceneIds,', '),bindingSha,binding.model_checkpoint_sha256,binding.model_sha256);
write_text_new(taskbookPath,taskbook);
fprintf('C524_SCREEN12_PREPARED_NO_PLANT; binding=%s; sha256=%s; scenes=%d\n',bindingPath,bindingSha,numel(sceneIds));
end

function verify_file(path,expected)
assert(isfile(path),'C524Prepare:MissingFile','Missing pinned file: %s.',path);
if ~isempty(expected), assert(strcmpi(sha256_file(path),expected),'C524Prepare:Hash','Hash mismatch: %s.',path); end
end
function h=sha256_file(path)
md=java.security.MessageDigest.getInstance('SHA-256'); fid=fopen(path,'r');
assert(fid>=0,'C524Prepare:Read','Cannot read %s.',path); c=onCleanup(@()fclose(fid)); %#ok<NASGU>
while true, b=fread(fid,8*1024*1024,'*uint8'); if isempty(b), break; end, md.update(b); end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
function write_json_new(path,value)
assert(~isfile(path),'C524Prepare:NoOverwrite','Refusing to overwrite %s.',path);
fid=fopen(path,'w'); assert(fid>=0,'C524Prepare:Write','Cannot create %s.',path); c=onCleanup(@()fclose(fid)); %#ok<NASGU>
fwrite(fid,jsonencode(value),'char');
end
function write_text_new(path,value)
assert(~isfile(path),'C524Prepare:NoOverwrite','Refusing to overwrite %s.',path);
fid=fopen(path,'w'); assert(fid>=0,'C524Prepare:Write','Cannot create %s.',path); c=onCleanup(@()fclose(fid)); %#ok<NASGU>
fwrite(fid,value,'char');
end
function t=utc_now()
t=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z'''));
end
