function result = run_c524_screen12_v1(sceneId,bindingPath,bindingSha256)
% Execute one scene of the fixed C5_24 attitude-RBF replacement screen.
if nargin~=3, error('C524Screen:Args','Pass scene ID, frozen binding path, and binding SHA-256.'); end
here=fileparts(mfilename('fullpath')); repoRoot=fileparts(fileparts(here));
sceneId=char(sceneId); bindingPath=char(bindingPath); bindingSha256=lower(char(bindingSha256));
assert(isfile(bindingPath)&&strcmpi(sha256_file(bindingPath),bindingSha256), ...
    'C524Screen:BindingHash','The frozen experiment binding is missing or changed.');
binding=jsondecode(fileread(bindingPath));
expectedIds={'DL1018_DEV_T1_C01_W15','DL1018_DEV_T1_C00_W03','DL1018_DEV_T1_C15_W14', ...
    'DL1018_DEV_T1_C05_W06','DL1018_DEV_T2_C00_W04','DL1018_DEV_T2_C02_W15', ...
    'DL1018_VAL_T2_C15_W09','DL1018_DEV_T2_C06_W07','DL1018_DEV_T3_C00_W05', ...
    'DL1018_DEV_T3_C03_W15','DL1018_DEV_T3_C15_W14','DL1018_DEV_T3_C05_W02'};
assert(strcmp(binding.schema,'CM18_C5_24_SCREEN12_BINDING_V1')&& ...
    strcmp(binding.status,'PREPARED_NO_PLANT')&&isequal(cellstr(string(binding.scene_ids(:))),expectedIds(:))&& ...
    binding.plant_calls==0&&binding.training_steps==0&&binding.optimizer_steps==0&&~binding.TEST_accessed&& ...
    strcmp(binding.model_id,'C5_24_FINAL60000')&&strcmpi(binding.runner_sha256,sha256_file([mfilename('fullpath') '.m']))&& ...
    any(strcmp(expectedIds,sceneId)), ...
    'C524Screen:Scope','Frozen binding, runner identity, or fixed scene scope is invalid.');
assert(strcmpi(binding.model_sha256,sha256_file(binding.model_path))&& ...
    strcmpi(binding.model_export_receipt_sha256,sha256_file(binding.model_export_receipt_path))&& ...
    strcmpi(binding.c5_snapshot_sha256,sha256_file(binding.c5_snapshot_path))&& ...
    strcmpi(binding.engine_sha256,sha256_file(binding.engine_path))&& ...
    strcmpi(binding.forward_sha256,sha256_file(binding.forward_path))&& ...
    strcmpi(binding.delayed_prediction_helper_sha256,sha256_file(binding.delayed_prediction_helper_path))&& ...
    strcmpi(binding.manifest_sha256,sha256_file(binding.manifest_path)), ...
    'C524Screen:SourceHash','A frozen model, source, or screen manifest changed.');
assert(java.io.File(repoRoot).getFreeSpace()>=30*1024^3+100*1024^2, ...
    'C524Screen:Disk','Less than 30 GiB plus one-flight output reserve is available.');
rows=binding.scene_rows; rowIx=find(strcmp({rows.scene_id},sceneId));
assert(numel(rows)==12&&numel(rowIx)==1,'C524Screen:SceneRow','Scene binding is missing or duplicated.');
row=rows(rowIx); verify_file(row.c5_raw_path,row.c5_raw_sha256);
verify_file(row.prepared_snapshot_path,row.prepared_snapshot_sha256);
verify_file(row.b_raw_path,row.b_raw_sha256);
assert(row.b_payload_matches_c5,'C524Screen:BaselineScene','Original B payload was not aligned to the frozen scene.');

c5=load(binding.c5_snapshot_path,'cfg','opts','sceneIdentity');
idx=find(strcmp({c5.sceneIdentity.scene_id},sceneId));
assert(numel(idx)==1,'C524Screen:C5Scene','Frozen C5 scene identity is missing or duplicated.');
pack=load(row.prepared_snapshot_path,'cfg','opts','scene','sceneIdentity','sourceIdentity');
c5Raw=load(row.c5_raw_path,'scene','runIdentity');
bRaw=load(row.b_raw_path,'scene','log');
bSceneIdRaw=char(bRaw.scene.scene_id); bCanonicalScene=bRaw.scene;
if row.b_scene_id_alias
    assert(strcmp(bSceneIdRaw,[sceneId '_ACC_FIX_V1']),'C524Screen:BAlias','B legacy scene ID alias changed.');
    bCanonicalScene.scene_id=sceneId;
else
    assert(strcmp(bSceneIdRaw,sceneId),'C524Screen:BSceneId','Original B scene ID differs from the frozen scene.');
end
assert(all(isfield(pack,{'cfg','opts','scene','sceneIdentity','sourceIdentity'}))&& ...
    isequaln(pack.cfg,c5.cfg)&&isequaln(pack.sceneIdentity,c5.sceneIdentity(idx))&& ...
    strcmp(char(pack.scene.scene_id),sceneId)&&isequaln(pack.scene,c5Raw.scene)&& ...
    isequaln(pack.scene,bCanonicalScene)&& ...
    strcmp(char(c5Raw.runIdentity.candidate),'C5_AXIS_MIXED_COORDINATE_M110')&& ...
    isequal(double(c5Raw.runIdentity.coordinate_mask(:)),[1;1;0]), ...
    'C524Screen:BaselinePayload','Scene, C5 preparation, C5 raw, or original B raw payload differs.');

active=pack.sourceIdentity.c5_active_source_inventory; shared=pack.sourceIdentity.c5_shared_inputs;
assert(numel(active)==32&&numel(shared)==6&& ...
    strcmpi(pack.sourceIdentity.c5_active_source_inventory_sha256,binding.c5_active_source_inventory_sha256), ...
    'C524Screen:SourceInventory','C5 active/shared source inventory changed.');
for k=1:numel(active), verify_file(char(active(k).path),char(active(k).sha256)); end
for k=1:numel(shared), verify_file(char(shared(k).path),char(shared(k).sha256)); end

originalOpts=load(binding.c5_snapshot_path,'opts'); originalOpts=originalOpts.opts;
opts=pack.opts; removable=intersect({'cm18_attitude_v1','r2e_first_plant_step_marker'},fieldnames(opts));
if ~isempty(removable), opts=rmfield(opts,removable); end
rbfFlags={'rbf_attitude_enabled','rbf_attitude_output_enabled','rbf_attitude_update_enabled'};
assert(all(isfield(opts,rbfFlags))&&all(isfield(originalOpts,rbfFlags)), ...
    'C524Screen:RbfFields','The matched C5 attitude flags are missing.');
for k=1:numel(rbfFlags), opts.(rbfFlags{k})=originalOpts.(rbfFlags{k}); end
assert(isequaln(opts,originalOpts)&&isequaln(pack.cfg,c5.cfg), ...
    'C524Screen:C5StackDrift','Prepared stack differs from original C5 outside the old A1 model/marker.');
for k=1:numel(rbfFlags)
    assert(islogical(opts.(rbfFlags{k}))&&isscalar(opts.(rbfFlags{k})), ...
        'C524Screen:RbfFlagType','RBF flag must be an explicit logical scalar.');
    opts.(rbfFlags{k})=false;
end
modelPackage=load(binding.model_path,'model');
assert(isfield(modelPackage,'model')&&isstruct(modelPackage.model), ...
    'C524Screen:Model','C5_24 model MAT does not contain the expected model struct.');
opts.cm18_attitude_v1=struct('enabled',true,'model',modelPackage.model);
attemptDir=fullfile(here,'runs',sceneId,'attempt_01');
runRoot=fullfile(here,'runs'); lockPath=fullfile(runRoot,'.c524_screen12_plant_lock');
assert(~isfolder(attemptDir)&&~isfile(attemptDir),'C524Screen:NoRetry','This scene attempt already exists; do not retry.');
if ~isfolder(runRoot), mkdir(runRoot); end
assert(java.io.File(lockPath).createNewFile(),'C524Screen:Busy','Another screen flight is active or an old lock remains.');
lockCleanup=onCleanup(@()delete_lock(lockPath)); %#ok<NASGU>
assert(~isfolder(attemptDir)&&~isfile(attemptDir),'C524Screen:NoRetry','Scene attempt appeared before lock acquisition.');
if ~isfolder(fileparts(attemptDir)), mkdir(fileparts(attemptDir)); end
mkdir(attemptDir);
attemptMarker=fullfile(attemptDir,'attempt_started.marker');
firstStepMarker=fullfile(attemptDir,'first_plant_step.marker');
runStartPath=fullfile(attemptDir,'run_start.mat'); rawOutPath=fullfile(attemptDir,'raw_run.mat');
statusPath=fullfile(attemptDir,'run_status.json'); opts.r2e_first_plant_step_marker=firstStepMarker;

add_active_paths(active); addpath(fullfile(repoRoot,'matlab','runtime'),'-end'); addpath(fullfile(repoRoot,'matlab','core'),'-end');
addpath(fileparts(source_path(active,'position_only_search_options.m')),'-begin');
addpath(fileparts(source_path(active,'position_only_search_head_step.m')),'-begin');
addpath(fileparts(source_path(active,'position_stage1_model_forward_v2.m')),'-begin');
addpath(fileparts(source_path(active,'run_dl1018_closed_loop.m')),'-begin');
addpath(fileparts(binding.engine_path),'-begin'); addpath(fileparts(binding.forward_path),'-begin');
clear run_cm18_closed_loop_v1 cm18_a1_forward_v1 delayed_prediction_step_candidate; rehash;
assert(same_path(which('run_cm18_closed_loop_v1'),binding.engine_path)&& ...
    same_path(which('cm18_a1_forward_v1'),binding.forward_path)&& ...
    same_path(which('delayed_prediction_step_candidate'),binding.delayed_prediction_helper_path), ...
    'C524Screen:RuntimePath','The frozen engine/helper resolved to an unexpected source file.');
for k=1:numel(active)
    if endsWith(lower(char(active(k).path)),'.m')
        [~,n]=fileparts(char(active(k).path)); expectedPath=char(active(k).path);
        if strcmp(n,'delayed_prediction_step_candidate'), expectedPath=binding.delayed_prediction_helper_path; end
        assert(same_path(which(n),expectedPath),'C524Screen:C5Path','C5 dependency %s resolved outside its pinned source.',n);
    end
end

started=utc_now();
runStart=struct('schema','CM18_C5_24_SCREEN12_RUN_START_V1','scene_id',sceneId, ...
    'started_utc',started,'binding_path',bindingPath,'binding_sha256',bindingSha256, ...
    'c5_raw_path',row.c5_raw_path,'c5_raw_sha256',row.c5_raw_sha256, ...
    'b_raw_path',row.b_raw_path,'b_raw_sha256',row.b_raw_sha256, ...
    'prepared_snapshot_sha256',row.prepared_snapshot_sha256,'model_id',binding.model_id, ...
    'model_sha256',binding.model_sha256,'model_checkpoint_sha256',binding.model_checkpoint_sha256, ...
    'engine_sha256',binding.engine_sha256,'c5_active_source_inventory_sha256',binding.c5_active_source_inventory_sha256, ...
    'scene_identity',pack.sceneIdentity,'cfg',pack.cfg,'opts',opts, ...
    'plant_calls_before_invocation',0,'training_steps',0,'optimizer_steps',0,'TEST_accessed',false);
save(runStartPath,'runStart','-v7.3');
write_text_new(attemptMarker,[started newline 'ABOUT_TO_CALL_ONE_C524_SCREEN_SCENE' newline]);
append_ledger(fullfile(runRoot,'C524_SCREEN12_LEDGER.jsonl'),struct( ...
    'schema','CM18_C5_24_SCREEN12_LEDGER_V1','event','RUN_STARTED','status','RUN_STARTED', ...
    'scene_id',sceneId,'binding_sha256',bindingSha256,'created_utc',utc_now()));
entered=false;
try
    entered=true;
    log=run_cm18_closed_loop_v1(pack.scene,'B2-RBF-Full-SPLIT',pack.cfg,opts);
    log.scene_id=sceneId; log.collector='CM18_C5_24_SCREEN12';
    runIdentity=struct('schema','CM18_C5_24_SCREEN12_RUN_IDENTITY_V1','scene_id',sceneId, ...
        'candidate','C5_POSITION_C5_24_ATTITUDE','binding_sha256',bindingSha256, ...
        'model_id',binding.model_id,'model_sha256',binding.model_sha256, ...
        'model_checkpoint_sha256',binding.model_checkpoint_sha256, ...
        'c5_raw_sha256',row.c5_raw_sha256,'b_raw_sha256',row.b_raw_sha256, ...
        'training_steps',0,'optimizer_steps',0,'TEST_accessed',false);
    scene=pack.scene; save(rawOutPath,'log','scene','runStart','runIdentity','-v7.3');
    transitions=numel(log.transition_time); samples=numel(log.time); events=sum(log.cm18_event_flag);
    complete=isfield(log,'status')&&strcmpi(char(log.status),'STABLE')&& ...
        isfield(log,'safety_stop_reason')&&isempty(char(log.safety_stop_reason))&& ...
        transitions==20000&&samples==20001&&double(log.last_transition)==20000&& ...
        events==1999&&all(isfinite(log.state(:)))&&all(isfinite(log.reference.position(:)));
    statusLabel='FAILED_NO_RETRY'; if complete, statusLabel='RUN_COMPLETE_PENDING_AUDIT'; end
    runStatus=struct('schema','CM18_C5_24_SCREEN12_RUN_STATUS_V1','status',statusLabel, ...
        'scene_id',sceneId,'log_status',char(log.status),'safety_stop_reason',char(log.safety_stop_reason), ...
        'transitions',transitions,'state_samples',samples,'cm18_events',events, ...
        'raw_path',rawOutPath,'raw_sha256',sha256_file(rawOutPath), ...
        'run_start_sha256',sha256_file(runStartPath),'first_plant_step_marker_path',firstStepMarker, ...
        'first_plant_step_confirmed',isfile(firstStepMarker),'binding_sha256',bindingSha256, ...
        'plant_invocation_entered',true,'plant_calls',1,'training_steps',0,'optimizer_steps',0, ...
        'TEST_accessed',false,'output_directory_bytes',directory_bytes(attemptDir),'created_utc',utc_now());
    assert(runStatus.output_directory_bytes<=100*1024^2, ...
        'C524Screen:OutputBudget','One flight exceeded 100 MiB; retain output and stop.');
    write_json_new(statusPath,runStatus);
    append_ledger(fullfile(runRoot,'C524_SCREEN12_LEDGER.jsonl'),struct( ...
        'schema','CM18_C5_24_SCREEN12_LEDGER_V1','event','RUN_TERMINAL','status',statusLabel, ...
        'scene_id',sceneId,'raw_sha256',runStatus.raw_sha256,'created_utc',utc_now()));
    assert(complete&&runStatus.first_plant_step_confirmed,'C524Screen:Incomplete', ...
        'Scene stopped or lacked the first-Plant marker; retain evidence and stop without retry.');
    result=runStatus;
catch ME
    if entered&&~isfile(statusPath)
        failure=struct('schema','CM18_C5_24_SCREEN12_RUN_STATUS_V1','status','FAILED_NO_RETRY', ...
            'scene_id',sceneId,'error_identifier',ME.identifier,'error_message',ME.message, ...
            'first_plant_step_confirmed',isfile(firstStepMarker),'binding_sha256',bindingSha256, ...
            'plant_invocation_entered',true,'plant_calls',1,'training_steps',0, ...
            'optimizer_steps',0,'TEST_accessed',false,'created_utc',utc_now());
        write_json_new(statusPath,failure);
        append_ledger(fullfile(runRoot,'C524_SCREEN12_LEDGER.jsonl'),struct( ...
            'schema','CM18_C5_24_SCREEN12_LEDGER_V1','event','RUN_TERMINAL', ...
            'status','FAILED_NO_RETRY','scene_id',sceneId,'created_utc',utc_now()));
    end
    rethrow(ME);
end
end

function add_active_paths(items)
for k=1:numel(items), if endsWith(lower(char(items(k).path)),'.m'), addpath(fileparts(char(items(k).path)),'-end'); end, end
end
function path=source_path(items,name)
idx=[]; for k=1:numel(items), [~,n,e]=fileparts(char(items(k).path)); if strcmpi([n e],name), idx(end+1)=k; end, end %#ok<AGROW>
assert(numel(idx)==1,'C524Screen:SourceName','Expected one C5 source named %s.',name); path=char(items(idx).path);
end
function verify_file(path,expected)
assert(isfile(path)&&strcmpi(sha256_file(path),expected),'C524Screen:FileHash','Missing or changed input: %s.',path);
end
function h=sha256_file(path)
md=java.security.MessageDigest.getInstance('SHA-256'); fid=fopen(path,'r');
assert(fid>=0,'C524Screen:Read','Cannot read %s.',path); c=onCleanup(@()fclose(fid)); %#ok<NASGU>
while true, b=fread(fid,8*1024*1024,'*uint8'); if isempty(b), break; end, md.update(b); end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
function write_json_new(path,value)
assert(~isfile(path),'C524Screen:NoOverwrite','Refusing to overwrite %s.',path);
fid=fopen(path,'w'); assert(fid>=0,'C524Screen:Write','Cannot create %s.',path); c=onCleanup(@()fclose(fid)); %#ok<NASGU>
fwrite(fid,jsonencode(value),'char');
end
function write_text_new(path,value)
assert(~isfile(path),'C524Screen:NoOverwrite','Refusing to overwrite %s.',path);
fid=fopen(path,'w'); assert(fid>=0,'C524Screen:Write','Cannot create %s.',path); c=onCleanup(@()fclose(fid)); %#ok<NASGU>
fwrite(fid,value,'char');
end
function append_ledger(path,row)
fid=fopen(path,'a'); assert(fid>=0,'C524Screen:Ledger','Cannot append screen ledger.'); c=onCleanup(@()fclose(fid)); %#ok<NASGU>
fwrite(fid,[jsonencode(row) newline],'char');
end
function n=directory_bytes(path)
d=dir(fullfile(path,'**','*')); d=d(~[d.isdir]); n=sum(double([d.bytes]));
end
function delete_lock(path)
if isfile(path), delete(path); end
end
function tf=same_path(a,b)
tf=strcmpi(char(java.io.File(char(a)).getCanonicalPath()),char(java.io.File(char(b)).getCanonicalPath()));
end
function t=utc_now()
t=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z'''));
end
