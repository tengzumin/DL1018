function report=gate_holdout_no_plant_arm_check()
% Check the registered RBF/feedforward/observer contrasts without invoking Plant.
ids={'C5_RBF','C5_RBF_F','C5_00','C5_10','C5_01','C5_11'};
specs=cellfun(@gate_attitude_arm_spec,ids,'UniformOutput',false);
rbf=cellfun(@(s)s.rbf_enabled,specs);
helper=cellfun(@(s)s.physics_helper_enabled,specs);
F=cellfun(@(s)s.feedforward_enabled,specs);
O=cellfun(@(s)s.observer_enabled,specs);
assert(isequal(rbf,[true true false false false false])&& ...
    isequal(helper,[false true true true true true])&& ...
    isequal(F,[false true false true false true])&& ...
    isequal(O,[false false false false true true]), ...
    'GATE:ArmMap','Registered attitude arm mapping changed.');
contrasts={'C5_RBF_F','C5_RBF';'C5_11','C5_RBF_F';'C5_11','C5_RBF'};
report=struct('arm_ids',{ids},'contrast_pairs',{contrasts}, ...
    'plant_invoked',false,'helper_v2_parity_path', ...
    'F=O=1 delegates directly to phys_attitude_replacement_candidate_v2');
end