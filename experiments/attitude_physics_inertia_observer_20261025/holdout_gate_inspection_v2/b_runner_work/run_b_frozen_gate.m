assert(isequal(sort(actual(:)), sort(expectedFields(:))), ...
    'HoldoutB:SnapshotFields', 'Unexpected %s variable fields.', label);
end

function found = hasFieldName(value, needle)
found = false;
if isstruct(value)
    names = fieldnames(value);
    if any(cellfun(@(name) contains(lower(name), lower(needle)), names))
        found = true;
        return
    end
    for k = 1:numel(value)
        for j = 1:numel(names)
            if hasFieldName(value(k).(names{j}), needle), found = true; return; end
        end
    end
elseif iscell(value)
    for k = 1:numel(value)
        if hasFieldName(value{k}, needle), found = true; return; end
    end
end
end

