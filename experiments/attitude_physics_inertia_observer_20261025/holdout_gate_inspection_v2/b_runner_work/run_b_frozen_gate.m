function verifySourceTree(identity, sourceRoot)
files = identity.source_tree.files;
lockPath = char(identity.input_lock.path);
assert(strcmpi(sha256File(lockPath), char(identity.input_lock.sha256)), ...
    'HoldoutB:InputLockSha', 'Input lock SHA mismatch.');
lockData = jsondecode(fileread(lockPath));
lockedSources = lockData.active_source_inventory;
lockedNames = {lockedSources.path};
lockedIsMatlab = endsWith(lower(string(lockedNames)), '.m');
lockedSources = lockedSources(lockedIsMatlab);
supportFiles = identity.source_tree.support_files;
lockedSupport = lockData.active_source_inventory;
lockedSupportNames = {lockedSupport.path};
lockedIsMat = endsWith(lower(string(lockedSupportNames)), '.mat');
lockedSupport = lockedSupport(lockedIsMat);
assert(numel(files) == 31 && numel(lockedSources) == 31 && ...
    numel(supportFiles) == 1 && numel(lockedSupport) == 1 && ...
    numel(files) + numel(supportFiles) == double(identity.source_tree.active_inventory_count) && ...
    isfolder(sourceRoot), 'HoldoutB:SourceTree', ...
    'Expected all 31 locked MATLAB sources and their locked MAT support file.');
for k = 1:numel(files)
    sourcePath = char(files(k).source_path);
    match = find(strcmp({lockedSources.path}, sourcePath), 1);
    assert(~isempty(match) && strcmpi(char(lockedSources(match).sha256), char(files(k).sha256)), ...
        'HoldoutB:SourceLockSha', 'Source identity does not match the input lock: %s', sourcePath);
    assert(strcmpi(sha256File(sourcePath), char(files(k).sha256)), ...
        'HoldoutB:SourceOriginalSha', 'Locked source file changed: %s', sourcePath);
    mirrorPath = fullfile(fileparts(mfilename('fullpath')), char(files(k).mirror_relative_path));
    assert(isfile(mirrorPath) && strcmpi(sha256File(mirrorPath), char(files(k).sha256)), ...
        'HoldoutB:SourceSha', 'Frozen source mirror SHA mismatch: %s', mirrorPath);
end
for k = 1:numel(supportFiles)
    supportPath = char(supportFiles(k).source_path);
    match = find(strcmp({lockedSupport.path}, supportPath), 1);
    assert(~isempty(match) && strcmpi(char(lockedSupport(match).sha256), char(supportFiles(k).sha256)), ...
        'HoldoutB:SupportLockSha', 'Support identity does not match the input lock: %s', supportPath);
    assert(strcmpi(sha256File(supportPath), char(supportFiles(k).sha256)), ...
        'HoldoutB:SupportOriginalSha', 'Locked support file changed: %s', supportPath);
    mirrorPath = fullfile(fileparts(mfilename('fullpath')), char(supportFiles(k).mirror_relative_path));
    assert(isfile(mirrorPath) && strcmpi(sha256File(mirrorPath), char(supportFiles(k).sha256)), ...
        'HoldoutB:SupportSha', 'Frozen support mirror SHA mismatch: %s', mirrorPath);
end
overlayFiles = identity.source_tree.runtime_overlay_files;
assert(numel(overlayFiles) == 1, 'HoldoutB:RuntimeOverlay', ...
    'Expected the single locked log-trimming runtime overlay.');
overlayRoot = canonicalPath(sourceRoot);
for k = 1:numel(overlayFiles)
    sourcePath = char(overlayFiles(k).source_path);
    mirrorPath = fullfile(fileparts(mfilename('fullpath')), char(overlayFiles(k).mirror_relative_path));
    assert(strcmpi(sha256File(sourcePath), char(overlayFiles(k).sha256)) && ...
        isfile(mirrorPath) && strcmpi(sha256File(mirrorPath), char(overlayFiles(k).sha256)) && ...
        startsWith(canonicalPath(mirrorPath), [overlayRoot filesep], 'IgnoreCase', true), ...
        'HoldoutB:RuntimeOverlaySha', 'Locked runtime overlay source is missing or changed: %s', mirrorPath);
end
end

function verifyResolvedSourceTree(identity, sourceRoot)
files = identity.source_tree.files;
sourceRoot = canonicalPath(sourceRoot);
for k = 1:numel(files)
    [~, functionName] = fileparts(char(files(k).mirror_relative_path));
    resolved = which(functionName);
    assert(~isempty(resolved), 'HoldoutB:PathIsolation', ...
        'MATLAB could not resolve locked source %s.', functionName);
    expected = fullfile(fileparts(mfilename('fullpath')), char(files(k).mirror_relative_path));
    resolvedPath = canonicalPath(resolved);
    assert(strcmpi(resolvedPath, canonicalPath(expected)) && ...
        startsWith(resolvedPath, [sourceRoot filesep], 'IgnoreCase', true), ...
        'HoldoutB:PathIsolation', 'MATLAB resolved %s outside the locked source tree.', functionName);
end
overlayFiles = identity.source_tree.runtime_overlay_files;
for k = 1:numel(overlayFiles)
    [~, functionName] = fileparts(char(overlayFiles(k).mirror_relative_path));
    expected = fullfile(fileparts(mfilename('fullpath')), char(overlayFiles(k).mirror_relative_path));
    resolved = which(functionName);
    assert(~isempty(resolved) && strcmpi(canonicalPath(resolved), canonicalPath(expected)) && ...
        startsWith(canonicalPath(resolved), [sourceRoot filesep], 'IgnoreCase', true), ...
        'HoldoutB:PathIsolation', 'MATLAB did not resolve locked runtime overlay %s inside B source tree.', functionName);
end
end

