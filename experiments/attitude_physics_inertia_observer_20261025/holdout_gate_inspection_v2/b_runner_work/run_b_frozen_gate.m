function hex = sha256File(filePath)
fid = fopen(filePath, 'rb');
assert(fid >= 0, 'HoldoutB:HashOpen', 'Cannot open file for SHA256: %s', filePath);
cleanup = onCleanup(@() fclose(fid));
bytes = fread(fid, Inf, '*uint8');
hex = sha256Bytes(bytes);
end

function hex = sha256Bytes(bytes)
md = java.security.MessageDigest.getInstance('SHA-256');
md.update(typecast(uint8(bytes(:)), 'int8'));
digest = typecast(md.digest(), 'uint8');
hex = lower(reshape(dec2hex(digest, 2).', 1, []));
end

function atomicWriteJson(filePath, value)
tmpPath = [filePath '.tmp'];
fid = fopen(tmpPath, 'w', 'n', 'UTF-8');
assert(fid >= 0, 'HoldoutB:StatusOpen', 'Cannot write attempt metadata: %s', filePath);
cleanup = onCleanup(@() fclose(fid));
bytes = unicode2native(jsonencode(value), 'UTF-8');
fwrite(fid, bytes, 'uint8');
clear cleanup;
movefile(tmpPath, filePath, 'f');
end










