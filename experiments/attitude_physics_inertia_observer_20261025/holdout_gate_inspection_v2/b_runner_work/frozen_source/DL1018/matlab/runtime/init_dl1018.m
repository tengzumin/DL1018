function [cfg,opts,projectRoot] = init_dl1018()
% Initialize an isolated DL1018 MATLAB path and its fixed V3.11/R2E contract.
projectRoot=fileparts(fileparts(fileparts(mfilename('fullpath'))));
restoredefaultpath;
rehash toolboxcache;
addpath(fullfile(projectRoot,'matlab','core'), ...
    fullfile(projectRoot,'matlab','models'), ...
    fullfile(projectRoot,'matlab','runtime'), ...
    fullfile(projectRoot,'matlab','data'), ...
    fullfile(projectRoot,'matlab','scenes'), ...
    fullfile(projectRoot,'matlab','metrics'));

configPath=fullfile(projectRoot,'configs','effective_config.mat');
assert(isfile(configPath),'DL1018:EffectiveConfigMissing', ...
    'Generate configs/effective_config.mat from the migration contract before running.');
loaded=load(configPath,'cfg');
assert(isfield(loaded,'cfg')&&isstruct(loaded.cfg),'DL1018:EffectiveConfigInvalid', ...
    'The effective configuration MAT must contain cfg.');
cfg=loaded.cfg;
assert(strcmpi(cfg.plant.mass_model,'distributed_v1')&& ...
    strcmpi(cfg.controller_morphology_mode,'fixed')&& ...
    isequal(double(cfg.control.command_filter.acceleration_limit(:)),[Inf;Inf;6])&& ...
    abs(cfg.plant.dt-.001)<1e-12&&isfield(cfg.rbf,'runtime')&& ...
    cfg.rbf.runtime.position_update_hz==100&&cfg.rbf.runtime.attitude_update_hz==100, ...
    'DL1018:EffectiveConfigContract','Effective configuration does not match the fixed V3.11/R2E contract.');
opts=controller_options_dl1018(cfg,'B');
end
