function attemptDir=run_candidate_gate_attempt(scenePayloadPath,attitudeArm,geometryArm,attemptDir)
%RUN_CANDIDATE_GATE_ATTEMPT Released pilot-only wrapper around the isolated C5 Plant runner.
prepared=prepare_gate_candidate_no_plant(scenePayloadPath,attitudeArm,geometryArm);
taskRoot=fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));
releasePath=fullfile(taskRoot,'PILOT_RELEASE_v1.json');
assert(isfile(releasePath),'GATE:ReleaseMissing','No root-issued pilot release exists.');
release=jsondecode(fileread(releasePath));
assert(strcmp(char(release.schema),'DL1018_GATE_PILOT_RELEASE_V1')&& ...
    strcmp(char(release.status),'RELEASED')&&double(release.plant_calls_authorized)==54, ...
    'GATE:ReleaseInvalid','Pilot release does not authorize the frozen 54-call pilot.');
taskbookPath=fullfile(taskRoot,'GATE_INSPECTION_HOLDOUT_TASKBOOK_v1_FROZEN_ZH.md');
assert(strcmpi(sha256_file(taskbookPath),char(release.taskbook_sha256))&& ...
    strcmpi(prepared.taskbook_sha256,char(release.taskbook_sha256)), ...
    'GATE:TaskbookSHA','Pilot release does not match the frozen taskbook.');
assert(ismember(prepared.attitude_arm,cellstr(string(release.candidate_arm_ids))), ...
    'GATE:ArmRelease','Attitude arm is not released.');
allowed=release.pilot_payloads;
hit=find(strcmp({allowed.scene_id},char(prepared.scene.scene_id))& ...
    strcmp({allowed.geometry_arm},prepared.geometry_arm)& ...
    strcmpi({allowed.payload_sha256},prepared.scene_payload_sha256));
assert(numel(hit)==1,'GATE:PayloadRelease','Scene payload is not in the pilot release.');
if strcmp(prepared.geometry_arm,'ACTIVE')
    assert(isfield(release,'b_payloads')&&~isempty(release.b_payloads), ...
        'GATE:BRelease','Pilot release has no B comparator payloads.');
else
    assert(strcmp(prepared.attitude_arm,'C5_11'),'GATE:FixedArmRelease', ...
        'Only C5+11 is released on fixed geometry arms.');
end
sourceLockPath=fullfile(taskRoot,'CANDIDATE_SOURCE_LOCK_PILOT_v1.json');
sourceLockSha=char(release.candidate_source_lock_sha256);
assert(isfile(sourceLockPath)&&strcmpi(sha256_file(sourceLockPath),sourceLockSha), ...
    'GATE:SourceLock','Candidate source lock differs from pilot release.');
verify_candidate_tree(jsondecode(fileread(sourceLockPath)),prepared.candidate_runner_root);attemptDir=char(java.io.File(char(attemptDir)).getCanonicalPath());
runsRoot=char(java.io.File(fullfile(taskRoot,'pilot_runs')).getCanonicalPath());
assert(startsWith(lower(attemptDir),[lower(runsRoot) filesep]), ...
    'GATE:OutputPath','Candidate attempt output must stay under the isolated pilot_runs directory.');
assert(~isfolder(attemptDir)&&~isfile(attemptDir),'GATE:NoOverwrite','Attempt directory already exists.');
attemptFolder=java.io.File(attemptDir);
assert(attemptFolder.mkdirs(),'GATE:AttemptCreate','Could not create unique attempt directory.');
markerPath=fullfile(attemptDir,'attempt_started.marker');
startPath=fullfile(attemptDir,'run_start.json');
statusPath=fullfile(attemptDir,'run_status.json');
rawPath=fullfile(attemptDir,'raw_run.mat');

runIdentity=struct('schema','DL1018_GATE_CANDIDATE_RUN_START_V1', ...
    'scene_id',char(prepared.scene.scene_id),'attitude_arm',prepared.attitude_arm, ...
    'geometry_arm',prepared.geometry_arm,'started_utc',utcNow(), ...
    'taskbook_sha256',char(release.taskbook_sha256), ...
    'candidate_source_lock_sha256',sourceLockSha, ...
    'scene_payload_sha256',prepared.scene_payload_sha256, ...
    'r_task_sha256',char(prepared.scene.R_task_sha256), ...
    'c5_input_lock_sha256',prepared.c5_input_lock_sha256, ...
    'c5_snapshot_sha256',prepared.c5_snapshot_sha256,'model_mat_sha256',prepared.model_mat_sha256, ...
    'cfg_identity',prepared.identity.geometry,'common_identity',prepared.identity.common, ...
    'runner_entry','run_gate_holdout_closed_loop(scene,cfg,opts)');
write_json(markerPath,struct('schema','DL1018_GATE_ATTEMPT_STARTED_V1', ...
    'scene_id',runIdentity.scene_id,'attitude_arm',runIdentity.attitude_arm, ...
    'geometry_arm',runIdentity.geometry_arm,'created_utc',runIdentity.started_utc,'stage','RUNNING'));
write_json(startPath,runIdentity);
try
    log=run_gate_holdout_closed_loop(prepared.scene,prepared.cfg,prepared.opts);
    assert(isfield(log,'complete_transitions')&&isscalar(log.complete_transitions), ...
        'GATE:TransitionAudit','Candidate runner omitted complete-transition status.');
    scene=prepared.scene;
    save(rawPath,'log','scene','runIdentity','-v7.3');
    status=struct('schema','DL1018_GATE_CANDIDATE_RUN_STATUS_V1', ...
        'state','COMPLETED','scene_id',runIdentity.scene_id, ...
        'attitude_arm',runIdentity.attitude_arm,'geometry_arm',runIdentity.geometry_arm, ...
        'finished_utc',utcNow(),'plant_calls',1,'scene_payload_sha256',prepared.scene_payload_sha256, ...
        'raw_output_path',rawPath,'raw_output_sha256',sha256_file(rawPath), ...
        'complete_transitions',logical(log.complete_transitions), ...
        'actual_transition_count',double(log.actual_transition_count), ...
        'actual_state_sample_count',double(log.actual_state_sample_count), ...
        'status_value',char(string(log.status)), ...
        'safety_stop_reason',char(string(log.safety_stop_reason)), ...
        'source_lock_sha256',sourceLockSha);
    write_json(statusPath,status);
    attemptDir=char(attemptDir);
    fprintf('CANDIDATE_ATTEMPT_DIR=%s',attemptDir);
catch ME
    status=struct('schema','DL1018_GATE_CANDIDATE_RUN_STATUS_V1', ...
        'state','FAILED','scene_id',runIdentity.scene_id, ...
        'attitude_arm',runIdentity.attitude_arm,'geometry_arm',runIdentity.geometry_arm, ...
        'failed_utc',utcNow(),'plant_calls',1,'scene_payload_sha256',prepared.scene_payload_sha256, ...
        'error_identifier',char(ME.identifier),'error_message',char(ME.message), ...
        'source_lock_sha256',sourceLockSha);
    write_json(statusPath,status);
    rethrow(ME);
end
end
function verify_candidate_tree(lock,runnerRoot)
assert(strcmp(char(lock.schema),'DL1018_CANDIDATE_SOURCE_LOCK_V1')&& ...
    strcmpi(char(lock.root),runnerRoot),'GATE:SourceLockSchema','Unexpected candidate source lock.');
for i=1:numel(lock.files)
    p=fullfile(runnerRoot,char(lock.files(i).relative_path));
    assert(isfile(p)&&strcmpi(sha256_file(p),char(lock.files(i).sha256)), ...
        'GATE:SourceTreeSHA','Candidate source changed: %s',p);
end
expectedFiles=dir(fullfile(runnerRoot,'matlab','**','*.m'));
rootCanonical=char(java.io.File(runnerRoot).getCanonicalPath());
rootPrefix=[rootCanonical filesep];
expectedRelative=cell(numel(expectedFiles),1);
for i=1:numel(expectedFiles)
    p=char(java.io.File(fullfile(expectedFiles(i).folder,expectedFiles(i).name)).getCanonicalPath());
    assert(startsWith(p,rootPrefix,'IgnoreCase',true),'GATE:SourceTreeEscape', ...
        'Candidate source file escaped the locked root: %s',p);
    expectedRelative{i}=p(numel(rootPrefix)+1:end);
end
lockedRelative={lock.files.relative_path};
normalizePaths=@(x) lower(string(strrep(char(x),'/','\')));
expectedNormalized=cellfun(normalizePaths,expectedRelative,'UniformOutput',false);
lockedNormalized=cellfun(normalizePaths,lockedRelative,'UniformOutput',false);
assert(numel(unique(lockedNormalized))==numel(lockedNormalized)&& ...
    isequal(sort(string(expectedNormalized(:))),sort(string(lockedNormalized(:)))), ...
    'GATE:SourceTreeCount','Candidate source lock must cover every MATLAB file exactly once.');
end
function h=sha256_file(p)
fid=fopen(p,'r');assert(fid>=0,'GATE:FileRead','Cannot read %s.',p);
cl=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(b);end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear cl;
end
function write_json(p,x)
fid=fopen(p,'w');assert(fid>=0,'GATE:Write','Cannot write %s.',p);
cl=onCleanup(@()fclose(fid));fwrite(fid,[jsonencode(x,'PrettyPrint',true) newline],'char');clear cl;
end
function s=utcNow()
s=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z'''));
end