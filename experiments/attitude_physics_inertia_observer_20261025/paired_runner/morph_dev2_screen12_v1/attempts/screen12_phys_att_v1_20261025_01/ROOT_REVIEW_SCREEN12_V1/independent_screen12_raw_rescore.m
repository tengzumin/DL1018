function m=score_raw(log,scene,isCandidate)
n=20000;
assert(isequal(size(log.time),[n+1,1])&&isequal(size(log.state),[n+1,12])&& ...
    isequal(size(log.reference.position),[n+1,3])&&isequal(log.time,scene.time)&& ...
    strcmp(char(log.status),'STABLE')&&isempty(char(log.safety_stop_reason))&&log.last_transition==n);
e=double(log.state(:,1:3))-double(log.reference.position);
en=sqrt(sum(e.^2,2)); t=double(log.time); early=t<2.2; late=~early;
theta=zeros(n,1);
for k=1:n
    R=rotzyx(double(log.state(k,7:9).'));
    Rd=rotzyx(double(log.filtered_attitude_reference(k,:).'));
    theta(k)=acos(max(min((trace(Rd.'*R)-1)/2,1),-1));
end
assert(all(isfinite([e(:);theta]))&&nnz(early)==2200&&nnz(late)==17801);
m=struct('q_rmse_m',sqrt(mean(en.^2)),'q_axis_rmse_m',sqrt(mean(e.^2,1)), ...
    'q_peak_m',max(en),'q_early_rmse_m',sqrt(mean(sum(e(early,:).^2,2))), ...
    'q_late_rmse_m',sqrt(mean(sum(e(late,:).^2,2))), ...
    'so3_rmse_rad',sqrt(mean(theta.^2)),'so3_peak_rad',max(theta), ...
    'so3_early_rmse_rad',sqrt(mean(theta(double(log.transition_time)<2.2).^2)), ...
    'so3_late_rmse_rad',sqrt(mean(theta(double(log.transition_time)>=2.2).^2)), ...
    'motor_saturation_count',nnz(any(log.motor_saturated,2)), ...
    'generalized_clip_count',nnz(any(log.generalized_clipped,2)), ...
    'tilt_limited_count',nnz(log.tilt_limited), ...
    'controller_call_time_s_mean',mean(double(log.controller_call_time_s)));
if isCandidate
    assert(isscalar(log.attitude_fusion_rbf_output_enabled)&&~logical(log.attitude_fusion_rbf_output_enabled)&& ...
        isscalar(log.attitude_fusion_rbf_update_enabled)&&~logical(log.attitude_fusion_rbf_update_enabled));
    assert(size(log.rbf_output_held,1)==n&&all(log.rbf_output_held(:)==0));
    assert(size(log.attitude_rbf_estimate_acceleration_rads2,1)==n&& ...
        all(log.attitude_rbf_estimate_acceleration_rads2(:)==0));
    assert(size(log.attitude_rbf_compensation_torque_Nm,1)==n&& ...
        all(log.attitude_rbf_compensation_torque_Nm(:)==0));
    assert(numel(log.phys_attitude_trace)==n);
    for k=1:n
        x=log.phys_attitude_trace{k};
        assert(x.sample_index==k&&x.prepare.time_s==log.transition_time(k)&& ...
            x.commit.time_s==log.transition_time(k)&& ...
            isequal(double(x.morph_command(:)),double(scene.arms.command(k,:).'))&& ...
            isequal(double(x.omega_body(:)),double(log.state(k,10:12).'))&& ...
            isequal(double(x.commit.tau_cmd_clipped_Nm(:)), ...
                double(log.controller_clipped_generalized(k,2:4).'))&& ...
            isequal(double(x.prepare.estimateTorque_Nm(:)),-double(x.prepare.tau_comp_Nm(:)))&& ...
            logical(x.is_attitude_event)==logical(log.attitude_event_flag(k))&& ...
            logical(x.prepare.observer.updated)==logical(x.is_attitude_event)&& ...
            ~logical(x.rbf_output_enabled)&&~logical(x.rbf_update_enabled));
        if x.prepare.observer.updated
            assert(x.prepare.observer.delta_s>0&& ...
                abs(x.prepare.observer.delta_s-x.event_delta_s)<1e-10);
        end
    end
else
    assert(isscalar(log.attitude_fusion_rbf_output_enabled)&&logical(log.attitude_fusion_rbf_output_enabled));
    assert(isscalar(log.attitude_fusion_rbf_update_enabled)&&logical(log.attitude_fusion_rbf_update_enabled));
end
end
function verify_stored_score(m,s)
for f={'q_rmse_m','q_peak_m','q_early_rmse_m','q_late_rmse_m','so3_rmse_rad', ...
        'so3_peak_rad','so3_early_rmse_rad','so3_late_rmse_rad', ...
        'motor_saturation_count','generalized_clip_count','tilt_limited_count'}
    close_metric(m.(f{1}),s.(f{1}));
end
close_metric(m.q_axis_rmse_m,s.q_axis_rmse_m);
end
function close_metric(a,b)
assert(numel(a)==numel(b)&&all(abs(double(a(:))-double(b(:)))<=1e-12), ...
    'Independent score differs from stored score.');
end
function R=rotzyx(e)
r=e(1);p=e(2);y=e(3);cr=cos(r);sr=sin(r);cp=cos(p);sp=sin(p);cy=cos(y);sy=sin(y);
R=[cy*cp,cy*sp*sr-sy*cr,cy*sp*cr+sy*sr; ...
    sy*cp,sy*sp*sr+cy*cr,sy*sp*cr-cy*sr;-sp,cp*sr,cp*cr];
end
