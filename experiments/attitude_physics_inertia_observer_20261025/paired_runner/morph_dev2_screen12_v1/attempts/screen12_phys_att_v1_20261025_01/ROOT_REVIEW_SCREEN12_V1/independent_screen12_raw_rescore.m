function h=json_sha256(x)
h=sha256_bytes(unicode2native(jsonencode(x),'UTF-8'));
end
function h=sha256_file(p)
fid=fopen(p,'r');assert(fid>=0,'Cannot read %s',p); clean=onCleanup(@()fclose(fid));
md=java.security.MessageDigest.getInstance('SHA-256');
while true
    b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end
    md.update(b);
end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
function h=sha256_bytes(b)
md=java.security.MessageDigest.getInstance('SHA-256'); md.update(uint8(b(:)));
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
function write_text(p,s)
fid=fopen(p,'w');assert(fid>=0); clean=onCleanup(@()fclose(fid));
fwrite(fid,unicode2native([s newline],'UTF-8'),'uint8');
end