function run_morph_dev2_dev58(releasePath,releaseSha,attemptDir)
% Candidate-only DEV58 continuation. B72 raw and 14 prior candidate raws are read-only.
entry=fileparts(mfilename('fullpath'));releasePath=char(releasePath);releaseSha=lower(char(releaseSha));attemptDir=char(attemptDir);
assert(strcmp(sha256_file(releasePath),releaseSha),'DEV58:ReleaseSHA','Root release SHA differs.');
release=jsondecode(fileread(releasePath));
assert(strcmp(release.schema,'PAIRED_MORPH_DEV2_DEV58_ROOT_RELEASE_V1')&& ...
    logical(release.approved)&&strcmp(release.scope,'MORPH_DEV2_DEV58')&& ...
    double(release.max_runner_calls)==58&&double(release.max_transitions)==1160000&& ...
    logical(release.no_fixed_output_cap)&&double(release.minimum_free_bytes)==30*1024^3&& ...
    ~logical(release.training_authorized)&&~logical(release.TEST_authorized)&& ...
    ~logical(release.retry_authorized)&&strcmp(release.comparator,'B_TRACEABLE_C3CORE_V1')&& ...
    isequal(string(release.arm_order(:)).',"candidate"), ...
    'DEV58:Release','Root release does not authorize exactly 58 candidate-only DEV58 calls.');
lockPath=char(release.source_lock_path);
assert(strcmp(sha256_file(lockPath),lower(char(release.source_lock_sha256))), ...
    'DEV58:SourceLockSHA','Source-lock SHA differs.');
lock=jsondecode(fileread(lockPath));
assert(strcmp(lock.schema,'SOURCE_LOCK_MORPH_DEV2_DEV58_V1')&& ...
    strcmp(lock.status,'FROZEN_INPUTS')&&~logical(lock.executed)&& ...
    ~logical(lock.closed_loop_runs_authorized)&&logical(lock.root_release_issued)&& ...
    strcmp(lock.root_approval_status,'APPROVED')&&numel(lock.reused_candidate_raws)==14&& ...
    strcmp(lock.manifest.sha256,release.manifest_sha256)&&numel(lock.sources)==39&& ...
    numel(lock.inputs)==11&&numel(lock.diagnostic_scenes)==58&& ...
    strcmpi(lock.wrapper.path,fullfile(entry,'run_morph_dev2_dev58.m'))&& ...
    strcmpi(lock.manifest.path,fullfile(entry,'manifest','DEV58_PREPARED_MANIFEST_B72_V2.json')), ...
    'DEV58:Lock','Frozen DEV58 lock differs from the approved scope.');
assert(strcmpi(sha256_file(lock.root_review.path),release.root_review_sha256)&& ...
    strcmpi(lock.root_review.sha256,release.root_review_sha256), ...
    'DEV58:RootReviewSHA','Root review SHA differs from the signed release.');
manifest=jsondecode(fileread(lock.manifest.path));
assert(strcmp(sha256_file(lock.manifest.path),lock.manifest.sha256)&& ...
    strcmp(manifest.schema,'MORPH_DEV2_DEV58_PREPARED_MANIFEST_V1')&& ...
    manifest.plant_calls==0&&manifest.training_runs==0&&~logical(manifest.TEST_accessed)&& ...
    numel(manifest.scenes)==58&&logical(manifest.b_comparator.all_72_B_raw_reused)&& ...
    ~logical(manifest.b_comparator.new_B_runs_authorized), ...
    'DEV58:Manifest','Prepared manifest is not the frozen no-Plant DEV58 manifest.');
ids=string({manifest.scenes.scene_id});ids=ids(:).';
assert(isequal(ids,string(release.scene_ids(:)).')&& ...
    isequal(ids,string({lock.diagnostic_scenes.scene_id}))&& ...
    all(~contains(ids,'TEST')),'DEV58:SceneIds','Frozen 58-scene identity differs.');
expectedAttempt=fullfile(entry,'attempts',char(release.attempt_id));
assert(isfolder(attemptDir)&&same_path(attemptDir,expectedAttempt)&& ...
    ~isfile(fullfile(attemptDir,'batch_status.json'))&& ...
    ~isfile(fullfile(attemptDir,'runner_invocation.json')), ...
    'DEV58:Attempt','Attempt directory is not fresh or differs from root release.');
verify_control_files(releasePath,releaseSha,lockPath,release,lock);verify_files(lock);
assert(strcmp(version('-release'),'2025b'),'DEV58:MATLABRelease','Expected MATLAB R2025b.');
for k=1:numel(lock.reused_candidate_raws)
    r=lock.reused_candidate_raws(k);
    assert(strcmpi(sha256_file(r.raw_path),r.raw_sha256)&& ...
        strcmpi(sha256_file(r.status_path),r.status_sha256), ...
        'DEV58:ReuseSHA','A prior candidate raw/status changed: %s.',r.scene_id);
    if isfield(r,'review_path')&&~isempty(r.review_path)
        assert(strcmpi(sha256_file(r.review_path),r.review_sha256), ...
            'DEV58:ReuseReviewSHA','Prior candidate review changed: %s.',r.scene_id);
    end
end
restoredefaultpath;addpath(fullfile(entry,'matlab','runtime'));activate_paired_runner();
modelPath=find_input(lock,'model_mat');snapshotPath=find_input(lock,'c5_snapshot_mat');
modelPack=load(modelPath,'model');snapshot=load(snapshotPath,'cfg','opts','W0','modelIdentity');
assert(isequal(fieldnames(modelPack),{'model'})&&numel(fieldnames(snapshot))==4&& ...
    all(isfield(snapshot,{'cfg','opts','W0','modelIdentity'})), ...
    'DEV58:MATVariables','C5 model/snapshot variable set differs.');
model=modelPack.model;cfg=bind_paired_fixed_j0(snapshot.cfg);
assert(strcmp(char(snapshot.cfg.controller_morphology_mode),'fixed')&& ...
    double(cfg.plant.dt)==.001&&isequaln(rmfield(cfg,'attitude_replacement'),snapshot.cfg)&& ...
    strcmp(char(model.model_id),'DSSM14')&&strcmp(char(model.architecture),'DSSM')&& ...
    double(model.seed)==2026102001&&double(model.selected_step)==60000&& ...
    double(model.input_dim)==14&&double(model.window)==32&& ...
    isequal(size(model.output_W),[33,3])&&isequal(double(model.output_W),double(snapshot.W0)), ...
    'DEV58:ModelCfg','Frozen C5 DSSM14 model/config differs.');
identity=manifest.c5;identity.scenes=lock.diagnostic_scenes;
assert(strcmp(paired_sha256_double(double(model.output_W)),identity.W0_sha256)&& ...
    strcmp(hash_normalizer_arrays(model),identity.normalizer_arrays_sha256)&& ...
    strcmp(snapshot.modelIdentity.W0_sha256,identity.W0_sha256)&& ...
    strcmp(snapshot.modelIdentity.normalizer_arrays_sha256,identity.normalizer_arrays_sha256), ...
    'DEV58:ModelIdentity','W0 or normalizer identity differs.');
[cfgSha,~]=json_sha256(cfg);
assert(strcmp(cfgSha,identity.cfg_sha256)&& ...
    strcmp(cfg.attitude_replacement.J0_controller_fixed_sha256,identity.J0_controller_fixed_sha256), ...
    'DEV58:CfgJ0','Frozen cfg or controller J0 differs.');
fixedPlant=simulation_parameters(cfg,cfg.plant.arm_initial,zeros(4,1));
fixedController=controller_parameters(cfg,fixedPlant,'fixed');
assert(isequal(double(fixedController.inertia),double(cfg.attitude_replacement.J0_controller_fixed_kgm2)), ...
    'DEV58:J0','Fixed controller inertia differs.');
[baseline,candidateOpts]=make_paired_c5_options(cfg,model);
c5opts=rmfield(baseline,{'paired_arm','paired_position_method_id','rbf_attitude_initial_weight'});
assert(isequaln(c5opts,snapshot.opts)&&strcmp(json_sha256(c5opts),identity.c5_options_sha256)&& ...
    strcmp(json_sha256(baseline),identity.baseline_options_sha256)&& ...
    strcmp(json_sha256(candidateOpts),identity.candidate_options_sha256), ...
    'DEV58:Options','Frozen C5/candidate effective options differ.');
flags={'rbf_attitude_enabled','rbf_attitude_output_enabled','rbf_attitude_update_enabled'};
common=rmfield(baseline,[flags,{'paired_arm'}]);
commonCandidate=rmfield(candidateOpts,[flags,{'paired_arm'}]);
assert(isequaln(common,commonCandidate)&&strcmp(json_sha256(common),identity.common_options_sha256)&& ...
    all(cellfun(@(x)logical(baseline.(x))&&~logical(candidateOpts.(x)),flags))&& ...
    strcmp(paired_sha256_double(zeros(size(cfg.rbf.position.centers,2),3)), ...
    identity.rbf_position_initial_weight_sha256)&& ...
    strcmp(paired_sha256_double(double(baseline.rbf_attitude_initial_weight)), ...
    identity.rbf_attitude_initial_weight_sha256), ...
    'DEV58:CommonOptions','Frozen common options or initial RBF weights differ.');
assert(strcmp(manifest.b_comparator.controller,'B_TRACEABLE_C3CORE_V1')&& ...
    strcmpi(manifest.b_comparator.input_lock_sha256,find_input_sha(lock,'b_input_lock'))&& ...
    ~logical(manifest.b_comparator.new_B_runs_authorized), ...
    'DEV58:BIdentity','Comparator is not the locked original B cohort.');
results=repmat(struct('scene_id','','arm','candidate','status','NOT_RUN','reason','', ...
    'score',struct(),'delta_score',struct(),'wall_seconds',NaN,'run_dir',''),1,58);
for k=1:58,results(k).scene_id=char(ids(k));end
runnerCalls=0;confirmedPlantRuns=0;confirmedTransitions=0;unknownPlantInvocations=0;
completed=false(1,58);safetyPass=false(1,58);batchStart=utc_now();batchTimer=tic;currentDir='';
try
    for i=1:58
        frozen=identity.scenes(i);sceneRec=manifest.scenes(i);id=char(ids(i));
        assert(strcmp(sceneRec.scene_id,id)&&sceneRec.seed==frozen.seed, ...
            'DEV58:ManifestRow','Manifest scene or seed changed: %s.',id);
        out=make_paired_dev58_scene(id,cfg);spec=table2struct(out.spec);scene=out.scene;metadata=out.metadata;
        sceneHashes=struct('spec_sha256',json_sha256(spec),'scene_sha256',json_sha256(scene), ...
            'metadata_sha256',json_sha256(metadata));
        assert(strcmp(sceneHashes.spec_sha256,frozen.spec_sha256)&& ...
            strcmp(sceneHashes.scene_sha256,frozen.scene_sha256)&& ...
            strcmp(sceneHashes.metadata_sha256,frozen.metadata_sha256)&& ...
            isequal(size(scene.time),[20001,1])&&isequal(scene.time,(0:.001:20).'), ...
            'DEV58:SceneSHA','Regenerated frozen scene differs: %s.',id);
        bStatusPath=sceneRec.b_run_status_path;bRawPath=sceneRec.b_raw_path;
        assert(isfile(bStatusPath)&&isfile(bRawPath)&& ...
            strcmpi(sha256_file(bStatusPath),sceneRec.b_run_status_sha256)&& ...
            strcmpi(sha256_file(bRawPath),sceneRec.b_raw_sha256), ...
            'DEV58:BFiles','Locked B72 raw/status SHA differs: %s.',id);
        bs=jsondecode(fileread(bStatusPath));
        assert(strcmp(bs.status,'RUN_COMPLETE_RAW_PENDING_AUDIT')&&strcmp(bs.log_status,'STABLE')&& ...
            isempty(bs.safety_stop_reason)&&bs.last_transition==20000&&bs.transitions==20000&& ...
            bs.state_samples==20001&&bs.plant_calls==1&&strcmp(bs.scene_id,id)&& ...
            strcmp(bs.raw_path,bRawPath)&&strcmpi(bs.raw_sha256,sceneRec.b_raw_sha256)&& ...
            strcmp(bs.external_identity_sha256,sceneRec.external_identity_sha256)&& ...
            strcmp(bs.scene_raw_sha256,sceneRec.b_source_raw_sha256)&&~logical(bs.TEST_accessed), ...
            'DEV58:BStatus','Locked original B72 status differs: %s.',id);
        bLoaded=load(bRawPath,'log');bLog=bLoaded.log;clear bLoaded;
        assert(strcmp(char(bLog.status),'STABLE')&&isempty(char(bLog.safety_stop_reason))&& ...
            isequal(bLog.time,scene.time)&&isequal(bLog.transition_time,scene.time(1:20000))&& ...
            isequal(double(bLog.initial_state(:)),double(scene.initial_state(:)))&& ...
            isequaln(bLog.reference.position,scene.reference.position)&& ...
            isequaln(bLog.reference.velocity,scene.reference.velocity)&& ...
            isequaln(bLog.reference.acceleration,scene.reference.acceleration)&& ...
            isequaln(bLog.reference.yaw,scene.reference.yaw)&& ...
            isequaln(bLog.reference.yaw_rate,scene.reference.yaw_rate)&& ...
            isequaln(bLog.reference.yaw_acceleration,scene.reference.yaw_acceleration)&& ...
            isequaln(bLog.environment_wind_I,scene.environment_wind_I)&& ...
            isequaln(bLog.arms.command,scene.arms.command)&& ...
            isequaln(bLog.arms.rho_true,scene.arms.rho_true)&& ...
            isequaln(bLog.arms.rho_hat,scene.arms.rho_hat)&& ...
            isequaln(bLog.arms.rhoDot_true,scene.arms.rhoDot_true)&& ...
            isequaln(bLog.arms.rhoDot_hat,scene.arms.rhoDot_hat), ...
            'DEV58:BScene','B72 raw does not match exact scene/reference/wind/morphology: %s.',id);
        bScore=score_log(bLog,scene,false);clear bLog;
        assert(get_free_bytes()>=double(release.minimum_free_bytes), ...
            'DEV58:Disk','C drive is below the free-space safety floor.');
        verify_control_files(releasePath,releaseSha,lockPath,release,lock);verify_files(lock);
        assert(strcmp(json_sha256(scene),sceneHashes.scene_sha256)&& ...
            strcmp(json_sha256(cfg),cfgSha)&&strcmp(json_sha256(candidateOpts),identity.candidate_options_sha256), ...
            'DEV58:Immutable','Scene/cfg/options changed before candidate runner.');
        runDir=fullfile(attemptDir,sprintf('%02d_%s_candidate',i,id));
        assert(~isfolder(runDir),'DEV58:NoOverwrite','Candidate output directory already exists.');
        mkdir(runDir);currentDir=runDir;
        baseRecord=struct('release_sha256',releaseSha,'source_lock_sha256', ...
            lower(char(release.source_lock_sha256)),'manifest_sha256',lock.manifest.sha256, ...
            'runner_sha256',char(lock.wrapper.sha256),'scene_id',id, ...
            'seed',double(sceneRec.seed),'arm','candidate','scene_sha256',sceneHashes.scene_sha256, ...
            'spec_sha256',sceneHashes.spec_sha256,'metadata_sha256',sceneHashes.metadata_sha256, ...
            'cfg_sha256',cfgSha,'common_options_sha256',identity.common_options_sha256, ...
            'effective_options_sha256',identity.candidate_options_sha256,'W0_sha256',identity.W0_sha256, ...
            'normalizer_arrays_sha256',identity.normalizer_arrays_sha256, ...
            'b_comparator','B_TRACEABLE_C3CORE_V1','b_raw_path',bRawPath, ...
            'b_raw_sha256',sceneRec.b_raw_sha256,'b_run_status_path',bStatusPath, ...
            'b_run_status_sha256',sceneRec.b_run_status_sha256,'b_score',bScore, ...
            'batch_stdout_path',fullfile(attemptDir,'stdout.log'), ...
            'batch_stderr_path',fullfile(attemptDir,'stderr.log'));
        startRecord=baseRecord;startRecord.started_utc=utc_now();
        startRecord.status='STARTED_BEFORE_RUNNER_INVOCATION';
        write_json_new(fullfile(runDir,'run_start.json'),startRecord);
        marker=baseRecord;marker.recorded_utc=utc_now();marker.kind='RUNNER_INVOCATION';
        marker.first_plant_step_claimed=false;write_json_new(fullfile(runDir,'runner_invocation.json'),marker);
        runnerCalls=runnerCalls+1;unknownPlantInvocations=unknownPlantInvocations+1;
        wall=tic;countedLog=false;
        try
            rng(double(sceneRec.seed),'twister');
            log=run_paired_observer_closed_loop(scene,'B2-RBF-Full-SPLIT',cfg,candidateOpts);
            assert(isfield(log,'last_transition')&&isnumeric(log.last_transition)&& ...
                isscalar(log.last_transition)&&isfinite(log.last_transition)&& ...
                log.last_transition>=0&&log.last_transition==floor(log.last_transition), ...
                'DEV58:TransitionCount','Candidate returned invalid transition count: %s.',id);
            confirmedTransitions=confirmedTransitions+double(log.last_transition);
            if log.last_transition>0,confirmedPlantRuns=confirmedPlantRuns+1;end
            unknownPlantInvocations=unknownPlantInvocations-1;countedLog=true;
            wallSeconds=toc(wall);rawPath=fullfile(runDir,'run_raw.mat');
            assert(java.io.File(rawPath).createNewFile(),'DEV58:NoOverwrite','Candidate raw exists.');
            save(rawPath,'log','-v7.3');rawSha=sha256_file(rawPath);
            assert(strcmp(json_sha256(scene),sceneHashes.scene_sha256)&& ...
                strcmp(json_sha256(cfg),cfgSha)&&strcmp(json_sha256(candidateOpts),identity.candidate_options_sha256), ...
                'DEV58:Immutable','Candidate mutated scene/cfg/options.');
            verify_control_files(releasePath,releaseSha,lockPath,release,lock);verify_files(lock);
            audit=baseRecord;audit.time_size=size(scene.time);audit.scene_sha256_after=json_sha256(scene);
            audit.same_scene_payload_sha256=sceneHashes.scene_sha256;
            write_json_new(fullfile(runDir,'scene_audit.json'),audit);
            [candidateScore,gate]=score_log(log,scene,true);
            delta=score_delta(bScore,candidateScore);results(i).score=candidateScore;
            results(i).delta_score=delta;results(i).wall_seconds=wallSeconds;
            safetyReasons={};
            if ~logical(gate.passed),safetyReasons{end+1}='Full stable run/candidate trace contract failed.';end
            if candidateScore.motor_saturation_count~=0,safetyReasons{end+1}='Candidate motor saturation count is nonzero.';end
            if candidateScore.generalized_clip_count~=0,safetyReasons{end+1}='Candidate generalized clipping count is nonzero.';end
            safetyGate=struct('passed',isempty(safetyReasons),'requirements',{safetyReasons}, ...
                'reason',strjoin(safetyReasons,' '));
            status=baseRecord;if safetyGate.passed,status.status='COMPLETED_DEV58_CANDIDATE';
            else,status.status='FAILED_SAFETY_GATE';end
            status.ended_utc=utc_now();status.last_transition=double(log.last_transition);
            status.runner_status=char(log.status);status.safety_stop_reason=char(log.safety_stop_reason);
            status.wall_seconds=wallSeconds;status.raw_path=rawPath;status.raw_sha256=rawSha;
            status.raw_bytes=dir(rawPath).bytes;status.score=candidateScore;
            status.delta_candidate_minus_B=delta;status.engineering_gate=gate;status.safety_gate=safetyGate;
            status.performance_metrics_are_nongating=true;status.confirmed_plant_calls=1;
            status.training_run_count=0;status.TEST_accessed=false;
            write_json_new(fullfile(runDir,'run_status.json'),status);
            pair=struct('schema','MORPH_DEV2_DEV58_B72_PAIR_AUDIT_V1','scope','MORPH_DEV2_DEV58', ...
                'scene_id',id,'baseline_controller','B_TRACEABLE_C3CORE_V1', ...
                'baseline_raw_path',bRawPath,'baseline_raw_sha256',sceneRec.b_raw_sha256, ...
                'baseline_run_status_path',bStatusPath,'baseline_run_status_sha256',sceneRec.b_run_status_sha256, ...
                'baseline_score',bScore,'candidate_score',candidateScore, ...
                'delta_candidate_minus_B',delta,'same_scene_sha256',sceneHashes.scene_sha256, ...
                'external_identity_sha256',sceneRec.external_identity_sha256, ...
                'candidate_raw_path',rawPath,'candidate_raw_sha256',rawSha, ...
                'candidate_status_path',fullfile(runDir,'run_status.json'), ...
                'candidate_status_sha256',sha256_file(fullfile(runDir,'run_status.json')), ...
                'candidate_engineering_gate',gate,'safety_gate',safetyGate, ...
                'candidate_plant_calls',1,'training_run_count',0,'TEST_accessed',false, ...
                'performance_metrics_are_nongating',true,'status','RECORDED');
            write_json_new(fullfile(attemptDir,sprintf('pair_%02d_audit.json',i)),pair);
            results(i).status=status.status;results(i).reason=safetyGate.reason;results(i).run_dir=runDir;
            completed(i)=true;safetyPass(i)=safetyGate.passed;clear log
            assert(safetyGate.passed,'DEV58:SafetyGate','Candidate safety/engineering gate failed: %s.',id);
        catch runError
            if ~countedLog&&unknownPlantInvocations<runnerCalls
                unknownPlantInvocations=unknownPlantInvocations+1;
            end
            if ~isfile(fullfile(runDir,'run_status.json'))
                fail=baseRecord;fail.status='FAILED_ENGINEERING';fail.ended_utc=utc_now();
                fail.reason=getReport(runError,'extended','hyperlinks','off');
                fail.last_transition='unknown_if_no_returned_log';fail.wall_seconds=toc(wall);
                if exist('log','var')&&isstruct(log)&&isfield(log,'last_transition')&& ...
                        isnumeric(log.last_transition)&&isscalar(log.last_transition)&& ...
                        isfinite(log.last_transition)&&log.last_transition>=0&& ...
                        log.last_transition==floor(log.last_transition)
                    fail.last_transition=double(log.last_transition);
                    if isfield(log,'status'),fail.runner_status=char(log.status);end
                    if isfield(log,'safety_stop_reason'),fail.safety_stop_reason=char(log.safety_stop_reason);end
                end
                fail.candidate_runner_invocations=1;fail.confirmed_transitions=0;
                if countedLog,fail.confirmed_transitions=double(log.last_transition);end
                rawPath=fullfile(runDir,'run_raw.mat');if isfile(rawPath)
                    fail.raw_path=rawPath;fail.raw_sha256=sha256_file(rawPath);fail.raw_bytes=dir(rawPath).bytes;
                end
                write_json_new(fullfile(runDir,'run_status.json'),fail);
            end
            results(i).status='FAILED';results(i).reason=runError.message;results(i).run_dir=runDir;
            rethrow(runError);
        end
    end
    assert(runnerCalls==58&&all(completed)&&all(safetyPass)&&confirmedTransitions==1160000, ...
        'DEV58:Incomplete','All 58 candidate-only runs must complete safely.');
    batchStatus='MORPH_DEV2_DEV58_COMPLETE';failureReason='';
catch batchError
    batchStatus='STOPPED_ON_FAILURE';failureReason=getReport(batchError,'extended','hyperlinks','off');
end
summary=struct('schema','MORPH_DEV2_DEV58_BATCH_STATUS_V1','scope','MORPH_DEV2_DEV58', ...
    'status',batchStatus,'started_utc',batchStart,'ended_utc',utc_now(), ...
    'release_sha256',releaseSha,'source_lock_sha256',char(release.source_lock_sha256), ...
    'manifest_sha256',lock.manifest.sha256,'runner_invocation_count',runnerCalls, ...
    'confirmed_plant_runs',confirmedPlantRuns,'confirmed_transitions',confirmedTransitions, ...
    'unknown_plant_invocations',unknownPlantInvocations,'training_run_count',0, ...
    'TEST_accessed',false,'completed_scenes',completed,'safety_pass',safetyPass, ...
    'performance_is_nongating',true,'results',results,'failure_reason',failureReason, ...
    'batch_wall_seconds',toc(batchTimer),'artifact_errors',{{}});
artifactErrors={};
try,write_results_csv(fullfile(attemptDir,'results.csv'),results);
catch e,artifactErrors{end+1}=getReport(e,'extended','hyperlinks','off');end
if ~isempty(artifactErrors),batchStatus='STOPPED_ON_FAILURE';summary.status=batchStatus;summary.failure_reason=strjoin(artifactErrors,' | ');end
summary.artifact_errors=artifactErrors;
try,write_dev58_report(fullfile(attemptDir,'report.md'),summary);
catch e,artifactErrors{end+1}=getReport(e,'extended','hyperlinks','off');end
if ~isempty(artifactErrors),batchStatus='STOPPED_ON_FAILURE';summary.status=batchStatus;summary.failure_reason=strjoin(artifactErrors,' | ');end
summary.artifact_errors=artifactErrors;summary.batch_wall_seconds=toc(batchTimer);
summary.new_bytes=tree_bytes(attemptDir);write_json_new(fullfile(attemptDir,'batch_status.json'),summary);
fprintf('MORPH_DEV2_DEV58_BATCH_JSON:%s\n',jsonencode(summary));
assert(strcmp(batchStatus,'MORPH_DEV2_DEV58_COMPLETE'),'DEV58:BatchFailed','DEV58 batch stopped; see batch_status.json.');
end

function sha=find_input_sha(lock,name)
items=lock.inputs(strcmp({lock.inputs.role},name));assert(numel(items)==1,'DEV58:Input','Missing unique input %s.',name);sha=char(items.sha256);
end
function write_dev58_report(path,summary)
lines={sprintf('# MORPH_DEV2_DEV58: %s',summary.status), ...
    sprintf('Candidate-only calls: %d / 58; confirmed Plant runs: %d; transitions: %d; unknown invocations: %d.', ...
    summary.runner_invocation_count,summary.confirmed_plant_runs,summary.confirmed_transitions,summary.unknown_plant_invocations), ...
    'Baseline is the same-scene raw from B_TRACEABLE_C3CORE_V1. Performance is descriptive; no per-scene performance stop is applied.'};
for k=1:numel(summary.results)
    r=summary.results(k);if isempty(fieldnames(r.delta_score)),lines{end+1}=sprintf('%s: %s (%s).',r.scene_id,r.status,r.reason); %#ok<AGROW>
    else,d=r.delta_score;lines{end+1}=sprintf('%s: dQ %.17g m; dSO3 %.17g rad; candidate %s; tilt %d.', ...
        r.scene_id,d.q_rmse_m,d.so3_rmse_rad,r.status,r.score.tilt_limited_count); %#ok<AGROW>
    end
end
write_text_new(path,[strjoin(lines,newline) newline]);
end
function verify_control_files(releasePath,releaseSha,lockPath,release,lock)
assert(strcmp(sha256_file(releasePath),releaseSha)&& ...
    strcmp(sha256_file(lockPath),lower(char(release.source_lock_sha256)))&& ...
