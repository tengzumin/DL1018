function rescore_screen12_against_b_v1
% Read-only comparison: existing observer candidate raw logs versus locked B72 logs.
entry=fileparts(fileparts(mfilename('fullpath')));
projectRoot=fileparts(fileparts(fileparts(fileparts(entry))));
screenEntry=fullfile(projectRoot,'experiments','attitude_physics_inertia_observer_20261025', ...
    'paired_runner','morph_dev2_screen12_v1');
attemptDir=fullfile(screenEntry,'attempts','screen12_phys_att_v1_20261025_01');
reviewDir=fullfile(entry,'review');
c5Path=fullfile(projectRoot,'experiments','position_axis_coordinate_c5_dev72_20261023', ...
    'C5_DEV72_INPUT_LOCK_v3.json');
manifestPath=fullfile(screenEntry,'manifest','SCREEN12_PREPARED_MANIFEST.json');
candidateCsv=fullfile(attemptDir,'ROOT_REVIEW_SCREEN12_V1','independent_run_metrics.csv');
c5=jsondecode(fileread(c5Path));manifest=jsondecode(fileread(manifestPath));
assert(strcmp(sha256_file(c5Path),'82024c01276cc4bfbd9b7772cf5332dee3fdfcbed422969589b68f1c90ed2d75'));
assert(strcmp(sha256_file(manifestPath),'322957f7e446dd6a58607f70e0be379d98ad5ed6ae8b3e772fc42f10ea056fba'));
assert(strcmp(sha256_file(candidateCsv),'9d7946e0ef17dd621cc5e0acd5597e6e2adf3a383c795aba161cba25856ef42b'), ...
    'DEV58:CandidateCSV','Existing independent candidate scores changed.');
candidate=readtable(candidateCsv,'TextType','string');
candidate=candidate(candidate.arm=="candidate",:);
ids=string({manifest.scenes.scene_id}).';
assert(height(candidate)==12&&isequal(string(candidate.scene_id),ids));
rows=repmat(struct('scene_id','','w',0,'candidate_raw_sha256','','b_raw_sha256','', ...
    'candidate_q_rmse_m',NaN,'b_q_rmse_m',NaN,'delta_q_candidate_minus_b_m',NaN, ...
    'candidate_so3_rmse_rad',NaN,'b_so3_rmse_rad',NaN,'delta_so3_candidate_minus_b_rad',NaN),1,12);
for i=1:12
    id=char(ids(i));cix=find(strcmp({c5.scenes.scene_id},id));
    assert(numel(cix)==1,'DEV58:Scene','Scene missing from C5 B72 lock: %s',id);
    armDir=fullfile(attemptDir,sprintf('%02d_%s_candidate',i,id));
    candStatusPath=fullfile(armDir,'run_status.json');candStatus=jsondecode(fileread(candStatusPath));
    candRaw=char(candStatus.raw_path);
    assert(strcmp(candStatus.scene_id,id)&&strcmp(candStatus.arm,'candidate')&& ...
        strcmp(candStatus.status,'COMPLETED_SCREEN12')&&strcmp(candStatus.runner_status,'STABLE')&& ...
        candStatus.last_transition==20000&&strcmp(sha256_file(candRaw),candStatus.raw_sha256)&& ...
        strcmpi(char(candidate.raw_sha256(i)),candStatus.raw_sha256), ...
        'DEV58:CandidateRaw','Candidate raw/status identity failed for %s',id);
    b=c5.scenes(cix).B72_scoring;
    assert(strcmp(b.scene_id,id)&&b.plant_calls==1&&strcmp(sha256_file(b.raw_path),b.raw_sha256)&& ...
        strcmp(sha256_file(b.run_status_path),b.run_status_sha256), ...
        'DEV58:BIdentity','B72 raw/status identity failed for %s',id);
    bs=jsondecode(fileread(b.run_status_path));
    assert(strcmp(bs.status,'RUN_COMPLETE_RAW_PENDING_AUDIT')&&strcmp(bs.log_status,'STABLE')&& ...
        isempty(bs.safety_stop_reason)&&bs.last_transition==20000&&bs.transitions==20000&& ...
        bs.plant_calls==1&&~bs.TEST_accessed, ...
        'DEV58:BStatus','B72 run is not a complete stable 20,000-transition B sortie for %s',id);
    cData=load(candRaw,'log');bData=load(b.raw_path,'log');
    cm=score_log(cData.log);bm=score_log(bData.log);
    rows(i)=struct('scene_id',id,'w',double(manifest.scenes(i).wind_id), ...
        'candidate_raw_sha256',candStatus.raw_sha256,'b_raw_sha256',b.raw_sha256, ...
        'candidate_q_rmse_m',cm.q_rmse_m,'b_q_rmse_m',bm.q_rmse_m, ...
        'delta_q_candidate_minus_b_m',cm.q_rmse_m-bm.q_rmse_m, ...
        'candidate_so3_rmse_rad',cm.so3_rmse_rad,'b_so3_rmse_rad',bm.so3_rmse_rad, ...
        'delta_so3_candidate_minus_b_rad',cm.so3_rmse_rad-bm.so3_rmse_rad);
    assert(abs(cm.q_rmse_m-candidate.q_rmse_m(i))<=1e-12&& ...
        abs(cm.so3_rmse_rad-candidate.so3_rmse_rad(i))<=1e-12, ...
        'DEV58:CandidateScore','Independent candidate rescore differs from prior audit for %s',id);
    clear cData bData
end
hf=[rows.w]>=9&[rows.w]<=14;w15=[rows.w]==15;
summary=struct('schema','MORPH_DEV2_SCREEN12_VS_B_RAW_REVIEW_V1', ...
    'status','INDEPENDENT_B_COMPARATOR_RESCORING_COMPLETE','candidate_controller','C5 position stack + frozen physics/observer attitude replacement', ...
    'b_controller','Traceable original B with online position and attitude RBF enabled', ...
    'candidate_position_reference','C5 + original B attitude RBF pair raw independently rescored and SHA-bound', ...
    'b_source_lock_sha256',sha256_file(fullfile(projectRoot,'experiments','b_traceable_c3core_dev72_20261023','B_TRACEABLE_DEV72_INPUT_LOCK_v3.json')), ...
    'c5_input_lock_sha256',sha256_file(c5Path),'screen12_manifest_sha256',sha256_file(manifestPath), ...
    'scene_count',12,'candidate_q_mean_m',mean([rows.candidate_q_rmse_m]), ...
    'b_q_mean_m',mean([rows.b_q_rmse_m]),'q_delta_candidate_minus_b_m',mean([rows.delta_q_candidate_minus_b_m]), ...
    'candidate_so3_mean_rad',mean([rows.candidate_so3_rmse_rad]), ...
    'b_so3_mean_rad',mean([rows.b_so3_rmse_rad]),'so3_delta_candidate_minus_b_rad',mean([rows.delta_so3_candidate_minus_b_rad]), ...
    'candidate_q_wins',nnz([rows.delta_q_candidate_minus_b_m]<0), ...
    'candidate_so3_wins',nnz([rows.delta_so3_candidate_minus_b_rad]<0), ...
    'high_frequency_count',nnz(hf),'high_frequency_q_delta_m',mean([rows(hf).delta_q_candidate_minus_b_m]), ...
    'high_frequency_so3_delta_rad',mean([rows(hf).delta_so3_candidate_minus_b_rad]), ...
    'w15_count',nnz(w15),'w15_q_delta_m',mean([rows(w15).delta_q_candidate_minus_b_m]), ...
    'w15_so3_delta_rad',mean([rows(w15).delta_so3_candidate_minus_b_rad]), ...
    'macro_both_metrics_better',mean([rows.delta_q_candidate_minus_b_m])<0&&mean([rows.delta_so3_candidate_minus_b_rad])<0, ...
    'TEST_accessed',false,'pairs',rows);
if ~isfolder(reviewDir),mkdir(reviewDir);end
writetable(struct2table(rows),fullfile(reviewDir,'SCREEN12_CANDIDATE_VS_B_RAW.csv'));
write_text(fullfile(reviewDir,'SCREEN12_CANDIDATE_VS_B_RAW.json'),jsonencode(summary,'PrettyPrint',true));
fprintf('SCREEN12_VS_B %s Q_delta=%.17g SO3_delta=%.17g Q_wins=%d/12 SO3_wins=%d/12\n', ...
    string(summary.macro_both_metrics_better),summary.q_delta_candidate_minus_b_m, ...
    summary.so3_delta_candidate_minus_b_rad,summary.candidate_q_wins,summary.candidate_so3_wins);
end

function m=score_log(log)
n=20000;
assert(isequal(size(log.time),[n+1,1])&&isequal(size(log.state),[n+1,12])&& ...
    isequal(size(log.reference.position),[n+1,3])&&isequal(size(log.filtered_attitude_reference),[n,3])&& ...
    strcmp(char(log.status),'STABLE')&&isempty(char(log.safety_stop_reason))&&double(log.last_transition)==n);
e=double(log.state(:,1:3))-double(log.reference.position);en=sqrt(sum(e.^2,2));
theta=zeros(n,1);
for k=1:n
    R=rotzyx(double(log.state(k,7:9).'));
    Rd=rotzyx(double(log.filtered_attitude_reference(k,:).'));
    theta(k)=acos(max(min((trace(Rd.'*R)-1)/2,1),-1));
end
assert(all(isfinite([e(:);theta])));
m=struct('q_rmse_m',sqrt(mean(en.^2)),'so3_rmse_rad',sqrt(mean(theta.^2)));
end
function R=rotzyx(e)
r=e(1);p=e(2);y=e(3);cr=cos(r);sr=sin(r);cp=cos(p);sp=sin(p);cy=cos(y);sy=sin(y);
R=[cy*cp,cy*sp*sr-sy*cr,cy*sp*cr+sy*sr; ...
    sy*cp,sy*sp*sr+cy*cr,sy*sp*cr-cy*sr;-sp,cp*sr,cp*cr];
end
function h=sha256_file(p)
fid=fopen(p,'r');assert(fid>=0,'Cannot read %s',p);cl=onCleanup(@()fclose(fid));
md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(b);end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
function write_text(p,s)
fid=fopen(p,'w');assert(fid>=0);cl=onCleanup(@()fclose(fid));
fwrite(fid,unicode2native([s newline],'UTF-8'),'uint8');
end
