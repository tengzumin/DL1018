function audit_prior_dev_reuse_t2
% Independent offline audit of the previously completed T2/W15 candidate raw.
entry=fileparts(fileparts(mfilename('fullpath')));
projectRoot=fileparts(fileparts(fileparts(fileparts(entry))));
sourceRaw=fullfile(projectRoot,'experiments','attitude_physics_inertia_observer_20261025', ...
    'paired_runner','morph_dev2_diagnostic_v1','attempts','MORPH_DEV2_20261025_A02', ...
    '01_DL1018_DEV_T2_C02_W15_candidate','run_raw.mat');
sourceStatus=fullfile(fileparts(sourceRaw),'run_status.json');
pairPath=fullfile(fileparts(fileparts(sourceRaw)),'pair_01_audit.json');
diagnosticBStatusPath=fullfile(fileparts(fileparts(sourceRaw)), ...
    '01_DL1018_DEV_T2_C02_W15_baseline','run_status.json');
c5LockPath=fullfile(projectRoot,'experiments','position_axis_coordinate_c5_dev72_20261023', ...
    'C5_DEV72_INPUT_LOCK_v3.json');
assert(isfile(sourceRaw)&&isfile(sourceStatus)&&isfile(pairPath)&& ...
    isfile(diagnosticBStatusPath)&&isfile(c5LockPath), ...
    'T2Reuse:Files','Prior T2 raw/status/pair/C5 lock is missing.');
sourceStatusValue=jsondecode(fileread(sourceStatus));
diagnosticBStatus=jsondecode(fileread(diagnosticBStatusPath));
pair=jsondecode(fileread(pairPath));c5Lock=jsondecode(fileread(c5LockPath));
ix=find(strcmp({c5Lock.scenes.scene_id},'DL1018_DEV_T2_C02_W15'));
assert(numel(ix)==1,'T2Reuse:C5Lock','Expected one locked T2/W15 B comparator.');
bRef=c5Lock.scenes(ix).B72_scoring;
assert(strcmpi(sha256_file(sourceRaw),sourceStatusValue.raw_sha256)&& ...
    strcmpi(sha256_file(bRef.raw_path),bRef.raw_sha256)&& ...
    strcmpi(sha256_file(bRef.run_status_path),bRef.run_status_sha256), ...
    'T2Reuse:SHA','Candidate or B raw/status SHA differs from its locked record.');
bStatus=jsondecode(fileread(bRef.run_status_path));
assert(strcmp(bStatus.status,'RUN_COMPLETE_RAW_PENDING_AUDIT')&& ...
    strcmp(bStatus.log_status,'STABLE')&&bStatus.last_transition==20000&& ...
    bStatus.transitions==20000&&bStatus.state_samples==20001&&bStatus.plant_calls==1&& ...
    strcmp(bStatus.scene_id,'DL1018_DEV_T2_C02_W15')&& ...
    strcmp(bStatus.external_identity_sha256,c5Lock.scenes(ix).external_identity_sha256), ...
    'T2Reuse:BStatus','Locked original B run is incomplete or belongs to another scene.');
c=load(sourceRaw,'log');b=load(bRef.raw_path,'log');cl=c.log;bl=b.log;
assert(strcmp(cl.status,'STABLE')&&isempty(cl.safety_stop_reason)&&cl.last_transition==20000&& ...
    isequal(size(cl.state),[20001,12])&&isequal(size(cl.time),[20001,1])&& ...
    numel(cl.transition_time)==20000&&isequal(size(bl.state),[20001,12])&& ...
    isequal(size(bl.time),[20001,1])&&numel(bl.transition_time)==20000&& ...
    max(abs(double(bl.time(:))-double(cl.time(:))))<=1e-12&& ...
    max(abs(double(bl.transition_time(:))-double(cl.transition_time(:))))<=1e-12&& ...
    isequal(double(bl.state(1,:)),double(cl.state(1,:))), ...
    'T2Reuse:Complete','Candidate or B raw did not complete the same 20 s timeline.');
refFields={'position','velocity','acceleration','yaw','yaw_rate','yaw_acceleration'};
for k=1:numel(refFields)
    name=refFields{k};assert(isequaln(cl.reference.(name),bl.reference.(name)), ...
        'T2Reuse:Reference','Candidate and B reference differ in %s.',name);
end
assert(isequaln(cl.environment_wind_I,bl.environment_wind_I)&& ...
    isequaln(cl.arms.command,bl.arms.command)&&isequaln(cl.initial_state,bl.initial_state), ...
    'T2Reuse:Scene','Candidate and locked B wind/morphology/initial state differ.');
n=20000;flagFields={'attitude_fusion_rbf_output_enabled','attitude_fusion_rbf_update_enabled'};
for k=1:numel(flagFields)
    name=flagFields{k};assert(isfield(cl,name)&&all_false(cl.(name)), ...
        'T2Reuse:RBFFlag','RBF flag is missing or true: %s.',name);
end
traceFields={'phys_attitude_trace','attitude_event_flag','rbf_output_held', ...
    'rbf_weight_norm','rbf_weight_max','rbf_weight_derivative_norm', ...
    'attitude_rbf_estimate_acceleration_rads2','attitude_rbf_compensation_torque_Nm'};
assert(all(isfield(cl,traceFields))&&iscell(cl.phys_attitude_trace)&& ...
    numel(cl.phys_attitude_trace)==n&&numel(cl.attitude_event_flag)==n&& ...
    zero_axis(cl.rbf_output_held,n)&&zero_axis(cl.attitude_rbf_estimate_acceleration_rads2,n)&& ...
    zero_axis(cl.attitude_rbf_compensation_torque_Nm,n)&& ...
    zero_scalar(cl.rbf_weight_norm,n)&&zero_scalar(cl.rbf_weight_max,n)&& ...
    zero_scalar(cl.rbf_weight_derivative_norm,n), ...
    'T2Reuse:TraceShape','RBF trace dimensions or zero-output history differ.');
traceValid=true;badIndex=0;badReason='';eventCount=0;
for k=1:n
    tr=cl.phys_attitude_trace{k};
    fields={'sample_index','prepare','commit','morph_command','omega_body', ...
        'is_attitude_event','event_delta_s','rbf_output_enabled','rbf_update_enabled'};
    prepFields={'time_s','observer','tau_comp_Nm','estimateTorque_Nm'};
    commitFields={'time_s','tau_cmd_clipped_Nm'};
    valid=isstruct(tr)&&isscalar(tr)&&all(isfield(tr,fields))&& ...
        isstruct(tr.prepare)&&all(isfield(tr.prepare,prepFields))&& ...
        isstruct(tr.commit)&&all(isfield(tr.commit,commitFields))&& ...
        isstruct(tr.prepare.observer)&&all(isfield(tr.prepare.observer,{'updated','delta_s'}))&& ...
        isscalar(tr.sample_index)&&isscalar(tr.prepare.time_s)&&isscalar(tr.commit.time_s)&& ...
        isscalar(tr.is_attitude_event)&&isscalar(tr.rbf_output_enabled)&& ...
        isscalar(tr.rbf_update_enabled)&&isscalar(tr.event_delta_s)&&finite_struct(tr);
    if valid
        valid=tr.sample_index==k&&tr.prepare.time_s==cl.transition_time(k)&& ...
            tr.commit.time_s==cl.transition_time(k)&& ...
            isequal(double(tr.morph_command(:)),double(cl.arms.command(k,:).'))&& ...
            isequal(double(tr.omega_body(:)),double(cl.state(k,10:12).'))&& ...
            isequal(double(tr.commit.tau_cmd_clipped_Nm(:)), ...
                double(cl.controller_clipped_generalized(k,2:4).'))&& ...
            isequal(double(tr.prepare.estimateTorque_Nm(:)),-double(tr.prepare.tau_comp_Nm(:)))&& ...
            logical(tr.is_attitude_event)==logical(cl.attitude_event_flag(k))&& ...
            logical(tr.prepare.observer.updated)==logical(tr.is_attitude_event)&& ...
            ~logical(tr.rbf_output_enabled)&&~logical(tr.rbf_update_enabled);
        if valid&&tr.prepare.observer.updated
            eventCount=eventCount+1;
            valid=tr.prepare.observer.delta_s>0&& ...
                abs(tr.prepare.observer.delta_s-tr.event_delta_s)<1e-10;
        end
    end
    if ~valid,traceValid=false;badIndex=k;badReason='Per-step physical observer/RBF causal lineage mismatch.';break;end
end
assert(traceValid,'T2Reuse:CausalTrace','%s transition=%d.',badReason,badIndex);
scoreCandidate=score_log(cl);scoreB=score_log(bl);
scoreDiffs=[scoreCandidate.q_rmse_m-sourceStatusValue.score.q_rmse_m, ...
    scoreCandidate.so3_rmse_rad-sourceStatusValue.score.so3_rmse_rad, ...
    scoreCandidate.q_rmse_m-pair.candidate.q_rmse_m, ...
    scoreCandidate.so3_rmse_rad-pair.candidate.so3_rmse_rad];
scoreAgreementPass=all(abs(scoreDiffs)<=1e-12);
% The prior diagnostic runner used incompatible numel checks for scalar flags and 3-axis histories.
flagSizes=struct();for k=1:numel(flagFields),flagSizes.(flagFields{k})=size(cl.(flagFields{k}));end
compactPath=fullfile(entry,'review','PRIOR_T2_CANDIDATE_CANONICAL.mat');
assert(isfile(compactPath),'T2Reuse:Canonical','Canonical review copy is missing.');
canonical=load(compactPath,'log');
assert(isstruct(canonical.log.phys_attitude_trace)&& ...
    numel(canonical.log.phys_attitude_trace)==n&& ...
    all_false(canonical.log.attitude_fusion_rbf_output_enabled)&& ...
    all_false(canonical.log.attitude_fusion_rbf_update_enabled), ...
    'T2Reuse:Canonical','Canonical trace copy is invalid.');
report=struct('schema','MORPH_DEV2_PRIOR_T2_REUSE_RAW_REVIEW_V2', ...
    'status','PASS_REUSE_AFTER_INDEPENDENT_CAUSAL_REVIEW', ...
    'scene_id','DL1018_DEV_T2_C02_W15','candidate_source_raw_path',sourceRaw, ...
    'candidate_source_raw_sha256',sha256_file(sourceRaw), ...
    'original_runner_status',sourceStatusValue.status, ...
    'original_runner_failure_reason',sourceStatusValue.engineering_gate.trace_errors, ...
    'old_failure_explained_by','The old diagnostic checker used numel(flag)==n for scalar false flags and numel(axis_history)==n for [n,3] histories; these incompatible shape checks rejected a valid all-false/zero trace before per-step inspection.', ...
    'attitude_rbf_output_enabled_all_false',true,'attitude_rbf_update_enabled_all_false',true, ...
    'rbf_history_all_zero',true,'causal_observer_trace_passed',traceValid, ...
    'causal_trace_samples',n,'observer_update_events',eventCount, ...
    'flag_field_sizes',flagSizes,'same_scene_inputs_as_locked_B',true, ...
    'independent_score_matches_prior_within_1e_12',scoreAgreementPass, ...
    'candidate_score_differences_status_q_so3_pair_q_so3',scoreDiffs, ...
    'diagnostic_pair_B_raw_path',diagnosticBStatus.raw_path, ...
    'diagnostic_pair_B_raw_sha256',diagnosticBStatus.raw_sha256, ...
    'diagnostic_pair_B_is_locked_B72_raw',strcmpi(diagnosticBStatus.raw_sha256,bRef.raw_sha256), ...
    'locked_B_raw_path',bRef.raw_path,'locked_B_raw_sha256',bRef.raw_sha256, ...
    'candidate_scores',scoreCandidate,'B_scores',scoreB, ...
    'candidate_minus_B_q_rmse_m',scoreCandidate.q_rmse_m-scoreB.q_rmse_m, ...
    'candidate_minus_B_so3_rmse_rad',scoreCandidate.so3_rmse_rad-scoreB.so3_rmse_rad, ...
    'canonical_raw_path',compactPath,'canonical_raw_sha256',sha256_file(compactPath), ...
    'canonical_raw_bytes',double(dir(compactPath).bytes), ...
    'canonical_trace_container','20,000-element struct array; numeric/causal fields preserved', ...
    'plant_calls_this_review',0,'training_runs_this_review',0,'TEST_accessed',false);
write_json_new(fullfile(entry,'review','PRIOR_T2_RAW_REUSE_REVIEW_V2.json'),report);
fprintf('T2_REUSE_REVIEW_PASS q_delta=%.17g so3_delta=%.17g source_bytes=%d canonical_bytes=%d trace_samples=%d\n', ...
    report.candidate_minus_B_q_rmse_m,report.candidate_minus_B_so3_rmse_rad, ...
    double(dir(sourceRaw).bytes),report.canonical_raw_bytes,n);
end

function score=score_log(log)
e=double(log.state(:,1:3))-double(log.reference.position);q=sqrt(mean(sum(e.^2,2)));
r=sqrt(mean(e.^2,1));
theta=zeros(20000,1);for k=1:20000
    A=rotation_zyx(double(log.state(k,7:9).'));B=rotation_zyx(double(log.filtered_attitude_reference(k,:).'));
    theta(k)=acos(max(min((trace(B.'*A)-1)/2,1),-1));
end
score=struct('q_rmse_m',q,'q_axis_rmse_m',r,'so3_rmse_rad',sqrt(mean(theta.^2)), ...
    'q_peak_m',max(sqrt(sum(e.^2,2))),'so3_peak_rad',max(theta), ...
    'motor_saturation_count',nnz(any(log.motor_saturated,2)), ...
    'generalized_clip_count',nnz(any(log.generalized_clipped,2)), ...
    'tilt_limited_count',nnz(log.tilt_limited));
end

function R=rotation_zyx(e)
r=e(1);p=e(2);y=e(3);cr=cos(r);sr=sin(r);cp=cos(p);sp=sin(p);cy=cos(y);sy=sin(y);
R=[cy*cp,cy*sp*sr-sy*cr,cy*sp*cr+sy*sr;sy*cp,sy*sp*sr+cy*cr,sy*sp*cr-cy*sr;-sp,cp*sr,cp*cr];
end
function tf=all_false(x),tf=(islogical(x)||isnumeric(x))&&~isempty(x)&&all(isfinite(double(x(:))))&&all(~logical(x(:)));end
function tf=zero_axis(x,n),tf=isnumeric(x)&&isequal(size(x),[n,3])&&all(isfinite(double(x(:))))&&all(x(:)==0);end
function tf=zero_scalar(x,n),tf=isnumeric(x)&&isequal(size(x),[n,1])&&all(isfinite(double(x(:))))&&all(x(:)==0);end
function tf=finite_struct(x)
tf=true;if isnumeric(x),tf=all(isfinite(x(:)));elseif isstruct(x),for v=reshape(x,1,[]),n=fieldnames(v);for k=1:numel(n),if ~finite_struct(v.(n{k})),tf=false;return;end,end,end;elseif iscell(x),for k=1:numel(x),if ~finite_struct(x{k}),tf=false;return;end,end,end
end
function h=sha256_file(p)
f=fopen(p,'r');assert(f>=0,'T2Reuse:Read','Cannot read %s.',p);c=onCleanup(@()fclose(f));m=java.security.MessageDigest.getInstance('SHA-256');while true,b=fread(f,8*1024*1024,'*uint8');if isempty(b),break;end;m.update(b);end;h=lower(reshape(dec2hex(typecast(m.digest(),'uint8'),2).',1,[]));clear c
end
function write_json_new(p,x)
f=java.io.File(p);assert(f.createNewFile(),'T2Reuse:NoOverwrite','Refusing overwrite: %s.',p);fid=fopen(p,'w');assert(fid>=0,'T2Reuse:Write','Cannot write report.');c=onCleanup(@()fclose(fid));fwrite(fid,[jsonencode(x,'PrettyPrint',true) newline],'char');clear c
end
