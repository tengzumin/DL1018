% Three isolated DEV scene payloads only. No runner, Plant step, MAT, or saved scene.
root=fileparts(mfilename('fullpath'));
restoredefaultpath;
addpath(fullfile(root,'matlab','runtime'));
activate_paired_runner();
assert(strcmp(version('-release'),'2025b'),'PAIRED:MATLABRelease','Expected MATLAB R2025b.');
cfg=bind_paired_fixed_j0(default_config());
assert(strcmp(which('make_paired_dev_scene'),fullfile(root,'matlab','scenes','make_paired_dev_scene.m')), ...
    'PAIRED:SceneSource','Scene builder resolved outside paired_runner.');
assert(strcmp(which('default_config'),fullfile(root,'matlab','core','default_config.m')), ...
    'PAIRED:CfgSource','Configuration resolved outside paired_runner.');
assert(strcmp(which('bind_paired_fixed_j0'),fullfile(root,'matlab','runtime','bind_paired_fixed_j0.m')), ...
    'PAIRED:J0Source','J0 binder resolved outside paired_runner.');
Pplant=simulation_parameters(cfg,cfg.plant.arm_initial,zeros(4,1));
Pfixed=controller_parameters(cfg,Pplant,'fixed');
J0=double(cfg.attitude_replacement.J0_controller_fixed_kgm2);
assert(isequal(J0,double(Pfixed.inertia))&& ...
    strcmp(cfg.attitude_replacement.J0_controller_fixed_sha256,paired_sha256_double(J0)), ...
    'PAIRED:J0','Frozen J0 differs from the fixed controller inertia.');
receipt=jsondecode(fileread(fullfile(root,'configs','scene_specs_dev3_receipt.json')));
ids=["DL1018_DEV_T1_C00_W03","DL1018_DEV_T2_C02_W15","DL1018_DEV_T3_C10_W11"];
seeds=[2026121803,2026122847,2026123971];
tasks=["HELIX","FIG8_3D","SQUARE"];
assert(numel(receipt.rows)==3&&isequal(string({receipt.rows.scene_id}),ids), ...
    'PAIRED:Input','DEV receipt IDs differ.');
entry=cell(1,3);
for i=1:3
    out=make_paired_dev_scene(ids(i),cfg);
    assert(istable(out.spec)&&height(out.spec)==1, ...
        'PAIRED:SpecShape','Each scene spec must be one table row.');
    spec=table2struct(out.spec);
    scene=out.scene;
    meta=out.metadata;
    n=20001;
    assert(isequal(size(scene.initial_state),[12,1])&& ...
        all(isfinite(scene.initial_state(:)))&&all(scene.initial_state(:)==0), ...
        'PAIRED:InitialState','Initial state must be finite zero 12-by-1.');
    assert(string(spec.scene_id)==ids(i)&&double(spec.seed)==seeds(i)&& ...
        string(spec.task)==tasks(i)&&double(receipt.rows(i).seed)==seeds(i), ...
        'PAIRED:Spec','Scene spec identity differs.');
    assert(isequal(size(scene.time),[n,1])&& ...
        isequal(scene.time,(0:0.001:20).')&& ...
        all(isfinite(scene.time(:))), 'PAIRED:Time','Time grid differs.');
    ref=scene.reference;
    assert(isequal(size(ref.position),[n,3])&& ...
        isequal(size(ref.velocity),[n,3])&& ...
        isequal(size(ref.acceleration),[n,3])&& ...
        isequal(size(ref.yaw),[n,1])&& ...
        isequal(size(ref.yaw_rate),[n,1])&& ...
        isequal(size(ref.yaw_acceleration),[n,1])&& ...
        all(isfinite(ref.position(:)))&&all(isfinite(ref.velocity(:)))&& ...
        all(isfinite(ref.acceleration(:)))&&all(isfinite(ref.yaw(:)))&& ...
        all(isfinite(ref.yaw_rate(:)))&&all(isfinite(ref.yaw_acceleration(:))), ...
        'PAIRED:Reference','Reference shape or finiteness differs.');
    arms=scene.arms;
    assert(isequal(size(arms.command),[n,4])&& ...
        isequal(size(arms.rho_true),[n,4])&& ...
        isequal(size(arms.rhoDot_true),[n,4])&& ...
        isequal(size(arms.rho_hat),[n,4])&& ...
        isequal(size(arms.rhoDot_hat),[n,4])&& ...
        all(isfinite(arms.command(:)))&&all(isfinite(arms.rho_true(:)))&& ...
        all(isfinite(arms.rhoDot_true(:)))&&all(isfinite(arms.rho_hat(:)))&& ...
        all(isfinite(arms.rhoDot_hat(:))), ...
        'PAIRED:Arms','Morphology shape or finiteness differs.');
    wind=scene.environment_wind_I;
    assert(isequal(size(wind),[n,3])&&all(isfinite(wind(:))), ...
        'PAIRED:Wind','Wind shape or finiteness differs.');
    if double(spec.w)==15
        assert(all(wind(:)==0)&&double(meta.wind_speed_rms_mps)==0&& ...
            double(meta.wind_speed_peak_mps)==0, ...
            'PAIRED:Wind15','W15 must have zero wind.');
    end
    assert(string(scene.scene_id)==ids(i)&&string(meta.scene_id)==ids(i)&& ...
        isfinite(double(meta.wind_speed_rms_mps))&& ...
        isfinite(double(meta.wind_speed_peak_mps)), ...
        'PAIRED:Metadata','Metadata identity or wind statistics differ.');
    if i==1
        assert(isinf(meta.arm_hold_contract_min_s)&& ...
            isinf(meta.arm_retract_margin_min_s), ...
            'PAIRED:C0Sentinel','C0 has no active arms; hold/margin must be Inf sentinels.');
        holdSentinel='C0_NO_ACTIVE_ARMS_INF_TO_JSON_NULL';
    else
        assert(isfinite(meta.arm_hold_contract_min_s)&& ...
            isfinite(meta.arm_retract_margin_min_s), ...
            'PAIRED:ActiveArmTiming','Active-arm hold/margin must be finite.');
        holdSentinel='NONE';
    end
    % Canonicalization: MATLAB R2025b jsonencode defaults, UTF-8, no whitespace rewrite.
    [specHash,specBytes]=json_sha256(spec);
    [sceneHash,sceneBytes]=json_sha256(scene);
    [metaHash,metaBytes]=json_sha256(meta);
    entry{i}=struct('scene_id',char(ids(i)),'seed',double(spec.seed), ...
        'task',char(string(spec.task)),'class_id',char(string(spec.class_id)), ...
        'wind_id',double(spec.w),'source_row_sha256',char(receipt.rows(i).source_row_sha256), ...
        'spec_sha256',specHash,'scene_sha256',sceneHash,'metadata_sha256',metaHash, ...
        'spec_json_utf8_bytes',specBytes,'scene_json_utf8_bytes',sceneBytes, ...
        'metadata_json_utf8_bytes',metaBytes, ...
        'time_size',size(scene.time),'reference_position_size',size(ref.position), ...
        'initial_state_size',size(scene.initial_state), ...
        'wind_size',size(wind),'arm_command_size',size(arms.command), ...
        'wind_rms_mps',double(meta.wind_speed_rms_mps), ...
        'wind_peak_mps',double(meta.wind_speed_peak_mps), ...
        'morph_command_nonzero_count',nnz(arms.command), ...
        'metadata_hold_margin_sentinel',holdSentinel, ...
        'metadata_inactive_arm_start_inf_count',nnz(isinf(meta.arm_start_s)), ...
        'metadata_inactive_arm_retract_inf_count',nnz(isinf(meta.arm_retract_start_s)));
    clear out spec scene meta ref arms wind
end
[cfgHash,cfgBytes]=json_sha256(cfg);
result=struct('schema','PAIRED_DEV3_SCENE_PAYLOAD_HASH_V1', ...
    'status','NOT_FROZEN','closed_loop_runs_authorized',false,'executed',false, ...
    'matlab_release',version('-release'),'matlab_version',version, ...
    'json_canonicalization', ...
    'MATLAB R2025b jsonencode defaults (NaN/Inf to null); UTF-8 bytes; spec table2struct', ...
    'cfg_sha256',cfgHash,'cfg_json_utf8_bytes',cfgBytes, ...
    'J0_controller_fixed_sha256',char(cfg.attitude_replacement.J0_controller_fixed_sha256), ...
    'J0_controller_fixed_kgm2',J0,'scenes',[entry{:}]);
fprintf('PAIRED_DEV3_PAYLOAD_JSON:%s\n',jsonencode(result));

function [hash,nbytes]=json_sha256(value)
bytes=unicode2native(jsonencode(value),'UTF-8');
nbytes=numel(bytes);
md=java.security.MessageDigest.getInstance('SHA-256');
md.update(uint8(bytes(:)));
hash=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
