function [hash,nbytes]=json_sha256(value)
bytes=unicode2native(jsonencode(value),'UTF-8');
nbytes=numel(bytes);
md=java.security.MessageDigest.getInstance('SHA-256');
md.update(uint8(bytes(:)));
hash=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end

function verify_sha(path,expected)
assert(strcmpi(sha256_file(path),expected),'PAIRED:SHA','SHA differs: %s.',path);
end

function hash=sha256_file(path)
md=java.security.MessageDigest.getInstance('SHA-256');
fid=fopen(path,'r');
assert(fid>=0,'PAIRED:ReadFile','Cannot read %s.',path);
cleanup=onCleanup(@()fclose(fid)); %#ok<NASGU>
while true
    bytes=fread(fid,8*1024*1024,'*uint8');
    if isempty(bytes),break;end
    md.update(bytes);
end
hash=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end

function hash=hash_normalizer_arrays(model)
md=java.security.MessageDigest.getInstance('SHA-256');
for names={'input_mu','input_sigma'}
    field=names{1};
    value=reshape(double(model.(field)),1,[]);
    assert(numel(value)==14&&all(isfinite(value))&& ...
        (~strcmp(field,'input_sigma')||all(value>0)), ...
        'PAIRED:Normalizer','Invalid model normalizer.');
    header=[field char(0) '((1, 14), ''float64'')' char(0)];
    md.update(typecast(uint8(unicode2native(header,'UTF-8')),'int8'));
    md.update(typecast(value(:),'int8'));
end
hash=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
