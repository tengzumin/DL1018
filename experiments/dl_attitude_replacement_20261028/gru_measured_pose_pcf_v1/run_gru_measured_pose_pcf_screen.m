function dirs=run_gru_measured_pose_pcf_screen()
% Resume the explicitly released fixed scene screen.
studyRoot=fileparts(mfilename('fullpath'));cd(studyRoot);addpath(studyRoot,'-begin');
release=jsondecode(fileread(fullfile(studyRoot,'RELEASE.json')));
scenes=cellstr(string(release.authorized_scenes));
assert(strcmp(char(release.schema),'DL1018_GRU_STREAM_DEV_RELEASE_V1')&& ...
    strcmp(char(release.variant_schema),'DL1018_GRU_MEASURED_POSE_PCF_RELEASE_V1')&& ...
    strcmp(char(release.study_id),'gru_measured_pose_pcf_v1')&& ...
    strcmp(char(release.status),'RELEASED')&& ...
    double(release.authorized_Plant_calls)==numel(scenes)&& ...
    numel(scenes)<=12,'GRUMPCF:Release','Fixed scene release is not ready for launch.');
dirs=cell(size(scenes));runsRoot=fullfile(studyRoot,'runs');
for i=1:numel(scenes)
    sceneDir=fullfile(runsRoot,scenes{i});statusPath=fullfile(sceneDir,'run_status.json');
    if isfolder(sceneDir)||isfile(statusPath)
        assert(isfile(statusPath),'GRUMPCF:ExistingAttempt', ...
            'Existing attempt for %s is incomplete; refusing to overwrite.',scenes{i});
        status=jsondecode(fileread(statusPath));
        assert(strcmp(char(status.state),'COMPLETED')&&strcmp(char(status.scene_id),scenes{i})&& ...
            strcmp(char(status.candidate),'GRU32_STREAM72_COSINE_MEASURED_POSE_PCF_S2026102001')&& ...
            double(status.Plant_calls)==1&& ...
            strcmpi(char(status.gru_model_sha256),char(release.model_sha256))&& ...
            strcmpi(char(status.source_lock_sha256),char(release.source_lock_sha256)), ...
            'GRUMPCF:ExistingAttempt','Existing attempt for %s is not a matching complete run.',scenes{i});
        dirs{i}=sceneDir;
    else
        dirs{i}=run_gru_measured_pose_pcf_attempt(scenes{i});
    end
end
end
