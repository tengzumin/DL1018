function attemptDir=run_mlp15_dev72_attempt(scenePayloadPath,attemptDir)
% One released frozen-MLP candidate call on an exact DEV72 input scene.
entry=fileparts(mfilename('fullpath'));studyRoot=fileparts(fileparts(fileparts(entry)));
releasePath=fullfile(studyRoot,'MLP15_DEV72_RELEASE_v1.json');
assert(isfile(releasePath),'DEV72:ReleaseMissing','No root-issued DEV72 release exists.');
release=jsondecode(fileread(releasePath));
assert(strcmp(char(release.schema),'DL1018_MLP15_DEV72_RELEASE_V1')&& ...
    strcmp(char(release.status),'RELEASED')&&double(release.plant_calls_authorized)==72&& ...
    strcmp(char(release.candidate_arm_id),'DL_MLP15')&&~logical(release.test_data_read), ...
    'DEV72:Release','Release does not authorize this frozen candidate call.');
taskbookPath=fullfile(studyRoot,'MLP15_DEV72_EXPLORATORY_TASKBOOK_v2.md');
manifestPath=fullfile(studyRoot,'MLP15_DEV72_PAYLOAD_MANIFEST_v2.json');
sourceLockPath=fullfile(studyRoot,'MLP15_DEV72_CANDIDATE_SOURCE_LOCK_v1.json');
auditPath=fullfile(studyRoot,'audits','MLP15_DEV72_NO_PLANT_AUDIT_v1.json');
staticAuditPath=fullfile(studyRoot,'audits','MLP15_DEV72_STATIC_AUDIT_v1.json');
assert(strcmpi(sha256_file(taskbookPath),char(release.taskbook_sha256))&& ...
    strcmpi(sha256_file(manifestPath),char(release.payload_manifest_sha256))&& ...
    strcmpi(sha256_file(sourceLockPath),char(release.candidate_source_lock_sha256))&& ...
    strcmpi(sha256_file(auditPath),char(release.no_plant_audit_sha256))&& ...
    strcmpi(sha256_file(staticAuditPath),char(release.static_audit_sha256))&& ...
    strcmpi(sha256_file(fullfile(studyRoot,'MLP15_DEV72_PAYLOAD_MANIFEST_PARENT_v1.json')), ...
    char(release.parent_payload_manifest_sha256)), ...
    'DEV72:ReleaseHash','Taskbook/input/source/audit changed after release.');
sourceLock=jsondecode(fileread(sourceLockPath));
runnerRoot=fullfile(studyRoot,'candidate_runner_work');verify_candidate_tree(sourceLock,runnerRoot);
prepared=prepare_mlp15_dev72_no_plant(scenePayloadPath);
assert(strcmpi(prepared.mlp15_model_sha256,char(release.mlp15_model_sha256))&& ...
    strcmpi(prepared.c5_input_lock_sha256,char(release.c5_input_lock_sha256))&& ...
    strcmpi(sha256_file(fullfile(runnerRoot,'matlab','runtime','run_mlp15_dev72_closed_loop.m')), ...
    char(release.closed_loop_sha256)), ...
    'DEV72:CandidateIdentity','Model, C5 lock, or closed-loop entry differs from release.');
runsRoot=char(java.io.File(fullfile(studyRoot,'runs')).getCanonicalPath());
attemptDir=char(java.io.File(char(attemptDir)).getCanonicalPath());
assert(startsWith(lower(attemptDir),[lower(runsRoot) filesep])&& ...
    ~isfolder(attemptDir)&&~isfile(attemptDir), ...
    'DEV72:OutputPath','Attempt output must be a new path under the isolated run root.');
markers=dir(fullfile(runsRoot,'**','attempt_started.marker'));
assert(numel(markers)<double(release.plant_calls_authorized), ...
    'DEV72:CallBudget','All released candidate calls have been consumed.');
for i=1:numel(markers)
    priorStart=fullfile(markers(i).folder,'run_start.json');
    if isfile(priorStart)
        old=jsondecode(fileread(priorStart));
        assert(~strcmp(char(old.scene_id),prepared.scene_id), ...
            'DEV72:DuplicateScene','This DEV72 scene already has an attempt marker.');
    end
end
parent=char(java.io.File(fileparts(attemptDir)).getCanonicalPath());
assert(strcmpi(parent,fullfile(runsRoot,prepared.scene_id)), ...
    'DEV72:AttemptParent','Attempt directory must be grouped under its exact scene ID.');
assert(java.io.File(attemptDir).mkdirs(),'DEV72:AttemptCreate','Could not create a new attempt directory.');
startedUtc=utcNow();
runIdentity=struct('schema','DL1018_MLP15_DEV72_RUN_START_V1', ...
    'scene_id',prepared.scene_id,'attitude_arm','DL_MLP15','geometry_arm','ACTIVE', ...
    'started_utc',startedUtc,'release_sha256',sha256_file(releasePath), ...
    'taskbook_sha256',char(release.taskbook_sha256), ...
    'payload_manifest_sha256',char(release.payload_manifest_sha256), ...
    'candidate_source_lock_sha256',char(release.candidate_source_lock_sha256), ...
    'payload_sha256',prepared.scene_payload_sha256, ...
    'external_identity_sha256',prepared.external_identity_sha256, ...
    'b_raw_sha256',prepared.b_raw_sha256,'b_status_sha256',prepared.b_status_sha256, ...
    'c5_input_lock_sha256',prepared.c5_input_lock_sha256, ...
    'c5_snapshot_sha256',prepared.c5_snapshot_sha256, ...
    'position_model_sha256',prepared.position_model_sha256, ...
    'mlp15_model_sha256',prepared.mlp15_model_sha256, ...
    'mlp15_best_step',prepared.mlp15_best_step, ...
    'common_position_options_sha256',prepared.identity.common.position_options_sha256, ...
    'candidate_attitude_arm','DL_MLP15','observer_enabled',false, ...
    'physics_feedforward_enabled',false,'inertia_reconstruction_enabled',false, ...
    'controller_inputs','13 causal runtime features only','test_data_read',false, ...
    'closed_loop_entry','run_mlp15_dev72_closed_loop(scene,cfg,opts)');
write_json(fullfile(attemptDir,'attempt_started.marker'),struct( ...
    'schema','DL1018_MLP15_DEV72_ATTEMPT_MARKER_V1','scene_id',prepared.scene_id, ...
    'created_utc',startedUtc,'stage','RUNNING'));
write_json(fullfile(attemptDir,'run_start.json'),runIdentity);
try
    log=run_mlp15_dev72_closed_loop(prepared.scene,prepared.cfg,prepared.opts);
    transitions=double(log.last_transition);
    stateSamples=size(log.state,1);
    complete=transitions==20000&&stateSamples==20001&&strcmp(char(log.status),'STABLE');
    assert(complete,'DEV72:Incomplete','Candidate did not finish a stable 20,000-transition run.');
    scene=prepared.scene;save(fullfile(attemptDir,'raw_run.mat'),'log','scene','runIdentity','-v7.3');
    rawPath=fullfile(attemptDir,'raw_run.mat');
    status=struct('schema','DL1018_MLP15_DEV72_RUN_STATUS_V1','state','COMPLETED', ...
        'scene_id',prepared.scene_id,'attitude_arm','DL_MLP15','geometry_arm','ACTIVE', ...
        'finished_utc',utcNow(),'plant_calls',1,'raw_path',rawPath, ...
        'raw_sha256',sha256_file(rawPath),'transitions',transitions, ...
        'state_samples',stateSamples,'status_value',char(log.status), ...
        'safety_stop_reason',char(log.safety_stop_reason), ...
        'payload_sha256',prepared.scene_payload_sha256, ...
        'b_raw_sha256',prepared.b_raw_sha256,'source_lock_sha256',char(release.candidate_source_lock_sha256), ...
        'test_data_read',false);
    write_json(fullfile(attemptDir,'run_status.json'),status);
    fprintf('MLP15_DEV72_ATTEMPT_DIR=%s',attemptDir);
catch ME
    status=struct('schema','DL1018_MLP15_DEV72_RUN_STATUS_V1','state','FAILED', ...
        'scene_id',prepared.scene_id,'attitude_arm','DL_MLP15','geometry_arm','ACTIVE', ...
        'failed_utc',utcNow(),'plant_calls',1,'error_identifier',char(ME.identifier), ...
        'error_message',char(ME.message),'payload_sha256',prepared.scene_payload_sha256, ...
        'b_raw_sha256',prepared.b_raw_sha256,'source_lock_sha256',char(release.candidate_source_lock_sha256), ...
        'test_data_read',false);
    write_json(fullfile(attemptDir,'run_status.json'),status);rethrow(ME);
end
end
function verify_candidate_tree(lock,runnerRoot)
assert(strcmp(char(lock.schema),'DL1018_MLP15_DEV72_CANDIDATE_SOURCE_LOCK_V1')&& ...
    strcmpi(char(java.io.File(char(lock.root)).getCanonicalPath()), ...
    char(java.io.File(runnerRoot).getCanonicalPath())), ...
    'DEV72:SourceLockRoot','Unexpected candidate source root.');
files=dir(fullfile(runnerRoot,'matlab','**','*.m'));
assert(numel(files)==numel(lock.files),'DEV72:SourceCount','Locked source count changed.');
for i=1:numel(lock.files)
    path=fullfile(runnerRoot,char(lock.files(i).relative_path));
    canonical=char(java.io.File(path).getCanonicalPath());
    assert(isfile(path)&&strcmpi(sha256_file(path),char(lock.files(i).sha256))&& ...
        startsWith(lower(canonical),[lower(char(java.io.File(runnerRoot).getCanonicalPath())) filesep]), ...
        'DEV72:SourceHash','Candidate source changed/escaped: %s.',path);
end
end
function h=sha256_file(path)
fid=fopen(path,'rb');assert(fid>=0,'DEV72:Read','Cannot read %s.',path);
cleanup=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear cleanup;
end
function write_json(path,x)
fid=fopen(path,'w');assert(fid>=0,'DEV72:Write','Cannot write %s.',path);
cleanup=onCleanup(@()fclose(fid));fwrite(fid,[jsonencode(x,'PrettyPrint',true) newline],'char');clear cleanup;
end
function s=utcNow()
s=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z'''));
end




