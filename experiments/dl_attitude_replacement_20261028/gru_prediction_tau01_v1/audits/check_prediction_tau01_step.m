function result=check_prediction_tau01_step()
% Compare one pure delayed-head event against the frozen parent tau=1 helper.
studyRoot=fileparts(fileparts(mfilename('fullpath')));
projectRoot=fileparts(fileparts(fileparts(studyRoot)));
candidateRuntime=fullfile(studyRoot,'candidate_runner_work','matlab','runtime');
parentRuntime=fullfile(projectRoot,'experiments','dl_attitude_replacement_20261026', ...
    'gru_stream_cosine_tracking_head_full72_v1','candidate_runner_work','matlab','runtime');
W=zeros(33,3);phi=zeros(33,1);phi(1)=1;s=zeros(3,1);
phiPrev=zeros(33,1);phiPrev(2)=1;yPrev=[2;-1;0.5];
n=330;tN=n*.001;j=320;tJ=j*.001;
args={W,phi,s,n,tN,phiPrev,yPrev,j,tJ};
addpath(parentRuntime,'-begin');clear delayed_prediction_step_candidate;
parent=delayed_prediction_step_candidate(args{:});
rmpath(parentRuntime);addpath(candidateRuntime,'-begin');clear delayed_prediction_step_candidate;
candidate=delayed_prediction_step_candidate(args{:});
expectedTau1=.01*(phiPrev*yPrev.');expectedTau01=.1*(phiPrev*yPrev.');
assert(max(abs(parent.W_next-expectedTau1),[],'all')<1e-14&& ...
    max(abs(candidate.W_next-expectedTau01),[],'all')<1e-14&& ...
    isequal(candidate.raw,zeros(3,1))&&isequal(candidate.applied,zeros(3,1))&& ...
    abs(norm(candidate.W_next,'fro')-10*norm(parent.W_next,'fro'))<1e-12, ...
    'PredictionTau01:Step','Expected output-before-update zero and 10x delayed gradient update.');
result=struct('status','PASS','h_s',.01,'tau_parent_s',1,'rho_parent',.01, ...
    'tau_candidate_s',.1,'rho_candidate',.1,'parent_Wnext_norm',norm(parent.W_next,'fro'), ...
    'candidate_Wnext_norm',norm(candidate.W_next,'fro'), ...
    'candidate_current_raw',candidate.raw,'candidate_current_applied',candidate.applied, ...
    'phi_prev_norm',norm(phiPrev),'s_eff_norm',norm(s),'y_prev',yPrev, ...
    'n_zero_based',n,'j_zero_based',j);
end
