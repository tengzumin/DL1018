function attemptDir=run_dc_penalty_full24_single_pilot()
% One root-authorized fixed-scene diagnostic using the frozen DC-penalty model.
here=fileparts(mfilename('fullpath'));studyRoot=fileparts(here);
releasePath=fullfile(studyRoot,'RELEASE.json');lockPath=fullfile(studyRoot,'SOURCE_LOCK_v1.json');
release=jsondecode(fileread(releasePath));lock=jsondecode(fileread(lockPath));
assert(strcmp(char(release.study_id),'position_teacher_dc_penalty_full24_preflight_v1')&& ...
    strcmp(char(release.status),'RELEASED')&&double(release.authorized_Plant_calls)==1&& ...
    double(release.Plant_calls)==1&&strcmp(char(release.fixed_scene_id),'DL1018_VAL_T3_C01_W14')&& ...
    ~logical(release.TEST_read)&&~logical(release.inertia_reconstruction_enabled), ...
    'PositionDCPilot:Release','Release does not authorize exactly one diagnostic scene.');
assert(strcmpi(sha256_file(lockPath),char(release.source_lock_sha256))&& ...
    numel(lock.files)==double(lock.file_count)&&double(release.source_file_count)==double(lock.file_count), ...
    'PositionDCPilot:Lock','Source-lock SHA/count mismatch.');
for i=1:numel(lock.files)
    rec=lock.files(i);path=fullfile(studyRoot,strrep(char(rec.relative_path),'/',filesep));
    assert(isfile(path)&&strcmpi(sha256_file(path),char(rec.sha256)), ...
        'PositionDCPilot:SourceSHA','Locked source changed: %s.',path);
end
for i=1:numel(lock.external_inputs)
    rec=lock.external_inputs(i);path=char(rec.path);
    assert(isfile(path)&&strcmpi(sha256_file(path),char(rec.sha256)), ...
        'PositionDCPilot:ExternalSHA','Bound input changed: %s.',path);
end
noPlantPath=fullfile(studyRoot,'NO_PLANT_PREPARE_RESULT_v1.json');
noPlant=jsondecode(fileread(noPlantPath));noPlantReleasePath=fullfile(studyRoot,'RELEASE_NO_PLANT_v1.json');
assert(strcmp(char(noPlant.status),'PASS_STOPPED_BEFORE_PLANT')&& ...
    strcmp(char(noPlant.study_id),char(release.study_id))&&strcmp(char(noPlant.scene_id),char(release.fixed_scene_id))&& ...
    strcmpi(char(noPlant.source_lock_sha256),char(release.source_lock_sha256))&& ...
    strcmpi(sha256_file(noPlantReleasePath),char(noPlant.release_sha256))&& ...
    strcmpi(sha256_file(fullfile(studyRoot,'MLP15_DEV72_PAYLOAD_MANIFEST_v2.json')),char(release.payload_manifest_sha256)), ...
    'PositionDCPilot:NoPlantReceipt','No-Plant receipt/snapshot does not bind this run.');
sceneId=char(release.fixed_scene_id);assert(strcmp(sceneId,'DL1018_VAL_T3_C01_W14'), ...
    'PositionDCPilot:Scene','Only the fixed VAL diagnostic scene is permitted.');
runsRoot=fullfile(studyRoot,'runs');assert(~isfolder(runsRoot), ...
    'PositionDCPilot:PriorRun','A prior run directory exists; refusing another Plant call.');
sceneRunRoot=fullfile(runsRoot,sceneId);assert(mkdir(runsRoot)&&mkdir(sceneRunRoot), ...
    'PositionDCPilot:RunRoot','Could not create the one-call run folder.');
attemptDir=fullfile(sceneRunRoot,'attempt_001');assert(mkdir(attemptDir), ...
    'PositionDCPilot:AttemptFolder','Could not create attempt_001.');

parentTauStudy=fileparts(char(release.parent_tau01_release_path));oldDir=pwd;restore=onCleanup(@()cd(oldDir));
addpath(fullfile(parentTauStudy,'candidate_runner_work','matlab','runtime'),'-begin');
cd(parentTauStudy);prepared=prepare_gru_prediction_tau01_no_plant(sceneId,false);
cd(studyRoot);clear restore;
ownRuntime=fullfile(studyRoot,'candidate_runner_work','matlab','runtime');addpath(ownRuntime,'-begin');
runnerRoot=activate_paired_runner();
assert(strcmpi(char(java.io.File(runnerRoot).getCanonicalPath()), ...
    char(java.io.File(fullfile(studyRoot,'candidate_runner_work')).getCanonicalPath())), ...
    'PositionDCPilot:RunnerRoot','Runner resolved outside isolated DC study.');
modelPath=fullfile(studyRoot,strrep(char(release.position_residual_gru.weights_relative_path),'/',filesep));
m=load(modelPath);runtime=prepared.opts.stage1_position_runtime;
runtime.residual_gru=struct('enabled',true,'weights_sha256',char(release.position_residual_gru.weights_sha256), ...
    'input_mean',double(m.input_mean(:)),'input_std',double(m.input_std(:)), ...
    'gru_weight_ih_l0',double(m.gru_weight_ih_l0),'gru_weight_hh_l0',double(m.gru_weight_hh_l0), ...
    'gru_bias_ih_l0',double(m.gru_bias_ih_l0(:)),'gru_bias_hh_l0',double(m.gru_bias_hh_l0(:)), ...
    'head_weight',double(m.head_weight),'head_bias',double(m.head_bias(:)), ...
    'beta_rise_time_s',1.8,'delta_limit_mps2',.5,'action_limit_mps2',3.0);
opts=prepared.opts;opts.stage1_position_runtime=runtime;opts.no_plant_boundary_check=false;
markerPath=fullfile(attemptDir,'composite_attempt_marker.json');
marker=struct('scene_id',sceneId,'stage','RUNNING','created_utc',utcNow());write_json(markerPath,marker);
opts.composite_attempt_marker=markerPath;identityOpts=rmfield(opts,'composite_attempt_marker');
opts.gate_identity_lock=gate_holdout_identity_hashes(prepared.cfg,prepared.position_model,identityOpts);
runIdentity=struct('schema','POSITION_TEACHER_DC_PENALTY_FULL24_SINGLE_RUN_START_V1', ...
    'study_id',char(release.study_id),'scene_id',sceneId,'candidate_arm_id',char(release.candidate_arm_id), ...
    'started_utc',utcNow(),'release_sha256',sha256_file(releasePath), ...
    'release_no_plant_sha256',char(noPlant.release_sha256),'source_lock_sha256',char(release.source_lock_sha256), ...
    'weights_sha256',char(release.position_residual_gru.weights_sha256), ...
    'checkpoint_sha256',char(release.position_residual_gru.checkpoint_sha256), ...
    'training_data_sha256',char(release.training_data_sha256),'dc_cv_oof_sha256',char(release.dc_cv_oof_sha256), ...
    'scene_payload_sha256',prepared.scene_payload_sha256,'external_identity_sha256',prepared.external_identity_sha256, ...
    'B_raw_sha256',prepared.b_raw_sha256,'position_model_sha256',prepared.position_model_sha256, ...
    'parent_tau01_release_sha256',char(release.parent_tau01_release_sha256), ...
    'controller_arm','GRU_STREAM','geometry_arm','ACTIVE','position_method_id','C5_AXIS_MIXED_COORDINATE_M110', ...
    'position_delayed_prediction_h_s',.01,'position_delayed_prediction_tau_s',.1, ...
    'position_delayed_prediction_rho',.1,'notch_enabled',false,'model_input','causal X14 only', ...
    'teacher_at_inference',false,'first_event_time_s',.01,'first_ready_event_index_zero_based',31, ...
    'first_ready_event_time_s',.32,'beta_formula','clip(event_time_s/1.8,0,1)', ...
    'delta_clip_mps2',.5,'total_action_clip_mps2',3,'test_data_read',false, ...
    'inertia_reconstruction_enabled',false,'development_diagnostic_not_independent_validation',true, ...
    'no_plant_preflight_receipt_path',noPlantPath,'entry','run_mlp15_dev72_closed_loop');
write_json(fullfile(attemptDir,'run_start.json'),runIdentity);firstStep=fullfile(attemptDir,'first_plant_step.marker');
try
    log=run_mlp15_dev72_closed_loop(prepared.scene,prepared.cfg,opts);
    transitions=double(log.last_transition);stateSamples=size(log.state,1);
    complete=transitions==20000&&stateSamples==20001&&strcmp(char(log.status),'STABLE');
    assert(complete,'PositionDCPilot:Incomplete','Expected a stable 20,000-transition run.');
    scene=prepared.scene;save(fullfile(attemptDir,'raw_run.mat'),'log','scene','runIdentity','-v7.3');
    rawPath=fullfile(attemptDir,'raw_run.mat');status=struct( ...
        'schema','POSITION_TEACHER_DC_PENALTY_FULL24_RUN_STATUS_V1','state','COMPLETED', ...
        'study_id',char(release.study_id),'scene_id',sceneId,'candidate_arm_id',char(release.candidate_arm_id), ...
        'finished_utc',utcNow(),'plant_calls',1,'raw_path',rawPath,'raw_sha256',sha256_file(rawPath), ...
        'transitions',transitions,'state_samples',stateSamples,'status_value',char(log.status), ...
        'safety_stop_reason',char(log.safety_stop_reason),'release_sha256',sha256_file(releasePath), ...
        'release_no_plant_sha256',char(noPlant.release_sha256),'source_lock_sha256',char(release.source_lock_sha256), ...
        'scene_payload_sha256',prepared.scene_payload_sha256,'B_raw_sha256',prepared.b_raw_sha256, ...
        'first_plant_step_marker_exists',isfile(firstStep),'TEST_read',false,'test_data_read',false, ...
        'inertia_reconstruction_enabled',false,'independent_validation',false);
    write_json(fullfile(attemptDir,'run_status.json'),status);marker.stage='COMPLETED';marker.finished_utc=utcNow();
    write_json(markerPath,marker);
catch ME
    plantReached=isfile(firstStep);status=struct('schema','POSITION_TEACHER_DC_PENALTY_FULL24_RUN_STATUS_V1', ...
        'state','FAILED','study_id',char(release.study_id),'scene_id',sceneId, ...
        'candidate_arm_id',char(release.candidate_arm_id),'failed_utc',utcNow(), ...
        'plant_calls',double(plantReached),'first_plant_step_marker_exists',plantReached, ...
        'error_identifier',char(ME.identifier),'error_message',char(ME.message), ...
        'release_sha256',sha256_file(releasePath),'release_no_plant_sha256',char(noPlant.release_sha256), ...
        'source_lock_sha256',char(release.source_lock_sha256),'TEST_read',false,'test_data_read',false);
    write_json(fullfile(attemptDir,'run_status.json'),status);marker.stage='FAILED';
    marker.error_identifier=char(ME.identifier);write_json(markerPath,marker);rethrow(ME);
end
end

function h=sha256_file(path)
fid=fopen(path,'rb');assert(fid>=0,'PositionDCPilot:Read','Cannot read %s.',path);
clean=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear clean;
end
function write_json(path,value)
fid=fopen(path,'w','n','UTF-8');assert(fid>=0);clean=onCleanup(@()fclose(fid));
fprintf(fid,'%s\n',jsonencode(value,'PrettyPrint',true));clear clean;
end
function s=utcNow()
s=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z'''));
end
