function report=prepare_no_plant_check()
% Freeze-check the DC-penalty runtime and stop at the pre-Plant boundary.
here=fileparts(mfilename('fullpath'));studyRoot=fileparts(here);
releasePath=fullfile(studyRoot,'RELEASE.json');lockPath=fullfile(studyRoot,'SOURCE_LOCK_v1.json');
release=jsondecode(fileread(releasePath));lock=jsondecode(fileread(lockPath));
assert(strcmp(char(release.study_id),'position_teacher_dc_penalty_full24_preflight_v1')&& ...
    strcmp(char(release.status),'PREPARED_NO_PLANT_PENDING_ROOT_AUDIT')&& ...
    double(release.authorized_Plant_calls)==0&&double(release.Plant_calls)==0&& ...
    ~logical(release.TEST_read)&&~logical(release.inertia_reconstruction_enabled), ...
    'PositionDCPenaltyPreflight:Release','No-Plant release/scope check failed.');
assert(strcmpi(sha256_file(lockPath),char(release.source_lock_sha256))&& ...
    numel(lock.files)==double(lock.file_count)&&double(release.source_file_count)==double(lock.file_count), ...
    'PositionDCPenaltyPreflight:Lock','Source-lock SHA/count mismatch.');
for i=1:numel(lock.files)
    rec=lock.files(i);path=fullfile(studyRoot,strrep(char(rec.relative_path),'/',filesep));
    assert(isfile(path)&&strcmpi(sha256_file(path),char(rec.sha256)), ...
        'PositionDCPenaltyPreflight:SourceSHA','Locked source changed: %s.',path);
end
for i=1:numel(lock.external_inputs)
    rec=lock.external_inputs(i);path=char(rec.path);
    assert(isfile(path)&&strcmpi(sha256_file(path),char(rec.sha256)), ...
        'PositionDCPenaltyPreflight:ExternalSHA','Bound source changed: %s.',path);
end
assert(strcmpi(sha256_file(char(release.parent_tau01_release_path)),char(release.parent_tau01_release_sha256))&& ...
    strcmpi(sha256_file(char(release.parent_cosine_release_path)),char(release.parent_cosine_release_sha256)), ...
    'PositionDCPenaltyPreflight:ParentSHA','Parent release identity changed.');
weightsPath=fullfile(studyRoot,strrep(char(release.position_residual_gru.weights_relative_path),'/',filesep));
assert(strcmpi(sha256_file(weightsPath),char(release.position_residual_gru.weights_sha256)), ...
    'PositionDCPenaltyPreflight:WeightsSHA','Runtime model file differs from the frozen release.');
payloadPath=fullfile(studyRoot,'MLP15_DEV72_PAYLOAD_MANIFEST_v2.json');
assert(strcmpi(sha256_file(payloadPath),char(release.payload_manifest_sha256)), ...
    'PositionDCPenaltyPreflight:PayloadSHA','Copied DEV/VAL payload manifest differs from release.');
sceneId=char(release.fixed_scene_id);
assert(strcmp(sceneId,'DL1018_VAL_T3_C01_W14')&&any(strcmp(cellstr(string(release.authorized_scenes)),sceneId)), ...
    'PositionDCPenaltyPreflight:Scene','Unexpected fixed scene identity.');

% Require exact parity over every TRAIN event before configuring the no-Plant call.
parity=check_matlab_eventwise_parity_v1();
assert(strcmp(parity.status,'PASS_TRAIN24_EVENTWISE_PARITY')&&~logical(parity.plant_called), ...
    'PositionDCPenaltyPreflight:Parity','MATLAB/Python eventwise parity failed.');

tauStudy=fileparts(char(release.parent_tau01_release_path));
parentRuntime=fullfile(tauStudy,'candidate_runner_work','matlab','runtime');
addpath(parentRuntime,'-begin');oldDir=pwd;restore=onCleanup(@()cd(oldDir));
cd(tauStudy);prepared=prepare_gru_prediction_tau01_no_plant(sceneId,false);
cd(studyRoot);clear restore;
ownRuntime=fullfile(studyRoot,'candidate_runner_work','matlab','runtime');addpath(ownRuntime,'-begin');
candidateRoot=activate_paired_runner();
assert(strcmpi(char(java.io.File(candidateRoot).getCanonicalPath()), ...
    char(java.io.File(fullfile(studyRoot,'candidate_runner_work')).getCanonicalPath())), ...
    'PositionDCPenaltyPreflight:RunnerRoot','Runner did not resolve from the isolated study.');
mat=load(weightsPath);runtime=prepared.opts.stage1_position_runtime;
runtime.residual_gru=struct('enabled',true,'weights_sha256',char(release.position_residual_gru.weights_sha256), ...
    'input_mean',double(mat.input_mean(:)),'input_std',double(mat.input_std(:)), ...
    'gru_weight_ih_l0',double(mat.gru_weight_ih_l0),'gru_weight_hh_l0',double(mat.gru_weight_hh_l0), ...
    'gru_bias_ih_l0',double(mat.gru_bias_ih_l0(:)),'gru_bias_hh_l0',double(mat.gru_bias_hh_l0(:)), ...
    'head_weight',double(mat.head_weight),'head_bias',double(mat.head_bias(:)), ...
    'beta_rise_time_s',1.8,'delta_limit_mps2',.5,'action_limit_mps2',3.0);
opts=prepared.opts;opts.stage1_position_runtime=runtime;opts.no_plant_boundary_check=true;
markerPath=fullfile(here,['NO_PLANT_ATTEMPT_' datestr(now,'yyyymmddTHHMMSSFFF') '.json']);
marker=struct('study_id',char(release.study_id),'scene_id',sceneId,'stage','RUNNING', ...
    'created_utc',char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z''')));
write_json(markerPath,marker);opts.composite_attempt_marker=markerPath;
identityOpts=rmfield(opts,'composite_attempt_marker');
opts.gate_identity_lock=gate_holdout_identity_hashes(prepared.cfg,prepared.position_model,identityOpts);
caught='';expectedId='PositionNotch:NoPlantPreflightStop';
try
    run_mlp15_dev72_closed_loop(prepared.scene,prepared.cfg,opts);
catch ME
    caught=ME.identifier;if ~strcmp(caught,expectedId),rethrow(ME);end
end
assert(strcmp(caught,expectedId),'PositionDCPenaltyPreflight:Boundary','Did not stop at the no-Plant boundary.');
marker.stage='STOPPED_BEFORE_PLANT';write_json(markerPath,marker);
assert(~isfile(fullfile(fileparts(markerPath),'first_plant_step.marker'))&&no_run_history(studyRoot), ...
    'PositionDCPenaltyPreflight:Plant','Unexpected Plant marker or run history exists.');
report=struct('schema','POSITION_TEACHER_DC_PENALTY_FULL24_NO_PLANT_PREPARE_V1', ...
    'status','PASS_STOPPED_BEFORE_PLANT','study_id',char(release.study_id),'scene_id',sceneId, ...
    'parent_tau01_release_sha256',char(release.parent_tau01_release_sha256), ...
    'parent_cosine_release_sha256',char(release.parent_cosine_release_sha256), ...
    'source_lock_sha256',char(release.source_lock_sha256),'release_sha256',sha256_file(releasePath), ...
    'weights_sha256',char(release.position_residual_gru.weights_sha256), ...
    'model_manifest_sha256',char(release.position_residual_gru.model_manifest_sha256), ...
    'resolved_runner_root',candidateRoot,'resolved_runner_entry',which('run_mlp15_dev72_closed_loop'), ...
    'no_plant_boundary_error',caught,'plant_called',false,'Plant_calls',0,'authorized_Plant_calls',0, ...
    'test_data_read',false,'inertia_reconstruction_enabled',false, ...
    'position_method_id','C5_AXIS_MIXED_COORDINATE_M110','position_delayed_prediction_tau_s',.1, ...
    'position_delayed_prediction_rho',.1,'dc_penalty_training_objective',char(release.position_residual_gru.objective), ...
    'model_input','causal X14 only','teacher_used_at_runtime',false, ...
    'hidden_reset_per_scene',true,'hidden_updates_during_warmup',true, ...
    'first_event_time_s',.01,'first_ready_event_index_zero_based',31,'first_ready_event_time_s',.32, ...
    'beta_formula','clip(event_time_s/1.8,0,1)','delta_clip_mps2',.5,'total_action_clip_mps2',3, ...
    'runtime_event_loop_executed',false,'prior_run_history_exists',false,'eventwise_parity_result',parity);
write_json(fullfile(studyRoot,'NO_PLANT_PREPARE_RESULT_v1.json'),report);
end

function ok=no_run_history(studyRoot)
ok=~isfolder(fullfile(studyRoot,'runs'));
end
function h=sha256_file(path)
fid=fopen(path,'rb');assert(fid>=0,'PositionDCPenaltyPreflight:Read','Cannot read %s.',path);
clean=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear clean;
end
function write_json(path,value)
fid=fopen(path,'w','n','UTF-8');assert(fid>=0);clean=onCleanup(@()fclose(fid));
fprintf(fid,'%s\n',jsonencode(value,'PrettyPrint',true));clear clean;
end
