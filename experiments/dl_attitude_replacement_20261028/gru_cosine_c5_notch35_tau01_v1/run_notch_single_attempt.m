function attemptDir=run_notch_single_attempt()
% Run the fixed C01_W14 interaction probe after a one-call root release.
studyRoot=fileparts(mfilename('fullpath'));releasePath=fullfile(studyRoot,'RELEASE.json');
release=jsondecode(fileread(releasePath));sceneId=char(release.fixed_scene_id);
authorizedScenes=reshape(cellstr(string(release.authorized_scenes)),1,[]);
assert(strcmp(char(release.schema),'DL1018_GRU_POSITION_APPLIED_NOTCH_TAU01_NOPLANT_V1')&& ...
    strcmp(char(release.study_id),'gru_cosine_c5_notch35_tau01_v1')&& ...
    strcmp(char(release.status),'RELEASED')&&double(release.authorized_Plant_calls)==1&& ...
    double(release.Plant_calls)==0&&isscalar(authorizedScenes)&& ...
    strcmp(authorizedScenes{1},sceneId)&&strcmp(sceneId,'DL1018_VAL_T3_C01_W14'), ...
    'PositionNotchTau01:PlantAuthorization','A root-reviewed one-call release is required.');

sourceLockPath=fullfile(studyRoot,'SOURCE_LOCK_v1.json');
assert(strcmpi(sha256_file(sourceLockPath),char(release.source_lock_sha256)), ...
    'PositionNotchTau01:SourceLock','Source lock does not match the release.');
sourceLock=jsondecode(fileread(sourceLockPath));
for i=1:numel(sourceLock.files)
    rec=sourceLock.files(i);path=fullfile(studyRoot,strrep(char(rec.path),'/',filesep));
    assert(isfile(path)&&strcmpi(sha256_file(path),char(rec.sha256)), ...
        'PositionNotchTau01:SourceHash','Isolated source changed: %s.',path);
end
payloadManifestPath=fullfile(studyRoot,'MLP15_DEV72_PAYLOAD_MANIFEST_v2.json');
assert(strcmpi(sha256_file(payloadManifestPath),char(release.parent_payload_manifest_sha256))&& ...
    strcmpi(sha256_file(char(release.parent_notch_hf6_release_path)), ...
        char(release.parent_notch_hf6_release_sha256))&& ...
    strcmpi(sha256_file(char(release.parent_notch_hf6_source_lock_path)), ...
        char(release.parent_notch_hf6_source_lock_sha256)), ...
    'PositionNotchTau01:ParentBinding','Payload or parent notch source binding changed.');

projectRoot=fileparts(fileparts(fileparts(studyRoot)));
parentRoot=fullfile(projectRoot,'experiments','dl_attitude_replacement_20261028','gru_prediction_tau01_v1');
oldFolder=pwd;restoreFolder=onCleanup(@()cd(oldFolder));cd(parentRoot);
addpath(fullfile(parentRoot,'candidate_runner_work','matlab','runtime'),'-begin');
clear activate_paired_runner prepare_gru_prediction_tau01_no_plant;
prepared=prepare_gru_prediction_tau01_no_plant(sceneId,false);
cd(studyRoot);restoredefaultpath;rehash toolboxcache;
candidateRuntime=fullfile(studyRoot,'candidate_runner_work','matlab','runtime');
addpath(candidateRuntime,'-begin');clear activate_paired_runner;
runnerRoot=activate_paired_runner();
assert(strcmpi(which('run_mlp15_dev72_closed_loop'), ...
    fullfile(runnerRoot,'matlab','runtime','run_mlp15_dev72_closed_loop.m'))&& ...
    strcmp(sceneId,char(prepared.scene.scene_id)), ...
    'PositionNotchTau01:RunnerBinding','Runner path or fixed scene binding changed.');

notch=release.applied_acceleration_notch;
prepared.opts.stage1_position_runtime.applied_acceleration_notch=struct( ...
    'enabled',logical(notch.enabled),'center_hz',double(notch.center_hz), ...
    'quality_factor',double(notch.quality_factor),'sample_rate_hz',double(notch.sample_rate_hz), ...
    'b',double(notch.b(:).'),'a',double(notch.a(:).'),'initial_state',zeros(3,4));
prepared.opts.no_plant_boundary_check=false;
identityOpts=prepared.opts;
prepared.opts.gate_identity_lock=gate_holdout_identity_hashes( ...
    prepared.cfg,prepared.opts.stage1_position_runtime.model,identityOpts);
runIdentity=struct('schema','DL1018_GRU_POSITION_APPLIED_NOTCH_TAU01_RUN_IDENTITY_V1', ...
    'scene_id',sceneId,'attempt_sequence',1,'started_utc',utc_now(), ...
    'release_sha256',sha256_file(releasePath),'source_lock_sha256',sha256_file(sourceLockPath), ...
    'payload_manifest_sha256',sha256_file(payloadManifestPath), ...
    'parent_notch_hf6_release_sha256',char(release.parent_notch_hf6_release_sha256), ...
    'parent_notch_hf6_source_lock_sha256',char(release.parent_notch_hf6_source_lock_sha256), ...
    'parent_cosine_release_sha256',char(release.parent_cosine_release_sha256), ...
    'scene_payload_path',prepared.scene_payload_path,'scene_payload_sha256',prepared.scene_payload_sha256, ...
    'external_identity_sha256',prepared.external_identity_sha256,'b_raw_path',prepared.b_raw_path, ...
    'b_raw_sha256',prepared.b_raw_sha256,'c5_input_lock_sha256',prepared.c5_input_lock_sha256, ...
    'c5_snapshot_sha256',prepared.c5_snapshot_sha256,'position_model_sha256',prepared.position_model_sha256, ...
    'gru_model_sha256',prepared.gru_model_sha256,'position_method_id','C5_AXIS_MIXED_COORDINATE_M110', ...
    'position_delayed_prediction_tau_s',.1,'position_delayed_prediction_rho',.1, ...
    'position_delayed_prediction_mode','FIXED_NO_RAMP','position_nn_compensation_scale',1, ...
    'notch_center_hz',3.5,'notch_quality_factor',1,'notch_sample_rate_hz',100, ...
    'notch_b',double(notch.b(:).'),'notch_a',double(notch.a(:).'),'notch_initial_state',zeros(3,4), ...
    'common_position_options_sha256',prepared.identity.common.position_options_sha256, ...
    'gate_identity_lock',prepared.opts.gate_identity_lock,'controller_arm','GRU_STREAM', ...
    'geometry_arm','ACTIVE','Plant_calls_authorized',1,'inertia_reconstruction_enabled',false, ...
    'TEST_read',false);

attemptDir=fullfile(studyRoot,'runs',sceneId);
assert(~isfolder(attemptDir),'PositionNotchTau01:DuplicateScene','Refusing to overwrite the scene attempt.');
runsRoot=fileparts(attemptDir);
if ~isfolder(runsRoot)
    assert(java.io.File(runsRoot).mkdirs(),'PositionNotchTau01:AttemptCreate','Could not create runs root.');
end
assert(java.io.File(attemptDir).mkdirs(),'PositionNotchTau01:AttemptCreate','Could not create scene directory.');
startedUtc=runIdentity.started_utc;releaseSha=runIdentity.release_sha256;
markerPath=fullfile(attemptDir,'attempt_started.marker');
write_json(markerPath,struct('schema','DL1018_GRU_POSITION_APPLIED_NOTCH_TAU01_ATTEMPT_V1', ...
    'scene_id',sceneId,'created_utc',startedUtc,'stage','RUNNING','attempt_sequence',1, ...
    'release_sha256',releaseSha));
prepared.opts.composite_attempt_marker=markerPath;
write_json(fullfile(attemptDir,'run_start.json'),runIdentity);
rawPath=fullfile(attemptDir,'raw_run.mat');firstStepMarker=fullfile(attemptDir,'first_plant_step.marker');
try
    log=run_mlp15_dev72_closed_loop(prepared.scene,prepared.cfg,prepared.opts);
    assert(isfile(firstStepMarker),'PositionNotchTau01:PlantStepMarker','No first-step marker was written.');
    scene=prepared.scene;log.position_applied_notch_tau01_release_sha256=releaseSha;
    save(rawPath,'log','scene','runIdentity','-v7.3');
    assert(double(log.last_transition)==20000&&size(log.state,1)==20001&& ...
        strcmp(char(log.status),'STABLE'),'PositionNotchTau01:Incomplete','Scene did not finish stably.');
    write_json(fullfile(attemptDir,'run_status.json'),struct( ...
        'schema','DL1018_GRU_POSITION_APPLIED_NOTCH_TAU01_RUN_STATUS_V1','state','COMPLETED', ...
        'scene_id',sceneId,'finished_utc',utc_now(),'Plant_calls',1,'raw_path',rawPath, ...
        'raw_sha256',sha256_file(rawPath),'transitions',double(log.last_transition), ...
        'state_samples',size(log.state,1),'status_value',char(log.status), ...
        'safety_stop_reason',char(log.safety_stop_reason),'release_sha256',releaseSha, ...
        'source_lock_sha256',sha256_file(sourceLockPath),'TEST_read',false));
catch ME
    write_json(fullfile(attemptDir,'run_status.json'),struct( ...
        'schema','DL1018_GRU_POSITION_APPLIED_NOTCH_TAU01_RUN_STATUS_V1','state','FAILED', ...
        'scene_id',sceneId,'failed_utc',utc_now(),'Plant_calls',double(isfile(firstStepMarker)), ...
        'raw_path',rawPath,'raw_present',isfile(rawPath),'error_identifier',char(ME.identifier), ...
        'error_message',char(ME.message),'release_sha256',releaseSha, ...
        'source_lock_sha256',sha256_file(sourceLockPath),'TEST_read',false));
    rethrow(ME);
end
clear restoreFolder
end

function h=sha256_file(path)
fid=fopen(path,'rb');assert(fid>=0,'PositionNotchTau01:Read','Cannot open %s.',path);
cleanup=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear cleanup;
end
function write_json(path,value)
fid=fopen(path,'w','n','UTF-8');assert(fid>=0,'PositionNotchTau01:Write','Cannot write %s.',path);
cleanup=onCleanup(@()fclose(fid));fprintf(fid,'%s\n',jsonencode(value,'PrettyPrint',true));clear cleanup;
end
function value=utc_now()
value=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z'''));
end
