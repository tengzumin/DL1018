function attemptDir=run_mlp15_candidate_gate_attempt(scenePayloadPath,attemptDir)
% One released MLP15 closed-loop call with identity-matched reusable baselines.
entry=fileparts(mfilename('fullpath'));
runnerTaskRoot=fileparts(fileparts(fileparts(entry)));
researchRoot=fileparts(runnerTaskRoot);
releasePath=fullfile(researchRoot,'MLP15_PILOT_RELEASE_v2.json');
assert(isfile(releasePath),'GATE:ReleaseMissing','No root-issued MLP15 pilot release exists.');
release=jsondecode(fileread(releasePath));
assert(strcmp(release.schema,'DL1018_MLP15_GHP7_PILOT_RELEASE_V2')&& ...
    strcmp(release.status,'RELEASED')&&release.plant_calls_authorized==6&& ...
    strcmp(release.candidate_arm_id,'DL_MLP15')&& ...
    strcmp(release.geometry_arm,'ACTIVE')&&release.test_data_read==false, ...
    'GATE:ReleaseInvalid','Release does not authorize the six-scene MLP15 pilot.');

sourceLockPath=fullfile(researchRoot,'MLP15_CANDIDATE_SOURCE_LOCK_v2.json');
sourceLockSha=char(release.candidate_source_lock_sha256);
assert(isfile(sourceLockPath)&&strcmpi(sha256_file(sourceLockPath),sourceLockSha), ...
    'GATE:SourceLock','MLP15 pilot source lock differs from release.');
runnerAuditPath=fullfile(researchRoot,'MATLAB_NO_PLANT_AUDIT_MLP15_v2.json');
assert(strcmpi(sha256_file(runnerAuditPath),char(release.no_plant_audit_sha256)), ...
    'GATE:StaticAuditHash','MLP15 no-Plant audit report differs from release.');
runnerAudit=jsondecode(fileread(runnerAuditPath));
assert(strcmp(runnerAudit.status,'PASS')&&~runnerAudit.plant_invoked&& ...
    ~runnerAudit.test_data_read&&runnerAudit.runner_matlab_file_count==52, ...
    'GATE:StaticAudit','MLP15 no-Plant source audit is not a complete PASS.');
codeAuditPath=fullfile(researchRoot,'MLP15_RUNNER_CODE_ANALYZER_COMPARISON_v2.json');
assert(strcmpi(sha256_file(codeAuditPath),char(release.code_analyzer_comparison_sha256)), ...
    'GATE:CodeAuditHash','MLP15 runner code-analyzer comparison differs from release.');
codeAudit=jsondecode(fileread(codeAuditPath));
assert(strcmp(codeAudit.status,'PASS_NO_NEW_DIAGNOSTIC_IDS_OR_COUNTS')&& ...
    codeAudit.no_new_diagnostics&&codeAudit.plant_invoked==false&& ...
    codeAudit.test_data_read==false, ...
    'GATE:CodeAudit','MLP15 runner introduced a Code Analyzer diagnostic.');

runnerRoot=fullfile(runnerTaskRoot,'candidate_runner_work');
verify_candidate_tree(jsondecode(fileread(sourceLockPath)),runnerRoot);
prepared=prepare_gate_candidate_no_plant(scenePayloadPath,'DL_MLP15','ACTIVE');
taskbookPath=fullfile(researchRoot,'DL_ATTITUDE_REPLACEMENT_TASKBOOK_v1_FROZEN_ZH.md');
amendment02Path=fullfile(researchRoot,'DL_ATTITUDE_REPLACEMENT_TASKBOOK_v1_AMENDMENT02_SUPERVISION_FIX.md');
amendment03Path=fullfile(researchRoot,'DL_ATTITUDE_REPLACEMENT_TASKBOOK_v1_AMENDMENT03_RUNTIME_FEATURE_FIX.md');
amendment04Path=fullfile(researchRoot,'DL_ATTITUDE_REPLACEMENT_TASKBOOK_v1_AMENDMENT04_PILOT_BINDING_FIX.md');
amendment09Path=fullfile(researchRoot,'DL_ATTITUDE_REPLACEMENT_TASKBOOK_v1_AMENDMENT09_MLP15_FORMAL_TRAINING.md');
pilotTaskbookPath=fullfile(researchRoot,'MLP15_CLOSED_LOOP_PILOT_TASKBOOK_v2.md');
payloadManifestPath=fullfile(researchRoot,'GHP7_PILOT_PAYLOAD_MANIFEST_v1.json');
baselineManifestPath=fullfile(researchRoot,'GHP7_BASELINE_REUSE_MANIFEST_v1.json');
trainingDir=fullfile(researchRoot,'mlp15_formal_v1','run_v1');
assert(strcmpi(sha256_file(taskbookPath),char(release.taskbook_sha256))&& ...
    strcmpi(sha256_file(amendment02Path),char(release.amendment02_sha256))&& ...
    strcmpi(sha256_file(amendment03Path),char(release.amendment03_sha256))&& ...
    strcmpi(sha256_file(amendment04Path),char(release.amendment04_sha256))&& ...
    strcmpi(sha256_file(amendment09Path),char(release.amendment09_sha256))&& ...
    strcmpi(sha256_file(pilotTaskbookPath),char(release.pilot_taskbook_sha256))&& ...
    strcmpi(prepared.dataset_manifest_sha256,char(release.dataset_manifest_sha256))&& ...
    strcmpi(prepared.dataset_audit_sha256,char(release.screen_audit_sha256))&& ...
    strcmpi(prepared.parity_report_sha256,char(release.parity_report_sha256))&& ...
    strcmpi(prepared.mlp15_checkpoint_audit_sha256,char(release.checkpoint_audit_sha256))&& ...
    strcmpi(sha256_file(payloadManifestPath),char(release.payload_manifest_sha256))&& ...
    strcmpi(prepared.payload_manifest_sha256,char(release.payload_manifest_sha256))&& ...
    strcmpi(sha256_file(baselineManifestPath),char(release.baseline_reuse_manifest_sha256))&& ...
    strcmpi(prepared.baseline_reuse_manifest_sha256,char(release.baseline_reuse_manifest_sha256))&& ...
    strcmpi(prepared.c5_receipt_sha256,char(release.c5_receipt_sha256))&& ...
    strcmpi(sha256_file(fullfile(researchRoot,'mlp15_formal_v1','TRAINING_RELEASE_v1.json')), ...
        char(release.training_release_sha256))&& ...
    strcmpi(prepared.mlp15_training_release_sha256,char(release.training_release_sha256))&& ...
    strcmpi(sha256_file(fullfile(trainingDir,'training_config.json')),char(release.training_config_sha256))&& ...
    strcmpi(sha256_file(fullfile(trainingDir,'mlp15_attitude_weights_v1.mat')),char(release.model_sha256))&& ...
    strcmpi(prepared.mlp15_model_mat_sha256,char(release.model_sha256))&& ...
    double(prepared.mlp15_best_step)==double(release.best_step), ...
    'GATE:ReleaseIdentity','Taskbook, data, MLP15 training, or model differs from pilot release.');

allowed=release.pilot_payloads;
hit=find(strcmp({allowed.scene_id},char(prepared.scene.scene_id)) & ...
    strcmp({allowed.geometry_arm},'ACTIVE') & ...
    strcmpi({allowed.payload_sha256},prepared.scene_payload_sha256) & ...
    strcmpi({allowed.payload_path},prepared.scene_payload_path));
assert(isscalar(hit),'GATE:PayloadRelease','Payload is not one of six released GHP7 scenes.');

runsRoot=char(java.io.File(fullfile(researchRoot,'pilot_runs_mlp15_v2')).getCanonicalPath());
attemptDir=char(java.io.File(char(attemptDir)).getCanonicalPath());
assert(startsWith(lower(attemptDir),[lower(runsRoot) filesep])&& ...
    ~isfolder(attemptDir)&&~isfile(attemptDir), ...
    'GATE:OutputPath','Attempt output must be a new directory under pilot_runs_mlp15_v2.');
if ~isfolder(runsRoot),assert(java.io.File(runsRoot).mkdirs(),'GATE:RunRoot','Cannot create MLP15 run root.');end
markers=dir(fullfile(runsRoot,'**','attempt_started.marker'));
assert(numel(markers)<double(release.plant_calls_authorized), ...
    'GATE:CallBudget','All released MLP15 candidate calls have been consumed.');
for i=1:numel(markers)
    startPath=fullfile(markers(i).folder,'run_start.json');
    if isfile(startPath)
        prior=jsondecode(fileread(startPath));
        assert(~strcmp(char(prior.scene_id),char(prepared.scene.scene_id)), ...
            'GATE:DuplicateScene','This GHP7 scene already has a started MLP15 attempt.');
    end
end

assert(java.io.File(attemptDir).mkdirs(),'GATE:AttemptCreate','Could not create unique MLP15 attempt directory.');
startedUtc=utcNow();
runIdentity=struct('schema','DL1018_MLP15_GHP7_RUN_START_V2', ...
    'scene_id',char(prepared.scene.scene_id),'attitude_arm','DL_MLP15', ...
    'geometry_arm','ACTIVE','started_utc',startedUtc, ...
    'pilot_release_sha256',sha256_file(releasePath), ...
    'taskbook_sha256',char(release.taskbook_sha256), ...
    'amendment02_sha256',char(release.amendment02_sha256), ...
    'amendment03_sha256',char(release.amendment03_sha256), ...
    'amendment04_sha256',char(release.amendment04_sha256), ...
    'amendment09_sha256',char(release.amendment09_sha256), ...
    'pilot_taskbook_sha256',char(release.pilot_taskbook_sha256), ...
    'dataset_manifest_sha256',char(release.dataset_manifest_sha256), ...
    'screen_audit_sha256',char(release.screen_audit_sha256), ...
    'parity_report_sha256',char(release.parity_report_sha256), ...
    'checkpoint_audit_sha256',char(release.checkpoint_audit_sha256), ...
    'code_analyzer_comparison_sha256',char(release.code_analyzer_comparison_sha256), ...
    'candidate_source_lock_sha256',sourceLockSha, ...
    'scene_payload_path',prepared.scene_payload_path, ...
    'scene_payload_sha256',prepared.scene_payload_sha256, ...
    'r_task_sha256',char(prepared.scene.R_task_sha256), ...
    'c5_input_lock_sha256',prepared.c5_input_lock_sha256, ...
    'c5_snapshot_sha256',prepared.c5_snapshot_sha256, ...
    'position_model_mat_sha256',prepared.position_model_mat_sha256, ...
    'mlp15_model_mat_sha256',prepared.mlp15_model_mat_sha256, ...
    'training_release_sha256',char(release.training_release_sha256), ...
    'training_config_sha256',char(release.training_config_sha256), ...
    'best_step',prepared.mlp15_best_step, ...
    'cfg_identity',prepared.identity.geometry,'common_identity',prepared.identity.common, ...
    'runner_entry','run_gate_holdout_closed_loop(scene,cfg,opts)');
write_json(fullfile(attemptDir,'attempt_started.marker'),struct( ...
    'schema','DL1018_MLP15_GHP7_ATTEMPT_STARTED_V2','scene_id',runIdentity.scene_id, ...
    'created_utc',startedUtc,'stage','RUNNING'));
write_json(fullfile(attemptDir,'run_start.json'),runIdentity);
try
    log=run_gate_holdout_closed_loop(prepared.scene,prepared.cfg,prepared.opts);
    assert(isfield(log,'complete_transitions')&&isscalar(log.complete_transitions), ...
        'GATE:TransitionAudit','MLP15 runner omitted complete-transition status.');
    scene=prepared.scene;
    save(fullfile(attemptDir,'raw_run.mat'),'log','scene','runIdentity','-v7.3');
    status=struct('schema','DL1018_MLP15_GHP7_RUN_STATUS_V2','state','COMPLETED', ...
        'scene_id',runIdentity.scene_id,'attitude_arm','DL_MLP15','geometry_arm','ACTIVE', ...
        'finished_utc',utcNow(),'plant_calls',1,'scene_payload_sha256',prepared.scene_payload_sha256, ...
        'raw_output_path',fullfile(attemptDir,'raw_run.mat'), ...
        'raw_output_sha256',sha256_file(fullfile(attemptDir,'raw_run.mat')), ...
        'complete_transitions',logical(log.complete_transitions), ...
        'actual_transition_count',double(log.actual_transition_count), ...
        'actual_state_sample_count',double(log.actual_state_sample_count), ...
        'status_value',char(string(log.status)), ...
        'safety_stop_reason',char(string(log.safety_stop_reason)), ...
        'source_lock_sha256',sourceLockSha);
    write_json(fullfile(attemptDir,'run_status.json'),status);
    fprintf('MLP15_CANDIDATE_ATTEMPT_DIR=%s',attemptDir);
catch ME
    write_json(fullfile(attemptDir,'run_status.json'),struct( ...
        'schema','DL1018_MLP15_GHP7_RUN_STATUS_V2','state','FAILED', ...
        'scene_id',runIdentity.scene_id,'attitude_arm','DL_MLP15','geometry_arm','ACTIVE', ...
        'failed_utc',utcNow(),'plant_calls',1, ...
        'scene_payload_sha256',prepared.scene_payload_sha256, ...
        'error_identifier',char(ME.identifier),'error_message',char(ME.message), ...
        'source_lock_sha256',sourceLockSha));
    rethrow(ME);
end
end

function verify_candidate_tree(lock,runnerRoot)
assert(strcmp(char(lock.schema),'DL1018_MLP15_CANDIDATE_SOURCE_LOCK_V2')&& ...
    strcmpi(char(java.io.File(char(lock.root)).getCanonicalPath()), ...
    char(java.io.File(runnerRoot).getCanonicalPath())), ...
    'GATE:SourceLockSchema','Unexpected MLP15 candidate source lock.');
rootCanonical=char(java.io.File(runnerRoot).getCanonicalPath());
rootPrefix=[rootCanonical filesep];
expectedFiles=dir(fullfile(runnerRoot,'matlab','**','*.m'));
assert(numel(expectedFiles)==numel(lock.files),'GATE:SourceTreeCount', ...
    'Locked MLP15 source file count changed.');
for i=1:numel(lock.files)
    p=fullfile(runnerRoot,char(lock.files(i).relative_path));
    canonical=char(java.io.File(p).getCanonicalPath());
    assert(startsWith(lower(canonical),lower(rootPrefix))&&isfile(p)&& ...
        strcmpi(sha256_file(p),char(lock.files(i).sha256)), ...
        'GATE:SourceTreeSHA','Candidate source changed or escaped its tree: %s.',p);
end
end

function h=sha256_file(p)
fid=fopen(p,'rb');assert(fid>=0,'GATE:FileRead','Cannot read %s.',p);
closer=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear closer;
end

function write_json(p,x)
fid=fopen(p,'w');assert(fid>=0,'GATE:JsonWrite','Cannot write %s.',p);
closer=onCleanup(@()fclose(fid));fwrite(fid,[jsonencode(x,'PrettyPrint',true) newline],'char');clear closer;
end

function s=utcNow()
s=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z'''));
end
