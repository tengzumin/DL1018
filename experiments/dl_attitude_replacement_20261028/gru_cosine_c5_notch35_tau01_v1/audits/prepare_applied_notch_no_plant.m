function p=prepare_applied_notch_no_plant(writeReceipt)
% Bind one frozen DEV/VAL scene and stop immediately before the Plant loop.
if nargin<1,writeReceipt=false;end
studyRoot=fileparts(fileparts(mfilename('fullpath')));
assert(strcmpi(pwd,studyRoot),'PositionNotch:CurrentDirectory', ...
    'Run preparation from the isolated notch study root.');
releasePath=fullfile(studyRoot,'RELEASE.json');release=jsondecode(fileread(releasePath));
sourceLockPath=fullfile(studyRoot,'SOURCE_LOCK_v1.json');sourceLock=jsondecode(fileread(sourceLockPath));
assert(strcmp(char(release.schema),'DL1018_GRU_POSITION_APPLIED_NOTCH_TAU01_NOPLANT_V1')&& ...
    strcmp(char(release.study_id),'gru_cosine_c5_notch35_tau01_v1')&& ...
    strcmp(char(release.status),'PREPARED_NO_PLANT_PENDING_ROOT_AUDIT')&& ...
    double(release.authorized_Plant_calls)==0&&double(release.Plant_calls)==0&& ...
    abs(double(release.position_delayed_prediction_tau_s)-.1)<1e-12&& ...
    abs(double(release.position_delayed_prediction_rho)-.1)<1e-12&& ...
    strcmp(char(release.position_delayed_prediction_mode),'FIXED_NO_RAMP')&& ...
    ~logical(release.TEST_read)&&~logical(release.test_data_read)&& ...
    ~logical(release.inertia_reconstruction_enabled)&& ...
    strcmpi(sha256_file(sourceLockPath),char(release.source_lock_sha256))&& ...
    strcmpi(char(java.io.File(char(sourceLock.root)).getCanonicalPath()), ...
    char(java.io.File(fullfile(studyRoot,'candidate_runner_work')).getCanonicalPath())), ...
    'PositionNotch:Release','Release or source lock identity is invalid.');
payloadManifestPath=fullfile(studyRoot,'MLP15_DEV72_PAYLOAD_MANIFEST_v2.json');
assert(isfile(payloadManifestPath)&&strcmpi(sha256_file(payloadManifestPath), ...
    char(release.parent_payload_manifest_sha256)), ...
    'PositionNotch:PayloadManifest','Frozen DEV/VAL payload manifest is missing or changed.');
for i=1:numel(sourceLock.files)
    rec=sourceLock.files(i);path=fullfile(studyRoot,strrep(char(rec.path),'/',filesep));
    assert(isfile(path)&&strcmpi(sha256_file(path),char(rec.sha256)), ...
        'PositionNotch:SourceHash','Isolated source changed: %s.',path);
end
notch=release.applied_acceleration_notch;
b=[0.9005755352793756,-1.757773520542205,0.9005755352793756];
a=[1,-1.757773520542205,0.8011510705587512];
assert(logical(notch.enabled)&&abs(double(notch.center_hz)-3.5)<1e-12&& ...
    abs(double(notch.quality_factor)-1)<1e-12&&abs(double(notch.sample_rate_hz)-100)<1e-12&& ...
    max(abs(double(notch.b(:).')-b))<1e-14&&max(abs(double(notch.a(:).')-a))<1e-14, ...
    'PositionNotch:Coefficients','Release does not contain the frozen scipy iirnotch coefficients.');
poleRadius=max(abs(roots(a)));w0=2*pi*3.5/100;z=exp(-1i*w0);
Hnotch=(b(1)+b(2)*z+b(3)*z^2)/(a(1)+a(2)*z+a(3)*z^2);Hdc=sum(b)/sum(a);
assert(poleRadius<1&&abs(Hnotch)<1e-12&&abs(Hdc-1)<1e-12, ...
    'PositionNotch:Stability','Notch stability, center attenuation, or DC gain failed.');

% Reuse the established no-Plant C5/GRU payload binder to construct this scene.
sceneId=char(release.fixed_scene_id);projectRoot=fileparts(fileparts(fileparts(studyRoot)));
parentRoot=fullfile(projectRoot,'experiments','dl_attitude_replacement_20261028','gru_prediction_tau01_v1');
parentRuntime=fullfile(parentRoot,'candidate_runner_work','matlab','runtime');
parentReleasePath=char(release.parent_cosine_release_path);
parentTauReleasePath=fullfile(parentRoot,'RELEASE.json');
parentTauHelper=fullfile(projectRoot,'experiments','dl_attitude_replacement_20261026', ...
    'gru_stream_cosine_tracking_head_full72_v1','candidate_runner_work','matlab','runtime', ...
    'delayed_prediction_step_candidate.m');
assert(strcmpi(sha256_file(parentReleasePath),char(release.parent_cosine_release_sha256))&& ...
    strcmpi(sha256_file(parentTauReleasePath),char(release.parent_tau01_release_sha256))&& ...
    strcmpi(sha256_file(parentTauHelper),char(release.parent_tau1_helper_sha256)), ...
    'PositionNotch:ParentHashes','Cosine parent release/helper or scene binder release changed.');
assert(strcmpi(sha256_file(char(release.parent_notch_hf6_release_path)), ...
    char(release.parent_notch_hf6_release_sha256))&& ...
    strcmpi(sha256_file(char(release.parent_notch_hf6_source_lock_path)), ...
    char(release.parent_notch_hf6_source_lock_sha256)), ...
    'PositionNotch:NotchParent','Notch HF6 source release or lock changed.');
tau1Source=fileread(parentTauHelper);
assert(contains(tau1Source,'tau=1; rho=h/tau;')&&contains(tau1Source,'rho=h/tau'), ...
    'PositionNotch:ParentTau','Frozen parent helper does not define tau=1, rho=.01.');
oldFolder=pwd;restoreFolder=onCleanup(@()cd(oldFolder));
cd(parentRoot);addpath(parentRuntime,'-begin');clear activate_paired_runner prepare_gru_prediction_tau01_no_plant;
base=prepare_gru_prediction_tau01_no_plant(sceneId,false);
cd(studyRoot);restoredefaultpath;rehash toolboxcache;
candidateRuntime=fullfile(studyRoot,'candidate_runner_work','matlab','runtime');
addpath(candidateRuntime,'-begin');clear activate_paired_runner;
runnerRoot=activate_paired_runner();candidateRuntime=fullfile(runnerRoot,'matlab','runtime');
assert(strcmpi(which('run_mlp15_dev72_closed_loop'), ...
    fullfile(candidateRuntime,'run_mlp15_dev72_closed_loop.m'))&& ...
    strcmpi(which('position_applied_accel_notch_zoh'), ...
    fullfile(candidateRuntime,'position_applied_accel_notch_zoh.m')), ...
    'PositionNotch:RunnerPath','Runner or notch helper resolved outside this source snapshot.');
delayedSource=fileread(fullfile(candidateRuntime,'delayed_prediction_step_candidate.m'));
assert(contains(delayedSource,'tau=0.1; rho=h/tau;')&&~contains(delayedSource,'rhoStart='), ...
    'PositionNotch:FixedTauSource','Candidate must use fixed tau=.1, rho=.1 with no delayed ramp.');
assert(strcmp(sceneId,char(base.scene.scene_id))&&base.position_runtime_enabled&& ...
    base.position_runtime_update_enabled&&base.position_coordination_enabled&& ...
    base.position_delayed_prediction_enabled&& ...
    abs(double(base.position_nn_compensation_scale)-1)<1e-12, ...
    'PositionNotch:ParentBinding','Scene or frozen cosine/C5 parent identity differs.');

runtimeNotch=struct('enabled',true,'center_hz',3.5,'quality_factor',1, ...
    'sample_rate_hz',100,'b',b,'a',a,'initial_state',zeros(3,4), ...
    'discretization','causal IIR recurrence at 10-ms events; zero state; hold between events');
base.opts.stage1_position_runtime.applied_acceleration_notch=runtimeNotch;
base.opts.no_plant_boundary_check=true;
markerPath=fullfile(studyRoot,'audits','NO_PLANT_BOUNDARY_ATTEMPT.json');
write_json(markerPath,struct('scene_id',sceneId,'stage','RUNNING','Plant_calls',0));
base.opts.composite_attempt_marker=markerPath;
identityOpts=rmfield(base.opts,'composite_attempt_marker');
base.opts.gate_identity_lock=gate_holdout_identity_hashes( ...
    base.cfg,base.opts.stage1_position_runtime.model,identityOpts);

% Check the causal zero-state recurrence and output bound without a Plant.
state=zeros(3,4);u=[1;-0.5;0.25];[state1,y1]=position_applied_accel_notch_zoh(state,u,b,a);
assert(norm(y1-b(1)*u,inf)<1e-14&&isequal(state1(:,1),u), ...
    'PositionNotch:ZeroState','First event does not match the zero-state recurrence.');
limit=[0.4;0.2;0.1];issued=min(max(y1,-limit),limit);
assert(all(abs(issued)<=limit+1e-14)&&any(abs(y1)>limit), ...
    'PositionNotch:BoundedOutput','Output-limit clipping self-check failed.');

% Runtime setup runs in full; this fixed option always stops before the Plant loop.
probeError='';probeErrorMessage='';
try
    run_mlp15_dev72_closed_loop(base.scene,base.cfg,base.opts);
catch ME
    probeError=char(ME.identifier);probeErrorMessage=char(ME.message);
end
assert(strcmp(probeError,'PositionNotch:NoPlantPreflightStop')&& ...
    ~isfile(fullfile(studyRoot,'first_plant_step.marker'))&&double(release.Plant_calls)==0, ...
    'PositionNotch:MainLoopBoundary','Preflight did not stop exactly before the Plant loop (got %s: %s).', ...
    probeError,probeErrorMessage);
p=struct('scene_id',sceneId,'release_sha256',sha256_file(releasePath), ...
    'source_lock_sha256',sha256_file(sourceLockPath),'parent_release_sha256',sha256_file(parentReleasePath), ...
    'scene_payload_sha256',base.scene_payload_sha256,'external_identity_sha256',base.external_identity_sha256, ...
    'b_raw_sha256',base.b_raw_sha256,'gru_model_sha256',base.gru_model_sha256, ...
    'common_position_options_sha256',base.identity.common.position_options_sha256, ...
    'runner_path',which('run_mlp15_dev72_closed_loop'),'tau_s',.1,'rho',.1, ...
    'parent_notch_hf6_release_sha256',char(release.parent_notch_hf6_release_sha256), ...
    'parent_notch_hf6_source_lock_sha256',char(release.parent_notch_hf6_source_lock_sha256), ...
    'notch_b',b,'notch_a',a,'pole_radius',poleRadius,'center_gain_abs',abs(Hnotch), ...
    'dc_gain',Hdc,'first_event_output',y1,'clip_selfcheck_raw',y1, ...
    'clip_selfcheck_applied',issued,'boundary_error_identifier',probeError);
if writeReceipt
    receipt=struct('schema','DL1018_GRU_POSITION_APPLIED_NOTCH_TAU01_NOPLANT_RECEIPT_V1', ...
        'status','PASS_REACHED_MAIN_LOOP_BOUNDARY_NO_PLANT','study_id',char(release.study_id), ...
        'scene_id',sceneId,'release_sha256',p.release_sha256,'source_lock_sha256',p.source_lock_sha256, ...
        'parent_cosine_release_sha256',p.parent_release_sha256, ...
        'parent_notch_hf6_release_sha256',p.parent_notch_hf6_release_sha256, ...
        'parent_notch_hf6_source_lock_sha256',p.parent_notch_hf6_source_lock_sha256, ...
        'scene_payload_sha256',p.scene_payload_sha256, ...
        'external_identity_sha256',p.external_identity_sha256,'b_raw_sha256',p.b_raw_sha256, ...
        'gru_model_sha256',p.gru_model_sha256,'common_position_options_sha256',p.common_position_options_sha256, ...
        'position_method_id','C5_AXIS_MIXED_COORDINATE_M110','position_delayed_prediction_tau_s',.1, ...
        'position_delayed_prediction_rho',.1,'position_delayed_prediction_mode','FIXED_NO_RAMP', ...
        'notch_center_hz',3.5,'notch_quality_factor',1, ...
        'notch_sample_rate_hz',100,'notch_b',b,'notch_a',a,'initial_state',zeros(3,4), ...
        'pole_radius',poleRadius,'center_gain_abs',abs(Hnotch),'dc_gain',Hdc, ...
        'first_event_output_for_test_input',y1,'clip_selfcheck_raw',y1, ...
        'clip_selfcheck_applied',issued,'resolved_runner_path',p.runner_path, ...
        'main_loop_boundary_error_identifier',probeError,'Plant_calls',0,'plant_called',false, ...
        'inertia_reconstruction_enabled',false,'TEST_read',false,'training_runs',0);
    write_json(fullfile(studyRoot,'NO_PLANT_PREPARE_RESULT_v1.json'),receipt);
end
clear restoreFolder
end

function h=sha256_file(path)
fid=fopen(path,'rb');assert(fid>=0,'PositionNotch:Read','Cannot open %s.',path);
cleanup=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear cleanup;
end
function write_json(path,value)
fid=fopen(path,'w','n','UTF-8');assert(fid>=0,'PositionNotch:Write','Cannot write %s.',path);
cleanup=onCleanup(@()fclose(fid));fprintf(fid,'%s\n',jsonencode(value,'PrettyPrint',true));clear cleanup;
end
