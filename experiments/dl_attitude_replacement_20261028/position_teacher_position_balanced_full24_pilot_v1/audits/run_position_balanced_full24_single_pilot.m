function attemptDir=run_position_balanced_full24_single_pilot()
% One root-authorized fixed-scene Plant attempt after the no-Plant audit passes.
here=fileparts(mfilename('fullpath'));studyRoot=fileparts(here);releasePath=fullfile(studyRoot,'RELEASE.json');
lockPath=fullfile(studyRoot,'SOURCE_LOCK_v1.json');release=jsondecode(fileread(releasePath));lock=jsondecode(fileread(lockPath));
assert(strcmp(char(release.schema),'DL1018_POSITION_C5_RESIDUAL_GRU_NOPLANT_V1')&& ...
    strcmp(char(release.study_id),'position_teacher_position_balanced_full24_pilot_v1')&& ...
    strcmp(char(release.status),'RELEASED')&&double(release.authorized_Plant_calls)==1&& ...
    double(release.Plant_calls)==1&&~logical(release.TEST_read)&& ...
    ~logical(release.inertia_reconstruction_enabled), ...
    'PositionBalancedPilot:Release','Release does not authorize exactly one fixed-scene call.');
assert(strcmpi(sha256_file(lockPath),char(release.source_lock_sha256))&& ...
    numel(lock.files)==double(lock.file_count)&&double(release.source_file_count)==double(lock.file_count), ...
    'PositionBalancedPilot:Lock','Source lock SHA/count mismatch.');
for i=1:numel(lock.files)
    rec=lock.files(i);path=fullfile(studyRoot,strrep(char(rec.relative_path),'/',filesep));
    assert(isfile(path)&&strcmpi(sha256_file(path),char(rec.sha256)), ...
        'PositionBalancedPilot:SourceSHA','Locked source changed: %s.',path);
end
for i=1:numel(lock.external_inputs)
    rec=lock.external_inputs(i);path=char(rec.path);
    assert(isfile(path)&&strcmpi(sha256_file(path),char(rec.sha256)), ...
        'PositionBalancedPilot:ExternalSHA','Bound TRAIN/teacher/parent source changed: %s.',path);
end
noPlantPath=fullfile(studyRoot,'NO_PLANT_PREPARE_RESULT_v1.json');
noPlant=jsondecode(fileread(noPlantPath));noPlantReleasePath=fullfile(studyRoot,'RELEASE_NO_PLANT_v1.json');
assert(strcmp(char(noPlant.status),'PASS_STOPPED_BEFORE_PLANT')&& ...
    strcmp(char(noPlant.scene_id),char(release.fixed_scene_id))&& ...
    strcmpi(char(noPlant.source_lock_sha256),char(release.source_lock_sha256))&& ...
    strcmpi(sha256_file(noPlantReleasePath),char(noPlant.release_sha256))&& ...
    strcmpi(sha256_file(payload_path(studyRoot)),char(release.payload_manifest_sha256)), ...
    'PositionBalancedPilot:NoPlantReceipt','Prior no-Plant boundary receipt is not bound to this source lock.');
sceneId=char(release.fixed_scene_id);
assert(strcmp(sceneId,'DL1018_VAL_T3_C01_W14')&& ...
    any(strcmp(cellstr(string(release.authorized_scenes)),sceneId)), ...
    'PositionBalancedPilot:Scene','Only the fixed VAL pilot scene is authorized.');
runsRoot=fullfile(studyRoot,'runs');sceneRunRoot=fullfile(runsRoot,sceneId);attemptIndex=1;
if isfolder(runsRoot)
    assert(isfolder(sceneRunRoot),'PositionBalancedPilot:PriorRun','Unexpected run folder exists.');
    prior=dir(fullfile(sceneRunRoot,'attempt_*'));prior=prior([prior.isdir]);
    assert(numel(prior)==1&&strcmp(prior(1).name,'attempt_001'), ...
        'PositionBalancedPilot:PriorRun','Only one recorded pre-Plant attempt may be retried.');
    priorDir=fullfile(sceneRunRoot,prior(1).name);priorStatusPath=fullfile(priorDir,'run_status.json');
    assert(isfile(priorStatusPath),'PositionBalancedPilot:PriorStatus','Prior attempt lacks status.');
    priorStatus=jsondecode(fileread(priorStatusPath));priorFirstStep=fullfile(priorDir,'first_plant_step.marker');
    assert(strcmp(char(priorStatus.state),'FAILED')&&double(priorStatus.plant_calls)==0&& ...
        strcmp(char(priorStatus.scene_id),sceneId)&&~isfile(priorFirstStep)&& ...
        ~isfile(fullfile(priorDir,'raw_run.mat')), ...
        'PositionBalancedPilot:RetryBudget','Prior attempt reached Plant or wrote a raw run; no retry allowed.');
    attemptIndex=2;
else
    assert(mkdir(runsRoot),'PositionBalancedPilot:RunRoot','Could not create run root.');
    assert(mkdir(sceneRunRoot),'PositionBalancedPilot:RunFolder','Could not create scene folder.');
end
attemptDir=fullfile(sceneRunRoot,sprintf('attempt_%03d',attemptIndex));
assert(mkdir(attemptDir),'PositionBalancedPilot:AttemptFolder','Could not create attempt folder.');

parentTauStudy=fileparts(char(release.parent_tau01_release_path));
oldDir=pwd;restore=onCleanup(@()cd(oldDir));
addpath(fullfile(parentTauStudy,'candidate_runner_work','matlab','runtime'),'-begin');
cd(parentTauStudy);prepared=prepare_gru_prediction_tau01_no_plant(sceneId,false);
cd(studyRoot);clear restore;
ownRuntime=fullfile(studyRoot,'candidate_runner_work','matlab','runtime');addpath(ownRuntime,'-begin');
runnerRoot=activate_paired_runner();
assert(strcmpi(char(java.io.File(runnerRoot).getCanonicalPath()), ...
    char(java.io.File(fullfile(studyRoot,'candidate_runner_work')).getCanonicalPath())), ...
    'PositionBalancedPilot:RunnerRoot','Runner resolved outside the isolated candidate copy.');

modelPath=fullfile(studyRoot,strrep(char(release.position_residual_gru.weights_relative_path),'/',filesep));
m=load(modelPath);runtime=prepared.opts.stage1_position_runtime;
runtime.residual_gru=struct('enabled',true,'weights_sha256',char(release.position_residual_gru.weights_sha256), ...
    'input_mean',double(m.input_mean(:)),'input_std',double(m.input_std(:)), ...
    'gru_weight_ih_l0',double(m.gru_weight_ih_l0),'gru_weight_hh_l0',double(m.gru_weight_hh_l0), ...
    'gru_bias_ih_l0',double(m.gru_bias_ih_l0(:)),'gru_bias_hh_l0',double(m.gru_bias_hh_l0(:)), ...
    'head_weight',double(m.head_weight),'head_bias',double(m.head_bias(:)), ...
    'beta_rise_time_s',1.8,'delta_limit_mps2',0.5,'action_limit_mps2',3.0);
opts=prepared.opts;opts.stage1_position_runtime=runtime;opts.no_plant_boundary_check=false;
markerPath=fullfile(attemptDir,'composite_attempt_marker.json');
marker=struct('scene_id',sceneId,'stage','RUNNING','created_utc',utcNow());write_json(markerPath,marker);
opts.composite_attempt_marker=markerPath;identityOpts=rmfield(opts,'composite_attempt_marker');
opts.gate_identity_lock=gate_holdout_identity_hashes(prepared.cfg,prepared.position_model,identityOpts);
runIdentity=struct('schema','POSITION_TEACHER_POSITION_BALANCED_FULL24_SINGLE_RUN_START_V1', ...
    'scene_id',sceneId,'candidate_arm_id',char(release.candidate_arm_id), ...
    'started_utc',utcNow(),'release_sha256',sha256_file(releasePath), ...
    'release_no_plant_sha256',char(noPlant.release_sha256), ...
    'source_lock_sha256',char(release.source_lock_sha256), ...
    'weights_sha256',char(release.position_residual_gru.weights_sha256), ...
    'checkpoint_sha256',char(release.position_residual_gru.checkpoint_sha256), ...
    'training_data_sha256',char(release.training_data_sha256), ...
    'teacher_npz_sha256',char(release.position_residual_gru.teacher_npz_sha256), ...
    'scene_payload_sha256',prepared.scene_payload_sha256, ...
    'external_identity_sha256',prepared.external_identity_sha256, ...
    'B_raw_sha256',prepared.b_raw_sha256,'position_model_sha256',prepared.position_model_sha256, ...
    'parent_tau01_release_sha256',char(release.parent_tau01_release_sha256), ...
    'controller_arm','GRU_STREAM','geometry_arm','ACTIVE', ...
    'position_method_id','C5_AXIS_MIXED_COORDINATE_M110', ...
    'position_delayed_prediction_h_s',0.01,'position_delayed_prediction_tau_s',0.1, ...
    'position_delayed_prediction_rho',0.1,'notch_enabled',false, ...
    'model_input','causal X14 only','teacher_at_inference',false, ...
    'first_event_time_s',0.01,'first_ready_event_index_zero_based',31, ...
    'first_ready_event_time_s',0.32,'beta_formula','clip(event_time_s/1.8,0,1)', ...
    'delta_clip_mps2',0.5,'total_action_clip_mps2',3.0, ...
    'test_data_read',false,'inertia_reconstruction_enabled',false, ...
    'no_plant_preflight_receipt_path',noPlantPath,'entry','run_mlp15_dev72_closed_loop');
write_json(fullfile(attemptDir,'run_start.json'),runIdentity);
firstStep=fullfile(attemptDir,'first_plant_step.marker');
try
    log=run_mlp15_dev72_closed_loop(prepared.scene,prepared.cfg,opts);
    transitions=double(log.last_transition);stateSamples=size(log.state,1);
    complete=transitions==20000&&stateSamples==20001&&strcmp(char(log.status),'STABLE');
    assert(complete,'PositionBalancedPilot:Incomplete','Candidate did not complete a stable 20,000-transition run.');
    scene=prepared.scene;save(fullfile(attemptDir,'raw_run.mat'),'log','scene','runIdentity','-v7.3');
    rawPath=fullfile(attemptDir,'raw_run.mat');
    status=struct('schema','POSITION_TEACHER_POSITION_BALANCED_FULL24_RUN_STATUS_V1', ...
        'state','COMPLETED','scene_id',sceneId,'candidate_arm_id',char(release.candidate_arm_id), ...
        'finished_utc',utcNow(),'plant_calls',1,'raw_path',rawPath,'raw_sha256',sha256_file(rawPath), ...
        'transitions',transitions,'state_samples',stateSamples,'status_value',char(log.status), ...
        'safety_stop_reason',char(log.safety_stop_reason),'release_sha256',sha256_file(releasePath), ...
        'release_no_plant_sha256',char(noPlant.release_sha256), ...
        'source_lock_sha256',char(release.source_lock_sha256), ...
        'scene_payload_sha256',prepared.scene_payload_sha256,'B_raw_sha256',prepared.b_raw_sha256, ...
        'first_plant_step_marker_exists',isfile(firstStep),'TEST_read',false, ...
        'test_data_read',false,'inertia_reconstruction_enabled',false);
    write_json(fullfile(attemptDir,'run_status.json'),status);marker.stage='COMPLETED';
    marker.finished_utc=utcNow();write_json(markerPath,marker);
catch ME
    plantReached=isfile(firstStep);
    status=struct('schema','POSITION_TEACHER_POSITION_BALANCED_FULL24_RUN_STATUS_V1', ...
        'state','FAILED','scene_id',sceneId,'candidate_arm_id',char(release.candidate_arm_id), ...
        'failed_utc',utcNow(),'plant_calls',double(plantReached), ...
        'first_plant_step_marker_exists',plantReached,'error_identifier',char(ME.identifier), ...
        'error_message',char(ME.message),'release_sha256',sha256_file(releasePath), ...
        'release_no_plant_sha256',char(noPlant.release_sha256), ...
        'source_lock_sha256',char(release.source_lock_sha256),'TEST_read',false,'test_data_read',false);
    write_json(fullfile(attemptDir,'run_status.json'),status);marker.stage='FAILED';
    marker.error_identifier=char(ME.identifier);write_json(markerPath,marker);rethrow(ME);
end
end

function path=payload_path(studyRoot)
path=fullfile(studyRoot,'MLP15_DEV72_PAYLOAD_MANIFEST_v2.json');
end
function h=sha256_file(path)
fid=fopen(path,'rb');assert(fid>=0,'PositionBalancedPilot:Read','Cannot read %s.',path);
cleanup=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear cleanup;
end
function write_json(path,value)
fid=fopen(path,'w','n','UTF-8');assert(fid>=0);cleanup=onCleanup(@()fclose(fid));
fprintf(fid,'%s\n',jsonencode(value,'PrettyPrint',true));clear cleanup;
end
function s=utcNow()
s=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z'''));
end
