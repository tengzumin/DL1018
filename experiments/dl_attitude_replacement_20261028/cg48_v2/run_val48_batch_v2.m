function audit=run_val48_batch_v2()
% One locked VAL48 source check followed by one immutable call and score per scene.
studyRoot=fileparts(mfilename('fullpath'));
runtime=fullfile(studyRoot,'candidate_runner_work','matlab','runtime');
addpath(runtime);activate_paired_runner();addpath(runtime);addpath(fullfile(studyRoot,'runtime'));
planPath=fullfile(studyRoot,'BATCH_PLAN_v2.json');
protocolPath=fullfile(studyRoot,'BATCH_EXECUTION_PROTOCOL_v2.json');
budgetPath=fullfile(studyRoot,'BUDGET_LEDGER_v2.json');
releasePath=fullfile(studyRoot,'RELEASE.json');
lockPath=fullfile(studyRoot,'SOURCE_LOCK_VAL48_v1.json');
ledgerPath=fullfile(studyRoot,'VAL48_BUDGET_JOURNAL_v1.jsonl');
progressPath=fullfile(studyRoot,'VAL48_BATCH_PROGRESS_v1.json');
plan=jsondecode(fileread(planPath));protocol=jsondecode(fileread(protocolPath));
budget=jsondecode(fileread(budgetPath));baseRelease=jsondecode(fileread(releasePath));
lock=jsondecode(fileread(lockPath));
batchInput=jsondecode(fileread(fullfile(studyRoot,'BATCH_INPUT_v2.json')));
inputIds=cellstr(string(batchInput.cohort.source_scene_ids));
lockSha=sha256_file(lockPath);
pythonExe=char(protocol.python_executable_path);
assert(isfile(pythonExe)&&strcmpi(sha256_file(pythonExe),char(protocol.python_executable_sha256)), ...
    'N4Batch:Python','Frozen TCN0906 Python executable is missing or changed.');
assert(strcmpi(lockSha,char(baseRelease.source_lock_sha256))&& ...
    strcmpi(lockSha,char(plan.source_lock_sha256))&& ...
    strcmpi(sha256_file(planPath),char(baseRelease.batch_plan_sha256))&& ...
    strcmpi(sha256_file(fullfile(studyRoot,'BATCH_INPUT_v2.json')),char(baseRelease.batch_input_sha256)), ...
    'N4Batch:Lock','Frozen source lock, batch plan, or input does not match release.');
assert(strcmp(plan.status,'FROZEN_VAL48_48_NEW_SCENES_READY')&& ...
    strcmp(protocol.status,'FROZEN_BEFORE_VAL48_PLANT_CALLS')&& ...
    strcmp(budget.status,'FROZEN_CAP_48'), ...
    'N4Batch:Freeze','Batch protocol/plan/budget are not frozen for execution.');
assert(strcmp(baseRelease.schema,'DL1018_CAUSAL_N4_GATE_VAL48_NOPLANT_V2')&& ...
    strcmp(baseRelease.status,'PREPARED_NO_PLANT_PENDING_ROOT_AUDIT')&& ...
    strcmp(baseRelease.source_split,'VAL48')&&baseRelease.VAL_data_read&& ...
    baseRelease.authorized_Plant_calls==0&&baseRelease.Plant_calls==0&& ...
    baseRelease.potential_budget_calls==0&& ...
    strcmpi(baseRelease.candidate_identity_sha256,plan.candidate_identity_sha256)&& ...
    strcmpi(baseRelease.candidate_identity_sha256,protocol.candidate_identity_sha256)&& ...
    strcmpi(baseRelease.call_protocol_sha256,protocol.n4_call_protocol_sha256)&& ...
    isequaln(baseRelease.applied_acceleration_static_n4,protocol.fixed_n4_filter), ...
    'N4Batch:Release','No-Plant release template differs from the frozen N4 candidate.');
assert(isequal(cellstr(string(protocol.ordered_scene_ids)),cellstr(string(plan.ordered_scene_ids)))&& ...
    isequal(cellstr(string(protocol.new_attempt_scene_ids)),cellstr(string(budget.scene_order)))&& ...
    numel(protocol.ordered_scene_ids)==48&&numel(budget.scene_order)==48&& ...
    budget.authorized_batch_call_cap==48&&budget.max_attempts_per_scene==1&& ...
    strcmp(protocol.source_split,'VAL48')&&strcmp(budget.source_split,'VAL48'), ...
    'N4Batch:Cohort','Cohort/order/budget differs from the fixed VAL48 plan.');
reuseIds=cellstr(string(protocol.reuse_scene_ids));newIds=cellstr(string(protocol.new_attempt_scene_ids));
assert(strcmp(batchInput.cohort.source_split,'VAL48')&&numel(inputIds)==48&& ...
    isempty(reuseIds)&&numel(unique(newIds))==48&& ...
    isequal(newIds,cellstr(string(plan.ordered_scene_ids)))&& ...
    isequal(newIds,inputIds), ...
    'N4Batch:Membership','New-attempt order must equal the exact BATCH_INPUT VAL48 cohort.');
hasLedger=isfile(ledgerPath);hasProgress=isfile(progressPath);
hasAttempts=isfolder(fullfile(studyRoot,'runs'))||isfolder(fullfile(studyRoot,'scores'));
preplantResume=hasLedger||hasProgress;
assert(hasLedger==hasProgress&&~hasAttempts, ...
    'N4Batch:NoOverwrite','Prior attempt state exists or the batch journal/progress pair is incomplete.');
if preplantResume
    lines=splitlines(string(fileread(ledgerPath)));
    lines=lines(strlength(strtrim(lines))>0);
    priorStart=jsondecode(lines(1));priorProgress=jsondecode(fileread(progressPath));
    assert(numel(lines)>=1&&strcmp(priorStart.event,'BATCH_STARTED')&& ...
        priorStart.Plant_calls==0&&priorStart.authorized_call_cap==48&& ...
        isequal(cellstr(string(priorStart.new_attempt_scene_ids)),newIds)&& ...
        numel(lines)>=1&&priorProgress.calls_reserved==0&&priorProgress.Plant_calls==0&& ...
        isempty(priorProgress.completed_scenes)&&strcmp(priorProgress.status,'RUNNING')&& ...
        strcmpi(priorProgress.source_lock_sha256,priorStart.source_lock_sha256)&& ...
        all(arrayfun(@(k)strcmp(jsondecode(lines(k)).event,'PREPLANT_RESUME'),2:numel(lines))), ...
        'N4Batch:ResumeState','Only the audited zero-reservation pre-Plant state may resume.');
    progress=priorProgress;
else
    progress=struct('status','RUNNING','source_lock_sha256',lockSha,'budget_cap',48, ...
        'calls_reserved',0,'completed_scenes',{{}},'stopped_scene_id','','stop_reason','', ...
        'Plant_calls',0,'TEST_read',false,'VAL_data_read',true,'inertia_reconstruction_enabled',false);
end

% The full lock is checked once. The scene helper then rechecks each binding's
% B/C5/parent/model/payload sources immediately before its own attempt.
for i=1:numel(lock.files)
    p=char(lock.files(i).path);
    assert(isfile(p)&&strcmpi(sha256_file(p),char(lock.files(i).sha256)), ...
        'N4Batch:SourceHash','Locked source changed: %s',p);
end

if preplantResume
    append_event(ledgerPath,struct('event','PREPLANT_RESUME','utc',utcNow(), ...
        'previous_source_lock_sha256',char(priorStart.source_lock_sha256), ...
        'source_lock_sha256',lockSha,'calls_reserved',0,'Plant_calls',0, ...
        'reason','adapter_runtime_path_repair'));
    progress.source_lock_sha256=lockSha;
    write_json_replace(progressPath,progress);
else
    append_event(ledgerPath,struct('event','BATCH_STARTED','utc',utcNow(), ...
        'source_lock_sha256',lockSha,'authorized_call_cap',48,'reuse_scene_ids',{reuseIds}, ...
        'new_attempt_scene_ids',{newIds},'Plant_calls',0));
    write_json_replace(progressPath,progress);
end
attemptOrdinal=0;
try
    for i=1:numel(newIds)
        sceneId=newIds{i};attemptOrdinal=attemptOrdinal+1;
        assert(attemptOrdinal<=48,'N4Batch:Budget','The 48-call batch budget is exhausted.');
        bindingPath=fullfile(studyRoot,'bindings',[sceneId '.json']);
        binding=jsondecode(fileread(bindingPath));
        attempt=binding.candidate_attempt;attemptDir=char(attempt.attempt_dir);
        marker=char(attempt.attempt_started_marker_path);firstPlant=char(attempt.first_plant_step_marker_path);
        assert(~isfolder(attemptDir)&&~isfile(marker)&&~isfile(firstPlant), ...
            'N4Batch:NoRetry','Attempt/marker already exists for %s.',sceneId);

        singleRelease=baseRelease;
        singleRelease.schema='DL1018_CAUSAL_N4_GATE_VAL48_SINGLE_CALL_V2';
        singleRelease.study_id=baseRelease.study_id;
        singleRelease.status='RELEASED';singleRelease.fixed_scene_id=sceneId;
        singleRelease.source_split='VAL48';singleRelease.VAL_data_read=true;
        singleRelease.TEST_read=false;singleRelease.val_used_for_tuning=false;
        singleRelease.parameter_tuning=false;singleRelease.inertia_reconstruction_enabled=false;
        singleRelease.authorized_scenes={sceneId};
        singleRelease.authorized_Plant_calls=1;singleRelease.Plant_calls=1;
        singleRelease.potential_budget_calls=1;
        singleRelease.source_lock_path=lockPath;singleRelease.source_lock_sha256=lockSha;
        write_json_replace(releasePath,singleRelease);
        releaseSha=sha256_file(releasePath);
        prepared=prepare_cg48_val48_scene_no_plant(sceneId);
        assert(strcmp(prepared.scene_id,sceneId)&& ...
            ~prepared.opts.no_plant_boundary_check&& ...
            ~isfield(prepared.opts.stage1_position_runtime,'residual_gru')&& ...
            strcmpi(prepared.binding_sha256,sha256_file(bindingPath)), ...
            'N4Batch:PreparedIdentity','Prepared call differs from the exact scene binding.');

        % Consume the budget durably before any attempt marker or Plant call.
        append_event(ledgerPath,struct('event','RESERVED','ordinal',attemptOrdinal, ...
            'scene_id',sceneId,'utc',utcNow(),'release_sha256',releaseSha, ...
            'source_lock_sha256',lockSha,'binding_sha256',prepared.binding_sha256, ...
            'attempt_dir',attemptDir,'reserved_budget_calls',1, ...
            'budget_consumed_before_plant',true,'Plant_calls',0));
        progress.calls_reserved=attemptOrdinal;
        write_json_replace(progressPath,progress);

        assert(java.io.File(attemptDir).mkdirs(),'N4Batch:AttemptDir', ...
            'Cannot create the unique attempt directory for %s.',sceneId);
        write_new(marker,struct('stage','RUNNING','scene_id',sceneId,'Plant_calls',0, ...
            'reserved_budget_calls',1,'budget_ordinal',attemptOrdinal));
        start=struct('scene_id',sceneId,'source_split','VAL48','started_utc',utcNow(), ...
            'budget_ordinal',attemptOrdinal,'reserved_budget_calls',1,'Plant_calls',0, ...
            'release_sha256',releaseSha, ...
            'source_lock_sha256',lockSha,'binding_sha256',prepared.binding_sha256, ...
            'candidate_identity_sha256',char(plan.candidate_identity_sha256), ...
            'execution_identity',prepared.execution_identity, ...
            'payload_sha256',prepared.payload_sha256, ...
            'scene_identity_sha256',prepared.scene_audit.external_identity_sha256, ...
            'B_raw_sha256',prepared.b_raw_sha256,'parent_raw_sha256',prepared.parent_raw_sha256, ...
            'C5_raw_sha256',prepared.c5_raw_sha256,'TEST_read',false,'VAL_data_read',true, ...
            'inertia_reconstruction_enabled',false);
        write_new(char(attempt.run_start_path),start);
        opts=prepared.opts;opts.composite_attempt_marker=marker;
        try
            log=run_mlp15_dev72_closed_loop(prepared.scene,prepared.cfg,opts);
            transitions=double(log.last_transition);samples=size(log.state,1);
            scene=prepared.scene;identity=start;
            save(char(attempt.raw_path),'log','scene','identity','-v7.3');
            complete=transitions==20000&&samples==20001&&strcmp(log.status,'STABLE')&& ...
                all(isfinite(double(log.state(:))))&&isfile(firstPlant);
            actualPlant=double(isfile(firstPlant));
            status=struct('state',ternary(complete,'COMPLETED','INCOMPLETE'), ...
                'scene_id',sceneId,'finished_utc',utcNow(),'Plant_calls',actualPlant, ...
                'reserved_budget_calls',1, ...
                'raw_path',char(attempt.raw_path),'raw_sha256',sha256_file(char(attempt.raw_path)), ...
                'transitions',transitions,'state_samples',samples,'status_value',log.status, ...
                'safety_stop_reason',char(string(field_or(log,'safety_stop_reason',''))), ...
                'first_plant_step_marker_created',isfile(firstPlant), ...
                'budget_ordinal',attemptOrdinal,'release_sha256',releaseSha, ...
                'source_lock_sha256',lockSha,'binding_sha256',prepared.binding_sha256, ...
                'TEST_read',false,'VAL_data_read',true,'inertia_reconstruction_enabled',false);
            write_new(char(attempt.status_path),status);
            assert(complete,'N4Batch:StableRun','Stable 20k run/non-finite/safety gate failed for %s.',sceneId);
            write_json_replace(marker,struct('stage','COMPLETED','scene_id',sceneId, ...
                'Plant_calls',actualPlant,'first_plant_step_marker_created',true, ...
                'budget_ordinal',attemptOrdinal));
        catch ME
            actualPlant=double(isfile(firstPlant));
            statusPath=char(attempt.status_path);
            if ~isfile(statusPath)
                failure=struct('state','FAILED','scene_id',sceneId,'failed_utc',utcNow(), ...
                    'Plant_calls',actualPlant,'reserved_budget_calls',1, ...
                    'error_identifier',ME.identifier,'error_message',ME.message, ...
                    'first_plant_step_marker_created',isfile(firstPlant), ...
                    'budget_ordinal',attemptOrdinal,'release_sha256',releaseSha, ...
                    'source_lock_sha256',lockSha,'binding_sha256',prepared.binding_sha256, ...
                    'TEST_read',false,'VAL_data_read',true,'inertia_reconstruction_enabled',false);
                write_new(statusPath,failure);
            end
            if isfile(marker)
                write_json_replace(marker,struct('stage','FAILED','scene_id',sceneId, ...
                    'Plant_calls',actualPlant,'reserved_budget_calls',1, ...
                    'first_plant_step_marker_created',isfile(firstPlant), ...
                    'budget_ordinal',attemptOrdinal,'error_identifier',ME.identifier));
            end
            append_event(ledgerPath,struct('event','ATTEMPT_FAILED','ordinal',attemptOrdinal, ...
                'scene_id',sceneId,'utc',utcNow(),'error_identifier',ME.identifier, ...
                'error_message',ME.message,'reserved_budget_calls',1, ...
                'Plant_calls',actualPlant,'first_plant_step_marker_created',isfile(firstPlant)));
            progress.status='STOPPED_FATAL';progress.stopped_scene_id=sceneId;
            progress.Plant_calls=count_first_plant_markers(studyRoot);
            progress.stop_reason=ME.identifier;write_json_replace(progressPath,progress);
            rethrow(ME);
        end

        scorePath=char(attempt.score_path);
        command=sprintf('"%s" "%s" --scene "%s"',pythonExe, ...
            fullfile(studyRoot,'score_val48_batch_v2.py'),sceneId);
        [scoreCode,scoreOutput]=system(command);fprintf('%s',scoreOutput);
        progress.Plant_calls=count_first_plant_markers(studyRoot);
        append_event(ledgerPath,struct('event','ATTEMPT_SCORED','ordinal',attemptOrdinal, ...
            'scene_id',sceneId,'utc',utcNow(),'score_path',scorePath, ...
            'reserved_budget_calls',1,'Plant_calls',double(isfile(firstPlant)), ...
            'score_exit_code',scoreCode,'score_sha256',conditional_hash(scorePath)));
        if scoreCode~=0
            progress.status='STOPPED_FATAL';progress.stopped_scene_id=sceneId;
            progress.stop_reason='SCORER_FATAL_OR_SOURCE_INTEGRITY';write_json_replace(progressPath,progress);
            error('N4Batch:ScoreFatal','Fatal safety/stability/non-finite or scoring integrity error at %s.',sceneId);
        end
        score=jsondecode(fileread(scorePath));
        progress.completed_scenes{end+1}=sceneId;progress.last_score=score;
        progress.Plant_calls=count_first_plant_markers(studyRoot);
        write_json_replace(progressPath,progress);
        write_json_replace(releasePath,baseRelease);
    end
    [summaryCode,summaryOutput]=system(sprintf('"%s" "%s" --summary',pythonExe, ...
        fullfile(studyRoot,'score_val48_batch_v2.py')));
    fprintf('%s',summaryOutput);
    assert(summaryCode==0,'N4Batch:Summary','Could not write the frozen 48-scene score summary.');
    progress.status='COMPLETE_VAL48_48_SCENES';
    progress.finished_utc=utcNow();write_json_replace(progressPath,progress);
    append_event(ledgerPath,struct('event','BATCH_COMPLETED','utc',utcNow(), ...
        'reserved_budget_calls',attemptOrdinal,'Plant_calls',progress.Plant_calls, ...
        'score_summary_sha256', ...
        sha256_file(fullfile(studyRoot,'VAL48_SCORE_SUMMARY_v2.json'))));
catch ME
    write_json_replace(releasePath,baseRelease);
    rethrow(ME);
end
audit=progress;
end

function append_event(path,event)
fid=fopen(path,'a');assert(fid>=0,'N4Batch:Journal','Cannot append budget journal: %s',path);
c=onCleanup(@()fclose(fid));fprintf(fid,'%s\n',jsonencode(event));clear c;
end
function write_new(path,x)
assert(~isfile(path),'N4Batch:NoOverwrite','Refusing to overwrite %s.',path);
write_json_replace(path,x);
end
function write_json_replace(path,x)
tmp=[path '.tmp'];
if isfile(tmp),delete(tmp);end
fid=fopen(tmp,'w');assert(fid>=0,'N4Batch:Write','Cannot write %s.',tmp);
c=onCleanup(@()fclose(fid));fwrite(fid,[jsonencode(x,'PrettyPrint',true) newline],'char');clear c;
[ok,msg]=movefile(tmp,path,'f');assert(ok,'N4Batch:Move','Cannot atomically replace %s: %s',path,msg);
end
function h=conditional_hash(path)
if isfile(path),h=sha256_file(path);else,h='';end
end
function n=count_first_plant_markers(studyRoot)
d=dir(fullfile(studyRoot,'runs','**','first_plant_step.marker'));n=numel(d);
end
function h=sha256_file(path)
fid=fopen(path,'rb');assert(fid>=0,'N4Batch:Read','Cannot open %s.',path);
c=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear c;
end
function s=utcNow()
s=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z'''));
end
function y=ternary(c,a,b)
if c,y=a;else,y=b;end
end
function v=field_or(s,name,default)
if isstruct(s)&&isfield(s,name),v=s.(name);else,v=default;end
end
