function report=prepare_first_val48_single_call()
here=fileparts(mfilename('fullpath'));addpath(fullfile(here,'runtime'));
prepared=prepare_cg48_val48_scene_no_plant('DL1018_VAL_T1_C00_W07');
input=jsondecode(fileread(fullfile(here,'BATCH_INPUT_v2.json')));
release=jsondecode(fileread(fullfile(here,'RELEASE.json')));
authorized=cellstr(string(release.authorized_scenes));
assert(strcmp(release.schema,'DL1018_CAUSAL_N4_GATE_VAL48_SINGLE_CALL_V2')&& ...
    strcmp(release.status,'RELEASED')&&strcmp(release.source_split,'VAL48')&& ...
    strcmp(release.fixed_scene_id,prepared.scene_id)&&numel(authorized)==1&& ...
    strcmp(authorized{1},prepared.scene_id)&& ...
    isequal(authorized{1},input.cohort.source_scene_ids{1})&& ...
    strcmp(prepared.scene_audit.source_split,'VAL48')&& ...
    ~prepared.opts.no_plant_boundary_check&&~isfolder(prepared.candidate_attempt.attempt_dir)&& ...
    ~isfile(prepared.candidate_attempt.attempt_started_marker_path)&& ...
    ~isfile(prepared.candidate_attempt.first_plant_step_marker_path), ...
    'CG48:SinglePrepare','Single-scene release must prepare only the first exact VAL48 scene.');
boundary=jsondecode(fileread(fullfile(here,'audits','VAL48_FIRST_NO_PLANT_BOUNDARY_v1.json')));
assert(isequaln(prepared.identity.common,boundary.numeric_identity.common)&& ...
    isequaln(rmfield(prepared.identity.geometry,'options_sha256'), ...
             rmfield(boundary.numeric_identity.geometry,'options_sha256')), ...
    'CG48:ExecutionIdentity','Single-call identity changed the frozen numeric/model identity.');
report=struct('status','PASS_FIRST_VAL48_SINGLE_RELEASE_PREPARE_ONLY', ...
    'scene_id',prepared.scene_id,'source_split','VAL48','authorized_scene_count',1, ...
    'cohort_scene_count',double(input.cohort.scene_count),'Plant_calls',0, ...
    'TEST_read',false,'runner_invoked',false,'binding_sha256',prepared.binding_sha256, ...
    'identity',prepared.identity,'release_sha256',sha256_file(fullfile(here,'RELEASE.json')));
out=fullfile(here,'audits','VAL48_FIRST_SINGLE_PREPARE_v1.json');
assert(~isfile(out)&&~isfile(fullfile(here,'audits','VAL48_FIRST_SINGLE_RELEASE_v1.json')), ...
    'CG48:NoOverwrite','Single-prepare audit already exists.');
write_json(out,report);copyfile(fullfile(here,'RELEASE.json'), ...
    fullfile(here,'audits','VAL48_FIRST_SINGLE_RELEASE_v1.json'));
disp(jsonencode(report));
end

function h=sha256_file(path)
fid=fopen(path,'rb');assert(fid>=0,'CG48:Read','Cannot open %s.',path);
c=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear c;
end
function write_json(path,value)
fid=fopen(path,'w');assert(fid>=0,'CG48:Write','Cannot write %s.',path);
c=onCleanup(@()fclose(fid));fwrite(fid,[jsonencode(value,'PrettyPrint',true) newline],'char');clear c;
end
