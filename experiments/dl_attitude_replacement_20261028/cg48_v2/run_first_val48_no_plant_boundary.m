function report=run_first_val48_no_plant_boundary()
here=fileparts(mfilename('fullpath'));runtime=fullfile(here,'candidate_runner_work','matlab','runtime');
addpath(fullfile(here,'runtime'));addpath(runtime);
prepared=prepare_cg48_val48_scene_no_plant('DL1018_VAL_T1_C00_W07');
assert(strcmp(which('run_mlp15_dev72_closed_loop'), ...
    fullfile(runtime,'run_mlp15_dev72_closed_loop.m'))&& ...
    strcmp(which('validate_val48_scene_binding_v1'), ...
    fullfile(runtime,'validate_val48_scene_binding_v1.m'))&& ...
    strcmp(which('position_compensation_n4_causal_gate_step'), ...
    fullfile(runtime,'position_compensation_n4_causal_gate_step.m')), ...
    'CG48:RunnerPath','Full runner or VAL48 scene gate resolved outside the copied runner tree.');
marker=prepared.marker_path;auditDir=fileparts(marker);
if ~isfolder(auditDir),mkdir(auditDir);end
assert(~isfile(marker),'CG48:NoOverwrite','No-Plant boundary marker already exists.');
write_json(marker,struct('stage','RUNNING','scene_id',prepared.scene_id,'Plant_calls',0, ...
    'TEST_read',false,'source_split','VAL48'));
opts=prepared.opts;opts.no_plant_boundary_check=true;opts.composite_attempt_marker=marker;
stoppedAtBoundary=false;
try
    run_mlp15_dev72_closed_loop(prepared.scene,prepared.cfg,opts);
catch ME
    if strcmp(ME.identifier,'PositionNotch:NoPlantPreflightStop')
        stoppedAtBoundary=true;
    else
        write_json(marker,struct('stage','FAILED','scene_id',prepared.scene_id, ...
            'Plant_calls',0,'error_identifier',ME.identifier,'error_message',ME.message));
        rethrow(ME);
    end
end
firstPlant=char(prepared.candidate_attempt.first_plant_step_marker_path);
assert(stoppedAtBoundary&&~isfile(firstPlant), ...
    'CG48:NoPlantBoundary','Runner did not stop at the pre-Plant boundary.');
report=struct('status','PASS_FIRST_VAL48_FULL_RUNNER_NOPLANT_BOUNDARY', ...
    'scene_id',prepared.scene_id,'source_split','VAL48','Plant_calls',0, ...
    'TEST_read',false,'runner_invoked',true, ...
    'runner_path',which('run_mlp15_dev72_closed_loop'), ...
    'binding_sha256',prepared.binding_sha256,'prepared_identity',prepared.identity, ...
    'execution_identity',prepared.execution_identity);
write_json(fullfile(auditDir,'VAL48_FIRST_NO_PLANT_BOUNDARY_v1.json'),report);
write_json(marker,struct('stage','NO_PLANT_BOUNDARY_PASSED','scene_id',prepared.scene_id, ...
    'Plant_calls',0,'TEST_read',false,'result_path',fullfile(auditDir,'VAL48_FIRST_NO_PLANT_BOUNDARY_v1.json')));
disp(jsonencode(report));
end

function write_json(path,value)
fid=fopen(path,'w');assert(fid>=0,'CG48:Write','Cannot write %s.',path);
c=onCleanup(@()fclose(fid));fwrite(fid,[jsonencode(value,'PrettyPrint',true) newline],'char');clear c;
end
