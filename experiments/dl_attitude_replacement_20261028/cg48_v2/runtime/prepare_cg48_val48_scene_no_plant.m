function prepared=prepare_cg48_val48_scene_no_plant(sceneId)
% VAL48 source-only fork; fixed controller and N4 math stay in the shared runtime.
entry=fileparts(mfilename('fullpath'));studyRoot=fileparts(entry);
projectRoot=fileparts(fileparts(fileparts(studyRoot)));
inputPath=fullfile(studyRoot,'BATCH_INPUT_v2.json');input=jsondecode(fileread(inputPath));
sharedRoot=studyRoot;
sharedRuntime=fullfile(sharedRoot,char(input.n4_gate_v2.shared_runtime_relative),'matlab','runtime');
assert(isfolder(sharedRuntime),'N4Train24:Runtime','Shared N4 v2 runtime is missing.');
addpath(sharedRuntime);activate_paired_runner();addpath(entry);
releasePath=fullfile(studyRoot,'RELEASE.json');lockPath=fullfile(studyRoot,'SOURCE_LOCK_VAL48_v1.json');
release=jsondecode(fileread(releasePath));lock=jsondecode(fileread(lockPath));
assert(strcmpi(sha256_file(lockPath),char(release.source_lock_sha256))&& ...
    strcmpi(sha256_file(inputPath),char(release.batch_input_sha256)), ...
    'N4Val48:Lock','VAL48 source lock or batch input changed.');
manifestRef=input.cohort_sources.source_manifest_v1;
manifestPath=fullfile(projectRoot,char(manifestRef.path));
assert(strcmpi(sha256_file(manifestPath),char(manifestRef.sha256))&& ...
    strcmpi(sha256_file(manifestPath),char(release.source_manifest_sha256)), ...
    'N4Val48:Manifest','Pinned VAL source manifest changed.');
sceneId=char(sceneId);authorized=cellstr(string(release.authorized_scenes));
noPlantRelease=strcmp(release.schema,'DL1018_CAUSAL_N4_GATE_VAL48_NOPLANT_V2')&& ...
    strcmp(release.status,'PREPARED_NO_PLANT_PENDING_ROOT_AUDIT')&& ...
    strcmp(release.source_split,'VAL48')&&strcmp(release.study_id,input.study_id)&& ...
    numel(authorized)==48&&numel(unique(authorized))==48&& ...
    release.authorized_Plant_calls==0&&release.Plant_calls==0&&release.potential_budget_calls==0&& ...
    release.VAL_data_read&&~release.TEST_read&&~release.val_used_for_tuning&& ...
    ~release.inertia_reconstruction_enabled&&~release.parameter_tuning;
singleCallRelease=strcmp(release.schema,'DL1018_CAUSAL_N4_GATE_VAL48_SINGLE_CALL_V2')&& ...
    strcmp(release.status,'RELEASED')&&strcmp(release.source_split,'VAL48')&& ...
    strcmp(release.study_id,input.study_id)&&numel(authorized)==1&& ...
    strcmp(char(release.fixed_scene_id),sceneId)&&strcmp(authorized{1},sceneId)&& ...
    release.authorized_Plant_calls==1&&release.Plant_calls==1&&release.potential_budget_calls==1&& ...
    release.VAL_data_read&&~release.TEST_read&&~release.val_used_for_tuning&& ...
    ~release.inertia_reconstruction_enabled&&~release.parameter_tuning;
assert((noPlantRelease||singleCallRelease)&& ...
    (noPlantRelease&&isequal(authorized,cellstr(string(input.cohort.source_scene_ids)))||singleCallRelease)&& ...
    strcmp(input.cohort.source_split,'VAL48')&&double(input.cohort.scene_count)==48&& ...
    ~input.cohort.val_used_for_tuning&&~input.cohort.TEST_read&&input.cohort.Plant_calls==0, ...
    'N4Val48:Release','Expected a locked VAL48 zero-Plant or fixed-scene release.');
bindingPath=fullfile(studyRoot,'bindings',[sceneId '.json']);
binding=jsondecode(fileread(bindingPath));
assert(strcmp(binding.schema,'DL1018_CAUSAL_N4_VAL48_SCENE_BINDING_V2')&& ...
    strcmp(binding.status,'PASS_VAL48_FIXED_COHORT_BINDING')&& ...
    strcmp(binding.source_split,'VAL48')&& ...
    strcmp(binding.study_id,release.study_id)&&strcmp(binding.selected_scene_id,sceneId)&& ...
    binding.Plant_calls==0&&~binding.TEST_read&&binding.VAL_data_read&& ...
    ~binding.inertia_reconstruction_enabled&&~binding.extra_position_residual_gru_enabled&& ...
    binding.fixed_J0,'N4Val48:Binding','Binding must identify this fixed VAL48 scene row.');
assert(strcmpi(sha256_file(binding.dataset_manifest_path),binding.dataset_manifest_sha256)&& ...
    strcmpi(sha256_file(binding.dataset_source_lock_path),binding.dataset_source_lock_sha256)&& ...
    strcmpi(sha256_file(binding.parent_cosine_model_path),binding.parent_cosine_model_sha256)&& ...
    strcmpi(sha256_file(binding.c5_snapshot_path),binding.c5_snapshot_sha256)&& ...
    strcmpi(sha256_file(binding.position_model_path),binding.position_model_sha256)&& ...
    strcmpi(sha256_file(binding.c5_receipt_path),binding.c5_receipt_sha256)&& ...
    strcmpi(sha256_file(binding.local_scene_payload_path),binding.local_scene_payload_sha256)&& ...
    strcmpi(sha256_file(binding.parent_raw_path),binding.parent_raw_sha256)&& ...
    strcmpi(sha256_file(binding.parent_status_path),binding.parent_status_sha256)&& ...
    strcmpi(sha256_file(binding.parent_run_start_path),binding.parent_run_start_sha256)&& ...
    strcmpi(sha256_file(binding.c5_raw_path),binding.c5_raw_sha256)&& ...
    strcmpi(sha256_file(binding.c5_status_path),binding.c5_status_sha256)&& ...
    strcmpi(sha256_file(binding.b72_scoring_raw_path),binding.b72_scoring_raw_sha256)&& ...
    strcmpi(sha256_file(binding.b72_scoring_status_path),binding.b72_scoring_status_sha256), ...
    'N4Val48:SourceHash','A scene, controller, model, or baseline source changed.');
% The training dataset hash above is model provenance only; VAL membership is input-cohort based.
ids=cellstr(string(input.cohort.source_scene_ids));order=double(binding.source_order_zero_based)+1;
validOrder=isscalar(order)&&isfinite(order)&&order>=1&&order<=48&&order==floor(order);
authorizedOrderOk=validOrder&&numel(authorized)==48&&strcmp(authorized{order},sceneId);
if singleCallRelease
    authorizedOrderOk=numel(authorized)==1&&strcmp(char(release.fixed_scene_id),sceneId)&& ...
        strcmp(authorized{1},sceneId);
end
assert(strcmp(input.cohort.source_split,'VAL48')&&double(input.cohort.scene_count)==48&& ...
    numel(ids)==48&&numel(unique(ids))==48&&validOrder&&strcmp(ids{order},sceneId)&& ...
    authorizedOrderOk,'N4Val48:Membership', ...
    'Scene must match its exact BATCH_INPUT_v2.json.cohort VAL48 member and order.');
parentStatus=jsondecode(fileread(binding.parent_status_path));
parentStart=jsondecode(fileread(binding.parent_run_start_path));
c5Status=jsondecode(fileread(binding.c5_status_path));bStatus=jsondecode(fileread(binding.b72_scoring_status_path));
assert(strcmp(parentStatus.status_value,'STABLE')&&parentStatus.transitions==20000&& ...
    parentStatus.state_samples==20001&&parentStatus.Plant_calls==1&& ...
    strcmp(parentStart.scene_id,sceneId)&&strcmpi(parentStart.c5_raw_sha256,binding.c5_raw_sha256)&& ...
    strcmpi(parentStart.b_raw_sha256,binding.b72_scoring_raw_sha256)&& ...
    strcmpi(parentStart.payload_sha256,binding.scene_payload_source_sha256)&& ...
    strcmp(c5Status.scene_id,sceneId)&&c5Status.transitions==20000&& ...
    c5Status.state_samples==20001&&c5Status.plant_calls==1&& ...
    strcmp(bStatus.scene_id,sceneId)&&bStatus.transitions==20000&& ...
    bStatus.state_samples==20001&&strcmp(bStatus.log_status,'STABLE')&& ...
    ~parentStatus.TEST_read&&~c5Status.TEST_accessed&&~bStatus.TEST_accessed, ...
    'N4Train24:BaselinePair','Parent/B/C5 baselines are not this completed TRAIN scene.');
payload=load(binding.local_scene_payload_path,'scene');scene=payload.scene;
assert(strcmp(char(scene.scene_id),sceneId),'N4Train24:Payload','Payload scene id mismatch.');
scene.reference_contract_id='DL1018_SCENE_REF_FIG8_A2_V2';
snapshot=load(binding.c5_snapshot_path,'cfg','W0');positionPack=load(binding.position_model_path,'model');
positionModel=positionPack.model;receipt=jsondecode(fileread(binding.c5_receipt_path));
assert(strcmp(positionModel.model_id,'DSSM14')&&positionModel.input_dim==14&&positionModel.window==32&& ...
    isequal(double(positionModel.output_W),double(snapshot.W0))&& ...
    strcmpi(paired_sha256_double(double(snapshot.W0)),receipt.W0_sha256), ...
    'N4Train24:C5Model','C5 DSSM14, snapshot, and receipt do not match.');
cfg=snapshot.cfg;if isfield(cfg,'attitude_replacement'),cfg=rmfield(cfg,'attitude_replacement');end
cfg.plant.arm_initial=repmat(.15,4,1);cfg=bind_paired_fixed_j0(cfg);
parentModel=load(binding.parent_cosine_model_path);
opts=make_gate_holdout_options(cfg,positionModel,'GRU_STREAM','ACTIVE',struct, ...
    parentModel,binding.parent_cosine_model_sha256);
assert(~isfield(opts.stage1_position_runtime,'residual_gru'), ...
    'N4Train24:PositionGRU','The extra position-GRU runtime must be absent.');
opts.no_plant_boundary_check=noPlantRelease;
identity=gate_holdout_identity_hashes(cfg,positionModel,opts);
assert(strcmpi(identity.common.position_options_sha256,receipt.common_position_options_sha256), ...
    'N4Train24:ExactOptions','Parent/C5 position options changed.');
executionIdentity=identity;identityModeAudit=struct('changed_option','no_plant_boundary_check', ...
    'prepared_no_plant_value',noPlantRelease,'execution_value',false,'identity_common_equal',true, ...
    'identity_geometry_except_options_equal',true,'runner_invoked',false);
if noPlantRelease
    executionOpts=opts;executionOpts.no_plant_boundary_check=false;
    executionIdentity=gate_holdout_identity_hashes(cfg,positionModel,executionOpts);
    identityModeAudit.identity_common_equal=isequaln(identity.common,executionIdentity.common);
    identityModeAudit.identity_geometry_except_options_equal=isequaln( ...
        rmfield(identity.geometry,'options_sha256'),rmfield(executionIdentity.geometry,'options_sha256'));
    assert(identityModeAudit.identity_common_equal&&identityModeAudit.identity_geometry_except_options_equal, ...
        'N4Train24:ExecutionIdentity','Changing only the no-Plant control flag changed numeric/model identity.');
end
opts.gate_identity_lock=identity;
opts.stage1_position_runtime.applied_acceleration_static_n4=release.applied_acceleration_static_n4;
opts.composite_attempt_marker=fullfile(studyRoot,'audits',[sceneId '_marker.json']);
sceneAudit=validate_val48_scene_binding_v1(scene,cfg,binding,parentStart,input.cohort);
prepared=struct('scene',scene,'cfg',cfg,'opts',opts,'identity',identity,'scene_audit',sceneAudit, ...
    'scene_id',sceneId,'binding_path',bindingPath,'binding_sha256',sha256_file(bindingPath), ...
    'payload_sha256',binding.local_scene_payload_sha256,'parent_raw_sha256',binding.parent_raw_sha256, ...
    'c5_raw_sha256',binding.c5_raw_sha256,'b_raw_sha256',binding.b72_scoring_raw_sha256, ...
    'marker_path',opts.composite_attempt_marker,'candidate_attempt',binding.candidate_attempt, ...
    'execution_identity',executionIdentity,'identity_mode_audit',identityModeAudit);
end
function h=sha256_file(path)
fid=fopen(path,'rb');assert(fid>=0,'N4Train24:Read','Cannot open %s.',path);
cleanup=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear cleanup;
end
function audit=validate_val48_scene_binding_v1(scene,cfg,binding,parentStart,cohort)
if nargin<4||~isstruct(parentStart)||~isfield(parentStart,'c5_raw_sha256')
    startPath=char(binding.parent_run_start_path);
    assert(isfile(startPath)&&strcmpi(sha256_file(startPath),char(binding.parent_run_start_sha256)), ...
        'VAL48Pair:ParentStartHash','Parent run_start is not bound by the VAL48 input lock.');
    parentStart=jsondecode(fileread(startPath));
end
sceneId=char(string(field_or(scene,'scene_id','')));
ids=cellstr(string(cohort.source_scene_ids));order=double(binding.source_order_zero_based);
assert(strcmp(sceneId,char(binding.selected_scene_id))&& ...
    strcmp(char(cohort.source_split),'VAL48')&&double(cohort.scene_count)==48&& ...
    numel(ids)==48&&numel(unique(ids))==48&&isscalar(order)&&isfinite(order)&& ...
    order>=0&&order<48&&order==floor(order)&&strcmp(ids{order+1},sceneId)&& ...
    strcmp(char(binding.source_split),'VAL48')&&logical(binding.VAL_data_read)&& ...
    ~logical(binding.TEST_read)&&double(binding.Plant_calls)==0&& ...
    ~logical(binding.inertia_reconstruction_enabled), ...
    'VAL48Pair:SceneMembership','Scene is not the exact input-cohort VAL48 member.');
assert(isstruct(scene)&&isfield(scene,'reference_contract_id')&& ...
    strcmp(char(string(scene.reference_contract_id)),'DL1018_SCENE_REF_FIG8_A2_V2'), ...
    'VAL48Pair:ReferenceContract','Scene reference contract differs from the existing paired controller.');
assert(isstruct(cfg)&&isfield(cfg,'plant')&&isscalar(cfg.plant.dt)&& ...
    abs(double(cfg.plant.dt)-.001)<1e-12, ...
    'VAL48Pair:PlantDt','Expected the locked 1 kHz plant configuration.');
N=20001;t=double(scene.time(:));
assert(numel(t)==N&&all(isfinite(t))&&max(abs(t-(0:N-1)'*.001))<1e-12, ...
    'VAL48Pair:Time','Expected 20,001 scene samples from 0 to 20 s at 1 ms.');
assert(isfield(scene,'initial_state')&&numel(scene.initial_state)==12&& ...
    all(isfinite(double(scene.initial_state(:)))), ...
    'VAL48Pair:InitialState','Initial state must contain 12 finite values.');
assert(isstruct(scene.reference)&&all(isfield(scene.reference, ...
    {'position','velocity','acceleration','yaw','yaw_rate','yaw_acceleration'})), ...
    'VAL48Pair:Reference','Missing analytic task reference arrays.');
for field={'position','velocity','acceleration'}
    x=double(scene.reference.(field{1}));
    assert(isequal(size(x),[N,3])&&all(isfinite(x),'all'), ...
        'VAL48Pair:Reference','Invalid reference.%s array.',field{1});
end
for field={'yaw','yaw_rate','yaw_acceleration'}
    x=double(scene.reference.(field{1}));
    assert(numel(x)==N&&all(isfinite(x(:))), ...
        'VAL48Pair:Reference','Invalid reference.%s array.',field{1});
end
assert(isfield(scene,'environment_wind_I')&&isequal(size(scene.environment_wind_I),[N,3])&& ...
    all(isfinite(double(scene.environment_wind_I)),'all'), ...
    'VAL48Pair:Wind','Expected finite VAL scene wind input Nx3.');
assert(isstruct(scene.arms)&&all(isfield(scene.arms, ...
    {'command','rho_true','rho_hat','rhoDot_true','rhoDot_hat'})), ...
    'VAL48Pair:Arms','Missing morphology arrays.');
for field={'command','rho_true','rho_hat','rhoDot_true','rhoDot_hat'}
    x=double(scene.arms.(field{1}));
    assert(isequal(size(x),[N,4])&&all(isfinite(x),'all'), ...
        'VAL48Pair:Arms','Invalid scene.arms.%s array.',field{1});
end
rTaskHash='';
if isfield(scene,'R_task')
    R=double(scene.R_task);
    assert(isequal(size(R),[3,3,N])&&all(isfinite(R),'all'), ...
        'VAL48Pair:RTask','Optional R_task is malformed.');
    rTaskHash=paired_sha256_double(R);
end
assert(strcmp(char(parentStart.scene_id),sceneId)&& ...
    strcmpi(char(parentStart.c5_raw_sha256),char(binding.c5_raw_sha256))&& ...
    strcmpi(char(parentStart.b_raw_sha256),char(binding.b72_scoring_raw_sha256)), ...
    'VAL48Pair:SourceBinding','Parent run_start does not bind this scene''s B/C5 source.');
audit=struct('scene_id',sceneId,'source_split','VAL48', ...
    'geometry_arm','ACTIVE','scene_payload_sha256',char(binding.local_scene_payload_sha256), ...
    'external_identity_sha256',char(binding.external_identity_sha256), ...
    'b_raw_sha256',char(parentStart.b_raw_sha256),'parent_cosine_gru_raw_sha256',char(binding.parent_raw_sha256), ...
    'c5_raw_sha256',char(binding.c5_raw_sha256),'R_task_sha256',rTaskHash, ...
    'TEST_read',false,'VAL_data_read',true,'Plant_called',false,'inertia_reconstruction_enabled',false);
end
function value=field_or(s,name,default)
if isstruct(s)&&isfield(s,name),value=s.(name);else,value=default;end
end
