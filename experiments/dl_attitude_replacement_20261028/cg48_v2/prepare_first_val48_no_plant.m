function report=prepare_first_val48_no_plant()
here=fileparts(mfilename('fullpath'));addpath(fullfile(here,'runtime'));
sceneId='DL1018_VAL_T1_C00_W07';
prepared=prepare_cg48_val48_scene_no_plant(sceneId);
assert(strcmp(prepared.scene_id,sceneId)&&strcmp(prepared.scene_audit.source_split,'VAL48')&& ...
    prepared.opts.no_plant_boundary_check&&~prepared.scene_audit.Plant_called&& ...
    ~prepared.scene_audit.TEST_read,'CG48:PrepareHarness','First VAL48 no-Plant prepare check failed.');
report=struct('status','PASS_FIRST_VAL48_PREPARE_NO_PLANT','scene_id',sceneId, ...
    'source_split','VAL48','Plant_calls',0,'TEST_read',false, ...
    'val_used_for_tuning',false,'runner_invoked',false);
disp(jsonencode(report));
end
