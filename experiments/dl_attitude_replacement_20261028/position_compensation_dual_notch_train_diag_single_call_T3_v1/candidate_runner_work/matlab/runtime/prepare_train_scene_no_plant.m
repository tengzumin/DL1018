function prepared=prepare_train_scene_no_plant()
% Bind one TRAIN-only, fold-heldout C5/GRU pair and the DC-penalty fold model.
entry=fileparts(mfilename('fullpath'));
runnerRoot=fileparts(fileparts(entry));
studyRoot=fileparts(runnerRoot);
projectRoot=fileparts(fileparts(fileparts(studyRoot)));
activate_paired_runner();
release=jsondecode(fileread(fullfile(studyRoot,'RELEASE.json')));
bindingPath=fullfile(studyRoot,'TRAIN_SCENE_BINDING_v1.json');
modelManifestPath=fullfile(studyRoot,'OOF_FOLD_MODEL_MANIFEST_v1.json');
binding=jsondecode(fileread(bindingPath));modelManifest=jsondecode(fileread(modelManifestPath));
authorized=cellstr(string(release.authorized_scenes));
preflightRelease=strcmp(char(release.status),'PREPARED_NO_PLANT_PENDING_ROOT_AUDIT')&& ...
    double(release.authorized_Plant_calls)==0&&double(release.Plant_calls)==0;
singleRunRelease=strcmp(char(release.status),'RELEASED')&& ...
    double(release.authorized_Plant_calls)==1&&double(release.Plant_calls)==1;
assert(any(strcmp(char(release.schema),{'DL1018_POSITION_C5_RESIDUAL_GRU_NOPLANT_V1','DL1018_POSITION_C5_DUAL_NOTCH_SINGLE_CALL_V1'}))&& ...
    strcmp(char(release.study_id),'position_compensation_dual_notch_train_diag_single_call_T3_v1')&& ...
    xor(preflightRelease,singleRunRelease)&& ...
    ~logical(release.TEST_read)&&~logical(release.inertia_reconstruction_enabled)&& ...
    isfield(release,'fixed_scene_id')&&strcmp(char(release.fixed_scene_id),char(binding.selected_scene_id))&& ...
    numel(authorized)==1&&strcmp(char(authorized{1}),char(binding.selected_scene_id)), ...
    'TRAINPair:Release','Release must authorize only the selected TRAIN no-Plant preflight.');
assert(strcmp(char(binding.status),'PASS_TRAIN_ONLY_PAIR_BINDING')&& ...
    strcmp(char(modelManifest.status),'PASS_FOLD_HELDOUT_TRAIN_PARITY_INPUTS_READY')&& ...
    strcmp(char(modelManifest.fold_id),char(binding.fold_id))&& ...
    any(strcmp(char(binding.selected_scene_id),cellstr(string(binding.fold_holdout_scene_ids))))&& ...
    ~any(strcmp(binding.selected_scene_id,binding.fold_train_scene_ids)), ...
    'TRAINPair:FoldIdentity','Selected scene is not held out from its exact fold model.');
assert(strcmpi(sha256_file(char(binding.dataset_path)),char(binding.dataset_sha256))&& ...
    strcmpi(sha256_file(char(binding.dataset_manifest_path)),char(binding.dataset_manifest_sha256))&& ...
    strcmpi(sha256_file(char(binding.dataset_source_lock_path)),char(binding.dataset_source_lock_sha256))&& ...
    strcmpi(sha256_file(char(binding.oof_path)),char(binding.oof_sha256))&& ...
    strcmpi(sha256_file(char(binding.oof_plan_path)),char(binding.oof_plan_sha256))&& ...
    strcmpi(sha256_file(char(binding.oof_result_path)),char(binding.oof_result_sha256))&& ...
    strcmpi(sha256_file(char(binding.oof_source_lock_path)),char(binding.oof_source_lock_sha256))&& ...
    strcmpi(sha256_file(char(binding.fold_checkpoint_path)),char(binding.fold_checkpoint_sha256))&& ...
    strcmpi(sha256_file(char(binding.local_fold_checkpoint_path)),char(binding.local_fold_checkpoint_sha256)), ...
    'TRAINPair:TrainingInputs','TRAIN24 data, fold plan, OOF, or fold checkpoint binding changed.');
trainManifest=jsondecode(fileread(char(binding.dataset_manifest_path)));
trainSourceLock=jsondecode(fileread(char(binding.dataset_source_lock_path)));
manifestIds=cellstr(string(trainManifest.source_scene_ids));
assert(double(trainManifest.scene_count)==24&&numel(manifestIds)==24&& ...
    strcmp(manifestIds{double(binding.source_order_zero_based)+1},char(binding.selected_scene_id))&& ...
    all(startsWith(string(manifestIds),'DL1018_DEV_'))&& ...
    strcmpi(char(trainManifest.dataset_sha256),char(binding.dataset_sha256))&& ...
    strcmpi(char(trainManifest.source_lock_sha256),char(binding.dataset_source_lock_sha256))&& ...
    numel(trainSourceLock.scene_rows)==24&&strcmp(char(trainSourceLock.scene_rows(double(binding.source_order_zero_based)+1).scene_id), ...
    char(binding.selected_scene_id)), ...
    'TRAINPair:ManifestOrder','Dataset manifest/source lock do not identify the first TRAIN scene.');
assert(strcmpi(sha256_file(char(binding.parent_cosine_release_path)), ...
    char(binding.parent_cosine_release_sha256))&& ...
    strcmpi(sha256_file(char(binding.parent_cosine_manifest_path)), ...
    char(binding.parent_cosine_manifest_sha256))&& ...
    strcmpi(sha256_file(char(binding.parent_cosine_source_lock_path)), ...
    char(binding.parent_cosine_source_lock_sha256))&& ...
    strcmpi(sha256_file(char(binding.parent_cosine_model_path)), ...
    char(binding.parent_cosine_model_sha256))&& ...
    strcmpi(sha256_file(char(binding.c5_input_lock_path)),char(binding.c5_input_lock_sha256))&& ...
    strcmpi(sha256_file(char(binding.c5_snapshot_path)),char(binding.c5_snapshot_sha256))&& ...
    strcmpi(sha256_file(char(binding.position_model_path)),char(binding.position_model_sha256))&& ...
    strcmpi(sha256_file(char(binding.c5_receipt_path)),char(binding.c5_receipt_sha256)), ...
    'TRAINPair:ParentC5Lineage','Parent GRU/C5 model or frozen C5 input lineage changed.');
assert(strcmpi(sha256_file(bindingPath),char(release.train_scene_binding_sha256))&& ...
    strcmpi(sha256_file(modelManifestPath),char(release.model_manifest_sha256))&& ...
    strcmpi(sha256_file(char(binding.weights_mat_path)),char(release.weights_sha256))&& ...
    strcmpi(sha256_file(char(binding.local_scene_payload_path)),char(binding.local_scene_payload_sha256))&& ...
    strcmpi(sha256_file(char(binding.parent_raw_path)),char(binding.parent_raw_sha256))&& ...
    strcmpi(sha256_file(char(binding.parent_status_path)),char(binding.parent_status_sha256))&& ...
    strcmpi(sha256_file(char(binding.parent_run_start_path)),char(binding.parent_run_start_sha256))&& ...
    strcmpi(sha256_file(char(binding.c5_raw_path)),char(binding.c5_raw_sha256))&& ...
    strcmpi(sha256_file(char(binding.c5_status_path)),char(binding.c5_status_sha256))&& ...
    strcmpi(sha256_file(char(binding.c5_run_start_path)),char(binding.c5_run_start_sha256)), ...
    'TRAINPair:InputHash','A bound scene/model input hash changed.');
payloadPath=char(binding.local_scene_payload_path);
vars=whos('-file',payloadPath);
assert(isscalar(vars)&&strcmp(char(vars.name),'scene'),'TRAINPair:Payload','Expected only one scene variable in payload.');
payload=load(payloadPath,'scene');scene=payload.scene;
sceneId=char(string(field_or(scene,'scene_id','')));
assert(strcmp(sceneId,char(binding.selected_scene_id))&&startsWith(sceneId,'DL1018_DEV_')&& ...
    ~contains(sceneId,'TEST')&&~contains(sceneId,'VAL'),'TRAINPair:SceneScope', ...
    'The preflight input must be the manifest-listed TRAIN/DEV scene.');
scene.reference_contract_id='DL1018_SCENE_REF_FIG8_A2_V2';

% Verify completed parent/C5 evidence and the fixed C5 snapshot/model receipt.
parentStatus=jsondecode(fileread(char(binding.parent_status_path)));
parentStart=jsondecode(fileread(char(binding.parent_run_start_path)));
c5Status=jsondecode(fileread(char(binding.c5_status_path)));
c5InputLock=jsondecode(fileread(char(binding.c5_input_lock_path)));
c5LockRows={c5InputLock.scenes.scene_id};c5LockHit=find(strcmp(c5LockRows,sceneId));
assert(isscalar(c5LockHit)&&strcmpi(sha256_file(char(binding.c5_input_lock_path)), ...
    char(binding.c5_input_lock_sha256)), ...
    'TRAINPair:C5InputLock','C5 scene input lock hash or selected row is invalid.');
bRecord=c5InputLock.scenes(c5LockHit).B72_scoring;
bStatus=jsondecode(fileread(char(bRecord.run_status_path)));
assert(strcmpi(char(bRecord.raw_sha256),char(binding.b72_scoring_raw_sha256))&& ...
    strcmpi(char(bRecord.run_status_sha256),char(binding.b72_scoring_status_sha256))&& ...
    strcmpi(sha256_file(char(bRecord.raw_path)),char(bRecord.raw_sha256))&& ...
    strcmpi(sha256_file(char(bRecord.run_status_path)),char(bRecord.run_status_sha256))&& ...
    strcmp(char(bStatus.scene_id),sceneId)&&strcmpi(char(bStatus.raw_sha256),char(bRecord.raw_sha256))&& ...
    strcmp(char(bStatus.log_status),'STABLE')&&double(bStatus.transitions)==20000&& ...
    double(bStatus.state_samples)==20001&&~logical(bStatus.TEST_accessed), ...
    'TRAINPair:B72Source','Selected TRAIN B72 raw/status differs from the locked C5 input identity.');
assert(strcmp(char(parentStatus.state),'COMPLETED')&&strcmp(char(parentStatus.status_value),'STABLE')&& ...
    double(parentStatus.transitions)==20000&&double(parentStatus.state_samples)==20001&& ...
    double(parentStatus.Plant_calls)==1&&~logical(parentStatus.TEST_read)&& ...
    strcmpi(char(parentStatus.raw_sha256),char(binding.parent_raw_sha256))&& ...
    strcmp(char(parentStart.scene_id),sceneId)&&~logical(parentStart.TEST_read)&& ...
    strcmpi(char(parentStart.c5_raw_sha256),char(binding.c5_raw_sha256))&& ...
    strcmpi(char(parentStart.payload_sha256),char(binding.scene_payload_source_sha256))&& ...
    strcmpi(char(c5Status.scene_id),sceneId)&&strcmp(char(c5Status.status),'RUN_COMPLETE_RAW_PENDING_AUDIT')&& ...
    strcmpi(char(c5Status.raw_sha256),char(binding.c5_raw_sha256))&& ...
    isequal(double(c5Status.coordinate_mask(:)),[1;1;0])&&double(c5Status.transitions)==20000&& ...
    double(c5Status.state_samples)==20001&&~logical(c5Status.TEST_accessed)&&double(c5Status.plant_calls)==1, ...
    'TRAINPair:HistoricalRaw','Historical TRAIN parent/C5 runs are not complete or do not bind this scene.');
c5Receipt=jsondecode(fileread(char(binding.c5_receipt_path)));
assert(strcmp(char(c5Receipt.status),'PASS_NO_PLANT_PILOT_PAYLOADS_ONLY')&& ...
    double(c5Receipt.plant_calls)==0&&double(c5Receipt.training_runs)==0&& ...
    ~logical(c5Receipt.tests_data_read)&& ...
    strcmpi(char(c5Receipt.input_records.c5_snapshot_mat.sha256),char(binding.c5_snapshot_sha256))&& ...
    strcmpi(char(c5Receipt.input_records.model_mat.sha256),char(binding.position_model_sha256)), ...
    'TRAINPair:C5Receipt','Frozen C5 receipt is invalid or outside the permitted scope.');
snapshot=load(char(binding.c5_snapshot_path),'cfg','W0');
positionPack=load(char(binding.position_model_path),'model');positionModel=positionPack.model;
assert(strcmp(char(positionModel.model_id),'DSSM14')&&double(positionModel.input_dim)==14&& ...
    double(positionModel.window)==32&&isequal(double(positionModel.output_W),double(snapshot.W0))&& ...
    strcmpi(paired_sha256_double(double(snapshot.W0)),char(c5Receipt.W0_sha256)), ...
    'TRAINPair:C5Model','C5 position model and snapshot W0 do not match the frozen receipt.');
cfg=geometry_cfg(snapshot.cfg);

% Build exactly the parent's cosine-GRU/C5 option set before adding this fold model.
parentModel=load(char(binding.parent_cosine_model_path));
assert(strcmpi(sha256_file(char(binding.parent_cosine_model_path)),char(binding.parent_cosine_model_sha256)), ...
    'TRAINPair:ParentModelSHA','Parent cosine-GRU weights changed.');
opts=make_gate_holdout_options(cfg,positionModel,'GRU_STREAM','ACTIVE',struct, ...
    parentModel,char(binding.parent_cosine_model_sha256));
weightsPath=char(binding.weights_mat_path);w=load(weightsPath);
residual=struct('enabled',true,'weights_sha256',char(release.weights_sha256), ...
    'input_mean',double(w.input_mean(:)),'input_std',double(w.input_std(:)), ...
    'gru_weight_ih_l0',double(w.gru_weight_ih_l0),'gru_weight_hh_l0',double(w.gru_weight_hh_l0), ...
    'gru_bias_ih_l0',double(w.gru_bias_ih_l0(:)),'gru_bias_hh_l0',double(w.gru_bias_hh_l0(:)), ...
    'head_weight',double(w.head_weight),'head_bias',double(w.head_bias(:)), ...
    'beta_rise_time_s',double(w.beta_rise_time_s),'delta_limit_mps2',double(w.delta_limit_mps2), ...
    'action_limit_mps2',double(w.action_limit_mps2));
assert(strcmp(char(w.fold_id),char(binding.fold_id))&& ...
    strcmp(char(modelManifest.fold_id),char(binding.fold_id))&& ...
    isequal(size(residual.gru_weight_ih_l0),[96,14])&& ...
    isequal(size(residual.gru_weight_hh_l0),[96,32])&& ...
    isequal(size(residual.head_weight),[3,32])&& ...
    double(w.seed)==double(release.training_seed)&& ...
    abs(residual.beta_rise_time_s-1.8)<1e-12&&abs(residual.delta_limit_mps2-.5)<1e-12&& ...
    abs(residual.action_limit_mps2-3)<1e-12, ...
    'TRAINPair:WeightsContract','Fold checkpoint export or action contract differs from release.');
opts.stage1_position_runtime.residual_gru=residual;
opts.no_plant_boundary_check=preflightRelease;
markerPath=fullfile(studyRoot,'audits','TRAIN_PAIR_PREFLIGHT_MARKER_v1.json');
opts.composite_attempt_marker=markerPath;
identityOpts=rmfield(opts,'composite_attempt_marker');
identity=gate_holdout_identity_hashes(cfg,positionModel,identityOpts);
opts.gate_identity_lock=identity;
assert(isfield(release,'applied_acceleration_dual_notch'), ...
    'DualNotch:Release','Missing fixed dual-notch diagnostic contract.');
opts.stage1_position_runtime.applied_acceleration_dual_notch= ...
    release.applied_acceleration_dual_notch;
assert(isfield(release,'applied_acceleration_dual_notch'), ...
    'DualNotch:Release','Missing fixed dual-notch diagnostic contract.');
opts.stage1_position_runtime.applied_acceleration_dual_notch= ...
    release.applied_acceleration_dual_notch;
assert(strcmpi(char(identity.common.position_options_sha256), ...
    char(c5Receipt.common_position_options_sha256)), ...
    'TRAINPair:OptionsIdentity','C5/geometry options differ from the fixed parent controller.');
sceneAudit=validate_train_scene_binding_v1(scene,cfg,binding,parentStart);
prepared=struct('scene',scene,'cfg',cfg,'opts',opts,'identity',identity, ...
    'scene_audit',sceneAudit,'scene_id',sceneId,'fold_id',char(binding.fold_id), ...
    'binding_path',bindingPath,'binding_sha256',sha256_file(bindingPath), ...
    'weights_path',weightsPath,'weights_sha256',sha256_file(weightsPath), ...
    'payload_path',payloadPath,'payload_sha256',sha256_file(payloadPath), ...
    'parent_raw_path',char(binding.parent_raw_path),'parent_raw_sha256',char(binding.parent_raw_sha256), ...
    'c5_raw_path',char(binding.c5_raw_path),'c5_raw_sha256',char(binding.c5_raw_sha256), ...
    'marker_path',markerPath,'candidate_runner_root',runnerRoot);
end

function cfg=geometry_cfg(sourceCfg)
cfg=sourceCfg;
if isfield(cfg,'attitude_replacement'),cfg=rmfield(cfg,'attitude_replacement');end
cfg.plant.arm_initial=repmat(.15,4,1);
cfg=bind_paired_fixed_j0(cfg);
end

function value=field_or(s,name,default)
if isstruct(s)&&isfield(s,name),value=s.(name);else,value=default;end
end

function h=sha256_file(path)
fid=fopen(path,'rb');assert(fid>=0,'TRAINPair:Read','Cannot open %s.',path);
cleanup=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear cleanup;
end
