function attemptDir=run_gru_tau01_delayed_start_attempt(sceneId)
% Run one root-released cosine-GRU tracking scene with delayed-head tau=0.1 s.
studyRoot=fileparts(mfilename('fullpath'));cd(studyRoot);addpath(fullfile(studyRoot,'candidate_runner_work','matlab','runtime'),'-begin');addpath(studyRoot,'-begin');
sceneId=char(string(sceneId));release=jsondecode(fileread(fullfile(studyRoot,'RELEASE.json')));
authorized=cellstr(string(release.authorized_scenes));
assert(strcmp(char(release.schema),'DL1018_GRU_STREAM_DEV_RELEASE_V1')&& ...
    strcmp(char(release.variant_schema),'DL1018_GRU_TAU01_DELAYED_START_RELEASE_V1')&& ...
    strcmp(char(release.study_id),'gru_tau01_delayed_start_v1')&& ...
    strcmp(char(release.status),'RELEASED')&&double(release.authorized_Plant_calls)>0&& ...
    any(strcmp(authorized,sceneId)), ...
    'GRUTAU01:BudgetClosed','Prediction-tau Plant release is pending or this scene is not authorized.');
assert(isscalar(regexp(sceneId,'^DL1018_(DEV|VAL)_T[1-3]_C\d{2}_W\d{2}$','once')), ...
    'GRUTAU01:SceneID','Only manifest-bound DEV/VAL scene IDs are accepted.');
prepared=prepare_gru_tau01_delayed_start_no_plant(sceneId,false);
manifest=jsondecode(fileread(fullfile(studyRoot,'SCENE_INPUT_MANIFEST_v1.json')));
hit=find(strcmp({manifest.records.scene_id},sceneId));record=manifest.records(hit);
runsRoot=fullfile(studyRoot,'runs');if ~isfolder(runsRoot),mkdir(runsRoot);end;attemptDir=fullfile(runsRoot,sceneId);
assert(~isfolder(attemptDir)&&~isfile(attemptDir), ...
    'GRUTAU01:DuplicateScene','Refusing to overwrite an existing same-scene attempt.');
markers=dir(fullfile(runsRoot,'**','attempt_started.marker'));
assert(numel(markers)<double(release.authorized_Plant_calls), ...
    'GRUTAU01:CallBudget','All root-authorized Plant calls have been consumed.');
for i=1:numel(markers)
    startPath=fullfile(markers(i).folder,'run_start.json');
    if isfile(startPath)
        prior=jsondecode(fileread(startPath));
        assert(~strcmp(char(prior.scene_id),sceneId),'GRUTAU01:DuplicateScene', ...
            'A prior attempt already used this scene.');
    end
end
assert(java.io.File(attemptDir).mkdirs(),'GRUTAU01:AttemptCreate','Could not create scene attempt.');
releaseSha=sha256_file(fullfile(studyRoot,'RELEASE.json'));startedUtc=utc_now();
write_json(fullfile(attemptDir,'attempt_started.marker'),struct( ...
    'schema','DL1018_GRU_TAU01_DELAYED_START_ATTEMPT_MARKER_V1','scene_id',sceneId, ...
    'created_utc',startedUtc,'stage','RUNNING','release_sha256',releaseSha));
runIdentity=struct('schema','DL1018_GRU_TAU01_DELAYED_START_RUN_START_V1','scene_id',sceneId, ...
    'source_split',char(record.source_split),'candidate','GRU32_STREAM72_COSINE_TAU01_DELAYED_START_S2026102001', ...
    'parent_candidate','GRU32_STREAM72_COSINE_TRACKING_HEAD_S2026102001', ...
    'attitude_arm','GRU_STREAM','geometry_arm','ACTIVE','started_utc',startedUtc, ...
    'release_sha256',releaseSha,'source_hash_manifest_sha256',prepared.source_hash_manifest_sha256, ...
    'source_lock_sha256',prepared.source_lock_sha256, ...
    'scene_input_manifest_sha256',prepared.input_manifest_sha256, ...
    'parent_manifest_sha256',char(release.parent_manifest_sha256), ...
    'scene_payload_sha256',prepared.scene_payload_sha256, ...
    'external_identity_sha256',prepared.external_identity_sha256, ...
    'b_raw_sha256',prepared.b_raw_sha256,'c5_input_lock_sha256',prepared.c5_input_lock_sha256, ...
    'c5_snapshot_sha256',prepared.c5_snapshot_sha256, ...
    'position_model_sha256',prepared.position_model_sha256, ...
    'gru_model_sha256',prepared.gru_model_sha256,'cosine_target_rms',prepared.target_rms, ...
    'position_method_id','C5_AXIS_MIXED_COORDINATE_M110', ...
    'position_nn_compensation_scale',1,'command_filter_wn_rad_s',[18;18;12], ...
    'position_path_changed',true,'position_delayed_prediction_h_s',0.01, ...
    'position_delayed_prediction_rho_schedule',prepared.rho_schedule, ...
    'position_delayed_prediction_gamma',12,'position_delayed_prediction_lambda',0.002, ...
    'position_model_normalizer_changed',false, ...
    'attitude_model_normalizer_changed',false, ...
    'stage1_position_runtime_enabled',prepared.position_runtime_enabled, ...
    'stage1_position_update_enabled',prepared.position_runtime_update_enabled, ...
    'stage1_position_coordination_enabled',prepared.position_coordination_enabled, ...
    'position_delayed_prediction_enabled',prepared.position_delayed_prediction_enabled, ...
    'tracking_runtime','gru_stream_tracking_head_step_v1', ...
    'base_model_weights_fixed',true,'tracking_delta_weights_online',true, ...
    'Plant_truth_deployment_input',false,'inertia_reconstruction_enabled',false, ...
    'test_data_read',false,'closed_loop_entry','run_mlp15_dev72_closed_loop(scene,cfg,opts)');
write_json(fullfile(attemptDir,'run_start.json'),runIdentity);
prepared.opts.composite_attempt_marker=fullfile(attemptDir,'attempt_started.marker');
rawPath=fullfile(attemptDir,'raw_run.mat');rawSha='';plantCallStarted=false;
try
    plantCallStarted=true;
    log=run_mlp15_dev72_closed_loop(prepared.scene,prepared.cfg,prepared.opts);
    log.gru_tau01_delayed_start_release_sha256=releaseSha;scene=prepared.scene;
    save(rawPath,'log','scene','runIdentity','-v7.3');rawSha=sha256_file(rawPath);
    transitions=double(log.last_transition);stateSamples=size(log.state,1);
    assert(transitions==20000&&stateSamples==20001&&strcmp(char(log.status),'STABLE'), ...
        'GRUTAU01:Incomplete','Candidate did not finish a stable 20,000-transition run.');
    status=struct('schema','DL1018_GRU_TAU01_DELAYED_START_RUN_STATUS_V1','state','COMPLETED', ...
        'candidate','GRU32_STREAM72_COSINE_TAU01_DELAYED_START_S2026102001','scene_id',sceneId, ...
        'finished_utc',utc_now(),'Plant_calls',1,'raw_path',rawPath,'raw_sha256',rawSha, ...
        'transitions',transitions,'state_samples',stateSamples,'status_value',char(log.status), ...
        'safety_stop_reason',char(log.safety_stop_reason),'release_sha256',releaseSha, ...
        'source_lock_sha256',prepared.source_lock_sha256, ...
        'position_delayed_prediction_rho_schedule',prepared.rho_schedule, ...
        'position_path_changed',true,'stage1_position_runtime_enabled',prepared.position_runtime_enabled, ...
        'stage1_position_update_enabled',prepared.position_runtime_update_enabled, ...
        'position_delayed_prediction_enabled',prepared.position_delayed_prediction_enabled, ...
        'gru_model_sha256',prepared.gru_model_sha256,'test_data_read',false);
    write_json(fullfile(attemptDir,'run_status.json'),status);
    fprintf('GRU_PREDICTION_TAU01_ATTEMPT_DIR=%s\n',attemptDir);
catch ME
    write_json(fullfile(attemptDir,'run_status.json'),struct( ...
        'schema','DL1018_GRU_TAU01_DELAYED_START_RUN_STATUS_V1','state','FAILED', ...
        'candidate','GRU32_STREAM72_COSINE_TAU01_DELAYED_START_S2026102001','scene_id',sceneId, ...
        'failed_utc',utc_now(),'Plant_calls',double(plantCallStarted),'raw_path',rawPath, ...
        'raw_sha256',rawSha,'raw_present',isfile(rawPath), ...
        'error_identifier',char(ME.identifier),'error_message',char(ME.message), ...
        'release_sha256',releaseSha,'source_lock_sha256',prepared.source_lock_sha256, ...
        'position_delayed_prediction_rho_schedule',prepared.rho_schedule, ...
        'position_path_changed',true,'stage1_position_runtime_enabled',prepared.position_runtime_enabled, ...
        'stage1_position_update_enabled',prepared.position_runtime_update_enabled, ...
        'position_delayed_prediction_enabled',prepared.position_delayed_prediction_enabled, ...
        'gru_model_sha256',prepared.gru_model_sha256,'test_data_read',false));
    write_json(fullfile(attemptDir,'run_failure.json'),struct('scene_id',sceneId, ...
        'failed_utc',utc_now(),'error_identifier',char(ME.identifier), ...
        'error_message',char(ME.message),'stack',{ME.stack}));
    rethrow(ME);
end
end
function h=sha256_file(path)
fid=fopen(path,'rb');assert(fid>=0,'GRUTAU01:Read','Cannot read %s.',path);
cleanup=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear cleanup;
end
function write_json(path,value)
fid=fopen(path,'w','n','UTF-8');assert(fid>=0,'GRUTAU01:Write','Cannot write %s.',path);
cleanup=onCleanup(@()fclose(fid));fprintf(fid,'%s\n',jsonencode(value,'PrettyPrint',true));clear cleanup;
end
function value=utc_now()
value=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z'''));
end
