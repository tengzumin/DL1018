function audit=resume_large_gru_dev24_ordinal2_v1()
% Resume only ordinals 2:23 after the immutable C00 Plant run and action replay.
studyRoot=fileparts(mfilename('fullpath'));
runtime=fullfile(studyRoot,'candidate_runner_work','matlab','runtime');
addpath(runtime);activate_paired_runner();addpath(runtime);
addpath(fullfile(studyRoot,'batch_adapter','matlab','runtime'));
planPath=fullfile(studyRoot,'BATCH_PLAN_v1.json');
protocolPath=fullfile(studyRoot,'BATCH_EXECUTION_PROTOCOL_v1.json');
budgetPath=fullfile(studyRoot,'BUDGET_LEDGER_v1.json');
releasePath=fullfile(studyRoot,'RELEASE.json');
lockPath=fullfile(studyRoot,'SOURCE_LOCK_SINGLE_v2.json');
ledgerPath=fullfile(studyRoot,'BUDGET_JOURNAL_v1.jsonl');
progressPath=fullfile(studyRoot,'BATCH_PROGRESS_v1.json');
plan=jsondecode(fileread(planPath));protocol=jsondecode(fileread(protocolPath));
budget=jsondecode(fileread(budgetPath));baseRelease=jsondecode(fileread(releasePath));
lock=jsondecode(fileread(lockPath));
lockSha=sha256_file(lockPath);
pythonExe=char(protocol.python_executable_path);
assert(isfile(pythonExe)&&strcmpi(sha256_file(pythonExe),char(protocol.python_executable_sha256)), ...
    'LargeGRUDev24:Python','Frozen TCN0906 Python executable is missing or changed.');
assert(strcmpi(lockSha,char(baseRelease.source_lock_sha256))&& ...
    strcmpi(lockSha,char(plan.source_lock_sha256)), ...
    'LargeGRUDev24:Lock','Frozen source lock does not match plan/release.');
assert(strcmp(plan.status,'FROZEN_DEV24_REMAINING23_READY_FOR_ROOT_REVIEW')&& ...
    strcmp(protocol.status,'FROZEN_DEV24_BEFORE_23_PLANT_CALLS')&& ...
    strcmp(budget.status,'FROZEN_CAP_23'), ...
    'LargeGRUDev24:Freeze','Batch protocol/plan/budget are not frozen for execution.');
assert(strcmp(baseRelease.schema,'DL1018_CAUSAL_N4_GATE_NOPLANT_V2')&& ...
    strcmp(baseRelease.status,'PREPARED_NO_PLANT_PENDING_ROOT_AUDIT')&& ...
    baseRelease.authorized_Plant_calls==0&&baseRelease.Plant_calls==0&& ...
    baseRelease.potential_budget_calls==0&& ...
    strcmpi(baseRelease.candidate_identity_sha256,plan.candidate_identity_sha256)&& ...
    strcmpi(baseRelease.candidate_identity_sha256,protocol.candidate_identity_sha256)&& ...
    strcmpi(baseRelease.call_protocol_sha256,protocol.n4_call_protocol_sha256)&& ...
    isequaln(baseRelease.applied_acceleration_static_n4,protocol.fixed_n4_filter), ...
    'LargeGRUDev24:Release','No-Plant release template differs from the frozen N4 candidate.');
assert(isequal(cellstr(string(protocol.ordered_scene_ids)),cellstr(string(plan.ordered_scene_ids)))&& ...
    isequal(cellstr(string(protocol.new_attempt_scene_ids)),cellstr(string(budget.scene_order)))&& ...
    numel(protocol.ordered_scene_ids)==24&&numel(budget.scene_order)==23&& ...
    budget.authorized_batch_call_cap==23&&budget.max_attempts_per_scene==1, ...
    'LargeGRUDev24:Cohort','Cohort/order/budget differs from the fixed TRAIN24 plan.');
reuseIds=cellstr(string(protocol.reuse_scene_ids));newIds=cellstr(string(protocol.new_attempt_scene_ids));
assert(numel(unique([reuseIds;newIds]))==24&&all(ismember(reuseIds,cellstr(string(plan.ordered_scene_ids)))), ...
    'LargeGRUDev24:Membership','Reuse/new membership is not a disjoint 24-scene partition.');
resumeEvidence=verify_resume_state(studyRoot,plan,protocol,budget,baseRelease,lockSha,ledgerPath,progressPath);
assert(~isfile(fullfile(studyRoot,'BATCH_RESUME_ORDINAL2_STARTED_v1.json')), ...
    'LargeGRUDev24:NoResumeRetry','Resume entry was already started; refusing to restart it.');

% The full lock is checked once. The scene helper then rechecks each binding's
% B/C5/parent/model/payload sources immediately before its own attempt.
for i=1:numel(lock.files)
    p=char(lock.files(i).path);
    assert(isfile(p)&&strcmpi(sha256_file(p),char(lock.files(i).sha256)), ...
        'LargeGRUDev24:SourceHash','Locked source changed: %s',p);
end

append_event(ledgerPath,struct('event','BATCH_RESUMED_FROM_ORDINAL_2','utc',utcNow(), ...
    'source_lock_sha256',lockSha,'previous_reserved_calls',1, ...
    'resume_scene_id',newIds{2},'remaining_scene_ids',{newIds(2:end)}, ...
    'previous_completed_raw_scene_id',resumeEvidence.completed_run_scene_id, ...
    'previous_raw_sha256',resumeEvidence.raw_sha256, ...
    'previous_status_sha256',resumeEvidence.status_sha256, ...
    'previous_score_sha256',resumeEvidence.score_sha256,'Plant_calls',1));
progress=jsondecode(fileread(progressPath));
progress.status='RUNNING_RESUMED_FROM_ORDINAL_2';
progress.previous_stop_reason='SCORER_FATAL_OR_SOURCE_INTEGRITY';
progress.resume_from_ordinal=2;progress.resume_utc=utcNow();
progress.resume_prior_scene_id=resumeEvidence.completed_run_scene_id;
progress.resume_prior_raw_sha256=resumeEvidence.raw_sha256;
progress.resume_prior_score_status='PASS_ACTION_REPLAY';
progress.completed_scenes=cellstr(string(progress.completed_scenes));
if ~any(strcmp(progress.completed_scenes,resumeEvidence.completed_run_scene_id))
    progress.completed_scenes{end+1}=resumeEvidence.completed_run_scene_id;
end
progress.last_score=resumeEvidence.c00_score;
progress.Plant_calls=1;progress.calls_reserved=1;
write_json_replace(progressPath,progress);
attemptOrdinal=1;
try
    for i=2:numel(newIds)
        sceneId=newIds{i};attemptOrdinal=attemptOrdinal+1;
        assert(attemptOrdinal<=23,'LargeGRUDev24:Budget','The 23-call batch budget is exhausted.');
        bindingPath=fullfile(studyRoot,'bindings',[sceneId '.json']);
        binding=jsondecode(fileread(bindingPath));
        attempt=binding.candidate_attempt;attemptDir=char(attempt.attempt_dir);
        marker=char(attempt.attempt_started_marker_path);firstPlant=char(attempt.first_plant_step_marker_path);
        assert(~isfolder(attemptDir)&&~isfile(marker)&&~isfile(firstPlant), ...
            'LargeGRUDev24:NoRetry','Attempt/marker already exists for %s.',sceneId);

        singleRelease=baseRelease;
        singleRelease.schema='DL1018_CAUSAL_N4_GATE_SINGLE_CALL_V2';
        singleRelease.study_id='large_gru_dual_loop_dev_v1';
        singleRelease.status='RELEASED';singleRelease.fixed_scene_id=sceneId;
        singleRelease.authorized_scenes={sceneId};
        singleRelease.authorized_Plant_calls=1;singleRelease.Plant_calls=1;
        singleRelease.potential_budget_calls=1;
        singleRelease.source_lock_path=lockPath;singleRelease.source_lock_sha256=lockSha;
        singleRelease.phase='DEV24';singleRelease.candidate_gru=baseRelease.candidate_gru;
        write_json_replace(releasePath,singleRelease);
        write_json_replace(fullfile(studyRoot,'SINGLE_CALL_RELEASE.json'),singleRelease);
        releaseSha=sha256_file(releasePath);
        prepared=prepare_causal_n4_train24_scene_no_plant(sceneId);
        assert(strcmp(prepared.scene_id,sceneId)&& ...
            ~prepared.opts.no_plant_boundary_check&& ...
            ~isfield(prepared.opts.stage1_position_runtime,'residual_gru')&& ...
            strcmpi(prepared.binding_sha256,sha256_file(bindingPath)), ...
            'LargeGRUDev24:PreparedIdentity','Prepared call differs from the exact scene binding.');

        % Consume the budget durably before any attempt marker or Plant call.
        append_event(ledgerPath,struct('event','RESERVED','ordinal',attemptOrdinal, ...
            'scene_id',sceneId,'utc',utcNow(),'release_sha256',releaseSha, ...
            'source_lock_sha256',lockSha,'binding_sha256',prepared.binding_sha256, ...
            'attempt_dir',attemptDir,'reserved_budget_calls',1, ...
            'budget_consumed_before_plant',true,'Plant_calls',0));
        progress.calls_reserved=attemptOrdinal;
        write_json_replace(progressPath,progress);

        assert(java.io.File(attemptDir).mkdirs(),'LargeGRUDev24:AttemptDir', ...
            'Cannot create the unique attempt directory for %s.',sceneId);
        write_new(marker,struct('stage','RUNNING','scene_id',sceneId,'Plant_calls',0, ...
            'reserved_budget_calls',1,'budget_ordinal',attemptOrdinal));
        snapshotPath=fullfile(attemptDir,'single_call_release_snapshot.json');
        start=struct('scene_id',sceneId,'source_split','TRAIN_C5_24','started_utc',utcNow(), ...
            'budget_ordinal',attemptOrdinal,'reserved_budget_calls',1,'Plant_calls',0, ...
            'release_sha256',releaseSha,'single_call_release_snapshot_path',snapshotPath, ...
            'single_call_release_snapshot_sha256',releaseSha, ...
            'source_lock_sha256',lockSha,'binding_sha256',prepared.binding_sha256, ...
            'candidate_identity_sha256',char(plan.candidate_identity_sha256), ...
            'execution_identity',prepared.execution_identity, ...
            'payload_sha256',prepared.payload_sha256, ...
            'scene_identity_sha256',prepared.scene_audit.external_identity_sha256, ...
            'B_raw_sha256',prepared.b_raw_sha256,'parent_raw_sha256',prepared.parent_raw_sha256, ...
            'candidate_gru_model_sha256',prepared.candidate_gru_model_sha256, ...
            'old_parent_comparator_raw_sha256',prepared.old_parent_comparator_raw_sha256, ...
            'C5_raw_sha256',prepared.c5_raw_sha256,'TEST_read',false,'VAL_read',false, ...
            'inertia_reconstruction_enabled',false);
        write_new(char(attempt.run_start_path),start);
        opts=prepared.opts;opts.composite_attempt_marker=marker;
        try
            assert(~isfile(snapshotPath),'LargeGRUDev24:ResumeNoOverwrite', ...
                'Single-call release snapshot already exists for %s.',sceneId);
            [copied,msg]=copyfile(fullfile(studyRoot,'SINGLE_CALL_RELEASE.json'),snapshotPath);
            assert(copied&&strcmpi(sha256_file(snapshotPath),releaseSha), ...
                'LargeGRUDev24:ReleaseSnapshot','Could not preserve exact per-call release: %s',msg);
            log=run_mlp15_dev72_closed_loop(prepared.scene,prepared.cfg,opts);
            transitions=double(log.last_transition);samples=size(log.state,1);
            scene=prepared.scene;identity=start;
            save(char(attempt.raw_path),'log','scene','identity','-v7.3');
            complete=transitions==20000&&samples==20001&&strcmp(log.status,'STABLE')&& ...
                all(isfinite(double(log.state(:))))&&isfile(firstPlant);
            actualPlant=double(isfile(firstPlant));
            status=struct('state',ternary(complete,'COMPLETED','INCOMPLETE'), ...
                'scene_id',sceneId,'finished_utc',utcNow(),'Plant_calls',actualPlant, ...
                'single_call_release_snapshot_path',snapshotPath, ...
                'single_call_release_snapshot_sha256',conditional_hash(snapshotPath), ...
                'reserved_budget_calls',1, ...
                'raw_path',char(attempt.raw_path),'raw_sha256',sha256_file(char(attempt.raw_path)), ...
                'transitions',transitions,'state_samples',samples,'status_value',log.status, ...
                'safety_stop_reason',char(string(field_or(log,'safety_stop_reason',''))), ...
                'first_plant_step_marker_created',isfile(firstPlant), ...
                'budget_ordinal',attemptOrdinal,'release_sha256',releaseSha, ...
                'source_lock_sha256',lockSha,'binding_sha256',prepared.binding_sha256, ...
                'candidate_gru_model_sha256',prepared.candidate_gru_model_sha256, ...
                'TEST_read',false,'VAL_read',false,'inertia_reconstruction_enabled',false);
            write_new(char(attempt.status_path),status);
            assert(complete,'LargeGRUDev24:StableRun','Stable 20k run/non-finite/safety gate failed for %s.',sceneId);
            write_json_replace(marker,struct('stage','COMPLETED','scene_id',sceneId, ...
                'Plant_calls',actualPlant,'first_plant_step_marker_created',true, ...
                'budget_ordinal',attemptOrdinal));
        catch ME
            actualPlant=double(isfile(firstPlant));
            statusPath=char(attempt.status_path);
            if ~isfile(statusPath)
                failure=struct('state','FAILED','scene_id',sceneId,'failed_utc',utcNow(), ...
                    'Plant_calls',actualPlant,'reserved_budget_calls',1, ...
                    'error_identifier',ME.identifier,'error_message',ME.message, ...
                    'first_plant_step_marker_created',isfile(firstPlant), ...
                    'budget_ordinal',attemptOrdinal,'release_sha256',releaseSha, ...
                    'source_lock_sha256',lockSha,'binding_sha256',prepared.binding_sha256, ...
                    'TEST_read',false,'VAL_read',false,'inertia_reconstruction_enabled',false);
                write_new(statusPath,failure);
            end
            if isfile(marker)
                write_json_replace(marker,struct('stage','FAILED','scene_id',sceneId, ...
                    'Plant_calls',actualPlant,'reserved_budget_calls',1, ...
                    'first_plant_step_marker_created',isfile(firstPlant), ...
                    'budget_ordinal',attemptOrdinal,'error_identifier',ME.identifier));
            end
            append_event(ledgerPath,struct('event','ATTEMPT_FAILED','ordinal',attemptOrdinal, ...
                'scene_id',sceneId,'utc',utcNow(),'error_identifier',ME.identifier, ...
                'error_message',ME.message,'reserved_budget_calls',1, ...
                'Plant_calls',actualPlant,'first_plant_step_marker_created',isfile(firstPlant)));
            progress.status='STOPPED_FATAL';progress.stopped_scene_id=sceneId;
            progress.Plant_calls=count_first_plant_markers(studyRoot);
            progress.stop_reason=ME.identifier;write_json_replace(progressPath,progress);
            rethrow(ME);
        end

        scorePath=char(attempt.score_path);
        command=sprintf('"%s" "%s" --scene "%s" --candidate-dir "%s"', ...
            pythonExe,fullfile(studyRoot,'..','large_gru_b768_v1','aggregate_large_gru_dev24_scores_v2.py'), ...
            sceneId,studyRoot);
        [scoreCode,scoreOutput]=system(command);fprintf('%s',scoreOutput);
        progress.Plant_calls=count_first_plant_markers(studyRoot);
        append_event(ledgerPath,struct('event','ATTEMPT_SCORED','ordinal',attemptOrdinal, ...
            'scene_id',sceneId,'utc',utcNow(),'score_path',scorePath, ...
            'reserved_budget_calls',1,'Plant_calls',double(isfile(firstPlant)), ...
            'score_exit_code',scoreCode,'score_sha256',conditional_hash(scorePath)));
        if scoreCode~=0
            progress.status='STOPPED_FATAL';progress.stopped_scene_id=sceneId;
            progress.stop_reason='SCORER_FATAL_OR_SOURCE_INTEGRITY';write_json_replace(progressPath,progress);
            error('LargeGRUDev24:ScoreFatal','Fatal safety/stability/non-finite or scoring integrity error at %s.',sceneId);
        end
        score=jsondecode(fileread(scorePath));
        progress.completed_scenes=cellstr(string(progress.completed_scenes));
        progress.completed_scenes{end+1}=sceneId;progress.last_score=score;
        progress.Plant_calls=count_first_plant_markers(studyRoot);
        write_json_replace(progressPath,progress);
        write_json_replace(releasePath,baseRelease);
    end
    progress.status='COMPLETE_23_NEW_SCENES_PLUS_1_B768_PILOT_REUSE';
    progress.finished_utc=utcNow();write_json_replace(progressPath,progress);
    append_event(ledgerPath,struct('event','BATCH_COMPLETED','utc',utcNow(), ...
        'reserved_budget_calls',attemptOrdinal,'Plant_calls',progress.Plant_calls, ...
        'score_summary_sha256', ...
        sha256_file(fullfile(studyRoot,'..','large_gru_b768_v1','paired_results','DEV24','paired_progress_v2.json'))));
catch ME
    write_json_replace(releasePath,baseRelease);
    rethrow(ME);
end
audit=progress;
end

function evidence=verify_resume_state(studyRoot,plan,protocol,budget,release,lockSha,ledgerPath,progressPath)
assert(isfile(ledgerPath)&&isfile(progressPath)&&isfolder(fullfile(studyRoot,'runs'))&& ...
    isfolder(fullfile(studyRoot,'scores'))&&isfile(fullfile(studyRoot,'SINGLE_CALL_RELEASE.json')), ...
    'LargeGRUDev24:ResumeState','Expected the stopped ordinal-1 batch artifacts.');
assert(strcmp(release.status,'PREPARED_NO_PLANT_PENDING_ROOT_AUDIT')&& ...
    strcmpi(char(release.source_lock_sha256),lockSha)&& ...
    strcmpi(char(plan.source_lock_sha256),lockSha)&& ...
    budget.authorized_batch_call_cap==23&&budget.max_attempts_per_scene==1, ...
    'LargeGRUDev24:ResumeIdentity','Base release/source lock/budget do not match the frozen batch.');
manifestPath=fullfile(studyRoot,'RESUME_ORDINAL2_MANIFEST_v1.json');
manifest=jsondecode(fileread(manifestPath));
resumeScript=[mfilename('fullpath') '.m'];
assert(strcmp(manifest.status,'PREPARED_FOR_ROOT_REVIEW')&& ...
    strcmpi(sha256_file(resumeScript),char(manifest.resume_script_sha256))&& ...
    strcmpi(char(manifest.source_lock_sha256),lockSha)&& ...
    strcmpi(char(manifest.score_wrapper_path), ...
        fullfile(studyRoot,'..','large_gru_b768_v1','aggregate_large_gru_dev24_scores_v2.py'))&& ...
    isfile(char(manifest.score_wrapper_path))&& ...
    strcmpi(sha256_file(char(manifest.score_wrapper_path)),char(manifest.score_wrapper_sha256))&& ...
    strcmpi(char(manifest.initial_journal_sha256),sha256_file(ledgerPath))&& ...
    strcmpi(char(manifest.initial_progress_sha256),sha256_file(progressPath)), ...
    'LargeGRUDev24:ResumeManifest','Resume source/lock does not match its prepared manifest.');
events=read_jsonl(ledgerPath);
assert(numel(events)==3&&strcmp(events{1}.event,'BATCH_STARTED')&& ...
    strcmp(events{2}.event,'RESERVED')&&events{2}.ordinal==1&& ...
    strcmp(events{3}.event,'ATTEMPT_SCORED')&&events{3}.ordinal==1&& ...
    events{3}.score_exit_code~=0&&events{3}.Plant_calls==1, ...
    'LargeGRUDev24:ResumeJournal','Journal is not the exact one-call scorer-failure state.');
newIds=cellstr(string(protocol.new_attempt_scene_ids));
sceneId=newIds{1};assert(strcmp(sceneId,'DL1018_DEV_T1_C00_W03')&& ...
    numel(newIds)==23&&strcmp(newIds{2},manifest.resume_scene_id), ...
    'LargeGRUDev24:ResumeQueue','The required ordinal-1/ordinal-2 scene order differs.');
progress=jsondecode(fileread(progressPath));
assert(strcmp(progress.status,'STOPPED_FATAL')&&progress.calls_reserved==1&& ...
    progress.Plant_calls==1&&strcmp(progress.stopped_scene_id,sceneId)&& ...
    strcmp(progress.stop_reason,'SCORER_FATAL_OR_SOURCE_INTEGRITY'), ...
    'LargeGRUDev24:ResumeProgress','Progress is not the stopped C00 state.');
first=jsondecode(fileread(fullfile(studyRoot,'bindings',[sceneId '.json'])));
attempt=first.candidate_attempt;attemptDir=char(attempt.attempt_dir);
bindingPath=fullfile(studyRoot,'bindings',[sceneId '.json']);
runStart=jsondecode(fileread(char(attempt.run_start_path)));
status=jsondecode(fileread(char(attempt.status_path)));
startMarker=char(attempt.attempt_started_marker_path);plantMarker=char(attempt.first_plant_step_marker_path);
rawSha=sha256_file(char(attempt.raw_path));statusSha=sha256_file(char(attempt.status_path));
snapshotPath=fullfile(attemptDir,'single_call_release_snapshot.json');
bindingSha=sha256_file(bindingPath);releasePath=fullfile(studyRoot,'SINGLE_CALL_RELEASE.json');
releaseSha=sha256_file(releasePath);
assert(isfolder(attemptDir)&&isfile(startMarker)&&isfile(plantMarker)&& ...
    strcmp(status.state,'COMPLETED')&&strcmp(status.status_value,'STABLE')&& ...
    status.transitions==20000&&status.state_samples==20001&&status.Plant_calls==1&& ...
    strcmpi(status.raw_sha256,rawSha)&&strcmpi(status.binding_sha256,bindingSha)&& ...
    strcmpi(status.source_lock_sha256,lockSha)&&strcmpi(status.release_sha256,releaseSha)&& ...
    strcmpi(runStart.binding_sha256,bindingSha)&&strcmpi(runStart.source_lock_sha256,lockSha)&& ...
    strcmpi(runStart.release_sha256,releaseSha)&&isfile(snapshotPath)&& ...
    strcmpi(sha256_file(snapshotPath),releaseSha)&& ...
    strcmpi(runStart.candidate_gru_model_sha256,char(first.candidate_gru_model_sha256)), ...
    'LargeGRUDev24:ResumeRaw','C00 raw/status/start/marker identity is incomplete or changed.');
scorePath=char(attempt.score_path);score=jsondecode(fileread(scorePath));scoreSha=sha256_file(scorePath);
assert(strcmp(score.status,'PASS_ACTION_REPLAY')&&strcmp(score.phase,'DEV24')&& ...
    strcmp(score.scene_id,sceneId)&&score.Plant_calls==1&& ...
    strcmpi(score.raw_sha256,rawSha)&&strcmpi(score.candidate_model_sha256,char(first.candidate_gru_model_sha256))&& ...
    strcmpi(score.source_lock_sha256,lockSha)&& ...
    strcmpi(score.single_call_release_sha256,releaseSha)&& ...
    score.action_replay.criteria.same_new_raw_input_N4_replay&& ...
    score.action_replay.criteria.held_1ms_and_force_chain, ...
    'LargeGRUDev24:ResumeScore','C00 action-replay PASS is missing or bound to another raw/model.');
assert(strcmp(events{2}.scene_id,sceneId)&&strcmpi(events{2}.binding_sha256,bindingSha)&& ...
    strcmpi(events{2}.release_sha256,releaseSha)&&strcmpi(events{2}.source_lock_sha256,lockSha)&& ...
    strcmpi(events{3}.score_sha256,scoreSha)&& ...
    numel(dir(fullfile(studyRoot,'runs','**','first_plant_step.marker')))==1, ...
    'LargeGRUDev24:ResumeEvidence','C00 journal hash/marker count differs.');
for i=2:numel(newIds)
    b=jsondecode(fileread(fullfile(studyRoot,'bindings',[newIds{i} '.json'])));
    a=b.candidate_attempt;
    assert(~isfolder(char(a.attempt_dir))&&~isfile(char(a.attempt_started_marker_path))&& ...
        ~isfile(char(a.first_plant_step_marker_path))&&~isfile(char(a.status_path))&& ...
        ~isfile(char(a.score_path)), ...
        'LargeGRUDev24:ResumeNoRetry','A later ordinal already has artifacts: %s',newIds{i});
end
evidence=struct('completed_run_scene_id',sceneId,'raw_sha256',rawSha, ...
    'status_sha256',statusSha,'score_sha256',scoreSha,'binding_sha256',bindingSha, ...
    'release_sha256',releaseSha,'source_lock_sha256',lockSha, ...
    'initial_journal_sha256',sha256_file(ledgerPath),'initial_progress_sha256',sha256_file(progressPath), ...
    'c00_score',score);
end
function events=read_jsonl(path)
raw=fileread(path);lines=regexp(strtrim(raw),'\r?\n','split');events=cell(numel(lines),1);
for i=1:numel(lines),events{i}=jsondecode(lines{i});end
end

function append_event(path,event)
fid=fopen(path,'a');assert(fid>=0,'LargeGRUDev24:Journal','Cannot append budget journal: %s',path);
c=onCleanup(@()fclose(fid));fprintf(fid,'%s\n',jsonencode(event));clear c;
end
function write_new(path,x)
assert(~isfile(path),'LargeGRUDev24:NoOverwrite','Refusing to overwrite %s.',path);
write_json_replace(path,x);
end
function write_json_replace(path,x)
tmp=[path '.tmp'];
if isfile(tmp),delete(tmp);end
fid=fopen(tmp,'w');assert(fid>=0,'LargeGRUDev24:Write','Cannot write %s.',tmp);
c=onCleanup(@()fclose(fid));fwrite(fid,[jsonencode(x,'PrettyPrint',true) newline],'char');clear c;
[ok,msg]=movefile(tmp,path,'f');assert(ok,'LargeGRUDev24:Move','Cannot atomically replace %s: %s',path,msg);
end
function h=conditional_hash(path)
if isfile(path),h=sha256_file(path);else,h='';end
end
function n=count_first_plant_markers(studyRoot)
d=dir(fullfile(studyRoot,'runs','**','first_plant_step.marker'));n=numel(d);
end
function h=sha256_file(path)
fid=fopen(path,'rb');assert(fid>=0,'LargeGRUDev24:Read','Cannot open %s.',path);
c=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear c;
end
function s=utcNow()
s=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z'''));
end
function y=ternary(c