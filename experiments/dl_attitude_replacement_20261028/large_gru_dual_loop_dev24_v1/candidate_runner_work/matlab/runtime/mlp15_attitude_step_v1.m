function [memory,out]=mlp15_attitude_step_v1(action,memory,in,model)
% Frozen MLP15 representation with an optional past-residual linear update head.
switch lower(char(action))
    case 'init'
        validate_model(model);
        memory=struct('history_normalized',zeros(13,14),'event_count',0, ...
            'head_weight',zeros(33,3),'head_covariance',10*eye(33), ...
            'previous_phi',zeros(33,1),'previous_base_normalized',zeros(3,1), ...
            'previous_sample_index',0,'previous_time_s',0,'previous_beta',0, ...
            'fixed_J0',zeros(0,0));
        out=struct('initialized',true);
    case 'step'
        validate_model(model);
        required={'feature','J0','beta','dmax'};
        assert(isstruct(in)&&all(isfield(in,required)), ...
            'DLMLP:StepInput','Missing MLP15 step input fields.');
        feature=double(in.feature(:));J0=double(in.J0);
        beta=double(in.beta);dmax=double(in.dmax(:));
        assert(numel(feature)==13&&all(isfinite(feature))&&isequal(size(J0),[3,3])&& ...
            all(isfinite(J0),'all')&&numel(dmax)==3&&all(isfinite(dmax))&&all(dmax>0)&& ...
            isscalar(beta)&&isfinite(beta)&&beta>=0&&beta<=1, ...
            'DLMLP:StepShape','Invalid feature, J0, beta, or output limit.');
        assert(isstruct(memory)&&isequal(size(memory.history_normalized),[13,14])&& ...
            all(isfinite(memory.history_normalized),'all'), ...
            'DLMLP:Memory','MLP15 causal history is invalid.');
        xNorm=(feature-double(model.input_mean(:)))./double(model.input_std(:));
        window=[double(memory.history_normalized),xNorm];
        [baseResidual,hidden]=mlp15_attitude_forward_v1(window,model);
        enabled=isfield(in,'head_enabled')&&logical(in.head_enabled);
        [memory,residual,head]=causal_head(memory,in,baseResidual,hidden,model,enabled);
        clipped=min(max(residual,-dmax),dmax);
        estimateTorque=J0*(beta*clipped);
        memory.history_normalized=window(:,2:end);
        memory.event_count=double(memory.event_count)+1;
        out=struct('raw_residual_rad_s2',residual, ...
            'clipped_residual_rad_s2',clipped,'beta',beta, ...
            'estimateTorque_Nm',estimateTorque,'feature_normalized',xNorm, ...
            'history_count',memory.event_count,'head',head);
    otherwise
        error('DLMLP:Action','Unknown action %s.',char(action));
end
end

function [memory,residual,d]=causal_head(memory,in,base,hidden,model,enabled)
scale=double(model.target_rms(:));phi=[double(hidden(:));1];phi=phi/norm(phi);
before=double(memory.head_weight);P=double(memory.head_covariance);
assert(isequal(size(before),[33,3])&&isequal(size(P),[33,33])&& ...
    all(isfinite([before(:);P(:)]))&&norm(before,'fro')<=20+1e-10, ...
    'DLMLP:HeadState','Invalid causal head state.');
residual=base;
if enabled,residual=base+scale.*(before.'*phi);end
% Output is fixed above; the following observation changes only the next output.
d=struct('enabled',logical(enabled),'update_executed',false, ...
    'weight_before',before,'weight_after',before,'phi',phi, ...
    'base_residual_rad_s2',base,'correction_residual_rad_s2',residual-base, ...
    'observation_residual_rad_s2',zeros(3,1),'observation_start_time_s',0, ...
    'observation_end_time_s',0,'previous_feature_sample_index',memory.previous_sample_index, ...
    'previous_feature_time_s',memory.previous_time_s,'issued_torque_max_sample_index',0, ...
    'projection_active',false,'covariance_min_cholesky_diagonal',sqrt(10), ...
    'covariance_diagonal_after',diag(P),'weight_norm_before',norm(before,'fro'), ...
    'weight_norm_after',norm(before,'fro'),'tracking_drive',zeros(33,3), ...
    'tracking_surface',zeros(3,1),'tracking_euler_rate_map',eye(3), ...
    'actual_event_dt',0,'tracking_update_executed',false);
if ~enabled,return;end
assert(all(isfield(in,{'sample_index','time_s','tracking_surface', ...
    'tracking_euler_rate_map','actual_event_dt'}))&&isscalar(in.sample_index)&& ...
    in.sample_index==round(in.sample_index)&&in.sample_index>memory.previous_sample_index&& ...
    isfinite(in.time_s)&&in.time_s>memory.previous_time_s&& ...
    isscalar(in.actual_event_dt)&&isfinite(in.actual_event_dt)&&in.actual_event_dt>=0&& ...
    isequal(size(in.tracking_euler_rate_map),[3,3])&& ...
    all(isfinite(in.tracking_euler_rate_map),'all')&&numel(in.tracking_surface)==3&& ...
    all(isfinite(in.tracking_surface)), ...
    'DLMLP:HeadTime','Head events or tracking inputs are invalid.');
T=double(in.tracking_euler_rate_map);surface=double(in.tracking_surface(:));
if memory.previous_sample_index>0
    assert(abs(double(in.actual_event_dt)-(double(in.time_s)-memory.previous_time_s))<1e-10, ...
        'DLMLP:EventDt','Tracking dt must equal the interval between actual head events.');
else
    assert(double(in.actual_event_dt)==0,'DLMLP:EventDt', ...
        'The first head event has no preceding event interval.');
end
d.tracking_surface=surface;d.tracking_euler_rate_map=T;
d.actual_event_dt=double(in.actual_event_dt);
J0=double(in.J0);
if isempty(memory.fixed_J0),memory.fixed_J0=J0;end
assert(isequal(J0,memory.fixed_J0),'DLMLP:FixedJ0','The nominal J0 must remain constant.');
after=before;
if memory.previous_sample_index>0
    assert(all(isfield(in,{'omega_history','torque_history','history_time','history_sample_indices'})), ...
        'DLMLP:HistoryFields','Missing measured past interval.');
    omega=double(in.omega_history);torque=double(in.torque_history);
    times=double(in.history_time(:));indices=double(in.history_sample_indices(:));
    count=numel(times);
    assert(count==11&&isequal(size(omega),[count,3])&&isequal(size(torque),[count-1,3])&& ...
        all(isfinite([omega(:);torque(:);times;indices]))&& ...
        indices(1)==memory.previous_sample_index&&indices(end)==in.sample_index&&all(diff(indices)==1)&& ...
        abs(times(1)-memory.previous_time_s)<1e-10&&abs(times(end)-in.time_s)<1e-10&& ...
        max(abs(diff(times)-.001))<1e-10&& ...
        max(abs(omega(end,:).'-double(in.feature(4:6))))<1e-12, ...
        'DLMLP:HistoryCausality','Gyro/control history must exactly cover the preceding 10 ms.');
    span=times(end)-times(1);
    gyro=cross(omega(1:end-1,:),omega(1:end-1,:)*J0.',2);
    observed=((omega(end,:)-omega(1,:))/span+mean((gyro-torque)/J0.',1)).';
    d.observation_residual_rad_s2=observed;d.observation_start_time_s=times(1);
    d.observation_end_time_s=times(end);d.issued_torque_max_sample_index=indices(end)-1;
    if memory.previous_beta>=1&&double(in.beta)>=1
        previousPhi=double(memory.previous_phi);Pprior=P/.999;
        gain=(Pprior*previousPhi)/(1+previousPhi.'*Pprior*previousPhi);
        innovation=observed./scale-double(memory.previous_base_normalized)-before.'*previousPhi;
        after=before+gain*innovation.';
        A=eye(33)-gain*previousPhi.';
        P=A*Pprior*A.'+gain*gain.';P=(P+P.')/2;
        [factor,flag]=chol(P);assert(flag==0,'DLMLP:HeadSPD','RLS covariance lost positive definiteness.');
        d.update_executed=true;
        d.covariance_min_cholesky_diagonal=min(diag(factor));
        d.covariance_diagonal_after=diag(P);
    end
end
if memory.previous_sample_index>0&&double(in.beta)>=1
    trackingDrive=-(P*phi)*(double(in.beta)*(scale.*(T.'*surface))).';
    after=after+double(in.actual_event_dt)*trackingDrive;
    d.tracking_drive=trackingDrive;d.tracking_update_executed=true;
end
magnitude=norm(after,'fro');
if magnitude>20,after=after*(20/magnitude);d.projection_active=true;end
memory.head_weight=after;memory.head_covariance=P;
d.weight_after=after;d.weight_norm_after=norm(after,'fro');
memory.previous_phi=phi;memory.previous_base_normalized=base./scale;
memory.previous_sample_index=double(in.sample_index);memory.previous_time_s=double(in.time_s);
memory.previous_beta=double(in.beta);
assert(all(isfinite([residual(:);memory.head_weight(:);memory.head_covariance(:)]))&& ...
    memory.head_weight(1,1)==d.weight_after(1,1), ...
    'DLMLP:HeadFinite','Head output/update became invalid.');
end

function validate_model(model)
required={'input_mean','input_std','target_rms','fc1_weight','fc1_bias', ...
    'fc2_weight','fc2_bias','head_weight','head_bias'};
assert(isstruct(model)&&all(isfield(model,required)), ...
    'DLMLP:Model','MLP15 model fields are incomplete.');
assert(numel(model.input_mean)==13&&numel(model.input_std)==13&& ...
    numel(model.target_rms)==3&&all(double(model.input_std(:))>0)&& ...
    all(double(model.target_rms(:))>0)&&all(isfinite([double(model.input_mean(:)); ...
    double(model.input_std(:));double(model.target_rms(:))])), ...
    'DLMLP:Normalizer','MLP15 normalizer is invalid.');
assert(isequal(size(model.fc1_weight),[64,195])&&numel(model.fc1_bias)==64&& ...
    isequal(size(model.fc2_weight),[32,64])&&numel(model.fc2_bias)==32&& ...
    isequal(size(model.head_weight),[3,32])&&numel(model.head_bias)==3&& ...
    all(isfinite(double(model.fc1_weight(:))))&&all(isfinite(double(model.fc1_bias(:))))&& ...
    all(isfinite(double(model.fc2_weight(:))))&&all(isfinite(double(model.fc2_bias(:))))&& ...
    all(isfinite(double(model.head_weight(:))))&&all(isfinite(double(model.head_bias(:)))), ...
    'DLMLP:WeightShape','MLP15 weights have invalid shapes or values.');
end
