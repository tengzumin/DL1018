function attemptDir=run_causal_n4_single_call()
% Exactly one fixed TRAIN call, with passing no-Plant audit and locked sources.
entry=fileparts(mfilename('fullpath'));studyRoot=fileparts(fileparts(fileparts(entry)));
releasePath=fullfile(studyRoot,'SINGLE_CALL_RELEASE.json');lockPath=fullfile(studyRoot,'SOURCE_LOCK_SINGLE_v2.json');
release=jsondecode(fileread(releasePath));lock=jsondecode(fileread(lockPath));
assert(strcmpi(sha256_file(lockPath),release.source_lock_sha256),'N4Gate:Lock','Single-call source lock changed.');
for i=1:numel(lock.files)
    p=char(lock.files(i).path);
    assert(isfile(p)&&strcmpi(sha256_file(p),char(lock.files(i).sha256)), ...
        'N4Gate:SourceHash','Locked source changed: %s',p);
end
priorPath=char(release.prior_no_plant_preflight_path);
assert(strcmpi(sha256_file(priorPath),release.prior_no_plant_preflight_sha256), ...
    'N4Gate:PriorHash','No-Plant preflight changed.');
prior=jsondecode(fileread(priorPath));
assert(strcmp(prior.status,'PASS_FULL_RUNNER_NOPLANT_BOUNDARY')&& ...
    strcmp(prior.scene_id,release.fixed_scene_id)&&prior.Plant_calls==0&& ...
    prior.attempt_markers==0&&prior.first_plant_step_markers==0, ...
    'N4Gate:Prior','No-Plant audit is not a clean same-scene pass.');
assert(strcmp(release.schema,'DL1018_CAUSAL_N4_GATE_SINGLE_CALL_V2')&& ...
    strcmp(release.status,'RELEASED')&&release.authorized_Plant_calls==1&& ...
    release.Plant_calls==1&&release.potential_budget_calls==1&& ...
    numel(release.authorized_scenes)==1&&strcmp(release.authorized_scenes{1},release.fixed_scene_id)&& ...
    ~release.TEST_read&&~release.VAL_data_read&&~release.inertia_reconstruction_enabled&& ...
    ~release.Plant_truth_deployment_input,'N4Gate:Budget','Expected the exact one-call TRAIN release.');
prepared=prepare_causal_n4_scene_single_call(release.fixed_scene_id);
assert(~prepared.opts.no_plant_boundary_check&&~isfield(prepared.opts.stage1_position_runtime,'residual_gru'), ...
    'N4Gate:PreparedIdentity','Prepared runtime does not match the release.');
attemptDir=fullfile(studyRoot,'runs',prepared.scene_id,'attempt_01');
assert(~isfolder(attemptDir)&&~isfile(attemptDir),'N4Gate:NoOverwrite','Attempt already exists.');
assert(java.io.File(attemptDir).mkdirs(),'N4Gate:AttemptDir','Cannot create attempt directory.');
marker=fullfile(attemptDir,'attempt_started.marker');firstPlant=fullfile(attemptDir,'first_plant_step.marker');
opts=prepared.opts;opts.composite_attempt_marker=marker;
start=struct('scene_id',prepared.scene_id,'source_split','TRAIN_C5_24','started_utc',utcNow(), ...
    'release_sha256',sha256_file(releasePath),'source_lock_sha256',sha256_file(lockPath), ...
    'prior_no_plant_preflight_sha256',sha256_file(priorPath),'binding_sha256',prepared.binding_sha256, ...
    'payload_sha256',prepared.payload_sha256,'scene_identity_sha256',prepared.scene_audit.external_identity_sha256, ...
    'candidate_gru_model_sha256',prepared.candidate_gru_model_sha256, ...
    'B_raw_sha256',prepared.b_raw_sha256, ...
    'old_parent_comparator_raw_sha256',prepared.old_parent_comparator_raw_sha256, ...
    'C5_raw_sha256',prepared.c5_raw_sha256,'TEST_read',false,'VAL_read',false, ...
    'inertia_reconstruction_enabled',false);
write_new(marker,struct('stage','RUNNING','scene_id',prepared.scene_id,'Plant_calls',1));
write_new(fullfile(attemptDir,'run_start.json'),start);
try
    log=run_mlp15_dev72_closed_loop(prepared.scene,prepared.cfg,opts);
    transitions=double(log.last_transition);samples=size(log.state,1);
    scene=prepared.scene;identity=start;save(fullfile(attemptDir,'raw_run.mat'),'log','scene','identity','-v7.3');
    rawPath=fullfile(attemptDir,'raw_run.mat');
    complete=transitions==20000&&samples==20001&&strcmp(log.status,'STABLE')&&isfile(firstPlant);
    status=struct('state',ternary(complete,'COMPLETED','INCOMPLETE'),'scene_id',prepared.scene_id, ...
        'finished_utc',utcNow(),'Plant_calls',1,'raw_path',rawPath,'raw_sha256',sha256_file(rawPath), ...
        'transitions',transitions,'state_samples',samples,'status_value',log.status, ...
        'safety_stop_reason',log.safety_stop_reason,'first_plant_step_marker_created',isfile(firstPlant), ...
        'release_sha256',start.release_sha256,'source_lock_sha256',start.source_lock_sha256, ...
        'prior_no_plant_preflight_sha256',start.prior_no_plant_preflight_sha256, ...
        'TEST_read',false,'VAL_read',false,'inertia_reconstruction_enabled',false);
    write_new(fullfile(attemptDir,'run_status.json'),status);
    assert(complete,'N4Gate:Incomplete','Single call did not complete a stable 20k run.');
    write_json(marker,struct('stage','COMPLETED','scene_id',prepared.scene_id,'Plant_calls',1, ...
        'first_plant_step_marker_created',true));
    fprintf('CAUSAL_N4_SINGLE_ATTEMPT=%s\n',attemptDir);
catch ME
    statusPath=fullfile(attemptDir,'run_status.json');
    if ~isfile(statusPath)
        failure=struct('state','FAILED','scene_id',prepared.scene_id,'failed_utc',utcNow(),'Plant_calls',1, ...
            'error_identifier',ME.identifier,'error_message',ME.message, ...
            'first_plant_step_marker_created',isfile(firstPlant),'release_sha256',start.release_sha256, ...
            'source_lock_sha256',start.source_lock_sha256,'TEST_read',false,'VAL_read',false, ...
            'inertia_reconstruction_enabled',false);
        write_new(statusPath,failure);
    end
    rethrow(ME);
end
end
function write_new(path,x)
assert(~isfile(path),'N4Gate:NoOverwrite','Refusing to overwrite %s.',path);write_json(path,x);
end
function write_json(path,x)
fid=fopen(path,'w');assert(fid>=0,'N4Gate:Write','Cannot write %s.',path);
c=onCleanup(@()fclose(fid));fwrite(fid,[jsonencode(x,'PrettyPrint',true) newline],'char');clear c;
end
function h=sha256_file(path)
fid=fopen(path,'rb');assert(fid>=0,'N4Gate:Read','Cannot open %s.',path);
c=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear c;
end
function s=utcNow()
s=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z'''));
end
function y=ternary(c,a,b)
if c,y=a;else,y=b;end
end
