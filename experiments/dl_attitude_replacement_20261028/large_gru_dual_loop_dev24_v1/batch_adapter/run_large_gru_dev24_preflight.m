function audit=run_large_gru_dev24_preflight()
entry=fileparts(mfilename('fullpath'));studyRoot=fileparts(entry);
addpath(fullfile(studyRoot,'candidate_runner_work','matlab','runtime'));
addpath(fullfile(studyRoot,'batch_adapter','matlab','runtime'));
activate_paired_runner();
release=jsondecode(fileread(fullfile(studyRoot,'RELEASE.json')));
plan=jsondecode(fileread(fullfile(studyRoot,'BATCH_PLAN_v1.json')));
protocol=jsondecode(fileread(fullfile(studyRoot,'BATCH_EXECUTION_PROTOCOL_v1.json')));
budget=jsondecode(fileread(fullfile(studyRoot,'BUDGET_LEDGER_v1.json')));
lockPath=fullfile(studyRoot,'SOURCE_LOCK_SINGLE_v2.json');lock=jsondecode(fileread(lockPath));
assert(strcmpi(sha256_file(lockPath),release.source_lock_sha256)&& ...
    strcmpi(release.source_lock_sha256,plan.source_lock_sha256), ...
    'LargeGRUDev24:Lock','Candidate source lock differs from release/plan.');
checked=0;
for i=1:numel(lock.files)
    p=char(lock.files(i).path);
    assert(isfile(p)&&strcmpi(sha256_file(p),char(lock.files(i).sha256)), ...
        'LargeGRUDev24:SourceHash','Locked source changed: %s',p);
    checked=checked+1;
end
authority=jsondecode(fileread(char(plan.authoritative_scene_list_path)));
ids=cell(numel(authority.scenes),1);
for i=1:numel(ids),ids{i}=char(authority.scenes(i).scene_id);end
assert(isequal(ids,cellstr(string(plan.ordered_scene_ids)))&& ...
    isequal(ids,cellstr(string(protocol.ordered_scene_ids)))&& ...
    isequal(cellstr(string(protocol.new_attempt_scene_ids)),cellstr(string(budget.scene_order)))&& ...
    numel(ids)==24&&numel(protocol.new_attempt_scene_ids)==23&& ...
    numel(protocol.reuse_scene_ids)==1&&strcmp(protocol.reuse_scene_ids{1},'DL1018_DEV_T3_C09_W09'), ...
    'LargeGRUDev24:Cohort','DEV24 queue differs from the frozen TRAIN24 summary.');
assert(strcmp(release.schema,'DL1018_CAUSAL_N4_GATE_NOPLANT_V2')&& ...
    strcmp(release.status,'PREPARED_NO_PLANT_PENDING_ROOT_AUDIT')&& ...
    numel(release.authorized_scenes)==24&&release.authorized_Plant_calls==0&& ...
    release.Plant_calls==0&&release.potential_budget_calls==0&& ...
    ~release.TEST_read&&~release.VAL_data_read&&~release.inertia_reconstruction_enabled, ...
    'LargeGRUDev24:NoPlantRelease','DEV24 release must remain zero-Plant.');
assert(~isfile(fullfile(studyRoot,'SINGLE_CALL_RELEASE.json'))&& ...
    ~isfolder(fullfile(studyRoot,'runs'))&&~isfolder(fullfile(studyRoot,'scores'))&& ...
    ~isfolder(fullfile(studyRoot,'audits'))&&~isfile(fullfile(studyRoot,'BUDGET_JOURNAL_v1.jsonl'))&& ...
    ~isfile(fullfile(studyRoot,'BATCH_PROGRESS_v1.json')), ...
    'LargeGRUDev24:NoPlantMutation','A run/attempt/budget artifact already exists.');
entries=cell(numel(ids),1);
for i=1:numel(ids)
    prepared=prepare_causal_n4_train24_scene_no_plant(ids{i});
    assert(prepared.opts.no_plant_boundary_check&& ...
        strcmpi(prepared.candidate_gru_model_sha256,char(release.candidate_gru.sha256)), ...
        'LargeGRUDev24:CandidateIdentity','Scene was not prepared with the B768 candidate.');
    entries{i}=struct('scene_id',ids{i},'binding_sha256',prepared.binding_sha256, ...
        'candidate_gru_model_sha256',prepared.candidate_gru_model_sha256, ...
        'old_parent_comparator_raw_sha256',prepared.old_parent_comparator_raw_sha256, ...
        'C5_raw_sha256',prepared.c5_raw_sha256,'B_raw_sha256',prepared.b_raw_sha256);
end
audit=struct('schema','DL1018_LARGE_GRU_DUAL_LOOP_DEV24_NOPLANT_AUDIT_V1', ...
    'status','PASS_DEV24_BATCH_NOPLANT_PREPARE','study_id',release.study_id, ...
    'phase','DEV24','scene_count',24,'ordered_scene_ids',{ids}, ...
    'new_attempt_count',23,'reuse_count',1,'candidate_gru_model_sha256',release.candidate_gru.sha256, ...
    'source_lock_sha256',release.source_lock_sha256,'source_hashes_checked',checked, ...
    'Plant_calls',0,'authorized_Plant_calls',0,'potential_budget_calls',0, ...
    'attempt_directories_created',0,'attempt_markers_created',0,'first_plant_markers_created',0, ...
    'TEST_read',false,'VAL_read',false,'inertia_reconstruction_enabled',false,'entries',{entries});
out=fullfile(studyRoot,'DEV24_NOPLANT_AUDIT_v1.json');
assert(~isfile(out),'LargeGRUDev24:NoOverwrite','Refusing to overwrite no-Plant audit.');
fid=fopen(out,'w');assert(fid>=0,'LargeGRUDev24:Write','Cannot write no-Plant audit.');
c=onCleanup(@()fclose(fid));fwrite(fid,[jsonencode(audit,'PrettyPrint',true) newline],'char');clear c;
disp(['DEV24_NOPLANT_AUDIT=' out]);
end
function h=sha256_file(path)
fid=fopen(path,'rb');assert(fid>=0,'LargeGRUDev24:Read','Cannot open %s.',path);
c=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear c;
end
