function receipt=run_position_applied_lowpass_prepare()
studyRoot=fileparts(mfilename('fullpath'));cd(studyRoot);
addpath(fullfile(studyRoot,'audits'),'-begin');
p=prepare_position_applied_lowpass_candidate_no_plant();
receipt=jsondecode(fileread(fullfile(studyRoot,'NO_PLANT_PREPARE_RESULT_v1.json')));
assert(strcmp(char(receipt.status),'PASS_NO_PLANT_PREPARE')&& ...
    receipt.Plant_calls==0&&~receipt.plant_called&&~receipt.TEST_data_read&& ...
    receipt.run_directory_created==0&& ...
    strcmp(char(p.scene_id),char(receipt.prepared_scene_id))&& ...
    strcmp(char(receipt.prepared_scene_id),char(receipt.parent_scene_id))&& ...
    logical(receipt.prepared_position_runtime_enabled)&& ...
    logical(receipt.prepared_position_update_enabled)&& ...
    logical(receipt.prepared_pcf_coordination_enabled)&& ...
    logical(receipt.prepared_delayed_prediction_enabled)&& ...
    abs(double(receipt.prepared_lowpass_tau_s)-.1)<1e-12&& ...
    receipt.prior_failure_count==4&&receipt.prior_entry_wrapper_invocations==4&& ...
    receipt.prior_entry_runner_invocations==3&& ...
    ~logical(receipt.prior_entry_plant_dynamics_started)&& ...
    isequal(double(receipt.prior_entry_wrapper_reported_Plant_calls(:)),[1;0;0])&& ...
    receipt.authorized_plant_dynamics_calls_remaining==1&& ...
    receipt.previous_failure_directory_preserved&&~receipt.new_retry_run_directory_created&& ...
    receipt.prior_failure_records_preserved&& ...
    receipt.retry_preflight_existing_runs_root&&receipt.retry_preflight_clean_target_absent&& ...
    strcmp(char(receipt.release_schema_gate_probe), ...
    'PASS_REJECTED_AT_MISSING_MARKER_BEFORE_SIMULATION')&& ...
    strcmp(char(receipt.release_schema_gate_probe_error_identifier),'CompositeDEV:AttemptMarker')&& ...
    strcmp(char(receipt.release_main_loop_preflight_probe),'PASS_STOPPED_BEFORE_MAIN_LOOP')&& ...
    strcmp(char(receipt.release_main_loop_preflight_error_identifier),'PositionLPF:NoPlantPreflightStop')&& ...
    logical(receipt.candidate_gate_identity_lock_includes_lowpass_tau)&& ...
    logical(receipt.candidate_gate_identity_lock_revalidated_by_runner)&& ...
    strcmp(char(receipt.clean_retry_relative_path), ...
    ['runs/' char(p.scene_id) '_retry_005'])&& ...
    strcmp(char(receipt.run_identity_preflight), ...
    'PASS_COMPLETE_IDENTITY_BEFORE_DIRECTORY_OR_MARKER')&& ...
    any(contains(string(receipt.run_identity_preflight_fields),'parent_manifest_sha256'))&& ...
    strcmp(char(p.parent_manifest_sha256),char(receipt.parent_manifest_sha256))&& ...
    abs(double(p.lowpass_tau_s)-.1)<1e-12&& ...
    strcmpi(which('run_mlp15_dev72_closed_loop'), ...
    fullfile(studyRoot,'candidate_runner_work','matlab','runtime','run_mlp15_dev72_closed_loop.m'))&& ...
    strcmpi(char(receipt.resolved_closed_loop_path),which('run_mlp15_dev72_closed_loop')));
end
