function receipt=prepare_position_applied_lowpass_no_plant()
% Verify the isolated source fork and filter contract without invoking Plant.
studyRoot=fileparts(fileparts(mfilename('fullpath')));
runnerRoot=fullfile(studyRoot,'candidate_runner_work');
assert(strcmpi(pwd,studyRoot),'PositionLPF:StudyRoot','Run from the isolated low-pass study root.');
release=jsondecode(fileread(fullfile(studyRoot,'RELEASE.json')));
manifestPath=fullfile(studyRoot,'SOURCE_HASH_MANIFEST_v1.json');
lockPath=fullfile(studyRoot,'SOURCE_LOCK_v1.json');
assert(strcmpi(sha256_file(manifestPath),char(release.source_hash_manifest_sha256))&& ...
    strcmpi(sha256_file(lockPath),char(release.source_lock_sha256)), ...
    'PositionLPF:LockDigest','Source manifest or lock digest differs from release.');
manifest=jsondecode(fileread(manifestPath));lock=jsondecode(fileread(lockPath));
assert(strcmp(char(manifest.schema),'DL1018_POSITION_APPLIED_LOWPASS_SOURCE_MANIFEST_V1')&& ...
    numel(manifest.files)==double(manifest.source_file_count)&& ...
    strcmpi(char(java.io.File(char(lock.root)).getCanonicalPath()), ...
    char(java.io.File(studyRoot).getCanonicalPath())), ...
    'PositionLPF:LockShape','Source manifest or lock shape is invalid.');
for i=1:numel(manifest.files)
    f=manifest.files(i);path=fullfile(studyRoot,strrep(char(f.path),'/',filesep));
    assert(isfile(path)&&strcmpi(sha256_file(path),char(f.sha256)), ...
        'PositionLPF:SourceHash','Locked source changed: %s.',path);
end
for i=1:numel(lock.files)
    f=lock.files(i);path=fullfile(studyRoot,strrep(char(f.path),'/',filesep));
    assert(isfile(path)&&strcmpi(sha256_file(path),char(f.sha256)), ...
        'PositionLPF:SourceLock','Locked source changed: %s.',path);
end
assert(isfield(lock,'external_artifacts'),'PositionLPF:ExternalLock', ...
    'Source lock is missing runtime data artifacts.');
for i=1:numel(lock.external_artifacts)
    f=lock.external_artifacts(i);path=fullfile(studyRoot,strrep(char(f.path),'/',filesep));
    assert(isfile(path)&&strcmpi(sha256_file(path),char(f.sha256)), ...
        'PositionLPF:ExternalArtifactHash','Locked runtime data artifact changed: %s.',path);
end

parentRoot=char(java.io.File(fullfile(studyRoot,'..','gru_tau01_delayed_start_v1')).getCanonicalPath());
parentReceiptPath=fullfile(parentRoot,'NO_PLANT_PREPARE_RESULT_v1.json');
parentReceipt=jsondecode(fileread(parentReceiptPath));parentCfg=jsondecode(fileread(fullfile(parentRoot,'LOCKED_CFG.json')));
assert(strcmp(char(parentReceipt.status),'PASS_NO_PLANT_PREPARE')&& ...
    double(parentReceipt.Plant_calls)==0&&~logical(parentReceipt.plant_called)&& ...
    ~logical(parentReceipt.test_data_read)&& ...
    strcmpi(sha256_file(fullfile(parentRoot,'LOCKED_CFG.json')),char(release.parent_locked_cfg_sha256))&& ...
    isequal(double(parentReceipt.command_filter_wn_rad_s(:)),[18;18;12])&& ...
    isequal(double(parentReceipt.fixed_J0),double(parentCfg.J0_kgm2))&& ...
    abs(double(parentReceipt.beta_rise_time_s)-2.2)<1e-12, ...
    'PositionLPF:ParentBinding','Parent no-Plant identity/config binding is invalid.');
dependencyPath=fullfile(studyRoot,char(release.runtime_dependency_manifest_path));
assert(isfile(dependencyPath)&&strcmpi(sha256_file(dependencyPath), ...
    char(release.runtime_dependency_manifest_sha256)), ...
    'PositionLPF:RuntimeDependencyHash','Runtime dependency manifest SHA differs from release.');
dependencies=jsondecode(fileread(dependencyPath));
parentPayloadManifest=fullfile(parentRoot,'MLP15_DEV72_PAYLOAD_MANIFEST_v2.json');
candidatePayloadManifest=fullfile(studyRoot,'MLP15_DEV72_PAYLOAD_MANIFEST_v2.json');
assert(strcmp(char(dependencies.schema),'DL1018_POSITION_APPLIED_LOWPASS_RUNTIME_DEPENDENCIES_V1')&& ...
    strcmp(char(dependencies.status),'PASS_LOCKED_ACTIVE_RUNNER_DEPENDENCIES')&& ...
    strcmpi(sha256_file(parentPayloadManifest),char(release.parent_dev72_payload_manifest_sha256))&& ...
    strcmpi(sha256_file(candidatePayloadManifest),char(release.parent_dev72_payload_manifest_sha256))&& ...
    strcmpi(char(dependencies.parent_payload_manifest_sha256), ...
    char(release.parent_dev72_payload_manifest_sha256)), ...
    'PositionLPF:RuntimeDependency','Parent DEV72 manifest copy/hash is not bound.');
readRecords=dependencies.study_root_file_reads;
readPaths=string({readRecords.path});readerNames=string({readRecords.reader});
assert(all(ismember(["RELEASE.json","attempt_started.marker", ...
    "MLP15_DEV72_PAYLOAD_MANIFEST_v2.json"],readPaths))&& ...
    any(readerNames=="run_mlp15_dev72_closed_loop")&& ...
    any(readerNames=="gate_holdout_validate_dev72_scene"), ...
    'PositionLPF:RuntimeDependencyInventory','Active runner studyRoot reads are not fully enumerated.');
for i=1:numel(dependencies.source_bindings)
    rec=dependencies.source_bindings(i);
    path=fullfile(studyRoot,strrep(char(rec.path),'/',filesep));
    assert(isfile(path)&&strcmpi(sha256_file(path),char(rec.sha256)), ...
        'PositionLPF:RuntimeDependencySource','Active runtime dependency caller changed: %s.',path);
end
runnerPath=fullfile(studyRoot,'candidate_runner_work','matlab','runtime','run_mlp15_dev72_closed_loop.m');
validatorPath=fullfile(studyRoot,'candidate_runner_work','matlab','runtime','gate_holdout_validate_dev72_scene.m');
attemptPath=fullfile(studyRoot,'run_position_applied_lowpass_attempt.m');
assert(contains(fileread(runnerPath),'sceneAudit=gate_holdout_validate_dev72_scene(s,cfg,gateGeometryArm);')&& ...
    contains(fileread(runnerPath),'releasePath=fullfile(studyRoot,''RELEASE.json'');')&& ...
    contains(fileread(runnerPath),'markerPath=char(string(field_or(opts,''composite_attempt_marker'','''')));')&& ...
    contains(fileread(validatorPath),'MLP15_DEV72_PAYLOAD_MANIFEST_v2.json')&& ...
    contains(fileread(attemptPath),'prepare_position_applied_lowpass_candidate_no_plant()')&& ...
    contains(fileread(attemptPath),'run_mlp15_dev72_closed_loop(prepared.scene,prepared.cfg,prepared.opts)'), ...
    'PositionLPF:RuntimeDependencyCallers','Active studyRoot file readers/callers differ from the locked dependency inventory.');

% Only one existing runtime and one new helper may differ from the parent.
parentRunner=fullfile(parentRoot,'candidate_runner_work');
parentFiles=relative_m_files(parentRunner);childFiles=relative_m_files(runnerRoot);
added=setdiff(childFiles,parentFiles);missing=setdiff(parentFiles,childFiles);
assert(isequal(added,{'matlab/models/position_applied_accel_lowpass_zoh.m'})&&isempty(missing), ...
    'PositionLPF:ForkFiles','Fork added/removed source files beyond the filter helper.');
changed={};
for i=1:numel(parentFiles)
    rel=parentFiles{i};a=sha256_file(fullfile(parentRunner,strrep(rel,'/',filesep)));
    b=sha256_file(fullfile(runnerRoot,strrep(rel,'/',filesep)));
    if ~strcmpi(a,b),changed{end+1}=rel;end %#ok<AGROW>
end
assert(isequal(changed,{'matlab/runtime/run_mlp15_dev72_closed_loop.m'})&& ...
    isequal(sort(added),sort(cellstr(string(release.allowed_added_source_files)))), ...
    'PositionLPF:ForkDiff','Only the intended runtime insertion may differ from parent.');
runtimeText=fileread(fullfile(runnerRoot,'matlab','runtime','run_mlp15_dev72_closed_loop.m'));
assert(contains(runtimeText,'position_applied_accel_lowpass_zoh(stage1PositionAppliedLowpassState')&& ...
    contains(runtimeText,'stage1PositionHeldForce=P.mass*stage1PositionAppliedLowpassState;')&& ...
    contains(runtimeText,'dF=stage1PositionHeldForce;')&& ...
    contains(runtimeText,'positionInfo.commanded_acceleration,stage1PcfEta'), ...
    'PositionLPF:SignalPath','Filtered acceleration must feed the held force and existing PCF path.');

addpath(fullfile(studyRoot,'audits'),'-begin');
check=check_position_applied_lowpass_zoh(runnerRoot);
assert(strcmp(char(check.status),'PASS_NO_PLANT_FILTER_CHECK')&&double(check.Plant_calls)==0&& ...
    abs(double(check.tau_s)-.1)<1e-12&&abs(double(check.event_dt_s)-.01)<1e-12, ...
    'PositionLPF:Check','No-Plant filter arithmetic checks failed.');
receipt=struct('schema','DL1018_POSITION_APPLIED_LOWPASS_NOPLANT_PREPARE_V1', ...
    'status','PASS_NO_PLANT_PREPARE','study_id',char(release.study_id), ...
    'parent_study_id','gru_tau01_delayed_start_v1','parent_scene_id',char(parentReceipt.scene_id), ...
    'parent_no_plant_receipt_sha256',sha256_file(parentReceiptPath), ...
    'source_hash_manifest_sha256',sha256_file(manifestPath),'source_lock_sha256',sha256_file(lockPath), ...
    'runtime_dependency_manifest_sha256',sha256_file(dependencyPath), ...
    'parent_dev72_payload_manifest_sha256',sha256_file(parentPayloadManifest), ...
    'parent_manifest_sha256',char(dependencies.parent_preparation.parent_manifest_sha256), ...
    'active_runtime_dependency_inventory_verified',true, ...
    'changed_parent_source_files',{changed},'added_source_files',{added}, ...
    'tau_s',double(check.tau_s),'event_rate_hz',100,'event_dt_s',double(check.event_dt_s), ...
    'alpha_first_event',double(check.alpha_100hz),'alpha_1khz_comparison',double(check.alpha_1khz_comparison), ...
    'filter_initial_state',[0 0 0],'saturation_bound_violation',double(check.max_beta_dmax_bound_violation), ...
    'position_force_uses_filtered_output',true,'pcf_uses_same_force_derived_position_request',true, ...
    'Plant_calls',0,'plant_called',false,'TEST_data_read',false,'run_directory_created',false, ...
    'no_plant_checks',check);
write_json(fullfile(studyRoot,'NO_PLANT_PREPARE_RESULT_v1.json'),receipt);
fprintf('POSITION_APPLIED_LOWPASS_NOPLANT=PASS tau=%.3f s event=%.3f s alpha=%.8f\n', ...
    receipt.tau_s,receipt.event_dt_s,receipt.alpha_first_event);
end

function files=relative_m_files(root)
d=dir(fullfile(root,'**','*.m'));files=cell(1,numel(d));
for i=1:numel(d)
    full=fullfile(d(i).folder,d(i).name);rel=extractAfter(full,[root filesep]);
    files{i}=strrep(char(rel),filesep,'/');
end
files=sort(files);
end
function h=sha256_file(path)
fid=fopen(path,'rb');assert(fid>=0,'PositionLPF:Read','Cannot read %s.',path);
cleanup=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear cleanup;
end
function write_json(path,value)
fid=fopen(path,'w','n','UTF-8');assert(fid>=0,'PositionLPF:Write','Cannot write %s.',path);
cleanup=onCleanup(@()fclose(fid));fprintf(fid,'%s\n',jsonencode(value,'PrettyPrint',true));clear cleanup;
end
