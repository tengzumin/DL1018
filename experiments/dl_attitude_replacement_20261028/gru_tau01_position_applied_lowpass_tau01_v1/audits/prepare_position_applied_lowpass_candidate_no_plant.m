function write_json(path,value)
fid=fopen(path,'w','n','UTF-8');assert(fid>=0,'PositionLPF:Write','Cannot write %s.',path);
cleanup=onCleanup(@()fclose(fid));fprintf(fid,'%s\n',jsonencode(value,'PrettyPrint',true));clear cleanup;
end
function h=sha256_file(path)
fid=fopen(path,'rb');assert(fid>=0,'PositionLPF:Read','Cannot read %s.',path);
cleanup=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear cleanup;
end
function h=sha256_text(value)
md=java.security.MessageDigest.getInstance('SHA-256');
md.update(typecast(uint8(unicode2native(char(value),'UTF-8')),'int8'));
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
function assert_preserved_failure(folder,hashes)
names={'attempt_started.marker','run_start.json','run_status.json','run_failure.json'};
keys={'marker','run_start','run_status','run_failure'};
for i=1:numel(names)
    path=fullfile(folder,names{i});
    assert(isfile(path)&&strcmpi(sha256_file(path),char(hashes.(keys{i}))), ...
        'PositionLPF:FailureEvidence','Preserved attempt evidence changed: %s.',path);
end
assert(~isfile(fullfile(folder,'raw_run.mat'))&& ...
    ~isfile(fullfile(folder,'first_plant_step.marker')), ...
    'PositionLPF:FailureDynamics','Prior failure contains Plant dynamics evidence: %s.',folder);
end
