function result=check_gru_tau01_delayed_start_step()
% Verify the rho schedule against the 1-ms simulation clock at 100-Hz events.
W=zeros(33,3);phi=zeros(33,1);phi(1)=1;s=zeros(3,1);
phiPrev=zeros(33,1);phiPrev(2)=1;yPrev=[2;-1;.5];
nValues=[330 4990 5000 5500 5990 6000 6010 19990];rhoValues=zeros(size(nValues));
for q=1:numel(nValues)
    n=nValues(q);j=n-10;tN=n*.001;tJ=j*.001;
    rhoExpected=.01+.09*min(max((n*.001-5)/(6-5),0),1);
    out=delayed_prediction_step_candidate(W,phi,s,n,tN,phiPrev,yPrev,j,tJ);
    expected=rhoExpected*(phiPrev*yPrev.');
    assert(max(abs(out.W_next-expected),[],'all')<1e-14&& ...
        isequal(out.raw,zeros(3,1))&&isequal(out.applied,zeros(3,1))&& ...
        abs(out.beta-min((n+1)*.001/1.8,1))<1e-14, ...
        'PredictionDelayedStart:Step','Gradient schedule, units, or unchanged output-before-update behavior failed at n=%d.',n);
    rhoValues(q)=rhoExpected;
end
assert(max(abs(rhoValues([1 2 3])-[.01 .01 .01]))<1e-14&& ...
    abs(rhoValues(4)-.055)<1e-14&&abs(rhoValues(5)-.0991)<1e-14&& ...
    max(abs(rhoValues(6:8)-[.1 .1 .1]))<1e-14, ...
    'PredictionDelayedStart:RhoSchedule','rho hold/ramp/final schedule mismatch.');
result=struct('status','PASS','simulation_dt_s',.001,'event_stride_steps',10, ...
    'event_indices_zero_based',nValues,'event_times_s',nValues*.001, ...
    'rho_values',rhoValues,'rho_before_5s',.01,'rho_at_5s',.01, ...
    'rho_at_5_5s',.055,'rho_at_6s_and_later',.1, ...
    'gradient_units','unchanged coefficient on delayed prediction gradient', ...
    'prediction_h_s',.01,'gamma',12,'lambda',.002,'Plant_calls',0);
end
