function identity=build_position_applied_lowpass_run_identity(prepared,release,releaseSha,startedUtc)
% Construct the complete run identity before an attempt directory/marker exists.
required={'scene','scene_id','scene_payload_sha256','external_identity_sha256', ...
    'b_raw_sha256','c5_input_lock_sha256','c5_snapshot_sha256','position_model_sha256', ...
    'gru_model_sha256','source_lock_sha256','input_manifest_sha256','parent_manifest_sha256', ...
    'rho_schedule','candidate_source_hash_manifest_sha256','candidate_source_lock_sha256', ...
    'runtime_dependency_manifest_sha256','parent_dev72_payload_manifest_sha256','cfg','opts'};
assert(isstruct(prepared)&&all(isfield(prepared,required))&& ...
    isfield(prepared.scene,'scene_id')&&strcmp(char(prepared.scene.scene_id),char(prepared.scene_id))&& ...
    isfield(prepared.opts,'stage1_position_runtime')&& ...
    abs(double(prepared.opts.stage1_position_runtime.applied_acceleration_lowpass_tau_s)-.1)<1e-12, ...
    'PositionLPF:RunIdentityFields','Prepared scene/options or a run identity field is missing.');
assert(all(isfield(release,{'study_id','retry_sequence','retry_of_relative_path', ...
    'prior_gate_failure_audit_sha256','prior_dependency_failure_audit_sha256', ...
    'prior_identity_failure_audit_sha256','prior_exact_options_failure_audit_sha256'}))&& ...
    isscalar(release.retry_sequence)&&double(release.retry_sequence)==5, ...
    'PositionLPF:RunIdentityRelease','Release retry identity is incomplete or not sequence 5.');
identity=struct('schema','DL1018_POSITION_APPLIED_LOWPASS_RUN_START_V1', ...
    'scene_id',char(prepared.scene_id),'parent_study_id','gru_tau01_delayed_start_v1', ...
    'candidate_study_id',char(release.study_id),'started_utc',char(startedUtc), ...
    'attempt_sequence',double(release.retry_sequence), ...
    'retry_of',char(release.retry_of_relative_path), ...
    'prior_gate_failure_audit_sha256',char(release.prior_gate_failure_audit_sha256), ...
    'prior_dependency_failure_audit_sha256',char(release.prior_dependency_failure_audit_sha256), ...
    'prior_identity_failure_audit_sha256',char(release.prior_identity_failure_audit_sha256), ...
    'prior_exact_options_failure_audit_sha256',char(release.prior_exact_options_failure_audit_sha256), ...
    'release_sha256',char(releaseSha), ...
    'source_hash_manifest_sha256',char(prepared.candidate_source_hash_manifest_sha256), ...
    'source_lock_sha256',char(prepared.candidate_source_lock_sha256), ...
    'parent_source_lock_sha256',char(prepared.source_lock_sha256), ...
    'parent_scene_input_manifest_sha256',char(prepared.input_manifest_sha256), ...
    'parent_manifest_sha256',char(prepared.parent_manifest_sha256), ...
    'parent_c5_snapshot_sha256',char(prepared.c5_snapshot_sha256), ...
    'runtime_dependency_manifest_sha256',char(prepared.runtime_dependency_manifest_sha256), ...
    'parent_dev72_payload_manifest_sha256',char(prepared.parent_dev72_payload_manifest_sha256), ...
    'scene_payload_sha256',char(prepared.scene_payload_sha256), ...
    'external_identity_sha256',char(prepared.external_identity_sha256), ...
    'b_raw_sha256',char(prepared.b_raw_sha256), ...
    'c5_input_lock_sha256',char(prepared.c5_input_lock_sha256), ...
    'position_model_sha256',char(prepared.position_model_sha256), ...
    'gru_model_sha256',char(prepared.gru_model_sha256), ...
    'position_method_id','C5_AXIS_MIXED_COORDINATE_M110', ...
    'position_delayed_prediction_h_s',.01, ...
    'position_delayed_prediction_rho_schedule',prepared.rho_schedule, ...
    'applied_acceleration_lowpass_tau_s',.1, ...
    'applied_acceleration_lowpass_event_rate_hz',100, ...
    'applied_acceleration_lowpass_initial_state_mps2',[0;0;0], ...
    'applied_acceleration_lowpass_event_dt_source','actual rbfFullDt', ...
    'position_force_and_pcf_use_same_filtered_output',true, ...
    'command_filter_wn_rad_s',[18;18;12], ...
    'inertia_reconstruction_enabled',false,'TEST_data_read',false, ...
    'closed_loop_entry','run_mlp15_dev72_closed_loop(scene,cfg,opts)');
end
