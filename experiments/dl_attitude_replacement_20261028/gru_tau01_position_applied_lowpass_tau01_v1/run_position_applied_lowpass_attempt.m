function attemptDir=run_position_applied_lowpass_attempt()
% One root-authorized scene; intentionally fails closed while release is pending.
studyRoot=fileparts(mfilename('fullpath'));cd(studyRoot);
addpath(fullfile(studyRoot,'audits'),'-begin');
releasePath=fullfile(studyRoot,'RELEASE.json');release=jsondecode(fileread(releasePath));
sceneId=char(release.fixed_scene_id);authorized=cellstr(string(release.authorized_scenes));
assert(strcmp(char(release.schema),'DL1018_POSITION_APPLIED_LOWPASS_RELEASE_V1')&& ...
    strcmp(char(release.status),'RELEASED')&&double(release.authorized_Plant_calls)==1&& ...
    double(release.Plant_calls)==0&&numel(authorized)==1&&strcmp(authorized{1},sceneId)&& ...
    ~logical(release.TEST_data_read)&&~logical(release.inertia_reconstruction_enabled), ...
    'PositionLPF:BudgetClosed','This single-scene Plant call requires an explicit one-call root release.');
assert(isscalar(regexp(sceneId,'^DL1018_(DEV|VAL)_T[1-3]_C\d{2}_W\d{2}$','once')), ...
    'PositionLPF:SceneID','Only one manifest-bound DEV/VAL scene is accepted.');
prepared=prepare_position_applied_lowpass_candidate_no_plant();
addpath(fullfile(studyRoot,'audits'),'-begin');
assert(strcmp(char(prepared.scene.scene_id),sceneId)&& ...
    abs(double(prepared.opts.stage1_position_runtime.applied_acceleration_lowpass_tau_s)-.1)<1e-12, ...
    'PositionLPF:SceneBinding','Prepared scene or low-pass config differs from the release.');
candidateRuntime=fullfile(studyRoot,'candidate_runner_work','matlab','runtime');
expectedRunner=fullfile(candidateRuntime,'run_mlp15_dev72_closed_loop.m');
assert(strcmpi(which('run_mlp15_dev72_closed_loop'),expectedRunner), ...
    'PositionLPF:RunnerResolution','Refusing to invoke a runner outside this candidate source tree.');
% Preserve the rejected attempt and permit exactly one separately named retry
% only after its pre-Plant schema-gate failure has been hash-audited.
runsRoot=fullfile(studyRoot,'runs');priorAttemptDir=fullfile(runsRoot,sceneId);
auditPath=fullfile(studyRoot,'audits','FAILED_ATTEMPT_GATE_CORRECTION_v1.json');
assert(isfolder(priorAttemptDir)&&isfile(auditPath)&& ...
    strcmpi(sha256_file(auditPath),char(release.prior_gate_failure_audit_sha256)), ...
    'PositionLPF:RetryAudit','A locked pre-Plant gate-failure audit is required before retry.');
retryAudit=jsondecode(fileread(auditPath));
assert(strcmp(char(retryAudit.status),'VERIFIED_FAILURE_BEFORE_PLANT_DYNAMICS')&& ...
    strcmp(char(retryAudit.scene_id),sceneId)&&retryAudit.physical_Plant_calls==0&& ...
    retryAudit.wrapper_reported_Plant_calls==1&& ...
    strcmp(char(retryAudit.failure_identifier),'CompositeDEV:BudgetClosed')&& ...
    retryAudit.failure_stack_top.line==22&&~retryAudit.raw_run_present, ...
    'PositionLPF:RetryEvidence','Previous entry is not a verified pre-Plant gate rejection.');
priorStatusPath=fullfile(priorAttemptDir,'run_status.json');
priorFailurePath=fullfile(priorAttemptDir,'run_failure.json');
priorStartPath=fullfile(priorAttemptDir,'run_start.json');
priorMarkerPath=fullfile(priorAttemptDir,'attempt_started.marker');
assert(strcmpi(sha256_file(priorStatusPath),char(retryAudit.immutable_evidence_sha256.run_status))&& ...
    strcmpi(sha256_file(priorFailurePath),char(retryAudit.immutable_evidence_sha256.run_failure))&& ...
    strcmpi(sha256_file(priorStartPath),char(retryAudit.immutable_evidence_sha256.run_start))&& ...
    strcmpi(sha256_file(priorMarkerPath),char(retryAudit.immutable_evidence_sha256.marker))&& ...
    ~isfile(fullfile(priorAttemptDir,'raw_run.mat'))&& ...
    ~isfile(fullfile(priorAttemptDir,'first_plant_step.marker')), ...
    'PositionLPF:RetryEvidence','Original failed attempt evidence changed or shows Plant dynamics.');
dependencyAuditPath=fullfile(studyRoot,'audits','FAILED_ATTEMPT_DEPENDENCY_CORRECTION_v1.json');
assert(isfile(dependencyAuditPath)&& ...
    strcmpi(sha256_file(dependencyAuditPath),char(release.prior_dependency_failure_audit_sha256)), ...
    'PositionLPF:RetryAudit','The second pre-Plant dependency failure is not hash-bound.');
dependencyAudit=jsondecode(fileread(dependencyAuditPath));
secondAttemptDir=fullfile(runsRoot,[sceneId '_retry_002']);
secondPaths=struct('marker',fullfile(secondAttemptDir,'attempt_started.marker'), ...
    'run_start',fullfile(secondAttemptDir,'run_start.json'), ...
    'run_status',fullfile(secondAttemptDir,'run_status.json'), ...
    'run_failure',fullfile(secondAttemptDir,'run_failure.json'));
assert(strcmp(char(dependencyAudit.status),'VERIFIED_FAILURE_BEFORE_PLANT_DYNAMICS')&& ...
    strcmp(char(dependencyAudit.scene_id),sceneId)&&dependencyAudit.physical_Plant_calls==0&& ...
    strcmp(char(dependencyAudit.failure_identifier),'MATLAB:fileread:cannotOpenFile')&& ...
    strcmp(char(dependencyAudit.missing_study_root_dependency), ...
    'MLP15_DEV72_PAYLOAD_MANIFEST_v2.json')&&~dependencyAudit.raw_run_present&& ...
    strcmpi(sha256_file(secondPaths.marker),char(dependencyAudit.immutable_evidence_sha256.marker))&& ...
    strcmpi(sha256_file(secondPaths.run_start),char(dependencyAudit.immutable_evidence_sha256.run_start))&& ...
    strcmpi(sha256_file(secondPaths.run_status),char(dependencyAudit.immutable_evidence_sha256.run_status))&& ...
    strcmpi(sha256_file(secondPaths.run_failure),char(dependencyAudit.immutable_evidence_sha256.run_failure))&& ...
    ~isfile(fullfile(secondAttemptDir,'raw_run.mat'))&& ...
    ~isfile(fullfile(secondAttemptDir,'first_plant_step.marker')), ...
    'PositionLPF:RetryEvidence','Second failed attempt changed or shows Plant dynamics.');
identityAuditPath=fullfile(studyRoot,'audits','FAILED_ATTEMPT_IDENTITY_FAILURE_CORRECTION_v1.json');
assert(isfile(identityAuditPath)&& ...
    strcmpi(sha256_file(identityAuditPath),char(release.prior_identity_failure_audit_sha256)), ...
    'PositionLPF:RetryAudit','The third pre-Plant identity failure is not hash-bound.');
identityAudit=jsondecode(fileread(identityAuditPath));
thirdAttemptDir=fullfile(runsRoot,[sceneId '_retry_003']);
thirdMarker=fullfile(thirdAttemptDir,'attempt_started.marker');
thirdEntries=dir(thirdAttemptDir);thirdEntries=thirdEntries(~ismember({thirdEntries.name},{'.','..'}));
assert(strcmp(char(identityAudit.status),'VERIFIED_FAILURE_BEFORE_PLANT_DYNAMICS')&& ...
    strcmp(char(identityAudit.scene_id),sceneId)&&identityAudit.physical_Plant_calls==0&& ...
    strcmp(char(identityAudit.missing_prepared_field),'parent_manifest_sha256')&& ...
    strcmpi(sha256_file(thirdMarker),char(identityAudit.immutable_evidence_sha256.marker))&& ...
    numel(thirdEntries)==1&&strcmp(thirdEntries(1).name,'attempt_started.marker')&& ...
    ~isfile(fullfile(thirdAttemptDir,'raw_run.mat'))&& ...
    ~isfile(fullfile(thirdAttemptDir,'first_plant_step.marker')), ...
    'PositionLPF:RetryEvidence','Third failed attempt changed or shows Plant dynamics.');
exactAuditPath=fullfile(studyRoot,'audits','FAILED_ATTEMPT_EXACT_OPTIONS_FAILURE_CORRECTION_v1.json');
assert(isfile(exactAuditPath)&&strcmpi(sha256_file(exactAuditPath), ...
    char(release.prior_exact_options_failure_audit_sha256)), ...
    'PositionLPF:RetryAudit','The fourth pre-Plant exact-options failure is not hash-bound.');
exactAudit=jsondecode(fileread(exactAuditPath));
fourthAttemptDir=fullfile(runsRoot,[sceneId '_retry_004']);
fourthPaths=struct('marker',fullfile(fourthAttemptDir,'attempt_started.marker'), ...
    'run_start',fullfile(fourthAttemptDir,'run_start.json'), ...
    'run_status',fullfile(fourthAttemptDir,'run_status.json'), ...
    'run_failure',fullfile(fourthAttemptDir,'run_failure.json'));
assert(strcmp(char(exactAudit.status),'VERIFIED_FAILURE_BEFORE_PLANT_DYNAMICS')&& ...
    strcmp(char(exactAudit.scene_id),sceneId)&&exactAudit.physical_Plant_calls==0&& ...
    strcmp(char(exactAudit.failure_identifier),'GATE:ExactOptions')&& ...
    strcmpi(sha256_file(fourthPaths.marker),char(exactAudit.immutable_evidence_sha256.marker))&& ...
    strcmpi(sha256_file(fourthPaths.run_start),char(exactAudit.immutable_evidence_sha256.run_start))&& ...
    strcmpi(sha256_file(fourthPaths.run_status),char(exactAudit.immutable_evidence_sha256.run_status))&& ...
    strcmpi(sha256_file(fourthPaths.run_failure),char(exactAudit.immutable_evidence_sha256.run_failure))&& ...
    ~isfile(fullfile(fourthAttemptDir,'raw_run.mat'))&& ...
    ~isfile(fullfile(fourthAttemptDir,'first_plant_step.marker')), ...
    'PositionLPF:RetryEvidence','Fourth failed attempt changed or shows Plant dynamics.');
markers=dir(fullfile(runsRoot,'**','attempt_started.marker'));
markerPaths=sort(reshape(arrayfun(@(m)fullfile(m.folder,m.name),markers,'UniformOutput',false),1,[]));
expectedMarkers=sort({priorMarkerPath,secondPaths.marker,thirdMarker,fourthPaths.marker});
assert(numel(markers)==4&&isequal(markerPaths,expectedMarkers), ...
    'PositionLPF:RetryBudget','Unexpected attempt markers exist; one clean retry is no longer available.');
attemptDir=fullfile(studyRoot,strrep(char(release.clean_retry_relative_path),'/',filesep));
assert(~isfile(attemptDir)&&~isfolder(attemptDir), ...
    'PositionLPF:DuplicateScene','Refusing to overwrite the clean retry directory.');
assert(double(release.retry_sequence)==5&& ...
    strcmp(char(release.retry_of_relative_path),['runs/' sceneId '_retry_004'])&& ...
    strcmp(char(release.clean_retry_relative_path),['runs/' sceneId '_retry_005']), ...
    'PositionLPF:RetrySequence','Release does not name the clean fifth retry.');
releaseSha=sha256_file(releasePath);startedUtc=utc_now();
runIdentity=build_position_applied_lowpass_run_identity(prepared,release,releaseSha,startedUtc);
if ~isfolder(runsRoot)
    assert(java.io.File(runsRoot).mkdirs(), ...
        'PositionLPF:AttemptCreate','Could not create the runs root.');
end
assert(java.io.File(attemptDir).mkdirs(), ...
    'PositionLPF:AttemptCreate','Could not create the released scene directory.');
write_json(fullfile(attemptDir,'attempt_started.marker'),struct( ...
    'schema','DL1018_POSITION_APPLIED_LOWPASS_ATTEMPT_MARKER_V1','scene_id',sceneId, ...
    'created_utc',startedUtc,'stage','RUNNING','attempt_sequence',5, ...
    'retry_of',char(release.retry_of_relative_path),'release_sha256',releaseSha));
write_json(fullfile(attemptDir,'run_start.json'),runIdentity);
prepared.opts.composite_attempt_marker=fullfile(attemptDir,'attempt_started.marker');
firstStepMarker=fullfile(attemptDir,'first_plant_step.marker');
rawPath=fullfile(attemptDir,'raw_run.mat');runnerEntryInvoked=false;rawSha='';
try
    runnerEntryInvoked=true;
    log=run_mlp15_dev72_closed_loop(prepared.scene,prepared.cfg,prepared.opts);
    assert(isfile(firstStepMarker),'PositionLPF:PlantStepMarker','Runner returned without a first-Plant-step marker.');
    log.position_applied_lowpass_release_sha256=releaseSha;scene=prepared.scene;
    save(rawPath,'log','scene','runIdentity','-v7.3');rawSha=sha256_file(rawPath);
    transitions=double(log.last_transition);stateSamples=size(log.state,1);
    assert(transitions==20000&&stateSamples==20001&&strcmp(char(log.status),'STABLE'), ...
        'PositionLPF:Incomplete','Candidate did not finish a stable 20,000-transition run.');
    write_json(fullfile(attemptDir,'run_status.json'),struct( ...
        'schema','DL1018_POSITION_APPLIED_LOWPASS_RUN_STATUS_V1','state','COMPLETED', ...
        'scene_id',sceneId,'finished_utc',utc_now(),'Plant_calls',1, ...
        'runner_entry_invocations',1,'plant_dynamics_started',true, ...
        'first_plant_step_marker',firstStepMarker,'retry_of',char(release.retry_of_relative_path), ...
        'raw_path',rawPath, ...
        'raw_sha256',rawSha,'transitions',transitions,'state_samples',stateSamples, ...
        'status_value',char(log.status),'safety_stop_reason',char(log.safety_stop_reason), ...
        'release_sha256',releaseSha,'source_lock_sha256',prepared.candidate_source_lock_sha256, ...
        'tau_s',.1,'event_rate_hz',100,'TEST_data_read',false));
    fprintf('POSITION_APPLIED_LOWPASS_ATTEMPT_DIR=%s\n',attemptDir);
catch ME
    write_json(fullfile(attemptDir,'run_status.json'),struct( ...
        'schema','DL1018_POSITION_APPLIED_LOWPASS_RUN_STATUS_V1','state','FAILED', ...
        'scene_id',sceneId,'failed_utc',utc_now(),'Plant_calls',double(isfile(firstStepMarker)), ...
        'runner_entry_invocations',double(runnerEntryInvoked), ...
        'plant_dynamics_started',isfile(firstStepMarker), ...
        'first_plant_step_marker',firstStepMarker,'retry_of',char(release.retry_of_relative_path), ...
        'raw_path',rawPath,'raw_sha256',rawSha,'raw_present',isfile(rawPath), ...
        'error_identifier',char(ME.identifier),'error_message',char(ME.message), ...
        'release_sha256',releaseSha,'source_lock_sha256',prepared.candidate_source_lock_sha256, ...
        'TEST_data_read',false));
    write_json(fullfile(attemptDir,'run_failure.json'),struct('scene_id',sceneId, ...
        'failed_utc',utc_now(),'error_identifier',char(ME.identifier), ...
        'error_message',char(ME.message),'stack',{ME.stack}));
    rethrow(ME);
end
end
function h=sha256_file(path)
fid=fopen(path,'rb');assert(fid>=0,'PositionLPF:Read','Cannot read %s.',path);
cleanup=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear cleanup;
end
function write_json(path,value)
fid=fopen(path,'w','n','UTF-8');assert(fid>=0,'PositionLPF:Write','Cannot write %s.',path);
cleanup=onCleanup(@()fclose(fid));fprintf(fid,'%s\n',jsonencode(value,'PrettyPrint',true));clear cleanup;
end
function value=utc_now()
value=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z'''));
end
