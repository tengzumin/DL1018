function binding=run_position_applied_lowpass_hf6_remaining()
% Run the five remaining fixed HF6 scenes after no-Plant preflight.
studyRoot=fileparts(mfilename('fullpath'));cd(studyRoot);
addpath(fullfile(studyRoot,'audits'),'-begin');
releasePath=fullfile(studyRoot,'RELEASE.json');release=jsondecode(fileread(releasePath));
archivePath=fullfile(studyRoot,char(release.previous_release_archive_path));
releaseSha=sha256_file(releasePath);archiveSha=sha256_file(archivePath);
scenes=reshape(cellstr(string(release.continuation_scene_ids)),1,[]);
allScenes=reshape(cellstr(string(release.authorized_scenes)),1,[]);
expectedAll={'DL1018_VAL_T3_C01_W14','DL1018_DEV_T1_C10_W09', ...
    'DL1018_DEV_T2_C09_W10','DL1018_DEV_T3_C09_W09', ...
    'DL1018_VAL_T1_C07_W14','DL1018_VAL_T2_C04_W14'};
expectedContinuation=expectedAll(2:end);
assert(strcmp(char(release.schema),'DL1018_POSITION_APPLIED_LOWPASS_RELEASE_V1')&& ...
    strcmp(char(release.status),'RELEASED')&&double(release.release_generation)==2&& ...
    double(release.authorized_Plant_calls)==6&&double(release.Plant_calls)==1&& ...
    double(release.remaining_authorized_Plant_calls)==5&&isequal(allScenes(:),expectedAll(:))&& ...
    isequal(scenes(:),expectedContinuation(:))&&strcmpi(archiveSha,char(release.previous_release_archive_sha256))&& ...
    strcmpi(char(release.previous_release_sha256),archiveSha), ...
    'PositionLPF:HF6Release','The generation-2 release does not bind the fixed remaining HF6 cohort.');
assert(strcmpi(sha256_file(fullfile(studyRoot,char(release.source_hash_manifest_path))), ...
    char(release.source_hash_manifest_sha256))&& ...
    strcmpi(sha256_file(fullfile(studyRoot,char(release.source_lock_path))), ...
    char(release.source_lock_sha256)), ...
    'PositionLPF:HF6SourceLock','Source manifest or lock differs from the HF6 release.');
prepare_position_applied_lowpass_no_plant();
parentRoot=char(java.io.File(fullfile(studyRoot,'..','gru_tau01_delayed_start_v1')).getCanonicalPath());
planPath=fullfile(parentRoot,'audits','HF6_CONTINUATION_PLAN_v1.json');
plan=jsondecode(fileread(planPath));
assert(strcmp(char(plan.status),'PREPARED_NO_PLANT_PENDING_START')&& ...
    isequal(sort(reshape(cellstr(string(plan.remaining_scene_ids)),[],1)),sort(scenes(:)))&& ...
    isequal(sort(reshape(cellstr(string(plan.fixed_hf6_scene_ids)),[],1)),sort(allScenes(:))), ...
    'PositionLPF:ParentHF6Binding','Remaining scenes differ from the reviewed fixed HF6 list.');
pilotDir=fullfile(studyRoot,'runs','DL1018_VAL_T3_C01_W14_retry_005');
pilotStart=jsondecode(fileread(fullfile(pilotDir,'run_start.json')));
pilotStatus=jsondecode(fileread(fullfile(pilotDir,'run_status.json')));
pilotRaw=fullfile(pilotDir,'raw_run.mat');
assert(strcmpi(char(pilotStart.release_sha256),archiveSha)&& ...
    strcmpi(char(pilotStatus.release_sha256),archiveSha)&& ...
    strcmp(char(pilotStatus.status_value),'STABLE')&&double(pilotStatus.Plant_calls)==1&& ...
    isfile(fullfile(pilotDir,'first_plant_step.marker'))&& ...
    strcmpi(sha256_file(pilotRaw),char(pilotStatus.raw_sha256)), ...
    'PositionLPF:PilotBinding','The completed pilot is not bound to the archived generation-1 release.');
runsRoot=fullfile(studyRoot,'runs');
targetDirs=cell(size(scenes));
for i=1:numel(scenes)
    targetDirs{i}=fullfile(runsRoot,[scenes{i} '_HF6_LPF_TAU01_G2']);
    if i==1&&isfolder(targetDirs{i})
        failedMarker=fullfile(targetDirs{i},'attempt_started.marker');
        failureAuditPath=fullfile(studyRoot,char(release.hf6_identity_failure_audit_path));
        failureAudit=jsondecode(fileread(failureAuditPath));
        failedEntries=dir(targetDirs{i});failedEntries=failedEntries(~ismember({failedEntries.name},{'.','..'}));
        assert(strcmp(char(failureAudit.status),'VERIFIED_FAILURE_BEFORE_PLANT_DYNAMICS')&& ...
            strcmp(char(failureAudit.scene_id),scenes{i})&&failureAudit.physical_Plant_calls==0&& ...
            strcmpi(sha256_file(failureAuditPath),char(release.hf6_identity_failure_audit_sha256))&& ...
            strcmpi(sha256_file(failedMarker),char(failureAudit.immutable_evidence_sha256.marker))&& ...
            numel(failedEntries)==1&&strcmp(failedEntries(1).name,'attempt_started.marker')&& ...
            ~isfile(fullfile(targetDirs{i},'run_start.json'))&& ...
            ~isfile(fullfile(targetDirs{i},'raw_run.mat'))&& ...
            ~isfile(fullfile(targetDirs{i},'first_plant_step.marker')), ...
            'PositionLPF:HF6PriorIdentityFailure','First-scene marker-only failure changed or is not audited.');
        targetDirs{i}=[targetDirs{i} '_retry_002'];
    end
    assert(~isfolder(targetDirs{i})&&~isfile(targetDirs{i}), ...
        'PositionLPF:HF6Duplicate','Refusing to overwrite an existing HF6 scene directory: %s.',targetDirs{i});
end
firstSteps=dir(fullfile(runsRoot,'**','first_plant_step.marker'));
assert(numel(firstSteps)==1&& ...
    strcmpi(sha256_file(fullfile(firstSteps(1).folder,firstSteps(1).name)), ...
    sha256_file(fullfile(pilotDir,'first_plant_step.marker'))), ...
    'PositionLPF:HF6PriorCalls','Expected exactly one completed Plant call from the preserved pilot.');

% Parent scene/config and candidate option identities are rebuilt before each ordered attempt.
for i=1:numel(scenes)
    currentRelease=jsondecode(fileread(releasePath));
    assert(strcmpi(sha256_file(releasePath),releaseSha)&& ...
        double(currentRelease.Plant_calls)==1&&numel(dir(fullfile(runsRoot, ...
        '**','first_plant_step.marker')))==i, ...
        'PositionLPF:HF6Budget','Release changed or physical call count drifted before %s.',scenes{i});
    p=prepare_candidate_scene(studyRoot,parentRoot,scenes{i});
    runOneScene(studyRoot,p,currentRelease,releaseSha,archiveSha,scenes{i},i+1,targetDirs{i});
    clear p
    fprintf('HF6_LOWPASS_SCENE_COMPLETED=%s\n',scenes{i});
end
firstSteps=dir(fullfile(runsRoot,'**','first_plant_step.marker'));
assert(numel(firstSteps)==6&&strcmpi(sha256_file(releasePath),releaseSha), ...
    'PositionLPF:HF6Complete','Expected six total physical calls with an unchanged generation-2 release.');
binding=make_run_binding(studyRoot,scenes,releaseSha,archiveSha);
write_json(fullfile(studyRoot,'audits','HF6_RUN_BINDING_v1.json'),binding);
fprintf('POSITION_APPLIED_LOWPASS_HF6_COMPLETE Plant_calls=6 release=%s\n',releaseSha);
end

function p=prepare_candidate_scene(studyRoot,parentRoot,sceneId)
oldFolder=pwd;folderCleanup=onCleanup(@()cd(oldFolder));
parentRuntime=fullfile(parentRoot,'candidate_runner_work','matlab','runtime');
cd(parentRoot);addpath(parentRuntime,'-begin');
clear prepare_gru_tau01_delayed_start_no_plant activate_paired_runner
p=prepare_gru_tau01_delayed_start_no_plant(sceneId,false);
cd(studyRoot);clear activate_paired_runner
candidateRuntime=fullfile(studyRoot,'candidate_runner_work','matlab','runtime');
addpath(candidateRuntime,'-begin');resolved=activate_paired_runner();
assert(strcmpi(which('run_mlp15_dev72_closed_loop'), ...
    fullfile(candidateRuntime,'run_mlp15_dev72_closed_loop.m'))&& ...
    strcmpi(char(java.io.File(resolved).getCanonicalPath()), ...
    char(java.io.File(fullfile(studyRoot,'candidate_runner_work')).getCanonicalPath())), ...
    'PositionLPF:HF6RunnerPath','The candidate runner did not resolve from the locked study tree.');
assert(strcmp(char(p.scene.scene_id),sceneId)&& ...
    ~isfield(p.opts.stage1_position_runtime,'applied_acceleration_lowpass_tau_s'), ...
    'PositionLPF:HF6ParentPrepare','Parent scene/options are unexpected or already filtered.');
positionRuntime=p.opts.stage1_position_runtime;positionRuntime.applied_acceleration_lowpass_tau_s=.1;
p.opts.stage1_position_runtime=positionRuntime;
p.opts.gate_identity_lock=gate_holdout_identity_hashes( ...
    p.cfg,p.opts.stage1_position_runtime.model,p.opts);
clear folderCleanup
end

function runOneScene(studyRoot,p,release,releaseSha,archiveSha,sceneId,sequence,attemptDir)
assert(~isfolder(attemptDir)&&~isfile(attemptDir), ...
    'PositionLPF:HF6Duplicate','Refusing to overwrite %s.',attemptDir);
startedUtc=utc_now();markerPath=fullfile(attemptDir,'attempt_started.marker');
attemptSequence=1;retryOf='';
if endsWith(attemptDir,'_retry_002')
    attemptSequence=2;retryOf=['runs/' sceneId '_HF6_LPF_TAU01_G2'];
end
runIdentity=struct('schema','DL1018_POSITION_APPLIED_LOWPASS_HF6_RUN_START_V1', ...
    'scene_id',sceneId,'hf6_scene_sequence',sequence,'attempt_sequence',attemptSequence, ...
    'retry_of',retryOf,'parent_study_id','gru_tau01_delayed_start_v1', ...
    'candidate_study_id',char(release.study_id),'release_generation',2, ...
    'started_utc',startedUtc,'release_sha256',releaseSha, ...
    'pilot_release_archive_sha256',archiveSha, ...
    'source_hash_manifest_sha256',char(release.source_hash_manifest_sha256), ...
    'source_lock_sha256',char(release.source_lock_sha256), ...
    'runtime_dependency_manifest_sha256',char(release.runtime_dependency_manifest_sha256), ...
    'parent_source_lock_sha256',p.source_lock_sha256, ...
    'parent_scene_input_manifest_sha256',p.input_manifest_sha256, ...
    'parent_manifest_sha256',char(release.parent_manifest_sha256), ...
    'parent_c5_snapshot_sha256',p.c5_snapshot_sha256, ...
    'parent_dev72_payload_manifest_sha256',char(release.parent_dev72_payload_manifest_sha256), ...
    'scene_payload_sha256',p.scene_payload_sha256, ...
    'external_identity_sha256',p.external_identity_sha256, ...
    'b_raw_sha256',p.b_raw_sha256,'c5_input_lock_sha256',p.c5_input_lock_sha256, ...
    'position_model_sha256',p.position_model_sha256,'gru_model_sha256',p.gru_model_sha256, ...
    'position_method_id','C5_AXIS_MIXED_COORDINATE_M110', ...
    'position_delayed_prediction_h_s',.01,'position_delayed_prediction_rho_schedule',p.rho_schedule, ...
    'applied_acceleration_lowpass_tau_s',.1,'applied_acceleration_lowpass_event_rate_hz',100, ...
    'applied_acceleration_lowpass_initial_state_mps2',[0;0;0], ...
    'applied_acceleration_lowpass_event_dt_source','actual rbfFullDt', ...
    'position_force_and_pcf_use_same_filtered_output',true, ...
    'command_filter_wn_rad_s',[18;18;12],'Plant_calls_before_scene',sequence-1, ...
    'inertia_reconstruction_enabled',false,'TEST_data_read',false, ...
    'closed_loop_entry','run_mlp15_dev72_closed_loop(scene,cfg,opts)');
assert(java.io.File(attemptDir).mkdirs(),'PositionLPF:HF6AttemptCreate', ...
    'Could not create %s.',attemptDir);
write_json(markerPath,struct('schema','DL1018_POSITION_APPLIED_LOWPASS_HF6_ATTEMPT_MARKER_V1', ...
    'scene_id',sceneId,'created_utc',startedUtc,'stage','RUNNING', ...
    'attempt_sequence',attemptSequence,'retry_of',retryOf, ...
    'hf6_scene_sequence',sequence,'release_generation',2,'release_sha256',releaseSha, ...
    'pilot_release_archive_sha256',archiveSha));
write_json(fullfile(attemptDir,'run_start.json'),runIdentity);
p.opts.composite_attempt_marker=markerPath;
firstStepMarker=fullfile(attemptDir,'first_plant_step.marker');
rawPath=fullfile(attemptDir,'raw_run.mat');rawSha='';runnerInvoked=false;
try
    runnerInvoked=true;log=run_mlp15_dev72_closed_loop(p.scene,p.cfg,p.opts);
    assert(isfile(firstStepMarker),'PositionLPF:HF6PlantMarker', ...
        'Runner returned without a first dynamics marker.');
    log.position_applied_lowpass_release_sha256=releaseSha;
    log.position_applied_lowpass_pilot_release_archive_sha256=archiveSha;
    scene=p.scene;save(rawPath,'log','scene','runIdentity','-v7.3');rawSha=sha256_file(rawPath);
    transitions=double(log.last_transition);stateSamples=size(log.state,1);
    assert(transitions==20000&&stateSamples==20001&&strcmp(char(log.status),'STABLE'), ...
        'PositionLPF:HF6Incomplete','Scene did not finish a stable 20,000-transition run.');
    write_json(fullfile(attemptDir,'run_status.json'),struct( ...
        'schema','DL1018_POSITION_APPLIED_LOWPASS_HF6_RUN_STATUS_V1','state','COMPLETED', ...
        'scene_id',sceneId,'hf6_scene_sequence',sequence,'finished_utc',utc_now(), ...
        'Plant_calls',1,'runner_entry_invocations',1,'plant_dynamics_started',true, ...
        'first_plant_step_marker',firstStepMarker,'raw_path',rawPath,'raw_sha256',rawSha, ...
        'transitions',transitions,'state_samples',stateSamples,'status_value',char(log.status), ...
        'safety_stop_reason',char(log.safety_stop_reason),'release_sha256',releaseSha, ...
        'pilot_release_archive_sha256',archiveSha,'source_lock_sha256',char(release.source_lock_sha256), ...
        'tau_s',.1,'event_rate_hz',100,'TEST_data_read',false));
catch ME
    write_json(fullfile(attemptDir,'run_status.json'),struct( ...
        'schema','DL1018_POSITION_APPLIED_LOWPASS_HF6_RUN_STATUS_V1','state','FAILED', ...
        'scene_id',sceneId,'hf6_scene_sequence',sequence,'failed_utc',utc_now(), ...
        'Plant_calls',double(isfile(firstStepMarker)), ...
        'runner_entry_invocations',double(runnerInvoked), ...
        'plant_dynamics_started',isfile(firstStepMarker),'first_plant_step_marker',firstStepMarker, ...
        'raw_path',rawPath,'raw_sha256',rawSha,'raw_present',isfile(rawPath), ...
        'release_sha256',releaseSha,'pilot_release_archive_sha256',archiveSha, ...
        'source_lock_sha256',char(release.source_lock_sha256), ...
        'error_identifier',char(ME.identifier),'error_message',char(ME.message), ...
        'TEST_data_read',false));
    write_json(fullfile(attemptDir,'run_failure.json'),struct('scene_id',sceneId, ...
        'failed_utc',utc_now(),'error_identifier',char(ME.identifier), ...
        'error_message',char(ME.message),'stack',{ME.stack}));
    rethrow(ME);
end
end

function binding=make_run_binding(studyRoot,scenes,releaseSha,archiveSha)
pilotDir=fullfile(studyRoot,'runs','DL1018_VAL_T3_C01_W14_retry_005');
pilot=jsondecode(fileread(fullfile(pilotDir,'run_status.json')));
pilotStart=jsondecode(fileread(fullfile(pilotDir,'run_start.json')));
runs=repmat(struct('scene_id','','state','','status_value','','Plant_calls',0, ...
    'run_start_path','','run_start_sha256','','run_status_path','','run_status_sha256','', ...
    'raw_path','','raw_sha256','','release_sha256','','source_lock_sha256','', ...
    'TEST_data_read',false,'inertia_reconstruction_enabled',false),1,numel(scenes));
for i=1:numel(scenes)
    d=fullfile(studyRoot,'runs',[scenes{i} '_HF6_LPF_TAU01_G2']);
    if ~isfile(fullfile(d,'raw_run.mat'))&& ...
            isfile(fullfile([d '_retry_002'],'raw_run.mat'))
        d=[d '_retry_002'];
    end
    startPath=fullfile(d,'run_start.json');statusPath=fullfile(d,'run_status.json');
    status=jsondecode(fileread(statusPath));start=jsondecode(fileread(startPath));
    runs(i)=struct('scene_id',scenes{i},'state',char(status.state), ...
        'status_value',char(status.status_value),'Plant_calls',double(status.Plant_calls), ...
        'run_start_path',startPath,'run_start_sha256',sha256_file(startPath), ...
        'run_status_path',statusPath,'run_status_sha256',sha256_file(statusPath), ...
        'raw_path',char(status.raw_path),'raw_sha256',char(status.raw_sha256), ...
        'release_sha256',char(start.release_sha256), ...
        'source_lock_sha256',char(status.source_lock_sha256), ...
        'TEST_data_read',logical(status.TEST_data_read), ...
        'inertia_reconstruction_enabled',logical(start.inertia_reconstruction_enabled));
end
binding=struct('schema','DL1018_POSITION_APPLIED_LOWPASS_HF6_RUN_BINDING_V1', ...
    'status','COMPLETE_HF6_POSITION_LOWPASS_SCREEN','scope', ...
    'Fixed six-scene DEV/VAL development screen; not independent validation.', ...
    'release_chain',struct('generation',{1,2},'release_sha256',{archiveSha,releaseSha}, ...
    'scenes',{{'DL1018_VAL_T3_C01_W14'},scenes}), ...
    'prior_completed_scene',struct('scene_id',char(pilot.scene_id), ...
    'state',char(pilot.state),'Plant_calls',double(pilot.Plant_calls), ...
    'run_start_sha256',sha256_file(fullfile(pilotDir,'run_start.json')), ...
    'run_status_sha256',sha256_file(fullfile(pilotDir,'run_status.json')), ...
    'raw_sha256',char(pilot.raw_sha256),'release_sha256',char(pilotStart.release_sha256)), ...
    'remaining_scene_ids',{scenes},'scene_runs',runs, ...
    'source_lock_sha256',char(jsondecode(fileread(fullfile(studyRoot,'RELEASE.json'))).source_lock_sha256), ...
    'scene_count',6,'Plant_calls',6,'TEST_data_read',false,'inertia_reconstruction_enabled',false);
end

function h=sha256_file(path)
fid=fopen(path,'rb');assert(fid>=0,'PositionLPF:Read','Cannot read %s.',path);
cleanup=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear cleanup;
end
function write_json(path,value)
fid=fopen(path,'w','n','UTF-8');assert(fid>=0,'PositionLPF:Write','Cannot write %s.',path);
cleanup=onCleanup(@()fclose(fid));fprintf(fid,'%s\n',jsonencode(value,'PrettyPrint',true));clear cleanup;
end
function value=utc_now()
value=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z'''));
end
