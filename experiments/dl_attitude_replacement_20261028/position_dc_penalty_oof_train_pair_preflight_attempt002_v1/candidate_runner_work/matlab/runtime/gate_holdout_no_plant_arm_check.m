function report=gate_holdout_no_plant_arm_check()
% Check the frozen RBF baseline and no-inertia DL_MLP15 replacement without Plant.
ids={'C5_RBF','DL_MLP15'};
specs=cellfun(@gate_attitude_arm_spec,ids,'UniformOutput',false);
rbf=cellfun(@(s)s.rbf_enabled,specs);
helper=cellfun(@(s)s.physics_helper_enabled,specs);
F=cellfun(@(s)s.feedforward_enabled,specs);
O=cellfun(@(s)s.observer_enabled,specs);
assert(isequal(rbf,[true false])&&isequal(helper,[false false])&& ...
    isequal(F,[false false])&&isequal(O,[false false])&& ...
    strcmp(specs{1}.paired_arm,'baseline')&&strcmp(specs{2}.paired_arm,'candidate'), ...
    'GATE:ArmMap','Registered attitude arm mapping changed.');
report=struct('arm_ids',{ids},'paired_roles',{{'baseline','candidate'}}, ...
    'rbf_enabled',rbf,'inertia_reconstruction_enabled',helper, ...
    'feedforward_enabled',F,'observer_enabled',O,'plant_invoked',false, ...
    'mlp15_runtime_inputs',13,'mlp15_window_events',15,'mlp15_uses_fixed_J0',true);
end
