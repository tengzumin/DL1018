function attemptDir=run_gru_yaw_consistent_attempt(sceneId)
% Root-controlled single-call entry; release remains PREPARED until authorized.
studyRoot=fileparts(mfilename('fullpath'));cd(studyRoot);addpath(studyRoot,'-begin');
sceneId=char(string(sceneId));release=jsondecode(fileread(fullfile(studyRoot,'RELEASE.json')));
assert(strcmp(char(release.schema),'DL1018_GRU_STREAM_DEV_RELEASE_V1')&& ...
    strcmp(char(release.variant_schema),'DL1018_GRU_YAW_CONSISTENT_RELEASE_V1')&& ...
    strcmp(char(release.study_id),'gru_yaw_consistent_v1')&& ...
    strcmp(char(release.candidate_arm_id), ...
    'GRU32_STREAM72_COSINE_TRACKING_HEAD_YAWCONSISTENT_S2026102001')&& ...
    strcmp(char(release.status),'RELEASED')&&double(release.authorized_Plant_calls)==1&& ...
    any(strcmp(cellstr(string(release.authorized_scenes)),sceneId)), ...
    'GRUYaw:BudgetClosed','Yaw-consistent GRU Plant release is pending or scene is not authorized.');
assert(isscalar(regexp(sceneId,'^DL1018_(DEV|VAL)_T[1-3]_C\d{2}_W\d{2}$','once')), ...
    'GRUYaw:SceneID','Only fixed DEV/VAL scene IDs are accepted.');
prepared=prepare_gru_yaw_consistent_no_plant(sceneId,false);
manifest=jsondecode(fileread(fullfile(studyRoot,'SCENE_INPUT_MANIFEST_v1.json')));
hit=find(strcmp({manifest.records.scene_id},sceneId));assert(isscalar(hit), ...
    'GRUYaw:Scene','Scene is not unique in the frozen input manifest.');record=manifest.records(hit);
runsRoot=fullfile(studyRoot,'runs');attemptDir=fullfile(runsRoot,sceneId);
assert(~isfolder(attemptDir)&&~isfile(attemptDir), ...
    'GRUYaw:DuplicateScene','Refusing to overwrite a same-scene attempt.');
markers=dir(fullfile(runsRoot,'**','attempt_started.marker'));
assert(numel(markers)<1,'GRUYaw:CallBudget','The single authorized Plant call has been used.');
assert(java.io.File(attemptDir).mkdir(),'GRUYaw:AttemptCreate','Cannot create scene attempt directory.');
releaseSha=sha256_file(fullfile(studyRoot,'RELEASE.json'));startedUtc=utc_now();
write_json(fullfile(attemptDir,'attempt_started.marker'),struct( ...
    'schema','DL1018_GRU_YAW_CONSISTENT_ATTEMPT_MARKER_V1','scene_id',sceneId, ...
    'created_utc',startedUtc,'stage','RUNNING','release_sha256',releaseSha));
runIdentity=struct('schema','DL1018_GRU_YAW_CONSISTENT_RUN_START_V1', ...
    'scene_id',sceneId,'source_split',char(record.source_split), ...
    'candidate','GRU32_STREAM72_COSINE_TRACKING_HEAD_YAWCONSISTENT_S2026102001', ...
    'parent_candidate','GRU32_STREAM72_COSINE_TRACKING_HEAD_S2026102001', ...
    'attitude_arm','GRU_STREAM','geometry_arm','ACTIVE','started_utc',startedUtc, ...
    'release_sha256',releaseSha,'source_lock_sha256',prepared.source_lock_sha256, ...
    'source_hash_manifest_sha256',prepared.source_hash_manifest_sha256, ...
    'scene_input_manifest_sha256',prepared.input_manifest_sha256, ...
    'parent_manifest_sha256',char(release.parent_manifest_sha256), ...
    'scene_payload_sha256',prepared.scene_payload_sha256, ...
    'external_identity_sha256',prepared.external_identity_sha256, ...
    'b_raw_sha256',prepared.b_raw_sha256,'c5_raw_sha256',char(record.c5_raw_sha256), ...
    'c5_input_lock_sha256',prepared.c5_input_lock_sha256, ...
    'c5_snapshot_sha256',prepared.c5_snapshot_sha256, ...
    'position_model_sha256',prepared.position_model_sha256, ...
    'gru_model_sha256',prepared.gru_model_sha256, ...
    'common_position_options_sha256',prepared.identity.common.position_options_sha256, ...
    'command_filter_wn_rad_s',[18;18;12], ...
    'position_method_id','C5_AXIS_MIXED_COORDINATE_M110', ...
    'position_nn_compensation_scale',1, ...
    'active_control_change','force-to-attitude roll/pitch solve uses desired r.euler(3) yaw', ...
    'tracking_runtime','gru_stream_tracking_head_step_v1', ...
    'base_model_weights_fixed',true,'tracking_delta_weights_online',true, ...
    'inertia_reconstruction_enabled',false,'Plant_truth_deployment_input',false, ...
    'test_data_read',false,'closed_loop_entry','run_mlp15_dev72_closed_loop(scene,cfg,opts)');
write_json(fullfile(attemptDir,'run_start.json'),runIdentity);
prepared.opts.composite_attempt_marker=fullfile(attemptDir,'attempt_started.marker');
rawPath=fullfile(attemptDir,'raw_run.mat');rawSha='';plantCallStarted=false;
try
    plantCallStarted=true;
    log=run_mlp15_dev72_closed_loop(prepared.scene,prepared.cfg,prepared.opts);
    log.gru_yaw_consistent_release_sha256=releaseSha;scene=prepared.scene;
    save(rawPath,'log','scene','runIdentity','-v7.3');rawSha=sha256_file(rawPath);
    transitions=double(log.last_transition);stateSamples=size(log.state,1);
    assert(transitions==20000&&stateSamples==20001&&strcmp(char(log.status),'STABLE'), ...
        'GRUYaw:Incomplete','Candidate did not finish a stable 20,000-transition run.');
    write_json(fullfile(attemptDir,'run_status.json'),struct( ...
        'schema','DL1018_GRU_YAW_CONSISTENT_RUN_STATUS_V1','state','COMPLETED', ...
        'scene_id',sceneId,'finished_utc',utc_now(),'Plant_calls',1, ...
        'raw_path',rawPath,'raw_sha256',rawSha,'transitions',transitions, ...
        'state_samples',stateSamples,'status_value',char(log.status), ...
        'safety_stop_reason',char(log.safety_stop_reason), ...
        'gru_model_sha256',prepared.gru_model_sha256,'test_data_read',false));
catch ME
    write_json(fullfile(attemptDir,'run_status.json'),struct( ...
        'schema','DL1018_GRU_YAW_CONSISTENT_RUN_STATUS_V1','state','FAILED', ...
        'scene_id',sceneId,'failed_utc',utc_now(),'Plant_calls',double(plantCallStarted), ...
        'raw_path',rawPath,'raw_sha256',rawSha,'raw_present',isfile(rawPath), ...
        'error_identifier',char(ME.identifier),'error_message',char(ME.message), ...
        'gru_model_sha256',prepared.gru_model_sha256,'test_data_read',false));
    write_json(fullfile(attemptDir,'run_failure.json'),struct('scene_id',sceneId, ...
        'failed_utc',utc_now(),'error_identifier',char(ME.identifier), ...
        'error_message',char(ME.message),'stack',{ME.stack}));
    rethrow(ME);
end
end
function h=sha256_file(path)
fid=fopen(path,'rb');assert(fid>=0,'GRUYaw:Read','Cannot read %s.',path);
cleanup=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear cleanup;
end
function write_json(path,value)
fid=fopen(path,'w','n','UTF-8');assert(fid>=0,'GRUYaw:Write','Cannot write %s.',path);
cleanup=onCleanup(@()fclose(fid));fprintf(fid,'%s\n',jsonencode(value,'PrettyPrint',true));clear cleanup;
end
function value=utc_now()
value=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z'''));
end
