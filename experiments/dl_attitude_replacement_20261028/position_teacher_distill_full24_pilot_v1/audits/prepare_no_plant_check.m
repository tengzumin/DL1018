function report=prepare_no_plant_check()
% Validate the frozen single-scene candidate and stop exactly before the Plant loop.
here=fileparts(mfilename('fullpath'));studyRoot=fileparts(here);projectRoot=fileparts(fileparts(fileparts(studyRoot)));
releasePath=fullfile(studyRoot,'RELEASE.json');lockPath=fullfile(studyRoot,'SOURCE_LOCK_v1.json');
release=jsondecode(fileread(releasePath));lock=jsondecode(fileread(lockPath));
assert(strcmp(char(release.schema),'DL1018_POSITION_C5_RESIDUAL_GRU_NOPLANT_V1')&& ...
    strcmp(char(release.study_id),'position_teacher_distill_full24_pilot_v1')&& ...
    strcmp(char(release.status),'PREPARED_NO_PLANT_PENDING_ROOT_AUDIT')&& ...
    double(release.authorized_Plant_calls)==0&&double(release.Plant_calls)==0&& ...
    ~logical(release.TEST_read)&&~logical(release.inertia_reconstruction_enabled), ...
    'PositionTeacherPilot:Release','No-Plant release/status/budget check failed.');
assert(strcmpi(sha256_file(lockPath),char(release.source_lock_sha256))&& ...
    numel(lock.files)==double(lock.file_count)&&double(release.source_file_count)==double(lock.file_count), ...
    'PositionTeacherPilot:Lock','Source lock SHA or count mismatch.');
for i=1:numel(lock.files)
    rec=lock.files(i);path=fullfile(studyRoot,strrep(char(rec.relative_path),'/',filesep));
    assert(isfile(path)&&strcmpi(sha256_file(path),char(rec.sha256)), ...
        'PositionTeacherPilot:SourceSHA','Locked source changed: %s.',path);
end
for i=1:numel(lock.external_inputs)
    rec=lock.external_inputs(i);path=char(rec.path);
    assert(isfile(path)&&strcmpi(sha256_file(path),char(rec.sha256)), ...
        'PositionTeacherPilot:ExternalSHA','Bound TRAIN/teacher/parent input changed: %s.',path);
end
parentTauPath=char(release.parent_tau01_release_path);parentCosPath=char(release.parent_cosine_release_path);
assert(strcmpi(sha256_file(parentTauPath),char(release.parent_tau01_release_sha256))&& ...
    strcmpi(sha256_file(parentCosPath),char(release.parent_cosine_release_sha256)), ...
    'PositionTeacherPilot:ParentSHA','Parent release identity changed.');
weightsPath=fullfile(studyRoot,strrep(char(release.position_residual_gru.weights_relative_path),'/',filesep));
assert(strcmpi(sha256_file(weightsPath),char(release.position_residual_gru.weights_sha256)), ...
    'PositionTeacherPilot:WeightsSHA','Runtime weights differ from the frozen release.');
payloadManifestPath=fullfile(studyRoot,'MLP15_DEV72_PAYLOAD_MANIFEST_v2.json');
assert(strcmpi(sha256_file(payloadManifestPath),char(release.payload_manifest_sha256)), ...
    'PositionTeacherPilot:PayloadManifest','Copied DEV/VAL payload manifest differs from release.');
sceneId=char(release.fixed_scene_id);
assert(strcmp(sceneId,'DL1018_VAL_T3_C01_W14')&&any(strcmp(cellstr(string(release.authorized_scenes)),sceneId)), ...
    'PositionTeacherPilot:Scene','Pilot scene identity is not the fixed reviewed scene.');

% Run offline TRAIN24 eventwise parity before preparing the fixed scene.
parity=check_matlab_eventwise_parity_v1();
assert(strcmp(parity.status,'PASS_TRAIN24_EVENTWISE_PARITY')&& ...
    logical(parity.plant_called)==false,'PositionTeacherPilot:Parity','MATLAB/Python parity failed.');

% Reuse the reviewed parent tau01 preparer, then isolate all future resolution to our copy.
parentTauStudy=fileparts(parentTauPath);parentRuntime=fullfile(parentTauStudy,'candidate_runner_work','matlab','runtime');
addpath(parentRuntime,'-begin');oldDir=pwd;restore=onCleanup(@()cd(oldDir));
cd(parentTauStudy);prepared=prepare_gru_prediction_tau01_no_plant(sceneId,false);
cd(studyRoot);clear restore;
ownRuntime=fullfile(studyRoot,'candidate_runner_work','matlab','runtime');addpath(ownRuntime,'-begin');
candidateRoot=activate_paired_runner();
assert(strcmpi(char(java.io.File(candidateRoot).getCanonicalPath()), ...
    char(java.io.File(fullfile(studyRoot,'candidate_runner_work')).getCanonicalPath())), ...
    'PositionTeacherPilot:RunnerRoot','Runner did not resolve from the isolated candidate copy.');
mat=load(weightsPath);
runtime=prepared.opts.stage1_position_runtime;
runtime.residual_gru=struct('enabled',true,'weights_sha256',char(release.position_residual_gru.weights_sha256), ...
    'input_mean',double(mat.input_mean(:)),'input_std',double(mat.input_std(:)), ...
    'gru_weight_ih_l0',double(mat.gru_weight_ih_l0),'gru_weight_hh_l0',double(mat.gru_weight_hh_l0), ...
    'gru_bias_ih_l0',double(mat.gru_bias_ih_l0(:)),'gru_bias_hh_l0',double(mat.gru_bias_hh_l0(:)), ...
    'head_weight',double(mat.head_weight),'head_bias',double(mat.head_bias(:)), ...
    'beta_rise_time_s',1.8,'delta_limit_mps2',0.5,'action_limit_mps2',3.0);
assert(~isfield(runtime,'applied_acceleration_notch')|| ...
    ~logical(field_or(runtime.applied_acceleration_notch,'enabled',false)), ...
    'PositionTeacherPilot:Notch','Unexpected notch must remain disabled.');
opts=prepared.opts;opts.stage1_position_runtime=runtime;opts.no_plant_boundary_check=true;
markerPath=fullfile(here,['NO_PLANT_ATTEMPT_' datestr(now,'yyyymmddTHHMMSSFFF') '.json']);
marker=struct('scene_id',sceneId,'stage','RUNNING','created_utc',char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z''')));
write_json(markerPath,marker);opts.composite_attempt_marker=markerPath;
identityOpts=rmfield(opts,'composite_attempt_marker');
opts.gate_identity_lock=gate_holdout_identity_hashes(prepared.cfg,prepared.position_model,identityOpts);
expectedId='PositionNotch:NoPlantPreflightStop';caught='';
try
    run_mlp15_dev72_closed_loop(prepared.scene,prepared.cfg,opts);
catch ME
    caught=ME.identifier;
    if ~strcmp(caught,expectedId),rethrow(ME);end
end
assert(strcmp(caught,expectedId),'PositionTeacherPilot:Boundary','Expected pre-Plant boundary stop did not occur.');
marker.stage='STOPPED_BEFORE_PLANT';write_json(markerPath,marker);
assert(~isfile(fullfile(fileparts(markerPath),'first_plant_step.marker'))&& ...
    ~isfolder(fullfile(studyRoot,'runs')),'PositionTeacherPilot:PlantMarker', ...
    'A Plant-step marker or run output unexpectedly exists.');

report=struct('schema','POSITION_TEACHER_DISTILL_FULL24_NO_PLANT_PREPARE_V1', ...
    'status','PASS_STOPPED_BEFORE_PLANT','study_id',char(release.study_id),'scene_id',sceneId, ...
    'scene_payload_sha256',prepared.scene_payload_sha256, ...
    'parent_tau01_release_sha256',char(release.parent_tau01_release_sha256), ...
    'parent_cosine_release_sha256',char(release.parent_cosine_release_sha256), ...
    'source_lock_sha256',char(release.source_lock_sha256),'release_sha256',sha256_file(releasePath), ...
    'weights_sha256',char(release.position_residual_gru.weights_sha256), ...
    'resolved_runner_root',candidateRoot,'resolved_runner_entry',which('run_mlp15_dev72_closed_loop'), ...
    'no_plant_boundary_error',caught,'plant_called',false,'Plant_calls',0, ...
    'authorized_Plant_calls',0,'test_data_read',false,'inertia_reconstruction_enabled',false, ...
    'controller_arm','GRU_STREAM','geometry_arm','ACTIVE','position_method_id','C5_AXIS_MIXED_COORDINATE_M110', ...
    'position_delayed_prediction_h_s',0.01,'position_delayed_prediction_tau_s',0.1, ...
    'position_delayed_prediction_rho',0.1,'notch_enabled',false, ...
    'model_input','causal X14 only','C5_base_action','causal final applied C5 acceleration', ...
    'hidden_reset_per_scene',true,'hidden_updated_during_warmup',true, ...
    'first_event_time_s',0.01,'first_ready_event_index_zero_based',31, ...
    'first_ready_event_time_s',0.32,'warmup_delta_and_action_exactly_zero',true, ...
    'beta_formula','clip(event_time_s/1.8,0,1)','delta_clip_mps2',0.5,'total_action_clip_mps2',3.0, ...
    'runtime_event_loop_executed',false,'eventwise_parity_result',parity);
write_json(fullfile(studyRoot,'NO_PLANT_PREPARE_RESULT_v1.json'),report);
end

function value=field_or(s,name,default)
if isstruct(s)&&isfield(s,name),value=s.(name);else,value=default;end
end
function h=sha256_file(path)
fid=fopen(path,'rb');assert(fid>=0,'PositionTeacherPilot:Read','Cannot read %s.',path);
cleanup=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear cleanup;
end
function write_json(path,value)
fid=fopen(path,'w','n','UTF-8');assert(fid>=0);cleanup=onCleanup(@()fclose(fid));
fprintf(fid,'%s\n',jsonencode(value,'PrettyPrint',true));clear cleanup;
end
