function attemptDir=run_position_residual_gru_single_attempt()
% Run only after root changes the frozen single-scene release to RELEASED.
studyRoot=fileparts(mfilename('fullpath'));releasePath=fullfile(studyRoot,'RELEASE.json');
release=jsondecode(fileread(releasePath));sceneId=char(release.fixed_scene_id);
assert(strcmp(char(release.status),'RELEASED')&& ...
    double(release.authorized_Plant_calls)==1&&double(release.Plant_calls)==1&& ...
    strcmp(sceneId,'DL1018_VAL_T3_C01_W14')&& ...
    strcmp(char(release.schema),'DL1018_POSITION_C5_RESIDUAL_GRU_NOPLANT_V1'), ...
    'PositionResidualGRU:PlantAuthorization','The single-scene Plant release has not been approved.');
sourceLockPath=fullfile(studyRoot,'SOURCE_LOCK_v1.json');sourceLock=jsondecode(fileread(sourceLockPath));
assert(strcmpi(sha256_file(sourceLockPath),char(release.source_lock_sha256)), ...
    'PositionResidualGRU:SourceLock','Source lock changed after review.');
for i=1:numel(sourceLock.files)
    rec=sourceLock.files(i);path=fullfile(studyRoot,strrep(char(rec.path),'/',filesep));
    assert(isfile(path)&&strcmpi(sha256_file(path),char(rec.sha256)), ...
        'PositionResidualGRU:SourceHash','Isolated source changed: %s.',path);
end
weightsPath=fullfile(studyRoot,'candidate_runner_work','matlab','models', ...
    'position_residual_gru_full_train24.mat');
assert(strcmpi(sha256_file(weightsPath),char(release.position_residual_gru.weights_sha256)), ...
    'PositionResidualGRU:WeightsHash','Frozen residual model weights changed.');

projectRoot=fileparts(fileparts(fileparts(studyRoot)));
parentRoot=fullfile(projectRoot,'experiments','dl_attitude_replacement_20261028','gru_prediction_tau01_v1');
assert(strcmpi(sha256_file(fullfile(parentRoot,'RELEASE.json')), ...
    char(release.parent_tau01_release_sha256))&& ...
    strcmpi(sha256_file(char(release.parent_cosine_release_path)), ...
    char(release.parent_cosine_release_sha256))&& ...
    strcmpi(sha256_file(char(release.parent_tau1_helper_path)), ...
    char(release.parent_tau1_helper_sha256)), ...
    'PositionResidualGRU:ParentRelease','Parent C5/cosine release or helper changed.');
oldFolder=pwd;restoreFolder=onCleanup(@()cd(oldFolder));
cd(parentRoot);addpath(fullfile(parentRoot,'candidate_runner_work','matlab','runtime'),'-begin');
clear activate_paired_runner prepare_gru_prediction_tau01_no_plant;
prepared=prepare_gru_prediction_tau01_no_plant(sceneId,false);
cd(studyRoot);restoredefaultpath;rehash toolboxcache;
addpath(fullfile(studyRoot,'candidate_runner_work','matlab','runtime'),'-begin');
clear activate_paired_runner;runnerRoot=activate_paired_runner();
candidateRuntime=fullfile(runnerRoot,'matlab','runtime');
assert(strcmpi(which('run_mlp15_dev72_closed_loop'), ...
    fullfile(candidateRuntime,'run_mlp15_dev72_closed_loop.m'))&& ...
    strcmp(sceneId,char(prepared.scene.scene_id)), ...
    'PositionResidualGRU:RunnerBinding','Runner path or fixed scene binding changed.');
if isfield(prepared.opts.stage1_position_runtime,'applied_acceleration_notch')
    prepared.opts.stage1_position_runtime=rmfield( ...
        prepared.opts.stage1_position_runtime,'applied_acceleration_notch');
end
m=load(weightsPath);
prepared.opts.stage1_position_runtime.residual_gru=struct( ...
    'enabled',true,'weights_sha256',char(release.position_residual_gru.weights_sha256), ...
    'input_mean',double(m.input_mean(:)),'input_std',double(m.input_std(:)), ...
    'gru_weight_ih_l0',double(m.gru_weight_ih_l0),'gru_weight_hh_l0',double(m.gru_weight_hh_l0), ...
    'gru_bias_ih_l0',double(m.gru_bias_ih_l0(:)),'gru_bias_hh_l0',double(m.gru_bias_hh_l0(:)), ...
    'head_weight',double(m.head_weight),'head_bias',double(m.head_bias(:)), ...
    'beta_rise_time_s',1.8,'delta_limit_mps2',.5,'action_limit_mps2',3, ...
    'smooth_lambda',.01,'seed',20261028,'optimizer_steps',300);
prepared.opts.no_plant_boundary_check=false;
attemptDir=fullfile(studyRoot,'runs',sceneId);
assert(~isfolder(attemptDir),'PositionResidualGRU:DuplicateScene','Refusing to overwrite a prior scene attempt.');
assert(java.io.File(attemptDir).mkdirs(),'PositionResidualGRU:AttemptCreate','Could not create attempt directory.');
startedUtc=utc_now();releaseSha=sha256_file(releasePath);
markerPath=fullfile(attemptDir,'attempt_started.marker');
write_json(markerPath,struct('schema','POSITION_C5_RESIDUAL_GRU_ATTEMPT_V1', ...
    'scene_id',sceneId,'created_utc',startedUtc,'stage','RUNNING','release_sha256',releaseSha));
prepared.opts.composite_attempt_marker=markerPath;
identityOpts=rmfield(prepared.opts,'composite_attempt_marker');
prepared.opts.gate_identity_lock=gate_holdout_identity_hashes( ...
    prepared.cfg,prepared.opts.stage1_position_runtime.model,identityOpts);
runIdentity=struct('schema','POSITION_C5_RESIDUAL_GRU_SINGLE_PILOT_IDENTITY_V1', ...
    'scene_id',sceneId,'started_utc',startedUtc,'release_sha256',releaseSha, ...
    'source_lock_sha256',sha256_file(sourceLockPath), ...
    'parent_tau01_release_sha256',char(release.parent_tau01_release_sha256), ...
    'scene_payload_path',prepared.scene_payload_path,'scene_payload_sha256',prepared.scene_payload_sha256, ...
    'external_identity_sha256',prepared.external_identity_sha256,'b_raw_path',prepared.b_raw_path, ...
    'b_raw_sha256',prepared.b_raw_sha256,'c5_input_lock_sha256',prepared.c5_input_lock_sha256, ...
    'c5_snapshot_sha256',prepared.c5_snapshot_sha256,'position_model_sha256',prepared.position_model_sha256, ...
    'attitude_gru_model_sha256',prepared.gru_model_sha256, ...
    'residual_gru_weights_sha256',sha256_file(weightsPath), ...
    'position_method_id','C5_AXIS_MIXED_COORDINATE_M110', ...
    'position_delayed_prediction_tau_s',1,'position_delayed_prediction_rho',.01, ...
    'residual_gru_lambda',.01,'residual_gru_beta_rise_time_s',1.8, ...
    'residual_gru_delta_limit_mps2',.5,'residual_gru_action_limit_mps2',3, ...
    'residual_gru_event_rate_hz',100,'residual_gru_first_event_time_s',.01, ...
    'residual_gru_first_ready_event_index_zero_based',31, ...
    'residual_gru_first_ready_event_time_s',.32,'notch_enabled',false, ...
    'gate_identity_lock',prepared.opts.gate_identity_lock,'controller_arm','GRU_STREAM', ...
    'geometry_arm','ACTIVE','Plant_calls_authorized_for_attempt',1, ...
    'inertia_reconstruction_enabled',false,'TEST_read',false);
write_json(fullfile(attemptDir,'run_start.json'),runIdentity);
rawPath=fullfile(attemptDir,'raw_run.mat');firstStepMarker=fullfile(attemptDir,'first_plant_step.marker');
try
    log=run_mlp15_dev72_closed_loop(prepared.scene,prepared.cfg,prepared.opts);
    assert(isfile(firstStepMarker),'PositionResidualGRU:PlantStepMarker','No first-Plant-step marker was recorded.');
    scene=prepared.scene;log.position_residual_gru_release_sha256=releaseSha;
    save(rawPath,'log','scene','runIdentity','-v7.3');
    assert(double(log.last_transition)==20000&&size(log.state,1)==20001&& ...
        strcmp(char(log.status),'STABLE'),'PositionResidualGRU:Incomplete','Scene did not complete safely.');
    write_json(fullfile(attemptDir,'run_status.json'),struct( ...
        'schema','POSITION_C5_RESIDUAL_GRU_RUN_STATUS_V1','state','COMPLETED', ...
        'scene_id',sceneId,'finished_utc',utc_now(),'Plant_calls',1,'raw_path',rawPath, ...
        'raw_sha256',sha256_file(rawPath),'transitions',double(log.last_transition), ...
        'state_samples',size(log.state,1),'status_value',char(log.status), ...
        'safety_stop_reason',char(log.safety_stop_reason),'release_sha256',releaseSha, ...
        'source_lock_sha256',sha256_file(sourceLockPath),'TEST_read',false));
catch ME
    write_json(fullfile(attemptDir,'run_status.json'),struct( ...
        'schema','POSITION_C5_RESIDUAL_GRU_RUN_STATUS_V1','state','FAILED', ...
        'scene_id',sceneId,'failed_utc',utc_now(),'Plant_calls',double(isfile(firstStepMarker)), ...
        'raw_path',rawPath,'raw_present',isfile(rawPath),'error_identifier',char(ME.identifier), ...
        'error_message',char(ME.message),'release_sha256',releaseSha, ...
        'source_lock_sha256',sha256_file(sourceLockPath),'TEST_read',false));
    rethrow(ME);
end
clear restoreFolder
end

function h=sha256_file(path)
fid=fopen(path,'rb');assert(fid>=0,'PositionResidualGRU:Read','Cannot open %s.',path);
cleanup=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear cleanup;
end
function write_json(path,value)
fid=fopen(path,'w','n','UTF-8');assert(fid>=0,'PositionResidualGRU:Write','Cannot write %s.',path);
cleanup=onCleanup(@()fclose(fid));fprintf(fid,'%s\n',jsonencode(value,'PrettyPrint',true));clear cleanup;
end
function value=utc_now()
value=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z'''));
end
