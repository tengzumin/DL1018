function result=check_position_residual_gru_matlab_parity_v1()
studyRoot=fileparts(fileparts(mfilename('fullpath')));
inputPath=fullfile(studyRoot,'audits','MATLAB_PARITY_INPUTS_v1.mat');
modelPath=fullfile(studyRoot,'candidate_runner_work','matlab','models', ...
    'position_residual_gru_full_train24.mat');
input=load(inputPath);model=load(modelPath);
assert(isequal(size(input.x14),[24,1999,14])&& ...
    isequal(size(input.base_action),[24,1999,3])&& ...
    isequal(size(input.python_delta),[24,1999,3])&& ...
    isequal(size(input.python_action),[24,1999,3]), ...
    'PositionResidualGRU:ParityShape','Unexpected MATLAB parity input shape.');
assert(all(isfinite(input.x14),'all')&&all(isfinite(input.base_action),'all')&& ...
    all(isfinite(input.event_time_s),'all')&&all(isfinite(input.python_delta),'all')&& ...
    all(isfinite(input.python_action),'all'), ...
    'PositionResidualGRU:ParityFinite','Parity inputs contain non-finite values.');
assert(isequal(logical(input.ready),repmat(reshape(1:1999>=32,1,1999),24,1))&& ...
    abs(double(input.event_time_s(1,1))-.01)<2e-7&& ...
    abs(double(input.event_time_s(1,32))-.32)<2e-7, ...
    'PositionResidualGRU:ParityClock','Warmup or event-time alignment changed.');
model.input_mean=double(model.input_mean(:));model.input_std=double(model.input_std(:));
assert(numel(model.input_mean)==14&&numel(model.input_std)==14&& ...
    all(model.input_std>0),'PositionResidualGRU:ParityNormalizer','Invalid frozen normalizer.');

delta=zeros(24,1999,3);action=zeros(24,1999,3);warmupHiddenNorm=zeros(24,1);
for scene=1:24
    hidden=zeros(32,1); % Per-scene reset; process all events starting at 10 ms.
    for event=1:1999
        x=squeeze(input.x14(scene,event,:));
        [hidden,raw]=position_residual_gru_step_v1(hidden,x,model);
        if event==31,warmupHiddenNorm(scene)=norm(hidden);end
        if input.ready(scene,event)
            d=max(min(raw,.5),-.5);
        else
            d=zeros(3,1);
        end
        beta=min(max(double(input.event_time_s(scene,event))/1.8,0),1);
        base=reshape(double(input.base_action(scene,event,:)),1,3);
        a=min(max(base+beta*d.',-3),3);
        delta(scene,event,:)=d;
        action(scene,event,:)=reshape(a,[1,1,3]);
    end
end
deltaErr=max(abs(delta-double(input.python_delta)),[],'all');
actionErr=max(abs(action-double(input.python_action)),[],'all');
assert(all(isfinite(warmupHiddenNorm))&&all(warmupHiddenNorm>0)&& ...
    all(delta(:,1:31,:)==0,'all')&&deltaErr<2e-6&&actionErr<2e-6, ...
    'PositionResidualGRU:ParityFail','MATLAB/Python eventwise parity failed.');
result=struct('schema','POSITION_RESIDUAL_GRU_MATLAB_PYTHON_PARITY_V1', ...
    'status','PASS','scene_count',24,'events_per_scene',1999, ...
    'total_events',24*1999,'ready_events',24*1968,'per_scene_hidden_reset',true, ...
    'events_processed_from_t_0_01',true,'first_ready_event_index_zero_based',31, ...
    'first_ready_event_time_s',double(input.event_time_s(1,32)), ...
    'pre_ready_hidden_norm_min_max',[min(warmupHiddenNorm),max(warmupHiddenNorm)], ...
    'unready_delta_exactly_zero',all(delta(:,1:31,:)==0,'all'), ...
    'max_abs_delta_error_mps2',deltaErr,'max_abs_action_error_mps2',actionErr, ...
    'per_scene_base_and_beta_formula','clip(base + clip(event_time_s/1.8,0,1)*clip(delta,±0.5),±3)', ...
    'weights_sha256',sha256_file(modelPath),'parity_inputs_sha256',sha256_file(inputPath), ...
    'scope','TRAIN24 numerical replay only; no TEST, Plant, or inertia reconstruction');
write_json(fullfile(studyRoot,'audits','MATLAB_PYTHON_PARITY_v1.json'),result);
disp(jsonencode(result,'PrettyPrint',true));
end

function h=sha256_file(path)
fid=fopen(path,'rb');assert(fid>=0,'PositionResidualGRU:Read','Cannot open %s.',path);
cleanup=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear cleanup;
end
function write_json(path,value)
fid=fopen(path,'w','n','UTF-8');assert(fid>=0,'PositionResidualGRU:Write','Cannot write %s.',path);
cleanup=onCleanup(@()fclose(fid));fprintf(fid,'%s\n',jsonencode(value,'PrettyPrint',true));clear cleanup;
end
