function p=prepare_position_residual_gru_no_plant(writeReceipt)
% Bind the fixed VAL scene and stop at the main-loop boundary without Plant.
if nargin<1,writeReceipt=false;end
studyRoot=fileparts(fileparts(mfilename('fullpath')));
assert(strcmpi(pwd,studyRoot),'PositionResidualGRU:CurrentDirectory', ...
    'Run preparation from the isolated residual-GRU study root.');
releasePath=fullfile(studyRoot,'RELEASE.json');release=jsondecode(fileread(releasePath));
sourceLockPath=fullfile(studyRoot,'SOURCE_LOCK_v1.json');sourceLock=jsondecode(fileread(sourceLockPath));
assert(strcmp(char(release.schema),'DL1018_POSITION_C5_RESIDUAL_GRU_NOPLANT_V1')&& ...
    strcmp(char(release.study_id),'position_c5_residual_gru_single_pilot_v1')&& ...
    strcmp(char(release.status),'PREPARED_NO_PLANT_PENDING_ROOT_AUDIT')&& ...
    double(release.authorized_Plant_calls)==0&&double(release.Plant_calls)==0&& ...
    ~logical(release.TEST_read)&&~logical(release.inertia_reconstruction_enabled)&& ...
    strcmpi(sha256_file(sourceLockPath),char(release.source_lock_sha256))&& ...
    strcmpi(char(java.io.File(char(sourceLock.root)).getCanonicalPath()), ...
    char(java.io.File(fullfile(studyRoot,'candidate_runner_work')).getCanonicalPath())), ...
    'PositionResidualGRU:Release','Release or source lock identity is invalid.');
payloadManifestPath=fullfile(studyRoot,'MLP15_DEV72_PAYLOAD_MANIFEST_v2.json');
assert(isfile(payloadManifestPath)&&strcmpi(sha256_file(payloadManifestPath), ...
    char(release.parent_payload_manifest_sha256)), ...
    'PositionResidualGRU:PayloadManifest','Frozen DEV/VAL payload manifest is missing or changed.');
for i=1:numel(sourceLock.files)
    rec=sourceLock.files(i);path=fullfile(studyRoot,strrep(char(rec.path),'/',filesep));
    assert(isfile(path)&&strcmpi(sha256_file(path),char(rec.sha256)), ...
        'PositionResidualGRU:SourceHash','Isolated source changed: %s.',path);
end
weightsPath=fullfile(studyRoot,'candidate_runner_work','matlab','models', ...
    'position_residual_gru_full_train24.mat');
assert(strcmpi(sha256_file(weightsPath),char(release.position_residual_gru.weights_sha256)), ...
    'PositionResidualGRU:WeightsHash','Frozen GRU MAT weights changed.');
modelManifestPath=fullfile(fileparts(studyRoot), ...
    'position_c5_residual_gru_full_train_v1','MODEL_MANIFEST_v1.json');
modelManifest=jsondecode(fileread(modelManifestPath));
assert(strcmpi(sha256_file(weightsPath),char(modelManifest.mat_weights_sha256))&& ...
    strcmpi(char(release.position_residual_gru.checkpoint_sha256),char(modelManifest.checkpoint_sha256)), ...
    'PositionResidualGRU:ModelManifest','Frozen residual model package does not match its manifest.');

sceneId=char(release.fixed_scene_id);projectRoot=fileparts(fileparts(fileparts(studyRoot)));
parentRoot=fullfile(projectRoot,'experiments','dl_attitude_replacement_20261028','gru_prediction_tau01_v1');
parentReleasePath=fullfile(parentRoot,'RELEASE.json');
parentRuntime=fullfile(parentRoot,'candidate_runner_work','matlab','runtime');
assert(strcmpi(sha256_file(parentReleasePath),char(release.parent_tau01_release_sha256))&& ...
    strcmpi(sha256_file(char(release.parent_cosine_release_path)), ...
    char(release.parent_cosine_release_sha256))&& ...
    strcmpi(sha256_file(char(release.parent_tau1_helper_path)), ...
    char(release.parent_tau1_helper_sha256)), ...
    'PositionResidualGRU:ParentRelease','Parent C5/cosine release or delayed-prediction helper changed.');
oldFolder=pwd;restoreFolder=onCleanup(@()cd(oldFolder));
cd(parentRoot);addpath(parentRuntime,'-begin');
clear activate_paired_runner prepare_gru_prediction_tau01_no_plant;
base=prepare_gru_prediction_tau01_no_plant(sceneId,false);
cd(studyRoot);restoredefaultpath;rehash toolboxcache;
candidateRuntime=fullfile(studyRoot,'candidate_runner_work','matlab','runtime');
addpath(candidateRuntime,'-begin');clear activate_paired_runner;
runnerRoot=activate_paired_runner();candidateRuntime=fullfile(runnerRoot,'matlab','runtime');
assert(strcmpi(which('run_mlp15_dev72_closed_loop'), ...
    fullfile(candidateRuntime,'run_mlp15_dev72_closed_loop.m'))&& ...
    strcmp(sceneId,char(base.scene.scene_id))&&base.position_runtime_enabled&& ...
    base.position_runtime_update_enabled&&base.position_coordination_enabled&& ...
    base.position_delayed_prediction_enabled&&abs(double(base.position_nn_compensation_scale)-1)<1e-12, ...
    'PositionResidualGRU:ParentBinding','Scene or frozen cosine/C5 parent identity differs.');
if isfield(base.opts.stage1_position_runtime,'applied_acceleration_notch')
    base.opts.stage1_position_runtime=rmfield(base.opts.stage1_position_runtime,'applied_acceleration_notch');
end
m=load(weightsPath);
residual=struct('enabled',true,'weights_sha256',char(release.position_residual_gru.weights_sha256), ...
    'input_mean',double(m.input_mean(:)),'input_std',double(m.input_std(:)), ...
    'gru_weight_ih_l0',double(m.gru_weight_ih_l0),'gru_weight_hh_l0',double(m.gru_weight_hh_l0), ...
    'gru_bias_ih_l0',double(m.gru_bias_ih_l0(:)),'gru_bias_hh_l0',double(m.gru_bias_hh_l0(:)), ...
    'head_weight',double(m.head_weight),'head_bias',double(m.head_bias(:)), ...
    'beta_rise_time_s',1.8,'delta_limit_mps2',.5,'action_limit_mps2',3, ...
    'smooth_lambda',.01,'seed',20261028,'optimizer_steps',300);
base.opts.stage1_position_runtime.residual_gru=residual;
base.opts.no_plant_boundary_check=true;
markerPath=fullfile(studyRoot,'audits','NO_PLANT_BOUNDARY_ATTEMPT.json');
write_json(markerPath,struct('scene_id',sceneId,'stage','RUNNING','Plant_calls',0));
base.opts.composite_attempt_marker=markerPath;
identityOpts=rmfield(base.opts,'composite_attempt_marker');
base.opts.gate_identity_lock=gate_holdout_identity_hashes( ...
    base.cfg,base.opts.stage1_position_runtime.model,identityOpts);

probeError='';probeErrorMessage='';
try
    run_mlp15_dev72_closed_loop(base.scene,base.cfg,base.opts);
catch ME
    probeError=char(ME.identifier);probeErrorMessage=char(ME.message);
end
assert(strcmp(probeError,'PositionNotch:NoPlantPreflightStop')&& ...
    ~isfile(fullfile(studyRoot,'first_plant_step.marker'))&&double(release.Plant_calls)==0, ...
    'PositionResidualGRU:MainLoopBoundary','Preflight failed before the expected Plant boundary (%s: %s).', ...
    probeError,probeErrorMessage);
p=struct('scene_id',sceneId,'release_sha256',sha256_file(releasePath), ...
    'source_lock_sha256',sha256_file(sourceLockPath),'parent_tau01_release_sha256',sha256_file(parentReleasePath), ...
    'scene_payload_sha256',base.scene_payload_sha256,'external_identity_sha256',base.external_identity_sha256, ...
    'b_raw_sha256',base.b_raw_sha256,'gru_model_sha256',base.gru_model_sha256, ...
    'position_model_sha256',base.position_model_sha256,'weights_sha256',sha256_file(weightsPath), ...
    'common_position_options_sha256',base.identity.common.position_options_sha256, ...
    'runner_path',which('run_mlp15_dev72_closed_loop'),'event_rate_hz',100, ...
    'first_event_time_s',.01,'first_ready_event_index_zero_based',31, ...
    'first_ready_event_time_s',.32,'residual_beta','clip(event_time_s/1.8,0,1)', ...
    'action_formula','clip(C5_applied + beta*clip(delta,-0.5,0.5),-3,3)', ...
    'notch_enabled',false,'boundary_error_identifier',probeError,'Plant_calls',0);
if writeReceipt
    write_json(fullfile(studyRoot,'NO_PLANT_PREPARE_RESULT_v1.json'),struct( ...
        'schema','POSITION_C5_RESIDUAL_GRU_NOPLANT_RECEIPT_V1', ...
        'status','PASS_REACHED_MAIN_LOOP_BOUNDARY_NO_PLANT', ...
        'scene_id',sceneId,'release_sha256',p.release_sha256, ...
        'source_lock_sha256',p.source_lock_sha256,'parent_tau01_release_sha256',p.parent_tau01_release_sha256, ...
        'scene_payload_sha256',p.scene_payload_sha256,'external_identity_sha256',p.external_identity_sha256, ...
        'b_raw_sha256',p.b_raw_sha256,'gru_model_sha256',p.gru_model_sha256, ...
        'position_model_sha256',p.position_model_sha256,'residual_gru_weights_sha256',p.weights_sha256, ...
        'common_position_options_sha256',p.common_position_options_sha256, ...
        'position_method_id','C5_AXIS_MIXED_COORDINATE_M110','event_rate_hz',100, ...
        'first_event_time_s',.01,'first_ready_event_index_zero_based',31, ...
        'first_ready_event_time_s',.32,'residual_beta','clip(event_time_s/1.8,0,1)', ...
        'action_formula',p.action_formula,'notch_enabled',false, ...
        'resolved_runner_path',p.runner_path,'main_loop_boundary_error_identifier',probeError, ...
        'Plant_calls',0,'plant_called',false,'inertia_reconstruction_enabled',false,'TEST_read',false));
end
clear restoreFolder
end

function h=sha256_file(path)
fid=fopen(path,'rb');assert(fid>=0,'PositionResidualGRU:Read','Cannot open %s.',path);
cleanup=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear cleanup;
end
function write_json(path,value)
fid=fopen(path,'w','n','UTF-8');assert(fid>=0,'PositionResidualGRU:Write','Cannot write %s.',path);
cleanup=onCleanup(@()fclose(fid));fprintf(fid,'%s\n',jsonencode(value,'PrettyPrint',true));clear cleanup;
end
