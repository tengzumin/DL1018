function prepared=prepare_causal_n4_train24_scene_no_plant(sceneId)
% Source-only fork of the fixed N4 v2 preparer; candidate math stays in shared n4cg_v2 runtime.
entry=fileparts(mfilename('fullpath'));runnerRoot=fileparts(fileparts(entry));studyRoot=fileparts(runnerRoot);
input=jsondecode(fileread(fullfile(studyRoot,'BATCH_INPUT_v2.json')));
sharedRoot=fullfile(studyRoot,char(input.n4_gate_v2.shared_runtime_relative));
sharedRuntime=fullfile(sharedRoot,'matlab','runtime');
assert(isfolder(sharedRuntime),'N4Train24:Runtime','Shared N4 v2 runtime is missing.');
addpath(sharedRuntime);activate_paired_runner();addpath(entry);
releasePath=fullfile(studyRoot,'RELEASE.json');lockPath=fullfile(studyRoot,'SOURCE_LOCK_TRAIN24_v2.json');
release=jsondecode(fileread(releasePath));lock=jsondecode(fileread(lockPath));
assert(strcmpi(sha256_file(lockPath),char(release.source_lock_sha256)), ...
    'N4Train24:Lock','TRAIN24 source lock changed.');
sceneId=char(sceneId);authorized=cellstr(string(release.authorized_scenes));
noPlantRelease=strcmp(release.schema,'DL1018_CAUSAL_N4_GATE_TRAIN24_NOPLANT_V2')&& ...
    strcmp(release.status,'PREPARED_NO_PLANT_PENDING_ROOT_AUDIT')&& ...
    numel(authorized)==24&&numel(unique(authorized))==24&& ...
    release.authorized_Plant_calls==0&&release.Plant_calls==0&&release.potential_budget_calls==0;
singleCallRelease=strcmp(release.schema,'DL1018_CAUSAL_N4_GATE_TRAIN24_SINGLE_CALL_V2')&& ...
    strcmp(release.status,'RELEASED')&&numel(authorized)==1&& ...
    strcmp(char(release.fixed_scene_id),sceneId)&&release.authorized_Plant_calls==1&& ...
    release.Plant_calls==1&&release.potential_budget_calls==1;
assert(strcmp(release.study_id,'causal_n4_gate_train24_batch_v2')&& ...
    strcmp(release.source_split,'TRAIN_C5_24')&&(noPlantRelease||singleCallRelease)&& ...
    any(strcmp(authorized,sceneId))&&~release.TEST_read&&~release.VAL_data_read&& ...
    ~release.inertia_reconstruction_enabled,'N4Train24:Release', ...
    'Expected a zero-Plant batch release or a fixed one-call TRAIN release.');
bindingPath=fullfile(studyRoot,'bindings',[sceneId '.json']);
binding=jsondecode(fileread(bindingPath));
assert(strcmp(binding.schema,'DL1018_CAUSAL_N4_TRAIN24_SCENE_BINDING_V2')&& ...
    strcmp(binding.status,'PASS_TRAIN_ONLY_PAIR_BINDING')&& ...
    strcmp(binding.source_split,'TRAIN_C5_24 (canonical ID prefix DEV)')&& ...
    strcmp(binding.study_id,release.study_id)&&strcmp(binding.selected_scene_id,sceneId)&& ...
    binding.Plant_calls==0&&~binding.TEST_read&&~binding.VAL_data_read&& ...
    ~binding.inertia_reconstruction_enabled&&~binding.extra_position_residual_gru_enabled&& ...
    binding.fixed_J0,'N4Train24:Binding','Binding must be the exact TRAIN-only scene row.');
assert(strcmpi(sha256_file(binding.dataset_manifest_path),binding.dataset_manifest_sha256)&& ...
    strcmpi(sha256_file(binding.dataset_source_lock_path),binding.dataset_source_lock_sha256)&& ...
    strcmpi(sha256_file(binding.parent_cosine_model_path),binding.parent_cosine_model_sha256)&& ...
    strcmpi(sha256_file(binding.c5_snapshot_path),binding.c5_snapshot_sha256)&& ...
    strcmpi(sha256_file(binding.position_model_path),binding.position_model_sha256)&& ...
    strcmpi(sha256_file(binding.c5_receipt_path),binding.c5_receipt_sha256)&& ...
    strcmpi(sha256_file(binding.local_scene_payload_path),binding.local_scene_payload_sha256)&& ...
    strcmpi(sha256_file(binding.parent_raw_path),binding.parent_raw_sha256)&& ...
    strcmpi(sha256_file(binding.parent_status_path),binding.parent_status_sha256)&& ...
    strcmpi(sha256_file(binding.parent_run_start_path),binding.parent_run_start_sha256)&& ...
    strcmpi(sha256_file(binding.c5_raw_path),binding.c5_raw_sha256)&& ...
    strcmpi(sha256_file(binding.c5_status_path),binding.c5_status_sha256)&& ...
    strcmpi(sha256_file(binding.b72_scoring_raw_path),binding.b72_scoring_raw_sha256)&& ...
    strcmpi(sha256_file(binding.b72_scoring_status_path),binding.b72_scoring_status_sha256), ...
    'N4Train24:SourceHash','A scene, controller, model, or baseline source changed.');
manifest=jsondecode(fileread(binding.dataset_manifest_path));
ids=cellstr(string(manifest.source_scene_ids));order=double(binding.source_order_zero_based)+1;
validOrder=isscalar(order)&&isfinite(order)&&order>=1&&order<=24&&order==floor(order);
authorizedOrderOk=false;
if validOrder
    if noPlantRelease
        authorizedOrderOk=numel(authorized)==24&&strcmp(ids{order},authorized{order});
    else
        authorizedOrderOk=numel(authorized)==1&&strcmp(authorized{1},sceneId);
    end
end
assert(double(manifest.scene_count)==24&&numel(ids)==24&&validOrder&& ...
    strcmp(ids{order},sceneId)&&authorizedOrderOk, ...
    'N4Train24:TrainMembership','Scene is not the exact manifest-listed TRAIN member.');
parentStatus=jsondecode(fileread(binding.parent_status_path));
parentStart=jsondecode(fileread(binding.parent_run_start_path));
c5Status=jsondecode(fileread(binding.c5_status_path));bStatus=jsondecode(fileread(binding.b72_scoring_status_path));
assert(strcmp(parentStatus.status_value,'STABLE')&&parentStatus.transitions==20000&& ...
    parentStatus.state_samples==20001&&parentStatus.Plant_calls==1&& ...
    strcmp(parentStart.scene_id,sceneId)&&strcmpi(parentStart.c5_raw_sha256,binding.c5_raw_sha256)&& ...
    strcmpi(parentStart.b_raw_sha256,binding.b72_scoring_raw_sha256)&& ...
    strcmpi(parentStart.payload_sha256,binding.scene_payload_source_sha256)&& ...
    strcmp(c5Status.scene_id,sceneId)&&c5Status.transitions==20000&& ...
    c5Status.state_samples==20001&&c5Status.plant_calls==1&& ...
    strcmp(bStatus.scene_id,sceneId)&&bStatus.transitions==20000&& ...
    bStatus.state_samples==20001&&strcmp(bStatus.log_status,'STABLE')&& ...
    ~parentStatus.TEST_read&&~c5Status.TEST_accessed&&~bStatus.TEST_accessed, ...
    'N4Train24:BaselinePair','Parent/B/C5 baselines are not this completed TRAIN scene.');
payload=load(binding.local_scene_payload_path,'scene');scene=payload.scene;
assert(strcmp(char(scene.scene_id),sceneId),'N4Train24:Payload','Payload scene id mismatch.');
scene.reference_contract_id='DL1018_SCENE_REF_FIG8_A2_V2';
snapshot=load(binding.c5_snapshot_path,'cfg','W0');positionPack=load(binding.position_model_path,'model');
positionModel=positionPack.model;receipt=jsondecode(fileread(binding.c5_receipt_path));
assert(strcmp(positionModel.model_id,'DSSM14')&&positionModel.input_dim==14&&positionModel.window==32&& ...
    isequal(double(positionModel.output_W),double(snapshot.W0))&& ...
    strcmpi(paired_sha256_double(double(snapshot.W0)),receipt.W0_sha256), ...
    'N4Train24:C5Model','C5 DSSM14, snapshot, and receipt do not match.');
cfg=snapshot.cfg;if isfield(cfg,'attitude_replacement'),cfg=rmfield(cfg,'attitude_replacement');end
cfg.plant.arm_initial=repmat(.15,4,1);cfg=bind_paired_fixed_j0(cfg);
parentModel=load(binding.parent_cosine_model_path);
opts=make_gate_holdout_options(cfg,positionModel,'GRU_STREAM','ACTIVE',struct, ...
    parentModel,binding.parent_cosine_model_sha256);
assert(~isfield(opts.stage1_position_runtime,'residual_gru'), ...
    'N4Train24:PositionGRU','The extra position-GRU runtime must be absent.');
opts.no_plant_boundary_check=noPlantRelease;
identity=gate_holdout_identity_hashes(cfg,positionModel,opts);
assert(strcmpi(identity.common.position_options_sha256,receipt.common_position_options_sha256), ...
    'N4Train24:ExactOptions','Parent/C5 position options changed.');
executionIdentity=identity;identityModeAudit=struct('changed_option','no_plant_boundary_check', ...
    'prepared_no_plant_value',true,'execution_value',false,'identity_common_equal',true, ...
    'identity_geometry_except_options_equal',true,'runner_invoked',false);
if noPlantRelease
    executionOpts=opts;executionOpts.no_plant_boundary_check=false;
    executionIdentity=gate_holdout_identity_hashes(cfg,positionModel,executionOpts);
    identityModeAudit.identity_common_equal=isequaln(identity.common,executionIdentity.common);
    identityModeAudit.identity_geometry_except_options_equal=isequaln( ...
        rmfield(identity.geometry,'options_sha256'),rmfield(executionIdentity.geometry,'options_sha256'));
    assert(identityModeAudit.identity_common_equal&&identityModeAudit.identity_geometry_except_options_equal, ...
        'N4Train24:ExecutionIdentity','Changing only the no-Plant control flag changed numeric/model identity.');
end
opts.gate_identity_lock=identity;
opts.stage1_position_runtime.applied_acceleration_static_n4=release.applied_acceleration_static_n4;
opts.composite_attempt_marker=fullfile(studyRoot,'audits',[sceneId '_marker.json']);
sceneAudit=validate_train_scene_binding_v1(scene,cfg,binding,parentStart);
prepared=struct('scene',scene,'cfg',cfg,'opts',opts,'identity',identity,'scene_audit',sceneAudit, ...
    'scene_id',sceneId,'binding_path',bindingPath,'binding_sha256',sha256_file(bindingPath), ...
    'payload_sha256',binding.local_scene_payload_sha256,'parent_raw_sha256',binding.parent_raw_sha256, ...
    'c5_raw_sha256',binding.c5_raw_sha256,'b_raw_sha256',binding.b72_scoring_raw_sha256, ...
    'marker_path',opts.composite_attempt_marker,'candidate_attempt',binding.candidate_attempt, ...
    'execution_identity',executionIdentity,'identity_mode_audit',identityModeAudit);
end
function h=sha256_file(path)
fid=fopen(path,'rb');assert(fid>=0,'N4Train24:Read','Cannot open %s.',path);
cleanup=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear cleanup;
end
