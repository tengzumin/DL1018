function audit=run_dual_notch_no_plant_parity_v1()
% Pure helper parity over frozen TRAIN action sequences; no runner or Plant call.
here=fileparts(mfilename('fullpath'));study=fileparts(here);
inputPath=fullfile(study,'DUAL_NOTCH_EVENTWISE_PARITY_INPUTS_v1.mat');
metadataPath=fullfile(study,'DUAL_NOTCH_EVENTWISE_PARITY_INPUTS_v1.json');
protocolPath=fullfile(study,'DIAGNOSTIC_PROTOCOL_v1.json');
outPath=fullfile(study,'MATLAB_NOPLANT_PARITY_v1.json');
assert(isfile(inputPath)&&isfile(metadataPath)&&isfile(protocolPath)&&~isfile(outPath), ...
    'DualNotch:InputFiles','Missing parity inputs or refusing to overwrite result.');
meta=jsondecode(fileread(metadataPath));protocol=jsondecode(fileread(protocolPath));d=load(inputPath);
assert(strcmp(meta.status,'PASS_TRAIN_PARITY_INPUTS_READY')&&numel(meta.scenes)==2&& ...
    all(strcmp({meta.scenes.scene_id},{'DL1018_DEV_T1_C10_W09','DL1018_DEV_T3_C09_W09'}))&& ...
    protocol.plant_calls_allowed==0&&protocol.plant_calls_made==0&& ...
    ~protocol.TEST_read&&~protocol.VAL_read, ...
    'DualNotch:Scope','Parity input metadata is outside the locked TRAIN/no-Plant scope.');
rows=repmat(struct('scene_id','','max_abs_action_error_mps2',NaN, ...
    'max_abs_coefficient_error',NaN,'matlab_clip_count',NaN,'expected_clip_count',NaN,'status','FAIL'),1,2);
for j=1:2
    prefix=sprintf('scene%d_',j);id=char(d.([prefix 'id']));
    action=d.([prefix 'action_mps2']);events=logical(d.([prefix 'event']));expected=d.([prefix 'expected_mps2']);
    expectedB=d.([prefix 'b']);expectedA=d.([prefix 'a']);expectedClips=double(d.([prefix 'clip_count']));
    assert(size(action,1)==3&&isequal(size(action),size(expected))&& ...
        numel(events)==size(action,2)&&all(isfinite(action(:)))&&all(isfinite(expected(:))), ...
        'DualNotch:Shape','Malformed frozen action input.');
    s=position_compensation_dual_notch_init();
    coeffError=max([abs(s.b(:)-expectedB(:));abs(s.a(:)-expectedA(:))]);
    output=zeros(size(action));
    for k=1:size(action,2)
        [s,output(:,k)]=position_compensation_dual_notch_step(s,action(:,k),events(k));
    end
    actionError=max(abs(output(:)-expected(:)));
    status='FAIL';
    if actionError<=protocol.parity_contract.max_abs_action_error_mps2&& ...
            coeffError<=protocol.parity_contract.max_abs_coefficient_error&&s.clip_count==expectedClips
        status='PASS';
    end
    rows(j)=struct('scene_id',id,'max_abs_action_error_mps2',actionError, ...
        'max_abs_coefficient_error',coeffError,'matlab_clip_count',s.clip_count, ...
        'expected_clip_count',expectedClips,'status',status);
end
pass=all(strcmp({rows.status},'PASS'));
audit=struct('schema','POSITION_COMPENSATION_DUAL_NOTCH_MATLAB_NOPLANT_PARITY_V1', ...
    'status',ternary(pass,'PASS_MATLAB_HELPER_PARITY_NOPLANT','FAIL_MATLAB_HELPER_PARITY_NOPLANT'), ...
    'study_id',meta.study_id,'scenes',rows,'diagnostic_baseline_measured',protocol.diagnostic_baseline_measured, ...
    'intervention_closed_loop_Q_m',[],'intervention_closed_loop_task_SO3_rad',[], ...
    'plant_called',false,'Plant_calls',0,'TEST_read',false,'VAL_read',false, ...
    'inertia_reconstruction_enabled',false,'runner_invoked',false, ...
    'frozen_replay_status_preserved',protocol.entry_reason.prior_frozen_replay_status, ...
    'interpretation','Helper recurrence parity only. Q/task values are measured current-candidate baselines; no closed-loop intervention Q/task were measured.');
fid=fopen(outPath,'w');assert(fid>=0,'DualNotch:NoOverwrite','Cannot create parity result.');
cleanup=onCleanup(@()fclose(fid));fwrite(fid,[jsonencode(audit,'PrettyPrint',true) newline],'char');clear cleanup;
fprintf('DUAL_NOTCH_NOPLANT_PARITY=%s\n',outPath);
end

function y=ternary(c,a,b)
if c,y=a;else,y=b;end
end
