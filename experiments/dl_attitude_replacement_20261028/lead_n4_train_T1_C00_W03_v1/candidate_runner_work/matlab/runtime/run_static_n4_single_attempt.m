function attemptDir=run_static_n4_single_attempt()
% Exactly one predeclared TRAIN N4 call, guarded by the no-Plant audit and lock.
entry=fileparts(mfilename('fullpath'));runnerRoot=fileparts(fileparts(entry));studyRoot=fileparts(runnerRoot);
releasePath=fullfile(studyRoot,'RELEASE.json');lockPath=fullfile(studyRoot,'SOURCE_LOCK_SINGLE_CALL_v1.json');
release=jsondecode(fileread(releasePath));lock=jsondecode(fileread(lockPath));
assert(strcmpi(sha256_file(lockPath),release.source_lock_sha256), ...
    'StaticN4:Lock','Single-call source lock differs from release.');
for i=1:numel(lock.files)
    p=char(lock.files(i).path);
    assert(isfile(p)&&strcmpi(sha256_file(p),char(lock.files(i).sha256)), ...
        'StaticN4:SourceHash','Locked source changed: %s',p);
end
priorPath=char(release.prior_no_plant_preflight_path);
assert(isfile(priorPath)&&strcmpi(sha256_file(priorPath),release.prior_no_plant_preflight_sha256), ...
    'StaticN4:PriorNoPlantHash','Passing no-Plant audit changed.');
prior=jsondecode(fileread(priorPath));
assert(strcmp(prior.status,'PASS_FULL_RUNNER_NOPLANT_BOUNDARY')&& ...
    strcmp(prior.scene_id,release.fixed_scene_id)&&prior.Plant_calls==0&& ...
    prior.attempt_markers==0&&prior.first_plant_step_markers==0, ...
    'StaticN4:PriorNoPlant','No-Plant audit is not a clean same-scene boundary pass.');
assert(strcmp(release.schema,'DL1018_POSITION_C5_STATIC_N4_NO_POSITION_GRU_SINGLE_CALL_V1')&& ...
    strcmp(release.status,'RELEASED')&&release.authorized_Plant_calls==1&& ...
    release.Plant_calls==1&&release.potential_budget_calls==1&& ...
    numel(release.authorized_scenes)==1&&strcmp(release.authorized_scenes{1},release.fixed_scene_id)&& ...
    ~release.TEST_read&&~release.VAL_data_read&&~release.inertia_reconstruction_enabled&& ...
    ~release.Plant_truth_deployment_input, ...
    'StaticN4:Budget','Release must authorize exactly one fixed TRAIN call.');
prepared=prepare_static_n4_train_scene_single_call();
assert(~prepared.opts.no_plant_boundary_check&& ...
    ~isfield(prepared.opts.stage1_position_runtime,'residual_gru')&& ...
    strcmp(prepared.scene_id,release.fixed_scene_id), ...
    'StaticN4:PreparedIdentity','Prepared scene/runtime differs from the single-call release.');
sceneRunRoot=fullfile(studyRoot,'runs',prepared.scene_id);attemptDir=fullfile(sceneRunRoot,'attempt_01');
assert(~isfolder(attemptDir)&&~isfile(attemptDir),'StaticN4:NoOverwrite','Attempt directory already exists.');
assert(java.io.File(attemptDir).mkdirs(),'StaticN4:AttemptDir','Cannot create attempt directory.');
attemptMarker=fullfile(attemptDir,'attempt_started.marker');firstPlant=fullfile(attemptDir,'first_plant_step.marker');
opts=prepared.opts;opts.composite_attempt_marker=attemptMarker;
runStart=struct('schema','STATIC_N4_RUN_START_V1','scene_id',prepared.scene_id, ...
    'source_split','TRAIN_C5_24','started_utc',utcNow(),'release_sha256',sha256_file(releasePath), ...
    'source_lock_sha256',sha256_file(lockPath), ...
    'prior_no_plant_preflight_sha256',sha256_file(priorPath), ...
    'binding_sha256',prepared.binding_sha256,'payload_sha256',prepared.payload_sha256, ...
    'scene_identity_sha256',prepared.scene_audit.external_identity_sha256, ...
    'B_raw_sha256',prepared.b_raw_sha256,'parent_raw_sha256',prepared.parent_raw_sha256, ...
    'C5_raw_sha256',prepared.c5_raw_sha256,'no_plant_boundary_check',false, ...
    'position_residual_gru_enabled',false,'TEST_read',false,'VAL_read',false, ...
    'inertia_reconstruction_enabled',false,'entry','run_mlp15_dev72_closed_loop');
write_json_new(attemptMarker,struct('stage','RUNNING','scene_id',prepared.scene_id,'Plant_calls',1));
write_json_new(fullfile(attemptDir,'run_start.json'),runStart);
try
    log=run_mlp15_dev72_closed_loop(prepared.scene,prepared.cfg,opts);
    transitions=double(log.last_transition);samples=size(log.state,1);
    scene=prepared.scene;identity=runStart;save(fullfile(attemptDir,'raw_run.mat'),'log','scene','identity','-v7.3');
    rawPath=fullfile(attemptDir,'raw_run.mat');complete=transitions==20000&&samples==20001&&strcmp(log.status,'STABLE');
    status=struct('schema','STATIC_N4_RUN_STATUS_V1','state',ternary(complete,'COMPLETED','INCOMPLETE'), ...
        'scene_id',prepared.scene_id,'source_split','TRAIN_C5_24','finished_utc',utcNow(), ...
        'Plant_calls',1,'raw_path',rawPath,'raw_sha256',sha256_file(rawPath), ...
        'transitions',transitions,'state_samples',samples,'status_value',log.status, ...
        'safety_stop_reason',log.safety_stop_reason,'first_plant_step_marker_created',isfile(firstPlant), ...
        'release_sha256',runStart.release_sha256,'source_lock_sha256',runStart.source_lock_sha256, ...
        'prior_no_plant_preflight_sha256',runStart.prior_no_plant_preflight_sha256, ...
        'TEST_read',false,'VAL_read',false,'inertia_reconstruction_enabled',false);
    write_json_new(fullfile(attemptDir,'run_status.json'),status);
    assert(complete&&isfile(firstPlant),'StaticN4:RunIncomplete','Single call did not complete stable 20k run.');
    write_json_overwrite(attemptMarker,struct('stage','COMPLETED','scene_id',prepared.scene_id, ...
        'Plant_calls',1,'first_plant_step_marker_created',true));
    fprintf('STATIC_N4_SINGLE_ATTEMPT=%s\n',attemptDir);
catch ME
    failure=struct('schema','STATIC_N4_RUN_STATUS_V1','state','FAILED','scene_id',prepared.scene_id, ...
        'source_split','TRAIN_C5_24','failed_utc',utcNow(),'Plant_calls',1, ...
        'error_identifier',ME.identifier,'error_message',ME.message, ...
        'first_plant_step_marker_created',isfile(firstPlant), ...
        'release_sha256',runStart.release_sha256,'source_lock_sha256',runStart.source_lock_sha256, ...
        'TEST_read',false,'VAL_read',false,'inertia_reconstruction_enabled',false);
    write_json_new(fullfile(attemptDir,'run_status.json'),failure);rethrow(ME);
end
end

function write_json_new(path,x)
assert(~isfile(path),'StaticN4:NoOverwrite','Refusing to overwrite %s.',path);write_json_overwrite(path,x);
end
function write_json_overwrite(path,x)
fid=fopen(path,'w');assert(fid>=0,'StaticN4:Write','Cannot write %s.',path);
cleanup=onCleanup(@()fclose(fid));fwrite(fid,[jsonencode(x,'PrettyPrint',true) newline],'char');clear cleanup;
end
function h=sha256_file(path)
fid=fopen(path,'rb');assert(fid>=0,'StaticN4:Read','Cannot open %s.',path);
cleanup=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear cleanup;
end
function s=utcNow()
s=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z'''));
end
function y=ternary(c,a,b)
if c,y=a;else,y=b;end
end
