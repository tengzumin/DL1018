function attemptDir=run_train_scene_single_attempt()
% One authorized paired closed-loop TRAIN diagnostic, tied to the prior no-Plant pass.
entry=fileparts(mfilename('fullpath'));
runnerRoot=fileparts(fileparts(entry));
studyRoot=fileparts(runnerRoot);
releasePath=fullfile(studyRoot,'RELEASE.json');
sourceLockPath=fullfile(studyRoot,'SOURCE_LOCK_SINGLE_CALL_v1.json');
release=jsondecode(fileread(releasePath));sourceLock=jsondecode(fileread(sourceLockPath));
assert(strcmpi(sha256_file(sourceLockPath),char(release.source_lock_sha256)), ...
    'TRAINPair:SourceLock','Single-call source lock differs from release.');
for i=1:numel(sourceLock.files)
    path=char(sourceLock.files(i).path);
    assert(isfile(path)&&strcmpi(sha256_file(path),char(sourceLock.files(i).sha256)), ...
        'TRAINPair:SourceHash','Locked source changed: %s',path);
end
authorized=cellstr(string(release.authorized_scenes));
assert(strcmp(char(release.schema),'DL1018_POSITION_C5_DUAL_NOTCH_SINGLE_CALL_V1')&& ...
    strcmp(char(release.study_id),'position_compensation_dual_notch_train_diag_single_call_T1_v1')&& ...
    strcmp(char(release.status),'RELEASED')&&double(release.authorized_Plant_calls)==1&& ...
    double(release.Plant_calls)==1&&double(release.potential_budget_calls)==1&& ...
    numel(authorized)==1&&strcmp(char(authorized{1}),char(release.fixed_scene_id))&& ...
    ~logical(release.TEST_read)&&~logical(release.VAL_data_read)&& ...
    ~logical(release.inertia_reconstruction_enabled)&&~logical(release.Plant_truth_deployment_input), ...
    'TRAINPair:SingleCallRelease','Release is not the exact one-scene, one-call TRAIN authorization.');
priorPath=char(release.prior_no_plant_preflight_path);
assert(isfile(priorPath)&&strcmpi(sha256_file(priorPath),char(release.prior_no_plant_preflight_sha256)), ...
    'TRAINPair:PriorPreflightHash','The passing no-Plant audit changed or is missing.');
prior=jsondecode(fileread(priorPath));
assert(strcmp(char(prior.status),'PASS')&&strcmp(char(prior.scene_id),char(release.fixed_scene_id))&& ...
    strcmp(char(prior.fold_id),char(release.position_residual_gru.fold_id))&& ...
    strcmpi(char(prior.weights_sha256),char(release.weights_sha256))&& ...
    double(prior.Plant_calls)==0&&~logical(prior.VAL_read)&&~logical(prior.TEST_read), ...
    'TRAINPair:PriorPreflight','Prior no-Plant pass does not match this fixed model/scene.');

% Prepare once, check the exact release/model/scene/options, then create the one-use marker.
prepared=prepare_train_scene_no_plant();
assert(~logical(prepared.opts.no_plant_boundary_check)&& ...
    strcmp(prepared.scene_id,char(release.fixed_scene_id))&& ...
    strcmp(prepared.fold_id,char(release.position_residual_gru.fold_id))&& ...
    strcmpi(prepared.weights_sha256,char(release.weights_sha256)), ...
    'TRAINPair:PreparedIdentity','Prepared controller or scene differs from the one-call release.');
sceneRunRoot=fullfile(studyRoot,'runs',prepared.scene_id);
attemptDir=fullfile(sceneRunRoot,'attempt_01');
assert(~isfolder(attemptDir)&&~isfile(attemptDir), ...
    'TRAINPair:NoOverwrite','Refusing to reuse an attempt directory.');
attemptStartedPath=fullfile(attemptDir,'attempt_started.marker');
firstPlantPath=fullfile(attemptDir,'first_plant_step.marker');
opts=prepared.opts;opts.composite_attempt_marker=attemptStartedPath;
identity=struct('schema','POSITION_DC_OOF_TRAIN_PAIR_RUN_START_V1', ...
    'scene_id',prepared.scene_id,'source_split','TRAIN_C5_24','fold_id',prepared.fold_id, ...
    'started_utc',utcNow(),'release_sha256',sha256_file(releasePath), ...
    'source_lock_sha256',sha256_file(sourceLockPath), ...
    'prior_no_plant_preflight_sha256',sha256_file(priorPath), ...
    'train_scene_binding_sha256',prepared.binding_sha256, ...
    'weights_sha256',prepared.weights_sha256,'payload_sha256',prepared.payload_sha256, ...
    'external_identity_sha256',prepared.scene_audit.external_identity_sha256, ...
    'B_raw_sha256',prepared.scene_audit.b_raw_sha256, ...
    'parent_cosine_gru_raw_sha256',prepared.parent_raw_sha256,'c5_raw_sha256',prepared.c5_raw_sha256, ...
    'no_plant_boundary_check',false,'inertia_reconstruction_enabled',false, ...
    'Plant_truth_deployment_input',false,'VAL_data_read',false,'TEST_read',false, ...
    'closed_loop_entry','run_mlp15_dev72_closed_loop(scene,cfg,opts)');
assert(java.io.File(attemptDir).mkdirs(),'TRAINPair:AttemptDir','Cannot create the unique attempt directory.');
write_json_new(attemptStartedPath,struct('schema','POSITION_DC_OOF_TRAIN_PAIR_ATTEMPT_MARKER_V1', ...
    'scene_id',prepared.scene_id,'stage','RUNNING','Plant_calls',1, ...
    'release_sha256',identity.release_sha256));
write_json_new(fullfile(attemptDir,'run_start.json'),identity);
try
    log=run_mlp15_dev72_closed_loop(prepared.scene,prepared.cfg,opts);
    transitions=double(log.last_transition);stateSamples=size(log.state,1);
    complete=transitions==20000&&stateSamples==20001&&strcmp(char(log.status),'STABLE');
    scene=prepared.scene;save(fullfile(attemptDir,'raw_run.mat'),'log','scene','identity','-v7.3');
    rawPath=fullfile(attemptDir,'raw_run.mat');
    status=struct('schema','POSITION_DC_OOF_TRAIN_PAIR_RUN_STATUS_V1', ...
        'state',conditional(complete,'COMPLETED','SAFETY_STOP_OR_INCOMPLETE'), ...
        'scene_id',prepared.scene_id,'source_split','TRAIN_C5_24','fold_id',prepared.fold_id, ...
        'finished_utc',utcNow(),'Plant_calls',1,'raw_path',rawPath,'raw_sha256',sha256_file(rawPath), ...
        'transitions',transitions,'state_samples',stateSamples,'status_value',char(log.status), ...
        'safety_stop_reason',char(log.safety_stop_reason), ...
        'first_plant_step_marker_created',isfile(firstPlantPath), ...
        'weights_sha256',prepared.weights_sha256,'payload_sha256',prepared.payload_sha256, ...
        'B_raw_sha256',prepared.scene_audit.b_raw_sha256, ...
        'parent_cosine_gru_raw_sha256',prepared.parent_raw_sha256,'c5_raw_sha256',prepared.c5_raw_sha256, ...
        'release_sha256',identity.release_sha256,'source_lock_sha256',identity.source_lock_sha256, ...
        'prior_no_plant_preflight_sha256',identity.prior_no_plant_preflight_sha256, ...
        'VAL_data_read',false,'TEST_read',false,'inertia_reconstruction_enabled',false);
    write_json_new(fullfile(attemptDir,'run_status.json'),status);
    write_json_overwrite(attemptStartedPath,struct('schema','POSITION_DC_OOF_TRAIN_PAIR_ATTEMPT_MARKER_V1', ...
        'scene_id',prepared.scene_id,'stage','COMPLETED','Plant_calls',1, ...
        'release_sha256',identity.release_sha256,'first_plant_step_marker_created',isfile(firstPlantPath)));
    fprintf('TRAIN_PAIR_SINGLE_ATTEMPT_DIR=%s\n',attemptDir);
catch ME
    failure=struct('schema','POSITION_DC_OOF_TRAIN_PAIR_RUN_STATUS_V1','state','FAILED', ...
        'scene_id',prepared.scene_id,'source_split','TRAIN_C5_24','fold_id',prepared.fold_id, ...
        'failed_utc',utcNow(),'Plant_calls',1,'error_identifier',char(ME.identifier), ...
        'error_message',char(ME.message),'first_plant_step_marker_created',isfile(firstPlantPath), ...
        'release_sha256',identity.release_sha256,'source_lock_sha256',identity.source_lock_sha256, ...
        'prior_no_plant_preflight_sha256',identity.prior_no_plant_preflight_sha256, ...
        'VAL_data_read',false,'TEST_read',false,'inertia_reconstruction_enabled',false);
    write_json_new(fullfile(attemptDir,'run_status.json'),failure);
    rethrow(ME);
end
end

function write_json_new(path,x)
assert(~isfile(path),'TRAINPair:NoOverwrite','Refusing to overwrite %s.',path);
write_json_overwrite(path,x);
end
function write_json_overwrite(path,x)
fid=fopen(path,'w');assert(fid>=0,'TRAINPair:Write','Cannot write %s.',path);
cleanup=onCleanup(@()fclose(fid));fwrite(fid,[jsonencode(x,'PrettyPrint',true) newline],'char');clear cleanup;
end
function h=sha256_file(path)
fid=fopen(path,'rb');assert(fid>=0,'TRAINPair:Read','Cannot open %s.',path);
cleanup=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear cleanup;
end
function s=utcNow()
s=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z'''));
end
function v=conditional(c,a,b)
if c,v=a;else,v=b;end
end
