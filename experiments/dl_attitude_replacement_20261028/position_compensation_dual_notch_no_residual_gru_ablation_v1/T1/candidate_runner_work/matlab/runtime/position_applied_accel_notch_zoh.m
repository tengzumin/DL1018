function [state,y] = position_applied_accel_notch_zoh(state,x,b,a)
% One causal three-axis IIR-notch event; caller holds y between 100-Hz events.
assert(isnumeric(state)&&isreal(state)&&isequal(size(state),[3,4])&&all(isfinite(state(:)))&& ...
    isnumeric(x)&&isreal(x)&&isequal(size(x),[3,1])&&all(isfinite(x(:)))&& ...
    isnumeric(b)&&isreal(b)&&isequal(size(b),[1,3])&&all(isfinite(b(:)))&& ...
    isnumeric(a)&&isreal(a)&&isequal(size(a),[1,3])&&all(isfinite(a(:)))&&abs(a(1)-1)<1e-12, ...
    'PositionNotch:BadState','Expected finite 3x4 state, 3x1 input, and normalized 1x3 coefficients.');
x=double(x);b=double(b);a=double(a);
y=b(1)*x+b(2)*state(:,1)+b(3)*state(:,2)-a(2)*state(:,3)-a(3)*state(:,4);
state=[x,state(:,1),y,state(:,3)];
assert(all(isfinite([state(:);y(:)])),'PositionNotch:Nonfinite','Notch state or output became nonfinite.');
end
