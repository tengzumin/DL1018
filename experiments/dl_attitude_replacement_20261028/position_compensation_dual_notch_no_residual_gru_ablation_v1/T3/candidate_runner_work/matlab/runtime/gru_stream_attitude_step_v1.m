function [memory,out]=gru_stream_attitude_step_v1(action,memory,in,model)
% Frozen GRU_STREAM residual with one current event and scene-local hidden carry.
switch lower(char(action))
    case 'init'
        assert(isstruct(model)&&all(isfield(model,{'input_mean','input_std'}))&& ...
            numel(model.input_mean)==13&&numel(model.input_std)==13&& ...
            all(isfinite(double(model.input_mean(:))))&& ...
            all(isfinite(double(model.input_std(:))))&&all(double(model.input_std(:))>0), ...
            'DLGRUStream:Normalizer','GRU_STREAM normalizer is invalid.');
        gru_stream_attitude_forward_v1(zeros(13,1),zeros(32,1),model);
        memory=struct('hidden',zeros(32,1),'event_count',0);
        out=struct('initialized',true,'hidden_state',memory.hidden);
    case 'step'
        required={'feature','J0','beta','dmax'};
        assert(isstruct(in)&&all(isfield(in,required)), ...
            'DLGRUStream:StepInput','Missing GRU_STREAM step input fields.');
        feature=double(in.feature(:));J0=double(in.J0);
        beta=double(in.beta);dmax=double(in.dmax(:));
        assert(numel(feature)==13&&all(isfinite(feature))&&isequal(size(J0),[3,3])&& ...
            all(isfinite(J0),'all')&&numel(dmax)==3&&all(isfinite(dmax))&&all(dmax>0)&& ...
            isscalar(beta)&&isfinite(beta)&&beta>=0&&beta<=1, ...
            'DLGRUStream:StepShape','Invalid feature, fixed J0, event beta, or dmax.');
        assert(isstruct(model)&&all(isfield(model,{'input_mean','input_std'}))&& ...
            numel(model.input_mean)==13&&numel(model.input_std)==13&& ...
            all(isfinite(double(model.input_mean(:))))&& ...
            all(isfinite(double(model.input_std(:))))&&all(double(model.input_std(:))>0), ...
            'DLGRUStream:Normalizer','GRU_STREAM normalizer is invalid.');
        assert(isstruct(memory)&&isfield(memory,'hidden')&& ...
            numel(memory.hidden)==32&&all(isfinite(double(memory.hidden(:))))&& ...
            isfield(memory,'event_count')&&isscalar(memory.event_count)&& ...
            isfinite(double(memory.event_count))&&memory.event_count>=0, ...
            'DLGRUStream:Memory','GRU_STREAM carried hidden state is invalid.');
        featureNormalized=(feature-double(model.input_mean(:)))./double(model.input_std(:));
        hiddenBefore=double(memory.hidden(:));
        [rawResidual,hiddenAfter]=gru_stream_attitude_forward_v1( ...
            featureNormalized,hiddenBefore,model);
        clippedResidual=min(max(rawResidual,-dmax),dmax);
        betaScaledResidual=beta.*clippedResidual;
        estimateTorque=J0*betaScaledResidual;
        memory.hidden=hiddenAfter;
        memory.event_count=double(memory.event_count)+1;
        out=struct('feature_normalized',featureNormalized, ...
            'raw_residual_rad_s2',rawResidual,'clipped_residual_rad_s2',clippedResidual, ...
            'beta_scaled_residual_rad_s2',betaScaledResidual, ...
            'estimateTorque_Nm',estimateTorque,'hidden_before',hiddenBefore, ...
            'hidden_after',hiddenAfter,'event_count',memory.event_count);
    otherwise
        error('DLGRUStream:Action','Unknown action %s.',char(action));
end
end
