function [optsPcfOff, audit] = build_round2_pcf_off_options(cfg, model)
% Same online FEATURE Head baseline; the sole intervention disables PCF coordination.
arguments
    cfg (1,1) struct
    model (1,1) struct
end
assert(strcmp(char(model.model_id), 'DSSM14') && ...
    strcmp(char(model.architecture), 'DSSM') && double(model.seed) == 2026102001 && ...
    double(model.selected_step) == 60000 && double(model.input_dim) == 14 && ...
    double(model.window) == 32 && double(model.context_length) == 32, ...
    'ROUND2:ModelIdentity', 'Unexpected model package identity.');
W0 = double(model.output_W);
assert(isequal(size(W0), [33,3]) && strcmpi(hash_bytes(typecast(W0(:),'uint8')), ...
    '88f8c4f2495438c3797655c48bab1bf0c11ac2e27bff1f5f2a7423a8f0a2cf53'), ...
    'ROUND2:W0Identity', 'W0 shape or array identity changed.');
normalizerIdentity = hash_normalizer_arrays(model);
assert(strcmpi(normalizerIdentity, ...
    '533aad9a2c66874cfa67f5d268661835e81e58b797cba7d6fc1c12d4013de5f0'), ...
    'ROUND2:NormalizerIdentity', 'Loaded normalizer-array identity changed.');

optsPcfOn = position_only_search_options(cfg, model, 'FEATURE', 12, 1);
optsPcfOff = optsPcfOn;
optsPcfOff.stage1_position_runtime.command_filter_coordination_v3_5.enabled = false;
expected = optsPcfOn;
expected.stage1_position_runtime.command_filter_coordination_v3_5.enabled = false;
assert(isequaln(optsPcfOff, expected), 'ROUND2:SingleFactor', ...
    'PCF-off options differ from PCF-on outside command_filter_coordination_v3_5.enabled.');
p = optsPcfOff.stage1_position_runtime;
h = p.position_only_search_head;
assert(logical(p.enabled) && logical(p.update_enabled) && logical(h.enabled) && ...
    strcmpi(char(h.head_type),'FEATURE') && double(h.gamma)==12 && double(h.kappa)==1 && ...
    double(p.beta_scale)==1 && isequal(double(p.weight),W0) && isequal(double(h.W0),W0), ...
    'ROUND2:HeadContract', 'Head/update/W0/gamma/kappa/beta changed.');
assert(~logical(p.command_filter_coordination_v3_5.enabled), ...
    'ROUND2:PCFStillEnabled', 'The only option difference must disable PCF coordination.');
fusionEnabled = isfield(optsPcfOff,'attitude_fusion_v3_6') && ...
    isstruct(optsPcfOff.attitude_fusion_v3_6) && logical(optsPcfOff.attitude_fusion_v3_6.enabled);
assert(~fusionEnabled, 'ROUND2:FusionContract', ...
    'P_A options must leave V3.6 attitude fusion disabled for the PCF-off branch.');
assert(logical(optsPcfOff.formal_rbf_baseline) && logical(optsPcfOff.rbf_attitude_enabled) && ...
    logical(optsPcfOff.rbf_attitude_output_enabled) && logical(optsPcfOff.rbf_attitude_update_enabled), ...
    'ROUND2:AttitudeControl', 'C0/J0/B attitude control changed.');
assert(abs(double(cfg.plant.dt)-0.001)<=1e-12 && ...
    double(cfg.rbf.runtime.position_update_hz)==100, ...
    'ROUND2:Clocks', 'Expected 1-kHz Plant and 100-Hz position event clock.');
audit = struct('experimental_difference', ...
    'opts.stage1_position_runtime.command_filter_coordination_v3_5.enabled', ...
    'pcf_enabled', false, 'update_enabled', true, 'head_enabled', true, ...
    'head_type', 'FEATURE', 'gamma', 12, 'kappa', 1, 'beta_scale', 1, ...
    'attitude_fusion_enabled', false, ...
    'normalizer_identity_sha256', normalizerIdentity, ...
    'W0_output_W_sha256', hash_bytes(typecast(W0(:),'uint8')));
end
function h = hash_normalizer_arrays(model)
md = java.security.MessageDigest.getInstance('SHA-256');
for name = {'input_mu','input_sigma'}
    field = name{1}; a = reshape(double(model.(field)),1,[]);
    assert(numel(a)==14,'ROUND2:NormalizerShape','Expected fourteen %s values.',field);
    header = [field char(0) '((1, 14), ''float64'')' char(0)];
    md.update(typecast(uint8(unicode2native(header,'UTF-8')),'int8'));
    md.update(typecast(a(:),'int8'));
end
h = lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
function h = hash_bytes(bytes)
md=java.security.MessageDigest.getInstance('SHA-256');
md.update(typecast(uint8(bytes(:)),'int8'));
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end

