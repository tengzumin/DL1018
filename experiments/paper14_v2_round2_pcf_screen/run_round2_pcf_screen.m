function verify_locked_file(path, expectedHash, label)
path = char(path);
assert(isfile(path), 'ROUND2:LockedFileMissing', 'Missing locked %s: %s.', label, path);
actualHash = sha256_file_local(path);
assert(strcmpi(actualHash, char(expectedHash)), ...
    'ROUND2:LockedFileHash', 'SHA256 mismatch for locked %s: %s.', label, path);
end

function identity = file_identity(path)
path = char(path);
before = dir(path);
assert(numel(before) == 1 && ~before.isdir, ...
    'ROUND2:RawFileMissing', 'Expected a single raw file: %s.', path);
digest = sha256_file_local(path);
after = dir(path);
assert(numel(after) == 1 && ~after.isdir && before.bytes == after.bytes && ...
    before.datenum == after.datenum, ...
    'ROUND2:RawChangedDuringHash', 'Raw size/mtime changed while hashing: %s.', path);
identity = struct('bytes', double(after.bytes), 'mtime', double(after.datenum), ...
    'sha256', digest);
end

function identity = verify_runtime_chain(files)
identity = repmat(struct('path', '', 'sha256', ''), numel(files), 1);
for k = 1:numel(files)
    path = char(files(k).path);
    [~, name, ext] = fileparts(path);
    if strcmpi(ext, '.m')
        activePath = which(name);
        assert(~isempty(activePath) && strcmpi(char(java.io.File(activePath).getCanonicalPath()), ...
            char(java.io.File(path).getCanonicalPath())), ...
            'ROUND2:RuntimeSourcePath', 'Active runtime/helper path differs for %s.', name);
    end
    actualHash = sha256_file_local(path);
    assert(strcmpi(actualHash, char(files(k).sha256)), ...
        'ROUND2:RuntimeSourceHash', 'Runtime source SHA256 changed: %s.', path);
    identity(k) = struct('path', path, 'sha256', actualHash);
end
end

function total = directory_bytes(path)
total = 0;
if ~isfolder(path), return; end
files = dir(fullfile(path, '**', '*'));
for k = 1:numel(files)
    if ~files(k).isdir, total = total + double(files(k).bytes); end
end
end

function write_text(path, text)
fid = fopen(path, 'w', 'n', 'UTF-8');
assert(fid >= 0, 'ROUND2:Write', 'Cannot write %s.', path);
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fwrite(fid, text, 'char');
end

function h = sha256_file_local(path)
md = java.security.MessageDigest.getInstance('SHA-256');
fid = fopen(path, 'r');
assert(fid >= 0, 'ROUND2:HashRead', 'Cannot read %s.', path);
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
while true
    block = fread(fid, 1024 * 1024, '*uint8');
    if isempty(block), break; end
    md.update(typecast(block(:), 'int8'));
end
h = lower(reshape(dec2hex(typecast(md.digest(), 'uint8'), 2).', 1, []));
end





