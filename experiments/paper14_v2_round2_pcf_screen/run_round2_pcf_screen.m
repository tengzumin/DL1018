function run_round2_pcf_screen(mode)
% FUTURE RUN ENTRY. Parent model review is required before any launch.
if nargin < 1, mode = 'PROBE'; end
mode = upper(char(mode));
assert(ismember(mode, {'PROBE','CONTINUE'}), 'ROUND2:Mode', 'Mode must be PROBE or CONTINUE.');
here = fileparts(mfilename('fullpath'));
repoRoot = fileparts(fileparts(here));
lockPath = fullfile(here, 'frozen_inputs.json');
lock = jsondecode(fileread(lockPath));
assert(strcmp(lock.schema,'ROUND2_PCF_SCREEN_INPUTS_V1') && ...
    strcmpi(char(java.io.File(lock.experiment_dir).getCanonicalPath()),char(java.io.File(here).getCanonicalPath())), ...
    'ROUND2:LockSchemaOrRoot','Round 2 lock schema or isolated output root changed.');
globalDeadline = datetime(lock.safety.global_deadline_utc, 'InputFormat', ...
    'yyyy-MM-dd''T''HH:mm:ss''Z''', 'TimeZone', 'UTC');
assert(globalDeadline == datetime('2026-10-24T17:01:00Z', ...
    'InputFormat', 'yyyy-MM-dd''T''HH:mm:ss''Z''', 'TimeZone', 'UTC') && ...
    datetime('now', 'TimeZone', 'UTC') < globalDeadline, ...
    'ROUND2:GlobalDeadline', 'Global hard deadline changed or has passed.');
preflightPath = fullfile(here, 'reports', 'preflight_round2.json');
assert(isfile(preflightPath), 'ROUND2:PreflightMissing', 'Run the PowerShell preflight first.');
pf = jsondecode(fileread(preflightPath));
pfCreated = datetime(pf.created_utc, 'InputFormat', ...
    'yyyy-MM-dd''T''HH:mm:ss.SSSSSSS''Z''', 'TimeZone', 'UTC');
pfAge = datetime('now', 'TimeZone', 'UTC') - pfCreated;
assert(strcmp(pf.status, 'PASS') && strcmp(pf.mode, mode) && ...
    logical(pf.parent_reviewed_switch_present) && pf.matlab_process_count == 0 && ...
    pfAge >= seconds(0) && pfAge <= minutes(5), ...
    'ROUND2:PreflightBlocked', 'Fresh reviewed mode-specific preflight is not a PASS.');
assert(isfield(pf, 'frozen_inputs_sha256') && ...
    strcmpi(char(pf.frozen_inputs_sha256), sha256_file_local(lockPath)), ...
    'ROUND2:LockHash', 'Frozen input lock changed after preflight.');
frozenInputsSha256 = sha256_file_local(lockPath);
verify_locked_inputs(lock);
assert(strcmpi(frozenInputsSha256, sha256_file_local(lockPath)), ...
    'ROUND2:LockChanged', 'Frozen input lock changed during runner-side identity checks.');

expectedIds = string({lock.scenes.scene_id});
sceneListPath = lock.scene_list.path;
assert(strcmpi(sha256_file_local(sceneListPath), lock.scene_list.sha256), ...
    'ROUND2:SceneListHash', 'Frozen VAL scene-list SHA256 changed.');
sceneTable = readtable(sceneListPath, 'TextType', 'string', 'VariableNamingRule', 'preserve');
assert(height(sceneTable) == 12 && ...
    isequal(sceneTable.Properties.VariableNames, {'task','band','scene_id'}) && ...
    isequal(sceneTable.scene_id(:), expectedIds(:)) && ...
    all(startsWith(sceneTable.scene_id, "DL1018_VAL_")), ...
    'ROUND2:SceneList', 'Expected the exact ordered twelve frozen VAL IDs and CSV schema.');
assert(strcmpi(sha256_file_local(lock.scene_payload_identity.path), lock.scene_payload_identity.sha256), ...
    'ROUND2:SceneIdentityHash', 'Frozen ON/B scene-payload identity SHA256 changed.');
sceneEvidence = readtable(lock.scene_payload_identity.path, 'TextType', 'string', ...
    'VariableNamingRule', 'preserve');
assert(height(sceneEvidence) == 12 && isequal(sceneEvidence.scene_id(:), expectedIds(:)) && ...
    all(sceneEvidence.status == "IDENTICAL") && all(sceneEvidence.physical_field_count == 14) && ...
    all(sceneEvidence.time_samples == 20001) && all(sceneEvidence.max_abs_physical_scene_diff == 0), ...
    'ROUND2:ScenePayloadIdentity', 'ON/B payload identity must be 12/12 identical over 14 fields.');
rawManifest = readtable(lock.reuse_manifest.path, 'TextType', 'string', ...
    'VariableNamingRule', 'preserve');
assert(height(rawManifest) == 24 && all(rawManifest.split == "VAL"), ...
    'ROUND2:ReuseManifest', 'Expected exactly the 12 paired ON/B VAL raws.');

runsRoot = fullfile(here, 'runs');
if strcmp(mode, 'PROBE')
    if isfolder(runsRoot)
        entries = dir(fullfile(runsRoot, '*'));
        entries = entries(~ismember({entries.name}, {'.','..'}));
        assert(isempty(entries), 'ROUND2:NoRetry', ...
            'PROBE refuses existing attempts or partial output.');
    end
    sceneIndices = 1;
else
    sceneIndices = 2:12;
    probeId = char(expectedIds(1));
    probeDir = fullfile(runsRoot, probeId, 'attempt_01');
    statusPath = fullfile(probeDir, 'run_status.json');
    probeSummaryPath = fullfile(here, 'reports', 'probe_round2.json');
    assert(isfile(statusPath) && isfile(probeSummaryPath), ...
        'ROUND2:ProbeRequired', 'CONTINUE requires a complete successful first-scene probe.');
    probeItems = dir(fullfile(probeDir, '*'));
    probeItems = probeItems(~ismember({probeItems.name}, {'.','..'}));
    expectedProbeFiles = sort({'attempt_started.marker','raw_run.mat','run_start.mat','run_status.json'});
    assert(isequal(sort({probeItems.name}), expectedProbeFiles), ...
        'ROUND2:ProbeArtifacts', 'CONTINUE requires exactly the first probe marker/raw/run_start/status.');
    probeStatus = jsondecode(fileread(statusPath));
    probeSummary = jsondecode(fileread(probeSummaryPath));
    assert(strcmp(probeStatus.scene_id, probeId) && strcmp(probeStatus.status, 'STABLE') && ...
        probeStatus.last_transition == 20000 && probeStatus.update_enabled && ...
        probeStatus.head_enabled && ~probeStatus.pcf_enabled && ...
        probeStatus.update_event_count > 0 && probeStatus.max_abs_event_weight_delta_unitless > lock.run.weight_delta_threshold_unitless && ...
        strcmpi(probeStatus.model_mat_sha256, lock.model.mat_sha256) && ...
        strcmpi(probeStatus.model_binding_sha256, lock.model_binding.sha256) && ...
        strcmpi(probeStatus.normalizer_npz_sha256, lock.normalizer.npz_file_sha256) && ...
        strcmpi(probeStatus.normalizer_arrays_identity_sha256, lock.normalizer.actual_runner_arrays_identity_sha256) && ...
        strcmpi(probeStatus.W0_output_W_sha256, lock.model.w0_output_W_double_f_order_sha256) && ...
        strcmpi(probeStatus.scene_payload_identity_csv_sha256, lock.scene_payload_identity.sha256) && ...
        strcmpi(sha256_file_local(fullfile(probeDir, 'run_start.mat')), probeStatus.run_start_sha256) && ...
        probeStatus.max_abs_eta_before_mps <= lock.run.signal_tolerance_mps && ...
        probeStatus.max_abs_eta_after_mps <= lock.run.signal_tolerance_mps && ...
        probeStatus.max_abs_surface_clip_error_mps <= lock.run.signal_tolerance_mps && ...
        strcmp(probeSummary.status, 'PROBE_COMPLETE') && strcmp(probeSummary.scene_id, probeId) && ...
        probeSummary.episode_runtime_seconds > 0 && ...
        probeSummary.attempt_execution_and_raw_persistence_seconds > 0 && probeSummary.attempt_output_bytes > 0 && ...
        strcmpi(sha256_file_local(fullfile(probeDir, 'raw_run.mat')), probeStatus.raw_sha256), ...
        'ROUND2:ProbeInvalid', 'First-scene probe evidence is incomplete or invalid.');
    probeStarted = datetime(probeSummary.probe_started_utc, 'InputFormat', ...
        'yyyy-MM-dd''T''HH:mm:ss.SSS''Z''', 'TimeZone', 'UTC');
    projectedSeconds = ceil(max(double(lock.safety.estimated_runtime_per_attempt_seconds), ...
        double(probeSummary.attempt_execution_and_raw_persistence_seconds)) * 11 * 1.25);
    projectedBytes = ceil(max(double(lock.safety.estimated_bytes_per_attempt), ...
        double(probeSummary.attempt_output_bytes)) * 1.25 * 11);
    nowUtc = datetime('now','TimeZone','UTC');
    assert(probeStarted <= nowUtc && nowUtc + seconds(projectedSeconds) <= globalDeadline, ...
        'ROUND2:Deadline', 'Projected remaining runtime exceeds the fixed global deadline.');
    assert(directory_bytes(runsRoot) + projectedBytes <= lock.safety.max_cycle_output_bytes && ...
        double(java.io.File(repoRoot).getUsableSpace()) - projectedBytes >= lock.safety.minimum_free_bytes, ...
        'ROUND2:OutputBudget', 'Projected remaining output violates the 80 GB cap or 30 GB floor.');
    for k = sceneIndices
        assert(~isfolder(fullfile(runsRoot, char(expectedIds(k)), 'attempt_01')), ...
            'ROUND2:NoRetry', 'CONTINUE refuses an existing/partial attempt for %s.', expectedIds(k));
    end
end

restoredefaultpath;
initRuntimeIndex = find(endsWith(string({lock.runtimeFiles.path}), ...
    string(filesep) + "init_dl1018.m"), 1, 'first');
assert(~isempty(initRuntimeIndex), ...
    'ROUND2:RuntimeInitLock', 'Locked runtimeFiles must include init_dl1018.m.');
initRuntimeDir = fileparts(lock.runtimeFiles(initRuntimeIndex).path);
assert(isfile(fullfile(initRuntimeDir, 'init_dl1018.m')), ...
    'ROUND2:RuntimeInitMissing', 'Locked runtime directory must contain init_dl1018.m.');
addpath(initRuntimeDir, '-begin');
[cfg, ~, resolvedRoot] = init_dl1018();
assert(strcmpi(char(java.io.File(resolvedRoot).getCanonicalPath()), ...
    char(java.io.File(repoRoot).getCanonicalPath())), ...
    'ROUND2:ProjectRoot', 'Project initializer resolved another repository.');
coreDir = fullfile(repoRoot, 'matlab', 'core');
addpath(here, '-begin');
addpath(coreDir, '-begin');
lockedRuntimeDir = fileparts(lock.runtimeFiles(1).path);
addpath(lockedRuntimeDir, '-begin');
clear run_dl1018_closed_loop run_episode_dl1018 position_stage1_model_forward_v2 ...
    position_only_search_head_step position_only_search_options rk4_vehicle_step ...
    vehicle_derivative allocate_control position_bs_step baseline_force_to_attitude ...
    command_filter_step morphology_aware_wind_load simulation_parameters ...
    arm_mass_properties allocation_matrix
rehash;
plantSourceIdentity = verify_source_chain(lock.plantFiles);
runtimeSourceIdentity = verify_runtime_chain(lock.runtimeFiles);
assert(strcmpi(which('run_dl1018_closed_loop'), fullfile(lockedRuntimeDir, 'run_dl1018_closed_loop.m')) && ...
    strcmpi(which('run_episode_dl1018'), fullfile(lockedRuntimeDir, 'run_episode_dl1018.m')) && ...
    strcmpi(which('position_only_search_options'), fullfile(lockedRuntimeDir, 'position_only_search_options.m')) && ...
    strcmpi(which('run_round2_pcf_screen'), fullfile(here, 'run_round2_pcf_screen.m')) && ...
    strcmpi(which('build_round2_pcf_off_options'), fullfile(here, 'build_round2_pcf_off_options.m')), ...
    'ROUND2:RuntimePath', 'The reviewed private runner/helper is not active.');

modelPack = load(lock.model.mat_path, 'model');
model = modelPack.model;
[optsPcfOff, optionAudit] = build_round2_pcf_off_options(cfg, model);
assert(abs(double(cfg.plant.dt) - lock.run.plant_dt_s) < 1e-12 && ...
    double(cfg.rbf.runtime.position_update_hz) == lock.run.position_event_hz, ...
    'ROUND2:Timing', 'Plant or position event clock changed.');

for i = sceneIndices
    sceneId = char(expectedIds(i));
    onRow = rawManifest(rawManifest.scene_id == string(sceneId) & rawManifest.role == "ON_CANDIDATE", :);
    bRow = rawManifest(rawManifest.scene_id == string(sceneId) & rawManifest.role == "B_BASELINE", :);
    assert(height(onRow) == 1 && height(bRow) == 1, ...
        'ROUND2:RawPair', 'Missing or duplicate ON/B identity for %s.', sceneId);
    evidenceRow = sceneEvidence(sceneEvidence.scene_id == string(sceneId), :);
    assert(height(evidenceRow) == 1 && strcmpi(char(evidenceRow.on_raw_sha256), char(onRow.raw_sha256)) && ...
        strcmpi(char(evidenceRow.b_raw_sha256), char(bRow.raw_sha256)), ...
        'ROUND2:SceneRawIdentity', 'Scene-payload identity file does not bind both raw hashes for %s.', sceneId);
    verify_locked_file(char(onRow.raw_path), char(onRow.raw_sha256), ...
        sprintf('candidate raw for %s', sceneId));
    bIdentityBeforeLoad = file_identity(char(bRow.raw_path));
    assert(strcmpi(bIdentityBeforeLoad.sha256, char(bRow.raw_sha256)), ...
        'ROUND2:PairRawHash', 'Frozen B raw hash changed before load for %s.', sceneId);
    b = load(char(bRow.raw_path), 'scene');
    bIdentityAfterLoad = file_identity(char(bRow.raw_path));
    assert(bIdentityAfterLoad.bytes == bIdentityBeforeLoad.bytes && ...
        bIdentityAfterLoad.mtime == bIdentityBeforeLoad.mtime && ...
        strcmpi(bIdentityAfterLoad.sha256, char(bRow.raw_sha256)), ...
        'ROUND2:RawChangedDuringLoad', ...
        'B raw size/mtime/SHA changed while loading scene for %s.', sceneId);
    assert(isfield(b, 'scene') && isstruct(b.scene) && isfield(b.scene, 'time') && ...
        numel(b.scene.time) == 20001 && abs(double(b.scene.time(1))) <= 1e-12 && ...
        abs(double(b.scene.time(end)) - 20) <= 1e-12 && ...
        isfield(b.scene, 'reference') && isfield(b.scene.reference, 'position') && ...
        numel(b.scene.reference.position) == 3 * 20001 && ...
        any(size(b.scene.reference.position) == 3) && any(size(b.scene.reference.position) == 20001), ...
        'ROUND2:ScenePayload', 'B raw does not contain the complete 20,001-point VAL scene for %s.', sceneId);
    scene = b.scene;
    assert(strcmp(char(scene.scene_id), sceneId) || strcmp(char(scene.scene_id), [sceneId '_ACC_FIX_V1']), ...
        'ROUND2:SceneIdentity', 'B scene identity does not match frozen VAL ID %s.', sceneId);
    scene.scene_id = sceneId; % Metadata alias only; payload arrays remain unchanged.
    inputIdentity = struct('scene_id', sceneId, ...
        'frozen_inputs_path', lockPath, 'frozen_inputs_sha256', frozenInputsSha256, ...
        'on_raw_path', char(onRow.raw_path), 'on_raw_sha256', char(onRow.raw_sha256), ...
        'b_raw_path', char(bRow.raw_path), 'b_raw_sha256', char(bRow.raw_sha256), ...
        'scene_payload_identity_csv_path', char(lock.scene_payload_identity.path), ...
        'scene_payload_identity_csv_sha256', char(lock.scene_payload_identity.sha256), ...
        'model_mat_sha256', char(lock.model.mat_sha256), ...
        'model_binding_sha256', char(lock.model_binding.sha256), ...
        'normalizer_npz_sha256', char(lock.normalizer.npz_file_sha256), ...
        'normalizer_report_sha256', char(lock.normalizer.train_only_report_sha256), ...
        'normalizer_arrays_identity_sha256', optionAudit.normalizer_identity_sha256, ...
        'W0_output_W_sha256', optionAudit.W0_output_W_sha256, ...
        'head_type', char(optionAudit.head_type), ...
        'update_enabled', logical(optsPcfOff.stage1_position_runtime.update_enabled), ...
        'position_only_search_head_enabled', logical(optsPcfOff.stage1_position_runtime.position_only_search_head.enabled), ...
        'pcf_enabled', logical(optsPcfOff.stage1_position_runtime.command_filter_coordination_v3_5.enabled), ...
        'on_scene_payload_sha256_excluding_scene_id', char(evidenceRow.on_scene_payload_sha256_excluding_scene_id), ...
        'b_scene_payload_sha256_excluding_scene_id', char(evidenceRow.b_scene_payload_sha256_excluding_scene_id), ...
        'physical_field_count', double(evidenceRow.physical_field_count), ...
        'time_samples', double(evidenceRow.time_samples), ...
        'max_abs_physical_scene_diff', double(evidenceRow.max_abs_physical_scene_diff));
    inputIdentity.plant_source_identity = plantSourceIdentity;
    inputIdentity.runtime_source_identity = runtimeSourceIdentity;

    cycleBytesBefore = directory_bytes(runsRoot);
    freeBytes = double(java.io.File(repoRoot).getUsableSpace());
    remainingCount = 13 - i;
    plannedBytes = double(lock.safety.estimated_bytes_per_attempt) * remainingCount;
    assert(cycleBytesBefore + plannedBytes <= double(lock.safety.max_cycle_output_bytes) && ...
        freeBytes - plannedBytes >= double(lock.safety.minimum_free_bytes), ...
        'ROUND2:OutputBudget', 'Output cap or 30 GB post-run free-space floor would be exceeded.');
    attemptDir = fullfile(runsRoot, sceneId, 'attempt_01');
    assert(~isfolder(attemptDir), 'ROUND2:NoRetry', ...
        'Attempt already exists for %s; automatic retry is forbidden.', sceneId);
    mkdir(attemptDir);
    marker = fullfile(attemptDir, 'attempt_started.marker');
    write_text(marker, [char(datetime('now', 'TimeZone', 'UTC', ...
        'Format', 'yyyy-MM-dd''T''HH:mm:ss.SSS''Z''')) newline]);
    runStartPath = fullfile(attemptDir, 'run_start.mat');
    rawPath = fullfile(attemptDir, 'raw_run.mat');
    statusPath = fullfile(attemptDir, 'run_status.json');
    startedAt = datetime('now', 'TimeZone', 'UTC', ...
        'Format', 'yyyy-MM-dd''T''HH:mm:ss.SSS''Z''');
    method = 'ROUND2_PCF_OFF';
    weightDeltaThreshold = double(lock.run.weight_delta_threshold_unitless);
    signalToleranceMps = double(lock.run.signal_tolerance_mps);
    try
        % run_start is provenance only: scene ID and input identity, never the frozen scene payload/options/model.
        attemptExecutionTimer = tic;
        save(runStartPath, 'sceneId', 'inputIdentity', '-v7.3');
        timerStart = tic;
        log = run_episode_dl1018(scene, method, cfg, optsPcfOff); % Omit rawPath: locked wrapper would embed scene.
        episodeRuntimeSeconds = toc(timerStart);
        % R2 raw contains new run output and identity only; the complete frozen scene is not copied.
        runIdentity = struct('scene_id', sceneId, 'method', method, 'mode', mode, ...
            'frozen_inputs_sha256', frozenInputsSha256);
        runIdentity.input_identity = inputIdentity;
        save(rawPath, 'log', 'method', 'runIdentity', '-v7.3');
        attemptExecutionAndRawPersistenceSeconds = toc(attemptExecutionTimer);
    before = double(log.stage1_position_event_weight_before_33x3);
    after = double(log.stage1_position_event_weight_after_33x3);
    eventDelta = max(abs(after(:) - before(:)));
    updateExecuted = logical(log.position_head_update_executed(:));
    etaBefore = double(log.stage1_position_pcf_eta_before_mps);
    etaAfter = double(log.stage1_position_pcf_eta_after_mps);
    etaMax = max([abs(etaBefore(:)); abs(etaAfter(:)); 0]);
    sCoord = double(log.stage1_position_pcf_event_s_coord_mps);
    sCoordEff = double(log.stage1_position_pcf_event_s_coord_eff_mps);
    clippedSurface = max(min(sCoord, [7 8 10]), -[7 8 10]);
    surfaceClipError = max(abs(sCoordEff(:) - clippedSurface(:)));
    assert(strcmp(char(log.scene_id), sceneId) && strcmp(char(log.status), 'STABLE') && ...
        double(log.last_transition) == 20000 && logical(log.stage1_position_update_enabled) && ...
        logical(log.stage1_position_search_head_enabled) && ...
        ~logical(log.stage1_position_pcf_coordination_enabled) && any(updateExecuted) && ...
        eventDelta > weightDeltaThreshold && etaMax <= signalToleranceMps && ...
        surfaceClipError <= signalToleranceMps, ...
        'ROUND2:RunInvariant', 'PCF-off, online Head update, eta=0, clipping, or safety invariant failed for %s.', sceneId);
    result = struct('scene_id', sceneId, 'status', char(log.status), ...
        'last_transition', double(log.last_transition), 'update_enabled', true, ...
        'frozen_inputs_sha256', frozenInputsSha256, ...
        'head_enabled', true, 'head_type', char(optionAudit.head_type), ...
        'pcf_enabled', false, ...
        'model_mat_sha256', char(lock.model.mat_sha256), ...
        'model_binding_sha256', char(lock.model_binding.sha256), ...
        'normalizer_npz_sha256', char(lock.normalizer.npz_file_sha256), ...
        'normalizer_report_sha256', char(lock.normalizer.train_only_report_sha256), ...
        'normalizer_arrays_identity_sha256', optionAudit.normalizer_identity_sha256, ...
        'W0_output_W_sha256', optionAudit.W0_output_W_sha256, ...
        'scene_payload_identity_csv_sha256', char(lock.scene_payload_identity.sha256), ...
        'on_raw_sha256', char(onRow.raw_sha256), 'b_raw_sha256', char(bRow.raw_sha256), ...
        'update_event_count', sum(updateExecuted), ...
        'max_abs_event_weight_delta_unitless', eventDelta, ...
        'weight_delta_threshold_unitless', weightDeltaThreshold, ...
        'max_abs_eta_before_mps', max(abs(etaBefore(:))), 'max_abs_eta_after_mps', max(abs(etaAfter(:))), ...
        'max_abs_surface_clip_error_mps', surfaceClipError, ...
        'run_start_sha256', sha256_file_local(runStartPath), ...
        'raw_sha256', sha256_file_local(rawPath), ...
        'episode_runtime_seconds', episodeRuntimeSeconds, ...
        'attempt_execution_and_raw_persistence_seconds', attemptExecutionAndRawPersistenceSeconds, ...
        'probe_started_utc', char(startedAt));
    result.input_identity = inputIdentity;
    result.plant_source_sha256 = {plantSourceIdentity.sha256};
    result.runtime_source_sha256 = {runtimeSourceIdentity.sha256};
    result.plant_source_identity = plantSourceIdentity;
    result.runtime_source_identity = runtimeSourceIdentity;
    % run_status is the compact, directly inspectable identity/safety summary for this attempt.
    write_text(statusPath, jsonencode(result));
    cycleBytesAfter = directory_bytes(runsRoot);
    assert(cycleBytesAfter <= double(lock.safety.max_cycle_output_bytes) && ...
        double(java.io.File(repoRoot).getUsableSpace()) >= lock.safety.minimum_free_bytes, ...
        'ROUND2:OutputCap', 'The 80 GB output cap was exceeded; stopping without deleting evidence.');
    result.cycle_output_bytes = cycleBytesAfter;
    if strcmp(mode, 'PROBE')
        result.status = 'PROBE_COMPLETE';
        result.attempt_output_bytes = directory_bytes(attemptDir);
        write_text(fullfile(here, 'reports', 'probe_round2.json'), jsonencode(result));
        fprintf('ROUND2_PCF_PROBE %s stable=%s episode_seconds=%.3f attempt_exec_raw_seconds=%.3f output_bytes=%d\n', ...
            sceneId, char(log.status), episodeRuntimeSeconds, attemptExecutionAndRawPersistenceSeconds, directory_bytes(attemptDir));
        return; % No automatic continuation after the timing probe.
    end
    fprintf('ROUND2_PCF_OFF %02d/12 %s stable=%s last_transition=%d max_dW=%.3g\n', ...
        i, sceneId, char(log.status), double(log.last_transition), eventDelta);
    catch ME
        % Preserve the marker and any partial run_start/raw; record one failure, then stop without retry.
        failure = struct('scene_id', sceneId, 'status', 'FAILED', ...
            'error_identifier', ME.identifier, 'error_message', ME.message, ...
            'failure_utc', char(datetime('now', 'TimeZone', 'UTC', ...
                'Format', 'yyyy-MM-dd''T''HH:mm:ss.SSS''Z''')), ...
            'attempt_started_marker_present', isfile(marker), ...
            'frozen_inputs_sha256', frozenInputsSha256, ...
            'model_mat_sha256', char(lock.model.mat_sha256), ...
            'model_binding_sha256', char(lock.model_binding.sha256), ...
            'normalizer_npz_sha256', char(lock.normalizer.npz_file_sha256), ...
            'normalizer_report_sha256', char(lock.normalizer.train_only_report_sha256), ...
            'normalizer_arrays_identity_sha256', optionAudit.normalizer_identity_sha256, ...
            'W0_output_W_sha256', optionAudit.W0_output_W_sha256, ...
            'head_enabled', true, 'head_type', char(optionAudit.head_type), ...
            'update_enabled', true, 'pcf_enabled', false, ...
            'scene_payload_identity_csv_sha256', char(lock.scene_payload_identity.sha256), ...
            'on_raw_sha256', char(onRow.raw_sha256), 'b_raw_sha256', char(bRow.raw_sha256));
        failure.input_identity = inputIdentity;
        failure.plant_source_identity = plantSourceIdentity;
        failure.runtime_source_identity = runtimeSourceIdentity;
        failure.plant_source_sha256 = {plantSourceIdentity.sha256};
        failure.runtime_source_sha256 = {runtimeSourceIdentity.sha256};
        if isfile(runStartPath), failure.run_start_sha256 = sha256_file_local(runStartPath); end
        if isfile(rawPath), failure.raw_sha256 = sha256_file_local(rawPath); end
        try
            write_text(statusPath, jsonencode(failure));
        catch statusError
            warning('ROUND2:FailureStatusWrite', 'Could not write failure status: %s', statusError.message);
        end
        rethrow(ME);
    end
end
end

function identity = verify_source_chain(files)
identity = repmat(struct('name', '', 'path', '', 'sha256', ''), numel(files), 1);
for k = 1:numel(files)
    expectedPath = char(files(k).path);
    activePath = which(char(files(k).name));
    assert(~isempty(activePath) && strcmpi(char(java.io.File(activePath).getCanonicalPath()), ...
        char(java.io.File(expectedPath).getCanonicalPath())), ...
        'ROUND2:PlantSourcePath', 'Active Plant source path differs for %s.', files(k).name);
    actualHash = sha256_file_local(expectedPath);
    assert(strcmpi(actualHash, char(files(k).sha256)), ...
