    same_path(lock.source_files.runner.path,fullfile(here,'run_b_traceable_dev72_v3.m'))&& ...
    same_path(lock.source_files.contract.path,contractPath), ...
    'BDEV72:EntryIdentity','Prepare, runner, or contract path differs from the lock.');
sourceFileNames=fieldnames(lock.source_files);
for k=1:numel(sourceFileNames), verify_ref(lock.source_files.(sourceFileNames{k})); end
upstreamNames=fieldnames(lock.upstream_refs);
for k=1:numel(upstreamNames), verify_ref(lock.upstream_refs.(upstreamNames{k})); end
assert(numel(lock.active_source_inventory)==32&&double(lock.source_counts.total)==32&& ...
    double(lock.source_counts.matlab)==31&&double(lock.source_counts.mat)==1&& ...
    numel(lock.scenes)==71, ...
    'BDEV72:Inventory','Expected 71 scenes and the exact 31-M plus 1-MAT B1 inventory.');
for k=1:numel(lock.active_source_inventory), verify_ref(lock.active_source_inventory(k)); end
assert(strcmpi(lock.new_scene_ids_sha256,contract.new_scene_ids_sha256)&& ...
    isequal(string(lock.new_scene_ids(:)),string(contract.new_scene_ids(:))), ...
    'BDEV72:SceneSet','Lock and contract scene sets differ.');
sceneIds=cellstr(string(lock.new_scene_ids));
assert(isequal(string(sceneIds(:)),string(sort(sceneIds(:))))&&numel(unique(sceneIds))==71&& ...
    ~any(strcmp(sceneIds,lock.completed_reference_scene_id)), ...
    'BDEV72:SceneOrder','New scene IDs must be the 71 sorted IDs excluding completed B1.');
assert(strcmp(contract.completed_reference_scene_id,'DL1018_VAL_T2_C00_W10')&& ...
    strcmp(contract.method,'B2-RBF-Full-SPLIT')&& ...
    strcmp(contract.collector_tag,'B_TRACEABLE_C3CORE_V1')&& ...
    ~logical(contract.TEST_accessed)&&double(contract.training_steps)==0&& ...
    double(contract.optimizer_steps)==0&&logical(contract.controller_options_reconstructed_per_scene), ...
    'BDEV72:Baseline','The fixed B2-RBF-Full-SPLIT baseline contract changed.');

% Bind the already reviewed B1 as the sole completed scene; never rerun it.
b1=lock.completed_reference;
b1Status=jsondecode(fileread(b1.run_status.path));
b1Exit=jsondecode(fileread(b1.os_exit.path));
b1Review=jsondecode(fileread(b1.parent_raw_root_review.path));
b1Body=jsondecode(fileread(b1.body_complete.path));
assert(strcmp(b1Status.status,'RUN_COMPLETE_RAW_PENDING_AUDIT')&& ...
    strcmp(b1Status.log_status,'STABLE')&&double(b1Status.plant_calls)==1&& ...
    double(b1Status.last_transition)==20000&&double(b1Status.state_samples)==20001&& ...
    strcmpi(b1Status.raw_sha256,b1.raw_sha256)&&logical(b1Body.body_completed)&& ...
    strcmpi(b1Body.raw_sha256,b1.raw_sha256)&&double(b1Exit.exit_code)==0&& ...
    strcmp(b1Review.status,b1.parent_raw_review_status)&& ...
    strcmp(b1Review.status,'PASS_TRACEABLE_B_REPRODUCES_ONE_HISTORICAL_SCENE_EXACTLY')&& ...
    double(b1Review.natural_matlab_OS_exit_code)==0&& ...
    b1Review.historical_72_runtime_tree_gap_closed==false, ...
    'BDEV72:B1Audit','Completed B1 run/status/root review no longer matches the frozen reference.');
assert(double(b1.full_numeric_array_groups)==33&& ...
    double(b1.full_numeric_arrays_max_abs_difference)==0&& ...
    double(b1PrepareReviewActiveCount(lock))==32, ...
    'BDEV72:B1Arrays','B1 must remain the independently audited complete-array reference.');
b1Lock=jsondecode(fileread(b1.input_lock.path));
assert(isequaln(lock.active_source_inventory,b1Lock.active_source_inventory), ...
    'BDEV72:B1Sources','New batch must use the exact B1 32-source inventory.');

c3Lock=jsondecode(fileread(lock.upstream_refs.c3_dev72_input_lock.path));
assert(strcmp(c3Lock.schema,'C3_DELAYED_PREDICTION_DEV72_INPUT_LOCK_V1')&& ...
    numel(c3Lock.scenes)==72&&numel(unique(string({c3Lock.scenes.scene_id})))==72, ...
    'BDEV72:C3Lock','Frozen C3 DEV72 lock is incomplete or changed.');
expectedFields={'initial_state','time','environment_wind_I','arms/command','arms/rho_true', ...
    'arms/rhoDot_true','arms/rho_hat','arms/rhoDot_hat','reference/acceleration', ...
    'reference/position','reference/velocity','reference/yaw','reference/yaw_acceleration','reference/yaw_rate'};
c3Ids=string({c3Lock.scenes.scene_id});
b1Pack=load(b1.cfg_opts_snapshot.path,'cfg','opts','sceneIdentity');
assert(isfield(b1Pack,'sceneIdentity')&&isstruct(b1Pack.sceneIdentity)&& ...
    ~isempty(b1Pack.sceneIdentity),'BDEV72:B1IdentitySchema', ...
    'Reviewed B1 snapshot must contain the complete sceneIdentity prototype.');
sceneIdentityPrototype=b1Pack.sceneIdentity(1);
sceneIdentities=repmat(sceneIdentityPrototype,1,numel(sceneIds));
for k=1:numel(sceneIds)
    sceneId=sceneIds{k}; row=lock.scenes(k);
    c3ix=find(c3Ids==string(sceneId));
    assert(numel(c3ix)==1&&strcmp(char(row.scene_id),sceneId), ...
        'BDEV72:SceneRow','Scene is missing, duplicated, or reordered in the C3 lock.');
    c3row=c3Lock.scenes(c3ix);
    fields=cellstr(string(row.scored_log.matching_fields(:)));
    c3Fields=cellstr(string(c3row.b_scene_to_scored_log.matching_fields(:)));
    assert(strcmp(row.candidate_action,char(c3row.candidate_action))&& ...
        same_path(row.B_source.path,c3row.B_source.path)&& ...
        strcmpi(row.B_source.sha256,c3row.B_source.sha256)&& ...
        same_path(row.scored_log.path,c3row.b_scene_to_scored_log.path)&& ...
        strcmpi(row.scored_log.sha256,c3row.b_scene_to_scored_log.sha256)&& ...
        same_path(row.B_source.path,row.scored_log.path)&& ...
        strcmpi(row.B_source.sha256,row.scored_log.sha256)&& ...
        strcmpi(row.external_identity_sha256,c3row.external_identity_sha256)&& ...
        isequal(fields(:),expectedFields(:))&& ...
        isequal(fields(:),c3Fields(:)), ...
        'BDEV72:ExternalBinding','B_source/scored-log/14-field identity differs for %s.',sceneId);
    verify_file(row.B_source.path,row.B_source.sha256);
    scenePack=load(row.B_source.path,'scene');
    assert(isfield(scenePack,'scene')&&valid_scene(scenePack.scene,sceneId), ...
        'BDEV72:SceneSchema','Locked B scene fails the complete C2 schema/time/alias contract: %s.',sceneId);
    rawId=char(scenePack.scene.scene_id);
    sceneIdentities(k)=sceneIdentityPrototype;
    sceneIdentities(k).scene_id=sceneId;
    sceneIdentities(k).raw_scene_id=rawId;
    sceneIdentities(k).canonical_scene_id=sceneId;
    sceneIdentities(k).alias_normalized_in_memory=~strcmp(rawId,sceneId);
    sceneIdentities(k).alias_rule='C2 valid_scene: canonical scene ID or canonical ID plus _ACC_FIX_V1';
    sceneIdentities(k).B_raw_path=char(row.B_source.path);
    sceneIdentities(k).B_raw_sha256=char(row.B_source.sha256);
    sceneIdentities(k).external_identity_sha256=char(row.external_identity_sha256);
    sceneIdentities(k).B_scored_log_path=char(row.scored_log.path);
    sceneIdentities(k).B_scored_log_sha256=char(row.scored_log.sha256);
    sceneIdentities(k).matching_fields=fields;
end

