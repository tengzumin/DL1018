add_active_paths(active); addpath(fullfile(repoRoot,'matlab','runtime'),'-end');
addpath(fullfile(repoRoot,'matlab','core'),'-end');
addpath(fileparts(initPath),'-begin'); addpath(fileparts(optionsPath),'-begin');
