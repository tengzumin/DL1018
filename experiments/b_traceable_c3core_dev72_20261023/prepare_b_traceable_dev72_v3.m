assert(strcmp(lock.schema,'B_TRACEABLE_C3CORE_DEV72_INPUT_LOCK_V3')&& ...
    strcmp(lock.state,'LOCKED_DEV72_WITH_B1_REUSED_NO_PLANT_PARENT_REVIEW_REQUIRED_V3')&& ...
    ~logical(lock.plant_authorized_by_this_lock)&& ...
    strcmp(contract.schema,'B_TRACEABLE_C3CORE_DEV72_CONTRACT_V3')&& ...
    strcmp(contract.state,'FIXED_71_REMAINING_SCENES_PARENT_RELEASE_REQUIRED_V3')&& ...
    double(contract.new_scene_count)==71&&double(contract.limits.max_new_Plant)==71&& ...
    double(lock.new_scene_count)==71&&double(lock.total_scene_count)==72&& ...
    double(contract.limits.max_output_bytes)==6442450944&& ...
    double(contract.limits.reserve_per_scene_bytes)==80000000&& ...
    double(contract.limits.minimum_free_bytes_after_reserve)==30000000000&& ...
    strcmp(contract.limits.hard_deadline_utc,'2026-10-24T17:01:00Z'), ...
    'BDEV72:Scope','Fixed 71-scene no-Plant contract or resource cap changed.');
