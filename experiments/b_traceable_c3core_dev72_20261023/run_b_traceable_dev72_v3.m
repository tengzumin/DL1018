function batchResult=run_b_traceable_dev72_v3(mode)
% Sequentially run the 71 release-authorized remaining B scenes; never retry.
if nargin~=1||~strcmpi(char(mode),'PARENT_APPROVED_B_TRACEABLE_DEV72_V3')
    error('BDEV72:Mode','Pass exactly PARENT_APPROVED_B_TRACEABLE_DEV72_V3 after parent review.');
end
here=fileparts(mfilename('fullpath')); repoRoot=fileparts(fileparts(here));
lockPath=fullfile(here,'B_TRACEABLE_DEV72_INPUT_LOCK_v3.json');
contractPath=fullfile(here,'B_TRACEABLE_DEV72_RUN_CONTRACT_v3.json');
releasePath=fullfile(here,'B_TRACEABLE_DEV72_RELEASE_v3.json');
preparePath=fullfile(here,'B_TRACEABLE_DEV72_PREPARE_RESULT_v3.json');
snapshotPath=fullfile(here,'B_TRACEABLE_DEV72_PREPARED_CFG_OPTS_v3.mat');
bodyPath=fullfile(here,'B_TRACEABLE_DEV72_BODY_COMPLETE_v3.json');
assert(all([isfile(lockPath),isfile(contractPath),isfile(releasePath), ...
    isfile(preparePath),isfile(snapshotPath)])&&~isfile(bodyPath), ...
    'BDEV72:ReleaseInputs','Parent release and complete no-Plant inputs are required.');
lock=jsondecode(fileread(lockPath)); contract=jsondecode(fileread(contractPath));
release=jsondecode(fileread(releasePath)); prep=jsondecode(fileread(preparePath));
lockSha=sha256_file(lockPath); contractSha=sha256_file(contractPath);
releaseSha=sha256_file(releasePath); prepareSha=sha256_file(preparePath);
snapshotSha=sha256_file(snapshotPath); runnerPath=[mfilename('fullpath') '.m'];
runnerSha=sha256_file(runnerPath);
runCommandSha=sha256_file(lock.source_files.run_command.path);
sceneIds=cellstr(string(lock.new_scene_ids));
assert(strcmp(release.schema,'B_TRACEABLE_C3CORE_DEV72_RELEASE_V3')&& ...
    strcmp(release.state,'APPROVED_B_TRACEABLE_DEV72_V3')&&logical(release.plant_authorized)&& ...
    double(release.max_new_Plant)==71&&strcmpi(release.input_lock_sha256,lockSha)&& ...
    strcmpi(release.contract_sha256,contractSha)&&strcmpi(release.prepare_result_sha256,prepareSha)&& ...
    strcmpi(release.cfg_opts_snapshot_sha256,snapshotSha)&&strcmpi(release.runner_sha256,runnerSha)&& ...
    strcmpi(release.run_command_sha256,runCommandSha)&& ...
    strcmpi(release.new_scene_ids_sha256,lock.new_scene_ids_sha256)&& ...
    strcmpi(release.B1_raw_sha256,lock.completed_reference.raw_sha256)&& ...
    strcmpi(release.B1_run_status_sha256,lock.completed_reference.run_status_sha256)&& ...
    strcmpi(release.B1_parent_raw_review_sha256,lock.completed_reference.parent_raw_review_sha256), ...
    'BDEV72:Release','Release does not bind this exact 71-scene batch and completed B1 reference.');
assert(strcmp(lock.state,'LOCKED_DEV72_WITH_B1_REUSED_NO_PLANT_PARENT_REVIEW_REQUIRED_V3')&& ...
    ~logical(lock.plant_authorized_by_this_lock)&& ...
    strcmp(prep.status,'PREPARED_NO_PLANT_WAIT_PARENT_RELEASE_V3')&& ...
    double(prep.new_scene_count)==71&&double(prep.plant_calls)==0&& ...
    ~logical(prep.run_episode_called)&&~logical(prep.plant_authorized)&& ...
    strcmpi(prep.input_lock_sha256,lockSha)&&strcmpi(prep.snapshot_sha256,snapshotSha)&& ...
    strcmpi(lock.source_files.runner.sha256,runnerSha)&& ...
    isequal(string(prep.new_scene_ids_sha256),string(lock.new_scene_ids_sha256)), ...
    'BDEV72:PreparedBinding','No-Plant prepare does not bind this batch.');
assert(numel(sceneIds)==71&&isequal(string(sceneIds(:)),string(sort(sceneIds(:))))&& ...
    ~any(strcmp(sceneIds,lock.completed_reference_scene_id)), ...
    'BDEV72:SceneSet','The locked 71-scene sequence is not canonical or includes B1.');
verify_ref(lock.source_files.prepare_entry); verify_ref(lock.source_files.runner);
verify_ref(lock.source_files.contract); verify_ref(lock.source_files.input_lock_builder);
verify_ref(lock.source_files.prepare_command); verify_ref(lock.source_files.run_command);
upstreamNames=fieldnames(lock.upstream_refs);
for k=1:numel(upstreamNames), verify_ref(lock.upstream_refs.(upstreamNames{k})); end
for k=1:numel(lock.active_source_inventory), verify_ref(lock.active_source_inventory(k)); end
b1=lock.completed_reference;
b1Status=jsondecode(fileread(b1.run_status.path));
b1Review=jsondecode(fileread(b1.parent_raw_root_review.path));
assert(strcmpi(sha256_file(b1.raw.path),b1.raw_sha256)&& ...
    strcmp(b1Status.status,'RUN_COMPLETE_RAW_PENDING_AUDIT')&& ...
    strcmp(b1Review.status,'PASS_TRACEABLE_B_REPRODUCES_ONE_HISTORICAL_SCENE_EXACTLY'), ...
    'BDEV72:B1Changed','The only completed reference B1 no longer matches its audit.');
verify_file(lock.shared_heavy_job_lock_path,lock.upstream_refs.shared_heavy_job_lock.sha256);
attemptRoot=fullfile(here,'runs_b');
assert(~isfolder(attemptRoot),'BDEV72:NoRetry','Batch output exists; refusing to retry or overwrite.');
deadline=datetime(char(contract.limits.hard_deadline_utc), ...
    'InputFormat',"yyyy-MM-dd'T'HH:mm:ss'Z'",'TimeZone','UTC');
reserveBytes=double(contract.limits.reserve_per_scene_bytes);
maxBytes=double(contract.limits.max_output_bytes);
minimumFree=double(contract.limits.minimum_free_bytes_after_reserve);
minimumSeconds=double(contract.limits.minimum_seconds_per_remaining_scene);
exitReserveSeconds=double(contract.limits.batch_exit_reserve_seconds);
assert(numel(lock.active_source_inventory)==32&& ...
    double(contract.new_scene_count)==71&&double(contract.limits.max_new_Plant)==71&& ...
    double(contract.limits.transitions)==20000&&double(contract.limits.state_samples)==20001&& ...
    double(contract.limits.score_horizon_s)==20, ...
    'BDEV72:Contract','Frozen run count/time/method limits changed.');
assert(directory_bytes(here)+numel(sceneIds)*reserveBytes<=maxBytes&& ...
    double(java.io.File(repoRoot).getUsableSpace())-numel(sceneIds)*reserveBytes>=minimumFree&& ...
    (datetime('now','TimeZone','UTC')+seconds(numel(sceneIds)*minimumSeconds+exitReserveSeconds))<deadline, ...
    'BDEV72:ResourceDeadline','Output, free-space reserve, or conservative completion deadline is insufficient.');

active=lock.active_source_inventory;
initPath=source_path(active,'init_dl1018.m');
optionsPath=source_path(active,'controller_options_dl1018.m');
corePath=source_path(active,'run_dl1018_closed_loop.m');
forwardPath=source_path(active,'position_stage1_model_forward_v2.m');
headPath=source_path(active,'position_only_search_head_step.m');
archiveDirs=unique({fileparts(forwardPath),fileparts(headPath), ...
    fileparts(source_path(active,'position_only_search_options.m'))},'stable');
add_active_paths(active); addpath(fullfile(repoRoot,'matlab','runtime'),'-end');
addpath(fullfile(repoRoot,'matlab','core'),'-end');
addpath(fileparts(initPath),'-begin'); addpath(fileparts(optionsPath),'-begin');
for k=1:numel(archiveDirs), addpath(archiveDirs{k},'-begin'); end
addpath(fileparts(corePath),'-begin'); addpath(here,'-begin');
clear init_dl1018 controller_options_dl1018 run_episode_dl1018 run_dl1018_closed_loop; rehash;
assert(same_path(which('init_dl1018'),initPath)&& ...
    same_path(which('controller_options_dl1018'),optionsPath), ...
    'BDEV72:InitPath','Frozen init/options source resolves to a shadow.');
[cfg,optsInit,resolvedRoot]=init_dl1018();
assert(same_path(resolvedRoot,repoRoot),'BDEV72:ProjectRoot','Runtime resolved another repository.');
add_active_paths(active); addpath(fullfile(repoRoot,'matlab','runtime'),'-end');
addpath(fullfile(repoRoot,'matlab','core'),'-end');
addpath(fileparts(initPath),'-begin'); addpath(fileparts(optionsPath),'-begin');
for k=1:numel(archiveDirs), addpath(archiveDirs{k},'-begin'); end
addpath(fileparts(corePath),'-begin'); addpath(here,'-begin');
clear controller_options_dl1018 run_episode_dl1018 run_dl1018_closed_loop; rehash;
whichCount=0;
for k=1:numel(active)
    item=active(k); [~,name,ext]=fileparts(char(item.path));
    if strcmpi(ext,'.m')
        assert(same_path(which(name),char(item.path)),'BDEV72:WhichShadow', ...
            'Active source %s resolves to a shadow.',name);
        whichCount=whichCount+1;
    end
end
assert(whichCount==31&&same_path(which('run_episode_dl1018'),source_path(active,'run_episode_dl1018.m'))&& ...
    same_path(which('run_dl1018_closed_loop'),corePath), ...
    'BDEV72:RuntimePath','Frozen C3 wrapper/core resolution changed.');
pack=load(snapshotPath,'cfg','opts','sceneIds','sceneIdentities','sourceIdentity');
assert(all(isfield(pack,{'cfg','opts','sceneIds','sceneIdentities','sourceIdentity'}))&& ...
    isequal(string(pack.sceneIds(:)),string(sceneIds(:)))&&numel(pack.sceneIdentities)==71, ...
    'BDEV72:Snapshot','Prepared cfg/options/scene identity snapshot is incomplete.');
assert(isequaln(cfg,pack.cfg)&&isequaln(controller_options_dl1018(cfg,'B'),pack.opts)&& ...
    isequaln(optsInit,pack.opts), ...
    'BDEV72:CfgOptsChanged','Fresh cfg/B options differ from no-Plant and init snapshots.');
assert(isfile(lock.upstream_refs.c3_prepared_snapshot.path),'BDEV72:C3Snapshot','C3 cfg snapshot is missing.');
c3Pack=load(lock.upstream_refs.c3_prepared_snapshot.path,'cfg');
assert(isequaln(cfg,c3Pack.cfg),'BDEV72:C3Config','Fresh cfg differs from frozen C3 cfg.');
assert(~isfield(pack.opts,'stage1_position_runtime')&& ...
    ~isfield(pack.opts,'position_delayed_prediction_enabled')&& ...
    logical(pack.opts.rbf_position_output_enabled)&&logical(pack.opts.rbf_position_update_enabled), ...
    'BDEV72:NotBaselineB','B options include a candidate state or disable baseline RBF.');

raf=java.io.RandomAccessFile(lock.shared_heavy_job_lock_path,'rw');
channel=raf.getChannel(); jobLock=channel.tryLock();
assert(~isempty(jobLock),'BDEV72:ConcurrentHeavyJob','Shared heavy-job lock is held; never wait or seize it.');
cleanup=onCleanup(@()release_job_lock(jobLock,channel,raf)); %#ok<NASGU>
startedUtc=utc_now(); completed=cell(1,numel(sceneIds)); plantCalls=0;
for k=1:numel(sceneIds)
    sceneId=sceneIds{k}; remaining=numel(sceneIds)-k+1;
    assert((datetime('now','TimeZone','UTC')+seconds(remaining*minimumSeconds+exitReserveSeconds))<deadline, ...
        'BDEV72:DeadlineStop','Remaining scenes cannot conservatively finish before the frozen deadline.');
    assert(directory_bytes(here)+remaining*reserveBytes<=maxBytes&& ...
        double(java.io.File(repoRoot).getUsableSpace())-remaining*reserveBytes>=minimumFree, ...
        'BDEV72:ReserveStop','Remaining scene reserve or minimum free-space floor is unavailable.');
    for si=1:numel(active), verify_ref(active(si)); end
    rowIx=find(strcmp({lock.scenes.scene_id},sceneId));
    identityIx=find(strcmp({pack.sceneIdentities.scene_id},sceneId));
    assert(numel(rowIx)==1&&numel(identityIx)==1,'BDEV72:SceneIdentity','Scene row/identity is not unique.');
    row=lock.scenes(rowIx); identity=pack.sceneIdentities(identityIx);
    assert(same_path(row.B_source.path,row.scored_log.path)&& ...
        strcmpi(row.B_source.sha256,row.scored_log.sha256)&& ...
        strcmpi(row.external_identity_sha256,identity.external_identity_sha256), ...
        'BDEV72:ExternalInputs','B source/score input binding changed for %s.',sceneId);
    verify_file(char(row.B_source.path),char(row.B_source.sha256));
    scenePack=load(char(row.B_source.path),'scene'); scene=scenePack.scene;
    rawId=char(scene.scene_id);
    assert(valid_scene(scene,sceneId)&&strcmp(rawId,identity.raw_scene_id)&& ...
        same_path(row.B_source.path,identity.B_raw_path)&& ...
        strcmpi(row.B_source.sha256,identity.B_raw_sha256), ...
        'BDEV72:SceneChanged','Scene bytes/schema/alias differ from prepared identity: %s.',sceneId);
    scene.scene_id=sceneId;
    opts=controller_options_dl1018(cfg,'B');
    assert(isequaln(opts,pack.opts)&&isequaln(opts,optsInit)&& ...
        logical(opts.rbf_position_output_enabled)&&logical(opts.rbf_position_update_enabled), ...
        'BDEV72:OptionsReset','Fresh B controller options differ; refusing to reuse/mutate prior scene opts.');
    attemptDir=fullfile(attemptRoot,sceneId,contract.collector_tag,'attempt_01');
    assert(~isfolder(attemptDir),'BDEV72:NoRetry','Attempt exists for %s; refusing retry.',sceneId);
    mkdir(attemptDir);
    markerPath=fullfile(attemptDir,'first_plant_step.marker');
    rawPath=fullfile(attemptDir,'raw_run.mat');
    runStartPath=fullfile(attemptDir,'run_start.mat');
    statusPath=fullfile(attemptDir,'run_status.json');
    failurePath=fullfile(attemptDir,'B_TRACEABLE_FAILURE.json');
    exitRecordPath=fullfile(attemptDir,'B_TRACEABLE_OS_EXIT.json');
    assert(all(~[isfile(markerPath),isfile(rawPath),isfile(runStartPath),isfile(statusPath), ...
        isfile(failurePath),isfile(exitRecordPath)]), ...
        'BDEV72:NoOverwrite','Attempt artifacts already exist for %s.',sceneId);
    opts.r2e_first_plant_step_marker=markerPath;
    runStart=struct('schema','B_TRACEABLE_C3CORE_DEV72_RUN_START_V3', ...
        'batch_id','B_TRACEABLE_C3CORE_DEV72_20261023','scene_id',sceneId, ...
        'source_scene_id',rawId,'condition',contract.collector_tag, ...
        'runtime_method',contract.method,'scene_index',k,'scene_count',numel(sceneIds), ...
        'started_utc',utc_now(),'release_sha256',releaseSha,'input_lock_sha256',lockSha, ...
        'contract_sha256',contractSha,'prepare_result_sha256',prepareSha, ...
        'cfg_opts_snapshot_sha256',snapshotSha,'scene_identity',identity, ...
        'source_identity',pack.sourceIdentity,'source_paths',{pack.sourceIdentity.source_paths}, ...
        'source_sha256',{pack.sourceIdentity.source_sha256},'runner_path',runnerPath, ...
        'runner_sha256',runnerSha,'command_path',lock.source_files.run_command.path, ...
        'command_sha256',runCommandSha,'cfg',cfg,'opts',opts, ...
        'plant_calls_before_invocation',0,'training_steps',0,'optimizer_steps',0,'TEST_accessed',false);
    invocationEntered=false; statusWritten=false;
    save(runStartPath,'runStart','-v7.3');
    write_text_new(fullfile(attemptDir,'attempt_started.marker'), ...
        [runStart.started_utc newline 'ABOUT_TO_CALL_EPISODE' newline]);
    try
        invocationEntered=true; plantCalls=plantCalls+1;
        clear run_dl1018_closed_loop;
        log=run_episode_dl1018(scene,contract.collector_tag,cfg,opts,rawPath);
        assert(isfile(rawPath)&&isfile(markerPath),'BDEV72:PlantOutput', ...
            'Episode returned without raw or first-Plant marker for %s.',sceneId);
        runIdentity=struct('schema','B_TRACEABLE_C3CORE_DEV72_RUN_IDENTITY_V3', ...
            'batch_id','B_TRACEABLE_C3CORE_DEV72_20261023','scene_id',sceneId, ...
            'collector_tag',contract.collector_tag,'runtime_method',contract.method, ...
            'release_sha256',releaseSha,'input_lock_sha256',lockSha, ...
            'prepare_result_sha256',prepareSha,'scene_raw_sha256',row.B_source.sha256, ...
            'external_identity_sha256',row.external_identity_sha256, ...
            'runner_sha256',runnerSha,'command_sha256',runCommandSha, ...
            'training_steps',0,'optimizer_steps',0,'TEST_accessed',false);
        save(rawPath,'runIdentity','-append');
        rawSha=sha256_file(rawPath); runStartSha=sha256_file(runStartPath);
        markerSha=sha256_file(markerPath);
        finiteLog=isfield(log,'state')&&all(isfinite(log.state(:)))&& ...
            isfield(log,'reference')&&all(isfinite(log.reference.position(:)))&& ...
            all(isfinite(log.time(:)));
        complete=strcmpi(log.status,'STABLE')&&isempty(char(log.safety_stop_reason))&& ...
            double(log.last_transition)==20000&&numel(log.transition_time)==20000&& ...
            numel(log.time)==20001&&finiteLog;
        stateLabel='FAILED_NO_RETRY'; if complete, stateLabel='RUN_COMPLETE_RAW_PENDING_AUDIT'; end
        runStatus=struct('schema','B_TRACEABLE_C3CORE_DEV72_RUN_STATUS_V3', ...
            'status',stateLabel,'batch_id','B_TRACEABLE_C3CORE_DEV72_20261023', ...
            'scene_id',sceneId,'source_scene_id',rawId,'scene_index',k,'scene_count',numel(sceneIds), ...
            'collector_tag',contract.collector_tag,'runtime_method',contract.method, ...
            'log_status',log.status,'safety_stop_reason',log.safety_stop_reason, ...
            'last_transition',double(log.last_transition),'transitions',numel(log.transition_time), ...
            'state_samples',numel(log.time),'raw_path',rawPath,'raw_sha256',rawSha, ...
            'raw_bytes',double(dir(rawPath).bytes),'run_start_path',runStartPath, ...
            'run_start_sha256',runStartSha,'attempt_started_marker_path',fullfile(attemptDir,'attempt_started.marker'), ...
            'attempt_started_marker_sha256',sha256_file(fullfile(attemptDir,'attempt_started.marker')), ...
            'first_plant_step_marker_path',markerPath,'first_plant_step_marker_sha256',markerSha, ...
            'os_exit_record_path',exitRecordPath,'release_sha256',releaseSha, ...
            'input_lock_sha256',lockSha,'contract_sha256',contractSha, ...
            'prepare_result_sha256',prepareSha,'cfg_opts_snapshot_sha256',snapshotSha, ...
            'scene_raw_sha256',row.B_source.sha256,'external_identity_sha256',row.external_identity_sha256, ...
            'command_path',lock.source_files.run_command.path,'command_sha256',runCommandSha, ...
            'plant_invocation_entered',true,'plant_start_confirmed',true,'plant_calls',1, ...
            'training_steps',0,'optimizer_steps',0,'parameter_or_seed_search',false, ...
            'TEST_accessed',false,'output_bytes_after_raw',directory_bytes(here), ...
            'created_utc',utc_now());
        if runStatus.output_bytes_after_raw+remaining*reserveBytes>maxBytes
            runStatus.status='FAILED_NO_RETRY';
            runStatus.failure_reason='Remaining output reserve would exceed the frozen 6-GiB cap.';
        end
        write_json_new(statusPath,runStatus); statusWritten=true;
        assert(strcmp(runStatus.status,'RUN_COMPLETE_RAW_PENDING_AUDIT'), ...
            'BDEV72:UnsafeStop','Run is incomplete/non-STABLE or exceeds cap; evidence retained, no retry.');
        completed{k}=struct('scene_id',sceneId,'status_path',statusPath, ...
            'status_sha256',sha256_file(statusPath),'raw_path',rawPath,'raw_sha256',rawSha, ...
            'plant_calls',1);
    catch ME
        if ~statusWritten
            failedStatus=struct('schema','B_TRACEABLE_C3CORE_DEV72_RUN_STATUS_V3', ...
                'status','FAILED_NO_RETRY','batch_id','B_TRACEABLE_C3CORE_DEV72_20261023', ...
                'scene_id',sceneId,'scene_index',k,'scene_count',numel(sceneIds), ...
                'error_identifier',ME.identifier,'error_message',ME.message, ...
                'attempt_dir',attemptDir,'plant_invocation_entered',invocationEntered, ...
                'plant_start_confirmed',isfile(markerPath),'plant_calls',double(invocationEntered), ...
                'raw_path',rawPath,'partial_raw_preserved',isfile(rawPath), ...
                'partial_raw_sha256',file_sha_if_exists(rawPath), ...
                'run_start_sha256',file_sha_if_exists(runStartPath), ...
                'release_sha256',releaseSha,'input_lock_sha256',lockSha, ...
                'command_path',lock.source_files.run_command.path,'command_sha256',runCommandSha, ...
                'TEST_accessed',false,'created_utc',utc_now());
            write_json_new(statusPath,failedStatus);
        end
        failed=struct('schema','B_TRACEABLE_C3CORE_DEV72_FAILURE_V3', ...
            'status','FAILED_NO_RETRY','batch_id','B_TRACEABLE_C3CORE_DEV72_20261023', ...
            'scene_id',sceneId,'scene_index',k,'error_identifier',ME.identifier, ...
            'error_message',ME.message,'failed_utc',utc_now(),'attempt_dir',attemptDir, ...
            'plant_invocation_entered',invocationEntered,'plant_start_confirmed',isfile(markerPath), ...
            'plant_calls',double(invocationEntered),'raw_path',rawPath, ...
            'partial_raw_preserved',isfile(rawPath),'partial_raw_sha256',file_sha_if_exists(rawPath), ...
            'input_lock_sha256',lockSha,'release_sha256',releaseSha, ...
            'attempt_bytes_at_failure',directory_bytes(attemptDir), ...
            'experiment_bytes_at_failure',directory_bytes(here));
        if ~isfile(failurePath), write_json_new(failurePath,failed); end
        rethrow(ME);
    end
end
batchResult=struct('schema','B_TRACEABLE_C3CORE_DEV72_BATCH_RESULT_V3', ...
    'status','RUN_COMPLETE_RAW_PENDING_AUDIT','batch_id','B_TRACEABLE_C3CORE_DEV72_20261023', ...
    'created_utc',utc_now(),'input_lock_sha256',lockSha,'contract_sha256',contractSha, ...
    'release_sha256',releaseSha,'prepare_result_sha256',prepareSha, ...
    'cfg_opts_snapshot_sha256',snapshotSha,'runner_sha256',runnerSha, ...
    'run_command_sha256',runCommandSha,'new_scene_ids_sha256',lock.new_scene_ids_sha256, ...
    'completed_scene_count',numel(completed),'completed_scenes',{completed}, ...
    'plant_calls',plantCalls,'training_steps',0,'optimizer_steps',0, ...
    'parameter_or_seed_search',false,'TEST_accessed',false, ...
    'completed_utc',utc_now(),'batch_started_utc',startedUtc, ...
    'output_bytes_after_batch',directory_bytes(here));
end

function add_active_paths(items)
for k=1:numel(items), [~,~,ext]=fileparts(char(items(k).path)); if strcmpi(ext,'.m'), addpath(fileparts(char(items(k).path)),'-end'); end, end
end
function path=source_path(items,name)
names=cell(1,numel(items)); for k=1:numel(items), [~,n,e]=fileparts(char(items(k).path)); names{k}=[n e]; end
ix=find(strcmpi(names,name)); assert(numel(ix)==1,'BDEV72:SourceName','Expected exactly one frozen source %s.',name); path=char(items(ix).path);
end
function ok=valid_scene(s,sceneId)
ok=isstruct(s)&&isfield(s,'scene_id')&&(strcmp(char(s.scene_id),sceneId)||strcmp(char(s.scene_id),[sceneId '_ACC_FIX_V1']))&& ...
    isfield(s,'time')&&numel(s.time)==20001&&abs(double(s.time(1)))<=1e-12&&abs(double(s.time(end))-20)<=1e-12&& ...
    isfield(s,'environment_wind_I')&&isequal(size(s.environment_wind_I),[20001,3])&&isfield(s,'initial_state')&&numel(s.initial_state)==12&& ...
    isfield(s,'arms')&&all(isfield(s.arms,{'command','rhoDot_hat','rhoDot_true','rho_hat','rho_true'}))&&isfield(s,'reference')&& ...
    all(isfield(s.reference,{'position','velocity','acceleration','yaw','yaw_rate','yaw_acceleration'}))&& ...
    isequal(size(s.reference.position),[20001,3])&&isequal(size(s.reference.velocity),[20001,3])&& ...
    isequal(size(s.reference.acceleration),[20001,3])&&isequal(size(s.reference.yaw),[20001,1])&& ...
    isequal(size(s.reference.yaw_rate),[20001,1])&&isequal(size(s.reference.yaw_acceleration),[20001,1])&& ...
    isequal(size(s.arms.command),[20001,4])&&isequal(size(s.arms.rhoDot_hat),[20001,4])&& ...
    isequal(size(s.arms.rhoDot_true),[20001,4])&&isequal(size(s.arms.rho_hat),[20001,4])&&isequal(size(s.arms.rho_true),[20001,4])&& ...
    all(isfinite(s.time(:)))&&all(isfinite(s.environment_wind_I(:)))&&all(isfinite(s.initial_state(:)))&& ...
    all(isfinite(s.arms.command(:)))&&all(isfinite(s.arms.rhoDot_hat(:)))&&all(isfinite(s.arms.rhoDot_true(:)))&& ...
    all(isfinite(s.arms.rho_hat(:)))&&all(isfinite(s.arms.rho_true(:)))&&all(isfinite(s.reference.position(:)))&& ...
    all(isfinite(s.reference.velocity(:)))&&all(isfinite(s.reference.acceleration(:)))&&all(isfinite(s.reference.yaw(:)))&& ...
