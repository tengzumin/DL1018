function h=sha256_file(path)
md=java.security.MessageDigest.getInstance('SHA-256'); fid=fopen(path,'r'); assert(fid>=0,'BDEV72:Read','Cannot read %s.',path); c=onCleanup(@()fclose(fid)); %#ok<NASGU>
while true
    b=fread(fid,8*1024*1024,'*uint8');
    if isempty(b), break; end
    md.update(typecast(b(:),'int8'));
end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
