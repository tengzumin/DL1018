function [raw,applied,weightNext,projection,info] = position_stage1_update_head_transfer( ...
    phi,weight,surface,eventDt,beta,dmax,etaBefore,gamma)
% Frozen PCF FEATURE head with task-book Gamma and output-then-update timing.
phi=double(phi(:));weight=double(weight);surface=double(surface(:));etaBefore=double(etaBefore(:));
assert(numel(phi)==33&&isequal(size(weight),[33 3])&&numel(surface)==3&& ...
    numel(etaBefore)==3&&isscalar(eventDt)&&isfinite(eventDt)&&eventDt>0&& ...
    isscalar(beta)&&isfinite(beta)&&beta>=0&&beta<=1&& ...
    isscalar(gamma)&&ismember(gamma,[1 12])&&numel(dmax)==3&& ...
    all(isfinite([phi;weight(:);surface;etaBefore])), ...
    'OLDKAN:HeadInput','Invalid transfer Head input.');
updateSurface=surface;
if any(etaBefore~=0),updateSurface=surface-etaBefore;end
sEff=max(min(updateSurface,[7;8;10]),-[7;8;10]);
raw=weight.'*phi;
applied=beta*max(min(raw,double(dmax(:))),-double(dmax(:)));
weightRaw=weight+eventDt*(-double(gamma)*beta*phi*(sEff.')-0.002*weight);
projection=any(abs(weightRaw(:))>60);
weightNext=max(min(weightRaw,60),-60);
info=struct('surface',updateSurface,'surface_effective',sEff,'weight_raw',weightRaw, ...
    'gamma',double(gamma),'update_surface',sEff,'state_bound',60);
end
