    ptOld=position_stage1_model_forward_v2(oldModel,wt);ptNew=position_stage1_model_forward_v2(newModel,wt);
    pvOld=position_stage1_model_forward_v2(oldModel,wv);pvNew=position_stage1_model_forward_v2(newModel,wv);
    trainOldErr=max(trainOldErr,max(abs(ptOld-position_stage1_model_forward_old_reference(oldStored,wt))));
    trainNewErr=max(trainNewErr,max(abs(ptNew-position_stage1_model_forward_current(newModel,wt))));
    valOldErr=max(valOldErr,max(abs(pvOld-position_stage1_model_forward_old_reference(oldStored,wv))));
    valNewErr=max(valNewErr,max(abs(pvNew-position_stage1_model_forward_current(newModel,wv))));
