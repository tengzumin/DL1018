function candidateOpts = attitude_kan29_c5_opts_overlay_v1(baseOpts, model)
% Isolated C5 attitude replacement overlay. Does not alter cfg or position options.
assert(isstruct(baseOpts) && isscalar(baseOpts), 'C5KAN:BaseOpts', 'baseOpts must be a scalar struct.');
assert(isstruct(model) && isfield(model,'architecture') && isfield(model,'input_dim') && ...
    isfield(model,'input_mu') && isfield(model,'input_sigma') && isfield(model,'dmax') && ...
    isfield(model,'knots') && isfield(model,'params'), ...
    'C5KAN:ModelSchema','Expected the frozen top-level A_KAN29 MAT struct.');
assert(strcmpi(char(string(model.architecture)),'KAN') && double(model.input_dim)==29, ...
    'C5KAN:ModelIdentity','Expected A_KAN29 X29 model.');
assert(isequal(size(model.input_mu),[29 1]) && isequal(size(model.input_sigma),[29 1]) && ...
    isequal(size(model.dmax),[3 1]) && all(isfinite([model.input_mu(:);model.input_sigma(:);model.dmax(:)])) && ...
    all(model.input_sigma(:)>0) && all(model.dmax(:)>0), ...
    'C5KAN:ModelShape','Frozen model arrays are malformed.');
assert(all(isfield(baseOpts,{'rbf_attitude_enabled','rbf_attitude_update_enabled', ...
    'rbf_attitude_output_enabled'})), 'C5KAN:BaseSchema','C5 RBF attitude switches are missing.');

candidateOpts=baseOpts;
candidateOpts.attitude_fusion_v3_6=struct('enabled',true,'lambda',1,'model',model);
candidateOpts.rbf_attitude_enabled=false;
candidateOpts.rbf_attitude_update_enabled=false;
candidateOpts.rbf_attitude_output_enabled=false;
% Fields are required by the pinned C5 runner even when head learning is off.
candidateOpts.attitude_head_v39=struct('enabled',false,'gamma',0.002, ...
    'sigma_per_s',0.02,'projection_fro',0.20);
end
