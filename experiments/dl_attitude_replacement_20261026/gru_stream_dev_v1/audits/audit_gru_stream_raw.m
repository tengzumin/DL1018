function report=audit_gru_stream_raw(sceneId,candidateRawPath)
% Independent full-sequence GRU replay, sample/hold, and issued-torque closure audit.
here=char(java.io.File(fileparts(mfilename('fullpath'))).getCanonicalPath());
study=fileparts(here);outPath=fullfile(here,[char(sceneId) '_GRU_STREAM_RAW_AUDIT.json']);
assert(~isfile(outPath),'GRUStreamAudit:OutputExists','Refusing to overwrite an audit result.');
release=jsondecode(fileread(fullfile(study,'RELEASE.json')));
manifest=jsondecode(fileread(fullfile(study,'MANIFEST.json')));
hit=find(strcmp({manifest.records.scene_id},char(sceneId)));assert(isscalar(hit));record=manifest.records(hit);
candidateRawPath=char(java.io.File(candidateRawPath).getCanonicalPath());
prefix=[char(java.io.File(study).getCanonicalPath()) filesep];
assert(startsWith(lower(candidateRawPath),lower(prefix))&&isfile(candidateRawPath), ...
    'GRUStreamAudit:RawPath','Candidate raw must be inside this study.');
verify_source_lock(study,release);
check={'MANIFEST.json','manifest_sha256';'LOCKED_CFG.json','locked_cfg_sha256'; ...
    'SOURCE_LOCK_v1.json','source_lock_sha256';'SOURCE_DIFF_v1.json','source_diff_sha256'; ...
    'audits/NO_PLANT_CHECK_v1.json','no_plant_check_sha256'; ...
    'run_gru_stream_dev_attempt.m','driver_sha256'; ...
    'audits/audit_gru_stream_raw.m','raw_audit_script_sha256'};
for i=1:size(check,1)
    p=fullfile(study,check{i,1});assert(isfile(p)&&strcmpi(hash_file(p),char(release.(check{i,2}))), ...
        'GRUStreamAudit:ReleaseHash','Release-bound file changed: %s.',check{i,1});
end
runStatus=jsondecode(fileread(fullfile(fileparts(candidateRawPath),'run_status.json')));
assert(strcmp(char(runStatus.state),'COMPLETED')&&strcmp(char(runStatus.scene_id),char(sceneId))&& ...
    strcmpi(hash_file(candidateRawPath),char(runStatus.raw_sha256)), ...
    'GRUStreamAudit:RawIdentity','Raw/status identity failed.');
raw=load(candidateRawPath,'log','scene','runIdentity');L=raw.log;X=double(L.state);
modelPath=char(release.model_path);modelSha=hash_file(modelPath);model=load(modelPath);
locked=jsondecode(fileread(fullfile(study,'LOCKED_CFG.json')));J0=double(locked.J0_kgm2);
dmax=double(locked.dmax(:));betaRise=double(locked.beta_rise_time_s);
assert(strcmpi(modelSha,char(release.model_sha256))&& ...
    strcmpi(char(raw.runIdentity.gru_model_sha256),modelSha)&& ...
    strcmpi(char(L.gru_stream_attitude_model_sha256),modelSha)&& ...
    strcmp(char(L.status),'STABLE')&&logical(L.complete_transitions)&& ...
    strcmp(char(L.method),'GRU_STREAM')&&~logical(L.gru_stream_variable_inertia_reconstruction_used)&& ...
    ~logical(L.gru_stream_weight_update_enabled)&&~logical(L.gru_stream_rbf_output_enabled)&& ...
    ~logical(L.gru_stream_rbf_update_enabled)&&~logical(L.gate_feedforward_enabled)&& ...
    ~logical(L.gate_observer_enabled)&&~any(L.rbf_update_flag(:))&& ...
    all(abs(double(L.attitude_rbf_compensation_torque_Nm(:)))<1e-12), ...
    'GRUStreamAudit:RunIdentity','Raw is not a clean frozen GRU_STREAM run.');
traces=L.gru_stream_attitude_trace;events=find(~cellfun(@isempty,traces));
assert(numel(events)==1999,'GRUStreamAudit:EventCount','Expected 1999 stream events.');
eventFlag=logical(L.attitude_event_flag(1:20000));
assert(isequal(find(eventFlag),events(:)),'GRUStreamAudit:EventFlag','Hidden trace indices differ from actual event flags.');
assert(nnz(any(L.motor_saturated,2))==0&&nnz(any(L.generalized_clipped,2))==0, ...
    'GRUStreamAudit:EngineeringSafety','Motor saturation or generalized clipping occurred.');
assert(size(X,1)==20001&&double(L.last_transition)==20000&& ...
    size(L.requested_generalized,1)==20000,'GRUStreamAudit:Timeline','Unexpected control/state timeline.');
[memory,~]=gru_stream_attitude_step_v1('init',struct,struct,model);
outputError=0;hiddenError=0;featureError=0;torqueError=0;betaError=0;carryError=0;
expectedApplied=zeros(20000,3);held=zeros(3,1);eventCount=0;
for k=1:20000
    if ~isempty(traces{k})
        eventCount=eventCount+1;z=traces{k};
        feature=[wrap(double(L.filtered_attitude_reference(k,:)).'-X(k,7:9).'); ...
            X(k,10:12).';double(L.attitude_bs_nominal_torque_Nm(k,:)).'; ...
            double(L.arms.command(k,:)).'];
        beta=min(k*double(L.transition_time(2)-L.transition_time(1))/betaRise,1);
        assert(z.sample_index==k&&abs(double(z.time_s)-double(L.time(k)))<1e-12&& ...
            logical(z.is_attitude_event)&&~logical(z.rbf_output_enabled)&& ...
            ~logical(z.rbf_update_enabled)&&~logical(z.time_varying_inertia_reconstruction_used), ...
            'GRUStreamAudit:TraceBinding','Invalid event trace index or forbidden feature path.');
        featureError=max(featureError,max(abs(feature-double(z.feature_raw(:)))));
        betaError=max(betaError,abs(beta-double(z.beta)));
        in=struct('feature',feature,'J0',J0,'beta',beta,'dmax',dmax);
        [memory,out]=gru_stream_attitude_step_v1('step',memory,in,model);
        outputError=max(outputError,max(abs(out.raw_residual_rad_s2-double(z.raw_residual_rad_s2(:)))));
        hiddenError=max(hiddenError,max(abs(out.hidden_after-double(z.hidden_after(:)))));
        carryError=max(carryError,max(abs(out.hidden_before-double(z.hidden_before(:)))));
        torqueError=max(torqueError,max(abs(out.estimateTorque_Nm-double(z.estimateTorque_Nm(:)))));
        assert(double(z.event_count)==eventCount&&double(out.event_count)==eventCount, ...
            'GRUStreamAudit:HiddenCount','Hidden state did not update once per actual event.');
        held=double(out.estimateTorque_Nm(:));
    end
    expectedApplied(k,:)=held.';
end
applied=double(L.attitude_compensation_applied_torque_Nm(1:20000,:));
nominal=double(L.attitude_bs_nominal_torque_Nm(1:20000,:));
requested=double(L.requested_generalized(:,2:4));
heldError=max(abs(applied-expectedApplied),[],'all');
issuedError=max(abs(requested-(nominal-expectedApplied)),[],'all');
assert(featureError<1e-9&&outputError<1e-8&&hiddenError<1e-8&&carryError<1e-8&& ...
    torqueError<1e-9&&betaError<1e-12&&heldError<1e-9&&issuedError<1e-9, ...
    'GRUStreamAudit:Replay','Independent GRU, hidden carry, sample/hold, or issued-torque replay failed.');
report=struct('status','PASS_INDEPENDENT_GRU_STREAM_RAW_REPLAY','Plant_calls_by_audit',0, ...
    'TEST_read',false,'scene_id',char(sceneId),'candidate_raw_sha256',hash_file(candidateRawPath), ...
    'model_sha256',modelSha,'event_count',eventCount,'state_samples',size(X,1), ...
    'transitions',double(L.last_transition),'max_feature_rebuild_error',featureError, ...
    'max_raw_output_replay_error_rad_s2',outputError,'max_full_hidden_replay_error',hiddenError, ...
    'max_hidden_carry_error',carryError,'max_beta_error',betaError, ...
    'max_expected_torque_error_Nm',torqueError,'max_non_event_sample_hold_error_Nm',heldError, ...
    'max_requested_command_closure_error_Nm',issuedError, ...
    'motor_saturation_samples',nnz(any(L.motor_saturated,2)), ...
    'generalized_clip_samples',nnz(any(L.generalized_clipped,2)), ...
    'source_script_sha256',hash_file([mfilename('fullpath') '.m']));
write_json(outPath,report);disp(report);
end
function verify_source_lock(study,release)
lockPath=fullfile(study,'SOURCE_LOCK_v1.json');
assert(strcmpi(hash_file(lockPath),char(release.source_lock_sha256)), ...
    'GRUStreamAudit:SourceLockHash','Source lock hash changed.');
lock=jsondecode(fileread(lockPath));runner=fullfile(study,'candidate_runner_work');
assert(strcmpi(char(java.io.File(lock.root).getCanonicalPath()), ...
    char(java.io.File(runner).getCanonicalPath())),'GRUStreamAudit:SourceRoot','Source root changed.');
for i=1:numel(lock.files)
    p=fullfile(runner,strrep(char(lock.files(i).relative_path),'/',filesep));
    assert(isfile(p)&&strcmpi(hash_file(p),char(lock.files(i).sha256)), ...
        'GRUStreamAudit:SourceHash','Source changed: %s.',char(lock.files(i).relative_path));
end
end
function y=wrap(x),y=atan2(sin(x),cos(x));end
function h=hash_file(path)
fid=fopen(path,'rb');assert(fid>=0,'GRUStreamAudit:Read','Cannot read %s.',path);
cleanup=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear cleanup;
end
function write_json(path,value)
fid=fopen(path,'w','n','UTF-8');assert(fid>=0,'GRUStreamAudit:Write','Cannot write %s.',path);
cleanup=onCleanup(@()fclose(fid));fprintf(fid,'%s\n',jsonencode(value,'PrettyPrint',true));clear cleanup;
end