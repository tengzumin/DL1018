function [rawResidual,nextHidden]=gru_stream_attitude_forward_v1(featureNormalized,hidden,model)
% One current feature and explicit carried hidden state; frozen GRU32 weights.
required={'gru_weight_ih','gru_weight_hh','gru_bias_ih','gru_bias_hh', ...
    'head_weight','head_bias','target_rms'};
assert(isstruct(model)&&all(isfield(model,required)), ...
    'DLGRUStream:Model','GRU_STREAM model fields are incomplete.');
x=double(featureNormalized(:));h=double(hidden(:));hsize=32;
assert(numel(x)==13&&all(isfinite(x))&&numel(h)==hsize&&all(isfinite(h)), ...
    'DLGRUStream:Input','Expected one finite 13-vector and a finite 32-vector hidden state.');
assert(isequal(size(model.gru_weight_ih),[3*hsize,13])&& ...
    isequal(size(model.gru_weight_hh),[3*hsize,hsize])&& ...
    numel(model.gru_bias_ih)==3*hsize&&numel(model.gru_bias_hh)==3*hsize&& ...
    isequal(size(model.head_weight),[3,hsize])&&numel(model.head_bias)==3&& ...
    numel(model.target_rms)==3, ...
    'DLGRUStream:WeightShape','GRU_STREAM weights have invalid shapes.');
assert(all(isfinite(double(model.gru_weight_ih(:))))&& ...
    all(isfinite(double(model.gru_weight_hh(:))))&& ...
    all(isfinite(double(model.gru_bias_ih(:))))&& ...
    all(isfinite(double(model.gru_bias_hh(:))))&& ...
    all(isfinite(double(model.head_weight(:))))&& ...
    all(isfinite(double(model.head_bias(:))))&& ...
    all(isfinite(double(model.target_rms(:))))&&all(double(model.target_rms(:))>0), ...
    'DLGRUStream:WeightFinite','GRU_STREAM weights or target RMS are invalid.');
% PyTorch single-layer GRU gate order is reset, update, new.
wih=double(model.gru_weight_ih);whh=double(model.gru_weight_hh);
bih=double(model.gru_bias_ih(:));bhh=double(model.gru_bias_hh(:));
gi=wih*x+bih;gh=whh*h+bhh;
reset=1./(1+exp(-(gi(1:hsize)+gh(1:hsize))));
update=1./(1+exp(-(gi(hsize+1:2*hsize)+gh(hsize+1:2*hsize))));
newState=tanh(gi(2*hsize+1:3*hsize)+ ...
    reset.*gh(2*hsize+1:3*hsize));
nextHidden=(1-update).*newState+update.*h;
rawResidual=(double(model.head_weight)*nextHidden+double(model.head_bias(:))).* ...
    double(model.target_rms(:));
assert(numel(rawResidual)==3&&all(isfinite(rawResidual))&&all(isfinite(nextHidden)), ...
    'DLGRUStream:Output','GRU_STREAM output or hidden state is invalid.');
end
