function report=audit_composite_dev_v3_no_plant()
% Verify the real prepared identity survives the operational attempt marker.
here=char(java.io.File(fileparts(mfilename('fullpath'))).getCanonicalPath());
study=fileparts(here);research=fileparts(study);project=fileparts(fileparts(research));
reportPath=fullfile(here,'NO_PLANT_CHECK_v3.json');
assert(~isfile(reportPath),'CompositeDEV:AuditExists','Refusing to overwrite a prior v3 check.');
release=jsondecode(fileread(fullfile(study,'RELEASE.json')));
assert(strcmp(char(release.status),'PREPARED_ROOT_REVIEW_REQUIRED')&& ...
    double(release.authorized_Plant_calls)==0&&double(release.Plant_calls)==0&& ...
    isempty(release.authorized_scenes)&&~logical(release.TEST_read), ...
    'CompositeDEV:ReleaseBudget','v3 must remain prepared with zero Plant authorization.');
manifest=jsondecode(fileread(fullfile(study,'MANIFEST.json')));
assert(strcmp(char(manifest.status),'PASS_READ_ONLY_VALIDATION_BINDINGS')&& ...
    numel(manifest.records)==6&&all(strcmp({manifest.records.source_split},'VAL'))&& ...
    ~logical(manifest.TEST_read), ...
    'CompositeDEV:Manifest','Expected the six locked VAL records and no TEST reads.');
runner=fullfile(study,'candidate_runner_work');runtime=fullfile(runner,'matlab','runtime');
parent=fullfile(research,'mlp15_causal_head_v1','candidate_runner_work');
lock=jsondecode(fileread(fullfile(study,'SOURCE_LOCK_v3.json')));
diff=jsondecode(fileread(fullfile(study,'SOURCE_DIFF_v3.json')));
assert(strcmpi(char(java.io.File(lock.root).getCanonicalPath()),char(java.io.File(runner).getCanonicalPath()))&& ...
    logical(diff.generic_gate_byte_identical)&&logical(diff.forward_unchanged)&& ...
    numel(diff.changed_control_files)==2, ...
    'CompositeDEV:SourceDiff','v3 source lock or two-file source diff is invalid.');
for i=1:numel(lock.files)
    rel=char(lock.files(i).relative_path);path=fullfile(runner,strrep(rel,'/',filesep));
    assert(isfile(path)&&strcmpi(hash_file(path),char(lock.files(i).sha256)), ...
        'CompositeDEV:SourceLock','v3 source hash changed: %s.',rel);
end
changed=sort(string({diff.changed_control_files.relative_path}));
assert(isequal(changed,sort(["matlab/runtime/mlp15_attitude_step_v1.m", ...
    "matlab/runtime/run_mlp15_dev72_closed_loop.m"])), ...
    'CompositeDEV:ChangedFiles','Unexpected source changed from causal v1.');
assert(strcmpi(hash_file(fullfile(runtime,'run_gate_holdout_closed_loop.m')), ...
    hash_file(fullfile(parent,'matlab','runtime','run_gate_holdout_closed_loop.m'))), ...
    'CompositeDEV:GenericGate','Generic gate differs from causal v1.');
devPath=fullfile(runtime,'run_mlp15_dev72_closed_loop.m');devText=fileread(devPath);
assert(contains(devText,"identityOpts=opts;")&& ...
    contains(devText,"identityOpts=rmfield(identityOpts,'composite_attempt_marker');")&& ...
    contains(devText,'cfg,opts.stage1_position_runtime.model,identityOpts);')&& ...
    contains(devText,'assert(isequaln(opts.gate_identity_lock,gateIdentityHashes)'), ...
    'CompositeDEV:IdentityFix','DEV must remove only the marker from recomputation and retain exact identity assertion.');

addpath(runtime);activate_paired_runner();
firstScene='DL1018_VAL_T1_C08_W15';record=manifest.records(strcmp({manifest.records.scene_id},firstScene));
assert(isscalar(record),'CompositeDEV:Scene','Required first VAL scene is absent.');
p=prepare_mlp15_dev72_no_plant(char(record.payload_path));
modelPath=char(release.model_path);modelSha=hash_file(modelPath);
assert(strcmpi(modelSha,char(release.model_sha256)), ...
    'CompositeDEV:ModelHash','Locked full72 MLP model changed.');
mlpModel=load(modelPath);
p.opts=make_gate_holdout_options(p.cfg,p.model,'DL_MLP15','ACTIVE',struct,mlpModel,modelSha);
frozen=gate_holdout_identity_hashes(p.cfg,p.model,p.opts);
assert(strcmpi(frozen.common.position_options_sha256, ...
    p.identity.common.position_options_sha256)&& ...
    strcmpi(frozen.common.position_options_sha256,char(release.common_position_options_sha256)), ...
    'CompositeDEV:PositionIdentity','Full72 rebind changed the frozen C5 position identity.');
p.opts.gate_identity_lock=frozen;
markerPath=fullfile(study,'runs',firstScene,'attempt_started.marker');
p.opts.composite_attempt_marker=markerPath;
identityOpts=p.opts;identityOpts=rmfield(identityOpts,'composite_attempt_marker');
markerStripped=gate_holdout_identity_hashes(p.cfg,p.model,identityOpts);
naiveMarker=gate_holdout_identity_hashes(p.cfg,p.model,p.opts);
assert(isequaln(frozen,markerStripped)&& ...
    isequaln(frozen.common,markerStripped.common)&& ...
    isequaln(frozen.geometry,markerStripped.geometry)&& ...
    ~isequaln(frozen.geometry,naiveMarker.geometry), ...
    'CompositeDEV:MarkerIdentity','Removing only the marker must restore the exact frozen identity.');
locked=jsondecode(fileread(fullfile(study,'LOCKED_CFG.json')));
assert(isequal(double(p.cfg.control.command_filter.acceleration_limit(:)),[Inf;Inf;6])&& ...
    isequal(double(p.cfg.control.bs.attitude.k1(:)),double(locked.K1(:)))&& ...
    isequal(double(p.cfg.rbf.attitude.dmax(:)),double(locked.dmax(:)))&& ...
    abs(double(p.cfg.rbf.attitude.beta_rise_time)-double(locked.beta_rise_time_s))<1e-12&& ...
    strcmpi(char(p.cfg.controller_morphology_mode),'fixed'), ...
    'CompositeDEV:LockedCfg','Actual prepared cfg differs from inherited locked values.');
Pplant=simulation_parameters(p.cfg,p.cfg.plant.arm_initial,zeros(4,1));
Pfixed=controller_parameters(p.cfg,Pplant,'fixed');J0=double(Pfixed.inertia);
assert(isequal(J0,double(locked.J0_kgm2))&& ...
    isequal(double(Pfixed.inertia_dot_for_bs),zeros(3))&& ...
    isequal(J0,double(Pfixed.inertia)), ...
    'CompositeDEV:FixedJ0','Pfixed must use the locked J0 and zero Jdot0.');
assert(strcmpi(which('run_mlp15_dev72_closed_loop'),devPath)&& ...
    strcmpi(which('mlp15_attitude_step_v1'),fullfile(runtime,'mlp15_attitude_step_v1.m'))&& ...
    strcmpi(which('run_gate_holdout_closed_loop'),fullfile(runtime,'run_gate_holdout_closed_loop.m')), ...
    'CompositeDEV:WhichPath','A required function resolves outside v3.');

% Exercise only the real zero-budget entry guards; neither call can enter Plant.
actualDevBlocked=false;
try
    run_mlp15_dev72_closed_loop(struct('scene_id',firstScene),struct,struct);
catch ME
    actualDevBlocked=strcmp(ME.identifier,'CompositeDEV:BudgetClosed');
end
assert(actualDevBlocked,'CompositeDEV:EngineBudget','Actual DEV did not reject the zero budget.');
addpath(study);driverBlocked=false;
try
    run_composite_dev_attempt(firstScene);
catch ME
    driverBlocked=strcmp(ME.identifier,'CompositeDEV:BudgetClosed');
end
assert(driverBlocked&&~isfolder(fullfile(study,'runs')), ...
    'CompositeDEV:DriverBudget','Outer driver did not reject before creating an attempt marker.');
prior=jsondecode(fileread(fullfile(study,'V2_FAILURE_LINEAGE.json')));
report=struct('status','PASS_V3_MARKER_IDENTITY_NO_PLANT','Plant_calls',0, ...
    'authorized_Plant_calls',0,'training_started',false,'TEST_read',false, ...
    'scene_id',firstScene,'marker_path_checked_without_creation',markerPath, ...
    'marker_stripped_identity_exact_match',true,'naive_marker_changed_geometry_hash',true, ...
    'frozen_identity',frozen,'marker_stripped_identity',markerStripped, ...
    'actual_dev_zero_budget_rejected',actualDevBlocked, ...
    'outer_driver_zero_budget_rejected',driverBlocked, ...
    'command_filter_acceleration_limit',{{'Inf (unbounded)','Inf (unbounded)',6}}, ...
    'Pfixed_inertia_equals_locked_J0',isequal(J0,double(locked.J0_kgm2)), ...
    'Pfixed_inertia_dot_for_bs_is_zero',isequal(double(Pfixed.inertia_dot_for_bs),zeros(3)), ...
    'cfg_snapshot_sha256',char(locked.cfg_snapshot_sha256), ...
    'model_sha256',modelSha,'position_model_sha256',p.position_model_sha256, ...
    'common_position_options_sha256',frozen.common.position_options_sha256, ...
    'which_dev',which('run_mlp15_dev72_closed_loop'), ...
    'which_step',which('mlp15_attitude_step_v1'), ...
    'which_generic_gate',which('run_gate_holdout_closed_loop'), ...
    'source_lock_sha256',hash_file(fullfile(study,'SOURCE_LOCK_v3.json')), ...
    'source_diff_sha256',hash_file(fullfile(study,'SOURCE_DIFF_v3.json')), ...
    'changed_control_files',{ {diff.changed_control_files.relative_path} }, ...
    'inherited_v2_no_plant_sha256',prior.v2_no_plant_check_sha256, ...
    'inherited_prior_300_event_report_sha256',prior.prior_300_event_report_sha256, ...
    'inherited_residual_update_events',prior.prior_residual_update_events, ...
    'inherited_tracking_update_events',prior.prior_tracking_update_events, ...
    'baseline_metrics_recomputed',false, ...
    'audit_script_sha256',hash_file([mfilename('fullpath') '.m']));
write_json(reportPath,report);disp(report);
end

function h=hash_file(path)
fid=fopen(path,'rb');assert(fid>=0,'CompositeDEV:Read','Cannot read %s.',path);
cleanup=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear cleanup;
end
function write_json(path,value)
fid=fopen(path,'w','n','UTF-8');assert(fid>=0,'CompositeDEV:Write','Cannot write %s.',path);
cleanup=onCleanup(@()fclose(fid));fprintf(fid,'%s\n',jsonencode(value,'PrettyPrint',true));clear cleanup;
end


