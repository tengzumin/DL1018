function opts=controller_options_dl1018(cfg,id,positionModel,attitudeModel,positionHeadMode)
% Build one DL1018 method without loading legacy settings or learned weights.
if nargin<3,positionModel=[];end
if nargin<4,attitudeModel=[];end
if nargin<5||isempty(positionHeadMode),positionHeadMode='frozen';end
id=upper(char(id));
opts=struct('formal_rbf_baseline',true,'position_rbf_frequency_hz',100, ...
    'attitude_rbf_frequency_hz',100,'rbf_phase_start',-.1, ...
    'rbf_full_phase_start',-.1,'rbf_position_gamma_scale', ...
    double(cfg.rbf.position.gamma_scale),'rbf_attitude_gamma_scale', ...
    double(cfg.rbf.attitude.gamma_scale),'rbf_position_output_enabled',true, ...
    'rbf_position_update_enabled',true,'rbf_attitude_enabled',true, ...
    'rbf_attitude_output_enabled',true,'rbf_attitude_update_enabled',true, ...
    'v1_adaptive',false);

switch id
    case 'B'
    case 'POS_OFF'
        opts.rbf_position_output_enabled=false;
        opts.rbf_position_update_enabled=false;
    case {'P_INIT_STUDENT','P_F','P_A','P_STAR','A_INIT_STUDENT','PA_F','PA_A'}
        assert(isstruct(positionModel)&&isequal(size(positionModel.output_W),[33,3]), ...
            'DL1018:PositionModel','Position model must export a 33-by-3 W0.');
        online=ismember(id,{'P_INIT_STUDENT','P_A'})|| ...
            (ismember(id,{'P_STAR','A_INIT_STUDENT','PA_F','PA_A'})&& ...
             strcmpi(positionHeadMode,'online'));
        assert(ismember(lower(char(positionHeadMode)),{'frozen','online'}), ...
            'DL1018:PositionHeadMode','Position Head mode must be frozen or online.');
        p=struct('enabled',true,'model',positionModel, ...
            'weight',double(positionModel.output_W),'update_enabled',online, ...
            'update_dt_scale',1,'beta_scale',1, ...
            'command_filter_coordination_v3_5',struct('enabled',true));
        opts.stage1_position_runtime=p;
        opts.rbf_position_output_enabled=false;
        opts.rbf_position_update_enabled=false;
    otherwise
        error('DL1018:Controller','Unknown method %s.',id);
end

if ismember(id,{'A_INIT_STUDENT','PA_F','PA_A'})
    assert(isstruct(attitudeModel)&&double(attitudeModel.input_dim)==29&& ...
        isfield(attitudeModel,'params')&&isequal(size(attitudeModel.params.spline_W),[32,29,8])&& ...
        isequal(size(attitudeModel.params.linear_W),[32,29])&& ...
        isequal(size(attitudeModel.params.readout__weight),[3,33]), ...
        'DL1018:AttitudeModel','Attitude model must be a legal X29 KAN.');
    opts.attitude_fusion_v3_6=struct('enabled',true,'lambda',1,'model',attitudeModel);
    opts.attitude_head_v39=struct('enabled',strcmp(id,'PA_A'), ...
        'gamma',.002,'sigma_per_s',.02,'projection_fro',.20);
    opts.rbf_attitude_enabled=false;
    opts.rbf_attitude_output_enabled=false;
    opts.rbf_attitude_update_enabled=false;
end
end
