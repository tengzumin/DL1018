function e=maxabs(a,b)
a=double(a(:));b=double(b(:));
assert(numel(a)==numel(b),'GRUTrackAudit:CompareShape','Replay arrays have different sizes.');
if isempty(a),e=0;else,e=max(abs(a-b));end
end
function verify_source_lock(study,release)
lockPath=fullfile(study,'SOURCE_LOCK_v1.json');
assert(strcmpi(hash_file(lockPath),char(release.source_lock_sha256)), ...
    'GRUTrackAudit:SourceLockHash','Source lock hash changed.');
lock=jsondecode(fileread(lockPath));runner=fullfile(study,'candidate_runner_work');
assert(strcmpi(char(java.io.File(lock.root).getCanonicalPath()), ...
    char(java.io.File(runner).getCanonicalPath())),'GRUTrackAudit:SourceRoot','Source root changed.');
for i=1:numel(lock.files)
    p=fullfile(runner,strrep(char(lock.files(i).relative_path),'/',filesep));
    assert(isfile(p)&&strcmpi(hash_file(p),char(lock.files(i).sha256)), ...
        'GRUTrackAudit:SourceHash','Source changed: %s.',char(lock.files(i).relative_path));
end
end
function h=hash_file(path)
fid=fopen(path,'rb');assert(fid>=0,'GRUTrackAudit:Read','Cannot read %s.',path);
cleanup=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear cleanup;
end
function write_json(path,value)
fid=fopen(path,'w','n','UTF-8');assert(fid>=0,'GRUTrackAudit:Write','Cannot write %s.',path);
cleanup=onCleanup(@()fclose(fid));fprintf(fid,'%s\n',jsonencode(value,'PrettyPrint',true));clear cleanup;
end
