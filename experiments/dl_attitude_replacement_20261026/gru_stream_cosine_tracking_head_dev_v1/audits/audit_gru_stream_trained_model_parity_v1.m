function report=audit_gru_stream_trained_model_parity_v1()
% Full 1999-event double replay against Python and trainer float32 references.
here=char(java.io.File(fileparts(mfilename('fullpath'))).getCanonicalPath());
study=fileparts(here);project=fileparts(fileparts(fileparts(study)));
runDir=fullfile(project,'experiments','dl_attitude_replacement_20261026', ...
    'gru_stream_cosine_c5_teacher_v1','runs','GRU32_STREAM72_COSINE_S2026102001');
modelPath=fullfile(runDir,'gru_stream_c5_teacher_weights_v1.mat');
trainerParityPath=fullfile(runDir,'stream_parity_vector_v1.mat');
referencePath=fullfile(here,'trained_gru_parity_v1.mat');
reportPath=fullfile(here,'TRAINED_MODEL_MATLAB_PARITY_v1.json');
assert(isfile(modelPath)&&isfile(trainerParityPath)&&isfile(referencePath)&&~isfile(reportPath), ...
    'GRUStream:TrainedParityFiles','Trainer weights, parity vector, Python reference, or output path is missing.');
modelRaw=load(modelPath);p=load(trainerParityPath);ref=load(referencePath);
model=struct('input_mean',modelRaw.input_mean,'input_std',modelRaw.input_std, ...
    'target_rms',modelRaw.target_rms,'gru_weight_ih',modelRaw.gru_weight_ih, ...
    'gru_weight_hh',modelRaw.gru_weight_hh,'gru_bias_ih',modelRaw.gru_bias_ih, ...
    'gru_bias_hh',modelRaw.gru_bias_hh,'head_weight',modelRaw.head_weight, ...
    'head_bias',modelRaw.head_bias);
X=double(p.input_features_raw);expectedY=double(ref.expected_output_double);
expectedH=double(ref.expected_hidden_double);trainerY=double(p.expected_output_raw_rad_s2);
trainerH=double(p.expected_hidden_float32(:));N=size(X,1);
assert(N==1999&&size(X,2)==13&&isequal(size(expectedY),[N 3])&& ...
    isequal(size(expectedH),[N 32])&&isequal(size(trainerY),[N 3])&&numel(trainerH)==32, ...
    'GRUStream:TrainedParityShape','Full trainer parity must have 1999 current-feature events.');
assert(isequal(double(model.input_mean(:)).',double(p.input_mean(:)).')&& ...
    isequal(double(model.input_std(:)).',double(p.input_std(:)).')&& ...
    isequal(double(model.target_rms(:)).',double(p.target_rms(:)).'), ...
    'GRUStream:TrainedNormalizer','Trainer parity normalizers differ from frozen model export.');
[memory,~]=gru_stream_attitude_step_v1('init',struct,struct,model);
Y=zeros(N,3);H=zeros(N,32);carryError=0;
J0=eye(3);dmax=[45;45;4.7124];
for k=1:N
    in=struct('feature',X(k,:).','J0',J0,'beta',0,'dmax',dmax);
    [memory,out]=gru_stream_attitude_step_v1('step',memory,in,model);
    Y(k,:)=out.raw_residual_rad_s2(:).';H(k,:)=out.hidden_after(:).';
    if k==1,carryError=max(carryError,max(abs(out.hidden_before(:))));
    else,carryError=max(carryError,max(abs(out.hidden_before(:)-H(k-1,:).')));end
    assert(out.event_count==k,'GRUStream:TrainedEventCount','GRU hidden state did not advance once per feature.');
end
outputError=max(abs(Y-expectedY),[],'all');hiddenError=max(abs(H-expectedH),[],'all');
trainerOutputError=max(abs(Y-trainerY),[],'all');trainerFinalHiddenError=max(abs(H(end,:).'-trainerH));
assert(outputError<1e-8&&hiddenError<1e-8&&carryError==0&& ...
    trainerOutputError<1e-4&&trainerFinalHiddenError<1e-5, ...
    'GRUStream:TrainedParity','Trained GRU full trajectory differs from Python double or trainer float32.');
modelSha=hash_file(modelPath);refModelSha=char(ref.model_sha256);
assert(strcmpi(modelSha,refModelSha),'GRUStream:TrainedModelSHA', ...
    'Trainer model changed after Python double replay.');
pyReport=load_json(fullfile(here,'TRAINED_MODEL_PYTHON_PARITY_v1.json'));
report=struct('status','PASS_TRAINED_GRU_FULL_SEQUENCE_MATLAB_PARITY', ...
    'Plant_calls',0,'training_started',false,'TEST_read',false,'event_count',N, ...
    'feature_dim',13,'hidden_dim',32,'python_double_output_max_abs_error',outputError, ...
    'python_double_hidden_full_trajectory_max_abs_error',hiddenError, ...
    'hidden_carry_max_abs_error',carryError, ...
    'matlab_double_output_max_abs_error_vs_trainer_float32',trainerOutputError, ...
    'matlab_double_final_hidden_max_abs_error_vs_trainer_float32',trainerFinalHiddenError, ...
    'model_sha256',modelSha,'trainer_parity_sha256',hash_file(trainerParityPath), ...
    'python_double_reference_sha256',hash_file(referencePath), ...
    'python_float32_output_max_abs_error_vs_trainer', ...
        pyReport.python_float32_output_max_abs_error_vs_trainer, ...
    'python_float32_final_hidden_max_abs_error_vs_trainer', ...
        pyReport.python_float32_final_hidden_max_abs_error_vs_trainer, ...
    'audit_script_sha256',hash_file([mfilename('fullpath') '.m']));
write_json(reportPath,report);disp(report);
end
function value=load_json(path),value=jsondecode(fileread(path));end
function h=hash_file(path)
fid=fopen(path,'rb');assert(fid>=0,'GRUStream:Read','Cannot read %s.',path);
cleanup=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear cleanup;
end
function write_json(path,value)
fid=fopen(path,'w','n','UTF-8');assert(fid>=0,'GRUStream:Write','Cannot write %s.',path);
cleanup=onCleanup(@()fclose(fid));fprintf(fid,'%s\n',jsonencode(value,'PrettyPrint',true));clear cleanup;
end