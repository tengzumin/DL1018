function report=preflight_ghp7_balanced_candidate_v1()
% Validate all six payloads and candidate bindings without calling the Plant.
auditDir=fileparts(mfilename('fullpath'));taskRoot=fileparts(auditDir);
researchRoot=fileparts(taskRoot);
sharedTask=fullfile(researchRoot,'pilot_runner_mlp15_c5_full72_v1');
sharedRuntime=fullfile(sharedTask,'candidate_runner_work','matlab','runtime');
newRuntime=fullfile(taskRoot,'candidate_runner_work','matlab','runtime');
addpath(sharedRuntime);activate_paired_runner();addpath(newRuntime,'-end');
payloadManifestPath=fullfile(researchRoot,'GHP7_PILOT_PAYLOAD_MANIFEST_v1.json');
payloadManifest=jsondecode(fileread(payloadManifestPath));
assert(strcmp(payloadManifest.status,'PASS')&&payloadManifest.scene_count==6&& ...
    payloadManifest.tests_data_read==false&&payloadManifest.payloads_copied==false, ...
    'GATE:PayloadManifest','Frozen GHP7 payload manifest failed.');
rows=repmat(struct('scene_id','','payload_sha256','','r_task_sha256','', ...
    'candidate_model_sha256','','position_options_sha256','', ...
    'max_tilt_deg',NaN,'dmax_rad_s2',zeros(1,3),'plant_called',false),6,1);
for i=1:numel(payloadManifest.records)
    rec=payloadManifest.records(i);
    if ~strcmp(rec.geometry_arm,'ACTIVE'),continue;end
    addpath(sharedRuntime);activate_paired_runner();addpath(newRuntime,'-end');
    prepared=prepare_balanced_mlp15_candidate_no_plant(char(rec.payload_path));
    assert(strcmp(char(prepared.scene.scene_id),char(rec.scene_id))&& ...
        strcmpi(prepared.scene_payload_sha256,char(rec.payload_file_sha256)), ...
        'GATE:PayloadIdentity','Prepared payload does not match its manifest.');
    rows(i)=struct('scene_id',char(rec.scene_id), ...
        'payload_sha256',char(rec.payload_file_sha256), ...
        'r_task_sha256',char(prepared.scene.R_task_sha256), ...
        'candidate_model_sha256',prepared.mlp15_model_sha256, ...
        'position_options_sha256',prepared.identity.common.position_options_sha256, ...
        'max_tilt_deg',rad2deg(double(prepared.cfg.control.limits.max_tilt)), ...
        'dmax_rad_s2',double(prepared.cfg.rbf.attitude.dmax(:)).', ...
        'plant_called',false);
end
assert(all(~cellfun(@isempty,{rows.scene_id}))&& ...
    all(abs([rows.max_tilt_deg]-30)<1e-10)&& ...
    all(arrayfun(@(r)isequal(r.dmax_rad_s2,[45,45,4.7124]),rows)), ...
    'GATE:PreparedRows','One or more GHP7 scenes or frozen limits failed no-Plant preparation.');
runsRoot=fullfile(researchRoot,'pilot_runs_mlp15_c5_ghp7_balance_v1');
assert(~isfolder(runsRoot),'GATE:OutputDir','Balanced candidate output directory already exists.');
report=struct('schema','DL1018_MLP15_C5_GHP7_BALANCE_NO_PLANT_PREFLIGHT_V1', ...
    'status','PASS_NO_PLANT','created_utc',utcNow(),'scene_count',numel(rows), ...
    'plant_invoked',false,'plant_calls',0,'closed_loop_started',false, ...
    'TEST48_read',false,'baselines_reexecuted',false,'baseline_raws_copied',false, ...
    'candidate_output_directory_absent',true,'max_tilt_deg',30, ...
    'dmax_rad_s2',[45,45,4.7124],'rows',rows);
outPath=fullfile(auditDir,'NO_PLANT_PREFLIGHT_GHP7_BALANCE_v1.json');
fid=fopen(outPath,'w');assert(fid>=0,'GATE:ReportWrite','Cannot write no-Plant preflight.');
cleanup=onCleanup(@()fclose(fid));
fwrite(fid,[jsonencode(report,'PrettyPrint',true) newline],'char');
clear cleanup
end

function s=utcNow()
s=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z'''));
end
