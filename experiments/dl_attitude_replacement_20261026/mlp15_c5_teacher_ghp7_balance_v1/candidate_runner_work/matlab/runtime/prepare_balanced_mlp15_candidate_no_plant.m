function prepared=prepare_balanced_mlp15_candidate_no_plant(scenePayloadPath)
% Reuse the locked C5 scene/position preparer, then bind the new MLP15 weights.
here=fileparts(mfilename('fullpath'));
candidateRunnerWork=fileparts(fileparts(here));
taskRoot=fileparts(candidateRunnerWork);
basePrepared=prepare_gate_candidate_no_plant(scenePayloadPath,'DL_MLP15','ACTIVE');

trainingDir=fullfile(taskRoot,'runs','C5_MLP15_GHP7_BALANCE_SEED2026102001');
trainingLockPath=fullfile(taskRoot,'MLP15_C5_GHP7_BALANCE_SOURCE_LOCK_v1.json');
trainingLock=jsondecode(fileread(trainingLockPath));
trainingConfig=jsondecode(fileread(fullfile(trainingDir,'training_config.json')));
trainingProgress=jsondecode(fileread(fullfile(trainingDir,'training_progress.json')));
trainingReceipt=jsondecode(fileread(fullfile(trainingDir,'run_receipt.json')));
weightsPath=fullfile(trainingDir,'mlp15_attitude_weights_v1.mat');
checkpointPath=fullfile(trainingDir,'final_step_60000.pt');
parityPath=fullfile(taskRoot,'audits','MATLAB_PARITY_GHP7_BALANCE_v1.json');
parity=jsondecode(fileread(parityPath));
offlinePath=fullfile(taskRoot,'GHP7_BALANCED_MLP15_G3_OFFLINE_AUDIT_v1.json');
offline=jsondecode(fileread(offlinePath));
weightsSha=sha256_file(weightsPath);

assert(strcmp(trainingLock.schema,'DL1018_MLP15_C5_GHP7_BALANCE_SOURCE_LOCK_V1')&& ...
    strcmp(trainingLock.status,'APPROVED_FOR_OFFLINE_TRAINING')&& ...
    trainingLock.training_release.approved&&trainingLock.training_release.authorized_jobs==1&& ...
    trainingLock.safety_context.plant_called==false&&trainingLock.safety_context.TEST48_read==false&& ...
    trainingLock.safety_context.ghp7_holdout_opened_by_training==false, ...
    'GATE:BalancedTrainingLock','GHP7-balanced training lock failed.');
assert(strcmp(trainingConfig.schema,'DL1018_MLP15_C5_GHP7_BALANCE_CONFIG_V1')&& ...
    strcmp(trainingConfig.status,'PASS')&&strcmp(trainingConfig.architecture,'MLP15')&& ...
    trainingConfig.optimizer_steps==60000&&trainingConfig.seed==2026102001&& ...
    trainingConfig.ghp7_holdout_opened==false&&trainingConfig.TEST48_read==false&& ...
    trainingConfig.plant_called==false&& ...
    strcmp(trainingConfig.source_lock_sha256,sha256_file(trainingLockPath)), ...
    'GATE:BalancedTrainingConfig','GHP7-balanced training configuration failed.');
assert(strcmp(trainingProgress.status,'PASS')&&trainingProgress.completed_steps==60000&& ...
    trainingProgress.target_steps==60000&&trainingProgress.ghp7_holdout_opened==false&& ...
    trainingProgress.TEST48_read==false&&trainingProgress.plant_called==false, ...
    'GATE:BalancedTrainingProgress','GHP7-balanced progress report failed.');
assert(strcmp(trainingReceipt.status,'PASS')&&trainingReceipt.training_job_count==1&& ...
    trainingReceipt.optimizer_steps==60000&&trainingReceipt.unique_training_scenes==76&& ...
    trainingReceipt.unique_training_events==151924&&trainingReceipt.ghp7_holdout_opened==false&& ...
    trainingReceipt.TEST48_read==false&&trainingReceipt.plant_called==false&& ...
    strcmpi(trainingReceipt.output_sha256.mlp15_attitude_weights_v1_mat,weightsSha)&& ...
    strcmpi(trainingReceipt.output_sha256.final_step_60000_pt,sha256_file(checkpointPath)), ...
    'GATE:BalancedTrainingReceipt','GHP7-balanced training receipt failed.');
assert(strcmp(parity.schema,'DL1018_MLP15_C5_GHP7_BALANCE_MATLAB_PARITY_V1')&& ...
    strcmp(parity.status,'PASS')&&parity.plant_called==false&&parity.TEST48_read==false&& ...
    parity.max_abs_error_raw_rad_s2<=parity.tolerance_rad_s2&& ...
    parity.tolerance_rad_s2<=1e-5, ...
    'GATE:BalancedParity','GHP7-balanced MATLAB parity failed.');
assert(strcmp(offline.status,'PASS_OFFLINE_FIT_GATE')&&offline.plant_called==false&& ...
    offline.TEST48_read==false&&offline.predeclared_gate.passed, ...
    'GATE:BalancedOfflineFit','GHP7-balanced G3 offline gate failed.');

mlpModel=load(weightsPath);
weightVars=whos('-file',weightsPath);
expectedNames={'input_mean','input_std','target_rms','fc1_weight','fc1_bias', ...
    'fc2_weight','fc2_bias','head_weight','head_bias'};
assert(numel(weightVars)==numel(expectedNames)&& ...
    isequal(sort(string({weightVars.name})),sort(string(expectedNames)))&& ...
    numel(mlpModel.input_mean)==13&&numel(mlpModel.input_std)==13&& ...
    numel(mlpModel.target_rms)==3&&isequal(size(mlpModel.fc1_weight),[64,195])&& ...
    isequal(size(mlpModel.fc2_weight),[32,64])&&isequal(size(mlpModel.head_weight),[3,32])&& ...
    all(isfinite([mlpModel.input_mean(:);mlpModel.input_std(:);mlpModel.target_rms(:); ...
    mlpModel.fc1_weight(:);mlpModel.fc1_bias(:);mlpModel.fc2_weight(:); ...
    mlpModel.fc2_bias(:);mlpModel.head_weight(:);mlpModel.head_bias(:)])), ...
    'GATE:BalancedWeights','GHP7-balanced MLP15 exported weights are invalid.');

cfg=basePrepared.cfg;
assert(abs(double(cfg.control.limits.max_tilt)-pi/6)<1e-12&& ...
    isequal(double(cfg.rbf.attitude.dmax(:)),[45;45;4.7124]), ...
    'GATE:LimiterIdentity','Candidate must retain the frozen C5 tilt and residual limits.');
opts=make_gate_holdout_options(cfg,basePrepared.model,'DL_MLP15','ACTIVE', ...
    struct,mlpModel,weightsSha);
identity=gate_holdout_identity_hashes(cfg,basePrepared.model,opts);
opts.gate_identity_lock=identity;
assert(strcmpi(identity.common.position_options_sha256, ...
    basePrepared.identity.common.position_options_sha256), ...
    'GATE:CommonPositionIdentity','Balanced MLP candidate changed the paired C5 position stack.');

sceneAudit=gate_holdout_validate_scene(basePrepared.scene,cfg,'ACTIVE');
prepared=basePrepared;
prepared.opts=opts;prepared.identity=identity;prepared.scene_audit=sceneAudit;
prepared.mlp15_model=mlpModel;prepared.mlp15_model_sha256=weightsSha;
prepared.mlp15_model_path=weightsPath;
prepared.mlp15_training_config_sha256=sha256_file(fullfile(trainingDir,'training_config.json'));
prepared.mlp15_training_progress_sha256=sha256_file(fullfile(trainingDir,'training_progress.json'));
prepared.mlp15_training_receipt_sha256=sha256_file(fullfile(trainingDir,'run_receipt.json'));
prepared.mlp15_training_source_lock_sha256=sha256_file(trainingLockPath);
prepared.mlp15_parity_report_sha256=sha256_file(parityPath);
prepared.mlp15_offline_audit_sha256=sha256_file(offlinePath);
prepared.mlp15_final_checkpoint_sha256=sha256_file(checkpointPath);
prepared.mlp15_optimizer_steps=double(trainingConfig.optimizer_steps);
end

function h=sha256_file(path)
fid=fopen(path,'rb');assert(fid>=0,'GATE:FileRead','Cannot read %s.',path);
cleanup=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear cleanup
end
