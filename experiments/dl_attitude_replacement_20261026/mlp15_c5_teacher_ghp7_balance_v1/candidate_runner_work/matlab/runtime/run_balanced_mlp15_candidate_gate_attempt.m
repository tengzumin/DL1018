function attemptDir=run_balanced_mlp15_candidate_gate_attempt(scenePayloadPath,attemptDir)
% Run one release-authorized MLP15 GHP7 candidate scene through the shared C5 loop.
entry=fileparts(mfilename('fullpath'));
candidateRunnerWork=fileparts(fileparts(entry));
taskRoot=fileparts(candidateRunnerWork);researchRoot=fileparts(taskRoot);
sharedTask=fullfile(researchRoot,'pilot_runner_mlp15_c5_full72_v1');
sharedRuntime=fullfile(sharedTask,'candidate_runner_work','matlab','runtime');
addpath(sharedRuntime);activate_paired_runner();addpath(entry,'-end');

releasePath=fullfile(taskRoot,'MLP15_C5_GHP7_BALANCE_PILOT_RELEASE_v1.json');
lockPath=fullfile(taskRoot,'MLP15_C5_GHP7_BALANCE_PILOT_SOURCE_LOCK_v1.json');
release=jsondecode(fileread(releasePath));lock=jsondecode(fileread(lockPath));
assert(strcmp(release.schema,'DL1018_MLP15_C5_GHP7_BALANCE_PILOT_RELEASE_V1')&& ...
    strcmp(release.status,'RELEASED')&&release.plant_calls_authorized>=1&& ...
    release.plant_calls_authorized<=release.max_plant_calls&&release.max_plant_calls==6&& ...
    strcmp(release.runtime_arm_id,'DL_MLP15')&&strcmp(release.geometry_arm,'ACTIVE')&& ...
    release.TEST48_read==false, ...
    'GATE:ReleaseInvalid','Balanced MLP15 pilot release is pending or invalid.');
lockSha=sha256_file(lockPath);
assert(strcmp(lock.schema,'DL1018_MLP15_C5_GHP7_BALANCE_PILOT_SOURCE_LOCK_V1')&& ...
    strcmp(lock.status,'APPROVED_FOR_CLOSED_LOOP_SCREEN')&& ...
    strcmpi(lockSha,release.candidate_source_lock_sha256), ...
    'GATE:SourceLock','Balanced candidate source lock differs from the release.');
for i=1:numel(lock.source_file_sha256)
    relative=char(lock.source_file_sha256(i).path);
    full=fullfile(projectRootFromTask(taskRoot),relative);
    assert(isfile(full)&&strcmpi(sha256_file(full),char(lock.source_file_sha256(i).sha256)), ...
        'GATE:SourceSHA','Locked candidate source changed: %s.',relative);
end
sharedLockPath=fullfile(sharedTask,'MLP15_C5_FULL72_PILOT_SOURCE_LOCK_v1.json');
assert(strcmpi(sha256_file(sharedLockPath),lock.shared_runner_source_lock_sha256), ...
    'GATE:SharedRunnerLock','Shared C5 runner source-lock SHA changed.');
sharedLock=jsondecode(fileread(sharedLockPath));
for i=1:numel(sharedLock.candidate_runner.files)
    source=fullfile(sharedTask,'candidate_runner_work', ...
        char(sharedLock.candidate_runner.files(i).relative_path));
    assert(isfile(source)&&strcmpi(sha256_file(source), ...
        char(sharedLock.candidate_runner.files(i).sha256)), ...
        'GATE:SharedRunnerSHA','Shared C5 runner source changed: %s.',source);
end

taskbookPath=fullfile(taskRoot,'MLP15_C5_GHP7_BALANCED_CLOSED_LOOP_TASKBOOK_v1.md');
noPlantPath=fullfile(taskRoot,'audits','NO_PLANT_PREFLIGHT_GHP7_BALANCE_v1.json');
staticPath=fullfile(taskRoot,'STATIC_PREFLIGHT_GHP7_BALANCE_v1.json');
codeAuditPath=fullfile(taskRoot,'audits','MLP15_GHP7_BALANCE_CODE_ANALYZER_v1.json');
assert(strcmpi(sha256_file(taskbookPath),release.taskbook_sha256)&& ...
    strcmpi(sha256_file(noPlantPath),release.no_plant_audit_sha256)&& ...
    strcmpi(sha256_file(staticPath),release.static_preflight_sha256)&& ...
    strcmpi(sha256_file(codeAuditPath),release.code_analyzer_sha256), ...
    'GATE:PreflightHash','One or more frozen no-Plant preflight artifacts changed.');
noPlant=jsondecode(fileread(noPlantPath));static=jsondecode(fileread(staticPath));
codeAudit=jsondecode(fileread(codeAuditPath));
assert(strcmp(noPlant.status,'PASS_NO_PLANT')&&noPlant.plant_calls==0&& ...
    noPlant.TEST48_read==false&&noPlant.scene_count==6&& ...
    strcmp(static.status,'PASS_STATIC_NO_PLANT')&&static.plant_calls_authorized==0&& ...
    static.TEST48_read==false&&strcmp(codeAudit.status,'PASS_NO_NEW_DIAGNOSTICS')&& ...
    codeAudit.plant_called==false&&codeAudit.TEST48_read==false, ...
    'GATE:Preflight','No-Plant/static/Code Analyzer preflight failed.');

payloadManifestPath=fullfile(researchRoot,'GHP7_PILOT_PAYLOAD_MANIFEST_v1.json');
baselineManifestPath=fullfile(researchRoot,'GHP7_BASELINE_REUSE_MANIFEST_v1.json');
assert(strcmpi(sha256_file(payloadManifestPath),release.payload_manifest_sha256)&& ...
    strcmpi(sha256_file(baselineManifestPath),release.baseline_reuse_manifest_sha256), ...
    'GATE:ReuseManifestSHA','GHP7 payload or baseline reuse manifest changed.');
payloadManifest=jsondecode(fileread(payloadManifestPath));
baselineManifest=jsondecode(fileread(baselineManifestPath));
assert(strcmp(payloadManifest.status,'PASS')&&payloadManifest.scene_count==6&& ...
    payloadManifest.tests_data_read==false&&payloadManifest.payloads_copied==false&& ...
    strcmp(baselineManifest.status,'PASS')&&baselineManifest.record_count==12&& ...
    baselineManifest.test_data_read==false&&baselineManifest.raw_files_copied==false&& ...
    baselineManifest.baselines_reexecuted==false, ...
    'GATE:ReuseManifest','GHP7 payload/baseline reuse manifests failed.');
sceneId=scenePayloadPathToId(scenePayloadPath);
payloadHit=find(strcmp({payloadManifest.records.scene_id},sceneId)& ...
    strcmp({payloadManifest.records.geometry_arm},'ACTIVE'));
assert(isscalar(payloadHit),'GATE:Payload','Payload is not a frozen ACTIVE GHP7 scene.');
record=payloadManifest.records(payloadHit);
canonical=char(java.io.File(char(record.payload_path)).getCanonicalPath());
scenePayloadPath=char(java.io.File(char(scenePayloadPath)).getCanonicalPath());
assert(strcmpi(canonical,scenePayloadPath)&&isfile(scenePayloadPath)&& ...
    strcmpi(sha256_file(scenePayloadPath),char(record.payload_file_sha256)), ...
    'GATE:PayloadIdentity','Payload path or hash differs from its frozen identity.');
assert(any(strcmp(release.authorized_scene_ids,sceneId)), ...
    'GATE:SceneApproval','This scene has not been added to the approved release.');

prepared=prepare_balanced_mlp15_candidate_no_plant(scenePayloadPath);
assert(strcmp(char(prepared.scene.scene_id),sceneId)&& ...
    strcmpi(prepared.mlp15_model_sha256,release.model_sha256)&& ...
    prepared.mlp15_optimizer_steps==60000, ...
    'GATE:PreparedCandidate','Prepared candidate differs from this frozen release.');
runsRoot=char(java.io.File(fullfile(researchRoot,'pilot_runs_mlp15_c5_ghp7_balance_v1')).getCanonicalPath());
attemptDir=char(java.io.File(char(attemptDir)).getCanonicalPath());
assert(startsWith(lower(attemptDir),[lower(runsRoot) filesep])&& ...
    ~isfolder(attemptDir)&&~isfile(attemptDir), ...
    'GATE:OutputPath','Attempt output must be a new directory inside the isolated candidate output root.');
markers=dir(fullfile(runsRoot,'**','attempt_started.marker'));
assert(numel(markers)<double(release.plant_calls_authorized)&& ...
    numel(markers)<double(release.max_plant_calls), ...
    'GATE:CallBudget','Authorized candidate Plant-call budget is exhausted.');
if isempty(markers)
    assert(strcmp(sceneId,'DL1018_GHP7_G1_W00'), ...
        'GATE:FirstScene','The first engineering gate must be G1/W00.');
elseif release.continue_after_first_scene_approved==false
    error('GATE:Continuation','Remaining scenes have not been released after G1/W00 review.');
end
for i=1:numel(markers)
    markerPath=fullfile(markers(i).folder,markers(i).name);
    prior=jsondecode(fileread(markerPath));
    assert(isfield(prior,'scene_id')&&isfield(prior,'schema')&& ...
        strcmp(prior.schema,'DL1018_MLP15_C5_GHP7_BALANCE_ATTEMPT_STARTED_V1'), ...
        'GATE:AttemptMarker','An existing attempt marker is unreadable or has an unexpected schema.');
    assert(~strcmp(prior.scene_id,sceneId), ...
        'GATE:DuplicateScene','Scene already has a counted attempt marker.');
end

assert(java.io.File(runsRoot).mkdirs()||isfolder(runsRoot), ...
    'GATE:RunRoot','Cannot create balanced candidate run root.');
assert(java.io.File(attemptDir).mkdirs(), ...
    'GATE:AttemptCreate','Cannot create unique candidate attempt directory.');
startedUtc=utcNow();
runIdentity=struct('schema','DL1018_MLP15_C5_GHP7_BALANCE_RUN_START_V1', ...
    'scene_id',sceneId,'attitude_arm','DL_MLP15_C5_GHP7_BALANCED', ...
    'runtime_arm_id','DL_MLP15','geometry_arm','ACTIVE','started_utc',startedUtc, ...
    'pilot_release_sha256',sha256_file(releasePath), ...
    'candidate_source_lock_sha256',lockSha, ...
    'taskbook_sha256',release.taskbook_sha256, ...
    'model_sha256',release.model_sha256,'final_checkpoint_sha256',release.final_checkpoint_sha256, ...
    'training_source_lock_sha256',release.training_source_lock_sha256, ...
    'parity_report_sha256',release.parity_report_sha256, ...
    'offline_audit_sha256',release.offline_audit_sha256, ...
    'payload_path',scenePayloadPath,'payload_sha256',prepared.scene_payload_sha256, ...
    'r_task_sha256',char(prepared.scene.R_task_sha256), ...
    'c5_input_lock_sha256',prepared.c5_input_lock_sha256, ...
    'c5_snapshot_sha256',prepared.c5_snapshot_sha256, ...
    'position_model_sha256',prepared.position_model_mat_sha256, ...
    'common_identity',prepared.identity.common,'geometry_identity',prepared.identity.geometry, ...
    'max_tilt_deg',30,'dmax_rad_s2',[45,45,4.7124], ...
    'plant_entry','run_gate_holdout_closed_loop(scene,cfg,opts)');
write_json(fullfile(attemptDir,'attempt_started.marker'),struct( ...
    'schema','DL1018_MLP15_C5_GHP7_BALANCE_ATTEMPT_STARTED_V1', ...
    'scene_id',sceneId,'created_utc',startedUtc,'stage','RUNNING'));
write_json(fullfile(attemptDir,'run_start.json'),runIdentity);
try
    log=run_gate_holdout_closed_loop(prepared.scene,prepared.cfg,prepared.opts);
    assert(isfield(log,'complete_transitions')&&isfield(log,'actual_transition_count')&& ...
        isfield(log,'actual_state_sample_count'), ...
        'GATE:TransitionAudit','Closed-loop log omitted completion fields.');
    scene=prepared.scene;
    save(fullfile(attemptDir,'raw_run.mat'),'log','scene','runIdentity','-v7.3');
    rawPath=fullfile(attemptDir,'raw_run.mat');
    status=struct('schema','DL1018_MLP15_C5_GHP7_BALANCE_RUN_STATUS_V1', ...
        'state','COMPLETED','scene_id',sceneId, ...
        'attitude_arm','DL_MLP15_C5_GHP7_BALANCED','runtime_arm_id','DL_MLP15', ...
        'geometry_arm','ACTIVE','finished_utc',utcNow(),'plant_calls',1, ...
        'payload_sha256',prepared.scene_payload_sha256,'raw_path',rawPath, ...
        'raw_sha256',sha256_file(rawPath), ...
        'complete_transitions',logical(log.complete_transitions), ...
        'actual_transition_count',double(log.actual_transition_count), ...
        'actual_state_sample_count',double(log.actual_state_sample_count), ...
        'status_value',char(string(log.status)), ...
        'safety_stop_reason',char(string(log.safety_stop_reason)), ...
        'candidate_source_lock_sha256',lockSha);
    write_json(fullfile(attemptDir,'run_status.json'),status);
    fprintf('MLP15_C5_GHP7_BALANCE_ATTEMPT_DIR=%s',attemptDir);
catch ME
    write_json(fullfile(attemptDir,'run_status.json'),struct( ...
        'schema','DL1018_MLP15_C5_GHP7_BALANCE_RUN_STATUS_V1', ...
        'state','FAILED','scene_id',sceneId, ...
        'attitude_arm','DL_MLP15_C5_GHP7_BALANCED','runtime_arm_id','DL_MLP15', ...
        'geometry_arm','ACTIVE','failed_utc',utcNow(),'plant_calls',1, ...
        'payload_sha256',prepared.scene_payload_sha256, ...
        'error_identifier',char(ME.identifier),'error_message',char(ME.message), ...
        'candidate_source_lock_sha256',lockSha));
    rethrow(ME);
end
end

function id=scenePayloadPathToId(path)
[~,name]=fileparts(path);name=string(name);suffix='_ACTIVE_scene_payload';
assert(endsWith(name,suffix),'GATE:PayloadName','Unexpected ACTIVE scene-payload filename.');
id=char(extractBefore(name,suffix));
end

function root=projectRootFromTask(taskRoot)
root=fileparts(fileparts(fileparts(taskRoot)));
end

function h=sha256_file(path)
fid=fopen(path,'rb');assert(fid>=0,'GATE:FileRead','Cannot read %s.',path);
cleanup=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear cleanup
end

function write_json(path,value)
fid=fopen(path,'w');assert(fid>=0,'GATE:JsonWrite','Cannot write %s.',path);
cleanup=onCleanup(@()fclose(fid));
fwrite(fid,[jsonencode(value,'PrettyPrint',true) newline],'char');clear cleanup
end

function s=utcNow()
s=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z'''));
end
