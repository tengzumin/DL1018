function attemptDir=run_mlp15_candidate_gate_attempt(scenePayloadPath,attemptDir)
% Run one root-approved C5-24 candidate scene through the explicit Plant entry.
entry=fileparts(mfilename('fullpath'));
runnerTaskRoot=fileparts(fileparts(fileparts(entry)));
researchRoot=fileparts(runnerTaskRoot);
releasePath=fullfile(researchRoot,'MLP15_C5_24_PILOT_RELEASE_v1.json');
assert(isfile(releasePath),'GATE:ReleaseMissing','No C5-24 pilot release exists.');
release=jsondecode(fileread(releasePath));
assert(strcmp(release.schema,'DL1018_MLP15_C5_24_GHP7_PILOT_RELEASE_V1')&& ...
    strcmp(release.status,'RELEASED')&&release.plant_calls_authorized>=1&& ...
    release.plant_calls_authorized<=release.max_plant_calls&&release.max_plant_calls==6&& ...
    strcmp(release.candidate_arm_id,'DL_MLP15_C5_24')&& ...
    strcmp(release.runtime_arm_id,'DL_MLP15')&&strcmp(release.geometry_arm,'ACTIVE')&& ...
    ~release.test_data_read, ...
    'GATE:ReleaseInvalid','Release is pending root approval or has an invalid C5-24 scope.');

sourceLockPath=fullfile(researchRoot,'MLP15_C5_24_CANDIDATE_SOURCE_LOCK_v1.json');
sourceLockSha=char(release.candidate_source_lock_sha256);
assert(isfile(sourceLockPath)&&strcmpi(sha256_file(sourceLockPath),sourceLockSha), ...
    'GATE:SourceLock','C5-24 candidate source lock differs from release.');
runnerAuditPath=fullfile(researchRoot,'MATLAB_NO_PLANT_AUDIT_MLP15_C5_24_v1.json');
codeAuditPath=fullfile(researchRoot,'MLP15_C5_24_CODE_ANALYZER_v1.json');
assert(isfile(runnerAuditPath)&&strcmpi(sha256_file(runnerAuditPath),release.no_plant_audit_sha256)&& ...
    isfile(codeAuditPath)&&strcmpi(sha256_file(codeAuditPath),release.code_analyzer_sha256), ...
    'GATE:PreflightHash','C5-24 preflight reports differ from the release.');
runnerAudit=jsondecode(fileread(runnerAuditPath));
codeAudit=jsondecode(fileread(codeAuditPath));
assert(strcmp(runnerAudit.status,'PASS_NO_PLANT')&&~runnerAudit.plant_invoked&& ...
    ~runnerAudit.test_data_read&&runnerAudit.runner_matlab_file_count==52&& ...
    strcmp(codeAudit.status,'PASS_NO_NEW_DIAGNOSTICS')&& ...
    codeAudit.plant_invoked==false&&codeAudit.test_data_read==false, ...
    'GATE:Preflight','C5-24 preflight evidence is incomplete or failed.');

runnerRoot=fullfile(runnerTaskRoot,'candidate_runner_work');
verify_candidate_tree(jsondecode(fileread(sourceLockPath)),runnerRoot);
prepared=prepare_gate_candidate_no_plant(scenePayloadPath,'DL_MLP15','ACTIVE');
taskbookPath=fullfile(researchRoot,'MLP15_C5_24_CLOSED_LOOP_TASKBOOK_v3.md');
payloadManifestPath=fullfile(researchRoot,'GHP7_PILOT_PAYLOAD_MANIFEST_v1.json');
baselineManifestPath=fullfile(researchRoot,'GHP7_BASELINE_REUSE_MANIFEST_v1.json');
assert(strcmpi(sha256_file(taskbookPath),release.taskbook_sha256)&& ...
    strcmpi(prepared.dataset_manifest_sha256,release.dataset_manifest_sha256)&& ...
    strcmpi(prepared.parity_report_sha256,release.parity_report_sha256)&& ...
    strcmpi(prepared.mlp15_training_config_sha256,release.training_config_sha256)&& ...
    strcmpi(prepared.mlp15_training_progress_sha256,release.training_progress_sha256)&& ...
    strcmpi(prepared.mlp15_training_receipt_sha256,release.training_receipt_sha256)&& ...
    strcmpi(prepared.mlp15_model_mat_sha256,release.model_sha256)&& ...
    strcmpi(prepared.mlp15_best_pt_sha256,release.best_pt_sha256)&& ...
    prepared.mlp15_best_step==release.best_step&& ...
    strcmpi(prepared.payload_manifest_sha256,release.payload_manifest_sha256)&& ...
    strcmpi(sha256_file(payloadManifestPath),release.payload_manifest_sha256)&& ...
    strcmpi(prepared.baseline_reuse_manifest_sha256,release.baseline_reuse_manifest_sha256)&& ...
    strcmpi(sha256_file(baselineManifestPath),release.baseline_reuse_manifest_sha256)&& ...
    strcmpi(prepared.c5_receipt_sha256,release.c5_receipt_sha256), ...
    'GATE:ReleaseIdentity','Taskbook, C5-24 training, payload, or baseline identity differs.');

allowed=release.pilot_payloads;
hit=find(strcmp({allowed.scene_id},char(prepared.scene.scene_id)) & ...
    strcmp({allowed.geometry_arm},'ACTIVE') & ...
    strcmpi({allowed.payload_sha256},prepared.scene_payload_sha256) & ...
    strcmpi({allowed.payload_path},prepared.scene_payload_path));
assert(isscalar(hit),'GATE:PayloadRelease','Payload is not one of the six locked GHP7 scenes.');
assert(any(strcmp(release.authorized_scene_ids,char(prepared.scene.scene_id))), ...
    'GATE:SceneApproval','Root has not authorized this scene.');

runsRoot=char(java.io.File(fullfile(researchRoot,'pilot_runs_mlp15_c5_24_v1')).getCanonicalPath());
attemptDir=char(java.io.File(char(attemptDir)).getCanonicalPath());
assert(startsWith(lower(attemptDir),[lower(runsRoot) filesep])&& ...
    ~isfolder(attemptDir)&&~isfile(attemptDir), ...
    'GATE:OutputPath','Attempt output must be a new directory under pilot_runs_mlp15_c5_24_v1.');
markers=dir(fullfile(runsRoot,'**','attempt_started.marker'));
assert(numel(markers)<double(release.plant_calls_authorized)&& ...
    numel(markers)<double(release.max_plant_calls), ...
    'GATE:CallBudget','The authorized C5-24 Plant-call budget is exhausted.');
if isempty(markers)
    assert(strcmp(char(prepared.scene.scene_id),'DL1018_GHP7_G1_W00'), ...
        'GATE:FirstScene','The first C5-24 engineering gate must be G1/W00.');
elseif ~release.continue_after_first_scene_approved
    error('GATE:ContinuationApproval','Root has not approved continuation after G1/W00 review.');
end
for i=1:numel(markers)
    startPath=fullfile(markers(i).folder,'run_start.json');
    if isfile(startPath)
        prior=jsondecode(fileread(startPath));
        assert(~strcmp(char(prior.scene_id),char(prepared.scene.scene_id)), ...
            'GATE:DuplicateScene','This GHP7 scene already has a started C5-24 attempt.');
    end
end

if ~isfolder(runsRoot)
    assert(java.io.File(runsRoot).mkdirs(),'GATE:RunRoot','Cannot create C5-24 run root.');
end
assert(java.io.File(attemptDir).mkdirs(),'GATE:AttemptCreate','Could not create unique C5-24 attempt directory.');
startedUtc=utcNow();
runIdentity=struct('schema','DL1018_MLP15_C5_24_GHP7_RUN_START_V1', ...
    'scene_id',char(prepared.scene.scene_id),'attitude_arm','DL_MLP15_C5_24', ...
    'runtime_arm_id','DL_MLP15','geometry_arm','ACTIVE','started_utc',startedUtc, ...
    'pilot_release_sha256',sha256_file(releasePath),'taskbook_sha256',release.taskbook_sha256, ...
    'candidate_source_lock_sha256',sourceLockSha,'code_analyzer_sha256',release.code_analyzer_sha256, ...
    'no_plant_audit_sha256',release.no_plant_audit_sha256, ...
    'dataset_manifest_sha256',release.dataset_manifest_sha256, ...
    'training_progress_sha256',release.training_progress_sha256, ...
    'training_config_sha256',release.training_config_sha256, ...
    'training_receipt_sha256',release.training_receipt_sha256, ...
    'parity_report_sha256',release.parity_report_sha256,'best_pt_sha256',release.best_pt_sha256, ...
    'best_step',release.best_step,'mlp15_model_mat_sha256',release.model_sha256, ...
    'scene_payload_path',prepared.scene_payload_path, ...
    'scene_payload_sha256',prepared.scene_payload_sha256, ...
    'r_task_sha256',char(prepared.scene.R_task_sha256), ...
    'c5_input_lock_sha256',prepared.c5_input_lock_sha256, ...
    'c5_snapshot_sha256',prepared.c5_snapshot_sha256, ...
    'position_model_mat_sha256',prepared.position_model_mat_sha256, ...
    'cfg_identity',prepared.identity.geometry,'common_identity',prepared.identity.common, ...
    'runner_entry','run_gate_holdout_closed_loop(scene,cfg,opts)');
write_json(fullfile(attemptDir,'attempt_started.marker'),struct( ...
    'schema','DL1018_MLP15_C5_24_ATTEMPT_STARTED_V1','scene_id',runIdentity.scene_id, ...
    'created_utc',startedUtc,'stage','RUNNING'));
write_json(fullfile(attemptDir,'run_start.json'),runIdentity);
try
    log=run_gate_holdout_closed_loop(prepared.scene,prepared.cfg,prepared.opts);
    assert(isfield(log,'complete_transitions')&&isscalar(log.complete_transitions), ...
        'GATE:TransitionAudit','C5-24 runner omitted complete-transition status.');
    scene=prepared.scene;
    save(fullfile(attemptDir,'raw_run.mat'),'log','scene','runIdentity','-v7.3');
    status=struct('schema','DL1018_MLP15_C5_24_GHP7_RUN_STATUS_V1','state','COMPLETED', ...
        'scene_id',runIdentity.scene_id,'attitude_arm','DL_MLP15_C5_24', ...
        'runtime_arm_id','DL_MLP15','geometry_arm','ACTIVE','finished_utc',utcNow(), ...
        'plant_calls',1,'scene_payload_sha256',prepared.scene_payload_sha256, ...
        'raw_output_path',fullfile(attemptDir,'raw_run.mat'), ...
        'raw_output_sha256',sha256_file(fullfile(attemptDir,'raw_run.mat')), ...
        'complete_transitions',logical(log.complete_transitions), ...
        'actual_transition_count',double(log.actual_transition_count), ...
        'actual_state_sample_count',double(log.actual_state_sample_count), ...
        'status_value',char(string(log.status)), ...
        'safety_stop_reason',char(string(log.safety_stop_reason)), ...
        'source_lock_sha256',sourceLockSha);
    write_json(fullfile(attemptDir,'run_status.json'),status);
    fprintf('MLP15_C5_24_CANDIDATE_ATTEMPT_DIR=%s',attemptDir);
catch ME
    write_json(fullfile(attemptDir,'run_status.json'),struct( ...
        'schema','DL1018_MLP15_C5_24_GHP7_RUN_STATUS_V1','state','FAILED', ...
        'scene_id',runIdentity.scene_id,'attitude_arm','DL_MLP15_C5_24', ...
        'runtime_arm_id','DL_MLP15','geometry_arm','ACTIVE','failed_utc',utcNow(), ...
        'plant_calls',1,'scene_payload_sha256',prepared.scene_payload_sha256, ...
        'error_identifier',char(ME.identifier),'error_message',char(ME.message), ...
        'source_lock_sha256',sourceLockSha));
    rethrow(ME);
end
end

function verify_candidate_tree(lock,runnerRoot)
assert(strcmp(char(lock.schema),'DL1018_MLP15_CANDIDATE_SOURCE_LOCK_C5_24_V1')&& ...
    strcmpi(char(java.io.File(char(lock.root)).getCanonicalPath()), ...
    char(java.io.File(runnerRoot).getCanonicalPath())), ...
    'GATE:SourceLockSchema','Unexpected C5-24 candidate source lock.');
rootCanonical=char(java.io.File(runnerRoot).getCanonicalPath());
rootPrefix=[rootCanonical filesep];
expectedFiles=dir(fullfile(runnerRoot,'matlab','**','*.m'));
assert(numel(expectedFiles)==numel(lock.files),'GATE:SourceTreeCount', ...
    'Locked C5-24 source file count changed.');
for i=1:numel(lock.files)
    p=fullfile(runnerRoot,char(lock.files(i).relative_path));
    canonical=char(java.io.File(p).getCanonicalPath());
    assert(startsWith(lower(canonical),lower(rootPrefix))&&isfile(p)&& ...
        strcmpi(sha256_file(p),char(lock.files(i).sha256)), ...
        'GATE:SourceTreeSHA','C5-24 candidate source changed or escaped its tree: %s.',p);
end
end

function h=sha256_file(p)
fid=fopen(p,'rb');assert(fid>=0,'GATE:FileRead','Cannot read %s.',p);
closer=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear closer;
end

function write_json(p,x)
fid=fopen(p,'w');assert(fid>=0,'GATE:JsonWrite','Cannot write %s.',p);
closer=onCleanup(@()fclose(fid));fwrite(fid,[jsonencode(x,'PrettyPrint',true) newline],'char');clear closer;
end

function s=utcNow()
s=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z'''));
end
