function opts=make_gate_holdout_options(cfg,positionModel,attitudeArm,geometryArm,identityLock,tcnModel,tcnModelSha256)
% Bind a C5 method arm and a geometry-specific lock to the frozen C5 option builder.
if nargin<5,identityLock=struct;end
if nargin<6,tcnModel=struct;end
if nargin<7,tcnModelSha256='';end
attitudeArm=upper(char(attitudeArm));
geometryArm=upper(char(geometryArm));
spec=gate_attitude_arm_spec(attitudeArm);
assert(ismember(geometryArm,{'ACTIVE','FIXED_MIN','FIXED_BOUND15'}), ...
    'GATE:GeometryArm','Unknown gate geometry arm.');
[baseline,candidate]=make_paired_c5_options(cfg,positionModel);
if strcmp(spec.paired_arm,'baseline')
    opts=baseline;
else
    opts=candidate;
end
if strcmp(attitudeArm,'DL_TCN')
    required={'input_mean','input_std','target_rms','input_weight','input_bias', ...
        'conv1_weight','conv1_bias','conv2_weight','conv2_bias','conv3_weight','conv3_bias', ...
        'head_weight','head_bias'};
    assert(isstruct(tcnModel)&&all(isfield(tcnModel,required))&& ...
        numel(tcnModel.input_mean)==13&&numel(tcnModel.input_std)==13&& ...
        numel(tcnModel.target_rms)==3&&isequal(size(tcnModel.input_weight),[32,13])&& ...
        numel(tcnModel.input_bias)==32&&isequal(size(tcnModel.head_weight),[3,32])&& ...
        numel(tcnModel.head_bias)==3&&all(isfinite(double(tcnModel.input_mean(:))))&& ...
        all(isfinite(double(tcnModel.input_std(:))))&&all(double(tcnModel.input_std(:))>0)&& ...
        all(isfinite(double(tcnModel.target_rms(:))))&&all(double(tcnModel.target_rms(:))>0)&& ...
        all(isfinite(double(tcnModel.input_weight(:))))&&all(isfinite(double(tcnModel.input_bias(:))))&& ...
        all(isfinite(double(tcnModel.head_weight(:))))&&all(isfinite(double(tcnModel.head_bias(:))))&& ...
        ischar(tcnModelSha256)&&numel(tcnModelSha256)==64&&all(ismember(lower(tcnModelSha256),'0123456789abcdef')), ...
        'GATE:TCNModel','Frozen DL_TCN model, normalizers, or model SHA are invalid.');
    for layer=1:3
        w=tcnModel.(sprintf('conv%d_weight',layer));b=tcnModel.(sprintf('conv%d_bias',layer));
        assert(isequal(size(w),[32,32,3])&&numel(b)==32&& ...
            all(isfinite(double(w(:))))&&all(isfinite(double(b(:)))), ...
            'GATE:TCNModel','Frozen DL_TCN convolution layer %d is invalid.',layer);
    end
    opts.tcn_attitude_model=tcnModel;
    opts.tcn_attitude_model_sha256=lower(tcnModelSha256);
elseif ~isempty(fieldnames(tcnModel))||~isempty(tcnModelSha256)
    error('GATE:UnexpectedTCNModel','A TCN model may only be supplied for the DL_TCN arm.');
end
opts.gate_attitude_arm=attitudeArm;
opts.gate_geometry_arm=geometryArm;
opts.gate_identity_lock=identityLock;
end
