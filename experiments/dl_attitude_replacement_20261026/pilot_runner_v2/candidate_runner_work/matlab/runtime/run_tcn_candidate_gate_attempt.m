function attemptDir=run_tcn_candidate_gate_attempt(scenePayloadPath,attemptDir)
%RUN_TCN_CANDIDATE_GATE_ATTEMPT Released one-call wrapper for the frozen DL_TCN pilot.
entry=fileparts(mfilename('fullpath'));
runnerTaskRoot=fileparts(fileparts(fileparts(entry)));
researchRoot=fileparts(runnerTaskRoot);
releasePath=fullfile(researchRoot,'PILOT_RELEASE_v1.json');
assert(isfile(releasePath),'GATE:ReleaseMissing','No root-issued TCN pilot release exists.');
release=jsondecode(fileread(releasePath));
assert(strcmp(char(release.schema),'DL1018_TCN_GHP7_PILOT_RELEASE_V1')&& ...
    strcmp(char(release.status),'RELEASED')&&double(release.plant_calls_authorized)==6&& ...
    strcmp(char(release.candidate_arm_id),'DL_TCN')&&strcmp(char(release.geometry_arm),'ACTIVE')&& ...
    ~logical(release.tests_data_read), ...
    'GATE:ReleaseInvalid','Release does not authorize the frozen six-scene DL_TCN pilot.');
sourceLockPath=fullfile(researchRoot,'CANDIDATE_SOURCE_LOCK_v1.json');
sourceLockSha=char(release.candidate_source_lock_sha256);
assert(isfile(sourceLockPath)&&strcmpi(sha256_file(sourceLockPath),sourceLockSha), ...
    'GATE:SourceLock','TCN pilot source lock differs from release.');
sourceLock=jsondecode(fileread(sourceLockPath));
runnerRoot=fullfile(runnerTaskRoot,'candidate_runner_work');
verify_candidate_tree(sourceLock,runnerRoot);

prepared=prepare_gate_candidate_no_plant(scenePayloadPath,'DL_TCN','ACTIVE');
taskbookPath=fullfile(researchRoot,'DL_ATTITUDE_REPLACEMENT_TASKBOOK_v1_FROZEN_ZH.md');
payloadManifestPath=fullfile(researchRoot,'GHP7_PILOT_PAYLOAD_MANIFEST_v1.json');
baselineManifestPath=fullfile(researchRoot,'GHP7_BASELINE_REUSE_MANIFEST_v1.json');
trainingDir=fullfile(researchRoot,'training_v1_retry01');
assert(strcmpi(sha256_file(taskbookPath),char(release.taskbook_sha256))&& ...
    strcmpi(prepared.taskbook_sha256,char(release.taskbook_sha256))&& ...
    strcmpi(sha256_file(payloadManifestPath),char(release.payload_manifest_sha256))&& ...
    strcmpi(prepared.payload_manifest_sha256,char(release.payload_manifest_sha256))&& ...
    strcmpi(sha256_file(baselineManifestPath),char(release.baseline_reuse_manifest_sha256))&& ...
    strcmpi(prepared.baseline_reuse_manifest_sha256,char(release.baseline_reuse_manifest_sha256))&& ...
    strcmpi(sha256_file(fullfile(researchRoot,'TRAINING_RELEASE_v2.json')), ...
        char(release.training_release_sha256))&& ...
    strcmpi(prepared.tcn_training_release_sha256,char(release.training_release_sha256))&& ...
    strcmpi(prepared.c5_receipt_sha256,char(release.c5_receipt_sha256))&& ...
    strcmpi(sha256_file(fullfile(trainingDir,'training_config.json')), ...
        char(release.training_config_sha256))&& ...
    strcmpi(sha256_file(fullfile(trainingDir,'tcn_attitude_weights_v1.mat')), ...
        char(release.model_sha256))&&strcmpi(prepared.tcn_model_mat_sha256,char(release.model_sha256))&& ...
    double(prepared.tcn_best_step)==double(release.best_step), ...
    'GATE:ReleaseIdentity','Taskbook, data manifests, training release/config, or model differs from release.');
allowed=release.pilot_payloads;
hit=find(strcmp({allowed.scene_id},char(prepared.scene.scene_id))&& ...
    strcmp({allowed.geometry_arm},'ACTIVE')&& ...
    strcmpi({allowed.payload_sha256},prepared.scene_payload_sha256)&& ...
    strcmpi({allowed.payload_path},prepared.scene_payload_path));
assert(numel(hit)==1,'GATE:PayloadRelease','Payload is not one of the six released GHP7 pilot scenes.');

runsRoot=char(java.io.File(fullfile(researchRoot,'pilot_runs')).getCanonicalPath());
attemptDir=char(java.io.File(char(attemptDir)).getCanonicalPath());
assert(startsWith(lower(attemptDir),[lower(runsRoot) filesep])&& ...
    ~isfolder(attemptDir)&&~isfile(attemptDir), ...
    'GATE:OutputPath','Attempt output must be a new directory under this experiment pilot_runs.');
if ~isfolder(runsRoot),assert(java.io.File(runsRoot).mkdirs(),'GATE:RunRoot','Cannot create pilot_runs.');end
markers=dir(fullfile(runsRoot,'**','attempt_started.marker'));
assert(numel(markers)<double(release.plant_calls_authorized), ...
    'GATE:CallBudget','All released Plant calls have already been consumed.');
for i=1:numel(markers)
    priorStart=fullfile(markers(i).folder,'run_start.json');
    if isfile(priorStart)
        prior=jsondecode(fileread(priorStart));
        assert(~strcmp(char(prior.scene_id),char(prepared.scene.scene_id)), ...
            'GATE:DuplicateScene','This GHP7 scene already has a started candidate attempt.');
    end
end

folder=java.io.File(attemptDir);
assert(folder.mkdirs(),'GATE:AttemptCreate','Could not create unique candidate attempt directory.');
startedUtc=utcNow();
runIdentity=struct('schema','DL1018_TCN_GHP7_RUN_START_V1', ...
    'scene_id',char(prepared.scene.scene_id),'attitude_arm','DL_TCN', ...
    'geometry_arm','ACTIVE','started_utc',startedUtc, ...
    'taskbook_sha256',char(release.taskbook_sha256), ...
    'candidate_source_lock_sha256',sourceLockSha, ...
    'scene_payload_path',prepared.scene_payload_path, ...
    'scene_payload_sha256',prepared.scene_payload_sha256, ...
    'r_task_sha256',char(prepared.scene.R_task_sha256), ...
    'c5_input_lock_sha256',prepared.c5_input_lock_sha256, ...
    'c5_snapshot_sha256',prepared.c5_snapshot_sha256, ...
    'position_model_mat_sha256',prepared.position_model_mat_sha256, ...
    'tcn_model_mat_sha256',prepared.tcn_model_mat_sha256, ...
    'tcn_best_step',prepared.tcn_best_step, ...
    'cfg_identity',prepared.identity.geometry,'common_identity',prepared.identity.common, ...
    'runner_entry','run_gate_holdout_closed_loop(scene,cfg,opts)');
write_json(fullfile(attemptDir,'attempt_started.marker'),struct( ...
    'schema','DL1018_TCN_GHP7_ATTEMPT_STARTED_V1','scene_id',runIdentity.scene_id, ...
    'created_utc',startedUtc,'stage','RUNNING'));
write_json(fullfile(attemptDir,'run_start.json'),runIdentity);
try
    log=run_gate_holdout_closed_loop(prepared.scene,prepared.cfg,prepared.opts);
    assert(isfield(log,'complete_transitions')&&isscalar(log.complete_transitions), ...
        'GATE:TransitionAudit','Candidate runner omitted complete-transition status.');
    scene=prepared.scene;
    save(fullfile(attemptDir,'raw_run.mat'),'log','scene','runIdentity','-v7.3');
    status=struct('schema','DL1018_TCN_GHP7_RUN_STATUS_V1','state','COMPLETED', ...
        'scene_id',runIdentity.scene_id,'attitude_arm','DL_TCN','geometry_arm','ACTIVE', ...
        'finished_utc',utcNow(),'plant_calls',1,'scene_payload_sha256',prepared.scene_payload_sha256, ...
        'raw_output_path',fullfile(attemptDir,'raw_run.mat'), ...
        'raw_output_sha256',sha256_file(fullfile(attemptDir,'raw_run.mat')), ...
        'complete_transitions',logical(log.complete_transitions), ...
        'actual_transition_count',double(log.actual_transition_count), ...
        'actual_state_sample_count',double(log.actual_state_sample_count), ...
        'status_value',char(string(log.status)), ...
        'safety_stop_reason',char(string(log.safety_stop_reason)), ...
        'source_lock_sha256',sourceLockSha);
    write_json(fullfile(attemptDir,'run_status.json'),status);
    fprintf('TCN_CANDIDATE_ATTEMPT_DIR=%s',attemptDir);
catch ME
    write_json(fullfile(attemptDir,'run_status.json'),struct( ...
        'schema','DL1018_TCN_GHP7_RUN_STATUS_V1','state','FAILED', ...
        'scene_id',runIdentity.scene_id,'attitude_arm','DL_TCN','geometry_arm','ACTIVE', ...
        'failed_utc',utcNow(),'plant_calls',1, ...
        'scene_payload_sha256',prepared.scene_payload_sha256, ...
        'error_identifier',char(ME.identifier),'error_message',char(ME.message), ...
        'source_lock_sha256',sourceLockSha));
    rethrow(ME);
end
end

function verify_candidate_tree(lock,runnerRoot)
assert(strcmp(char(lock.schema),'DL1018_CANDIDATE_SOURCE_LOCK_V1')&& ...
    strcmpi(char(java.io.File(char(lock.root)).getCanonicalPath()), ...
    char(java.io.File(runnerRoot).getCanonicalPath())), ...
    'GATE:SourceLockSchema','Unexpected TCN candidate source lock.');
rootCanonical=char(java.io.File(runnerRoot).getCanonicalPath());
rootPrefix=[rootCanonical filesep];
expectedFiles=dir(fullfile(runnerRoot,'matlab','**','*.m'));
expectedRelative=cell(numel(expectedFiles),1);
for i=1:numel(expectedFiles)
    p=char(java.io.File(fullfile(expectedFiles(i).folder,expectedFiles(i).name)).getCanonicalPath());
    assert(startsWith(lower(p),lower(rootPrefix)),'GATE:SourceTreeEscape', ...
        'Candidate source file escaped the locked root: %s.',p);
    expectedRelative{i}=p(numel(rootPrefix)+1:end);
end
lockedRelative=cell(numel(lock.files),1);
for i=1:numel(lock.files)
    p=fullfile(runnerRoot,char(lock.files(i).relative_path));
    assert(isfile(p)&&strcmpi(sha256_file(p),char(lock.files(i).sha256)), ...
        'GATE:SourceTreeSHA','Candidate source changed: %s.',p);
    lockedRelative{i}=char(lock.files(i).relative_path);
end
assert(numel(unique(lower(string(lockedRelative))))==numel(lockedRelative)&& ...
    isequal(sort(lower(string(expectedRelative))),sort(lower(string(lockedRelative)))), ...
    'GATE:SourceTreeCount','Source lock must contain every MATLAB file exactly once.');
end

function h=sha256_file(p)
fid=fopen(p,'r');assert(fid>=0,'GATE:FileRead','Cannot read %s.',p);
cl=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(b);end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear cl;
end

function write_json(p,x)
fid=fopen(p,'w');assert(fid>=0,'GATE:Write','Cannot write %s.',p);
cl=onCleanup(@()fclose(fid));fwrite(fid,[jsonencode(x,'PrettyPrint',true) newline],'char');clear cl;
end

function s=utcNow()
s=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z'''));
end
