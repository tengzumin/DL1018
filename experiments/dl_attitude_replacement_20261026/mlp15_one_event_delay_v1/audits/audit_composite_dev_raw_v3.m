end

function T=euler_map(eta)
phi=eta(1);theta=max(min(eta(2),pi/2-1e-4),-pi/2+1e-4);
T=[1,sin(phi)*tan(theta),cos(phi)*tan(theta); ...
    0,cos(phi),-sin(phi);0,sin(phi)/cos(theta),cos(phi)/cos(theta)];
end

function y=wrap(x)
y=atan2(sin(x),cos(x));
end

function yes=chol_ok(P)
[~,flag]=chol(P);yes=flag==0;
end

function scene=load_scene(path)
pack=load(path,'scene');scene=pack.scene;
end

function yes=same_scene_arrays(a,b)
yes=isequaln(a.time,b.time)&&isequaln(a.initial_state,b.initial_state)&& ...
    isequaln(a.reference,b.reference)&&isequaln(a.arms,b.arms)&& ...
    isequaln(a.environment_wind_I,b.environment_wind_I);
end

function h=scene_hash(scene)
payload=struct('time',scene.time,'initial_state',scene.initial_state, ...
    'reference',scene.reference,'arms',scene.arms,'environment_wind_I',scene.environment_wind_I);
bytes=uint8(unicode2native(jsonencode(payload),'UTF-8'));
md=java.security.MessageDigest.getInstance('SHA-256');md.update(typecast(bytes(:),'int8'));
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end

