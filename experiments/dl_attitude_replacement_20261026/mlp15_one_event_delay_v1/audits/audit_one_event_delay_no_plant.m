function report=audit_one_event_delay_no_plant()
% Release-zero identity, budget, source, and synthetic torque-delay checks.
here=char(java.io.File(fileparts(mfilename('fullpath'))).getCanonicalPath());
study=fileparts(here);research=fileparts(study);reportPath=fullfile(here,'NO_PLANT_CHECK_v1.json');
assert(~isfile(reportPath),'OneEventDelay:AuditExists','Refusing to overwrite a previous no-Plant report.');
release=jsondecode(fileread(fullfile(study,'RELEASE.json')));
assert(strcmp(char(release.status),'PREPARED_ROOT_REVIEW_REQUIRED')&& ...
    double(release.authorized_Plant_calls)==0&&double(release.Plant_calls)==0&& ...
    isempty(release.authorized_scenes)&&~logical(release.TEST_read)&&double(release.training_jobs_authorized)==0, ...
    'OneEventDelay:ReleaseBudget','New study must remain release-zero.');
manifest=jsondecode(fileread(fullfile(study,'MANIFEST.json')));
assert(strcmp(char(manifest.status),'PASS_READ_ONLY_VALIDATION_BINDINGS')&& ...
    numel(manifest.records)==6&&~logical(manifest.TEST_read), ...
    'OneEventDelay:Manifest','Expected six locked VAL scenes and no TEST reads.');
runner=fullfile(study,'candidate_runner_work');runtime=fullfile(runner,'matlab','runtime');
lock=jsondecode(fileread(fullfile(study,'SOURCE_LOCK_v1.json')));
diff=jsondecode(fileread(fullfile(study,'SOURCE_DIFF_v1.json')));
assert(strcmpi(char(java.io.File(lock.root).getCanonicalPath()),char(java.io.File(runner).getCanonicalPath()))&& ...
    numel(lock.files)==56&&numel(diff.changed_control_files)==1&& ...
    strcmp(char(diff.changed_control_files.relative_path),'matlab/runtime/run_mlp15_dev72_closed_loop.m')&& ...
    logical(diff.step_byte_identical)&&logical(diff.generic_gate_byte_identical)&&logical(diff.forward_unchanged), ...
    'OneEventDelay:SourceScope','Expected one DEV control change; step/generic/forward must be identical.');
for i=1:numel(lock.files)
    rel=char(lock.files(i).relative_path);path=fullfile(runner,strrep(rel,'/',filesep));
    assert(isfile(path)&&strcmpi(hash_file(path),char(lock.files(i).sha256)), ...
        'OneEventDelay:SourceLock','Candidate source hash changed: %s.',rel);
end
parent=fullfile(research,'mlp15_composite_dev_v3','candidate_runner_work');
stepPath=fullfile(runtime,'mlp15_attitude_step_v1.m');
parentStep=fullfile(parent,'matlab','runtime','mlp15_attitude_step_v1.m');
assert(strcmpi(hash_file(stepPath),hash_file(parentStep))&& ...
    strcmpi(hash_file(stepPath),char(release.step_sha256)), ...
    'OneEventDelay:StepSHA','The numerical MLP step must remain byte-identical to v3.');
assert(strcmpi(hash_file(fullfile(runtime,'run_gate_holdout_closed_loop.m')), ...
    hash_file(fullfile(parent,'matlab','runtime','run_gate_holdout_closed_loop.m'))), ...
    'OneEventDelay:GenericGate','Generic gate changed from v3.');
devText=fileread(fullfile(runtime,'run_mlp15_dev72_closed_loop.m'));
assert(contains(devText,'appliedMlp15Torque=previousGeneratedMlp15Torque;')&& ...
    contains(devText,'generatedMlp15Torque=double(mlpOut.estimateTorque_Nm(:));')&& ...
    contains(devText,'previousGeneratedMlp15Torque=generatedMlp15Torque;')&& ...
    contains(devText,"'attitude_mlp15_generated_torque_Nm'")&& ...
    contains(devText,"'attitude_mlp15_applied_delay_age_s'"), ...
    'OneEventDelay:DevBinding','Actual DEV event cache/order/trace is incomplete.');

firstScene='DL1018_VAL_T1_C05_W12';record=manifest.records(strcmp({manifest.records.scene_id},firstScene));
assert(isscalar(record),'OneEventDelay:FirstScene','Required initial review scene is missing.');
addpath(runtime);activate_paired_runner();
p=prepare_mlp15_dev72_no_plant(char(record.payload_path));
modelPath=char(release.model_path);modelSha=hash_file(modelPath);
assert(strcmpi(modelSha,char(release.model_sha256)), ...
    'OneEventDelay:ModelHash','Locked full72 MLP model changed.');
model=load(modelPath);
p.opts=make_gate_holdout_options(p.cfg,p.model,'DL_MLP15','ACTIVE',struct,model,modelSha);
identity=gate_holdout_identity_hashes(p.cfg,p.model,p.opts);
assert(strcmpi(identity.common.position_options_sha256,p.identity.common.position_options_sha256)&& ...
    strcmpi(identity.common.position_options_sha256,char(release.common_position_options_sha256))&& ...
    strcmpi(p.c5_input_lock_sha256,char(release.c5_input_lock_sha256))&& ...
    strcmpi(p.c5_snapshot_sha256,char(release.c5_snapshot_sha256))&& ...
    strcmpi(p.position_model_sha256,char(release.position_model_sha256)), ...
    'OneEventDelay:Identity','Prepared C5/full72 identities differ from the fixed parent.');
locked=jsondecode(fileread(fullfile(study,'LOCKED_CFG.json')));
assert(isequal(double(p.cfg.control.command_filter.acceleration_limit(:)),[Inf;Inf;6])&& ...
    isequal(double(p.cfg.control.bs.attitude.k1(:)),double(locked.K1(:)))&& ...
    isequal(double(p.cfg.rbf.attitude.dmax(:)),double(locked.dmax(:)))&& ...
    abs(double(p.cfg.rbf.attitude.beta_rise_time)-double(locked.beta_rise_time_s))<1e-12&& ...
    strcmpi(char(p.cfg.controller_morphology_mode),'fixed'), ...
    'OneEventDelay:LockedCfg','Prepared C5 cfg differs from the audited fixed values.');
Pplant=simulation_parameters(p.cfg,p.cfg.plant.arm_initial,zeros(4,1));
Pfixed=controller_parameters(p.cfg,Pplant,'fixed');J0=double(Pfixed.inertia);
assert(isequal(J0,double(locked.J0_kgm2))&&isequal(double(Pfixed.inertia_dot_for_bs),zeros(3)), ...
    'OneEventDelay:FixedJ0','Fixed J0/Jdot0 differs from v3.');
assert(strcmpi(which('run_mlp15_dev72_closed_loop'),fullfile(runtime,'run_mlp15_dev72_closed_loop.m'))&& ...
    strcmpi(which('mlp15_attitude_step_v1'),fullfile(runtime,'mlp15_attitude_step_v1.m'))&& ...
    strcmpi(which('run_gate_holdout_closed_loop'),fullfile(runtime,'run_gate_holdout_closed_loop.m')), ...
    'OneEventDelay:WhichPath','Required controller code resolves outside the isolated v1 tree.');

% Both production entry points must reject release zero before creating a run marker.
actualBlocked=false;
try,run_mlp15_dev72_closed_loop(struct('scene_id',firstScene),struct,struct);
catch ME,actualBlocked=strcmp(ME.identifier,'CompositeDEV:BudgetClosed');end
assert(actualBlocked,'OneEventDelay:ActualBudget','Actual DEV did not reject release zero.');
addpath(study);driverBlocked=false;
try,run_composite_dev_attempt(firstScene);
catch ME,driverBlocked=strcmp(ME.identifier,'CompositeDEV:BudgetClosed');end
assert(driverBlocked&&~isfolder(fullfile(study,'runs')), ...
    'OneEventDelay:DriverBudget','Outer driver did not reject before creating a marker.');

% Inherit the existing 300-event mathematical-step evidence; do not rerun it.
v3Check=jsondecode(fileread(fullfile(research,'mlp15_composite_dev_v3','audits','NO_PLANT_CHECK_v3.json')));
prior300=fullfile(research,'mlp15_composite_dev_v2','preparation_attempt01','audits','NO_PLANT_CHECK_v2.json');
assert(isfile(prior300)&&strcmpi(hash_file(prior300),char(v3Check.inherited_prior_300_event_report_sha256)), ...
    'OneEventDelay:Inherited300','Inherited original 300-event step report SHA does not match.');

% Reuse the independently executed 300-event/1-ms queue report; this audit does not duplicate it.
queueReportPath=fullfile(here,'check_delay_queue_300_v1.json');
assert(isfile(queueReportPath),'OneEventDelay:QueueReportMissing','Independent 300-event queue report is missing.');
queue=jsondecode(fileread(queueReportPath));
assert(strcmp(char(queue.status),'PASS_DELAY_QUEUE_300_NO_PLANT')&& ...
    double(queue.event_count)==300&&logical(queue.first_event_applied_zero)&& ...
    logical(queue.current_generated_independence_pass)&&logical(queue.non_event_hold_pass)&& ...
    logical(queue.source_event_index_time_age_pass)&&logical(queue.no_second_beta_or_dmax), ...
    'OneEventDelay:QueueReport','Independent 300-event delay queue report failed its required checks.');

report=struct('schema','DL1018_MLP15_ONE_EVENT_DELAY_NO_PLANT_CHECK_V1', ...
    'status','PASS_ONE_EVENT_DELAY_NO_PLANT','Plant_calls',0,'authorized_Plant_calls',0, ...
    'training_started',false,'TEST_read',false,'MATLAB_used_for_no_plant_check',true, ...
    'first_root_review_scene',firstScene,'actual_dev_zero_budget_rejected',actualBlocked, ...
    'outer_driver_zero_budget_rejected',driverBlocked,'attempt_marker_created',false, ...
    'source_file_count',numel(lock.files),'changed_control_files',{ {diff.changed_control_files.relative_path} }, ...
    'step_sha256',hash_file(stepPath),'step_sha_matches_v3',true, ...
    'generic_gate_byte_identical',logical(diff.generic_gate_byte_identical), ...
    'prepared_cfg_acceleration_limit',{{'Inf (unbounded)','Inf (unbounded)',6}}, ...
    'fixed_J0_kgm2',J0,'fixed_Jdot0_for_bs',double(Pfixed.inertia_dot_for_bs), ...
    'common_position_options_sha256',identity.common.position_options_sha256, ...
    'model_sha256',modelSha,'cfg_snapshot_sha256',char(locked.cfg_snapshot_sha256), ...
    'which_dev',which('run_mlp15_dev72_closed_loop'),'which_step',which('mlp15_attitude_step_v1'), ...
    'which_generic_gate',which('run_gate_holdout_closed_loop'), ...
    'inherited_original_300_event_report_path',prior300, ...
    'inherited_original_300_event_report_sha256',hash_file(prior300), ...
    'delay_queue_300_report_path',queueReportPath, ...
    'delay_queue_300_report_sha256',hash_file(queueReportPath), ...
    'delay_queue_300_status',char(queue.status),'delay_queue_300_event_count',double(queue.event_count), ...
    'delay_queue_300_no_second_beta_or_dmax',logical(queue.no_second_beta_or_dmax), ...
    'baseline_metrics_recomputed',false, ...
    'variable_inertia_read_or_reconstructed',false,'source_lock_sha256',hash_file(fullfile(study,'SOURCE_LOCK_v1.json')), ...
    'source_diff_sha256',hash_file(fullfile(study,'SOURCE_DIFF_v1.json')), ...
    'audit_script_sha256',hash_file([mfilename('fullpath') '.m']));
write_json(reportPath,report);disp(report);
end

function h=hash_file(path)
fid=fopen(path,'rb');assert(fid>=0,'OneEventDelay:Read','Cannot read %s.',path);
cleanup=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear cleanup;
end
function write_json(path,value)
fid=fopen(path,'w','n','UTF-8');assert(fid>=0,'OneEventDelay:Write','Cannot write %s.',path);
cleanup=onCleanup(@()fclose(fid));fprintf(fid,'%s\n',jsonencode(value,'PrettyPrint',true));clear cleanup;
end
