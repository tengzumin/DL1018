function run_mlp15_full72_candidate_preflight_v1()
% Root-only static Code Analyzer and no-Plant G1/W00 preparation audit.
auditDir=fileparts(mfilename('fullpath'));
taskRoot=fileparts(auditDir);
projectRoot=fileparts(fileparts(fileparts(taskRoot)));
runnerRoot=fullfile(taskRoot,'candidate_runner_work');
newFiles={fullfile(runnerRoot,'matlab','runtime','prepare_gate_candidate_no_plant.m'), ...
    fullfile(runnerRoot,'matlab','runtime','run_mlp15_candidate_gate_attempt.m')};
oldRoot=fullfile(projectRoot,'experiments','dl_attitude_replacement_20261026', ...
    'pilot_runner_mlp15_c5_24_v1','candidate_runner_work');
oldFiles={fullfile(oldRoot,'matlab','runtime','prepare_gate_candidate_no_plant.m'), ...
    fullfile(oldRoot,'matlab','runtime','run_mlp15_candidate_gate_attempt.m')};
codeRows=repmat(struct('candidate_file','','baseline_file','','candidate_diagnostics',0, ...
    'baseline_diagnostics',0,'new_diagnostics',0),1,2);
for i=1:2
    candidateMessages=checkcode(newFiles{i},'-id');
    baselineMessages=checkcode(oldFiles{i},'-id');
    codeRows(i)=struct('candidate_file',newFiles{i},'baseline_file',oldFiles{i}, ...
        'candidate_diagnostics',numel(candidateMessages), ...
        'baseline_diagnostics',numel(baselineMessages), ...
        'new_diagnostics',max(0,numel(candidateMessages)-numel(baselineMessages)));
    assert(isempty(candidateMessages)&&isempty(baselineMessages), ...
        'DL1018:CodeAnalyzer','Unexpected MATLAB Code Analyzer findings.');
end
codeReport=struct('schema','DL1018_MLP15_C5_FULL72_CODE_ANALYZER_V1', ...
    'status','PASS_NO_NEW_DIAGNOSTICS','matlab_release',version('-release'), ...
    'files',codeRows,'diagnostic_count',0,'plant_invoked',false,'test_data_read',false, ...
    'closed_loop_started',false);
write_json(fullfile(taskRoot,'MLP15_C5_FULL72_CODE_ANALYZER_v1.json'),codeReport);
addpath(genpath(fullfile(runnerRoot,'matlab')));
release=jsondecode(fileread(fullfile(taskRoot,'MLP15_C5_FULL72_PILOT_RELEASE_v1.json')));
payloadPath=char(release.pilot_payloads(1).payload_path);
assert(strcmp(release.pilot_payloads(1).scene_id,'DL1018_GHP7_G1_W00')&& ...
    release.plant_calls_authorized==0&&strcmp(release.status,'PREPARED_PENDING_ROOT_APPROVAL'), ...
    'DL1018:PendingPilot','The pilot must still be pending with zero Plant calls.');
prepared=prepare_gate_candidate_no_plant(payloadPath,'DL_MLP15','ACTIVE');
assert(strcmp(prepared.scene.scene_id,'DL1018_GHP7_G1_W00')&& ...
    strcmp(prepared.attitude_arm,'DL_MLP15')&&strcmp(prepared.geometry_arm,'ACTIVE')&& ...
    strcmpi(prepared.mlp15_model_mat_sha256,release.model_sha256)&& ...
    prepared.mlp15_optimizer_steps==60000&&release.plant_calls_authorized==0, ...
    'DL1018:PreparedIdentity','No-Plant candidate identity differs from full72 release.');
noPlantReport=struct('schema','DL1018_MLP15_C5_FULL72_NO_PLANT_AUDIT_V1', ...
    'status','PASS_NO_PLANT','scene_id',prepared.scene.scene_id, ...
    'attitude_arm',prepared.attitude_arm,'geometry_arm',prepared.geometry_arm, ...
    'plant_invoked',false,'test_data_read',false,'closed_loop_started',false, ...
    'runner_matlab_file_count',52,'candidate_plant_calls_authorized',0, ...
    'training_optimizer_steps',prepared.mlp15_optimizer_steps, ...
    'mlp15_model_sha256',prepared.mlp15_model_mat_sha256, ...
    'parity_report_sha256',prepared.parity_report_sha256, ...
    'training_source_lock_sha256',prepared.training_lock_sha256, ...
    'position_model_id','DSSM14','position_coordinate_mask','M110', ...
    'attitude_rbf_output_enabled',false,'attitude_rbf_update_enabled',false, ...
    'physics_helper_enabled',false,'feedforward_enabled',false,'observer_enabled',false, ...
    'feature_groups',{{'wrapped_attitude_error_euler_rad_x3','body_rate_rad_s_x3', ...
        'nominal_bs_body_torque_Nm_x3','morph_command_x4'}}, ...
    'time_varying_inertia_reconstruction_used',false, ...
    'fixed_J0_used_only_for_residual_torque_mapping',true);
write_json(fullfile(taskRoot,'MATLAB_NO_PLANT_AUDIT_MLP15_C5_FULL72_v1.json'),noPlantReport);
end
function write_json(path,value)
fid=fopen(path,'w');assert(fid>=0,'DL1018:AuditReport','Cannot write %s.',path);
cleanup=onCleanup(@()fclose(fid));
fwrite(fid,jsonencode(value,'PrettyPrint',true),'char');fwrite(fid,newline,'char');clear cleanup;
end
