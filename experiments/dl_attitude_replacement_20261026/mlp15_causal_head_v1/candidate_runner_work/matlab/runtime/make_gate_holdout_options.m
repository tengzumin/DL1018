function opts=make_gate_holdout_options(cfg,positionModel,attitudeArm,geometryArm,identityLock,candidateModel,candidateModelSha256)
% Bind a C5 method arm and a geometry-specific lock to the frozen C5 option builder.
if nargin<5,identityLock=struct;end
if nargin<6,candidateModel=struct;end
if nargin<7,candidateModelSha256='';end
attitudeArm=upper(char(attitudeArm));
geometryArm=upper(char(geometryArm));
spec=gate_attitude_arm_spec(attitudeArm);
assert(ismember(geometryArm,{'ACTIVE','FIXED_MIN','FIXED_BOUND15'}), ...
    'GATE:GeometryArm','Unknown gate geometry arm.');
[baseline,candidate]=make_paired_c5_options(cfg,positionModel);
if strcmp(spec.paired_arm,'baseline')
    opts=baseline;
else
    opts=candidate;
end
if strcmp(attitudeArm,'DL_TCN')
    required={'input_mean','input_std','target_rms','input_weight','input_bias', ...
        'conv1_weight','conv1_bias','conv2_weight','conv2_bias','conv3_weight','conv3_bias', ...
        'head_weight','head_bias'};
    assert(isstruct(candidateModel)&&all(isfield(candidateModel,required))&& ...
        numel(candidateModel.input_mean)==13&&numel(candidateModel.input_std)==13&& ...
        numel(candidateModel.target_rms)==3&&isequal(size(candidateModel.input_weight),[32,13])&& ...
        numel(candidateModel.input_bias)==32&&isequal(size(candidateModel.head_weight),[3,32])&& ...
        numel(candidateModel.head_bias)==3&&all(isfinite(double(candidateModel.input_mean(:))))&& ...
        all(isfinite(double(candidateModel.input_std(:))))&&all(double(candidateModel.input_std(:))>0)&& ...
        all(isfinite(double(candidateModel.target_rms(:))))&&all(double(candidateModel.target_rms(:))>0)&& ...
        all(isfinite(double(candidateModel.input_weight(:))))&&all(isfinite(double(candidateModel.input_bias(:))))&& ...
        all(isfinite(double(candidateModel.head_weight(:))))&&all(isfinite(double(candidateModel.head_bias(:))))&& ...
        ischar(candidateModelSha256)&&numel(candidateModelSha256)==64&&all(ismember(lower(candidateModelSha256),'0123456789abcdef')), ...
        'GATE:TCNModel','Frozen DL_TCN model, normalizers, or model SHA are invalid.');
    for layer=1:3
        w=candidateModel.(sprintf('conv%d_weight',layer));b=candidateModel.(sprintf('conv%d_bias',layer));
        assert(isequal(size(w),[32,32,3])&&numel(b)==32&& ...
            all(isfinite(double(w(:))))&&all(isfinite(double(b(:)))), ...
            'GATE:TCNModel','Frozen DL_TCN convolution layer %d is invalid.',layer);
    end
    opts.tcn_attitude_model=candidateModel;
    opts.tcn_attitude_model_sha256=lower(candidateModelSha256);
elseif strcmp(attitudeArm,'DL_MLP15')
    required={'input_mean','input_std','target_rms','fc1_weight','fc1_bias', ...
        'fc2_weight','fc2_bias','head_weight','head_bias'};
    assert(isstruct(candidateModel)&&all(isfield(candidateModel,required))&& ...
        numel(candidateModel.input_mean)==13&&numel(candidateModel.input_std)==13&& ...
        numel(candidateModel.target_rms)==3&&isequal(size(candidateModel.fc1_weight),[64,195])&& ...
        numel(candidateModel.fc1_bias)==64&&isequal(size(candidateModel.fc2_weight),[32,64])&& ...
        numel(candidateModel.fc2_bias)==32&&isequal(size(candidateModel.head_weight),[3,32])&& ...
        numel(candidateModel.head_bias)==3&&all(isfinite(double(candidateModel.input_mean(:))))&& ...
        all(isfinite(double(candidateModel.input_std(:))))&&all(double(candidateModel.input_std(:))>0)&& ...
        all(isfinite(double(candidateModel.target_rms(:))))&&all(double(candidateModel.target_rms(:))>0)&& ...
        all(isfinite(double(candidateModel.fc1_weight(:))))&&all(isfinite(double(candidateModel.fc1_bias(:))))&& ...
        all(isfinite(double(candidateModel.fc2_weight(:))))&&all(isfinite(double(candidateModel.fc2_bias(:))))&& ...
        all(isfinite(double(candidateModel.head_weight(:))))&&all(isfinite(double(candidateModel.head_bias(:))))&& ...
        ischar(candidateModelSha256)&&numel(candidateModelSha256)==64&&all(ismember(lower(candidateModelSha256),'0123456789abcdef')), ...
        'GATE:MLP15Model','Frozen DL_MLP15 model, normalizers, or model SHA are invalid.');
    opts.mlp15_attitude_model=candidateModel;
    opts.mlp15_attitude_model_sha256=lower(candidateModelSha256);
elseif ~isempty(fieldnames(candidateModel))||~isempty(candidateModelSha256)
    error('GATE:UnexpectedModel','A frozen model may only be supplied for its matching DL arm.');
end
opts.gate_attitude_arm=attitudeArm;
opts.gate_geometry_arm=geometryArm;
opts.gate_identity_lock=identityLock;
end
