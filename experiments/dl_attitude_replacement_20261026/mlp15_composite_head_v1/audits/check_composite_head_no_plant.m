function report=check_composite_head_no_plant()
% Compare the copied deployment step with an independent 300-event NumPy fixture.
here=char(java.io.File(fileparts(mfilename('fullpath'))).getCanonicalPath());
study=fileparts(here);research=fileparts(study);
runner=fullfile(study,'candidate_runner_work');runtime=fullfile(runner,'matlab','runtime');
parent=fullfile(research,'mlp15_causal_head_v1','candidate_runner_work');
modelPath=fullfile(research,'mlp15_c5_teacher_full72_v1','runs', ...
    'C5_MLP15_FULL72_SEED2026102001','mlp15_attitude_weights_v1.mat');
fixturePath=fullfile(here,'fixtures','composite_head_fixture.mat');
reportPath=fullfile(here,'NO_PLANT_CHECK_v7.json');
assert(~isfile(reportPath),'CompositeCheck:OutputExists','Refusing to overwrite a check result.');
assert(strcmpi(hash_file(modelPath), ...
    '67a6564148ba8c1988d7457c04a5d3271516ff4010da18e61e29fd7da13be46b'), ...
    'CompositeCheck:ModelSHA','Frozen MLP15 model SHA changed.');
addpath(runtime);
preparedRelease=jsondecode(fileread(fullfile(study,'RELEASE.json')));
assert(strcmp(preparedRelease.status,'PREPARED_ROOT_REVIEW_REQUIRED')&& ...
    preparedRelease.authorized_Plant_calls==0&&preparedRelease.Plant_calls==0&& ...
    isempty(preparedRelease.authorized_scenes)&&preparedRelease.TEST_read==false, ...
    'CompositeCheck:PreparedRelease','Prepared release must have zero Plant budget.');
plantGateBlocked=false;
try
    run_gate_holdout_closed_loop(struct('scene_id','DL1018_VAL_T1_C08_W15'),struct,struct);
catch ME
    plantGateBlocked=strcmp(ME.identifier,'COMPOSITE:PlantBudgetZero');
end
assert(plantGateBlocked,'CompositeCheck:PlantGate','Prepared release did not hard-block the Plant runner.');
model=load(modelPath);F=load(fixturePath);count=numel(F.sample_indices);
assert(isequal(double(F.J0),double(preparedRelease.fixed_J0_kgm2))&& ...
    isequal(double(F.K1(:)),double(preparedRelease.locked_cfg.K1(:))), ...
    'CompositeCheck:LockedConstants','Fixture J0/K1 differs from locked release constants.');
assert(count==300&&isequal(size(F.features),[13,300])&& ...
    isequal(size(F.tracking_T),[3,3,300])&&isequal(size(F.tracking_surface),[3,300]), ...
    'CompositeCheck:Fixture','Synthetic cross-language fixture shape mismatch.');
assert(isequal(size(F.J0),[3,3])&&isequal(size(F.dmax),[3,1])&& ...
    all(F.event_dt(2:end)>0)&&F.event_dt(1)==0, ...
    'CompositeCheck:FixtureSchedule','Invalid fixed inertia, dmax, or event interval.');

[memory,~]=mlp15_attitude_step_v1('init',struct,struct,model);
[disabled,~]=mlp15_attitude_step_v1('init',struct,struct,model);
raw=zeros(3,count);base=zeros(3,count);torque=zeros(3,count);weightBefore=zeros(33,3,count);
weightAfter=zeros(33,3,count);trackingDrive=zeros(33,3,count);maxObservedError=0;
maxWeightError=0;maxDriveError=0;maxCovarianceDiagonalError=0;maxBaseError=0;
maxRawError=0;maxTorqueError=0;maxClippedError=0;minimumCholeskyDiagonal=Inf;
projectionCount=0;rlsCount=0;trackingCount=0;dmaxCount=0;alternativeObservation=[];alternativeSurface=[];
for i=1:count
    in=event_input(F,i,memory);
    beforeMemory=memory;
    [memory,out]=mlp15_attitude_step_v1('step',memory,in,model);
    off=in;off.head_enabled=false;
    [disabled,outOff]=mlp15_attitude_step_v1('step',disabled,off,model);
    d=out.head;
    raw(:,i)=double(out.raw_residual_rad_s2(:));base(:,i)=double(d.base_residual_rad_s2(:));
    torque(:,i)=double(out.estimateTorque_Nm(:));weightBefore(:,:,i)=double(d.weight_before);
    weightAfter(:,:,i)=double(d.weight_after);trackingDrive(:,:,i)=double(d.tracking_drive);
    maxRawError=max(maxRawError,max(abs(raw(:,i)-double(F.expected_raw(:,i)))));
    maxBaseError=max(maxBaseError,max(abs(base(:,i)-double(F.expected_base(:,i)))));
    maxTorqueError=max(maxTorqueError,max(abs(torque(:,i)-double(F.expected_torque(:,i)))));
    maxObservedError=max(maxObservedError,max(abs(double(d.observation_residual_rad_s2(:))- ...
        double(F.expected_observed(:,i)))));
    maxWeightError=max(maxWeightError,max(abs(double(d.weight_before)- ...
        double(F.expected_weight_before(:,:,i))),[],'all'));
    maxWeightError=max(maxWeightError,max(abs(double(d.weight_after)- ...
        double(F.expected_weight_after(:,:,i))),[],'all'));
    maxDriveError=max(maxDriveError,max(abs(double(d.tracking_drive)- ...
        double(F.expected_tracking_drive(:,:,i))),[],'all'));
    maxCovarianceDiagonalError=max(maxCovarianceDiagonalError,max(abs( ...
        double(d.covariance_diagonal_after(:))-double(F.expected_covariance_diagonal(:,i)))));
    actualClipped=double(out.clipped_residual_rad_s2(:));expectedClipped=double(F.expected_clipped(:,i));
    assert(isequal(size(actualClipped),size(expectedClipped)), ...
        'CompositeCheck:ClipShape','Clip shape mismatch: MATLAB %s, Python %s.', ...
        mat2str(size(actualClipped)),mat2str(size(expectedClipped)));
    maxClippedError=max(maxClippedError,max(abs(actualClipped-expectedClipped)));
    assert(logical(d.update_executed)==logical(F.expected_updated(i))&& ...
        logical(d.tracking_update_executed)==logical(F.expected_tracking_updated(i))&& ...
        logical(d.projection_active)==logical(F.expected_projection(i))&& ...
        isequal(any(abs(double(out.raw_residual_rad_s2(:))-double(out.clipped_residual_rad_s2(:)))>1e-12), ...
            logical(F.expected_clip_active(i))), ...
        'CompositeCheck:EventFlags','Update, tracking, projection, or dmax event flag mismatch.');
    projectionCount=projectionCount+logical(d.projection_active);
    rlsCount=rlsCount+logical(d.update_executed);
    trackingCount=trackingCount+logical(d.tracking_update_executed);
    dmaxCount=dmaxCount+logical(F.expected_clip_active(i));
    [~,flag]=chol(memory.head_covariance);assert(flag==0, ...
        'CompositeCheck:SPD','Joseph covariance is not positive definite.');
    minimumCholeskyDiagonal=min(minimumCholeskyDiagonal,min(diag(chol(memory.head_covariance))));
    assert(max(abs(outOff.raw_residual_rad_s2(:)-double(F.expected_base(:,i))))<1e-9, ...
        'CompositeCheck:FrozenForward','Disabled head changed the frozen MLP forward output.');
    if i==1
        assert(norm(memory.head_weight,'fro')==0&& ...
            max(abs(out.raw_residual_rad_s2(:)-double(F.expected_base(:,i))))<1e-9, ...
            'CompositeCheck:ZeroHead','Zero-head output does not equal frozen MLP output.');
    end
    if i==270
        alternativeObservation=beforeMemory;inObservation=in;
        inObservation.torque_history(end,1)=inObservation.torque_history(end,1)+.005;
        [alternativeObservation,observationOut]=mlp15_attitude_step_v1( ...
            'step',alternativeObservation,inObservation,model);
        alternativeSurface=beforeMemory;inSurface=in;
        inSurface.tracking_surface(1)=inSurface.tracking_surface(1)+.2;
        [alternativeSurface,surfaceOut]=mlp15_attitude_step_v1( ...
            'step',alternativeSurface,inSurface,model);
        assert(isequal(out.raw_residual_rad_s2,observationOut.raw_residual_rad_s2)&& ...
            isequal(out.raw_residual_rad_s2,surfaceOut.raw_residual_rad_s2)&& ...
            norm(alternativeObservation.head_weight-memory.head_weight,'fro')>1e-12&& ...
            norm(alternativeSurface.head_weight-memory.head_weight,'fro')>1e-12, ...
            'CompositeCheck:CurrentOutput','Current observation/tracking changed current output or not future state.');
    end
end
assert(maxRawError<1e-6&&maxBaseError<1e-7&&maxTorqueError<1e-8&& ...
    maxObservedError<1e-8&&maxWeightError<1e-7&&maxDriveError<1e-7&& ...
    maxCovarianceDiagonalError<1e-7&&maxClippedError<1e-9&& ...
    projectionCount>0&&rlsCount>0&&trackingCount>0&&dmaxCount>0, ...
    'CompositeCheck:Parity','Python/MATLAB composite-head parity failed.');
next=event_input(F,271,alternativeObservation);
[~,observationNext]=mlp15_attitude_step_v1('step',alternativeObservation,next,model);
[~,surfaceNext]=mlp15_attitude_step_v1('step',alternativeSurface,next,model);
assert(abs(observationNext.raw_residual_rad_s2(1)-raw(1,271))>1e-10&& ...
    abs(surfaceNext.raw_residual_rad_s2(1)-raw(1,271))>1e-10, ...
    'CompositeCheck:DelayedEffect','Current signals did not affect the next output.');

% This direct identity check does not call the production update implementation.
rng(20261027,'twister');A=randn(33);Pcheck=A*A.'+eye(33);phi=randn(33,1);phi=phi/norm(phi);
Dprobe=randn(33,3);Tcheck=double(F.tracking_T(:,:,260));scheck=double(F.tracking_surface(:,260));
scale=double(model.target_rms(:));beta=double(F.beta(260));h=beta*(scale.*(Tcheck.'*scheck));
rightHandSide=-(Pcheck*phi)*h.';
lyapunovRate=sum(Dprobe.*(Pcheck\rightHandSide),'all');
crossTerm=(scheck.'*Tcheck)*(beta*scale.*(Dprobe.'*phi));
signCancellationError=abs(lyapunovRate+crossTerm);
assert(signCancellationError<1e-10,'CompositeCheck:Sign','Tracking-drive cross term sign did not cancel.');

% Copied-source diff is restricted to the MLP step and event entry.
newFiles=dir(fullfile(runner,'matlab','**','*.m'));oldFiles=dir(fullfile(parent,'matlab','**','*.m'));
assert(numel(newFiles)==numel(oldFiles),'CompositeCheck:TreeCount','Copied source tree file count changed.');
changed=strings(0,1);
for i=1:numel(newFiles)
    p=fullfile(newFiles(i).folder,newFiles(i).name);rel=erase(p,[runner filesep]);
    if ~strcmpi(hash_file(p),hash_file(fullfile(parent,rel))),changed(end+1)=replace(rel,'\','/');end %#ok<AGROW>
end
expected=sort(["matlab/runtime/mlp15_attitude_step_v1.m"; ...
    "matlab/runtime/run_gate_holdout_closed_loop.m"]);
changed=sort(string(changed(:)));expected=sort(string(expected(:)));
assert(numel(changed)==numel(expected)&&all(changed==expected),'CompositeCheck:SourceDiff', ...
    'Copied control source diff contains unexpected paths: %s',strjoin(changed,' | '));

% Compare all copied MATLAB files; only pre-existing ALIGN line numbers normalize.
newDiagnosticCount=0;oldDiagnosticCount=0;newDiagnosticIds=strings(0,1);
for i=1:numel(newFiles)
    p=fullfile(newFiles(i).folder,newFiles(i).name);rel=erase(p,[runner filesep]);
    old=checkcode(fullfile(parent,rel),'-id');fresh=checkcode(p,'-id');
    oldSig=diagnostic_signature(old);newSig=diagnostic_signature(fresh);
    oldDiagnosticCount=oldDiagnosticCount+numel(oldSig);newDiagnosticCount=newDiagnosticCount+numel(newSig);
    assert(isequal(newSig,oldSig),'CompositeCheck:Analyzer', ...
        'Copied runtime Code Analyzer diagnostics differ from v1: %s.',rel);
    if ~isempty(fresh),newDiagnosticIds=[newDiagnosticIds;string({fresh.id}).'];end %#ok<AGROW>
end
supportNames={'audit_composite_raw.m','composite_metrics.m','prepare_composite_release_no_plant.m'};
supportAnalyzer=cell(1,numel(supportNames));
for i=1:numel(supportNames)
    items=checkcode(fullfile(here,supportNames{i}),'-id');
    ids=strings(numel(items),1);messages=strings(numel(items),1);
    for j=1:numel(items),ids(j)=string(items(j).id);messages(j)=string(items(j).message);end
    supportAnalyzer{i}=struct('file',supportNames{i},'diagnostic_count',numel(items), ...
        'ids',{cellstr(ids)},'messages',{cellstr(messages)});
end

report=struct('status','PASS_NO_PLANT_COMPOSITE_HEAD','Plant_calls',0, ...
    'authorized_Plant_calls',0,'training_jobs',0,'DEV72_runs',0,'TEST_read',false, ...
    'matlab_version',version,'model_sha256',hash_file(modelPath), ...
    'fixture_sha256',hash_file(fixturePath),'synthetic_events',count, ...
    'residual_update_events',rlsCount,'tracking_update_events',trackingCount, ...
    'projection_events',projectionCount,'dmax_clipped_events',dmaxCount, ...
    'minimum_covariance_cholesky_diagonal',minimumCholeskyDiagonal, ...
    'max_raw_replay_error_rad_s2',maxRawError,'max_frozen_forward_error_rad_s2',maxBaseError, ...
    'max_torque_error_Nm',maxTorqueError,'max_observation_error_rad_s2',maxObservedError, ...
    'max_weight_error',maxWeightError,'max_tracking_drive_error',maxDriveError, ...
    'max_covariance_diagonal_error',maxCovarianceDiagonalError, ...
    'max_dmax_error_rad_s2',maxClippedError,'sign_cancellation_error',signCancellationError, ...
    'current_update_does_not_change_current_output',true, ...
    'current_observation_changes_next_output',true,'current_tracking_changes_next_output',true, ...
    'prepared_release_hard_blocks_plant',plantGateBlocked, ...
    'past_interval_indices_match_v1',true,'changed_source_files',{cellstr(changed)}, ...
    'analyzer_status','PASS_NO_NEW_DIAGNOSTICS', ...
    'old_analyzer_diagnostic_count',oldDiagnosticCount, ...
    'new_analyzer_diagnostic_count',newDiagnosticCount, ...
    'new_analyzer_diagnostic_ids',{cellstr(newDiagnosticIds)}, ...
    'audit_support_analyzer',{supportAnalyzer}, ...
    'source_script_sha256',hash_file([mfilename('fullpath') '.m']));
write_json(reportPath,report);disp(report);
end

function in=event_input(F,i,memory)
k=double(F.sample_indices(i));in=struct('feature',double(F.features(:,i)), ...
    'J0',double(F.J0),'beta',double(F.beta(i)),'dmax',double(F.dmax(:)), ...
    'head_enabled',true,'sample_index',k,'time_s',double(F.time_all(k)), ...
    'tracking_surface',double(F.tracking_surface(:,i)), ...
    'tracking_euler_rate_map',double(F.tracking_T(:,:,i)), ...
    'actual_event_dt',double(F.event_dt(i)));
if memory.previous_sample_index>0
    previous=double(memory.previous_sample_index);
    in.omega_history=double(F.omega(previous:k,:));
    in.torque_history=double(F.issued_torque(previous:k-1,:));
    in.history_time=double(F.time_all(previous:k));
    in.history_sample_indices=(previous:k).';
    assert(in.history_sample_indices(1)==memory.previous_sample_index&& ...
        in.history_sample_indices(end)==k&&in.history_sample_indices(end)-1==k-1&& ...
        size(in.torque_history,1)==numel(in.history_sample_indices)-1, ...
        'CompositeCheck:PastIndex','Past interval endpoint/command indices differ from v1.');
end
end

function out=diagnostic_signature(items)
out=strings(numel(items),1);
for i=1:numel(items)
    id=string(items(i).id);message=string(items(i).message);
    if id=="ALIGN",message=regexprep(message,'\d+','#');end
    out(i)=id+":"+message;
end
out=sort(out);
end

function write_json(path,value)
fid=fopen(path,'w','n','UTF-8');assert(fid>=0);cleanup=onCleanup(@()fclose(fid));
fprintf(fid,'%s\n',jsonencode(value,'PrettyPrint',true));clear cleanup;
end

function h=hash_file(path)
fid=fopen(path,'rb');assert(fid>=0,'CompositeCheck:Hash','Cannot read %s.',path);
cleanup=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear cleanup;
end
