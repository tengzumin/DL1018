function attemptDir=run_gru_stream_tracking_head_full72_attempt(sceneId)
% One explicitly released cosine-GRU tracking-head attempt on a locked DEV/VAL scene.
studyRoot=fileparts(mfilename('fullpath'));
releasePath=fullfile(studyRoot,'RELEASE.json');
assert(isfile(releasePath),'GRUStream:ReleaseMissing','No GRU_STREAM release exists.');
release=jsondecode(fileread(releasePath));sceneId=char(string(sceneId));
authorizedScenes=cellstr(string(field_or(release,'authorized_scenes',{})));
assert(strcmp(char(field_or(release,'schema','')),'DL1018_GRU_STREAM_DEV_RELEASE_V1')&& ...
    strcmp(char(field_or(release,'study_id','')),'gru_stream_cosine_tracking_head_full72_v1')&& ...
    strcmp(char(field_or(release,'candidate','')),'GRU32_STREAM72_COSINE_TRACKING_HEAD_S2026102001')&& ...
    strcmp(char(field_or(release,'status','')),'RELEASED')&& ...
    double(field_or(release,'authorized_Plant_calls',0))>0&&any(strcmp(authorizedScenes,sceneId)), ...
    'GRUStream:BudgetClosed','GRU_STREAM Plant budget is zero or this scene is not authorized.');
assert(isscalar(regexp(sceneId,'^DL1018_(DEV|VAL)_T[1-3]_C\d{2}_W\d{2}$','once')), ...
    'GRUStream:SceneId','Only explicit manifest-bound DEV/VAL scene IDs are accepted.');
verify_release_inputs(studyRoot,release);
manifest=jsondecode(fileread(fullfile(studyRoot,'MANIFEST.json')));
hit=find(strcmp({manifest.records.scene_id},sceneId));
assert(isscalar(hit)&&strcmp(char(manifest.status),'PASS_READ_ONLY_VALIDATION_BINDINGS')&& ...
    strcmp(char(manifest.candidate),char(release.candidate))&& ...
    numel(manifest.records)==72&&~logical(manifest.TEST_read), ...
    'GRUStream:Manifest','Scene is not in the locked 72-scene DEV/VAL manifest.');
record=manifest.records(hit);
assert(~logical(record.candidate_reuse)&&ismember(char(record.source_split),{'DEV','VAL'}), ...
    'GRUStream:CandidateReuse','This scene is reused or outside the DEV/VAL execution scope.');
runsRoot=fullfile(studyRoot,'runs');attemptDir=fullfile(runsRoot,sceneId);
assert(~isfolder(attemptDir)&&~isfile(attemptDir), ...
    'GRUStream:DuplicateScene','Refusing to overwrite an existing same-scene attempt.');
markers=dir(fullfile(runsRoot,'**','attempt_started.marker'));
assert(numel(markers)<double(release.authorized_Plant_calls), ...
    'GRUStream:CallBudget','All root-authorized Plant calls have been consumed.');
for i=1:numel(markers)
    startPath=fullfile(markers(i).folder,'run_start.json');
    if isfile(startPath)
        prior=jsondecode(fileread(startPath));
        assert(~strcmp(char(field_or(prior,'scene_id','')),sceneId), ...
            'GRUStream:DuplicateScene','A prior attempt already used this scene.');
    end
end
runnerRoot=fullfile(studyRoot,'candidate_runner_work');
runtime=fullfile(runnerRoot,'matlab','runtime');
addpath(runtime);activate_paired_runner();addpath(runtime,'-begin');
prepared=prepare_mlp15_dev72_no_plant(char(record.payload_path));
modelPath=char(release.model_path);modelSha=sha256_file(modelPath);
assert(strcmpi(modelSha,char(release.model_sha256)), ...
    'GRUStream:ModelHash','Locked GRU_STREAM model SHA changed.');
model=load(modelPath);
prepared.opts=make_gate_holdout_options(prepared.cfg,prepared.model,'GRU_STREAM','ACTIVE', ...
    struct,model,modelSha);
identity=gate_holdout_identity_hashes(prepared.cfg,prepared.model,prepared.opts);
assert(strcmpi(identity.common.position_options_sha256, ...
    prepared.identity.common.position_options_sha256), ...
    'GRUStream:PositionIdentity','Binding the GRU model changed common C5 position options.');
prepared.opts.gate_identity_lock=identity;prepared.identity=identity;
locked=jsondecode(fileread(fullfile(studyRoot,'LOCKED_CFG.json')));
assert(strcmp(char(locked.capture_status),'PASS_REAL_PREPARED_CFG')&& ...
    isequal(double(prepared.cfg.control.command_filter.acceleration_limit(:)),[Inf;Inf;6])&& ...
    isequal(double(prepared.cfg.control.bs.attitude.k1(:)),double(locked.K1(:)))&& ...
    isequal(double(prepared.cfg.rbf.attitude.dmax(:)),double(locked.dmax(:)))&& ...
    abs(double(prepared.cfg.rbf.attitude.beta_rise_time)-double(locked.beta_rise_time_s))<1e-12, ...
    'GRUStream:LockedCfg','Actual prepared configuration differs from LOCKED_CFG.');
assert(isfield(prepared.cfg,'controller_morphology_mode')&& ...
    strcmpi(char(prepared.cfg.controller_morphology_mode),'fixed'), ...
    'GRUStream:FixedMode','The prepared C5 configuration must select fixed morphology.');
Pplant=simulation_parameters(prepared.cfg,prepared.cfg.plant.arm_initial,zeros(4,1));
Pfixed=controller_parameters(prepared.cfg,Pplant,'fixed');J0=double(Pfixed.inertia);
assert(isequal(J0,double(prepared.cfg.attitude_replacement.J0_controller_fixed_kgm2))&& ...
    isequal(double(Pfixed.inertia_dot_for_bs),zeros(3))&&isequal(J0,double(locked.J0_kgm2)), ...
    'GRUStream:FixedJ0','Fixed J0 or zero Jdot differs from the reviewed snapshot.');
assert(strcmpi(which('run_mlp15_dev72_closed_loop'),fullfile(runnerRoot,'matlab','runtime', ...
    'run_mlp15_dev72_closed_loop.m'))&& ...
    strcmpi(which('gru_stream_attitude_step_v1'),fullfile(runnerRoot,'matlab','runtime', ...
    'gru_stream_attitude_step_v1.m'))&& ...
    strcmpi(which('gru_stream_tracking_head_step_v1'),fullfile(runnerRoot,'matlab','runtime', ...
    'gru_stream_tracking_head_step_v1.m'))&& ...
    strcmpi(which('gru_stream_attitude_forward_v1'),fullfile(runnerRoot,'matlab','runtime', ...
    'gru_stream_attitude_forward_v1.m')), ...
    'GRUStream:WhichPath','A candidate function resolves outside the isolated GRU source tree.');
verify_scene_bindings(prepared.scene,record);
if ~java.io.File(runsRoot).isDirectory(),assert(java.io.File(runsRoot).mkdirs());end
assert(java.io.File(attemptDir).mkdir(),'GRUStream:AttemptCreate','Could not create a new scene attempt directory.');
startedUtc=utc_now();releaseSha=sha256_file(releasePath);
marker=struct('schema','DL1018_GRU_STREAM_ATTEMPT_MARKER_V1', ...
    'scene_id',sceneId,'created_utc',startedUtc,'stage','RUNNING','release_sha256',releaseSha);
write_json(fullfile(attemptDir,'attempt_started.marker'),marker);
runIdentity=struct('schema','DL1018_GRU_STREAM_COSINE_TRACKING_HEAD_RUN_START_V1','scene_id',sceneId, ...
    'candidate','GRU32_STREAM72_COSINE_TRACKING_HEAD_S2026102001', ...
    'frozen_model_candidate','GRU32_STREAM72_COSINE_S2026102001', ...
    'learning_rate_schedule',char(release.learning_rate_schedule), ...
    'attitude_arm','GRU_STREAM','geometry_arm','ACTIVE','started_utc',startedUtc, ...
    'release_sha256',releaseSha,'manifest_sha256',char(release.manifest_sha256), ...
    'source_lock_sha256',char(release.source_lock_sha256), ...
    'source_diff_sha256',char(release.source_diff_sha256), ...
    'locked_cfg_sha256',char(release.locked_cfg_sha256), ...
    'b_raw_sha256',char(record.b_raw_sha256),'c5_raw_sha256',char(record.c5_raw_sha256), ...
    'payload_sha256',char(record.payload_sha256),'gru_model_sha256',modelSha, ...
    'c5_input_lock_sha256',prepared.c5_input_lock_sha256, ...
    'c5_snapshot_sha256',prepared.c5_snapshot_sha256, ...
    'position_model_sha256',prepared.position_model_sha256, ...
    'common_position_options_sha256',identity.common.position_options_sha256, ...
    'cfg_binding_source','prepare_mlp15_dev72_no_plant(record.payload_path).cfg', ...
    'controller_inputs','current wrapped Euler error, body rate, nominal BS torque, arms command', ...
    'hidden_state_reset_per_scene',true,'base_model_weights_fixed',true, ...
    'tracking_delta_weights_online',true, ...
    'tracking_head_protocol', ...
    'GRU_H_AFTER_PLUS_DELTAW33_OUTPUT_BEFORE_UPDATE_T_CLIP_SURFACE_BETA_J0_V1', ...
    'rbf_attitude_output_enabled',false,'rbf_attitude_update_enabled',false, ...
    'inertia_reconstruction_enabled',false,'Plant_truth_deployment_input',false,'TEST_read',false, ...
    'closed_loop_entry','run_mlp15_dev72_closed_loop(scene,cfg,opts)');
write_json(fullfile(attemptDir,'run_start.json'),runIdentity);
prepared.opts.composite_attempt_marker=fullfile(attemptDir,'attempt_started.marker');
rawPath=fullfile(attemptDir,'raw_run.mat');rawSha='';
try
    log=run_mlp15_dev72_closed_loop(prepared.scene,prepared.cfg,prepared.opts);
    log.gru_stream_release_sha256=releaseSha;
    scene=prepared.scene;save(rawPath,'log','scene','runIdentity','-v7.3');rawSha=sha256_file(rawPath);
    transitions=double(log.last_transition);stateSamples=size(log.state,1);
    complete=transitions==20000&&stateSamples==20001&&strcmp(char(log.status),'STABLE');
    assert(complete,'GRUStream:Incomplete','Candidate did not finish a stable 20,000-transition run.');
    status=struct('schema','DL1018_GRU_STREAM_COSINE_TRACKING_HEAD_RUN_STATUS_V1','state','COMPLETED', ...
        'candidate','GRU32_STREAM72_COSINE_TRACKING_HEAD_S2026102001','scene_id',sceneId, ...
        'finished_utc',utc_now(),'Plant_calls',1,'raw_path',rawPath, ...
        'raw_sha256',rawSha,'transitions',transitions,'state_samples',stateSamples, ...
        'status_value',char(log.status),'safety_stop_reason',char(log.safety_stop_reason), ...
        'release_sha256',releaseSha,'source_lock_sha256',char(release.source_lock_sha256), ...
        'TEST_read',false);
    write_json(fullfile(attemptDir,'run_status.json'),status);
    fprintf('GRU_STREAM_ATTEMPT_DIR=%s\n',attemptDir);
catch ME
    status=struct('schema','DL1018_GRU_STREAM_COSINE_TRACKING_HEAD_RUN_STATUS_V1','state','FAILED', ...
        'candidate','GRU32_STREAM72_COSINE_TRACKING_HEAD_S2026102001','scene_id',sceneId, ...
        'failed_utc',utc_now(),'Plant_calls',1,'raw_path',rawPath, ...
        'raw_sha256',rawSha,'raw_present',isfile(rawPath),'error_identifier',char(ME.identifier), ...
        'error_message',char(ME.message),'release_sha256',releaseSha, ...
        'source_lock_sha256',char(release.source_lock_sha256),'TEST_read',false);
    write_json(fullfile(attemptDir,'run_status.json'),status);
    write_json(fullfile(attemptDir,'run_failure.json'),struct('scene_id',sceneId, ...
        'failed_utc',utc_now(),'error_identifier',char(ME.identifier), ...
        'error_message',char(ME.message),'stack',{ME.stack}));
    rethrow(ME);
end
end

function verify_release_inputs(studyRoot,release)
files={ 'MANIFEST.json','manifest_sha256'; 'run_gru_stream_tracking_head_full72_attempt.m','driver_sha256'; ...
    'IMPLEMENTATION_TASKBOOK_v1.md','taskbook_sha256'; ...
    'IMPLEMENTATION_STATUS_v1.json','implementation_status_sha256'; ...
    'LOCKED_CFG.json','locked_cfg_sha256'; 'SOURCE_LOCK_v1.json','source_lock_sha256'; ...
    'SOURCE_DIFF_v1.json','source_diff_sha256'; ...
    'audits/FULL72_INPUT_IDENTITY_POWERSHELL_v1.json','full72_input_identity_sha256'; ...
    'audits/audit_full72_scene_array_precheck.m','full72_scene_array_precheck_script_sha256'; ...
    'audits/FULL72_SCENE_ARRAY_PRECHECK_v1.json','full72_scene_array_precheck_sha256'};
for i=1:size(files,1)
    path=fullfile(studyRoot,files{i,1});
    assert(isfile(path)&&strcmpi(sha256_file(path),char(release.(files{i,2}))), ...
        'GRUStream:ReleaseHash','Reviewed release input changed: %s.',files{i,1});
end
lock=jsondecode(fileread(fullfile(studyRoot,'SOURCE_LOCK_v1.json')));
runnerRoot=fullfile(studyRoot,'candidate_runner_work');
assert(strcmpi(char(java.io.File(lock.root).getCanonicalPath()), ...
    char(java.io.File(runnerRoot).getCanonicalPath())), ...
    'GRUStream:SourceLockRoot','Source lock root differs from the isolated GRU candidate tree.');
for i=1:numel(lock.files)
    rel=char(lock.files(i).relative_path);path=fullfile(runnerRoot,rel);
    assert(isfile(path)&&strcmpi(sha256_file(path),char(lock.files(i).sha256)), ...
        'GRUStream:SourceLock','Locked candidate source changed: %s.',rel);
end
for i=1:numel(lock.study_artifacts)
    rel=char(lock.study_artifacts(i).relative_path);path=fullfile(studyRoot,strrep(rel,'/',filesep));
    assert(isfile(path)&&strcmpi(sha256_file(path),char(lock.study_artifacts(i).sha256)), ...
        'GRUStream:StudyArtifactLock','Locked study artifact changed: %s.',rel);
end
assert(strcmpi(sha256_file(char(release.training_accounting_review_path)), ...
    char(release.training_accounting_review_sha256))&& ...
    strcmpi(sha256_file(char(release.training_config_path)),char(release.training_config_sha256))&& ...
    strcmpi(sha256_file(char(release.run_receipt_path)),char(release.run_receipt_sha256))&& ...
    strcmpi(sha256_file(char(release.model_path)),char(release.model_sha256))&& ...
    strcmpi(sha256_file(char(release.training_parity_path)),char(release.training_parity_sha256)), ...
    'GRUCosine:TrainingBinding','Cosine model, configuration, receipt, parity vector, or accounting review changed.');
end
function verify_scene_bindings(scene,record)
fields={'time','initial_state','reference','arms','environment_wind_I'};
paths={char(record.payload_path),char(record.b_raw_path),char(record.c5_raw_path)};
hashes={char(record.payload_sha256),char(record.b_raw_sha256),char(record.c5_raw_sha256)};
for i=1:numel(paths)
    assert(strcmpi(sha256_file(paths{i}),hashes{i}), ...
        'GRUStream:PairedRawHash','A locked payload/B/C5 source changed: %s.',paths{i});
    raw=load(paths{i},'scene');assert(isfield(raw,'scene'), ...
        'GRUStream:PairedRaw','A locked payload/B/C5 source has no scene: %s.',paths{i});
    for j=1:numel(fields)
        f=fields{j};assert(isequaln(scene.(f),raw.scene.(f)), ...
            'GRUStream:PhysicalScene','Scene field %s differs from locked source %s.',f,paths{i});
    end
end
assert(strcmpi(sha256_file(char(record.b_status_path)),char(record.b_status_sha256))&& ...
    strcmpi(sha256_file(char(record.c5_status_path)),char(record.c5_status_sha256)), ...
    'GRUStream:PairedStatusHash','A locked B/C5 status file changed.');
end
function h=sha256_file(path)
fid=fopen(path,'rb');assert(fid>=0,'GRUStream:Read','Cannot read %s.',path);
cleanup=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear cleanup;
end
function write_json(path,value)
fid=fopen(path,'w','n','UTF-8');assert(fid>=0,'GRUStream:Write','Cannot write %s.',path);
cleanup=onCleanup(@()fclose(fid));fprintf(fid,'%s\n',jsonencode(value,'PrettyPrint',true));clear cleanup;
end
function value=field_or(s,name,default)
if isstruct(s)&&isfield(s,name),value=s.(name);else,value=default;end
end
function value=utc_now()
value=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z'''));
end








