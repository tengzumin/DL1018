function report = audit_full72_scene_array_precheck()
% Read-only, no-Plant verification of the 72 full-cohort scene bindings.
here = char(java.io.File(fileparts(mfilename('fullpath'))).getCanonicalPath());
study = fileparts(here);
project = fileparts(fileparts(fileparts(study)));
outPath = fullfile(here, 'FULL72_SCENE_ARRAY_PRECHECK_v1.json');
assert(~isfile(outPath), 'Full72:ReportExists', 'Refusing to overwrite the precheck report.');

release = jsondecode(fileread(fullfile(study, 'RELEASE.json')));
manifest = jsondecode(fileread(fullfile(study, 'MANIFEST.json')));
assert(strcmp(char(release.status), 'PENDING_ROOT_REVIEW') && ...
    double(release.authorized_Plant_calls) == 0 && isempty(release.authorized_scenes) && ...
    double(release.Plant_calls) == 0 && ~logical(release.TEST_read), ...
    'Full72:ReleaseGate', 'Precheck requires a zero-budget review-only release.');
assert(strcmp(char(manifest.status), 'PASS_READ_ONLY_VALIDATION_BINDINGS') && ...
    numel(manifest.records) == 72 && sum(strcmp({manifest.records.source_split}, 'DEV')) == 24 && ...
    sum(strcmp({manifest.records.source_split}, 'VAL')) == 48 && ~logical(manifest.TEST_read), ...
    'Full72:Manifest', 'Expected exactly the frozen DEV24+VAL48 manifest.');

runner = fullfile(study, 'candidate_runner_work');
runtime = fullfile(runner, 'matlab', 'runtime');
addpath(runtime); activate_paired_runner(); addpath(study, '-begin'); addpath(runtime, '-begin');
locked = jsondecode(fileread(fullfile(study, 'LOCKED_CFG.json')));
first = manifest.records(1);
prepared = prepare_mlp15_dev72_no_plant(char(first.payload_path));
actual = prepared.cfg;
assert(isequal(double(actual.control.command_filter.acceleration_limit(:)), [Inf; Inf; 6]) && ...
    isequal(double(actual.control.command_filter.wn(:)), [18; 18; 12]) && ...
    isequal(double(actual.control.command_filter.damping(:)), [1; 1; 1]) && ...
    isequal(double(actual.control.bs.attitude.k1(:)), double(locked.K1(:))) && ...
    isequal(double(actual.rbf.attitude.dmax(:)), double(locked.dmax(:))) && ...
    abs(double(actual.rbf.attitude.beta_rise_time) - double(locked.beta_rise_time_s)) < 1e-12 && ...
    strcmpi(char(actual.controller_morphology_mode), 'fixed'), ...
    'Full72:Config', 'Prepared C5 configuration differs from the frozen snapshot.');
Pplant = simulation_parameters(actual, actual.plant.arm_initial, zeros(4, 1));
Pfixed = controller_parameters(actual, Pplant, 'fixed');
assert(isequal(double(Pfixed.inertia), double(locked.J0_kgm2)) && ...
    isequal(double(Pfixed.inertia_dot_for_bs), zeros(3)), ...
    'Full72:FixedJ0', 'Prepared fixed J0/Jdot0 differs from the locked snapshot.');
modelPath = char(release.model_path);
assert(strcmpi(hash_file(modelPath), char(release.model_sha256)) && ...
    strcmpi(hash_file(modelPath), char(manifest.candidate_model_sha256)), ...
    'Full72:CandidateModel', 'Frozen candidate model SHA mismatch.');
candidateModel = load(modelPath);
opts = make_gate_holdout_options(actual, prepared.model, 'GRU_STREAM', 'ACTIVE', ...
    struct, candidateModel, char(release.model_sha256));
identity = gate_holdout_identity_hashes(actual, prepared.model, opts);
assert(strcmpi(identity.common.position_options_sha256, ...
    prepared.identity.common.position_options_sha256), ...
    'Full72:PositionIdentity', 'Binding the frozen GRU changed C5 position options.');
expectedFunctions = { ...
    'run_mlp15_dev72_closed_loop', 'gru_stream_attitude_step_v1', ...
    'gru_stream_tracking_head_step_v1', 'gru_stream_attitude_forward_v1'};
for i = 1:numel(expectedFunctions)
    name = expectedFunctions{i};
    resolved = char(which(name));
    assert(startsWith(lower(resolved), lower(runner)), ...
        'Full72:WhichPath', 'Function %s resolved outside the isolated source tree: %s', name, resolved);
end

fields = {'time', 'initial_state', 'reference', 'arms', 'environment_wind_I'};
template = struct('scene_id', '', 'source_split', '', 'candidate_reuse', false, ...
    'payload_sha256', '', 'b_raw_sha256', '', 'c5_raw_sha256', '', ...
    'candidate_raw_sha256', '', 'matched_fields', false, 'candidate_raw_fields_match', true);
rows = repmat(template, 1, numel(manifest.records));
for i = 1:numel(manifest.records)
    r = manifest.records(i);
    payload = load(char(r.payload_path), 'scene');
    b = load(char(r.b_raw_path), 'scene');
    c5 = load(char(r.c5_raw_path), 'scene');
    assert(isfield(payload, 'scene') && isfield(b, 'scene') && isfield(c5, 'scene'), ...
        'Full72:SceneVariable', 'Scene variable missing for %s.', char(r.scene_id));
    assert(strcmp(char(payload.scene.scene_id), char(r.scene_id)) && ...
        strcmp(char(b.scene.scene_id), char(r.scene_id)) && ...
        strcmp(char(c5.scene.scene_id), char(r.scene_id)), ...
        'Full72:SceneID', 'Scene ID mismatch for %s.', char(r.scene_id));
    for j = 1:numel(fields)
        f = fields{j};
        assert(isequaln(payload.scene.(f), b.scene.(f)) && ...
            isequaln(payload.scene.(f), c5.scene.(f)), ...
            'Full72:SceneArrayMismatch', 'Payload/B/C5 field %s differs for %s.', f, char(r.scene_id));
    end
    candidateRawSha = '';
    candidateFieldsMatch = true;
    if logical(r.candidate_reuse)
        assert(strcmpi(hash_file(char(r.candidate_raw_path)), char(r.candidate_raw_sha256)), ...
            'Full72:ReusedRawSHA', 'Reused candidate raw changed for %s.', char(r.scene_id));
        candidate = load(char(r.candidate_raw_path), 'scene');
        assert(isfield(candidate, 'scene') && strcmp(char(candidate.scene.scene_id), char(r.scene_id)), ...
            'Full72:ReusedSceneID', 'Reused candidate scene ID mismatch for %s.', char(r.scene_id));
        for j = 1:numel(fields)
            f = fields{j};
            assert(isequaln(payload.scene.(f), candidate.scene.(f)), ...
                'Full72:ReusedSceneMismatch', 'Reused candidate field %s differs for %s.', f, char(r.scene_id));
        end
        candidateRawSha = char(r.candidate_raw_sha256);
    end
    rows(i) = struct('scene_id', char(r.scene_id), 'source_split', char(r.source_split), ...
        'candidate_reuse', logical(r.candidate_reuse), 'payload_sha256', char(r.payload_sha256), ...
        'b_raw_sha256', char(r.b_raw_sha256), 'c5_raw_sha256', char(r.c5_raw_sha256), ...
        'candidate_raw_sha256', candidateRawSha, 'matched_fields', true, ...
        'candidate_raw_fields_match', candidateFieldsMatch);
end

report = struct('schema', 'DL1018_GRU_STREAM_TRACKING_HEAD_FULL72_SCENE_ARRAY_PRECHECK_V1', ...
    'status', 'PASS_NO_PLANT_ALL72_SCENE_ARRAY_EQUALITY', ...
    'created_utc', char(datetime('now', 'TimeZone', 'UTC', 'Format', "yyyy-MM-dd'T'HH:mm:ss.SSS'Z'")), ...
    'study_id', char(release.study_id), 'candidate', char(release.candidate), ...
    'scene_count', 72, 'dev_scene_count', 24, 'val_scene_count', 48, ...
    'reused_candidate_count', sum([manifest.records.candidate_reuse]), ...
    'new_candidate_count', 72 - sum([manifest.records.candidate_reuse]), ...
    'fields_compared', {fields}, 'all_payload_b_c5_fields_equal', true, ...
    'reused_candidate_fields_equal', true, 'actual_cfg_status', 'PASS', ...
    'which_path_status', 'PASS_ISOLATED_59_FILE_SOURCE_TREE', ...
    'position_options_sha256', identity.common.position_options_sha256, ...
    'candidate_model_sha256', char(release.model_sha256), ...
    'Plant_calls', 0, 'training_runs', 0, 'TEST_read', false, 'records', rows);
fid = fopen(outPath, 'w', 'n', 'UTF-8');
assert(fid >= 0, 'Full72:ReportWrite', 'Could not write precheck report.');
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, '%s\n', jsonencode(report, 'PrettyPrint', true));
clear cleanup;
end

function h = hash_file(path)
fid = fopen(path, 'rb');
assert(fid >= 0, 'Full72:ReadFile', 'Cannot read %s.', path);
cleanup = onCleanup(@() fclose(fid));
md = java.security.MessageDigest.getInstance('SHA-256');
while true
    bytes = fread(fid, 8 * 1024 * 1024, '*uint8');
    if isempty(bytes), break; end
    md.update(typecast(bytes(:), 'int8'));
end
h = lower(reshape(dec2hex(typecast(md.digest(), 'uint8'), 2).', 1, []));
clear cleanup;
end
