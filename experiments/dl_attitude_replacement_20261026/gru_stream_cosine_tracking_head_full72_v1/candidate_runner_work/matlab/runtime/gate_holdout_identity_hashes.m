function hashes=gate_holdout_identity_hashes(cfg,positionModel,opts)
% Return the C5-common and geometry/method-specific identities used by the gate runner.
assert(isstruct(cfg)&&isstruct(positionModel)&&isstruct(opts)&& ...
    all(isfield(positionModel,{'input_mu','input_sigma','output_W'})), ...
    'GATE:IdentityInput','Expected cfg, the C5 X14 model, and gate options.');
assert(numel(positionModel.input_mu)==14&&numel(positionModel.input_sigma)==14&& ...
    isequal(size(positionModel.output_W),[33,3])&& ...
    all(isfinite(double(positionModel.input_mu(:))))&& ...
    all(isfinite(double(positionModel.input_sigma(:))))&&all(double(positionModel.input_sigma(:))>0)&& ...
    all(isfinite(double(positionModel.output_W(:))), 'all'), ...
    'GATE:IdentityModel','Invalid frozen C5 normalizer or W0.');
[baseline,candidate]=make_paired_c5_options(cfg,positionModel);
rbfFlags={'rbf_attitude_enabled','rbf_attitude_output_enabled','rbf_attitude_update_enabled'};
commonOptions=rmfield(baseline,[rbfFlags,{'paired_arm'}]);
assert(isequaln(commonOptions,rmfield(candidate,[rbfFlags,{'paired_arm'}])), ...
    'GATE:IdentityPositionOptions','C5 position options differ across attitude arms.');
common=struct('model_sha256',gate_hash_value(positionModel), ...
    'normalizer_sha256',gate_hash_value(struct('input_mu',double(positionModel.input_mu(:)), ...
        'input_sigma',double(positionModel.input_sigma(:)))), ...
    'W0_sha256',paired_sha256_double(double(positionModel.output_W)), ...
    'position_options_sha256',gate_hash_value(commonOptions));
Pplant=simulation_parameters(cfg,cfg.plant.arm_initial,zeros(4,1));
Pfixed=controller_parameters(cfg,Pplant,'fixed');
assert(isfield(opts,'gate_identity_lock'),'GATE:IdentityLock','Missing gate_identity_lock.');
effectiveOptions=opts;
effectiveOptions=rmfield(effectiveOptions,'gate_identity_lock');
geometry=struct('cfg_sha256',gate_hash_value(cfg), ...
    'plant_sha256',gate_hash_value(cfg.plant), ...
    'filter_sha256',gate_hash_value(struct('command_filter',cfg.control.command_filter, ...
        'bs',cfg.control.bs,'limits',cfg.control.limits)), ...
    'allocator_sha256',gate_hash_value(struct('C0',double(Pfixed.allocation.C), ...
        'limits',Pfixed.limits,'arm_lengths',double(Pfixed.arm_lengths))), ...
    'J0_sha256',paired_sha256_double(double(Pfixed.inertia)), ...
    'C0_sha256',paired_sha256_double(double(Pfixed.allocation.C)), ...
    'options_sha256',gate_hash_value(effectiveOptions));
hashes=struct('common',common,'geometry',geometry);
end