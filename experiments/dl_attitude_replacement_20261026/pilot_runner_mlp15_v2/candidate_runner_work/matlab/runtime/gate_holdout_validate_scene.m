function audit=gate_holdout_validate_scene(scene,cfg,geometryArm)
% Fail closed on the task scene contract and fixed/active geometry schedule.
geometryArm=upper(char(geometryArm));
assert(isstruct(scene)&&isfield(scene,'reference_contract_id')&& ...
    strcmp(char(string(scene.reference_contract_id)),'DL1018_GATE_INSPECTION_HOLDOUT_V1'), ...
    'GATE:SceneContract','Expected DL1018_GATE_INSPECTION_HOLDOUT_V1.');
assert(isfield(scene,'scene_id')&&~isempty(char(string(scene.scene_id))), ...
    'GATE:SceneId','A nonempty scene_id is required.');
assert(isstruct(cfg)&&isfield(cfg,'plant')&&abs(double(cfg.plant.dt)-.001)<1e-12, ...
    'GATE:PlantDt','Expected the frozen 1 kHz Plant configuration.');
N=20001;
t=double(scene.time(:));
assert(numel(t)==N&&all(isfinite(t))&&abs(t(1))<1e-12&& ...
    max(abs(t-(0:N-1)'*.001))<1e-12, ...
    'GATE:Time','Expected 20,001 samples at exactly 1 ms from 0 to 20 s.');
assert(isfield(scene,'initial_state')&&numel(scene.initial_state)==12&& ...
    all(isfinite(double(scene.initial_state(:))))&& ...
    max(abs(double(scene.initial_state(:))-[-1.5;0;1.2;zeros(9,1)]))<1e-12, ...
    'GATE:InitialState','Unexpected initial state.');
assert(isstruct(scene.reference)&&all(isfield(scene.reference, ...
    {'position','velocity','acceleration','yaw','yaw_rate','yaw_acceleration'})), ...
    'GATE:Reference','Missing analytic reference arrays.');
for field={'position','velocity','acceleration'}
    value=double(scene.reference.(field{1}));
    assert(isequal(size(value),[N,3])&&all(isfinite(value),'all'), ...
        'GATE:ReferenceShape','Invalid reference.%s array.',field{1});
end
for field={'yaw','yaw_rate','yaw_acceleration'}
    value=double(scene.reference.(field{1}));
    value=value(:);
    assert(numel(value)==N&&all(isfinite(value)), ...
        'GATE:ReferenceShape','Invalid reference.%s array.',field{1});
end
assert(norm(double(scene.reference.position(1,:)).'-double(scene.initial_state(1:3)),inf)<1e-12&& ...
    norm(double(scene.reference.velocity(1,:)),inf)<1e-12&& ...
    abs(double(scene.reference.yaw(1)))<1e-12, ...
    'GATE:ReferenceStart','Reference does not start at the prescribed state.');
assert(isfield(scene,'environment_wind_I')&& ...
    isequal(size(scene.environment_wind_I),[N,3])&&all(isfinite(double(scene.environment_wind_I)),'all'), ...
    'GATE:Wind','Invalid scene wind array.');
assert(isstruct(scene.arms)&&all(isfield(scene.arms, ...
    {'command','rho_true','rho_hat','rhoDot_true','rhoDot_hat'})), ...
    'GATE:Arms','Missing morphology arrays.');
for field={'command','rho_true','rho_hat','rhoDot_true','rhoDot_hat'}
    value=double(scene.arms.(field{1}));
    assert(isequal(size(value),[N,4])&&all(isfinite(value),'all'), ...
        'GATE:ArmShape','Invalid arms.%s array.',field{1});
    assert(max(abs(value-value(:,1)),[],'all')<1e-12, ...
        'GATE:ArmSynchrony','Four arms must follow the same prescribed geometry.');
end
initial=double(cfg.plant.arm_initial(:));
assert(numel(initial)==4&&all(isfinite(initial))&&max(abs(initial-initial(1)))<1e-12, ...
    'GATE:GeometryCfg','cfg.plant.arm_initial must specify one synchronous fixed length.');
if strcmp(geometryArm,'FIXED_BOUND15')
    rho0=sqrt(2)*(.225-.0635-.015);
    assert(abs(initial(1)-rho0)<1e-12,'GATE:GeometryCfg','FIXED_BOUND15 cfg must start at rho*=0.207182 m.');
elseif ismember(geometryArm,{'ACTIVE','FIXED_MIN'})
    rho0=.15;
    assert(abs(initial(1)-rho0)<1e-12,'GATE:GeometryCfg','ACTIVE/FIXED_MIN cfg must start at 0.15 m.');
else
    error('GATE:GeometryArm','Unknown geometry arm %s.',geometryArm);
end
command=zeros(N,1);
if strcmp(geometryArm,'ACTIVE')
    command(t>=6&t<8)=1;
    command(t>=13&t<15)=-1;
end
expectedCommand=repmat(command,1,4);
assert(max(abs(double(scene.arms.command)-expectedCommand),[],'all')<1e-12, ...
    'GATE:ArmSchedule','Morphology command does not match the registered geometry schedule.');
rhoExpected=zeros(N,1);rhoExpected(1)=rho0;
for k=1:N-1
    rhoExpected(k+1)=min(max(rhoExpected(k)+.001*.05*command(k), ...
        double(cfg.plant.arm_length_min)),double(cfg.plant.arm_length_max));
end
expectedRho=repmat(rhoExpected,1,4);
expectedRhoDot=.05*expectedCommand;
assert(max(abs(double(scene.arms.rho_true)-expectedRho),[],'all')<1e-12&& ...
    max(abs(double(scene.arms.rho_hat)-expectedRho),[],'all')<1e-12&& ...
    max(abs(double(scene.arms.rhoDot_true)-expectedRhoDot),[],'all')<1e-12&& ...
    max(abs(double(scene.arms.rhoDot_hat)-expectedRhoDot),[],'all')<1e-12, ...
    'GATE:ArmTrajectory','rho/rhoDot arrays do not match command-integrated geometry.');
assert(isfield(scene,'R_task'),'GATE:RTaskRequired','The locked common R_task is required before any Plant run.');
RtaskHash=''; RtaskSerializedHash='';
if isfield(scene,'R_task')
    assert(isfield(scene,'R_task_sha256')&& ...
        (ischar(scene.R_task_sha256)||(isstring(scene.R_task_sha256)&&isscalar(scene.R_task_sha256))), ...
        'GATE:RTaskHash','R_task requires a scalar R_task_sha256 declaration.');
    R=double(scene.R_task);
    assert(isequal(size(R),[3,3,N])&&all(isfinite(R),'all'), ...
        'GATE:RTaskShape','R_task must be finite 3x3xN.');
    RtaskHash=paired_sha256_double(R);
    declaredRtaskHash=char(string(scene.R_task_sha256));
    assert(numel(declaredRtaskHash)==64&&strcmpi(declaredRtaskHash,RtaskHash), ...
        'GATE:RTaskHash','R_task_sha256 does not match raw column-major double bytes.');
    RtaskSerializedHash=gate_hash_value(R);
    for k=1:N
        assert(norm(R(:,:,k).'*R(:,:,k)-eye(3),'fro')<1e-8&&det(R(:,:,k))>0, ...
            'GATE:RTaskRotation','R_task contains an invalid rotation at sample %d.',k);
    end
end
payload=struct('scene_id',char(string(scene.scene_id)), ...
    'reference_contract_id',char(string(scene.reference_contract_id)), ...
    'time',t,'initial_state',double(scene.initial_state(:)), ...
    'reference',scene.reference,'arms',scene.arms, ...
    'environment_wind_I',double(scene.environment_wind_I));
if isfield(scene,'R_task'),payload.R_task=double(scene.R_task);end
if isfield(scene,'R_task_sha256'),payload.R_task_sha256=char(string(scene.R_task_sha256));end
audit=struct('scene_id',char(string(scene.scene_id)), ...
    'geometry_arm',geometryArm,'initial_arm_length_m',rho0, ...
    'scene_payload_sha256',gate_hash_value(payload), ...
    'R_task_sha256',RtaskHash,'R_task_serialized_sha256',RtaskSerializedHash);
end