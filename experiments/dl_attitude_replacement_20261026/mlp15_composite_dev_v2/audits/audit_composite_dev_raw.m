function report=audit_composite_dev_raw(sceneId,candidateRawPath)
% Independent state/trace replay. Rebuilds BS T and surface from logged measurements.
here=char(java.io.File(fileparts(mfilename('fullpath'))).getCanonicalPath());
study=fileparts(here);outPath=fullfile(here,[sceneId '_COMPOSITE_DEV_AUDIT.json']);
assert(~isfile(outPath),'CompositeAudit:OutputExists','Refusing to overwrite an audit.');
release=jsondecode(fileread(fullfile(study,'RELEASE.json')));
manifest=jsondecode(fileread(fullfile(study,'MANIFEST.json')));
records=manifest.records(strcmp({manifest.records.scene_id},sceneId));assert(isscalar(records));
candidateRawPath=char(java.io.File(candidateRawPath).getCanonicalPath());
prefix=[char(java.io.File(study).getCanonicalPath()) filesep];
assert(startsWith(lower(candidateRawPath),lower(prefix))&&isfile(candidateRawPath), ...
    'CompositeAudit:RawPath','Candidate raw must be inside this new study directory.');
verify_source_lock(study,release);
assert(strcmpi(hash_file([mfilename('fullpath') '.m']),char(release.raw_audit_script_sha256))&& ...
    strcmpi(hash_file(fullfile(study,'LOCKED_CFG.json')),release.locked_cfg_sha256)&& ...
    strcmpi(hash_file(fullfile(study,'SOURCE_LOCK_v2.json')),release.source_lock_sha256)&& ...
    strcmpi(hash_file(fullfile(study,'SOURCE_DIFF_v2.json')),release.source_diff_sha256)&& ...
    strcmpi(hash_file(fullfile(study,char(release.no_plant_check_path))),release.no_plant_check_sha256), ...
    'CompositeAudit:ReleaseLock','Release inputs no longer match their hashes.');
statusPath=fullfile(fileparts(candidateRawPath),'run_status.json');
runStatus=jsondecode(fileread(statusPath));
assert(strcmp(char(runStatus.state),'COMPLETED')&&strcmp(char(runStatus.scene_id),sceneId)&& ...
    strcmpi(hash_file(candidateRawPath),char(runStatus.raw_sha256)), ...
    'CompositeAudit:RawSHA','Candidate raw/status identity failed.');
raw=load(candidateRawPath,'log','scene','runIdentity');L=raw.log;X=double(L.state);
model=load(release.model_path);scale=double(model.target_rms(:));K1=double(release.locked_cfg.K1(:));
J0=double(release.fixed_J0_kgm2);dmax=double(release.locked_cfg.dmax(:));
assert(strcmpi(hash_file(release.model_path),release.model_sha256)&& ...
    strcmpi(raw.runIdentity.mlp15_model_sha256,release.model_sha256)&& ...
    strcmpi(L.composite_release_sha256,hash_file(fullfile(study,'RELEASE.json')))&& ...
    strcmp(L.status,'STABLE')&&L.complete_transitions&& ...
    L.mlp15_composite_head_enabled&&L.mlp15_causal_head_enabled&& ...
    ~L.mlp15_variable_inertia_reconstruction_used&&~L.gate_feedforward_enabled&& ...
    ~L.gate_observer_enabled&&~any(L.rbf_update_flag(:))&& ...
    all(abs(double(L.attitude_rbf_compensation_torque_Nm(:)))<1e-12), ...
    'CompositeAudit:RunIdentity','Raw is not a clean composite-head MLP run.');
predictionStatus=jsondecode(fileread(char(records(1).prediction_only_status_path)));
assert(strcmp(char(predictionStatus.state),'COMPLETED')&&logical(predictionStatus.engineering_pass)&& ...
    double(predictionStatus.Plant_calls)==1&&~logical(predictionStatus.TEST_read)&& ...
    strcmpi(hash_file(records(1).prediction_only_raw_path),char(records(1).prediction_only_raw_sha256))&& ...
    strcmpi(hash_file(char(records(1).prediction_only_status_path)),char(records(1).prediction_only_status_sha256))&& ...
    same_scene_arrays(raw.scene,load_scene(records(1).prediction_only_raw_path)), ...
    'CompositeAudit:SceneArrays','Candidate and prediction_only physical scene arrays differ.');
assert(strcmpi(scene_hash(raw.scene),records(1).scene_arrays_sha256), ...
    'CompositeAudit:SceneHash','Candidate physical scene-array hash differs from manifest.');
traces=L.mlp15_attitude_trace;events=find(~cellfun(@isempty,traces));assert(~isempty(events));
history=zeros(13,14);W=zeros(33,3);P=10*eye(33);previousPhi=zeros(33,1);
previousBase=zeros(3,1);previousEvent=0;previousBeta=0;outputError=0;featureError=0;
surfaceError=0;mapError=0;observationError=0;weightError=0;driveError=0;
covarianceError=0;torqueError=0;projectionCount=0;rlsCount=0;trackingCount=0;clipCount=0;
firstCorrectedEvent=NaN;firstUpdateTime=NaN;
for q=1:numel(events)
    k=events(q);z=traces{k};head=z.causal_head;
    eta=X(k,7:9).';omega=X(k,10:12).';
    T=euler_map(eta);e=wrap(double(L.filtered_attitude_reference(k,:)).'-eta);
    surface=double(L.filtered_attitude_rate(k,:)).'+K1.*e-T*omega;
    feature=[e;omega;double(L.attitude_bs_nominal_torque_Nm(k,:)).'; ...
        double(L.arms.command(k,:)).'];
    assert(logical(head.enabled)&&numel(feature)==13&&all(isfinite(feature))&&z.sample_index==k&& ...
        abs(z.time_s-L.time(k))<1e-12&&z.rbf_output_enabled==false&& ...
        z.rbf_update_enabled==false&&z.time_varying_inertia_reconstruction_used==false, ...
        'CompositeAudit:Feature','Illegal or misindexed MLP event feature.');
    featureError=max(featureError,max(abs(feature-double(z.feature_raw(:)))));
    surfaceError=max(surfaceError,max(abs(surface-double(head.tracking_surface(:)))));
    mapError=max(mapError,max(abs(T-double(head.tracking_euler_rate_map)),[],'all'));
    assert(isequal(double(z.tracking_surface(:)),double(head.tracking_surface(:)))&& ...
        isequal(double(z.tracking_euler_rate_map),double(head.tracking_euler_rate_map))&& ...
        isequal(double(z.actual_event_dt),double(head.actual_event_dt)), ...
        'CompositeAudit:TraceBinding','Top-level tracking trace differs from the MLP update input.');
    xnorm=(feature-double(model.input_mean(:)))./double(model.input_std(:));
    window=[history,xnorm];history=window(:,2:end);
    hidden=double(model.fc1_weight)*window(:)+double(model.fc1_bias(:));hidden=hidden./(1+exp(-hidden));
    hidden=double(model.fc2_weight)*hidden+double(model.fc2_bias(:));hidden=hidden./(1+exp(-hidden));
    base=(double(model.head_weight)*hidden+double(model.head_bias(:))).*scale;
    phi=[hidden;1];phi=phi/norm(phi);prediction=base+scale.*(W.'*phi);
    outputError=max(outputError,max(abs(prediction-double(z.raw_residual_rad_s2(:)))));
    weightError=max(weightError,max(abs(W-double(head.weight_before)),[],'all'));
    if norm(double(head.correction_residual_rad_s2(:)))>1e-12&&isnan(firstCorrectedEvent)
        firstCorrectedEvent=k;
    end
    clipped=min(max(prediction,-dmax),dmax);
    clipCount=clipCount+any(abs(prediction-clipped)>1e-12);
    expectedTorque=J0*(double(z.beta)*clipped);
    torqueError=max(torqueError,max(abs(expectedTorque-double(z.estimateTorque_Nm(:)))));
    if previousEvent>0
        indices=(previousEvent:k).';times=double(L.time(previousEvent:k));
        assert(numel(indices)==11&&all(diff(indices)==1)&& ...
            abs(times(1)-L.time(previousEvent))<1e-12&& ...
            abs(times(end)-L.time(k))<1e-12&&max(abs(diff(times)-.001))<1e-10&& ...
            head.previous_feature_sample_index==previousEvent&& ...
            head.issued_torque_max_sample_index==k-1&& ...
            abs(head.actual_event_dt-(L.time(k)-L.time(previousEvent)))<1e-10, ...
            'CompositeAudit:PastIndices','Past residual interval or event dt differs from v1.');
        omegaSegment=X(previousEvent:k-1,10:12);torqueSegment=double( ...
            L.requested_generalized(previousEvent:k-1,2:4));
        gyro=cross(omegaSegment,omegaSegment*J0.',2);
        observed=((X(k,10:12)-X(previousEvent,10:12))/(L.time(k)-L.time(previousEvent))+ ...
            mean((gyro-torqueSegment)/J0.',1)).';
        observationError=max(observationError,max(abs(observed-double( ...
            head.observation_residual_rad_s2(:)))));
        if previousBeta>=1&&double(z.beta)>=1
            Pprior=P/.999;gain=(Pprior*previousPhi)/(1+previousPhi.'*Pprior*previousPhi);
            innovation=observed./scale-previousBase-W.'*previousPhi;
            W=W+gain*innovation.';A=eye(33)-gain*previousPhi.';
            P=A*Pprior*A.'+gain*gain.';P=(P+P.')/2;chol(P);
            rlsCount=rlsCount+1;if isnan(firstUpdateTime),firstUpdateTime=L.time(k);end
        end
        if double(z.beta)>=1
            drive=-(P*phi)*(double(z.beta)*(scale.*(T.'*surface))).';
            W=W+double(head.actual_event_dt)*drive;trackingCount=trackingCount+1;
        else
            drive=zeros(33,3);
        end
        magnitude=norm(W,'fro');projected=magnitude>20;
        if projected,W=W*(20/magnitude);end
        assert(logical(head.projection_active)==projected&& ...
            logical(head.update_executed)==(previousBeta>=1&&double(z.beta)>=1)&& ...
            logical(head.tracking_update_executed)==(double(z.beta)>=1), ...
            'CompositeAudit:UpdateFlags','RLS, tracking, or projection event differs.');
        projectionCount=projectionCount+projected;
        driveError=max(driveError,max(abs(drive-double(head.tracking_drive)),[],'all'));
        covarianceError=max(covarianceError,max(abs(diag(P)-double( ...
            head.covariance_diagonal_after(:)))));
        if previousBeta>=1&&double(z.beta)>=1&&isnan(firstUpdateTime),firstUpdateTime=L.time(k);end
    else
        assert(head.actual_event_dt==0&&~head.tracking_update_executed, ...
            'CompositeAudit:FirstEvent','First event unexpectedly applied a tracking update.');
    end
    weightError=max(weightError,max(abs(W-double(head.weight_after)),[],'all'));
    assert(all(isfinite(P),'all')&&chol_ok(P),'CompositeAudit:SPD','RLS covariance lost SPD.');
    previousPhi=phi;previousBase=base./scale;previousEvent=k;previousBeta=double(z.beta);
end
assert(featureError<1e-9&&surfaceError<1e-9&&mapError<1e-9&& ...
    outputError<1e-7&&observationError<1e-7&&weightError<1e-6&& ...
    driveError<1e-7&&covarianceError<1e-6&&torqueError<1e-9&& ...
    rlsCount>0&&trackingCount>0, ...
    'CompositeAudit:Replay','Independent raw replay does not match the trace.');
assert(~isnan(firstCorrectedEvent),'CompositeAudit:NoCorrection','No corrected output was found.');
prediction=load(records(1).prediction_only_raw_path,'log','scene');
warmupError=max(abs(X(1:firstCorrectedEvent,:)-double( ...
    prediction.log.state(1:firstCorrectedEvent,:))),[],'all');
assert(warmupError<1e-10,'CompositeAudit:Warmup','State changed before first corrected output.');

pairedPaths={records(1).b_raw_path,records(1).c5_raw_path,records(1).frozen_raw_path};
pairedHashes={records(1).b_raw_sha256,records(1).c5_raw_sha256,records(1).frozen_raw_sha256};
for i=1:numel(pairedPaths),assert(strcmpi(hash_file(char(pairedPaths{i})),char(pairedHashes{i})), ...
    'CompositeAudit:PairedRawHash','A paired comparator raw changed.');end
b=load(records(1).b_raw_path,'log','scene');c5=load(records(1).c5_raw_path,'log','scene');
frozen=load(records(1).frozen_raw_path,'log','scene');
assert(same_scene_arrays(raw.scene,b.scene)&&same_scene_arrays(raw.scene,c5.scene)&& ...
    same_scene_arrays(raw.scene,frozen.scene),'CompositeAudit:BaselineArrays', ...
    'B/C5/frozen comparators are not the same physical scene.');
report=struct('status','PASS_INDEPENDENT_COMPOSITE_DEV_RAW_REPLAY', ...
    'Plant_calls_by_audit',0,'TEST_read',false,'scene_id',sceneId, ...
    'candidate_raw_sha256',hash_file(candidateRawPath), ...
    'scene_arrays_sha256',scene_hash(raw.scene),'model_sha256',release.model_sha256, ...
    'event_count',numel(events),'residual_update_events',rlsCount, ...
    'tracking_update_events',trackingCount,'projection_events',projectionCount, ...
    'dmax_clipped_events',clipCount,'first_update_time_s',firstUpdateTime, ...
    'first_corrected_sample_index',firstCorrectedEvent, ...
    'max_feature_error',featureError,'max_surface_rebuild_error',surfaceError, ...
    'max_euler_map_rebuild_error',mapError,'max_raw_output_replay_error_rad_s2',outputError, ...
    'max_observed_residual_error_rad_s2',observationError,'max_weight_replay_error',weightError, ...
    'max_tracking_drive_replay_error',driveError,'max_covariance_diagonal_error',covarianceError, ...
    'max_applied_torque_error_Nm',torqueError, ...
    'max_state_difference_before_first_corrected_output',warmupError, ...
    'candidate',metrics(L,raw.scene,release),'prediction_only',metrics(prediction.log,prediction.scene,release), ...
    'B',metrics(b.log,b.scene,release),'C5',metrics(c5.log,c5.scene,release), ...
    'frozen_MLP',metrics(frozen.log,frozen.scene,release), ...
    'tracking_effect_evaluated',true,'prediction_only_raw_sha256',char(records(1).prediction_only_raw_sha256), ...
    'source_script_sha256',hash_file([mfilename('fullpath') '.m']));
write_json(outPath,report);disp(report);
end

function verify_source_lock(study,release)
lockPath=fullfile(study,'SOURCE_LOCK_v2.json');
assert(strcmpi(hash_file(lockPath),char(release.source_lock_sha256)), ...
    'CompositeAudit:SourceLockHash','Candidate source lock file changed.');
lock=jsondecode(fileread(lockPath));runner=fullfile(study,'candidate_runner_work');
assert(strcmpi(char(java.io.File(lock.root).getCanonicalPath()), ...
    char(java.io.File(runner).getCanonicalPath())), ...
    'CompositeAudit:SourceLockRoot','Candidate source lock root changed.');
for i=1:numel(lock.files)
    rel=char(lock.files(i).relative_path);path=fullfile(runner,rel);
    assert(isfile(path)&&strcmpi(hash_file(path),char(lock.files(i).sha256)), ...
        'CompositeAudit:SourceLock','Locked source changed: %s.',rel);
end
end

function T=euler_map(eta)
phi=eta(1);theta=max(min(eta(2),pi/2-1e-4),-pi/2+1e-4);
T=[1,sin(phi)*tan(theta),cos(phi)*tan(theta); ...
    0,cos(phi),-sin(phi);0,sin(phi)/cos(theta),cos(phi)/cos(theta)];
end

function y=wrap(x)
y=atan2(sin(x),cos(x));
end

function yes=chol_ok(P)
[~,flag]=chol(P);yes=flag==0;
end

function scene=load_scene(path)
pack=load(path,'scene');scene=pack.scene;
end

function yes=same_scene_arrays(a,b)
yes=isequaln(a.time,b.time)&&isequaln(a.initial_state,b.initial_state)&& ...
    isequaln(a.reference,b.reference)&&isequaln(a.arms,b.arms)&& ...
    isequaln(a.environment_wind_I,b.environment_wind_I);
end

function h=scene_hash(scene)
payload=struct('time',scene.time,'initial_state',scene.initial_state, ...
    'reference',scene.reference,'arms',scene.arms,'environment_wind_I',scene.environment_wind_I);
bytes=uint8(unicode2native(jsonencode(payload),'UTF-8'));
md=java.security.MessageDigest.getInstance('SHA-256');md.update(typecast(bytes(:),'int8'));
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end

function s=metrics(L,scene,release)
X=double(L.state);t=double(L.time(:));assert(size(X,1)==20001&&L.last_transition==20000);
positionError=X(:,1:3)-double(scene.reference.position);acc=double(scene.reference.acceleration);
acc(:,3)=acc(:,3)+double(release.gravity_mps2);yaw=double(scene.reference.yaw(:));
A=cos(yaw).*acc(:,1)+sin(yaw).*acc(:,2);B=sin(yaw).*acc(:,1)-cos(yaw).*acc(:,2);
roll=atan2(B,hypot(acc(:,3),A));pitch=atan2(A,acc(:,3));
tilt=min(1,double(release.max_tilt_rad)./max(hypot(roll,pitch),eps));
outer=angle_error(X(:,7:9),[roll.*tilt,pitch.*tilt,yaw]);
inner=angle_error(X(1:20000,7:9),double(L.filtered_attitude_reference));
s=struct('Q_m',sqrt(mean(sum(positionError.^2,2))),'SO3_rad',sqrt(mean(outer.^2)), ...
    'inner_tracking_rad',sqrt(mean(inner.^2)),'RMSE_xyz_m',sqrt(mean(positionError.^2,1)), ...
    'motor_saturation_samples',nnz(any(L.motor_saturated,2)), ...
    'generalized_clip_samples',nnz(any(L.generalized_clipped,2)), ...
    'peak_position_error_m',max(vecnorm(positionError,2,2)),'peak_SO3_rad',max(outer), ...
    'Q_0_5_m',sqrt(mean(sum(positionError(t<5,:).^2,2))), ...
    'Q_15_20_m',sqrt(mean(sum(positionError(t>=15,:).^2,2))));
end

function theta=angle_error(a,b)
qa=quat(double(a));qb=quat(double(b));theta=2*acos(min(1,abs(sum(qa.*qb,2))));
end

function q=quat(e)
c=cos(e/2);s=sin(e/2);
q=[c(:,1).*c(:,2).*c(:,3)+s(:,1).*s(:,2).*s(:,3), ...
    s(:,1).*c(:,2).*c(:,3)-c(:,1).*s(:,2).*s(:,3), ...
    c(:,1).*s(:,2).*c(:,3)+s(:,1).*c(:,2).*s(:,3), ...
    c(:,1).*c(:,2).*s(:,3)-s(:,1).*s(:,2).*c(:,3)];
end

function write_json(path,value)
fid=fopen(path,'w','n','UTF-8');assert(fid>=0);cleanup=onCleanup(@()fclose(fid));
fprintf(fid,'%s\n',jsonencode(value,'PrettyPrint',true));clear cleanup;
end

function h=hash_file(path)
fid=fopen(path,'rb');assert(fid>=0);cleanup=onCleanup(@()fclose(fid));
md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear cleanup;
end




