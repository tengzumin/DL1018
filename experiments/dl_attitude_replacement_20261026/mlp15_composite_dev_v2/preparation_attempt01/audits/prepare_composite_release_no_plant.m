function release=prepare_composite_release_no_plant()
% Bind copied code and historical validation inputs without starting a Plant run.
here=char(java.io.File(fileparts(mfilename('fullpath'))).getCanonicalPath());
study=fileparts(here);research=fileparts(study);runtime=fullfile(study,'candidate_runner_work','matlab','runtime');
core=fullfile(study,'candidate_runner_work','matlab','core');addpath(runtime,core);
check=jsondecode(fileread(fullfile(here,'NO_PLANT_CHECK_v7.json')));
assert(strcmp(check.status,'PASS_NO_PLANT_COMPOSITE_HEAD')&&check.Plant_calls==0&& ...
    check.authorized_Plant_calls==0&&~check.TEST_read, ...
    'CompositePrep:NoPlantCheck','No passing no-Plant check exists.');
sourceManifestPath=fullfile(research,'mlp15_causal_head_v1','MANIFEST.json');
sourceManifest=jsondecode(fileread(sourceManifestPath));
assert(numel(sourceManifest.records)==6&&~sourceManifest.TEST_read&& ...
    all(strcmp({sourceManifest.records.source_split},'VAL')), ...
    'CompositePrep:SourceManifest','Only the six frozen VAL comparison records are allowed.');
modelPath=fullfile(research,'mlp15_c5_teacher_full72_v1','runs', ...
    'C5_MLP15_FULL72_SEED2026102001','mlp15_attitude_weights_v1.mat');
modelSha=hash_file(modelPath);
assert(strcmpi(modelSha,'67a6564148ba8c1988d7457c04a5d3271516ff4010da18e61e29fd7da13be46b'), ...
    'CompositePrep:ModelSHA','Frozen MLP15 model SHA differs from taskbook.');

cfg=bind_paired_fixed_j0(default_config());
K1=double(cfg.control.bs.attitude.k1(:));J0=double(cfg.attitude_replacement.J0_controller_fixed_kgm2);
dmax=double(cfg.rbf.attitude.dmax(:));betaRise=double(cfg.rbf.attitude.beta_rise_time);
assert(isequal(K1,[1.5;1.5;1.3])&&isequal(dmax,[45;45;4.7124])&& ...
    abs(betaRise-2.2)<eps&&isequal(size(J0),[3,3])&&all(eig(J0)>0), ...
    'CompositePrep:LockedCfg','K1, J0, beta rise, or dmax differs from frozen settings.');
lockedCfg=struct('schema','DL1018_MLP15_COMPOSITE_LOCKED_CFG_V1', ...
    'K1',K1,'K1_source','cfg.control.bs.attitude.k1', ...
    'default_config_sha256',hash_file(fullfile(core,'default_config.m')), ...
    'controller_parameters_sha256',hash_file(fullfile(core,'controller_parameters.m')), ...
    'bind_paired_fixed_j0_sha256',hash_file(fullfile(runtime,'bind_paired_fixed_j0.m')), ...
    'J0_kgm2',J0,'J0_sha256',paired_sha256_double(J0),'dmax',dmax, ...
    'beta_rise_time_s',betaRise,'simulation_sample_time_s',double(cfg.plant.dt), ...
    'forgetting_factor',.999,'P0',10*eye(33),'weight_projection_fro',20, ...
    'tracking_gain',1,'network_input_dim',13,'sequence_events',15, ...
    'plant_truth_read',false,'TEST_read',false);
lockedCfgPath=fullfile(study,'LOCKED_CFG.json');write_json(lockedCfgPath,lockedCfg);
lockedCfgSha=hash_file(lockedCfgPath);

sourceRoot=fullfile(study,'candidate_runner_work');parentRoot=fullfile(research, ...
    'mlp15_causal_head_v1','candidate_runner_work');
newFiles=dir(fullfile(sourceRoot,'matlab','**','*.m'));
oldFiles=dir(fullfile(parentRoot,'matlab','**','*.m'));
assert(numel(newFiles)==numel(oldFiles),'CompositePrep:SourceTreeCount', ...
    'Copied runtime and v1 source trees have different file counts.');
sourceFiles=struct('relative_path',{},'sha256',{},'parent_sha256',{});
diffs=struct('relative_path',{},'parent_sha256',{},'candidate_sha256',{});
for i=1:numel(newFiles)
    newPath=fullfile(newFiles(i).folder,newFiles(i).name);rel=erase(newPath,[sourceRoot filesep]);
    oldPath=fullfile(parentRoot,rel);newSha=hash_file(newPath);oldSha=hash_file(oldPath);
    sourceFiles(i)=struct('relative_path',replace(rel,'\','/'),'sha256',newSha, ...
        'parent_sha256',oldSha);
    if ~strcmpi(newSha,oldSha)
        diffs(end+1)=struct('relative_path',replace(rel,'\','/'), ...
            'parent_sha256',oldSha,'candidate_sha256',newSha); %#ok<AGROW>
    end
end
expected=sort(["matlab/runtime/mlp15_attitude_step_v1.m"; ...
    "matlab/runtime/run_gate_holdout_closed_loop.m"]);
changed=sort(string({diffs.relative_path}.'));
assert(numel(changed)==numel(expected)&&all(changed==expected), ...
    'CompositePrep:SourceDiff','Copied runtime contains an unexpected source change.');
sourceLock=struct('schema','DL1018_MLP15_COMPOSITE_SOURCE_LOCK_V1', ...
    'root',char(java.io.File(sourceRoot).getCanonicalPath()),'files',sourceFiles, ...
    'source_tree_file_count',numel(sourceFiles),'source_diff',diffs,'TEST_read',false);
sourceLockPath=fullfile(study,'SOURCE_LOCK.json');write_json(sourceLockPath,sourceLock);
sourceLockSha=hash_file(sourceLockPath);
sourceDiff=struct('schema','DL1018_MLP15_COMPOSITE_SOURCE_DIFF_V1', ...
    'parent_root',char(java.io.File(parentRoot).getCanonicalPath()), ...
    'candidate_root',char(java.io.File(sourceRoot).getCanonicalPath()), ...
    'changed_control_files',diffs,'change_count',numel(diffs), ...
    'patch_file','SOURCE_DIFF.patch','TEST_read',false);
sourceDiffPath=fullfile(study,'SOURCE_DIFF.json');write_json(sourceDiffPath,sourceDiff);

records=sourceManifest.records;
predictionRows=cell(1,numel(records));metricKeys={'Q_m','SO3_rad','inner_tracking_rad'};
predictionValues=zeros(numel(records),numel(metricKeys));bValues=predictionValues;
c5Values=predictionValues;frozenValues=predictionValues;
metricRelease=struct('gravity_mps2',9.8,'max_tilt_rad',pi/6);
for i=1:numel(records)
    sceneId=char(records(i).scene_id);oldRun=fullfile(research,'mlp15_causal_head_v1','runs',sceneId);
    oldRaw=fullfile(oldRun,'raw_run.mat');oldStatus=jsondecode(fileread(fullfile(oldRun,'run_status.json')));
    start=jsondecode(fileread(fullfile(oldRun,'run_start.json')));
    assert(strcmp(oldStatus.state,'COMPLETED')&&oldStatus.engineering_pass&& ...
        oldStatus.Plant_calls==1&&~oldStatus.TEST_read&&strcmp(start.scene_id,sceneId)&& ...
        strcmpi(hash_file(oldRaw),oldStatus.raw_sha256)&&strcmpi(start.model_sha256,modelSha), ...
        'CompositePrep:V1Raw','Historical v1 validation raw/status identity failed: %s.',sceneId);
    cand=load(oldRaw,'log','scene');
    bPath=char(records(i).b_raw_path);c5Path=char(records(i).c5_raw_path);
    frozenPath=char(records(i).frozen_raw_path);payloadPath=char(records(i).payload_path);
    b=load(bPath,'log','scene');c5=load(c5Path,'log','scene');frozen=load(frozenPath,'log','scene');
    payload=load(payloadPath,'scene');
    assert(same_scene_arrays(cand.scene,b.scene)&&same_scene_arrays(cand.scene,c5.scene)&& ...
        same_scene_arrays(cand.scene,frozen.scene)&&same_scene_arrays(cand.scene,payload.scene), ...
        'CompositePrep:PhysicalScene','Scene arrays differ among paired runs: %s.',sceneId);
    sceneSha=scene_hash(cand.scene);
    baselineHashes={records(i).b_raw_sha256,records(i).c5_raw_sha256,records(i).frozen_raw_sha256};
    paths={bPath,c5Path,frozenPath};
    for j=1:numel(paths)
        assert(strcmpi(hash_file(paths{j}),char(baselineHashes{j})), ...
            'CompositePrep:BaselineSHA','A frozen baseline raw SHA changed: %s.',paths{j});
    end
    records(i).prediction_only_raw_path=oldRaw;
    records(i).prediction_only_raw_sha256=oldStatus.raw_sha256;
    records(i).prediction_only_status_path=fullfile(oldRun,'run_status.json');
    records(i).prediction_only_status_sha256=hash_file(fullfile(oldRun,'run_status.json'));
    records(i).scene_arrays_sha256=sceneSha;
    records(i).composite_raw_path='';records(i).composite_raw_sha256='';
    baseMetric=struct('prediction_only',composite_metrics(cand.log,cand.scene,metricRelease), ...
        'B',composite_metrics(b.log,b.scene,metricRelease), ...
        'C5',composite_metrics(c5.log,c5.scene,metricRelease), ...
        'frozen_MLP',composite_metrics(frozen.log,frozen.scene,metricRelease));
    predictionRows{i}=struct('scene_id',sceneId,'source_split','VAL', ...
        'scene_arrays_sha256',sceneSha,'prediction_only_raw_sha256',oldStatus.raw_sha256, ...
        'prediction_only',baseMetric.prediction_only,'B',baseMetric.B,'C5',baseMetric.C5, ...
        'frozen_MLP',baseMetric.frozen_MLP);
    for j=1:numel(metricKeys)
        key=metricKeys{j};predictionValues(i,j)=baseMetric.prediction_only.(key);
        bValues(i,j)=baseMetric.B.(key);c5Values(i,j)=baseMetric.C5.(key);
        frozenValues(i,j)=baseMetric.frozen_MLP.(key);
    end
end
predictionRows=[predictionRows{:}];

manifest=struct('schema','DL1018_MLP15_COMPOSITE_MANIFEST_V1', ...
    'status','PASS_READ_ONLY_VALIDATION_BINDINGS','records',records, ...
    'source_v1_manifest_sha256',hash_file(sourceManifestPath), ...
    'scene_fields_bound',{{'time','initial_state','reference','arms','environment_wind_I'}}, ...
    'model_sha256',modelSha,'TEST_read',false,'Plant_calls_by_preparer',0);
manifestPath=fullfile(study,'MANIFEST.json');write_json(manifestPath,manifest);
manifestSha=hash_file(manifestPath);
macro=struct('metric_names',{metricKeys},'prediction_only_mean',mean(predictionValues,1), ...
    'B_mean',mean(bValues,1),'C5_mean',mean(c5Values,1),'frozen_MLP_mean',mean(frozenValues,1));
predictionReport=struct('schema','DL1018_MLP15_COMPOSITE_PREDICTION_ONLY_BASELINE_V1', ...
    'status','PASS_READ_ONLY_HISTORICAL_METRICS','records',predictionRows,'macro',macro, ...
    'tracking_effect_evaluated',false, ...
    'tracking_effect_pending','Requires the first root-authorized composite W15 raw; this preparation did not run Plant.', ...
    'historical_v1_raw_read_only',true,'Plant_calls_by_reporter',0,'TEST_read',false);
predictionPath=fullfile(study,'PREDICTION_ONLY_BASELINE_REPORT.json');
write_json(predictionPath,predictionReport);predictionSha=hash_file(predictionPath);
pythonReportPath=fullfile(here,'PYTHON_FIXTURE.json');pythonReport=jsondecode(fileread(pythonReportPath));
fixturePath=fullfile(here,'fixtures','composite_head_fixture.mat');
assert(strcmp(pythonReport.status,'PASS_SYNTHETIC_NUMPY_REFERENCE')&& ...
    pythonReport.synthetic_events==300&&pythonReport.Plant_calls==0&&~pythonReport.TEST_read, ...
    'CompositePrep:PythonFixture','Independent Python reference did not pass.');

release=struct('schema','DL1018_MLP15_COMPOSITE_HEAD_RELEASE_V1', ...
    'status','PREPARED_ROOT_REVIEW_REQUIRED','prepared_utc',char(datetime('now','TimeZone','UTC', ...
        'Format','yyyy-MM-dd''T''HH:mm:ss''Z''')),'authorized_Plant_calls',0,'Plant_calls',0, ...
    'authorized_scenes',{{}},'candidate_arm_id','DL_MLP15','geometry_arm','ACTIVE', ...
    'test_data_read',false,'TEST_read',false,'training_jobs_authorized',0, ...
    'DEV72_runs_authorized',0,'model_path',modelPath,'model_sha256',modelSha, ...
    'locked_cfg_path','LOCKED_CFG.json','locked_cfg_sha256',lockedCfgSha, ...
    'python_fixture_path','audits/fixtures/composite_head_fixture.mat', ...
    'python_fixture_sha256',hash_file(fixturePath), ...
    'python_reference_report_sha256',hash_file(pythonReportPath), ...
    'locked_cfg',struct('K1',K1,'J0_kgm2',J0,'dmax',dmax, ...
        'beta_rise_time_s',betaRise,'forgetting_factor',.999, ...
        'P0_scalar',10,'weight_projection_fro',20,'tracking_gain',1), ...
    'fixed_J0_kgm2',J0,'manifest_sha256',manifestSha, ...
    'prediction_only_report_path','PREDICTION_ONLY_BASELINE_REPORT.json', ...
    'prediction_only_report_sha256',predictionSha,'source_lock_sha256',sourceLockSha, ...
    'source_diff_json_sha256',hash_file(sourceDiffPath), ...
    'source_diff_patch_path','SOURCE_DIFF.patch', ...
    'no_plant_check_path','audits/NO_PLANT_CHECK_v7.json', ...
    'no_plant_check_sha256',hash_file(fullfile(here,'NO_PLANT_CHECK_v7.json')), ...
    'preparation_script_sha256',hash_file([mfilename('fullpath') '.m']), ...
    'raw_audit_script_sha256',hash_file(fullfile(here,'audit_composite_raw.m')), ...
    'required_first_scene','DL1018_VAL_T1_C08_W15', ...
    'required_second_scene_after_root_review','DL1018_VAL_T2_C05_W15', ...
    'required_third_scene_after_root_review','DL1018_VAL_T3_C02_W15', ...
    'W12_W13_extension_condition', ...
    'All three W15 scenes safe and macro Q, outer SO3, and inner tracking error each beat prediction_only.', ...
    'final_gate','Compare against B and C5; macro position degradation versus C5 must be <=10%.', ...
    'Plant_budget_note','This prepared release hard-rejects the Plant runner until root changes status, budget, and authorized_scenes.', ...
    'historical_v1_Plant_calls',6,'Plant_calls_by_preparer',0);
releasePath=fullfile(study,'RELEASE.json');write_json(releasePath,release);
releaseSha=hash_file(releasePath);
releaseRecord=struct('schema','DL1018_MLP15_COMPOSITE_RELEASE_RECORD_V1', ...
    'release_sha256',releaseSha,'release_path','RELEASE.json', ...
    'authorized_Plant_calls',0,'Plant_calls',0,'TEST_read',false);
write_json(fullfile(study,'RELEASE_RECORD.json'),releaseRecord);
fprintf('COMPOSITE_RELEASE_SHA256=%s\n',releaseSha);disp(release);
end

function yes=same_scene_arrays(a,b)
yes=isequaln(a.time,b.time)&&isequaln(a.initial_state,b.initial_state)&& ...
    isequaln(a.reference,b.reference)&&isequaln(a.arms,b.arms)&& ...
    isequaln(a.environment_wind_I,b.environment_wind_I);
end

function h=scene_hash(scene)
payload=struct('time',scene.time,'initial_state',scene.initial_state, ...
    'reference',scene.reference,'arms',scene.arms,'environment_wind_I',scene.environment_wind_I);
bytes=uint8(unicode2native(jsonencode(payload),'UTF-8'));
md=java.security.MessageDigest.getInstance('SHA-256');md.update(typecast(bytes(:),'int8'));
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end

function write_json(path,value)
fid=fopen(path,'w','n','UTF-8');assert(fid>=0);cleanup=onCleanup(@()fclose(fid));
fprintf(fid,'%s\n',jsonencode(value,'PrettyPrint',true));clear cleanup;
end

function h=hash_file(path)
fid=fopen(path,'rb');assert(fid>=0,'CompositePrep:Hash','Cannot read %s.',path);
cleanup=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear cleanup;
end
