function attemptDir=run_composite_dev_attempt(sceneId)
% One explicitly released composite MLP attempt on a manifest-bound VAL scene.
studyRoot=fileparts(mfilename('fullpath'));
releasePath=fullfile(studyRoot,'RELEASE.json');
assert(isfile(releasePath),'CompositeDEV:ReleaseMissing','No composite DEV release exists.');
release=jsondecode(fileread(releasePath));
sceneId=char(string(sceneId));
authorizedScenes=cellstr(string(field_or(release,'authorized_scenes',{})));
assert(strcmp(char(field_or(release,'schema','')),'DL1018_MLP15_COMPOSITE_DEV_RELEASE_V2')&& ...
    strcmp(char(field_or(release,'status','')),'RELEASED')&& ...
    double(field_or(release,'authorized_Plant_calls',0))>0&& ...
    any(strcmp(authorizedScenes,sceneId)), ...
    'CompositeDEV:BudgetClosed','Composite DEV Plant budget is zero or this scene is not authorized.');
assert(isscalar(regexp(sceneId,'^DL1018_VAL_T[1-3]_C\d{2}_W\d{2}$','once')), ...
    'CompositeDEV:SceneId','Only explicit manifest-bound VAL scene IDs are accepted.');
verify_release_inputs(studyRoot,release);
manifest=jsondecode(fileread(fullfile(studyRoot,'MANIFEST.json')));
hit=find(strcmp({manifest.records.scene_id},sceneId));
assert(isscalar(hit)&&strcmp(char(manifest.status),'PASS_READ_ONLY_VALIDATION_BINDINGS')&& ...
    numel(manifest.records)==6&&~logical(manifest.TEST_read), ...
    'CompositeDEV:Manifest','Scene is not one of the six locked validation records.');
record=manifest.records(hit);
runsRoot=fullfile(studyRoot,'runs');attemptDir=fullfile(runsRoot,sceneId);
assert(~isfolder(attemptDir)&&~isfile(attemptDir), ...
    'CompositeDEV:DuplicateScene','Refusing to overwrite an existing same-scene attempt.');
markers=dir(fullfile(runsRoot,'**','attempt_started.marker'));
assert(numel(markers)<double(release.authorized_Plant_calls), ...
    'CompositeDEV:CallBudget','All root-authorized Plant calls have been consumed.');
for i=1:numel(markers)
    startPath=fullfile(markers(i).folder,'run_start.json');
    if isfile(startPath)
        prior=jsondecode(fileread(startPath));
        assert(~strcmp(char(field_or(prior,'scene_id','')),sceneId), ...
            'CompositeDEV:DuplicateScene','A prior attempt already used this scene.');
    end
end
runnerRoot=fullfile(studyRoot,'candidate_runner_work');
addpath(fullfile(runnerRoot,'matlab','runtime'));activate_paired_runner();
prepared=prepare_mlp15_dev72_no_plant(char(record.payload_path));
mlp15ModelPath=char(release.model_path);mlp15ModelSha=sha256_file(mlp15ModelPath);
assert(strcmpi(mlp15ModelSha,char(release.model_sha256)), ...
    'CompositeDEV:ModelHash','Locked C5 full72 MLP model SHA changed.');
mlp15Model=load(mlp15ModelPath);
prepared.opts=make_gate_holdout_options(prepared.cfg,prepared.model,'DL_MLP15','ACTIVE', ...
    struct,mlp15Model,mlp15ModelSha);
identity=gate_holdout_identity_hashes(prepared.cfg,prepared.model,prepared.opts);
assert(strcmpi(identity.common.position_options_sha256, ...
    prepared.identity.common.position_options_sha256), ...
    'CompositeDEV:PositionIdentity','Rebinding the full72 MLP changed common C5 position options.');
prepared.opts.gate_identity_lock=identity;prepared.identity=identity;
prepared.mlp15_model_sha256=mlp15ModelSha;
assert(strcmp(prepared.scene_id,sceneId)&& ...
    strcmpi(prepared.c5_input_lock_sha256,char(release.c5_input_lock_sha256))&& ...
    strcmpi(prepared.c5_snapshot_sha256,char(release.c5_snapshot_sha256))&& ...
    strcmpi(prepared.position_model_sha256,char(release.position_model_sha256))&& ...
    strcmpi(prepared.identity.common.position_options_sha256,char(release.common_position_options_sha256)), ...
    'CompositeDEV:PreparedIdentity','Prepared C5 identity differs from the reviewed release.');
locked=jsondecode(fileread(fullfile(studyRoot,'LOCKED_CFG.json')));
assert(strcmp(char(locked.capture_status),'PASS_REAL_PREPARED_CFG')&& ...
    isequal(double(prepared.cfg.control.command_filter.acceleration_limit(:)),[Inf;Inf;6])&& ...
    isequal(double(prepared.cfg.control.bs.attitude.k1(:)),double(locked.K1(:)))&& ...
    isequal(double(prepared.cfg.rbf.attitude.dmax(:)),double(locked.dmax(:)))&& ...
    abs(double(prepared.cfg.rbf.attitude.beta_rise_time)-double(locked.beta_rise_time_s))<1e-12, ...
    'CompositeDEV:LockedCfg','Actual prepared configuration differs from LOCKED_CFG.');
assert(isfield(prepared.cfg,'controller_morphology_mode')&& ...
    strcmpi(char(prepared.cfg.controller_morphology_mode),'fixed'), ...
    'CompositeDEV:FixedMode','The prepared C5 configuration must select fixed morphology.');
Pplant=simulation_parameters(prepared.cfg,prepared.cfg.plant.arm_initial,zeros(4,1));
Pfixed=controller_parameters(prepared.cfg,Pplant,'fixed');
J0=double(Pfixed.inertia);
assert(isequal(J0,double(prepared.cfg.attitude_replacement.J0_controller_fixed_kgm2))&& ...
    isequal(double(Pfixed.inertia_dot_for_bs),zeros(3))&& ...
    isequal(J0,double(locked.J0_kgm2))&&strcmp(char(locked.morphology_mode),'fixed'), ...
    'CompositeDEV:FixedJ0','Fixed Pfixed inertia or zero inertia derivative differs from the reviewed J0.');
assert(strcmpi(which('run_mlp15_dev72_closed_loop'),fullfile(runnerRoot,'matlab','runtime', ...
    'run_mlp15_dev72_closed_loop.m'))&& ...
    strcmpi(which('mlp15_attitude_step_v1'),fullfile(runnerRoot,'matlab','runtime','mlp15_attitude_step_v1.m'))&& ...
    strcmpi(which('run_gate_holdout_closed_loop'),fullfile(runnerRoot,'matlab','runtime','run_gate_holdout_closed_loop.m')), ...
    'CompositeDEV:WhichPath','A candidate function resolves outside the isolated v2 source tree.');
verify_scene_bindings(prepared.scene,record);
if ~java.io.File(runsRoot).isDirectory(),assert(java.io.File(runsRoot).mkdirs());end
assert(java.io.File(attemptDir).mkdir(),'CompositeDEV:AttemptCreate','Could not create a new scene attempt directory.');
startedUtc=utc_now();releaseSha=sha256_file(releasePath);
marker=struct('schema','DL1018_MLP15_COMPOSITE_DEV_ATTEMPT_MARKER_V2', ...
    'scene_id',sceneId,'created_utc',startedUtc,'stage','RUNNING','release_sha256',releaseSha);
write_json(fullfile(attemptDir,'attempt_started.marker'),marker);
runIdentity=struct('schema','DL1018_MLP15_COMPOSITE_DEV_RUN_START_V2', ...
    'scene_id',sceneId,'attitude_arm','DL_MLP15_COMPOSITE','geometry_arm','ACTIVE', ...
    'started_utc',startedUtc,'release_sha256',releaseSha, ...
    'manifest_sha256',char(release.manifest_sha256), ...
    'source_lock_sha256',char(release.source_lock_sha256), ...
    'source_diff_sha256',char(release.source_diff_sha256), ...
    'locked_cfg_sha256',char(release.locked_cfg_sha256), ...
    'payload_sha256',char(record.payload_sha256), ...
    'prediction_only_raw_sha256',char(record.prediction_only_raw_sha256), ...
    'b_raw_sha256',char(record.b_raw_sha256),'c5_raw_sha256',char(record.c5_raw_sha256), ...
    'frozen_raw_sha256',char(record.frozen_raw_sha256), ...
    'c5_input_lock_sha256',prepared.c5_input_lock_sha256, ...
    'c5_snapshot_sha256',prepared.c5_snapshot_sha256, ...
    'position_model_sha256',prepared.position_model_sha256, ...
    'mlp15_model_sha256',prepared.mlp15_model_sha256, ...
    'common_position_options_sha256',prepared.identity.common.position_options_sha256, ...
    'cfg_binding_source','prepare_mlp15_dev72_no_plant(record.payload_path).cfg', ...
    'controller_inputs','13 causal features, filtered attitude reference/rate, current tracking surface', ...
    'inertia_reconstruction_enabled',false,'Plant_truth_deployment_input',false,'TEST_read',false, ...
    'closed_loop_entry','run_mlp15_dev72_closed_loop(scene,cfg,opts)');
write_json(fullfile(attemptDir,'run_start.json'),runIdentity);
prepared.opts.composite_attempt_marker=fullfile(attemptDir,'attempt_started.marker');
rawPath=fullfile(attemptDir,'raw_run.mat');rawSha='';
try
    log=run_mlp15_dev72_closed_loop(prepared.scene,prepared.cfg,prepared.opts);
    log.composite_release_sha256=releaseSha;
    log.mlp15_composite_head_enabled=true;
    scene=prepared.scene;save(rawPath,'log','scene','runIdentity','-v7.3');
    rawSha=sha256_file(rawPath);
    transitions=double(log.last_transition);stateSamples=size(log.state,1);
    complete=transitions==20000&&stateSamples==20001&&strcmp(char(log.status),'STABLE');
    assert(complete,'CompositeDEV:Incomplete','Candidate did not finish a stable 20,000-transition run.');
    status=struct('schema','DL1018_MLP15_COMPOSITE_DEV_RUN_STATUS_V2','state','COMPLETED', ...
        'scene_id',sceneId,'finished_utc',utc_now(),'Plant_calls',1, ...
        'raw_path',rawPath,'raw_sha256',rawSha, ...
        'transitions',transitions,'state_samples',stateSamples,'status_value',char(log.status), ...
        'safety_stop_reason',char(log.safety_stop_reason),'release_sha256',releaseSha, ...
        'source_lock_sha256',char(release.source_lock_sha256),'TEST_read',false);
    write_json(fullfile(attemptDir,'run_status.json'),status);
    fprintf('COMPOSITE_DEV_ATTEMPT_DIR=%s\n',attemptDir);
catch ME
    status=struct('schema','DL1018_MLP15_COMPOSITE_DEV_RUN_STATUS_V2','state','FAILED', ...
        'scene_id',sceneId,'failed_utc',utc_now(),'Plant_calls',1, ...
        'raw_path',rawPath,'raw_sha256',rawSha,'raw_present',isfile(rawPath), ...
        'error_identifier',char(ME.identifier),'error_message',char(ME.message), ...
        'release_sha256',releaseSha,'source_lock_sha256',char(release.source_lock_sha256), ...
        'TEST_read',false);
    write_json(fullfile(attemptDir,'run_status.json'),status);
    write_json(fullfile(attemptDir,'run_failure.json'),struct( ...
        'scene_id',sceneId,'failed_utc',utc_now(),'error_identifier',char(ME.identifier), ...
        'error_message',char(ME.message),'stack',{ME.stack}));
    rethrow(ME);
end
end

function verify_release_inputs(studyRoot,release)
files={ ...
    'MANIFEST.json','manifest_sha256'; ...
    'run_composite_dev_attempt.m','driver_sha256'; ...
    'PREDICTION_ONLY_BASELINE_REPORT.json','prediction_only_report_sha256'; ...
    'LOCKED_CFG.json','locked_cfg_sha256'; ...
    'SOURCE_LOCK_v2.json','source_lock_sha256'; ...
    'SOURCE_DIFF_v2.json','source_diff_sha256'; ...
    'SOURCE_DIFF_v2.patch','source_diff_patch_sha256'; ...
    'audits/NO_PLANT_CHECK_v2.json','no_plant_check_sha256'; ...
    'audits/audit_composite_dev_raw.m','raw_audit_script_sha256'; ...
    'audits/audit_composite_dev_no_plant_capture_v1.m','configuration_audit_script_sha256'};
for i=1:size(files,1)
    path=fullfile(studyRoot,files{i,1});
    assert(isfile(path)&&strcmpi(sha256_file(path),char(release.(files{i,2}))), ...
        'CompositeDEV:ReleaseHash','Reviewed release input changed: %s.',files{i,1});
end
lock=jsondecode(fileread(fullfile(studyRoot,'SOURCE_LOCK_v2.json')));
runnerRoot=fullfile(studyRoot,'candidate_runner_work');
assert(strcmpi(char(java.io.File(lock.root).getCanonicalPath()), ...
    char(java.io.File(runnerRoot).getCanonicalPath())), ...
    'CompositeDEV:SourceLockRoot','Source lock root differs from the isolated candidate tree.');
for i=1:numel(lock.files)
    rel=char(lock.files(i).relative_path);path=fullfile(runnerRoot,rel);
    assert(isfile(path)&&strcmpi(sha256_file(path),char(lock.files(i).sha256)), ...
        'CompositeDEV:SourceLock','Locked candidate source changed: %s.',rel);
end
end

function verify_scene_bindings(scene,record)
fields={'time','initial_state','reference','arms','environment_wind_I'};
paths={char(record.b_raw_path),char(record.c5_raw_path),char(record.frozen_raw_path), ...
    char(record.prediction_only_raw_path)};
hashes={char(record.b_raw_sha256),char(record.c5_raw_sha256),char(record.frozen_raw_sha256), ...
    char(record.prediction_only_raw_sha256)};
for i=1:numel(paths)
    assert(strcmpi(sha256_file(paths{i}),hashes{i}), ...
        'CompositeDEV:PairedRawHash','A paired source raw changed: %s.',paths{i});
    raw=load(paths{i},'scene');assert(isfield(raw,'scene'), ...
        'CompositeDEV:PairedRaw','A paired source raw has no scene: %s.',paths{i});
    for j=1:numel(fields)
        f=fields{j};assert(isequaln(scene.(f),raw.scene.(f)), ...
            'CompositeDEV:PhysicalScene','Scene field %s differs from paired raw %s.',f,paths{i});
    end
end
end

function h=sha256_file(path)
fid=fopen(path,'rb');assert(fid>=0,'CompositeDEV:Read','Cannot read %s.',path);
cleanup=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear cleanup;
end

function write_json(path,value)
fid=fopen(path,'w','n','UTF-8');assert(fid>=0,'CompositeDEV:Write','Cannot write %s.',path);
cleanup=onCleanup(@()fclose(fid));fprintf(fid,'%s\n',jsonencode(value,'PrettyPrint',true));clear cleanup;
end

function value=field_or(s,name,default)
if isstruct(s)&&isfield(s,name),value=s.(name);else,value=default;end
end

function value=utc_now()
value=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z'''));
end





