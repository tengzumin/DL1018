function prepared=prepare_gate_candidate_no_plant(scenePayloadPath,attitudeArm,geometryArm)
% Bind the frozen C5 position loop and one trained DL_TCN arm without Plant.
entry=fileparts(mfilename('fullpath'));
taskRoot=fileparts(fileparts(fileparts(entry)));
researchRoot=fileparts(taskRoot);
projectRoot=fileparts(fileparts(fileparts(taskRoot)));
runnerRoot=activate_paired_runner();
attitudeArm=upper(char(attitudeArm));geometryArm=upper(char(geometryArm));
assert(strcmp(attitudeArm,'DL_TCN')&&strcmp(geometryArm,'ACTIVE'), ...
    'GATE:TCNScope','This pilot preparer only accepts DL_TCN on ACTIVE GHP7 scenes.');

payloadManifestPath=fullfile(researchRoot,'GHP7_PILOT_PAYLOAD_MANIFEST_v1.json');
baselineManifestPath=fullfile(researchRoot,'GHP7_BASELINE_REUSE_MANIFEST_v1.json');
payloadManifest=jsondecode(fileread(payloadManifestPath));
baselineManifest=jsondecode(fileread(baselineManifestPath));
assert(strcmp(payloadManifest.schema,'DL1018_TCN_GHP7_PILOT_PAYLOAD_MANIFEST_V1')&& ...
    strcmp(payloadManifest.status,'PASS')&&payloadManifest.scene_count==6&& ...
    ~payloadManifest.tests_data_read&&~payloadManifest.payloads_copied&& ...
    strcmpi(sha256_file(baselineManifestPath),payloadManifest.baseline_manifest_sha256)&& ...
    strcmp(baselineManifest.schema,'DL1018_TCN_GHP7_BASELINE_REUSE_MANIFEST_V1')&& ...
    strcmp(baselineManifest.status,'PASS')&&baselineManifest.record_count==12&& ...
    ~baselineManifest.test_data_read&&~baselineManifest.raw_files_copied&& ...
    ~baselineManifest.baselines_reexecuted, ...
    'GATE:ReuseManifest','Frozen GHP7 payload/baseline manifests are invalid.');
scenePayloadPath=char(java.io.File(char(scenePayloadPath)).getCanonicalPath());
payloadHit=find(strcmp({payloadManifest.records.scene_id},char(scenePayloadPathToId(scenePayloadPath))) & ...
    strcmp({payloadManifest.records.geometry_arm},geometryArm));
assert(numel(payloadHit)==1,'GATE:PayloadManifest','Payload is not one of the six frozen ACTIVE GHP7 scenes.');
payloadRecord=payloadManifest.records(payloadHit);
expectedPayloadPath=char(java.io.File(char(payloadRecord.payload_path)).getCanonicalPath());
assert(strcmpi(scenePayloadPath,expectedPayloadPath)&&isfile(scenePayloadPath), ...
    'GATE:PayloadPath','Candidate must use the exact frozen GHP7 payload path.');
payloadSha=sha256_file(scenePayloadPath);
assert(strcmpi(payloadSha,char(payloadRecord.payload_file_sha256))&& ...
    strcmpi(payloadSha,char(payloadRecord.payload_logical_sha256)), ...
    'GATE:PayloadSHA','Payload file SHA does not match the frozen payload manifest.');
vars=whos('-file',scenePayloadPath);
assert(numel(vars)==1&&strcmp(vars(1).name,'scene'), ...
    'GATE:PayloadVariables','Pilot MAT must contain only the scene variable.');
payload=load(scenePayloadPath,'scene');scene=payload.scene;
assert(strcmp(char(scene.scene_id),char(payloadRecord.scene_id))&& ...
    abs(double(scene.metadata.seed)-double(payloadRecord.seed))<1e-9&& ...
    strcmpi(char(scene.R_task_sha256),char(payloadRecord.r_task_sha256)), ...
    'GATE:PayloadIdentity','GHP7 payload scene, seed, or R_task differs from its manifest.');
baseRows=baselineManifest.records(strcmp({baselineManifest.records.scene_id},char(scene.scene_id)));
assert(numel(baseRows)==2&&all(strcmp({baseRows.scene_payload_sha256},char(payloadRecord.payload_logical_sha256)))&& ...
    all(strcmp({baseRows.r_task_sha256},char(payloadRecord.r_task_sha256)))&& ...
    isequal(sort(string({baseRows.runner})),sort(["B","CANDIDATE"]))&& ...
    isequal(sort(string({baseRows.attitude_arm})),sort(["B","C5_RBF"])), ...
    'GATE:BaselinePair','B and C5_RBF are not both identity-matched to this payload.');

c5ReceiptPath=fullfile(projectRoot,'experiments', ...
    'attitude_physics_inertia_observer_20261025','holdout_gate_inspection_v2', ...
    'C5_R_TASK_BINDING_PILOT_RECEIPT_v5.json');
c5Receipt=jsondecode(fileread(c5ReceiptPath));
receiptHit=find(strcmp({c5Receipt.scenes.scene_id},char(scene.scene_id))& ...
    strcmp({c5Receipt.scenes.geometry_arm},geometryArm));
assert(strcmp(c5Receipt.status,'PASS_NO_PLANT_PILOT_PAYLOADS_ONLY')&& ...
    c5Receipt.plant_calls==0&&c5Receipt.training_runs==0&&~c5Receipt.tests_data_read&& ...
    numel(receiptHit)==1&&strcmpi(c5Receipt.scenes(receiptHit).payload_sha256,payloadSha), ...
    'GATE:C5Receipt','C5 no-Plant receipt does not match the selected GHP7 payload.');

lockDir=fullfile(projectRoot,'experiments','position_axis_coordinate_c5_dev72_20261023');
lockPath=fullfile(lockDir,'C5_DEV72_INPUT_LOCK_v3.json');
snapshotPath=fullfile(lockDir,'C5_DEV72_PREPARED_CFG_OPTS_v3.mat');
refRoot=fileparts(projectRoot);
positionModelPath=fullfile(refRoot,'REFERENCE_FIX_FULL72_20261021_022342_313', ...
    'corrected_reference_training_v1','corrected_pair_training','models','DSSM14','matlab_model_and_parity.mat');
inputRecords=c5Receipt.input_records;
verify_record(inputRecords.c5_input_lock,lockPath);
verify_record(inputRecords.c5_snapshot_mat,snapshotPath);
verify_record(inputRecords.model_mat,positionModelPath);
lock=jsondecode(fileread(lockPath));
modelRecord=lock.shared_input_files(strcmp({lock.shared_input_files.role},'model_mat'));
assert(numel(modelRecord)==1&&strcmpi(char(modelRecord.sha256),inputRecords.model_mat.sha256), ...
    'GATE:C5ModelLock','C5 position model hash differs from its source lock.');
modelPack=load(positionModelPath,'model');snapshot=load(snapshotPath,'cfg','W0');model=modelPack.model;
assert(strcmp(char(model.model_id),'DSSM14')&&double(model.input_dim)==14&& ...
    double(model.window)==32&&isequal(double(model.output_W),double(snapshot.W0))&& ...
    strcmpi(paired_sha256_double(double(snapshot.W0)),char(lock.candidate_identity.W0_sha256))&& ...
    strcmpi(normalizer_sha(model),char(lock.candidate_identity.normalizer_arrays_sha256)), ...
    'GATE:C5Model','C5 DSSM14, normalizer, or W0 identity mismatch.');
cfg=geometry_cfg(snapshot.cfg,geometryArm);

trainingDir=fullfile(researchRoot,'training_v1_retry01');
trainingProgress=jsondecode(fileread(fullfile(trainingDir,'training_progress.json')));
trainingConfig=jsondecode(fileread(fullfile(trainingDir,'training_config.json')));
normalizer=jsondecode(fileread(fullfile(trainingDir,'normalizer.json')));
datasetManifestPath=fullfile(researchRoot,'dataset_v3_corrected','DATASET_MANIFEST_v1.json');
datasetManifest=jsondecode(fileread(datasetManifestPath));
datasetManifestSha=sha256_file(datasetManifestPath);
weightsPath=fullfile(trainingDir,'tcn_attitude_weights_v1.mat');
trainingConfigPath=fullfile(trainingDir,'training_config.json');
weightsSha=sha256_file(weightsPath);
releasePath=fullfile(researchRoot,'TRAINING_RELEASE_v2.json');
releaseSha=sha256_file(releasePath);
expectedFeatures={'attitude_error_euler_rad_x3','body_rate_rad_s_x3', ...
    'nominal_bs_body_angular_acceleration_rad_s2_x3','morph_command_x4'};
assert(strcmp(trainingProgress.status,'PASS')&&trainingProgress.completed_steps==60000&& ...
    strcmp(trainingConfig.status,'PASS')&&trainingConfig.optimizer_steps==60000&& ...
    trainingConfig.seed==2026102001&&trainingConfig.best_step==trainingProgress.best_step&& ...
    trainingConfig.test_data_read==false&&normalizer.test_data_read==false&& ...
    strcmp(normalizer.fit_split,'TRAIN')&&strcmp(datasetManifest.status,'PASS')&& ...
    datasetManifest.test_data_read==false&&strcmpi(trainingConfig.dataset_manifest_sha256,datasetManifestSha)&& ...
    strcmpi(normalizer.dataset_manifest_sha256,datasetManifestSha)&& ...
    strcmpi(trainingConfig.training_release_sha256,releaseSha)&& ...
    isequal(string(trainingConfig.feature_order(:)).',string(expectedFeatures))&& ...
    strcmp(trainingConfig.target_contract,'(omega[k+10]-omega[k])/0.010-alpha_bs_body[k]')&& ...
    trainingConfig.architecture.input_dim==13&&trainingConfig.architecture.window==15&& ...
    isequal(double(trainingConfig.architecture.dilations(:)).',[1,2,4]), ...
    'GATE:TCNTrainingLock','Trained model/config/dataset do not satisfy the frozen TCN taskbook.');
weightVars=whos('-file',weightsPath);
weightNames={'input_mean','input_std','target_rms','input_weight','input_bias', ...
    'conv1_weight','conv1_bias','conv2_weight','conv2_bias','conv3_weight','conv3_bias', ...
    'head_weight','head_bias'};
assert(numel(weightVars)==numel(weightNames)&&isequal(sort(string({weightVars.name})),sort(string(weightNames))), ...
    'GATE:TCNWeightVariables','Exported TCN MAT has unexpected variables.');
tcnModel=load(weightsPath);
assert(isequaln(double(tcnModel.input_mean(:)),double(normalizer.input_mean(:)))&& ...
    isequaln(double(tcnModel.input_std(:)),double(normalizer.input_std_used(:)))&& ...
    isequaln(double(tcnModel.target_rms(:)),double(normalizer.target_rms(:))), ...
    'GATE:TCNNormalizer','MAT and JSON TCN normalizers differ.');

opts=make_gate_holdout_options(cfg,model,attitudeArm,geometryArm,struct,tcnModel,weightsSha);
identity=gate_holdout_identity_hashes(cfg,model,opts);
opts.gate_identity_lock=identity;
sceneAudit=gate_holdout_validate_scene(scene,cfg,geometryArm);
assert(strcmpi(scene.R_task_sha256,char(payloadRecord.r_task_sha256))&& ...
    strcmpi(identity.common.position_options_sha256,c5Receipt.common_position_options_sha256), ...
    'GATE:IdentityMismatch','Scene R_task or common C5 position identity differs from the frozen receipt.');
prepared=struct('scene',scene,'cfg',cfg,'model',model,'opts',opts, ...
    'identity',identity,'scene_audit',sceneAudit,'scene_payload_sha256',payloadSha, ...
    'scene_payload_path',scenePayloadPath,'taskbook_sha256',sha256_file( ...
        fullfile(researchRoot,'DL_ATTITUDE_REPLACEMENT_TASKBOOK_v1_FROZEN_ZH.md')), ...
    'candidate_runner_root',runnerRoot,'attitude_arm',attitudeArm,'geometry_arm',geometryArm, ...
    'c5_input_lock_sha256',char(inputRecords.c5_input_lock.sha256), ...
    'c5_snapshot_sha256',char(inputRecords.c5_snapshot_mat.sha256), ...
    'position_model_mat_sha256',char(inputRecords.model_mat.sha256), ...
    'tcn_model_mat_sha256',weightsSha,'tcn_training_config_sha256',sha256_file(trainingConfigPath), ...
    'tcn_training_release_sha256',releaseSha,'tcn_best_step',double(trainingConfig.best_step), ...
    'payload_manifest_sha256',sha256_file(payloadManifestPath), ...
    'baseline_reuse_manifest_sha256',sha256_file(baselineManifestPath), ...
    'c5_receipt_sha256',sha256_file(c5ReceiptPath));
end

function id=scenePayloadPathToId(path)
[~,name]=fileparts(path);id=extractBefore(string(name),'_ACTIVE_scene_payload.mat');id=char(id);
end

function cfg=geometry_cfg(sourceCfg,geometryArm)
cfg=sourceCfg;
if isfield(cfg,'attitude_replacement'),cfg=rmfield(cfg,'attitude_replacement');end
switch upper(char(geometryArm))
    case {'ACTIVE','FIXED_MIN'}
        rho=.15;
    case 'FIXED_BOUND15'
        rho=sqrt(2)*(.225-.0635-.015);
    otherwise
        error('GATE:GeometryCfg','Unsupported pilot geometry arm.');
end
cfg.plant.arm_initial=repmat(rho,4,1);
cfg=bind_paired_fixed_j0(cfg);
end

function verify_record(r,p)
assert(strcmpi(sha256_file(p),char(r.sha256))&& ...
    strcmpi(char(java.io.File(p).getCanonicalPath()),char(java.io.File(char(r.path)).getCanonicalPath())), ...
    'GATE:InputSHA','Locked C5 input identity mismatch: %s',p);
end

function h=normalizer_sha(m)
md=java.security.MessageDigest.getInstance('SHA-256');
for n={'input_mu','input_sigma'}
    f=n{1};a=reshape(double(m.(f)),1,[]);
    hdr=[f char(0) '((1, 14), ''float64'')' char(0)];
    md.update(typecast(uint8(unicode2native(hdr,'UTF-8')),'int8'));
    md.update(typecast(a(:),'int8'));
end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end

function h=sha256_file(p)
fid=fopen(p,'r');assert(fid>=0,'GATE:FileRead','Cannot read %s.',p);
cl=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(b);end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear cl;
end
