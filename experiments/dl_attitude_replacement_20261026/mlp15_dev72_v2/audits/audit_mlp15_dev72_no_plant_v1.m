function reportPath=audit_mlp15_dev72_no_plant_v1()
% Prepare all locked scenes and controller options without invoking the Plant.
here=fileparts(mfilename('fullpath'));studyRoot=fileparts(here);
runtime=fullfile(studyRoot,'candidate_runner_work','matlab','runtime');addpath(runtime);
manifestPath=fullfile(studyRoot,'MLP15_DEV72_PAYLOAD_MANIFEST_v2.json');
manifest=jsondecode(fileread(manifestPath));
assert(strcmp(char(manifest.status),'PASS_NO_PLANT_REUSE')&&double(manifest.scene_count)==72&& ...
    ~logical(manifest.test_data_read),'DEV72:AuditManifest','Invalid locked payload manifest.');
records=manifest.records;ids=string({records.scene_id});
assert(numel(unique(ids))==72&&all(startsWith(ids,"DL1018_DEV_")|startsWith(ids,"DL1018_VAL_"))&& ...
    ~any(contains(ids,'TEST')),'DEV72:AuditScope','Scene scope is not exactly the locked DEV/VAL cohort.');
rows=repmat(struct('scene_id','','payload_sha256','','b_raw_sha256','', ...
    'external_identity_sha256','','position_options_sha256','','mlp15_model_sha256','', ...
    'rbf_output_enabled',false,'rbf_update_enabled',false,'observer_enabled',false, ...
    'physics_feedforward_enabled',false,'inertia_reconstruction_enabled',false, ...
    'plant_invoked',false,'test_data_read',false),72,1);
positionHashes=strings(72,1);modelHashes=strings(72,1);
for k=1:72
    x=prepare_mlp15_dev72_no_plant(char(records(k).payload_path));
    spec=gate_attitude_arm_spec('DL_MLP15');
    assert(~spec.rbf_enabled&&~spec.observer_enabled&&~spec.feedforward_enabled&& ...
        ~spec.physics_helper_enabled&&~logical(x.opts.rbf_attitude_enabled)&& ...
        ~logical(x.opts.rbf_attitude_output_enabled)&&~logical(x.opts.rbf_attitude_update_enabled)&& ...
        isfield(x.opts,'mlp15_attitude_model')&& ...
        strcmp(char(x.scene.reference_contract_id),'DL1018_SCENE_REF_FIG8_A2_V2'), ...
        'DEV72:AuditController','Candidate no-Plant arm does not match the learned-only contract.');
    positionHashes(k)=string(x.identity.common.position_options_sha256);
    modelHashes(k)=string(x.mlp15_model_sha256);
    rows(k)=struct('scene_id',x.scene_id,'payload_sha256',x.scene_payload_sha256, ...
        'b_raw_sha256',x.b_raw_sha256,'external_identity_sha256',x.external_identity_sha256, ...
        'position_options_sha256',x.identity.common.position_options_sha256, ...
        'mlp15_model_sha256',x.mlp15_model_sha256,'rbf_output_enabled',false, ...
        'rbf_update_enabled',false,'observer_enabled',false, ...
        'physics_feedforward_enabled',false,'inertia_reconstruction_enabled',false, ...
        'plant_invoked',false,'test_data_read',false);
end
assert(isscalar(unique(positionHashes))&&isscalar(unique(modelHashes)), ...
    'DEV72:AuditStack','Position or MLP model identity changed across scenes.');
report=struct('schema','DL1018_MLP15_DEV72_NO_PLANT_AUDIT_V1','status','PASS', ...
    'created_utc',char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z''')), ...
    'taskbook_sha256',manifest.taskbook_sha256,'payload_manifest_sha256',sha256_file(manifestPath), ...
    'source_c5_input_lock_sha256',manifest.source_c5_input_lock_sha256, ...
    'scene_count',72,'dev_scene_count',sum(startsWith(ids,"DL1018_DEV_")), ...
    'val_scene_count',sum(startsWith(ids,"DL1018_VAL_")), ...
    'plant_invoked',false,'test_data_read',false,'training_runs',0, ...
    'unique_position_options_hashes',numel(unique(positionHashes)), ...
    'unique_mlp15_model_hashes',numel(unique(modelHashes)), ...
    'time_samples_are_independent',false,'rows',rows);
reportPath=fullfile(here,'MLP15_DEV72_NO_PLANT_AUDIT_v1.json');write_json(reportPath,report);
fprintf('MLP15_DEV72_NO_PLANT_AUDIT=%s\n',reportPath);
end
function h=sha256_file(path)
fid=fopen(path,'rb');assert(fid>=0,'DEV72:Read','Cannot read %s.',path);
cleanup=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear cleanup;
end
function write_json(path,x)
fid=fopen(path,'w');assert(fid>=0,'DEV72:Write','Cannot write %s.',path);
cleanup=onCleanup(@()fclose(fid));fwrite(fid,[jsonencode(x,'PrettyPrint',true) newline],'char');clear cleanup;
end

