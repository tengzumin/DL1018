function outPath=audit_mlp15_dev72_first_scene_v1()
here=fileparts(mfilename('fullpath'));studyRoot=fileparts(here);
projectRoot=fileparts(fileparts(fileparts(studyRoot)));
runtime=fullfile(studyRoot,'candidate_runner_work','matlab','runtime');
addpath(runtime);activate_paired_runner();
sceneId='DL1018_DEV_T1_C00_W03';attemptDir=fullfile(studyRoot,'runs',sceneId,'attempt_01');
rawPath=fullfile(attemptDir,'raw_run.mat');statusPath=fullfile(attemptDir,'run_status.json');
startPath=fullfile(attemptDir,'run_start.json');
manifest=jsondecode(fileread(fullfile(studyRoot,'MLP15_DEV72_PAYLOAD_MANIFEST_v2.json')));
recordHit=find(strcmp({manifest.records.scene_id},sceneId));assert(isscalar(recordHit));
record=manifest.records(recordHit);status=jsondecode(fileread(statusPath));runStart=jsondecode(fileread(startPath));
assert(strcmpi(sha256_file(rawPath),char(status.raw_sha256))&& ...
    strcmpi(char(status.payload_sha256),char(record.payload_sha256))&& ...
    strcmpi(char(status.b_raw_sha256),char(record.b_raw_sha256))&& ...
    strcmp(char(status.state),'COMPLETED')&&strcmp(char(status.status_value),'STABLE')&& ...
    double(status.plant_calls)==1&&double(status.transitions)==20000&& ...
    double(status.state_samples)==20001&&~logical(status.test_data_read)&& ...
    strcmpi(char(runStart.release_sha256),sha256_file(fullfile(studyRoot,'MLP15_DEV72_RELEASE_v1.json')))&& ...
    strcmpi(char(runStart.candidate_source_lock_sha256), ...
      sha256_file(fullfile(studyRoot,'MLP15_DEV72_CANDIDATE_SOURCE_LOCK_v1.json'))), ...
    'FIRST:RunReceipt','Candidate run receipt/hash/status does not match the frozen release.');
bRaw=char(record.b_raw_path);bStatusPath=char(record.b_status_path);
assert(strcmpi(sha256_file(bRaw),char(record.b_raw_sha256))&& ...
    strcmpi(sha256_file(bStatusPath),char(record.b_status_sha256)), ...
    'FIRST:BHash','Locked B raw/status hash mismatch.');
bStatus=jsondecode(fileread(bStatusPath));
assert(strcmp(char(bStatus.scene_id),sceneId)&&strcmp(char(bStatus.log_status),'STABLE')&& ...
    double(bStatus.transitions)==20000&&double(bStatus.state_samples)==20001&& ...
    ~logical(bStatus.TEST_accessed), 'FIRST:BStatus','Locked B status is invalid.');
candidate=load(rawPath,'log','scene','runIdentity');b=load(bRaw,'log','scene','runIdentity');
logC=candidate.log;logB=b.log;sC=candidate.scene;sB=b.scene;
assert(strcmp(char(sC.scene_id),sceneId)&&strcmp(char(sB.scene_id),sceneId)&& ...
    isequaln(sC.time,sB.time)&&isequaln(sC.initial_state,sB.initial_state)&& ...
    isequaln(sC.reference,sB.reference)&&isequaln(sC.arms,sB.arms)&& ...
    isequaln(sC.environment_wind_I,sB.environment_wind_I), ...
    'FIRST:PairScene','Candidate and B physical/trajectory input arrays differ.');
assert(strcmpi(char(candidate.runIdentity.external_identity_sha256), ...
    char(record.external_identity_sha256))&& ...
    strcmpi(char(b.runIdentity.external_identity_sha256),char(record.external_identity_sha256)), ...
    'FIRST:ExternalIdentity','Candidate/B external scene identity mismatch.');
payloadPath=char(record.payload_path);
prepared=prepare_mlp15_dev72_no_plant(payloadPath);
P0=simulation_parameters(prepared.cfg,prepared.cfg.plant.arm_initial,zeros(4,1));
score=scene_score(logC,sC,P0);base=scene_score(logB,sB,P0);
n=numel(sC.time);assert(score.complete&&base.complete,'FIRST:Timeline','Candidate or B timeline incomplete.');
trace=logC.mlp15_attitude_trace;eventIdx=find(~cellfun(@isempty,trace));
eventCount=numel(eventIdx);traceOK=eventCount>0;maxTraceApplyError=0;lastTime=-Inf;
for j=1:eventCount
    z=trace{eventIdx(j)};si=double(z.sample_index);ti=double(z.time_s);
    traceOK=traceOK&&logical(z.is_attitude_event)&&si>=1&&si<=n&&si==round(si)&& ...
      abs(ti-double(logC.time(si)))<1e-12&&ti>lastTime&&numel(z.feature_raw)==13&& ...
      all(isfinite(double(z.feature_raw(:))))&&numel(z.estimateTorque_Nm)==3&& ...
      all(isfinite(double(z.estimateTorque_Nm(:))))&& ...
      ~logical(z.rbf_output_enabled)&&~logical(z.rbf_update_enabled)&& ...
      ~logical(z.time_varying_inertia_reconstruction_used);
    lastTime=ti;
    e=max(abs(double(logC.attitude_compensation_applied_torque_Nm(si,:))- ...
        reshape(double(z.estimateTorque_Nm),1,3)));
    maxTraceApplyError=max(maxTraceApplyError,e);
end
traceOK=traceOK&&maxTraceApplyError<=1e-12&& ...
    ~any(logical(logC.rbf_update_flag(:)))&& ...
    all(abs(double(logC.rbf_output_held(:)))<=1e-12)&& ...
    ~logical(logC.attitude_fusion_enabled)&&~logical(logC.attitude_head_enabled)&& ...
    all(abs(double(logC.attitude_rbf_compensation_torque_Nm(:)))<=1e-12)&& ...
    ~logical(logC.mlp15_variable_inertia_reconstruction_used)&& ...
    ~logical(logC.gate_feedforward_enabled)&&~logical(logC.gate_observer_enabled);
candidateSafety=strcmp(char(logC.status),'STABLE')&&isempty(char(logC.safety_stop_reason))&& ...
    all(isfinite(logC.state(:)))&&all(isfinite(logC.attitude_compensation_applied_torque_Nm(:)))&& ...
    ~any(logical(logC.motor_saturated(:)))&&~any(logical(logC.generalized_clipped(:)));
candidateTilt=sum(logical(logC.tilt_limited(:)));bTilt=sum(logical(logB.tilt_limited(:)));
engineeringGate=score.complete&&base.complete&&candidateSafety&&traceOK&&candidateTilt<=bTilt;
report=struct('schema','DL1018_MLP15_DEV72_FIRST_SCENE_AUDIT_V1', ...
    'status',ternary(engineeringGate,'PASS_ENGINEERING_GATE','FAIL_ENGINEERING_GATE'), ...
    'created_utc',char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z''')), ...
    'scene_id',sceneId,'plant_invoked_by_audit',false,'test_data_read',false, ...
    'candidate_plant_calls',1,'candidate_raw_sha256',sha256_file(rawPath), ...
    'candidate_status_sha256',sha256_file(statusPath),'b_raw_sha256',sha256_file(bRaw), ...
    'b_status_sha256',sha256_file(bStatusPath), ...
    'scoring_rule_sha256',sha256_file(fullfile(studyRoot,'MLP15_DEV72_SCORING_RULE_v1.md')), ...
    'candidate',score,'B',base,'candidate_tilt_projection_samples',candidateTilt, ...
    'B_tilt_projection_samples',bTilt,'candidate_motor_saturation_samples',sum(any(logical(logC.motor_saturated),2)), ...
    'candidate_generalized_clipping_samples',sum(any(logical(logC.generalized_clipped),2)), ...
    'candidate_safety_stop_reason',char(logC.safety_stop_reason), ...
    'mlp15_event_count',eventCount,'mlp15_trace_ok',traceOK, ...
    'max_trace_to_applied_torque_abs_error_Nm',maxTraceApplyError, ...
    'engineering_gate_pass',engineeringGate,'position_or_attitude_single_scene_win_is_gate',false);
outPath=fullfile(here,'MLP15_DEV72_FIRST_SCENE_AUDIT_v1.json');
fid=fopen(outPath,'w');fwrite(fid,[jsonencode(report,'PrettyPrint',true) newline],'char');fclose(fid);
fprintf('FIRST_SCENE_AUDIT=%s\n',outPath);
end
function s=scene_score(log,scene,P0)
required={'time','state','reference','last_transition','status','safety_stop_reason', ...
    'motor_saturated','generalized_clipped','tilt_limited'};
assert(all(isfield(log,required))&&isfield(scene,'reference'),'FIRST:Schema','Missing raw fields.');
time=double(log.time(:));X=double(log.state);n=numel(time);
ref=double(scene.reference.position);tref=double(scene.time(:));
assert(isequal(size(X),[n 12])&&isequal(size(ref),[n 3])&&n==20001&& ...
    numel(tref)==n&&max(abs(time-tref))<1e-12&&double(log.last_transition)==20000&& ...
    all(isfinite(X(:)))&&all(isfinite(ref(:)))&&strcmp(char(log.status),'STABLE'), ...
    'FIRST:Timeline','Invalid or incomplete raw timeline.');
err=X(:,1:3)-ref;rmseAxis=sqrt(mean(err.^2,1));q=sqrt(mean(sum(err.^2,2)));
angles=zeros(n,1);targetTiltLimited=false(n,1);
for k=1:n
    [~,eta,limited]=baseline_force_to_attitude(double(scene.reference.acceleration(k,:)).', ...
        double(scene.reference.yaw(k)),P0);
    targetTiltLimited(k)=limited;Rref=rotation_zyx_local(eta);
    Ractual=rotation_zyx_local(X(k,7:9).');D=Rref.'*Ractual;
    angles(k)=acos(max(min((trace(D)-1)/2,1),-1));
end
s=struct('q0_20_m',q,'rmse_x_m',rmseAxis(1),'rmse_y_m',rmseAxis(2), ...
    'rmse_z_m',rmseAxis(3),'so3_rmse_rad',sqrt(mean(angles.^2)), ...
    'maximum_so3_error_rad',max(angles),'target_tilt_projection_samples',sum(targetTiltLimited), ...
    'complete',true,'state_finite',all(isfinite(X(:))));
end
function R=rotation_zyx_local(e)
p=e(1);q=e(2);y=e(3);cp=cos(p);sp=sin(p);cq=cos(q);sq=sin(q);cy=cos(y);sy=sin(y);
R=[cy*cq,cy*sq*sp-sy*cp,cy*sq*cp+sy*sp; ...
   sy*cq,sy*sq*sp+cy*cp,sy*sq*cp-cy*sp; ...
   -sq,cq*sp,cq*cp];
end
function h=sha256_file(path)
fid=fopen(path,'rb');assert(fid>=0,'FIRST:HashOpen','Cannot open %s.',path);
c=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,x=fread(fid,8*1024*1024,'*uint8');if isempty(x),break;end;md.update(typecast(x(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear c;
end
function y=ternary(c,a,b)
if c,y=a;else,y=b;end
end

