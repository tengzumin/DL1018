function summary=aggregate(rows)
qC=[rows.q_candidate_m];qB=[rows.q_b_m];aC=[rows.so3_candidate_rad];aB=[rows.so3_b_rad];
dq=qC-qB;da=aC-aB;w=[rows.wind_index];
