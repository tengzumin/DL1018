function verify_source_lock(lock,root)
expected=dir(fullfile(root,'matlab','**','*.m'));
assert(strcmp(char(lock.schema),'DL1018_MLP15_DEV72_CANDIDATE_SOURCE_LOCK_V1')&& ...
    strcmpi(char(java.io.File(char(lock.root)).getCanonicalPath()), ...
      char(java.io.File(root).getCanonicalPath()))&&numel(expected)==numel(lock.files), ...
    'FULL:SourceLock','Candidate source lock root/coverage mismatch.');
for j=1:numel(lock.files)
    p=fullfile(root,char(lock.files(j).relative_path));
    assert(isfile(p)&&strcmpi(sha256_file(p),char(lock.files(j).sha256)), ...
      'FULL:SourceFile','Candidate source hash mismatch: %s.',p);
end
end
