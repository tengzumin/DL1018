function s=reference_target(scene,P0)
acc=double(scene.reference.acceleration);yaw=double(scene.reference.yaw(:));
specific=acc+[zeros(size(acc,1),2),repmat(double(P0.g),size(acc,1),1)];
A=cos(yaw).*specific(:,1)+sin(yaw).*specific(:,2);
B=sin(yaw).*specific(:,1)-cos(yaw).*specific(:,2);
roll=atan2(B,hypot(specific(:,3),A));pitch=atan2(A,specific(:,3));
tilt=hypot(roll,pitch);scale=min(ones(size(tilt)),double(P0.limits.max_tilt)./max(tilt,eps));
roll=roll.*scale;pitch=pitch.*scale;
s=struct('R',rotation_rows([roll,pitch,yaw]),'target_tilt_projection_count',sum(tilt>double(P0.limits.max_tilt)));
end
function s=scene_score(log,scene,target)
time=double(log.time(:));X=double(log.state);ref=double(scene.reference.position);tref=double(scene.time(:));
assert(size(X,1)==20001&&size(X,2)==12&&isequal(size(ref),[20001 3])&& ...
    numel(time)==20001&&max(abs(time-tref))<1e-12&& ...
    double(log.last_transition)==20000&&all(isfinite(X(:)))&&all(isfinite(ref(:)))&& ...
    strcmp(char(log.status),'STABLE'),'FULL:Timeline','Invalid/incomplete stable scene timeline.');
err=X(:,1:3)-ref;rmse=sqrt(mean(err.^2,1));q=sqrt(mean(sum(err.^2,2)));
actualR=rotation_rows(X(:,7:9));cang=(sum(target.R.*actualR,2)-1)/2;
theta=acos(max(min(cang,1),-1));
q05=window_q(err,time,0,5);q510=window_q(err,time,5,10);
q1015=window_q(err,time,10,15);q1520=window_q(err,time,15,20);
s=struct('complete',true,'state_finite',all(isfinite(X(:))),'q0_20_m',q, ...
    'rmse_x_m',rmse(1),'rmse_y_m',rmse(2),'rmse_z_m',rmse(3), ...
    'so3_rmse_rad',sqrt(mean(theta.^2)),'maximum_so3_error_rad',max(theta), ...
    'so3_0_5_rad',window_rmse(theta,time,0,5),'so3_5_10_rad',window_rmse(theta,time,5,10), ...
    'so3_10_15_rad',window_rmse(theta,time,10,15),'so3_15_20_rad',window_rmse(theta,time,15,20), ...
    'peak_position_error_m',max(sqrt(sum(err.^2,2))), ...
    'end_position_error_m',norm(err(end,:)),'q_0_5_m',q05,'q_5_10_m',q510, ...
    'q_10_15_m',q1015,'q_15_20_m',q1520, ...
    'max_body_rate_radps',max(sqrt(sum(X(:,10:12).^2,2))));
end
function R=rotation_rows(e)
p=e(:,1);q=e(:,2);y=e(:,3);cp=cos(p);sp=sin(p);cq=cos(q);sq=sin(q);cy=cos(y);sy=sin(y);
R=[cy.*cq,cy.*sq.*sp-sy.*cp,cy.*sq.*cp+sy.*sp, ...
   sy.*cq,sy.*sq.*sp+cy.*cp,sy.*sq.*cp-cy.*sp, ...
   -sq,cq.*sp,cq.*cp];
end
function q=window_rmse(x,time,t0,t1)
mask=time>=t0-1e-12;if t1<20,mask=mask&time<t1-1e-12;else,mask=mask&time<=t1+1e-12;end
q=sqrt(mean(double(x(mask)).^2));
end
function q=window_q(err,time,t0,t1)
mask=time>=t0-1e-12;
if t1<20,mask=mask&time<t1-1e-12;else,mask=mask&time<=t1+1e-12;end
assert(any(mask),'FULL:Window','Empty metric window.');
q=sqrt(mean(sum(err(mask,:).^2,2)));
end
function [ok,count,maxErr]=audit_trace(log)
trace=log.mlp15_attitude_trace;idx=find(~cellfun(@isempty,trace));count=numel(idx);
ok=count>0;maxErr=0;lastTime=-Inf;n=numel(log.time);
for j=1:count
    z=trace{idx(j)};si=double(z.sample_index);t=double(z.time_s);
    ok=ok&&logical(z.is_attitude_event)&&isscalar(si)&&si>=1&&si<=n&&si==round(si)&& ...
        abs(t-double(log.time(si)))<1e-12&&t>lastTime&&numel(z.feature_raw)==13&& ...
        all(isfinite(double(z.feature_raw(:))))&&numel(z.estimateTorque_Nm)==3&& ...
        all(isfinite(double(z.estimateTorque_Nm(:))))&& ...
        ~logical(z.rbf_output_enabled)&&~logical(z.rbf_update_enabled)&& ...
        ~logical(z.time_varying_inertia_reconstruction_used);
    lastTime=t;delta=max(abs(double(log.attitude_compensation_applied_torque_Nm(si,:))- ...
        reshape(double(z.estimateTorque_Nm),1,3)));maxErr=max(maxErr,delta);
end
ok=ok&&maxErr<=1e-12&&~any(logical(log.rbf_update_flag(:)))&& ...
    all(abs(double(log.rbf_output_held(:)))<=1e-12)&& ...
    all(abs(double(log.attitude_rbf_compensation_torque_Nm(:)))<=1e-12);
end
