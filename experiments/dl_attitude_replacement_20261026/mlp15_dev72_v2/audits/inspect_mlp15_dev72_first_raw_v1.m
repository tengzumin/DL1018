    'scene_reference_fields',{fieldnames(scene.reference)}, ...
    'log_reference_fields',{fieldnames(log.reference)}, ...
    'first_mlp15_event_fields',{fieldnames(event)},'mlp_event_count',numel(idx), ...
    'state_size',size(log.state),'time_size',size(log.time), ...
    'reference_position_size',size(log.reference.position), ...
    'R_task_present',isfield(scene,'R_task'),'scene_id',char(scene.scene_id), ...
    'status',char(log.status),'last_transition',double(log.last_transition), ...
    'finite_state',all(isfinite(log.state(:))), ...
    'finite_position_reference',all(isfinite(log.reference.position(:))));
