function report=audit_candidate_runner_no_plant_v1()
% Static parse and arm-scope audit for the isolated DL_TCN gate runner; never calls Plant.
researchRoot=fileparts(fileparts(mfilename('fullpath')));
runnerRoot=fullfile(researchRoot,'pilot_runner_v2','candidate_runner_work');
runtime=fullfile(runnerRoot,'matlab','runtime');
files={ ...
    fullfile(runtime,'gate_attitude_arm_spec.m'), ...
    fullfile(runtime,'gate_holdout_no_plant_arm_check.m'), ...
    fullfile(runtime,'make_gate_holdout_options.m'), ...
    fullfile(runtime,'prepare_gate_candidate_no_plant.m'), ...
    fullfile(runtime,'run_gate_holdout_closed_loop.m'), ...
    fullfile(runtime,'run_tcn_candidate_gate_attempt.m'), ...
    fullfile(runtime,'tcn_attitude_forward_v1.m'), ...
    fullfile(runtime,'tcn_attitude_step_v1.m'), ...
    fullfile(researchRoot,'matlab','score_tcn_ghp7_pilot_v1.m')};
assert(all(isfile(files)),'DLTCN:SourceMissing','One or more isolated candidate MATLAB files are missing.');
rows=struct('path',{},'diagnostic_count',{},'diagnostics',{});
for i=1:numel(files)
    messages=checkcode(files{i},'-id');
    rows(i).path=files{i};
    rows(i).diagnostic_count=numel(messages);
    rows(i).diagnostics=messages;
end
projectRoot=fileparts(fileparts(researchRoot));
legacyRunner=fullfile(projectRoot,'experiments','attitude_physics_inertia_observer_20261025', ...
    'holdout_gate_inspection_v2','candidate_runner_work','matlab','runtime','run_gate_holdout_closed_loop.m');
legacyMessages=checkcode(legacyRunner,'-id');
newRunnerMessages=rows(5).diagnostics;
legacyDiagnosticIds=sort(string({legacyMessages.id}));
newDiagnosticIds=sort(string({newRunnerMessages.id}));
assert(isequal(legacyDiagnosticIds,newDiagnosticIds), ...
    'DLTCN:InheritedDiagnostics','The isolated runner changed the Code Analyzer diagnostic-ID counts.');
addpath(runtime);
cleanup=onCleanup(@()rmpath(runtime));
arms=gate_holdout_no_plant_arm_check();
assert(isequal(arms.arm_ids,{'C5_RBF','DL_TCN'})&& ...
    isequal(arms.rbf_enabled,[true false])&& ...
    isequal(arms.inertia_reconstruction_enabled,[false false])&& ...
    isequal(arms.feedforward_enabled,[false false])&& ...
    isequal(arms.observer_enabled,[false false])&&~arms.plant_invoked&& ...
    arms.tcn_runtime_inputs==13&&arms.tcn_uses_fixed_J0, ...
    'DLTCN:ArmScope','No-Plant attitude-arm scope checks failed.');
stepText=fileread(fullfile(runtime,'tcn_attitude_step_v1.m'));
forbidden={'Jhat','Jdot_hat','rho_true','rhoDot_true','true_torque'};
for i=1:numel(forbidden)
    assert(~contains(stepText,forbidden{i},'IgnoreCase',true), ...
        'DLTCN:PrivilegedInput','TCN step uses forbidden Plant/inertia field %s.',forbidden{i});
end
report=struct('schema','DL1018_TCN_CANDIDATE_NO_PLANT_AUDIT_V1', ...
    'status','PASS','plant_invoked',false,'arm_scope',arms, ...
    'parsed_source_count',numel(rows),'sources',rows, ...
    'legacy_runner_diagnostic_count',numel(legacyMessages), ...
    'isolated_runner_diagnostic_count',numel(newRunnerMessages), ...
    'inherited_runner_diagnostic_ids_match',true, ...
    'inertia_reconstruction_in_tcn_step',false,'test_data_read',false, ...
    'completed_utc',char(datetime('now','TimeZone','UTC', ...
    'Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z''')));
outPath=fullfile(researchRoot,'MATLAB_NO_PLANT_AUDIT_TCN_v1.json');
fid=fopen(outPath,'w');assert(fid>=0,'DLTCN:AuditWrite','Could not write no-Plant audit.');
guard=onCleanup(@()fclose(fid));
fwrite(fid,[jsonencode(report,'PrettyPrint',true) newline],'char');clear guard cleanup;
fprintf('NO_PLANT_AUDIT=PASS SOURCES=%d DIAGNOSTICS=%d PLANT_INVOKED=false\n', ...
    numel(rows),sum([rows.diagnostic_count]));
end
