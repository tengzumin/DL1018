function result=score_tcn_ghp7_pilot_v1()
% Score the six released DL_TCN GHP7 calls and reuse hash-bound B/C5_RBF rows.
researchRoot=fileparts(fileparts(mfilename('fullpath')));
projectRoot=fileparts(fileparts(researchRoot));
releasePath=fullfile(researchRoot,'PILOT_RELEASE_v1.json');
payloadPath=fullfile(researchRoot,'GHP7_PILOT_PAYLOAD_MANIFEST_v1.json');
baselinePath=fullfile(researchRoot,'GHP7_BASELINE_REUSE_MANIFEST_v1.json');
assert(isfile(releasePath),'DLTCN:NoRelease','Pilot release is missing.');
release=jsondecode(fileread(releasePath));
payloadManifest=jsondecode(fileread(payloadPath));
baseline=jsondecode(fileread(baselinePath));
assert(strcmp(release.status,'RELEASED')&&double(release.plant_calls_authorized)==6&& ...
    strcmp(payloadManifest.status,'PASS')&&payloadManifest.scene_count==6&& ...
    ~payloadManifest.tests_data_read&&strcmp(baseline.status,'PASS')&& ...
    baseline.record_count==12&&~baseline.test_data_read, ...
    'DLTCN:ReleaseGate','Release/payload/baseline gate is invalid.');
assert(strcmpi(sha256_file(payloadPath),char(release.payload_manifest_sha256))&& ...
    strcmpi(sha256_file(baselinePath),char(release.baseline_reuse_manifest_sha256)), ...
    'DLTCN:ManifestHash','Pilot input manifest changed after release.');
verify_candidate_lock(release,fullfile(researchRoot,'pilot_runner_v2','candidate_runner_work'));
for i=1:numel(baseline.records)
    rec=baseline.records(i);
    assert(isfile(char(rec.raw_path))&&strcmpi(sha256_file(char(rec.raw_path)),char(rec.raw_sha256)), ...
        'DLTCN:BaselineRawHash','Reused baseline raw changed: %s / %s.', ...
        char(rec.scene_id),char(rec.runner));
end

oldTaskRoot=fullfile(projectRoot,'experiments','attitude_physics_inertia_observer_20261025', ...
    'holdout_gate_inspection_v2');
c5ReceiptPath=fullfile(oldTaskRoot,'C5_R_TASK_BINDING_PILOT_RECEIPT_v5.json');
c5Receipt=jsondecode(fileread(c5ReceiptPath));
assert(strcmpi(sha256_file(c5ReceiptPath),char(release.c5_receipt_sha256))&& ...
    strcmpi(char(c5Receipt.status),'PASS_NO_PLANT_PILOT_PAYLOADS_ONLY')&& ...
    c5Receipt.plant_calls==0&&~c5Receipt.tests_data_read, ...
    'DLTCN:C5Receipt','The no-Plant C5 receipt differs from the release.');
snapshotPath=char(c5Receipt.input_records.c5_snapshot_mat.path);
assert(strcmpi(sha256_file(snapshotPath),char(c5Receipt.input_records.c5_snapshot_mat.sha256)), ...
    'DLTCN:C5Snapshot','C5 scoring configuration changed.');
snapshot=load(snapshotPath,'cfg');cfg=snapshot.cfg;
addpath(fullfile(oldTaskRoot,'scene_builder_work'));
cleanup=onCleanup(@()rmpath(fullfile(oldTaskRoot,'scene_builder_work')));

records=payloadManifest.records;
expectedIds=sort(string({records.scene_id}));
assert(numel(records)==6&&numel(unique(expectedIds))==6, ...
    'DLTCN:ExpectedScenes','The released six-scene set is not unique.');
runsRoot=fullfile(researchRoot,'pilot_runs');
starts=dir(fullfile(runsRoot,'**','run_start.json'));
rows=repmat(empty_row(),numel(records),1);
for i=1:numel(records)
    p=records(i);row=empty_row();row.scene_id=char(p.scene_id);row.gust_group=char(extractBetween(string(p.scene_id),'GHP7_','_W'));
    row.wind_id=char(extractAfter(string(p.scene_id),"_W"));
    row.payload_sha256=char(p.payload_file_sha256);row.r_task_sha256=char(p.r_task_sha256);
    hit=[];
    for j=1:numel(starts)
        start=jsondecode(fileread(fullfile(starts(j).folder,starts(j).name)));
        if isfield(start,'scene_id')&&strcmp(char(start.scene_id),row.scene_id),hit(end+1)=j;end %#ok<AGROW>
    end
    row.attempt_count=numel(hit);
    if isempty(hit)
        row.score_state='MISSING_ATTEMPT';rows(i)=row;continue
    elseif numel(hit)>1
        row.score_state='DUPLICATE_ATTEMPTS';rows(i)=row;continue
    end
    attemptDir=starts(hit).folder;row.attempt_dir=attemptDir;
    try
        start=jsondecode(fileread(fullfile(attemptDir,'run_start.json')));
        statusPath=fullfile(attemptDir,'run_status.json');
        if ~isfile(statusPath),row.score_state='MISSING_STATUS';rows(i)=row;continue;end
        status=jsondecode(fileread(statusPath));
        row.run_state=char(status.state);
        rawPath=fullfile(attemptDir,'raw_run.mat');
        if ~isfile(rawPath),row.score_state='MISSING_RAW';rows(i)=row;continue;end
        rawSha=sha256_file(rawPath);
        if isfield(status,'raw_output_sha256')&&~strcmpi(rawSha,char(status.raw_output_sha256))
            row.score_state='RAW_HASH_MISMATCH';rows(i)=row;continue
        end
        assert(strcmp(char(start.attitude_arm),'DL_TCN')&&strcmp(char(start.geometry_arm),'ACTIVE')&& ...
            strcmpi(char(start.scene_payload_sha256),row.payload_sha256)&& ...
            strcmpi(char(start.r_task_sha256),row.r_task_sha256)&& ...
            strcmpi(char(start.taskbook_sha256),char(release.taskbook_sha256))&& ...
            strcmpi(char(start.candidate_source_lock_sha256),char(release.candidate_source_lock_sha256))&& ...
            strcmpi(char(start.tcn_model_mat_sha256),char(release.model_sha256)), ...
            'DLTCN:RunIdentity','Candidate run start does not match frozen release/payload.');
        raw=load(rawPath,'log','scene');log=raw.log;scene=raw.scene;
        assert(strcmp(char(scene.scene_id),row.scene_id)&& ...
            strcmpi(char(scene.R_task_sha256),row.r_task_sha256)&& ...
            strcmpi(paired_sha256_double(double(scene.R_task)),row.r_task_sha256), ...
            'DLTCN:RawScene','Candidate raw scene or R_task identity differs.');
        [row,logAudit]=score_log(row,log,scene,cfg);
        row.run_state=char(status.state);row.raw_sha256=rawSha;
        row.status_value=char(string(log.status));row.safety_stop_reason=char(string(log.safety_stop_reason));
        row.complete_transitions=logical(logAudit.complete);
        row.completion_flag_consistent=logical(logAudit.flag_consistent)&& ...
            isfield(status,'complete_transitions')&&logical(status.complete_transitions);
        row.motor_saturation_any=logical(logAudit.motor_saturation_any);
        row.generalized_clip_any=logical(logAudit.generalized_clip_any);
        row.tilt_limit_any=logical(logAudit.tilt_limit_any);
        row.geometry_checked=logical(logAudit.geometry_checked);
        row.pass_bidirectional=logical(logAudit.pass_bidirectional);
        row.pass_15mm_proxy=logical(logAudit.pass_15mm_proxy);
        row.application_feasible=logical(logAudit.application_feasible);
        row.tcn_trace_ok=logical(logAudit.tcn_trace_ok);
        row.score_state='SCORED_COMPLETE';
        if ~row.complete_transitions||~row.completion_flag_consistent|| ...
                ~strcmp(row.run_state,'COMPLETED')||~strcmp(row.status_value,'STABLE')|| ...
                ~isempty(row.safety_stop_reason)||~row.tcn_trace_ok|| ...
                row.motor_saturation_any||row.generalized_clip_any||row.tilt_limit_any
            row.score_state='SCORED_FAILED_OR_UNSAFE';
        end
    catch ME
        row.score_state='SCORER_ERROR';row.failure_reason=char(ME.message);
    end
    rows(i)=row;
end

for i=1:numel(rows)
    b=find(strcmp({baseline.records.scene_id},rows(i).scene_id)&strcmp({baseline.records.runner},'B'));
    c=find(strcmp({baseline.records.scene_id},rows(i).scene_id)&strcmp({baseline.records.attitude_arm},'C5_RBF'));
    assert(isscalar(b)&&isscalar(c),'DLTCN:BaselinePair','Missing B/C5_RBF paired baseline row.');
    rows(i).baseline_B_raw_sha256=char(baseline.records(b).raw_sha256);
    rows(i).baseline_C5_raw_sha256=char(baseline.records(c).raw_sha256);
    rows(i).baseline_B_q0_20_m=double(baseline.records(b).q0_20_m);
    rows(i).baseline_C5_q0_20_m=double(baseline.records(c).q0_20_m);
    rows(i).baseline_B_so3_rmse_rad=double(baseline.records(b).so3_rmse_rad);
    rows(i).baseline_C5_so3_rmse_rad=double(baseline.records(c).so3_rmse_rad);
    rows(i).baseline_B_completion_flag_consistent=logical(baseline.records(b).score_completion_flag_consistent);
    rows(i).baseline_C5_completion_flag_consistent=logical(baseline.records(c).score_completion_flag_consistent);
    rows(i).baseline_B_score_valid=logical(baseline.records(b).score_run_valid);
    rows(i).baseline_C5_score_valid=logical(baseline.records(c).score_run_valid);
    rows(i).win_position_vs_B=isfinite(rows(i).q0_20_m)&& ...
        rows(i).q0_20_m<rows(i).baseline_B_q0_20_m-1e-12;
    rows(i).win_attitude_vs_B=isfinite(rows(i).so3_rmse_rad)&& ...
        rows(i).so3_rmse_rad<rows(i).baseline_B_so3_rmse_rad-1e-12;
    rows(i).win_position_vs_C5=isfinite(rows(i).q0_20_m)&& ...
        rows(i).q0_20_m<rows(i).baseline_C5_q0_20_m-1e-12;
    rows(i).win_attitude_vs_C5=isfinite(rows(i).so3_rmse_rad)&& ...
        rows(i).so3_rmse_rad<rows(i).baseline_C5_so3_rmse_rad-1e-12;
end
summary=struct('expected_scenes',numel(rows), ...
    'completed_scenes',sum(strcmp({rows.run_state},'COMPLETED')), ...
    'unsafe_or_failed_scenes',sum(strcmp({rows.score_state},'SCORED_FAILED_OR_UNSAFE')), ...
    'wins_position_vs_B',sum([rows.win_position_vs_B]), ...
    'wins_attitude_vs_B',sum([rows.win_attitude_vs_B]), ...
    'wins_position_vs_C5_RBF',sum([rows.win_position_vs_C5]), ...
    'wins_attitude_vs_C5_RBF',sum([rows.win_attitude_vs_C5]), ...
    'B_baseline_flag_mismatch_count',sum(~[rows.baseline_B_completion_flag_consistent]), ...
    'C5_RBF_baseline_flag_mismatch_count',sum(~[rows.baseline_C5_completion_flag_consistent]), ...
    'mean_position_Q_DL_TCN_m',mean_finite([rows.q0_20_m]), ...
    'mean_position_Q_B_m',mean_finite([rows.baseline_B_q0_20_m]), ...
    'mean_position_Q_C5_RBF_m',mean_finite([rows.baseline_C5_q0_20_m]), ...
    'mean_SO3_DL_TCN_rad',mean_finite([rows.so3_rmse_rad]), ...
    'mean_SO3_B_rad',mean_finite([rows.baseline_B_so3_rmse_rad]), ...
    'mean_SO3_C5_RBF_rad',mean_finite([rows.baseline_C5_so3_rmse_rad]));
result=struct('schema','DL1018_TCN_GHP7_PILOT_SCORE_V1', ...
    'created_utc',char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z''')), ...
    'taskbook_sha256',char(release.taskbook_sha256), ...
    'release_sha256',sha256_file(releasePath), ...
    'payload_manifest_sha256',sha256_file(payloadPath), ...
    'baseline_manifest_sha256',sha256_file(baselinePath), ...
    'candidate_source_lock_sha256',char(release.candidate_source_lock_sha256), ...
    'model_sha256',char(release.model_sha256),'test_data_read',false, ...
    'time_samples_are_independent',false,'summary',summary,'rows',rows);
outDir=fullfile(researchRoot,'pilot_score_v1');
assert(~isfolder(outDir)&&~isfile(outDir),'DLTCN:NoOverwrite','Pilot scoring output already exists.');
mkdir(outDir);write_json(fullfile(outDir,'pilot_score.json'),result);
writetable(struct2table(rows),fullfile(outDir,'pilot_score.csv'));
clear cleanup;
end

function [row,a]=score_log(row,log,scene,cfg)
required={'time','transition_time','state','reference','arms','motor_saturated', ...
    'generalized_clipped','tilt_limited','last_transition','status','safety_stop_reason', ...
    'complete_transitions','tcn_attitude_trace','tcn_variable_inertia_reconstruction_used'};
assert(all(isfield(log,required))&&isfield(log.reference,'position')&&isfield(log.arms,'rho_true'), ...
    'DLTCN:TraceSchema','Candidate raw log lacks required score/TCN traces.');
time=double(log.time(:));X=double(log.state);ref=double(log.reference.position);
transitionTime=double(log.transition_time(:));sceneTime=double(scene.time(:));n=numel(time);
assert(size(X,1)==n&&size(X,2)==12&&isequal(size(ref),[n,3]), ...
    'DLTCN:TraceShape','Candidate state/reference shape is invalid.');
a=struct('complete',n==numel(sceneTime)&&numel(transitionTime)==numel(sceneTime)-1&& ...
    double(log.last_transition)==numel(sceneTime)-1&&max(abs(time-sceneTime))<=1e-10&& ...
    max(abs(transitionTime-sceneTime(1:end-1)))<=1e-10&&all(isfinite(X(:)))&&all(isfinite(ref(:))), ...
    'flag_consistent',logical(log.complete_transitions)&&logical(log.tcn_variable_inertia_reconstruction_used==false), ...
    'motor_saturation_any',any(logical(log.motor_saturated(:))), ...
    'generalized_clip_any',any(logical(log.generalized_clipped(:))), ...
    'tilt_limit_any',any(logical(log.tilt_limited(:))), ...
    'geometry_checked',false,'pass_bidirectional',false,'pass_15mm_proxy',false, ...
    'application_feasible',false,'tcn_trace_ok',false);
trace=log.tcn_attitude_trace;events=trace(~cellfun(@isempty,trace));
assert(~isempty(events),'DLTCN:TCNTrace','No TCN inference event was logged.');
a.tcn_trace_ok=all(cellfun(@(z)all(isfinite(double(z.feature_raw(:))))&& ...
    all(isfinite(double(z.estimateTorque_Nm(:))))&& ...
    ~logical(z.rbf_output_enabled)&&~logical(z.rbf_update_enabled)&& ...
    ~logical(z.time_varying_inertia_reconstruction_used),events));
err=X(:,1:3)-ref;row.q0_20_m=sqrt(mean(sum(err.^2,2)));
row.rmse_x_m=sqrt(mean(err(:,1).^2));row.rmse_y_m=sqrt(mean(err(:,2).^2));row.rmse_z_m=sqrt(mean(err(:,3).^2));
row.end_position_error_m=norm(err(end,:));
q8=time>=8-1e-10&time<=12+1e-10;if sum(q8)==4001,row.q8_12_m=sqrt(mean(sum(err(q8,:),2)));end
Rtask=double(scene.R_task);so3=nan(n,1);
assert(size(Rtask,3)>=n,'DLTCN:OrientationTimeline','R_task is shorter than candidate state timeline.');
for k=1:n
    R=rotation_zyx_local(X(k,7:9).');D=Rtask(:,:,k)'*R;
    so3(k)=acos(max(min((trace(D)-1)/2,1),-1));
end
row.so3_rmse_rad=sqrt(mean(so3.^2));row.max_body_rate_radps=max(sqrt(sum(X(:,10:12).^2,2)));
rho=double(log.arms.rho_true);
if isequal(size(rho),[n 4])&&all(isfinite(rho(:)))
    geom=check_gate_inspection_geometry(time,X,rho,cfg);
    a.geometry_checked=true;a.pass_bidirectional=logical(geom.pass_bidirectional);
    a.pass_15mm_proxy=logical(geom.pass_15mm_proxy);row.minimum_clearance_m=double(geom.minimum_clearance_m);
end
a.application_feasible=strcmp(char(string(log.status)),'STABLE')&&a.complete&&a.flag_consistent&& ...
    a.tcn_trace_ok&&isempty(char(string(log.safety_stop_reason)))&& ...
    ~a.motor_saturation_any&&~a.generalized_clip_any&&~a.tilt_limit_any&& ...
    a.geometry_checked&&a.pass_bidirectional&&a.pass_15mm_proxy&& ...
    row.q0_20_m<=.05&&row.q8_12_m<=.05&&row.end_position_error_m<=.10;
end

function row=empty_row()
row=struct('scene_id','','gust_group','','wind_id','','attempt_dir','','attempt_count',0, ...
    'run_state','','score_state','','failure_reason','','payload_sha256','','r_task_sha256','', ...
    'raw_sha256','','q0_20_m',NaN,'q8_12_m',NaN,'end_position_error_m',NaN, ...
    'rmse_x_m',NaN,'rmse_y_m',NaN,'rmse_z_m',NaN,'so3_rmse_rad',NaN, ...
    'max_body_rate_radps',NaN,'minimum_clearance_m',NaN,'complete_transitions',false, ...
    'completion_flag_consistent',false,'status_value','','safety_stop_reason','', ...
    'motor_saturation_any',false,'generalized_clip_any',false,'tilt_limit_any',false, ...
    'geometry_checked',false,'pass_bidirectional',false,'pass_15mm_proxy',false, ...
    'application_feasible',false,'tcn_trace_ok',false, ...
    'baseline_B_raw_sha256','','baseline_C5_raw_sha256','', ...
    'baseline_B_q0_20_m',NaN,'baseline_C5_q0_20_m',NaN, ...
    'baseline_B_so3_rmse_rad',NaN,'baseline_C5_so3_rmse_rad',NaN, ...
    'baseline_B_completion_flag_consistent',false,'baseline_C5_completion_flag_consistent',false, ...
    'baseline_B_score_valid',false,'baseline_C5_score_valid',false, ...
    'win_position_vs_B',false,'win_attitude_vs_B',false, ...
    'win_position_vs_C5',false,'win_attitude_vs_C5',false);
end

function h=paired_sha256_double(a)
md=java.security.MessageDigest.getInstance('SHA-256');md.update(typecast(double(a(:)),'uint8'));
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
function verify_candidate_lock(release,runnerRoot)
lockPath=fullfile(fileparts(fileparts(runnerRoot)),'CANDIDATE_SOURCE_LOCK_v1.json');
assert(isfile(lockPath)&&strcmpi(sha256_file(lockPath),char(release.candidate_source_lock_sha256)), ...
    'DLTCN:SourceLockSHA','Candidate source lock differs from release.');
lock=jsondecode(fileread(lockPath));root=char(java.io.File(runnerRoot).getCanonicalPath());
expected=dir(fullfile(runnerRoot,'matlab','**','*.m'));prefix=[root filesep];paths=cell(numel(expected),1);
for i=1:numel(expected)
    p=char(java.io.File(fullfile(expected(i).folder,expected(i).name)).getCanonicalPath());
    assert(startsWith(lower(p),lower(prefix)),'DLTCN:SourcePath','Candidate source escaped locked root.');
    paths{i}=lower(strrep(p(numel(prefix)+1:end),'/','\'));
end
locked=lower(strrep(string({lock.files.relative_path}),'/','\'));
assert(strcmp(char(lock.schema),'DL1018_CANDIDATE_SOURCE_LOCK_V1')&& ...
    strcmpi(char(java.io.File(char(lock.root)).getCanonicalPath()),root)&& ...
    numel(unique(locked))==numel(locked)&&isequal(sort(locked(:)),sort(string(paths(:)))), ...
    'DLTCN:SourceLockCoverage','Candidate source lock does not cover the full runner.');
for i=1:numel(lock.files)
    p=fullfile(root,char(lock.files(i).relative_path));
    assert(isfile(p)&&strcmpi(sha256_file(p),char(lock.files(i).sha256)), ...
        'DLTCN:SourceFileHash','Candidate source changed: %s.',p);
end
end
function h=sha256_file(p)
fid=fopen(p,'rb');assert(fid>=0,'DLTCN:HashOpen','Cannot open %s.',p);
c=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear c;
end
function x=mean_finite(x)
x=x(isfinite(x));if isempty(x),x=NaN;else,x=mean(x);end
end
function R=rotation_zyx_local(e)
p=e(1);q=e(2);y=e(3);
R=[cos(y)*cos(q),cos(y)*sin(q)*sin(p)-sin(y)*cos(p),cos(y)*sin(q)*cos(p)+sin(y)*sin(p); ...
    sin(y)*cos(q),sin(y)*sin(q)*sin(p)+cos(y)*cos(p),sin(y)*sin(q)*cos(p)-cos(y)*sin(p); ...
    -sin(q),cos(q)*sin(p),cos(q)*cos(p)];
end
function write_json(p,x)
fid=fopen(p,'w','n','UTF-8');assert(fid>=0,'DLTCN:Write','Cannot write %s.',p);
c=onCleanup(@()fclose(fid));fwrite(fid,unicode2native([jsonencode(x,'PrettyPrint',true) newline],'UTF-8'),'uint8');clear c;
end
