function result=audit_c5_rbf_completion_marker_v1()
% Trace the sole C5_RBF completion-marker mismatch to its locked runner source.
taskRoot=fileparts(fileparts(mfilename('fullpath')));
physicsRoot=fullfile(fileparts(taskRoot),'attitude_physics_inertia_observer_20261025');
pilotRoot=fullfile(physicsRoot,'holdout_gate_inspection_v2');
payloadPath=fullfile(taskRoot,'GHP7_PILOT_PAYLOAD_MANIFEST_v1.json');
baselinePath=fullfile(taskRoot,'GHP7_BASELINE_REUSE_MANIFEST_v1.json');
comparisonPath=fullfile(taskRoot,'C5_10_PHYSICS_PAIRED_COMPARISON_v1.json');
lockV4Path=fullfile(pilotRoot,'CANDIDATE_SOURCE_LOCK_PILOT_v4.json');
lockV5Path=fullfile(pilotRoot,'CANDIDATE_SOURCE_LOCK_PILOT_v5.json');
runnerV4Path=fullfile(physicsRoot,'holdout_gate_inspection_v1','candidate_runner_work', ...
    'matlab','runtime','run_gate_holdout_closed_loop.m');
runnerV5Path=fullfile(pilotRoot,'candidate_runner_work','matlab','runtime', ...
    'run_gate_holdout_closed_loop.m');
payload=jsondecode(fileread(payloadPath));baseline=jsondecode(fileread(baselinePath));
comparison=jsondecode(fileread(comparisonPath));
lockV4=jsondecode(fileread(lockV4Path));lockV5=jsondecode(fileread(lockV5Path));
lockV4Sha=sha256_file(lockV4Path);lockV5Sha=sha256_file(lockV5Path);
c5=baseline.records(strcmp({baseline.records.attitude_arm},'C5_RBF'));
assert(numel(c5)==6&&numel(comparison.rows)==6&&strcmp(comparison.status,'PASS')&& ...
    comparison.metrics_independently_recomputed_from_raw&&~comparison.test_data_read, ...
    'GHP7:PriorAudit','The independent paired raw audit is absent or invalid.');
old=c5(strcmp({c5.scene_id},'DL1018_GHP7_G1_W00'));
assert(isscalar(old)&&strcmpi(char(old.source_lock_sha256),lockV4Sha)&& ...
    sum(strcmpi({c5.source_lock_sha256},lockV4Sha))==1&& ...
    sum(strcmpi({c5.source_lock_sha256},lockV5Sha))==5, ...
    'GHP7:SourceLineage','C5_RBF source-lock assignment does not match the recorded pilot lineage.');
payloadRow=payload.records(strcmp({payload.records.scene_id},char(old.scene_id)));
comparisonRow=comparison.rows(strcmp({comparison.rows.scene_id},char(old.scene_id)));
assert(isscalar(payloadRow)&&isscalar(comparisonRow)&& ...
    strcmpi(char(payloadRow.payload_file_sha256),char(old.scene_payload_sha256))&& ...
    strcmpi(char(comparisonRow.C5_RBF_raw_sha256),char(old.raw_sha256))&& ...
    abs(double(comparisonRow.C5_RBF_q0_20_m)-double(old.q0_20_m))<=1e-10&& ...
    abs(double(comparisonRow.C5_RBF_so3_rmse_rad)-double(old.so3_rmse_rad))<=1e-10, ...
    'GHP7:ResultLineage','False-marker raw is not the row in the independent comparison.');

v4Code=fileread(runnerV4Path);v5Code=fileread(runnerV5Path);
v4Entry=lockV4.files(strcmp({lockV4.files.relative_path}, ...
    'matlab\runtime\run_gate_holdout_closed_loop.m'));
v5Entry=lockV5.files(strcmp({lockV5.files.relative_path}, ...
    'matlab\runtime\run_gate_holdout_closed_loop.m'));
assert(isscalar(v4Entry)&&isscalar(v5Entry)&& ...
    strcmpi(sha256_file(runnerV4Path),char(v4Entry.sha256))&& ...
    strcmpi(sha256_file(runnerV5Path),char(v5Entry.sha256))&& ...
    contains(v4Code,'n=N-1;')&&contains(v4Code,'log.complete_transitions=(last==n-1)')&& ...
    contains(v5Code,'n=N-1;')&&contains(v5Code,'log.complete_transitions=(last==n)'), ...
    'GHP7:SourceCode','Locked source files do not match the completion-check expressions.');

statusPath=fullfile(char(old.attempt_dir),'run_status.json');
status=jsondecode(fileread(statusPath));
rawPath=char(old.raw_path);rawSha=sha256_file(rawPath);s=load(rawPath,'log');log=s.log;
assert(strcmpi(rawSha,char(old.raw_sha256))&&strcmp(status.state,'COMPLETED')&& ...
    strcmp(status.status_value,'STABLE')&&isempty(status.safety_stop_reason)&& ...
    ~logical(status.complete_transitions)&&double(status.actual_transition_count)==20000&& ...
    double(status.actual_state_sample_count)==20001&&logical(old.score_run_valid)&& ...
    ~logical(old.score_completion_flag_consistent)&&numel(log.time)==20001&& ...
    double(log.last_transition)==20000&&double(log.actual_transition_count)==20000&& ...
    double(log.actual_state_sample_count)==20001&&~logical(log.complete_transitions)&& ...
    all(log.state_is_finite(:))&&all(log.transition_is_finite(:))&& ...
    all(isfinite(double(log.state(:)))), ...
    'GHP7:FalseCompletionMarker','The false marker does not meet the expected full-trace/finite evidence.');

later=status_rows(c5(strcmpi({c5.source_lock_sha256},lockV5Sha)));
physics=jsondecode(fileread(fullfile(taskRoot,'GHP7_C5_10_PHYSICS_REFERENCE_REUSE_MANIFEST_v1.json')));
assert(all([later.complete_flag])&&all([later.transition_count]==20000)&& ...
    all(strcmpi({physics.records.candidate_source_lock_sha256},lockV5Sha))&& ...
    all([physics.records.complete_transitions]==20000), ...
    'GHP7:V5Control','V5-source comparison controls do not show complete run markers.');

result=struct('schema','DL1018_C5_RBF_COMPLETION_MARKER_ROOT_CAUSE_V1', ...
    'status','PASS','plant_invoked',false,'test_data_read',false, ...
    'classification','IMPLEMENTATION_ERROR_IN_COMPLETION_MARKER', ...
    'affected_scene',char(old.scene_id),'affected_raw_sha256',rawSha, ...
    'affected_source_lock_sha256',lockV4Sha,'v4_runner_sha256',sha256_file(runnerV4Path), ...
    'v4_expression','n=N-1; complete=(last==n-1)', ...
    'v5_source_lock_sha256',lockV5Sha,'v5_runner_sha256',sha256_file(runnerV5Path), ...
    'v5_expression','n=N-1; complete=(last==n)', ...
    'expected_transitions',20000,'observed_last_transition',double(log.last_transition), ...
    'observed_state_samples',numel(log.time),'all_state_samples_finite',all(log.state_is_finite(:)), ...
    'all_transition_samples_finite',all(log.transition_is_finite(:)), ...
    'status_state',char(status.state),'status_value',char(status.status_value), ...
    'status_complete_flag',logical(status.complete_transitions), ...
    'score_completion_flag_consistent',logical(old.score_completion_flag_consistent), ...
    'v5_c5_rbf_control_rows',numel(later),'v5_c5_10_control_rows',numel(physics.records), ...
    'comparison_artifact_sha256',sha256_file(comparisonPath), ...
    'payload_manifest_sha256',sha256_file(payloadPath), ...
    'baseline_manifest_sha256',sha256_file(baselinePath));
jsonPath=fullfile(taskRoot,'C5_RBF_COMPLETION_FLAG_ROOT_CAUSE_v1.json');
assert(~isfile(jsonPath),'GHP7:NoOverwrite','Root-cause report already exists.');
write_json(jsonPath,result);
end

function rows=status_rows(records)
rows=repmat(struct('scene_id','','complete_flag',false,'transition_count',0),numel(records),1);
for i=1:numel(records)
    r=records(i);s=jsondecode(fileread(fullfile(char(r.attempt_dir),'run_status.json')));
    assert(strcmp(s.scene_id,char(r.scene_id))&&strcmp(s.state,'COMPLETED'), ...
        'GHP7:ControlStatus','A V5 control run status is invalid.');
    rows(i).scene_id=char(r.scene_id);rows(i).complete_flag=logical(s.complete_transitions);
    rows(i).transition_count=double(s.actual_transition_count);
end
end

function h=sha256_file(path)
fid=fopen(path,'rb');assert(fid>=0,'GHP7:HashOpen','Cannot open %s.',path);
closer=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true
    bytes=fread(fid,8*1024*1024,'*uint8');if isempty(bytes),break;end
    md.update(typecast(bytes(:),'int8'));
end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear closer;
end
function write_json(path,value)
fid=fopen(path,'w','n','UTF-8');assert(fid>=0,'GHP7:Write','Cannot write %s.',path);
closer=onCleanup(@()fclose(fid));
fwrite(fid,unicode2native([jsonencode(value,'PrettyPrint',true) newline],'UTF-8'),'uint8');clear closer;
end
