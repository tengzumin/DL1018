    'created_utc',utcNow(),'plant_calls_authorized',6,'candidate_arm_id','DL_TCN', ...
    'geometry_arm','ACTIVE','test_data_read',false, ...
    'runtime_variable_inertia_reconstruction_enabled',false, ...
    'candidate_source_lock_sha256',sourceLockSha,'score_script_sha256',sha256_file(scorePath), ...
    'taskbook_sha256',sha256_file(taskbookPath), ...
    'amendment02_sha256',sha256_file(amendment02Path), ...
    'amendment03_sha256',sha256_file(amendment03Path), ...
    'amendment04_sha256',sha256_file(amendment04Path), ...
    'amendment05_sha256',sha256_file(amendment05Path), ...
    'freeze_script_sha256',sha256_file(freezeScriptPath), ...
