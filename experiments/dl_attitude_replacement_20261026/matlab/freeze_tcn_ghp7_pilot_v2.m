    strcmp(comparison.status,'PASS')&&comparison.metrics_independently_recomputed_from_raw&& ...
    ~comparison.plant_invoked&&~comparison.test_data_read&&strcmp(completionAudit.status,'PASS')&& ...
    ~completionAudit.plant_invoked&&strcmp(smoke.status,'PASS')&&~smoke.plant_invoked&& ...
    strcmp(runnerAudit.schema,'DL1018_TCN_TEACHER_RUNNER_V4_NO_PLANT_AUDIT_V1')&& ...
    strcmp(runnerAudit.status,'PASS')&&~runnerAudit.plant_invoked&&~runnerAudit.test_data_read&& ...
    runnerAudit.runner_matlab_file_count==49&& ...
    strcmp(trainingProgress.status,'PASS')&&trainingProgress.completed_steps==60000&& ...
    trainingConfig.optimizer_steps==60000&&strcmp(trainingConfig.status,'PASS')&& ...
