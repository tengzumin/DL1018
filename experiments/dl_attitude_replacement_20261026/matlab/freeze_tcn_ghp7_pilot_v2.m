function h=sha256_file(filePath)
fid=fopen(filePath,'rb');assert(fid>=0,'DLTCN:HashOpen','Cannot open %s.',filePath);
closer=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true
    bytes=fread(fid,8*1024*1024,'*uint8');if isempty(bytes),break;end
    md.update(typecast(bytes(:),'int8'));
end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear closer;
end
function write_json(outputPath,value)
fid=fopen(outputPath,'w','n','UTF-8');assert(fid>=0,'DLTCN:Write','Cannot write %s.',outputPath);
closer=onCleanup(@()fclose(fid));
fwrite(fid,unicode2native([jsonencode(value,'PrettyPrint',true) newline],'UTF-8'),'uint8');clear closer;
end
function s=utcNow()
s=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z'''));
end
