function report=audit_tcn_teacher_runner_v4_no_plant()
% Static no-Plant audit of the exact v4 teacher-distillation candidate tree.
researchRoot=fileparts(fileparts(mfilename('fullpath')));
runnerV3=char(java.io.File(fullfile(researchRoot,'pilot_runner_v3_teacher_distill', ...
    'candidate_runner_work','matlab')).getCanonicalPath());
runnerV4=char(java.io.File(fullfile(researchRoot,'pilot_runner_v4_teacher_distill', ...
    'candidate_runner_work','matlab')).getCanonicalPath());
priorPath=fullfile(researchRoot,'MATLAB_NO_PLANT_RUNTIME_AUDIT_v3.json');
prior=jsondecode(fileread(priorPath));
assert(strcmp(prior.status,'PASS')&&~prior.plant_called&&~prior.test_data_read, ...
    'DLTCN:PriorAudit','The v3 shared-runtime audit is not a clean PASS.');

shared={'runtime/run_gate_holdout_closed_loop.m','runtime/make_gate_holdout_options.m', ...
    'runtime/gate_attitude_arm_spec.m','runtime/tcn_attitude_step_v1.m', ...
    'runtime/tcn_attitude_forward_v1.m'};
for i=1:numel(shared)
    a=fullfile(runnerV3,shared{i});b=fullfile(runnerV4,shared{i});
    assert(isfile(a)&&isfile(b)&&strcmpi(sha256_file(a),sha256_file(b)), ...
        'DLTCN:SharedRuntimeChanged','v4 changed an already-audited runtime file: %s.',shared{i});
end

prepPath=fullfile(runnerV4,'runtime','prepare_gate_candidate_no_plant.m');
runPath=fullfile(runnerV4,'runtime','run_tcn_candidate_gate_attempt.m');
prepText=fileread(prepPath);runText=fileread(runPath);
assert(contains(prepText,'training_v2_teacher_distill')&& ...
    contains(prepText,'TRAINING_RELEASE_v3.json')&& ...
    contains(prepText,'DATASET_MANIFEST_v2.json')&& ...
    contains(prepText,'TEACHER_DATASET_V2_VAL_AUDIT.json')&& ...
    contains(prepText,'MATLAB_PYTHON_PARITY_V2.json')&& ...
    contains(prepText,'trainingProgress.completed_steps==60000')&& ...
    contains(prepText,'parity.max_abs_error<=parity.tolerance')&& ...
    ~contains(prepText,'run_gate_holdout_closed_loop('), ...
    'DLTCN:PrepareBinding','v4 no-Plant preparer does not bind the teacher release or calls the Plant runner.');
assert(contains(runText,'PILOT_RELEASE_v2.json')&& ...
    contains(runText,'CANDIDATE_SOURCE_LOCK_v2.json')&& ...
    contains(runText,'double(release.plant_calls_authorized)==6')&& ...
    contains(runText,'pilot_runs_v2')&&contains(runText,'run_gate_holdout_closed_loop(prepared.scene'), ...
    'DLTCN:RunBinding','v4 Plant wrapper is missing its release, source-lock, scope, or output gates.');

changed={prepPath,runPath};diagnostics=cell(numel(changed),1);
for i=1:numel(changed)
    d=checkcode(changed{i},'-id');
    assert(isempty(d),'DLTCN:CodeAnalyzer','Code Analyzer reported an issue in %s.',changed{i});
    diagnostics{i}=struct('file',changed{i},'diagnostic_count',numel(d));
end
filesV3=dir(fullfile(runnerV3,'**','*.m'));filesV4=dir(fullfile(runnerV4,'**','*.m'));
assert(numel(filesV3)==49&&numel(filesV4)==49, ...
    'DLTCN:SourceCount','Expected v3 and v4 trees to contain 49 MATLAB files each.');
relativeV3=strings(numel(filesV3),1);relativeV4=strings(numel(filesV4),1);
for i=1:numel(filesV3)
    relativeV3(i)=strrep([strrep(filesV3(i).folder,[runnerV3 filesep],'') filesep filesV3(i).name],filesep,'/');
    relativeV4(i)=strrep([strrep(filesV4(i).folder,[runnerV4 filesep],'') filesep filesV4(i).name],filesep,'/');
end
[relativeV3,order3]=sort(lower(relativeV3));filesV3=filesV3(order3);
[relativeV4,order4]=sort(lower(relativeV4));filesV4=filesV4(order4);
assert(isequal(relativeV3,relativeV4),'DLTCN:TreeShape','v3 and v4 MATLAB source trees differ in file paths.');
changedFiles=strings(0,1);
for i=1:numel(filesV4)
    p3=fullfile(filesV3(i).folder,filesV3(i).name);
    p4=fullfile(filesV4(i).folder,filesV4(i).name);
    if ~strcmpi(sha256_file(p3),sha256_file(p4)),changedFiles(end+1,1)=relativeV4(i);end %#ok<AGROW>
end
expectedChanges=["runtime/prepare_gate_candidate_no_plant.m"; ...
    "runtime/run_tcn_candidate_gate_attempt.m"];
assert(isequal(sort(changedFiles),sort(expectedChanges)), ...
    'DLTCN:UnexpectedTreeDiff','v4 contains an unreviewed MATLAB file change.');
report=struct('schema','DL1018_TCN_TEACHER_RUNNER_V4_NO_PLANT_AUDIT_V1', ...
    'status','PASS','plant_invoked',false,'test_data_read',false, ...
    'shared_runtime_files_hash_matched_v3',{shared}, ...
    'changed_v4_files_checked',{diagnostics},'changed_v4_relative_files',{cellstr(changedFiles)}, ...
    'runner_matlab_file_count',numel(filesV4), ...
    'prepare_binds_teacher_training_parity',true,'wrapper_binds_release_source_lock_scope',true, ...
    'created_utc',char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z''')));
outPath=fullfile(researchRoot,'MATLAB_NO_PLANT_AUDIT_TCN_V4_v1.json');
fid=fopen(outPath,'w');assert(fid>=0,'DLTCN:AuditOutput','Could not write v4 audit report.');
closer=onCleanup(@()fclose(fid));
fwrite(fid,[jsonencode(report,'PrettyPrint',true) newline],'char');clear closer;
fprintf('TCN_V4_NO_PLANT_AUDIT=PASS FILES=%d CHANGED=%d PLANT_INVOKED=false\n', ...
    numel(filesV4),numel(changedFiles));
end

function h=sha256_file(p)
fid=fopen(p,'rb');assert(fid>=0,'DLTCN:HashOpen','Cannot read %s.',p);
closer=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true
    b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end
    md.update(typecast(b(:),'int8'));
end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear closer;
end
