function report=audit_tcn_runtime_feature_contract_v3()
% Static, no-Plant audit for the teacher-distilled TCN runtime adapter.
taskRoot=fileparts(fileparts(mfilename('fullpath')));
runnerRoot=fullfile(taskRoot,'pilot_runner_v3_teacher_distill','candidate_runner_work','matlab');
runtime=fullfile(runnerRoot,'runtime');
files={fullfile(runtime,'run_gate_holdout_closed_loop.m'), ...
    fullfile(runtime,'make_gate_holdout_options.m'), ...
    fullfile(runtime,'gate_attitude_arm_spec.m'), ...
    fullfile(runtime,'tcn_attitude_step_v1.m'), ...
    fullfile(runtime,'tcn_attitude_forward_v1.m'), ...
    fullfile(taskRoot,'..','..','matlab','core','attitude_bs_step.m')};
assert(all(cellfun(@isfile,files)),'DLTCN:AuditFiles','A required source file is missing.');

runnerText=fileread(files{1});
armText=fileread(files{3});
stepText=fileread(files{4});
assert(contains(runnerText,'double(ai0.nominal_moment(:))')&& ...
    ~contains(runnerText,'double(ai0.nominal_body_angular_acceleration(:))'), ...
    'DLTCN:FeatureContract','Runtime input is not aligned to nominal BS body torque.');
assert(contains(runnerText, ...
    "'J0',double(cfg.attitude_replacement.J0_controller_fixed_kgm2)")&& ...
    contains(stepText,'estimateTorque=J0*(beta*clipped)'), ...
    'DLTCN:TorqueMap','The fixed controller J0 torque mapping changed.');
assert(contains(armText,"'rbf_enabled',false")&& ...
    contains(runnerText,"'time_varying_inertia_reconstruction_used',false")&& ...
    contains(runnerText,'log.tcn_variable_inertia_reconstruction_used=false'), ...
    'DLTCN:Isolation','TCN arm must disable RBF and time-varying inertia reconstruction.');

diagnostics=cell(numel(files),1);
for i=1:numel(files)
    d=checkcode(files{i},'-id');
    diagnostics{i}=struct('file',files{i},'diagnostic_count',numel(d), ...
        'diagnostic_ids',{{d.id}});
end
report=struct('schema','DL1018_CAUSAL_TCN_RUNTIME_STATIC_AUDIT_V1', ...
    'status','PASS','created_local',char(datetime('now','TimeZone','local')), ...
    'matlab_release',version('-release'),'files_checked',{files}, ...
    'feature_order',{{'attitude_error_euler_rad_x3','body_rate_rad_s_x3', ...
        'nominal_bs_body_torque_Nm_x3','morph_command_x4'}}, ...
    'fixed_J0_output_map','J0 * beta * clip(TCN_acceleration_action)', ...
    'rbf_output_enabled',false,'rbf_update_enabled',false, ...
    'time_varying_inertia_reconstruction_used',false, ...
    'plant_called',false,'simulation_started',false,'test_data_read',false, ...
    'diagnostics',{diagnostics});
outPath=fullfile(taskRoot,'MATLAB_NO_PLANT_RUNTIME_AUDIT_v3.json');
fid=fopen(outPath,'w');
assert(fid>=0,'DLTCN:AuditOutput','Could not open audit report output.');
cleanup=onCleanup(@()fclose(fid));
fwrite(fid,jsonencode(report,'PrettyPrint',true),'char');
fwrite(fid,newline,'char');
fprintf('%s\n',jsonencode(struct('status',report.status,'files_checked',numel(files), ...
    'plant_called',report.plant_called,'report',outPath)));
end
