function result=audit_c5_10_physics_comparison_v1()
% Independently rescore the existing six-scene B/C5_RBF/C5_10 pilot raws.
taskRoot=fileparts(fileparts(mfilename('fullpath')));
payloadPath=fullfile(taskRoot,'GHP7_PILOT_PAYLOAD_MANIFEST_v1.json');
baselinePath=fullfile(taskRoot,'GHP7_BASELINE_REUSE_MANIFEST_v1.json');
physicsPath=fullfile(taskRoot,'GHP7_C5_10_PHYSICS_REFERENCE_REUSE_MANIFEST_v1.json');
payload=jsondecode(fileread(payloadPath));baseline=jsondecode(fileread(baselinePath));
physics=jsondecode(fileread(physicsPath));
assert(strcmp(payload.status,'PASS')&&payload.scene_count==6&&~payload.tests_data_read&& ...
    strcmp(baseline.status,'PASS')&&baseline.record_count==12&&~baseline.test_data_read&& ...
    strcmp(physics.status,'PASS')&&physics.scene_count==6&&~physics.test_data_read&& ...
    physics.inertia_reconstruction_used&&~physics.observer_enabled&& ...
    ~physics.rbf_attitude_output_enabled&&~physics.rbf_attitude_update_enabled, ...
    'GHP7:ManifestGate','Pilot comparison manifests do not pass the frozen scope checks.');
assert(isequal(sort(string({payload.records.scene_id})), ...
    sort(string({physics.records.scene_id}))), ...
    'GHP7:SceneSet','Physics pilot scenes differ from the frozen payload set.');

rows=repmat(empty_row(),6,1);
for i=1:6
    p=payload.records(i);row=empty_row();row.scene_id=char(p.scene_id);
    row.payload_sha256=char(p.payload_file_sha256);row.r_task_sha256=char(p.r_task_sha256);
    b=baseline.records(strcmp({baseline.records.scene_id},row.scene_id)&strcmp({baseline.records.runner},'B'));
    c=baseline.records(strcmp({baseline.records.scene_id},row.scene_id)&strcmp({baseline.records.attitude_arm},'C5_RBF'));
    f=physics.records(strcmp({physics.records.scene_id},row.scene_id));
    assert(isscalar(b)&&isscalar(c)&&isscalar(f)&& ...
        strcmpi(char(b.scene_payload_sha256),row.payload_sha256)&& ...
        strcmpi(char(c.scene_payload_sha256),row.payload_sha256)&& ...
        strcmpi(char(f.scene_payload_sha256),row.payload_sha256)&& ...
        strcmpi(char(b.r_task_sha256),row.r_task_sha256)&& ...
        strcmpi(char(c.r_task_sha256),row.r_task_sha256)&& ...
        strcmpi(char(f.r_task_sha256),row.r_task_sha256), ...
        'GHP7:PairIdentity','A paired method has a different payload or R_task: %s.',row.scene_id);
    assert(b.score_run_valid&&c.score_run_valid, ...
        'GHP7:InvalidBaseline','A paired baseline raw is not score-valid: %s.',row.scene_id);

    mb=score_raw(char(b.raw_path),char(b.raw_sha256),row.scene_id,row.r_task_sha256,char(b.attempt_dir));
    mc=score_raw(char(c.raw_path),char(c.raw_sha256),row.scene_id,row.r_task_sha256,char(c.attempt_dir));
    mf=score_raw(char(f.raw_path),char(f.raw_sha256),row.scene_id,row.r_task_sha256,char(f.attempt_dir));
    metricDiffs=[abs(mb.q0_20_m-double(b.q0_20_m)), ...
        abs(mb.so3_rmse_rad-double(b.so3_rmse_rad)), ...
        abs(mc.q0_20_m-double(c.q0_20_m)), ...
        abs(mc.so3_rmse_rad-double(c.so3_rmse_rad)), ...
        abs(mf.q0_20_m-double(f.q0_20_m)), ...
        abs(mf.q8_12_m-double(f.q8_12_m)), ...
        abs(mf.so3_rmse_rad-double(f.so3_rmse_rad))];
    assert(all(metricDiffs<=1e-10), ...
        'GHP7:MetricMismatch','Independent raw rescore differs from a source manifest: %s; diffs=%s.', ...
        row.scene_id,mat2str(metricDiffs,16));

    row.B_q0_20_m=mb.q0_20_m;row.B_q8_12_m=mb.q8_12_m;row.B_so3_rmse_rad=mb.so3_rmse_rad;
    row.C5_RBF_q0_20_m=mc.q0_20_m;row.C5_RBF_q8_12_m=mc.q8_12_m;
    row.C5_RBF_so3_rmse_rad=mc.so3_rmse_rad;
    row.B_application_feasible=logical(b.application_feasible);
    row.C5_RBF_application_feasible=logical(c.application_feasible);
    row.C5_RBF_completion_flag_consistent=logical(c.score_completion_flag_consistent);
    row.C5_RBF_run_status_complete_flag=mc.run_status_complete_flag;
    row.C5_RBF_raw_log_complete_flag=mc.raw_log_complete_flag;
    row.C5_RBF_status_vs_raw_flag_consistent=mc.status_vs_raw_flag_consistent;
    row.C5_RBF_raw_trace_complete=mc.timeline_complete;
    row.C5_RBF_false_flag_full_trace=~mc.run_status_complete_flag&&mc.timeline_complete;
    row.C5_RBF_state_finite_all=mc.state_finite_all;
    row.C5_RBF_transition_finite_all=mc.transition_finite_all;
    row.C5_10_q0_20_m=mf.q0_20_m;row.C5_10_q8_12_m=mf.q8_12_m;
    row.C5_10_so3_rmse_rad=mf.so3_rmse_rad;
    row.C5_10_application_feasible=logical(f.application_feasible);
    row.win_C5_10_position_vs_B=mf.q0_20_m<mb.q0_20_m-1e-12;
    row.win_C5_10_attitude_vs_B=mf.so3_rmse_rad<mb.so3_rmse_rad-1e-12;
    row.win_C5_10_position_vs_C5_RBF=mf.q0_20_m<mc.q0_20_m-1e-12;
    row.win_C5_10_attitude_vs_C5_RBF=mf.so3_rmse_rad<mc.so3_rmse_rad-1e-12;
    row.B_raw_sha256=char(b.raw_sha256);row.C5_RBF_raw_sha256=char(c.raw_sha256);
    row.C5_10_raw_sha256=char(f.raw_sha256);rows(i)=row;
end

summary=struct('scene_count',6, ...
    'mean_Q0_20_B_m',mean([rows.B_q0_20_m]), ...
    'mean_Q0_20_C5_RBF_m',mean([rows.C5_RBF_q0_20_m]), ...
    'mean_Q0_20_C5_10_m',mean([rows.C5_10_q0_20_m]), ...
    'mean_Q8_12_B_m',mean([rows.B_q8_12_m]), ...
    'mean_Q8_12_C5_RBF_m',mean([rows.C5_RBF_q8_12_m]), ...
    'mean_Q8_12_C5_10_m',mean([rows.C5_10_q8_12_m]), ...
    'mean_SO3_B_rad',mean([rows.B_so3_rmse_rad]), ...
    'mean_SO3_C5_RBF_rad',mean([rows.C5_RBF_so3_rmse_rad]), ...
    'mean_SO3_C5_10_rad',mean([rows.C5_10_so3_rmse_rad]), ...
    'C5_10_position_wins_vs_B',sum([rows.win_C5_10_position_vs_B]), ...
    'C5_10_attitude_wins_vs_B',sum([rows.win_C5_10_attitude_vs_B]), ...
    'C5_10_position_wins_vs_C5_RBF',sum([rows.win_C5_10_position_vs_C5_RBF]), ...
    'C5_10_attitude_wins_vs_C5_RBF',sum([rows.win_C5_10_attitude_vs_C5_RBF]), ...
    'B_feasible_scenes',sum([rows.B_application_feasible]), ...
    'C5_RBF_feasible_scenes',sum([rows.C5_RBF_application_feasible]), ...
    'C5_10_feasible_scenes',sum([rows.C5_10_application_feasible]), ...
    'C5_RBF_flag_mismatch_scenes',sum(~[rows.C5_RBF_completion_flag_consistent]), ...
    'C5_RBF_status_raw_flag_mismatch_scenes',sum(~[rows.C5_RBF_status_vs_raw_flag_consistent]), ...
    'C5_RBF_false_flag_full_trace_scenes',sum([rows.C5_RBF_false_flag_full_trace]), ...
    'C5_RBF_fully_finite_state_and_transition_scenes',sum([rows.C5_RBF_state_finite_all]& ...
        [rows.C5_RBF_transition_finite_all]), ...
    'C5_RBF_raw_trace_complete_scenes',sum([rows.C5_RBF_raw_trace_complete]));
result=struct('schema','DL1018_C5_10_PHYSICS_PAIRED_RESCORING_V1', ...
    'status','PASS','plant_invoked',false,'test_data_read',false, ...
    'metrics_independently_recomputed_from_raw',true, ...
    'metric_tolerance_m_rad',1e-10,'win_tolerance_m_rad',1e-12, ...
    'physics_method_contract',char(physics.method_contract), ...
    'payload_manifest_sha256',sha256_file(payloadPath), ...
    'baseline_manifest_sha256',sha256_file(baselinePath), ...
    'physics_manifest_sha256',sha256_file(physicsPath), ...
    'summary',summary,'rows',rows);
jsonPath=fullfile(taskRoot,'C5_10_PHYSICS_PAIRED_COMPARISON_v1.json');
csvPath=fullfile(taskRoot,'C5_10_PHYSICS_PAIRED_COMPARISON_v1.csv');
assert(~isfile(jsonPath)&&~isfile(csvPath),'GHP7:NoOverwrite','Comparison output already exists.');
write_json(jsonPath,result);writetable(struct2table(rows),csvPath);
end

function m=score_raw(path,expectedSha,sceneId,rTaskSha,attemptDir)
assert(isfile(path)&&strcmpi(sha256_file(path),expectedSha), ...
    'GHP7:RawHash','Raw file is missing or changed: %s.',path);
statusPath=fullfile(attemptDir,'run_status.json');
assert(isfile(statusPath),'GHP7:StatusMissing','Run status is missing: %s.',statusPath);
status=jsondecode(fileread(statusPath));
assert(strcmp(char(status.state),'COMPLETED')&&strcmp(char(status.scene_id),sceneId)&& ...
    strcmp(char(status.status_value),'STABLE')&&isempty(char(status.safety_stop_reason))&& ...
    double(status.actual_transition_count)==20000&&double(status.actual_state_sample_count)==20001&& ...
    strcmpi(char(status.raw_output_sha256),expectedSha), ...
    'GHP7:StatusInvalid','Run status or completion counts are invalid: %s.',sceneId);
s=load(path,'log','scene');log=s.log;scene=s.scene;
assert(strcmp(char(scene.scene_id),sceneId)&& ...
    strcmpi(paired_sha256_double(double(scene.R_task)),rTaskSha), ...
    'GHP7:RawIdentity','Raw scene/R_task identity mismatch: %s.',sceneId);
time=double(log.time(:));X=double(log.state);ref=double(log.reference.position);
transitionTime=double(log.transition_time(:));sceneTime=double(scene.time(:));n=numel(time);
assert(size(X,1)==n&&size(X,2)>=9&&isequal(size(ref),[n,3])&& ...
    n==20001&&numel(transitionTime)==20000&&numel(sceneTime)==n&& ...
    max(abs(time-sceneTime))<=1e-10&& ...
    max(abs(transitionTime-sceneTime(1:end-1)))<=1e-10&&all(isfinite(X(:)))&& ...
    all(isfinite(ref(:)))&&double(log.last_transition)==20000, ...
    'GHP7:RawTimeline','Raw timeline is incomplete or invalid: %s.',sceneId);
err=X(:,1:3)-ref;m.q0_20_m=sqrt(mean(sum(err.^2,2)));
q=time>=8-1e-10&time<=12+1e-10;assert(sum(q)==4001,'GHP7:Window','Q8-12 window is invalid.');
m.q8_12_m=sqrt(mean(sum(err(q,:).^2,2)));
Rtask=double(scene.R_task);so3=zeros(n,1);
assert(size(Rtask,3)>=n,'GHP7:AttitudeTimeline','R_task is shorter than raw state.');
for k=1:n
    R=rotation_zyx(double(X(k,7:9)).');D=Rtask(:,:,k)'*R;
    so3(k)=acos(max(min((trace(D)-1)/2,1),-1));
end
m.so3_rmse_rad=sqrt(mean(so3.^2));
m.timeline_complete=true;
m.run_status_complete_flag=logical(status.complete_transitions);
m.raw_log_complete_flag=isfield(log,'complete_transitions')&&logical(log.complete_transitions);
m.status_vs_raw_flag_consistent=m.run_status_complete_flag==m.raw_log_complete_flag;
m.state_finite_all=isfield(log,'state_is_finite')&&all(log.state_is_finite(:));
m.transition_finite_all=isfield(log,'transition_is_finite')&&all(log.transition_is_finite(:));
end

function row=empty_row()
row=struct('scene_id','','payload_sha256','','r_task_sha256','', ...
    'B_q0_20_m',NaN,'B_q8_12_m',NaN,'B_so3_rmse_rad',NaN, ...
    'C5_RBF_q0_20_m',NaN,'C5_RBF_q8_12_m',NaN,'C5_RBF_so3_rmse_rad',NaN, ...
    'B_application_feasible',false,'C5_RBF_application_feasible',false, ...
    'C5_RBF_completion_flag_consistent',false, ...
    'C5_RBF_run_status_complete_flag',false,'C5_RBF_raw_log_complete_flag',false, ...
    'C5_RBF_status_vs_raw_flag_consistent',false,'C5_RBF_raw_trace_complete',false, ...
    'C5_RBF_false_flag_full_trace',false,'C5_RBF_state_finite_all',false, ...
    'C5_RBF_transition_finite_all',false, ...
    'C5_10_q0_20_m',NaN,'C5_10_q8_12_m',NaN,'C5_10_so3_rmse_rad',NaN, ...
    'C5_10_application_feasible',false, ...
    'win_C5_10_position_vs_B',false,'win_C5_10_attitude_vs_B',false, ...
    'win_C5_10_position_vs_C5_RBF',false,'win_C5_10_attitude_vs_C5_RBF',false, ...
    'B_raw_sha256','','C5_RBF_raw_sha256','','C5_10_raw_sha256','');
end

function R=rotation_zyx(e)
p=e(1);q=e(2);y=e(3);
R=[cos(y)*cos(q),cos(y)*sin(q)*sin(p)-sin(y)*cos(p),cos(y)*sin(q)*cos(p)+sin(y)*sin(p); ...
    sin(y)*cos(q),sin(y)*sin(q)*sin(p)+cos(y)*cos(p),sin(y)*sin(q)*cos(p)-cos(y)*sin(p); ...
    -sin(q),cos(q)*sin(p),cos(q)*cos(p)];
end
function h=paired_sha256_double(a)
md=java.security.MessageDigest.getInstance('SHA-256');md.update(typecast(double(a(:)),'uint8'));
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
function h=sha256_file(path)
fid=fopen(path,'rb');assert(fid>=0,'GHP7:HashOpen','Cannot open %s.',path);
closer=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true
    bytes=fread(fid,8*1024*1024,'*uint8');if isempty(bytes),break;end
    md.update(typecast(bytes(:),'int8'));
end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear closer;
end
function write_json(path,value)
fid=fopen(path,'w','n','UTF-8');assert(fid>=0,'GHP7:Write','Cannot write %s.',path);
closer=onCleanup(@()fclose(fid));
fwrite(fid,unicode2native([jsonencode(value,'PrettyPrint',true) newline],'UTF-8'),'uint8');
clear closer;
end
