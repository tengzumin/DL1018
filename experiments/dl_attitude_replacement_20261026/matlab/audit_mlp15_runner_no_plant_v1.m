function report=audit_mlp15_runner_no_plant_v1()
% Plant-free source, identity, and one-step audit for the isolated MLP15 runner.
researchRoot=fileparts(fileparts(mfilename('fullpath')));
projectRoot=fileparts(fileparts(researchRoot));
runnerRoot=fullfile(researchRoot,'pilot_runner_mlp15_v1','candidate_runner_work');
runnerMatlab=fullfile(runnerRoot,'matlab');
v4Matlab=fullfile(researchRoot,'pilot_runner_v4_teacher_distill', ...
    'candidate_runner_work','matlab');
mlpFiles={'runtime/gate_attitude_arm_spec.m','runtime/make_gate_holdout_options.m', ...
    'runtime/prepare_gate_candidate_no_plant.m','runtime/run_gate_holdout_closed_loop.m', ...
    'runtime/run_mlp15_candidate_gate_attempt.m','runtime/mlp15_attitude_step_v1.m', ...
    'runtime/mlp15_attitude_forward_v1.m'};
for i=1:numel(mlpFiles)
    assert(isfile(fullfile(runnerMatlab,mlpFiles{i})), ...
        'DLMLP15:MissingSource','Missing MLP15 runner source: %s.',mlpFiles{i});
end
reportPath=fullfile(researchRoot,'MATLAB_NO_PLANT_AUDIT_MLP15_v1.json');
assert(~isfile(reportPath),'DLMLP15:NoOverwrite','MLP15 runner audit already exists.');

shared={'core/attitude_bs_step.m','core/arm_mass_properties.m', ...
    'core/distributed_mass_properties.m','runtime/run_gate_holdout_closed_loop.m', ...
    'runtime/make_gate_holdout_options.m','runtime/gate_attitude_arm_spec.m'};
for i=1:numel(shared)
    if ismember(shared{i},{'runtime/run_gate_holdout_closed_loop.m', ...
            'runtime/make_gate_holdout_options.m','runtime/gate_attitude_arm_spec.m'})
        continue
    end
    assert(strcmpi(sha256_file(fullfile(v4Matlab,shared{i})), ...
        sha256_file(fullfile(runnerMatlab,shared{i}))), ...
        'DLMLP15:SharedSource','Unexpected change to shared file %s.',shared{i});
end

addpath(fullfile(runnerMatlab,'runtime'));
activate_paired_runner();
spec=gate_holdout_no_plant_arm_check();
assert(isequal(spec.rbf_enabled,[true false])&& ...
    all(~spec.inertia_reconstruction_enabled)&&all(~spec.feedforward_enabled)&& ...
    all(~spec.observer_enabled),'DLMLP15:ArmIsolation','MLP15 isolation mapping failed.');
payloadManifest=jsondecode(fileread(fullfile(researchRoot,'GHP7_PILOT_PAYLOAD_MANIFEST_v1.json')));
prepared=prepare_gate_candidate_no_plant(payloadManifest.records(1).payload_path,'DL_MLP15','ACTIVE');
assert(strcmp(prepared.scene.scene_id,payloadManifest.records(1).scene_id)&& ...
    prepared.mlp15_best_step==59000&&isfield(prepared.opts,'mlp15_attitude_model')&& ...
    ~prepared.opts.rbf_attitude_enabled&&~prepared.opts.rbf_attitude_output_enabled&& ...
    ~prepared.opts.rbf_attitude_update_enabled, ...
    'DLMLP15:PreparedCandidate','Prepared candidate or paired C5 source identity is invalid.');
vectorPath=fullfile(researchRoot,'mlp15_formal_v1','run_v1','parity_vector_v1.mat');
vector=load(vectorPath,'input_raw_window');
input=struct('feature',double(vector.input_raw_window(end,:)).', ...
    'J0',double(prepared.cfg.attitude_replacement.J0_controller_fixed_kgm2), ...
    'beta',0.5,'dmax',double(prepared.cfg.rbf.attitude.dmax(:)));
[memory,~]=mlp15_attitude_step_v1('init',struct,struct,prepared.opts.mlp15_attitude_model);
[memory,out]=mlp15_attitude_step_v1('step',memory,input,prepared.opts.mlp15_attitude_model);
assert(memory.event_count==1&&all(isfinite(out.estimateTorque_Nm))&& ...
    all(isfinite(out.raw_residual_rad_s2))&&~isfield(input,'Jhat')&&~isfield(input,'Jdot_hat'), ...
    'DLMLP15:StepSmoke','MLP15 one-event no-Plant step failed.');

changed={...
    fullfile(runnerMatlab,'runtime','gate_attitude_arm_spec.m'), ...
    fullfile(runnerMatlab,'runtime','make_gate_holdout_options.m'), ...
    fullfile(runnerMatlab,'runtime','prepare_gate_candidate_no_plant.m'), ...
    fullfile(runnerMatlab,'runtime','run_gate_holdout_closed_loop.m'), ...
    fullfile(runnerMatlab,'runtime','run_mlp15_candidate_gate_attempt.m'), ...
    fullfile(runnerMatlab,'runtime','mlp15_attitude_step_v1.m'), ...
    fullfile(runnerMatlab,'runtime','mlp15_attitude_forward_v1.m')};
diagnosticCounts=zeros(numel(changed),1);
for i=1:numel(changed)
    diagnosticCounts(i)=numel(checkcode(changed{i},'-id'));
end
files=dir(fullfile(runnerMatlab,'**','*.m'));
assert(numel(files)==52,'DLMLP15:SourceCount','Expected 52 frozen runner MATLAB files.');
scorePath=fullfile(researchRoot,'matlab','score_mlp15_ghp7_pilot_v1.m');
assert(isempty(checkcode(scorePath,'-id')),'DLMLP15:ScorerCodeAnalyzer', ...
    'MLP15 scorer has MATLAB Code Analyzer diagnostics.');
report=struct('schema','DL1018_MLP15_GHP7_NO_PLANT_AUDIT_V1', ...
    'status','PASS','plant_invoked',false,'test_data_read',false, ...
    'runner_matlab_file_count',numel(files),'changed_source_diagnostic_counts',diagnosticCounts.', ...
    'source_hashes_checked',true,'c5_position_identity_checked',true, ...
    'candidate_arm','DL_MLP15','rbf_output_enabled',false,'rbf_update_enabled',false, ...
    'inertia_reconstruction_enabled',false,'observer_enabled',false, ...
    'single_step_smoke_passed',true,'screen_audit_sha256',sha256_file( ...
        fullfile(researchRoot,'architecture_screen_v1','SCREEN_AUDIT_v1.json')), ...
    'checkpoint_audit_sha256',sha256_file(fullfile(researchRoot, ...
        'mlp15_formal_v1','run_v1','MLP15_CHECKPOINT_AUDIT_v1.json')), ...
    'parity_audit_sha256',sha256_file(fullfile(researchRoot, ...
        'mlp15_formal_v1','run_v1','MATLAB_PARITY_AUDIT_v1.json')), ...
    'created_utc',char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z''')));
fid=fopen(reportPath,'w');assert(fid>=0,'DLMLP15:AuditOutput','Cannot write no-Plant audit.');
closer=onCleanup(@()fclose(fid));fwrite(fid,[jsonencode(report,'PrettyPrint',true) newline],'char');clear closer;
end

function h=sha256_file(p)
fid=fopen(p,'rb');assert(fid>=0,'DLMLP15:HashOpen','Cannot hash %s.',p);
closer=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear closer;
end
