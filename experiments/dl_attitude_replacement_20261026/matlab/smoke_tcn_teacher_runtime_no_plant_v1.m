function result=smoke_tcn_teacher_runtime_no_plant_v1()
% Exercise the frozen TCN step interface with synthetic weights, without Plant.
taskRoot=fileparts(fileparts(mfilename('fullpath')));
runtimeRoot=fullfile(taskRoot,'pilot_runner_v4_teacher_distill', ...
    'candidate_runner_work','matlab','runtime');
addpath(runtimeRoot);
cleanup=onCleanup(@()rmpath(runtimeRoot));
arm=gate_holdout_no_plant_arm_check();
assert(~arm.plant_invoked&&isequal(arm.rbf_enabled,[true false])&& ...
    ~any(arm.inertia_reconstruction_enabled)&&~any(arm.feedforward_enabled)&& ...
    ~any(arm.observer_enabled), ...
    'DLTCN:ArmMapping','DL_TCN arm unexpectedly enables RBF/physics/observer.');

model=struct('input_mean',zeros(13,1),'input_std',ones(13,1), ...
    'target_rms',ones(3,1),'input_weight',zeros(32,13), ...
    'input_bias',zeros(32,1),'conv1_weight',zeros(32,32,3), ...
    'conv1_bias',zeros(32,1),'conv2_weight',zeros(32,32,3), ...
    'conv2_bias',zeros(32,1),'conv3_weight',zeros(32,32,3), ...
    'conv3_bias',zeros(32,1),'head_weight',zeros(3,32), ...
    'head_bias',ones(3,1));
[memory,~]=tcn_attitude_step_v1('init',[],[],model);
input=struct('feature',zeros(13,1),'J0',diag([2,3,4]), ...
    'beta',0.5,'dmax',0.1*ones(3,1));
[memory,out]=tcn_attitude_step_v1('step',memory,input,model);
expectedTorque=[0.1;0.15;0.2];
assert(max(abs(out.estimateTorque_Nm-expectedTorque))<1e-12&& ...
    memory.event_count==1&&~isfield(input,'Jhat')&&~isfield(input,'Jdot'), ...
    'DLTCN:TorqueMapping','Synthetic TCN action/J0 mapping failed.');

result=struct('schema','DL1018_TCN_NO_PLANT_RUNTIME_SMOKE_V1', ...
    'status','PASS','matlab_version',version,'plant_invoked',false, ...
    'synthetic_weights_only',true,'feature_dim',13,'fixed_J0_used',true, ...
    'time_varying_inertia_reconstruction_used',false, ...
    'rbf_output_enabled',false,'rbf_update_enabled',false, ...
    'observer_enabled',false,'feedforward_enabled',false, ...
    'expected_torque_Nm',expectedTorque(:).', ...
    'observed_torque_Nm',out.estimateTorque_Nm(:).', ...
    'history_count',memory.event_count, ...
    'source_sha256',struct( ...
        'arm_check',sha256_file(fullfile(runtimeRoot,'gate_holdout_no_plant_arm_check.m')), ...
        'arm_spec',sha256_file(fullfile(runtimeRoot,'gate_attitude_arm_spec.m')), ...
        'step',sha256_file(fullfile(runtimeRoot,'tcn_attitude_step_v1.m')), ...
        'forward',sha256_file(fullfile(runtimeRoot,'tcn_attitude_forward_v1.m'))));
outPath=fullfile(taskRoot,'MATLAB_NO_PLANT_TCN_STEP_SMOKE_v1.json');
assert(~isfile(outPath),'DLTCN:NoOverwrite','Smoke report already exists.');
fid=fopen(outPath,'w','n','UTF-8');assert(fid>=0,'DLTCN:Write','Cannot create smoke report.');
closer=onCleanup(@()fclose(fid));
fwrite(fid,unicode2native([jsonencode(result,'PrettyPrint',true) newline],'UTF-8'),'uint8');
clear closer cleanup;
end

function h=sha256_file(path)
fid=fopen(path,'rb');assert(fid>=0,'DLTCN:HashOpen','Cannot open %s.',path);
closer=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true
    bytes=fread(fid,8*1024*1024,'*uint8');
    if isempty(bytes),break;end
    md.update(typecast(bytes(:),'int8'));
end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
clear closer;
end
