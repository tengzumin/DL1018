function result=score_mlp15_ghp7_pilot_v2t()
% Score the six released DL_MLP15 calls against hash-bound B/C5_RBF/C5_10 rows.
researchRoot=fileparts(fileparts(mfilename('fullpath')));
projectRoot=fileparts(fileparts(researchRoot));
releasePath=fullfile(researchRoot,'MLP15_PILOT_RELEASE_v2.json');
payloadPath=fullfile(researchRoot,'GHP7_PILOT_PAYLOAD_MANIFEST_v1.json');
baselinePath=fullfile(researchRoot,'GHP7_BASELINE_REUSE_MANIFEST_v1.json');
physicsPath=fullfile(researchRoot,'GHP7_C5_10_PHYSICS_REFERENCE_REUSE_MANIFEST_v1.json');
physicsComparisonPath=fullfile(researchRoot,'C5_10_PHYSICS_PAIRED_COMPARISON_v1.json');
completionAuditPath=fullfile(researchRoot,'C5_RBF_COMPLETION_FLAG_ROOT_CAUSE_v1.json');
runtimeSmokePath=fullfile(researchRoot,'MATLAB_NO_PLANT_AUDIT_MLP15_v2.json');
amendment09Path=fullfile(researchRoot,'DL_ATTITUDE_REPLACEMENT_TASKBOOK_v1_AMENDMENT09_MLP15_FORMAL_TRAINING.md');
pilotTaskbookPath=fullfile(researchRoot,'MLP15_CLOSED_LOOP_PILOT_TASKBOOK_v2.md');
scoringAmendmentPath=fullfile(researchRoot,'MLP15_SCORER_AMENDMENT_v3.md');
scoreReleasePath=fullfile(researchRoot,'MLP15_SCORE_RELEASE_v3.json');
parityPath=fullfile(researchRoot,'mlp15_formal_v1','run_v1','MATLAB_PARITY_AUDIT_v1.json');
checkpointAuditPath=fullfile(researchRoot,'mlp15_formal_v1','run_v1','MLP15_CHECKPOINT_AUDIT_v1.json');
codeAuditPath=fullfile(researchRoot,'MLP15_RUNNER_CODE_ANALYZER_COMPARISON_v2.json');
assert(isfile(releasePath),'DLMLP15:NoRelease','Pilot release is missing.');
release=jsondecode(fileread(releasePath));
scoreRelease=jsondecode(fileread(scoreReleasePath));
payloadManifest=jsondecode(fileread(payloadPath));
baseline=jsondecode(fileread(baselinePath));
physics=jsondecode(fileread(physicsPath));
physicsComparison=jsondecode(fileread(physicsComparisonPath));
completionAudit=jsondecode(fileread(completionAuditPath));
runtimeSmoke=jsondecode(fileread(runtimeSmokePath));
parity=jsondecode(fileread(parityPath));
checkpointAudit=jsondecode(fileread(checkpointAuditPath));
codeAudit=jsondecode(fileread(codeAuditPath));
scoreScriptPath=[mfilename('fullpath') '.m'];scoreScriptSha=sha256_file(scoreScriptPath);
assert(strcmp(release.schema,'DL1018_MLP15_GHP7_PILOT_RELEASE_V2')&& ...
    strcmp(release.status,'RELEASED')&&double(release.plant_calls_authorized)==6&& ...
    ~release.test_data_read&&~release.variable_inertia_reconstruction_enabled&& ...
    ~release.observer_enabled&&~release.feedforward_enabled&& ...
    strcmp(parity.status,'PASS')&&parity.plant_called==false&&parity.test_data_read==false&& ...
    parity.max_abs_error_rad_s2<=parity.tolerance_rad_s2&&parity.tolerance_rad_s2<=1e-5&& ...
    strcmp(checkpointAudit.status,'PASS_READ_ONLY_VAL48_AND_EXPORT')&& ...
    checkpointAudit.plant_called==false&&checkpointAudit.test_data_read==false&& ...
    strcmp(payloadManifest.status,'PASS')&&payloadManifest.scene_count==6&& ...
    ~payloadManifest.tests_data_read&&strcmp(baseline.status,'PASS')&& ...
    baseline.record_count==12&&~baseline.test_data_read&& ...
    strcmp(physics.schema,'DL1018_GHP7_C5_10_PHYSICS_REFERENCE_REUSE_MANIFEST_V1')&& ...
    strcmp(physics.status,'PASS')&&physics.scene_count==6&&numel(physics.records)==6&& ...
    physics.inertia_reconstruction_used&&~physics.observer_enabled&& ...
    ~physics.rbf_attitude_output_enabled&&~physics.rbf_attitude_update_enabled&& ...
    ~physics.test_data_read&&strcmp(physicsComparison.status,'PASS')&& ...
    physicsComparison.metrics_independently_recomputed_from_raw&& ...
    ~physicsComparison.plant_invoked&&~physicsComparison.test_data_read&& ...
    strcmp(completionAudit.status,'PASS')&&~completionAudit.plant_invoked&& ...
    strcmp(runtimeSmoke.status,'PASS')&&~runtimeSmoke.plant_invoked&& ...
    ~runtimeSmoke.test_data_read&& ...
    strcmp(codeAudit.status,'PASS_NO_NEW_DIAGNOSTIC_IDS_OR_COUNTS')&& ...
    codeAudit.no_new_diagnostics&&codeAudit.plant_invoked==false&&codeAudit.test_data_read==false, ...
    'DLMLP15:ReleaseGate','Release/payload/baseline gate is invalid.');
assert(strcmp(scoreRelease.schema,'DL1018_MLP15_SCORE_RELEASE_V3')&& ...
    strcmp(scoreRelease.status,'FROZEN')&&scoreRelease.plant_invoked==false&& ...
    scoreRelease.test_data_read==false&& ...
    strcmpi(sha256_file(releasePath),char(scoreRelease.candidate_release_sha256))&& ...
    strcmpi(scoreScriptSha,char(scoreRelease.score_script_sha256))&& ...
    strcmpi(sha256_file(pilotTaskbookPath),char(scoreRelease.pilot_taskbook_sha256))&& ...
    strcmpi(sha256_file(scoringAmendmentPath),char(scoreRelease.scoring_amendment_sha256)), ...
    'DLMLP15:ScoreScriptHash','Scorer amendment/release does not bind this read-only scoring script.');
assert(strcmpi(sha256_file(physicsComparisonPath),char(release.physics_comparison_sha256))&& ...
    strcmpi(sha256_file(completionAuditPath),char(release.completion_marker_audit_sha256))&& ...
    strcmpi(sha256_file(runtimeSmokePath),char(release.no_plant_audit_sha256))&& ...
    strcmpi(sha256_file(checkpointAuditPath),char(release.checkpoint_audit_sha256))&& ...
    strcmpi(sha256_file(codeAuditPath),char(release.code_analyzer_comparison_sha256)), ...
    'DLMLP15:EvidenceHash','A no-Plant audit or physics comparison changed after release.');
assert(strcmpi(sha256_file(amendment09Path),char(release.amendment09_sha256))&& ...
    strcmpi(sha256_file(pilotTaskbookPath),char(release.pilot_taskbook_sha256))&& ...
    strcmpi(sha256_file(parityPath),char(release.parity_report_sha256))&& ...
    strcmpi(sha256_file(fullfile(researchRoot,'mlp15_formal_v1','TRAINING_RELEASE_v1.json')), ...
        char(release.training_release_sha256))&& ...
    strcmpi(sha256_file(fullfile(researchRoot,'mlp15_formal_v1','run_v1','training_config.json')), ...
        char(release.training_config_sha256)), ...
    'DLMLP15:ParityHash','Batch parity amendment or report changed after release.');
assert(strcmpi(sha256_file(payloadPath),char(release.payload_manifest_sha256))&& ...
    strcmpi(sha256_file(baselinePath),char(release.baseline_reuse_manifest_sha256))&& ...
    isfield(release,'physics_reference_manifest_sha256')&& ...
    strcmpi(sha256_file(physicsPath),char(release.physics_reference_manifest_sha256)), ...
    'DLMLP15:ManifestHash','Pilot input manifest changed after release.');
verify_candidate_lock(release,fullfile(researchRoot,'pilot_runner_mlp15_v2','candidate_runner_work'));
for i=1:numel(baseline.records)
    rec=baseline.records(i);
    assert(isfile(char(rec.raw_path))&&strcmpi(sha256_file(char(rec.raw_path)),char(rec.raw_sha256)), ...
        'DLMLP15:BaselineRawHash','Reused baseline raw changed: %s / %s.', ...
        char(rec.scene_id),char(rec.runner));
end
assert(isequal(sort(string({physics.records.scene_id})),sort(string({payloadManifest.records.scene_id}))), ...
    'DLMLP15:PhysicsSceneSet','C5_10 reference scenes differ from the released pilot scenes.');
for i=1:numel(physics.records)
    rec=physics.records(i);p=find(strcmp({payloadManifest.records.scene_id},char(rec.scene_id)));
    assert(isscalar(p)&&strcmpi(char(rec.scene_payload_sha256), ...
        char(payloadManifest.records(p).payload_file_sha256))&& ...
        strcmpi(char(rec.r_task_sha256),char(payloadManifest.records(p).r_task_sha256))&& ...
        strcmp(char(rec.attitude_arm),'C5_10')&&strcmp(char(rec.geometry_arm),'ACTIVE')&& ...
        double(rec.complete_transitions)==20000&&strcmp(char(rec.status),'STABLE')&& ...
        logical(rec.application_feasible), ...
        'DLMLP15:PhysicsIdentity','C5_10 row does not match the released scene/method: %s.',char(rec.scene_id));
    assert(isfile(char(rec.raw_path))&&strcmpi(sha256_file(char(rec.raw_path)),char(rec.raw_sha256))&& ...
        strcmpi(sha256_file(fullfile(char(rec.attempt_dir),'run_start.json')),char(rec.run_start_sha256))&& ...
        strcmpi(sha256_file(fullfile(char(rec.attempt_dir),'run_status.json')),char(rec.run_status_sha256)), ...
        'DLMLP15:PhysicsRawHash','C5_10 reference files changed: %s.',char(rec.scene_id));
end

oldTaskRoot=fullfile(projectRoot,'experiments','attitude_physics_inertia_observer_20261025', ...
    'holdout_gate_inspection_v2');
c5ReceiptPath=fullfile(oldTaskRoot,'C5_R_TASK_BINDING_PILOT_RECEIPT_v5.json');
c5Receipt=jsondecode(fileread(c5ReceiptPath));
assert(strcmpi(sha256_file(c5ReceiptPath),char(release.c5_receipt_sha256))&& ...
    strcmpi(char(c5Receipt.status),'PASS_NO_PLANT_PILOT_PAYLOADS_ONLY')&& ...
    c5Receipt.plant_calls==0&&~c5Receipt.tests_data_read, ...
    'DLMLP15:C5Receipt','The no-Plant C5 receipt differs from the release.');
snapshotPath=char(c5Receipt.input_records.c5_snapshot_mat.path);
assert(strcmpi(sha256_file(snapshotPath),char(c5Receipt.input_records.c5_snapshot_mat.sha256)), ...
    'DLMLP15:C5Snapshot','C5 scoring configuration changed.');
snapshot=load(snapshotPath,'cfg');cfg=snapshot.cfg;
addpath(fullfile(oldTaskRoot,'scene_builder_work'));
cleanup=onCleanup(@()rmpath(fullfile(oldTaskRoot,'scene_builder_work')));

records=payloadManifest.records;
expectedIds=sort(string({records.scene_id}));
assert(numel(records)==6&&numel(unique(expectedIds))==6, ...
    'DLMLP15:ExpectedScenes','The released six-scene set is not unique.');
runsRoot=fullfile(researchRoot,'pilot_runs_mlp15_v2');
starts=dir(fullfile(runsRoot,'**','run_start.json'));
rows=repmat(empty_row(),numel(records),1);
for i=1:numel(records)
    p=records(i);row=empty_row();row.scene_id=char(p.scene_id);row.gust_group=char(extractBetween(string(p.scene_id),'GHP7_','_W'));
    row.wind_id=char(extractAfter(string(p.scene_id),"_W"));
    row.payload_sha256=char(p.payload_file_sha256);row.r_task_sha256=char(p.r_task_sha256);
    hit=[];
    for j=1:numel(starts)
        start=jsondecode(fileread(fullfile(starts(j).folder,starts(j).name)));
        if isfield(start,'scene_id')&&strcmp(char(start.scene_id),row.scene_id),hit(end+1)=j;end %#ok<AGROW>
    end
    row.attempt_count=numel(hit);
    if isempty(hit)
        row.score_state='MISSING_ATTEMPT';rows(i)=row;continue
    elseif numel(hit)>1
        row.score_state='DUPLICATE_ATTEMPTS';rows(i)=row;continue
    end
    attemptDir=starts(hit).folder;row.attempt_dir=attemptDir;
    try
        start=jsondecode(fileread(fullfile(attemptDir,'run_start.json')));
        statusPath=fullfile(attemptDir,'run_status.json');
        if ~isfile(statusPath),row.score_state='MISSING_STATUS';rows(i)=row;continue;end
        status=jsondecode(fileread(statusPath));
        row.run_state=char(status.state);
        rawPath=fullfile(attemptDir,'raw_run.mat');
        if ~isfile(rawPath),row.score_state='MISSING_RAW';rows(i)=row;continue;end
        rawSha=sha256_file(rawPath);
        if isfield(status,'raw_output_sha256')&&~strcmpi(rawSha,char(status.raw_output_sha256))
            row.score_state='RAW_HASH_MISMATCH';rows(i)=row;continue
        end
        assert(strcmp(char(start.attitude_arm),'DL_MLP15')&&strcmp(char(start.geometry_arm),'ACTIVE')&& ...
            strcmpi(char(start.scene_payload_sha256),row.payload_sha256)&& ...
            strcmpi(char(start.r_task_sha256),row.r_task_sha256)&& ...
            strcmpi(char(start.taskbook_sha256),char(release.taskbook_sha256))&& ...
            strcmpi(char(start.pilot_release_sha256),sha256_file(releasePath))&& ...
            strcmpi(char(start.amendment02_sha256),char(release.amendment02_sha256))&& ...
            strcmpi(char(start.amendment03_sha256),char(release.amendment03_sha256))&& ...
            strcmpi(char(start.amendment04_sha256),char(release.amendment04_sha256))&& ...
            strcmpi(char(start.amendment09_sha256),char(release.amendment09_sha256))&& ...
            strcmpi(char(start.pilot_taskbook_sha256),char(release.pilot_taskbook_sha256))&& ...
            strcmpi(char(start.dataset_manifest_sha256),char(release.dataset_manifest_sha256))&& ...
            strcmpi(char(start.screen_audit_sha256),char(release.screen_audit_sha256))&& ...
            strcmpi(char(start.parity_report_sha256),char(release.parity_report_sha256))&& ...
            strcmpi(char(start.checkpoint_audit_sha256),char(release.checkpoint_audit_sha256))&& ...
            strcmpi(char(start.code_analyzer_comparison_sha256),char(release.code_analyzer_comparison_sha256))&& ...
            strcmpi(char(start.candidate_source_lock_sha256),char(release.candidate_source_lock_sha256))&& ...
            strcmpi(char(start.mlp15_model_mat_sha256),char(release.model_sha256))&& ...
            strcmpi(char(start.training_release_sha256),char(release.training_release_sha256))&& ...
            strcmpi(char(start.training_config_sha256),char(release.training_config_sha256))&& ...
            double(start.best_step)==double(release.best_step), ...
            'DLMLP15:RunIdentity','Candidate run start does not match frozen release/payload.');
        raw=load(rawPath,'log','scene');log=raw.log;scene=raw.scene;
        assert(strcmp(char(scene.scene_id),row.scene_id)&& ...
            strcmpi(char(scene.R_task_sha256),row.r_task_sha256)&& ...
            strcmpi(paired_sha256_double(double(scene.R_task)),row.r_task_sha256), ...
            'DLMLP15:RawScene','Candidate raw scene or R_task identity differs.');
        [row,logAudit]=score_log(row,log,scene,cfg);
        row.run_state=char(status.state);row.raw_sha256=rawSha;
        row.status_value=char(string(log.status));row.safety_stop_reason=char(string(log.safety_stop_reason));
        row.complete_transitions=logical(logAudit.complete);
        row.completion_flag_consistent=logical(logAudit.flag_consistent)&& ...
            isfield(status,'complete_transitions')&&logical(status.complete_transitions);
        row.motor_saturation_any=logical(logAudit.motor_saturation_any);
        row.generalized_clip_any=logical(logAudit.generalized_clip_any);
        row.tilt_limit_any=logical(logAudit.tilt_limit_any);
        row.geometry_checked=logical(logAudit.geometry_checked);
        row.pass_bidirectional=logical(logAudit.pass_bidirectional);
        row.pass_15mm_proxy=logical(logAudit.pass_15mm_proxy);
        row.application_feasible=logical(logAudit.application_feasible);
        row.mlp15_trace_ok=logical(logAudit.mlp15_trace_ok);
        row.score_state='SCORED_COMPLETE';
        if ~row.complete_transitions||~row.completion_flag_consistent|| ...
                ~strcmp(row.run_state,'COMPLETED')||~strcmp(row.status_value,'STABLE')|| ...
                ~isempty(row.safety_stop_reason)||~row.mlp15_trace_ok|| ...
                row.motor_saturation_any||row.generalized_clip_any||row.tilt_limit_any
            row.score_state='SCORED_FAILED_OR_UNSAFE';
        end
    catch ME
        row.score_state='SCORER_ERROR';row.failure_reason=char(ME.message);
    end
    rows(i)=row;
end

for i=1:numel(rows)
    b=find(strcmp({baseline.records.scene_id},rows(i).scene_id)&strcmp({baseline.records.runner},'B'));
    c=find(strcmp({baseline.records.scene_id},rows(i).scene_id)&strcmp({baseline.records.attitude_arm},'C5_RBF'));
    assert(isscalar(b)&&isscalar(c),'DLMLP15:BaselinePair','Missing B/C5_RBF paired baseline row.');
    rows(i).baseline_B_raw_sha256=char(baseline.records(b).raw_sha256);
    rows(i).baseline_C5_raw_sha256=char(baseline.records(c).raw_sha256);
    rows(i).baseline_B_q0_20_m=double(baseline.records(b).q0_20_m);
    rows(i).baseline_C5_q0_20_m=double(baseline.records(c).q0_20_m);
    rows(i).baseline_B_so3_rmse_rad=double(baseline.records(b).so3_rmse_rad);
    rows(i).baseline_C5_so3_rmse_rad=double(baseline.records(c).so3_rmse_rad);
    p=find(strcmp({physics.records.scene_id},rows(i).scene_id));
    assert(isscalar(p),'DLMLP15:PhysicsPair','Missing C5_10 paired reference row.');
    rows(i).physics_C5_10_raw_sha256=char(physics.records(p).raw_sha256);
    rows(i).physics_C5_10_q0_20_m=double(physics.records(p).q0_20_m);
    rows(i).physics_C5_10_q8_12_m=double(physics.records(p).q8_12_m);
    rows(i).physics_C5_10_so3_rmse_rad=double(physics.records(p).so3_rmse_rad);
    rows(i).physics_C5_10_application_feasible=logical(physics.records(p).application_feasible);
    rows(i).baseline_B_completion_flag_consistent=logical(baseline.records(b).score_completion_flag_consistent);
    rows(i).baseline_C5_completion_flag_consistent=logical(baseline.records(c).score_completion_flag_consistent);
    rows(i).baseline_B_score_valid=logical(baseline.records(b).score_run_valid);
    rows(i).baseline_C5_score_valid=logical(baseline.records(c).score_run_valid);
    candidateComparable=strcmp(rows(i).score_state,'SCORED_COMPLETE');
    rows(i).win_position_vs_B=candidateComparable&&isfinite(rows(i).q0_20_m)&& ...
        rows(i).q0_20_m<rows(i).baseline_B_q0_20_m-1e-12;
    rows(i).win_attitude_vs_B=candidateComparable&&isfinite(rows(i).so3_rmse_rad)&& ...
        rows(i).so3_rmse_rad<rows(i).baseline_B_so3_rmse_rad-1e-12;
    rows(i).win_position_vs_C5=candidateComparable&&isfinite(rows(i).q0_20_m)&& ...
        rows(i).q0_20_m<rows(i).baseline_C5_q0_20_m-1e-12;
    rows(i).win_attitude_vs_C5=candidateComparable&&isfinite(rows(i).so3_rmse_rad)&& ...
        rows(i).so3_rmse_rad<rows(i).baseline_C5_so3_rmse_rad-1e-12;
    rows(i).win_position_vs_C5_10=candidateComparable&&isfinite(rows(i).q0_20_m)&& ...
        rows(i).q0_20_m<rows(i).physics_C5_10_q0_20_m-1e-12;
    rows(i).win_attitude_vs_C5_10=candidateComparable&&isfinite(rows(i).so3_rmse_rad)&& ...
        rows(i).so3_rmse_rad<rows(i).physics_C5_10_so3_rmse_rad-1e-12;
end
scoredCompleteMask=strcmp({rows.score_state},'SCORED_COMPLETE');
scoredFailedMask=strcmp({rows.score_state},'SCORED_FAILED_OR_UNSAFE');
unscoredMask=~scoredCompleteMask&~scoredFailedMask;
applicationFeasibleMask=scoredCompleteMask&[rows.application_feasible];
applicationInfeasibleMask=scoredCompleteMask&~[rows.application_feasible];
pairedRows=rows(scoredCompleteMask);
summary=struct('expected_scenes',numel(rows), ...
    'completed_scenes',sum(strcmp({rows.run_state},'COMPLETED')), ...
    'scored_complete_scenes',sum(scoredCompleteMask), ...
    'unsafe_or_failed_scenes',sum(scoredFailedMask), ...
    'unscored_missing_or_error_scenes',sum(unscoredMask), ...
    'application_feasible_scenes',sum(applicationFeasibleMask), ...
    'application_infeasible_complete_scenes',sum(applicationInfeasibleMask), ...
    'mean_metric_scope','SCORED_COMPLETE candidate scenes; all reference means use the same paired scenes', ...
    'wins_position_vs_B',sum([rows.win_position_vs_B]), ...
    'wins_attitude_vs_B',sum([rows.win_attitude_vs_B]), ...
    'wins_position_vs_C5_RBF',sum([rows.win_position_vs_C5]), ...
    'wins_attitude_vs_C5_RBF',sum([rows.win_attitude_vs_C5]), ...
    'wins_position_vs_C5_10_physics',sum([rows.win_position_vs_C5_10]), ...
    'wins_attitude_vs_C5_10_physics',sum([rows.win_attitude_vs_C5_10]), ...
    'B_baseline_flag_mismatch_count',sum(~[rows.baseline_B_completion_flag_consistent]), ...
    'C5_RBF_baseline_flag_mismatch_count',sum(~[rows.baseline_C5_completion_flag_consistent]), ...
    'mean_position_Q_DL_MLP15_m',mean_finite([pairedRows.q0_20_m]), ...
    'mean_position_Q_B_m',mean_finite([pairedRows.baseline_B_q0_20_m]), ...
    'mean_position_Q_C5_RBF_m',mean_finite([pairedRows.baseline_C5_q0_20_m]), ...
    'mean_position_Q_C5_10_physics_m',mean_finite([pairedRows.physics_C5_10_q0_20_m]), ...
    'mean_SO3_DL_MLP15_rad',mean_finite([pairedRows.so3_rmse_rad]), ...
    'mean_SO3_B_rad',mean_finite([pairedRows.baseline_B_so3_rmse_rad]), ...
    'mean_SO3_C5_RBF_rad',mean_finite([pairedRows.baseline_C5_so3_rmse_rad]), ...
    'mean_SO3_C5_10_physics_rad',mean_finite([pairedRows.physics_C5_10_so3_rmse_rad]), ...
    'C5_10_physics_feasible_scenes',sum([rows.physics_C5_10_application_feasible]));
result=struct('schema','DL1018_MLP15_GHP7_PILOT_SCORE_V2T', ...
    'created_utc',char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z''')), ...
    'taskbook_sha256',char(release.taskbook_sha256), ...
    'amendment02_sha256',char(release.amendment02_sha256), ...
    'amendment03_sha256',char(release.amendment03_sha256), ...
    'amendment04_sha256',char(release.amendment04_sha256), ...
    'amendment09_sha256',char(release.amendment09_sha256), ...
    'pilot_taskbook_sha256',char(release.pilot_taskbook_sha256), ...
    'dataset_manifest_sha256',char(release.dataset_manifest_sha256), ...
    'screen_audit_sha256',char(release.screen_audit_sha256), ...
    'checkpoint_audit_sha256',char(release.checkpoint_audit_sha256), ...
    'code_analyzer_comparison_sha256',char(release.code_analyzer_comparison_sha256), ...
    'parity_report_sha256',char(release.parity_report_sha256), ...
    'release_sha256',sha256_file(releasePath), ...
    'score_release_sha256',sha256_file(scoreReleasePath), ...
    'score_script_sha256',scoreScriptSha, ...
    'payload_manifest_sha256',sha256_file(payloadPath), ...
    'baseline_manifest_sha256',sha256_file(baselinePath), ...
    'physics_reference_manifest_sha256',sha256_file(physicsPath), ...
    'physics_comparison_sha256',sha256_file(physicsComparisonPath), ...
    'completion_marker_audit_sha256',sha256_file(completionAuditPath), ...
    'no_plant_audit_sha256',sha256_file(runtimeSmokePath), ...
    'physics_reference_method_contract',char(physics.method_contract), ...
    'candidate_source_lock_sha256',char(release.candidate_source_lock_sha256), ...
    'model_sha256',char(release.model_sha256),'test_data_read',false, ...
    'time_samples_are_independent',false,'summary',summary,'rows',rows);
outDir=fullfile(researchRoot,'pilot_score_mlp15_v2t');
assert(~isfolder(outDir)&&~isfile(outDir),'DLMLP15:NoOverwrite','Pilot scoring output already exists.');
