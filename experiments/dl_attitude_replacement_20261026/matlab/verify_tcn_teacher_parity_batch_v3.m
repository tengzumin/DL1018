function report=verify_tcn_teacher_parity_batch_v3(trainingDir)
% Compare Python and MATLAB TCN outputs over 240 deterministic VAL windows plus one full sequential runtime replay.
here=fileparts(mfilename('fullpath'));
taskRoot=fileparts(here);
if nargin<1,trainingDir=fullfile(taskRoot,'training_v2_teacher_distill');end
addpath(here);
inputPath=fullfile(trainingDir,'parity_vectors_batch_v3.mat');
selectionPath=fullfile(trainingDir,'parity_vectors_batch_v3.json');
modelPath=fullfile(trainingDir,'tcn_attitude_weights_v2.mat');
assert(isfile(inputPath)&&isfile(selectionPath)&&isfile(modelPath), ...
    'DLTCN:ParityFiles','Batch parity input, selection report, or model is missing.');
selection=jsondecode(fileread(selectionPath));
requiredSelectionFields={'schema','status','sample_count','scene_count', ...
    'sequence_step_count','times_event_index','selection','training_split_only', ...
    'test_data_read','plant_called','sequence_scene_id','dataset_manifest_sha256', ...
    'dataset_npz_sha256','exporter_sha256','model_sha256','mat_sha256'};
assert(isstruct(selection)&&all(isfield(selection,requiredSelectionFields)), ...
    'DLTCN:ParitySelectionFields','Parity selection report is incomplete.');
assert(strcmp(selection.schema,'DL1018_CAUSAL_TCN_PARITY_BATCH_V3')&& ...
    strcmp(selection.status,'PASS')&&selection.sample_count==240&& ...
    selection.scene_count==48&&selection.sequence_step_count==1999&& ...
    selection.training_split_only&&~selection.test_data_read&&~selection.plant_called, ...
    'DLTCN:ParitySelection','Parity selection is not a clean 48-by-5 VAL-only PASS.');
assert(isequal(double(selection.times_event_index(:).'),[0,1,100,999,1998])&& ...
    strcmp(selection.selection,'all 48 B VAL scenes x event indices [0,1,100,999,1998]'), ...
    'DLTCN:ParityIndices','Parity event indices differ from the frozen 48-by-5 selection.');
manifestPath=fullfile(taskRoot,'dataset_v4_teacher_distill','DATASET_MANIFEST_v2.json');
manifest=jsondecode(fileread(manifestPath));
assert(strcmp(manifest.status,'PASS')&&~manifest.test_data_read&& ...
    ~manifest.plant_truth_read&&~manifest.nominal_inertia_read&& ...
    manifest.split_counts.TRAIN==768&&manifest.split_counts.VAL==48&& ...
    strcmpi(selection.dataset_manifest_sha256,sha256_file(manifestPath))&& ...
    strcmpi(selection.dataset_npz_sha256,manifest.npz_sha256), ...
    'DLTCN:ParityDataset','Parity selection does not match the frozen TRAIN/VAL dataset manifest.');
valRows=manifest.rows(strcmp({manifest.rows.split},'VAL'));
assert(numel(valRows)==48&&any(strcmp({valRows.scene_id},char(selection.sequence_scene_id))), ...
    'DLTCN:ParitySequenceScene','Sequential replay scene is not in the frozen VAL cohort.');
assert(strcmpi(selection.model_sha256,sha256_file(modelPath))&& ...
    strcmpi(selection.mat_sha256,sha256_file(inputPath))&& ...
    strcmpi(selection.exporter_sha256,sha256_file(fullfile(taskRoot, ...
    'export_tcn_teacher_parity_batch_v3.py'))), ...
    'DLTCN:ParityIdentity','Parity model, vectors, or exporter SHA differs from the frozen files.');
S=load(inputPath,'input_normalized','expected_teacher_rbf_output_rad_s2', ...
    'sequence_feature_raw','sequence_expected_rad_s2');
X=double(S.input_normalized);
Y=double(S.expected_teacher_rbf_output_rad_s2);
sequenceFeatures=double(S.sequence_feature_raw);
sequenceExpected=double(S.sequence_expected_rad_s2);
assert(size(X,1)==13&&size(X,2)==15&&size(X,3)==selection.sample_count&& ...
    isequal(size(Y),[3,selection.sample_count])&& ...
    size(sequenceFeatures,1)==13&&size(sequenceFeatures,2)==selection.sequence_step_count&& ...
    isequal(size(sequenceExpected),[3,selection.sequence_step_count])&& ...
    selection.sequence_step_count==1999&& ...
    all(isfinite(X),'all')&&all(isfinite(Y),'all')&& ...
    all(isfinite(sequenceFeatures),'all')&&all(isfinite(sequenceExpected),'all'), ...
    'DLTCN:ParityShape','Batch or sequential parity arrays have invalid shape or non-finite values.');
model=load(modelPath);
actual=zeros(3,selection.sample_count);
for i=1:selection.sample_count
    actual(:,i)=tcn_attitude_forward_v1(X(:,:,i),model);
end
absoluteError=abs(actual-Y);
maxBatchAbs=max(absoluteError,[],'all');
[~,linearIndex]=max(absoluteError(:));
[worstAxis,worstSample]=ind2sub(size(absoluteError),linearIndex);

% Exercise the runtime memory shift over one full causal VAL sequence.
[sequenceMemory,~]=tcn_attitude_step_v1('init',struct,struct,model);
sequenceActual=zeros(3,selection.sequence_step_count);
sequenceInput=struct('J0',eye(3),'beta',1,'dmax',realmax*ones(3,1));
for i=1:selection.sequence_step_count
    sequenceInput.feature=sequenceFeatures(:,i);
    [sequenceMemory,sequenceOutput]=tcn_attitude_step_v1( ...
        'step',sequenceMemory,sequenceInput,model);
    sequenceActual(:,i)=double(sequenceOutput.raw_residual_rad_s2(:));
end
assert(sequenceMemory.event_count==selection.sequence_step_count, ...
    'DLTCN:ParitySequence','Runtime TCN history did not process every causal event.');
sequenceError=abs(sequenceActual-sequenceExpected);
maxSequenceAbs=max(sequenceError,[],'all');
maxAbs=max(maxBatchAbs,maxSequenceAbs);
report=struct('schema','DL1018_CAUSAL_TCN_PYTHON_MATLAB_PARITY_V2', ...
    'verification_version','batch_v3', ...
    'status','PASS','sample_count',selection.sample_count,'scene_count',selection.scene_count, ...
    'event_indices',selection.times_event_index, ...
    'sequence_step_count',selection.sequence_step_count, ...
    'sequence_scene_id',selection.sequence_scene_id, ...
    'max_batch_abs_error',maxBatchAbs,'max_sequential_abs_error',maxSequenceAbs, ...
    'max_abs_error',maxAbs,'worst_batch_sample_index',worstSample,'worst_batch_axis_1based',worstAxis, ...
    'tolerance',1e-5,'training_split_only',true, ...
    'test_data_read',false,'plant_called',false, ...
    'python_exporter_sha256',selection.exporter_sha256, ...
    'parity_vector_sha256',selection.mat_sha256, ...
    'matlab_verifier_sha256',sha256_file([mfilename('fullpath') '.m']));
assert(maxAbs<=report.tolerance,'DLTCN:Parity', ...
    'Python/MATLAB batch parity failed: %.17g over %d outputs.',maxAbs,numel(actual));
write_json(fullfile(trainingDir,'MATLAB_PYTHON_PARITY_V2.json'),report);
write_json(fullfile(trainingDir,'MATLAB_PYTHON_PARITY_BATCH_V3.json'),report);
disp(jsonencode(report));
end

function h=sha256_file(filePath)
fid=fopen(filePath,'rb');assert(fid>=0,'DLTCN:ParityHash','Cannot hash %s.',filePath);
cleanup=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true
    bytes=fread(fid,8*1024*1024,'*uint8');
    if isempty(bytes),break;end
    md.update(typecast(bytes(:),'int8'));
end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
clear cleanup;
end

function write_json(outputPath,value)
fid=fopen(outputPath,'w','n','UTF-8');
assert(fid>=0,'DLTCN:ParityWrite','Cannot write %s.',outputPath);
cleanup=onCleanup(@()fclose(fid));
fwrite(fid,unicode2native([jsonencode(value,'PrettyPrint',true) newline],'UTF-8'),'uint8');
clear cleanup;
end



