function report=audit_mlp15_ghp7_scores_independent_v1()
% Independently recompute paired GHP7 pilot metrics from 18 immutable raw files.
researchRoot=fileparts(fileparts(mfilename('fullpath')));
payload=jsondecode(fileread(fullfile(researchRoot,'GHP7_PILOT_PAYLOAD_MANIFEST_v1.json')));
baseline=jsondecode(fileread(fullfile(researchRoot,'GHP7_BASELINE_REUSE_MANIFEST_v1.json')));
scorePath=fullfile(researchRoot,'pilot_score_mlp15_v2v','pilot_score.json');
score=jsondecode(fileread(scorePath));
assert(strcmp(payload.status,'PASS')&&payload.scene_count==6&&~payload.tests_data_read&& ...
    strcmp(baseline.status,'PASS')&&baseline.record_count==12&&~baseline.test_data_read&& ...
    strcmp(score.schema,'DL1018_MLP15_GHP7_PILOT_SCORE_V2V')&&~score.test_data_read, ...
    'AUDIT:InputManifest','Pilot payload, baseline, or score release is invalid.');
ids=sort(string({payload.records.scene_id}));
methods={'B','C5_RBF','DL_MLP15'};
rows=repmat(empty_row(),numel(ids)*numel(methods),1);
out=0;
for i=1:numel(ids)
    id=char(ids(i));
    p=payload.records(strcmp({payload.records.scene_id},id));
    assert(isscalar(p),'AUDIT:PayloadRow','Payload record is not unique for %s.',id);
    scoreRow=score.rows(strcmp({score.rows.scene_id},id));
    assert(isscalar(scoreRow),'AUDIT:ScoreRow','Score row is not unique for %s.',id);
    for m=1:numel(methods)
        method=methods{m};
        if strcmp(method,'B')
            b=baseline.records(strcmp({baseline.records.scene_id},id)&strcmp({baseline.records.runner},'B'));
            assert(isscalar(b),'AUDIT:BaselineB','Missing B row for %s.',id);
            rawPath=char(b.raw_path);expectedRaw=char(b.raw_sha256);
            baselineCompletionConsistent=logical(b.score_completion_flag_consistent);
        elseif strcmp(method,'C5_RBF')
            b=baseline.records(strcmp({baseline.records.scene_id},id)&strcmp({baseline.records.attitude_arm},'C5_RBF'));
            assert(isscalar(b),'AUDIT:BaselineC5','Missing C5_RBF row for %s.',id);
            rawPath=char(b.raw_path);expectedRaw=char(b.raw_sha256);
            baselineCompletionConsistent=logical(b.score_completion_flag_consistent);
        else
            rawPath=fullfile(researchRoot,'pilot_runs_mlp15_v2',id,'raw_run.mat');
            expectedRaw=char(scoreRow.raw_sha256);
            baselineCompletionConsistent=true;
        end
        rawSha=sha256_file(rawPath);
        assert(strcmpi(rawSha,expectedRaw),'AUDIT:RawSHA','Raw SHA changed for %s / %s.',id,method);
        d=load(rawPath,'log','scene');log=d.log;scene=d.scene;
        assert(strcmp(char(scene.scene_id),id)&& ...
            strcmpi(char(scene.R_task_sha256),char(p.r_task_sha256))&& ...
            strcmpi(paired_sha256_double(double(scene.R_task)),char(p.r_task_sha256)), ...
            'AUDIT:SceneIdentity','Scene or R_task identity mismatch for %s / %s.',id,method);
        t=double(log.time(:));X=double(log.state);ref=double(log.reference.position);
        assert(isreal(t)&&isreal(X)&&isreal(ref)&&size(X,1)==numel(t)&& ...
            size(X,2)==12&&isequal(size(ref),[numel(t),3])&& ...
            all(isfinite(t))&&all(isfinite(X(:)))&&all(isfinite(ref(:))), ...
            'AUDIT:RawShape','Nonreal, nonfinite, or malformed state/reference in %s / %s.',id,method);
        err=X(:,1:3)-ref;
        q0=sqrt(mean(sum(err.^2,2)));
        q8mask=t>=8-1e-10&t<=12+1e-10;
        assert(sum(q8mask)==4001,'AUDIT:Q8Timeline','Expected 4001 samples in 8-12s for %s.',id);
        q8=sqrt(mean(sum(err(q8mask,:).^2,2)));
        Rtask=double(scene.R_task);n=numel(t);
        assert(isreal(Rtask)&&size(Rtask,3)>=n,'AUDIT:RTaskShape','Invalid R_task timeline for %s.',id);
        theta=zeros(n,1);
        for k=1:n
            R=rotation_zyx_local(X(k,7:9).');
            D=Rtask(:,:,k)'*R;
            theta(k)=acos(max(min((trace(D)-1)/2,1),-1));
        end
        so3=sqrt(mean(theta.^2));
        tiltCount=nnz(log.tilt_limited);
        satCount=nnz(log.motor_saturated);
        clipCount=nnz(log.generalized_clipped);
        row=empty_row();row.scene_id=id;row.method=method;row.wind_id=char(extractAfter(string(id),"_W"));
        row.raw_path=rawPath;row.raw_sha256=rawSha;row.q0_20_m=q0;row.q8_12_m=q8;row.so3_rmse_rad=so3;
        row.status=char(string(log.status));
        row.complete_transitions=numel(t)==numel(scene.time)&&isfield(log,'last_transition')&& ...
            double(log.last_transition)==numel(scene.time)-1;
        if isfield(log,'complete_transitions')
            row.logged_complete_flag=logical(log.complete_transitions);
        end
        row.baseline_completion_flag_consistent=baselineCompletionConsistent;
        row.safety_stop_reason=char(string(log.safety_stop_reason));row.tilt_limited_count=tiltCount;
        row.motor_saturation_count=satCount;row.generalized_clip_count=clipCount;
        if strcmp(method,'DL_MLP15')
            row.score_state=char(scoreRow.score_state);
            row.position_score_abs_diff_m=abs(q0-double(scoreRow.q0_20_m));
            row.q8_score_abs_diff_m=abs(q8-double(scoreRow.q8_12_m));
            row.so3_score_abs_diff_rad=abs(so3-double(scoreRow.so3_rmse_rad));
            assert(row.position_score_abs_diff_m<=1e-12&&row.q8_score_abs_diff_m<=1e-12&& ...
                row.so3_score_abs_diff_rad<=1e-12,'AUDIT:ScoreDifference', ...
                'Independent metric differs from frozen scorer for %s.',id);
        else
            row.score_state='REFERENCE_RAW';
            row.position_score_abs_diff_m=abs(q0-double(b.q0_20_m));
            row.so3_score_abs_diff_rad=abs(so3-double(b.so3_rmse_rad));
            assert(row.position_score_abs_diff_m<=1e-12&&row.so3_score_abs_diff_rad<=1e-12, ...
                'AUDIT:BaselineMetric','Independent metric differs from paired baseline manifest for %s / %s.',id,method);
        end
        assert(numel(t)==20001&&row.complete_transitions&& ...
            strcmp(row.status,'STABLE')&&isempty(row.safety_stop_reason), ...
            'AUDIT:RunStatus','Incomplete or unstable raw for %s / %s.',id,method);
        out=out+1;rows(out)=row;clear d log scene;
    end
end
candidate=rows(strcmp({rows.method},'DL_MLP15'));
b=rows(strcmp({rows.method},'B'));
c=rows(strcmp({rows.method},'C5_RBF'));
c5FlagMismatches=c(~[c.baseline_completion_flag_consistent]);
if isempty(c5FlagMismatches),c5MismatchScenes='';else,c5MismatchScenes=strjoin({c5FlagMismatches.scene_id},',');end
summary=struct( ...
    'scene_count',numel(ids), ...
    'candidate_q0_20_mean_m',mean([candidate.q0_20_m]), ...
    'B_q0_20_mean_m',mean([b.q0_20_m]), ...
    'candidate_q_vs_B_improvement_fraction',1-mean([candidate.q0_20_m])/mean([b.q0_20_m]), ...
    'candidate_q8_12_mean_m',mean([candidate.q8_12_m]), ...
    'B_q8_12_mean_m',mean([b.q8_12_m]), ...
    'candidate_so3_mean_rad',mean([candidate.so3_rmse_rad]), ...
    'B_so3_mean_rad',mean([b.so3_rmse_rad]), ...
    'candidate_so3_vs_B_improvement_fraction',1-mean([candidate.so3_rmse_rad])/mean([b.so3_rmse_rad]), ...
    'C5_RBF_q0_20_mean_m',mean([c.q0_20_m]), ...
    'C5_RBF_so3_mean_rad',mean([c.so3_rmse_rad]), ...
    'B_baseline_completion_flag_mismatch_count',sum(~[b.baseline_completion_flag_consistent]), ...
    'C5_RBF_baseline_completion_flag_mismatch_count',numel(c5FlagMismatches), ...
    'C5_RBF_baseline_completion_flag_mismatch_scenes',c5MismatchScenes, ...
    'position_wins_vs_B',sum([candidate.q0_20_m]<[b.q0_20_m]-1e-12), ...
    'attitude_wins_vs_B',sum([candidate.so3_rmse_rad]<[b.so3_rmse_rad]-1e-12), ...
    'position_wins_vs_C5_RBF',sum([candidate.q0_20_m]<[c.q0_20_m]-1e-12), ...
    'attitude_wins_vs_C5_RBF',sum([candidate.so3_rmse_rad]<[c.so3_rmse_rad]-1e-12), ...
    'candidate_tilt_limited_total',sum([candidate.tilt_limited_count]), ...
    'B_tilt_limited_total',sum([b.tilt_limited_count]), ...
    'C5_RBF_tilt_limited_total',sum([c.tilt_limited_count]), ...
    'candidate_motor_saturation_count',sum([candidate.motor_saturation_count]), ...
    'candidate_generalized_clip_count',sum([candidate.generalized_clip_count]), ...
    'strict_v2_pilot_gate_passed',all([candidate.tilt_limited_count]==0), ...
    'raw_score_recompute_max_abs_difference_m',max([candidate.position_score_abs_diff_m,candidate.q8_score_abs_diff_m]), ...
    'raw_score_recompute_max_so3_difference_rad',max([candidate.so3_score_abs_diff_rad]));
report=struct('schema','DL1018_MLP15_GHP7_INDEPENDENT_SCORE_AUDIT_V1', ...
    'created_utc',char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z''')), ...
    'plant_invoked',false,'test_data_read',false,'raw_count',numel(rows), ...
    'independent_recompute',true,'time_samples_are_independent',false, ...
    'score_script_sha256',sha256_file(fullfile(researchRoot,'matlab','score_mlp15_ghp7_pilot_v2v.m')), ...
    'score_report_sha256',sha256_file(scorePath),'candidate_release_sha256', ...
    sha256_file(fullfile(researchRoot,'MLP15_PILOT_RELEASE_v2.json')), ...
    'summary',summary,'rows',rows);
outPath=fullfile(researchRoot,'MLP15_GHP7_SCORE_RECOMPUTE_AUDIT_v1.json');
assert(~isfile(outPath),'AUDIT:NoOverwrite','Independent score report already exists.');
fid=fopen(outPath,'w','n','UTF-8');assert(fid>=0,'AUDIT:Write','Cannot write independent report.');
c=onCleanup(@()fclose(fid));fwrite(fid,unicode2native([jsonencode(report,'PrettyPrint',true) newline],'UTF-8'),'uint8');clear c;
end

function row=empty_row()
row=struct('scene_id','','method','','wind_id','','raw_path','','raw_sha256','', ...
    'q0_20_m',NaN,'q8_12_m',NaN,'so3_rmse_rad',NaN,'status','','complete_transitions',false, ...
    'logged_complete_flag',false,'baseline_completion_flag_consistent',true, ...
    'safety_stop_reason','','tilt_limited_count',0,'motor_saturation_count',0, ...
    'generalized_clip_count',0,'score_state','','position_score_abs_diff_m',NaN, ...
    'q8_score_abs_diff_m',NaN,'so3_score_abs_diff_rad',NaN);
end
function h=sha256_file(p)
f=fopen(p,'rb');assert(f>=0,'AUDIT:FileOpen','Cannot read %s.',p);c=onCleanup(@()fclose(f));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(f,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear c;
end
function h=paired_sha256_double(a)
md=java.security.MessageDigest.getInstance('SHA-256');md.update(typecast(double(a(:)),'uint8'));
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
function R=rotation_zyx_local(e)
p=e(1);q=e(2);y=e(3);
R=[cos(y)*cos(q),cos(y)*sin(q)*sin(p)-sin(y)*cos(p),cos(y)*sin(q)*cos(p)+sin(y)*sin(p); ...
    sin(y)*cos(q),sin(y)*sin(q)*sin(p)+cos(y)*cos(p),sin(y)*sin(q)*cos(p)-cos(y)*sin(p); ...
    -sin(q),cos(q)*sin(p),cos(q)*cos(p)];
end
