function prepared=prepare_mlp15_dev72_no_plant(scenePayloadPath)
% Bind one exact DEV/VAL B72 scenario to the frozen C5+DSSM14 / MLP15 stack.
entry=fileparts(mfilename('fullpath'));
taskRoot=fileparts(fileparts(fileparts(entry)));
researchRoot=fileparts(taskRoot);
projectRoot=fileparts(fileparts(fileparts(taskRoot)));
runnerRoot=activate_paired_runner();
manifestPath=fullfile(taskRoot,'MLP15_DEV72_PAYLOAD_MANIFEST_v1.json');
manifest=jsondecode(fileread(manifestPath));
assert(strcmp(char(manifest.schema),'DL1018_MLP15_DEV72_PAYLOAD_MANIFEST_V1')&& ...
    strcmp(char(manifest.status),'PASS_NO_PLANT')&&double(manifest.scene_count)==72&& ...
    ~logical(manifest.test_data_read)&&double(manifest.plant_calls)==0&& ...
    strcmpi(sha256_file(fullfile(projectRoot,'experiments','position_axis_coordinate_c5_dev72_20261023', ...
    'C5_DEV72_INPUT_LOCK_v3.json')),char(manifest.source_c5_input_lock_sha256)), ...
    'DEV72:Manifest','Frozen DEV72 payload manifest is invalid.');
scenePayloadPath=char(java.io.File(char(scenePayloadPath)).getCanonicalPath());
hit=find(strcmp({manifest.records.payload_path},scenePayloadPath));
assert(isscalar(hit),'DEV72:PayloadPath','Payload is not a unique locked DEV72 path.');
record=manifest.records(hit);
assert(strcmp(sha256_file(scenePayloadPath),lower(char(record.payload_sha256)))&& ...
    isfile(char(record.b_raw_path))&&isfile(char(record.b_status_path)), ...
    'DEV72:PayloadSHA','Payload or bound B72 file is missing/changed.');
status=jsondecode(fileread(char(record.b_status_path)));
assert(strcmp(char(status.scene_id),char(record.scene_id))&& ...
    strcmpi(char(status.raw_sha256),char(record.b_raw_sha256))&& ...
    strcmp(char(status.log_status),'STABLE')&&double(status.transitions)==20000&& ...
    double(status.state_samples)==20001&&~logical(status.TEST_accessed), ...
    'DEV72:BStatus','Bound B72 status no longer matches the frozen manifest.');
vars=whos('-file',scenePayloadPath);
assert(isscalar(vars)&&strcmp(char(vars.name),'scene'), ...
    'DEV72:PayloadVariable','DEV72 payload must contain only the locked Plant scene.');
payload=load(scenePayloadPath,'scene');scene=payload.scene;
assert(strcmp(char(scene.scene_id),char(record.scene_id))&& ...
    any(startsWith(string(record.scene_id),["DL1018_DEV_","DL1018_VAL_"]))&& ...
    ~contains(string(record.scene_id),'TEST'), ...
    'DEV72:SceneID','Payload scene is not a locked DEV/VAL ID.');
lockPath=fullfile(projectRoot,'experiments','position_axis_coordinate_c5_dev72_20261023', ...
    'C5_DEV72_INPUT_LOCK_v3.json');
lock=jsondecode(fileread(lockPath));
lockHit=find(strcmp({lock.scenes.scene_id},char(record.scene_id)));
assert(isscalar(lockHit)&&strcmpi(char(lock.scenes(lockHit).B72_scoring.raw_sha256), ...
    char(record.b_raw_sha256))&&strcmpi(char(lock.scenes(lockHit).external_identity_sha256), ...
    char(record.external_identity_sha256)), ...
    'DEV72:InputLock','Scene/B72 identity differs from C5 lock v3.');
sourceIdentity=load(char(record.b_raw_path),'runIdentity');
assert(isfield(sourceIdentity,'runIdentity')&& ...
    strcmpi(char(sourceIdentity.runIdentity.external_identity_sha256), ...
    char(record.external_identity_sha256))&&~logical(sourceIdentity.runIdentity.TEST_accessed), ...
    'DEV72:ExternalIdentity','B raw external identity does not match the locked scene.');

c5ReceiptPath=fullfile(projectRoot,'experiments','attitude_physics_inertia_observer_20261025', ...
    'holdout_gate_inspection_v2','C5_R_TASK_BINDING_PILOT_RECEIPT_v5.json');
c5Receipt=jsondecode(fileread(c5ReceiptPath));
c5InputLockPath=char(c5Receipt.input_records.c5_input_lock.path);
c5SnapshotPath=char(c5Receipt.input_records.c5_snapshot_mat.path);
positionModelPath=char(c5Receipt.input_records.model_mat.path);
verify_record(c5Receipt.input_records.c5_input_lock,c5InputLockPath);
verify_record(c5Receipt.input_records.c5_snapshot_mat,c5SnapshotPath);
verify_record(c5Receipt.input_records.model_mat,positionModelPath);
assert(strcmp(char(c5Receipt.status),'PASS_NO_PLANT_PILOT_PAYLOADS_ONLY')&& ...
    double(c5Receipt.plant_calls)==0&&double(c5Receipt.training_runs)==0&& ...
    ~logical(c5Receipt.tests_data_read)&&strcmpi(c5Receipt.input_records.c5_input_lock.sha256, ...
    sha256_file(lockPath))&&strcmpi(c5Receipt.input_records.c5_input_lock.sha256, ...
    char(manifest.source_c5_input_lock_sha256)), ...
    'DEV72:C5Receipt','Frozen C5 no-Plant receipt does not bind this DEV72 stack.');
positionModelPack=load(positionModelPath,'model');snapshot=load(c5SnapshotPath,'cfg','W0');
model=positionModelPack.model;
assert(strcmp(char(model.model_id),'DSSM14')&&double(model.input_dim)==14&& ...
    double(model.window)==32&&isequal(double(model.output_W),double(snapshot.W0))&& ...
    strcmpi(paired_sha256_double(double(snapshot.W0)), ...
    char(c5Receipt.W0_sha256))&&strcmpi(normalizer_sha(model), ...
    char(c5Receipt.normalizer_arrays_sha256)), ...
    'DEV72:C5Model','C5 DSSM14 model/W0/normalizer identity mismatch.');
cfg=geometry_cfg(snapshot.cfg,'ACTIVE');

trainingDir=fullfile(researchRoot,'mlp15_formal_v1','run_v1');
trainingConfig=jsondecode(fileread(fullfile(trainingDir,'training_config.json')));
trainingProgress=jsondecode(fileread(fullfile(trainingDir,'training_progress.json')));
trainingRelease=jsondecode(fileread(fullfile(researchRoot,'mlp15_formal_v1','TRAINING_RELEASE_v1.json')));
weightsPath=fullfile(trainingDir,'mlp15_attitude_weights_v1.mat');
weightsSha=sha256_file(weightsPath);weights=load(weightsPath);
assert(strcmp(char(trainingConfig.status),'PASS')&&double(trainingConfig.optimizer_steps)==60000&& ...
    double(trainingConfig.best_step)==59000&&strcmp(char(trainingProgress.status),'PASS')&& ...
    double(trainingProgress.completed_steps)==60000&& ...
    ~logical(trainingConfig.test_data_read)&&~logical(trainingConfig.plant_truth_read)&& ...
    ~logical(trainingConfig.variable_inertia_reconstruction_used)&& ...
    strcmp(char(trainingRelease.status),'FROZEN')&&~logical(trainingRelease.test_data_read)&& ...
    strcmp(char(trainingConfig.target),'B logged rbf_output_raw at event k, pre-beta, rad/s^2'), ...
    'DEV72:Training','Frozen MLP15 training/checkpoint release identity failed.');
opts=make_gate_holdout_options(cfg,model,'DL_MLP15','ACTIVE',struct,weights,weightsSha);
identity=gate_holdout_identity_hashes(cfg,model,opts);
opts.gate_identity_lock=identity;
spec=gate_attitude_arm_spec('DL_MLP15');
assert(~spec.rbf_enabled&&~spec.physics_helper_enabled&&~spec.feedforward_enabled&& ...
    ~spec.observer_enabled&&strcmpi(identity.common.position_options_sha256, ...
    char(c5Receipt.common_position_options_sha256)), ...
    'DEV72:ControllerContract','MLP15 arm or shared C5 position identity is invalid.');
sceneAudit=gate_holdout_validate_scene(scene,cfg,'ACTIVE');
prepared=struct('scene',scene,'cfg',cfg,'model',model,'opts',opts,'identity',identity, ...
    'scene_audit',sceneAudit,'scene_payload_sha256',char(record.payload_sha256), ...
    'scene_payload_path',scenePayloadPath,'scene_id',char(record.scene_id), ...
    'external_identity_sha256',char(record.external_identity_sha256), ...
    'b_raw_path',char(record.b_raw_path),'b_raw_sha256',char(record.b_raw_sha256), ...
    'b_status_path',char(record.b_status_path),'b_status_sha256',char(record.b_status_sha256), ...
    'c5_input_lock_sha256',char(manifest.source_c5_input_lock_sha256), ...
    'c5_snapshot_sha256',char(c5Receipt.input_records.c5_snapshot_mat.sha256), ...
    'position_model_sha256',char(c5Receipt.input_records.model_mat.sha256), ...
    'mlp15_model_sha256',weightsSha,'mlp15_best_step',double(trainingConfig.best_step), ...
    'candidate_runner_root',runnerRoot,'attitude_arm','DL_MLP15','geometry_arm','ACTIVE');
end
function cfg=geometry_cfg(sourceCfg,geometryArm)
cfg=sourceCfg;if isfield(cfg,'attitude_replacement'),cfg=rmfield(cfg,'attitude_replacement');end
assert(strcmp(upper(char(geometryArm)),'ACTIVE'),'DEV72:Geometry','Expected ACTIVE geometry.');
cfg.plant.arm_initial=repmat(.15,4,1);cfg=bind_paired_fixed_j0(cfg);
end
function verify_record(record,path)
assert(isfile(path)&&strcmpi(sha256_file(path),char(record.sha256))&& ...
    strcmpi(char(java.io.File(path).getCanonicalPath()),char(java.io.File(char(record.path)).getCanonicalPath())), ...
    'DEV72:LockedInput','C5 locked input mismatch: %s',path);
end
function h=normalizer_sha(model)
md=java.security.MessageDigest.getInstance('SHA-256');
for name={'input_mu','input_sigma'}
    f=name{1};a=reshape(double(model.(f)),1,[]);
    header=[f char(0) '((1, 14), ''float64'')' char(0)];
    md.update(typecast(uint8(unicode2native(header,'UTF-8')),'int8'));
    md.update(typecast(a(:),'int8'));
end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
function h=sha256_file(path)
fid=fopen(path,'rb');assert(fid>=0,'DEV72:Read','Cannot open %s.',path);
cleanup=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear cleanup;
end



