function [memory,out]=mlp15_attitude_step_v1(action,memory,in,model)
% Frozen causal MLP15 attitude residual; no online weights or inertia reconstruction.
switch lower(char(action))
    case 'init'
        validate_model(model);
        memory=struct('history_normalized',zeros(13,14),'event_count',0);
        out=struct('initialized',true);
    case 'step'
        validate_model(model);
        required={'feature','J0','beta','dmax'};
        assert(isstruct(in)&&all(isfield(in,required)), ...
            'DLMLP:StepInput','Missing MLP15 step input fields.');
        feature=double(in.feature(:));J0=double(in.J0);
        beta=double(in.beta);dmax=double(in.dmax(:));
        assert(numel(feature)==13&&all(isfinite(feature))&&isequal(size(J0),[3,3])&& ...
            all(isfinite(J0),'all')&&numel(dmax)==3&&all(isfinite(dmax))&&all(dmax>0)&& ...
            isscalar(beta)&&isfinite(beta)&&beta>=0&&beta<=1, ...
            'DLMLP:StepShape','Invalid feature, J0, beta, or output limit.');
        assert(isstruct(memory)&&isequal(size(memory.history_normalized),[13,14])&& ...
            all(isfinite(memory.history_normalized),'all'), ...
            'DLMLP:Memory','MLP15 causal history is invalid.');
        xNorm=(feature-double(model.input_mean(:)))./double(model.input_std(:));
        window=[double(memory.history_normalized),xNorm];
        residual=mlp15_attitude_forward_v1(window,model);
        clipped=min(max(residual,-dmax),dmax);
        estimateTorque=J0*(beta*clipped);
        memory.history_normalized=window(:,2:end);
        memory.event_count=double(memory.event_count)+1;
        out=struct('raw_residual_rad_s2',residual, ...
            'clipped_residual_rad_s2',clipped,'beta',beta, ...
            'estimateTorque_Nm',estimateTorque,'feature_normalized',xNorm, ...
            'history_count',memory.event_count);
    otherwise
        error('DLMLP:Action','Unknown action %s.',char(action));
end
end

function validate_model(model)
required={'input_mean','input_std','target_rms','fc1_weight','fc1_bias', ...
    'fc2_weight','fc2_bias','head_weight','head_bias'};
assert(isstruct(model)&&all(isfield(model,required)), ...
    'DLMLP:Model','MLP15 model fields are incomplete.');
assert(numel(model.input_mean)==13&&numel(model.input_std)==13&& ...
    numel(model.target_rms)==3&&all(double(model.input_std(:))>0)&& ...
    all(double(model.target_rms(:))>0)&&all(isfinite([double(model.input_mean(:)); ...
    double(model.input_std(:));double(model.target_rms(:))])), ...
    'DLMLP:Normalizer','MLP15 normalizer is invalid.');
assert(isequal(size(model.fc1_weight),[64,195])&&numel(model.fc1_bias)==64&& ...
    isequal(size(model.fc2_weight),[32,64])&&numel(model.fc2_bias)==32&& ...
    isequal(size(model.head_weight),[3,32])&&numel(model.head_bias)==3&& ...
    all(isfinite(double(model.fc1_weight(:))))&&all(isfinite(double(model.fc1_bias(:))))&& ...
    all(isfinite(double(model.fc2_weight(:))))&&all(isfinite(double(model.fc2_bias(:))))&& ...
    all(isfinite(double(model.head_weight(:))))&&all(isfinite(double(model.head_bias(:)))), ...
    'DLMLP:WeightShape','MLP15 weights have invalid shapes or values.');
end
