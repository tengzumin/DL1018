function manifestPath=prepare_mlp15_dev72_payloads_v1()
% Extract exact scenario inputs from already-audited B72 raw files, without Plant.
here=fileparts(mfilename('fullpath'));
projectRoot=fileparts(fileparts(fileparts(here)));
researchRoot=fileparts(here);
lockPath=fullfile(projectRoot,'experiments','position_axis_coordinate_c5_dev72_20261023', ...
    'C5_DEV72_INPUT_LOCK_v3.json');
taskbookPath=fullfile(researchRoot,'MLP15_DEV72_EXPLORATORY_TASKBOOK_v1.md');
payloadRoot=fullfile(here,'payloads');
assert(isfile(lockPath)&&isfile(taskbookPath)&&isfolder(payloadRoot), ...
    'DEV72:Inputs','Required locked input or output path is missing.');
lockSha=sha256_file(lockPath);lock=jsondecode(fileread(lockPath));
assert(strcmp(char(lock.schema),'C5_AXIS_COORDINATE_DEV72_INPUT_LOCK_V3')&&numel(lock.scenes)==72&& ...
    numel(lock.scene_ids_all_72)==72 , ...
    'DEV72:Lock','Expected the existing exact DEV72 C5/B input lock.');
ids=string({lock.scenes.scene_id});
assert(numel(unique(ids))==72&&all(startsWith(ids,"DL1018_DEV_")|startsWith(ids,"DL1018_VAL_"))&& ...
    ~any(contains(ids,"TEST"))&&isequal(ids(:),string(lock.scene_ids_all_72(:))), ...
    'DEV72:Scope','Locked scene list is not exactly 72 unique DEV/VAL scenes.');
assert(all(arrayfun(@(x)strcmp(char(x.source_split),'DEV')||strcmp(char(x.source_split),'VAL'),lock.scenes)), ...
    'DEV72:Split','A locked scene is outside DEV/VAL.');
assert(isempty(dir(fullfile(payloadRoot,'*_scene_payload.mat'))), ...
    'DEV72:NoOverwrite','Payload directory is not empty; refusing to overwrite any artifact.');
records=repmat(struct('scene_id','','source_split','','external_identity_sha256','', ...
    'b_raw_path','','b_raw_sha256','','b_status_path','','b_status_sha256','', ...
    'payload_path','','payload_sha256','','transitions',0,'state_samples',0),72,1);
for k=1:72
    entry=lock.scenes(k);b=entry.B72_scoring;
    assert(strcmp(char(b.scene_id),char(entry.scene_id))&&isfile(char(b.raw_path))&& ...
        isfile(char(b.run_status_path))&&strcmpi(sha256_file(char(b.raw_path)),char(b.raw_sha256))&& ...
        strcmpi(sha256_file(char(b.run_status_path)),char(b.run_status_sha256)), ...
        'DEV72:BHash','B72 raw/status hash mismatch at %s.',entry.scene_id);
    status=jsondecode(fileread(char(b.run_status_path)));
    assert(strcmp(char(status.scene_id),char(entry.scene_id))&& ...
        strcmp(char(status.log_status),'STABLE')&&double(status.transitions)==20000&& ...
        double(status.state_samples)==20001&&double(status.plant_calls)==1&& ...
        double(status.training_steps)==0&&~logical(status.TEST_accessed)&& ...
        strcmpi(char(status.raw_sha256),char(b.raw_sha256)), ...
        'DEV72:BStatus','B72 status is not complete/stable or touched TEST at %s.',entry.scene_id);
    source=load(char(b.raw_path),'scene','runIdentity');
    assert(isfield(source,'scene')&&isfield(source,'runIdentity')&& ...
        strcmp(char(source.scene.scene_id),char(entry.scene_id))&& ...
        strcmp(char(source.runIdentity.scene_id),char(entry.scene_id))&& ...
        strcmpi(char(source.runIdentity.external_identity_sha256),char(entry.external_identity_sha256))&& ...
        strcmpi(char(source.runIdentity.scene_raw_sha256),char(entry.B_source.sha256))&& ...
        ~logical(source.runIdentity.TEST_accessed), ...
        'DEV72:SceneIdentity','B72 raw scene/run identity mismatch at %s.',entry.scene_id);
    assert(numel(source.scene.time)==20001&&isequal(size(source.scene.reference.position),[20001,3])&& ...
        isequal(size(source.scene.environment_wind_I),[20001,3])&& ...
        all(isfield(source.scene.arms,{'command','rho_true','rhoDot_true','rho_hat','rhoDot_hat'})), ...
        'DEV72:SceneShape','B72 scene input shape mismatch at %s.',entry.scene_id);
    scene=source.scene;payloadPath=fullfile(payloadRoot,[char(entry.scene_id) '_scene_payload.mat']);
    save(payloadPath,'scene','-v7.3');
    records(k)=struct('scene_id',char(entry.scene_id),'source_split',char(entry.source_split), ...
        'external_identity_sha256',char(entry.external_identity_sha256), ...
        'b_raw_path',char(b.raw_path),'b_raw_sha256',char(b.raw_sha256), ...
        'b_status_path',char(b.run_status_path),'b_status_sha256',char(b.run_status_sha256), ...
        'payload_path',payloadPath,'payload_sha256',sha256_file(payloadPath), ...
        'transitions',double(status.transitions),'state_samples',double(status.state_samples));
end
manifest=struct('schema','DL1018_MLP15_DEV72_PAYLOAD_MANIFEST_V1','status','PASS_NO_PLANT', ...
    'created_utc',char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z''')), ...
    'source_c5_input_lock_path',lockPath,'source_c5_input_lock_sha256',lockSha, ...
    'taskbook_path',taskbookPath,'taskbook_sha256',sha256_file(taskbookPath), ...
    'scene_count',72,'dev_scene_count',sum(startsWith(ids,"DL1018_DEV_")), ...
    'val_scene_count',sum(startsWith(ids,"DL1018_VAL_")),'test_data_read',false, ...
    'plant_calls',0,'training_runs',0,'payloads_copied_from_B_raw',false,'scene_payloads_extracted_from_B_raw',true, ...
    'payload_origin','scene variable extracted read-only from hash-verified B72 raw; saved as isolated input MAT', ...
    'records',records);
manifestPath=fullfile(here,'MLP15_DEV72_PAYLOAD_MANIFEST_v1.json');
write_json(manifestPath,manifest);
fprintf('MLP15_DEV72_PAYLOAD_MANIFEST=%s\n',manifestPath);
end
function h=sha256_file(path)
fid=fopen(path,'rb');assert(fid>=0,'DEV72:Read','Cannot open %s.',path);
cleanup=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear cleanup;
end
function write_json(path,x)
fid=fopen(path,'w');assert(fid>=0,'DEV72:Write','Cannot create %s.',path);
cleanup=onCleanup(@()fclose(fid));fwrite(fid,[jsonencode(x,'PrettyPrint',true) newline],'char');clear cleanup;
end


