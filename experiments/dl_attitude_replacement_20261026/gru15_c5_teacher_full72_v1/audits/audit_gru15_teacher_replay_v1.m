function report=audit_gru15_teacher_replay_v1()
% Offline same-state replay against frozen C5-RBF raw on the six GHP7 scenes.
auditDir=fileparts(mfilename('fullpath'));taskRoot=fileparts(auditDir);
researchRoot=fileparts(taskRoot);projectRoot=fileparts(fileparts(researchRoot));
addpath(fullfile(taskRoot,'candidate_runner_work','matlab','runtime'));
mlpTaskRoot=fullfile(researchRoot,'mlp15_c5_teacher_full72_v1');
addpath(fullfile(researchRoot,'pilot_runner_mlp15_c5_full72_v1', ...
    'candidate_runner_work','matlab','runtime'));
baselinePath=fullfile(researchRoot,'GHP7_BASELINE_REUSE_MANIFEST_v1.json');
baseline=jsondecode(fileread(baselinePath));
assert(strcmp(baseline.status,'PASS')&&~baseline.test_data_read&& ...
    ~baseline.raw_files_copied&&~baseline.baselines_reexecuted, ...
    'Replay:BaselineManifest','Frozen C5 baseline reuse manifest is invalid.');
trainDir=fullfile(taskRoot,'runs','C5_GRU15_FULL72_SEED2026102001');
model=load(fullfile(trainDir,'gru15_attitude_weights_v1.mat'));
modelSha=sha256_file(fullfile(trainDir,'gru15_attitude_weights_v1.mat'));
mlpModelPath=fullfile(mlpTaskRoot,'runs','C5_MLP15_FULL72_SEED2026102001', ...
    'mlp15_attitude_weights_v1.mat');
mlpModel=load(mlpModelPath);mlpModelSha=sha256_file(mlpModelPath);
receiptPath=fullfile(projectRoot,'experiments','attitude_physics_inertia_observer_20261025', ...
    'holdout_gate_inspection_v2','C5_R_TASK_BINDING_PILOT_RECEIPT_v5.json');
receipt=jsondecode(fileread(receiptPath));
snapshotPath=char(receipt.input_records.c5_snapshot_mat.path);
assert(strcmpi(sha256_file(snapshotPath),char(receipt.input_records.c5_snapshot_mat.sha256)), ...
    'Replay:C5Snapshot','Locked C5 config snapshot changed.');
snapshot=load(snapshotPath,'cfg');dmax=double(snapshot.cfg.rbf.attitude.dmax(:));
c5=baseline.records(strcmp({baseline.records.attitude_arm},'C5_RBF'));
assert(numel(c5)==6,'Replay:SceneCount','Expected six reused C5-RBF GHP7 records.');
rows=repmat(struct('scene_id','','raw_sha256','','event_count',0, ...
    'feature_reconstruction_max_abs',0,'rmse_rad_s2',nan(1,3), ...
    'teacher_rms_rad_s2',nan(1,3),'normalized_rmse',nan(1,3), ...
    'correlation',nan(1,3),'prediction_to_teacher_rms_ratio',nan(1,3), ...
    'mlp15_normalized_rmse',nan(1,3),'mlp15_correlation',nan(1,3), ...
    'mlp15_prediction_to_teacher_rms_ratio',nan(1,3), ...
    'max_abs_prediction_rad_s2',nan(1,3),'max_abs_normalized_input',nan(1,13), ...
    'input_coordinate_fraction_abs_z_gt3',NaN,'input_coordinate_fraction_abs_z_gt5',NaN, ...
    'prediction_clip_event_count_by_axis',zeros(1,3), ...
    'max_abs_raw_prediction_rad_s2',nan(1,3)),6,1);
allPrediction=zeros(0,3);allMlpPrediction=zeros(0,3);allTeacher=zeros(0,3);allDiff=zeros(0,3);
for i=1:6
    rec=c5(i);rawPath=char(rec.raw_path);rawSha=sha256_file(rawPath);
    assert(strcmpi(rawSha,char(rec.raw_sha256)), ...
        'Replay:RawHash','Reused C5 raw hash mismatch for %s.',char(rec.scene_id));
    pack=load(rawPath,'log');L=pack.log;
    events=find(logical(L.attitude_event_flag(:)));
    assert(numel(events)==1999&&size(L.rbf_output_raw,1)>=max(events)&& ...
        size(L.rbf_output_raw,2)==3,'Replay:TeacherShape','C5 teacher events/output invalid.');
    memory=zeros(13,14);mlpMemory=zeros(13,14);
    pred=zeros(numel(events),3);mlpPred=zeros(numel(events),3);teacher=zeros(numel(events),3);
    maxFeatureError=0;maxAbsZ=zeros(13,1);zOver3=0;zOver5=0;
    clipCount=zeros(1,3);maxRawPrediction=zeros(1,3);
    for j=1:numel(events)
        k=events(j);e=double(L.filtered_attitude_reference(k,:)).'-double(L.state(k,7:9)).';
        e=atan2(sin(e),cos(e));
        feature=[e;double(L.state(k,10:12)).'; ...
            double(L.attitude_bs_nominal_torque_Nm(k,:)).'; ...
            double(L.arms.command(k,:)).'];
        assert(numel(feature)==13&&all(isfinite(feature)), ...
            'Replay:Feature','Invalid legal C5-state GRU input for %s.',char(rec.scene_id));
        if isfield(L,'attitude_rbf_feature_13')
            logged=double(L.attitude_rbf_feature_13(k,:)).';
            maxFeatureError=max(maxFeatureError,max(abs(feature-logged)));
        end
        xNorm=(feature-double(model.input_mean(:)))./double(model.input_std(:));
        maxAbsZ=max(maxAbsZ,abs(xNorm));zOver3=zOver3+nnz(abs(xNorm)>3);
        zOver5=zOver5+nnz(abs(xNorm)>5);
        window=[memory,xNorm];y=gru15_attitude_forward_v1(window,model);
        yMlp=mlp15_attitude_forward_v1([mlpMemory,xNorm],mlpModel);
        clipCount=clipCount+(abs(y(:)).'>dmax(:).');
        maxRawPrediction=max(maxRawPrediction,abs(y(:).'));
        pred(j,:)=min(max(y(:),-dmax),dmax).';
        mlpPred(j,:)=min(max(yMlp(:),-dmax),dmax).';
        memory=window(:,2:end);
        mlpMemory=[mlpMemory(:,2:end),xNorm];
        teacher(j,:)=double(L.rbf_output_raw(k,:));
    end
    diff=pred-teacher;targetRms=sqrt(mean(teacher.^2,1));
    corrAxis=zeros(1,3);
    for axis=1:3
        c=corrcoef(pred(:,axis),teacher(:,axis));corrAxis(axis)=c(1,2);
    end
    mlpDiff=mlpPred-teacher;mlpCorr=zeros(1,3);
    for axis=1:3
        c=corrcoef(mlpPred(:,axis),teacher(:,axis));mlpCorr(axis)=c(1,2);
    end
    rows(i)=struct('scene_id',char(rec.scene_id),'raw_sha256',rawSha, ...
        'event_count',numel(events),'feature_reconstruction_max_abs',maxFeatureError, ...
        'rmse_rad_s2',sqrt(mean(diff.^2,1)),'teacher_rms_rad_s2',targetRms, ...
        'normalized_rmse',sqrt(mean(diff.^2,1))./max(targetRms,1e-12), ...
        'correlation',corrAxis, ...
        'prediction_to_teacher_rms_ratio',sqrt(mean(pred.^2,1))./max(targetRms,1e-12), ...
        'mlp15_normalized_rmse',sqrt(mean(mlpDiff.^2,1))./max(targetRms,1e-12), ...
        'mlp15_correlation',mlpCorr, ...
        'mlp15_prediction_to_teacher_rms_ratio',sqrt(mean(mlpPred.^2,1))./max(targetRms,1e-12), ...
        'max_abs_prediction_rad_s2',max(abs(pred),[],1), ...
        'max_abs_normalized_input',maxAbsZ(:).', ...
        'input_coordinate_fraction_abs_z_gt3',zOver3/(numel(events)*13), ...
        'input_coordinate_fraction_abs_z_gt5',zOver5/(numel(events)*13), ...
        'prediction_clip_event_count_by_axis',clipCount, ...
        'max_abs_raw_prediction_rad_s2',maxRawPrediction);
    allPrediction=[allPrediction;pred]; %#ok<AGROW>
    allMlpPrediction=[allMlpPrediction;mlpPred]; %#ok<AGROW>
    allTeacher=[allTeacher;teacher];allDiff=[allDiff;diff]; %#ok<AGROW>
end
axisRms=sqrt(mean(allDiff.^2,1));teacherRms=sqrt(mean(allTeacher.^2,1));
report=struct('schema','DL1018_GRU15_C5_TEACHER_GHP7_REPLAY_AUDIT_V1', ...
    'created_utc',char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z''')), ...
    'status','PASS_OFFLINE_REPLAY','plant_invoked',false,'plant_calls',0, ...
    'test_data_read',false,'six_scenes_all_included',true, ...
    'model_sha256',modelSha,'baseline_manifest_sha256',sha256_file(baselinePath), ...
    'mlp15_reference_model_sha256',mlpModelSha, ...
    'teacher_contract','C5 logged rbf_output_raw, post-dmax/pre-beta, rad/s^2', ...
    'input_contract',{{'wrapped attitude error x3','body rate x3', ...
        'nominal BS torque x3','morph command x4'}}, ...
    'dmax_rad_s2',dmax(:).','total_event_count',size(allDiff,1), ...
    'macro_rmse_rad_s2',axisRms,'macro_teacher_rms_rad_s2',teacherRms, ...
    'macro_normalized_rmse',axisRms./max(teacherRms,1e-12), ...
    'macro_prediction_to_teacher_rms_ratio',sqrt(mean(allPrediction.^2,1))./max(teacherRms,1e-12), ...
    'macro_correlation',axis_correlation(allPrediction,allTeacher), ...
    'mlp15_macro_normalized_rmse',sqrt(mean((allMlpPrediction-allTeacher).^2,1))./max(teacherRms,1e-12), ...
    'mlp15_macro_prediction_to_teacher_rms_ratio', ...
        sqrt(mean(allMlpPrediction.^2,1))./max(teacherRms,1e-12), ...
    'mlp15_macro_correlation',axis_correlation(allMlpPrediction,allTeacher), ...
    'rows',{rows});
outPath=fullfile(auditDir,'GRU15_C5_TEACHER_GHP7_REPLAY_AUDIT_v1.json');
fid=fopen(outPath,'w','n','UTF-8');assert(fid>=0,'Replay:ReportWrite','Cannot create replay audit.');
cleanup=onCleanup(@()fclose(fid));
fwrite(fid,unicode2native([jsonencode(report,'PrettyPrint',true) newline],'UTF-8'),'uint8');
clear cleanup
end

function c=axis_correlation(a,b)
c=zeros(1,size(a,2));
for j=1:size(a,2),q=corrcoef(a(:,j),b(:,j));c(j)=q(1,2);end
end

function h=sha256_file(path)
fid=fopen(path,'rb');assert(fid>=0,'Replay:HashOpen','Cannot read %s.',path);
cleanup=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear cleanup
end
