function report=audit_gru15_c5_full72_g1w00_v1()
% Read-only raw audit of the single released GRU15 G1/W00 attempt.
auditDir=fileparts(mfilename('fullpath'));taskRoot=fileparts(auditDir);
researchRoot=fileparts(taskRoot);projectRoot=fileparts(fileparts(researchRoot));
runDir=fullfile(researchRoot,'pilot_runs_gru15_c5_full72_v1', ...
    fullfile('DL1018_GHP7_G1_W00','attempt_01'));
releasePath=fullfile(taskRoot,'GRU15_C5_FULL72_PILOT_RELEASE_v1.json');
lockPath=fullfile(taskRoot,'GRU15_C5_FULL72_PILOT_SOURCE_LOCK_v1.json');
baselinePath=fullfile(researchRoot,'GHP7_BASELINE_REUSE_MANIFEST_v1.json');
payloadPath=fullfile(researchRoot,'GHP7_PILOT_PAYLOAD_MANIFEST_v1.json');
release=jsondecode(fileread(releasePath));lock=jsondecode(fileread(lockPath));
baseline=jsondecode(fileread(baselinePath));payload=jsondecode(fileread(payloadPath));
start=jsondecode(fileread(fullfile(runDir,'run_start.json')));
status=jsondecode(fileread(fullfile(runDir,'run_status.json')));
rawPath=fullfile(runDir,'raw_run.mat');rawSha=sha256_file(rawPath);
releaseSha=sha256_file(releasePath);sourceLockSha=sha256_file(lockPath);
assert(strcmp(release.status,'RELEASED')&&release.plant_calls_authorized==1&& ...
    isequal(string(release.authorized_scene_ids),"DL1018_GHP7_G1_W00")&& ...
    strcmpi(sourceLockSha,release.candidate_source_lock_sha256)&& ...
    strcmpi(sha256_file(fullfile(taskRoot,'GRU15_CLOSED_LOOP_PILOT_TASKBOOK_v1.md')), ...
        release.taskbook_sha256)&&~release.test_data_read, ...
    'G1Audit:Release','Release scope or source identity changed.');
p=payload.records(strcmp({payload.records.scene_id},'DL1018_GHP7_G1_W00'));
assert(isscalar(p)&&strcmpi(sha256_file(char(p.payload_path)),char(p.payload_file_sha256))&& ...
    strcmpi(start.pilot_release_sha256,releaseSha)&& ...
    strcmpi(start.candidate_source_lock_sha256,sourceLockSha)&& ...
    strcmp(char(start.attitude_arm),'DL_GRU15_C5_FULL72')&& ...
    strcmp(char(start.runtime_arm_id),'DL_GRU15')&& ...
    strcmpi(char(start.gru15_model_mat_sha256),char(release.model_sha256))&& ...
    strcmpi(char(start.taskbook_sha256),char(release.taskbook_sha256))&& ...
    strcmpi(start.scene_payload_sha256,char(p.payload_file_sha256))&& ...
    strcmpi(status.raw_output_sha256,rawSha)&&status.plant_calls==1&& ...
    strcmp(status.state,'COMPLETED')&&status.complete_transitions&& ...
    status.actual_transition_count==20000&&status.actual_state_sample_count==20001&& ...
    strcmp(status.status_value,'STABLE')&&isempty(status.safety_stop_reason), ...
    'G1Audit:RunIdentity','Candidate marker/status/raw does not match the one-call release.');

receiptPath=fullfile(projectRoot,'experiments','attitude_physics_inertia_observer_20261025', ...
    'holdout_gate_inspection_v2','C5_R_TASK_BINDING_PILOT_RECEIPT_v5.json');
receipt=jsondecode(fileread(receiptPath));snapshotPath=char(receipt.input_records.c5_snapshot_mat.path);
assert(strcmpi(sha256_file(snapshotPath),char(receipt.input_records.c5_snapshot_mat.sha256)), ...
    'G1Audit:C5Snapshot','Locked C5 config snapshot changed.');
snapshot=load(snapshotPath,'cfg');helperDir=fullfile(fileparts(receiptPath),'scene_builder_work');
addpath(helperDir);cleanup=onCleanup(@()rmpath(helperDir)); %#ok<NASGU>

methods={'B','C5_RBF','DL_GRU15_C5_FULL72'};rows=repmat(empty_row(),1,3);
for i=1:3
    method=methods{i};
    if strcmp(method,'DL_GRU15_C5_FULL72')
        thisPath=rawPath;expectedSha=rawSha;flagConsistent=true;
    elseif strcmp(method,'B')
        b=baseline.records(strcmp({baseline.records.scene_id},'DL1018_GHP7_G1_W00')& ...
            strcmp({baseline.records.runner},'B'));
        assert(isscalar(b),'G1Audit:BaselineB','B reference row is not unique.');
        thisPath=char(b.raw_path);expectedSha=char(b.raw_sha256);
        flagConsistent=logical(b.score_completion_flag_consistent);
    else
        b=baseline.records(strcmp({baseline.records.scene_id},'DL1018_GHP7_G1_W00')& ...
            strcmp({baseline.records.attitude_arm},'C5_RBF'));
        assert(isscalar(b),'G1Audit:BaselineC5','C5_RBF reference row is not unique.');
        thisPath=char(b.raw_path);expectedSha=char(b.raw_sha256);
        flagConsistent=logical(b.score_completion_flag_consistent);
    end
    assert(strcmpi(sha256_file(thisPath),expectedSha),'G1Audit:RawHash', ...
        'Raw hash differs for %s.',method);
    d=load(thisPath,'log','scene');log=d.log;scene=d.scene;
    assert(strcmp(char(scene.scene_id),'DL1018_GHP7_G1_W00')&& ...
        strcmpi(char(scene.R_task_sha256),char(p.r_task_sha256))&& ...
        strcmpi(paired_sha256_double(double(scene.R_task)),char(p.r_task_sha256)), ...
        'G1Audit:Scene','Scene or R_task identity differs for %s.',method);
    row=score_raw(log,scene,snapshot.cfg,method,thisPath,sha256_file(thisPath));
    row.baseline_completion_flag_consistent=flagConsistent;
    row.score_state='REFERENCE_RAW';
    if strcmp(method,'DL_GRU15_C5_FULL72')
        row.score_state='SCORED_COMPLETE';row.application_feasible= ...
            strcmp(row.status,'STABLE')&&row.complete_transitions&&row.logged_complete_flag&& ...
            row.trace_legal&&isempty(row.safety_stop_reason)&&~row.motor_saturation_any&& ...
            ~row.generalized_clip_any&&~row.tilt_limit_any&&row.geometry_pass_bidirectional&& ...
            row.geometry_pass_15mm&&row.q0_20_m<=.05&&row.q8_12_m<=.05&&row.end_position_error_m<=.10;
    end
    rows(i)=row;clear d log scene;
end
candidate=rows(3);b=rows(1);c=rows(2);
report=struct('schema','DL1018_GRU15_C5_FULL72_G1W00_RAW_AUDIT_V1', ...
    'created_utc',char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z''')), ...
    'plant_invoked',false,'test_data_read',false,'independent_metric_recompute',true, ...
    'time_samples_are_independent',false,'candidate_release_sha256',releaseSha, ...
    'candidate_source_lock_sha256',sourceLockSha,'candidate_raw_sha256',rawSha, ...
    'candidate_scene_id','DL1018_GHP7_G1_W00','candidate_complete_transitions',candidate.complete_transitions, ...
    'candidate_logged_complete_flag',candidate.logged_complete_flag, ...
    'candidate_status',candidate.status,'candidate_safety_stop_reason',candidate.safety_stop_reason, ...
    'candidate_application_feasible',candidate.application_feasible, ...
    'candidate_input_audit',candidate.input_audit, ...
    'candidate_q0_20_m',candidate.q0_20_m,'candidate_q8_12_m',candidate.q8_12_m, ...
    'candidate_rmse_xyz_m',candidate.rmse_xyz_m,'candidate_so3_rmse_rad',candidate.so3_rmse_rad, ...
    'candidate_end_position_error_m',candidate.end_position_error_m, ...
    'candidate_tilt_limited_count',candidate.tilt_limited_count, ...
    'candidate_motor_saturation_count',candidate.motor_saturation_count, ...
    'candidate_generalized_clip_count',candidate.generalized_clip_count, ...
    'candidate_minimum_clearance_m',candidate.minimum_clearance_m, ...
    'candidate_geometry_pass_bidirectional',candidate.geometry_pass_bidirectional, ...
    'candidate_geometry_pass_15mm',candidate.geometry_pass_15mm, ...
    'position_win_vs_B',candidate.q0_20_m<b.q0_20_m-1e-12, ...
    'attitude_win_vs_B',candidate.so3_rmse_rad<b.so3_rmse_rad-1e-12, ...
    'position_win_vs_C5_RBF',candidate.q0_20_m<c.q0_20_m-1e-12, ...
    'attitude_win_vs_C5_RBF',candidate.so3_rmse_rad<c.so3_rmse_rad-1e-12, ...
    'historical_C5_RBF_completion_flag_mismatch',~c.baseline_completion_flag_consistent, ...
    'rows',rows);
outPath=fullfile(auditDir,'G1_W00_RAW_AUDIT_v1.json');
assert(~isfile(outPath),'G1Audit:NoOverwrite','Audit output already exists.');
write_json(outPath,report);
end

function row=score_raw(log,scene,cfg,method,path,sha)
t=double(log.time(:));X=double(log.state);ref=double(log.reference.position);n=numel(t);
assert(n==20001&&size(X,1)==n&&size(X,2)==12&&isequal(size(ref),[n,3])&& ...
    all(isfinite([t;X(:);ref(:)])),'G1Audit:RawShape','Invalid/nonfinite raw arrays for %s.',method);
err=X(:,1:3)-ref;q8=t>=8-1e-10&t<=12+1e-10;
assert(sum(q8)==4001&&numel(scene.time)==n&&numel(log.transition_time)==n-1, ...
    'G1Audit:Timeline','Expected a complete 20 s, 1 ms scene for %s.',method);
theta=zeros(n,1);Rtask=double(scene.R_task);
for k=1:n
    R=rotation_zyx_local(X(k,7:9).');D=Rtask(:,:,k)'*R;
    theta(k)=acos(max(min((trace(D)-1)/2,1),-1));
end
complete=max(abs(t-double(scene.time(:))))<=1e-10&& ...
    double(log.last_transition)==n-1&&all(isfinite(X(:)))&&all(isfinite(ref(:)));
rho=double(log.arms.rho_true);geom=check_gate_inspection_geometry(t,X,rho,cfg);
row=empty_row();row.method=method;row.raw_path=path;row.raw_sha256=sha;
row.q0_20_m=sqrt(mean(sum(err.^2,2)));row.q8_12_m=sqrt(mean(sum(err(q8,:).^2,2)));
row.rmse_xyz_m=sqrt(mean(err.^2,1));row.so3_rmse_rad=sqrt(mean(theta.^2));
row.end_position_error_m=norm(err(end,:));row.status=char(string(log.status));
row.safety_stop_reason=char(string(log.safety_stop_reason));row.complete_transitions=complete;
row.logged_complete_flag=isfield(log,'complete_transitions')&&logical(log.complete_transitions);
row.tilt_limited_count=nnz(log.tilt_limited);row.motor_saturation_count=nnz(log.motor_saturated);
row.generalized_clip_count=nnz(log.generalized_clipped);
row.motor_saturation_any=row.motor_saturation_count>0;row.tilt_limit_any=row.tilt_limited_count>0;
row.generalized_clip_any=row.generalized_clip_count>0;
row.minimum_clearance_m=geom.minimum_clearance_m;
row.geometry_pass_bidirectional=geom.pass_bidirectional;
row.geometry_pass_15mm=geom.pass_15mm_proxy;
row.trace_legal=true;row.input_audit=struct('event_count',0,'max_abs_feature_reconstruction_error',0, ...
    'feature_dimension',13,'all_features_finite',true,'rbf_output_enabled_any',false, ...
    'rbf_update_enabled_any',false,'time_varying_inertia_reconstruction_used_any',false, ...
    'reconstruction_inputs_checked',{{'wrapped_attitude_error','body_rate','nominal_bs_torque','morph_command'}});
if strcmp(method,'DL_GRU15_C5_FULL72')
    nref=double(log.filtered_attitude_reference);nm=double(log.attitude_bs_nominal_torque_Nm);
    cmd=double(log.arms.command);traceLog=log.gru15_attitude_trace;
    assert(isequal(size(nref),[n-1,3])&&isequal(size(nm),[n-1,3])&& ...
        isequal(size(cmd),[n,4])&&numel(traceLog)==n-1&& ...
        ~logical(log.gru15_variable_inertia_reconstruction_used), ...
        'G1Audit:FeatureSource','Candidate raw lacks logged legal feature sources or uses inertia reconstruction.');
    events=traceLog(~cellfun(@isempty,traceLog));maxDiff=0;rbfOut=false;rbfUpdate=false;inertia=false;
    dmax=double(cfg.rbf.attitude.dmax(:));eventCounts=zeros(numel(events),1);
    for j=1:numel(events)
        z=events{j};k=double(z.sample_index);feature=double(z.feature_raw(:));
        e=nref(k,:).'-X(k,7:9).';e=atan2(sin(e),cos(e));
        expected=[e;X(k,10:12).';nm(k,:).';cmd(k,:).'];
        assert(numel(feature)==13&&all(isfinite(feature))&&all(isfinite(z.feature_normalized(:)))&& ...
            all(isfinite(z.estimateTorque_Nm(:)))&&numel(expected)==13, ...
            'G1Audit:FeatureFinite','Invalid candidate feature or inference output.');
        maxDiff=max(maxDiff,max(abs(feature-expected)));
        clipped=double(z.clipped_residual_rad_s2(:));
        eventCounts(j)=double(z.history_count);
        assert(numel(clipped)==3&&all(isfinite(clipped))&& ...
            all(abs(clipped)<=dmax+1e-12)&&all(isfinite(z.raw_residual_rad_s2(:)))&& ...
            double(z.beta)>=0&&double(z.beta)<=1, ...
            'G1Audit:OutputBound','GRU residual, beta, or C5 dmax output bound is invalid.');
        rbfOut=rbfOut||logical(z.rbf_output_enabled);rbfUpdate=rbfUpdate||logical(z.rbf_update_enabled);
        inertia=inertia||logical(z.time_varying_inertia_reconstruction_used);
    end
    row.trace_legal=maxDiff<=1e-10&&~rbfOut&&~rbfUpdate&&~inertia&& ...
        isequal(eventCounts(:),(1:numel(events)).');
    row.input_audit=struct('event_count',numel(events),'max_abs_feature_reconstruction_error',maxDiff, ...
        'feature_dimension',13,'all_features_finite',true,'rbf_output_enabled_any',rbfOut, ...
        'rbf_update_enabled_any',rbfUpdate,'time_varying_inertia_reconstruction_used_any',inertia, ...
        'reconstruction_inputs_checked',{{'wrapped_attitude_error','body_rate','nominal_bs_torque','morph_command'}});
end
end

function row=empty_row()
row=struct('method','','raw_path','','raw_sha256','','score_state','','q0_20_m',NaN,'q8_12_m',NaN, ...
    'rmse_xyz_m',nan(1,3),'so3_rmse_rad',NaN,'end_position_error_m',NaN,'status','', ...
    'safety_stop_reason','','complete_transitions',false,'logged_complete_flag',false, ...
    'baseline_completion_flag_consistent',true,'tilt_limited_count',0,'motor_saturation_count',0, ...
    'generalized_clip_count',0,'motor_saturation_any',false,'tilt_limit_any',false, ...
    'generalized_clip_any',false,'minimum_clearance_m',NaN,'geometry_pass_bidirectional',false, ...
    'geometry_pass_15mm',false,'trace_legal',true,'application_feasible',false,'input_audit',struct());
end
function R=rotation_zyx_local(e)
p=e(1);q=e(2);y=e(3);
R=[cos(y)*cos(q),cos(y)*sin(q)*sin(p)-sin(y)*cos(p),cos(y)*sin(q)*cos(p)+sin(y)*sin(p); ...
    sin(y)*cos(q),sin(y)*sin(q)*sin(p)+cos(y)*cos(p),sin(y)*sin(q)*cos(p)-cos(y)*sin(p); ...
    -sin(q),cos(q)*sin(p),cos(q)*cos(p)];
end
function h=paired_sha256_double(a)
md=java.security.MessageDigest.getInstance('SHA-256');md.update(typecast(double(a(:)),'uint8'));
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
function h=sha256_file(path)
fid=fopen(path,'rb');assert(fid>=0,'G1Audit:Open','Cannot read %s.',path);
c=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true,b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end;md.update(typecast(b(:),'int8'));end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear c;
end
function write_json(path,value)
fid=fopen(path,'w','n','UTF-8');assert(fid>=0,'G1Audit:Write','Cannot create %s.',path);
c=onCleanup(@()fclose(fid));fwrite(fid,unicode2native([jsonencode(value,'PrettyPrint',true) newline],'UTF-8'),'uint8');clear c;
end
