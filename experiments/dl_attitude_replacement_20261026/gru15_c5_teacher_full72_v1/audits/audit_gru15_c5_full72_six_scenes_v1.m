function row=score_raw(log,scene,cfg,method,path,sha)
t=double(log.time(:));X=double(log.state);ref=double(log.reference.position);n=numel(t);
assert(n==20001&&size(X,1)==n&&size(X,2)==12&&isequal(size(ref),[n,3])&& ...
    all(isfinite([t;X(:);ref(:)])),'SixAudit:RawShape','Invalid/nonfinite raw arrays for %s.',method);
err=X(:,1:3)-ref;q8=t>=8-1e-10&t<=12+1e-10;
assert(sum(q8)==4001&&numel(scene.time)==n&&numel(log.transition_time)==n-1, ...
    'SixAudit:Timeline','Expected a complete 20 s, 1 ms scene for %s.',method);
theta=zeros(n,1);Rtask=double(scene.R_task);
for k=1:n,R=rotation_zyx_local(X(k,7:9).');D=Rtask(:,:,k)'*R; ...
    theta(k)=acos(max(min((trace(D)-1)/2,1),-1));end
complete=max(abs(t-double(scene.time(:))))<=1e-10&& ...
    double(log.last_transition)==n-1&&all(isfinite(X(:)))&&all(isfinite(ref(:)));
geom=check_gate_inspection_geometry(t,X,double(log.arms.rho_true),cfg);
row=empty_row();row.method=method;row.raw_path=path;row.raw_sha256=sha;
row.q0_20_m=sqrt(mean(sum(err.^2,2)));row.q8_12_m=sqrt(mean(sum(err(q8,:).^2,2)));
row.rmse_xyz_m=sqrt(mean(err.^2,1));row.so3_rmse_rad=sqrt(mean(theta.^2));
row.end_position_error_m=norm(err(end,:));row.status=char(string(log.status));
row.safety_stop_reason=char(string(log.safety_stop_reason));row.complete_transitions=complete;
row.logged_complete_flag=isfield(log,'complete_transitions')&&logical(log.complete_transitions);
row.tilt_limited_count=nnz(log.tilt_limited);row.motor_saturation_count=nnz(log.motor_saturated);
row.generalized_clip_count=nnz(log.generalized_clipped);row.motor_saturation_any=row.motor_saturation_count>0;
row.tilt_limit_any=row.tilt_limited_count>0;row.generalized_clip_any=row.generalized_clip_count>0;
row.minimum_clearance_m=geom.minimum_clearance_m;row.geometry_pass_bidirectional=geom.pass_bidirectional;
row.geometry_pass_15mm=geom.pass_15mm_proxy;row.trace_legal=true;
row.input_audit=struct('event_count',0,'max_abs_feature_reconstruction_error',0, ...
    'feature_dimension',13,'all_features_finite',true,'rbf_output_enabled_any',false, ...
    'rbf_update_enabled_any',false,'time_varying_inertia_reconstruction_used_any',false);
if strcmp(method,'DL_GRU15_C5_FULL72')
    nref=double(log.filtered_attitude_reference);nm=double(log.attitude_bs_nominal_torque_Nm);
    cmd=double(log.arms.command);traceLog=log.gru15_attitude_trace;
    assert(isequal(size(nref),[n-1,3])&&isequal(size(nm),[n-1,3])&& ...
        isequal(size(cmd),[n,4])&&numel(traceLog)==n-1&& ...
        ~logical(log.gru15_variable_inertia_reconstruction_used), ...
        'SixAudit:FeatureSource','Candidate legal feature sources or reconstruction guard invalid.');
    events=traceLog(~cellfun(@isempty,traceLog));maxDiff=0;rbfOut=false;rbfUpdate=false;inertia=false;
    dmax=double(cfg.rbf.attitude.dmax(:));eventCounts=zeros(numel(events),1);
    for j=1:numel(events)
        z=events{j};k=double(z.sample_index);f=double(z.feature_raw(:));
        e=nref(k,:).'-X(k,7:9).';e=atan2(sin(e),cos(e));
        expected=[e;X(k,10:12).';nm(k,:).';cmd(k,:).'];
        assert(numel(f)==13&&all(isfinite(f))&&all(isfinite(z.feature_normalized(:)))&& ...
            all(isfinite(z.estimateTorque_Nm(:))), ...
            'SixAudit:FeatureFinite','Nonfinite/invalid GRU15 input or output.');
        maxDiff=max(maxDiff,max(abs(f-expected)));
        clipped=double(z.clipped_residual_rad_s2(:));eventCounts(j)=double(z.history_count);
        assert(numel(clipped)==3&&all(isfinite(clipped))&& ...
            all(abs(clipped)<=dmax+1e-12)&&all(isfinite(z.raw_residual_rad_s2(:)))&& ...
            double(z.beta)>=0&&double(z.beta)<=1, ...
            'SixAudit:OutputBound','GRU residual, beta, or C5 dmax bound is invalid.');
        rbfOut=rbfOut||logical(z.rbf_output_enabled);rbfUpdate=rbfUpdate||logical(z.rbf_update_enabled);
        inertia=inertia||logical(z.time_varying_inertia_reconstruction_used);
    end
    row.trace_legal=maxDiff<=1e-10&&~rbfOut&&~rbfUpdate&&~inertia&& ...
        isequal(eventCounts(:),(1:numel(events)).');
    row.input_audit=struct('event_count',numel(events),'max_abs_feature_reconstruction_error',maxDiff, ...
        'feature_dimension',13,'all_features_finite',true,'rbf_output_enabled_any',rbfOut, ...
        'rbf_update_enabled_any',rbfUpdate,'time_varying_inertia_reconstruction_used_any',inertia);
end
end
