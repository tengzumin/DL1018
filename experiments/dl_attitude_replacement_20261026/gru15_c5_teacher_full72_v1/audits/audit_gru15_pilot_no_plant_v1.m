function report=audit_gru15_pilot_no_plant_v1()
% Verify frozen GRU15 pilot preparation and source diagnostics without Plant.
entry=fileparts(mfilename('fullpath'));
taskRoot=fileparts(entry);
researchRoot=fileparts(taskRoot);
runnerRoot=fullfile(taskRoot,'candidate_runner_work');
addpath(fullfile(runnerRoot,'matlab','runtime'));
activate_paired_runner();
manifest=jsondecode(fileread(fullfile(researchRoot,'GHP7_PILOT_PAYLOAD_MANIFEST_v1.json')));
hit=find(strcmp({manifest.records.scene_id},'DL1018_GHP7_G1_W00')& ...
    strcmp({manifest.records.geometry_arm},'ACTIVE'));
assert(isscalar(hit),'GRU15:Payload','Expected one locked G1/W00 ACTIVE payload.');
payloadPath=char(manifest.records(hit).payload_path);
armReport=gate_holdout_no_plant_arm_check();
prepared=prepare_gate_candidate_no_plant(payloadPath,'DL_GRU15','ACTIVE');
assert(strcmp(char(prepared.scene.scene_id),'DL1018_GHP7_G1_W00')&& ...
    strcmp(prepared.attitude_arm,'DL_GRU15')&&strcmp(prepared.geometry_arm,'ACTIVE'), ...
    'GRU15:PreparedIdentity','No-Plant preparation returned an unexpected scene or arm.');

changed={'gate_attitude_arm_spec.m','make_gate_holdout_options.m', ...
    'prepare_gate_candidate_no_plant.m', ...
    'gate_holdout_no_plant_arm_check.m','run_gru15_candidate_gate_attempt.m', ...
    'gru15_attitude_forward_v1.m','gru15_attitude_step_v1.m'};
diagnosticCount=0;diagnostics=struct('file',{},'line',{},'id',{},'message',{});
for i=1:numel(changed)
    filePath=fullfile(runnerRoot,'matlab','runtime',changed{i});
    messages=checkcode(filePath,'-id');
    diagnosticCount=diagnosticCount+numel(messages);
    for j=1:numel(messages)
        diagnostics(end+1)=struct('file',changed{i},'line',double(messages(j).line), ...
            'id',char(messages(j).id),'message',char(messages(j).message)); %#ok<AGROW>
    end
end
assert(diagnosticCount==0,'GRU15:CodeAnalyzer','Changed MATLAB source has Code Analyzer diagnostics.');
projectRoot=fileparts(fileparts(fileparts(taskRoot)));
runnerFile='run_gate_holdout_closed_loop.m';
candidateRunnerFile=fullfile(runnerRoot,'matlab','runtime',runnerFile);
baselineRunnerFile=fullfile(projectRoot,'experiments', ...
    'dl_attitude_replacement_20261026','pilot_runner_mlp15_c5_full72_v1', ...
    'candidate_runner_work','matlab','runtime',runnerFile);
candidateRunnerDiagnostics=checkcode(candidateRunnerFile,'-id');
baselineRunnerDiagnostics=checkcode(baselineRunnerFile,'-id');
candidateFingerprints=sort(string({candidateRunnerDiagnostics.id}));
baselineFingerprints=sort(string({baselineRunnerDiagnostics.id}));
assert(isequal(candidateFingerprints,baselineFingerprints), ...
    'GRU15:RunnerDiagnostics','GRU insertion introduced MATLAB Code Analyzer diagnostics.');

sourceFiles=dir(fullfile(runnerRoot,'matlab','**','*.m'));
fileRows=repmat(struct('relative_path','','sha256',''),numel(sourceFiles),1);
for i=1:numel(sourceFiles)
    p=fullfile(sourceFiles(i).folder,sourceFiles(i).name);
    fileRows(i)=struct('relative_path',strrep(p(numel(runnerRoot)+2:end),filesep,'/'), ...
        'sha256',sha256_file(p));
end
report=struct('schema','DL1018_GRU15_C5_FULL72_NO_PLANT_AUDIT_V1', ...
    'status','PASS_NO_PLANT','created_utc',utcNow(),'plant_invoked',false, ...
    'test_data_read',false,'runner_matlab_file_count',numel(sourceFiles), ...
    'candidate_runner_files',{fileRows},'code_analyzer_status','PASS_NO_NEW_DIAGNOSTICS', ...
    'code_analyzer_diagnostic_count',diagnosticCount,'code_analyzer_diagnostics',{diagnostics}, ...
    'large_runner_existing_diagnostic_count',numel(candidateRunnerDiagnostics), ...
    'large_runner_no_new_diagnostics',true, ...
    'scene_id',char(prepared.scene.scene_id), ...
    'scene_payload_sha256',prepared.scene_payload_sha256, ...
    'model_sha256',prepared.gru15_model_mat_sha256, ...
    'position_model_sha256',prepared.position_model_mat_sha256, ...
    'dataset_manifest_sha256',prepared.dataset_manifest_sha256, ...
    'parity_report_sha256',prepared.parity_report_sha256, ...
    'taskbook_sha256',prepared.taskbook_sha256, ...
    'attitude_arm',prepared.attitude_arm,'geometry_arm',prepared.geometry_arm, ...
    'feature_dim',13,'causal_window_events',15,'fixed_J0_only',true, ...
    'rbf_output_enabled',false,'rbf_online_update_enabled',false, ...
    'time_varying_inertia_reconstruction_used',false, ...
    'max_tilt_rad',double(prepared.cfg.control.limits.max_tilt), ...
    'attitude_residual_dmax_rad_s2',double(prepared.cfg.rbf.attitude.dmax(:).'), ...
    'arm_mapping',armReport);
outPath=fullfile(entry,'MATLAB_NO_PLANT_AUDIT_GRU15_C5_FULL72_v1.json');
fid=fopen(outPath,'w');assert(fid>=0,'GRU15:ReportWrite','Cannot write no-Plant audit report.');
cleanup=onCleanup(@()fclose(fid));
fwrite(fid,[jsonencode(report,'PrettyPrint',true) newline],'char');
clear cleanup
end

function h=sha256_file(path)
fid=fopen(path,'rb');assert(fid>=0,'GRU15:HashRead','Cannot read %s.',path);
cleanup=onCleanup(@()fclose(fid));md=java.security.MessageDigest.getInstance('SHA-256');
while true
    b=fread(fid,8*1024*1024,'*uint8');if isempty(b),break;end
    md.update(typecast(b(:),'int8'));
end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));clear cleanup
end

function s=utcNow()
s=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z'''));
end
