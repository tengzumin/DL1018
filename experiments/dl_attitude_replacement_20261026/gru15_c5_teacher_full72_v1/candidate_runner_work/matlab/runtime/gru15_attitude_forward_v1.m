function residual=gru15_attitude_forward_v1(windowNormalized,model)
% Frozen GRU15 forward pass; window is 13-by-15, oldest event first.
assert(isstruct(model)&&all(isfield(model,{'gru_weight_ih','gru_weight_hh', ...
    'gru_bias_ih','gru_bias_hh','head_weight','head_bias','target_rms'})), ...
    'DLGRU:Model','GRU15 model fields are incomplete.');
x=double(windowNormalized);hsize=32;
assert(isequal(size(x),[13,15])&&all(isfinite(x),'all'), ...
    'DLGRU:Window','GRU15 input window must be finite 13-by-15.');
assert(isequal(size(model.gru_weight_ih),[3*hsize,13])&& ...
    isequal(size(model.gru_weight_hh),[3*hsize,hsize])&& ...
    numel(model.gru_bias_ih)==3*hsize&&numel(model.gru_bias_hh)==3*hsize&& ...
    isequal(size(model.head_weight),[3,hsize])&&numel(model.head_bias)==3&& ...
    numel(model.target_rms)==3, ...
    'DLGRU:WeightShape','GRU15 weights have invalid dimensions.');
assert(all(isfinite(double(model.gru_weight_ih(:))))&& ...
    all(isfinite(double(model.gru_weight_hh(:))))&& ...
    all(isfinite(double(model.gru_bias_ih(:))))&& ...
    all(isfinite(double(model.gru_bias_hh(:))))&& ...
    all(isfinite(double(model.head_weight(:))))&& ...
    all(isfinite(double(model.head_bias(:))))&& ...
    all(isfinite(double(model.target_rms(:))))&&all(double(model.target_rms(:))>0), ...
    'DLGRU:WeightFinite','GRU15 model contains non-finite or invalid values.');
wih=double(model.gru_weight_ih);whh=double(model.gru_weight_hh);
bih=double(model.gru_bias_ih(:));bhh=double(model.gru_bias_hh(:));
h=zeros(hsize,1);
for t=1:15
    gi=wih*x(:,t)+bih;gh=whh*h+bhh;
    reset=1./(1+exp(-(gi(1:hsize)+gh(1:hsize))));
    update=1./(1+exp(-(gi(hsize+1:2*hsize)+gh(hsize+1:2*hsize))));
    candidate=tanh(gi(2*hsize+1:3*hsize)+ ...
        reset.*gh(2*hsize+1:3*hsize));
    h=(1-update).*candidate+update.*h;
end
residual=double(model.head_weight)*h+double(model.head_bias(:));
residual=residual.*double(model.target_rms(:));
assert(numel(residual)==3&&all(isfinite(residual)), ...
    'DLGRU:Output','GRU15 output is invalid.');
end
