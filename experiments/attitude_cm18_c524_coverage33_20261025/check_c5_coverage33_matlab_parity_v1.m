function result = check_c5_coverage33_matlab_parity_v1(releaseSha256,checkpointSha256,exportReceiptSha256)
% Pure MATLAB inference parity check for one frozen C5_COVERAGE33 export.
if nargin~=3, error('C5Coverage33Parity:Args','Pass external release, checkpoint, and export-receipt SHA-256 values.'); end
assert((ischar(releaseSha256)&&isrow(releaseSha256))||(isstring(releaseSha256)&&isscalar(releaseSha256)), ...
    'C5Coverage33Parity:Args','Release SHA-256 must be a scalar string.');
assert((ischar(checkpointSha256)&&isrow(checkpointSha256))||(isstring(checkpointSha256)&&isscalar(checkpointSha256)), ...
    'C5Coverage33Parity:Args','Checkpoint SHA-256 must be a scalar string.');
assert((ischar(exportReceiptSha256)&&isrow(exportReceiptSha256))||(isstring(exportReceiptSha256)&&isscalar(exportReceiptSha256)), ...
    'C5Coverage33Parity:Args','Export receipt SHA-256 must be a scalar string.');
releaseSha256=lower(char(releaseSha256)); checkpointSha256=lower(char(checkpointSha256));
exportReceiptSha256=lower(char(exportReceiptSha256));
assert(all(cellfun(@(x)~isempty(regexp(x,'^[0-9a-f]{64}$','once')), ...
    {releaseSha256,checkpointSha256,exportReceiptSha256})), ...
    'C5Coverage33Parity:Args','All external SHA-256 pins must be 64 hexadecimal characters.');

here=fileparts(mfilename('fullpath')); root=fileparts(fileparts(here));
modelDir=fullfile(here,'models');
trainingDir=fullfile(here,'training_C5_COVERAGE33_v1');
releasePath=fullfile(root,'reports','attitude_cm18_c524_coverage33_20261025', ...
    'C5_COVERAGE33_TRAINING_RELEASE_v1.json');
trainingReceiptPath=fullfile(trainingDir,'run_receipt.json');
checkpointPath=fullfile(trainingDir,'final.pt');
modelPath=fullfile(modelDir,'C5_COVERAGE33_model.mat');
fixturePath=fullfile(modelDir,'matlab_parity_fixture.mat');
exportReceiptPath=fullfile(modelDir,'export_receipt.json');
helper=fullfile(root,'experiments','attitude_cm18_a1_20261024','matlab','cm18_a1_forward_v1.m');
exporter=fullfile(here,'export_c5_coverage33_v1.py');
checker=[mfilename('fullpath') '.m'];
helperSha='1ff450f9be6a5c16fe98cb4f169ef9930f1b806fecfc10ad664c11ce940f42e9';
reportDir=fullfile(root,'reports','attitude_cm18_c524_coverage33_20261025');
outputPath=fullfile(reportDir,'C5_COVERAGE33_MATLAB_PARITY_v1.json');

assert(isfile(releasePath)&&isfile(trainingReceiptPath)&&isfile(checkpointPath)&& ...
    isfile(modelPath)&&isfile(fixturePath)&&isfile(exportReceiptPath)&&isfile(helper)&& ...
    isfile(exporter)&&isfile(checker), ...
    'C5Coverage33Parity:Paths','A pinned release, final checkpoint, export, fixture, or helper is missing.');
assert(strcmpi(sha256_file(releasePath),releaseSha256)&& ...
    strcmpi(sha256_file(checkpointPath),checkpointSha256)&& ...
    strcmpi(sha256_file(exportReceiptPath),exportReceiptSha256), ...
    'C5Coverage33Parity:ExternalHash','An artifact differs from its externally supplied SHA-256.');
assert(strcmpi(sha256_file(helper),helperSha), ...
    'C5Coverage33Parity:HelperHash','The deployed CM18 forward helper differs from its frozen identity.');
assert(~isfile(outputPath),'C5Coverage33Parity:NoOverwrite','Refusing to overwrite the parity report.');

releaseText=fileread(releasePath);
release=jsondecode(releaseText); training=jsondecode(fileread(trainingReceiptPath));
receipt=jsondecode(fileread(exportReceiptPath));
modelRel='experiments/attitude_cm18_c524_coverage33_20261025/models/C5_COVERAGE33_model.mat';
fixtureRel='experiments/attitude_cm18_c524_coverage33_20261025/models/matlab_parity_fixture.mat';
checkpointRel='experiments/attitude_cm18_c524_coverage33_20261025/training_C5_COVERAGE33_v1/final.pt';
[releaseSourcePaths,releaseSourceShas]=verify_release_sources(releaseText,root);
train=release.training;
fixedTraining=train.seed==2026102001&&train.steps==60000&&train.batch_size==512&& ...
    strcmp(train.optimizer,'Adam')&&train.lr==0.001&& ...
    isequal(reshape(double(train.betas),1,[]),[0.9 0.999])&&train.eps==1e-8&& ...
    train.weight_decay==1e-5&& ...
    strcmp(train.loss,'SmoothL1 beta=1; mean over normalized three-axis output');
trainIds=cellstr(string(release.train_scene_ids(:)));
holdoutIds=cellstr(string(release.holdout_scene_ids(:)));
assert(strcmp(release.schema,'CM18_C5_COVERAGE33_TRAINING_RELEASE_V1')&& ...
    strcmp(release.decision,'APPROVE_ONE_MODEL_TRAINING')&& ...
    strcmp(release.output_directory,'experiments/attitude_cm18_c524_coverage33_20261025/training_C5_COVERAGE33_v1')&& ...
    fixedTraining&&release.train_scene_count==33&&release.fit_rows==13200&& ...
    numel(release.train_scene_ids)==33&&numel(release.holdout_scene_ids)==15&& ...
    isempty(intersect(trainIds,holdoutIds))&& ...
    ~release.holdout_or_validation_used_for_training_or_selection&& ...
    strcmp(release.checkpoint_selection,'none; fixed final step 60000')&& ...
    strcmp(release.model.architecture,'CM18-A1 18-32-32-24 tanh/bilinear')&& ...
    release.model.parameter_count==2456&&~release.TEST_accessed&&~release.C5_VAL48_accessed&& ...
    strcmpi(release.self_check.initial_float32_state_sha256,release.model.initial_float32_state_sha256)&& ...
    strcmp(training.schema,'CM18_C5_COVERAGE33_TRAINING_RECEIPT_V1')&& ...
    strcmp(training.status,'COMPLETED')&&training.candidate_frozen&& ...
    training.optimizer_steps_target==60000&&training.optimizer_steps_completed==60000&& ...
    training.optimizer_step_calls_attempted==60000&&training.fit_rows==13200&& ...
    numel(training.train_scene_ids)==33&& ...
    isequal(cellstr(string(training.train_scene_ids(:))),trainIds)&& ...
    strcmp(training.checkpoint_selection,'fixed_final_60000_no_validation_selection')&& ...
    ~training.holdout_used_for_training_or_selection&& ...
    ~training.TEST_accessed&&~training.C5_VAL48_accessed&&training.Plant_calls==0&& ...
    strcmpi(training.release_sha256,releaseSha256)&& ...
    strcmpi(training.final_checkpoint_sha256,checkpointSha256)&& ...
    strcmpi(training.initial_float32_state_sha256,release.model.initial_float32_state_sha256)&& ...
    strcmpi(training.final_float32_state_sha256,receipt.final_float32_state_sha256)&& ...
    strcmp(receipt.schema,'CM18_C5_COVERAGE33_EXPORT_V1')&&strcmp(receipt.status,'PASS')&& ...
    strcmp(receipt.candidate_id,'C5_COVERAGE33')&&strcmp(receipt.model_id,'C5_COVERAGE33')&& ...
    strcmp(receipt.architecture,'CM18-A1 18-32-32-24 tanh/bilinear')&&receipt.parameter_count==2456&& ...
    strcmp(receipt.model_mat_path,modelRel)&&strcmpi(receipt.model_mat_sha256,sha256_file(modelPath))&& ...
    strcmp(receipt.fixture_path,fixtureRel)&&strcmpi(receipt.fixture_sha256,sha256_file(fixturePath))&& ...
    strcmp(receipt.checkpoint_path,checkpointRel)&&strcmpi(receipt.checkpoint_sha256,checkpointSha256)&& ...
    strcmpi(receipt.training_release_sha256,releaseSha256)&& ...
    strcmpi(receipt.training_receipt_sha256,sha256_file(trainingReceiptPath))&& ...
    strcmp(receipt.exporter_path,'experiments/attitude_cm18_c524_coverage33_20261025/export_c5_coverage33_v1.py')&& ...
    strcmpi(receipt.exporter_sha256,sha256_file(exporter))&& ...
    strcmp(receipt.parity_checker_path,'experiments/attitude_cm18_c524_coverage33_20261025/check_c5_coverage33_matlab_parity_v1.m')&& ...
    strcmpi(receipt.parity_checker_sha256,sha256_file(checker))&& ...
    strcmpi(receipt.initial_float32_state_sha256,release.model.initial_float32_state_sha256)&& ...
    strcmpi(receipt.matlab_helper_sha256,helperSha)&&receipt.zero_basis_exact_zero&& ...
    receipt.plant_calls==0&&receipt.training_steps==60000&&receipt.optimizer_steps==60000&& ...
    ~receipt.TEST_accessed, ...
    'C5Coverage33Parity:Identity','Release, training, export, model, checkpoint, or fixture identity is invalid.');

addpath(fileparts(helper),'-begin'); clear cm18_a1_forward_v1; rehash;
assert(strcmpi(which('cm18_a1_forward_v1'),helper), ...
    'C5Coverage33Parity:HelperPath','Wrong CM18 forward helper resolved.');
f=load(fixturePath,'X18','C5_COVERAGE33_expected','zero_basis_rows');
assert(isequal(size(f.X18),[64,18])&&isequal(size(f.C5_COVERAGE33_expected),[64,3])&& ...
    all(isfinite(f.X18),'all')&&all(isfinite(f.C5_COVERAGE33_expected),'all')&& ...
    numel(f.zero_basis_rows)==1&&double(f.zero_basis_rows(1))==1&&all(f.X18(1,8:15)==0)&& ...
    all(f.C5_COVERAGE33_expected(1,:)==0), ...
    'C5Coverage33Parity:Fixture','Frozen Python parity fixture or zero-basis row is malformed.');
pack=load(modelPath,'model');
assert(isfield(pack,'model')&&isstruct(pack.model),'C5Coverage33Parity:Model','MAT model struct is missing.');
required={'W1','b1','W2','b2','W3','b3','input_mean','input_std','train_axis_rms_rad_s2'};
assert(isequal(sort(fieldnames(pack.model)),sort(required(:))), ...
    'C5Coverage33Parity:ModelFields','MAT model fields differ from the deployed CM18-A1 contract.');
p=pack.model;
assert(isequal(size(p.W1),[32,18])&&numel(p.b1)==32&& ...
    isequal(size(p.W2),[32,32])&&numel(p.b2)==32&& ...
    isequal(size(p.W3),[24,32])&&numel(p.b3)==24&& ...
    numel(p.input_mean)==18&&numel(p.input_std)==18&&numel(p.train_axis_rms_rad_s2)==3, ...
    'C5Coverage33Parity:ModelShape','MAT model tensor shapes differ from CM18-A1 18-32-32-24.');
parameterCount=numel(p.W1)+numel(p.b1)+numel(p.W2)+numel(p.b2)+numel(p.W3)+numel(p.b3);
assert(parameterCount==release.model.parameter_count&&all(double(p.input_std(:))>=1e-6)&& ...
    all(double(p.train_axis_rms_rad_s2(:))>0), ...
    'C5Coverage33Parity:ModelScale','MAT parameter count or normalization scales are invalid.');
for k=1:numel(required)
    values=p.(required{k});
    assert(isnumeric(values)&&isreal(values)&&all(isfinite(double(values(:)))), ...
        'C5Coverage33Parity:ModelFinite','MAT model field %s is not finite real numeric data.',required{k});
end
actual=zeros(size(f.C5_COVERAGE33_expected));
for k=1:size(f.X18,1)
    actual(k,:)=cm18_a1_forward_v1(f.X18(k,:),pack.model);
end
delta=actual-f.C5_COVERAGE33_expected;
axisMax=max(abs(delta),[],1);
zeroBasisExact=all(actual(1,:)==0)&&all(f.C5_COVERAGE33_expected(1,:)==0);
assert(all(isfinite(actual),'all')&&all(axisMax<=1e-10)&&zeroBasisExact, ...
    'C5Coverage33Parity:Numerics','MATLAB/Python parity or exact zero-basis constraint failed.');

result=struct('schema','CM18_C5_COVERAGE33_MATLAB_PARITY_V1','status','PASS', ...
    'scope','Pure MATLAB inference only; no Plant, optimizer, or TEST', ...
    'candidate_id','C5_COVERAGE33','release_sha256',releaseSha256, ...
    'checkpoint_sha256',checkpointSha256,'training_receipt_sha256',sha256_file(trainingReceiptPath), ...
    'release_source_paths',{releaseSourcePaths},'release_source_sha256',{releaseSourceShas}, ...
    'export_receipt_sha256',exportReceiptSha256,'model_mat_path',modelPath, ...
    'model_mat_sha256',sha256_file(modelPath),'fixture_path',fixturePath, ...
    'fixture_sha256',sha256_file(fixturePath),'helper_path',helper, ...
    'helper_sha256',sha256_file(helper),'exporter_sha256',sha256_file(exporter), ...
    'parity_checker_sha256',sha256_file(checker),'rows',size(actual,1), ...
    'max_abs_delta_by_axis_rad_s2',axisMax,'max_abs_delta_rad_s2',max(axisMax), ...
    'zero_basis_row_matlab_1based',1,'zero_basis_exact',zeroBasisExact, ...
    'plant_calls',0,'training_steps',0,'optimizer_steps',0, ...
    'model_training_steps',60000,'model_optimizer_steps',60000,'TEST_accessed',false, ...
    'created_at_utc',char(datetime('now','TimeZone','UTC', ...
    'Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z''')));
result.report_path=outputPath;
if ~isfolder(reportDir), mkdir(reportDir); end
write_json_new(outputPath,result);
fprintf('C5_COVERAGE33_MATLAB_PARITY=PASS; max_delta_xyz=[%.3g %.3g %.3g] rad/s^2\n',axisMax);
end

function [paths,shas]=verify_release_sources(releaseText,root)
block=regexp(releaseText,'"source_files"\s*:\s*\{([^}]*)\}','tokens','once');
assert(~isempty(block),'C5Coverage33Parity:SourceList','Training release source SHA map is missing.');
pairs=regexp(block{1},'"([^"]+)"\s*:\s*"([0-9a-fA-F]{64})"','tokens');
releaseObj=jsondecode(releaseText);
expected={'experiments/attitude_cm18_c524_coverage33_20261025/train_c5_coverage33_v1.py', ...
    'experiments/attitude_position_context_probe_20261024/b24_c524_paired_v1/train_cm18_b24_c524_paired_v1.py', ...
    'experiments/attitude_position_context_probe_20261024/b24_c524_paired_v1/read_b24_c524_paired_v1.py', ...
    'experiments/attitude_cm18_a1_20261024/model_cm18_v1.py', ...
    'experiments/attitude_cm18_a1_20261024/torch_model_cm18_v1.py'};
assert(numel(pairs)==numel(expected),'C5Coverage33Parity:SourceList','Unexpected release source count.');
assert(isfield(releaseObj,'source_files')&& ...
    numel(fieldnames(releaseObj.source_files))==numel(expected), ...
    'C5Coverage33Parity:SourceList','Release source SHA map has unexpected entries.');
paths=cell(1,numel(pairs)); shas=cell(1,numel(pairs));
for k=1:numel(pairs)
    pair=pairs{k}; paths{k}=pair{1}; shas{k}=lower(pair{2});
    assert(~startsWith(paths{k},'/')&&~contains(paths{k},'\')&& ...
        ~any(strcmp(regexp(paths{k},'/','split'),'..')), ...
        'C5Coverage33Parity:SourcePath','Unsafe release source path.');
    sourcePath=fullfile(root,strrep(paths{k},'/',filesep));
    assert(isfile(sourcePath)&&strcmpi(sha256_file(sourcePath),shas{k}), ...
        'C5Coverage33Parity:SourceHash','Training source differs from release SHA: %s.',paths{k});
end
assert(isequal(sort(paths),sort(expected)),'C5Coverage33Parity:SourceList', ...
    'Release source set differs from the frozen C5_COVERAGE33 training sources.');
end

function write_json_new(path,value)
assert(~isfile(path),'C5Coverage33Parity:NoOverwrite','Refusing to overwrite %s.',path);
folder=fileparts(path); if ~isfolder(folder), mkdir(folder); end
payload=[jsonencode(value) newline];
tempPath=fullfile(folder,['.C5_COVERAGE33_PARITY_TMP_' char(java.util.UUID.randomUUID()) '.json']);
tempFile=java.io.File(tempPath);
assert(tempFile.createNewFile(),'C5Coverage33Parity:Temp','Could not exclusively create temporary report.');
cleanup=onCleanup(@()delete_if_exists(tempPath)); %#ok<NASGU>
fid=fopen(tempPath,'w'); assert(fid>=0,'C5Coverage33Parity:Write','Cannot create temporary report.');
try
    count=fwrite(fid,payload,'char');
    closeStatus=fclose(fid); fid=-1;
    assert(closeStatus==0&&count==numel(payload),'C5Coverage33Parity:Write','Temporary report write was incomplete.');
catch ME
    if fid>=0, fclose(fid); end
    rethrow(ME);
end
from=java.nio.file.Paths.get(tempPath,javaArray('java.lang.String',0));
to=java.nio.file.Paths.get(path,javaArray('java.lang.String',0));
java.nio.file.Files.createLink(to,from);
java.nio.file.Files.delete(from);
clear cleanup;
end

function delete_if_exists(path)
if isfile(path), delete(path); end
end

function h=sha256_file(path)
md=java.security.MessageDigest.getInstance('SHA-256'); fid=fopen(path,'r');
assert(fid>=0,'C5Coverage33Parity:Read','Cannot read %s.',path);
closer=onCleanup(@()fclose(fid)); %#ok<NASGU>
while true
    bytes=fread(fid,8*1024*1024,'*uint8');
    if isempty(bytes), break; end
    md.update(bytes);
end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
