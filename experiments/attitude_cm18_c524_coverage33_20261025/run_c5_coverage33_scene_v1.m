assert(isequal(source.active_paths(:),paths(:))&&isequal(snapshotShas(:),shas(:))&& ...
    numel(coreIx)==1&&numel(wrapperIx)==1&&numel(helperIx)==1&& ...
    strcmp(char(source.c5_core_path),char(active(coreIx).path))&& ...
    strcmpi(char(source.c5_core_sha256),char(active(coreIx).sha256))&& ...
    strcmp(char(source.episode_wrapper_path),char(active(wrapperIx).path))&& ...
    strcmpi(char(source.episode_wrapper_sha256),char(active(wrapperIx).sha256))&& ...
    strcmp(char(source.prediction_helper_path),char(active(helperIx).path))&& ...
    strcmpi(char(source.prediction_helper_sha256),char(active(helperIx).sha256))&& ...
    strcmpi(inventory_sha(active),expectedSha), ...
    'C5Coverage33:SourceInventory','Snapshot source arrays or pinned inventory digest differ from the C5 input lock.');
for k=1:numel(active), verify_file(char(active(k).path),char(active(k).sha256)); end
for k=1:numel(shared), verify_file(char(shared(k).path),char(shared(k).sha256)); end
end
function h=inventory_sha(items)
parts=cell(1,3*numel(items));
for k=1:numel(items)
    parts{3*k-2}=char(items(k).role); parts{3*k-1}=char(items(k).path);
    parts{3*k}=lower(char(items(k).sha256));
end
bytes=unicode2native(strjoin(parts,newline),'UTF-8');
md=java.security.MessageDigest.getInstance('SHA-256'); md.update(typecast(uint8(bytes(:)),'int8'));
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
function verify_file(path,expected)
assert(isfile(path)&&strcmpi(sha256_file(path),expected),'C5Coverage33:FileHash','Missing or changed input: %s.',path);
end
function h=sha256_file(path)
md=java.security.MessageDigest.getInstance('SHA-256'); fid=fopen(path,'r');
assert(fid>=0,'C5Coverage33:Read','Cannot read %s.',path); c=onCleanup(@()fclose(fid)); %#ok<NASGU>
while true, b=fread(fid,8*1024*1024,'*uint8'); if isempty(b), break; end, md.update(b); end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
