function active=verified_c5_sources(source,lock,expectedSha)
required={'active_paths','active_sha256','which_checks','c5_core_path','c5_core_sha256', ...
    'episode_wrapper_path','episode_wrapper_sha256','prediction_helper_path','prediction_helper_sha256'};
