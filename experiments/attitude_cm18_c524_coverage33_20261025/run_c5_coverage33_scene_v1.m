    all(isfield(lock,{'active_source_inventory','shared_input_files'})), ...
    'C5Coverage33:SourceInventory','Frozen C5 source inventory schema is incomplete.');
active=lock.active_source_inventory(:); shared=lock.shared_input_files(:);
assert(all(isfield(active,{'role','path','sha256'}))&&all(isfield(shared,{'role','path','sha256'}))&& ...
    numel(active)==32&&numel(shared)==6&&numel(source.active_paths)==32&& ...
    numel(source.active_sha256)==32&&source.which_checks==31, ...
    'C5Coverage33:SourceInventory','Frozen C5 source inventory counts or fields changed.');
paths=arrayfun(@(x)char(x.path),active,'UniformOutput',false);
shas=arrayfun(@(x)lower(char(x.sha256)),active,'UniformOutput',false);
snapshotShas=cellfun(@(x)lower(char(x)),source.active_sha256(:),'UniformOutput',false);
coreIx=find(strcmp({active.role},'runtime_core'));
wrapperIx=find(strcmp({active.role},'episode_wrapper'));
