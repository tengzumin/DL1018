        double(log.rbf_event_count)==1999&&sum(log.attitude_event_flag)==1999, ...
        'C524Coverage:TeacherLog','C5 teacher log is incomplete or has no full RBF event schedule for %s.',id);

    E=extract_cm18_events_v1(cfg,raw.scene,log);
    assert(strcmp(E.schema,'CM18_RECONSTRUCTED_EVENTS_V1')&& ...
        isequal(size(E.X18),[1999,18])&&isequal(size(E.target_raw),[1999,3])&& ...
