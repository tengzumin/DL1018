        any(strcmp(status.status,{'RUN_COMPLETE_RAW_PENDING_AUDIT','RUN_COMPLETE_STABLE'}))&& ...
        strcmp(status.scene_id,id)&&strcmp(status.log_status,'STABLE')&& ...
        isempty(char(status.safety_stop_reason))&&double(status.transitions)==20000&& ...
        double(status.state_samples)==20001&&double(status.plant_calls)==1&& ...
        double(status.training_steps)==0&&double(status.optimizer_steps)==0&& ...
        ~logical(status.TEST_accessed)&&strcmpi(status.raw_sha256,rawSha)&& ...
        strcmpi(status.run_start_sha256,startSha), ...
        'C524Coverage:RunStatus','C5 source status is incomplete or mismatched for %s.',id);
    verify_file(char(status.first_plant_step_marker_path),char(status.first_plant_step_marker_sha256));
    identity=c5.sceneIdentity(ci); bPath=char(identity.B_raw_path); bSha=char(identity.B_raw_sha256);
    verify_file(bPath,bSha);
    raw=load(rawPath,'scene','log','runIdentity'); startPack=load(startPath,'runStart');
    bRaw=load(bPath,'scene','log');
    assert(all(isfield(raw,{'scene','log','runIdentity'}))&&isfield(startPack,'runStart')&& ...
        strcmp(raw.runIdentity.candidate,'C5_AXIS_MIXED_COORDINATE_M110')&& ...
        isequal(double(raw.runIdentity.coordinate_mask(:)),[1;1;0])&& ...
        strcmp(raw.scene.scene_id,id)&&isequaln(startPack.runStart.cfg,cfg), ...
        'C524Coverage:RawIdentity','C5 raw/run identity/cfg mismatch for %s.',id);
