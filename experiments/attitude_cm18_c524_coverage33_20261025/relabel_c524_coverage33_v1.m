rows=repmat(struct('scene_id','','split','','c5_raw_path','','c5_raw_sha256','', ...
    'c5_run_status_path','','c5_run_status_sha256','','c5_run_start_path','', ...
    'c5_run_start_sha256','','b_raw_path','','b_raw_sha256','', ...
