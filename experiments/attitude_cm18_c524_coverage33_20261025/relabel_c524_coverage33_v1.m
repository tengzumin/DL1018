    'DL1018_DEV_T2_C09_W10','DL1018_DEV_T2_C12_W13','DL1018_DEV_T2_C14_W14', ...
    'DL1018_DEV_T3_C06_W08','DL1018_DEV_T3_C09_W09','DL1018_DEV_T3_C10_W11', ...
    'DL1018_DEV_T3_C13_W12'};
ids=[trainExtra,holdout]; split=[repmat({'TRAIN_EXTRA'},1,numel(trainExtra)),repmat({'HOLDOUT'},1,numel(holdout))];
