function add_active_paths(items)
for k=1:numel(items), if endsWith(lower(items(k).path),'.m'), addpath(fileparts(items(k).path),'-end'); end, end
end
function verify_file(path,expected)
assert(isfile(path)&&strcmpi(sha256_file(path),expected),'C524Coverage:FileHash','Missing or changed file: %s.',path);
end
function h=sha256_file(path)
md=java.security.MessageDigest.getInstance('SHA-256'); fid=fopen(path,'r');
assert(fid>=0,'C524Coverage:Read','Cannot read %s.',path); c=onCleanup(@()fclose(fid)); %#ok<NASGU>
while true, b=fread(fid,8*1024*1024,'*uint8'); if isempty(b), break; end, md.update(b); end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
function h=inventory_sha(items)
parts=cell(1,3*numel(items));
for k=1:numel(items), parts{3*k-2}=items(k).path;parts{3*k-1}=items(k).sha256;parts{3*k}=num2str(k);end
h=sha256_text(strjoin(parts,char(10)));
end
function h=sha256_text(x)
md=java.security.MessageDigest.getInstance('SHA-256'); md.update(typecast(uint8(unicode2native(x,'UTF-8')),'int8'));
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
function tf=same_path(a,b)
tf=strcmpi(char(java.io.File(char(a)).getCanonicalPath()),char(java.io.File(char(b)).getCanonicalPath()));
end
function n=directory_bytes(path)
d=dir(fullfile(path,'**','*'));d=d(~[d.isdir]);n=sum(double([d.bytes]));
end
function write_json_new(path,x)
assert(~isfile(path),'C524Coverage:NoOverwrite','Refusing to overwrite %s.',path);
fid=fopen(path,'w');assert(fid>=0,'C524Coverage:Write','Cannot create %s.',path);c=onCleanup(@()fclose(fid)); %#ok<NASGU>
fwrite(fid,jsonencode(x),'char');
end
function t=utc_now()
t=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z'''));
end
