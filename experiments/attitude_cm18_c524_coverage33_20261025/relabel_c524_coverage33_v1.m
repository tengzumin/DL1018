verify_file(c5LockPath,'82024c01276cc4bfbd9b7772cf5332dee3fdfcbed422969589b68f1c90ed2d75');
verify_file(extractorPath,'15d8fb369b93e3a251d70c7eb7a590f732da839d35a5bebfb2011f25123e37c1');
lock=jsondecode(fileread(c5LockPath)); c5=load(c5SnapshotPath,'cfg','sceneIdentity','sourceIdentity');
assert(strcmp(lock.schema,'C5_AXIS_COORDINATE_DEV72_INPUT_LOCK_V3')&& ...
    numel(lock.scenes)==72&&sum(strcmp({lock.scenes.source_split},'DEV'))==24&& ...
    numel(c5.sceneIdentity)==72,'C524Coverage:SourceLock','Frozen C5 DEV72 source lock/snapshot changed.');

activePaths=cellstr(string(c5.sourceIdentity.active_paths(:)));
