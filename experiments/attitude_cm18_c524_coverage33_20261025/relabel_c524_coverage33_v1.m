    startPath=fullfile(runDir,'run_start.mat');
    assert(isfile(rawPath)&&isfile(statusPath)&&isfile(startPath), ...
        'C524Coverage:RawMissing','C5 raw/status/start is missing for %s.',id);
    status=jsondecode(fileread(statusPath)); rawSha=sha256_file(rawPath);
    startSha=sha256_file(startPath); statusSha=sha256_file(statusPath);
