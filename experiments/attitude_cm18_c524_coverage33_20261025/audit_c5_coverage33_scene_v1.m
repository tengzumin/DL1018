function h=inventory_sha(items)
parts=cell(1,3*numel(items));
for k=1:numel(items)
    parts{3*k-2}=char(items(k).role); parts{3*k-1}=char(items(k).path);
    parts{3*k}=lower(char(items(k).sha256));
end
bytes=unicode2native(strjoin(parts,newline),'UTF-8');
md=java.security.MessageDigest.getInstance('SHA-256'); md.update(typecast(uint8(bytes(:)),'int8'));
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
function verify_file(path,expected)
