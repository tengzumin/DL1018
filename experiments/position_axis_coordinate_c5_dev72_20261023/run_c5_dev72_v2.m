function batch=run_c5_dev72_v2(mode)
% Fixed C5 DEV72 batch plus an explicit no-Plant preflight-only mode.
preflightOnly=nargin==1&&strcmpi(char(mode),'PREFLIGHT_ONLY');
plantRun=nargin==1&&strcmpi(char(mode),'PARENT_APPROVED_C5_M110_DEV72_V2');
if ~(preflightOnly||plantRun)
    error('C5DEV72:Mode','Use PREFLIGHT_ONLY or the exact parent-approved V2 mode.');
end
here=fileparts(mfilename('fullpath')); repoRoot=fileparts(fileparts(here));
lockPath=fullfile(here,'C5_DEV72_INPUT_LOCK_v2.json');
contractPath=fullfile(here,'C5_DEV72_RUN_CONTRACT_v2.json');
prepPath=fullfile(here,'C5_DEV72_PREPARE_RESULT_v2.json');
snapshotPath=fullfile(here,'C5_DEV72_PREPARED_CFG_OPTS_v2.mat');
bindingPath=fullfile(here,'C5_DEV72_SOURCE_BINDING_v2.json');
releasePath=fullfile(here,'C5_DEV72_RELEASE_v2.json');
releaseContractPath=fullfile(here,'C5_DEV72_PARENT_RELEASE_CONTRACT_v2.json');
batchPath=fullfile(here,'C5_DEV72_BATCH_STATUS_v2.json');
bodyPath=fullfile(here,'C5_DEV72_BODY_COMPLETE_v2.json');
preflightPath=fullfile(here,'C5_DEV72_PREFLIGHT_FAILURE_v2.json');
runnerPreflightPath=fullfile(here,'C5_DEV72_RUNNER_PREFLIGHT_RESULT_v2.json');
attemptRoot=fullfile(here,'runs_dev72_v2'); batchWritten=false; batch=struct(); records=empty_records();
try
    needed={lockPath,contractPath,prepPath,snapshotPath,bindingPath,releaseContractPath};
    if ~preflightOnly, needed{end+1}=releasePath; end
    assert(all(cellfun(@isfile,needed))&&~any(isfile({batchPath,bodyPath,preflightPath,runnerPreflightPath})), ...
        'C5DEV72:NoRetry','Frozen inputs/release are required and previous batch outputs must remain absent.');
    lock=jsondecode(fileread(lockPath)); contract=jsondecode(fileread(contractPath));
    prep=jsondecode(fileread(prepPath)); binding=jsondecode(fileread(bindingPath));
    releaseContract=jsondecode(fileread(releaseContractPath));
    if preflightOnly, release=struct('b72_manifest_sha256',lock.b72_scoring_manifest_sha256);
    else, release=jsondecode(fileread(releasePath)); end
    lockSha=sha256_file(lockPath); contractSha=sha256_file(contractPath); prepSha=sha256_file(prepPath);
    snapshotSha=sha256_file(snapshotPath); bindingSha=sha256_file(bindingPath);
    if preflightOnly, releaseSha=''; else, releaseSha=sha256_file(releasePath); end
    releaseContractSha=sha256_file(releaseContractPath);
    runnerPath=[mfilename('fullpath') '.m']; runnerSha=sha256_file(runnerPath);
    assert(strcmp(lock.schema,'C5_AXIS_COORDINATE_DEV72_INPUT_LOCK_V2')&& ...
        strcmp(lock.state,'LOCKED_C5_M110_DEV72_NO_PLANT_WAIT_PARENT_RELEASE_V2')&& ...
        ~logical(lock.plant_authorized_by_this_lock)&&strcmp(prep.status,'PREPARED_C5_M110_DEV72_NO_PLANT_WAIT_PARENT_RELEASE_V2')&& ...
        strcmpi(prep.input_lock_sha256,lockSha)&&strcmpi(prep.run_contract_sha256,contractSha)&& ...
        strcmpi(prep.snapshot_sha256,snapshotSha)&&strcmpi(prep.source_binding_sha256,bindingSha)&& ...
        strcmp(contract.schema,'C5_AXIS_COORDINATE_DEV72_RUN_CONTRACT_V2')&& ...
        strcmp(contract.state,lock.state)&&isequal(double(contract.coordinate_mask(:)),[1;1;0])&& ...
        double(contract.limits.max_new_Plant)==60&&double(contract.limits.per_scene_output_reserve_bytes)==80000000&& ...
        double(contract.limits.max_output_bytes)==5*1024^3&&double(contract.limits.minimum_free_bytes)==30000000000&& ...
        strcmpi(binding.input_lock_sha256,lockSha)&&strcmpi(binding.run_contract_sha256,contractSha)&& ...
        strcmpi(binding.runner_sha256,runnerSha)&&same_path(binding.runner_path,runnerPath)&& ...
        strcmpi(binding.release_contract_sha256,releaseContractSha), ...
        'C5DEV72:FrozenInputs','No-Plant preparation/source binding does not match the frozen C5 inputs.');
    verify_file(lock.source_files.batch_runner.path,runnerSha);
    verify_file(binding.prepare_entry_path,binding.prepare_entry_sha256);
    verify_file(binding.no_plant_launcher_path,binding.no_plant_launcher_sha256);
    verify_file(binding.plant_launcher_path,binding.plant_launcher_sha256);
    sourceNames=fieldnames(lock.source_files);
    for q=1:numel(sourceNames)
        x=lock.source_files.(sourceNames{q});
        if isstruct(x)&&isfield(x,'path'), for z=1:numel(x), verify_ref(x(z)); end, end
    end
    upstreamNames=fieldnames(lock.upstream_refs);
    for q=1:numel(upstreamNames)
        x=lock.upstream_refs.(upstreamNames{q});
        if strcmp(upstreamNames{q},'screen_evidence_refs')
            for z=1:numel(x), verify_ref(x(z)); end
        else
            verify_ref(x);
        end
    end
    for k=1:numel(lock.active_source_inventory), verify_ref(lock.active_source_inventory(k)); end
    for k=1:numel(lock.shared_input_files), verify_ref(lock.shared_input_files(k)); end
    if ~preflightOnly
        verify_dev72_release_contract(releaseContract,release,lock,contract,prep,binding, ...
            lockSha,contractSha,prepSha,snapshotSha,bindingSha,releaseContractSha,runnerSha);
    end
    verify_upstream_evidence(lock,release);

    % Rebuild the exact C5 dependency path and compare all candidate settings before Plant use.
    active=lock.active_source_inventory; initPath=source_path(active,'init_dl1018.m');
    optionsPath=source_path(active,'position_only_search_options.m');
    headPath=source_path(active,'position_only_search_head_step.m');
    forwardPath=source_path(active,'position_stage1_model_forward_v2.m');
    add_active_paths(active); addpath(fullfile(repoRoot,'matlab','runtime'),'-end'); addpath(fullfile(repoRoot,'matlab','core'),'-end');
    addpath(fileparts(initPath),'-begin'); clear init_dl1018; rehash;
    [cfgNow,~,resolvedRoot]=init_dl1018();
    assert(same_path(resolvedRoot,repoRoot),'C5DEV72:ProjectRoot','Runtime resolved another project root.');
    add_active_paths(active); addpath(fullfile(repoRoot,'matlab','runtime'),'-end'); addpath(fullfile(repoRoot,'matlab','core'),'-end');
    addpath(fileparts(optionsPath),'-begin'); addpath(fileparts(headPath),'-begin');
    addpath(fileparts(forwardPath),'-begin'); addpath(here,'-begin');
    clear run_episode_dl1018 run_dl1018_closed_loop delayed_prediction_step_candidate ...
        position_only_search_options position_only_search_head_step position_stage1_model_forward_v2 init_dl1018; rehash;
    for k=1:numel(active)
        verify_ref(active(k)); [~,n,e]=fileparts(char(active(k).path));
        if strcmpi(e,'.m'), assert(same_path(which(n),active(k).path),'C5DEV72:WhichShadow','Locked source %s resolves to a shadow.',n); end
    end
    pack=load(snapshotPath,'cfg','opts','W0','modelIdentity','sceneIdentity','sourceIdentity');
    assert(isequaln(cfgNow,pack.cfg)&&leaf_count(pack.cfg)==120&&leaf_count(pack.opts)==43&& ...
        logical(pack.opts.position_delayed_prediction_enabled)&&isequal(double(pack.opts.position_coordinate_mask(:)),[1;1;0])&& ...
        numel(pack.sceneIdentity)==72&&double(pack.sourceIdentity.which_checks)==31, ...
        'C5DEV72:Snapshot','Prepared C5 cfg/opts/source/scene snapshot differs.');
    modelPath=source_role(lock.shared_input_files,'model_mat'); modelPack=load(modelPath,'model'); model=modelPack.model;
    optsCurrent=position_only_search_options(cfgNow,model,'FEATURE',12,1);
    optsCurrent.position_delayed_prediction_enabled=true; optsCurrent.position_coordinate_mask=[1;1;0];
    assert(isequaln(cfgNow,pack.cfg)&&isequaln(optsCurrent,pack.opts)&& ...
        isequal(double(model.output_W),double(pack.W0))&& ...
        strcmpi(hash_bytes(typecast(double(pack.W0(:)),'uint8')),contract.model.W0_sha256)&& ...
        strcmp(char(model.model_id),contract.model.id)&&double(model.seed)==double(contract.model.seed)&& ...
        double(model.selected_step)==double(contract.model.selected_step), ...
        'C5DEV72:ModelOrOpts','Frozen model, W0 or rebuilt C5 options changed.');
    assert(isequal(string({pack.sceneIdentity.scene_id}).',string(lock.scene_ids_all_72(:))), ...
        'C5DEV72:SceneIdentity','Prepared full scene identity order changed.');

    sceneIds=cellstr(string(lock.scene_ids_new_60(:)));
    assert(numel(sceneIds)==60&&isequal(sceneIds(:),cellstr(string(contract.scene_ids_new_60(:)))), ...
        'C5DEV72:FixedOrder','New C5 scenes differ from the original C3 DEV72 order.');
    maxBytes=double(contract.limits.max_output_bytes); reserve=double(contract.limits.per_scene_output_reserve_bytes);
    minFree=double(contract.limits.minimum_free_bytes);
    deadline=datetime(char(contract.limits.deadline_utc),'InputFormat',"yyyy-MM-dd'T'HH:mm:ss'Z'",'TimeZone','UTC');
    check_resources(here,repoRoot,maxBytes,reserve,minFree,deadline,numel(sceneIds));
    assert(~isfolder(attemptRoot)||isempty(dir(fullfile(attemptRoot,'**','attempt_started.marker')))&& ...
        (~isfolder(attemptRoot)||isempty(dir(fullfile(attemptRoot,'**','first_plant_step.marker')))), ...
        'C5DEV72:ExistingAttempts','New attempt/Plant markers already exist; do not overwrite or retry.');
    if preflightOnly
        batch=struct('schema','C5_AXIS_COORDINATE_DEV72_RUNNER_PREFLIGHT_RESULT_V2', ...
            'status','PREFLIGHT_PASS_WAIT_PARENT_RELEASE_V2','process_scope','PREFLIGHT_ONLY_NO_PLANT', ...
            'release_presence_and_release_contract_validation_skipped',true,'plant_calls',0, ...
            'training_steps',0,'optimizer_steps',0,'TEST_accessed',false,'scene_count',72, ...
            'new_scene_count',numel(sceneIds),'reuse_scene_count',12,'input_lock_sha256',lockSha, ...
            'run_contract_sha256',contractSha,'prepare_result_sha256',prepSha, ...
            'snapshot_sha256',snapshotSha,'source_binding_sha256',bindingSha, ...
            'runner_sha256',runnerSha,'created_utc',utc_now());
        write_json_new(runnerPreflightPath,batch);
        return;
    end

    shared=jsondecode(fileread(lock.upstream_refs.shared_heavy_job_release.path));
    assert(isfile(shared.shared_heavy_job_lock_path),'C5DEV72:SharedLock','Frozen shared job lock is missing.');
    raf=java.io.RandomAccessFile(shared.shared_heavy_job_lock_path,'rw'); channel=raf.getChannel(); jobLock=channel.tryLock();
    assert(~isempty(jobLock),'C5DEV72:ConcurrentHeavyJob','Shared heavy-job lock is held; do not wait or seize it.');
    lockCleanup=onCleanup(@()release_job_lock(jobLock,channel,raf)); %#ok<NASGU>
    if ~isfolder(attemptRoot), mkdir(attemptRoot); end
    batchId=['C5_DEV72_' strrep(utc_now(),':','')];
    batch=struct('schema','C5_AXIS_COORDINATE_DEV72_BATCH_STATUS_V2','status','RUNNING', ...
        'batch_id',batchId,'process_scope','ONE_SEQUENTIAL_MATLAB_PROCESS','release_sha256',releaseSha, ...
        'source_binding_sha256',bindingSha,'runner_sha256',runnerSha,'input_lock_sha256',lockSha, ...
        'prepare_result_sha256',prepSha,'snapshot_sha256',snapshotSha,'scene_ids_new_60',{sceneIds}, ...
        'completed_scenes',0,'plant_calls',0,'training_steps',0,'optimizer_steps',0, ...
        'TEST_accessed',false,'records',records,'created_utc',utc_now());
    write_json_new(batchPath,batch); batchWritten=true;
    for k=1:numel(sceneIds)
        id=char(sceneIds{k}); row=scene_row(lock,id); b72=row.B72_scoring;
        attemptDir=fullfile(attemptRoot,id,'C5_AXIS_MASK_M110','attempt_01');
        paths=struct('attempt_started',fullfile(attemptDir,'attempt_started.marker'), ...
            'plant_marker',fullfile(attemptDir,'first_plant_step.marker'),'raw',fullfile(attemptDir,'raw_run.mat'), ...
            'run_start',fullfile(attemptDir,'run_start.mat'),'run_status',fullfile(attemptDir,'run_status.json'), ...
            'failure',fullfile(attemptDir,'C5_DEV72_FAILURE_V2.json'));
        invocationEntered=false; attemptCreated=false; startedUtc=utc_now();
        try
            remaining=numel(sceneIds)-k+1;
            check_resources(here,repoRoot,maxBytes,reserve,minFree,deadline,remaining);
            verify_file(row.B_source.path,row.B_source.sha256);
            verify_file(b72.raw_path,b72.raw_sha256); verify_file(b72.run_status_path,b72.run_status_sha256);
            verify_status(b72,id,false);
            verify_file(bindingPath,bindingSha); verify_file(releasePath,releaseSha);
            for q=1:numel(active), verify_ref(active(q)); end
            assert(strcmp(row.candidate_action,'PROPOSE_NEW_C5_M110_RUN')&&~logical(row.C5_reuse.reused), ...
                'C5DEV72:SceneAction','Scene action/reuse status differs from locked scope.');
            ix=find(strcmp({pack.sceneIdentity.scene_id},id));
            assert(numel(ix)==1&&same_path(row.B_source.path,pack.sceneIdentity(ix).B_raw_path)&& ...
                strcmpi(row.B_source.sha256,pack.sceneIdentity(ix).B_raw_sha256), ...
                'C5DEV72:PreparedScene','Scene physical identity differs from preparation: %s.',id);
            assert(~isfolder(attemptDir),'C5DEV72:NoRetry','Attempt directory exists for %s.',id);
            scenePack=load(row.B_source.path,'scene'); scene=scenePack.scene; sourceSceneId=char(scene.scene_id);
            assert(valid_scene(scene,id),'C5DEV72:Scene','Frozen scene schema/time/alias failed for %s.',id);
            scene.scene_id=id;
            if ~isfolder(attemptDir), mkdir(attemptDir); attemptCreated=true; end
            startedUtc=utc_now();
            opts=pack.opts; opts.r2e_first_plant_step_marker=paths.plant_marker;
            assert(isequal(double(opts.position_coordinate_mask(:)),[1;1;0])&& ...
                isequal(double(opts.stage1_position_runtime.position_only_search_head.W0),double(pack.W0)), ...
                'C5DEV72:W0Reset','Candidate mask or W0 reset differs for %s.',id);
            runSceneIdentity=struct('scene_id',id,'source_scene_id',sourceSceneId, ...
                'identity',pack.sceneIdentity(ix),'external_identity_sha256',row.external_identity_sha256);
            runStart=struct('schema','C5_AXIS_COORDINATE_DEV72_RUN_START_V2','scene_id',id, ...
                'source_scene_id',sourceSceneId,'started_utc',startedUtc,'release_sha256',releaseSha, ...
                'input_lock_sha256',lockSha,'run_contract_sha256',contractSha, ...
                'prepare_result_sha256',prepSha,'cfg_opts_snapshot_sha256',snapshotSha, ...
                'model_identity',pack.modelIdentity,'scene_identity',runSceneIdentity, ...
                'B_physical_source_path',row.B_source.path,'B_physical_source_sha256',row.B_source.sha256, ...
                'B72_raw_path',b72.raw_path,'B72_raw_sha256',b72.raw_sha256, ...
                'B72_run_status_path',b72.run_status_path,'B72_run_status_sha256',b72.run_status_sha256, ...
                'C3_raw_path',row.C3_reference.raw_path,'C3_raw_sha256',row.C3_reference.raw_sha256, ...
                'source_paths',{arrayfun(@(x)char(x.path),active,'UniformOutput',false)}, ...
                'source_sha256',{arrayfun(@(x)char(x.sha256),active,'UniformOutput',false)}, ...
                'runner_path',runnerPath,'runner_sha256',runnerSha,'coordinate_mask',[1 1 0], ...
                'initial_W0_sha256',contract.model.W0_sha256,'cfg',pack.cfg,'opts',opts, ...
                'plant_calls_before_invocation',0,'training_steps',0,'optimizer_steps',0,'TEST_accessed',false);
            save(paths.run_start,'runStart','-v7.3');
            write_text(paths.attempt_started,[startedUtc newline 'ABOUT_TO_CALL_EPISODE' newline]);
            invocationEntered=true; clear run_dl1018_closed_loop delayed_prediction_step_candidate;
            log=run_episode_dl1018(scene,contract.candidate,pack.cfg,opts,paths.raw);
            assert(isfile(paths.raw)&&isfile(paths.plant_marker),'C5DEV72:PlantOutput', ...
                'Episode returned without raw or first-Plant marker for %s.',id);
            runIdentity=struct('schema','C5_AXIS_COORDINATE_DEV72_RUN_IDENTITY_V2','scene_id',id, ...
                'candidate',contract.candidate,'coordinate_mask',[1 1 0],'release_sha256',releaseSha, ...
                'input_lock_sha256',lockSha,'prepare_result_sha256',prepSha, ...
                'model_identity',pack.modelIdentity,'initial_W0_sha256',contract.model.W0_sha256, ...
                'external_identity_sha256',row.external_identity_sha256,'training_steps',0, ...
                'optimizer_steps',0,'TEST_accessed',false);
            save(paths.raw,'runIdentity','-append');
            logStatus=field_or_empty(log,'status'); safetyReason=field_or_empty(log,'safety_stop_reason');
            complete=strcmpi(logStatus,'STABLE')&&isempty(char(safetyReason))&& ...
                numel(log.time)==20001&&numel(log.transition_time)==20000&& ...
                double(log.last_transition)==20000&&all(isfinite(log.state(:)))&& ...
                all(isfinite(log.reference.position(:)));
            statusLabel='FAILED_NO_RETRY'; if complete, statusLabel='RUN_COMPLETE_RAW_PENDING_AUDIT'; end
            runStatus=struct('schema','C5_AXIS_COORDINATE_DEV72_RUN_STATUS_V2','status',statusLabel, ...
                'scene_id',id,'source_scene_id',sourceSceneId,'candidate',contract.candidate, ...
                'coordinate_mask',[1 1 0],'log_status',logStatus,'safety_stop_reason',char(safetyReason), ...
                'last_transition',double(log.last_transition),'transitions',numel(log.transition_time), ...
                'state_samples',numel(log.time),'raw_path',paths.raw,'raw_sha256',sha256_file(paths.raw), ...
                'run_start_path',paths.run_start,'run_start_sha256',sha256_file(paths.run_start), ...
                'run_status_path',paths.run_status, ...
                'attempt_started_marker_path',paths.attempt_started, ...
                'attempt_started_marker_sha256',sha256_file(paths.attempt_started), ...
                'first_plant_step_marker_path',paths.plant_marker, ...
                'first_plant_step_marker_sha256',sha256_file(paths.plant_marker), ...
                'physical_B_source_path',row.B_source.path,'physical_B_source_sha256',row.B_source.sha256, ...
                'scoring_B72_raw_path',b72.raw_path,'scoring_B72_raw_sha256',b72.raw_sha256, ...
                'scoring_B72_status_path',b72.run_status_path,'scoring_B72_status_sha256',b72.run_status_sha256, ...
                'C3_raw_path',row.C3_reference.raw_path,'C3_raw_sha256',row.C3_reference.raw_sha256, ...
                'release_sha256',releaseSha,'input_lock_sha256',lockSha,'run_contract_sha256',contractSha, ...
                'prepare_result_sha256',prepSha,'cfg_opts_snapshot_sha256',snapshotSha, ...
                'plant_invocation_entered',true,'plant_start_confirmed',isfile(paths.plant_marker), ...
                'plant_calls',1,'training_steps',0,'optimizer_steps',0,'parameter_or_seed_search',false, ...
                'TEST_accessed',false,'created_utc',utc_now());
            write_json_new(paths.run_status,runStatus);
            assert(complete,'C5DEV72:UnsafeStop','Scene %s stopped/incomplete; raw/status retained; no retry.',id);
            assert(directory_bytes(attemptDir)<=reserve&&directory_bytes(here)<=maxBytes, ...
                'C5DEV72:OutputCap','Per-scene 80-MB reserve or C5 5-GiB output cap exceeded.');
            records(end+1)=record_from_status(batchId,k,runStatus,b72,row); %#ok<AGROW>
            batch.status='RUNNING'; batch.completed_scenes=k; batch.plant_calls=k;
            batch.records=records; batch.updated_utc=utc_now(); write_json_replace(batchPath,batch);
        catch ME
            failure=struct('schema','C5_AXIS_COORDINATE_DEV72_FAILURE_V2','status','FAILED_NO_RETRY', ...
                'scene_id',id,'batch_index',k,'identifier',ME.identifier,'message',ME.message, ...
                'failed_utc',utc_now(),'attempt_dir',attemptDir,'attempt_created',attemptCreated, ...
                'plant_invocation_entered',invocationEntered,'plant_start_confirmed',isfile(paths.plant_marker), ...
                'plant_calls',double(invocationEntered),'raw_path',paths.raw, ...
                'partial_raw_preserved',isfile(paths.raw),'partial_raw_sha256',file_sha_if_exists(paths.raw), ...
                'run_start_sha256',file_sha_if_exists(paths.run_start),'input_lock_sha256',lockSha, ...
                'release_sha256',releaseSha,'completed_before_failure',k-1);
            if isfolder(attemptDir)&&~isfile(paths.failure), write_json_new(paths.failure,failure); end
            batch.status='FAILED_NO_RETRY'; batch.completed_scenes=numel(records);
            batch.plant_calls=numel(records)+double(invocationEntered); batch.records=records;
            batch.failure=failure; batch.updated_utc=utc_now(); write_json_replace(batchPath,batch);
            rethrow(ME);
        end
    end
    batch.status='COMPLETE_RAW_PENDING_PARENT_AUDIT'; batch.completed_scenes=60; batch.plant_calls=60;
    batch.records=records; batch.completed_utc=utc_now(); write_json_replace(batchPath,batch);
    body=struct('schema','C5_AXIS_COORDINATE_DEV72_BODY_COMPLETE_V2', ...
        'status','COMPLETE_RAW_PENDING_PARENT_AUDIT','batch_id',batchId, ...
        'matlab_process_count',1,'shared_matlab_os_exit_code',[], ...
        'completed_scene_count',60,'plant_calls',60,'scene_ids_new_60',{sceneIds}, ...
        'records',records,'source_binding_sha256',bindingSha,'release_sha256',releaseSha, ...
        'training_steps',0,'optimizer_steps',0,'TEST_accessed',false,'completed_utc',utc_now());
    write_json_new(bodyPath,body);
catch ME
    if ~batchWritten&&~isfile(preflightPath)
        write_json_new(preflightPath,struct('schema','C5_AXIS_COORDINATE_DEV72_PREFLIGHT_FAILURE_V2', ...
            'status','FAILED_BEFORE_BATCH','identifier',ME.identifier,'message',ME.message, ...
            'failed_utc',utc_now(),'plant_calls',0,'partial_work_started',false));
    elseif batchWritten&&isfile(batchPath)
        saved=jsondecode(fileread(batchPath));
        if strcmp(saved.status,'RUNNING')
            saved.status='FAILED_NO_RETRY'; saved.failure_outside_scene=struct('identifier',ME.identifier, ...
                'message',ME.message,'failed_utc',utc_now(),'plant_calls',saved.plant_calls);
            saved.updated_utc=utc_now(); write_json_replace(batchPath,saved);
        end
    end
    rethrow(ME);
end
end

function verify_dev72_release_contract(c,release,lock,contract,prep,binding,lockSha,contractSha,prepSha,snapshotSha,bindingSha,contractSha2,runnerSha)
assert(strcmp(c.schema,'C5_AXIS_COORDINATE_DEV72_PARENT_RELEASE_CONTRACT_V2')&& ...
    strcmp(c.state,'RELEASE_REQUIRED_AFTER_CODE_AND_NOPLANT_REVIEW_V2')&& ...
    all(isfield(release,c.required_fields))&&strcmp(release.schema,'C5_AXIS_COORDINATE_DEV72_PARENT_RELEASE_V2')&& ...
    strcmp(release.state,'APPROVED_C5_M110_DEV72_V2')&&logical(release.plant_authorized)&& ...
    double(release.max_new_Plant)==60&&strcmp(release.candidate,contract.candidate)&& ...
    strcmpi(release.launcher_sha256,binding.plant_launcher_sha256)&& ...
    strcmpi(release.input_lock_sha256,lockSha)&& ...
    strcmpi(release.run_contract_sha256,contractSha)&&strcmpi(release.prepare_result_sha256,prepSha)&& ...
    strcmpi(release.prepared_snapshot_sha256,snapshotSha)&&strcmpi(release.source_binding_sha256,bindingSha)&& ...
    strcmpi(release.runner_sha256,runnerSha)&&isequal(string(release.scene_ids_new_60(:)),string(lock.scene_ids_new_60(:)))&& ...
    strcmpi(release.c5_screen_summary_sha256,lock.c5_screen_summary_sha256)&& ...
    strcmpi(release.b72_manifest_sha256,lock.b72_scoring_manifest_sha256)&& ...
    strcmpi(release.parent_release_contract_sha256,contractSha2)&& ...
    double(release.training_steps)==0&&double(release.optimizer_steps)==0&& ...
    ~logical(release.parameter_or_seed_search)&&double(release.new_B_sorties)==0&& ...
