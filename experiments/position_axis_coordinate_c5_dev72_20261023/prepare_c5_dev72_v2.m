function result=prepare_c5_dev72_v2()
% No-Plant preparation for the fixed C5 M110 completion screen.
here=fileparts(mfilename('fullpath')); repoRoot=fileparts(fileparts(here));
lockPath=fullfile(here,'C5_DEV72_INPUT_LOCK_v2.json');
contractPath=fullfile(here,'C5_DEV72_RUN_CONTRACT_v2.json');
bindingPath=fullfile(here,'C5_DEV72_SOURCE_BINDING_v2.json');
resultPath=fullfile(here,'C5_DEV72_PREPARE_RESULT_v2.json');
snapshotPath=fullfile(here,'C5_DEV72_PREPARED_CFG_OPTS_v2.mat');
assert(isfile(lockPath)&&isfile(contractPath)&&isfile(bindingPath)&&~isfile(resultPath)&&~isfile(snapshotPath), ...
    'C5DEV72:NoOverwrite','Frozen lock/contract/binding must exist and prepare outputs must be absent.');
lock=jsondecode(fileread(lockPath)); contract=jsondecode(fileread(contractPath)); binding=jsondecode(fileread(bindingPath));
lockSha=sha256_file(lockPath); contractSha=sha256_file(contractPath); bindingSha=sha256_file(bindingPath);
allSceneIds=string(lock.scene_ids_all_72(:)); newSceneIds=string(lock.scene_ids_new_60(:));
reuseSceneIds=string(lock.scene_ids_reuse_12(:)); reuseMaskInAll=ismember(allSceneIds,reuseSceneIds);
assert(strcmp(lock.schema,'C5_AXIS_COORDINATE_DEV72_INPUT_LOCK_V2')&& ...
    strcmp(lock.state,'LOCKED_C5_M110_DEV72_NO_PLANT_WAIT_PARENT_RELEASE_V2')&& ...
    ~logical(lock.plant_authorized_by_this_lock)&&strcmp(contract.schema,'C5_AXIS_COORDINATE_DEV72_RUN_CONTRACT_V2')&& ...
    strcmp(contract.state,lock.state)&&isequal(double(lock.coordinate_mask(:)),[1;1;0])&& ...
    isequal(double(contract.coordinate_mask(:)),[1;1;0])&&logical(lock.pcf_auxiliary_enabled)&& ...
    logical(contract.pcf_auxiliary_enabled)&&double(lock.counts.total)==72&& ...
    double(lock.counts.new_c5_plants)==60&&double(lock.counts.c5_reuse)==12&& ...
    isequal(string(lock.scene_ids_all_72(:)),string(contract.scene_ids_all_72(:)))&& ...
    isequal(string(lock.scene_ids_new_60(:)),string(contract.scene_ids_new_60(:)))&& ...
    isequal(string(lock.scene_ids_reuse_12(:)),string(contract.scene_ids_reuse_12(:)))&& ...
    isequal(newSceneIds,allSceneIds(~reuseMaskInAll))&&isequal(reuseSceneIds,allSceneIds(reuseMaskInAll))&& ...
    numel(lock.scenes)==72&&numel(unique(string({lock.scenes.scene_id})))==72, ...
    'C5DEV72:Scope','C5 M110 DEV72 lock/contract scope or order changed.');
assert(strcmp(contract.candidate,'C5_AXIS_MIXED_COORDINATE_M110')&& ...
    strcmp(contract.scoring_comparator,'B_TRACEABLE_DEV72')&&double(contract.limits.max_new_Plant)==60&& ...
    double(contract.limits.max_output_bytes)==5*1024^3&&double(contract.limits.per_scene_output_reserve_bytes)==80000000&& ...
    double(contract.limits.minimum_free_bytes)==30000000000&&strcmp(contract.limits.deadline_utc,'2026-10-24T17:01:00Z')&& ...
    double(contract.limits.seconds_per_remaining_scene_for_deadline_guard)==180&& ...
    double(contract.limits.process_exit_buffer_seconds)==600&& ...
    double(contract.prohibitions.training_steps)==0&&double(contract.prohibitions.optimizer_steps)==0&& ...
    double(contract.prohibitions.new_B_sorties)==0&&~logical(contract.prohibitions.TEST_accessed)&& ...
    ~logical(contract.prohibitions.automatic_retry)&&~logical(contract.prohibitions.parameter_or_seed_search), ...
    'C5DEV72:Contract','C5 DEV72 limits or prohibitions differ from the frozen taskbook.');
assert(strcmpi(binding.input_lock_sha256,lockSha)&&strcmpi(binding.run_contract_sha256,contractSha)&& ...
    strcmpi(binding.prepare_entry_sha256,sha256_file(fullfile(here,'prepare_c5_dev72_v2.m')))&& ...
    same_path(binding.prepare_entry_path,fullfile(here,'prepare_c5_dev72_v2.m'))&& ...
    isequal(string(binding.scene_ids_all_72(:)),string(lock.scene_ids_all_72(:)))&& ...
    isequal(string(binding.scene_ids_new_60(:)),string(lock.scene_ids_new_60(:)))&& ...
    isequal(string(binding.scene_ids_reuse_12(:)),string(lock.scene_ids_reuse_12(:)))&& ...
    isequal(double(binding.coordinate_mask(:)),[1;1;0]), ...
    'C5DEV72:Binding','Input binding differs from the locked C5 DEV72 sources.');

% Verify source, upstream JSON and shared-input identities.
sourceNames=fieldnames(lock.source_files);
for f=1:numel(sourceNames)
    item=lock.source_files.(sourceNames{f});
    if isstruct(item)&&isfield(item,'path'), for j=1:numel(item), verify_ref(item(j)); end, end
end
upstreamNames=fieldnames(lock.upstream_refs);
for f=1:numel(upstreamNames)
    item=lock.upstream_refs.(upstreamNames{f});
    if strcmp(upstreamNames{f},'screen_evidence_refs')
        for j=1:numel(item), verify_ref(item(j)); end
    else
        verify_ref(item);
    end
end
active=lock.active_source_inventory;
assert(numel(active)==32&&double(lock.source_counts.total)==32&& ...
    double(lock.source_counts.matlab)==31&&double(lock.source_counts.mat)==1&& ...
    numel(lock.shared_input_files)==6,'C5DEV72:SourceCount','Expected frozen 32-source/31-M/1-MAT inventory.');
for k=1:numel(active), verify_ref(active(k)); end
for k=1:numel(lock.shared_input_files), verify_ref(lock.shared_input_files(k)); end
assert(strcmpi(lock.source_files.run_contract.sha256,contractSha)&& ...
    strcmpi(lock.source_files.batch_runner.sha256,binding.runner_sha256)&& ...
    same_path(binding.runner_path,fullfile(here,'run_c5_dev72_v2.m'))&& ...
    strcmpi(lock.source_files.batch_runner.sha256,sha256_file(fullfile(here,'run_c5_dev72_v2.m'))), ...
    'C5DEV72:SourceBinding','Runner or contract source reference changed.');

% Rebuild source lookup after init_dl1018 resets the MATLAB path.
initPath=source_path(active,'init_dl1018.m'); optionsPath=source_path(active,'position_only_search_options.m');
headPath=source_path(active,'position_only_search_head_step.m'); forwardPath=source_path(active,'position_stage1_model_forward_v2.m');
add_active_paths(active); addpath(fullfile(repoRoot,'matlab','runtime'),'-end'); addpath(fullfile(repoRoot,'matlab','core'),'-end');
addpath(fileparts(initPath),'-begin'); clear init_dl1018; rehash;
assert(same_path(which('init_dl1018'),initPath),'C5DEV72:InitPath','init_dl1018 resolved outside locked sources.');
[cfg,~,resolvedRoot]=init_dl1018();
assert(same_path(resolvedRoot,repoRoot),'C5DEV72:ProjectRoot','Runtime resolved a different project root.');
add_active_paths(active); addpath(fullfile(repoRoot,'matlab','runtime'),'-end'); addpath(fullfile(repoRoot,'matlab','core'),'-end');
addpath(fileparts(optionsPath),'-begin'); addpath(fileparts(headPath),'-begin');
addpath(fileparts(forwardPath),'-begin'); addpath(here,'-begin');
clear run_episode_dl1018 run_dl1018_closed_loop delayed_prediction_step_candidate ...
    position_only_search_options position_only_search_head_step position_stage1_model_forward_v2 init_dl1018; rehash;
whichChecks=0;
for k=1:numel(active)
    verify_ref(active(k)); [~,name,ext]=fileparts(char(active(k).path));
    if strcmpi(ext,'.m'), assert(same_path(which(name),active(k).path), ...
            'C5DEV72:WhichShadow','Locked source %s resolves to a shadow.',name); whichChecks=whichChecks+1; end
end
assert(whichChecks==31&&same_path(which('run_dl1018_closed_loop'),fullfile(here,'run_dl1018_closed_loop.m'))&& ...
    same_path(which('run_episode_dl1018'),fullfile(here,'run_episode_dl1018.m'))&& ...
    same_path(which('delayed_prediction_step_candidate'),fullfile(here,'delayed_prediction_step_candidate.m')), ...
    'C5DEV72:Isolation','Copied C5 core/wrapper/helper did not win path resolution.');

% Match the fresh runtime and model exactly to the audited C5 snapshot.
c3Lock=jsondecode(fileread(lock.upstream_refs.c3_input_lock.path));
c3Pack=load(lock.upstream_refs.c3_prepared_snapshot.path,'cfg','opts','W0','modelIdentity','sceneIdentity','sourceIdentity');
c5Pack=load(lock.upstream_refs.c5_prepared_snapshot.path,'cfg','opts','W0','modelIdentity','sceneIdentity','sourceIdentity');
assert(all(isfield(c3Pack,{'cfg','opts','W0','modelIdentity','sceneIdentity','sourceIdentity'}))&& ...
    all(isfield(c5Pack,{'cfg','opts','W0','modelIdentity','sceneIdentity','sourceIdentity'}))&& ...
    isequaln(cfg,c3Pack.cfg)&&isequaln(cfg,c5Pack.cfg)&&leaf_count(cfg)==120&& ...
    leaf_count(c5Pack.cfg)==120&&leaf_count(c3Pack.opts)==42&&leaf_count(c5Pack.opts)==43, ...
    'C5DEV72:ConfigShape','Fresh cfg and audited C3/C5 leaf counts differ.');
assert(isfield(c3Pack.opts,'position_delayed_prediction_enabled')&& ...
    ~isfield(c3Pack.opts,'position_coordinate_mask')&&isfield(c5Pack.opts,'position_coordinate_mask')&& ...
    isequal(double(c5Pack.opts.position_coordinate_mask(:)),[1;1;0]), ...
    'C5DEV72:Mask','The only candidate-specific option is M=diag(1,1,0).');
modelPath=source_role(lock.shared_input_files,'model_mat'); modelPack=load(modelPath,'model');
assert(isfield(modelPack,'model')&&isstruct(modelPack.model),'C5DEV72:Model','Frozen model is missing.');
model=modelPack.model; W0=double(model.output_W);
assert(strcmp(char(model.model_id),char(contract.model.id))&&double(model.seed)==double(contract.model.seed)&& ...
    double(model.selected_step)==double(contract.model.selected_step)&&double(model.input_dim)==14&&double(model.window)==32&& ...
    isequal(size(W0),[33 3])&&all(isfinite(W0(:)))&& ...
    strcmpi(hash_bytes(typecast(W0(:),'uint8')),contract.model.W0_sha256)&& ...
    strcmpi(hash_normalizer_arrays(model),contract.model.normalizer_arrays_sha256)&& ...
    isequal(W0,double(c3Pack.W0))&&isequal(W0,double(c5Pack.W0))&& ...
    strcmpi(c3Pack.modelIdentity.W0_sha256,contract.model.W0_sha256)&& ...
    strcmpi(c5Pack.modelIdentity.W0_sha256,contract.model.W0_sha256)&& ...
    strcmpi(c3Pack.modelIdentity.normalizer_arrays_sha256,contract.model.normalizer_arrays_sha256)&& ...
    strcmpi(c5Pack.modelIdentity.normalizer_arrays_sha256,contract.model.normalizer_arrays_sha256), ...
    'C5DEV72:ModelIdentity','DSSM14, W0 or normalizer differs from audited C3/C5 identity.');
opts=position_only_search_options(cfg,model,'FEATURE',12,1);
opts.position_delayed_prediction_enabled=true; opts.position_coordinate_mask=[1;1;0];
assert(isequaln(opts,c5Pack.opts)&&isequaln(rmfield(opts,'position_coordinate_mask'),c3Pack.opts), ...
    'C5DEV72:Opts','Fresh opts differ from the audited C5 mask and frozen C3 base.');

% Reuse the exact full C3 identity structures, and verify all referenced outcome JSONs.
requiredIdentity={'B_raw_path','B_raw_sha256','alias_normalized_in_memory','canonical_scene_id', ...
    'payload_review_sha256','raw_scene_id','scene_id'};
assert(isstruct(c3Pack.sceneIdentity)&&numel(c3Pack.sceneIdentity)==72&& ...
    all(isfield(c3Pack.sceneIdentity,requiredIdentity))&& ...
    isequal(string({c3Pack.sceneIdentity.scene_id}).',string(c3Lock.scene_ids_all_72(:)))&& ...
    isequal(string({c3Lock.scenes.scene_id}).',string(lock.scene_ids_all_72(:))), ...
    'C5DEV72:SceneIdentity','C3 full 72-scene identity rows/fields are incomplete or out of order.');
sceneIdentity=repmat(c3Pack.sceneIdentity(1),1,72);
for k=1:72
    id=char(lock.scene_ids_all_72{k}); row=scene_row(lock,id);
    ix=find(strcmp({c3Pack.sceneIdentity.scene_id},id));
    assert(numel(ix)==1&&same_path(row.B_source.path,c3Pack.sceneIdentity(ix).B_raw_path)&& ...
        strcmpi(row.B_source.sha256,c3Pack.sceneIdentity(ix).B_raw_sha256), ...
        'C5DEV72:IdentityMap','C3 physical-source and scene identity disagree for %s.',id);
    assert(isfile(row.B_source.path),'C5DEV72:PhysicalSource','Locked physical B source is missing for %s.',id);
    verify_scene_evidence(row.C3_reference,id);
    verify_status(row.C3_reference,id,false);
    b=row.B72_scoring; verify_comparator(b,id); verify_status(b,id,false);
    if logical(row.C5_reuse.reused)
        assert(strcmp(row.candidate_action,'REUSE_AUDITED_C5_SCREEN')&& ...
            double(row.C5_reuse.parent_screen_event_count)==1968&& ...
            strcmp(row.C5_reuse.parent_screen_status,'PASS_C5_RAW_ALL_EVENTS'), ...
            'C5DEV72:C5Reuse','C5 screen reuse is not the exact parent-audited scene.');
        verify_scene_evidence(row.C5_reuse,id); verify_status(row.C5_reuse,id,true);
        oldIx=find(strcmp({c5Pack.sceneIdentity.scene_id},id));
        assert(numel(oldIx)==1&&isequaln(c5Pack.sceneIdentity(oldIx),c3Pack.sceneIdentity(ix)), ...
            'C5DEV72:C5Identity','Reused C5 scene identity differs from C3 physical identity for %s.',id);
    else
        assert(strcmp(row.candidate_action,'PROPOSE_NEW_C5_M110_RUN'), ...
            'C5DEV72:NewAction','A new scene is incorrectly marked as C5 reuse.');
    end
    sceneIdentity(k)=c3Pack.sceneIdentity(ix);
end
reuseMask=arrayfun(@(r)logical(r.C5_reuse.reused),lock.scenes);
assert(sum(reuseMask)==12&&isequal(string({lock.scenes(reuseMask).scene_id}).',string(lock.scene_ids_reuse_12(:))), ...
    'C5DEV72:ReuseCount','The only reuse rows must be the exact twelve audited C5 scenes.');

% Reuse the C5 cross-language check, since core and helper bytes are unchanged.
syntheticPath=lock.source_files.c5_crosslang_result.path;
fixturePath=lock.source_files.c5_crosslang_fixture.path;
synthetic=jsondecode(fileread(syntheticPath)); helper=active(strcmp({active.role},'prediction_helper'));
assert(numel(helper)==1&&strcmp(synthetic.schema,'C5_AXIS_COORDINATE_CROSSLANG_RESULT_V1')&& ...
    strcmp(synthetic.status,'PASS_SYNTHETIC_CROSSLANGUAGE_ONLY')&& ...
    ~logical(synthetic.plant_or_real_data_used)&&double(synthetic.tolerance_abs)==2e-12&& ...
    strcmpi(synthetic.fixture_sha256,sha256_file(fixturePath))&& ...
    strcmpi(synthetic.matlab_helper_sha256,helper.sha256), ...
    'C5DEV72:Synthetic','Existing cross-language evidence no longer binds the copied helper.');

corePath=fullfile(here,'run_dl1018_closed_loop.m'); wrapperPath=fullfile(here,'run_episode_dl1018.m');
helperPath=fullfile(here,'delayed_prediction_step_candidate.m');
checkcodeRows=struct('path',{},'id',{},'line',{},'message',{});
for p={corePath,wrapperPath,helperPath}
    rows=checkcode(p{1},'-id');
    for j=1:numel(rows), checkcodeRows(end+1)=struct('path',p{1},'id',rows(j).id, ...
            'line',rows(j).line,'message',rows(j).message); end %#ok<AGROW>
end
sourceIdentity=struct('active_paths',{arrayfun(@(x)char(x.path),active,'UniformOutput',false)}, ...
    'active_sha256',{arrayfun(@(x)char(x.sha256),active,'UniformOutput',false)}, ...
    'which_checks',whichChecks,'c5_core_path',corePath,'c5_core_sha256',sha256_file(corePath), ...
    'episode_wrapper_path',wrapperPath,'episode_wrapper_sha256',sha256_file(wrapperPath), ...
    'prediction_helper_path',helperPath,'prediction_helper_sha256',sha256_file(helperPath));
modelIdentity=c5Pack.modelIdentity;
assert(isequaln(modelIdentity,c3Pack.modelIdentity)&&isequaln(opts,c5Pack.opts), ...
    'C5DEV72:IdentityCopy','Model or candidate options diverged from audited C5 preparation.');
cfgLeaves=leaf_count(cfg); optsLeaves=leaf_count(opts);
assert(cfgLeaves==120&&optsLeaves==43,'C5DEV72:LeafCount','Expected exactly 120 cfg and 43 C5 opts leaves.');
save(snapshotPath,'cfg','opts','W0','modelIdentity','sceneIdentity','sourceIdentity','-v7.3');
result=struct('schema','C5_AXIS_COORDINATE_DEV72_PREPARE_RESULT_V2', ...
    'status','PREPARED_C5_M110_DEV72_NO_PLANT_WAIT_PARENT_RELEASE_V2','created_utc',utc_now(), ...
    'input_lock_path',lockPath,'input_lock_sha256',lockSha,'run_contract_path',contractPath, ...
    'run_contract_sha256',contractSha,'source_binding_path',bindingPath,'source_binding_sha256',bindingSha, ...
    'snapshot_path',snapshotPath,'snapshot_sha256',sha256_file(snapshotPath), ...
    'cfg_leaf_count',cfgLeaves,'opts_leaf_count',optsLeaves,'source_identity',sourceIdentity, ...
    'model_identity',modelIdentity,'scene_identity_count',numel(sceneIdentity), ...
    'scene_identity_fields',{fieldnames(sceneIdentity)},'scene_ids_all_72',{contract.scene_ids_all_72}, ...
    'scene_ids_new_60',{contract.scene_ids_new_60},'scene_ids_reuse_12',{contract.scene_ids_reuse_12}, ...
    'coordinate_mask',[1 1 0],'pcf_auxiliary_enabled',true,'which_checks',whichChecks, ...
    'checkcode',checkcodeRows,'crosslang_result_sha256',sha256_file(syntheticPath), ...
    'crosslang_fixture_sha256',sha256_file(fixturePath),'status_jsons_checked',156, ...
    'plant_calls',0,'run_episode_called',false,'training_steps',0,'optimizer_steps',0, ...
    'parameter_or_seed_search',false,'new_B_sorties',0,'TEST_accessed',false);
