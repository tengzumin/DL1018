end

function verify_scene_evidence(row,id)
assert(isfile(row.raw_path)&&numel(row.raw_sha256)==64,'C5DEV72:RawIdentity','Raw identity missing for %s.',id);
verify_file(row.run_status_path,row.run_status_sha256);
assert(isfile(row.run_start_path)&&numel(row.run_start_sha256)==64,'C5DEV72:RunStart','Run-start identity missing for %s.',id);
verify_file(row.run_start_path,row.run_start_sha256);
if isfield(row,'first_plant_step_marker_path')&&~isempty(row.first_plant_step_marker_path)
    verify_file(row.first_plant_step_marker_path,row.first_plant_step_marker_sha256);
end
if isfield(row,'attempt_started_marker_path')&&~isempty(row.attempt_started_marker_path)
    verify_file(row.attempt_started_marker_path,row.attempt_started_marker_sha256);
end
end
function verify_comparator(row,id)
assert(isfile(row.raw_path)&&numel(row.raw_sha256)==64,'C5DEV72:B72Raw','B72 raw identity missing for %s.',id);
verify_file(row.run_status_path,row.run_status_sha256);
end
function verify_status(row,id,isC5)
s=jsondecode(fileread(row.run_status_path));
assert(strcmp(s.scene_id,id)&&strcmp(s.status,'RUN_COMPLETE_RAW_PENDING_AUDIT')&& ...
    strcmp(s.log_status,'STABLE')&&double(s.plant_calls)==1&& ...
    same_path(s.raw_path,row.raw_path)&&strcmpi(s.raw_sha256,row.raw_sha256)&& ...
    double(s.training_steps)==0&&double(s.optimizer_steps)==0&&~logical(s.TEST_accessed), ...
    'C5DEV72:Status','Status JSON values differ from locked scene %s.',id);
if isC5
    assert(isequal(double(s.coordinate_mask(:)),[1;1;0])&&double(s.last_transition)==20000&& ...
        double(s.transitions)==20000&&double(s.state_samples)==20001, ...
        'C5DEV72:C5Status','C5 reused status is incomplete or has a different mask for %s.',id);
elseif isfield(s,'last_transition')
    assert(double(s.last_transition)==20000&&double(s.transitions)==20000&&double(s.state_samples)==20001, ...
        'C5DEV72:B72Status','B72 status is incomplete for %s.',id);
end
end
function row=scene_row(lock,id)
ix=find(strcmp({lock.scenes.scene_id},id)); assert(numel(ix)==1,'C5DEV72:Scene','Scene is not unique: %s.',id); row=lock.scenes(ix);
end
function add_active_paths(items)
for k=1:numel(items), [~,~,ext]=fileparts(char(items(k).path)); if strcmpi(ext,'.m'), addpath(fileparts(char(items(k).path)),'-end'); end, end
end
function path=source_path(items,name)
idx=[]; for k=1:numel(items), [~,n,e]=fileparts(char(items(k).path)); if strcmpi([n e],name), idx(end+1)=k; end, end %#ok<AGROW>
assert(numel(idx)==1,'C5DEV72:SourceName','Expected one locked source %s.',name); path=char(items(idx).path);
end
function path=source_role(items,role)
idx=find(strcmpi({items.role},role)); assert(numel(idx)==1,'C5DEV72:SourceRole','Expected one shared-input role %s.',role); path=char(items(idx).path);
end
function n=leaf_count(x)
if isstruct(x)
    fields=fieldnames(x); n=0; if isempty(fields), n=1; return; end
    for e=1:numel(x), for k=1:numel(fields), n=n+leaf_count(x(e).(fields{k})); end, end
elseif iscell(x)
    n=0; for k=1:numel(x), n=n+leaf_count(x{k}); end
else
    n=1;
end
end
function verify_ref(item), verify_file(item.path,item.sha256); end
function verify_file(path,expected)
assert(isfile(path),'C5DEV72:MissingFile','Missing frozen file: %s.',path);
assert(strcmpi(sha256_file(path),expected),'C5DEV72:SHA','SHA-256 mismatch: %s.',path);
end
function h=sha256_file(path)
md=java.security.MessageDigest.getInstance('SHA-256'); fid=fopen(path,'r'); assert(fid>=0,'C5DEV72:ReadFile','Cannot read %s.',path); c=onCleanup(@()fclose(fid)); %#ok<NASGU>
while true, b=fread(fid,8*1024*1024,'*uint8'); if isempty(b), break; end; md.update(b); end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
function h=hash_bytes(bytes)
md=java.security.MessageDigest.getInstance('SHA-256'); md.update(typecast(uint8(bytes(:)),'int8'));
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
function h=hash_normalizer_arrays(model)
md=java.security.MessageDigest.getInstance('SHA-256');
for name={'input_mu','input_sigma'}, field=name{1}; a=reshape(double(model.(field)),1,[]);
    assert(numel(a)==14&&all(isfinite(a)),'C5DEV72:NormalizerShape','Invalid %s.',field);
    header=[field char(0) '((1, 14), ''float64'')' char(0)];
    md.update(typecast(uint8(unicode2native(header,'UTF-8')),'int8')); md.update(typecast(a(:),'int8'));
end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
function tf=same_path(a,b), tf=strcmpi(char(java.io.File(a).getCanonicalPath()),char(java.io.File(b).getCanonicalPath())); end
function write_json_new(path,value)
assert(~isfile(path),'C5DEV72:NoOverwrite','Refusing to overwrite %s.',path);
fid=fopen(path,'w'); assert(fid>=0,'C5DEV72:Write','Cannot create %s.',path); c=onCleanup(@()fclose(fid)); %#ok<NASGU>
fwrite(fid,jsonencode(value),'char');
end
function t=utc_now(), t=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z''')); end
