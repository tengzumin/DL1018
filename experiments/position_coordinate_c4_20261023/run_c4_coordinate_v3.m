function runStatus=run_c4_coordinate_v3(mode)
% One first-scene C4 run, released only after parent binds the prepared inputs.
if nargin~=1||~strcmpi(char(mode),'PARENT_APPROVED_C4_FIRST_V3')
    error('C4:Mode','Pass exactly PARENT_APPROVED_C4_FIRST_V3 after parent release.');
end
here=fileparts(mfilename('fullpath')); repoRoot=fileparts(fileparts(here));
lockPath=fullfile(here,'C4_INPUT_LOCK_v3.json'); contractPath=fullfile(here,'C4_RUN_CONTRACT_v3.json');
releasePath=fullfile(here,'C4_RELEASE_v3.json'); prepPath=fullfile(here,'C4_PREPARE_RESULT_v3.json');
snapshotPath=fullfile(here,'C4_PREPARED_CFG_OPTS_v3.mat');
assert(all([isfile(lockPath),isfile(contractPath),isfile(releasePath),isfile(prepPath),isfile(snapshotPath)]), ...
    'C4:ReleaseInputs','Exact parent release and no-Plant artifacts are required.');
lock=jsondecode(fileread(lockPath)); contract=jsondecode(fileread(contractPath));
release=jsondecode(fileread(releasePath)); prep=jsondecode(fileread(prepPath));
lockSha=sha256_file(lockPath); contractSha=sha256_file(contractPath); releaseSha=sha256_file(releasePath);
prepSha=sha256_file(prepPath); snapshotSha=sha256_file(snapshotPath); runnerPath=[mfilename('fullpath') '.m'];
runnerSha=sha256_file(runnerPath);
firstRow=scene_row(lock,lock.first_scene_id);
assert(strcmp(release.schema,'C4_COORDINATE_RELEASE_V3')&& ...
    strcmp(release.state,'APPROVED_C4_FIRST_SCENE_V3')&&logical(release.plant_authorized)&& ...
    double(release.max_new_Plant)==1&&strcmpi(release.c4_input_lock_sha256,lockSha)&& ...
    strcmpi(release.contract_sha256,contractSha)&&strcmpi(release.prepare_result_sha256,prepSha)&& ...
    strcmpi(release.cfg_opts_snapshot_sha256,snapshotSha)&&strcmpi(release.runner_sha256,runnerSha)&& ...
    same_path(release.runner_path,runnerPath)&&strcmp(release.scene_id,lock.first_scene_id)&& ...
    strcmpi(release.scene_b_raw_sha256,firstRow.B_source.sha256), ...
    'C4:Release','Release does not bind the exact C4 first-scene runner, source, and prepared inputs.');
assert(strcmp(lock.state,'LOCKED_C4_COORDINATE_NO_PLANT_PARENT_REVIEW_REQUIRED_V3')&& ...
    strcmp(prep.status,'PREPARED_NO_PLANT_WAIT_PARENT_RELEASE_V3')&&double(prep.plant_calls)==0&& ...
    ~logical(prep.run_episode_called)&&~logical(prep.TEST_accessed)&& ...
    strcmpi(prep.input_lock_sha256,lockSha)&&strcmpi(prep.snapshot_sha256,snapshotSha)&& ...
    strcmpi(lock.source_files.single_scene_runner.sha256,runnerSha), ...
    'C4:PreparedBinding','Prepared no-Plant inputs changed or are not bound.');
verify_ref(lock.source_files.lock_builder); verify_ref(lock.source_files.prepare_entry);
verify_ref(lock.source_files.contract); verify_ref(lock.source_files.synthetic_check);
for k=1:numel(lock.active_source_inventory), verify_ref(lock.active_source_inventory(k)); end
refNames=fieldnames(lock.upstream_refs); for k=1:numel(refNames), verify_ref(lock.upstream_refs.(refNames{k})); end
for k=1:numel(lock.shared_input_files), verify_ref(lock.shared_input_files(k)); end
assert(strcmpi(contractSha,lock.source_files.contract.sha256), ...
    'C4:ContractSHA','Run contract differs from the locked contract.');
assert(datetime(char(contract.limits.deadline_utc),'InputFormat',"yyyy-MM-dd'T'HH:mm:ss'Z'",'TimeZone','UTC')>datetime('now','TimeZone','UTC')&& ...
    double(java.io.File(repoRoot).getUsableSpace())>=double(contract.limits.minimum_free_bytes), ...
    'C4:ResourceDeadline','C4 hard deadline or free-space floor has been reached.');
assert(directory_bytes(here)+1e6<double(contract.limits.max_output_bytes), ...
    'C4:OutputReserve','Insufficient space remains under the frozen C4 output cap.');

active=lock.active_source_inventory; initPath=source_path(active,'init_dl1018.m');
optionsPath=source_path(active,'position_only_search_options.m'); headPath=source_path(active,'position_only_search_head_step.m');
forwardPath=source_path(active,'position_stage1_model_forward_v2.m');
add_active_paths(active); addpath(fullfile(repoRoot,'matlab','runtime'),'-end'); addpath(fullfile(repoRoot,'matlab','core'),'-end');
addpath(fileparts(initPath),'-begin'); clear init_dl1018; rehash; [cfgNow,~,resolvedRoot]=init_dl1018();
assert(same_path(resolvedRoot,repoRoot),'C4:ProjectRoot','Runtime resolved a different repository root.');
add_active_paths(active); addpath(fullfile(repoRoot,'matlab','runtime'),'-end'); addpath(fullfile(repoRoot,'matlab','core'),'-end');
addpath(fileparts(optionsPath),'-begin'); addpath(fileparts(headPath),'-begin'); addpath(fileparts(forwardPath),'-begin'); addpath(here,'-begin');
clear run_episode_dl1018 run_dl1018_closed_loop delayed_prediction_step_candidate ...
    position_only_search_options position_only_search_head_step position_stage1_model_forward_v2 init_dl1018; rehash;
for k=1:numel(active), verify_ref(active(k)); [~,n,e]=fileparts(active(k).path);
    if strcmpi(e,'.m'), assert(same_path(which(n),active(k).path),'C4:WhichShadow','Source %s resolves to a shadow.',n); end
end
pack=load(snapshotPath,'cfg','opts','W0','modelIdentity','sourceIdentity','sceneIdentity');
assert(all(isfield(pack,{'cfg','opts','W0','modelIdentity','sourceIdentity','sceneIdentity'}))&& ...
    isequaln(cfgNow,pack.cfg)&&double(pack.opts.position_coordinate_m)==0&& ...
    logical(pack.opts.position_delayed_prediction_enabled), ...
    'C4:Snapshot','Fresh C4 config/options differ from the no-Plant snapshot.');
modelPath=source_role(lock.shared_input_files,'model_mat'); modelPack=load(modelPath,'model'); model=modelPack.model;
opts=position_only_search_options(cfgNow,model,'FEATURE',12,1);
opts.position_delayed_prediction_enabled=true; opts.position_coordinate_m=0;
assert(isequaln(opts,pack.opts)&&isequal(double(model.output_W),double(pack.W0)), ...
    'C4:OptsChanged','C4 options/W0 changed after preparation.');
row=scene_row(lock,release.scene_id); verify_file(row.B_source.path,row.B_source.sha256);
scenePack=load(row.B_source.path,'scene'); scene=scenePack.scene;
assert(valid_scene(scene,row.scene_id)&&strcmpi(row.B_source.sha256,release.scene_b_raw_sha256), ...
    'C4:SceneChanged','Released scene input no longer matches its locked identity.');
rawSceneId=char(scene.scene_id); scene.scene_id=char(row.scene_id);

sharedRelease=jsondecode(fileread(lock.upstream_refs.shared_job_release.path));
assert(strcmpi(sha256_file(lock.upstream_refs.shared_job_release.path),lock.upstream_refs.shared_job_release.sha256)&& ...
    isfile(sharedRelease.shared_heavy_job_lock_path),'C4:SharedLockMissing','Frozen shared-job lock is missing.');
raf=java.io.RandomAccessFile(sharedRelease.shared_heavy_job_lock_path,'rw'); channel=raf.getChannel(); jobLock=channel.tryLock();
assert(~isempty(jobLock),'C4:ConcurrentHeavyJob','Shared heavy-job lock is held; do not wait or seize it.');
cleanup=onCleanup(@()release_job_lock(jobLock,channel,raf)); %#ok<NASGU>
attemptRoot=fullfile(here,'runs_c4_v3'); attemptDir=fullfile(attemptRoot,row.scene_id,'C4_COORDINATE_M0','attempt_01');
assert(~isfolder(attemptDir)&&(~isfolder(attemptRoot)||isempty(dir(fullfile(attemptRoot,'**','attempt_started.marker'))))&& ...
    (~isfolder(attemptRoot)||isempty(dir(fullfile(attemptRoot,'**','first_plant_step.marker')))), ...
    'C4:NoRetry','Prior attempt or Plant marker exists; refusing another run.');
if ~isfolder(attemptDir), mkdir(attemptDir); end
markerPath=fullfile(attemptDir,'first_plant_step.marker'); rawPath=fullfile(attemptDir,'raw_run.mat');
runStartPath=fullfile(attemptDir,'run_start.mat'); statusPath=fullfile(attemptDir,'run_status.json');
failurePath=fullfile(attemptDir,'C4_FAILURE.json');
assert(~any(cellfun(@isfile,{markerPath,rawPath,runStartPath,statusPath,failurePath})), ...
    'C4:NoOverwrite','Attempt output already exists.');
opts.r2e_first_plant_step_marker=markerPath; startedUtc=utc_now(); invocationEntered=false;
runStart=struct('schema','C4_COORDINATE_RUN_START_V3','scene_id',row.scene_id,'source_scene_id',rawSceneId, ...
    'method',contract.candidate,'coordinate_factor_m',0,'started_utc',startedUtc, ...
    'release_sha256',releaseSha,'input_lock_sha256',lockSha,'prepare_result_sha256',prepSha, ...
    'cfg_opts_snapshot_sha256',snapshotSha,'scene_raw_sha256',row.B_source.sha256, ...
    'source_identity',pack.sourceIdentity,'cfg',cfgNow,'opts',opts,'plant_calls_before_invocation',0, ...
    'training_steps',0,'optimizer_steps',0,'TEST_accessed',false);
save(runStartPath,'runStart','-v7.3'); write_text(fullfile(attemptDir,'attempt_started.marker'),[startedUtc newline 'ABOUT_TO_CALL_EPISODE' newline]);
try
    invocationEntered=true; clear run_dl1018_closed_loop;
    log=run_episode_dl1018(scene,contract.candidate,cfgNow,opts,rawPath);
    assert(isfile(rawPath)&&isfile(markerPath),'C4:PlantOutput','Episode returned without raw or first-Plant marker.');
    runIdentity=struct('schema','C4_COORDINATE_RUN_IDENTITY_V3','scene_id',row.scene_id, ...
        'candidate',contract.candidate,'coordinate_factor_m',0,'release_sha256',releaseSha, ...
        'input_lock_sha256',lockSha,'prepare_result_sha256',prepSha,'scene_b_raw_sha256',row.B_source.sha256, ...
        'training_steps',0,'optimizer_steps',0,'TEST_accessed',false);
    save(rawPath,'runIdentity','-append'); rawSha=sha256_file(rawPath);
    complete=strcmpi(log.status,'STABLE')&&isempty(char(log.safety_stop_reason))&& ...
        double(log.last_transition)==20000&&numel(log.transition_time)==20000&&numel(log.time)==20001&& ...
        all(isfinite(log.state(:)))&&all(isfinite(log.reference.position(:)));
    state='FAILED_NO_RETRY'; if complete, state='RUN_COMPLETE_RAW_PENDING_AUDIT'; end
    runStatus=struct('schema','C4_COORDINATE_RUN_STATUS_V3','status',state,'scene_id',row.scene_id, ...
        'source_scene_id',rawSceneId,'candidate',contract.candidate,'coordinate_factor_m',0, ...
        'log_status',log.status,'safety_stop_reason',log.safety_stop_reason,'last_transition',double(log.last_transition), ...
        'transitions',numel(log.transition_time),'state_samples',numel(log.time),'raw_path',rawPath, ...
        'raw_sha256',rawSha,'raw_bytes',double(dir(rawPath).bytes),'run_start_path',runStartPath, ...
        'run_start_sha256',sha256_file(runStartPath),'first_plant_step_marker_path',markerPath, ...
        'first_plant_step_marker_sha256',sha256_file(markerPath),'release_sha256',releaseSha, ...
        'input_lock_sha256',lockSha,'prepare_result_sha256',prepSha,'plant_invocation_entered',true, ...
        'plant_start_confirmed',true,'plant_calls',1,'output_bytes_after_raw',directory_bytes(here), ...
        'training_steps',0,'optimizer_steps',0, ...
        'parameter_or_seed_search',false,'TEST_accessed',false,'created_utc',utc_now());
    if runStatus.output_bytes_after_raw+1e6>double(contract.limits.max_output_bytes)
        runStatus.status='FAILED_NO_RETRY'; runStatus.failure_reason='C4 output cap exceeded; raw retained.';
    end
    write_json_new(statusPath,runStatus);
    assert(strcmp(runStatus.status,'RUN_COMPLETE_RAW_PENDING_AUDIT'), ...
        'C4:UnsafeStop','Run incomplete/non-STABLE or exceeds output cap; raw and status retained, no retry.');
catch ME
    failed=struct('schema','C4_COORDINATE_FAILURE_V3','status','FAILED_NO_RETRY','scene_id',row.scene_id, ...
        'identifier',ME.identifier,'message',ME.message,'failed_utc',utc_now(),'attempt_dir',attemptDir, ...
        'plant_invocation_entered',invocationEntered,'plant_start_confirmed',isfile(markerPath), ...
        'plant_calls',double(invocationEntered),'raw_path',rawPath,'partial_raw_preserved',isfile(rawPath), ...
        'partial_raw_sha256',file_sha_if_exists(rawPath),'release_sha256',releaseSha,'input_lock_sha256',lockSha);
    if ~isfile(failurePath), write_json_new(failurePath,failed); end
    rethrow(ME);
end
end

function row=scene_row(lock,id), ix=find(strcmp({lock.scenes.scene_id},id)); assert(numel(ix)==1,'C4:Scene','Scene is not locked.'); row=lock.scenes(ix); end
function add_active_paths(items), for k=1:numel(items), [~,~,e]=fileparts(char(items(k).path)); if strcmpi(e,'.m'), addpath(fileparts(char(items(k).path)),'-end'); end, end, end
function path=source_path(items,name), idx=[]; for k=1:numel(items), [~,n,e]=fileparts(char(items(k).path)); if strcmpi([n e],name), idx(end+1)=k; end, end; assert(numel(idx)==1,'C4:SourceName','Expected one source %s.',name); path=char(items(idx).path); end
function path=source_role(items,role), idx=find(strcmpi({items.role},role)); assert(numel(idx)==1,'C4:SourceRole','Expected one shared input role %s.',role); path=char(items(idx).path); end
function verify_ref(item), verify_file(item.path,item.sha256); end
function verify_file(path,expected), assert(isfile(path),'C4:MissingFile','Missing frozen file: %s.',path); assert(strcmpi(sha256_file(path),expected),'C4:SHA','SHA mismatch: %s.',path); end
function h=sha256_file(path), md=java.security.MessageDigest.getInstance('SHA-256'); fid=fopen(path,'r'); assert(fid>=0,'C4:ReadFile','Cannot read %s.',path); c=onCleanup(@()fclose(fid)); %#ok<NASGU>
while true, b=fread(fid,8*1024*1024,'*uint8'); if isempty(b), break; end, md.update(b); end, h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[])); end
function ok=valid_scene(s,id), ok=isstruct(s)&&isfield(s,'scene_id')&&(strcmp(char(s.scene_id),id)||strcmp(char(s.scene_id),[id '_ACC_FIX_V1']))&& ...
    isfield(s,'time')&&numel(s.time)==20001&&abs(double(s.time(1)))<1e-12&&abs(double(s.time(end))-20)<1e-12&& ...
    isfield(s,'environment_wind_I')&&isequal(size(s.environment_wind_I),[20001,3])&&isfield(s,'initial_state')&&numel(s.initial_state)==12&& ...
    isfield(s,'arms')&&all(isfield(s.arms,{'command','rhoDot_hat','rhoDot_true','rho_hat','rho_true'}))&&isfield(s,'reference')&& ...
    all(isfield(s.reference,{'position','velocity','acceleration','yaw','yaw_rate','yaw_acceleration'}))&& ...
    isequal(size(s.reference.position),[20001,3])&&isequal(size(s.reference.velocity),[20001,3])&&isequal(size(s.reference.acceleration),[20001,3])&& ...
    isequal(size(s.arms.command),[20001,4])&&isequal(size(s.arms.rhoDot_hat),[20001,4])&&isequal(size(s.arms.rhoDot_true),[20001,4])&& ...
    isequal(size(s.arms.rho_hat),[20001,4])&&isequal(size(s.arms.rho_true),[20001,4])&& ...
    isequal(size(s.reference.yaw),[20001,1])&&isequal(size(s.reference.yaw_rate),[20001,1])&& ...
    isequal(size(s.reference.yaw_acceleration),[20001,1])&&all(isfinite(s.time(:)))&& ...
    all(isfinite(s.environment_wind_I(:)))&&all(isfinite(s.initial_state(:)))&&all(isfinite(s.reference.position(:)))&& ...
    all(isfinite(s.reference.velocity(:)))&&all(isfinite(s.reference.acceleration(:)))&& ...
    all(isfinite(s.reference.yaw(:)))&&all(isfinite(s.reference.yaw_rate(:)))&& ...
    all(isfinite(s.reference.yaw_acceleration(:)))&&all(isfinite(s.arms.command(:)))&& ...
    all(isfinite(s.arms.rhoDot_hat(:)))&&all(isfinite(s.arms.rhoDot_true(:)))&&all(isfinite(s.arms.rho_hat(:)))&&all(isfinite(s.arms.rho_true(:))); end
function t=utc_now(), t=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z''')); end
function write_text(path,value), fid=fopen(path,'w'); assert(fid>=0,'C4:Write','Cannot create %s.',path); c=onCleanup(@()fclose(fid)); fwrite(fid,value,'char'); end
function write_json_new(path,value), assert(~isfile(path),'C4:NoOverwrite','Refusing to overwrite %s.',path); write_text(path,jsonencode(value)); end
function h=file_sha_if_exists(path), if isfile(path), h=sha256_file(path); else, h=''; end, end
function n=directory_bytes(path), n=0; if ~isfolder(path), return; end; d=dir(fullfile(path,'**','*')); for k=1:numel(d), if ~d(k).isdir, n=n+double(d(k).bytes); end, end, end
function tf=same_path(a,b), tf=strcmpi(char(java.io.File(a).getCanonicalPath()),char(java.io.File(b).getCanonicalPath())); end
function release_job_lock(lock,channel,raf), try, lock.release(); catch, end, try, channel.close(); catch, end, try, raf.close(); catch, end, end
