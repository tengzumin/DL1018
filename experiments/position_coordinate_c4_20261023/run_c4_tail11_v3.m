assert(strcmp(binding.pilot.scene_id,contract.first_scene_id)&& ...
    strcmp(pilot.status,'RUN_COMPLETE_RAW_PENDING_AUDIT')&&strcmp(pilot.log_status,'STABLE')&& ...
    double(pilot.last_transition)==20000&&double(pilot.state_samples)==20001&&double(pilot.plant_calls)==1&& ...
    strcmpi(pilot.raw_sha256,binding.pilot_refs.raw.sha256)&&strcmpi(pilot.raw_sha256,pilotReview.raw_sha256)&& ...
    strcmp(pilotReview.status,'PASS_C4_RAW_ALL_EVENTS')&&double(pilotReview.event_count)==1968&& ...
    strcmp(pilotCfgReview.status,'PASS_ACTUAL_RUN_CFG_OPTS_AND_NATURAL_OS0')&& ...
    double(pilotCfgReview.OS_exit)==0&&logical(pilotCfgReview.body_complete)&& ...
    strcmpi(pilotBody.raw_sha256,pilot.raw_sha256)&&logical(pilotBody.body_completed)&&double(pilotBody.plant_calls)==1&& ...
    double(pilotExit.exit_code)==0&&strcmpi(pilotExit.command_sha256,binding.pilot_refs.first_run_script.sha256)&& ...
    strcmp(firstRelease.state,'APPROVED_C4_FIRST_SCENE_V3')&&strcmpi(firstRelease.runner_sha256,binding.source_files.single_scene_runner.sha256)&& ...
    strcmp(pilotStart.scene_id,binding.pilot.scene_id)&&double(pilotStart.plant_calls_before_invocation)==0&& ...
    double(pilotStart.training_steps)==0&&double(pilotStart.optimizer_steps)==0&&~logical(pilotStart.TEST_accessed), ...
    'C4:TailPilotBinding','The parent-reviewed pilot/raw/configuration/OS evidence changed or is incomplete.');
assert(strcmpi(release.pilot_raw_sha256,binding.pilot_refs.raw.sha256)&& ...
    strcmpi(release.pilot_run_status_sha256,binding.pilot_refs.run_status.sha256)&& ...
    strcmpi(release.pilot_run_start_sha256,binding.pilot_refs.run_start.sha256)&& ...
    strcmpi(release.pilot_marker_sha256,binding.pilot_refs.marker.sha256)&& ...
    strcmpi(release.pilot_body_complete_sha256,binding.pilot_refs.body_complete.sha256)&& ...
    strcmpi(release.pilot_os_exit_sha256,binding.pilot_refs.os_exit.sha256)&& ...
    strcmpi(release.pilot_raw_review_sha256,binding.pilot_refs.raw_review.sha256)&& ...
    strcmpi(release.pilot_cfg_opts_os_review_sha256,binding.pilot_refs.cfg_opts_os_review.sha256), ...
    'C4:TailPilotRelease','Parent release does not bind every pilot audit artifact.');

tailIds=contract.scene_ids; tailIds(5)=[];
assert(isequal(string(tailIds(:)),string(binding.tail_scene_ids(:)))&& ...
    isequal(string(tailIds(:)),string(release.tail_scene_ids(:)))&& ...
    double(release.per_scene_output_reserve_bytes)==80000000&& ...
    double(release.max_output_bytes)==double(contract.limits.max_output_bytes)&& ...
    double(release.minimum_free_bytes)==double(contract.limits.minimum_free_bytes)&& ...
    strcmp(char(release.deadline_utc),char(contract.limits.deadline_utc))&& ...
    double(release.training_steps)==0&&double(release.optimizer_steps)==0&& ...
    ~logical(release.parameter_or_seed_search)&&double(release.new_B_sorties)==0&& ...
    ~logical(release.TEST_accessed)&&~logical(release.automatic_retry), ...
    'C4:TailContract','Tail11 list, reserve, total cap, deadline or prohibitions changed.');
assert(strcmpi(contractSha,lock.source_files.contract.sha256)&& ...
    strcmpi(runnerSha,binding.source_files.tail_runner.sha256), ...
    'C4:TailSHA','Runner or contract is not bound to the reviewed source set.');

% Restore the exact prepared dependency stack after init_dl1018 resets MATLAB's path.
active=lock.active_source_inventory; initPath=source_path(active,'init_dl1018.m');
optionsPath=source_path(active,'position_only_search_options.m');
headPath=source_path(active,'position_only_search_head_step.m');
forwardPath=source_path(active,'position_stage1_model_forward_v2.m');
add_active_paths(active); addpath(fullfile(repoRoot,'matlab','runtime'),'-end'); addpath(fullfile(repoRoot,'matlab','core'),'-end');
addpath(fileparts(initPath),'-begin'); clear init_dl1018; rehash;
assert(same_path(which('init_dl1018'),initPath),'C4:InitPath','init_dl1018 resolves outside the frozen runtime.');
[cfgNow,~,resolvedRoot]=init_dl1018();
assert(same_path(resolvedRoot,repoRoot),'C4:ProjectRoot','Runtime resolved a different repository root.');
add_active_paths(active); addpath(fullfile(repoRoot,'matlab','runtime'),'-end'); addpath(fullfile(repoRoot,'matlab','core'),'-end');
addpath(fileparts(optionsPath),'-begin'); addpath(fileparts(headPath),'-begin');
addpath(fileparts(forwardPath),'-begin'); addpath(here,'-begin');
clear run_episode_dl1018 run_dl1018_closed_loop delayed_prediction_step_candidate ...
    position_only_search_options position_only_search_head_step position_stage1_model_forward_v2 init_dl1018; rehash;
for k=1:numel(active)
    verify_ref(active(k)); [~,name,ext]=fileparts(char(active(k).path));
    if strcmpi(ext,'.m'), assert(same_path(which(name),active(k).path), ...
            'C4:WhichShadow','Locked source %s resolves to a shadow.',name); end
end
assert(same_path(which('run_dl1018_closed_loop'),fullfile(here,'run_dl1018_closed_loop.m'))&& ...
    same_path(which('run_episode_dl1018'),fullfile(here,'run_episode_dl1018.m'))&& ...
    same_path(which('delayed_prediction_step_candidate'),fullfile(here,'delayed_prediction_step_candidate.m')), ...
    'C4:Isolation','C4 core/wrapper/helper must resolve from the isolated directory.');

pack=load(snapshotPath,'cfg','opts','W0','modelIdentity','sourceIdentity','sceneIdentity');
assert(all(isfield(pack,{'cfg','opts','W0','modelIdentity','sourceIdentity','sceneIdentity'}))&& ...
    isequaln(cfgNow,pack.cfg)&&double(pack.opts.position_coordinate_m)==0&& ...
    logical(pack.opts.position_delayed_prediction_enabled), ...
    'C4:Snapshot','Fresh C4 config/options differ from the no-Plant snapshot.');
modelPath=source_role(lock.shared_input_files,'model_mat'); modelPack=load(modelPath,'model');
assert(isfield(modelPack,'model')&&isstruct(modelPack.model),'C4:Model','Frozen model is missing.');
model=modelPack.model;
opts=position_only_search_options(cfgNow,model,'FEATURE',12,1);
opts.position_delayed_prediction_enabled=true; opts.position_coordinate_m=0;
assert(isequaln(opts,pack.opts)&&isequal(double(model.output_W),double(pack.W0))&& ...
    strcmp(char(model.model_id),'DSSM14')&&double(model.seed)==2026102001&& ...
    double(model.selected_step)==60000&&double(model.input_dim)==14&&double(model.window)==32, ...
    'C4:OptsChanged','Frozen model/options differ from the prepared C4 snapshot.');

% Preflight every remaining source and attempt before publishing RUNNING status.
maxBytes=double(contract.limits.max_output_bytes); reserveBytes=double(release.per_scene_output_reserve_bytes);
minFree=double(contract.limits.minimum_free_bytes); deadline=datetime(char(contract.limits.deadline_utc), ...
    'InputFormat',"yyyy-MM-dd'T'HH:mm:ss'Z'",'TimeZone','UTC');
check_resources(here,repoRoot,maxBytes,reserveBytes,minFree,deadline);
runRoot=fullfile(here,'runs_c4_v3');
for k=1:numel(tailIds)
    row=scene_row(lock,char(tailIds{k}));
    verify_file(row.B_source.path,row.B_source.sha256);
    verify_file(row.C3_reuse.status_path,row.C3_reuse.status_sha256);
    verify_file(row.C3_reuse.run_start_path,row.C3_reuse.run_start_sha256);
    verify_file(row.C3_reuse.first_plant_step_marker_path,row.C3_reuse.first_plant_step_marker_sha256);
    attemptDir=fullfile(runRoot,char(tailIds{k}),'C4_COORDINATE_M0','attempt_01');
    assert(~isfolder(attemptDir),'C4:TailNoRetry','Prior attempt exists for %s.',char(tailIds{k}));
end
