for k=1:numel(binding.shared_input_files), verify_ref(binding.shared_input_files(k)); end
refNames=fieldnames(binding.upstream_refs); for k=1:numel(refNames), verify_ref(binding.upstream_refs.(refNames{k})); end
assert(strcmp(lock.schema,'C4_COORDINATE_INPUT_LOCK_V3')&& ...
    ~logical(lock.plant_authorized_by_this_lock)&&logical(lock.pcf_auxiliary_enabled)&& ...
    strcmp(lock.state,'LOCKED_C4_COORDINATE_NO_PLANT_PARENT_REVIEW_REQUIRED_V3')&& ...
    strcmp(contract.schema,'C4_COORDINATE_RUN_CONTRACT_V3')&&strcmp(contract.state,lock.state)&& ...
    strcmp(prep.schema,'C4_COORDINATE_PREPARE_RESULT_V3')&& ...
    strcmp(prep.status,'PREPARED_NO_PLANT_WAIT_PARENT_RELEASE_V3')&&double(prep.plant_calls)==0&& ...
    ~logical(prep.run_episode_called)&&~logical(prep.TEST_accessed)&& ...
    strcmpi(prep.input_lock_sha256,lockSha)&&strcmpi(prep.snapshot_sha256,snapshotSha), ...
    'C4:TailPrepared','Frozen v3 lock/preparation changed or was not no-Plant.');
assert(strcmpi(binding.source_files.lock_builder.sha256,lock.source_files.lock_builder.sha256)&& ...
    strcmpi(binding.source_files.prepare_entry.sha256,lock.source_files.prepare_entry.sha256)&& ...
    strcmpi(binding.source_files.single_scene_runner.sha256,lock.source_files.single_scene_runner.sha256)&& ...
    strcmpi(binding.source_files.synthetic_check.sha256,lock.source_files.synthetic_check.sha256)&& ...
    strcmpi(contractSha,binding.source_files.run_contract.sha256)&& ...
    numel(lock.active_source_inventory)==32&&lock.source_counts.matlab==31&&lock.source_counts.mat==1&& ...
    numel(contract.scene_ids)==12&&strcmp(contract.first_scene_id,'DL1018_VAL_T2_C00_W10')&& ...
    double(contract.coordinate_factor_m)==0&&logical(contract.pcf_auxiliary_enabled), ...
    'C4:TailScope','Frozen C4 v3 inventory or scope differs.');

% Verify the already-reviewed pilot, including its actual OS return and raw identity.
for name={'raw','run_status','run_start','marker','body_complete','os_exit','first_run_script','raw_review','cfg_opts_os_review','first_scene_release'}
    verify_ref(binding.pilot_refs.(name{1}));
end
pilot=jsondecode(fileread(binding.pilot_refs.run_status.path));
pilotBody=jsondecode(fileread(binding.pilot_refs.body_complete.path)); pilotExit=jsondecode(fileread(binding.pilot_refs.os_exit.path));
pilotReview=jsondecode(fileread(binding.pilot_refs.raw_review.path)); pilotCfgReview=jsondecode(fileread(binding.pilot_refs.cfg_opts_os_review.path));
