lockSha=sha256_file(lockPath); contractSha=sha256_file(contractPath); prepSha=sha256_file(prepPath);
snapshotSha=sha256_file(snapshotPath); bindingSha=sha256_file(bindingPath); releaseContractSha=sha256_file(releaseContractPath);
releaseSha=sha256_file(releasePath); runnerPath=[mfilename('fullpath') '.m']; runnerSha=sha256_file(runnerPath);
assert(all(isfield(release,releaseContract.required_fields))&& ...
    strcmp(binding.schema,'C4_TAIL11_SOURCE_BINDING_V1')&& ...
    strcmp(binding.state,'TAIL11_SOURCE_BOUND_WAIT_PARENT_RELEASE')&& ...
    strcmp(releaseContract.schema,'C4_TAIL11_PARENT_RELEASE_CONTRACT_V1')&& ...
    strcmp(releaseContract.state,'CONTRACT_ONLY_PARENT_RELEASE_REQUIRED')&& ...
    strcmp(releaseContract.parent_release_schema,'C4_TAIL11_PARENT_RELEASE_V1')&& ...
    strcmp(releaseContract.required_release_state,'APPROVED_C4_TAIL11_V1')&& ...
    strcmp(release.schema,'C4_TAIL11_PARENT_RELEASE_V1')&& ...
    strcmp(release.state,'APPROVED_C4_TAIL11_V1')&&logical(release.plant_authorized)&& ...
    logical(release.subsequent_11_flights_authorized)&&double(release.max_new_Plant)==11, ...
    'C4:TailRelease','An exact approved parent release for eleven remaining scenes is required.');
