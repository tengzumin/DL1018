    verify_ref(binding.source_files.(name{1}));
end
assert(same_path(binding.source_files.tail_runner.path,runnerPath)&&strcmpi(binding.source_files.tail_runner.sha256,runnerSha)&& ...
    same_path(binding.source_files.input_lock.path,lockPath)&&strcmpi(binding.source_files.input_lock.sha256,lockSha)&& ...
    same_path(binding.source_files.run_contract.path,contractPath)&&strcmpi(binding.source_files.run_contract.sha256,contractSha)&& ...
    same_path(binding.source_files.prepare_result.path,prepPath)&&strcmpi(binding.source_files.prepare_result.sha256,prepSha)&& ...
    same_path(binding.source_files.prepared_snapshot.path,snapshotPath)&&strcmpi(binding.source_files.prepared_snapshot.sha256,snapshotSha)&& ...
    same_path(binding.source_files.parent_release_contract.path,releaseContractPath)&& ...
    strcmpi(binding.source_files.parent_release_contract.sha256,releaseContractSha), ...
    'C4:TailSourceBinding','Tail source binding does not match the exact v3 inputs/runner.');
