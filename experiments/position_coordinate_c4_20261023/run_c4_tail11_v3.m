lockPath=fullfile(here,'C4_INPUT_LOCK_v3.json'); contractPath=fullfile(here,'C4_RUN_CONTRACT_v3.json');
prepPath=fullfile(here,'C4_PREPARE_RESULT_v3.json'); snapshotPath=fullfile(here,'C4_PREPARED_CFG_OPTS_v3.mat');
