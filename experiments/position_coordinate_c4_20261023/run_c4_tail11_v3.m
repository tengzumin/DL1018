function batch=run_c4_tail11_v3(mode)
% Sequentially execute the remaining eleven frozen C4 scenes after parent release.
if nargin~=1||~strcmpi(char(mode),'PARENT_APPROVED_C4_TAIL11_V1')
    error('C4:TailMode','Pass exactly PARENT_APPROVED_C4_TAIL11_V1 after parent release.');
end
