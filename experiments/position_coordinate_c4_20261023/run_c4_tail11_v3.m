    strcmpi(release.tail_runner_sha256,runnerSha)&&strcmpi(release.launcher_sha256,binding.source_files.launcher.sha256)&& ...
    strcmpi(release.parent_release_contract_sha256,releaseContractSha)&& ...
    strcmpi(release.c4_input_lock_sha256,lockSha)&&strcmpi(release.c4_run_contract_sha256,contractSha)&& ...
    strcmpi(release.prepare_result_sha256,prepSha)&&strcmpi(release.cfg_opts_snapshot_sha256,snapshotSha), ...
    'C4:TailReleaseBinding','Parent release does not bind this exact tail batch and prepared inputs.');
verify_ref(binding.source_files.single_scene_runner); verify_ref(binding.source_files.synthetic_check);
