assert(~isempty(jobLock),'C4:ConcurrentHeavyJob','Shared heavy-job lock is held; do not wait or seize it.');
cleanup=onCleanup(@()release_job_lock(jobLock,channel,raf)); %#ok<NASGU>
records=struct('batch_index',{},'scene_id',{},'status',{},'raw_path',{},'raw_sha256',{}, ...
    'run_status_path',{},'run_status_sha256',{},'plant_calls',{},'created_utc',{});
batch=struct('schema','C4_TAIL11_BATCH_STATUS_V1','status','RUNNING','source_binding_sha256',bindingSha, ...
    'tail_release_sha256',releaseSha,'runner_sha256',runnerSha,'completed_scenes',0,'plant_calls',0, ...
    'records',records,'created_utc',utc_now());
write_json_new(batchStatusPath,batch);
for k=1:numel(tailIds)
    sceneId=char(tailIds{k}); attemptDir=fullfile(runRoot,sceneId,'C4_COORDINATE_M0','attempt_01');
    markerPath=fullfile(attemptDir,'first_plant_step.marker'); rawPath=fullfile(attemptDir,'raw_run.mat');
    runStartPath=fullfile(attemptDir,'run_start.mat'); statusPath=fullfile(attemptDir,'run_status.json');
    failurePath=fullfile(attemptDir,'C4_TAIL11_FAILURE.json');
    invocationEntered=false; attemptCreated=false; rawSceneId=''; startedUtc=utc_now();
    try
        check_resources(here,repoRoot,maxBytes,reserveBytes,minFree,deadline);
        verify_file(bindingPath,bindingSha); verify_file(releasePath,releaseSha);
        for j=1:numel(active), verify_ref(active(j)); end
        row=scene_row(lock,sceneId);
        verify_file(row.B_source.path,row.B_source.sha256);
        verify_file(row.C3_reuse.status_path,row.C3_reuse.status_sha256);
        verify_file(row.C3_reuse.run_start_path,row.C3_reuse.run_start_sha256);
        verify_file(row.C3_reuse.first_plant_step_marker_path,row.C3_reuse.first_plant_step_marker_sha256);
        assert(~isfolder(attemptDir),'C4:TailNoRetry','Prior attempt exists for %s.',sceneId);
        [mkStatus,mkMessage]=mkdir(attemptDir);
        assert(mkStatus,'C4:TailCreateAttempt','Cannot create attempt directory for %s: %s.',sceneId,mkMessage);
        attemptCreated=true;
        assert(~any(cellfun(@isfile,{markerPath,rawPath,runStartPath,statusPath,failurePath})), ...
            'C4:TailNoOverwrite','Attempt output already exists for %s.',sceneId);
        scenePack=load(row.B_source.path,'scene'); scene=scenePack.scene;
        assert(valid_scene(scene,sceneId),'C4:SceneChanged','B source is not a valid locked scene: %s.',sceneId);
        rawSceneId=char(scene.scene_id); scene.scene_id=sceneId;
        optsForScene=opts; optsForScene.r2e_first_plant_step_marker=markerPath;
        runStart=struct('schema','C4_TAIL11_RUN_START_V1','batch_index',k,'scene_id',sceneId, ...
            'source_scene_id',rawSceneId,'candidate',contract.candidate,'coordinate_factor_m',0, ...
            'started_utc',startedUtc,'source_binding_sha256',bindingSha,'tail_release_sha256',releaseSha, ...
            'input_lock_sha256',lockSha,'contract_sha256',contractSha,'prepare_result_sha256',prepSha, ...
            'cfg_opts_snapshot_sha256',snapshotSha,'scene_raw_sha256',row.B_source.sha256, ...
            'source_identity',pack.sourceIdentity,'cfg',cfgNow,'opts',optsForScene,'plant_calls_before_invocation',0, ...
            'training_steps',0,'optimizer_steps',0,'TEST_accessed',false);
        save(runStartPath,'runStart','-v7.3'); write_text(fullfile(attemptDir,'attempt_started.marker'), ...
            [startedUtc newline 'ABOUT_TO_CALL_EPISODE' newline]);
        invocationEntered=true; clear run_dl1018_closed_loop;
        log=run_episode_dl1018(scene,contract.candidate,cfgNow,optsForScene,rawPath);
        assert(isfile(rawPath)&&isfile(markerPath),'C4:PlantOutput','Episode returned without raw/first-Plant marker for %s.',sceneId);
        runIdentity=struct('schema','C4_TAIL11_RUN_IDENTITY_V1','batch_index',k,'scene_id',sceneId, ...
            'candidate',contract.candidate,'coordinate_factor_m',0,'source_binding_sha256',bindingSha, ...
            'tail_release_sha256',releaseSha,'input_lock_sha256',lockSha,'prepare_result_sha256',prepSha, ...
            'scene_b_raw_sha256',row.B_source.sha256,'training_steps',0,'optimizer_steps',0,'TEST_accessed',false);
        save(rawPath,'runIdentity','-append'); rawSha=sha256_file(rawPath);
        complete=strcmpi(log.status,'STABLE')&&isempty(char(log.safety_stop_reason))&& ...
            double(log.last_transition)==20000&&numel(log.transition_time)==20000&&numel(log.time)==20001&& ...
            all(isfinite(log.state(:)))&&all(isfinite(log.reference.position(:)));
        state='FAILED_NO_RETRY'; if complete, state='RUN_COMPLETE_RAW_PENDING_AUDIT'; end
        attemptBytes=directory_bytes(attemptDir); totalBytes=directory_bytes(here);
        if attemptBytes>reserveBytes||totalBytes>maxBytes, state='FAILED_NO_RETRY'; end
        runStatus=struct('schema','C4_TAIL11_RUN_STATUS_V1','status',state,'batch_index',k, ...
            'scene_id',sceneId,'source_scene_id',rawSceneId,'candidate',contract.candidate, ...
            'coordinate_factor_m',0,'log_status',log.status,'safety_stop_reason',log.safety_stop_reason, ...
            'last_transition',double(log.last_transition),'transitions',numel(log.transition_time), ...
            'state_samples',numel(log.time),'raw_path',rawPath,'raw_sha256',rawSha, ...
            'raw_bytes',double(dir(rawPath).bytes),'attempt_bytes',attemptBytes,'run_start_path',runStartPath, ...
            'run_start_sha256',sha256_file(runStartPath),'first_plant_step_marker_path',markerPath, ...
            'first_plant_step_marker_sha256',sha256_file(markerPath),'source_binding_sha256',bindingSha, ...
            'tail_release_sha256',releaseSha,'input_lock_sha256',lockSha,'prepare_result_sha256',prepSha, ...
            'plant_invocation_entered',true,'plant_start_confirmed',true,'plant_calls',1, ...
            'total_output_bytes_after_raw',totalBytes,'training_steps',0,'optimizer_steps',0, ...
            'parameter_or_seed_search',false,'TEST_accessed',false,'created_utc',utc_now());
        if attemptBytes>reserveBytes, runStatus.failure_reason='Per-scene 80,000,000-byte reserve exceeded; stop batch.'; end
        if totalBytes>maxBytes, runStatus.failure_reason='C4 total 1-GiB cap exceeded; raw retained and batch stopped.'; end
        write_json_new(statusPath,runStatus);
        attemptBytes=directory_bytes(attemptDir); totalBytes=directory_bytes(here);
        runStatus.attempt_bytes=attemptBytes; runStatus.total_output_bytes_after_status=totalBytes;
        if attemptBytes>reserveBytes
            runStatus.status='FAILED_NO_RETRY'; runStatus.failure_reason='Per-scene 80,000,000-byte reserve exceeded; stop batch.';
        end
        if totalBytes>maxBytes
            runStatus.status='FAILED_NO_RETRY'; runStatus.failure_reason='C4 total 1-GiB cap exceeded; raw retained and batch stopped.';
        end
        write_json_replace(statusPath,runStatus);
        assert(strcmp(runStatus.status,'RUN_COMPLETE_RAW_PENDING_AUDIT'), ...
            'C4:TailUnsafeStop','Scene %s incomplete, unsafe, or over budget; preserve and stop without retry.',sceneId);
    catch ME
        failed=struct('schema','C4_TAIL11_FAILURE_V1','status','FAILED_NO_RETRY','batch_index',k, ...
            'scene_id',sceneId,'identifier',ME.identifier,'message',ME.message,'failed_utc',utc_now(), ...
            'attempt_dir',attemptDir,'attempt_created_by_this_invocation',attemptCreated, ...
            'plant_invocation_entered',invocationEntered,'plant_start_confirmed',isfile(markerPath), ...
            'plant_calls',double(isfile(markerPath)),'raw_path',rawPath,'partial_raw_preserved',isfile(rawPath), ...
            'partial_raw_sha256',file_sha_if_exists(rawPath),'tail_release_sha256',releaseSha, ...
            'source_binding_sha256',bindingSha,'input_lock_sha256',lockSha);
        if attemptCreated&&~isfile(failurePath), write_json_new(failurePath,failed); end
        batch.status='FAILED_STOP_NO_RETRY'; batch.completed_scenes=numel(records);
        batch.plant_calls=numel(records)+double(isfile(markerPath)); batch.records=records;
        batch.failure=failed; batch.created_utc=utc_now(); write_json_replace(batchStatusPath,batch);
        rethrow(ME);
    end
    rec=struct('batch_index',k,'scene_id',sceneId,'status',runStatus.status,'raw_path',rawPath,'raw_sha256',rawSha, ...
        'run_status_path',statusPath,'run_status_sha256',sha256_file(statusPath),'plant_calls',1,'created_utc',utc_now());
    records(end+1)=rec; %#ok<AGROW>
    batch.records=records; batch.completed_scenes=k; batch.plant_calls=k; batch.created_utc=utc_now();
    write_json_replace(batchStatusPath,batch);
    if k<numel(tailIds)&&directory_bytes(here)+reserveBytes>maxBytes
        batch.status='FAILED_STOP_NO_RETRY'; batch.failure=sprintf('Insufficient total-cap reserve before scene %s.',tailIds{k+1});
        batch.created_utc=utc_now(); write_json_replace(batchStatusPath,batch);
        error('C4:TailOutputReserve','Stop before next scene; 80,000,000-byte reserve unavailable.');
    end
end
batch.status='COMPLETE_RAW_PENDING_PARENT_AUDIT'; batch.completed_scenes=numel(records); batch.plant_calls=numel(records);
batch.records=records; batch.created_utc=utc_now(); write_json_replace(batchStatusPath,batch);
end

