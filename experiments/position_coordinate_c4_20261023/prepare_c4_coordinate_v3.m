function result=prepare_c4_coordinate_v3()
% No-Plant preparation for the fixed m=0 C4 coordinate screen.
here=fileparts(mfilename('fullpath')); repoRoot=fileparts(fileparts(here));
lockPath=fullfile(here,'C4_INPUT_LOCK_v3.json'); contractPath=fullfile(here,'C4_RUN_CONTRACT_v3.json');
resultPath=fullfile(here,'C4_PREPARE_RESULT_v3.json'); snapshotPath=fullfile(here,'C4_PREPARED_CFG_OPTS_v3.mat');
assert(isfile(lockPath)&&isfile(contractPath)&&~isfile(resultPath)&&~isfile(snapshotPath), ...
    'C4:NoOverwrite','C4 lock/contract must exist and preparation outputs must be absent.');
lock=jsondecode(fileread(lockPath)); contract=jsondecode(fileread(contractPath));
assert(strcmp(lock.schema,'C4_COORDINATE_INPUT_LOCK_V3')&& ...
    strcmp(lock.state,'LOCKED_C4_COORDINATE_NO_PLANT_PARENT_REVIEW_REQUIRED_V3')&& ...
    ~logical(lock.plant_authorized_by_this_lock)&&logical(lock.pcf_auxiliary_enabled)&& ...
    double(lock.coordinate_factor_m)==0&&strcmp(contract.schema,'C4_COORDINATE_RUN_CONTRACT_V3')&& ...
    strcmp(contract.state,lock.state)&&isequal(string(lock.scene_ids_reuse_12(:)), ...
    string(contract.scene_ids(:)))&&numel(lock.scenes)==12&& ...
    strcmp(lock.first_scene_id,'DL1018_VAL_T2_C00_W10')&& ...
    strcmp(lock.first_scene_id,contract.scene_ids{5}), ...
    'C4:Scope','C4 scope/order differs from the frozen twelve-scene contract.');
verify_ref(lock.source_files.lock_builder); verify_ref(lock.source_files.prepare_entry);
verify_ref(lock.source_files.single_scene_runner); verify_ref(lock.source_files.contract);
verify_ref(lock.source_files.synthetic_check);
for k=1:numel(lock.active_source_inventory), verify_ref(lock.active_source_inventory(k)); end
refNames=fieldnames(lock.upstream_refs); for k=1:numel(refNames), verify_ref(lock.upstream_refs.(refNames{k})); end
for k=1:numel(lock.shared_input_files), verify_ref(lock.shared_input_files(k)); end
assert(numel(lock.active_source_inventory)==32&&lock.source_counts.matlab==31&&lock.source_counts.mat==1, ...
    'C4:SourceCount','Expected the locked 32-source/31-M/1-MAT runtime inventory.');

% Restore the frozen dependency path after init_dl1018 resets the MATLAB path.
active=lock.active_source_inventory; initPath=source_path(active,'init_dl1018.m');
optionsPath=source_path(active,'position_only_search_options.m');
headPath=source_path(active,'position_only_search_head_step.m');
forwardPath=source_path(active,'position_stage1_model_forward_v2.m');
add_active_paths(active); addpath(fullfile(repoRoot,'matlab','runtime'),'-end'); addpath(fullfile(repoRoot,'matlab','core'),'-end');
addpath(fileparts(initPath),'-begin'); clear init_dl1018; rehash;
assert(same_path(which('init_dl1018'),initPath),'C4:InitPath','init_dl1018 resolves outside the frozen runtime.');
[cfg,~,resolvedRoot]=init_dl1018(); assert(same_path(resolvedRoot,repoRoot),'C4:ProjectRoot','Runtime resolved a different repository root.');
add_active_paths(active); addpath(fullfile(repoRoot,'matlab','runtime'),'-end'); addpath(fullfile(repoRoot,'matlab','core'),'-end');
addpath(fileparts(optionsPath),'-begin'); addpath(fileparts(headPath),'-begin'); addpath(fileparts(forwardPath),'-begin'); addpath(here,'-begin');
clear run_episode_dl1018 run_dl1018_closed_loop delayed_prediction_step_candidate ...
    position_only_search_options position_only_search_head_step position_stage1_model_forward_v2 init_dl1018; rehash;
for k=1:numel(active)
    verify_ref(active(k)); [~,name,ext]=fileparts(active(k).path);
    if strcmpi(ext,'.m'), assert(same_path(which(name),active(k).path), ...
            'C4:WhichShadow','Locked source %s resolves to a shadow.',name); end
end
assert(same_path(which('run_dl1018_closed_loop'),fullfile(here,'run_dl1018_closed_loop.m'))&& ...
    same_path(which('run_episode_dl1018'),fullfile(here,'run_episode_dl1018.m'))&& ...
    same_path(which('delayed_prediction_step_candidate'),fullfile(here,'delayed_prediction_step_candidate.m')), ...
    'C4:Isolation','C4 core/wrapper/helper must resolve from the isolated directory.');

% Compare fresh m=0 options with frozen C3, differing only by the coordinate field.
c3Prep=jsondecode(fileread(lock.upstream_refs.c3_prepare_result.path));
assert(strcmp(c3Prep.status,'PREPARED_NO_PLANT_WAIT_PARENT_RELEASE')&& ...
    double(c3Prep.plant_calls)==0&&~logical(c3Prep.run_episode_called)&& ...
    ~logical(c3Prep.TEST_accessed)&&strcmpi(c3Prep.snapshot_sha256,lock.upstream_refs.c3_prepared_snapshot.sha256), ...
    'C4:C3Prepare','Frozen C3 no-Plant preparation identity changed.');
c3Pack=load(lock.upstream_refs.c3_prepared_snapshot.path,'cfg','opts','W0','modelIdentity','sceneIdentity','sourceIdentity');
assert(all(isfield(c3Pack,{'cfg','opts','W0','modelIdentity','sceneIdentity','sourceIdentity'})), ...
    'C4:C3Snapshot','C3 prepared snapshot is incomplete.');
modelPath=source_role(lock.shared_input_files,'model_mat'); modelPack=load(modelPath,'model');
assert(isfield(modelPack,'model')&&isstruct(modelPack.model),'C4:Model','Frozen model missing.');
model=modelPack.model; W0=double(model.output_W);
assert(strcmp(char(model.model_id),'DSSM14')&&double(model.seed)==2026102001&& ...
    double(model.selected_step)==60000&&double(model.input_dim)==14&&double(model.window)==32&& ...
    isequal(size(W0),[33,3])&&all(isfinite(W0(:)))&& ...
    strcmpi(hash_bytes(typecast(W0(:),'uint8')),lock.candidate_identity.W0_sha256)&& ...
    strcmpi(hash_normalizer_arrays(model),lock.candidate_identity.normalizer_arrays_sha256), ...
    'C4:ModelIdentity','Frozen DSSM14/W0/normalizer identity changed.');
assert(isequaln(cfg,c3Pack.cfg),'C4:ConfigChanged','C4 config differs from frozen C3.');
opts=position_only_search_options(cfg,model,'FEATURE',12,1);
opts.position_delayed_prediction_enabled=true; opts.position_coordinate_m=0;
assert(isfield(c3Pack.opts,'position_delayed_prediction_enabled')&& ...
    ~isfield(c3Pack.opts,'position_coordinate_m')&& ...
    isequaln(rmfield(opts,'position_coordinate_m'),c3Pack.opts), ...
    'C4:OptsChanged','C4 opts must equal C3 opts except for position_coordinate_m=0.');
assert(isequal(W0,double(c3Pack.W0))&& ...
    strcmpi(c3Pack.modelIdentity.W0_sha256,lock.candidate_identity.W0_sha256)&& ...
    strcmpi(c3Pack.modelIdentity.normalizer_arrays_sha256,lock.candidate_identity.normalizer_arrays_sha256), ...
    'C4:C3Model','C3 snapshot model identity differs from the frozen C4 identity.');

% Reuse the already audited C3 scene identity table without rereading old raw MAT files.
sceneIdentity=repmat(c3Pack.sceneIdentity(1),1,12);
for k=1:12
    row=lock.scenes(k); ix=find(strcmp({c3Pack.sceneIdentity.scene_id},row.scene_id));
    assert(numel(ix)==1&&same_path(row.B_source.path,c3Pack.sceneIdentity(ix).B_raw_path)&& ...
        strcmpi(row.B_source.sha256,c3Pack.sceneIdentity(ix).B_raw_sha256)&& ...
        same_path(row.C3_reuse.raw_path,row.C3_reuse.scope_raw_path)&& ...
        strcmpi(row.C3_reuse.raw_sha256,row.C3_reuse.scope_raw_sha256)&& ...
        strcmpi(row.C3_reuse.status_sha256,row.C3_reuse.scope_status_sha256), ...
        'C4:SceneReuseBinding','Locked C3/B identities differ for %s.',row.scene_id);
    verify_file(row.C3_reuse.status_path,row.C3_reuse.status_sha256);
    verify_file(row.C3_reuse.run_start_path,row.C3_reuse.run_start_sha256);
    verify_file(row.C3_reuse.first_plant_step_marker_path,row.C3_reuse.first_plant_step_marker_sha256);
    status=jsondecode(fileread(row.C3_reuse.status_path));
    assert(strcmp(status.status,'RUN_COMPLETE_RAW_PENDING_AUDIT')&&strcmp(status.log_status,'STABLE')&& ...
        double(status.plant_calls)==1&&strcmpi(status.raw_sha256,row.C3_reuse.scope_raw_sha256), ...
        'C4:C3ReuseStatus','C3 reused outcome/status changed for %s.',row.scene_id);
    sceneIdentity(k)=c3Pack.sceneIdentity(ix);
end

corePath=fullfile(here,'run_dl1018_closed_loop.m'); helperPath=fullfile(here,'delayed_prediction_step_candidate.m');
checkcodeRows=struct('path',{},'id',{},'line',{},'message',{});
for p={corePath,fullfile(here,'run_episode_dl1018.m'),helperPath}
    rows=checkcode(p{1},'-id');
    for j=1:numel(rows), checkcodeRows(end+1)=struct('path',p{1},'id',rows(j).id, ...
            'line',rows(j).line,'message',rows(j).message); end %#ok<AGROW>
end
sourceIdentity=struct('active_paths',{arrayfun(@(x)char(x.path),active,'UniformOutput',false)}, ...
    'active_sha256',{arrayfun(@(x)char(x.sha256),active,'UniformOutput',false)}, ...
    'which_checks',numel(active),'c4_core_path',corePath,'c4_core_sha256',sha256_file(corePath), ...
    'prediction_helper_sha256',sha256_file(helperPath));
modelIdentity=c3Pack.modelIdentity; modelIdentity.W0_sha256=lock.candidate_identity.W0_sha256;
save(snapshotPath,'cfg','opts','W0','modelIdentity','sceneIdentity','sourceIdentity','-v7.3');
result=struct('schema','C4_COORDINATE_PREPARE_RESULT_V3','status','PREPARED_NO_PLANT_WAIT_PARENT_RELEASE_V3', ...
    'created_utc',utc_now(),'input_lock_path',lockPath,'input_lock_sha256',sha256_file(lockPath), ...
    'contract_path',contractPath,'contract_sha256',sha256_file(contractPath), ...
    'snapshot_path',snapshotPath,'snapshot_sha256',sha256_file(snapshotPath), ...
    'source_identity',sourceIdentity,'model_identity',modelIdentity,'scene_identity',sceneIdentity, ...
    'coordinate_factor_m',0,'pcf_auxiliary_enabled',true,'scene_ids',{contract.scene_ids}, ...
    'first_scene_id',contract.first_scene_id,'which_checks',numel(active),'checkcode',checkcodeRows, ...
    'synthetic_check_required',true,'synthetic_check_path',lock.source_files.synthetic_check.path, ...
    'plant_calls',0,'run_episode_called',false,'training_steps',0,'optimizer_steps',0, ...
    'parameter_or_seed_search',false,'new_B_sorties',0,'TEST_accessed',false);
write_json_new(resultPath,result);
end

function add_active_paths(items)
for k=1:numel(items), [~,~,ext]=fileparts(char(items(k).path)); if strcmpi(ext,'.m'), addpath(fileparts(char(items(k).path)),'-end'); end, end
end
function path=source_path(items,name)
idx=[]; for k=1:numel(items), [~,n,e]=fileparts(char(items(k).path)); if strcmpi([n e],name), idx(end+1)=k; end, end %#ok<AGROW>
assert(numel(idx)==1,'C4:SourceName','Expected one locked source %s.',name); path=char(items(idx).path);
end
function path=source_role(items,role)
idx=find(strcmpi({items.role},role));
assert(numel(idx)==1,'C4:SourceRole','Expected one shared input role %s.',role); path=char(items(idx).path);
end
function verify_ref(item), verify_file(item.path,item.sha256); end
function verify_file(path,expected)
assert(isfile(path),'C4:MissingFile','Missing frozen file: %s.',path);
assert(strcmpi(sha256_file(path),expected),'C4:SHA','SHA-256 mismatch: %s.',path);
end
function h=sha256_file(path)
md=java.security.MessageDigest.getInstance('SHA-256'); fid=fopen(path,'r'); assert(fid>=0,'C4:ReadFile','Cannot read %s.',path); c=onCleanup(@()fclose(fid)); %#ok<NASGU>
while true, b=fread(fid,8*1024*1024,'*uint8'); if isempty(b), break; end, md.update(b); end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
function h=hash_bytes(bytes)
md=java.security.MessageDigest.getInstance('SHA-256'); md.update(typecast(uint8(bytes(:)),'int8'));
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
function h=hash_normalizer_arrays(model)
md=java.security.MessageDigest.getInstance('SHA-256');
for name={'input_mu','input_sigma'}, field=name{1}; a=reshape(double(model.(field)),1,[]);
    assert(numel(a)==14&&all(isfinite(a)),'C4:NormalizerShape','Invalid %s.',field);
    header=[field char(0) '((1, 14), ''float64'')' char(0)];
    md.update(typecast(uint8(unicode2native(header,'UTF-8')),'int8')); md.update(typecast(a(:),'int8'));
end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
function tf=same_path(a,b), tf=strcmpi(char(java.io.File(a).getCanonicalPath()),char(java.io.File(b).getCanonicalPath())); end
function write_json_new(path,value)
assert(~isfile(path),'C4:NoOverwrite','Refusing to overwrite %s.',path); fid=fopen(path,'w'); assert(fid>=0,'C4:Write','Cannot create %s.',path); c=onCleanup(@()fclose(fid)); fwrite(fid,jsonencode(value),'char');
end
function t=utc_now(), t=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z''')); end
