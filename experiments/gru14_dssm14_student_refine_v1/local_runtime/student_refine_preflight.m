function report=student_refine_preflight(root)
root=char(java.io.File(root).getCanonicalPath());
out=fullfile(root,'experiments','gru14_dssm14_student_refine_v1');
protocol=jsondecode(fileread(fullfile(out,'protocol.json')));
assert(strcmp(protocol.status,'FROZEN_BEFORE_FIRST_PLANT')&&~protocol.plant_started, ...
    'STUDENT:Protocol','Protocol must be frozen before the first Plant.');
[cfg,~,resolved]=init_dl1018();
assert(strcmp(root,resolved),'STUDENT:Root','Unexpected project root.');
search=fullfile(root,'experiments','position_only_closed_loop_search_v1','local_runtime');
teacher=fullfile(root,'experiments','teacher_reuse_model_screen_v1','local_runtime');
addpath(genpath(search),'-begin');addpath(genpath(teacher),'-begin');rehash;
plan=readtable(fullfile(out,'manifests','student_scene_plan.csv'),'TextType','string');
assert(height(plan)==240&&sum(plan.split=="train")==192,'STUDENT:Plan','Expected 240 model-scene rows.');
for modelId={"GRU14","DSSM14"}
    modelId=char(modelId{1});
    package=fullfile(root,'experiments','teacher_reuse_model_screen_v1','models','official_export', ...
        modelId,sprintf('seed%.0f',protocol.checkpoints.(modelId).original_seed),'final_step','matlab_model_and_parity.mat');
    saved=load(package,'model');model=saved.model;model.model_id=modelId;
    assert(double(model.input_dim)==14&&double(model.window)==32&&isequal(size(model.output_W),[33,3]), ...
        'STUDENT:PackageShape','Wrong X14/32/W0 package for %s.',modelId);
    opts=position_only_search_options(cfg,model,'FEATURE',12,1);
    p=opts.stage1_position_runtime;
    assert(~opts.rbf_position_output_enabled&&~opts.rbf_position_update_enabled&& ...
        opts.rbf_attitude_enabled&&opts.rbf_attitude_output_enabled&&opts.rbf_attitude_update_enabled&& ...
        p.update_enabled&&p.command_filter_coordination_v3_5.enabled&& ...
        norm(p.weight-double(model.output_W),'fro')==0, ...
        'STUDENT:Controller','Position/attitude/PCF isolation failed for %s.',modelId);
end
bridge=["DL1018_TRAIN_T1_C02_W08","DL1018_TRAIN_T1_C02_W15", ...
    "DL1018_TRAIN_T2_C01_W08","DL1018_TRAIN_T2_C01_W15", ...
    "DL1018_TRAIN_T3_C03_W08","DL1018_TRAIN_T3_C03_W15"];
assert(all(ismember(bridge,string(plan.scene_id(plan.split=="train")))), ...
    'STUDENT:Bridge','The TRAIN Student plan must include all BRIDGE6 scenes.');
assert(all(plan.A1_mps(plan.w==15)==0)&&all(plan.A2_mps(plan.w==15)==0), ...
    'STUDENT:Wind15','W15 must have zero environmental wind amplitudes.');
assert(cfg.plant.dt==.001&&abs(cfg.rbf.position.beta_rise_time-1.8)<1e-12&& ...
    isequal(double(cfg.rbf.position.dmax(:)),[3;3;3]), ...
    'STUDENT:AcceptedConfig','Accepted physical/head configuration changed.');
sceneIds=plan.scene_id(plan.model_id=="GRU14"&plan.split=="train");
sceneId=char(sceneIds(1));g=make_scenes_dl1018('GET',root,sceneId);scene=g.scene;
assert(numel(scene.time)==20001&&abs(scene.time(end)-20)<1e-12, ...
    'STUDENT:Scene','The first selected scene does not match the 20-second Plant contract.');
assert(count_plants(out)==0,'STUDENT:PlantBeforePreflight','Plant was started before zero-Plant preflight.');
report=struct('status','ZERO_PLANT_PREFLIGHT_PASS','created_at_utc',utc_now(), ...
    'plant_starts',0,'models',{{'GRU14','DSSM14'}},'scene_plan_rows',height(plan), ...
    'student_train_scenes_per_model',96,'student_val_scenes_per_model',24, ...
    'position_rbf_output_enabled',false,'position_rbf_update_enabled',false, ...
    'B_attitude_rbf_enabled',true,'B_attitude_rbf_update_enabled',true, ...
    'feature_head','FEATURE_G12_K1_PCF','plant_dt_s',cfg.plant.dt, ...
    'command_filter_coordination',true,'selected_first_scene',sceneId, ...
    'w15_A1_A2_mps_zero',true,'test_accessed',false,'cfg_snapshot',cfg);
write_json(fullfile(out,'reports','zero_plant_preflight.json'),report);
fprintf('STUDENT_REFINE_PREFLIGHT PASS Plant=0 TRAIN=96/model VAL=24/model BRIDGE6=6\n');
end

function n=count_plants(out)
d=dir(fullfile(out,'student_raw','**','plant_started.marker'));n=numel(d);
end
function s=utc_now()
s=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSSXXX'));
end
function write_json(path,value)
fid=fopen(path,'w');assert(fid>0,'STUDENT:Write','Cannot write %s.',path);
cleanup=onCleanup(@()fclose(fid));fwrite(fid,jsonencode(value,'PrettyPrint',true),'char');
end
