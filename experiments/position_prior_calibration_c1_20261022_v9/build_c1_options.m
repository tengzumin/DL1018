function [optsB, opts1, optsC, audit] = build_c1_options(cfg, model, cStar, lock)
% C1 changes only the FEATURE Head initial 33x3 state from W0 to cStar*W0.
arguments
    cfg (1,1) struct
    model (1,1) struct
    cStar (1,1) double {mustBeFinite,mustBeGreaterThanOrEqual(cStar,0),mustBeLessThanOrEqual(cStar,1)}
    lock (1,1) struct
end
assert(strcmp(char(model.model_id),'DSSM14') && strcmp(char(model.architecture),'DSSM') && ...
    double(model.seed)==2026102001 && double(model.selected_step)==60000 && ...
    double(model.input_dim)==14 && double(model.window)==32 && double(model.context_length)==32, ...
    'C1:ModelIdentity','Unexpected fixed DSSM14 model identity.');
W0=double(model.output_W);
assert(isequal(size(W0),[33,3]) && all(isfinite(W0(:))) && ...
    strcmpi(hash_bytes(typecast(W0(:),'uint8')),char(lock.model.w0_output_W_double_f_order_sha256)), ...
    'C1:W0Identity','W0 identity changed.');
normalizerHash=hash_normalizer_arrays(model);
assert(strcmpi(normalizerHash,char(lock.normalizer.actual_runner_arrays_identity_sha256)), ...
    'C1:NormalizerIdentity','Loaded X14 normalizer identity changed.');
assert(abs(double(cfg.plant.dt)-0.001)<=1e-12 && ...
    double(cfg.rbf.runtime.position_update_hz)==100, ...
    'C1:Clocks','Expected 1-kHz Plant and 100-Hz position events.');
optsB=controller_options_dl1018(cfg,'B',[],[],'online');
opts1=position_only_search_options(cfg,model,'FEATURE',12,1);
optsC=position_only_search_options(cfg,model,'FEATURE',12,cStar);
assert(logical(optsB.formal_rbf_baseline) && logical(optsB.rbf_position_output_enabled) && ...
    logical(optsB.rbf_position_update_enabled) && logical(optsB.rbf_attitude_enabled) && ...
    ~isfield(optsB,'stage1_position_runtime'), ...
    'C1:BaselineB','B baseline options are not the fixed original RBF controller.');
p1=opts1.stage1_position_runtime; pC=optsC.stage1_position_runtime;
h1=p1.position_only_search_head; hC=pC.position_only_search_head;
assert(logical(p1.enabled) && logical(p1.update_enabled) && logical(pC.enabled) && logical(pC.update_enabled) && ...
    logical(h1.enabled) && logical(hC.enabled) && strcmpi(char(h1.head_type),'FEATURE') && ...
    strcmpi(char(hC.head_type),'FEATURE') && double(h1.gamma)==12 && double(hC.gamma)==12 && ...
    double(h1.kappa)==1 && abs(double(hC.kappa)-cStar)<=eps(max(1,cStar)) && ...
    double(p1.beta_scale)==1 && double(pC.beta_scale)==1 && ...
    logical(p1.command_filter_coordination_v3_5.enabled) && logical(pC.command_filter_coordination_v3_5.enabled), ...
    'C1:OnlineContract','FEATURE, online update, PCF, gamma, beta, or kappa contract changed.');
assert(isequal(double(p1.weight),W0) && isequal(double(pC.weight),cStar*W0) && ...
    isequal(double(p1.model.output_W),W0) && isequal(double(pC.model.output_W),W0) && ...
    isequal(double(h1.W0),W0) && isequal(double(hC.W0),W0), ...
    'C1:InitialWeight','Only the runtime initial state may scale; frozen model W0 must remain unchanged.');
restored=optsC;
restored.stage1_position_runtime.weight=opts1.stage1_position_runtime.weight;
restored.stage1_position_runtime.position_only_search_head.kappa= ...
    opts1.stage1_position_runtime.position_only_search_head.kappa;
assert(isequaln(restored,opts1), 'C1:OptionDiff', ...
    'ON(c*) may differ from ON(1) only in initial weight and FEATURE kappa metadata.');
audit=struct('model_id',char(model.model_id),'seed',double(model.seed),'selected_step',double(model.selected_step), ...
    'c_star',cStar,'pcf_enabled',true,'update_enabled',true,'head_type','FEATURE','gamma',12, ...
    'beta_scale',1,'model_output_W_sha256',hash_bytes(typecast(W0(:),'uint8')), ...
    'normalizer_arrays_sha256',normalizerHash,'on1_initial_weight_sha256',hash_bytes(typecast(double(p1.weight(:)),'uint8')), ...
    'onc_initial_weight_sha256',hash_bytes(typecast(double(pC.weight(:)),'uint8')), ...
    'allowed_option_differences',{{'stage1_position_runtime.weight','stage1_position_runtime.position_only_search_head.kappa'}}, ...
    'b_baseline','controller_options_dl1018(cfg,''B'',[],[],''online'')');
end
function h=hash_normalizer_arrays(model)
md=java.security.MessageDigest.getInstance('SHA-256');
for name={'input_mu','input_sigma'}
    field=name{1}; a=reshape(double(model.(field)),1,[]);
    assert(numel(a)==14,'C1:NormalizerShape','Expected fourteen %s values.',field);
    header=[field char(0) '((1, 14), ''float64'')' char(0)];
    md.update(typecast(uint8(unicode2native(header,'UTF-8')),'int8'));
    md.update(typecast(a(:),'int8'));
end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
function h=hash_bytes(bytes)
md=java.security.MessageDigest.getInstance('SHA-256');
md.update(typecast(uint8(bytes(:)),'int8'));
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
