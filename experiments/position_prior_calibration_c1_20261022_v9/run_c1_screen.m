        strcmpi(rs.model_W0_sha256,r2.model.w0_output_W_double_f_order_sha256)&&abs(double(rs.c_star)-cStar)<=1e-15&& ...
        strcmpi(rs.r2_frozen_inputs_sha256,lock.r2_lock.sha256), ...
