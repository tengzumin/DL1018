function verify_file(path,expected)
assert(isfile(path)&&strcmpi(sha256_file(path),char(expected)),'C1:InputSHA','Input SHA mismatch: %s',char(path));
end
function yes=same_path(a,b), yes=strcmpi(char(java.io.File(a).getCanonicalPath()),char(java.io.File(b).getCanonicalPath())); end
function id=file_identity(path,expected)
before=dir(path); digest=sha256_file(path); after=dir(path);
assert(numel(before)==1&&numel(after)==1&&before.bytes==after.bytes&&before.datenum==after.datenum&&strcmpi(digest,expected), ...
    'C1:RawIdentity','Frozen raw changed or SHA mismatched: %s',path);
id=struct('bytes',double(after.bytes),'mtime',double(after.datenum),'sha256',digest);
end
function n=directory_bytes(path)
n=0; if ~isfolder(path), return; end; d=dir(fullfile(path,'**','*'));
for k=1:numel(d), if ~d(k).isdir, n=n+double(d(k).bytes); end, end
end
function write_text(path,text)
fid=fopen(path,'w','n','UTF-8'); assert(fid>=0); cleanup=onCleanup(@()fclose(fid)); fwrite(fid,text,'char');
end
function write_json(path,value), write_text(path,jsonencode(value)); end
function h=sha256_file(path)
md=java.security.MessageDigest.getInstance('SHA-256'); fid=fopen(path,'r'); assert(fid>=0); cleanup=onCleanup(@()fclose(fid));
while true, block=fread(fid,1024*1024,'*uint8'); if isempty(block), break; end; md.update(typecast(block(:),'int8')); end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
