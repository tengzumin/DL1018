function verify_probe(probe,runsRoot,sceneId,sourceLockSha,releaseSha,cStar,lock,r2,release,here)
expected={'B','ON1','ONC'}; rows=probe.run_rows;
assert(numel(rows)==3&&isequal({rows.condition},expected)&&all(strcmp({rows.scene_id},sceneId))&& ...
    all(strcmp({rows.status},'STABLE'))&&probe.completed_runs==3&&probe.reused_prior_runs==1&& ...
    probe.new_attempt_runs==2,'C1:ProbeRows','Recovered probe must include one reused B and two new stable rows.');
for k=1:3
    row=rows(k);
    if k==1
        assert(logical(row.reused_prior_run)&&strcmpi(row.actual_run_release,release.prior_release_sha256)&& ...
            strcmpi(row.source_lock_sha256,sourceLockSha),'C1:ProbeBRelease','Recovered B must remain bound to v8.');
        expectedB=verify_reused_b(here,release,lock,r2,sourceLockSha);
        assert(strcmpi(row.raw_sha256,expectedB.raw_sha256)&&strcmpi(row.run_status_sha256,expectedB.run_status_sha256)&& ...
            strcmpi(row.run_start_sha256,expectedB.run_start_sha256)&&strcmpi(row.preflight_sha256,expectedB.preflight_sha256)&& ...
            row.attempt_output_bytes==expectedB.attempt_output_bytes,'C1:ProbeBIdentity','Reused B summary identity mismatch.');
        continue
    end
    assert(~logical(row.reused_prior_run)&&strcmpi(row.actual_run_release,releaseSha)&& ...
        strcmpi(row.source_lock_sha256,sourceLockSha),'C1:ProbeNewRelease','New ON rows must bind v9.');
    attemptDir=fullfile(runsRoot,sceneId,row.condition,'attempt_01');
    rawPath=fullfile(attemptDir,'raw_run.mat'); statusPath=fullfile(attemptDir,'run_status.json');
    runStartPath=fullfile(attemptDir,'run_start.mat');
    verify_file(rawPath,row.raw_sha256); verify_file(statusPath,row.run_status_sha256); verify_file(runStartPath,row.run_start_sha256);
    status=jsondecode(fileread(statusPath)); loaded=load(rawPath,'runIdentity'); start=load(runStartPath,'runStart');
    assert(isfield(loaded,'runIdentity')&&isfield(start,'runStart')&& ...
        strcmp(status.status,'STABLE')&&strcmp(status.scene_id,sceneId)&&strcmp(status.condition,row.condition)&& ...
        logical(status.timing_isolated)==logical(row.timing_isolated)&& ...
        logical(status.formal_timing_qualified)==logical(row.formal_timing_qualified)&& ...
        strcmpi(status.preflight_sha256,row.preflight_sha256)&&strcmpi(status.preflight_sha256,probe.preflight_sha256)&& ...
        double(status.completed_transition)==20000&&strcmp(status.output_before_update_validation,'PASS')&& ...
        strcmpi(status.raw_sha256,row.raw_sha256)&&strcmpi(status.run_start_sha256,row.run_start_sha256)&& ...
        strcmpi(status.source_lock_sha256,sourceLockSha)&&strcmpi(status.release_sha256,releaseSha)&& ...
        strcmpi(status.model_mat_sha256,r2.model.mat_sha256)&&strcmpi(status.normalizer_npz_sha256,r2.normalizer.npz_file_sha256)&& ...
        strcmpi(status.scene_source_raw_sha256,row.scene_source_raw_sha256)&& ...
        double(row.attempt_output_bytes)==directory_bytes(attemptDir)&&abs(double(status.c_star)-cStar)<=1e-15, ...
        'C1:ProbeStatusIdentity','Probe status identity mismatch for %s.',row.condition);
    identity=loaded.runIdentity; rs=start.runStart;
    method=ternary(strcmp(row.condition,'ON1'),'C1_ON_FEATURE_G12_C1','C1_ON_FEATURE_G12_CSTAR');
    assert(strcmp(identity.scene_id,sceneId)&&strcmp(identity.condition,row.condition)&&strcmp(identity.method,method)&& ...
        strcmpi(identity.source_lock_sha256,sourceLockSha)&&strcmpi(identity.release_sha256,releaseSha)&& ...
        logical(identity.timing_isolated)==logical(row.timing_isolated)&& ...
        logical(identity.formal_timing_qualified)==logical(row.formal_timing_qualified)&& ...
        strcmpi(identity.preflight_sha256,row.preflight_sha256)&& ...
        strcmpi(identity.model_mat_sha256,r2.model.mat_sha256)&&strcmpi(identity.normalizer_npz_sha256,r2.normalizer.npz_file_sha256)&& ...
        strcmpi(identity.scene_source_raw_sha256,row.scene_source_raw_sha256)&&logical(identity.plant_called)&& ...
        double(identity.optimizer_steps)==0&&double(identity.gpu_jobs)==0&&~logical(identity.test_accessed)&&~logical(identity.dev_labels_used)&& ...
        strcmp(rs.scene_id,sceneId)&&strcmp(rs.condition,row.condition)&&strcmpi(rs.source_lock_sha256,sourceLockSha)&& ...
        strcmpi(rs.release_sha256,releaseSha)&&strcmpi(rs.preflight_sha256,row.preflight_sha256)&& ...
        strcmpi(rs.model_mat_sha256,r2.model.mat_sha256)&&strcmpi(rs.normalizer_npz_sha256,r2.normalizer.npz_file_sha256)&& ...
