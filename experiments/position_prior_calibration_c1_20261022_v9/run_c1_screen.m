function run_c1_screen(mode)
% Future entry only; Plant starts require a separate parent approval and fresh PS7 preflight.
if nargin~=1, error('C1:Mode','Pass exactly PROBE or CONTINUE.'); end
mode=upper(char(mode)); assert(ismember(mode,{'PROBE','CONTINUE'}),'C1:Mode','Mode must be PROBE or CONTINUE.');
here=fileparts(mfilename('fullpath')); repoRoot=fileparts(fileparts(here));
lockPath=fullfile(here,'C1_SOURCE_LOCK_v2.json'); releasePath=fullfile(here,'C1_RELEASE_v9.json');
lock=jsondecode(fileread(lockPath)); release=jsondecode(fileread(releasePath));
assert(strcmp(lock.schema,'C1_PRIOR_SCALE_SCREEN_V1') && strcmpi(lock.repo_root,repoRoot));
sourceLockSha=sha256_file(lockPath); releaseSha=sha256_file(releasePath);
assert(strcmpi(sourceLockSha,release.source_lock_sha256),'C1:ReleaseLock','Release does not bind this source lock.');
assert(isfield(lock,'resource_timing_clarification')&& ...
    strcmpi(sha256_file(lock.resource_timing_clarification.path),lock.resource_timing_clarification.sha256), ...
    'C1:TimingClarification','Resource/timing clarification SHA mismatch.');
assert(strcmpi(sha256_file(lock.r2_lock.path),lock.r2_lock.sha256) && ...
    strcmpi(sha256_file(lock.calibration.result_path),lock.calibration.result_sha256) && ...
    strcmpi(sha256_file(fullfile(here,'run_c1_screen.m')),release.runner_sha256) && ...
    strcmpi(sha256_file(fullfile(here,'build_c1_options.m')),release.builder_sha256) && ...
    strcmpi(sha256_file(fullfile(here,'offline_options_smoke_c1.m')),release.smoke_sha256) && ...
    strcmpi(sha256_file(fullfile(here,'preflight_c1.ps1')),release.preflight_sha256), ...
    'C1:ImplementationSHA','C1 source or input identity changed after review.');
c1=jsondecode(fileread(lock.calibration.result_path)); cStar=double(c1.solver.c_star);
assert(strcmp(c1.status,'PASS_C1_TRAIN_CALIBRATION_GATE') && c1.solver.train_gate_pass && ...
    abs(cStar-double(lock.calibration.c_star))<=1e-15);
approvalPath=fullfile(here,'reports',['C1_' mode '_APPROVAL_v9.json']);
assert(isfile(approvalPath),'C1:ApprovalMissing','Separate parent %s approval is required.',mode);
approval=jsondecode(fileread(approvalPath));
assert(strcmp(approval.status,['APPROVED_' mode]) && strcmp(approval.mode,mode) && ...
    strcmpi(approval.source_lock_sha256,sourceLockSha) && strcmpi(approval.release_sha256,releaseSha) && ...
    abs(double(approval.c_star)-cStar)<=1e-15,'C1:ApprovalMismatch','Approval does not bind this exact release/c*.');
probePath=fullfile(here,'reports','probe_c1_v9.json');
if strcmp(mode,'CONTINUE')
    assert(isfile(probePath)&&isfield(approval,'probe_summary_sha256'), ...
        'C1:ProbeApprovalMissing','CONTINUE approval must bind reports/probe_c1_v9.json SHA.');
    assert(strcmpi(approval.probe_summary_sha256,sha256_file(probePath)), ...
        'C1:ProbeApprovalMismatch','CONTINUE approval does not bind the current probe summary.');
end
pfPath=fullfile(here,'reports',['preflight_c1_' lower(mode) '_v9.json']);
assert(isfile(pfPath),'C1:PreflightMissing','Run preflight_c1.ps1 first.'); pf=jsondecode(fileread(pfPath));
pfTime=datetime(pf.created_utc,'InputFormat','yyyy-MM-dd''T''HH:mm:ss.SSS''Z''','TimeZone','UTC');
pfAge=datetime('now','TimeZone','UTC')-pfTime;
deadline=datetime('2026-10-24T17:01:00Z','InputFormat','yyyy-MM-dd''T''HH:mm:ss''Z''','TimeZone','UTC');
assert(strcmp(pf.status,'PASS') && strcmp(pf.mode,mode) && strcmpi(pf.source_lock_sha256,sourceLockSha) && ...
    strcmpi(pf.release_sha256,releaseSha) && pfAge>=seconds(0) && pfAge<=minutes(5) && ...
    isfield(pf,'fixed_step_screen_allowed')&&logical(pf.fixed_step_screen_allowed)&& ...
    isfield(pf,'timing_isolated')&&isfield(pf,'formal_timing_qualified')&& ...
    logical(pf.timing_isolated)==logical(pf.formal_timing_qualified)&& ...
    datetime('now','TimeZone','UTC')<deadline,'C1:PreflightStale','Fresh matching preflight and remaining deadline are required.');
% OS-managed exclusive lock prevents concurrent C1 heavy jobs and is released automatically on exit/crash.
lockFile=char(release.shared_heavy_job_lock_path); raf=java.io.RandomAccessFile(lockFile,'rw');
channel=raf.getChannel(); jobLock=channel.tryLock();
assert(~isempty(jobLock),'C1:ConcurrentHeavyJob','Another C1 heavy job holds the exclusive lock.');
cleanup=onCleanup(@()release_job_lock(jobLock,channel,raf)); %#ok<NASGU>
r2=jsondecode(fileread(lock.r2_lock.path)); verify_inputs(here,lock,r2,release);
sceneTable=readtable(r2.scene_list.path,'TextType','string','VariableNamingRule','preserve');
evidence=readtable(r2.scene_payload_identity.path,'TextType','string','VariableNamingRule','preserve');
manifest=readtable(r2.reuse_manifest.path,'TextType','string','VariableNamingRule','preserve');
sceneIds=string({r2.scenes.scene_id}).';
assert(height(sceneTable)==12 && isequal(sceneTable.scene_id(:),sceneIds) && all(startsWith(sceneIds,"DL1018_VAL_")), ...
    'C1:SceneList','The runner is restricted to the frozen twelve VAL scenes.');
assert(height(evidence)==12 && isequal(evidence.scene_id(:),sceneIds) && all(evidence.status=="IDENTICAL") && ...
    all(evidence.physical_field_count==14) && all(evidence.time_samples==20001) && ...
    all(evidence.max_abs_physical_scene_diff==0) && height(manifest)==24 && all(manifest.split=="VAL"), ...
    'C1:SharedPayloadEvidence','Frozen complete shared-payload evidence is required.');
if strcmp(mode,'PROBE')
    indices=1; runsRoot=fullfile(here,'runs_v9');
    if isfolder(runsRoot)
        entries=dir(fullfile(runsRoot,'*')); entries=entries(~ismember({entries.name},{'.','..'}));
        assert(isempty(entries),'C1:NoRetry','PROBE refuses existing or partial attempts.');
    end
else
    indices=2:12; runsRoot=fullfile(here,'runs_v9'); probePath=fullfile(here,'reports','probe_c1_v9.json');
    assert(isfile(probePath),'C1:ProbeMissing','CONTINUE requires a separately reviewed complete probe.');
    probe=jsondecode(fileread(probePath));
    assert(strcmp(probe.status,'PROBE_RECOVERED_COMPLETE') && strcmp(char(probe.scene_id),char(sceneIds(1))) && ...
        probe.completed_runs==3 && probe.reused_prior_runs==1 && probe.new_attempt_runs==2 && ...
        strcmpi(probe.source_lock_sha256,sourceLockSha) && ...
        strcmpi(probe.release_sha256,releaseSha),'C1:ProbeInvalid','Probe evidence is incomplete or mismatched.');
    verify_probe(probe,runsRoot,char(sceneIds(1)),sourceLockSha,releaseSha,cStar,lock,r2,release,here);
end
for si=indices
    for conditionCheck={'B','ON1','ONC'}
        attemptCheck=fullfile(runsRoot,char(sceneIds(si)),conditionCheck{1},'attempt_01');
        assert(~isfolder(attemptCheck),'C1:NoRetry','Stage contains a pre-existing attempt: %s.',attemptCheck);
    end
end
initPath='';
for k=1:numel(r2.runtimeFiles)
    [~,runtimeName,runtimeExt]=fileparts(char(r2.runtimeFiles(k).path));
    if strcmpi([runtimeName runtimeExt],'init_dl1018.m'), initPath=char(r2.runtimeFiles(k).path); break; end
end
assert(~isempty(initPath),'C1:InitSourceMissing','Locked runtime inventory has no init_dl1018.m.');
addpath(fileparts(initPath),'-begin'); clear init_dl1018; rehash;
activeInit=which('init_dl1018');
assert(~isempty(activeInit)&&same_path(activeInit,initPath),'C1:InitPath','init_dl1018 is not resolved from its locked source.');
[cfg,~,resolvedRoot]=init_dl1018();
assert(strcmpi(char(java.io.File(resolvedRoot).getCanonicalPath()),char(java.io.File(repoRoot).getCanonicalPath())));
addpath(here,'-begin'); addpath(fullfile(repoRoot,'matlab','runtime'),'-begin');
addpath(fullfile(repoRoot,'matlab','core'),'-begin'); addpath(fileparts(r2.runtimeFiles(1).path),'-begin');
clear run_episode_dl1018 run_dl1018_closed_loop position_only_search_options position_only_search_head_step position_filter_realization_pcf_step_v3_5 controller_options_dl1018
rehash; verify_active_sources(r2);
modelPack=load(r2.model.mat_path,'model'); [optsB,opts1,optsC,optionAudit]=build_c1_options(cfg,modelPack.model,cStar,r2); %#ok<ASGLU>
if ~isfolder(runsRoot), mkdir(runsRoot); end
conditionOrder={'B','ON1','ONC'}; optsByCondition={optsB,opts1,optsC};
methods={'C1_B_BASELINE','C1_ON_FEATURE_G12_C1','C1_ON_FEATURE_G12_CSTAR'};
completed=0; runRows=struct([]); firstCondition=1;
if strcmp(mode,'PROBE')
    runRows=append_run_row(runRows,verify_reused_b(here,release,lock,r2,sourceLockSha));
    completed=1; firstCondition=2;
end
startedUtc=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z'''));
for si=indices
    sceneId=char(sceneIds(si)); bRow=manifest(manifest.scene_id==sceneIds(si)&manifest.role=="B_BASELINE",:);
    onRow=manifest(manifest.scene_id==sceneIds(si)&manifest.role=="ON_CANDIDATE",:); ev=evidence(evidence.scene_id==sceneIds(si),:);
    assert(height(bRow)==1 && height(onRow)==1 && height(ev)==1 && ...
        strcmpi(char(bRow.raw_sha256),char(ev.b_raw_sha256)) && strcmpi(char(onRow.raw_sha256),char(ev.on_raw_sha256)) && ...
        strcmpi(char(ev.b_scene_payload_sha256_excluding_scene_id),char(ev.on_scene_payload_sha256_excluding_scene_id)), ...
        'C1:SharedPayloadIdentity','Frozen B/ON payload identity does not close for %s.',sceneId);
    rawPath=char(bRow.raw_path); rawBefore=file_identity(rawPath,char(bRow.raw_sha256));
    source=load(rawPath,'scene'); rawAfter=file_identity(rawPath,char(bRow.raw_sha256));
    assert(isequaln(rawBefore,rawAfter) && isfield(source,'scene') && valid_scene(source.scene,sceneId), ...
        'C1:ScenePayload','Frozen B scene failed identity/shape/finite/time checks: %s.',sceneId);
    sceneBase=source.scene; if ~strcmp(char(sceneBase.scene_id),sceneId), sceneBase.scene_id=sceneId; end
    for ci=firstCondition:3
        condition=conditionOrder{ci}; attemptDir=fullfile(runsRoot,sceneId,condition,'attempt_01');
        assert(~isfolder(attemptDir),'C1:NoRetry','Attempt exists; no retry or overwrite: %s.',attemptDir);
        priorRunsRoot=char(release.reused_b_runs_root);
        outputBytes=directory_bytes(runsRoot)+directory_bytes(priorRunsRoot);
        projected=ternary(strcmp(mode,'PROBE'),35,33)*55000000;
        assert(outputBytes+projected<=6*1024^3 && double(java.io.File(repoRoot).getUsableSpace())-projected>=30000000000, ...
            'C1:ResourceBudget','6-GiB output cap or 30-GB free-space floor would be violated.');
        mkdir(attemptDir); marker=fullfile(attemptDir,'attempt_started.marker'); write_text(marker,startedUtc);
        attemptTimer=tic;
        runStart=struct('scene_id',sceneId,'condition',condition,'method',methods{ci}, ...
            'started_utc',char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z''')), ...
            'c_star',cStar,'model_mat_sha256',r2.model.mat_sha256,'model_W0_sha256',r2.model.w0_output_W_double_f_order_sha256, ...
            'normalizer_npz_sha256',r2.normalizer.npz_file_sha256,'r2_frozen_inputs_sha256',lock.r2_lock.sha256, ...
            'source_lock_sha256',sourceLockSha,'release_sha256',releaseSha,'scene_source_raw_sha256',rawBefore.sha256, ...
        'preflight_sha256',sha256_file(pfPath),'timing_isolated',logical(pf.timing_isolated), ...
        'formal_timing_qualified',logical(pf.formal_timing_qualified), ...
        'timing_mark',ternary(logical(pf.timing_isolated),'ISOLATED','NON_RESEARCH_DESKTOP_LOAD_CONTAMINATED'), ...
        'non_research_desktop_loads',pf.non_research_desktop_loads, ...
            'scene_payload_identity_csv_sha256',r2.scene_payload_identity.sha256, ...
            'physical_payload_pair_sha256',char(ev.b_scene_payload_sha256_excluding_scene_id), ...
            'options_audit',optionAudit,'condition_order',{conditionOrder},'optimizer_steps',0,'gpu_jobs',0);
        runStartPath=fullfile(attemptDir,'run_start.mat'); save(runStartPath,'runStart','-v7.3');
        rawOut=fullfile(attemptDir,'raw_run.mat'); log=[];
        try
            episodeTimer=tic; log=run_episode_dl1018(sceneBase,methods{ci},cfg,optsByCondition{ci}); episodeSeconds=toc(episodeTimer);
            log=validate_log(log,condition,cStar,modelPack.model.output_W);
            runIdentity=struct('scene_id',sceneId,'condition',condition,'method',methods{ci}, ...
                'c_star',cStar,'model_id',lock.calibration.model_id,'source_lock_sha256',sourceLockSha, ...
                'release_sha256',releaseSha,'model_mat_sha256',r2.model.mat_sha256, ...
                'normalizer_npz_sha256',r2.normalizer.npz_file_sha256, ...
                'preflight_sha256',sha256_file(pfPath),'timing_isolated',logical(pf.timing_isolated), ...
                'formal_timing_qualified',logical(pf.formal_timing_qualified), ...
                'timing_mark',ternary(logical(pf.timing_isolated),'ISOLATED','NON_RESEARCH_DESKTOP_LOAD_CONTAMINATED'), ...
                'scene_source_raw_sha256',rawBefore.sha256,'plant_called',true, ...
                'optimizer_steps',0,'gpu_jobs',0,'test_accessed',false,'dev_labels_used',false);
            save(rawOut,'log','runIdentity','-v7.3');
            attemptWallSeconds=toc(attemptTimer);
            if strcmp(condition,'B')
                status=struct('output_before_update_validation','NOT_APPLICABLE_B');
            else
                status=struct('output_before_update_validation','PASS', ...
                    'output_before_update_max_abs_error',log.c1_output_before_update_max_abs_error, ...
                    'initial_weight_max_abs_error',log.c1_initial_weight_max_abs_error);
            end
            status.status=char(log.status); status.scene_id=sceneId; status.condition=condition;
            status.completed_transition=double(log.last_transition); status.episode_runtime_seconds=episodeSeconds;
            status.attempt_execution_and_raw_persistence_seconds=attemptWallSeconds;
            status.raw_sha256=sha256_file(rawOut); status.run_start_sha256=sha256_file(runStartPath); status.c_star=cStar;
            status.source_lock_sha256=sourceLockSha; status.release_sha256=releaseSha;
            status.model_mat_sha256=r2.model.mat_sha256; status.normalizer_npz_sha256=r2.normalizer.npz_file_sha256;
            status.scene_source_raw_sha256=rawBefore.sha256;
            status.preflight_sha256=sha256_file(pfPath); status.timing_isolated=logical(pf.timing_isolated);
            status.formal_timing_qualified=logical(pf.formal_timing_qualified);
            status.timing_mark=ternary(logical(pf.timing_isolated),'ISOLATED','NON_RESEARCH_DESKTOP_LOAD_CONTAMINATED');
            status.non_research_desktop_loads=pf.non_research_desktop_loads;
            statusPath=fullfile(attemptDir,'run_status.json'); write_json(statusPath,status); attemptBytes=directory_bytes(attemptDir);
            completed=completed+1; row=row_from_status(status,attemptDir,status.raw_sha256, ...
                sha256_file(statusPath),status.run_start_sha256,rawBefore.sha256,releaseSha,sourceLockSha,false);
            runRows=append_run_row(runRows,row); %#ok<AGROW>
        catch ME
            if isstruct(log)&&~isempty(fieldnames(log))&&~isfile(rawOut)
                failedIdentity=struct('scene_id',sceneId,'condition',condition,'method',methods{ci}, ...
                    'c_star',cStar,'model_id',lock.calibration.model_id,'source_lock_sha256',sourceLockSha, ...
                    'release_sha256',releaseSha,'scene_source_raw_sha256',rawBefore.sha256,'verification_failed',true);
                save(rawOut,'log','failedIdentity','-v7.3');
            end
            failure=struct('scene_id',sceneId,'condition',condition,'identifier',ME.identifier,'message',ME.message, ...
                'failed_utc',char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z''')), ...
                'attempt_dir',attemptDir,'attempt_started_marker_present',isfile(marker),'partial_raw_preserved',isfile(rawOut));
            failurePath=fullfile(here,'reports',['C1_FAILURE_' datestr(now,'yyyymmddTHHMMSSFFF') '.json']); write_json(failurePath,failure); rethrow(ME);
        end
    end
end
newAttempts=ternary(strcmp(mode,'PROBE'),completed-1,completed);
sortiesBefore=ternary(strcmp(mode,'PROBE'),1,3); sortiesAfter=ternary(strcmp(mode,'PROBE'),3,36);
overallTimingIsolated=all([runRows.timing_isolated]);
overallFormalTiming=all([runRows.formal_timing_qualified]);
summary=struct('status',ternary(strcmp(mode,'PROBE'),'PROBE_RECOVERED_COMPLETE','CONTINUE_COMPLETE'), ...
    'mode',mode,'scene_id',char(sceneIds(1)),'probe_scene_id',char(sceneIds(1)), ...
    'scene_ids',{cellstr(sceneIds(indices))},'completed_runs',completed,'expected_runs',ternary(strcmp(mode,'PROBE'),3,3*numel(indices)), ...
    'run_rows',runRows,'c_star',cStar,'source_lock_sha256',sourceLockSha,'release_sha256',releaseSha, ...
    'preflight_sha256',sha256_file(pfPath),'timing_isolated',overallTimingIsolated, ...
    'formal_timing_qualified',overallFormalTiming,'formal_timing_authorized',false, ...
    'timing_mark',ternary(overallTimingIsolated,'ISOLATED','NON_RESEARCH_DESKTOP_LOAD_CONTAMINATED'), ...
    'non_research_desktop_loads',pf.non_research_desktop_loads, ...
    'probe_actual_runs',3,'probe_new_attempts',2,'reused_prior_runs',1,'new_attempt_runs',newAttempts, ...
    'actual_sorties_used_before_stage',sortiesBefore,'actual_sorties_used_after_stage',sortiesAfter, ...
    'remaining_runs_after_probe',33,'max_total_runs',36,'started_utc',startedUtc, ...
    'finished_utc',char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z''')), ...
    'output_bytes_v8_prior',directory_bytes(char(release.reused_b_runs_root)), ...
    'output_bytes_v9',directory_bytes(runsRoot), ...
    'output_bytes',directory_bytes(char(release.reused_b_runs_root))+directory_bytes(runsRoot), ...
    'optimizer_steps',0,'gpu_jobs',0,'test_accessed',false,'dev_labels_used',false);
if strcmp(mode,'PROBE'), out=fullfile(here,'reports','probe_c1_v9.json'); else, out=fullfile(here,'reports','continue_c1_v9.json'); end
assert(~isfile(out),'C1:NoOverwrite','Refusing to overwrite stage summary.'); write_json(out,summary);
fprintf('C1_%s COMPLETE runs=%d/%d c*=%.15g\n',mode,completed,3*numel(indices),cStar);
end
function log=validate_log(log,condition,cStar,W0)
assert(isstruct(log)&&isfield(log,'status')&&strcmp(char(log.status),'STABLE')&& ...
    isfield(log,'last_transition')&&double(log.last_transition)==20000,'C1:RunStatus','Run did not finish stable at 20 s.');
if strcmp(condition,'B'), assert(~logical(log.stage1_position_replacement_enabled)); return; end
expectedKappa=1; if strcmp(condition,'ONC'), expectedKappa=cStar; end
assert(log.stage1_position_replacement_enabled&&log.stage1_position_update_enabled&& ...
    log.stage1_position_search_head_enabled&&strcmpi(char(log.stage1_position_search_head_type),'FEATURE')&& ...
    abs(double(log.stage1_position_search_gamma)-12)<=1e-12&& ...
    abs(double(log.stage1_position_search_kappa)-expectedKappa)<=1e-12&& ...
    logical(log.stage1_position_pcf_coordination_enabled),'C1:RuntimeOptions','ON runtime options mismatch.');
expectedWeight=expectedKappa*double(W0); initErr=max(abs(double(log.stage1_position_weight_initial(:))-expectedWeight(:)));
valid=find(log.stage1_position_event_inference_valid); n=numel(valid);
wb=log.stage1_position_event_weight_before_33x3; phi=log.stage1_position_event_phi_33(valid,:);
raw=log.stage1_position_event_raw_acceleration_mps2(valid,:);
assert(size(wb,3)==n&&size(phi,1)==n&&size(raw,1)==n&&n>0,'C1:EventAudit','Incomplete event output/update log.');
err=0; for j=1:n, pred=double(wb(:,:,j)).'*double(phi(j,:).'); err=max(err,max(abs(pred-double(raw(j,:).')))); end
assert(initErr<=1e-12&&err<=1e-12&&any(double(log.stage1_position_event_weight_delta_fro(valid))>1e-12), ...
    'C1:OutputBeforeUpdate','Initial state/output-before-update/update evidence failed.');
log.c1_initial_weight_max_abs_error=initErr; log.c1_output_before_update_max_abs_error=err;
end
function ok=valid_scene(scene,sceneId)
ok=isstruct(scene)&&isfield(scene,'scene_id')&& ...
    (strcmp(char(scene.scene_id),sceneId)||strcmp(char(scene.scene_id),[sceneId '_ACC_FIX_V1']))&& ...
    isfield(scene,'time')&&numel(scene.time)==20001&&abs(double(scene.time(1)))<=1e-12&& ...
    abs(double(scene.time(end))-20)<=1e-12&&isfield(scene,'environment_wind_I')&& ...
    isequal(size(scene.environment_wind_I),[20001,3])&&isfield(scene,'initial_state')&&numel(scene.initial_state)==12&& ...
    isfield(scene,'arms')&&all(isfield(scene.arms,{'command','rhoDot_hat','rhoDot_true','rho_hat','rho_true'}))&& ...
    isfield(scene,'reference')&&all(isfield(scene.reference,{'position','velocity','acceleration','yaw','yaw_rate','yaw_acceleration'}))&& ...
    isequal(size(scene.reference.position),[20001,3])&&isequal(size(scene.reference.velocity),[20001,3])&& ...
    isequal(size(scene.reference.acceleration),[20001,3])&&isequal(size(scene.reference.yaw),[20001,1])&& ...
    isequal(size(scene.reference.yaw_rate),[20001,1])&&isequal(size(scene.reference.yaw_acceleration),[20001,1])&& ...
    isequal(size(scene.arms.command),[20001,4])&&isequal(size(scene.arms.rhoDot_hat),[20001,4])&& ...
    isequal(size(scene.arms.rhoDot_true),[20001,4])&&isequal(size(scene.arms.rho_hat),[20001,4])&& ...
    isequal(size(scene.arms.rho_true),[20001,4])&&all(isfinite(scene.time(:)))&& ...
    all(isfinite(scene.environment_wind_I(:)))&&all(isfinite(scene.initial_state(:)))&& ...
    all(isfinite(scene.arms.command(:)))&&all(isfinite(scene.arms.rhoDot_hat(:)))&& ...
    all(isfinite(scene.arms.rhoDot_true(:)))&&all(isfinite(scene.arms.rho_hat(:)))&&all(isfinite(scene.arms.rho_true(:)))&& ...
    all(isfinite(scene.reference.position(:)))&&all(isfinite(scene.reference.velocity(:)))&& ...
    all(isfinite(scene.reference.acceleration(:)))&&all(isfinite(scene.reference.yaw(:)))&& ...
    all(isfinite(scene.reference.yaw_rate(:)))&&all(isfinite(scene.reference.yaw_acceleration(:)));
end
function verify_inputs(here,lock,r2,release)
assert(strcmpi(sha256_file(lock.r2_lock.path),lock.r2_lock.sha256)&& ...
    strcmpi(sha256_file(lock.calibration.result_path),lock.calibration.result_sha256)&& ...
    strcmpi(sha256_file(lock.calibration.fit_script_path),lock.calibration.fit_script_sha256)&& ...
    strcmpi(sha256_file(lock.resource_timing_clarification.path),lock.resource_timing_clarification.sha256)&& ...
    strcmpi(sha256_file(lock.taskbook.path),lock.taskbook.sha256));
verify_file(release.reuse_authorization_path,release.reuse_authorization_sha256);
verify_file(release.prior_rescore_path,release.prior_rescore_sha256);
verify_file(release.prior_release_path,release.prior_release_sha256);
verify_file(release.prior_source_lock_path,release.prior_source_lock_sha256);
