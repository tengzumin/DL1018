function result=run_c5_matched_ablation_v1(mode)
% The same frozen runner supports a no-Plant preflight and separately released phases.
if nargin~=1
    error('C5Ablation:Mode','Pass exactly one supported C5 matched-ablation mode.');
end
mode=upper(char(mode));
allowed={'PREFLIGHT_ONLY_C5_MATCHED_ABLATION_V1','PARENT_APPROVED_C5_ABLATION_FIRST_V1', ...
    'PARENT_APPROVED_C5_ABLATION_TAIL11_V1'};
assert(any(strcmp(mode,allowed)),'C5Ablation:Mode','Unsupported C5 matched-ablation mode: %s.',mode);
preflightOnly=strcmp(mode,allowed{1});
phase=''; if strcmp(mode,allowed{2}), phase='FIRST'; elseif strcmp(mode,allowed{3}), phase='TAIL11'; end
here=fileparts(mfilename('fullpath')); repoRoot=fileparts(fileparts(fileparts(here)));
lockPath=fullfile(here,'C5_ABLATION_INPUT_LOCK_v1.json');
contractPath=fullfile(here,'C5_ABLATION_RUN_CONTRACT_v1.json');
bindingPath=fullfile(here,'C5_ABLATION_SOURCE_BINDING_v1.json');
prepPath=fullfile(here,'C5_ABLATION_PREPARE_RESULT_v1.json');
snapshotPath=fullfile(here,'C5_ABLATION_PREPARED_CFG_OPTS_v1.mat');
fixturePath=fullfile(here,'C5_ABLATION_CROSSLANG_FIXTURE_v2.json');
syntheticResultPath=fullfile(here,'C5_ABLATION_CROSSLANG_RESULT_v1.json');
resultPath=fullfile(here,'C5_ABLATION_RUNNER_PREFLIGHT_v1.json');
failurePath=fullfile(here,'C5_ABLATION_RUNNER_PREFLIGHT_FAILURE_v1.json');
releasePath=fullfile(here,['C5_ABLATION_' phase '_PARENT_RELEASE_v1.json']);
batchPath=fullfile(here,['C5_ABLATION_' phase '_BATCH_STATUS_v1.json']);
bodyPath=fullfile(here,['C5_ABLATION_' phase '_BODY_COMPLETE_v1.json']);
phaseFailurePath=fullfile(here,['C5_ABLATION_' phase '_PHASE_FAILURE_v1.json']);
if preflightOnly
    assert(~isfile(resultPath)&&~isfile(failurePath),'C5Ablation:NoRetry','Preserve existing preflight evidence; do not rerun.');
else
    assert(isfile(resultPath)&&~isfile(failurePath)&&isfile(releasePath)&& ...
        ~isfile(batchPath)&&~isfile(bodyPath)&&~isfile(phaseFailurePath), ...
        'C5Ablation:NoRetry','A successful preflight, exact parent release, and unused phase outputs are required.');
end
result=struct();
try
    required={lockPath,contractPath,bindingPath,prepPath,snapshotPath,fixturePath,syntheticResultPath};
    assert(all(cellfun(@isfile,required)),'C5Ablation:Inputs','Prepared files or source binding are missing.');
    lock=jsondecode(fileread(lockPath)); contract=jsondecode(fileread(contractPath));
    binding=jsondecode(fileread(bindingPath)); prep=jsondecode(fileread(prepPath));
    lockSha=sha256_file(lockPath); contractSha=sha256_file(contractPath); bindingSha=sha256_file(bindingPath);
    prepSha=sha256_file(prepPath); snapshotSha=sha256_file(snapshotPath);
    runnerPath=[mfilename('fullpath') '.m']; runnerSha=sha256_file(runnerPath);
    assert(strcmp(lock.schema,'C5_MATCHED_ABLATION_INPUT_LOCK_V1')&& ...
        strcmp(lock.state,'LOCKED_C5_MATCHED_ABLATION_NO_PLANT_PARENT_REVIEW_REQUIRED_V1')&& ...
        ~logical(lock.plant_authorized_by_this_lock)&&logical(lock.pcf_auxiliary_enabled)&& ...
        strcmp(contract.schema,'C5_MATCHED_ABLATION_RUN_CONTRACT_V1')&&strcmp(contract.state,lock.state)&& ...
        strcmp(lock.variant_id,contract.variant_id)&&strcmp(lock.ablation_mode,contract.ablation_mode)&& ...
        strcmp(contract.variant_id,contract.ablation_mode)&& ...
        strcmp(binding.schema,'C5_MATCHED_ABLATION_SOURCE_BINDING_V1')&& ...
        strcmp(binding.state,'SOURCE_BOUND_NO_PLANT_PARENT_REVIEW_REQUIRED_V1')&& ...
        ~logical(binding.plant_authorized)&& ...
        strcmp(binding.variant_id,contract.variant_id)&&strcmp(binding.ablation_mode,contract.ablation_mode)&& ...
        logical(binding.actual_weight_update_enabled)==logical(contract.actual_weight_update_enabled)&& ...
        ~logical(binding.actual_prediction_gradient_enabled)&& ...
        logical(binding.legacy_stage1_update_enabled)&& ...
        strcmp(prep.schema,'C5_MATCHED_ABLATION_PREPARE_RESULT_V1')&& ...
        strcmp(prep.status,'PREPARED_C5_MATCHED_ABLATION_NO_PLANT_WAIT_PARENT_RELEASE_V1')&& ...
        strcmp(prep.variant_id,contract.variant_id)&&strcmp(prep.ablation_mode,contract.ablation_mode)&& ...
        logical(prep.legacy_stage1_update_enabled)&& ...
        logical(prep.actual_weight_update_enabled)==logical(contract.actual_weight_update_enabled)&& ...
        ~logical(prep.actual_prediction_gradient_enabled)&& ...
        double(prep.plant_calls)==0&& ...
        ~logical(prep.run_episode_called)&&~logical(prep.TEST_accessed)&& ...
        strcmpi(prep.input_lock_sha256,lockSha)&&strcmpi(prep.contract_sha256,contractSha)&& ...
        strcmpi(prep.snapshot_sha256,snapshotSha)&& ...
        isequal(double(contract.coordinate_mask(:)),[1;1;0])&& ...
        logical(contract.position_delayed_prediction_enabled)&&logical(contract.stage1_update_enabled)&& ...
        logical(contract.legacy_stage1_update_enabled)&& ...
        logical(contract.actual_weight_update_enabled)==strcmp(contract.variant_id,'C5_NO_DELAYED_PREDICTION')&& ...
        ~logical(contract.actual_prediction_gradient_enabled)&& ...
        numel(lock.scenes)==12&&numel(contract.scene_ids)==12&& ...
        isequal(string({lock.scenes.scene_id}).',string(contract.scene_ids(:)))&& ...
        strcmp(contract.first_scene_id,contract.scene_ids{1}), ...
        'C5Ablation:FrozenIdentity','Lock, contract, preparation, or mode identity changed.');
    assert(numel(lock.active_source_inventory)==32&&double(lock.source_counts.total)==32&& ...
        double(lock.source_counts.matlab)==31&&double(lock.source_counts.mat)==1&& ...
        numel(lock.shared_input_files)==6&&double(binding.active_source_count)==32&& ...
        double(binding.shared_input_count)==6&&strcmpi(contractSha,lock.source_files.contract.sha256)&& ...
        strcmpi(runnerSha,lock.source_files.runner_entry.sha256)&& ...
        strcmpi(runnerSha,binding.runner_sha256)&&strcmpi(lockSha,binding.input_lock_sha256)&& ...
        strcmpi(contractSha,binding.contract_sha256)&&same_path(binding.input_lock_path,lockPath), ...
        'C5Ablation:Binding','Source binding differs from the isolated inputs/runner.');
    verify_lock_refs(lock); verify_binding_refs(binding);
    synthetic=jsondecode(fileread(syntheticResultPath));
    helperRef=lock.active_source_inventory(strcmp({lock.active_source_inventory.role},'prediction_helper'));
    assert(numel(helperRef)==1&&strcmp(synthetic.status,'PASS_SYNTHETIC_CROSSLANGUAGE_ONLY')&& ...
        strcmp(synthetic.variant_id,contract.variant_id)&&~logical(synthetic.plant_or_real_data_used)&& ...
        logical(synthetic.actual_weight_update_enabled)==logical(contract.actual_weight_update_enabled)&& ...
        ~logical(synthetic.actual_prediction_gradient_enabled)&&logical(synthetic.legacy_stage1_update_enabled)&& ...
        double(synthetic.plant_calls)==0&&strcmpi(synthetic.fixture_sha256,sha256_file(fixturePath))&& ...
        strcmpi(synthetic.matlab_helper_sha256,helperRef.sha256)&& ...
        strcmpi(synthetic.python_kernel_sha256,lock.source_files.python_kernel.sha256)&& ...
        strcmpi(prep.synthetic_result_sha256,sha256_file(syntheticResultPath)), ...
        'C5Ablation:Synthetic','Synthetic fixture/result does not match this helper/configuration.');

    % Rebuild and check the exact frozen runtime path after init_dl1018 resets MATLAB paths.
    active=lock.active_source_inventory; initPath=source_path(active,'init_dl1018.m');
    optionsPath=source_path(active,'position_only_search_options.m');
    headPath=source_path(active,'position_only_search_head_step.m');
    forwardPath=source_path(active,'position_stage1_model_forward_v2.m');
    add_active_paths(active); addpath(fullfile(repoRoot,'matlab','runtime'),'-end');
    addpath(fullfile(repoRoot,'matlab','core'),'-end'); addpath(fileparts(initPath),'-begin');
    clear init_dl1018; rehash; assert(same_path(which('init_dl1018'),initPath), ...
        'C5Ablation:InitPath','init_dl1018 resolves outside the locked runtime.');
    [cfgNow,~,resolvedRoot]=init_dl1018();
    assert(same_path(resolvedRoot,repoRoot),'C5Ablation:ProjectRoot','Runtime resolved another project root.');
    add_active_paths(active); addpath(fullfile(repoRoot,'matlab','runtime'),'-end');
    addpath(fullfile(repoRoot,'matlab','core'),'-end'); addpath(fileparts(optionsPath),'-begin');
    addpath(fileparts(headPath),'-begin'); addpath(fileparts(forwardPath),'-begin'); addpath(here,'-begin');
    clear run_episode_dl1018 run_dl1018_closed_loop delayed_prediction_step_candidate ...
        position_only_search_options position_only_search_head_step position_stage1_model_forward_v2 init_dl1018; rehash;
    for k=1:numel(active)
        verify_ref(active(k)); [~,name,ext]=fileparts(char(active(k).path));
        if strcmpi(ext,'.m')
            assert(same_path(which(name),active(k).path),'C5Ablation:WhichShadow', ...
                'Locked source %s resolves to a shadow.',name);
        end
    end
    assert(same_path(which('run_dl1018_closed_loop'),fullfile(here,'run_dl1018_closed_loop.m'))&& ...
        same_path(which('run_episode_dl1018'),fullfile(here,'run_episode_dl1018.m'))&& ...
        same_path(which('delayed_prediction_step_candidate'),fullfile(here,'delayed_prediction_step_candidate.m')), ...
        'C5Ablation:Isolation','Core, wrapper and mode helper must resolve from this isolated config.');

    pack=load(snapshotPath,'cfg','opts','W0','modelIdentity','sceneIdentity','sourceIdentity');
    assert(all(isfield(pack,{'cfg','opts','W0','modelIdentity','sceneIdentity','sourceIdentity'}))&& ...
        isequaln(cfgNow,pack.cfg)&&isequal(double(pack.opts.position_coordinate_mask(:)),[1;1;0])&& ...
        logical(pack.opts.position_delayed_prediction_enabled)&& ...
        logical(pack.opts.stage1_position_runtime.update_enabled)&& ...
        strcmp(pack.sourceIdentity.variant_id,contract.variant_id)&& ...
        strcmp(pack.sourceIdentity.ablation_mode,contract.ablation_mode)&& ...
        logical(pack.sourceIdentity.actual_weight_update_enabled)==logical(contract.actual_weight_update_enabled)&& ...
        double(pack.sourceIdentity.which_checks)==numel(active)&& ...
        same_path(pack.sourceIdentity.c5_core_path,fullfile(here,'run_dl1018_closed_loop.m'))&& ...
        strcmpi(pack.sourceIdentity.c5_core_sha256,sha256_file(fullfile(here,'run_dl1018_closed_loop.m')))&& ...
        strcmpi(pack.sourceIdentity.prediction_helper_sha256,helperRef.sha256), ...
        'C5Ablation:Snapshot','Prepared cfg/opts/source identity differs from the active runtime.');
    modelPath=source_role(lock.shared_input_files,'model_mat'); modelPack=load(modelPath,'model');
    assert(isfield(modelPack,'model')&&isstruct(modelPack.model),'C5Ablation:Model','Frozen model is missing.');
    model=modelPack.model; W0=double(model.output_W);
    optsNow=position_only_search_options(cfgNow,model,'FEATURE',12,1);
    optsNow.position_delayed_prediction_enabled=true; optsNow.position_coordinate_mask=[1;1;0];
    assert(isequaln(optsNow,pack.opts)&&isequal(W0,double(pack.W0))&&all(abs(W0(:))<=60)&& ...
        strcmp(char(model.model_id),char(contract.model.id))&& ...
        double(model.seed)==double(contract.model.seed)&&double(model.selected_step)==double(contract.model.selected_step)&& ...
        double(model.input_dim)==double(contract.model.input_dim)&&double(model.window)==double(contract.model.window)&& ...
        logical(pack.opts.stage1_position_runtime.update_enabled)&& ...
        strcmpi(hash_bytes(typecast(W0(:),'uint8')),contract.model.W0_sha256), ...
        'C5Ablation:ModelOpts','Model/W0 or the C3-identical options changed.');
    c3Pack=load(lock.upstream_refs.c3_prepared_snapshot.path,'cfg','opts','W0','modelIdentity','sceneIdentity','sourceIdentity');
    assert(isequaln(pack.cfg,c3Pack.cfg)&&isequal(pack.W0,c3Pack.W0)&& ...
        isequaln(rmfield(pack.opts,'position_coordinate_mask'),c3Pack.opts), ...
        'C5Ablation:C3Parity','Ablation cfg/W0/options differ from frozen C3 except M110 mask.');
    assert(numel(pack.sceneIdentity)==12&&isequal(string({pack.sceneIdentity.scene_id}).',string(contract.scene_ids(:))), ...
        'C5Ablation:SceneIdentity','Prepared scene identities/order differ from the locked C5 screen12.');
    verify_scene_rows(lock,pack.sceneIdentity,contract);

    remaining=12; reserve=double(contract.limits.per_scene_output_reserve_bytes);
    usable=double(java.io.File(repoRoot).getUsableSpace());
    currentBytes=directory_bytes(here);
    deadline=datetime(char(contract.limits.deadline_utc),'InputFormat',"yyyy-MM-dd'T'HH:mm:ss'Z'",'TimeZone','UTC');
    requiredSeconds=remaining*double(contract.limits.seconds_per_remaining_scene_for_deadline_guard)+ ...
        double(contract.limits.process_exit_buffer_seconds);
    assert(usable-remaining*reserve>=double(contract.limits.minimum_free_bytes)&& ...
        currentBytes+remaining*reserve<=double(contract.limits.max_output_bytes)&& ...
        deadline>datetime('now','TimeZone','UTC')+seconds(requiredSeconds), ...
        'C5Ablation:Resources','Reserve-adjusted disk, output budget, or frozen deadline guard failed.');
    phaseSceneIds=contract.scene_ids;
    if strcmp(phase,'FIRST')
        phaseSceneIds=contract.scene_ids(1);
    elseif strcmp(phase,'TAIL11')
        phaseSceneIds(1)=[];
    end
    runRoot=fullfile(here,'runs_c5_matched_ablation_v1');
    for k=1:numel(phaseSceneIds)
        attemptDir=fullfile(runRoot,char(phaseSceneIds{k}),contract.variant_id,'attempt_01');
        assert(~isfolder(attemptDir),'C5Ablation:PriorAttempt','Attempt already exists for %s.',phaseSceneIds{k});
    end
    result=struct('schema','C5_MATCHED_ABLATION_RUNNER_PREFLIGHT_V1', ...
        'status','PREFLIGHT_COMPLETE_NO_PLANT_WAIT_PARENT_RELEASE_V1','variant_id',contract.variant_id, ...
        'ablation_mode',contract.ablation_mode,'legacy_stage1_update_enabled',true, ...
        'actual_weight_update_enabled',logical(contract.actual_weight_update_enabled), ...
        'actual_prediction_gradient_enabled',false, ...
        'input_lock_sha256',lockSha,'contract_sha256',contractSha,'source_binding_sha256',bindingSha, ...
        'prepare_result_sha256',prepSha,'snapshot_sha256',snapshotSha,'runner_sha256',runnerSha, ...
        'synthetic_result_sha256',sha256_file(syntheticResultPath),'fixture_sha256',sha256_file(fixturePath), ...
        'scene_ids',{contract.scene_ids},'scene_count',numel(contract.scene_ids), ...
        'active_source_count',numel(active),'which_checks',numel(active), ...
        'usable_space_bytes',usable,'remaining_scene_reserve_bytes',remaining*reserve, ...
        'directory_bytes',currentBytes,'deadline_utc',contract.limits.deadline_utc, ...
        'mode',mode,'returned_before_shared_lock_or_episode',true, ...
        'plant_calls',0,'training_steps',0,'optimizer_steps',0,'TEST_accessed',false,'created_utc',utc_now());
    if preflightOnly
        write_json_new(resultPath,result);
        return
    end

    preflight=jsondecode(fileread(resultPath)); preflightSha=sha256_file(resultPath);
    assert(strcmp(preflight.schema,'C5_MATCHED_ABLATION_RUNNER_PREFLIGHT_V1')&& ...
        strcmp(preflight.status,'PREFLIGHT_COMPLETE_NO_PLANT_WAIT_PARENT_RELEASE_V1')&& ...
        strcmp(preflight.variant_id,contract.variant_id)&&strcmp(preflight.ablation_mode,contract.ablation_mode)&& ...
        strcmpi(preflight.input_lock_sha256,lockSha)&&strcmpi(preflight.contract_sha256,contractSha)&& ...
        strcmpi(preflight.source_binding_sha256,bindingSha)&&strcmpi(preflight.prepare_result_sha256,prepSha)&& ...
        strcmpi(preflight.snapshot_sha256,snapshotSha)&&strcmpi(preflight.runner_sha256,runnerSha)&& ...
        double(preflight.plant_calls)==0&&double(preflight.training_steps)==0&& ...
        double(preflight.optimizer_steps)==0&&~logical(preflight.TEST_accessed), ...
        'C5Ablation:PreflightResult','Same-runner no-Plant preflight result does not match current inputs.');
    parentContract=jsondecode(fileread(lock.source_files.parent_release_contract.path));
    release=jsondecode(fileread(releasePath)); releaseSha=sha256_file(releasePath);
    assert(strcmp(parentContract.schema,'C5_MATCHED_ABLATION_PARENT_RELEASE_CONTRACT_V1')&& ...
        strcmp(parentContract.variant_id,contract.variant_id)&&all(isfield(release,parentContract.required_fields))&& ...
        strcmp(release.schema,'C5_MATCHED_ABLATION_PARENT_RELEASE_V1')&& ...
        strcmp(release.state,['APPROVED_C5_ABLATION_' phase '_V1'])&&logical(release.plant_authorized)&& ...
        strcmp(release.variant_id,contract.variant_id)&&strcmp(release.ablation_mode,contract.ablation_mode)&& ...
        strcmp(release.first_scene_id,contract.first_scene_id)&& ...
        logical(release.actual_weight_update_enabled)==logical(contract.actual_weight_update_enabled)&& ...
        ~logical(release.actual_prediction_gradient_enabled)&&logical(release.legacy_stage1_update_enabled)&& ...
        isequal(double(release.coordinate_mask(:)),[1;1;0])&&strcmp(release.candidate,contract.candidate)&& ...
        strcmp(release.phase,phase)&&strcmpi(release.input_lock_sha256,lockSha)&& ...
        strcmpi(release.run_contract_sha256,contractSha)&&strcmpi(release.source_binding_sha256,bindingSha)&& ...
        strcmpi(release.parent_release_contract_sha256,sha256_file(lock.source_files.parent_release_contract.path))&& ...
        strcmpi(release.prepare_result_sha256,prepSha)&&strcmpi(release.snapshot_sha256,snapshotSha)&& ...
        strcmpi(release.synthetic_fixture_sha256,sha256_file(fixturePath))&& ...
        strcmpi(release.synthetic_result_sha256,sha256_file(syntheticResultPath))&& ...
        strcmpi(release.runner_preflight_sha256,preflightSha)&&strcmpi(release.runner_sha256,runnerSha)&& ...
        strcmpi(release.launcher_sha256,lock.source_files.parent_launcher.sha256)&& ...
        isequal(string(release.scene_ids(:)),string(phaseSceneIds(:)))&& ...
        double(release.max_new_Plant)==numel(phaseSceneIds)&& ...
        double(release.training_steps)==0&&double(release.optimizer_steps)==0&& ...
        double(release.new_B_sorties)==0&&~logical(release.TEST_accessed)&& ...
        ~logical(release.automatic_retry)&&~logical(release.parameter_or_seed_search)&& ...
        strcmp(char(release.deadline_utc),char(contract.limits.deadline_utc))&& ...
        double(release.minimum_free_bytes)==double(contract.limits.minimum_free_bytes)&& ...
        double(release.per_scene_output_reserve_bytes)==double(contract.limits.per_scene_output_reserve_bytes)&& ...
        double(release.max_output_bytes)==double(contract.limits.max_output_bytes), ...
        'C5Ablation:ParentRelease','A separate exact phase release bound to this completed preflight is required.');
    if strcmp(phase,'TAIL11')
        assert(all(isfield(release,{'pilot_raw_path','pilot_raw_sha256','pilot_run_status_path', ...
            'pilot_run_status_sha256','pilot_release_sha256'})), ...
            'C5Ablation:PilotFields','Tail release must bind the already-reviewed first-flight artifacts.');
        pilotRaw=release.pilot_raw_path; pilotStatusPath=release.pilot_run_status_path;
        verify_file(pilotRaw,release.pilot_raw_sha256); verify_file(pilotStatusPath,release.pilot_run_status_sha256);
        pilotStatus=jsondecode(fileread(pilotStatusPath)); pilotPack=load(pilotRaw,'runIdentity');
        assert(strcmp(pilotStatus.status,'RUN_COMPLETE_RAW_PENDING_AUDIT')&& ...
            strcmp(pilotStatus.log_status,'STABLE')&&double(pilotStatus.plant_calls)==1&& ...
            strcmp(pilotStatus.scene_id,contract.first_scene_id)&& ...
            strcmp(pilotStatus.variant_id,contract.variant_id)&&strcmp(pilotStatus.ablation_mode,contract.ablation_mode)&& ...
            strcmpi(pilotStatus.raw_sha256,release.pilot_raw_sha256)&& ...
            strcmp(pilotPack.runIdentity.variant_id,contract.variant_id)&& ...
            strcmp(pilotPack.runIdentity.ablation_mode,contract.ablation_mode)&& ...
            strcmp(pilotPack.runIdentity.scene_id,contract.first_scene_id)&& ...
            strcmpi(pilotPack.runIdentity.release_sha256,release.pilot_release_sha256)&& ...
            logical(pilotPack.runIdentity.actual_weight_update_enabled)==logical(contract.actual_weight_update_enabled), ...
            'C5Ablation:PilotBinding','Tail release does not bind the completed same-configuration first flight.');
    end
    result=run_released_phase(mode,phase,here,repoRoot,lock,contract,release,releaseSha, ...
        phaseSceneIds,pack,cfgNow,modelPath,lockSha,contractSha,bindingSha,prepSha,snapshotSha,runnerSha,preflightSha);
catch ME
    failure=struct('schema','C5_MATCHED_ABLATION_RUNNER_PREFLIGHT_FAILURE_V1', ...
        'status','FAILED_NO_PLANT','identifier',ME.identifier,'message',ME.message, ...
        'variant_id',safe_mode(lockPath),'mode',mode,'plant_calls',0,'training_steps',0,'TEST_accessed',false, ...
        'failed_utc',utc_now());
    if preflightOnly&&~isfile(failurePath), write_json_new(failurePath,failure); end
    if ~preflightOnly&&~isfile(batchPath)&&~isfile(phaseFailurePath)
        failure.schema='C5_MATCHED_ABLATION_PHASE_FAILURE_V1'; failure.status='FAILED_BEFORE_PLANT';
        failure.release_sha256=file_sha_if_exists(releasePath); write_json_new(phaseFailurePath,failure);
    end
    rethrow(ME);
end
end

function batch=run_released_phase(mode,phase,here,repoRoot,lock,contract,release,releaseSha, ...
    sceneIds,pack,cfgNow,modelPath,lockSha,contractSha,bindingSha,prepSha,snapshotSha,runnerSha,preflightSha)
batchPath=fullfile(here,['C5_ABLATION_' phase '_BATCH_STATUS_v1.json']);
bodyPath=fullfile(here,['C5_ABLATION_' phase '_BODY_COMPLETE_v1.json']);
runRoot=fullfile(here,'runs_c5_matched_ablation_v1');
reserveBytes=double(contract.limits.per_scene_output_reserve_bytes);
maxBytes=double(contract.limits.max_output_bytes); minFree=double(contract.limits.minimum_free_bytes);
deadline=datetime(char(contract.limits.deadline_utc),'InputFormat',"yyyy-MM-dd'T'HH:mm:ss'Z'",'TimeZone','UTC');
assert(~isfile(batchPath)&&~isfile(bodyPath),'C5Ablation:NoRetry','Phase output exists; preserve it and stop.');
sharedRelease=jsondecode(fileread(lock.upstream_refs.shared_job_release.path));
assert(isfile(sharedRelease.shared_heavy_job_lock_path),'C5Ablation:SharedLock','Shared heavy-job lock file is missing.');
raf=java.io.RandomAccessFile(sharedRelease.shared_heavy_job_lock_path,'rw');
channel=raf.getChannel(); jobLock=channel.tryLock();
assert(~isempty(jobLock),'C5Ablation:ConcurrentHeavyJob','Shared heavy-job lock is held; do not wait or seize it.');
cleanup=onCleanup(@()release_job_lock(jobLock,channel,raf)); %#ok<NASGU>
batchId=['C5_ABLATION_' phase '_' strrep(utc_now(),':','')]; records=empty_phase_records();
batch=struct('schema','C5_MATCHED_ABLATION_BATCH_V1','status','RUNNING','batch_id',batchId, ...
    'phase',phase,'variant_id',contract.variant_id,'ablation_mode',contract.ablation_mode, ...
    'process_scope','ONE_SEQUENTIAL_MATLAB_PROCESS','mode',mode,'scene_ids',{sceneIds}, ...
    'source_binding_sha256',bindingSha,'release_sha256',releaseSha,'runner_sha256',runnerSha, ...
    'preflight_sha256',preflightSha,'completed_scenes',0,'plant_calls',0,'records',records, ...
    'training_steps',0,'optimizer_steps',0,'TEST_accessed',false,'created_utc',utc_now());
write_json_new(batchPath,batch);
for k=1:numel(sceneIds)
    sceneId=char(sceneIds{k}); row=scene_row(lock,sceneId);
    attemptDir=fullfile(runRoot,sceneId,contract.variant_id,'attempt_01');
    attemptStartedPath=fullfile(attemptDir,'attempt_started.marker');
