function result = root_screen12_physical_hold_fresh_v2()
%ROOT_SCREEN12_PHYSICAL_HOLD_FRESH_V1 Offline same-state action diagnosis.
% Reads two frozen SCREEN12 raw runs and the released deployment JSON only.
% It never calls the engine/episode/Plant or advances a state.

here=fileparts(mfilename('fullpath')); reportDir=here; root=fileparts(fileparts(here));
experimentDir=fullfile(root,'experiments','attitude_cm18_a1_20261024');
modelPath=fullfile(experimentDir,'deployment_v1','deployment_parameters_v1.json');
modelSha='ee00c46af42cbce83a630ae9b03eaf1a86bfc6047910ed68bc4e7b8b020aa6ae';
assert(strcmp(sha256_file(modelPath),modelSha),'Screen12DiagV2:ModelHash','Deployment artifact hash changed.');
model=jsondecode(fileread(modelPath));
assert(strcmp(model.schema,'CM18_A1_DEPLOYMENT_PARAMETERS_V1')&& ...
    strcmp(model.artifact_class,'MODEL_PRODUCT_DO_NOT_GIT_UPLOAD'), ...
    'Screen12DiagV2:ModelSchema','Unexpected deployment model schema.');
p=model.parameters;

oldPath=path; pathCleanup=onCleanup(@()path(oldPath)); %#ok<NASGU>
addpath(fullfile(root,'matlab','core'),'-begin');
addpath(fullfile(experimentDir,'matlab'),'-begin');
assert(strcmpi(which('attitude_bs_step'),fullfile(root,'matlab','core','attitude_bs_step.m'))&& ...
    strcmpi(which('simulation_parameters'),fullfile(root,'matlab','core','simulation_parameters.m'))&& ...
    strcmpi(which('controller_parameters'),fullfile(root,'matlab','core','controller_parameters.m'))&& ...
    strcmpi(which('allocate_control'),fullfile(root,'matlab','core','allocate_control.m'))&& ...
    strcmpi(which('cm18_a1_forward_v1'),fullfile(experimentDir,'matlab','cm18_a1_forward_v1.m')), ...
    'Screen12DiagV2:Resolution','A helper resolved outside its frozen source path.');

ids={'DL1018_DEV_T1_C15_W14','DL1018_DEV_T3_C15_W14'};
expectedRawSha={ ...
    '23150766d0b5e2888c35bc5bf96af30f9cc516ffca61e124f0d3d6e4f5ac9476', ...
    '9887fe6425d6868b75e6209fd343d66275ee99dd258efa039477cf8c22d82114'};
rows=cell(numel(ids),1);
for q=1:numel(ids)
    runDir=fullfile(experimentDir,'screen12_remaining_v1','runs',ids{q},'attempt_01');
    rawPath=fullfile(runDir,'raw_run.mat'); startPath=fullfile(runDir,'run_start.mat');
    assert(isfile(rawPath)&&isfile(startPath),'Screen12DiagV2:RawMissing','Missing raw/start for %s.',ids{q});
    rawSha=sha256_file(rawPath);
    assert(strcmp(rawSha,expectedRawSha{q}),'Screen12DiagV2:RawHash','Pinned raw hash changed for %s.',ids{q});
    rows{q}=diagnose_one(ids{q},rawPath,startPath,rawSha,modelSha,model,p,root);
end
result=struct('schema','ROOT_CM18_SCREEN12_PHYSICAL_HOLD_FRESH_V2', ...
    'status','PASS_OFFLINE_SAME_STATE_ONLY','model_json_sha256',modelSha, ...
    'model_checkpoint_sha256',model.identity.checkpoint_sha256, ...
    'selected_step',model.identity.selected_step,'scenes',[rows{:}], ...
    'scope',struct('plant_calls',0,'engine_calls',0,'episode_steps',0, ...
    'state_integrated',false,'optimizer_steps',0,'training',false,'TEST_accessed',false, ...
    'interpretation','Counterfactual accelerations are evaluated at recorded states. They do not establish closed-loop causality or stability.'));
outPath=fullfile(reportDir,'ROOT_SCREEN12_PHYSICAL_HOLD_FRESH_DIAGNOSTIC_v2.json');
assert(~isfile(outPath),'Screen12DiagV2:NoOverwrite','Refusing to overwrite an existing result.');
write_json(outPath,result);
end

function R=diagnose_one(sceneId,rawPath,startPath,rawSha,modelSha,model,p,root)
startPack=load(startPath,'runStart'); raw=load(rawPath,'log','scene');
assert(isfield(startPack,'runStart')&&all(isfield(raw,{'log','scene'})), ...
    'Screen12DiagV2:MatSchema','Raw/start MAT structure is incomplete.');
rs=startPack.runStart; L=raw.log; s=raw.scene; cfg=rs.cfg;
assert(strcmp(rs.scene_id,sceneId)&&strcmp(char(string(s.scene_id)),sceneId)&& ...
    strcmp(rs.deployment_parameters_sha256,modelSha)&& ...
    strcmp(rs.model_identity.checkpoint_sha256,model.identity.checkpoint_sha256)&& ...
    double(rs.model_identity.selected_step)==double(model.identity.selected_step)&& ...
    strcmpi(cfg.controller_morphology_mode,'fixed')&& ...
    strcmpi(cfg.controller_inertia_derivative_mode,'full'), ...
    'Screen12DiagV2:RunIdentity','Run identity or frozen controller mode differs.');
assert(strcmp(model.identity.checkpoint_sha256,'105585385157da3f1b404ab24606d0717287638e4a1ca710790633cd16d233a4')&& ...
    double(model.identity.selected_step)==30000&& ...
    ~logical(rs.opts.rbf_attitude_enabled)&&~logical(rs.opts.rbf_attitude_output_enabled)&& ...
    ~logical(rs.opts.rbf_attitude_update_enabled)&& ...
    ~logical(rs.opts.rbf_position_output_enabled)&&~logical(rs.opts.rbf_position_update_enabled), ...
    'Screen12DiagV2:ControllerIdentity','Run does not use the frozen selected checkpoint/fixed CM18 controller.');

dt=diff(double(s.time(:))); n=numel(dt); event=find(logical(L.cm18_event_flag(:)));
assert(n==20000&&isequal(size(double(L.state)),[n+1,12])&& ...
    isequal(event,(11:10:19991).')&&all(abs(dt-.001)<1e-12), ...
    'Screen12DiagV2:Schedule','Expected 20,000 x 1 ms transitions and 100 Hz updates.');
required={'requested_generalized','realized_generalized','wind_torque_B', ...
    'attitude_bs_nominal_torque_Nm','attitude_compensation_applied_torque_Nm', ...
    'filtered_attitude_reference','filtered_attitude_rate','command_filter_acceleration_applied_rads2', ...
    'motor_command','motor_time_constant_s','cm18_event_input_18','cm18_event_raw_acceleration_rad_s2', ...
    'cm18_applied_acceleration_held_rad_s2','cm18_beta_held','cm18_dmax_rad_s2','cm18_beta_rise_time_s'};
assert(all(isfield(L,required)),'Screen12DiagV2:LogFields','Raw is missing a required frozen engine field.');
assert(isequal(size(double(L.cm18_event_input_18)),[n,18])&& ...
    isequal(size(double(L.cm18_event_raw_acceleration_rad_s2)),[n,3])&& ...
    isequal(size(double(L.cm18_applied_acceleration_held_rad_s2)),[n,3]), ...
    'Screen12DiagV2:EventFields','Event/held output shapes do not match transition rows.');

PplantNom=simulation_parameters(cfg,cfg.plant.arm_initial(:),zeros(4,1));
Pnom=controller_parameters(cfg,PplantNom,'fixed'); J0=double(Pnom.inertia); Jdot0=double(Pnom.inertia_dot_for_bs);
C0=double(Pnom.allocation.C); mass=double(Pnom.mass);
command=double(s.arms.command); request=double(L.requested_generalized);
assert(isequal(size(command),[n+1,4])&&isequal(size(request),[n,4])&& ...
    all(isfinite([command(:);request(:)])),'Screen12DiagV2:Inputs','Invalid command/request arrays.');
z=zeros(n,4); for k=2:n,z(k,:)=z(k-1,:)+dt(k-1)*command(k-1,:);end
motorTc=0; if isfield(rs.opts,'motor_time_constant_s'),motorTc=double(rs.opts.motor_time_constant_s);end
assert(motorTc==0&&all(abs(double(L.motor_time_constant_s(:)))<1e-12), ...
    'Screen12DiagV2:MotorDynamics','This G-based comparison requires the pinned zero motor time constant.');
dmax=double(L.cm18_dmax_rad_s2(1,:)); betaRise=double(L.cm18_beta_rise_time_s(1));
assert(isequal(size(dmax),[1,3])&&all(dmax==[45,45,4.7124])&&betaRise==2.2, ...
    'Screen12DiagV2:OutputContract','Clip/beta limits differ from frozen CM18 settings.');

alphaBS=nan(n,3); alphaBack=nan(n,3); tauBS=nan(n,3); X=nan(n,18);
freshRaw=nan(n,3); freshApplied=nan(n,3); freshBeta=nan(n,1); G=nan(3,3,n);
alphaActual=nan(n,3); alphaZero=nan(n,3); alphaHeldPred=nan(n,3); alphaFreshPred=nan(n,3);
idealAction=nan(n,3); inverseRawAction=nan(n,3); inverseApplied=nan(n,3); alphaInverse=nan(n,3);
inverseClipAxis=false(n,3); inverseAllocClip=false(n,4); inverseAllocSat=false(n,4);
zeroClip=false(n,4); zeroSat=false(n,4); heldClip=false(n,4);
heldSat=false(n,4); freshClip=false(n,4); freshSat=false(n,4);
held=double(L.cm18_applied_acceleration_held_rad_s2);
nomTorqueLogged=double(L.attitude_bs_nominal_torque_Nm);
realized=double(L.realized_generalized); wind=double(L.wind_torque_B); state=double(L.state);
inputEvent=double(L.cm18_event_input_18); rawEvent=double(L.cm18_event_raw_acceleration_rad_s2);
maxBackDelta=0; maxFeatureDelta=0; maxEventForwardDelta=0; maxNominalCompDelta=0; maxFreshGDelta=0;
for k=11:n
    w=state(k,10:12).';
    ref=struct('euler',double(L.filtered_attitude_reference(k,:)).', ...
        'euler_rate',double(L.filtered_attitude_rate(k,:)).', ...
        'euler_acceleration',double(L.command_filter_acceleration_applied_rads2(k,:)).');
    [~,info]=attitude_bs_step(state(k,:).',ref,zeros(3,1),Pnom);
    alphaBS(k,:)=double(info.nominal_body_angular_acceleration(:)).';
    tauBS(k,:)=double(info.nominal_moment(:)).';
    alphaBack(k,:)=(J0\(nomTorqueLogged(k,:).'-cross(w,J0*w)-Jdot0*w)).';
    maxBackDelta=max(maxBackDelta,max(abs(alphaBS(k,:)-alphaBack(k,:))));
    past=(k-10):(k-1); pastDt=dt(past);
    aPrevious=sum(request(past,2:4).*pastDt,1)/sum(pastDt);
    X(k,:)=[w.',alphaBS(k,:),request(k,1)/mass,command(k,:),z(k,:),aPrevious];
    freshRaw(k,:)=cm18_a1_forward_v1(X(k,:),p);
    clipped=max(min(freshRaw(k,:),dmax),-dmax);
    freshBeta(k)=min(k*dt(k)/betaRise,1); freshApplied(k,:)=freshBeta(k)*clipped;
    if L.cm18_event_flag(k)
        maxFeatureDelta=max(maxFeatureDelta,max(abs(X(k,:)-inputEvent(k,:))));
        maxEventForwardDelta=max(maxEventForwardDelta,max(abs(freshRaw(k,:)-rawEvent(k,:))));
    end
    Ptrue=simulation_parameters(cfg,double(s.arms.rho_true(k,:)).',double(s.arms.rhoDot_true(k,:)).');
    J=double(Ptrue.inertia); Jdot=double(Ptrue.inertia_dot); Ctrue=double(Ptrue.allocation.C);
    Mc=Ctrue/C0; G(:,:,k)=J\(Mc(2:4,2:4)*J0);
    alphaActual(k,:)=(J\(realized(k,2:4).'+wind(k,:).'-cross(w,J*w)-Jdot*w)).';
    prev=double(L.motor_command(k-1,:)).';
    [zeroMotor,~,zeroInfo]=allocate_control([request(k,1);tauBS(k,:).'],Pnom,Ptrue,prev);
    zeroWrench=Ctrue*(zeroMotor(:).^2);
    alphaZero(k,:)=(J\(zeroWrench(2:4)+wind(k,:).'-cross(w,J*w)-Jdot*w)).';
    zeroClip(k,:)=logical(zeroInfo.generalized_command_clipped(:)).';
    zeroSat(k,:)=logical(zeroInfo.motor_saturated(:)).';
    alphaHeldPred(k,:)=alphaZero(k,:).'-G(:,:,k)*held(k,:).';
    alphaFreshPred(k,:)=alphaZero(k,:).'-G(:,:,k)*freshApplied(k,:).';
    idealAction(k,:)=(G(:,:,k)\(alphaZero(k,:).'-alphaBS(k,:).')).';
    inverseRawAction(k,:)=(G(:,:,k)\freshRaw(k,:).').';
    inverseClip=max(min(inverseRawAction(k,:),dmax),-dmax);
    inverseClipAxis(k,:)=inverseClip~=inverseRawAction(k,:);
    inverseApplied(k,:)=freshBeta(k)*inverseClip;
    [inverseMotor,~,inverseInfo]=allocate_control( ...
        [request(k,1);tauBS(k,:).'-J0*inverseApplied(k,:).'],Pnom,Ptrue,prev);
    inverseWrench=Ctrue*(inverseMotor(:).^2);
    alphaInverse(k,:)=(J\(inverseWrench(2:4)+wind(k,:).'-cross(w,J*w)-Jdot*w)).';
    inverseAllocClip(k,:)=logical(inverseInfo.generalized_command_clipped(:)).';
    inverseAllocSat(k,:)=logical(inverseInfo.motor_saturated(:)).';
    expectedTorque=tauBS(k,:).'-J0*held(k,:).';
    maxNominalCompDelta=max(maxNominalCompDelta,max(abs(request(k,2:4).'-expectedTorque)));
    [heldMotor,~,heldInfo]=allocate_control([request(k,1);expectedTorque],Pnom,Ptrue,prev);
    heldWrench=Ctrue*(heldMotor(:).^2);
    heldAlpha=(J\(heldWrench(2:4)+wind(k,:).'-cross(w,J*w)-Jdot*w)).';
    heldClip(k,:)=logical(heldInfo.generalized_command_clipped(:)).';
    heldSat(k,:)=logical(heldInfo.motor_saturated(:)).';
    [freshMotor,~,freshInfo]=allocate_control([request(k,1);tauBS(k,:).'-J0*freshApplied(k,:).'],Pnom,Ptrue,prev);
    freshWrench=Ctrue*(freshMotor(:).^2);
    freshAlpha=(J\(freshWrench(2:4)+wind(k,:).'-cross(w,J*w)-Jdot*w)).';
    freshClip(k,:)=logical(freshInfo.generalized_command_clipped(:)).';
    freshSat(k,:)=logical(freshInfo.motor_saturated(:)).';
    maxFreshGDelta=max(maxFreshGDelta,max(abs(freshAlpha-alphaFreshPred(k,:))));
end

assert(maxBackDelta<1e-7&&maxFeatureDelta<1e-10&&maxEventForwardDelta<1e-9&& ...
    maxNominalCompDelta<1e-9,'Screen12DiagV2:Reconstruction','Recorded X18/action does not reconstruct independently.');
assert(~any(zeroClip(:))&&~any(zeroSat(:))&&~any(heldClip(:))&&~any(heldSat(:))&& ...
    ~any(freshClip(:))&&~any(freshSat(:)), ...
    'Screen12DiagV2:LinearMap','A same-state action variant is clipped/saturated; affine G comparison is invalid.');
heldClosure=alphaHeldPred(11:n,:)-alphaActual(11:n,:);
assert(max(abs(heldClosure),[],'all')<1e-7&&maxFreshGDelta<1e-7, ...
    'Screen12DiagV2:HeldClosure','Recorded/fresh action does not reproduce physical acceleration via G.');

phase=cell(4,1); edges=[0 5;5 10;10 15;15 20]; t=double(L.transition_time(:));
err0=alphaZero(11:n,:)-alphaBS(11:n,:);
errHeld=alphaActual(11:n,:)-alphaBS(11:n,:);
errFresh=alphaFreshPred(11:n,:)-alphaBS(11:n,:);
heldFresh=held(11:n,:)-freshApplied(11:n,:);
heldFreshAlpha=alphaHeldPred(11:n,:)-alphaFreshPred(11:n,:);
dSelf=alphaActual(11:n,:)-alphaBS(11:n,:)+held(11:n,:);
fRaw=freshRaw(11:n,:); cIdeal=idealAction(11:n,:);
fRawMinusDSelf=fRaw-dSelf; cIdealMinusDSelf=cIdeal-dSelf;
inverseError=alphaInverse(11:n,:)-alphaBS(11:n,:);
idxAll=(11:n).';
for q=1:4
    mask=t(idxAll)>=edges(q,1)&t(idxAll)<edges(q,2); idx=idxAll(mask); local=mask;
    ev=logical(L.cm18_event_flag(idx));
    phase{q}=struct('interval_s',edges(q,:),'transition_count',numel(idx), ...
        'event_count',nnz(ev),'zero_action_error_rms_rad_s2',rms_axis(err0(local,:)), ...
        'zero_action_error_mean_rad_s2',mean_axis(err0(local,:)), ...
        'recorded_held_error_rms_rad_s2',rms_axis(errHeld(local,:)), ...
        'recorded_held_error_mean_rad_s2',mean_axis(errHeld(local,:)), ...
        'fresh_per_ms_error_rms_rad_s2',rms_axis(errFresh(local,:)), ...
        'fresh_per_ms_error_mean_rad_s2',mean_axis(errFresh(local,:)), ...
        'd_self_mean_rad_s2',mean_axis(dSelf(local,:)), ...
        'd_self_rms_rad_s2',rms_axis(dSelf(local,:)), ...
        'f_raw_mean_rad_s2',mean_axis(fRaw(local,:)), ...
        'f_raw_rms_rad_s2',rms_axis(fRaw(local,:)), ...
        'c_ideal_mean_rad_s2',mean_axis(cIdeal(local,:)), ...
        'c_ideal_rms_rad_s2',rms_axis(cIdeal(local,:)), ...
        'f_raw_minus_d_self_mean_rad_s2',mean_axis(fRawMinusDSelf(local,:)), ...
        'f_raw_minus_d_self_rms_rad_s2',rms_axis(fRawMinusDSelf(local,:)), ...
        'c_ideal_minus_d_self_mean_rad_s2',mean_axis(cIdealMinusDSelf(local,:)), ...
        'c_ideal_minus_d_self_rms_rad_s2',rms_axis(cIdealMinusDSelf(local,:)), ...
        'G_inverse_raw_action_physical_error_rms_rad_s2',rms_axis(inverseError(local,:)), ...
        'held_minus_fresh_accel_rms_rad_s2',rms_axis(heldFresh(local,:)), ...
        'held_minus_fresh_alpha_rms_rad_s2',rms_axis(heldFreshAlpha(local,:)), ...
        'fresh_better_than_held_fraction_by_axis',mean(abs(errFresh(local,:))<abs(errHeld(local,:)),1));
end

eventG=G(:,:,event); singular=zeros(numel(event),3); gdelta=zeros(numel(event),1);
for q=1:numel(event),singular(q,:)=svd(eventG(:,:,q)); gdelta(q)=norm(eventG(:,:,q)-eye(3),'fro');end
meanG=mean(eventG,3); eigMean=eig(meanG);
heldVsFreshOff=heldFreshAlpha(~logical(L.cm18_event_flag(11:n)),:);
R=struct('scene_id',sceneId,'raw_path',relative_path(root,rawPath),'raw_sha256',rawSha, ...
    'run_start_sha256',sha256_file(startPath),'model_checkpoint_sha256',model.identity.checkpoint_sha256, ...
    'selected_step',model.identity.selected_step, ...
    'controller_identity',struct('run_start_schema',rs.schema,'morphology_mode',cfg.controller_morphology_mode, ...
    'inertia_derivative_mode',cfg.controller_inertia_derivative_mode, ...
    'position_mask',double(rs.opts.position_coordinate_mask(:)).', ...
    'attitude_bs_k1',double(cfg.control.bs.attitude.k1(:)).', ...
    'attitude_bs_k2',double(cfg.control.bs.attitude.k2(:)).','attitude_update_hz',100, ...
    'cm18_dmax_rad_s2',dmax,'cm18_beta_rise_time_s',betaRise,'motor_time_constant_s',motorTc, ...
    'legacy_attitude_rbf_enabled',false,'fixed_J0_kgm2',J0), ...
    'reconstruction',struct('transition_count',n,'event_count',numel(event), ...
    'max_abs_filtered_reference_BS_backcalc_delta_rad_s2',maxBackDelta, ...
    'max_abs_event_X18_delta',maxFeatureDelta,'max_abs_event_raw_forward_delta_rad_s2',maxEventForwardDelta, ...
    'max_abs_requested_torque_minus_nominal_minus_compensation_Nm',maxNominalCompDelta, ...
    'max_abs_actual_acceleration_vs_G_held_reconstruction_rad_s2',max(abs(heldClosure),[],'all'), ...
    'max_abs_fresh_allocation_vs_G_acceleration_rad_s2',maxFreshGDelta, ...
    'all_zero_held_fresh_action_allocations_unclipped_unsaturated',true), ...
    'effective_G',struct('definition','Jtrue^{-1} * (Ctrue*C0^{-1})(2:4,2:4) * J0', ...
    'mean_event_G',meanG,'eigenvalues_mean_event_G_real_imag',[real(eigMean),imag(eigMean)], ...
    'event_singular_value_quantiles_0_50_95_100',qtiles(singular), ...
    'event_fro_norm_G_minus_I_quantiles_0_50_95_100',qtiles(gdelta)), ...
    'same_state_actions',struct('zero_action_error_rms_rad_s2',rms_axis(err0), ...
    'zero_action_error_mean_rad_s2',mean_axis(err0), ...
    'recorded_held_actual_error_rms_rad_s2',rms_axis(errHeld), ...
    'recorded_held_actual_error_mean_rad_s2',mean_axis(errHeld), ...
    'fresh_per_ms_predicted_error_rms_rad_s2',rms_axis(errFresh), ...
    'fresh_per_ms_predicted_error_mean_rad_s2',mean_axis(errFresh), ...
    'd_self_mean_rad_s2',mean_axis(dSelf),'d_self_rms_rad_s2',rms_axis(dSelf), ...
    'f_raw_mean_rad_s2',mean_axis(fRaw),'f_raw_rms_rad_s2',rms_axis(fRaw), ...
    'c_ideal_mean_rad_s2',mean_axis(cIdeal),'c_ideal_rms_rad_s2',rms_axis(cIdeal), ...
    'f_raw_minus_d_self_mean_rad_s2',mean_axis(fRawMinusDSelf), ...
    'f_raw_minus_d_self_rms_rad_s2',rms_axis(fRawMinusDSelf), ...
    'c_ideal_minus_d_self_mean_rad_s2',mean_axis(cIdealMinusDSelf), ...
    'c_ideal_minus_d_self_rms_rad_s2',rms_axis(cIdealMinusDSelf), ...
    'G_inverse_raw_action_mean_rad_s2',mean_axis(inverseApplied(11:n,:)), ...
    'G_inverse_raw_action_rms_rad_s2',rms_axis(inverseApplied(11:n,:)), ...
    'G_inverse_raw_action_physical_error_mean_rad_s2',mean_axis(inverseError), ...
    'G_inverse_raw_action_physical_error_rms_rad_s2',rms_axis(inverseError), ...
    'G_inverse_raw_action_controller_clip_fraction_by_axis',mean(inverseClipAxis(11:n,:),1), ...
    'G_inverse_raw_action_allocator_clip_counts_by_axis',sum(inverseAllocClip(11:n,:),1), ...
    'G_inverse_raw_action_motor_saturation_counts_by_motor',sum(inverseAllocSat(11:n,:),1), ...
    'held_minus_fresh_applied_acceleration_rms_rad_s2',rms_axis(heldFresh), ...
    'held_minus_fresh_predicted_physical_accel_rms_rad_s2',rms_axis(heldFreshAlpha), ...
    'held_minus_fresh_physical_accel_rms_off_event_rad_s2',rms_axis(heldVsFreshOff), ...
    'ideal_same_state_action_rms_rad_s2',rms_axis(idealAction(11:n,:)), ...
    'ideal_action_outside_dmax_fraction_by_axis',mean(abs(idealAction(11:n,:))>dmax,1)), ...
    'phase_summaries',[phase{:}]);
end

function v=rms_axis(x)
v=sqrt(mean(double(x).^2,1));
end

function v=mean_axis(x)
v=mean(double(x),1);
end

function q=qtiles(x)
x=sort(double(x),1); n=size(x,1); ix=max(1,min(n,round([0 .5 .95 1]*(n-1))+1));
q=x(ix,:);
end

function s=sha256_file(p)
fid=fopen(p,'rb'); assert(fid>=0,'Screen12DiagV2:FileOpen','Cannot read %s.',p);
c=onCleanup(@()fclose(fid)); bytes=fread(fid,inf,'*uint8'); %#ok<NASGU>
md=java.security.MessageDigest.getInstance('SHA-256'); md.update(bytes);
s=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end

function p=relative_path(root,p)
root=char(java.io.File(root).getCanonicalPath()); p=char(java.io.File(p).getCanonicalPath());
assert(startsWith(lower(p),[lower(root),filesep]),'Screen12DiagV2:Path','Path escapes repository.');
p=strrep(p(length(root)+2:end),filesep,'/');
end

function write_json(p,value)
fid=fopen(p,'w'); assert(fid>=0,'Screen12DiagV2:Output','Cannot create result.');
c=onCleanup(@()fclose(fid)); fwrite(fid,jsonencode(value),'char'); fwrite(fid,newline,'char');
end

