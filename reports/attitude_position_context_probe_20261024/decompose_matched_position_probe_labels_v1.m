function sceneResult=decompose_one(input,repoRoot,phaseNames,componentNames)
c=input.contract;E=input.event;R=input.runStart;cfg=R.cfg;rawPath=input.raw_path;
assert(strcmpi(matlab_text(cfg.controller_morphology_mode),'fixed')&& ...
    strcmpi(matlab_text(cfg.controller_inertia_derivative_mode),'full'), ...
    'CM18Probe:ControllerMode','Fixed nominal/full-Jdot controller mode required.');
n=20000;sceneTime=read_vector(rawPath,'/scene/time',n+1);
command=read_rows(rawPath,'/scene/arms/command',n+1,4);
rho=read_rows(rawPath,'/scene/arms/rho_true',n+1,4);
rhoDot=read_rows(rawPath,'/scene/arms/rhoDot_true',n+1,4);
time=read_vector(rawPath,'/log/time',n+1);
transitionTime=read_vector(rawPath,'/log/transition_time',n);
state=read_rows(rawPath,'/log/state',n+1,12);
eventFlag=read_vector(rawPath,'/log/attitude_event_flag',n)~=0;
tauNom=read_rows(rawPath,'/log/attitude_bs_nominal_torque_Nm',n,3);
tauComp=read_rows(rawPath,'/log/attitude_compensation_applied_torque_Nm',n,3);
requested=read_rows(rawPath,'/log/requested_generalized',n,4);
realized=read_rows(rawPath,'/log/realized_generalized',n,4);
windTorque=read_rows(rawPath,'/log/wind_torque_B',n,3);
controllerWrench=read_rows(rawPath,'/log/controller_clipped_generalized',n,4);
controllerClip=abs(controllerWrench-requested)>1e-9;
allocatorClip=read_rows(rawPath,'/log/generalized_clipped',n,4)~=0;
motorSaturated=read_rows(rawPath,'/log/motor_saturated',n,4)~=0;
motorTc=double(h5read(rawPath,'/log/motor_time_constant_s'));
assert(isscalar(motorTc)&&isfinite(motorTc),'CM18Probe:MotorTimeConstant','Invalid motor time constant.');
idx=find(eventFlag);expectedIdx=(11:10:19991).';dt=diff(sceneTime);
assert(numel(idx)==1999&&isequal(idx,expectedIdx)&& ...
    max(abs(sceneTime-time))<=1e-12&&max(abs(transitionTime-time(1:n)))<=1e-12&& ...
    all(diff(sceneTime)>0)&&max(abs(dt-0.001))<=1e-12&& ...
    isequal(size(state),[n+1,12]), ...
    'CM18Probe:Timebase','Raw time/event schedule changed.');
assert(all(isfinite([state(:);tauNom(:);tauComp(:);requested(:);realized(:); ...
    windTorque(:);rho(:);rhoDot(:);command(:)])), ...
    'CM18Probe:Finite','A selected physical input contains a non-finite value.');
assert(nnz(any(motorSaturated(idx,:),2))==double(input.audit_row.motor_saturated_steps)&& ...
    nnz(any(allocatorClip(idx,:),2))==double(input.audit_row.generalized_clipped_steps), ...
    'CM18Probe:AuditCounts','Raw saturation/clipping counts differ from the Root audit.');
if isfield(R,'opts')&&isstruct(R.opts)&&isfield(R.opts,'motor_time_constant_s')
    assert(abs(double(R.opts.motor_time_constant_s)-motorTc)<=1e-12, ...
        'CM18Probe:MotorTimeConstant','run_start and raw motor time constants differ.');
end

zAll=[zeros(1,4);cumsum(command(1:end-1,:).*repmat(dt,1,4),1)];
u=command(idx,:);z=zAll(idx,:);
P0=simulation_parameters(cfg,cfg.plant.arm_initial,zeros(4,1));
Pc=controller_parameters(cfg,P0,'fixed');J0=double(P0.inertia);Jdot0=double(P0.inertia_dot);
C0=double(Pc.allocation.C);J0inv=J0\eye(3);
nominalControllerInertiaMismatch=max(abs(double(Pc.inertia)-J0),[],'all');
nominalYawInverseOffdiag=max(abs(J0inv(3,1:2)));
nominalJdotYawCross=max(abs(Jdot0(3,1:2)));
assert(isequal(size(J0),[3,3])&&isequal(size(Jdot0),[3,3])&& ...
    isequal(size(C0),[4,4])&&nominalControllerInertiaMismatch<=1e-14, ...
    'CM18Probe:NominalModel','Nominal J0/C0/controller identities invalid.');

N=numel(idx);alphaBS=zeros(N,3);X18=zeros(N,18);targetDirect=zeros(N,3);
comp=zeros(N,numel(componentNames));cOld=zeros(N,3);gzz=zeros(N,1);
windZOverJzz=zeros(N,1);simpleCandidate=zeros(N,1);yawRowMismatch=zeros(N,1);
yawInverseRowOffdiag=zeros(N,1);requestGapYaw=zeros(N,1);realizedGapYaw=zeros(N,1);
