    summary(p+1)=summarize_group(phaseNames{p+1},p,phase(:)==p, ...
        components,target,residual,componentNames);
end
end

function summary=summarize_group(name,phaseCode,mask,components,target,residual,componentNames)
mask=mask(:);values=components(mask,:);y=target(mask);r=residual(mask);n=numel(y);
stats=repmat(struct('name','','mean',[],'second_moment',[],'rms',[]),1,numel(componentNames));
for j=1:numel(componentNames)
    stats(j).name=componentNames{j};
    if n>0
        stats(j).mean=mean(values(:,j));stats(j).second_moment=mean(values(:,j).^2);
        stats(j).rms=sqrt(stats(j).second_moment);
    end
end
pairs=repmat(struct('first','','second','','mean_product',[]),0,1);expandedSecondMoment=[];
if n>0
    expandedSecondMoment=sum(mean(values.^2,1));
    for i=1:size(values,2)
        for j=i+1:size(values,2)
            pairs(end+1,1)=struct('first',componentNames{i}, ...
                'second',componentNames{j},'mean_product',mean(values(:,i).*values(:,j))); %#ok<AGROW>
            expandedSecondMoment=expandedSecondMoment+2*pairs(end).mean_product;
        end
    end
    targetMean=mean(y);targetSecondMoment=mean(y.^2);targetRMS=sqrt(targetSecondMoment);
    residualMax=max(abs(r));secondMomentError=expandedSecondMoment-targetSecondMoment;
else
    targetMean=[];targetSecondMoment=[];targetRMS=[];residualMax=[];secondMomentError=[];
end
summary=struct('phase',name,'phase_code',phaseCode,'event_count',n, ...
    'components',stats,'pairwise_mean_products',pairs, ...
    'expanded_sum_second_moment',expandedSecondMoment, ...
    'target_mean',targetMean,'target_second_moment',targetSecondMoment, ...
    'target_rms',targetRMS,'second_moment_expansion_error',secondMomentError, ...
    'max_abs_closure_residual',residualMax);
end

function phase=classify_phase(command,rho,idx)
phase=zeros(numel(idx),1,'uint8');
for q=1:numel(idx)
    k=idx(q);
    if ~any(abs(command(:))>0)
        code=0;
    elseif any(command(k,:)>0)
        code=2;
    elseif any(command(k,:)<0)
        code=4;
    elseif any(rho(k,:)>.150001)
        code=3;
    elseif any(any(abs(command(1:k,:))>0))&&~any(any(abs(command(k:end,:))>0))
        code=5;
    else
        code=1;
    end
    phase(q)=uint8(code);
end
end

