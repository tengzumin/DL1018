function summary=summarize_phases(phase,components,target,residual,phaseNames,componentNames)
template=summarize_group(phaseNames{1},0,phase(:)==0,components,target,residual,componentNames);
summary=repmat(template,1,numel(phaseNames));summary(1)=template;
