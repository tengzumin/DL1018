function rows=reorder_rows(rowsIn,expectedIds)
assert(numel(rowsIn)==12,'A1R:SceneCount','SCREEN12 must contain exactly twelve scenes.');
rows=rowsIn([]);
for k=1:numel(expectedIds)
    ix=find(strcmp({rowsIn.scene_id},expectedIds{k}));
    assert(numel(ix)==1,'A1R:SceneSet','Scene %s missing or duplicated.',expectedIds{k});
    rows(k)=rowsIn(ix); %#ok<AGROW>
end
end
function model=deployment_model(p)
model=struct('W1',double(p.W1),'b1',double(p.b1(:)), ...
    'W2',double(p.W2),'b2',double(p.b2(:)),'W3',double(p.W3),'b3',double(p.b3(:)), ...
    'input_mean',double(p.input_mean(:)),'input_std',double(p.input_std(:)), ...
    'train_axis_rms_rad_s2',double(p.train_axis_rms_rad_s2(:)));
expected={[32 18],32,[32 32],32,[24 32],24,18,18,3};
names={'W1','b1','W2','b2','W3','b3','input_mean','input_std','train_axis_rms_rad_s2'};
for k=1:numel(names)
    value=model.(names{k}); shape=expected{k};
    if isscalar(shape)&&shape~=1, valid=numel(value)==shape; else, valid=isequal(size(value),shape); end
    assert(valid&&all(isfinite(value(:))),'A1R:ModelShape','Invalid A1R model field %s.',names{k});
end
assert(all(model.input_std(:)>=1e-6)&&all(model.train_axis_rms_rad_s2(:)>0), ...
    'A1R:Normalizer','Canonical normalizer is invalid.');
end
function assert_c5_only_opts_change(opts,c5opts)
fields={'cm18_attitude_v1','r2e_first_plant_step_marker','rbf_attitude_enabled', ...
    'rbf_attitude_output_enabled','rbf_attitude_update_enabled'};
remaining=opts; base=c5opts;
for k=1:numel(fields)
    if isfield(remaining,fields{k}), remaining=rmfield(remaining,fields{k}); end
    if isfield(base,fields{k}), base=rmfield(base,fields{k}); end
end
assert(isequaln(remaining,base),'A1R:OptsChanged','Prepared opts differ from frozen C5 outside approved A1R/RBF fields.');
end
function verify_inventory(items)
for k=1:numel(items), verify_file(char(items(k).path),char(items(k).sha256)); end
end
function verify_file(path,expected)
assert(isfile(path),'A1R:MissingFile','Missing pinned input: %s.',path);
assert(strcmpi(sha256_file(path),expected),'A1R:SHA','SHA-256 mismatch: %s.',path);
end
function h=sha256_file(path)
md=java.security.MessageDigest.getInstance('SHA-256'); fid=fopen(path,'r');
assert(fid>=0,'A1R:ReadFile','Cannot read %s.',path); c=onCleanup(@()fclose(fid)); %#ok<NASGU>
while true, b=fread(fid,8*1024*1024,'*uint8'); if isempty(b), break; end, md.update(b); end
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
function write_json_new(path,value)
assert(~isfile(path),'A1R:NoOverwrite','Refusing to overwrite %s.',path);
fid=fopen(path,'w'); assert(fid>=0,'A1R:Write','Cannot create %s.',path); c=onCleanup(@()fclose(fid)); %#ok<NASGU>
fwrite(fid,jsonencode(value),'char');
end
function write_new(path,text)
assert(~isfile(path),'A1R:NoOverwrite','Refusing to overwrite %s.',path);
fid=fopen(path,'w'); assert(fid>=0,'A1R:Write','Cannot create %s.',path); c=onCleanup(@()fclose(fid)); %#ok<NASGU>
fwrite(fid,text,'char');
end
function tf=same_path(a,b), tf=strcmpi(char(java.io.File(char(a)).getCanonicalPath()),char(java.io.File(char(b)).getCanonicalPath())); end
function t=utc_now(), t=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z''')); end
